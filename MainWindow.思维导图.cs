        /// <summary>
        /// 一个节点点开之后有什么 —— **看它身上挂的是哪一种料**(`附加` 那一格):
        ///   · `项目项C` → 它的文件;· `文件项C` → 那个文件的框树(文件框的两个区);
        ///   · `框来源C` → 这个框的**两个区框**(H61-1:"声明区 / 调用区"本身就是两个可折叠的大框);
        ///   · `导图区C` → 那个区里的内容(声明项 / 语句项 / 流程块框);
        ///   · `分区项C` → 语句的**调用链**(H60-10),`包含`那一项则钻到被包含的那份文件;
        ///   · `调用链节C` → 它的**声明线**(一个指向声明处的框,画虚线)+ **被调方法的框**(H63-1,
        ///     跟着调用走)+ 它自己调用出去的那些;
        ///   · `声明处C` → 到底了(它的行号就是终点)。
        /// </summary>
        private List<导图子项C> 思维导图取子项(导图节点C 节)
        {
            var 结果 = new List<导图子项C>();
            try
            {
                switch (节.附加)
                {
                    case 项目项C 项目: 长工程(项目, 结果); break;
                    case 文件项C 文: 长文件框(文, 结果); break;
                    case 框来源C 框: 长框(框, 节.文件, 结果); break;
                    case 导图区C 区: 长区框(区, 结果); break;
                    case 分区项C 项: 长分区项(项, 节, 结果); break;
                    case 调用链节C 链: 长链节(链, 节, 结果); break;
                    case 声明处C: 结果.Add(说明项("这是声明处本身,没有再往下的东西")); break;
                }
            }
            catch (Exception 异常)
            {
                结果.Add(说明项("这一层读不出来:" + 异常.Message));
            }
            return 结果;
        }

        /// <summary> 工程下面 = 它的文件(顺序 = `.hbp` 的文件表顺序;文件本身没有行号)</summary>
        private void 长工程(项目项C 项目, List<导图子项C> 结果)
        {
            foreach (var 文 in 项目.文件) 结果.Add(文件根(文));
            if (结果.Count == 0) 结果.Add(说明项("这个工程里一个文件都没有"));
        }

        /// <summary> 文件节点点开 = 那个文件的**文件框**(一份文本扫一遍即得;同一扇窗里扫过的存着重用)</summary>
        private void 长文件框(文件项C 文, List<导图子项C> 结果)
        {
            if (取框树(文.全称) is { } 树) 长框(树, 文.全称, 结果);
            else 结果.Add(说明项("这一份读不出来(文件不在盘上?)"));
        }

        // ---------------- 框树(扫一次,存这一扇窗里) ----------------

        /// <summary>
        /// 一份文件 → `导图分区C` 的**框树**(根 = 文件框)。H60-8 / 9 / 11 三步串起来,这里只串不算。
        /// 扫不出来(文件不在盘上 / 读炸了)给 null —— 界面照旧说一句人话,不抛。
        /// </summary>
        private 框来源C? 取框树(string 全称)
        {
            if (全称.Length == 0) return null;
            if (_导图框树.TryGetValue(全称, out var 有)) return 有;
            try
            {
                string 文本 = 取文件文本(全称);
                var 结构 = 源码声明扫描C.扫结构(文本, 全称);
                var 索引 = 声明线C.建(结构, 前端契约C.服务.编译.最近结果?.名字表);
                var 树 = 导图分区C.建(结构, 索引);
                _导图框树[全称] = 树;
                return 树;
            }
            catch (编译异常C 错)
            {
                // T3(2026-09-27 评测整改):嵌套太深这一档**照普通错误路径提示** —— 以前它是一条
                // .NET 栈溢出(接不住,进程当场消失);现在引擎抛带行号的编译错误,这里就得让人看见,
                // 不能只丢进 `异常收集C` 换回一个 null(用户只会看到"这一份读不出来",看不出为什么)。
                异常收集C.记($"思维导图扫结构失败({全称}):{错.Message}");
                说一句($"思维导图:{错.中文}");
                return null;
            }
            catch (Exception 异常)
            {
                异常收集C.记($"思维导图扫结构失败({全称}):{异常.Message}");
                return null;
            }
        }

        /// <summary> 光标落在哪个**方法框**里(按源码行认;不再问编译结果 —— 数据源已经是这棵树)</summary>
        private static 框来源C? 找框含行(框来源C? 框, int 行)
        {
            if (框 == null) return null;
            if (框.种类 == 导图分区C.种类方法 && 行 >= 框.行 && (框.止行 <= 0 || 行 <= 框.止行)) return 框;
            foreach (var 子 in 框.子框们)
                if (找框含行(子, 行) is { } 中) return 中;
            return null;
        }

        // ---------------- 一个框摊成下一层节点 ----------------

        /// <summary>
        /// **一个框长出来的就是两个「区」框**(H61-1 施工图 ②;用户原话「主程序.hb 后直接跟两个子节点
        /// (声明区 / 调用区)**可折叠大框**,不然对于大文件会显示很长很长」):
        /// 点一次先出「声明区」与「调用区」两个大框,大框再点开才是它自己那些项 ——
        /// 一个几百行的文件就不会一次性铺成一大片。
        ///
        /// **子框们不再另挂一组**(老那版是区标签 + 项 + 一组子框):它们各自归位 ——
        /// 声明区里**有登记**的结构 / 方法那几条,`新框项` 直接换成那个框(点它长出它自己两个区);
        /// **流程块**归**调用区**(按行号排在它那句的位置);声明区里没登记的(容器的裸成员头)补进声明区。
        /// 两个区各自按行号排好(那是 H60-12 在 `导图分区C` 里排的,这里一条都不重排)。
        /// </summary>
        private void 长框(框来源C 框, string 全称, List<导图子项C> 结果)
        {
            int 声明条数 = 声明区子项(框, 全称).Count;
            int 调用条数 = 调用区子项(框, 全称).Count;
            if (声明条数 > 0) 结果.Add(新区框(框, 全称, 是声明区: true, 声明条数));
            if (调用条数 > 0) 结果.Add(新区框(框, 全称, 是声明区: false, 调用条数));
            if (结果.Count == 0) 结果.Add(说明项("这个框里没有声明、没有语句,也没有子框"));
        }

        /// <summary> 一个「区」大框点开 = 这一边的内容(声明项 / 语句项 / 流程块框,都按行号排好)</summary>
        private void 长区框(导图区C 区, List<导图子项C> 结果)
        {
            foreach (var 节 in (区.是声明区 ? 声明区子项(区.框, 区.全称) : 调用区子项(区.框, 区.全称)))
                结果.Add(节);
            if (结果.Count == 0) 结果.Add(说明项(区.是声明区 ? "这个框没有声明" : "这个框里没有语句"));
        }

        /// <summary>
        /// **声明区**这一边有些什么(H61-1):
        ///   · `框.声明区` 里的每一条 —— 能在 `框.子框们` 里按**行**找到对应框的(结构 / 方法 / 结构方法)
        ///     就换成那个框(H61-1 口径 ③"声明项即框"),变量 / 常量 / 包含仍是普通项;
        ///   · `框.子框们` 里**没登记进声明区**的(容器的裸成员头那种)—— 不收就丢内容(与 H60-11 ⑤ 同一条);
        ///   · 流程块**不进这里**(它归调用区)。
        /// 一声明不重排:两张表本来就按行号排好,合起来只按行号稳定归并一次。
        /// </summary>
        private static List<导图子项C> 声明区子项(框来源C 框, string 全称)
        {
            var 表 = new List<导图子项C>();
            foreach (var 项 in 框.声明区)
                if (找对应子框(框, 项) is { } 子框) 表.Add(新框项(子框, 全称));
                else 表.Add(新项(项, 全称, 声明边: true));
            foreach (var 子 in 框.子框们)
            {
                if (子.种类 == 导图分区C.种类流程块) continue;
                if (框.声明区.Any(项 => 项.行 == 子.行)) continue;
                表.Add(新框项(子, 全称));
            }
            return 按行(表);
        }

        /// <summary>
        /// **调用区**这一边有些什么(H61-1):`框.调用区` 的语句项(H60-10 的调用链挂在它们自己下面)
        /// **加上** `框.子框们` 里的**流程块框** —— 用户口径 ③"顶层流程块归调用区",同一套手势往下通用:
        /// `循环` / `否则` / `情况` 这些块本来就是"一层语句的架子",按行号排在它那句话的位置上。
        /// </summary>
        private static List<导图子项C> 调用区子项(框来源C 框, string 全称)
        {
            var 表 = new List<导图子项C>();
            foreach (var 项 in 框.调用区) 表.Add(新项(项, 全称, 声明边: false));
            foreach (var 子 in 框.子框们)
                if (子.种类 == 导图分区C.种类流程块) 表.Add(新框项(子, 全称));
            return 按行(表);
        }

        /// <summary> 这一条声明项对应的那个框(按**行**认;流程块不算 —— 它归调用区)</summary>
        private static 框来源C? 找对应子框(框来源C 框, 分区项C 项)
        {
            foreach (var 子 in 框.子框们)
                if (子.种类 != 导图分区C.种类流程块 && 子.行 == 项.行) return 子;
            return null;
        }

        /// <summary> 按行号稳定归并(`OrderBy` 稳定 ⇒ 同号按加进来的先后;H60-12 那条口径在这一层也照办)</summary>
        private static List<导图子项C> 按行(List<导图子项C> 表) => 表.OrderBy(节 => 节.行).ToList();

        /// <summary> 一条语句 / 一条声明点开之后:语句 → 它的**调用线**;`包含` → 被包含的那份文件;别的到底 </summary>
        private void 长分区项(分区项C 项, 导图节点C 节, List<导图子项C> 结果)
        {
            if (项.种类 == "包含")
            {
                string? 目标 = 源码声明扫描C.解析包含路径(节.文件, 项.名);
                if (目标 == null || !File.Exists(目标)) { 结果.Add(说明项($"找不到这一份,钻不进去:{项.名}")); return; }
                结果.Add(文件根(取文件项(目标)));
                return;
            }
            if (项.链们.Count > 0)
            {
                foreach (var 链 in 项.链们) 结果.Add(新链节(链, 节.文件, 声明边: false));
                return;
            }
            结果.Add(说明项(项.种类 == "语句" ? "这一行没有调用别的(字面量 / 只是赋值)" : "这一项没有往下可看的东西"));
        }

        /// <summary>
        /// 一个调用链节点点开之后:**被调方法的框 / 声明线 + 它自己调用出去的那些**(画实线)。
        ///
        /// **H63-1**:"跟着调用走"就在这一处 —— 被调的是**源码里有定义的方法**(本文件 / 别的文件 /
        /// `包含` 进来的库)就把**那个方法框**挂上来;点它进去长出来的就是它的声明区 / 调用区,
        /// 里面那些语句再往下长就是它调用的下一个人(一路点到 `库\排序.hb` 里去)。
        /// **H61-2 的参数**照旧:声明**就在本文件**的别的名字不再加"声明处"小节点,
        /// 改由 `导图回连` 拉一条红色回连线指回声明区那一项(用户口径 ⑤:「变量的调用亦同」)。
        ///
        /// 三档(顺序即优先级):
        ///   ① **能钻的方法** ⇒ 挂它的框;这一枝上面**已经有同一个框**(递归调用)就不挂,
        ///      如实说一句"已经在这一枝上面了"(环护栏:模型 `祖先里有(键, 文件)`)。
        ///      框拿不到(文件不在盘上 / 那一行已经不是方法了)⇒ 退到 ③,不硬编一张空框;
        ///   ② **本文件声明的别的名字**(变量 / 常量 / 参数 / 局部 / 字段)⇒ 只走红线,不另加框;
        ///   ③ **跨文件非方法 / 内建 / 关键字 / 认不出** ⇒ 照旧"→ 声明处"小节点(没有源码定义就说清)。
        /// </summary>
        private void 长链节(调用链节C 链, 导图节点C 节, List<导图子项C> 结果)
        {
            bool 本文件 = 链.声明 != null && 同文件声明(链.声明, 节.文件);
            if (链.是调用 && 链.声明 is { } 处 && 导图分区C.能钻到方法框(处) && 被调框(处) is { } 被调)
            {
                if (节.祖先里有(被调.框.键, 被调.文件))
                    结果.Add(说明项($"「{被调.框.标题}」已经在这一枝上面了(递归调用),不再往里钻"));
                else
                    结果.Add(新框项(被调.框, 被调.文件));
            }
            else if (链.声明 != null && !本文件) 结果.Add(新声明处(链.声明, 链.名));
            foreach (var 子 in 链.子们) 结果.Add(新链节(子, 节.文件, 声明边: false));
            if (结果.Count == 0)
                结果.Add(说明项(本文件 ? "这一条已经用红线连回声明处了(展开它才会画出来)" : "这个名字既没有实参,也没查到声明处"));
        }

        /// <summary>
        /// **H63-1:那个被调方法的框**(本文件 / 别的文件 / `包含` 进来的库,都走这一条)。
        /// 复用现成的两件:`取框树(那一份)`(与「包含」钻取同一个口子、同一份缓存)+
        /// `导图分区C.找方法框(框树, 声明行)`(按**头行**认,容器里的成员方法也认得出)。
        /// 拿不到给 null —— 调用方照旧退到"→ 声明处"小节点,不硬编一张空框。
        /// </summary>
        private (框来源C 框, string 文件)? 被调框(声明处C 处)
        {
            if (取框树(处.文件) is not { } 树) return null;
            if (导图分区C.找方法框(树, 处.行) is not { } 框) return null;
            return (框, 处.文件);
        }

        /// <summary> 这条链节的声明**就在这一份文件里**吗(有源码行 + 文件对得上;H61-2 的判据) </summary>
        private static bool 同文件声明(声明处C 处, string 全称)
            => 处.是源码声明 && 处.行 > 0 && 全称.Length > 0 && 前端契约C.服务.宿主.是同一个文件(处.文件, 全称);

        // ---------------- 料 → 节点 ----------------

        /// <summary>
        /// 一个子框 → 节点(结构 / 方法 / 流程块;标题 / 说明 / 颜色 / 行号都照 `框来源C` 来)。
        /// **H61-1 口径 ①④**:文件框的**标题只留文件名**(全路径进 `提示`)、**左边竖排**一个种类名;
        /// 文件框自己不竖排(口径 ④)。
        /// </summary>
        private static 导图子项C 新框项(框来源C 框, string 全称)
        {
            bool 是文件 = 框.种类 == 导图分区C.种类文件;
            return new 导图子项C
            {
                键 = 框.键,
                标题 = 是文件 ? Path.GetFileName(框.标题) : 框.标题,
                说明 = 是文件 ? "" : 框.说明,
                提示 = 是文件 ? 框.说明 : "",
                种类 = 框.种类,
                行 = 框.行,
                文件 = 全称,
                声明边 = false,
                能往下长 = true,
                竖排 = !是文件,
                竖排字 = 是文件 ? "" : 框.种类,
                附加 = 框,
            };
        }

        /// <summary>
        /// 一个分区项 → 节点(声明项画虚线边;语句项画实线边。行号 / 种类照 `分区项C` 来)。
        /// **声明项左边竖排它的种类名**(H61-1 口径 ④);语句项不竖排。
        /// </summary>
        private static 导图子项C 新项(分区项C 项, string 全称, bool 声明边) => new()
        {
            键 = 项.键,
            标题 = 项.种类 == "语句" ? 项.名
                : (项.类型词.Length > 0 ? $"{项.名} {项.类型词}" : 项.名),
            说明 = 项.说明,
            种类 = 项.种类,
            行 = 项.行,
            文件 = 全称,
            声明边 = 声明边,
            能往下长 = 声明边 ? 项.种类 == "包含" : 项.链们.Count > 0,
            竖排 = 声明边,
            竖排字 = 声明边 ? 项.种类 : "",
            附加 = 项,
        };

        /// <summary> 一个调用链节 → 节点(种类 = `声明线C` 查出来的那一档;认不出就是空串,走中性色不硬猜)。
        /// **H63-6**:这一节在同一个框里**别的行**也用到时(`也在行`),把那几行写进提示 ——
        /// 画面上只留一格,但"还在哪几行用到"看得见。 </summary>
        private static 导图子项C 新链节(调用链节C 链, string 全称, bool 声明边) => new()
        {
            键 = $"调用:{链.全名}@{链.行}",
            标题 = 链.全名 + (链.是调用 ? "()" : ""),
            说明 = 链.种类.Length > 0 ? 链.种类 : (链.是调用 ? "调用（认不出是谁）" : "名字（认不出是谁）"),
            提示 = (链.收方.Length > 0 ? "收方:" + 链.收方 : "")
                + (链.也在行.Count > 0
                    ? (链.收方.Length > 0 ? " · " : "") + $"同一个框里第 {string.Join(" / ", 链.也在行)} 行也用到"
                    : ""),
            种类 = 链.种类,
            行 = 链.行,
            文件 = 全称,
            声明边 = 声明边,
            能往下长 = 链.声明 != null || 链.子们.Count > 0,
            附加 = 链,
        };

        /// <summary>
        /// 一个**声明处** → 节点(H60-9 那条声明线的终点;连到父框的那条线画虚线)。
        /// `行 = 0` 的那一档(内建 / 宿主 / 关键字 / 指令)**如实说"没有源码定义"**,不编假位置 ——
        /// 那句话就是 `声明线C` 从 `补全词表C.没有源码定义说明` 拿来的那一句。
        /// </summary>
        private static 导图子项C 新声明处(声明处C 处, string 名) => new()
        {
            键 = $"声明处:{处.名}@{处.行}",
            标题 = "→ " + (处.全名.Length > 0 ? 处.全名 : 名),
            说明 = 处.是源码声明
                ? $"第 {处.行} 行声明（{处.种类}{(处.类型词.Length > 0 ? " " + 处.类型词 : "")}）"
                : (处.说明.Length > 0 ? 处.说明 : $"没有源码定义（{处.种类}）"),
            提示 = 处.是源码声明 && 处.文件.Length > 0 ? Path.GetFileName(处.文件) : "",
            种类 = 处.种类,
            行 = 处.行,
            文件 = 处.文件,
            声明边 = true,
            能往下长 = false,
            附加 = 处,
        };

        /// <summary>
        /// **一个「区」框**(H61-1 施工图 ②):「声明区 / 调用区」在界面上**自己就是一个框** ——
        /// 点它长出这一边的内容,再点收起(口径 ②)。
        /// 它**不是源码里的东西**:数据仍然全部来自 `框来源C`(`附加` 里拿着那个框 + 是哪一边),
        /// 所以两个区的条数 / 顺序还是 H60-11 / H60-12 那一层说了算,这里一条都不重排。
        /// 边按它那一边画:声明区虚线、调用区实线(H60-14 的两条线口径不变)。
        /// `行 = 0`(它没有源码位置,双击如实说一句)。
        /// **第278批**加一排**斜体小字**「此为思维导图虚拟概念」(用户复查时点名要的):
        /// 声明区 / 调用区是**导图自己造的**分节,源码里一处都没有,明说一句免得当成真的语法结构。
        /// **H63-7 起这排小字只留在文件框的两个区框上**(用户口径「只留文件框的两个区框」)——
        /// 那句话是对"整张图"说的,在最外那一个框上说一遍就够了;方法 / 结构 / 流程块框的区框
        /// 再各写一遍只是重复占行(还占框高),所以按 `框.种类` 分档。
        /// </summary>
        private static 导图子项C 新区框(框来源C 框, string 全称, bool 是声明区, int 条数) => new()
        {
            键 = 区键(框, 是声明区),
            标题 = 是声明区 ? "声明区" : "调用区",
            说明 = $"{条数} 条",
            小字 = 框.种类 == 导图分区C.种类文件 ? "此为思维导图虚拟概念" : "",
            提示 = 是声明区
                ? "这个框自己声明的东西（点开；再点收起）"
                : "这个框里直接挂着的语句与流程块（点开；再点收起）",
            种类 = 导图种类C.区,
            文件 = 全称,
            声明边 = 是声明区,
            能往下长 = true,
            附加 = new 导图区C { 框 = 框, 是声明区 = 是声明区, 全称 = 全称 },
        };

        private static 导图子项C 说明项(string 文本) => new()
        {
            键 = "说明:" + 文本,
            标题 = 文本,
            种类 = 导图种类C.说明,
            能往下长 = false,
        };

        // ---------------- 回连线(H61-2:链节 → 声明区那一项) ----------------

        /// <summary>
        /// **H63-4:导图窗问"搜一个名字"** —— 用**现成的 `声明索引C`**(`取框树` 里那一步用的同一张索引,
        /// 里面还带着一次编译的 `名字表C` ⇒ 别的文件 / `包含` 进来的库里的声明也查得到),
        /// 再把声明行交给**同一个键路拼法** `声明键路(树, 名, 行)`(**不许另起一套** —— 施工图口径)。
        ///
        /// 三档:
        ///   ① **就在这一份文件里** ⇒ 给键路,窗口 `铺到` + 选中 + 滚过去;
        ///   ② **声明在别的文件**(跨文件 / 库)⇒ **换一扇窗**从那一份起,并把那一份里的键路当 `起路`
        ///      交给新窗(新窗 `Loaded` 那一下自己铺到 + 选中 —— 还是"一步铺过去并选中");
        ///   ③ **没有源码定义**(内建 / 关键字)/ **没这个名字** ⇒ 一句人话,**不硬铺**。
        /// </summary>
        private 搜索结果C 导图搜索(string 名字)
        {
            try
            {
                if (名字.Length == 0) return new 搜索结果C { 说明 = "先打个名字再按回车。" };
                string 根文件 = _导图根文件;
                if (根文件.Length == 0)
                    return new 搜索结果C
                    {
                        说明 = "这一扇窗是从工程根起的,不知道要在哪一份文件里找 —— 从某一份文件上重新开一张导图再搜。",
                    };
                if (取框树(根文件) is not { } 树)
                    return new 搜索结果C { 说明 = $"这一份读不出来,搜不了:{根文件}" };

                var 索引 = 声明线C.建(源码声明扫描C.扫结构(取文件文本(根文件), 根文件), 前端契约C.服务.编译.最近结果?.名字表);
                var 处 = 索引.查(名字, 0, 根文件);
                if (处 == null)
                    return new 搜索结果C
                    {
                        说明 = $"没找到「{名字}」:这一份文件里没有它,最近一次编译的名字表里也没有(检查一下拼写,或者先编一次)。",
                    };
                if (!处.是源码声明 || 处.行 <= 0)
                    return new 搜索结果C { 说明 = $"「{名字}」{处.说明}" };

                // ① 就在这一份文件里
                if (处.文件.Length == 0 || 前端契约C.服务.宿主.是同一个文件(处.文件, 根文件))
                {
                    var 路 = 声明键路(树, 处.名, 处.行);
                    return 路 == null
                        ? new 搜索结果C
                        {
                            说明 = $"「{名字}」声明在第 {处.行} 行,但这棵树里没找到对应的那一格(它可能在流程块 / 容器里 —— 先把那一段展开再搜)。",
                        }
                        : new 搜索结果C { 键路 = 路, 说明 = $"已铺到「{名字}」(第 {处.行} 行声明)并选中。" };
                }

                // ② 声明在别的文件:换一扇窗从那一份起(还是"一步铺过去并选中")
                if (取框树(处.文件) is not { } 别树)
                    return new 搜索结果C { 说明 = $"「{名字}」声明在 {处.文件},但那一份读不出来,钻不过去。" };
                var 别路 = 声明键路(别树, 处.名, 处.行);
                if (别路 == null)
                    return new 搜索结果C
                    {
                        说明 = $"「{名字}」声明在 {Path.GetFileName(处.文件)} 第 {处.行} 行,但那一份里没找到对应的那一格。",
                    };
                打开思维导图(文件根(取文件项(处.文件)), 别路);
                return new 搜索结果C
                {
                    另开文件 = 处.文件,
                    说明 = $"「{名字}」声明在 {Path.GetFileName(处.文件)} 第 {处.行} 行 —— 已经换了一张图从那一份文件起,并铺到它。",
                };
            }
            catch (编译异常C 错)
            {
                // T3:嵌套太深 / 别的"说人话的编译错误"——给中文那一份(英文夹在 Message 里是给日志看的)
                异常收集C.记($"思维导图搜索失败:{错.Message}");
                return new 搜索结果C { 说明 = $"搜索失败:{错.中文}" };
            }
            catch (Exception 异常)
            {
                异常收集C.记($"思维导图搜索失败:{异常.Message}");
                return new 搜索结果C { 说明 = $"搜索失败:{异常.Message}" };
            }
        }

        /// <summary>
        /// **H63-5:谁调用了这个方法**(方法框右键「看谁调用它」;交给窗口的 `调用者委托`)。
        ///
        /// 数据源是**还在仓库里**的 `调用关系扫描C`(`调用关系表C` / `调用边C`;H60-15 删的是右侧那块老面板,
        /// 不是这个扫描器 —— `未使用扫描` / `转到定义` 还在用它)。**口径要写清**(施工图点名):
        /// 它答的是**整个工程**(含 `包含` 进来的库文件),不是导图"本文件那棵树";
        /// 而且只有**真发 `CALL`** 的才算边 —— `测试输出(数字)` 这类原地展开的写法在源码里写了也不会出现,
        /// 所以"没查到"是**如实**的结论,不是这句代码坏了。
        ///
        /// 三件事:① 从这一份的**声明索引**里拿这个方法的**函数定义名**(调用边表的键是它,例如 `排序.整数升序`);
        /// ② `调用关系表C.谁调用了(定义名)` 拿入边;③ 每条摊成一个子项(**标题 = 文件:行**,双击跳那一行;
        /// 行号不可考的(库行 / 生成代码)照实说,不给假行号)。
        /// </summary>
        private 调用者结果C 导图调用者(导图节点C 节)
        {
            try
            {
                if (节.附加 is not 框来源C { 种类: 导图分区C.种类方法 } 框)
                    return new 调用者结果C { 说明 = "「看谁调用它」是给**方法框**用的(点一个方法框,再右键)。" };
                if (前端契约C.服务.编译.最近结果 == null)
                    return new 调用者结果C { 说明 = "还没编译过 —— 调用边是编译的时候扫出来的,先编一次(或者按 F5)再来问。" };

                string 文件 = 节.文件;
                string 定义名 = 框.标题;
                if (前端契约C.服务.编译.最近结果.名字表 is { } 名单)
                {
                    // 导图框上写的是**尾名**(`路径拼接`),调用边表里的键是**函数定义名**(`目录.路径拼接`,带模块前缀;
                    // 模块那一层是编译期的东西,导图不知道它)⇒ 从 `名字表C.函数范围` 里按"尾名对得上"挑出那个全名:
                    // 优先"同一份文件 + 头行也相同",其次同一份文件,再其次同名别处;挑不到就用尾名本身。
                    string? 同名同份同行 = null, 同名同份 = null, 同名别处 = null;
                    foreach (var (函数, 起, 止, 文) in 名单.函数范围)
                    {
                        if (!string.Equals(源码声明扫描C.尾名(函数), 框.标题, StringComparison.OrdinalIgnoreCase)) continue;
                        bool 同份 = 文件.Length == 0 || 文.Length == 0 || 前端契约C.服务.宿主.是同一个文件(文, 文件);
                        if (同份 && 起 == 框.行) { 同名同份同行 = 函数; break; }
                        if (同份) 同名同份 ??= 函数;
                        else 同名别处 ??= 函数;
                    }
                    定义名 = 同名同份同行 ?? 同名同份 ?? 同名别处 ?? 框.标题;
                }

                var 结果 = new 调用者结果C();
                var 表 = 调用关系扫描C.扫描(前端契约C.服务.编译.最近结果);
                var 见到 = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                // 两个名字都问一遍(边表里有的用全名、有的用尾名),同一条(文件 + 行 + 调用者)只留一条
                foreach (var 名 in new[] { 定义名, 框.标题 })
                    foreach (var 边 in 表.谁调用了(名))
                    {
                        if (!见到.Add($"{边.调用点文件}@{边.调用点行}:{边.调用者}")) continue;
                        结果.项们.Add(新调用者项(边, 文件));
                    }
                结果.说明 = 结果.项们.Count > 0
                    ? $"「{定义名}」有 {结果.项们.Count} 处调用(整个工程,含 `包含` 进来的库)—— 双击一条跳到那一行。"
                    : $"没查到谁调用「{定义名}」。这张表是**整个工程**扫出来的,而且只有真发 `CALL` 的才算 —— "
                        + "原地展开的写法(例如 `测试输出(…)`)本来就不在表里,所以这一句是如实说的,不是坏了。";
                return 结果;
            }
            catch (Exception 异常)
            {
                异常收集C.记($"思维导图查调用者失败:{异常.Message}");
                return new 调用者结果C { 说明 = $"查调用者失败:{异常.Message}" };
            }
        }

        /// <summary>
        /// 一个调用点 → 一个子项(**标题 = `文件:行`**,说明里写"谁调的";行号不可考的照实写)。
        /// `文件` 那一格给**能打开的全路径**(见 `解析调用点文件`),双击才跳得动。
        /// </summary>
        private 导图子项C 新调用者项(调用边C 边, string 根文件) => new()
        {
            键 = $"调用者:{边.调用点文件}@{边.调用点行}:{边.调用者}",
            标题 = 边.位置显示,
            说明 = $"{边.调用者显示} 调用了它（{边.种类名}{(边.备注.Length > 0 ? ":" + 边.备注 : "")}）",
            种类 = "调用者",
            行 = 边.调用点行,
            文件 = 解析调用点文件(边.调用点文件, 根文件),
            悬停 = 边.调用点文件,
            能往下长 = false,
        };

        /// <summary>
        /// 调用边里那个"文件"→ **能打开的全路径**(跳转那一层要 `File.Exists` 才认)。
        /// 三步:① 本身就是全路径就用它;② 按**这一扇图的根文件所在目录**拼一次(工程文件表里的名字多是相对的);
        /// ③ 拿**同一个工程的文件表**按 `文件判定C` 对一次。都对不上就原样返回 ——
        /// 跳转那一层会如实说"找不到这份文件",不编一个假路径。
        /// </summary>
        private string 解析调用点文件(string 名, string 根文件)
        {
            if (名.Length == 0) return "";
            try
            {
                if (File.Exists(名)) return 名;
                string 目录 = Path.GetDirectoryName(根文件) ?? "";
                if (目录.Length > 0)
                {
                    string 试 = Path.Combine(目录, 名);
                    if (File.Exists(试)) return 试;
                }
                var 项目 = 解决方案?.找所属项目(根文件);
                if (项目 != null)
                    foreach (var 文 in 项目.文件)
                        if (前端契约C.服务.宿主.是同一个文件(文.全称, 名)
                            || string.Equals(Path.GetFileName(文.全称), Path.GetFileName(名), StringComparison.OrdinalIgnoreCase))
                            return 文.全称;
            }
            catch { /* 解析不了就原样返回,跳转那一层会说人话 */ }
            return 名;
        }

        /// <summary>
        /// **这个框展开之后要不要拉一条红色回连线**(H61-2;交给窗口的 `回连委托`)。
        /// 口径 ⑤:「假如是本文件的方法,就用**红色线回连**到声明区的相关处……**变量的调用亦同**」。
        ///
        /// 给的是一条**从文件框走到那一格**的节点键路(见 `声明键路`),窗口拿 `导图模型C.铺到`
        /// 把目标那一枝自动展开、再记一条线。**跨文件 / 内建 / 认不出**一律给 null ——
        /// 那种继续走"声明处"小节点(没有源码定义就如实说一句,不硬画一条假线)。
        /// </summary>
        private IReadOnlyList<string>? 导图回连(导图节点C 节)
        {
            try
            {
                if (节.附加 is not 调用链节C 链) return null;
                if (链.声明 is not { } 处 || !同文件声明(处, 节.文件)) return null;
                if (取框树(节.文件) is not { } 树) return null;
                return 声明键路(树, 处.名, 处.行);
            }
            catch (Exception 异常)
            {
                异常收集C.记($"思维导图算回连线失败:{异常.Message}");
                return null;
            }
        }

        /// <summary>
        /// **一条声明项对应的节点键路**(H61-2 施工图 ③"先在框树里按'名字 + 行'找到那一条声明项")。
        /// 路 = **框树上从文件框到那一格**的每一级节点键(键怎么拼就照 `长框` / `新区框` / `新项` 那一套,
        /// 不许另起一套口径):文件框 →(一路上每一级的「区」框 + 框)→ 声明区那一项。
        /// 找不到给 null(不硬猜)。
        /// </summary>
        private static List<string>? 声明键路(框来源C 树, string 名, int 行)
        {
            if (树 == null || 名.Length == 0 || 行 <= 0) return null;
            if (找声明宿主(树, 名, 行) is not { } 宿主) return null;
            var 项 = 宿主.声明区.FirstOrDefault(x => x.行 == 行 && 同名(x.名, 名));
            if (项 == null) return null;

            var 路 = new List<string> { 树.键 };
            if (!找框路(树, 宿主, 路)) return null;
            路.Add(区键(宿主, 是声明区: true));
            // 声明区里那一条如果被换成了"框"(结构 / 方法 / 结构方法,见 `声明区子项`),目标就是那个框
            路.Add(找对应子框(宿主, 项) is { } 子框 ? 子框.键 : 项.键);
            return 路;
        }

        /// <summary> 这一条声明挂在**哪个框**的声明区里(自己先找,再往子框里递归;找不到给 null)</summary>
        private static 框来源C? 找声明宿主(框来源C 框, string 名, int 行)
        {
            foreach (var 项 in 框.声明区)
                if (项.行 == 行 && 同名(项.名, 名)) return 框;
            foreach (var 子 in 框.子框们)
                if (找声明宿主(子, 名, 行) is { } 中) return 中;
            return null;
        }

        /// <summary>
        /// 从当前框走到目标框的**键路**(每一级 = 一个「区」键 + 一个框键):
        /// 结构 / 方法那一族登记在**声明区**,流程块登记在**调用区**(与 `声明区子项` / `调用区子项` 同一套口径)。
        /// 走不通把这一级还原、给假。
        /// </summary>
        private static bool 找框路(框来源C 当前, 框来源C 目标, List<string> 路)
        {
            if (ReferenceEquals(当前, 目标)) return true;
            foreach (var 子 in 当前.子框们)
            {
                路.Add(区键(当前, 子.种类 != 导图分区C.种类流程块));
                路.Add(子.键);
                if (找框路(子, 目标, 路)) return true;
                路.RemoveRange(路.Count - 2, 2);
            }
            return false;
        }

        /// <summary> 一个「区」框的节点键(**唯一一处**拼法:`新区框` 与 `声明键路` 都走它,不许再抄一遍)</summary>
        private static string 区键(框来源C 框, bool 是声明区) => (是声明区 ? "区:声明@" : "区:调用@") + 框.键;

        /// <summary> 名字对得上吗(源码里的名字不分大小写;与 `声明索引C` 同一套认法)</summary>
        private static bool 同名(string 左, string 右) => string.Equals(左, 右, StringComparison.OrdinalIgnoreCase);

        // ---------------- 双击跳转(H60-14) ----------------

        /// <summary>
        /// 双击一个框 = **打开那一份文件并把光标落到那一行**(用户新增口径 ⑥;施工图 ④)。
        /// 走的是主窗现成那两条路:**`打开文件到标签页`**(没开着就先开)+ **`打开文件并跳到`**(切过去 + 定位光标)。
        /// 为什么中间要 `代码选卡.UpdateLayout()`:标签页的容器是**布局之后**才生成的,不刷一下
        /// `全部编辑器带页()` 就还看不见那个编辑器,跳转会静默落空(那就不是"说人话"了)。
        ///
        /// **H61-3**:这一处开出来的是**预览(临时)页**(`临时: true`)—— 用户原话「可以学 vs 的临时打开文件的方法」。
        /// 于是:同一时刻只留一个预览页(再跳别的就把它顶掉)、页头标题斜体、**再双击同一格 = 固定成普通页**
        /// (那一下由 `打开文件到标签页` 里"命中就是临时页 ⇒ 改回普通页"接住);改一下也会自动固定。
        /// 别的入口(项目树 / 打开文件 / 新建…)照旧开普通页。
        /// **返回空串 = 跳成了**;否则返回一句给人看的人话,由窗口写进 `状态行` —— 不许静默。
        /// </summary>
        private string 导图跳到(string 全称, int 行)
        {
            try
            {
                if (行 <= 0) return "这一项没有可跳的源码位置(它没有源码定义)。";
                if (全称.Length == 0) return "这一项没带文件名,跳不了。";
                if (!File.Exists(全称)) return $"找不到这份文件:{全称}";
                打开文件到标签页(全称, 临时: true);
                代码选卡.UpdateLayout();
                if (!全部编辑器带页().Any(x => 前端契约C.服务.宿主.是同一个文件(x.页.全称 ?? "", 全称)))
                    return $"打不开这一份文件(它不在打开列表里):{全称}";
                打开文件并跳到(全称, 行);
                return "";
            }
            catch (Exception 异常) { return $"跳转失败:{异常.Message}"; }
        }

        // ---------------- 小工具 ----------------

        /// <summary> 文本优先取**编辑器里那一份**(改过没保存也算),没有就现读盘 </summary>
        private string 取文件文本(string 全称)
        {
            try
            {
                foreach (var (编, 页) in 全部编辑器带页())
                    if (前端契约C.服务.宿主.是同一个文件(页.全称 ?? "", 全称)) return 编.获取代码();
            }
            catch { /* 标签页没造出来就走读盘那条 */ }
            try { return File.Exists(全称) ? File.ReadAllText(全称) : ""; } catch { return ""; }
        }
    }
