        private static T? 找视觉祖先<T>(DependencyObject? 起) where T : DependencyObject
        {
            for (var 节 = 起; 节 != null; 节 = VisualTreeHelper.GetParent(节))
                if (节 is T 命中) return 命中;
            return null;
        }

