            }
            catch (Exception 异常) { 记异常框($"从编辑器打开思维导图失败: {异常.Message}"); }
        }

        /// <summary> 框树里**正好落在这一行**的那条语句(递归找;连它挂在哪一层一起给回来) </summary>
        private static (框来源C? 宿主, 分区项C? 项) 找语句项(框来源C 框, int 行)
        {
            foreach (var 项 in 框.调用区)
                if (项.种类 == "语句" && 项.行 == 行) return (框, 项);
            foreach (var 子 in 框.子框们)
            {
                var (宿主, 项) = 找语句项(子, 行);
                if (项 != null) return (宿主, 项);
            }
            return (null, null);
        }

