// ============================================================
// 综合自检C.同名实参.cs —— R4-11:**F-6 的钉子**
//
//   盯的是这条**静默致错**的缺陷(比崩溃坏得多:程序照跑、编译器不报错,只是数变成 0):
//
//     **顶层变量与"库模块变量"同名时,把它当实参传进库函数,函数里收到的是 0。**
//
//   最小复现(`工具\临时\批22\同名实参探针\主程序.hb`):
//     `三维网格.hb` 这个模块里有 `顶点数`;调用方在顶层也写一个 `整数 顶点数 = 4;`
//     ⇒ 顶层打印是 4,但 `三维网格.装顶点(块, 顶点数)` 里面收到的 `几颗` 是 **0**,
//       于是一颗都装不进去 —— **编译器不报错、不警告**。
//
//   这一组**现在应当红**(缺陷还没修)。钉子的用意:
//   ① 把"缺陷还在"这件事钉成机械判据,别靠谁记得;
//   ② 缺陷修好的那一天,这一组自动变绿 —— 那时把它改成"必须装进去"的正面判据。
// ============================================================
using System;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 同名实参自检()
        {
            // ⚠ 判据写死成"**当前**的表现 = 装进去 0 颗",而不是"应当装进去 4 颗" ——
            //   因为缺陷还没修。这样:
            //     · 缺陷还在 ⇒ 这一组绿(它如实描述了现状);
            //     · 有人**修好了**它 ⇒ 这一组变红,提醒"该把判据改成正面判据了"。
            //   这是有意为之:一条已知缺陷最怕的就是"没人知道它还在不在"。
            const string 源 =
                "模块 库\n" +
                "整数 数 = 1;\n" +
                "方法 加(整数 几) 返回 整数\n" +
                "{\n" +
                "    整数 i = 0;\n" +
                "    当 (i < 几 && 数 < 100)\n" +
                "    {\n" +
                "        数 = 数 + 1;\n" +
                "        i = i + 1;\n" +
                "    }\n" +
                "    返回 i;\n" +
                "}\n" +
                "整数 数 = 50;\n" +                 // 顶层同名 —— 缺陷就在这个组合上
                "输出行(库.加(3));\n" +             // 传的是字面量:正常
                "输出行(数);\n" +
                "停止\n";

            // ⚠ 这一组的要点在于**编译器收不收它**:实测"顶层与同文件 `模块` 同名"会被编译器挡住
            //   (`变量 '记录.数' 在本作用域重复声明`)⇒ 这条缺陷**只在"库(通过 `包含` 进来的模块)
            //   变量 vs 顶层变量"**这个组合上露出来。所以下面两个判据分开记:
            //   ① 同文件模块同名:编译器**必须报错**(挡住是好事);
            //   ② 库模块同名:编译器**不报错**、值静默变 0(缺陷本体,记在 §30 第7节)。
            bool 挡住了;
            string 说明;
            try
            {
                new 汇编器C().汇编多文件带调试([("主程序.hb", 源)], 优化: true);
                挡住了 = false;
                说明 = "编译器收下了(期望它挡住)";
            }
            catch (Exception 错)
            {
                挡住了 = true;
                说明 = "编译器挡住了:" + 截断(错.Message, 90);
            }
            记录("同名实参 同文件模块与顶层同名:编译器必须当场报错(挡住是好事)", 挡住了, 说明);

            // ② 库模块同名这一档:**现在**应当是"不报错"——它正是缺陷的入口。
            //    判据写成"不报错 = 缺陷的门还开着";哪天编译器把这一档也挡了,这条会红,提醒改判据。
            const string 库源 =
                "包含 \"E:/Codes/CSharp/hehshihbeen-compiler/Sample/库/三维数学.hb\"\n" +
                "包含 \"E:/Codes/CSharp/hehshihbeen-compiler/Sample/库/三维网格.hb\"\n" +
                "整数 顶点数 = 4;\n" +
                "输出行(顶点数);\n" +
                "停止\n";
            bool 库挡了 = false;
            string 库说明;
            try
            {
                new 汇编器C().汇编多文件带调试([("主程序.hb", 库源)], 优化: true);
                库说明 = "编译器收下了(缺陷的门开着:这类同名不会被发现)";
            }
            catch (Exception 错)
            {
                库挡了 = true;
                库说明 = "编译器挡住了:" + 截断(错.Message, 90);
            }
            记录("同名实参 库模块与顶层同名:编译器**目前不报错**(缺陷的门开着,见 §30 第7节)",
                !库挡了, 库说明 + " —— ⚠ 这一条**绿**表示缺陷还在;哪天它红了,说明编译器开始挡这一类,"
                + "那时把 `未做任务清单.md` §30 第7节 改成已修,并把这一条判据翻过来");
        }
    }
}
