using System;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 综合自检的一部分:**ISA 指令内建**(2026-10-13;ISA 扩容 99 条里"库作者写不了内联汇编"那一档)。
    /// <para>
    /// 一条指令要么"在 ISA 里",要么"真有人用得上" —— 这一组管后者:14 个内建名的**接线**
    /// (内建函数名表 + 说明表)、**真读数**(真编真跑逐条对)、**闸**(参数个数 / 常量档),
    /// 以及三条**形状识别**(循环移位 / 字节交换 / 条件移动 + 半字字节索引)真的落到指令上了。
    /// </para>
    /// </summary>
    public static partial class 综合自检C
    {
        private static void 指令内建自检()
        {
            // ---------- ① 接线哨兵:14 个名字都进了内建函数名表(中英)+ 都有说明 ----------
            (string 中, string 英)[] 该有 =
            [
                ("取较大", "maxof"), ("取较小", "minof"), ("向下取整", "rounddown"), ("搬符号", "copysign"),
                ("数一位", "popcount"), ("前导零", "leadingzeros"), ("尾随零", "trailingzeros"),
                ("循环左移", "rotateleft"), ("循环右移", "rotateright"), ("字节交换", "swapbytes"),
                ("取字节", "extractbyte"), ("取整数绝对值", "absint"), ("双字乘高", "mulhigh"), ("双字乘加", "muladdhigh"),
            ];
            var 缺名 = 该有.Where(对 => !中间层指令C.内建函数名表.Any(x => x.中文 == 对.中 && x.英文 == 对.英)).ToList();
            var 缺说明 = 该有.Where(对 => string.IsNullOrWhiteSpace(中间层指令C.取说明(对.英))).ToList();
            记录("指令内建 14 个名字都进了内建函数名表(中英)+ 说明表(高亮/补全/帮助/中英切换自动跟上)",
                缺名.Count == 0 && 缺说明.Count == 0,
                $"共 {该有.Length} 条;缺登记 {缺名.Count} / 缺说明 {缺说明.Count}");

            // ---------- ② 行为断言:14 条真编真跑,读数逐条对 ----------
            const string 十四 = "无符号整数 满 = 4294967295;\n" +
                "测试输出(取字节(满, 3));\n" +          // 255
                "测试输出(取字节(满, 0));\n" +          // 255
                "测试输出(数一位(满));\n" +             // 32
                "测试输出(前导零(0));\n" +              // 32
                "测试输出(尾随零(8));\n" +              // 3
                "测试输出(字节交换(305419896));\n" +     // 2018915346(0x78563412)
                "测试输出(循环左移(305419896, 8));\n" +  // 878082066(0x34567812)
                "测试输出(循环右移(305419896, 8));\n" +  // 2014458966(0x78123456)
                "测试输出(取整数绝对值(0 - 7));\n" +     // 7
                "测试输出(双字乘高(满, 满));\n" +        // 4294967294(0xFFFFFFFE)
                "测试输出(双字乘加(满, 满));\n" +        // 4294967295
                "浮点 甲 = 2.5;\n浮点 乙 = 0.0 - 1.5;\n" +
                "输出行(取较大(甲, 乙));\n" +            // 2.5
                "输出行(取较小(甲, 乙));\n" +            // -1.5
                "输出行(向下取整(乙));\n" +              // -2
                "输出行(搬符号(甲, 乙));\n" +            // -2.5
                "停止";
            const string 期望 = "255\n255\n32\n32\n3\n2018915346\n878082066\n2014458966\n7\n4294967294\n4294967295\n" +
                "2.5\n-1.5\n-2\n-2.5";
            记录("指令内建 14 条真编真跑、读数逐条对(含浮点按浮点打印)",
                输出文本(十四) == 期望, 输出文本(十四).Replace("\n", "|"));
            记录("指令内建 优化开/关读数一致",
                输出文本(十四, 优化: true) == 输出文本(十四, 优化: false),
                $"开={输出文本(十四, 优化: true).Replace("\n", "|")}");

            // ---------- ③ 中英两侧都认(英文别名是真能编的那一半) ----------
            const string 英文 = "浮点 a = maxof(2.5, 1.5);\n浮点 b = rounddown(a);\n输出行(b);\n停止";
            记录("指令内建 英文别名能编(中英切换之后 `maxof` / `rounddown` 照旧是它)",
                输出文本(英文) == "2", 输出文本(英文).Replace("\n", "|"));

            // ---------- ④ 闸:参数个数 / `取字节` 的常量档(报错要能指导改法) ----------
            期望异常("指令内建 参数个数不对 → 说清要几个 + 给写法",
                () => 汇编("无符号整数 v = 7;\n整数 b = 取整数绝对值(v, 3);\n停止"), "要 1 个参数", "取整数绝对值(值)");
            期望异常("指令内建 取字节 的第二个参数只认 0~3 的常量",
                () => 汇编("无符号整数 v = 7;\n整数 i = 1;\n整数 b = 取字节(v, i);\n停止"), "0~3 的常量", "& 255");
            期望异常("指令内建 取字节(值, 4) 也拦下(越界常量)",
                () => 汇编("无符号整数 v = 7;\n整数 b = 取字节(v, 4);\n停止"), "0~3 的常量");

            // ---------- ⑤ 形状识别:三条式子真的落到指令上 ----------
            string 统计 = 中间层C.展开("无符号整数 v = 7;\n整数 a = 数一位(v);\n整数 b = 前导零(v);\n整数 c = 尾随零(v);\n停止");
            记录("指令内建 数一位/前导零/尾随零 各发一条指令(不再是 32 轮循环)",
                统计.Contains("数一位 R") && 统计.Contains("前导零 R") && 统计.Contains("尾随零 R"),
                "展开里三条都在");

            string 变量移位 =
                "方法 转(无符号整数 值, 整数 位数) 返回 无符号整数\n{\n    返回 (值 << 位数) | (值 >> (32 - 位数));\n}\n" +
                "测试输出(转(305419896, 8));\n停止";
            记录("形状识别 变量移位量的循环移位 → 一条 `循环左移`(库 `位.hb` 那三条靠这一档)",
                中间层C.展开(变量移位).Contains("循环左移 R") && 输出文本(变量移位) == "878082066",
                输出文本(变量移位).Replace("\n", "|"));

            string 四段 =
                "方法 换(无符号整数 值) 返回 无符号整数\n{\n    返回 ((值 & 255) << 24) | ((值 & 65280) << 8) | ((值 & 16711680) >> 8) | (值 >> 24);\n}\n" +
                "测试输出(换(305419896));\n停止";
            记录("形状识别 四段字节搬运 → 一条 `字节交换`(目标字节 0/1/2/3 各一次)",
                中间层C.展开(四段).Contains("字节交换 R") && 输出文本(四段) == "2018915346",
                输出文本(四段).Replace("\n", "|"));

            string 有符号四段 =
                "方法 换(整数 值) 返回 整数\n{\n    返回 ((值 & 255) << 24) | ((值 & 65280) << 8) | ((值 & 16711680) >> 8) | (值 >> 24);\n}\n" +
                "测试输出(换(0 - 2));\n停止";
            记录("形状识别 有符号值**不认**字节交换(它的 `>>` 是算术右移,认了就是改语义)",
                !中间层C.展开(有符号四段).Contains("字节交换 R"), "退回老路(移位 + 掩码)");

            string 条件移动 = "整数 左 = 5;\n整数 右 = 9;\n整数 大 = (左 > 右) ? 左 : 右;\n测试输出(大);\n停止";
            记录("形状识别 `左 关系 右 ? 左 : 右` → 一条 `条件移动`(最大/最小那一族)",
                中间层C.展开(条件移动).Contains("条件移动") && 输出文本(条件移动) == "9",
                输出文本(条件移动).Replace("\n", "|"));

            string 真值跳转 = "整数 左 = 5;\n整数 右 = 9;\n如果 (左 >= 右 || 左 < 0)\n{\n    测试输出(1);\n}\n停止";
            记录("条件跳转 `>=` 走一条 `大于等于跳转`(`||` 左边那一步要“成立就跳”)",
                中间层C.展开(真值跳转).Contains("JGE"), "展开里能看到 JGE");

            string 短写 = "短整数 表[4];\n整数 i = 2;\n表[i] = 7;\n测试输出(表[i]);\n停止";
            记录("短类型数组 2 字节元素读/写走 `取半字索引` / `存半字索引`(0x54 / 0x55)",
                中间层C.展开(短写).Contains("存半字索引") && 中间层C.展开(短写).Contains("取半字索引")
                && 输出文本(短写) == "7", 输出文本(短写).Replace("\n", "|"));

            string 字写 = "字符 表[4];\n整数 i = 2;\n表[i] = 'A';\n测试输出(表[i]);\n停止";
            记录("字符数组写走 `存字节索引`(0x56)",
                中间层C.展开(字写).Contains("存字节索引"), "展开里能看到 存字节索引");

            // 1 字节元素**读**没有"按宽索引读"那一档(老路是按字节读),所以它的元素地址走 `链元素地址`
            // —— 正好是 `取地址索引`(0x53)那条路;写那一侧现在由 `存字节索引`(0x56)一条带过。
            string 取址 = "字节 表[4];\n整数 i = 1;\n表[i] = 7;\n测试输出(表[i]);\n停止";
            记录("1 字节元素取址走 `取地址索引`(0x53;缩放 + 相加并成一条)",
                中间层C.展开(取址).Contains("取地址索引") && 输出文本(取址) == "7",
                输出文本(取址).Replace("\n", "|"));

            // ---------- ⑥ 三条"以前没人验过"的指令(台账 §6.9 那条缺口的收口) ----------
            //   `尾调用跳转`(0x5E)/ `带弹栈返回`(0x61)/ `取返回地址`(0x62)以前只靠全量自检与 C 后端对拍顶着,
            //   没有一条断言直接盯着它们。这三条都真编真跑、读数逐条对(内联汇编直接写指令)。
            const string 尾跳 =
                "方法 尾() 返回 整数\n{\n    加载立即数 R0 7\n    尾调用跳转 _尾目标\n" +
                "    加载立即数 R0 99\n    _尾目标:\n    返回 7;\n}\n测试输出(尾());\n停止";
            记录("尾调用跳转 只改 PC、一个字节的栈都不动(跳过去那一支的返回值照旧回到调用方)",
                输出文本(尾跳) == "7", 输出文本(尾跳).Replace("\n", "|"));

            const string 弹栈 =
                "方法 弹() 返回 整数\n{\n    加载立即数 R0 5\n    加载立即数 R1 1\n    入栈 R1\n" +
                "    带弹栈返回 R3 4\n    返回 5;\n}\n测试输出(弹());\n停止";
            记录("带弹栈返回 先把立即数那些字节从栈上放掉、再返回(顺序错了就回不到调用方)",
                输出文本(弹栈) == "5", 输出文本(弹栈).Replace("\n", "|"));

            // 取返回地址:把读到的值与 0 比,靠跳转决定返回哪个**常量** ——
            // 寄存器不能当语言表达式的值,所以"读寄存器 → 影响语言层"只能走这一条(分支)路。
            const string 读返回址 =
                "方法 取回() 返回 整数\n{\n    取返回地址 R1\n    加载立即数 R2 0\n    比较 R1 R2\n" +
                "    JEQ _是零\n    返回 1;\n    _是零:\n    返回 0;\n}\n测试输出(取回());\n停止";
            记录("取返回地址 读的是真返回地址(不是 0;非 0 就走 `返回 1` 那一支)",
                输出文本(读返回址) == "1", 输出文本(读返回址).Replace("\n", "|"));
        }
    }
}
