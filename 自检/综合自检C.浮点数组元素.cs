// R4-41(2026-10-10 收口):**浮点数组元素 / 浮点字段直接进表达式**
//
//   这一条是**编译器 / 中间层**的缺陷自检(不在任何库里),所以单列一组,名字走 `浮点数组元素`。
//   它是 R4-38 / R4-39 / R4-40 三班查到最后那个"最小复现"钉成的四条钉子 ——
//   **与 3D 无关,是纯语言缺陷**。
//
//   ── 缺陷长什么样(修前实测,探针 `工具\临时\r49\探针\顶层读.hb`)──
//     浮点 表[8];  表[3] = 0.923880;
//     输出行(整数(浮点(表[3]) * 1000.0));      // 修前 -2147483648(应为 923)
//     输出行(整数(表[3] * 1000.0));             // 修前 -2147483648(应为 923)
//     输出行(整数(表[3] * 1.0));                // 修前 1064076160(位模式当整数乘,应为 0)
//     浮点 y = 表[3]; 输出行(整数(y * 1000.0)); // 修前 923 ✅ —— **先落变量这一档一直是好的**
//   ⇒ 也就是说:**"浮点数组的元素直接进表达式"** 这一档,元素被判成了**整数**。
//
//   ── 根因(修的是语言层,不是库)──
//     `_变量类型` 登记的是**变量的声明类型**(键就是变量名):`是浮点变量("顶点x")` 真、
//     `是浮点变量("顶点x[下标]")` 假 ⇒ 元素在类型推断里一律算整数。修了三处:
//     ① `中间层C.串写入.cs` 的 `是浮点变量` 加一档 `是浮点标量引用`(元素 / 字段,判据 = 链 + 根变量类型);
//     ② `中间层C.引用链.cs` 的 `链是浮点标量`(手上已有链时用) + 链上新记 `末字段类型名`
//        (字段自己的类型在走完字段之后会被清掉,见那里的注释);
//     ③ `中间层C.表达式.cs` 的取名那一步(静态位置)与 `地址位置.是浮点`(结构字段 / 常量下标元素走的是它)。
//
//   ── 为什么它能藏这么久 ──
//     `示例56` 那条**线框**路一直是好的 —— 线框**不读法线**,这个缺陷**只在"加法线"时才暴露**:
//     库 `三维网格.着算亮度()` 里 `浮点 ux = 顶点x[填_v2] - 顶点x[填_v1];` 把两个位模式当整数相减
//     ⇒ 法线 NaN ⇒ 亮度溢出哨兵 `-2147483648` ⇒ **颜色塌成一个**。
//
//   ★ 这一组钉四件事(四条钉子)+ 一条接线哨兵:
//     ① **顶层**:浮点数组元素直接进表达式(乘 / 减 / 加,含显式 `浮点(...)` 那一档);
//     ② **库模块里**:同一个数组在**库函数**里读(元素直接相减 / 先落变量相减 / 元素乘 1.0)—— R4-39 的原现场;
//     ③ **不许串味**:整数数组元素、结构浮点字段、`== 小数`、直接 `输出行(浮点值)` 一起量;
//     ④ **几何硬算**(与 3D 无关):3-4-5 直角三角形的三条判据,全用"元素直接进表达式"写;
//     ⑤ **接线哨兵**:上面那三处判据还在源码里(只钉"还在不在",不许单独当正确性证据)。
//
//   ★ **这条自检为什么能钉住它**:修前 ①②③④ 全红(实测量过 —— 顶层那份打 `-2147483648`),
//     修后全绿;优化开 / 关两档都要一起跑(与 H71 同一条尺子:只跑默认档会漏掉"关掉优化才现形"的形状)。
