    public static partial class 综合自检C
    {
        private static void 浮点数组元素自检()
        {
            string? 仓库根 = 找仓库根目录();
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");

            // 真编真跑一趟(输出按 UTF-8 收、行尾换成 `|` —— 与位与数学库 / H71 那两组同一套跑法)
            static string 跑(string 源, bool 优化)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, 优化,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 说明(string 期望, string 实得)
                => 期望 == 实得 ? "一字不差" : $"期望 [{期望}] / 实得 [{实得}]";

            // 一条钉子:优化开 / 关两档都要与期望逐字一致
            void 钉子(string 名称, string 源, string 期望)
            {
                try
                {
                    string 开 = 跑(源, true), 关 = 跑(源, false);
                    bool 好 = 开 == 期望 && 关 == 期望;
                    记录(名称, 好,
                        $"优化开 [{开}] / 优化关 [{关}];该是 [{期望}]" + (好 ? "" : " —— " + 说明(期望, 开)));
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            // ---- ① 顶层:元素直接进表达式(四种写法)----
            钉子("浮点数组元素 顶层:元素直接进表达式(直接乘 / 显式 浮点() / 先落变量 / 元素相减)",
                "浮点 表[8];\n" +
                "表[0] = 0.0;\n" +
                "表[3] = 0.923880;\n" +
                "表[4] = 0.224936;\n" +
                "输出行(整数(表[3] * 1000.0));\n" +                    // 直接乘
                "输出行(整数(浮点(表[3]) * 1000.0));\n" +              // 显式转换
                "浮点 取来 = 表[3];\n" +
                "输出行(整数(取来 * 1000.0));\n" +                     // 先落变量(修前也只有这条对)
                "输出行(整数((表[3] - 表[0]) * 1000.0));\n" +          // 两个元素相减
                "输出行(整数(表[3] - 表[0]));\n" +
                "输出行(整数(表[3] * 1.0));\n" +
                "输出行(整数(表[3] + 表[3]));\n" +
                "输出行(整数(表[4] * 1000.0));\n" +
                "停止\n",
                "923|923|923|923|0|0|1|224");

            // ---- ② 库模块里:同一个数组在库函数里读(R4-39 的原现场形状)----
            if (仓库根 == null)
            {
                跳过("浮点数组元素 库模块里:元素直接相减 / 先落变量相减 / 元素乘 1.0",
                    "找不到仓库根(读不到 Sample 目录)");
            }
            else
            {
                string 点子 = Path.Combine(库目录, "三维数学.hb").Replace('\\', '/');
                string 网格 = Path.Combine(库目录, "三维网格.hb").Replace('\\', '/');
                钉子("浮点数组元素 库模块里:元素直接相减 / 先落变量相减 / 元素乘 1.0(库函数里读同一个数组)",
                    "模块 库末\n" +
                    "\n" +
                    "浮点 点表[8];\n" +
                    "\n" +
                    "方法 装() 返回 整数\n" +
                    "{\n" +
                    "    点表[0] = 0.309597;\n" +
                    "    点表[3] = 0.923880;\n" +
                    "    点表[4] = 0.224936;\n" +
                    "    返回 0;\n" +
                    "}\n" +
                    "\n" +
                    "方法 差(整数 一, 整数 二) 返回 整数\n" +
                    "{\n" +
                    "    浮点 d = 点表[一] - 点表[二];\n" +                    // ← R4-39 现场那一句
                    "    返回 整数(d * 1000.0);\n" +
                    "}\n" +
                    "\n" +
                    "方法 差落变量(整数 一, 整数 二) 返回 整数\n" +
                    "{\n" +
                    "    浮点 x = 点表[一];\n" +
                    "    浮点 y = 点表[二];\n" +
                    "    浮点 d = x - y;\n" +
                    "    返回 整数(d * 1000.0);\n" +
                    "}\n" +
                    "\n" +
                    "方法 元素乘一(整数 i) 返回 整数\n" +
                    "{\n" +
                    "    返回 整数(点表[i] * 1.0);\n" +
                    "}\n" +
                    "\n" +
                    "方法 元素(整数 i) 返回 浮点\n" +
                    "{\n" +
                    "    浮点 t = 点表[i];\n" +
                    "    返回 t;\n" +
                    "}\n" +
                    "\n" +
                    "库末.装();\n" +
                    "输出行(库末.差(3, 0));\n" +
                    "输出行(库末.差落变量(3, 0));\n" +
                    "输出行(库末.元素乘一(3));\n" +
                    "输出行(库末.元素(3));\n" +                          // 位模式:1064076134 = 0.923880
                    "停止\n",
                    "614|614|0|1064076134");

                // ---- ⑤ 端到端:库里的 `着算亮度`(R4-38 现场)---- 见下面那条 ----
                string 覆盖源 = "包含 \"" + 点子 + "\"\n" +
                    "包含 \"" + 网格 + "\"\n" +
                    "三维网格.清空();\n" +
                    "三维网格.顶点x[0] = 0.300000;\n" +
                    "三维网格.顶点y[0] = 0.400000;\n" +
                    "三维网格.顶点x[1] = 0.800000;\n" +
                    "三维网格.顶点y[1] = 0.400000;\n" +
                    "输出行(三维网格.顶点x[0]);\n" +
                    "输出行(三维网格.顶点数);\n" +
                    "停止\n";
                try
                {
                    // 这一条只看"库装得进来 + 元素在库里读得对"(不投影、不开窗)
                    if (!File.Exists(点子) || !File.Exists(网格))
                        跳过("浮点数组元素 库端到端:三维网格 的顶点数组在库函数里读得对", $"找不到 {点子} / {网格}");
                    else
                    {
                        string 开 = 跑(覆盖源, true);
                        记录("浮点数组元素 库端到端:三维网格 的顶点数组在库函数里读得对(元素取出来还是浮点)",
                            开 == "0.3|0", 说明("0.3|0", 开));
                    }
                }
                catch (Exception ex) { 记录异常("浮点数组元素 库端到端:三维网格 的顶点数组在库函数里读得对", ex); }
            }

            // ---- ③ 不许串味:整数数组元素 / 结构浮点字段 / 比较 / 直接打印 ----
            钉子("浮点数组元素 不许串味:整数数组元素照旧是整数、结构浮点字段照旧是浮点(含直接打印)",
                "浮点 表[8];\n" +
                "表[3] = 0.750000;\n" +
                "整数 整表[8];\n" +
                "整表[3] = 923880;\n" +
                "结构 点型\n" +
                "{\n" +
                "    浮点 x;\n" +
                "    浮点 y;\n" +
                "}\n" +
                "点型 点;\n" +
                "点.x = 0.250000;\n" +
                "点.y = 0.500000;\n" +
                "输出行(整数(表[3] * 1000.0));\n" +                    // 750
                "输出行(整表[3]);\n" +                                 // 923880(整数元素不许被当成浮点)
                "输出行(整表[3] + 1);\n" +
                "输出行(整数(点.x * 1000.0));\n" +                     // 250(结构浮点字段)
                "输出行(表[3] == 0.75);\n" +                           // 1(比较结果是整数)
                "输出行(900000 + 整数((表[3] + 0.25) * 1000.0));\n" +   // 901000
                "输出行(整数((表[3] + 点.x) * 1000.0));\n" +            // 1000
                "输出行(表[3] + 0.25);\n" +                            // 1(浮点打印:小数末尾的 0 去掉)
                "停止\n",
                "750|923880|923881|250|1|901000|1000|1");

            钉子("浮点数组元素 结构参数里的浮点字段(结构参数是按地址传的,别在那儿又丢一次类型)",
                "结构 点型\n" +
                "{\n" +
                "    浮点 x;\n" +
                "    浮点 y;\n" +
                "}\n" +
                "点型 点;\n" +
                "点.x = 0.250000;\n" +
                "点.y = 0.500000;\n" +
                "方法 看字段(点型 点值) 返回 整数\n" +
                "{\n" +
                "    输出行(点值.x);\n" +
                "    输出行(点值.y);\n" +
                "    返回 整数(点值.x * 1000.0);\n" +
                "}\n" +
                "输出行(看字段(点));\n" +
                "停止\n",
                "0.25|0.5|250");

            // ---- ④ 几何硬算(与 3D 无关):直角三角形的三条判据 ----
            //   ⚠ 顶点**刻意挑"单精度能精确表示的二进制小数"**(0.3 / 0.4 / 0.5 / 1.0):
            //     这样判据是**精确的 0**,不用容忍浮点误差 —— 与 `三维数学.开方` 那条口径一致。
            //   ⚠ 判据用的是**同一个直角顶点出发的两条边**(这里 A(0,0) 是直角顶点:
            //     AB = (0.3,0.4) ⊥ AC = (0.4,−0.3),0.12 − 0.12 = 0 精确)。
            //     (写这一条时我第一版把"从原点出发的两条边"当成直角边,量出来点积 0.4 ——
            //      **是判据写错了,不是程序错了**;所以这里把三个点的角色写在注释里。)
            钉子("浮点数组元素 几何硬算:直角三角形的三条判据(直角边点积 = 0 / 两直角边平方和 = 斜边平方 / 三条边长)",
                "浮点 点x[3];\n" +
                "浮点 点y[3];\n" +
                "点x[0] = 0.0;\n" +              // A(0,0):直角顶点
                "点y[0] = 0.0;\n" +
                "点x[1] = 0.300000;\n" +         // B(0.3,0.4)
                "点y[1] = 0.400000;\n" +
                "点x[2] = 0.400000;\n" +         // C(0.4,−0.3)
                "点y[2] = 0.0 - 0.300000;\n" +
                "浮点 ab边x = 点x[1] - 点x[0];\n" +      // AB = (0.3, 0.4)  ⇒ 平方 0.25
                "浮点 ab边y = 点y[1] - 点y[0];\n" +
                "浮点 ac边x = 点x[2] - 点x[0];\n" +      // AC = (0.4,−0.3)  ⇒ 平方 0.25,与 AB 垂直
                "浮点 ac边y = 点y[2] - 点y[0];\n" +
                "浮点 bc边x = 点x[2] - 点x[1];\n" +      // BC = (0.1,−0.7)  ⇒ 平方 0.5
                "浮点 bc边y = 点y[2] - 点y[1];\n" +
                "浮点 ab边长 = ab边x * ab边x + ab边y * ab边y;\n" +   // 0.25
                "浮点 ac边长 = ac边x * ac边x + ac边y * ac边y;\n" +   // 0.25
                "浮点 斜方 = bc边x * bc边x + bc边y * bc边y;\n" +   // 0.5
                "浮点 点积 = ab边x * ac边x + ab边y * ac边y;\n" +   // 0(直角判据)
                "输出行(整数(ab边长 * 1000000.0));\n" +          // 250000
                "输出行(整数(ac边长 * 1000000.0));\n" +          // 250000
                "输出行(整数(斜方 * 1000000.0));\n" +          // 500000
                "输出行(整数((ab边长 + ac边长) * 1000000.0));\n" +  // 500000 = 斜方 ⇒ 勾股
                "输出行(整数((ab边长 + ac边长 - 斜方) * 1000000.0));\n" +   // 0
                "输出行(整数(点积 * 1000000.0));\n" +          // 0
                "输出行(整数(ab边x * 1000.0));\n" +            // 300
                "输出行(整数(ab边y * 1000.0));\n" +            // 400
                "输出行(整数(ac边y * 1000.0));\n" +            // -300(负浮点:位模式不是补码)
                "停止\n",
                "250000|250000|500000|500000|0|0|300|400|-300");

            钉子("浮点数组元素 嵌套两层调用里读元素(3D 现场那个形状的最小复现:库读 / 顶层读 / 运行期下标)",
                "浮点 顶点x[6];\n" +
                "浮点 顶点y[6];\n" +
                "方法 小值(整数 i) 返回 整数\n" +
                "{\n" +
                "    返回 整数(顶点x[i] * 1000.0);\n" +
                "}\n" +
                "方法 总值(整数 i) 返回 整数\n" +
                "{\n" +
                "    返回 小值(i) + 小值(1);\n" +
                "}\n" +
                "顶点x[0] = 0.100000;\n" +
                "顶点y[0] = 0.200000;\n" +
                "顶点x[1] = 0.400000;\n" +
                "顶点y[1] = 0.600000;\n" +
                "顶点x[2] = 0.700000;\n" +
                "顶点y[2] = 0.800000;\n" +
                "整数 间下标 = 1;\n" +
                "输出行(总值(0));\n" +                                     // 100 + 400
                "输出行(小值(0));\n" +                                     // 100
                "输出行(小值(间下标));\n" +                                // 400(运行期下标)
                "输出行(整数(顶点x[间下标] * 1000.0));\n" +              // 400(顶层读同一格)
                "停止\n",
                "500|100|400|400");

            // ---- ⑥ 接线哨兵:三处判据还在源码里(只钉"还在不在")----
            const string 接线断言 = "浮点数组元素 接线:三处「元素 / 字段也是浮点」的判据与字段类型那一格还在";
            try
            {
                if (仓库根 == null)
                    跳过接线(接线断言, "找不到仓库根(读不到中间层那三份源码)");
                else
                {
                    string 串源 = File.ReadAllText(Path.Combine(仓库根, "中间层", "中间层C.串写入.cs"), Encoding.UTF8);
                    string 链源 = File.ReadAllText(Path.Combine(仓库根, "中间层", "中间层C.引用链.cs"), Encoding.UTF8);
                    string 表达源 = File.ReadAllText(Path.Combine(仓库根, "中间层", "中间层C.表达式.cs"), Encoding.UTF8);
                    string 变量源 = File.ReadAllText(Path.Combine(仓库根, "中间层", "中间层C.变量系统.cs"), Encoding.UTF8);
                    bool 判据 = 串源.Contains("private bool 是浮点标量引用(string 名)", StringComparison.Ordinal)
                        && 串源.Contains("_浮点推断深度 > 0", StringComparison.Ordinal)
                        && 串源.Contains("只查表: true", StringComparison.Ordinal)
                        && 链源.Contains("private bool 链是浮点标量(引用链C 链)", StringComparison.Ordinal)
                        && 链源.Contains("public string? 末字段类型名;", StringComparison.Ordinal)
                        && 表达源.Contains("是浮点: 链是浮点标量(链)", StringComparison.Ordinal)
                        && 表达源.Contains("是浮点: 位置.是浮点 || 是浮点变量(名称.名)", StringComparison.Ordinal)
                        && 变量源.Contains("bool 是浮点 = false)", StringComparison.Ordinal);
