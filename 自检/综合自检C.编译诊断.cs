        /// <summary> 展开文本里出现过的最大 FP 偏移 + 4 = 那个函数真用到的帧字节数(一个字 4 字节) </summary>
        private static int 展开里最大帧偏移(string 展开)
        {
            int 最大 = -4;
            foreach (System.Text.RegularExpressions.Match m in
                System.Text.RegularExpressions.Regex.Matches(展开, @"(?:取字帧|存字帧)\s+R\d+\s+(\d+)"))
                最大 = Math.Max(最大, int.Parse(m.Groups[1].Value, System.Globalization.CultureInfo.InvariantCulture));
            return 最大 + 4;
        }

