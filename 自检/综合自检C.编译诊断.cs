        /// T7 字符串字面量按码点 / T8 运行期错误一律带行号 / T9 末尾不写 `停止` 也不掉进数据段。
        ///
        /// 这几条都是**语义**,所以判据一律"真编真跑"(`跑一次` / `汇编`),不靠源码钉充数;
        /// 只有"行号在哪儿拼""文档里不该有的措辞"这种**收口位置**才用源码钉/正文查。
        /// </summary>
        private static void 评测整改阶段一自检()
        {
            // `跑一次` 把输出按**字节**收进 StringBuilder(`(char)b`)⇒ 非 ASCII 的字面量会变成"一个字节一个字符"。
            // 这一组要比对中文 / emoji 输出,所以按 UTF-8 还原一次(Latin1 把每个字符原样吐回它那个字节)。
            static string 还原(string 出) => Encoding.UTF8.GetString(Encoding.Latin1.GetBytes(出)).TrimEnd('\n');
            static string 跑文本(string 源, bool 优化 = true)
                => 还原(跑一次([("主程序.hb", 源)], 优化, 虚拟机C.默认内存大小).输出);

            // ---- T4:同一份数据、各种写法必须同一个答案(常量折叠的符号性) ----
            string 折叠源 = string.Join("\n", new[]
            {
