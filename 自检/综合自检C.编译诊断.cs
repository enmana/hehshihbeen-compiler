        /// (退出码 -1 / -2 = 没跑成,也算不合预期)。
        ///
        /// 起进程那一套(R4-8)已经提成公用的 `跑命令行`(见 `自检\综合自检C.CLI端到端.cs`)——
        /// 这一层只负责写探针文件 + 指定走哪条命令行开关(工作目录照旧继承父进程)。
