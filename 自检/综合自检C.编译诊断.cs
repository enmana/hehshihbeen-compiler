        /// <summary>
        /// 深括号**必须是真嵌套**(`1 + (1 + (1 + …))`),不能写成 `((((1))))` ——
        /// 后者被 `去外层括号` 一圈一圈剥掉(`中间层C.表达式工具.cs:1012`),根本到不了解析器,
        /// 拿它当"深括号"测试等于自欺(实测:1000 层全外括号一路编过、退出码 0)。
        /// </summary>
        private static string 深括号(int 层数) =>
            "整数 和 = " + string.Concat(Enumerable.Repeat("1 + (", 层数)) + "1" + new string(')', 层数) + ";\n测试输出(和);\n停止\n";

        /// <summary>
        /// 嵌套 `{ }`:`如果` / `当` 一层一对花括号;`选择` **必须带一个 `情况`**(不带的话撞的是另一条路 ——
        /// `选择` 里只许写 `情况 / 默认`,那是"说人话的编译错误",不是这一格要测的嵌套)。
        /// 每一层都写成真源码(不是靠栈溢出去撞),所以 `--asm` 与 `--导图` 两条路喂的是同一份语料。
        /// </summary>
        private static string 嵌套块(string 词, int 层数)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < 层数; i++)
                sb.Append(词 == "选择" ? "选择 (1)\n{\n情况 1\n{\n" : $"{词} (真)\n{{\n");
            sb.Append("整数 x = 1;\n");
            for (int i = 0; i < 层数; i++)
                sb.Append(词 == "选择" ? "}\n}\n" : "}\n");
            return sb.ToString();
        }

        /// <summary>
        /// `否则 如果` 长链:`如果 (x == 0) { … } 否则 如果 (x == 1) { … } …`。
        /// 它是**平**的(所有分支共用同一个结束标签),T20 起展开器用循环走这条链 —— 这一格判"编得过"。
        /// </summary>
        private static string 否则如果链(int 段数)
        {
            var sb = new StringBuilder("整数 x = 1;\n如果 (x == 0)\n{\n测试输出(0);\n}\n");
            for (int i = 1; i < 段数; i++)
                sb.Append($"否则 如果 (x == {i})\n{{\n测试输出({i});\n}}\n");
            return sb.ToString();
        }

        /// <summary> 子进程报错文案收成一行(报告里截断用) </summary>
        private static string 收尾(string 文本, int 上限)
        {
            string 一行 = 文本.Replace("\r", " ").Replace("\n", " ").Trim();
            return 一行.Length <= 上限 ? 一行 : 一行[..上限] + $"…(共 {一行.Length} 字)";
        }

        /// <summary>
        /// 找一份能起子进程的**命令行编译器**(`hbcc.dll`)。自检本来就是 `dotnet hbcc.dll --selftest` 跑起来的
        /// → 进程入口就是它,直接用;在 IDE(WPF)里跑自检时入口不是 hbcc,就按仓库根找构建产物,
        /// **先挑与本程序集同一个构建配置的**(Debug 自检不拿 Release 的旧 hbcc 去测新代码)。
        /// </summary>
        private static string? 找命令行编译器()
        {
            string? 入口 = System.Reflection.Assembly.GetEntryAssembly()?.Location;
            if (入口 != null && Path.GetFileName(入口).Equals("hbcc.dll", StringComparison.OrdinalIgnoreCase) && File.Exists(入口))
                return 入口;

            string? 示例目录 = 找示例目录();
            if (示例目录 == null) return null;
            string 仓库根 = Directory.GetParent(示例目录)?.FullName ?? 示例目录;

            string 本配置 = typeof(综合自检C).Assembly.Location.Contains(
                $"{Path.DirectorySeparatorChar}Debug{Path.DirectorySeparatorChar}", StringComparison.OrdinalIgnoreCase) ? "Debug" : "Release";
            foreach (string 配置 in new[] { 本配置, 本配置 == "Debug" ? "Release" : "Debug" })
            {
                string 候选 = Path.Combine(仓库根, "编译器CLI", "bin", 配置, "net10.0", "hbcc.dll");
                if (File.Exists(候选)) return 候选;
            }
            return null;
        }

        /// <summary>
