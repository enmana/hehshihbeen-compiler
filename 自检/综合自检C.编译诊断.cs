        /// <summary> 跑一段源码、把程序输出收成字符串(初值表自检里做"行为对不对"的对照);优化开关可指定 </summary>
        private static string 输出文本(string 源码, bool 优化 = true)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
            var vm = new 虚拟机C { 输入源 = () => null, 输出目标 = 解码.写 };
            vm.运行(new 汇编器C().汇编多文件带调试([("主程序.hb", 源码)], 优化));
            解码.收尾();
            return 缓冲.ToString().TrimEnd('\n');
        }

