        /// <summary>
        /// 格式纪律(内核加固计划批 5,用户建议四/五/六):把三条承诺**写成可执行的断言**。
        ///   ① **一行永远一条语句**(含一行块也只能一条)—— 报错要说人话,别让用户看到"无法识别的字符 ';'";
        ///   ② **分号必写** —— 不写要报"这句没写完",且哪些行不用写(块头/`{}`/内联汇编/标签/包含)一条不少;
        ///   ③ **只加不改** —— 文档里必须写着这句承诺(ISA 早就有,语法层这次补上)。
        /// 另附 `分号迁移C`(那个补分号的工具)**从来没有任何断言**,这里补上它的黄金文件:
        /// 尤其是 C# 插值字符串 `$"…{C#代码}…"` 的边界(插值段里的 `{}`/引号不能被当成 HB 的花括号)。
        /// </summary>
        private static void 格式承诺自检()
        {
            // ① 一行一条语句:两种写法都要被拦下,且文案是人话(带行号由 期望异常在第几行 单独钉)
            try
            {
                期望异常("格式 一行写两句 → 报错说人话",
                    () => 汇编("整数 a = 1; 整数 b = 2;\n停止"), "一行只能写一条语句", "拆成两行");
                期望异常("格式 一行块里写两条 → 也报错",
                    () => 汇编("整数 计数 = 0;\n如果 (1 < 2) { 计数 = 1; 计数 = 计数 + 2; }\n停止"), "一行只能写一条语句");
                期望异常在第几行("格式 一行两句的报错带对行号",
                    "整数 a = 1;\n整数 a2 = 1; 整数 b = 2;\n停止", 2);

                // 正例:一行块(整块一条语句)合法;字符串里的分号不算"第二条语句"
                记录("格式 一行块(整块一条语句)合法",
                    汇编("如果 (1 < 2) { 输出(65); }\n停止").Length > 0, "编得过");
                记录("格式 字符串字面量里的分号不算两条语句",
                    汇编("输出行(\"左;右;中\");\n停止").Length > 0, "编得过");
            }
            catch (Exception ex) { 记录异常("格式 一行一条语句", ex); }

            // ② 分号必写:该报的要报,不该报的五类一行都不能报
            try
            {
                期望异常("格式 缺分号 → 报错并说清少一个 ';'",
                    () => 汇编("整数 初值 = 1\n停止"), "没写完", "';'");
                var 该放行的 = new (string 名称, string 源)[]
                {
                    ("块头", "如果 (1 < 2)\n{\n输出(65);\n}\n停止"),
                    ("单独的 { }", "如果 (1 < 2)\n{\n}\n停止"),
                    ("内联汇编", "加载立即数 R1, 5\n停止"),
                    ("标签", "起点:\n跳转 起点\n停止"),
                    ("包含", "包含 \"没有这个文件.hb\"\n停止"),
                };
                foreach (var (名称, 源) in 该放行的)
                {
                    // R4-2:以前这里写的是 `catch { 不是分号错 = true; }` —— 编译器**自己崩**(抛的不是
                    // 编译异常C)也算"没报分号错"而 PASS。这条断言要守的是"别把该放行的行误报成分号错",
                    // 不是"别崩";崩了必须当场红,并且说清崩在哪(错就是错)。
                    bool 不是分号错 = true;
                    string 判据 = "编过了(这一行本来就不该写分号)";
                    try { 汇编(源); }
                    catch (编译异常C 错)
                    {
                        不是分号错 = !(错.中文.Contains("没写完") || 错.中文.Contains("少一个"));
                        判据 = 错.中文;
                    }
                    catch (Exception 崩)
                    {
                        不是分号错 = false;
                        判据 = "抛的不是编译异常C(编译器自己崩了): " + 崩.GetType().Name + " " + 崩.Message;
                    }
                    记录($"格式 不用写分号的行不报分号错:{名称}", 不是分号错, 判据);
                }
            }
            catch (Exception ex) { 记录异常("格式 分号必写", ex); }

            // ③ 文档里的三条承诺(帮助速查是代码里的文本,能直接断言)
            try
            {
                string 速查 = 帮助文本C.中间层速查();
                记录("格式 帮助速查写了'一行永远一条语句'", 速查.Contains("一行永远一条语句"));
                记录("格式 帮助速查写了'关键字与既有写法只加不改'", 速查.Contains("关键字与既有写法只加不改"));
            }
            catch (Exception ex) { 记录异常("格式 帮助承诺", ex); }

            // ④ 分号迁移工具(以前零断言):黄金文件 + 幂等 + 插值边界
            try
            {
                // HB 侧:缺分号的语句补上;块头/汇编/标签/包含不补;字符串与注释不动
                const string 原 = "整数 初值 = 1\n输出行(初值)   // 注释也不动\n如果 (1 < 2)\n{\n输出(65)\n}\n加载立即数 R1, 5\n起点:\n跳转 起点\n";
                string 补好 = 分号迁移C.补文本(原);
                记录("分号迁移 HB:缺分号的语句补上", 补好.Contains("整数 初值 = 1;") && 补好.Contains("输出行(初值);"), 补好.Split('\n')[0]);
                记录("分号迁移 HB:块头/汇编/标签不补(也不动注释)",
                    补好.Contains("如果 (1 < 2)\n{") && 补好.Contains("加载立即数 R1, 5\n")
                    && 补好.Contains("跳转 起点\n") && 补好.Contains("// 注释也不动"));
                记录("分号迁移 HB:幂等(补过的再补不变)", 分号迁移C.补文本(补好) == 补好);

                // C# 侧:普通字符串里内嵌的 HB 源码要补;逐字字符串 @"" 不动;插值段里的 C# 代码原样保留
                const string cs原 = "string a = \"整数 初值 = 1\\n测试输出(初值)\";\n" +
                    "string b = @\"整数 初值 = 2\\n测试输出(初值)\";\n" +
                    "string c = $\"整数 初值 = 3\\n测试输出({引号(Path.Combine(目录, \"x.hb\"))})\";\n";
                string cs补 = 分号迁移C.补CSharp文本(cs原);
                记录("分号迁移 C#:普通字符串里的 HB 源码补上了分号", cs补.Contains("整数 初值 = 1;\\n测试输出(初值);"));
                记录("分号迁移 C#:逐字字符串 @\"\" 一个字不动(那是真 C# 文本)",
                    cs补.Contains("@\"整数 初值 = 2\\n测试输出(初值)\""));
                记录("分号迁移 C#:插值段 `{…}` 原样保留(没被当 HB 花括号)",
                    cs补.Contains("{引号(Path.Combine(目录, \\\"x.hb\\\"))}"), cs补.Split('\n')[2]);
                记录("分号迁移 C#:幂等(补过的再补不变)", 分号迁移C.补CSharp文本(cs补) == cs补);
            }
            catch (Exception ex) { 记录异常("格式 分号迁移黄金文件", ex); }
        }

        /// <summary>
        /// 乱源轰炸(批 7):按**固定种子**随机拼"合法 token 序列",送进中间层展开 + 汇编。
        /// 判据只有一条:抛出**不是 `编译异常C`** 的东西(空引用 / 越界 / 栈溢出 / 内部断言…)就算一次**崩**,
        /// 并留下那份最小复现源。为什么要它:用户程序再怎么乱写,编译器要么给"说人话的编译错误"、要么正常编出来,
        /// **不许自己炸** —— 手写用例永远覆盖不到"乱"这一维,随机拼一万次比再加一百条用例管用。
        /// 固定种子 ⇒ 语料可复现(批 4 的确定性要求:同一个种子跑出同一批语料)。
        /// </summary>
        public static (int 试了, int 崩了, string 首例, string 首例说明) 乱源轰炸(int 次数, int 种子 = 20261017)
        {
            string[] 词 =
            [
                "整数", "短整数", "字节", "字符串", "逻辑", "变量", "地址", "文字",
                "a", "b", "c", "x", "y", "foo",
                "如果", "否则", "循环", "当", "遍历", "选择", "情况", "默认", "跳出", "继续",
                "函数", "返回", "结构", "方法", "静态", "模块", "私有", "包含", "测试", "断言",
                "输出行", "输出", "测试输出", "申请", "释放", "取字", "存字", "读取行", "当前时间", "写文件",
                "停止", "0", "1", "2", "-1", "255", "65535", "0x1F", "\"文\"", "'A'", "真", "假",
                "+", "-", "*", "/", "%", "&", "|", "^", "<<", ">>", "==", "!=", "<", ">", "<=", ">=",
                "&&", "||", "!", "=", "(", ")", "{", "}", "[", "]", ".", ",", ";", ":", "R0", "R15",
                "加载立即数", "加法", "停止", "主程序.hb",
            ];
            var 随 = new Random(种子);
            int 崩了 = 0;
            string 首例 = "", 首例说明 = "";

            // 语料一:纯随机 token(测"乱写"),大多数会被正常拒掉
            for (int k = 0; k < 次数 / 2; k++)
            {
                int 行数 = 随.Next(1, 9);
                var sb = new StringBuilder();
                for (int i = 0; i < 行数; i++)
                {
                    int 个数 = 随.Next(1, 7);
                    for (int j = 0; j < 个数; j++)
                    {
                        sb.Append(词[随.Next(词.Length)]);
                        if (j + 1 < 个数 && 随.Next(4) == 0) sb.Append(' ');
                    }
                    sb.Append('\n');
                }
                试一份(sb.ToString());
            }

            // 语料二:**形状对、内容乱**(模板生成) —— 纯随机 token 大多在头几行就被拒,
            // 到不了优化器/列表/字符串/虚拟机那些深水区。这里生成"结构一定合法、表达式随机"的程序,
            // 编译 + **限步跑一遍**(跑不动就跑不动,运行期错误也是正解),专抓深处的崩。
            for (int k = 0; k < 次数 - 次数 / 2; k++)
            {
                var b = new StringBuilder("整数 a = 3;\n整数 b = 5;\n整数 x = 1;\n短整数 表[8];\n字符串 名 = \"题\";\n");
                int 段数 = 随.Next(1, 5);
                for (int i = 0; i < 段数; i++) b.Append(生成语句(随, 2));
                b.Append("停止\n");
                试一份(b.ToString(), 跑一跑: true);
            }

            return (次数, 崩了, 首例, 首例说明);

            void 试一份(string 源, bool 跑一跑 = false)
            {
                try
                {
                    var 编译结果 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源)], true, 中间层C.默认堆大小);
                    if (!跑一跑) return;
                    var 机 = new 虚拟机C();
                    机.输出目标 = null;                       // 生成的程序想打什么都丢掉
                    机.输入源 = () => null;                   // 读输入就当 EOF,不阻塞
                    机.装载(编译结果);
                    long 步 = 0;
                    while (机.单步() && 步 < 200_000) 步++;   // **限步**:生成的代码可能死循环,不许把自检挂住
                }
                catch (编译异常C) { }                          // 说人话的编译错误 = 正解
                catch (运行期错误C) { }                        // 运行期错误(除零/越界)= 正解
                catch (Exception ex)
                {
                    崩了++;
                    if (首例.Length == 0) { 首例 = 源; 首例说明 = ex.GetType().Name + ": " + ex.Message; }
                }
            }

            string 生成表达式(Random r, int 深)
            {
                string[] 叶 = ["a", "b", "x", "0", "1", "7", "255", "3"];
                if (深 <= 0 || r.Next(3) == 0) return 叶[r.Next(叶.Length)];
                string[] 运算 = [" + ", " - ", " * ", " / ", " % ", " & ", " | ", " ^ ", " << ", " >> "];
                return "(" + 生成表达式(r, 深 - 1) + 运算[r.Next(运算.Length)] + 生成表达式(r, 深 - 1) + ")";
            }

            string 生成语句(Random r, int 深)
            {
                int 选 = r.Next(9);
                if (深 > 0 && 选 == 0)
                    return $"如果 ({生成表达式(r, 1)} < 1000)\n{{\n{生成语句(r, 深 - 1)}}}\n否则\n{{\n{生成语句(r, 深 - 1)}}}\n";
                if (深 > 0 && 选 == 1)
                    return $"循环 (整数 i{r.Next(10)} = 0; i{r.Next(10)} < {r.Next(1, 5)}; i{r.Next(10)} = i{r.Next(10)} + 1)\n{{\n{生成语句(r, 深 - 1)}}}\n";
                return 选 switch
                {
                    2 => $"a = {生成表达式(r, 2)};\n",
                    3 => $"输出行({生成表达式(r, 2)});\n",
                    4 => $"表[{生成表达式(r, 0)} % 8] = {生成表达式(r, 1)};\n",
                    5 => $"测试输出({生成表达式(r, 2)});\n",
                    6 => $"拼接到(名, \"段\");\n输出行(名.长度());\n",
                    7 => $"如果 ({生成表达式(r, 1)} == 0) {{ a = {生成表达式(r, 1)}; }}\n",
                    _ => $"测试输出(表[{生成表达式(r, 0)} % 8]);\n",
                };
            }
        }

        /// <summary>
        /// R4-3:`--乱源` 的**深度维** —— 长运算链 / 深括号 / 语句块嵌套 / `否则 如果` 长链 / 思维导图链,
        /// 语料固定,**一格一个子进程**,判据 = **子进程退出码**(不是 `catch`)。
        ///
        /// 为什么必须起子进程:栈溢出(`0xC00000FD`)**进不了 `catch`**(.NET 接不住)—— 在同一进程里跑就等于
        /// "崩的是自检自己",记不到"崩了 ++"里。这**正是 R2-1(1000 项平铺 / 600 层括号让编译器进程直接死)
        /// 当年漏掉的原因**:老 `乱源轰炸` 的表达式深度参数最大只到 2,判据又是 `catch`。
        ///
        /// **T20(2026-09-27 评测整改)补的格子**:这一维原来只有"长链 + 深括号"两族,**结构上不含块嵌套** ——
        /// 于是"450 层 `如果` 把编译器砸死"那个输入**从设计上就抓不到**(T2 就是这么漏过去的)。
        /// 现在补三族:① 嵌套 `如果` / `当` / `选择`(各 300 / 1000 / 5000,判"说人话的嵌套太深");
        /// ② `否则 如果` 长链(2000 / 5000,判**编得过** —— 它是平的,只共用同一个结束标签,不该占栈);
        /// ③ **思维导图链**(`--导图`:扫结构 → 声明线 → 分区,100 编得过 / 1000 与 5000 报"嵌套太深")。
        /// 补格之前先跑过实测:② 那一族 5000 段与 ③ 的深层两档在修之前都是 `0xC00000FD`(判**红**),
        /// 修完才转绿 —— 先红后绿才证明这几格真的抓得住东西。
        ///
        /// 判据:每格都有**期望退出码**(0 = 编过;1 = 说人话的编译错误),"嵌套太深"那几格还要求文案里带
        /// `嵌套太深`。退出码不对 / 文案里写着"内部错误 / 请回报"都算**不合预期**;走的是 `hbcc` 那条真命令行,
        /// 和用户同一条路。找不到命令行编译器时返回 `试了 = 0`(调用方记跳过 —— 在 IDE 里跑自检时会这样)。
        /// </summary>
        public static (int 试了, int 崩了, string 首例, string 首例说明) 乱源深度轰炸()
        {
            string? 编译器 = 找命令行编译器();
            if (编译器 == null) return (0, 0, "", "找不到 hbcc.dll(在 IDE 里跑自检时正常)");

            string 目录 = Path.Combine(临时区C.基目录(), "hbcc_乱源深度维", Environment.ProcessId.ToString());
            Directory.CreateDirectory(目录);

            var 格 = 深度维格表();

            try
            {
                int 崩了 = 0;
                string 首例 = "";
                var 说明段 = new List<string>();
                foreach (var (名, 源, 期望码, 期望文案, 开关) in 格)
                {
                    var (退出码, 文案) = 跑一格编译(编译器, 目录, 名, 源, 开关);
                    // 报错前缀有两种口径(`--asm` 走"中间层展开错误\n 第1行: …",别的路走"第 1 行: …"),
                    // 比之前把空白去掉 —— 两条路都能对上,也不至于被一个空格卡住。
                    string 紧凑 = 文案.Replace(" ", "").Replace("\t", "");
                    bool 合预期 = 退出码 == 期望码
                        && !文案.Contains("内部错误") && !文案.Contains("请回报")
                        && (期望文案.Length == 0 || 紧凑.Contains(期望文案));
                    if (合预期) continue;
                    崩了++;
                    if (首例.Length == 0) 首例 = 源;
                    if (说明段.Count < 4) 说明段.Add($"{名}:退出码 {退出码}(期望 {期望码})「{收尾(文案, 120)}」");
                }
                return (格.Count, 崩了, 首例, string.Join(" / ", 说明段));
            }
            finally
            {
                // H44(硬规矩 15):这份临时件用完自己收。CLI 端到端那一组会起 `hbcc --乱源 20` **子进程**,
                // 子进程跑的就是这一段 —— 它不走自检收尾那条 `finally`,不收就等于每跑一趟往临时区留一份。
                临时区C.清(目录);
            }
        }

        /// <summary>
        /// 深度维的**格子清单**(自检拿 `深度维格数` 判"一格没落")。`开关` 说这一格走哪条命令:
        /// `asm` = `--asm`(要看展开文本或编译错误)、`o` = `-o`(**期望编过**的大语料:别把几 MB 展开灌进管道)、
        /// `导图` = `--导图`(思维导图那条链)。
        /// </summary>
        public static List<(string 名, string 源, int 期望码, string 期望文案, string 开关)> 深度维格表() =>
        [
            ("长链50", 长链(50), 0, "", "asm"),
            ("长链200", 长链(200), 1, "第1行:表达式嵌套太深", "asm"),
            ("长链1000", 长链(1000), 1, "第1行:表达式嵌套太深", "asm"),
            ("长链5000", 长链(5000), 1, "第1行:表达式嵌套太深", "asm"),
