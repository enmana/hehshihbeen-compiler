                    }
                    // 护栏截断 = **这一次没跑完**:读到的只是"跑到一半"的状态,拿两次半截状态相比是没有意义的
                    // (优化那一档每步干的活多 ⇒ 在同一条上限里必然走得更远 ⇒ 值必然不同,而程序一点毛病没有)。
                    // 所以单独算一类、单独报,别混进"值不一致"里 —— 那会把"护栏不够长"说成"优化改了语义"。
