                $"开[{隐开.输出.Replace("\n", "|")}] 关[{隐关.输出.Replace("\n", "|")}]" +
                $"(该两档都打 6;打 1 就是常驻寄存器被 CALL 冲掉、循环提前退出了)");
        }

        /// <summary>
        /// Sample 目录下所有标准工程的 .hbp(找不到 Sample 就返回空) </summary>
        private static IEnumerable<string> 找全部工程文件()
        {
            string? 根 = 找示例目录();
            if (根 == null) return [];
            return Directory.GetFiles(根, "*.hbp", SearchOption.AllDirectories).OrderBy(f => f, StringComparer.Ordinal);
        }

        #region 确定性自检(批 4):同一份源码编译两次,机器码逐字节一致
        /// <summary>
        /// **确定性**(内核加固计划批 4):同一份源码 + 同一套设置(优化 / 堆 / 基目录),**编译两次机器码必须一致**。
        ///
        /// 为什么值得专门钉:①它是**增量编译缓存**(K6)能用得住的前提 —— 键一样就得给一样的结果;
        /// ②它是**回归对比**的地基(以后比"这次改动让机器码变了多少"全靠它);③不确定的来源往往很隐蔽:
        /// 字典序(HashSet/Dictionary 遍历)、绝对路径、时间戳、并行顺序 —— 一旦混进来,用户看到的
        /// 就是"改一个字,整个文件都变了",而这类问题不会自己冒出来,只有专门比才看得见。
        ///
        /// 做法:56 个标准工程**各编译两遍**(两次都重新读盘,顺带证明"编译器不改输入")比 SHA-256;
        /// 另加一个内存里的小程序双编译(快,专门盯编译器自己的遍历顺序)。
        /// </summary>
        private static void 确定性自检()
        {
            // ① 内存里的小程序:两次编译比哈希(快;先跑它,失败时最省排查时间)
            try
            {
                const string 源 = "整数 左 = 3;\n整数 右 = 4;\n" +
                    "方法 加(整数 a, 整数 b) 返回 整数\n{\n返回 a + b;\n}\n" +
                    "字符串 名字 = \"确定\";\n测试输出(加(左, 右));\n测试输出(名字.长度());\n停止";
                string 一 = 机器码指纹(源);
                string 二 = 机器码指纹(源);
                记录("确定性 同一份源码双编译字节一致(内存小程序)", 一 == 二, $"{一} / {二}");
            }
            catch (Exception ex) { 记录异常("确定性 内存小程序", ex); }

            // ② 全部标准工程:各编译两遍(两次都重新读文件)比哈希
            try
            {
                int 比过 = 0, 不一致 = 0, 跳过 = 0;
                string 首例 = "", 跳过首例 = "";
                var 全部工程 = 找全部工程文件().ToList();   // R4-2:松阈值(`比过 >= 30`)换成实数 —— 一个都不许跳
                foreach (string 工程路径 in 全部工程)
                {
                    try
                    {
                        var 工程 = 工程文件C.加载(工程路径);
                        if (工程.文件.Count == 0) { 跳过++; continue; }
                        int 堆;
                        try { 堆 = 工程.堆字节数; } catch { 堆 = 中间层C.默认堆大小; }
                        string 首指纹 = 工程指纹(工程, 堆);
                        string 次指纹 = 工程指纹(工程, 堆);
                        比过++;
                        if (首指纹 != 次指纹)
                        {
                            不一致++;
                            if (首例.Length == 0) 首例 = $" 首例:{Path.GetFileName(工程路径)}({首指纹}≠{次指纹})";
                        }
                    }
                    catch (Exception 异常)
                    {
                        跳过++;
                        if (跳过首例.Length == 0)
                            跳过首例 = $" 跳过首例:{Path.GetFileName(工程路径)}({异常.GetType().Name} {异常.Message})";
                    }
                }
                记录($"确定性 全示例双编译字节一致({比过} 个标准工程)",
                    不一致 == 0 && 跳过 == 0 && 比过 == 全部工程.Count && 比过 > 0,
                    $"{比过} 个一致(应跑 {全部工程.Count} 个),{不一致} 个不一致,{跳过} 个跳过{首例}{跳过首例}");
            }
            catch (Exception ex) { 记录异常("确定性 全示例双编译", ex); }
        }

        /// <summary> 编译一遍内存里的源码,回机器码哈希(16 位十六进制;比逐字节更好念) </summary>
        private static string 机器码指纹(string 源码)
            => 哈希(new 汇编器C().汇编(源码));

        /// <summary> 按工程编译一遍(**每次都重新读盘**),回机器码哈希;优化按默认开 </summary>
        private static string 工程指纹(工程文件C 工程, int 堆大小)
            => 哈希(new 汇编器C().汇编多文件带调试(工程.读全部编译输入(), true, 堆大小).机器码);

        private static string 哈希(byte[] 机器码)
            => Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(机器码))[..16];
        #endregion

        /// <summary>
        /// **全示例双跑**那一条用的步数上限(第426批)。
        ///
        /// 为什么要有这么个数:`跑一次` 得防"程序永远不返回",所以有一个步数护栏。
        /// 但护栏**必须是护栏,不能变成判据** —— 原先全示例那一趟用的是 `跑一次` 的缺省 200 万步,
        /// 而 200 万步**不够几个标准工程跑完**(实测:示例55 的 `素体.建()` 在优化关那一档
        /// 200 万步只长到三成、示例60 的"十万次表添加"同一条循环只走到 3 万次)。
        /// 后果不是"少跑一点"而是**比错了对象**:优化那一档每一步干的活多 ⇒ 在同一条上限里
        /// 走得更远 ⇒ 两次读到的都是**各自被截断的部分状态**,值必然不同。
        /// 实测就是这么红的:5 个工程(示例09 / 17 / 35 / 55 / 60),而它们的程序本身一点问题没有。
        ///
        /// ⇒ 这一档给足,**并且**把"到底停没停机"当读数传出来(`跑一次` 的 `停机`),
        /// 由调用方明确判一次:没停机就是没跑完,那是**红**,而不是"两边看着一样就算过"。
        /// 这样以后再冒出跑不完的工程,红得明明白白。
        ///
        /// **这个数怎么定的(实测,不是拍的)**:第427批把 `跑一次` 的步数一起报出来,
        /// 全示例那一趟逐工程记"最重的一个" —— 76 个工程里最重的是 `示例60_大内存档`
        /// (**开 10549843 步 / 关 11249869 步**),其次是几个三维的。⇒ 取 **5000 万步**
        /// (最重那个的 4.4 倍)当上限:够用,又不至于真碰上不返回的工程时白等太久。
        /// ⚠ 注意"上限大小不花时间":**程序自己会停**的话,跑多少步是它自己的事,与上限无关 ——
        /// 上限只决定"永远不返回"那种情况等多久。
        /// </summary>
        private const long 全示例步数上限 = 50_000_000;

        /// <summary> 按工程文件表编译、按指定内存与堆/池/软栈大小跑完,返回(程序输出, 全部命名变量的值指纹, 逐项读数, 这次编译, 是不是真停机了, 跑了多少步) </summary>
        private static (string 输出, string 变量, List<变量读数C> 读数, 汇编调试结果C 编译, bool 停机, long 步) 跑一次(IEnumerable<(string 名称, string 内容)> 文件表, bool 优化, int 内存大小, int 堆大小 = 中间层C.默认堆大小, int 池大小 = 中间层C.默认池大小, int 软栈大小 = -1, bool 边界检查 = true, long 步数上限 = 2_000_000)
        {
            var 编译 = new 汇编器C().汇编多文件带调试(文件表, 优化, 堆大小, null, 池大小, 内存大小, 软栈大小, 边界检查);
            var vm = new 虚拟机C();
            vm.设内存大小(内存大小);
            var sb = new System.Text.StringBuilder();
            vm.输出目标 = b => sb.Append((char)b);
            vm.装载(编译);
            long 步 = 0;
            bool 停机 = false;
            while (步 < 步数上限)
            {
                if (!vm.单步()) { 停机 = true; break; }        // 遇到 `停止`(或出错停机)= 真跑完了
                步++;
            }
            string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
            var 读数 = 变量读取C.取可见变量(编译.名字表, 编译.标签表, vm.内存, 0, int.MaxValue);
            string 变量 = string.Join(";", 读数.Select(x => $"{x.名字}={System.Text.RegularExpressions.Regex.Replace(x.值文本, "0x[0-9A-Fa-f]+", "0x?")}"));
            return (sb.ToString().Trim() + 报错, 变量, 读数, 编译, 停机, 步);
        }

        /// <summary>
        /// **R6-2(第194批)**:比"优化开 / 关两次跑出来的命名变量"是不是**语义相同**。
        ///
        /// 为什么不能直接比值:两次编译的**代码长度不同** ⇒ 数据段整体平移;而且 `短整数` 的槽宽在
        /// 优化关那档是 2 字节、开那档是 4 字节(C 档),连**同一个变量在数据段里的偏移**都会挪。
        /// 于是"装了 `地址(...)` 的变量"两边取值必然不同(实测 `pa` 560 / 624,两个变量差 64、
        /// 而两次的代码长度差是 68 —— 因为没有哪个单一的平移量能对上),可程序语义完全一致。
        ///
        /// 判据:逐项比**显示文本**;文本不同时只认两种情形 ——
        /// ① 两边这个值各自翻成「**落在哪个数据槽里 + 槽内偏移多少**」之后完全相同
        /// (同一个东西的地址,只是布局挪了);② `回调` 型的**代码地址**(G2 起 `回调` 变量装的就是它)
        /// 两边各自落到**同一个函数入口标签**上(同一个函数 —— 代码地址一样随布局平移)。
        /// 翻不出来的(普通整数、不在数据段也不在函数入口上的值)照旧要求逐字相同
        /// ⇒ 优化真把值改坏了、同一个槽里挪了位置、或者回调改指了**另一个函数**,照样红。
        ///
        /// **G2 补的那一半(第335批)**:`回调 处理 = 地址(首函数);` 的读数在优化开 / 关两档必然不同
        /// (代码长度不同 ⇒ 每个函数入口的地址都挪了),老判据只认数据槽 ⇒ 新标准工程 `示例26_回调`
        /// 一进来就把「优化 全示例双跑一致」顶红了。补的口子**只认函数入口那一个地址**
        /// (`地址(函数名)` 取的永远是标签起点):普通整数要误判成"同一个函数"得在两个构建里都恰好等于
        /// 同名标签的地址,实际上不可能。
        /// </summary>
        private static bool 变量一致(List<变量读数C> 开读数, 汇编调试结果C 开编译,
            List<变量读数C> 关读数, 汇编调试结果C 关编译,
            out int 按地址判过, out int 按函数地址判过, out string 说明)
        {
            按地址判过 = 0;
            按函数地址判过 = 0;
            // **同名变量要按"第几次出现"配,不能按名字装进字典**(第426批):
            // `示例35` 里 `看` 声明了两次(顶层一个、开窗那一块里一个),`变量读取C` 两条都会读出来。
            // 老写法 `关表[名字] = 读数` 是**后一条盖前一条** ⇒ 拿开的第一条去比关的第二条,
            // 于是"同一批值配错了对"报成不一致(实测判据说 `看:开<3 个> 关<12 个>`,而两边的
            // 36 项列表**逐位逐字相同** —— 那条红是判据自己的毛病,不是优化改坏了东西)。
            // 改成"同名的一组按出现次序排队,左边第 k 个配右边第 k 个":顺序由 `名字表.可见变量` 定,
            // 而它按**声明序**生成,两次编译同源 ⇒ 顺序稳定(实测 76 个工程逐位相同)。
            var 关表 = new Dictionary<string, Queue<变量读数C>>(StringComparer.Ordinal);
            foreach (var x in 关读数)
            {
                if (!关表.TryGetValue(x.名字, out var 队)) 关表[x.名字] = 队 = new Queue<变量读数C>();
                队.Enqueue(x);
            }
            var 不同 = new List<string>();
            foreach (var 左 in 开读数)
            {
                if (!关表.TryGetValue(左.名字, out var 队) || 队.Count == 0) { 不同.Add($"{左.名字}:只在优化开那边有"); continue; }
                var 右 = 队.Dequeue();
                if (左.值文本 == 右.值文本) continue;
                // 只有"裸地址字样"才允许按槽内偏移判:别的形状(列表个数、字符串内容…)一律逐字比
                // (数组那一档除外:它的 `值` 装的就是首元素本身,见 `是地址字样` 的说明)
                var 开值 = 左.可读 && 是地址字样(左.值文本) ? 值在哪个槽(开编译, 左.值) : null;
                var 关值 = 右.可读 && 是地址字样(右.值文本) ? 值在哪个槽(关编译, 右.值) : null;
                if (开值 is { } 开槽 && 关值 is { } 关槽 && 开槽.槽 == 关槽.槽 && 开槽.偏移 == 关槽.偏移) { 按地址判过++; continue; }
                // G2:回调变量装的是**代码地址** —— 两边绝对地址照旧不同,按「哪个函数入口」判
                string? 开函数 = 左.可读 ? 是哪个函数入口(开编译, 左.值) : null;
                string? 关函数 = 右.可读 ? 是哪个函数入口(关编译, 右.值) : null;
                if (开函数 != null && 开函数 == 关函数) { 按函数地址判过++; continue; }
                不同.Add($"{左.名字}:开<{左.值文本}> 关<{右.值文本}>");
            }
            foreach (var (名, 队) in 关表)
                foreach (var _ in 队) 不同.Add($"{名}:只在优化关那边有");
            说明 = 不同.Count > 0
                ? string.Join(" ; ", 不同.Take(4))
                : 按地址判过 > 0 || 按函数地址判过 > 0
                    ? $"{开读数.Count} 项全一致(其中 {按地址判过} 项的值是**数据地址**,按「同一个数据槽的同一个偏移」判过;"
                        + $"{按函数地址判过} 项的值是**代码地址**(回调),按「同一个函数入口」判过 —— 地址都随布局平移)"
                    : $"{开读数.Count} 项全一致";
            return 不同.Count == 0;
        }

        /// <summary>
        /// 值文本是不是"一个地址的样子"。**两种形状**:
        /// ① 裸数字,或引用那行的 `→ 0x…`(标量变量里装着一个地址);
        /// ② `[N 个] 首元素 = <数字>`(数组那一档)。
        ///
        /// ② 为什么该算进来:**`变量读数C.值` 在数组这一档装的正是"首元素本身"**
        /// (见 `变量读取C.读一个`:`读数.值 = 首`),与①是同一个东西,外面只多套了一层显示壳。
        /// 起因(`优化 示例双跑一致:示例09` 那一处,第426批):`地址 块地址[9]` 里装的是
        /// **堆块地址**,堆住在数据段里 ⇒ 代码长度一变、整段平移,两档取值必然不同
        /// (实测 开 88222 / 关 89010,与同一个堆基的标量 `堆基` 一模一样),
        /// 而标量那一份早就按①判过了 —— 只有数组这一层壳没被认出来,于是**同一个地址**,
        /// 装在标量里算一致、装在数组里算不一致。
        ///
        /// **列表那一档(`[现在 k 个 / 最多 N 个]`)进不来,而且不许放进来**:那里的 `值` 是
        /// **元素个数**,不是元素 —— 个数两边不一样就是真差异(示例35 的 `看` 就靠这一条红着)。
        /// 字符串数组那一档是 `[N 个] 首元素 = "…"`(带引号)⇒ 也进不来。别的形状照旧一律逐字比。
        /// 放进来的仍然只按「同一个槽的同一个偏移」判(见 `值在哪个槽`):普通整数落不进那一档,
        /// 落得进也要求两次**槽名与槽内偏移都对得上**,所以放宽的是形状、不是判据。
        /// </summary>
        private static bool 是地址字样(string 文本)
            => System.Text.RegularExpressions.Regex.IsMatch(文本, @"^(\d+|→ 0x[0-9A-Fa-f]+)")
            || System.Text.RegularExpressions.Regex.IsMatch(文本, @"^\[\d+ 个\] 首元素 = \d+$");

        /// <summary>
        /// **G2(第335批)**:值是不是某个**函数入口的代码地址**(`回调` 变量装的就是它)。
        /// 口径卡得很死:值必须**正好等于**某个标签的地址,而且那个标签要落在**代码段**里
        /// (`地址(函数名)` 取的永远是函数标签的起点 —— 语言面给不出"函数中间"的地址)。
        /// 为什么不能按"离它最近的标签 + 偏移"判:普通整数落进代码段的情形太多了,
        /// 那样放宽会让"两个不一样的整数恰好离各自标签一样远"混过去;只认入口就堵死了这条路。
        /// </summary>
        private static string? 是哪个函数入口(汇编调试结果C 编译, uint 值)
        {
            if (值 >= 编译.代码字节数) return null;                 // 不在代码段里 ⇒ 不是代码地址
            string? 命中 = null;
            foreach (var kv in 编译.标签表)
            {
                if (kv.Value != 值) continue;
                // 同一个地址上挂多个标签时取字典序最小的那个(两次编译必须取到同一个名字,不然会假红)
                if (命中 == null || string.CompareOrdinal(kv.Key, 命中) < 0) 命中 = kv.Key;
            }
            return 命中;
        }

        /// <summary>
        /// 把一个值翻成"落在哪个**数据槽**里 + 槽内偏移"(不在数据段里 → null)。
        /// 槽 = 汇编器给每个全局变量排的那一格(标签表里地址 ≥ 代码字节数的那些),按地址排;
        /// 同一个槽名 + 同一个偏移 ⇒ 两次编译里指的是**同一个东西**,只是整段布局挪了。
        /// </summary>
        private static (string 槽, int 偏移)? 值在哪个槽(汇编调试结果C 编译, uint 值)
        {
            if (值 < 编译.代码字节数 || 值 >= 编译.代码字节数 + 编译.数据字节数) return null;
            (string 槽, int 地址)? 命中 = null;
            foreach (var kv in 编译.标签表)
            {
                if (kv.Value < 编译.代码字节数 || kv.Value > 值) continue;
                if (命中 == null || kv.Value > 命中.Value.地址
                    || (kv.Value == 命中.Value.地址 && string.CompareOrdinal(kv.Key, 命中.Value.槽) < 0))
                    命中 = (kv.Key, kv.Value);
            }
            return 命中 == null ? null : (命中.Value.槽, (int)值 - 命中.Value.地址);
        }

