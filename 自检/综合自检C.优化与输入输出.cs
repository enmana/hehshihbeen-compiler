            try
            {
                var 调开 = 跑一遍(调源, true);
                var 调关 = 跑一遍(调源, false);
                bool 调一致 = 变量一致(调开.读数, 调开.编译, 调关.读数, 调关.编译, out _, out int 调按函数, out string 调说明);
                // 口径:`首函数` 是头一个函数,优化开 / 关两档里它的入口地址可能**恰好一样**(实测 288 / 288),
                // 真正会挪的是后头的 `次函数`(实测 300 / 304)⇒ 判据只要求"至少有一项按函数入口判过",
