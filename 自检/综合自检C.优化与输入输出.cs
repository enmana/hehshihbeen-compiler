                    {
                        没跑完++;
                        string 哪档 = 开.停机 ? $"关那一档跑到 {全示例步数上限} 步还没停"
                            : 关.停机 ? $"开那一档跑到 {全示例步数上限} 步还没停"
                            : $"开 / 关两档都跑到 {全示例步数上限} 步还没停";
                        记录($"优化 示例双跑一致:{Path.GetFileName(工程路径)}", false,
                            $"{哪档} —— 没跑完就没有可比性(把这一篇改短,或把 `全示例步数上限` 抬上去)");
                        continue;
                    }
                    bool 变量同 = 变量一致(开.读数, 开.编译, 关.读数, 关.编译, out int 本工程地址项, out int 本工程函数项, out string 变量说明);
                    地址项 += 本工程地址项;
                    函数地址项 += 本工程函数项;
                    if (开.输出 != 关.输出 || !变量同)
                    {
                        不一致++;
                        记录($"优化 示例双跑一致:{Path.GetFileName(工程路径)}", false,
                            $"开[{开.输出.Replace("\n", "|")}] 关[{关.输出.Replace("\n", "|")}]" +
                            $" 变量开[{开.变量}] 关[{关.变量}] 判据说[{变量说明}]");
                    }
                }
