                记录($"优化 双跑一致:{名称}", 开.输出 == 关.输出 && 变量同,
                    $"开[{开.输出.Replace("\n", "|")}] 关[{关.输出.Replace("\n", "|")}];变量 {变量说明}");
                记录($"优化 确实少跑指令:{名称}", 开.步数 < 关.步数, $"开 {开.步数} 条 / 关 {关.步数} 条");
            }
            // 展开文本里"循环体"那一段(开始标签 → 跳回开始标签),用来断言不变量真的被提到外面去了
            static string 循环体(string 源, bool 优化)
            {
