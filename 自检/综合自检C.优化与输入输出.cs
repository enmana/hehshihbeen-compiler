            双跑("入口清零:声明后马上赋值", 声明后赋值);
            双跑("入口清零:两句声明挤在一起", 两句声明);
            双跑("入口清零:先读后写(p = p + a)", 读了再写);

            string 序言清 = 取函数入口序言(声明后赋值, "试");
            记录("优化 声明后马上一句纯赋值 → 入口一个字都不清(序言里没有清零)",
                !序言清.Contains("存字帧"), $"序言=<{序言清}>");
            string 序言并 = 取函数入口序言(两句声明, "试");
            记录("优化 入口清零走 `存字帧`:两个字两条,连指针/间接寻址都不用",
                序言并.Split("存字帧").Length - 1 == 2 && !序言并.Contains("MOV") && !序言并.Contains("存字间接"),
                $"序言={序言并.Replace("\n", " / ")}");
            记录("优化 先读后写的局部照样清零(不能省)",
                取函数入口序言(读了再写, "试").Contains("存字帧"), $"序言={取函数入口序言(读了再写, "试").Replace("\n", " / ")}");

            // ⑬ 全面回归:Sample 下每个标准工程(.hbp),优化开/关各跑一遍 —— 程序输出与全部命名变量的值必须一致。
            //    这是"优化改的是生成代码"这件事最硬的证据:全部真示例两边跑出来必须一模一样。
            //    变量那一半按 `变量一致` 判(R6-2:装了 `地址(...)` 的变量两次的绝对地址必然不同,
            //    按"同一个数据槽的同一个偏移"判 —— 那不是语义差异)。
            int 扫过 = 0, 不一致 = 0, 跳过工程 = 0, 地址项 = 0, 函数地址项 = 0, 没跑完 = 0;
