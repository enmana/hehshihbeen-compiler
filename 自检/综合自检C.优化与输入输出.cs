                    if (工程.文件.Count == 0) { 跳过工程++; continue; }
                    int 内存;
                    try { 内存 = 工程.内存字节数; } catch { 内存 = 虚拟机C.默认内存大小; }
                    int 堆;
                    try { 堆 = 工程.堆字节数; } catch { 堆 = 中间层C.默认堆大小; }
                    var 表 = 工程.读全部编译输入();      // C22:`.hb` + `汇编` 表里的 `.hba`(顺序由引擎定死)
                    var 开 = 跑一次(表, true, 内存, 堆, 步数上限: 全示例步数上限);
                    var 关 = 跑一次(表, false, 内存, 堆, 步数上限: 全示例步数上限);
