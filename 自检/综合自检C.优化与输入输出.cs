            static (string 输出, long 步数, string 变量, List<变量读数C> 读数, 汇编调试结果C 编译) 跑一遍(string 源, bool 优化)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(new List<(string, string)> { ("主程序.hb", 源) }, 优化);
                var vm = new 虚拟机C();
                var sb = new System.Text.StringBuilder();
                vm.输出目标 = b => sb.Append((char)b);
                vm.装载(编译);
                long 步 = 0;
                while (vm.单步()) 步++;
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                var 读数 = 变量读取C.取可见变量(编译.名字表, 编译.标签表, vm.内存, 0, int.MaxValue);
                string 变量 = string.Join(";", 读数.Select(x => $"{x.名字}={System.Text.RegularExpressions.Regex.Replace(x.值文本, "0x[0-9A-Fa-f]+", "0x?")}"));
                return (sb.ToString().Trim() + 报错, 步, 变量, 读数, 编译);
            }
            static void 双跑(string 名称, string 源)
            {
                var 开 = 跑一遍(源, true);
                var 关 = 跑一遍(源, false);
