                    "队列只在从头跑时清 / 接着跑先清等待记号 / else-if 认的是调试会话那台虚拟机(经契约取)");
            }

            // ⑤ 给出明确错误的写法错误
            期望异常("I/O 输出() 不带值给指路", () => 汇编("输出();\n停止"), "空行");
            期望异常("I/O 读取行 的缓冲不是字符数组时报错", () => 汇编("短整数 缓冲 = 0;\n短整数 n = 读取行(缓冲);\n停止"), "字符/字节");
            期望异常("I/O 读取字符 单独成句给指路", () => 汇编("读取字符()\n停止"), "要用起来");

            // ⑥ 独立 exe 的"尾巴"格式:编译器贴进去、宿主读出来,必须原样对上
            var 假宿主 = new byte[] { 1, 2, 3, 4, 5 };
            var 打包 = 程序包C.打包(假宿主, [0xAA, 0xBB, 0xCC, 0xDD], ["下标越界:表[i] —— 只有 4 个", "池用完了"], 1234);
            var 解 = 程序包C.解包(打包);
            记录("I/O 独立 exe 的尾巴:机器码/报错说明/错误槽地址都原样拿得回来",
                解 != null && 解.机器码.SequenceEqual(new byte[] { 0xAA, 0xBB, 0xCC, 0xDD })
                && 解.错误槽地址 == 1234 && 解.消息表.Count == 2 && 解.消息表[0].Contains("下标越界"),
                解 == null ? "解包失败" : $"机器码 {解.机器码.Length} 字节,消息 {解.消息表.Count} 条,错误槽 {解.错误槽地址}");
            记录("I/O 没贴程序的 exe 解包返回 null(宿主会打用法提示)",
                程序包C.解包(new byte[64]) == null && 程序包C.解包(假宿主) == null, "不会瞎认");
        }

