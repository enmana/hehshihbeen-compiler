                string 文本 = 编译.调试文件表[0].展开文本;
                int 起 = 文本.IndexOf("WhileStart", StringComparison.Ordinal);
                if (起 < 0) return "";
                起 = 文本.LastIndexOf('\n', 起) + 1;                       // 退到这一行的行首(标签行)
                string 标签名 = 文本[起..].Split(':')[0].Trim();
                int 止 = 文本.IndexOf("JMP " + 标签名, 起, StringComparison.Ordinal);
                return 止 > 起 ? 文本[起..止] : "";
            }

