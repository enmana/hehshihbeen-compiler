            //    ⇒ 不变量提进常驻寄存器,被 CALL 一回来冲掉,循环提前退出(实测:优化开 `复 = 1` / 关 `复 = 6`)。
            //    为什么这条要单独钉:它是"隐式调用"这一类里唯一的一处,而且**全示例双跑那一趟**要撞上
