            }
            记录($"优化 全示例双跑一致({扫过} 个标准工程:优化开/关的程序输出与命名变量逐项相同;" +
                 $"`PC = …/SP = …` 那类随代码长度变的机器状态**不参与比较**;" +
                 $"两档都必须**跑到 `停止`** —— 被步数护栏截断的算没过)",
                不一致 == 0 && 没跑完 == 0 && 跳过工程 == 0 && 扫过 == 全部工程.Count && 扫过 > 0,
                $"{扫过} 个工程跑过(应跑 {全部工程.Count} 个),{不一致} 个不一致,{没跑完} 个没跑完(步数护栏截断),{跳过工程} 个跳过"
                + $",{地址项} 个变量的值是数据地址(按槽内偏移判过)"
                + $",{函数地址项} 个变量的值是代码地址(回调,按「同一个函数入口」判过)"
                + $";最重的一个工程:{最重工程}(上限 {全示例步数上限} 步)"
                + (跳过说明.Count > 0 ? " | " + string.Join(" ; ", 跳过说明) : ""));

            // ⑭ R6-2(第194批):命名变量里装**绝对地址**不再误报,而"真改了值"照样红。
            //    ① 先量事实:同一份源码(带循环,优化真把代码编短了)两边取值确实不同;
            //    ② 再钉判据:按"同一个数据槽的同一个偏移"判就一致,槽里挪 4 个字节、或普通整数变了,都必须红。
            const string 址源 = """
                短整数 倍 = 3;
                短整数 基 = 10;
                var 和 = 0;
                var i = 0;
                当 (i < 20) {
                    和 = 和 + i * 倍;
                    和 = 和 + i * 倍;
                    和 = 和 + 基;
                    i = i + 1;
                }
                整数 表[8];
                整数 pa = 地址(表[0]);
                整数 pb = 地址(表[6]);
                测试输出(和);
                测试输出(pa - 地址(表[0]));
                测试输出(pb - pa);
                停止
                """;
            双跑("循环里的地址变量(数据槽随布局平移,不算不一致)", 址源);
            try
            {
                var 址开 = 跑一遍(址源, true);
                var 址关 = 跑一遍(址源, false);
                bool 址一致 = 变量一致(址开.读数, 址开.编译, 址关.读数, 址关.编译, out int 址按地址, out _, out string 址说明);
                记录("优化 地址型变量:旧口径(比变量字符串)确实会不一致 —— 新判据认它一致",
                    址开.变量 != 址关.变量 && 址一致 && 址按地址 >= 2,
                    $"代码 开{址开.编译.代码字节数}/关{址关.编译.代码字节数} 字节,数据 开{址开.编译.数据字节数}/关{址关.编译.数据字节数} 字节;" +
                    $"旧口径 开[{址开.变量}] 关[{址关.变量}];新判据 {址说明}");

                // 判据自己的两条反向钉子:别把"能翻译成槽内偏移"放宽成"随便都算一致"
                int 首槽 = 址开.编译.标签表.Where(kv => kv.Value >= 址开.编译.代码字节数).Min(kv => kv.Value);
                var 普通前 = new List<变量读数C> { new() { 名字 = "x", 可读 = true, 值 = 7, 值文本 = "7" } };
                var 普通后 = new List<变量读数C> { new() { 名字 = "x", 可读 = true, 值 = 8, 值文本 = "8" } };
                记录("优化 变量判据:普通整数变了照样红(没在数据段里的值一个字都不许让)",
                    !变量一致(普通前, 址开.编译, 普通后, 址开.编译, out _, out _, out _), "7 → 8");
                var 槽前 = new List<变量读数C> { new() { 名字 = "x", 可读 = true, 值 = (uint)首槽, 值文本 = 首槽.ToString() } };
                var 槽后 = new List<变量读数C> { new() { 名字 = "x", 可读 = true, 值 = (uint)(首槽 + 4), 值文本 = (首槽 + 4).ToString() } };
                记录("优化 变量判据:同一个槽里挪了 4 个字节仍然算不一致",
                    !变量一致(槽前, 址开.编译, 槽后, 址开.编译, out _, out _, out _), $"{首槽} → {首槽 + 4}");
            }
            catch (Exception ex) { 记录异常("优化 地址型变量判据(R6-2)", ex); }

            // ⑮ G2(第335批):`回调` 变量装的是**代码地址** —— 同一套判据的第二半。
            //    ① 先量事实:`地址(首函数)` 在优化开 / 关两档取值确实不同(代码长度不同 ⇒ 函数入口整体平移);
            //    ② 再钉判据:按「同一个函数入口」判 ⇒ 一致;反过来"指到另一个函数"必须红。
            const string 调源 = """
