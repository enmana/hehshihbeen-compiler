            // ── 三、冲刷(宿主层):真落盘 / 只认写流 / 关掉的句柄一律作废 ──
            try
            {
                string 根 = 宿主根("运行时");
                清空目录(根);
                string 路径 = 根 + "冲刷.txt";
                var 内存 = new byte[64 * 1024];
                uint 块 = 4096;
                uint 串区 = 8192;
                (uint 路径址, uint 路径长) = 放串(内存, 串区, 路径);
                (uint 数据址, _) = 放串(内存, 串区 + 2048, "落盘");

                写字到块(内存, 块, 路径址);
                写字到块(内存, 块 + 4, 路径长);
                写字到块(内存, 块 + 8, 0x77777777);              // 句柄写回槽先塞垃圾
                int 开状态 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_打开写流);
                uint 句柄 = 读块字(内存, 块 + 8);

