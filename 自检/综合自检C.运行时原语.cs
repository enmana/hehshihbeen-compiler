                记录("运行时 四条都进了内建函数名表(中英)与说明表;`睡眠` 没抢 `等待` 的 `sleep`;帮助《第32节·运行时》在",
                    缺.Length == 0 && 缺说明.Length == 0 && 没抢名字 && 帮助有,
                    $"缺名字: {string.Join(", ", 缺.Select(x => x.中文))} / 缺说明: {string.Join(", ", 缺说明.Select(x => x.英文))}; " +
                    $"`sleep` 仍归 `等待` = {没抢名字};帮助那一段在 = {帮助有}");
            }
            catch (Exception ex) { 记录异常("运行时 四条 接线", ex); }
        }

        /// <summary>把一段 UTF-8 文本放进内存,返回 (地址, 字节数)—— 宿主参数区里那对"址 / 长"就是这么摆的</summary>
        private static (uint 址, uint 长) 放串(byte[] 内存, uint 地址, string 文本)
        {
            byte[] 字节 = Encoding.UTF8.GetBytes(文本);
            Array.Copy(字节, 0, 内存, (int)地址, 字节.Length);
            return (地址, (uint)字节.Length);
        }

        /// <summary>摆一个 `改名(旧路径, 新路径)` 的参数区(16 字节:旧址 / 旧长 / 新址 / 新长)并调它</summary>
        private static int 调改名(byte[] 内存, uint 块, string 旧路径, string 新路径)
        {
            (uint 旧址, uint 旧长) = 放串(内存, 8192, 旧路径);
            (uint 新址, uint 新长) = 放串(内存, 8192 + 2048, 新路径);
            写字到块(内存, 块, 旧址);
            写字到块(内存, 块 + 4, 旧长);
            写字到块(内存, 块 + 8, 新址);
            写字到块(内存, 块 + 12, 新长);
            return 宿主能力C.处理(内存, 块, 宿主能力C.功能_改名);
        }

        /// <summary>摆一个 `打开写流` 的参数区并开一条流,返回拿到的句柄(参数区里的路径址 / 长由调用方给)</summary>
        private static uint 开一个写流(byte[] 内存, uint 块, uint 址, uint 长)
        {
            写字到块(内存, 块, 址);
            写字到块(内存, 块 + 4, 长);
            写字到块(内存, 块 + 8, 0x77777777);
            宿主能力C.处理(内存, 块, 宿主能力C.功能_打开写流);
            return 读块字(内存, 块 + 8);
        }

