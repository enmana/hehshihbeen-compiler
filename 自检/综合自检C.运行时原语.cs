            catch (Exception ex) { 记录异常("运行时 句柄表清一次就回起点", ex); }

            // ── 七、接线哨兵:四个名字进表(中英)+ 说明表;`睡眠` 没抢 `等待` 的 `sleep`(硬规矩 8) ──
