                写字到块(内存, 块, 句柄);
                int 再冲状态 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_冲刷);       // 句柄作废 ⇒ 22

                // 读流也拿 `冲刷` 去冲:它没有要落盘的写缓冲 ⇒ 参数不合法 9
                uint 读句柄槽 = 块 + 8;
                写字到块(内存, 块, 路径址);
                写字到块(内存, 块 + 4, 路径长);
                写字到块(内存, 读句柄槽, 0x77777777);
                int 开读状态 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_打开读流);
