            bool 相接 = 表.Count > 0 && 表[0].起始 == 0 && 表[^1].末尾 == 内存;
            for (int i = 1; i < 表.Count; i++) 相接 &= 表[i].起始 == 表[i - 1].末尾;
            记录("内存布局与容量 分区表首尾相接、不重叠、正好铺满运行内存", 相接,
                $"共 {表.Count} 段:" + string.Join(" ", 表.Select(x => $"{x.区名}[0x{x.起始:X}~0x{x.末尾:X}]")));

            // ---- ② 三块隐藏区都在,大小与工程配的一致 ----
            var 堆区 = 表.FirstOrDefault(x => x.区名 == "堆");
            var 池区 = 表.FirstOrDefault(x => x.区名 == "池");
