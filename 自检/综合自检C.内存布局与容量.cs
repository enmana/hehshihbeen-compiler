// ============================================================
// 内存布局与容量自检(R1-3,第207批)
//
//   这一条治的是"1MB 是多大、被谁占了、还剩多少"看不见的问题:
//     · **布局表自洽**:`引擎\内存布局C.cs` 算出来的分区表首尾相接、正好铺满 [0, 内存),
//       堆 / 池 / 软栈三块的字节数与工程文件里配的一样,空闲区 = 池尾 → "运行内存末尾减硬件栈保留"
//       (与运行期 `池要一块` 同一个判据);
//     · **换了配值表跟着变**:内存 / 堆 / 池 / 软栈 四个旋钮各拿两组对照,表里的数跟着动;
//     · **小内存工程**:32KB 那种硬件栈按四分之一留(与 `虚拟机C.栈顶保留` 同源),布局不越界;
//     · **容量验收件**(R1-3 的验收,适应版 —— HB 侧还没有"HB 写的编译器",所以量的是**工程侧**):
//       ① 单文件 >32KB 的源码能编过、能跑对;② 主程序 + 库总源码 >64KB 的工程能编过、能跑对;
//       ③ 那两份大源码**真占地方**(代码 + 静态数据 >64KB)—— 防止哪天有人拿注释把字节数凑够就算过。
//
//   为什么是"验收件"而不是"扩容":R1-3 拍板走**流式路线**(按文件独立编译,不动 ISA);
//   把 1MB 用到看得见 + 拿一份大工程钉住现状,是本批能落地的那一半 —— 扩地址位是远期的事。
//   详见 `任务清单.md` 第207节。
// ============================================================

