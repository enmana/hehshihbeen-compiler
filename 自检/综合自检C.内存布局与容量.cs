        /// <summary> 定位到文件就按源码钉一条断言,找不到(不在工作副本里跑)就如实记跳过 </summary>
        private static void 跳过或钉(string 名, string? 路径, string 该有)
        {
            if (路径 == null || !File.Exists(路径))
            {
                跳过(名, "不在工作副本里跑,读不到源码文件");
                return;
            }
            记录(名, File.ReadAllText(路径).Contains(该有, StringComparison.Ordinal),
                File.ReadAllText(路径).Contains(该有, StringComparison.Ordinal) ? $"源码里有 `{该有}`" : $"源码里找不到 `{该有}`");
        }

        /// <summary> 编 + 跑一段 HB 工程(输出按 UTF-8 收、行尾折成 `|` 好写预期);编不过/跑不起来就把话带回来 </summary>
        private static (string 输出, 汇编调试结果C? 编译, string 报错) 编跑(            (string 名称, string 内容)[] 文件, int 内存大小, int 堆大小, int 池大小, int 软栈大小)
        {
            try
            {
                var 编译 = new 汇编器C().汇编多文件带调试(文件.ToList(), true, 堆大小, null, 池大小, 内存大小, 软栈大小);
                var 机 = new 虚拟机C();
                机.设内存大小(内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                机.输出目标 = 解码.写;
                机.运行(编译);
                解码.收尾();
                return (缓冲.ToString().Trim().Replace("\n", "|"), 编译,
                    编译.查运行期报错(机.内存) is { } 说明 ? 说明 : "");
            }
            catch (Exception ex)
            {
                return ("", null, ex.Message.Replace("\n", " "));
            }
        }

