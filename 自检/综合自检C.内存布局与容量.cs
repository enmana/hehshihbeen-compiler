                解码.收尾();
                return (缓冲.ToString().Trim().Replace("\n", "|"), 编译, 机,
                    编译.查运行期报错(机.内存) is { } 说明 ? 说明 : "");
            }
            catch (Exception ex)
            {
                return ("", null, null, ex.Message.Replace("\n", " "));
            }
        }

        /// <summary> `整数 数N = N;` + `累 = 累 + 数N * 3 + 1;` 共 条数 组(每组的期望值一起给出来) </summary>
        private static string 自累语句(int 条数, out long 和)
        {
            var sb = new StringBuilder();
            和 = 0;
            for (int i = 0; i < 条数; i++)
            {
                sb.AppendLine($"整数 数{i} = {i};");
                sb.AppendLine($"累 = 累 + 数{i} * 3 + 1;");
                和 += (long)i * 3 + 1;
            }
            return sb.ToString();
        }

        /// <summary> 库文件:一批带初值的全局变量(给"两个文件加起来 >64KB"那份验收件当第二个文件) </summary>
        private static string 库声明(int 条数, out long 和)
        {
            var sb = new StringBuilder();
            和 = 0;
            for (int i = 0; i < 条数; i++)
            {
                sb.AppendLine($"整数 库数{i} = {i * i % 97};");
                和 += i * i % 97;
            }
            return sb.ToString();
        }

        /// <summary> 主程序里把库文件那批变量累加进来(跨文件引用,顺带钉住"两个文件真一起编") </summary>
        private static string 库累加语句(int 条数)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < 条数; i++)
                sb.AppendLine($"累 = 累 + 库数{i};");
            return sb.ToString();
        }
