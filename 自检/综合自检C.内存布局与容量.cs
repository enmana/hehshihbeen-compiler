                "总 = 加(41);\n" +
                "输出行(问候);\n" +
                "输出行(总);\n" +
                "停止\n";

            int 内存 = 虚拟机C.默认内存大小;
            int 堆 = 128 * 1024, 池 = 16 * 1024, 软栈 = 32 * 1024;

