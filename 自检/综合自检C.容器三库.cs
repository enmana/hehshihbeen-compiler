//   判据照 `基础库施工计划.md` §2 批 7 那一行:"环形缓冲绕圈正确(逐个对表)"。
//   这一组六块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **栈那一套**:现场造一串"压 / 弹"操作(定长种子,现场用 .NET 的 Random 造),
