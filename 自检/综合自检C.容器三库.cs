            catch (Exception ex) { 记录异常("容器三库 边界(优先队列)", ex); }

            // ============================================================
            // ⑥ 接线哨兵:三个库在位 + 头注释该有的几段齐 + 公开方法个数
            // ============================================================
            try
            {
                string 栈文 = File.ReadAllText(栈路径);
