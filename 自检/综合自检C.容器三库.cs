//     ⑤ **边界那一档**:满 / 空 / 越界,逐条钉住"不报错、不停机、不给假结果"
//        (尤其 `弹 / 出队 / 取最小` 拿不到时**不许动 `收值`**);
//     ⑥ **接线哨兵**:三个库都在盘上 + 头注释五段齐 + 公开方法个数对上
//        —— 只钉"还在不在",不许单独当正确性证据。
