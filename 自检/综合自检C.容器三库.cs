using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 容器三库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 栈路径 = Path.Combine(库目录, "栈.hb").Replace('\\', '/');
            string 队列路径 = Path.Combine(库目录, "队列.hb").Replace('\\', '/');
            string 优先路径 = Path.Combine(库目录, "优先队列.hb").Replace('\\', '/');
            if (!File.Exists(栈路径) || !File.Exists(队列路径) || !File.Exists(优先路径))
            {
                跳过("容器三库 定位三个库文件", $"找不到 {栈路径} / {队列路径} / {优先路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{栈路径}\"\n包含 \"{队列路径}\"\n包含 \"{优先路径}\"\n";

            // 真编真跑一趟(输出按 UTF-8 收、行尾换成 `|`,与 数组列表统计库 那一组同一套跑法)
            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // ============================================================
            // ① 栈:压 / 弹 / 看顶 / 看第几 / 压一串(与 C# 的 Stack<int> 逐条对拍)
            // ============================================================
            try
            {
                const int 表长 = 6;
                var 随机 = new Random(20261007);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append($"整数 格[{表长}];\n整数 顶 = 0;\n整数 值 = -12345;\n");
                var 参考 = new Stack<int>();
                int 参考值 = -12345;                      // 调用方那一格(`收值`)现在是多少
                for (int 轮 = 0; 轮 < 120; 轮++)
                {
                    int 动作 = 随机.Next(6);
                    int 给 = 随机.Next(-40, 41);
                    if (动作 == 0)                             // 压
                    {
                        源.Append($"输出行(栈.压(格, 顶, {给}));\n");
                        if (参考.Count < 表长) { 参考.Push(给); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|');
                    }
                    else if (动作 == 1)                        // 弹
                    {
                        源.Append("输出行(栈.弹(格, 顶, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Pop(); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 2)                        // 看顶
                    {
                        源.Append("输出行(栈.看顶(格, 顶, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Peek(); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 3)                        // 看第几个(0 = 栈顶)
                    {
                        int 序号 = 随机.Next(-1, 表长 + 1);
                        源.Append($"输出行(栈.看第几个(格, 顶, {序号}, 值));\n输出行(值);\n");
                        if (序号 >= 0 && 序号 < 参考.Count) { 参考值 = 参考.ElementAt(序号); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 4)                        // 个数 / 是空 / 是满
                    {
                        源.Append("输出行(栈.个数(格, 顶));\n输出行(栈.是空(格, 顶));\n输出行(栈.是满(格, 顶));\n");
                        期望.Append(参考.Count).Append('|').Append(参考.Count == 0 ? 1 : 0).Append('|')
                            .Append(参考.Count >= 表长 ? 1 : 0).Append('|');
                    }
                    else                                       // 压一串(定长来源表)
                    {
                        int 来源个数 = 随机.Next(0, 5);
                        var 料 = Enumerable.Range(0, 来源个数).Select(_ => 随机.Next(-9, 10)).ToArray();
                        源.Append($"整数 来料{轮}[{Math.Max(来源个数, 1)}]");
                        源.Append(来源个数 > 0 ? " = [" + string.Join(", ", 料) + "];\n" : ";\n");
                        源.Append($"输出行(栈.压一串(格, 顶, 来料{轮}, {来源个数}));\n");
                        int 真压 = 0;
                        foreach (int 一个 in 料) { if (参考.Count >= 表长) break; 参考.Push(一个); 真压++; }
                        期望.Append(真压).Append('|');
                    }
                    // 顺手盯一下"个数"永远在 [0, 表长] 里
                    源.Append("输出行(栈.个数(格, 顶));\n");
                    期望.Append(参考.Count).Append('|');
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("容器三库 栈:压 / 弹 / 看顶 / 看第几 / 压一串 / 个数 / 是空 / 是满(120 轮随机操作,与 C# 的 Stack<int> 逐条对拍;容量 6)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("容器三库 栈", ex); }

            // ============================================================
            // ② 队列:入 / 出队 / 看头 / 看尾 / 取第 / 到数组(环形绕圈那条判据)
            // ============================================================
            try
            {
                const int 表长 = 5;
                var 随机 = new Random(20261008);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append($"整数 环[{表长}];\n整数 头 = 0;\n整数 用 = 0;\n整数 值 = -12345;\n");
                var 参考 = new Queue<int>();
                int 参考头 = 0, 参考值 = -12345;
                for (int 轮 = 0; 轮 < 160; 轮++)
                {
                    int 动作 = 随机.Next(7);
                    int 给 = 随机.Next(-40, 41);
                    if (动作 <= 1)                             // 入
                    {
                        源.Append($"输出行(队列.入(环, 头, 用, {给}));\n");
                        if (参考.Count < 表长) { 参考.Enqueue(给); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|');
                    }
                    else if (动作 == 2)                        // 出队
                    {
                        源.Append("输出行(队列.出队(环, 头, 用, 值));\n输出行(值);\n");
                        if (参考.Count > 0)
                        {
                            参考值 = 参考.Dequeue();
                            参考头 = (参考头 + 1) % 表长;
                            期望.Append('1');
                        }
                        else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 3)                        // 看头
                    {
                        源.Append("输出行(队列.看头(环, 头, 用, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Peek(); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 4)                        // 看尾
                    {
                        源.Append("输出行(队列.看尾(环, 头, 用, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Last(); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 5)                        // 取第几个(按出队顺序)
                    {
                        int 序号 = 随机.Next(-1, 表长 + 1);
                        源.Append($"输出行(队列.取第几个(环, 头, 用, {序号}, 值));\n输出行(值);\n");
                        if (序号 >= 0 && 序号 < 参考.Count) { 参考值 = 参考.ElementAt(序号); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else                                       // 到数组 + 个数 / 是空 / 是满
                    {
                        源.Append($"整数 顺{轮}[{表长}];\n");
                        源.Append($"输出行(队列.到数组(环, 头, 用, 顺{轮}));\n");
                        期望.Append(参考.Count).Append('|');
                        for (int i = 0; i < 表长; i++)
                        {
                            源.Append($"输出行(顺{轮}[{i}]);\n");
                            期望.Append(i < 参考.Count ? 参考.ElementAt(i) : 0).Append('|');
                        }
                        源.Append("输出行(队列.个数(环, 用));\n输出行(队列.是空(环, 用));\n输出行(队列.是满(环, 用));\n");
                        期望.Append(参考.Count).Append('|').Append(参考.Count == 0 ? 1 : 0).Append('|')
                            .Append(参考.Count >= 表长 ? 1 : 0).Append('|');
                    }
                    // `头` 必须永远落在 [0, 表长) —— 环没绕对时它会越界,这一条当场抓到
                    源.Append("输出行(头);\n");
                    期望.Append(参考头).Append('|');
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("容器三库 队列:入 / 出队 / 看头 / 看尾 / 取第 / 到数组(160 轮随机操作,容量 5 —— 环绕回去对不对就看这一段)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("容器三库 队列", ex); }

            // ============================================================
            // ③ 优先队列:放 / 取最小 / 看最小 / 建堆(与 C# 的 List<int> 每次取最小对拍)
            // ============================================================
            try
            {
                const int 表长 = 7;
                var 随机 = new Random(20261009);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append($"整数 堆格[{表长}];\n整数 用 = 0;\n整数 值 = -12345;\n");
                var 参考 = new List<int>();
                int 参考值 = -12345;
                for (int 轮 = 0; 轮 < 140; 轮++)
                {
                    int 动作 = 随机.Next(5);
                    int 给 = 随机.Next(-40, 41);
                    if (动作 <= 1)                             // 放
                    {
                        源.Append($"输出行(优先队列.放(堆格, 用, {给}));\n");
                        if (参考.Count < 表长) { 参考.Add(给); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|');
                    }
                    else if (动作 == 2)                        // 取最小
                    {
                        源.Append("输出行(优先队列.取最小(堆格, 用, 值));\n输出行(值);\n");
                        if (参考.Count > 0)
                        {
                            参考值 = 参考.Min();
                            参考.Remove(参考值);
                            期望.Append('1');
                        }
                        else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 3)                        // 看最小
                    {
                        源.Append("输出行(优先队列.看最小(堆格, 用, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Min(); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else                                       // 建堆 + 个数(建堆只理顺序,内容与个数都不变)
                    {
                        源.Append("优先队列.建堆(堆格, 用);\n输出行(优先队列.个数(堆格, 用));\n");
                        期望.Append(参考.Count).Append('|');
                    }
                    源.Append("输出行(优先队列.是空(堆格, 用));\n输出行(优先队列.是满(堆格, 用));\n");
                    期望.Append(参考.Count == 0 ? 1 : 0).Append('|').Append(参考.Count >= 表长 ? 1 : 0).Append('|');
                }
                // 收尾:升序取出必须是从小到大
                源.Append("整数 有序[8];\n输出行(优先队列.升序取出(堆格, 用, 有序));\n");
                期望.Append(参考.Count).Append('|');
                var 排 = 参考.OrderBy(x => x).ToArray();
                for (int i = 0; i < 8; i++)
                {
                    源.Append($"输出行(有序[{i}]);\n");
                    期望.Append(i < 排.Length ? 排[i] : 0).Append('|');
                }
                源.Append("输出行(用);\n停止\n");
                期望.Append(0).Append('|');
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("容器三库 优先队列:放 / 取最小 / 看最小 / 建堆 / 升序取出(140 轮随机操作 + 收尾取空,容量 7 —— 最小堆的父子关系靠它兜)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("容器三库 优先队列", ex); }

            // ============================================================
            // ④ 端到端:标准工程 示例39_栈与队列 的输出逐行对 `// 预期输出:`
            // ============================================================
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例39_栈与队列");
                string? 源码 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码 == null || !File.Exists(源码))
                {
                    跳过("容器三库 标准工程 示例39 逐行对预期输出", $"找不到 {源码}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码);
                    var 期望行 = 解析预期输出(行表);
                    // ⚠ 这一篇是**带 UI** 的标准工程:那一行 `// 预期输出:` 里既有窗口前那一段
                    //   `输出行`,也有开窗之后逐帧画出来的命令(H82 批 4 的口径)。
                    //   ⇒ 必须走共享帮手 `运行带输出`:它**挂无头呈现口**(绘制命令逐条进同一份输出缓冲)
                    //   并按 `基目录` 自动读工程目录那份 `事件脚本.txt`(帧数/键鼠都从那儿来)。
                    //   ⚠ 别退回"自己 new 虚拟机C"那一版:窗口开不出来 ⇒ 只跑出窗口前那一段,
                    //   这条断言看着红、其实红在**判据没挂呈现口**(实测期望 13631 条 / 实得 31 条)。
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录, 示例堆大小(工程目录));
                    string 实得 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望行);
                    bool 好 = 期望行.Count > 0 && 实得 == 应有;
                    记录("容器三库 标准工程 示例39 逐条对预期输出(三个库在真程序里的那一趟:栈转二进制 → 队列绕圈 → 优先队列取最急)",
                        好, 好 ? $"逐行一致({期望行.Count} 行,含开窗那一半)" : 逐行差说明(应有, 实得));
                }
            }
            catch (Exception ex) { 记录异常("容器三库 标准工程 示例39", ex); }

            // ============================================================
            // ⑤ 边界那一档:满 / 空 / 越界(全库统一口径:不报错、不停机、不动 `收值`)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 格[2];\n" +
                    "整数 顶 = 0;\n" +
                    "整数 值 = 99;\n" +
                    "输出行(栈.压(格, 顶, 1));\n" +              // 1:1
                    "输出行(栈.压(格, 顶, 2));\n" +              // 2:1
                    "输出行(栈.压(格, 顶, 3));\n" +              // 3:0(满)
                    "输出行(顶);\n" +                             // 4:2
                    "输出行(栈.弹(格, 顶, 值));\n" +             // 5:1
                    "输出行(值);\n" +                             // 6:2
                    "输出行(栈.弹(格, 顶, 值));\n" +             // 7:1
                    "输出行(值);\n" +                             // 8:1
                    "输出行(栈.弹(格, 顶, 值));\n" +             // 9:0(空)
                    "输出行(值);\n" +                             // 10:1(不动)
                    "输出行(栈.看顶(格, 顶, 值));\n" +           // 11:0
                    "输出行(值);\n" +                             // 12:1
