                {
                    int 数 = 0;
                    foreach (string 行 in 文.Split('\n'))
                        if (行.StartsWith("方法 ", StringComparison.Ordinal)) 数++;
                    return 数;
                }
                int 栈法 = 数方法(栈文), 队法 = 数方法(队文), 优法 = 数方法(优文);
