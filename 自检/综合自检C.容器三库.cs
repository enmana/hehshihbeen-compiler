            catch (Exception ex) { 记录异常("容器三库 边界(栈)", ex); }

            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 环[2];\n" +
                    "整数 头 = 0;\n" +
                    "整数 用 = 0;\n" +
