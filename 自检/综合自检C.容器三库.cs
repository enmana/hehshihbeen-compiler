//   ★ 这一组**敢放"多语句对拍"**(批 6 那一组当初把这几块撤了,只能跑小程序):
//     第352批把 **H71 的根因**抓出来修掉了(赋值右边算好的值会被"下标里的 CALL"冲掉)——
//     当时量出来的"一长就变"正是它。修完这一组一次跑一整组逐条对得上
//     (H71 自己有单独一组 `H71 数组赋值` 钉着最小复现)。
//
//   ⚠ 这一组**不引 `测试助手.hb`**:库与库之间互相引会把"谁坏了"搅浑(自检要能一眼定位)。
