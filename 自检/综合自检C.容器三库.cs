                string 期 = "1|1|0|2|1|2|1|1|0|1|0|1|0|0";
                string 实 = 跑(源.ToString());
                记录("容器三库 边界(栈):满了压不进 / 空了弹不出 / 取不到时不动 `收值` / 越界给假 —— 一律不报错、不停机",
                    实 == 期, 对拍说明(期, 实));
