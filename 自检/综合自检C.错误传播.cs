// 错误传播自检(R3-5,第323批)—— 「失败靠返回值传」这套口径的验收
//
//   这一批**不动语言 / 不动 ISA / 不动虚拟机**:R3-5 是拍板项,用户 2026-10-01 取的是
//   **「a + c —— 定标准结果形状 + 写进帮助与 Sample\说明.md」**。所以钉法分两半:
//     · **形状那一半**:标准结果形状 = 一个"成不成 + 值"的小捆 —— 缺省用元组
//       (`[逻辑, 值]`,`返回 [假, 0];`),要错误码 / 说明就换结构。三条真编真跑:
//       两支分岔 / 一层层往上穿 / 结构带错误码与说明;
//     · **口径那一半**:宿主能力失败**不停机、不写错误槽**(程序照常跑到最后),
//       帮助《第28节·错误怎么传》与 `Sample\说明.md` 各有一节写着这套规格。
//
//   为什么这么钉:这一条的核心不是"新加了个语法",而是"**以后写失败就往这个形状上靠**" ——
//   所以既要有真跑得通的形状(行为断言),也要有"规格写在用户看得见的地方"(文档钉子),
//   少了任何一半,下一个人还是会各写各的哨兵值。
//
//   标准工程 `示例25_错误传播` 的逐行对账由「全示例」那三条自检统一跑(自动扫
//   `Sample\**\*.hbp` + `// 预期输出:`),本组只钉"它还在盘上 + 有预期输出行"。
// ============================================================

using System;
using System.IO;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 错误传播自检()
        {
            // ---- ① 标准结果形状:元组 `[逻辑, 值]`,成功 / 失败两支当场分岔 ----
            跑输出断言("R3-5 标准结果形状(元组 `[逻辑, 值]`):成功与失败两支当场分岔,不必猜哨兵值",
                "方法 取一半(整数 数) 返回 [逻辑, 整数]\n{\n" +
                "如果 (数 < 0)\n{\n返回 [假, 0];\n}\n返回 [真, 数 / 2];\n}\n" +
                "[逻辑, 整数] 好 = 取一半(10);\n如果 (好.项0)\n{\n测试输出(好.项1);\n}\n否则\n{\n测试输出(0 - 1);\n}\n" +
                "[逻辑, 整数] 坏 = 取一半(0 - 2);\n如果 (坏.项0)\n{\n测试输出(坏.项1);\n}\n否则\n{\n测试输出(0 - 1);\n}\n停止",
                "5\n-1");

            // ---- ② 一层层往上穿:中层自己不看值,把那个小捆原样返回给上一层 ----
            跑输出断言("R3-5 失败能一层层往上穿(中层把结果形状原样 `返回`,不用另起一套写法)",
                "方法 取一半(整数 数) 返回 [逻辑, 整数]\n{\n" +
                "如果 (数 < 0)\n{\n返回 [假, 0];\n}\n返回 [真, 数 / 2];\n}\n" +
                "方法 平均值(整数 左, 整数 右) 返回 [逻辑, 整数]\n{\n" +
                "[逻辑, 整数] 左半 = 取一半(左);\n如果 (左半.项0)\n{\n" +
                "[逻辑, 整数] 右半 = 取一半(右);\n如果 (右半.项0)\n{\n返回 [真, 左半.项1 + 右半.项1];\n}\n" +
                "返回 [假, 0];\n}\n返回 [假, 0];\n}\n" +
                "[逻辑, 整数] 好 = 平均值(10, 20);\n如果 (好.项0)\n{\n测试输出(好.项1);\n}\n否则\n{\n测试输出(0 - 1);\n}\n" +
                "[逻辑, 整数] 坏 = 平均值(10, 0 - 2);\n如果 (坏.项0)\n{\n测试输出(坏.项1);\n}\n否则\n{\n测试输出(0 - 1);\n}\n停止",
                "15\n-1");

            // ---- ③ 结构当结果类型:错误码 + 说明一起带得回(说明文字原样读得到) ----
            跑输出断言("R3-5 要错误码 / 说明就用结构当结果类型(说明字符串跟着返回原样读得到)",
                "结构 取数结果\n{\n逻辑 成;\n整数 值;\n整数 错误码;\n字符串 说明;\n}\n" +
                "方法 取两倍(整数 原始) 返回 取数结果\n{\n取数结果 果;\n如果 (原始 < 0)\n{\n" +
                "果.成 = 假;\n果.值 = 0;\n果.错误码 = 7;\n果.说明 = \"负数取不了两倍\";\n返回 果;\n}\n" +
                "果.成 = 真;\n果.值 = 原始 * 2;\n果.错误码 = 0;\n果.说明 = \"\";\n返回 果;\n}\n" +
                "取数结果 结果 = 取两倍(0 - 1);\n如果 (结果.成)\n{\n测试输出(结果.值);\n}\n否则\n{\n" +
                "测试输出(结果.错误码);\n输出行(结果.说明);\n}\n停止",
                "7\n负数取不了两倍");

            // ---- ④ 口径:宿主能力失败不打断、不写错误槽(程序照常跑到最后) ----
            //      「不写错误槽」这一半靠 `编译并跑` 那条路本身钉住:错误槽里有号会走 `查运行期报错`,
            //      跑不到最后那句 `999` 就会当场抛出来(这一组另一条断言钉的是同一件事的反面)。
            跑输出断言("R3-5 宿主能力失败不打断也不写错误槽:读不到文件给假,程序照常跑到最后一句",
                "字符串 内容 = \"\";\n" +
                "逻辑 读到了 = 读文件(\"自检里没有这份文件_错误传播.txt\", 内容, 4096);\n" +
                "如果 (读到了)\n{\n测试输出(1);\n}\n否则\n{\n测试输出(0);\n}\n" +
                "测试输出(999);\n停止",
                "0\n999");

            // ---- ⑤ 文档钉子(帮助):《第28节·错误怎么传》写明三类失败 + 标准结果形状 ----
            string 上手 = 帮助文本C.快速上手();
            bool 帮助齐 = 上手.Contains("28,错误怎么传", StringComparison.Ordinal)
                && 上手.Contains("标准结果形状", StringComparison.Ordinal)
                && 上手.Contains("返回 [假, 0];", StringComparison.Ordinal)
                && 上手.Contains("语言里没有异常", StringComparison.Ordinal)
                && 上手.Contains("哨兵值", StringComparison.Ordinal);
            记录("R3-5 帮助《第28节·错误怎么传》写明三类失败 / 标准结果形状 / 没有异常 / 哨兵值的代价",
                帮助齐, "帮助正文 = `引擎\\帮助文本C.cs`(站点由它现场生成)");

            // ---- ⑥ 文档钉子(说明.md):同一套规格在 `Sample\说明.md` 里有一节 ----
            string? 根 = 找仓库根目录();
            string 说明路径 = 根 == null ? "" : Path.Combine(根, "Sample", "说明.md");
            string 说明文本 = 根 != null && File.Exists(说明路径) ? File.ReadAllText(说明路径) : "";
            bool 说明齐 = 说明文本.Contains("## 错误怎么传", StringComparison.Ordinal)
                && 说明文本.Contains("标准结果形状", StringComparison.Ordinal)
                && 说明文本.Contains("28,错误怎么传", StringComparison.Ordinal);
            记录("R3-5 `Sample\\说明.md` 有《错误怎么传》一节,并指路帮助《上手》第28节",
                说明齐, 根 == null ? "找不到仓库根" : $"读 {说明路径}");

            // ---- ⑦ 接线哨兵:标准工程 `示例25_错误传播` 还在盘上,且带 `// 预期输出:` ----
            string 示例目录 = 根 == null ? "" : Path.Combine(根, "Sample", "中间层", "示例25_错误传播");
            string 示例源 = Path.Combine(示例目录, "主程序.hb");
            bool 示例在 = 根 != null
                && File.Exists(Path.Combine(示例目录, "示例25_错误传播.hbp"))
                && File.Exists(示例源)
                && File.ReadAllText(示例源).Contains("// 预期输出:", StringComparison.Ordinal);
            记录("R3-5 标准工程 `示例25_错误传播` 在盘上(工程文件 + 主程序 + `// 预期输出:`;真跑对账交给「全示例」那三条)",
                示例在, 根 == null ? "找不到仓库根" : 示例目录);
        }
    }
