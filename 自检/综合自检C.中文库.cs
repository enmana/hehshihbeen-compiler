// 中文 库的自检(G4 批 13,第358批)
//   —— `Sample\库\中文.hb`
//
//   判据照 `基础库施工计划.md` §2 批 13 那一行:
//   **"UTF-8 解码一字 / 汉字个数 / 全角半角 / 中文数字"**。
//   这一组八块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **UTF-8 三件与 .NET 逐条对拍**:`UTF8字节数` 对 `Encoding.UTF8.GetByteCount`;
//        `UTF8解码一字` 把**每一个字节位置**(含落在字中间的那些)都过一遍,与"按码点走一遍"的
//        C# 参考实现比码点与字节宽;`UTF8编码一字` 对 `char.ConvertFromUtf32`
//        (越界 / 代理区两边都给空串);
//     ② **汉字**:一张字表(汉字 / 扩展 A / 兼容区 / 扩展 B / 〇 / 假名 / 谚文 / ASCII / 圈号 / 全角)
//        与 C# 参考区间逐条比,再用混合串比 `汉字个数` 与 `只留汉字`;
//     ③ **全角半角**:`转半角` / `转全角` / `是全角` 与 C# 参考逐条比(含全角空格与空串);
//     ④ **中文数字:读**:手写一张"认得的形态 + 该给几"表(含大写 / `两` / `〇` / 逐位 / 负号)
//        与一张"形态不合法"表,逐条比"给不给"与那个值;
//     ⑤ **中文数字:写**:`整数转中文数字` 与 C# 参考实现逐条比(边界 + 随机 400 个),
//        并当场做**往返**:`中文数字转整数(整数转中文数字(n))` 必须还是 n;
//     ⑥ **金额大写**:与 C# 参考实现逐条比(边界 + 随机 400 个,含负数与极限值);
//     ⑦ **端到端**:标准工程 **`示例45_中文文本`** 真编真跑,与它那行 `// 预期输出:` 逐行对;
//     ⑧ **接线哨兵**:库在盘上 + 头注释五段齐 + `模块 中文` + 公开方法数(13)。
//
//   ⚠ 这一组**不引 `测试助手.hb` / `string.hb`**:库与库之间互相引会把"谁坏了"搅浑(自检要能一眼定位);
//     夹具里只在"给输出加个非空前缀"时用一次 `拼接到`(不成循环),别的全靠一行一个数 —— 这样
//     `跑()` 收尾那一下 `Trim()` 不会把空结果吃掉(批 12 踩过:空行会被吃,期望与实得整段错位)。
// ============================================================

