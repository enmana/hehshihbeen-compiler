        /// <summary>HB 字符串字面量的转义(反斜杠 / 引号 / 控制字符走 `\xNN`)。</summary>
        private static string 转义HB(string 文本)
        {
            var 果 = new StringBuilder();
            foreach (char 字 in 文本)
            {
                if (字 == '\\') 果.Append("\\\\");
                else if (字 == '"') 果.Append("\\\"");
                else if (字 < 0x20 || 字 == 0x7F) 果.Append($"\\x{(int)字:X2}");
                else 果.Append(字);
            }
            return 果.ToString();
        }

        /// <summary>按**字节**位置取一个字:正好落在字边界上给 (码点, 占几个字节);否则给 (-1, 0)。</summary>
        private static (int 码, int 宽) 参考解码一字(string 文本, int 起)
        {
            int 偏移 = 0;
            foreach (Rune 字 in 文本.EnumerateRunes())
            {
                if (偏移 == 起) return (字.Value, 字.Utf8SequenceLength);
                偏移 += 字.Utf8SequenceLength;
            }
            return (-1, 0);
        }

        /// <summary>一个码点 → UTF-8 字节串;越界或代理区给空串。</summary>
        private static string 参考编码一字(uint 码点)
        {
            if (码点 > 0x10FFFF) return "";
            if (码点 >= 0xD800 && 码点 <= 0xDFFF) return "";
            return char.ConvertFromUtf32((int)码点);
        }

        /// <summary>是不是汉字:`中文.hb` 认的那六段 + 〇。</summary>
        private static bool 参考是汉字(int 码)
        {
            if (码 == 0x3007) return true;
            if (码 >= 0x3400 && 码 <= 0x4DBF) return true;
            if (码 >= 0x4E00 && 码 <= 0x9FFF) return true;
            if (码 >= 0xF900 && 码 <= 0xFAFF) return true;
            if (码 >= 0x20000 && 码 <= 0x2FA1F) return true;
            if (码 >= 0x30000 && 码 <= 0x3134F) return true;
            return false;
        }

        private static int 参考汉字个数(string 文本) => 文本.EnumerateRunes().Count(字 => 参考是汉字(字.Value));

        private static string 参考只留汉字(string 文本)
            => string.Concat(文本.EnumerateRunes().Where(字 => 参考是汉字(字.Value)).Select(字 => 字.ToString()));

        private static string 参考转半角(string 文本)
            => string.Concat(文本.Select(字 => 字 == '\u3000' ? ' ' : (字 >= '\uFF01' && 字 <= '\uFF5E') ? (char)(字 - 0xFEE0) : 字));

        private static string 参考转全角(string 文本)
            => string.Concat(文本.Select(字 => 字 == ' ' ? '\u3000' : (字 >= '!' && 字 <= '~') ? (char)(字 + 0xFEE0) : 字));

        private static bool 参考是全角(char 字) => 字 == '\u3000' || (字 >= '\uFF01' && 字 <= '\uFF5E');

        /// <summary>0~9 → 大写数字字(金额那一套)。</summary>
        private static char 参考大写数字(int 位) => "零壹贰叁肆伍陆柒捌玖"[位];

        /// <summary>
        /// 1~9999 那一段读成文字。`大写` 时不省"一"(`壹拾`);小写时"这一段正好是整串最高的一段、
        /// 又只有十位、又是 1"才省掉"一"(`十` / `十五` / `十万`;`一万零一十` 不省)。
        /// </summary>
        private static string 参考一段(int 值, bool 大写, bool 允许省一)
        {
            int 千 = 值 / 1000, 百 = 值 / 100 % 10, 十 = 值 / 10 % 10, 个 = 值 % 10;
            string 数字 = 大写 ? "零壹贰叁肆伍陆柒捌玖" : "零一二三四五六七八九";
            string 十位 = 大写 ? "拾" : "十", 百位 = 大写 ? "佰" : "百", 千位 = 大写 ? "仟" : "千";
            var 果 = new StringBuilder();
            bool 需零 = false;
            if (千 > 0) 果.Append(数字[千]).Append(千位);
            if (百 > 0)
            {
                if (需零) { 果.Append('零'); 需零 = false; }
                果.Append(数字[百]).Append(百位);
            }
            else if (千 > 0) 需零 = true;
            if (十 > 0)
            {
                if (需零) { 果.Append('零'); 需零 = false; }
                if (千 == 0 && 百 == 0 && 十 == 1 && 允许省一) 果.Append(十位);
                else 果.Append(数字[十]).Append(十位);
            }
            else if (千 > 0 || 百 > 0) 需零 = true;
            if (个 > 0)
            {
                if (需零) 果.Append('零');
                果.Append(数字[个]);
            }
            return 果.ToString();
        }

        /// <summary>亿 / 万 / 个 三段(0 给"零");段之间该补"零"就补;省"一"只给最高那一段。</summary>
        private static string 参考三段(uint 数, bool 大写)
        {
            if (数 == 0) return "零";
            uint 亿 = 数 / 100000000;
            int 万 = (int)(数 / 10000 % 10000);
            int 个 = (int)(数 % 10000);
            bool 小写 = !大写;
            var 果 = new StringBuilder();
            if (亿 > 0) 果.Append(参考一段((int)亿, 大写, 小写)).Append('亿');
            if (万 > 0)
            {
                if (亿 > 0 && 万 < 1000) 果.Append('零');
                果.Append(参考一段(万, 大写, 小写 && 亿 == 0)).Append('万');
            }
            if (个 > 0)
            {
                if ((亿 > 0 || 万 > 0) && 个 < 1000) 果.Append('零');
                果.Append(参考一段(个, 大写, 小写 && 亿 == 0 && 万 == 0));
            }
            return 果.ToString();
        }

        /// <summary>整数 → 小写中文数字(负数写"负";0 给"零")。</summary>
        private static string 参考整数转中文数字(int 值)
        {
            if (值 == 0) return "零";
            bool 负 = 值 < 0;
            uint 数 = 负 ? (uint)(-(long)值) : (uint)值;
            return (负 ? "负" : "") + 参考三段(数, false);
        }

        /// <summary>以"分"为单位的金额 → 票据那一套大写。</summary>
        private static string 参考金额大写(int 分)
        {
            bool 负 = 分 < 0;
            long 总 = 分 < 0 ? -(long)分 : 分;
            long 元 = 总 / 100;
            int 角 = (int)(总 / 10 % 10);
            int 分位 = (int)(总 % 10);
            var 果 = new StringBuilder();
            if (负) 果.Append('负');
            if (元 == 0) 果.Append("零元");
            else 果.Append(参考三段((uint)元, true)).Append('元');
            if (角 > 0) 果.Append(参考大写数字(角)).Append('角');
            else if (分位 > 0) 果.Append('零');
            if (分位 > 0) 果.Append(参考大写数字(分位)).Append('分');
            else 果.Append('整');
            return 果.ToString();
        }
