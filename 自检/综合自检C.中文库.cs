        private static void 中文库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 中路径 = Path.Combine(库目录, "中文.hb").Replace('\\', '/');
            if (!File.Exists(中路径))
            {
                跳过("中文库 定位库文件", $"找不到 {中路径}(不在工作副本里跑就跳过)");
                return;
            }

            // 夹具头:只引中文.hb,自带两个"加非空前缀"的帮手(空结果也留下痕迹)。
            //   `拼接到` 只收字符串变量 / 字面量 / 一个字节 / 一个文字,所以帮手只做一次两段拼接。
            string 头 = $"包含 \"{中路径}\"\n"
                + "方法 带标(字符串 标, 字符串 值) 返回 字符串\n"
                + "{\n"
                + "    字符串 结果 = \"\";\n"
                + "    拼接到(结果, 标, 值);\n"
                + "    返回 结果;\n"
                + "}\n"
                + "方法 带标逻辑(字符串 标, 逻辑 值) 返回 字符串\n"
                + "{\n"
                + "    字符串 结果 = \"\";\n"
                + "    拼接到(结果, 标);\n"
                + "    如果 (值) { 拼接到(结果, \"1\"); } 否则 { 拼接到(结果, \"0\"); }\n"
                + "    返回 结果;\n"
                + "}\n";

            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // 大批量的对拍**分块编译**:一个程序里字符串产生得太多会把 32KB 池用完
            //   (池会自己长,可 1MB 运行内存下到某一个数就长不动了 —— 实测四百多个值就报
            //   "字符串 结果 长不下了"),分块跑、每块一个新虚拟机才不会把"池满了"误判成"库错了"。
            (bool 好, string 详情) 分块对拍(string 变量名, List<int> 值们,
                Func<int, string> 造语句, Func<int, string> 造期望, int 每块)
            {
                var 错 = new List<string>();
                int 块数 = (值们.Count + 每块 - 1) / 每块;
                for (int 起 = 0; 起 < 值们.Count; 起 += 每块)
                {
                    var 源 = new StringBuilder(头);
                    源.Append($"整数 {变量名} = 0;\n");
                    源.Append("整数 回读 = 0;\n");
                    var 期望段 = new List<string>();
                    foreach (int 值 in 值们.Skip(起).Take(每块))
                    {
                        源.Append(造语句(值));
                        期望段.AddRange(造期望(值).Split('|'));
                    }
                    源.Append("停止\n");
                    string 期 = string.Join("|", 期望段), 实 = 跑(源.ToString());
                    if (期 != 实) 错.Add($"第 {起 / 每块 + 1}/{块数} 块:{对拍说明(期, 实)}");
                }
                return (错.Count == 0,
                    错.Count == 0 ? $"分 {块数} 块(每块最多 {每块} 个值),块块逐条一致" : string.Join(" ; ", 错));
            }

