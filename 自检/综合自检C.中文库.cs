                {
                    0x00, 0x41, 0x7F, 0x80, 0x7FF, 0x800, 0xD7FF, 0xD800, 0xDFFF, 0xE000,
                    0x4E2D, 0xFFFF, 0x10000, 0x1F600, 0x10FFFF, 0x110000, 0xFFFFFFFF,
                };
                var 源 = new StringBuilder(头);
                源.Append("字符串 文本 = \"\";\n");
                源.Append("整数 宽 = 0;\n");
                源.Append("无符号整数 码 = 0;\n");
                var 期望 = new List<string>();
                foreach (string 样 in 样们)
                {
                    源.Append($"文本 = \"{转义HB(样)}\";\n");
                    源.Append("输出行(中文.UTF8字节数(文本));\n");
                    int 字节数 = Encoding.UTF8.GetByteCount(样);
                    期望.Add(字节数.ToString());
                    for (int 起 = 0; 起 <= 字节数; 起++)
                    {
                        源.Append($"输出行(中文.UTF8解码一字(文本, {起}, 宽));\n");
                        源.Append("输出行(宽);\n");
                        (int 码, int 位宽) = 参考解码一字(样, 起);
                        期望.Add(码.ToString());
                        期望.Add(位宽.ToString());
                    }
                }
                foreach (uint 码点 in 码点们)
                {
                    源.Append($"码 = 0x{码点:X};\n");
                    源.Append("输出行(带标(\"E\", 中文.UTF8编码一字(码)));\n");
                    期望.Add("E" + 参考编码一字(码点));
                }
                源.Append("停止\n");
                string 期 = string.Join("|", 期望), 实 = 跑(源.ToString());
