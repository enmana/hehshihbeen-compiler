                记录("网络 套接字的句柄与流的句柄不在同一个号段(拿流句柄调网络原语只会得到'句柄无效')",
                    流句柄样式 == 64 && 宿主能力C.套接字表格数 == 32,
                    $"流表 {宿主能力C.流表格数} 格、套接字表 {宿主能力C.套接字表格数} 格 ⇒ 套接字句柄的表下标从 " +
