            }
            catch (Exception ex) { 记录异常("网络 号段与句柄号段", ex); }

            // ── 三、"没挂这一族能力"的形状:整族状态 1、写回槽一律 -1(手机端 / 独立 exe / 没给工程文件) ──
            try
