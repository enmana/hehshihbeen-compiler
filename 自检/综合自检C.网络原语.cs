        /// <summary>
        /// 真回环那份 HB 源码(端口由自检现挑):先监听、再连上去、把排着的那条接受下来,一来一回。
        /// 全篇**只打数字与 ASCII**,方便逐行对账;每一步都是同步阻塞,**没有一句等待**。
        /// </summary>
        private static string 网络回环源码(int 端口) =>
            "整数 听 = 0;\n" +
            $"听 = 监听(\"127.0.0.1\", {端口}, 听);\n" +
            "输出行(听 > 0);\n" +
            "整数 客 = 0;\n" +
            $"客 = 连到(\"127.0.0.1\", {端口}, 客);\n" +
            "输出行(客 > 0);\n" +
            "整数 服 = 0;\n" +
            "服 = 接受(听, 服);\n" +
            "输出行(服 > 0);\n" +
            "输出行(发送(客, \"abc\"));\n" +
            "字符串 块 = \"\";\n" +
            "整数 已收 = 0;\n" +
            "字符串 全文 = \"\";\n" +
            "整数 块长 = 1;\n" +
            "当 (已收 < 3 && 块长 > 0)\n" +
            "{\n" +
            "    块长 = 接收(服, 块, 8);\n" +
            "    如果 (块长 > 0)\n" +
            "    {\n" +
            "        拼接到(全文, 块);\n" +
            "        已收 = 已收 + 块长;\n" +
            "    }\n" +
            "}\n" +
            "输出行(已收);\n" +
            "输出行(全文);\n" +
            "输出行(关闭(客));\n" +
            "输出行(接收(服, 块, 8));\n" +              // 对端关掉了 ⇒ 0
            "输出行(关闭(服));\n" +
            "输出行(关闭(听));\n" +
            "输出行(关闭(听));\n" +                      // 同一个监听再关一次 ⇒ 22
            "字符串 地址 = \"\";\n" +
            "输出行(主机解析(\"127.0.0.1\", 地址));\n" +
            "输出行(地址);\n" +
            "整数 坏 = 0;\n" +
            $"坏 = 连到(\"127.0.0.1\", 1, 坏);\n" +       // 表里只有 {端口} ⇒ :1 连都不连
            "输出行(坏);\n" +
            "输出行(主机解析(\"例子.测试\", 地址));\n" +   // 白名单外的主机名 ⇒ 假
            "停止\n";

        /// <summary>二进制那一档的回环源码:6 个字节里有 0x00 也有 >=0x80 —— `发送` / `接收` 那一对办不到的那一档</summary>
        private static string 二进制回环源码(int 端口) =>
            "整数 听 = 0;\n" +
            $"听 = 监听(\"127.0.0.1\", {端口}, 听);\n" +
            "整数 客 = 0;\n" +
            $"客 = 连到(\"127.0.0.1\", {端口}, 客);\n" +
            "整数 服 = 0;\n" +
            "服 = 接受(听, 服);\n" +
            "地址 发块 = 申请(32);\n" +
            "存字(发块, 0, 0xC8007E81);\n" +            // 小端 ⇒ 字节 81 7E 00 C8
            "存字(发块, 4, 0x000041FF);\n" +            // 小端 ⇒ 字节 FF 41 00 00
            "输出行(发送块(客, 发块, 6));\n" +          // 6
            "地址 收块 = 申请(32);\n" +
            "整数 长 = 接收块(服, 收块, 32);\n" +
            "输出行(长);\n" +                            // 6
            "整数 i = 0;\n" +
            "当 (i < 长)\n" +
            "{\n" +
            "    整数 字起 = i - i % 4;\n" +
            "    整数 移位量 = (i % 4) * 8;\n" +
            "    输出行((取字(收块, 字起) >> 移位量) & 255);\n" +
            "    i = i + 1;\n" +
            "}\n" +                                       // 129 126 0 200 255 65
            "释放(发块);\n" +
            "释放(收块);\n" +
            "输出行(关闭(客));\n" +
            "输出行(关闭(服));\n" +
            "输出行(关闭(听));\n" +                        // 0 0 0
            "停止\n";

        /// <summary>问系统要一个**空闲端口**(绑 0 让内核挑,问出来就关掉 —— 紧接着用那个号)<summary>
        private static int 空闲端口()
        {
            var 听 = new TcpListener(IPAddress.Loopback, 0);
            听.Start();
            int 端口 = ((IPEndPoint)听.LocalEndpoint).Port;
            听.Stop();
            return 端口;
        }

        private static uint 读块字(byte[] 内存, uint 地址)
            => (uint)(内存[地址] | (内存[地址 + 1] << 8) | (内存[地址 + 2] << 16) | (内存[地址 + 3] << 24));

        private static void 写字到块(byte[] 内存, uint 地址, uint 值)
        {
            内存[地址] = (byte)(值 & 0xFF);
            内存[地址 + 1] = (byte)((值 >> 8) & 0xFF);
            内存[地址 + 2] = (byte)((值 >> 16) & 0xFF);
            内存[地址 + 3] = (byte)((值 >> 24) & 0xFF);
        }
    }
