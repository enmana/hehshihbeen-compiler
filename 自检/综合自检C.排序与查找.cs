// ============================================================
// 排序 / 查找两库自检(R3-4,第238批)—— `Sample\库\排序.hb` + `Sample\库\查找.hb`
//
//   两个库都是纯 HB(不动 ISA / 关键字 / 语言面),所以这一组的钉法 = **真编真跑一段 HB 程序看输出**:
//     · 排序库:整数升序 / 降序(稳定)、单元素与已有序的表、按键排序(值跟着键走、相同键稳定)、
//       部分升序(只保证前 k 个就位)
//     · 查找库:线性找 / 二分找(没有给 -1)、是升序、第k小(乱序也照算 + 不动原表 + k 越界给假)、
//       最大最小(正负混合)
//     · 库文件头的口径**按源码钉住**(改了代码忘了改说明就红灯)
//
//   本批实测出来的两条语言边界也钉在这里(它们是"库为什么长这样"的原因):
//     · **列表传不了**:动态列表当数组参数传,编译器当场报"列表的地址不能取" ⇒ 两个库只收固定数组;
//     · **长度 0 的数组不合法**(`数组长度非法: '0'`,要 1~65536)⇒ 库里"空表"那一支**到不了**,
//       只是将来收列表时别在 `表[0]` 上越界的护栏(库文件头把这条写明了)。
//   字符串表排序这一版没有:`字符串 表[]` 这种参数形态语言面还不收(库文件头写了原因)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 排序与查找自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 排序路径 = Path.Combine(库目录, "排序.hb").Replace('\\', '/');
            string 查找路径 = Path.Combine(库目录, "查找.hb").Replace('\\', '/');
            if (!File.Exists(排序路径) || !File.Exists(查找路径))
            {
                跳过("排序与查找库 定位 Sample\\库\\排序.hb + 查找.hb",
                    $"找不到 {排序路径} / {查找路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{排序路径}\"\n包含 \"{查找路径}\"\n";

            // 真编真跑一趟(与哈希表自检同一套跑法:输出按 UTF-8 收、行尾换成 `|`)
            static string 跑(string 源, int 堆大小, int 池大小, int 软栈大小 = 32 * 1024)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 堆大小, null, 池大小,
                    虚拟机C.默认内存大小, 软栈大小);
                var vm = new 虚拟机C();
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }
            string 跑小(string 源) => 跑(源, 中间层C.默认堆大小, 中间层C.默认池大小);

            // 打印一张表(每行一个,行尾换 `|` 好写预期)
            const string 打印 = "整数 i = 0;\n当 (i < 表.长度())\n{\n测试输出(表[i]);\ni = i + 1;\n}\n停止";

            // ---- ① 整数升序:乱序 + 有重复 ----
            记录("排序库 整数升序(乱序表 + 重复值,就地把调用方那张表排好)",
                跑小(头 + "整数 表[8] = [5, 2, 9, 2, 7, 1, 8, 3];\n排序.整数升序(表);\n" + 打印)
                    == "1|2|2|3|5|7|8|9",
                "5 2 9 2 7 1 8 3 → 1 2 2 3 5 7 8 9");

            // ---- ② 整数降序:同一个手势比的方向反过来 ----
            记录("排序库 整数降序(重复值也在)",
                跑小(头 + "整数 表[8] = [5, 2, 9, 2, 7, 1, 8, 3];\n排序.整数降序(表);\n" + 打印)
                    == "9|8|7|5|3|2|2|1",
                "降序:9 8 7 5 3 2 2 1");

            // ---- ③ 边界:单元素 / 已经有序(插排最好一档) ----
            记录("排序库 单元素表与已经有序的表都不出错(插排最好 O(n) 那一档)",
                跑小(头 + "整数 单[1] = [7];\n排序.整数升序(单);\n测试输出(单[0]);\n" +
                    "整数 序[3] = [1, 2, 3];\n排序.整数降序(序);\n" +
                    "测试输出(序[0]);\n测试输出(序[1]);\n测试输出(序[2]);\n停止")
                    == "7|3|2|1",
                "单元素原样;已经有序的降序表 1 2 3 → 3 2 1");

            // ---- ④ 按键排序:值跟着键走;两个 1 键保持原来的先后(稳定) ----
            记录("排序库 按键排序:值跟着键一起挪,相同键保持原来先后(稳定)",
                跑小(头 + "整数 值[5] = [100, 200, 300, 400, 500];\n整数 键[5] = [3, 1, 2, 1, 3];\n" +
                    "排序.按键排序(值, 键);\n整数 i = 0;\n当 (i < 5)\n{\n测试输出(键[i]);\ni = i + 1;\n}\n" +
                    "i = 0;\n当 (i < 5)\n{\n测试输出(值[i]);\ni = i + 1;\n}\n停止")
                    == "1|1|2|3|3|200|400|300|100|500",
                "键 3 1 2 1 3 → 1 1 2 3 3;值跟着走 200 400 300 100 500(两个 1 键没换位)");

            // ---- ⑤ 部分升序:只要最小的前 k 个就位,其余不保证 ----
            记录("排序库 部分升序:前 3 个就位,尾巴保持原样(不做稳定承诺)",
                跑小(头 + "整数 表[6] = [40, 10, 30, 20, 50, 0];\n排序.部分升序(表, 3);\n" + 打印)
                    == "0|10|20|30|50|40",
                "前 3 小 0 10 20;尾巴还是 30 50 40(选择排序换过的样子)");

            // ---- ⑥ 线性找:找到给下标(重复给第一个),没有给 -1 ----
            记录("查找库 线性找:首 / 中 / 尾 / 没有(没有给 -1)",
                跑小(头 + "整数 表[7] = [1, 3, 5, 7, 9, 11, 13];\n" +
                    "测试输出(查找.线性找(表, 1));\n测试输出(查找.线性找(表, 7));\n" +
                    "测试输出(查找.线性找(表, 13));\n测试输出(查找.线性找(表, 8));\n停止")
                    == "0|3|6|-1",
                "1→0 / 7→3 / 13→6 / 8→-1");

            // ---- ⑦ 二分找:要求升序,边界两个头尾都找得到 ----
            记录("查找库 二分找:首 / 中 / 尾 / 没有(表必须先升序)",
                跑小(头 + "整数 表[7] = [1, 3, 5, 7, 9, 11, 13];\n" +
                    "测试输出(查找.二分找(表, 1));\n测试输出(查找.二分找(表, 7));\n" +
                    "测试输出(查找.二分找(表, 13));\n测试输出(查找.二分找(表, 8));\n" +
                    "测试输出(查找.二分找(表, 0));\n测试输出(查找.二分找(表, 14));\n停止")
                    == "0|3|6|-1|-1|-1",
                "两头夹在表外的 0 / 14 也给 -1");

            // ---- ⑧ 是升序:有序真 / 乱序假 / 单元素真(相等算有序) ----
            记录("查找库 是升序:有序真、乱序假、单元素真、相等算有序",
                跑小(头 + "整数 有序[4] = [1, 2, 2, 3];\n整数 乱[3] = [3, 1, 2];\n整数 单[1] = [5];\n" +
                    "测试输出(查找.是升序(有序));\n测试输出(查找.是升序(乱));\n测试输出(查找.是升序(单));\n停止")
                    == "1|0|1",
                "1 2 2 3 → 真;3 1 2 → 假;单元素 → 真");

            // ---- ⑨ 第k小:乱序也照算、算完不动原表、k 从 1 开始 ----
            记录("查找库 第k小:第 1 / 第 n / 乱序表也照算,且不动调用方那张表",
                跑小(头 + "整数 序[7] = [1, 3, 5, 7, 9, 11, 13];\n整数 乱[3] = [3, 1, 2];\n整数 收 = 0;\n" +
                    "测试输出(查找.第k小(序, 1, 收));\n测试输出(收);\n" +
                    "测试输出(查找.第k小(序, 7, 收));\n测试输出(收);\n" +
                    "测试输出(查找.第k小(乱, 2, 收));\n测试输出(收);\n" +
                    "测试输出(乱[0]);\n停止")
                    == "1|1|1|13|1|2|3",
                "第 1 小 1 / 第 7 小 13 / 乱序第 2 小 2;乱[0] 还是 3(内部复制的那份排掉了)");

            // ---- ⑩ 第k小:k 越界给假,而且不动 `收值` ----
            记录("查找库 第k小:k 越界(0 / 比表长还大)给假且不动收值",
                跑小(头 + "整数 序[3] = [9, 8, 7];\n整数 收 = 42;\n" +
                    "测试输出(查找.第k小(序, 0, 收));\n测试输出(收);\n" +
                    "测试输出(查找.第k小(序, 4, 收));\n测试输出(收);\n停止")
                    == "0|42|0|42",
                "k=0 与 k=4 都给 0;收 一直是 42");

            // ---- ⑪ 最大最小:一趟走完两个值(含负数) ----
            记录("查找库 最大最小:正负混着一趟拿两个",
                跑小(头 + "整数 表[5] = [-3, 0, 12, 7, 5];\n整数 大 = 0;\n整数 小 = 0;\n" +
                    "测试输出(查找.最大最小(表, 大, 小));\n测试输出(大);\n测试输出(小);\n停止")
                    == "1|12|-3",
                "12 与 -3 一趟拿到");

            // ---- ⑫ 库文件头的口径按源码钉住(免得以后改了代码忘了改说明) ----
            string 排序文本 = File.ReadAllText(排序路径);
            string 查找文本 = File.ReadAllText(查找路径);
            记录("排序与查找库 头注释写清了口径(插入排序 / 稳定 / 只收固定数组 / 空表到不了)",
                排序文本.Contains("插入排序", StringComparison.Ordinal)
                && 排序文本.Contains("稳定", StringComparison.Ordinal)
                && 排序文本.Contains("只收固定数组", StringComparison.Ordinal)
                && 排序文本.Contains("编不过", StringComparison.Ordinal)
                && 查找文本.Contains("找不到一律给", StringComparison.Ordinal)
                && 查找文本.Contains("实际到不了", StringComparison.Ordinal)
                && 查找文本.Contains("必须先升序", StringComparison.Ordinal),
                "插入排序 / 稳定 / 只收固定数组 / 字符串表编不过 / -1 口径 / 空表到不了 / 二分要先升序");

            // ---- ⑬ R3-4 的验收数字:Sample\库 到 8 个库 ----
            int 库数 = Directory.Exists(库目录) ? Directory.GetFiles(库目录, "*.hb").Length : 0;
            记录("基础库 Sample\\库 到 8 个库(R3-4 验收线:本批 排序.hb + 查找.hb 入库)",
                库数 >= 8,
                $"{库数} 个 .hb(本批前是 7 个)");
        }
    }
}
