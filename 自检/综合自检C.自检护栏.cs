using System;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// R4-1:给自检自己的两道护栏各留一条**能红的钉子**。
    ///
    /// 为什么单开一组:护栏最容易"看着在守门、其实门开着"——
    /// 步数上限写错一个数(0 就等于没设)、分组表里组名重了(FAIL 行点不出是哪一组),
    /// 从外面看都是"自检全绿"。这里拿**真机器**跑一遍死循环、拿表里的名字数一遍。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary>
        /// ① **步数上限真能拦住死循环**:真跑一段 `当 (真)` 的循环,断言它撞上限报错。上限在这条用例里
        ///    **临时调小到 20 万条**(几毫秒就撞上)—— 验的是机制,不是那个大数;大数由 ② 单独钉。
        ///    **另外挂一个 3 秒的"保险丝"线程**(到点 `请求中断()`):上限哪天被改坏,这里也只会
        ///    在 3 秒内**如实红**、而不是把整个自检挂死 —— 护栏自己的用例不许变成新的挂死点。
        /// ② **默认值真挂上了**:自检里 `new 虚拟机C()` 出来的机器,步数上限必须等于 `自检步数上限`
        ///    (靠 `虚拟机C.本线程默认步数上限`,由 `运行()` 在开头设上、跑完还原)。
        /// ③ **分组表自己的体检**:组名唯一 + 每个动作都有着落。
        /// </summary>
        private static void 自检护栏自检()
        {
            // ① 死循环撞上限(上限临时调小;另配一根 3 秒保险丝,上限被改坏也不会挂死)
            var 死循环机 = new 虚拟机C { 步数上限 = 200_000 };
            var 保险丝 = new System.Threading.Thread(() =>
            {
                try { System.Threading.Thread.Sleep(3000); 死循环机.请求中断(); } catch { }
            })
            { IsBackground = true, Name = "R4-1 步数上限保险丝" };
            保险丝.Start();
            string 文案 = 异常文本(() => 死循环机.运行(编译("整数 i = 0;\n当 (真)\n{\ni = i + 1;\n}\n停止")));
            记录("R4-1 死循环撞步数上限(不再挂死自检)", 文案.Contains("超过上限"),
                $"上限 20 万条;文案 = {(文案.Length == 0 ? "(居然跑完了 —— 上限没生效,是保险丝把它停下的)" : 文案)}");

            // ② 自检里新造的机器默认带上限(线程级默认值在 `运行()` 里设)
            long 默认限 = new 虚拟机C().步数上限;
            记录("R4-1 自检里新造的虚拟机默认带步数上限(线程级)",
                默认限 == 自检步数上限, $"默认 {默认限} / 期望 {自检步数上限}");

            // ③ 分组表自己的体检
            var 重名 = 分组表.GroupBy(x => x.组名, StringComparer.Ordinal).Where(g => g.Count() > 1)
                .Select(g => g.Key).Take(3).ToArray();
            记录("R4-1 分组表 组名唯一且每个动作都有着落",
                重名.Length == 0 && 分组表.All(x => x.动作 != null),
                重名.Length == 0
                    ? $"共 {分组表.Length} 组,组名不重"
                    : $"{分组表.Length} 组里有重名:{string.Join(" / ", 重名)} —— FAIL 行点不出是哪一组");
        }
    }
}
