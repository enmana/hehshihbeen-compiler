                $"最大 {虚拟机C.最大内存大小} / 默认 {虚拟机C.默认内存大小}");

            // ② 调小/调大:内存数组与栈指针都跟着换
            默认.设内存大小(512 * 1024);
            记录("内存 设内存大小后数组与栈指针都跟着换", 默认.内存大小 == 512 * 1024 && 默认.内存.Length == 512 * 1024 && 默认.栈指针 == 512 * 1024,
