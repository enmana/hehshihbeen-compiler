                && 工程文件C.解析内存("40000") == 40000,
                "1MB/1m/512KB/512k/40000");
            期望异常("工程内存 写乱了给出明确错误", () => 工程文件C.解析内存("3GB"), "写的不对");
            期望异常("工程内存 超上限给出明确错误", () => 工程文件C.解析内存("128MB"), "超范围");
            记录("工程内存 8MB 认(通用化之后 1MB 不再是顶)",
                工程文件C.解析内存("8MB") == 8 * 1024 * 1024 && 工程文件C.解析内存("64MB") == 64 * 1024 * 1024,
