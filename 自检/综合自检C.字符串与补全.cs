            载.装载(一小段);
            记录("虚拟机 装载后记得住这份机器码(界面据此避免重复装载)", ReferenceEquals(载.机器码, 一小段),
                $"机器码 {载.机器码.Length} 字节");
            载.设内存大小(512 * 1024);
            记录("虚拟机 换了内存就把机器码标记成空(界面会重新装载)", 载.机器码.Length == 0, "换内存 → 机器码清空");

            // ③ 超范围给出明确错误
            期望异常("内存 小于下限报错", () => new 虚拟机C().设内存大小(16), "16");
            期望异常("内存 大于上限报错", () => new 虚拟机C().设内存大小(128 * 1024 * 1024), "134217728");
            期望异常("内存 装不下机器码时给出明确错误", () =>
            {
                var vm = new 虚拟机C();
                vm.设内存大小(虚拟机C.最小内存大小);
                vm.装载(new byte[虚拟机C.最小内存大小 + 4]);
            }, "装不进");

            // ④ 可调内存的实际用处:同一个程序在 4KB 里跑不动、在 1MB 里跑得动
            string 源 = "加载立即数 R0, 1\n存储 R0, [40000]\n加载 R0, [40000]\n停止";
            var 码 = 汇编(源);
            var 小 = new 虚拟机C();
            小.设内存大小(虚拟机C.最小内存大小);
            bool 小内存炸了 = false;
            try { 小.运行(码); } catch (Exception ex) { 小内存炸了 = ex.Message.Contains("越界"); }
