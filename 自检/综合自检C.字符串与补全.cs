                记录("工程堆 留空 = 默认 64KB", 工程文件C.解析堆("") == 64 * 1024 && 工程文件C.解析堆(null) == 64 * 1024, "留空");
                记录("工程堆 认 KB/K/纯数字,大小写不计较",
