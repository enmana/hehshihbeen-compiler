        /// <summary> 左列是不是右列的子序列(按顺序出现即可,中间可以夹别的) </summary>
        private static bool 子序列(IReadOnlyList<int> 左列, IReadOnlyList<int> 右列)
        {
            int j = 0;
            foreach (int 值 in 左列)
            {
                if (j < 右列.Count && 值 == 右列[j]) j++;
                if (j == 右列.Count) return true;
            }
            return j == 右列.Count;
        }

