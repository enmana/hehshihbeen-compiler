            catch (Exception ex) { 记录异常("日志与事件库 事件归一与分派", ex); }

            // ---- ⑨ 端到端:标准工程 示例53_日志与事件 ----
            //   走**共用那一份 `运行带输出`**:它自己认工程目录里的 `事件脚本.txt`(按帧喂)、
            //   也自己挂无头呈现 ⇒ 与 `hbcc --run --事件脚本 …` 同一条口径(硬规矩 6:不开窗也能验)。
            //   于是这一格对的就是文件末尾那行 `// 预期输出:`(逐段对,与自检通用那一条同一个口径)。
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例53_日志与事件");
                string? 源码路径 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码路径 == null || !File.Exists(源码路径))
                {
                    跳过("日志与事件库 标准工程 示例53 逐段对预期输出", $"找不到 {源码路径}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码路径);
                    var 期望段 = 解析预期输出(行表);
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录);
                    var 实得段 = 输出.Trim().Split('\n')
                        .Select(x => x.TrimEnd('\r').Trim()).Where(x => x.Length > 0).ToList();
                    bool 好 = 期望段.Count > 0 && 实得段.Count == 期望段.Count
                        && 实得段.Zip(期望段, (a, b) => a == b).All(x => x);
                    记录("日志与事件库 标准工程 示例53 逐段对预期输出(日志三出口 / 事件归一与分派 / 要退出)",
                        好, 好 ? $"逐段一致({期望段.Count} 段)"
                              : $"期望 {期望段.Count} 段 / 实得 {实得段.Count} 段" +
                                (期望段.Count > 0 && 实得段.Count > 0
                                    ? $";第 1 段 期望[{期望段[0]}] 实得[{实得段[0]}]" : ""));
                }
            }
            catch (Exception ex) { 记录异常("日志与事件库 标准工程 示例53", ex); }

            // ---- ⑩ 接线哨兵 ----
            try
            {
                var 期望模块 = new (string 路径, string 模块, int 公开)[]
                {
                    (日志路径, "模块 日志", 23),
                    (事件路径, "模块 事件", 23),
                };
                var 问题 = new List<string>();
                foreach (var (路径, 模块, 期望数) in 期望模块)
                {
                    string 文 = File.ReadAllText(路径);
                    int 公开数 = 0;
                    foreach (var 行 in 文.Split('\n'))
                        if (行.TrimStart().StartsWith("方法 ", StringComparison.Ordinal)) 公开数++;
                    string 名 = Path.GetFileName(路径);
                    if (!文.Contains(模块, StringComparison.Ordinal)) 问题.Add($"{名}:没有 `{模块}`");
                    if (!文.Contains("用法", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `用法`");
                    if (!文.Contains("复杂度:", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `复杂度:`");
                    if (!文.Contains("内存账", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `内存账`");
                    if (!文.Contains("英文对照", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `英文对照`");
                    if (公开数 != 期望数) 问题.Add($"{名}:公开函数 {公开数},期望 {期望数}");
                }
                记录("日志与事件库 接线哨兵:两个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(23 / 23)",
                    问题.Count == 0,
                    问题.Count == 0 ? "两个库五段齐、公开函数数对上" : string.Join(" / ", 问题));
            }
            catch (Exception ex) { 记录异常("日志与事件库 接线哨兵", ex); }
        }
    }
