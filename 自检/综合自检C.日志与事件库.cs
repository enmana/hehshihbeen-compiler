                bool 好 = 实得.Count == 期望行.Length;
                int 第一坏 = -1;
                if (好)
                {
                    for (int i = 0; i < 期望行.Length; i++)
                        if (实得[i] != 期望行[i]) { 好 = false; 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实得.Count} 行逐行对上"
                    : $"实测 {实得.Count} 行 / 期望 {期望行.Length} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实得[第一坏]}> 期望=<{期望行[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实得)}>");
                记录(名, 好, 说明);
            }

