using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 位集合与矩阵库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 集路径 = Path.Combine(库目录, "位集合.hb").Replace('\\', '/');
            string 查路径 = Path.Combine(库目录, "并查集.hb").Replace('\\', '/');
            string 阵路径 = Path.Combine(库目录, "矩阵.hb").Replace('\\', '/');
            if (!File.Exists(集路径) || !File.Exists(查路径) || !File.Exists(阵路径))
            {
                跳过("位集合与矩阵库 定位三个库文件", $"找不到 {集路径} / {查路径} / {阵路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{集路径}\"\n包含 \"{查路径}\"\n包含 \"{阵路径}\"\n";

            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // ============================================================
            // ① 32 倍省内存:两种装法各跑一遍,把**字节数**都从程序里打出来再算比值
            // ============================================================
            try
            {
                const int 标记数 = 1024;
                int 需要字 = (标记数 + 31) / 32;
                int 一格一个标记字节 = 标记数 * 4;        // 整数 标记[1024]
                int 位集合字节 = 需要字 * 4;              // 整数 格[32]
                var 源 = new StringBuilder(头);
                源.Append($"整数 标记[{标记数}];\n整数 格[{需要字}];\n位集合.清全部(格);\n");
                源.Append($"输出行(位集合.要几个字({标记数}));\n");
                源.Append("输出行(位集合.位宽(格));\n");
                源.Append("整数 i = 0;\n");
                源.Append($"当 (i < {标记数})\n{{\n    标记[i] = 1;\n    位集合.置位(格, i);\n    i = i + 1;\n}}\n");
                源.Append($"输出行(位集合.数一(格, {标记数}));\n");
                源.Append("整数 几个 = 0;\n整数 j = 0;\n");
                源.Append($"当 (j < {标记数})\n{{\n    如果 (标记[j] != 0)\n    {{\n        几个 = 几个 + 1;\n    }}\n    j = j + 1;\n}}\n");
                源.Append("输出行(几个);\n");
                源.Append($"输出行({需要字} * 4);\n");                 // 位集合这套占几个字节
                源.Append($"输出行({标记数} * 4);\n");               // 一格一个标记占几个字节
                源.Append($"输出行(位集合.要几个字(1000));\n");
                源.Append($"输出行(位集合.要几个字(32));\n");
                源.Append($"输出行(位集合.要几个字(0));\n");
                源.Append("停止\n");
                string 期 = string.Join("|", new[]
                {
                    需要字.ToString(), (需要字 * 32).ToString(), 标记数.ToString(), 标记数.ToString(),
                    位集合字节.ToString(), 一格一个标记字节.ToString(), "32", "1", "0"
                });
                string 实 = 跑(源.ToString());
                int 比值 = 一格一个标记字节 / 位集合字节;
                记录($"位集合 32 倍省内存**真量过**:{标记数} 个标记两种装法各跑一遍({一格一个标记字节} 字节 对 {位集合字节} 字节 = {比值} 倍)",
                    实 == 期 && 比值 == 32, 对拍说明(期, 实) + $";比值 {比值}(该是 32)");
            }
            catch (Exception ex) { 记录异常("位集合 32 倍省内存真量过", ex); }

            // ============================================================
            // ② 位集合:随机置 / 清 / 翻 / 取与 C# 的 bool[] 逐条对拍
            // ============================================================
            try
            {
                const int 位宽 = 256;                      // 8 个字
                var 随机 = new Random(20261010);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append($"整数 格[{位宽 / 32}];\n位集合.清全部(格);\n");
                var 参考 = new bool[位宽];
                for (int 轮 = 0; 轮 < 200; 轮++)
                {
                    int 位 = 随机.Next(-4, 位宽 + 4);
                    int 动作 = 随机.Next(4);
                    string 调用 = 动作 switch
                    {
                        0 => "置位", 1 => "清位", 2 => "翻位", _ => "取位"
                    };
                    源.Append($"输出行(位集合.{调用}(格, {位}));\n");
                    bool 在界内 = 位 >= 0 && 位 < 位宽;
                    if (调用 == "取位")
                        期望.Append(在界内 && 参考[位] ? 1 : 0);
                    else
                    {
                        if (!在界内) 期望.Append('0');
                        else
                        {
                            期望.Append('1');
                            if (调用 == "置位") 参考[位] = true;
                            else if (调用 == "清位") 参考[位] = false;
                            else 参考[位] = !参考[位];
                        }
                    }
                    期望.Append('|');
                    // 每几步把"数一"与"找首个一 / 找首个零"也对一遍(它们看的是前 `位宽` 位)
                    if (轮 % 20 == 19)
                    {
                        int 参考数一 = 参考.Count(x => x);
                        int 参考找一 = Array.IndexOf(参考, true);
                        int 参考找零 = Array.IndexOf(参考, false);
                        源.Append($"输出行(位集合.数一(格, {位宽}));\n");
                        源.Append($"输出行(位集合.找首个一(格, {位宽}));\n");
                        源.Append($"输出行(位集合.找首个零(格, {位宽}));\n");
                        期望.Append(参考数一).Append('|').Append(参考找一).Append('|').Append(参考找零).Append('|');
                    }
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("位集合与矩阵库 位集合:置位 / 清位 / 翻位 / 取位 / 数一 / 找首个一 / 找首个零(200 轮随机操作,位宽 256,与 C# 的 bool[] 逐条对拍;含越界那几档)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 位集合随机对拍", ex); }

            // ============================================================
            // ③ 并查集:随机并 / 同组与 C# 参考实现逐条对拍
            // ============================================================
            try
            {
                const int 几个 = 12;
                var 随机 = new Random(20261011);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append($"整数 父[{几个}];\n整数 秩[{几个}];\n并查集.初始化(父, 秩, {几个});\n");
                var 参考父 = Enumerable.Range(0, 几个).ToArray();
                var 参考秩 = new int[几个];
                // 参考实现**照库里的口径**来:找根(压不压缩都行 —— 根是一样的)+ **按秩合并**
                // (这一句必须照抄:不然"谁当新根"两边不一致,根的下标就对不上了)
                int 参考找(int x)
                {
                    while (参考父[x] != x) x = 参考父[x];
                    return x;
                }
                for (int 轮 = 0; 轮 < 160; 轮++)
                {
                    int 动作 = 随机.Next(5);
                    int 左 = 随机.Next(-1, 几个 + 1);
                    int 右 = 随机.Next(-1, 几个 + 1);
                    if (动作 <= 1)                             // 并
                    {
                        源.Append($"输出行(并查集.并(父, 秩, {左}, {右}));\n");
                        bool 界内 = 左 >= 0 && 左 < 几个 && 右 >= 0 && 右 < 几个;
                        int 根左 = 界内 ? 参考找(左) : -1, 根右 = 界内 ? 参考找(右) : -1;
                        if (根左 < 0 || 根右 < 0 || 根左 == 根右) 期望.Append('0');
                        else
                        {
                            if (参考秩[根左] < 参考秩[根右]) 参考父[根左] = 根右;
                            else if (参考秩[根左] > 参考秩[根右]) 参考父[根右] = 根左;
                            else { 参考父[根右] = 根左; 参考秩[根左] = 参考秩[根左] + 1; }
                            期望.Append('1');
                        }
                        期望.Append('|');
                    }
                    else if (动作 == 2)                        // 同组
                    {
                        源.Append($"输出行(并查集.同组(父, {左}, {右}));\n");
                        bool 界内 = 左 >= 0 && 左 < 几个 && 右 >= 0 && 右 < 几个;
                        期望.Append(界内 && 参考找(左) == 参考找(右) ? 1 : 0).Append('|');
                    }
                    else if (动作 == 3)                        // 找(要的是根,与压缩细节无关)
                    {
                        源.Append($"输出行(并查集.找(父, {左}));\n");
                        期望.Append(左 >= 0 && 左 < 几个 ? 参考找(左) : -1).Append('|');
                    }
                    else                                       // 组数 / 是根
                    {
                        源.Append($"输出行(并查集.组数(父, {几个}));\n");
                        源.Append($"输出行(并查集.是根(父, {左}));\n");
                        int 组数 = 0;
                        for (int i = 0; i < 几个; i++) if (参考找(i) == i) 组数++;
                        期望.Append(组数).Append('|');
                        期望.Append(左 >= 0 && 左 < 几个 && 参考父[左] == 左 ? 1 : 0).Append('|');
                    }
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("位集合与矩阵库 并查集:并 / 同组 / 找 / 组数 / 是根(160 轮随机操作,12 个元素,与 C# 参考实现逐条对拍;含越界那几档)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 并查集随机对拍", ex); }

            // ============================================================
            // ④ 并查集:路径压缩真起作用(手工造一条链,`找` 一次之后整条链都挂到根上)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 父[6];\n" +
                    "整数 秩[6];\n" +
                    "并查集.初始化(父, 秩, 6);\n" +
                    "父[1] = 0;\n" +                              // 手工造链:0 ← 1 ← 2 ← 3 ← 4
                    "父[2] = 1;\n" +
                    "父[3] = 2;\n" +
                    "父[4] = 3;\n" +
                    "输出行(并查集.找(父, 4));\n" +               // 1:根是 0
                    "输出行(父[4]);\n" +                           // 2:0(压过:原来指向 3)
                    "输出行(父[3]);\n" +                           // 3:0(原来指向 2)
                    "输出行(父[2]);\n" +                           // 4:0(原来指向 1)
                    "输出行(父[1]);\n" +                           // 5:0(本来就指 0)
                    "输出行(父[5]);\n" +                           // 6:5(没被碰过的还是自己)
                    "输出行(并查集.组里几个(父, 6, 0));\n" +      // 7:5(0..4 一伙)
                    "输出行(并查集.最大组人数(父, 6));\n" +           // 8:5
                    "输出行(并查集.组数(父, 6));\n" +             // 9:2(0..4 / 5)
                    "停止\n");
                string 期 = "0|0|0|0|0|5|5|5|2";
                string 实 = 跑(源.ToString());
                记录("位集合与矩阵库 并查集路径压缩:手工造 5 节链,`找` 一次之后链上每一节都直接挂在根上(逐个打出来对)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 并查集路径压缩", ex); }

            // ============================================================
            // ⑤ 矩阵:乘 / 转置 / 迹 / 行和 / 列和与 C# 参考实现逐条对拍
            // ============================================================
            try
            {
                var 随机 = new Random(20261012);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                // 固定一批小矩阵,逐个把五种动作走一遍(输出与 C# 侧现算的期望逐条对)
                for (int 轮 = 0; 轮 < 12; 轮++)
                {
                    int 左行 = 1 + 随机.Next(3), 左列 = 1 + 随机.Next(3);
                    int 右列 = 1 + 随机.Next(3);
                    var 左 = Enumerable.Range(0, 左行 * 左列).Select(_ => 随机.Next(-9, 10)).ToArray();
                    var 右 = Enumerable.Range(0, 左列 * 右列).Select(_ => 随机.Next(-9, 10)).ToArray();
                    源.Append($"整数 左阵{轮}[{左.Length}] = [{string.Join(", ", 左)}];\n");
                    源.Append($"整数 右阵{轮}[{右.Length}] = [{string.Join(", ", 右)}];\n");
                    源.Append($"整数 积{轮}[{左行 * 右列}];\n");
                    源.Append($"整数 转{轮}[{左.Length}];\n");
                    源.Append($"整数 行们{轮}[{左行}];\n");
                    源.Append($"整数 列们{轮}[{左列}];\n");
                    源.Append($"输出行(矩阵.相乘(左阵{轮}, {左行}, {左列}, 右阵{轮}, {右列}, 积{轮}));\n");
                    期望.Append('1').Append('|');
                    for (int r = 0; r < 左行; r++)
                        for (int c = 0; c < 右列; c++)
                        {
                            int 和 = 0;
                            for (int k = 0; k < 左列; k++) 和 += 左[r * 左列 + k] * 右[k * 右列 + c];
                            源.Append($"输出行(积{轮}[{r * 右列 + c}]);\n");
                            期望.Append(unchecked((int)和)).Append('|');
                        }
                    源.Append($"输出行(矩阵.转置(左阵{轮}, {左行}, {左列}, 转{轮}));\n");
                    期望.Append('1').Append('|');
                    for (int r = 0; r < 左行; r++)
                        for (int c = 0; c < 左列; c++)
                        {
                            源.Append($"输出行(转{轮}[{c * 左行 + r}]);\n");
                            期望.Append(左[r * 左列 + c]).Append('|');
                        }
                    // 转置之后"行列反过来"要用 `取格` 直接验一遍(转后的列数 = 原来的行数)
                    for (int r = 0; r < 左行; r++)
                        for (int c = 0; c < 左列; c++)
                        {
                            源.Append($"输出行(矩阵.取格(转{轮}, {左行}, {c}, {r}));\n");
                            期望.Append(左[r * 左列 + c]).Append('|');
                        }
                    源.Append($"输出行(矩阵.行和(左阵{轮}, {左列}, 行们{轮}));\n");
                    期望.Append(左行).Append('|');
                    for (int r = 0; r < 左行; r++)
                    {
                        int 和 = 0;
                        for (int c = 0; c < 左列; c++) 和 += 左[r * 左列 + c];
                        源.Append($"输出行(行们{轮}[{r}]);\n");
                        期望.Append(unchecked((int)和)).Append('|');
                    }
                    源.Append($"输出行(矩阵.列和(左阵{轮}, {左列}, 列们{轮}));\n");
                    期望.Append(左列).Append('|');
                    for (int c = 0; c < 左列; c++)
                    {
                        int 和 = 0;
                        for (int r = 0; r < 左行; r++) 和 += 左[r * 左列 + c];
                        源.Append($"输出行(列们{轮}[{c}]);\n");
                        期望.Append(unchecked((int)和)).Append('|');
                    }
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("位集合与矩阵库 矩阵:相乘 / 转置 / 取格 / 行和 / 列和(12 组随机小矩阵,与 C# 参考实现逐条对拍)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 矩阵随机对拍", ex); }

            // ============================================================
            // ⑥ 端到端:标准工程 示例40_位集合与矩阵 的输出逐行对 `// 预期输出:`
            // ============================================================
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例40_位集合与矩阵");
                string? 源码 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码 == null || !File.Exists(源码))
                {
                    跳过("位集合与矩阵库 标准工程 示例40 逐行对预期输出", $"找不到 {源码}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码);
                    var 期望行 = 解析预期输出(行表);
                    // ⚠ 这一篇是**带 UI** 的标准工程:那一行 `// 预期输出:` 里既有窗口前那一段
                    //   `输出行`,也有开窗之后逐帧画出来的命令(H82 批 4 的口径)。
                    //   ⇒ 必须走共享帮手 `运行带输出`:它**挂无头呈现口**(绘制命令逐条进同一份输出缓冲)
                    //   并按 `基目录` 自动读工程目录那份 `事件脚本.txt`(帧数/键鼠都从那儿来)。
                    //   ⚠ 别退回"自己 new 虚拟机C"那一版:窗口开不出来 ⇒ 只跑出窗口前那一段。
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录, 示例堆大小(工程目录));
                    string 实得 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望行);
                    bool 好 = 期望行.Count > 0 && 实得 == 应有;
                    记录("位集合与矩阵库 标准工程 示例40 逐条对预期输出(三个库在真程序里的那一趟:筛素数 → 并查集分组 → 矩阵算)",
                        好, 好 ? $"逐行一致({期望行.Count} 行,含开窗那一半)" : 逐行差说明(应有, 实得));
                }
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 标准工程 示例40", ex); }

            // ============================================================
            // ⑦ 接线哨兵:三个库在位 + 头注释五段齐 + 公开方法个数
            // ============================================================
            try
            {
                string 集文 = File.ReadAllText(集路径);
                string 查文 = File.ReadAllText(查路径);
                string 阵文 = File.ReadAllText(阵路径);
                bool 头齐(string 文)
                    => 文.Contains("口径(2026-", StringComparison.Ordinal)
                    && 文.Contains("提供的函数(", StringComparison.Ordinal)
                    && 文.Contains("英文对照", StringComparison.Ordinal)
                    && 文.Contains("复杂度", StringComparison.Ordinal)
                    && 文.Contains("边界(如实登记", StringComparison.Ordinal);
                int 数方法(string 文)
                {
                    int 数 = 0;
                    foreach (string 行 in 文.Split('\n'))
                        if (行.StartsWith("方法 ", StringComparison.Ordinal)) 数++;
                    return 数;
                }
                int 集法 = 数方法(集文), 查法 = 数方法(查文), 阵法 = 数方法(阵文);
                bool 好 = 头齐(集文) && 头齐(查文) && 头齐(阵文)
                    && 集文.Contains("模块 位集合", StringComparison.Ordinal)
                    && 查文.Contains("模块 并查集", StringComparison.Ordinal)
                    && 阵文.Contains("模块 矩阵", StringComparison.Ordinal)
                    && 集法 == 15 && 查法 == 9 && 阵法 == 12;
                记录("位集合与矩阵库 接线哨兵:三个库都在盘上、头注释五段齐、公开方法数(位集合 15 / 并查集 9 / 矩阵 12)",
                    好, $"位集合 {集法} 个 / 并查集 {查法} 个 / 矩阵 {阵法} 个");
            }
            catch (Exception ex) { 记录异常("位集合与矩阵库 接线哨兵", ex); }
        }
    }
