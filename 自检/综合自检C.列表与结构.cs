                    string 文本 = 异常文本(() => 汇编(源));
                    if (文本.Length == 0) { 问题.Add($"{名}:本该报错却没报"); continue; }
                    string 不合 = 扫(文本, 名);
                    if (不合.Length > 0) 问题.Add(不合);
                    if (文本.Contains("第") && 文本.Contains("行")) 带了行号++;
                    else 问题.Add($"{名}:报错没带行号 —— {文本}");
                }
                记录("P32 报错原文都合规范(无感叹号/口语词)且都带行号", 问题.Count == 0,
