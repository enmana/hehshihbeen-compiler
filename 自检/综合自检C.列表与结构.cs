        /// <summary> 汇编 + 跑一遍,返回(编译结果, 输出文本)—— 与 `列表自检` 里那个局部版同一套(那边自带内存/堆/池参数)</summary>
        private static (汇编调试结果C 编译, string 输出) 跑带初值(string 源)
        {
            var 编译 = new 汇编器C().汇编多文件带调试(new List<(string, string)> { ("主程序.hb", 源) });
            var vm = new 虚拟机C();
            var sb = new System.Text.StringBuilder();
            vm.输出目标 = b => sb.Append((char)b);
            vm.运行(编译);
            return (编译, sb.ToString().Trim());
        }

        /// <summary> 汇编应该失败,返回它的说明报错(没失败就返回空串)</summary>
        private static string 异常文本(Action 动作)
        {
            try { 动作(); return ""; }
            catch (Exception ex) { return ex.Message; }
        }

        /// <summary>
        /// 汇编应该失败,返回(真抛了异常没有, 报错文案)。
        ///
        /// **R4-2**:否定式断言("这条文案里**没有** X")必须先看**真抛了没有** —— `异常文本` 在"根本没抛"
        /// 的时候回的是**空串**,空串当然"不含 X" ⇒ 该报的错一个字没报,断言反而 PASS。拿这个函数写:
        /// `var (抛了, 文案) = 异常与文案(...); 记录(名, 抛了 &amp;&amp; !文案.Contains("X"), 文案);`
        /// </summary>
        private static (bool 抛了, string 文案) 异常与文案(Action 动作)
        {
            try { 动作(); return (false, ""); }
            catch (Exception ex) { return (true, ex.Message); }
        }

        /// <summary>
        /// P32:文案规范的**机检**。用户定的规矩是"① 书面语(不用口语、不用感叹句)② 报错必须带行号 ③ 给改法"。
        /// 三条里能被机器钉住的两条在这里钉:
        ///   ① 全角感叹号 `！`、口语词(吧/啦/哦/呀/嘛/呢/啊/哈)、表情符号 —— **任何面向用户的文本里都不许有**
        ///      (帮助四页 + 一批故意写错的程序的报错原文,一起扫);
        ///   ② 每条报错必须带行号(`第 N 行`)—— 界面靠它画红线、命令行靠它定位。
        /// 第三条(给改法)机器判不准,靠写的人 + `期望异常` 那条断言(每条都要求出现具体写法)兜着。
        /// </summary>
        private static void 文案规范自检()
        {
            string[] 禁词 = ["！", "吧", "啦", "哦", "呀", "嘛", "呢", "哈哈", "哎呀", "🙂", "😊", "😉"];
            string 扫(string 文本, string 哪)
            {
                var 抓到 = 禁词.Where(w => 文本.Contains(w, StringComparison.Ordinal)).ToArray();
                return 抓到.Length == 0 ? "" : $"{哪} 里出现了 {string.Join("、", 抓到)}";
            }

            // ① 帮助文本四页:面向用户最多的一份文案
            跑且断言("P32 帮助四页文案都合规范(无感叹号/口语词/表情)", () =>
            {
                var 页 = new (string 名, string 文本)[]
                {
                    ("快速上手", 帮助文本C.快速上手()),
                    ("指令速查", 帮助文本C.指令速查()),
                    ("中间层速查", 帮助文本C.中间层速查()),
                    ("关于", 帮助文本C.关于()),
                };
                var 问题 = 页.Select(x => 扫(x.文本, x.名)).Where(x => x.Length > 0).ToArray();
                记录("P32 帮助四页文案都合规范(无感叹号/口语词/表情)", 问题.Length == 0,
                    问题.Length == 0 ? $"四页共 {页.Sum(x => x.文本.Length)} 字符" : string.Join(";", 问题));
            });

