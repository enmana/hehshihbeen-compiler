                    ("字符串列表声明给初值", "字符串 名单[] = [\"文本\"];\n停止", "添加"),
                    ("结构字段里的列表放字符串元素", "结构 筐\n{\n字符串 数[];\n}\n停止", "放到结构外面的顶层列表"),
