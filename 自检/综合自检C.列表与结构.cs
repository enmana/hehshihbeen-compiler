            // ④ 保留字清单与类型表:帮助文档从唯一事实源生成,自检钉住"表和文档一致"(第96批)
            {
                string 速查 = 帮助文本C.中间层速查();
                var 缺类型 = 类型C.表.Where(类型 => !速查.Contains(类型.中文) || !速查.Contains(类型.英文)
                    || !速查.Contains($"{类型.宽度} 字节")).Select(x => x.中文).ToList();
                记录("帮助速查 类型表从 类型C.表 生成(每个类型的中英名 + 位宽都在)", 缺类型.Count == 0,
                    缺类型.Count == 0 ? $"{类型C.表.Length} 个基本类型逐条对过" : string.Join("/", 缺类型));
                记录("帮助速查 写清『整数=32 位 / 短整数=16 位 / 字节=8 位』(不用翻库文件才知道)",
                    速查.Contains("8 位") && 速查.Contains("16 位") && 速查.Contains("32 位")
                    && 速查.Contains("32 位有符号") && 速查.Contains("整数"), "位宽一句话");
