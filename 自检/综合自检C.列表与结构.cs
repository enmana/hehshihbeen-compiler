                    ("下标越界(编译期)", "整数 表[2];\n测试输出(表[5]);\n停止"),
                    ("重复定义", "整数 初值 = 1;\n整数 初值 = 2;\n停止"),
                    ("数组参数实参不对", "方法 g(整数 表[])\n{\n返回 表[0];\n}\n整数 初值 = 1;\ng(初值);\n停止"),
                    ("字符串列表声明给初值", "字符串 名单[] = [\"文本\"];\n停止"),
                    ("结构字段里的列表放字符串元素", "结构 筐\n{\n字符串 数[];\n}\n停止"),
                    ("出参数实参不对", "方法 f(字符串 出 s)\n{\ns = \"a\";\n}\nf(\"字面量\");\n停止"),
                    ("测试块写在函数里", "方法 f()\n{\n测试 用例\n{\n断言 1 == 1;\n}\n}\n停止"),
                    ("断言写在块外", "断言 1 == 1;\n停止"),
                    ("断言说明不是字面量", "测试 用例\n{\n整数 n = 1;\n断言 n == 1, n;\n}\n停止"),
                    ("模块头不在第一条", "整数 初值 = 1;\n模块 数学\n停止"),
                    ("含不存在的文件", "包含 \"没有这个文件.hb\"\n停止"),
                    ("多写了操作数", "停止 R5\n停止"),
                };
                var 问题 = new List<string>();
                int 带了行号 = 0;
