using System.Text;
using hehshihbeen_compiler;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **G2(回调 / 事件)**:`地址(函数名)` 取**代码地址** + `回调 名字 = 地址(处理函数);` 声明 +
    /// `间接调用(名字, 实参…)` 按地址调 —— 三件合起来才是"真回调"(排序比较器 / 按钮回调 / 状态机 /
    /// 自举解释器的分派表都靠它)。**ISA / 机器码一个字没动**:调用的还是 R1-4 那条 `调用寄存器`。
    ///
    /// 这个分组钉六件事:
    /// ① **语义**:取到的地址真的能调、`返回` 真的回得来、返回值在 R0(与直接调用一字不差);
    /// ② **换地址**:同一个回调变量中途改指另一个函数,下一次调用就调新的那个;
    /// ③ **当参数传**:`排序(数, 地址(升序))` 这种"回调参数"(形参写成 `回调 比较(整数, 整数)`)真能排对;
    /// ④ **实参表按声明核对**:个数不对在**编译期**就给带行号的话;
    /// ⑤ **老写法一个字不破**:`地址(变量)` 仍是数据地址(不是代码地址);
    /// ⑥ **调用约定同一条**(接线哨兵):同一段调用,直接调用与间接调用只差最后那一条指令。
    /// </summary>
    public static partial class 综合自检C
    {
        private static void 回调自检()
        {
            // 组里凡是"可能抛"的检查都走它:抛了如实记一条 FAIL,不让整组连坐
            void 检查(string 名称, Func<(bool 通过, string 详情)> 试)
            {
                try
                {
                    var (通过, 详情) = 试();
                    记录(名称, 通过, 详情);
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            (string 输出, string 报错) 跑(string 源)
            {
                var (输出, _, 报错) = 编跑([("主程序.hb", 源)], 虚拟机C.默认内存大小,
                    中间层C.默认堆大小, 中间层C.默认池大小, -1);
                return (输出, 报错);
            }

            // ---- ① 语义:地址取到了、间接调用真的调过去、返回值与直接调用一致 ----
            const string 基本源 = """
                方法 加一(整数 x) 返回 整数 {
                    返回 x + 1;
                }

                方法 双倍(整数 x) 返回 整数 {
                    返回 x * 2;
                }

                回调 处理 = 地址(加一);
                测试输出(间接调用(处理, 41));
                测试输出(处理 == 地址(加一));
                处理 = 地址(双倍);
                测试输出(间接调用(处理, 21));
                测试输出(处理 == 地址(加一));
                测试输出(间接调用(处理, 5) + 1);
                停止
                """;
            检查("G2 `地址(函数名)` + `间接调用` 真调得动、返回 42/42/50,回调变量还能改指别的函数、也能比较相等", () =>
            {
                var (输出, 报错) = 跑(基本源);
                return (输出 == "42|1|42|0|11", $"输出=[{输出}] 报错=[{报错}]");
            });

            // ---- ③ 当参数传:库函数收回调(形参带签名),排序真的按那个比较器排 ----
            //    ⚠ 形参名 H104 起也要过保留字那一关 ⇒ 那个比较器参数叫 `比法`(不能叫 `比较`:它是 ISA 助记符)
            const string 比较器源 = """
                方法 排序(整数 表[], 回调 比法(整数, 整数)) {
                    整数 i = 0;
                    当 (i < 表.长度()) {
                        整数 j = 0;
                        当 (j < 表.长度() - 1 - i) {
                            如果 (间接调用(比法, 表[j], 表[j + 1]) > 0) {
                                整数 换 = 表[j];
                                表[j] = 表[j + 1];
                                表[j + 1] = 换;
                            }
                            j = j + 1;
                        }
                        i = i + 1;
                    }
                    返回
                }

                方法 升序(整数 a, 整数 b) 返回 整数 {
                    返回 a - b;
                }

                方法 降序(整数 a, 整数 b) 返回 整数 {
                    返回 b - a;
                }

                整数 数[5] = [3, 1, 4, 1, 6];
                排序(数, 地址(升序));
                测试输出(数[0] * 10 + 数[4]);
                排序(数, 地址(降序));
                测试输出(数[0] * 10 + 数[4]);
                停止
                """;
            检查("G2 回调当**参数**传(`回调 比法(整数, 整数)` 形参):升序/降序两个比较器各排对一次(16 / 61)", () =>
            {
                var (输出, 报错) = 跑(比较器源);
                return (输出 == "16|61", $"输出=[{输出}] 报错=[{报错}]");
            });

            // ---- ④ 实参表按声明核对:个数不对,编译期就给带行号的话 ----
            检查("G2 间接调用的实参个数按声明核对(少一个当场编译报错、带行号)", () =>
            {
                var (输出, _, 报错) = 编跑([("主程序.hb", """
                    方法 加一(整数 x) 返回 整数 {
                        返回 x + 1;
                    }

                    回调 处理 = 地址(加一);
                    测试输出(间接调用(处理));
                    停止
                    """)], 虚拟机C.默认内存大小, 中间层C.默认堆大小, 中间层C.默认池大小, -1);
                return (输出.Length == 0 && 报错.Contains("需要 1 个实参", StringComparison.Ordinal) && 报错.Contains("第6行", StringComparison.Ordinal),
                    $"报错=[{报错}]");
            });

            // ---- ⑤ 老写法一个字不破:`地址(变量)` 仍是**数据地址**(不是代码地址) ----
            检查("G2 老写法不破:`地址(变量)` 仍是数据地址(元素间距照旧算得出 4)", () =>
            {
                var (输出, 报错) = 跑("""
                    整数 表[3] = [7, 8, 9];
                    测试输出(地址(表[1]) - 地址(表[0]));
                    停止
                    """);
                return (输出 == "4", $"输出=[{输出}] 报错=[{报错}]");
            });

            // ---- ⑥ 接线哨兵:直接调用与间接调用**只差最后那一条**(帧 / 参数槽 / 复原一字不差) ----
            检查("G2 接线 间接调用与直接调用只差最后一条指令(都是 取地址帧…MOV R15…调用/CALL…SUB_IMMEDIATE R15)", () =>
            {
                var (_, 直编译, 直错) = 编跑([("主程序.hb", """
                    方法 加一(整数 x) 返回 整数 {
                        返回 x + 1;
                    }

                    测试输出(加一(41));
                    停止
                    """)], 虚拟机C.默认内存大小, 中间层C.默认堆大小, 中间层C.默认池大小, -1);
                var (_, 间编译, 间错) = 编跑([("主程序.hb", """
                    方法 加一(整数 x) 返回 整数 {
                        返回 x + 1;
                    }

                    回调 处理 = 地址(加一);
                    测试输出(间接调用(处理, 41));
                    停止
                    """)], 虚拟机C.默认内存大小, 中间层C.默认堆大小, 中间层C.默认池大小, -1);
                if (直编译 == null || 间编译 == null) return (false, $"直错=[{直错}] 间错=[{间错}]");
                string 直文 = 中间层C.展开完整("""
                    方法 加一(整数 x) 返回 整数 {
                        返回 x + 1;
                    }

                    测试输出(加一(41));
                    停止
                    """).汇编文本;
                string 间文 = 中间层C.展开完整("""
                    方法 加一(整数 x) 返回 整数 {
                        返回 x + 1;
                    }

                    回调 处理 = 地址(加一);
                    测试输出(间接调用(处理, 41));
                    停止
                    """).汇编文本;
                bool 直有 = 直文.Contains("CALL 加一", StringComparison.Ordinal);
                bool 间有 = 间文.Contains("调用寄存器 R", StringComparison.Ordinal) && 间文.Contains("取地址 R", StringComparison.Ordinal);
                // 两边都有"切帧 + 复原"这一对(调用约定同一条)
                bool 直帧 = 直文.Contains("MOV R15 R", StringComparison.Ordinal) && 直文.Contains("SUB_IMMEDIATE R15 96", StringComparison.Ordinal);
                bool 间帧 = 间文.Contains("MOV R15 R", StringComparison.Ordinal) && 间文.Contains("SUB_IMMEDIATE R15 96", StringComparison.Ordinal);
                return (直有 && 间有 && 直帧 && 间帧,
                    $"直接有CALL 加一={直有} 间接有调用寄存器={间有} 直帧={直帧} 间帧={间帧}");
            });

            // ---- ISA / 语言面口径:这条语法本身没有新加指令(指令表的条数以 指令表 为准;
            //      通用化那一批另外加了浮点/间接跳转的指令,不归这条管) ----
            检查("G2 接线 没有新加 ISA 指令(间接调用走的就是 0x35)", () =>
            {
                bool 条数对 = 指令C.全部指令.Count == 指令C.取全部中文指令名().Length
                    && 指令C.取全部中文指令名().Length == 指令C.取全部英文指令名().Length;
                bool 有调用寄存器 = 指令C.取指令码表("调用寄存器") == 0x35;
                return (条数对 && 有调用寄存器, $"指令 {指令C.全部指令.Count} 条;调用寄存器=0x{指令C.取指令码表("调用寄存器"):X2}");
            });
        }
    }
}
