        }

        /// <summary>
        /// 自检专用的**假呈现口**(号 78):它**不碰任何字体**,只往"拿到的那块像素"里写三格 ——
        /// 钉的是引擎那一趟"呈现口改了它自己那份 ⇒ 拷回 `位图仓C` ⇒ `取图像素` 读得到"。
        /// 为什么不用真字体:自检这条线程没有 WPF 的 `Dispatcher`(硬规矩 6 也不许自检开窗)。
        /// </summary>
        private sealed class 写字呈现口C : 图形呈现口C
        {
            public void 打开窗口(string 标题, int 宽, int 高) { }
            public void 关闭窗口() { }
            public void 呈现(IReadOnlyList<绘制命令C> 命令) { }
            public void 等待(int 毫秒) { }

            /// <summary> 写三格:第 0 格红(0xFFFF0000)、第 width 格绿、最后一格蓝 —— 判据只看第 0 格 </summary>
            public bool 把文字画进像素(int x, int y, string 文本, uint 字色, int 字号, uint[] 像素, int 宽, int 高)
            {
                if (文本.Length == 0 || 宽 <= 0 || 高 <= 0 || 像素.Length < 宽 * 高) return false;
                像素[0] = 0xFFFF0000u;
                if (宽 * 高 > 宽) 像素[宽] = 0xFF00FF00u;
                像素[宽 * 高 - 1] = 0xFF0000FFu;
                return true;
            }
        }
    }
