using System;
using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// H45 第254批:**"这一条属于哪份文件"只留一个口径** ——
    /// `名字表C.函数范围` / `函数边界` 第 4 项 = **真正声明那一份文件**(被 `包含` 进来的库函数记**库文件**),
    /// 编译异常带的是**真正出错那一份文件**;而"这段码编进哪个调试段"是**另一件事**(`名字表C.函数段文件`),
    /// 调试段的名字表不许把两份文件的行号混着算(`名字表C.本段文件` + `行所属函数`)。
    ///
    /// H48 第276批:**「两个路径是不是同一个文件」这句判据也收成一处**(`引擎\文件判定C.cs`)——
    /// 从前全仓 5 份私有副本(界面 1 + 引擎 4),各认各的;这一组开头三条断言把新口径的四条逐条钉住,
    /// 外加一条"没有第二份副本回来"的护栏(与 H45 同一个病根:同一件事两处口径,查到的东西就不一样)。
    ///
    /// 为什么单列一组:这就是 H45"老口径残留"那一类的根 —— 从前第 4 项记的是**编译那一段的文件**,
    /// 而库函数的行号又是**库文件自己的**,于是"按文件名一筛"筛出 42 条、38 条行号越界(H33 用户实测),
    /// 思维导图 / 转到定义 / 文件级视图跟着全指错地方。这里用**真实标准工程**(示例19)把新口径钉死,
    /// 单文件那条腿另配一条"一个字没变"。
    /// 不在这份工作副本里跑就如实记跳过(与 H11 / H29 同一个口径)。
    /// </summary>
    public static partial class 综合自检C
    {
        private static void 文件归属自检()
        {
            try
            {
                // ---------------- ⓪ H48:「两个路径是不是同一个文件」只剩一处实现,四条口径逐条钉 ----------------
                // 从前全仓 5 份私有副本(界面 1 + 引擎 4:断点表 / 编译错误 / 转到定义 / 补全名字),行为略有出入。
                // H48 收成 `引擎\文件判定C.cs` 一处。这里 ①②正面、③④反面,后面再钉"没有第二份副本回来"。
                string 判据根 = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), "hb同文件判据"));
                string 左主 = Path.Combine(判据根, "左", "主程序.hb");
                string 右主 = Path.Combine(判据根, "右", "主程序.hb");
                string 相对写法 = Path.Combine("工具", "临时", "hb同文件判据.hb");
                string 绝对写法 = Path.GetFullPath(相对写法);
                记录("H48 同一个文件:相对对绝对算同一份 / 大小写不区分 / 光名对全称算同一份",
                    文件判定C.同文件(相对写法, 绝对写法)
                    && 文件判定C.同文件("主程序.hb", "主程序.HB")
                    && 文件判定C.同文件("主程序.hb", 左主),
                    $"相对 {相对写法} ↔ 绝对 {绝对写法};大小写与光名两条各真;两份绝对 = {左主} / {右主}");

                记录("H48 同一个文件:同名不同目录算两份 / 一边空一边不空不算 / 两边空才算(单文件、匿名来源)",
                    !文件判定C.同文件(左主, 右主)
                    && !文件判定C.同文件("", 左主) && !文件判定C.同文件(左主, "")
                    && 文件判定C.同文件("", "") && 文件判定C.同文件(null, null),
                    $"左\\主程序.hb 与 右\\主程序.hb 认成同一份吗 = {文件判定C.同文件(左主, 右主)}" +
                    $"(32 个标准工程每份都叫 主程序.hb,放宽了就会开错页 / 断点张冠李戴);空 ↔ 空 = {文件判定C.同文件("", "")}");

                // 判据只有一处:引擎 / 中间层 的源码里不许再冒出第二份同名判据(自检自己不算 —— 这条断言的字面量就在自检里)
                string? 仓根 = 找仓库根目录();
                if (仓根 == null)
                    跳过("H48 同一个文件判据全仓只剩一处实现(引擎\\文件判定C.cs)", "工作副本之外跑自检时跳过");
                else
                {
                    var 第二处 = new List<string>();
                    foreach (string 目录 in new[] { "引擎", "中间层", "编译器CLI", "HB宿主", "界面控件", "选卡控件", "图形宿主" })
                    {
                        string 全目录 = Path.Combine(仓根, 目录);
                        if (!Directory.Exists(全目录)) continue;
                        foreach (string 文件 in Directory.GetFiles(全目录, "*.cs", SearchOption.TopDirectoryOnly))
                        {
                            if (目录 == "引擎" && Path.GetFileName(文件) == "文件判定C.cs") continue;
                            string 文本 = File.ReadAllText(文件);
                            if (文本.Contains("bool 同文件(", StringComparison.Ordinal) || 文本.Contains("bool 同一文件(", StringComparison.Ordinal))
                                第二处.Add(Path.GetFileName(文件));
                        }
                    }
                    foreach (string 文件 in Directory.GetFiles(仓根, "MainWindow*.cs", SearchOption.TopDirectoryOnly))
                    {
                        string 文本 = File.ReadAllText(文件);
                        if (文本.Contains("bool 同文件(", StringComparison.Ordinal) || 文本.Contains("bool 同一文件(", StringComparison.Ordinal))
                            第二处.Add(Path.GetFileName(文件));
                    }
                    string 判据文件 = Path.Combine(仓根, "引擎", "文件判定C.cs");
                    bool 有唯一 = File.Exists(判据文件) && File.ReadAllText(判据文件).Contains("public static bool 同文件(", StringComparison.Ordinal);
                    记录("H48 同一个文件判据全仓只剩一处实现(引擎\\文件判定C.cs)",
                        第二处.Count == 0 && 有唯一,
                        第二处.Count == 0 && 有唯一
                            ? "引擎 / 中间层 / 界面 生产代码里 0 处第二份副本;唯一那份在 引擎\\文件判定C.cs"
                            : $"第二份副本:{string.Join(" / ", 第二处)};唯一那份在不在 = {有唯一}");
                }

                // ---------------- ① 单文件那条路:一个字没变 ----------------
                // 单文件展开(`规范化`)没有文件名(`来源` 是空串)⇒ 第 4 项照旧空串、段归属表照旧不记东西;
                // 而"一个文件的工程"(`汇编多文件带调试` 走的是工程级展开)文件表里那个名字就是它自己。
                const string 单源 = "方法 取数(整数 a) 返回 整数\n{\n返回 a + 1;\n}\n输出行(\"好\");\n停止\n";
                var 单 = 中间层C.展开完整带目录(单源, null, 带源行标记: true, 优化: false);
                var 单工程 = new 汇编器C().汇编多文件带调试([("主.hb", 单源)], 优化: false);
                记录("文件归属 单文件那条路一个字没变(没有文件名 ⇒ 第4项照旧空串;工程那条路记文件表里那个名字)",
                    单.名字表 != null && 单.名字表.函数范围.Count == 1
                    && 单.名字表.函数范围.All(x => x.文件.Length == 0) && 单.名字表.函数段文件.Count == 0
                    && 单工程.名字表.函数范围.Count == 1 && 单工程.名字表.函数范围.All(x => x.文件 == "主.hb")
                    && 单工程.名字表.函数段文件.Count == 0,
                    $"单文件展开:第4项 = '{单.名字表?.函数范围.FirstOrDefault().文件}',段归属表 {单.名字表?.函数段文件.Count} 条;" +
                    $"单文件工程:第4项 = '{单工程.名字表.函数范围.FirstOrDefault().文件}',段归属表 {单工程.名字表.函数段文件.Count} 条");

                // 下面三条要真实标准工程(示例19:主程序.hb 自己 0 条函数,函数全在 `库\目录.hb` / `库\string.hb` 里)
                string? 示例目录 = 找示例目录();
                if (示例目录 == null)
                {
                    foreach (string 名 in new[]
                    {
                        "文件归属 工程里的 `包含`:函数范围第4项是**库文件那一份**、行号按库文件算(不越界)",
                        "文件归属 调试段:库函数留在含它的那一段,但「第 N 行属哪个函数」只认本文件的函数",
                        "文件归属 转到定义:点库里的函数跳到**库文件那一行**",
                    })
                        跳过(名, "工作副本之外跑自检时跳过");
                    return;
                }

                string 主 = Path.GetFullPath(Path.Combine(示例目录, "中间层", "示例19_目录遍历", "主程序.hb"));
                string 目录库 = Path.GetFullPath(Path.Combine(示例目录, "库", "目录.hb"));
                if (!File.Exists(主) || !File.Exists(目录库))
                {
                    foreach (string 名 in new[]
                    {
                        "文件归属 工程里的 `包含`:函数范围第4项是**库文件那一份**、行号按库文件算(不越界)",
                        "文件归属 调试段:库函数留在含它的那一段,但「第 N 行属哪个函数」只认本文件的函数",
                        "文件归属 转到定义:点库里的函数跳到**库文件那一行**",
                    })
                        跳过(名, "示例19 或 库\\目录.hb 不在(工作副本被动过)");
                    return;
                }

                int 行数(string 文件) => File.Exists(文件) ? File.ReadAllLines(文件).Length : 0;

                // 工程级展开:文件表里只有 `主程序.hb`,库靠它那句 `包含` 拉进来(这就是老口径出事的那种形态)
                var 编 = new 汇编器C().汇编多文件带调试([(主, File.ReadAllText(主))], 优化: false);
                var 范围 = 编.名字表.函数范围;
                var 越界 = 范围.Where(x => x.文件.Length == 0 || !File.Exists(x.文件)
                    || x.起 < 1 || x.止 > 行数(x.文件) || x.止 < x.起).ToList();

                // ---------------- ② 第 4 项 = 库文件那一份,而且行号落在**那个文件**里 ----------------
                记录("文件归属 工程里的 `包含`:函数范围第4项是**库文件那一份**、行号按库文件算(不越界)",
                    范围.Count >= 12 && 范围.All(x => !文件判定C.同文件(x.文件, 主)) && 越界.Count == 0
                    && 范围.Any(x => 文件判定C.同文件(x.文件, 目录库)),
                    $"共 {范围.Count} 条,来自 {string.Join(" / ", 范围.Select(x => Path.GetFileName(x.文件)).Distinct())};" +
                    $"越界(行号超出那份文件的行数 / 文件不在盘上) {越界.Count} 条;" +
                    $"最大行号 {范围.Max(x => x.止)}");

                // ---------------- ③ 段归属与"第 N 行属哪个函数"是两件事 ----------------
                // 段里**照旧**装着库函数(调用关系扫描的"标签 ↔ 定义名"、调用栈的层名都要从段的名字表里拿);
                // 可"第 N 行属哪个函数"只能拿**本文件声明**的函数来答 —— 主程序.hb 自己 0 条函数 ⇒ 80 行全 null。
                var 段 = 编.调试文件表.FirstOrDefault(x => 文件判定C.同文件(x.文件, 主));
                int 认出行数 = 段 == null ? -1
                    : Enumerable.Range(1, 行数(主)).Count(i => 段.名字表.行所属函数(i) != null);
                记录("文件归属 调试段:库函数留在含它的那一段,但「第 N 行属哪个函数」只认本文件的函数",
                    段 != null && 段.名字表.函数范围.Count == 范围.Count && 段.名字表.函数段文件.Count > 0
                    && 文件判定C.同文件(段.名字表.本段文件, 主) && 认出行数 == 0,
                    $"段里函数范围 {段?.名字表.函数范围.Count} 条(工程级共 {范围.Count} 条) / " +
                    $"段归属表 {段?.名字表.函数段文件.Count} 条 / 本段文件 = {Path.GetFileName(段?.名字表.本段文件 ?? "")} / " +
                    $"主文件 {行数(主)} 行里被认成「在某个函数里」的 {认出行数} 行(库里的行号不许算到它头上)");

                // ---------------- ④ 转到定义:跳库文件,不跳主文件的同号行 ----------------
                var 调 = 调用关系扫描C.扫描(编);
                var 导 = 转到定义C.计算("列出", 主, 编.名字表, 调, [(主, File.ReadAllText(主))]);
                var 定义处 = 导.定义;
                记录("文件归属 转到定义:点库里的函数跳到**库文件那一行**",
                    定义处 != null && !文件判定C.同文件(定义处.文件, 主) && File.Exists(定义处.文件)
                    && 定义处.行 >= 1 && 定义处.行 <= 行数(定义处.文件),
                    $"{导.类别}:定义 = {Path.GetFileName(定义处?.文件 ?? "")} 第 {定义处?.行} 行" +
                    $"(那一份共 {行数(定义处?.文件 ?? "")} 行;主文件只有 {行数(主)} 行)");

                // ---------------- ⑥ H47:库函数体里的调用边也有调用者、有行号 ----------------
                // 标记尾巴上带的是**库文件全路径** ⇒ 拿"(库行号, 库文件)"去 `函数范围` 里认得出库函数。
                var 库边 = 调.边表.Where(e => e.是库行).ToList();
                int 无名 = 库边.Count(e => e.调用者.Length == 0 || e.调用点行 <= 0);
                记录("文件归属(H47)库函数体里的调用边:有调用者、行号落在**库文件**里(示例19 那几十条不再无名)",
                    库边.Count > 0 && 无名 == 0 && 库边.All(e => !文件判定C.同文件(e.调用点文件, 主))
                    && 库边.All(e => e.调用点行 >= 1 && e.调用点行 <= 行数(e.调用点文件)),
                    $"库行边 {库边.Count} 条、无名 {无名} 条;例:" +
                    string.Join(" / ", 库边.Take(3).Select(e => $"{e.调用者} → {e.被调标签} @{Path.GetFileName(e.调用点文件)}:{e.调用点行}")));

                // ---------------- ⑤ 报错带的是**真正出错那一份文件**(临时夹具:错在库文件里) ----------------
                string 临时 = Path.Combine(临时区C.基目录(), "hb文件归属_" + Guid.NewGuid().ToString("N")[..8]);
                try
                {
                    Directory.CreateDirectory(临时);
                    string 主夹具 = Path.Combine(临时, "主.hb");
                    string 库夹具 = Path.Combine(临时, "库.hb");
                    // 错在第 5 行(库文件里);主文件第 5 行是 `停止` —— 老口径会报"主.hb 第 5 行",指错方向
                    File.WriteAllText(库夹具, "模块 库\n\n方法 问候() 返回 字符串\n{\n    返回 没定义的东西;\n}\n");
                    File.WriteAllText(主夹具, "包含 \"库.hb\"\n\n输出行(库.问候());\n停止\n");
                    string 错文件 = "";
                    int? 错行 = null;
                    try
                    {
                        中间层C.展开工程带目录([(主夹具, File.ReadAllText(主夹具))], 带源行标记: true, 优化: false);
                    }
                    catch (编译异常C 错)
                    {
                        错文件 = 错.文件 ?? "";
                        错行 = 错.行号;
                    }
                    记录("文件归属 报错带的是**真正出错那一份文件**(库里的错报库文件,不报主文件的同号行)",
                        文件判定C.同文件(错文件, 库夹具) && 错行 is >= 1 and <= 7,
                        $"报的是 {Path.GetFileName(错文件)} 第 {错行} 行(库.hb 共 7 行;主.hb 第 5 行是 `停止`)");
                }
                finally
                {
                    try { 临时区C.清(临时); } catch { /* 清不掉只脏本机临时区,不影响断言 */ }
                }
            }
            catch (Exception ex) { 记录异常("文件归属", ex); }
        }
    }
}
