        /// <summary>
        /// K3(纯编译期强度削减第一段):循环条件里的**偏置掩码**与**偏置后的界**都是编译期常量,
        /// 以前每轮都要 `LUI/ORI` 装一遍(共 4 条),现在提到循环外各占一个常驻寄存器。
        /// 这里钉三件事:① 循环里不再每轮 LUI/ORI ② 省了几条 ③ 结果不变(开/关两档都要对)。
        /// </summary>
        private static void 循环常量提升自检()
        {
            // 注:这一格的**元素类型用 `整数`**(不是 `短整数`)—— T6 给"有符号 2 字节元素的运行期下标读"
            // 补了 2 条符号扩展指令,那两条会落在循环体里,把"少几条"这个**差值**吃掉 1 条。
            // 这一条要钉的是"偏置掩码 / 偏置后的界提到循环外",与元素窄不窄无关,所以让开那一处变动。
            const string 循环源 = "整数 数[5] = [1, 2, 3, 4, 5];\n整数 和 = 0;\n" +
                "循环 (整数 i = 0; i < 5; i = i + 1)\n{\n和 = 和 + 数[i];\n}\n测试输出(和);\n停止";
            var 开 = new 汇编器C().汇编多文件带调试([("主程序.hb", 循环源)], 优化: true);
            var 关 = new 汇编器C().汇编多文件带调试([("主程序.hb", 循环源)], 优化: false);

            static string 取循环段(string 展开)
            {
                // 多文件编译会把标签唯一化成 _f0_ForStart1,所以按后缀找
                int 起 = 展开.IndexOf("ForStart", StringComparison.Ordinal);
                if (起 < 0) return "";
                起 = 展开.LastIndexOf('\n', 起) + 1;
                int 止 = 展开.IndexOf("JMP _", 起, StringComparison.Ordinal);
                if (止 < 0) return "";
                return 展开[起..展开.LastIndexOf('\n', 止)];
            }
            string 段开 = 取循环段(开.调试文件表[0].展开文本), 段关 = 取循环段(关.调试文件表[0].展开文本);
            int 行开 = 段开.Split('\n').Count(x => x.Trim().Length > 0);
            int 行关 = 段关.Split('\n').Count(x => x.Trim().Length > 0);
            记录("K3 循环条件的偏置常量提到循环外(循环里不再每轮 LUI/ORI 装常量)",
                段开.Length > 0 && !段开.Contains("LUI") && 段关.Contains("LUI"),
                $"优化开:{行开} 行 / 优化关:{行关} 行");
            记录("K3 一轮少 4 条以上(偏置掩码 2 条 + 偏置后的界 2 条,另外步进常量也一起提了)",
                行关 - 行开 >= 4, $"{行关} → {行开}(少 {行关 - 行开} 条)");
            记录("K3 循环结果不变(优化开/关都是 15)", 输出文本(循环源) == "15" && 输出文本(循环源, 优化: false) == "15",
                $"开={输出文本(循环源)} 关={输出文本(循环源, false)}");
            // 嵌套循环:外层提的常驻寄存器不能被内层提重了(内层要跳过外层占着的号)
            string 嵌套源 = "短整数 数[4] = [1, 2, 3, 4];\n整数 和 = 0;\n循环 (整数 i = 0; i < 4; i = i + 1)\n{\n" +
                "    循环 (整数 j = 0; j < 4; j = j + 1)\n    {\n        和 = 和 + 数[i] + 数[j];\n    }\n}\n测试输出(和);\n停止";
            记录("K3 嵌套循环各提各的常驻寄存器,结果对(1+2+3+4=10,每个数加 4 次 → 80)",
                输出文本(嵌套源) == "80", $"输出={输出文本(嵌套源)}");

            // 第二段:有符号除/取余,除数是"正数常量"时省掉对除数的取绝对值/取符号
            记录("K3 有符号除取余语义按 C(向零截断,余数跟被除数)",
                输出文本("整数 a = -7;\n整数 b = 2;\n测试输出(a / b);\n测试输出(a % b);\n整数 c = 7;\n测试输出(c / b);\n" +
                    "测试输出(c % b);\n测试输出(a / 10);\n测试输出(a % 10);\n整数 d = -1;\n测试输出(d / 2);\n测试输出(d % 2);\n停止")
                == "-3\n-1\n3\n1\n0\n-7\n0\n-1", "负数除法/取余都要对");
            static long 跑完步数(汇编调试结果C 编)
            {
                var vm = new 虚拟机C { 输出目标 = _ => { } };
                vm.装载(编);
                long 步 = 0;
                while (vm.单步() && 步 < 100000) 步++;
                return 步;
            }
            long 常量除数 = 跑完步数(编译("整数 a = -7;\n整数 b = 2;\n测试输出(a / b);\n停止"));
            long 变量除数 = 跑完步数(编译("方法 商(整数 b)  返回 整数 {\n整数 a = -7;\n返回 a / b;\n}\n测试输出(商(2));\n停止"));
            记录("K3 正数常量除数比通用有符号除省 ≥8 条", 变量除数 - 常量除数 >= 8, $"变量除数 {变量除数} 条 → 常量除数 {常量除数} 条");

            // 同一个"重复执行的声明"家族:循环体里声明的数组/结构(含字面量初值)每轮都要**重新置零**
            // (以前只在"数据段天生是 0 / 函数入口清一次"上打主意 —— 循环第二轮起全是上一轮的值)
            记录("K3 循环里声明的数组每轮重置(不是 1-2-3)",
                输出文本("循环 (整数 i = 0; i < 3; i = i + 1)\n{\n字节 缓冲[2];\n缓冲[0] = 缓冲[0] + 1;\n测试输出(缓冲[0]);\n}\n停止")
                == "1\n1\n1", "数组声明在循环里也要清");
            记录("K3 循环里声明的结构每轮重置",
                输出文本("结构 点\n{\n整数 x;\n}\n循环 (整数 i = 0; i < 3; i = i + 1)\n{\n点 位置;\n位置.x = 位置.x + 1;\n测试输出(位置.x);\n}\n停止")
                == "1\n1\n1", "结构声明在循环里也要清");
            记录("K3 循环里带字面量初值的数组:没写到的元素每轮归 0",
                输出文本("循环 (整数 i = 0; i < 3; i = i + 1)\n{\n短整数 表[3] = [7];\n测试输出(表[0] + 表[1] + 表[2]);\n}\n停止")
                == "7\n7\n7", "初值只写了一个,其余必须是 0");
            记录("K3 函数里循环声明的数组也每轮重置(帧不只靠入口清一次)",
                输出文本("方法 累加()  返回 整数\n{\n整数 合 = 0;\n循环 (整数 i = 0; i < 3; i = i + 1)\n{\n字节 缓冲[2];\n" +
                    "缓冲[0] = 缓冲[0] + 1;\n合 = 合 + 缓冲[0];\n}\n返回 合;\n}\n测试输出(累加());\n停止") == "3",
                "帧里的数组在循环里也要清");
        }

        /// <summary>
        /// K3 余量 P1(数组地址增量):循环里 `数组[归纳变量]` 改成"常驻指针每轮步进" ——
        /// 以前一次访问要 `ADD;ADD;取地址;ADD`(4 字节元素 4 条),现在只在步进点 `ADD_IMMEDIATE 指针 元素宽`。
        /// 这里钉五件事:① 循环体里不再取址、一轮真省 3 条以上 ② 结果不变(优化开/关一致)
        /// ③ 该不提的一条都不提(写数组 / 下标不是归纳变量 / 嵌套循环)
        /// ④ 各种形状都对(2/1 字节元素、函数帧里的数组、两个数组、非零初值、非常量初值、步长 >1)
        /// ⑤ **越界照样被拦住**(省的是取址,越界检查一条不少)
        /// </summary>
        private static void 数组地址增量自检()
        {
            const string 读源 = "整数 表[8] = [1, 2, 3, 4, 5, 6, 7, 8];\n整数 和 = 0;\n" +
                "循环 (整数 i = 0; i < 8; i = i + 1)\n{\n和 = 和 + 表[i];\n}\n测试输出(和);\n停止";
            var 开 = new 汇编器C().汇编多文件带调试([("主程序.hb", 读源)], 优化: true);
            var 关 = new 汇编器C().汇编多文件带调试([("主程序.hb", 读源)], 优化: false);

            static string 取循环段(string 展开)
            {
                int 起 = 展开.IndexOf("ForStart", StringComparison.Ordinal);
                if (起 < 0) return "";
                起 = 展开.LastIndexOf('\n', 起) + 1;
                int 止 = 展开.IndexOf("JMP _", 起, StringComparison.Ordinal);
                if (止 < 0) return "";
