        private static string 模块铺文件((string 名, string 内容)[] 文件们)
        {
            string 目录 = Path.Combine(临时区C.基目录(), "hb模块_" + Guid.NewGuid().ToString("N")[..8]);
            foreach (var (名, 内容) in 文件们)
            {
                string 全 = Path.Combine(目录, 名);
                Directory.CreateDirectory(Path.GetDirectoryName(全)!);
                File.WriteAllText(全, 内容);
            }
            return 目录;
        }

        /// <summary> 模块自检:编"主程序.hb"并跑完,返回(程序输出, 运行期报错);编译不过直接抛 </summary>
        private static (string 输出, string 报错) 模块跑(string 目录, string 主程序, bool 优化 = true)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
            var vm = new 虚拟机C { 输入源 = () => null, 输出目标 = 解码.写 };
            var 编 = new 汇编器C().汇编多文件带调试([(Path.Combine(目录, "主程序.hb"), 主程序)], 优化);
            vm.运行(编);
            解码.收尾();
            return (缓冲.ToString().TrimEnd('\n'), 编.查运行期报错(vm.内存) ?? "");
        }

