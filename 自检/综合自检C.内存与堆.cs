        {
            string 源 = "方法 递归(整数 层) 返回 整数\n{\n如果 (层 <= 0)\n{\n返回 0;\n}\n返回 递归(层 - 1) + 1;\n}\n"
                + $"输出行(递归({层数}));\n停止";
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
            var vm = new 虚拟机C { 输入源 = () => null, 输出目标 = 解码.写 };
            var 编 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源)], true, 中间层C.默认堆大小, null,
                中间层C.默认池大小, 内存大小, 软栈大小);
            vm.运行(编);
            解码.收尾();
            return (缓冲.ToString().TrimEnd('\n'), 编.查运行期报错(vm.内存) ?? "");
        }
