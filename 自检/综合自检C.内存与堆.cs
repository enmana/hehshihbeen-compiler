        private static void 规模用例自检()
        {
            const int 函数数 = 250;
            var 源 = new StringBuilder();
            for (int i = 1; i <= 函数数; i++)
                源.Append($"方法 f{i}(整数 x)  返回 整数\n{{\n整数 基数 = x + {i};\n整数 结果 = 基数 * 2 - {i};\n" +
                    $"如果 (结果 > 100)\n{{\n结果 = 结果 - 100;\n}}\n返回 结果;\n}}\n");
            源.Append("整数 合 = 0;\n");
            for (int i = 1; i <= 函数数; i++) 源.Append($"合 = 合 + f{i}({i});\n");
            源.Append("测试输出(合);\n停止");
            string 源码 = 源.ToString();
            int 行数 = 源码.Split('\n').Length;

            var 表 = new System.Diagnostics.Stopwatch();
            表.Start();
            var 编 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源码)]);
            表.Stop();

            int 期望 = 0;
            for (int i = 1; i <= 函数数; i++)
            {
                int 结果 = (i + i) * 2 - i;
                if (结果 > 100) 结果 -= 100;
                期望 += 结果;
            }
            // 断言名**不许带会变的东西**(耗时/路径/地址)——批 4 的"断言清单比对"当场抓到过这一条:
            // 名字里写着 `耗时 148 ms` ⇒ 每次运行清单都对不上,红灯全是噪声。耗时段子挪进详情。
            记录($"规模 {行数} 行 / {函数数} 个函数能编出来",
                编.机器码.Length > 0 && 表.ElapsedMilliseconds < 8000,
                $"代码段 {编.机器码.Length} 字节,耗时 {表.ElapsedMilliseconds} ms");
            记录("规模 大源码跑出来的结果与现算一致", 输出文本(源码) == 期望.ToString(), $"期望={期望} 实际={输出文本(源码)}");
            记录("规模 代码段字节数与 4 字节/条对得上(条数整)",
                编.机器码.Length % 4 == 0 && 编.代码字节数 > 0 && 编.代码字节数 <= 编.机器码.Length,
                $"代码 {编.代码字节数} / 总 {编.机器码.Length}");
        }

