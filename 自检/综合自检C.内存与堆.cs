            记录("批8 后半 保守口径没松:把带字符串的**结构整体搬进全局结构**的函数照样不回收",
                !编译(结构逃逸源).编译提示.Any(x => x.Contains("回收池水位")), string.Join(" / ", 编译(结构逃逸源).编译提示));
        }
        /// <summary>
        /// K8 堆(动态内存):独立 64KB 堆区 + 申请/释放/取字/存字 四条入口。
        /// 钉十件事:
        ///   ① 申请→释放→再申请**拿回同一块**;② 交叉释放后还能申请到(先不做合并,有地方就给);
        ///   ③ 申请超过堆大小:当场停下,消息里带"堆"与字节数、行号对;③' 需要量比整堆还大也不许回绕成小数;
        ///   ④ 释放非法地址(申请来的地址 +4)被拦;⑤ 重复释放被拦;⑥ 释放后读写被拦;
        ///   ⑦ 一条语句里多个堆调用互不踩(分配例程保存/恢复寄存器);
        ///   ⑧ 堆与递归一起用(地址当参数/返回值,建树/中序/递归释放);
        ///   ⑨ 堆与老池互不干扰(字符串/列表照旧)。
        /// </summary>
        private static void 堆自检()
        {
            // ① 申请 16 → 释放 → 再申请 16:应当拿回同一块
            const string 复用源 = "地址 p = 申请(16);\n释放(p);\n地址 q = 申请(16);\n测试输出(p == q);\n停止";
            var 复用 = 堆跑(复用源);
            记录("K8 堆 申请→释放→再申请拿回同一块", 复用.输出 == "1", $"输出={复用.输出} 报错={复用.报错}");

            // ② 交叉释放:两个块都还回去以后,再要一块能拿到(不要求合并,只要求有地方就给)
            const string 交叉源 = "地址 块左 = 申请(16);\n地址 块右 = 申请(16);\n释放(块左);\n释放(块右);\n" +
                "地址 块尾 = 申请(32);\n测试输出(块尾 == 0);\n停止";
            var 交叉 = 堆跑(交叉源);
            记录("K8 堆 交叉释放后还能申请到(不要求合并)", 交叉.输出 == "0", $"输出={交叉.输出} 报错={交叉.报错}");

            // ③ 超过堆大小:当场停下;消息含"堆"与字节数,行号正好是第 3 行(那一行写着 申请(70000))
            const string 太大源 = "地址 小块 = 申请(16);\n释放(小块);\n地址 大块 = 申请(70000);\n停止";
            var 太大 = 堆跑(太大源);
            记录("K8 堆 申请超过堆大小被拦(消息含堆与字节数、行号对)",
                太大.报错.Contains("第 3 行") && 太大.报错.Contains("堆") && 太大.报错.Contains("70000")
                && 太大.报错.Contains("65536"),
                太大.报错.Length > 0 ? 太大.报错 : "(没有报错)");

            // ③' 需要量比整堆还大时同样拦住:不然"加块头 + 4 字节取整"会把大数回绕成小数,反而申请成功
            const string 回绕源 = "地址 块 = 申请(4294967295);\n测试输出(1);\n停止";
            var 回绕 = 堆跑(回绕源);
            记录("K8 堆 需要量比整堆还大时被拦(不回绕成小数)",
                回绕.输出 != "1" && 回绕.报错.Contains("第 1 行") && 回绕.报错.Contains("4294967295"),
                回绕.报错.Length > 0 ? 回绕.报错 : $"(没有报错,输出={回绕.输出})");

            // ④ 释放一个"不是块首"的地址(申请来的地址 +4):拦住
            const string 非法源 = "地址 p = 申请(16);\n释放(p + 4);\n停止";
            var 非法 = 堆跑(非法源);
            记录("K8 堆 释放非法地址被拦(带行号、说改法)",
                非法.报错.Contains("第 2 行") && 非法.报错.Contains("释放") && 非法.报错.Contains("办法"),
                非法.报错.Length > 0 ? 非法.报错 : "(没有报错)");

            // ⑤ 同一块释放两次:拦住
            const string 重复源 = "地址 p = 申请(16);\n释放(p);\n释放(p);\n停止";
            var 重复 = 堆跑(重复源);
            记录("K8 堆 重复释放被拦(带行号)", 重复.报错.Contains("第 3 行") && 重复.报错.Contains("重复释放"),
                重复.报错.Length > 0 ? 重复.报错 : "(没有报错)");

            // ⑥ 释放之后又去取字:拦住(读块头里的空闲标志)
            const string 释放后源 = "地址 p = 申请(16);\n存字(p, 0, 9);\n释放(p);\n测试输出(取字(p, 0));\n停止";
            var 释放后 = 堆跑(释放后源);
            记录("K8 堆 释放后读写被拦(带行号)", 释放后.报错.Contains("第 4 行") && 释放后.报错.Contains("释放"),
                释放后.报错.Length > 0 ? 释放后.报错 : "(没有报错)");

            // ⑦ 一条语句里好几个堆调用:每个结果都得活到用的时候(分配例程保存/恢复了 R0 之外的寄存器)
            const string 多个源 = "地址 p = 申请(16);\n存字(p, 0, 100);\n地址 q = 申请(16);\n存字(q, 0, 200);\n" +
                "整数 和 = 取字(p, 0) + 取字(q, 0);\n存字(p, 4, 取字(q, 0) + 1);\n测试输出(和);\n测试输出(取字(p, 4));\n停止";
            var 多个 = 堆跑(多个源);
            记录("K8 堆 一条语句里多个堆调用互不踩", 多个.输出 == "300\n201", $"输出={多个.输出.Replace("\n", "|")} 报错={多个.报错}");

            // ⑧ 堆 + 递归:`地址` 当参数与返回值,建二叉搜索树 → 中序打印 → 递归释放(整棵树都还回去)
            const string 树源 = """
                方法 插入(地址 根, 整数 新值) 返回 地址 {
                    如果 (根 == 0) {
                        地址 节点 = 申请(12);
                        存字(节点, 0, 新值);
                        存字(节点, 4, 0);
                        存字(节点, 8, 0);
                        返回 节点;
                    }
                    如果 (新值 < 取字(根, 0)) {
                        存字(根, 4, 插入(取字(根, 4), 新值));
                    } 否则 {
                        存字(根, 8, 插入(取字(根, 8), 新值));
                    }
                    返回 根;
                }
                方法 中序(地址 根) {
                    如果 (根 == 0) {
                        返回;
                    }
                    中序(取字(根, 4));
                    测试输出(取字(根, 0));
                    中序(取字(根, 8));
                }
                方法 释放树(地址 根) {
                    如果 (根 == 0) {
                        返回;
                    }
                    地址 左 = 取字(根, 4);
                    地址 右 = 取字(根, 8);
                    释放树(左);
                    释放树(右);
                    释放(根);
                }
                地址 树 = 0;
                树 = 插入(树, 5);
                树 = 插入(树, 3);
                树 = 插入(树, 8);
                树 = 插入(树, 1);
                中序(树);
                释放树(树);
                地址 再来 = 申请(12);
                测试输出(再来 == 0);
                停止
                """;
            var 树 = 堆跑(树源);
            记录("K8 堆 地址当参数/返回值:建树→中序→递归释放,还回去的还能再申请",
                树.输出 == "1\n3\n5\n8\n0", $"输出={树.输出.Replace("\n", "|")} 报错={树.报错}");

            // ⑨ 堆与老池互不干扰:同一个程序里列表/字符串照旧(堆是另一块内存,池的行为一个字没改)
            const string 一起源 = "短整数 分数[];\n分数.添加(7);\n分数.添加(9);\n字符串 词 = \"堆与池\";\n" +
                "地址 p = 申请(8);\n存字(p, 0, 分数.长度());\n整数 个 = 取字(p, 0);\n释放(p);\n" +
                "测试输出(分数[0] + 分数[1] + 个);\n输出行(词);\n停止";
            var 一起 = 堆跑(一起源);
            记录("K8 堆 与老池互不干扰(列表/字符串照旧)", 一起.输出 == "18\n堆与池", $"输出={一起.输出.Replace("\n", "|")} 报错={一起.报错}");

            // ⑩ 堆大小可配(P34):默认 64KB,能按 `堆` 配成别的;同一个源配不同大小必须给出不同结果
            记录("P34 堆大小 默认 64KB、上下限合理",
                中间层C.默认堆大小 == 64 * 1024 && 中间层C.最小堆大小 == 1024 && 中间层C.最大堆大小 == 虚拟机C.最大内存大小,
                $"默认={中间层C.默认堆大小} 范围={中间层C.最小堆大小}~{中间层C.最大堆大小}");

            // ⑩a 同一个源:64KB 下 100000 字节要不到(报 65536);128KB 下要得到,而且真的能存能读
            const string 大块源 = "地址 p = 申请(100000);\n存字(p, 0, 4242);\n测试输出(取字(p, 0));\n停止";
            var 小块 = 堆跑(大块源, 64 * 1024);
            记录("P34 堆 64KB 下 申请(100000) 被拦(消息说清堆只有 65536)",
                小块.报错.Contains("100000") && 小块.报错.Contains("65536") && 小块.报错.Contains("`堆`"),
                $"输出={小块.输出.Replace("\n", "|")} 报错={小块.报错}");
            var 大块 = 堆跑(大块源, 128 * 1024);
            记录("P34 堆 128KB 下同一段程序申请成功、读写都对", 大块.输出 == "4242" && 大块.报错.Length == 0,
                $"输出={大块.输出.Replace("\n", "|")} 报错={大块.报错}");

            // ⑩b 堆大小改了,机器码必须跟着变(K8 的堆初始化是编译期生成的)
            var 码小 = new 汇编器C().汇编多文件([("主程序.hb", 大块源)], true, 64 * 1024);
            var 码大 = new 汇编器C().汇编多文件([("主程序.hb", 大块源)], true, 128 * 1024);
            记录("P34 堆 换 `堆` 机器码跟着变(不是编译期常量被烤死)",
                !码小.SequenceEqual(码大), $"64KB={码小.Length} 字节,128KB={码大.Length} 字节");

            // ⑩c 展开缓存必须带上堆大小:先 128KB 再 64KB,拿到的不能是上一个大小的旧展开
            var 冷 = new 汇编器C().汇编多文件带调试([("主程序.hb", 大块源)], true, 128 * 1024);
            var 热 = new 汇编器C().汇编多文件带调试([("主程序.hb", 大块源)], true, 64 * 1024);
            var 再冷 = new 汇编器C().汇编多文件带调试([("主程序.hb", 大块源)], true, 128 * 1024);
            记录("P34 堆 展开缓存按堆大小分开(换大小不吃旧缓存)",
                热.机器码.SequenceEqual(码小) && 冷.机器码.SequenceEqual(再冷.机器码) && !热.机器码.SequenceEqual(冷.机器码),
                $"128KB→64KB 一致={热.机器码.SequenceEqual(码小)},64KB→128KB 一致={冷.机器码.SequenceEqual(再冷.机器码)}");

            // ⑩d 超出范围/乱传:给出明确错误,不许"默默按 0 字节堆"跑
            期望异常("P34 堆 堆大小太小说清范围", () => 堆跑("地址 p = 申请(4);\n停止", 16), "超范围", "1024");
            期望异常("P34 堆 堆大小超过内存上限说清范围", () => 堆跑("地址 p = 申请(4);\n停止", 128 * 1024 * 1024), "超范围", "67108864");
        }

        /// <summary>
        /// P33 相邻空闲块合并(堆碎片整理):还回来的块当场与**地址上相邻**的空闲块并成一块 ——
        /// 前邻空闲就并进去(前邻本来就在空闲表上,不用再插),后邻空闲就从空闲表摘下来并进来。
        /// 这里钉六件事:① 合并前拿不到、合并后拿得到(合并真起作用)② 合并出来的块从**第一个**邻居的地址开始
        /// ③ 三块连着释放能并成一大块 ④ 反复申请/释放一轮后堆能回到"一整块"(大小不虚增、链表不乱)
        /// ⑤ 被并掉的那一小块地址:再 `释放` 报"已经还回去了"、再 `取字/存字` 照样被拦
        /// ⑥ 邻居里的数据不被合并碰坏。
        /// </summary>
        private static void 堆合并自检()
        {
            // 16KB 堆,4 × 4000 正好铺满(每块连块头 4012,剩 336)。
            // 释放中间相邻两块 → 并出 8024;合并前单块最大只有 4012(其余是 336 的碎块),所以 申请(7000) 一定失败
            const string 头 = "地址 p1 = 申请(4000);\n地址 p2 = 申请(4000);\n地址 p3 = 申请(4000);\n地址 p4 = 申请(4000);\n";
            const string 尾 = "测试输出(大 == 0);\n测试输出(大 == p2);\n存字(大, 0, 1234);\n测试输出(取字(大, 0));\n停止";
            const string 不释放 = 头 + "地址 大 = 申请(7000);\n" + 尾;
            const string 释放两邻 = 头 + "释放(p2);\n释放(p3);\n地址 大 = 申请(7000);\n" + 尾;
            var 前 = 堆跑(不释放, 16 * 1024);
            var 后 = 堆跑(释放两邻, 16 * 1024);
            记录("P33 合并前 申请(7000) 拿不到(堆里没有一块够大)",
                前.输出.Length == 0 && 前.报错.Contains("放不下"), 前.报错.Length > 0 ? 前.报错 : $"(没报错,输出={前.输出})");
            记录("P33 释放相邻两块后能并出大块,申请(7000) 成功、读写都对",
                后.输出 == "0\n1\n1234" && 后.报错.Length == 0, $"输出={后.输出.Replace("\n", "|")} 报错={后.报错}");
            记录("P33 合并块从**前一个**邻居的地址开始(p2 的位置)", 后.输出.StartsWith("0\n1\n"), $"{后.输出.Replace("\n", "|")}");

            // 三块连着释放:12036 并成一块 → 申请(11000) 拿得到(单块只有 4012)
            var 三块 = 堆跑(头 + "释放(p1);\n释放(p2);\n释放(p3);\n地址 大 = 申请(11000);\n测试输出(大 == 0);\n" +
                "测试输出(大 == p1);\n存字(大, 0, 55);\n测试输出(取字(大, 0));\n测试输出(取字(p4, 0));\n停止", 16 * 1024);
            记录("P33 三块连着释放并成一大块(申请(11000) 成功,起点是 p1)",
                三块.输出 == "0\n1\n55\n0" && 三块.报错.Length == 0, $"输出={三块.输出.Replace("\n", "|")} 报错={三块.报错}");

            // 合并不能碰坏邻居的数据:p1 与 p4 先写标记,合并 p2/p3 之后标记还在
            var 邻居 = 堆跑(头 + "存字(p1, 0, 111);\n存字(p4, 0, 444);\n释放(p2);\n释放(p3);\n地址 大 = 申请(7000);\n" +
                "测试输出(取字(p1, 0));\n测试输出(取字(p4, 0));\n测试输出(取字(大, 0));\n停止", 16 * 1024);
            记录("P33 合并两个邻居时,边上两个块的数据没被碰坏(111 / 444 / 0)",
                邻居.输出 == "111\n444\n0", $"输出={邻居.输出.Replace("\n", "|")} 报错={邻居.报错}");

            // 反复"申请三块 → 倒着释放"30 轮:最后堆要回到一整块(大小不虚增:16000 拿得到、再要 1000 就没了)
            var 反复 = 堆跑("循环 (整数 轮 = 0; 轮 < 30; 轮 = 轮 + 1)\n{\n地址 块左 = 申请(1500);\n地址 块中 = 申请(1500);\n" +
                "地址 块右 = 申请(1500);\n释放(块右);\n释放(块中);\n释放(块左);\n}\n地址 大 = 申请(16000);\n测试输出(大 == 0);\n" +
                "地址 小 = 申请(1000);\n测试输出(小 == 0);\n停止", 16 * 1024);
            记录("P33 30 轮申请/倒序释放之后堆回到一整块(16000 拿得到、再要 1000 就没了)",
                反复.输出 == "0" && 反复.报错.Contains("1000") && 反复.报错.Contains("放不下"),
                $"输出={反复.输出.Replace("\n", "|")} 报错={反复.报错}");

            // 被并掉的那一小块地址:p2 已经不是块首了 —— 再释放报"已经还回去了",再读写仍被拦
            var 并掉再释放 = 堆跑(头 + "释放(p2);\n释放(p3);\n释放(p2);\n停止", 16 * 1024);
            记录("P33 被并掉的那一小块地址再 释放 → 报重复释放(不是笼统的非法地址)",
                并掉再释放.报错.Contains("重复释放") && 并掉再释放.报错.Contains("第 7 行"),
                并掉再释放.报错.Length > 0 ? 并掉再释放.报错 : "(没有报错)");
            var 并掉再读写 = 堆跑(头 + "释放(p2);\n释放(p3);\n存字(p2, 0, 9);\n停止", 16 * 1024);
            记录("P33 被并掉的那一小块地址再 存字 → 照样被'释放后读写'拦住",
                并掉再读写.报错.Contains("第 7 行") && 并掉再读写.报错.Contains("释放"),
                并掉再读写.报错.Length > 0 ? 并掉再读写.报错 : "(没有报错)");

            // 合并之后照样能切分:申请一小块要用大块的头,剩下的还得留在空闲表上
            var 再切 = 堆跑(头 + "释放(p2);\n释放(p3);\n地址 块左 = 申请(1000);\n地址 块中 = 申请(1000);\n地址 块右 = 申请(5000);\n" +
                "测试输出(块左 == 0);\n测试输出(块中 == 0);\n测试输出(块右 == 0);\n测试输出(块左 == p2);\n测试输出(块中 == p2 + 1012);\n停止", 16 * 1024);
            记录("P33 合并出来的大块还能继续切分(连要三块都要得到,且从并出来的起点开始)",
                再切.输出 == "0\n0\n0\n1\n1" && 再切.报错.Length == 0, $"输出={再切.输出.Replace("\n", "|")} 报错={再切.报错}");
        }

