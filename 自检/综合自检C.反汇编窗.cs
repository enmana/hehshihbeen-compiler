using System;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text.RegularExpressions;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 综合自检的一部分:**工具 → 反汇编当前文件**那个窗用的解码器(R4-7,2026-09-22)。
    ///
    /// 病根:那份解码表是**第二份**、只登记 `0x00~0x1A` 共 27 条(`工具\反汇编器C.cs`),
    /// 后面的一律打成 `OP_0x2B raw: …`(取字帧/乘法/读取字符/比较取值/断点/宿主调用/索引寻址全在里面),
    /// 与唯一事实源 `指令C.全部指令`(最高操作码 0x36)**已经漂移**。本批把它改成纯转发,
    /// 这里钉住"转发之后全表逐条都查得到、且助记符与操作数跟指令表逐字对上"。
    /// </summary>
    public static partial class 综合自检C
    {
        // ================= 工具反汇编窗 =================
        /// <summary>
        /// 反汇编窗那个类在哪(`hehshihbeen_compiler.工具.反汇编器C`)。**故意写名字串**,不走 `using 工具`:
        /// 自检是**共享**的(`引擎库` / `编译器CLI` / `MobileIDE` 都链自检),它一旦强绑 WPF 那一层就编不过 ——
        /// 那条路本来就没这个类,如实记跳过(断言名与主程序里一模一样)。
        /// </summary>
        private const string 反汇编器类名 = "hehshihbeen_compiler.工具.反汇编器C";

        private static void 工具反汇编自检()
        {
            Type? 反汇编器 = typeof(指令C).Assembly.GetType(反汇编器类名, throwOnError: false);

            // ① 工具反汇编窗:全表**逐条**查得到(助记符 + 操作数,来源都是指令表)
            try
            {
                if (反汇编器 == null)
                {
                    跳过("工具反汇编窗 全部指令逐条查得到(条数 == 指令表条数)",
                        "当前进程里没有 工具.反汇编器C(自检不在主程序里跑)");
                }
                else if (反汇编器.GetMethod("反汇编", [typeof(byte[])]) is not { } 反汇编)
                {
                    记录("工具反汇编窗 全部指令逐条查得到(条数 == 指令表条数)",
                        false, $"{反汇编器类名} 上没有 `反汇编(byte[])` —— 反汇编窗的入口签名换了");
                }
                else
                {
                    bool 逐条通 = true; string? 出岔的 = null; int 查过 = 0;
                    foreach (var (中文, 英文, 操作码, 格式) in 指令C.全部指令)
                    {
                        查过++;
                        // 按这条指令**自己的格式**造一条合成指令:目标寄存器放 R1,源寄存器也放 R1,
                        // 其余字段各放一个能看出来的值。三条容易踩的:
                        // ① `寄存器地址` / `寄存器立即数` 的第二操作数是**低 20 位** —— 源寄存器 [19:16] 会落进去,
                        //    所以那两种格式**不点源寄存器**(点了它,地址就从 0x12345 变成 0x22345);
                        // ② `跳转地址` 存的是"地址 >> 2"、占**整个低 24 位**,同理不点源寄存器;
                        // ③ 地址故意取 0x12345 这种不对齐的数,顺带把"存的是 >>2、反汇编要 <<2 回来"也钉住
                        //    (它必须小于 0x400000 —— 位 22 起是操作码的地盘,不能拿它当跳转目标)。
                        const uint 地址 = 0x12345;
                        uint 词 = ((uint)操作码 << 24);
                        if (格式 == 指令格式.跳转地址) 词 |= (地址 >> 2);
                        else 词 |= (1u << 20);
                        if (格式 is 指令格式.双寄存器 or 指令格式.双寄存器小立即数) 词 |= (1u << 16);
                        if (格式 == 指令格式.双寄存器小立即数) 词 |= (2u << 12);
                        else if (格式 == 指令格式.三寄存器小立即数) 词 |= (1u << 16) | (4u << 12) | (3u << 8);
                        else if (格式 is 指令格式.寄存器地址 or 指令格式.寄存器立即数) 词 |= 地址;
                        byte[] 码 = [(byte)词, (byte)(词 >> 8), (byte)(词 >> 16), (byte)(词 >> 24)];

                        // 期望行:助记符用**英文名**(反汇编窗的既有观感),操作数按指令表的格式字段值算出来。
                        // 逐字写清(不拿 `指令C.操作数写法` 去替换)—— 期望值一旦是从被验证的那份表推出来的,
                        // 表自己写错就一起错,这条断言就白钉了。
                        string 期望 = 格式 switch
                        {
                            指令格式.无操作数 => $"{英文}",
                            指令格式.单寄存器 => $"{英文} R1",
                            指令格式.双寄存器 => $"{英文} R1, R1",
                            指令格式.寄存器立即数 => $"{英文} R1, {地址}",
                            指令格式.寄存器地址 => $"{英文} R1, 0x{地址:X}",
                            指令格式.跳转地址 => $"{英文} 0x{(地址 >> 2) << 2:X}",
                            指令格式.双寄存器小立即数 => $"{英文} R1, R1, 2",
                            指令格式.三寄存器小立即数 => $"{英文} R1, R1, R4, 3",
                            _ => $"{英文} ?",
                        };

                        string 整行 = ((string)反汇编.Invoke(null, [码])!).Trim();
                        int 分界 = 整行.LastIndexOf("    ", StringComparison.Ordinal);
                        string 实际 = 分界 >= 0 ? 整行[(分界 + 4)..] : 整行;
                        if (实际 != 期望)
                        {
                            逐条通 = false; 出岔的 = $"{中文}({英文},操作码 {操作码:X2},格式 {格式}) → 实际 <{实际}> / 期望 <{期望}>";
                            break;
                        }
                    }
                    记录("工具反汇编窗 全部指令逐条查得到(条数 == 指令表条数)",
                        逐条通 && 查过 == 指令C.全部指令.Count,
                        逐条通 ? $"查过 {查过} 条,条数与指令表一致" : 出岔的);
                }
            }
            catch (Exception ex) { 记录异常("工具反汇编窗 全部指令逐条查得到", ex); }

            // ② 工具层**不再挂第二份解码表** —— 源码里出现"操作码字面量"或"指令名串"就说明它又在自己抄编码,
            //    那正是 R4-7 的病根(两份表注定再漂移一次)。找不到仓库根如实记跳过(不在工作副本里跑)。
            try
            {
                string? 根 = 找仓库根目录();
                if (根 != null)
                {
                    // 前后都要收口:前面不许贴着字母数字(别把 `0x1234` 里的 `0x12` 当操作码),
                    // 后面下一位也不许是十六进制数字(别把 `0x{地址:X}` 这种插值当操作码);
                    // 文件里那份**讲历史**的注释(写着"只登记 0x00~0x1A")先剔掉,免得它自己被当成第二份表。
                    var 操作码字面量 = new Regex(@"(?<![0-9A-Za-z_])0x[0-9A-Fa-f]{2}(?![0-9A-Fa-f])");
                    string 文件 = Path.Combine(根, "工具", "反汇编器C.cs");
                    string 源 = File.ReadAllText(文件);
                    string 代码 = 去注释(源);
                    var 字面量 = 操作码字面量.Matches(代码).Select(m => m.Value).Distinct().ToArray();
                    var 名字 = 指令C.取全部中文指令名().Concat(指令C.取全部英文指令名())
                        .Distinct(StringComparer.Ordinal)
                        .Where(名 => 代码.Contains($"\"{名}\"", StringComparison.Ordinal)).ToArray();
                    记录("工具反汇编窗 源码里不再挂第二份解码表(没有操作码字面量,也没有指令名串)",
                        字面量.Length == 0 && 名字.Length == 0,
                        字面量.Length == 0 && 名字.Length == 0
                            ? $"{文件} 里 0 个操作码字面量 / 0 个指令名串"
                            : $"操作码字面量 {字面量.Length} 个: {string.Join(" ", 字面量)}" +
                              $"{(名字.Length > 0 ? $";指令名串 {名字.Length} 个: {string.Join(" ", 名字)}" : "")}");
                }
                else
                {
                    跳过("工具反汇编窗 源码里不再挂第二份解码表(没有操作码字面量,也没有指令名串)",
                        "找不到仓库根(不在工作副本里跑)");
                }
            }
            catch (Exception ex) { 记录异常("工具反汇编窗 源码里不再挂第二份解码表", ex); }

            // ③ 同一件事的**反向钉子**:工具层没登记的操作码(指令表最大操作码往后一位)不许被装成一条指令
            try
            {
                if (反汇编器 == null)
                {
                    跳过("工具反汇编窗 没登记的操作码如实打未知(不装成一条指令)",
                        "当前进程里没有 工具.反汇编器C(自检不在主程序里跑)");
                }
                else if (反汇编器.GetMethod("反汇编", [typeof(byte[])]) is { } 反汇编)
                {
                    byte 野码 = (byte)(指令C.全部指令.Max(x => x.操作码) + 1);
                    uint 词 = (uint)野码 << 24;
                    byte[] 码 = [(byte)词, (byte)(词 >> 8), (byte)(词 >> 16), (byte)(词 >> 24)];
                    string 实际 = (string)反汇编.Invoke(null, [码])!;
                    记录("工具反汇编窗 没登记的操作码如实打未知(不装成一条指令)",
                        实际.Contains("未知操作码", StringComparison.Ordinal)
                            && 实际.Contains(野码.ToString("X2"), StringComparison.Ordinal),
                        $"没登记的操作码 {野码:X2} → <{实际.Replace("\r", " ").Replace("\n", " ").Trim()}>");
                }
            }
            catch (Exception ex) { 记录异常("工具反汇编窗 没登记的操作码", ex); }
        }

        /// <summary>
        /// 把源码里的 `//` 注释整段剔掉(字符串/字符字面量里的 `//` 原样留着)—— 用来判"有没有第二份解码表"。
        /// 为什么非要剔:**讲历史的那条注释自己就写着 `0x00~0x1A`**(解释 R4-7 以前错在哪),
        /// 不剔的话机检会把它当"又抄了一份表",那条断言就永远红着、没人再信它。
        /// </summary>
        private static string 去注释(string 代码)
        {
            var 结果 = new System.Text.StringBuilder(代码.Length);
            for (int i = 0; i < 代码.Length; i++)
            {
                char c = 代码[i];
                if (c == '"' || c == '\'')
                {
                    char 引号 = c;
                    结果.Append(c);
                    for (int j = i + 1; j < 代码.Length; j++)
                    {
                        结果.Append(代码[j]);
                        if (代码[j] == '\\' && j + 1 < 代码.Length) { 结果.Append(代码[++j]); continue; }
                        if (代码[j] == 引号) { i = j; break; }
                    }
                    continue;
                }
                if (c == '/' && i + 1 < 代码.Length && 代码[i + 1] == '/')
                {
                    while (i < 代码.Length && 代码[i] != '\n') i++;
                    结果.Append('\n');
                    continue;
                }
                结果.Append(c);
            }
            return 结果.ToString();
        }
    }
}
