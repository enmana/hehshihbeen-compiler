                    "    测试输出(轮);\n}\n停止\n";
                string 优化期望 = "打开窗口 标题=\"优化\" 宽=100 高=100\n2\n65\n3\n0\n4\n1\n3";
                var 优化开 = 跑图形源码(优化源, (2, 65, 0, 0), (3, 0, 0, 0), (4, 1, 0, 0));
                // 优化关:同一个入口、同一个呈现口,只是让 `汇编器C` 别做编译期优化(与 `优化自检` 里那套"双跑"同口径)
                string 优化关 = 跑图形源码带(优化源, 优化: false, (2, 65, 0, 0), (3, 0, 0, 0), (4, 1, 0, 0));
                记录("图形 取事件 的出参在循环体里每轮都重读(优化开/关双跑一致 —— 抓回提升循环不变量的那处缺陷)",
                    优化开.输出 == 优化期望 && 优化关 == 优化开.输出,
                    $"优化开=<{优化开.输出.Replace("\n", "|")}> 优化关=<{优化关.Replace("\n", "|")}> 期望=<{优化期望.Replace("\n", "|")}>");
                期望异常("图形 取事件 的四个实参必须写变量名(写表达式当场报错)",
                    () => 汇编("整数 类型 = 0;\n整数 键码 = 0;\n整数 mx = 0;\n整数 my = 0;\n如果 (取事件(类型 + 0, 键码, mx, my)) { }\n停止\n"),
                        "变量名");
            }
            catch (Exception ex) { 记录异常("图形 编译期护栏", ex); }

            // ---- ⑧ 标准工程 示例14_图形界面:逐行对 `// 预期输出:`(引擎内 + 命令行 --无头 两条路) ----
            try
            {
                string? 根 = 找示例目录();
                string? 文件 = 根 == null ? null
                    : Path.Combine(根, "中间层", "示例14_图形界面", "主程序.hb");
                if (文件 == null || !File.Exists(文件))
                {
                    跳过("图形 标准工程 示例14 逐行对预期输出", $"找不到 {文件 ?? "Sample 目录"}");
                    跳过("图形 CLI --无头 逐行对预期输出", "找不到标准工程");
                }
                else
                {
                    string[] 行表 = File.ReadAllLines(文件);
                    var 期望 = 解析预期输出(行表);
                    string 目录 = Path.GetDirectoryName(文件)!;
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 目录, 示例堆大小(目录));
                    string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望);
                    记录("图形 标准工程 示例14 逐行对预期输出(无头呈现)",
                        实际 == 应有 && 期望.Count > 0,
                        实际 == 应有 ? $"{期望.Count} 行逐字对上" : $"实际=<{实际.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");

                    // 命令行那条路:`hbcc --run --无头`(hbcc 没有窗口 ⇒ 无头呈现;`--无头` 是把它写明白)
                    string? 编译器 = 找命令行编译器();
                    if (编译器 == null)
                        跳过("图形 CLI --无头 逐行对预期输出", "找不到 hbcc.dll(在 IDE 里跑自检时正常)");
                    else
                    {
                        var (码, 出, 误) = 跑命令行(编译器, 目录, 120_000, "主程序.hb", "--run", "--无头");
                        string 规范出 = 出.Replace("\r\n", "\n");
                        bool 过 = 码 == 0 && 规范出.Contains(应有, StringComparison.Ordinal);
                        记录("图形 CLI --无头 逐行对预期输出(hbcc 无窗口 ⇒ 图形命令逐条打在标准输出上)", 过,
                            过 ? $"退出码 0;{期望.Count} 行一行不落" : $"退出码 {码};{截断(误 + 出, 160)}");
                    }
                }
            }
            catch (Exception ex) { 记录异常("图形 标准工程与技术", ex); }

            // ---- ⑨ 只量不判:一帧 N 条命令的入队 / dump 成本(拍板要的那个"实际帧率"出处) ----
            try
            {
                var 源 = new StringBuilder("如果 (打开窗口(\"量\", 320, 200))\n{\n");
                for (int i = 0; i < 120; i++)
                    源.Append($"    画矩形(1, {i}, 8, 8, 0xFF102030);\n");
                源.Append("    刷新();\n    关闭窗口();\n}\n停止\n");
                var 秒表 = System.Diagnostics.Stopwatch.StartNew();
                var 测 = 跑图形源码(源.ToString());
                秒表.Stop();
                int 条数 = 测.输出.Split('\n').Length;
                记录("图形 一帧 120 条命令:无头入队 + dump 一趟的开销(只量不判阈值,给『全量重绘还是脏矩形』作数)",
                    测.输出.Contains("刷新 命令=120", StringComparison.Ordinal),
                    $"120 条命令(共 {条数} 行输出)耗时 {秒表.Elapsed.TotalMilliseconds:F1} ms;" +
                    $"折合每秒约 {120 / Math.Max(0.001, 秒表.Elapsed.TotalSeconds):F0} 条命令(纯 C# 入队 + 写缓冲)");
            }
            catch (Exception ex) { 记录异常("图形 一帧开销实测", ex); }
        }
    }
