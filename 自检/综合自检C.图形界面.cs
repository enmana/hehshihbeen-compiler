        /// <summary>
        /// 跑一段图形源码:**无头呈现**挂在一份自己的缓冲上,跑完给出(输出, 没刷新的命令数, 窗口还开着吗)。
        /// 与 `运行带输出` 的区别:这一份**不摘呈现口**,所以能接着查队列状态。
        /// </summary>
        private static (string 输出, int 攒着, bool 开着, int 剩事件) 跑图形源码(
            string 源码, params (int 类型, int 键码, int x, int y)[] 事件)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(t => 缓冲.Append(t));
            var vm = new 虚拟机C
            {
                输入源 = () => null,
                输出目标 = 解码.写,
                宿主调用 = 宿主能力C.处理,
            };
            图形宿主C.清空();
            图形宿主C.挂上(new 无头呈现C(new StringWriter(缓冲) { NewLine = "\n" }));
            try
            {
                foreach (var 条 in 事件) 图形宿主C.投事件(条.类型, 条.键码, 条.x, 条.y);
                编译并跑(vm, 源码);
                解码.收尾();
                return (缓冲.ToString().Replace("\r\n", "\n").TrimEnd('\n'),
                        图形宿主C.待刷新命令().Length, 图形宿主C.窗口开着, 图形宿主C.事件数);
            }
            finally { 图形宿主C.摘掉(); }
        }

        /// <summary>
        /// 同上,但能指定**优化开/关**(与 `优化自检` 里那套"双跑"同口径:直接走 `汇编器C`)。
        /// 图形能力与优化开关本来无关,这里专门用来钉住"编译器自己造的写"不会被循环不变量提升漏掉。
        /// </summary>
        private static string 跑图形源码带(string 源码, bool 优化, params (int 类型, int 键码, int x, int y)[] 事件)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(t => 缓冲.Append(t));
            var 编译结果 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源码)], 优化);
            var vm = new 虚拟机C
            {
                输入源 = () => null,
                输出目标 = 解码.写,
                宿主调用 = 宿主能力C.处理,
                初值表 = 编译结果.初值表,
            };
            图形宿主C.清空();
            图形宿主C.挂上(new 无头呈现C(new StringWriter(缓冲) { NewLine = "\n" }));
            try
            {
                foreach (var 条 in 事件) 图形宿主C.投事件(条.类型, 条.键码, 条.x, 条.y);
                vm.运行(编译结果.机器码);
                解码.收尾();
                return 缓冲.ToString().Replace("\r\n", "\n").TrimEnd('\n');
            }
            finally { 图形宿主C.摘掉(); }
        }

        /// <summary> 引擎级的边界探针:手工造内存 + 参数区,走**真实入口** `宿主能力C.处理` 问状态码 </summary>
        private static int 问图形状态(byte[] 内存, uint 区, int 功能号) =>
            宿主能力C.处理(内存, 区, 功能号);

        private static void 图形写字(byte[] 内存, uint 地址, uint 值)
        {
            内存[地址] = (byte)(值 & 0xFF);
            内存[地址 + 1] = (byte)((值 >> 8) & 0xFF);
            内存[地址 + 2] = (byte)((值 >> 16) & 0xFF);
            内存[地址 + 3] = (byte)((值 >> 24) & 0xFF);
        }

        private static uint 图形读字(byte[] 内存, uint 地址) =>
            (uint)(内存[地址] | (内存[地址 + 1] << 8) | (内存[地址 + 2] << 16) | (内存[地址 + 3] << 24));

