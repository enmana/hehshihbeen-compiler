// ============================================================
// 元组自检(H68-3,第320批)—— `[整数, 整数] 一份 = [7, 3];`
//
//   语言面新增,所以这一组的钉法 = **真编真跑看输出** + 几处"报错文案 / 编辑器旁路信息"对着钉:
//     · 声明与成员:不写名 ⇒ `.项0` / `.项1`(**从 0 起**);写名 ⇒ 用真名;成员能读能改
//     · **元组就是"给结构起个名字"**:同一段程序用元组写与用手写结构写,机器码**逐字节相同**
//       (这条是这一批最硬的证据 —— 说明落地形态真的复用了结构那一整套)
//     · 整体赋值 = 独立的一份;元素类型:枚举 / 结构 / 另一个元组都行
//     · 处处能用:元组数组(含运行期下标)/ 当参数传(与结构一样按地址传)/ 当返回值 /
//       当结构字段 / `引用` 指一份元组
//     · 名义制:`[整数, 整数]` 与 `[整数 商, 整数 余]`(还有长得像的结构)是**三个类型**,不许互赋
//     · 报错口径:空元组 / 元素是字符串 / 括号不配 / 没有那个成员 / 成员名重复
//     · 编辑器:名字表(结构 + 变量类型名)、`.` 后面的成员补全、类型候选里不出现元组、高亮、声明扫描
//
//   为什么这么钉:元组**没有自己的语义** —— 它整份活在"声明期造一个结构类型"这一层,
//   所以"与手写结构机器码逐字节相同"这一条同时证明了三件事(布局对 / 访问对 / 传参对)。
// ============================================================

using System;
using System.Collections.Generic;
using System.Linq;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 元组自检()
        {
            // ---- ① 声明与成员:不写名 ⇒ .项0 / .项1;写名 ⇒ 用真名 ----
            跑输出断言("H68-3 元组:不写名字成员依次是 .项0 / .项1(从 0 起),写名字就用真名",
                "[整数, 整数] 一份 = [7, 3];\n" +
                "测试输出(一份.项0);\n测试输出(一份.项1);\n" +
                "[整数 商, 整数 余] 带名 = [17, 5];\n测试输出(带名.商);\n测试输出(带名.余);\n停止",
                "7\n3\n17\n5");

            // ---- ② 成员能改;整体赋值是独立的一份拷贝 ----
            跑输出断言("H68-3 元组成员能读能改;整体赋值是**独立的一份**(改副本不动原件)",
                "[整数, 整数] 一份 = [7, 3];\n" +
                "一份.项1 = 8;\n测试输出(一份.项1);\n" +
                "[整数, 整数] 副本 = 一份;\n副本.项0 = 100;\n" +
                "测试输出(一份.项0);\n测试输出(副本.项0);\n停止",
                "8\n7\n100");

            // ---- ③ 元素类型:枚举 / 结构 / 另一个元组 ----
            跑输出断言("H68-3 元组元素类型:枚举 / 结构 / **另一个元组** 都行(元组能套元组)",
                "枚举 颜色 { 赤, 绿, 蓝 }\n" +
                "结构 点\n{\n整数 x;\n整数 y;\n}\n" +
                "[颜色, 点] 卡片;\n卡片.项0 = 绿;\n卡片.项1.x = 8;\n" +
                "测试输出(卡片.项0);\n测试输出(卡片.项1.x);\n" +
                "[[整数, 整数], 整数] 套;\n套.项0.项0 = 1;\n套.项0.项1 = 2;\n套.项1 = 3;\n" +
                "测试输出(套.项0.项1 + 套.项1);\n停止",
                "1\n8\n5");

            // ---- ④ 元组数组(含运行期下标)与当结构字段 ----
            跑输出断言("H68-3 元组数组(元素紧排、运行期下标也认)与当结构字段",
                "结构 卡\n{\n[整数, 整数] 坐标;\n整数 号;\n}\n" +
                "[整数, 整数] 表[3];\n表[0].项0 = 1;\n表[0].项1 = 2;\n" +
                "循环 (var i = 0; i < 3; i = i + 1)\n{\n表[i].项1 = 表[i].项1 + i;\n}\n" +
                "测试输出(表[0].项0 + 表[0].项1 + 表[1].项1 + 表[2].项1);\n" +
                "卡 我的卡;\n我的卡.坐标.项0 = 3;\n我的卡.坐标.项1 = 4;\n我的卡.号 = 9;\n" +
                "测试输出(我的卡.坐标.项0 + 我的卡.坐标.项1);\n测试输出(我的卡.号);\n停止",
                "6\n7\n9");

            // ---- ⑤ 当参数传(与结构一样按地址传)/ 当返回值 / `引用` 指一份元组 ----
            跑输出断言("H68-3 元组当参数(按地址,改的就是调用方那份)/ 当返回值 / `引用` 指它",
                "方法 累加进(整数 值, [整数, 整数] 账) 返回 整数\n{\n账.项0 = 账.项0 + 值;\n返回 账.项0;\n}\n" +
                "方法 取一份() 返回 [整数, 整数]\n{\n[整数, 整数] 局 = [4, 5];\n返回 局;\n}\n" +
                "[整数, 整数] 账 = [0, 0];\n测试输出(累加进(5, 账));\n测试输出(账.项0);\n" +
                "[整数, 整数] 得到 = 取一份();\n测试输出(得到.项0);\n测试输出(得到.项1);\n" +
                "引用 [整数, 整数] 指 = 账;\n指.项0 = 99;\n测试输出(账.项0);\n停止",
                "5\n5\n4\n5\n99");

            // ---- ⑥ 元组就是"给结构起个名字":与手写结构机器码逐字节相同 ----
            byte[] 元组版 = 汇编("[整数, 整数] 对 = [7, 3];\n对.项0 = 对.项0 + 2;\n测试输出(对.项0);\n停止");
            byte[] 结构版 = 汇编("结构 对\n{\n整数 项0;\n整数 项1;\n}\n对 对值 = [7, 3];\n对值.项0 = 对值.项0 + 2;\n测试输出(对值.项0);\n停止");
            记录("H68-3 元组 = **给结构起个名字**:同一段程序用元组写与用手写结构写,机器码逐字节相同",
                元组版.SequenceEqual(结构版),
                $"元组 {元组版.Length} 字节 / 手写结构 {结构版.Length} 字节");

            // ---- ⑦ 名义制:写法不同就是两个类型,不许互赋(元组 / 结构都拦) ----
            string 两个元组 = 异常文本(() => 汇编(
                "[整数, 整数] 目标 = [1, 2];\n[整数 商, 整数 余] 来源 = [3, 4];\n目标 = 来源;\n停止"));
            记录("H68-3 名义制:写法不同的两个元组不能整块赋值,报错点明两边各是什么类型",
                两个元组.Contains("两边不是同一种类型", StringComparison.Ordinal)
                && 两个元组.Contains("[整数, 整数]", StringComparison.Ordinal)
                && 两个元组.Contains("[整数 商, 整数 余]", StringComparison.Ordinal), 两个元组);

            string 元组与结构 = 异常文本(() => 汇编(
                "结构 点\n{\n整数 x;\n整数 y;\n}\n[整数, 整数] 目标 = [1, 2];\n点 来源 = [3, 4];\n目标 = 来源;\n停止"));
            记录("H68-3 名义制:元组与长得像的结构也不能互赋(同上一条口径)",
                元组与结构.Contains("两边不是同一种类型", StringComparison.Ordinal)
                && 元组与结构.Contains("元组按**写法**认类型", StringComparison.Ordinal), 元组与结构);

            string 声明拷贝 = 异常文本(() => 汇编(
                "[整数, 整数] 目标 = [1, 2];\n[整数 商, 整数 余] 来源 = 目标;\n停止"));
            记录("H68-3 名义制在**声明拷贝**那条路上也拦(`[整数 商, 整数 余] 目标 = 来源;`)",
                声明拷贝.Contains("两边不是同一种类型", StringComparison.Ordinal), 声明拷贝);

            // ---- ⑧ 报错口径:空元组 / 元素是字符串 / 括号不配 / 没有那个成员 / 成员名重复 ----
            string 空元组 = 异常文本(() => 汇编("[] 值;\n停止"));
            记录("H68-3 空元组 `[]` 当场报错(带行号 + 写法 + 给改法)",
                空元组.Contains("元组类型写不出来", StringComparison.Ordinal)
                && 空元组.Contains("一个元素都没有", StringComparison.Ordinal), 空元组);

            string 字符串元素 = 异常文本(() => 汇编("[整数, 字符串] 值;\n停止"));
            记录("H68-3 元素是 `字符串` 的元组还没做(如实说清是哪一样没做)",
                字符串元素.Contains("元素是 `字符串` 的元组还没做", StringComparison.Ordinal), 字符串元素);

            string 括号不配 = 异常文本(() => 汇编("[整数, 整数 值;\n停止"));
            记录("H68-3 少一个 `]` 也走声明那条路报错(不掉进\"未知指令\"那种看不出所以然的话)",
                括号不配.Contains("方括号没配对", StringComparison.Ordinal), 括号不配);

            string 没有成员 = 异常文本(() => 汇编("[整数, 整数] 值 = [1, 2];\n测试输出(值.项2);\n停止"));
            记录("H68-3 点了没有的成员:`结构 '[整数, 整数]' 没有字段 '项2'`(与结构同一条报错)",
                没有成员.Contains("没有字段 '项2'", StringComparison.Ordinal), 没有成员);

            string 成员重名 = 异常文本(() => 汇编("[整数 x, 整数 x] 值;\n停止"));
            记录("H68-3 成员名重复当场报错",
                成员重名.Contains("成员名 'x' 重复了", StringComparison.Ordinal), 成员重名);

            // ---- ⑨ 名字表:元组类型进结构表(字段 项0 / 项1),变量记的类型名就是那份写法 ----
            try
            {
                var 结果 = new 汇编器C().汇编多文件带调试([("主.hb", "[整数, 整数] 结果 = [7, 3];\n停止")]);
                名字表C 表 = 结果.名字表;
                bool 登记对 = 表.结构.TryGetValue("[整数, 整数]", out var 字段们)
                    && 字段们.Count == 2 && 字段们[0].名字 == "项0" && 字段们[1].名字 == "项1";
                var 变量项 = 表.变量.FirstOrDefault(v => v.名字 == "结果");
                记录("H68-3 名字表:元组类型进\"结构\"那一格(字段 项0 / 项1),变量的类型名就是那份写法",
                    登记对 && 变量项 != null && 变量项.类型名 == "[整数, 整数]",
                    $"结构表里有没有 [{表.结构.ContainsKey("[整数, 整数]")}] / 结果的类型名=<{变量项?.类型名}>");
            }
            catch (Exception ex) { 记录异常("H68-3 名字表:元组登记", ex); }

            // ---- ⑩ 补全:元组变量 `.` 后面给成员;元组类型**不当类型候选**(它不是个标识符) ----
            try
            {
                const string 源 = "[整数, 整数] 结果 = [7, 3];\n测试输出(结果.项0);\n停止";
                var 编译 = new 汇编器C().汇编多文件带调试([("主.hb", 源)]);
                var 来源 = new 补全来源C { 本文件表 = 编译.调试文件表[0].名字表, 工程表 = 编译.名字表 };
                int 点后行 = 源[..源.IndexOf("测试输出(结果.项0)", StringComparison.Ordinal)].Count(c => c == '\n') + 1;
                var 成员 = 补全名字C.取(来源, new 补全请求C
                {
                    当前文件 = "主.hb",
                    当前行 = 点后行,
                    词 = "项",
                    点名 = "结果",
                    在点后 = true,
                    现场正文 = 源,
                    现场兜底 = false,
                    上限 = 50,
                });
                var 全候选 = 补全名字C.取(来源, new 补全请求C
                {
                    当前文件 = "主.hb",
                    当前行 = 点后行,
                    词 = "",
                    现场正文 = 源,
                    现场兜底 = false,
                    上限 = 500,
                });
                记录("H68-3 补全:元组变量 `.` 后面给得出 项0 / 项1",
                   成员.Any(x => x.词 == "项0") && 成员.Any(x => x.词 == "项1"),
                    string.Join(" / ", 成员.Select(x => x.词)));
                记录("H68-3 补全:元组类型自己**不进**类型候选(它没有标识符形状,插不进去)",
                    !全候选.Any(x => x.词.StartsWith("[", StringComparison.Ordinal)),
                    全候选.Any(x => x.词.StartsWith("[", StringComparison.Ordinal)) ? "候选里有 `[`" : "候选里没有 `[`");
            }
            catch (Exception ex) { 记录异常("H68-3 补全:元组成员", ex); }

            // ---- ⑪ 高亮 / 声明扫描 / 现场兜底:元组声明的变量都收得进来 ----
            var 名集 = 源码名字扫描C.扫描("[整数, 整数] 结果 = [7, 3];\n[整数, 整数] 表[3];\n测试输出(结果.项0);\n停止");
            记录("H68-3 高亮的名字扫描收得到元组声明的变量(结果 / 表,不是整行)",
                名集.变量.Contains("结果") && 名集.变量.Contains("表"),
                string.Join(" / ", 名集.变量));

            var 声明树 = 源码声明扫描C.扫结构("[整数, 整数] 结果 = [7, 3];\n[整数 商, 整数 余] 一份;\n停止");
            记录("H68-3 声明扫描(结构导图那条数据源)认得出元组声明:名字与类型词都对",
                声明树.变量们.Any(v => v.名 == "结果" && v.类型词.Contains("[整数, 整数]", StringComparison.Ordinal))
                && 声明树.变量们.Any(v => v.名 == "一份" && v.类型词.Contains("商", StringComparison.Ordinal)),
                string.Join(" / ", 声明树.变量们.Select(v => $"{v.名}:{v.类型词}")));

            var 补全名 = 补全词表C.从源码收集名字("[整数, 整数] 结果 = [7, 3];\n停止");
            记录("H68-3 补全(现场兜底那条路)也收得到元组声明的变量",
                补全名.Contains("结果"), string.Join(" / ", 补全名));

            // ---- ⑫ 排版:元组那几行一个字不动(画括号才拆块,方括号不拆) ----
            const string 待排 = "[整数, 整数] 结果 = [7, 3];\n[整数, 整数] 表[3];\n测试输出(结果.项0);\n";
            记录("H68-3 排版:元组声明与 `[…]` 初值原样留着(方括号不是语句块,一行还是一行)",
                string.Equals(代码排版C.排版(待排).文本, 待排, StringComparison.Ordinal),
                看白(代码排版C.排版(待排).文本));

            // ---- ⑬ 帮助:元组进规格,第27节写明三样不做 ----
            string 速查 = 帮助文本C.中间层速查();
            记录("帮助《中间层速查》把元组写成规格(写法 / 项0 从 0 起 / 起名 / 名义制 / 哪几样不做)",
                速查.Contains("[整数, 整数] 一份 = [7, 3];", StringComparison.Ordinal)
                && 速查.Contains("**元组**:类型位置写一对方括号", StringComparison.Ordinal)
                && 速查.Contains("从 0 起", StringComparison.Ordinal)
                && 速查.Contains("名义制", StringComparison.Ordinal)
                && 速查.Contains("按地址传", StringComparison.Ordinal),
                "《中间层速查》数据那一节");

            string 上手 = 帮助文本C.快速上手();
            记录("帮助《第27节·还没有的写法》写明元组哪三样不做(拆包 / 字符串元素 / 空元组)",
                上手.Contains("元组有三样不做", StringComparison.Ordinal)
                && 上手.Contains("拆包", StringComparison.Ordinal)
                && 上手.Contains("空元组 `[]` 不收", StringComparison.Ordinal),
                "硬规矩 18:用户文档只写规格");
        }
    }
}
