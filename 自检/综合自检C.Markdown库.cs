// ============================================================
// Markdown 库的自检(G4 批 17)
//   —— `Sample\库\Markdown.hb`
//
//   判据照 `基础库施工计划.md` §2 批 17 那一行:**生成的 `.md` 逐字节可复现;读回块 / 行内**。
//   这一组七块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **写**:同一串调用给同一串整篇(`标题 / 段落 / 要点 / 编号 / 引用 / 分隔线 / 代码块 / 表格`);
//     ② **读块**:块数 / 每一块的文本 / 种类合计 / 标题的级;
//     ③ **读行内**:正文 / 粗体 / 斜体 / 行内代码 / 链接(带地址)/ 图片(带地址);
//     ④ **表格**:行数(含列头)/ 每行格数 / 行首格 / 格文本 / 越界;
//     ⑤ **转纯文本 / 转HTML**:去掉标记的正文 + HTML 五个字符转义(正文里的 `<b>&"'` 只是字);
//     ⑥ **边界**:空文本给 0 / 标题级越界夹到 1~6 / 越界取块取行内给假 / 转义与中英空格逐字对;
//     ⑦ **接线哨兵**:库在盘上 + 头注释五段齐 + 模块名 + 公开函数数(32)。
//
//   ⚠ 这一组**不引 `string.hb`**(Markdown 那一族零依赖):整数单独打(每行一个),
//     要"整数与文字拼在一起"就得引 `string.hb` 的 `转字符串`,那会把另一个"循环里拼字符串"的库拉进来。
//   ⚠ `跑()` 把换行压成 `|`、并且**每行末尾的空白先去掉**(表格那一路会留一个尾空格,
//     那是排版口径不是判据)—— 两边的期望都照这一套写。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void Markdown库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 库路径 = Path.Combine(库目录, "Markdown.hb").Replace('\\', '/');
            if (!File.Exists(库路径))
            {
                跳过("Markdown库 定位库文件", $"找不到 {库路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{库路径}\"\n";

            // 跑一段 HB:输出按行收(每行末尾空白去掉、空行保留)
            static List<string> 跑行(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 中间层C.默认堆大小, null,
                    中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                var 行表 = 缓冲.ToString().Replace("\r", "").Split('\n')
                    .Select(x => x.TrimEnd()).ToList();
                while (行表.Count > 0 && 行表[^1].Length == 0) 行表.RemoveAt(行表.Count - 1);
                while (行表.Count > 0 && 行表[0].Length == 0) 行表.RemoveAt(0);
                if (编译.查运行期报错(vm.内存) is { } 说明) 行表.Add($"⚠{说明}");
                return 行表;
            }

            // 一行一条地比;不齐就报第一处不一样(带行号,好查)
            void 比行(string 名, List<string> 实得, params string[] 期望行)
            {
                bool 好 = 实得.Count == 期望行.Length;
                int 第一坏 = -1;
                if (好)
                {
                    for (int i = 0; i < 期望行.Length; i++)
                        if (实得[i] != 期望行[i]) { 好 = false; 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实得.Count} 行逐行对上"
                    : $"实测 {实得.Count} 行 / 期望 {期望行.Length} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实得[第一坏]}> 期望=<{期望行[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实得)}>");
                记录(名, 好, 说明);
            }

            // 整篇那一档:按**行**比内容(空行不参与)
            void 比篇(string 名, List<string> 实得, params string[] 期望行)
            {
                var 实净 = 实得.Where(x => x.Length > 0).ToList();
                var 期净 = 期望行.Where(x => x.Length > 0).ToList();
                bool 好 = 实净.Count == 期净.Count && 实净.Zip(期净, (a, b) => a == b).All(x => x);
                int 第一坏 = -1;
                if (!好)
                {
                    int 上限 = Math.Min(实净.Count, 期净.Count);
                    for (int i = 0; i < 上限; i++)
                        if (实净[i] != 期净[i]) { 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实净.Count} 行(不计空行)逐行对上"
                    : $"实测 {实净.Count} 行 / 期望 {期净.Count} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实净[第一坏]}> 期望=<{期净[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实净)}>");
                记录(名, 好, 说明);
            }

            // 一份能覆盖写那一半所有档的整篇(`\n` 在 HB 侧现拼成真换行)
            string 造篇 =
                "逻辑 丢一 = Markdown.开始();\n"
                + "逻辑 丢二 = Markdown.标题(2, \"周报\");\n"
                + "逻辑 丢三 = Markdown.段落(\"本周完成 Markdown 库。\");\n"
                + "逻辑 丢四 = Markdown.要点(\"要点\");\n"
                + "逻辑 丢五 = Markdown.编号(\"第一件\");\n"
                + "逻辑 丢六 = Markdown.编号(\"第二件\");\n"
                + "逻辑 丢七 = Markdown.引用(\"引用一句\");\n"
                + "逻辑 丢八 = Markdown.分隔线();\n"
                + "逻辑 丢九 = Markdown.代码块(\"hb\", \"输出行(1);\");\n"
                + "字符串 换 = \"\";\n"
                + "拼接到(换, '\\n');\n"
                + "字符串 表行 = \"\";\n"
                + "拼接到(表行, \"张三|28\");\n"
                + "拼接到(表行, 换);\n"
                + "拼接到(表行, \"李四|30\");\n"
                + "逻辑 丢十 = Markdown.表格(\"名字|年龄\", 表行);\n"
                + "字符串 全篇 = \"\";\n"
                + "逻辑 丢十一 = Markdown.取结果(全篇);\n";

            // ---- ① 写:同一串调用给同一串整篇(字节 / 文字数 / 整篇逐行) ----
            try
            {
                比篇("Markdown库 写:标题 / 段落 / 要点 / 编号 / 引用 / 分隔线 / 代码块 / 表格 串成一份,字节数 / 文字数 / 整篇逐行对",
                    跑行(头 + 造篇
                        + "输出行(Markdown.字节数());\n"
                        + "输出行(全篇.长度());\n"
                        + "输出行(全篇);\n"
                        + "停止"),
                    "186", "124",
                    "## 周报", "本周完成 Markdown 库。", "- 要点",
                    "1. 第一件", "2. 第二件", "> 引用一句", "---",
                    "```hb", "输出行(1);", "```",
                    "| 名字 | 年龄 |", "| --- | --- |", "| 张三 | 28 |", "| 李四 | 30 |");
            }
            catch (Exception ex) { 记录异常("Markdown库 写那一半", ex); }

            // ---- ② 读块 ----
            try
            {
                比篇("Markdown库 读块:块数 / 每块的文本 / 种类合计 / 标题的级(别的块给 0)",
                    跑行(头 + 造篇
                        + "整数 文档 = Markdown.解析(全篇);\n"
                        + "字符串 块文 = \"\";\n"
                        + "整数 种类 = 0;\n"
                        + "输出行(Markdown.块数(文档));\n"
                        + "整数 i = 0;\n"
                        + "整数 类和 = 0;\n"
                        + "当 (i < Markdown.块数(文档))\n"
                        + "{\n"
                        + "    逻辑 有 = Markdown.取块(文档, i, 种类, 块文);\n"
                        + "    类和 = 类和 + 种类;\n"
                        + "    输出行(块文);\n"
                        + "    i = i + 1;\n"
                        + "}\n"
                        + "输出行(类和);\n"
                        + "输出行(Markdown.块级(文档, 0));\n"
                        + "输出行(Markdown.块级(文档, 1));\n"
                        + "停止"),
                    // 种类:1 标题 / 2 段落 / 3 要点 / 4 编号 ×2 / 5 引用 / 8 分隔线 / 6 代码块 / 7 表格
                    //   ⇒ 1+2+3+4+4+5+8+6+7 = 40
                    "9", "周报", "本周完成 Markdown 库。", "要点", "第一件", "第二件",
                    " 引用一句", "---", "输出行(1);",
                    "| 名字 | 年龄 |", "| --- | --- |", "| 张三 | 28 |", "| 李四 | 30 |",
                    "40", "2", "0");
            }
            catch (Exception ex) { 记录异常("Markdown库 读块", ex); }

            // ---- ③ 读行内:正文 / 粗体 / 斜体 / 行内代码 / 链接 / 图片 ----
            try
            {
                比篇("Markdown库 读行内:正文 / 粗体 / 斜体 / 行内代码 / 链接(带地址)/ 图片(带地址)逐条对",
                    跑行(头
                        + "字符串 源 = \"\";\n"
                        + "拼接到(源, \"左右\");\n"
                        + "拼接到(源, \"**粗**\");\n"
                        + "拼接到(源, \"*斜*\");\n"
                        + "拼接到(源, \"`码`\");\n"
                        + "拼接到(源, \"[本站](http://a)\");\n"
                        + "拼接到(源, \"![图](p.png)\");\n"
                        + "整数 文档 = Markdown.解析(源);\n"
                        + "输出行(Markdown.块数(文档));\n"
                        + "输出行(Markdown.行内数(文档, 0));\n"
                        + "字符串 段文 = \"\";\n"
                        + "字符串 段址 = \"\";\n"
                        + "整数 内类 = 0;\n"
                        + "整数 k = 0;\n"
                        + "整数 类和 = 0;\n"
                        + "字符串 串 = \"\";\n"
                        + "当 (k < Markdown.行内数(文档, 0))\n"
                        + "{\n"
                        + "    逻辑 有 = Markdown.取行内(文档, 0, k, 内类, 段文, 段址);\n"
                        + "    类和 = 类和 + 内类;\n"
                        + "    拼接到(串, 段文);\n"
                        + "    拼接到(串, ':');\n"
                        + "    拼接到(串, 段址);\n"
                        + "    拼接到(串, '/');\n"
                        + "    k = k + 1;\n"
                        + "}\n"
                        + "输出行(串);\n"
                        + "输出行(类和);\n"
                        + "停止"),
                    "1", "6", "左右:/粗:/斜:/码:/本站:http://a/图:p.png/", "21");
            }
            catch (Exception ex) { 记录异常("Markdown库 读行内", ex); }

            // ---- ④ 表格:行数 / 格数 / 格号 ----
            try
            {
                比行("Markdown库 表格:行数(含列头)/ 每行格数 / 行首格 / 格文本 / 越界给 -1 与 0",
                    跑行(头 + 造篇
                        + "整数 文档 = Markdown.解析(全篇);\n"
                        + "输出行(Markdown.表行数(文档, 8));\n"
                        + "输出行(Markdown.行格数(文档, 8, 0));\n"
                        + "输出行(Markdown.行格数(文档, 8, 1));\n"
                        + "输出行(Markdown.行首格(文档, 8, 0));\n"
                        + "输出行(Markdown.行首格(文档, 8, 1));\n"
                        + "字符串 格文 = \"\";\n"
                        + "字符串 格址 = \"\";\n"
                        + "整数 内类 = 0;\n"
                        + "逻辑 有 = Markdown.取行内(文档, 8, 0, 内类, 格文, 格址);\n"
                        + "输出行(格文);\n"
                        + "输出行(Markdown.行首格(文档, 8, 9));\n"
                        + "输出行(Markdown.行格数(文档, 8, 9));\n"
                        + "输出行(Markdown.表行数(文档, 0));\n"
                        + "停止"),
                    "3", "2", "2", "0", "2", "名字", "-1", "0", "0");
            }
            catch (Exception ex) { 记录异常("Markdown库 表格", ex); }

            // ---- ⑤ 转纯文本 / 转 HTML(HTML 五个字符转义) ----
            try
            {
                比行("Markdown库 转纯文本 / 转HTML:去掉标记的正文 + HTML 五个字符转义(`<b>&\"'` 只是字)",
                    跑行(头
                        + "字符串 源 = \"\";\n"
                        + "拼接到(源, \"# 标题\");\n"
                        + "拼接到(源, \"\\n\\n\");\n"
                        + "拼接到(源, \"一段 **粗** 与 `码`\");\n"
                        + "拼接到(源, \"\\n\\n\");\n"
                        + "拼接到(源, \"- 要点\");\n"
                        + "拼接到(源, \"\\n\\n\");\n"
                        + "拼接到(源, \"<b>&\\\"'\");\n"
                        + "整数 文档 = Markdown.解析(源);\n"
                        + "字符串 纯文 = \"\";\n"
                        + "逻辑 有一 = Markdown.转纯文本(文档, 纯文);\n"
                        + "输出行(纯文);\n"
                        + "字符串 网页 = \"\";\n"
                        + "逻辑 有二 = Markdown.转HTML(文档, 网页);\n"
                        + "输出行(网页);\n"
                        + "停止"),
                    "# 标题", "一段 粗 与 码", "- 要点", "<b>&\"'",
                    "<h1>标题</h1>", "<p>一段 <strong>粗</strong> 与 <code>码</code></p>",
                    "<ul>", "<li>要点</li>", "</ul>", "<p>&lt;b&gt;&amp;&quot;&#39;</p>");
            }
            catch (Exception ex) { 记录异常("Markdown库 转纯文本与转HTML", ex); }

            // ---- ⑥ 边界 + 写读往返 ----
            try
            {
                比行("Markdown库 边界:空文本给 0 / 标题级夹到 1 与 6 / 越界取块取行内给假 / 转义与中英空格逐字对",
                    跑行(头
                        + "输出行(Markdown.解析(\"\"));\n"
                        + "逻辑 丢一 = Markdown.开始();\n"
                        + "逻辑 丢二 = Markdown.标题(0, \"要点\");\n"
                        + "逻辑 丢三 = Markdown.标题(9, \"另要点\");\n"
                        + "字符串 全篇 = \"\";\n"
                        + "逻辑 丢四 = Markdown.取结果(全篇);\n"
                        + "整数 文档 = Markdown.解析(全篇);\n"
                        + "输出行(Markdown.块数(文档));\n"
                        + "输出行(Markdown.块级(文档, 0));\n"
                        + "输出行(Markdown.块级(文档, 1));\n"
                        + "字符串 段文 = \"\";\n"
                        + "整数 种类 = 0;\n"
                        + "逻辑 有 = Markdown.取块(文档, 0, 种类, 段文);\n"
                        + "输出行(段文);\n"
                        + "输出行(Markdown.取块(文档, 9, 种类, 段文));\n"
                        + "字符串 逃 = \"\";\n"
                        + "逻辑 丢五 = Markdown.转义(\"a*b_c#d+e|f~g\", 逃);\n"
                        + "输出行(逃);\n"
                        + "字符串 空 = \"\";\n"
                        + "逻辑 丢六 = Markdown.中英空格(\"中文abc12中文\", 空);\n"
                        + "输出行(空);\n"
                        + "逻辑 丢七 = Markdown.中英空格(\"中文 abc 中文\", 空);\n"
                        + "输出行(空);\n"
                        + "停止"),
                    "0", "2", "1", "6", "要点", "0",
                    "a\\*b\\_c\\#d\\+e\\|f\\~g", "中文 abc12 中文", "中文 abc 中文");
            }
            catch (Exception ex) { 记录异常("Markdown库 边界", ex); }

            // ---- ⑦ 接线哨兵 ----
            try
            {
                string 库文 = File.ReadAllText(库路径);
                int 公开数 = 0;
                foreach (var 行 in 库文.Split('\n'))
                {
                    string 净 = 行.Trim();
                    if (净.StartsWith("方法 ", StringComparison.Ordinal)) 公开数++;
                }
                记录("Markdown库 接线哨兵:库在盘上 + 头注释四段齐 + 模块名 + 公开函数数 32",
                    File.Exists(库路径)
                    && 库文.Contains("模块 Markdown", StringComparison.Ordinal)
                    && 库文.Contains("用法", StringComparison.Ordinal)
                    && 库文.Contains("复杂度:", StringComparison.Ordinal)
                    && 库文.Contains("内存账", StringComparison.Ordinal)
                    && 库文.Contains("边界(如实登记", StringComparison.Ordinal)
                    && 公开数 == 32,
                    $"公开函数 {公开数}(期望 32)");
            }
            catch (Exception ex) { 记录异常("Markdown库 接线哨兵", ex); }
        }
    }
}
