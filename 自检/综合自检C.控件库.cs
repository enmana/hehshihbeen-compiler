    /// (`打开窗口` / `刷新` / `关闭窗口` 一次都不出现 —— 那是程序的事)。
    /// 最后是标准工程 `示例16_控件库` 的两条路(引擎内无头 + `hbcc --无头 --事件脚本`)逐行对 `// 预期输出:`。
    /// </summary>
