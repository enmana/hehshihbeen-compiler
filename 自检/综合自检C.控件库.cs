                    "送事件(面, 4, 1, 10, 13);\n送事件(面, 5, 1, 10, 13);\n" +
                    "测试输出(控件值(面, 勾号));\n" +
                    "测试输出(取点击(面));\n" +
                    "送事件(面, 4, 1, 10, 13);\n送事件(面, 5, 1, 10, 13);\n" +
                    "测试输出(控件值(面, 勾号));\n" +
                    "送事件(面, 4, 1, 10, 39);\n送事件(面, 5, 1, 10, 39);\n" +
                    "测试输出(控件值(面, 组首));\n测试输出(控件值(面, 组次));\n" +
                    "送事件(面, 4, 1, 10, 65);\n送事件(面, 5, 1, 10, 65);\n" +
                    "测试输出(控件值(面, 组首));\n测试输出(控件值(面, 组次));\n测试输出(控件值(面, 组尾));\n" +
                    "设控件值(面, 条号, 30);\n测试输出(控件值(面, 条号));\n" +
                    "设控件值(面, 条号, 999);\n测试输出(控件值(面, 条号));\n" +
                    "设控件值(面, 条号, 0 - 5);\n测试输出(控件值(面, 条号));\n" +
                    "测试输出(重画(面));\n" +
                    "停止\n";
                var 跑 = 跑库源码(库文本, 源);
                // 清屏 1 + 复选框 3 + 单选首 3 + 单选次 3 + 单选尾 3 + 进度条 2 = 15 条
                string 应有 = "5\n6\n7\n0\n1\n-1\n0\n1\n0\n0\n1\n0\n30\n60\n0\n15";                记录("控件库 G3:复选框点一下切换(再点一下取消)、单选组同组互斥(不同组各管各的)、" +
                    "进度条夹在 0~上限;重画条数把新三样一起算进去",
                    跑.输出 == 应有,
                    跑.输出 == 应有 ? "16 行逐行对上(组首选中 → 组次选中时组首落选、1 组那个不受影响;进度条 30 / 999→60 / 负→0)"
                                : $"实际=<{跑.输出.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("控件库 G3 三样新控件", ex); }

            // ---- ⑩ 确定性:同一份源码两次跑逐字节一致(优化开 / 关也一致)----
            try
            {
                const string 源 =
                    "界面 面;\n建界面(面, 0, 0, 200, 0);\n整数 输入号 = 加文本框(面, \"\");\n" +
                    "整数 列表号 = 加列表(面, 2, 20);\n加列表项(面, 列表号, 1, \"表项\");\n" +
                    "送事件(面, 4, 1, 10, 5);\n送事件(面, 2, 65, 0, 0);\n送事件(面, 2, 键退格(), 0, 0);\n" +
                    "送事件(面, 4, 1, 10, 25);\n送事件(面, 5, 1, 10, 25);\n" +
                    "测试输出(取点击(面));\n测试输出(焦点控件(面));\n" +
                    "输出行(文本框内容(面, 输入号));\n输出行(列表项文本(面, 列表号, 1));\n" +
                    "停止\n";
                var 一 = 跑库源码(库文本, 源);
                var 二 = 跑库源码(库文本, 源);
                var 三 = 跑库源码(库文本, 源, null, 优化: false);
                记录("控件库 同一份源码两次跑逐字节一致(优化开 / 关也一致 —— 控件的状态全是确定的数据)",
                    一.输出 == 二.输出 && 一.输出 == 三.输出 && 一.输出.Length > 0,
                    $"两次输出 {一.输出.Length} 字逐字节相同;优化关那一遍也一样:<{一.输出.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("控件库 确定性双跑", ex); }

            // ---- ⑩ 标准工程 示例16_控件库:自检这条路(工程目录里的 `事件脚本.txt` 自动喂)----
            try
            {
                string? 文件 = 示例 == null ? null
                    : Path.Combine(示例, "中间层", "示例16_控件库", "主程序.hb");
                if (文件 == null || !File.Exists(文件))
                {
                    跳过("控件库 标准工程 示例16 逐行对预期输出", $"找不到 {文件 ?? "Sample 目录"}");
                    跳过("控件库 CLI --无头 --事件脚本 逐行对预期输出", "找不到标准工程");
                }
                else
                {
                    string[] 行表 = File.ReadAllLines(文件);
                    var 期望 = 解析预期输出(行表);
                    string 目录 = Path.GetDirectoryName(文件)!;
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 目录, 示例堆大小(目录));
                    string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望);
                    记录("控件库 标准工程 示例16 逐行对预期输出(布局 / 命中测试 / 点击 / 敲字 / 重绘调度,无头呈现)",
                        实际 == 应有 && 期望.Count > 0,
                        实际 == 应有 ? $"{期望.Count} 行逐字对上(8 帧:6 帧有事件、2 帧干净只推进节拍)"
                                      : $"实际=<{截断(实际, 200)}> 期望=<{截断(应有, 200)}>");

                    string? 编译器 = 找命令行编译器();
                    if (编译器 == null)
                        跳过("控件库 CLI --无头 --事件脚本 逐行对预期输出", "找不到 hbcc.dll(在 IDE 里跑自检时正常)");
                    else
                    {
                        var (码, 出, 误) = 跑命令行(编译器, 目录, 120_000, "主程序.hb", "--run", "--无头", "--事件脚本", "事件脚本.txt");
                        string 规范出 = 出.Replace("\r\n", "\n");
                        bool 过 = 码 == 0 && 规范出.Contains(应有, StringComparison.Ordinal);
                        记录("控件库 CLI --无头 --事件脚本 逐行对预期输出(命令行那条路与自检同一种喂法)",
                            过, 过 ? $"退出码 0;{期望.Count} 行一行不落" : $"退出码 {码};{截断(误 + 出, 200)}");
                    }
                }
            }
            catch (Exception ex) { 记录异常("控件库 标准工程与技术", ex); }
        }
