        /// <summary>
        /// 跑一段用控件库的源码:库作为**另一个文件**内联进来(测试源码里不用写 `包含`),
        /// 无头呈现挂在自己的缓冲上,可选一份事件脚本。回来的是(程序输出, 队列里剩几条事件)。
        /// </summary>
        private static (string 输出, int 剩事件) 跑库源码(string 库文本, string 源码,
            事件脚本C? 脚本 = null, bool 优化 = true)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(t => 缓冲.Append(t));
            var 编译结果 = new 汇编器C().汇编多文件带调试(
                [("界面.hb", 库文本), ("主程序.hb", 源码)], 优化);
            var vm = new 虚拟机C
            {
                输入源 = () => null,
                输出目标 = 解码.写,
                宿主调用 = 宿主能力C.处理,
                初值表 = 编译结果.初值表,
                取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址),
            };
            图形宿主C.清空();
            图形宿主C.挂上(new 无头呈现C(new StringWriter(缓冲) { NewLine = "\n" }));
            try
            {
                图形宿主C.挂事件脚本(脚本);
                vm.运行(编译结果.机器码);
                解码.收尾();
                return (缓冲.ToString().Replace("\r\n", "\n").TrimEnd('\n'), 图形宿主C.事件数);
            }
            finally { 图形宿主C.摘掉(); }
        }

