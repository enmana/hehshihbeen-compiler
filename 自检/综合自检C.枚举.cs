// 枚举自检(H68-2,第319批)—— `枚举 颜色 { 赤, 绿, 蓝 }`
//
//   语言面新增,所以这一组的钉法 = **真编真跑看输出** + 几处"报错文案"对着钉:
//     · 声明与取值:成员从 0 起依次 +1、`= 3` 自己定值、裸名与全名都认
//     · **不占存储**:同一段程序带不带枚举声明,机器码**逐字节相同**(枚举不占槽、不发指令)
//     · 成员就是常量:比较 / `选择` 的 `情况` / 循环头 / 数组初值里直接用
//     · 处处能用:变量 / 数组 / 结构字段 / 方法参数(含数组参数)/ 返回值 / `引用` / 静态容器常驻字段
//     · 约束三条各一钉:不许隐式跨枚举(声明 / 赋值 / 返回)、不当数组长度、两处名字冲突
//     · 高亮 / 补全 / 名字表 / 帮助:枚举名与成员各归哪一档
//
//   为什么这么钉:枚举是"只活在编译期"的东西 —— 它**不进内存、不动 ISA**,
//   所以"机器码逐字节相同"那一条就是它最硬的证据(比读源码文本的接线哨兵强)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 枚举自检()
        {
            // ---- ① 声明与取值:从 0 起 / 自己定值 / 裸名与全名 ----
            跑输出断言("H68-2 枚举:成员从 0 起依次 +1,`= 3` 自己定值,裸名与全名都认",
                "枚举 颜色 { 赤, 绿, 蓝 }\n枚举 方向 { 上 = 3, 下, 左 = 10, 右 }\n" +
                "颜色 画 = 绿;\n测试输出(画);\n测试输出(颜色.蓝);\n测试输出(左);\n测试输出(右);\n测试输出(下);\n停止",
                "1\n2\n10\n11\n4");

            // ---- ② 不占存储:带不带枚举声明,机器码逐字节相同 ----
            byte[] 带枚举 = 汇编("枚举 颜色 { 赤 = 5, 绿 }\n整数 直接取 = 绿;\n整数 按名取 = 颜色.绿;\n测试输出(直接取 + 按名取);\n停止");
            byte[] 不带枚举 = 汇编("整数 直接取 = 6;\n整数 按名取 = 6;\n测试输出(直接取 + 按名取);\n停止");
            记录("H68-2 枚举**不占存储**:同一段程序带不带枚举声明,机器码逐字节相同(成员当场折成立即数)",
                带枚举.SequenceEqual(不带枚举),
                $"带枚举 {带枚举.Length} 字节 / 不带 {不带枚举.Length} 字节");

            // ---- ③ 成员就是常量:比较 / 情况 / 循环头 / 数组初值 ----
            跑输出断言("H68-2 枚举成员在 比较 / `情况`(能列多个)/ 循环头 / 数组初值 里都是常量",
                "枚举 颜色 { 赤, 绿, 蓝 }\n" +
                "颜色 画 = 绿;\n" +
                "如果 (画 == 绿) { 测试输出(100); }\n" +
                "选择 (画)\n{\n情况 赤, 绿 { 测试输出(200); }\n默认 { 测试输出(0); }\n}\n" +
                "循环 (颜色 走 = 赤; 走 < 蓝; 走++)\n{\n测试输出(走);\n}\n" +
                "颜色 名单[3] = [蓝, 赤, 颜色.绿];\n名单[1] = 名单[0];\n" +
                "测试输出(名单[0] + 名单[1] + 名单[2]);\n停止",
                "100\n200\n0\n1\n5");

            // ---- ④ 处处能用:变量 / 结构字段 / 参数(含数组参数)/ 返回值 / 引用 / 静态容器字段 ----
            跑输出断言("H68-2 枚举名当类型名:结构字段 / 数组参数 / 返回值 / `引用` / 静态容器常驻字段 处处能用",
                "枚举 颜色 { 赤, 绿 = 5, 蓝 }\n" +
                "结构 卡\n{\n颜色 花色;\n整数 点数;\n}\n" +
                "方法 数一数(颜色 表[], 整数 个数) 返回 整数\n{\n整数 总 = 0;\n" +
                "循环 (var i = 0; i < 个数; i = i + 1) { 总 = 总 + 表[i]; }\n返回 总;\n}\n" +
                "方法 下一个(颜色 当前) 返回 颜色\n{\n如果 (当前 == 赤) { 返回 绿; }\n返回 蓝;\n}\n" +
                "颜色 色表[3];\n色表[0] = 赤;\n色表[1] = 绿;\n色表[2] = 蓝;\n" +
                "卡 一张 = [绿, 9];\n测试输出(一张.花色);\n测试输出(一张.点数);\n" +
                "测试输出(数一数(色表, 3));\n测试输出(下一个(赤));\n" +
                "静态 方法 棋盘()\n{\n颜色 当前方 = 赤;\n整数 步数 = 0;\n}\n棋盘.当前方 = 蓝;\n" +
                "测试输出(棋盘.当前方);\n" +
                "颜色 画 = 赤;\n引用 颜色 参 = 画;\n参 = 绿;\n测试输出(画);\n停止",
                "5\n9\n11\n5\n6\n5");

            // ---- ⑤ 一行写完与分行写都认(归一化那一步把成员表整条收成一个伪行) ----
            跑输出断言("H68-2 枚举一行写完 / 成员分行写都认(都是同一棵成员表)",
                "枚举 颜色 {\n赤,\n绿 = 4,\n蓝\n}\n颜色 画 = 绿;\n测试输出(画);\n测试输出(蓝);\n停止",
                "4\n5");

            // ---- ⑥ 约束:不许隐式跨枚举(声明 / 赋值 / 返回 三条路都拦) ----
            string 声明跨 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n枚举 方向 { 上, 下 }\n颜色 色值 = 上;\n停止"));
            记录("H68-2 跨枚举(声明初值)当场报错:说清两个枚举名 + 两条改法",
                声明跨.Contains("不许隐式互赋") && 声明跨.Contains("方向") && 声明跨.Contains("颜色")
                && 声明跨.Contains("整数 中转"), 声明跨);

            string 赋值跨 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n枚举 方向 { 上, 下 }\n颜色 色值 = 赤;\n色值 = 上;\n停止"));
            记录("H68-2 跨枚举(赋值)也当场拦(靠名字表里记的\"这个变量是哪个枚举\")",
                赋值跨.Contains("不许隐式互赋") && 赋值跨.Contains("方向"), 赋值跨);

            string 返回跨 = 异常文本(() => 汇编(
                "枚举 颜色 { 赤, 绿 }\n枚举 方向 { 上, 下 }\n方法 取() 返回 颜色\n{\n返回 上;\n}\n停止"));
            记录("H68-2 跨枚举(返回值)也当场拦(与声明 / 赋值同一句话)",
                返回跨.Contains("不许隐式互赋") && 返回跨.Contains("方向"), 返回跨);

            // ---- ⑦ 约束:枚举不进 `[]` 当数组长度 ----
            string 当长度 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n整数 表[赤];\n停止"));
            记录("H68-2 枚举成员不当数组长度:说清\"它是个值不是个数\"并给两条改法",
                当长度.Contains("不能当数组长度") && 当长度.Contains("区间类型") && 当长度.Contains("列表"),
                当长度);

            // ---- ⑧ 约束:两处名字冲突(枚举名重复 / 成员重名) ----
            string 枚举重名 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n枚举 颜色 { 新赤, 新绿 }\n停止"));
            记录("H68-2 枚举名重复:带上一处位置(与结构重名同一套口径)",
                枚举重名.Contains("枚举名冲突") && 枚举重名.Contains("第 1 行"), 枚举重名);

            string 成员重名 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n枚举 天气 { 晴, 绿 }\n停止"));
            记录("H68-2 两个枚举里的成员不许重名(裸名会说不清指谁),报错点明已在哪个枚举里",
                成员重名.Contains("枚举成员名冲突") && 成员重名.Contains("颜色"), 成员重名);

            string 变量撞枚举 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n整数 颜色 = 1;\n停止"));
            记录("H68-2 变量名不能与枚举名冲突", 变量撞枚举.Contains("不能与枚举名冲突"), 变量撞枚举);

            string 变量撞成员 = 异常文本(() => 汇编("枚举 颜色 { 赤, 绿 }\n整数 绿 = 1;\n停止"));
            记录("H68-2 变量名不能与枚举成员冲突", 变量撞成员.Contains("不能与枚举成员冲突"), 变量撞成员);

            // ---- ⑨ 高亮 / 补全:枚举名与成员各归哪一档 ----
            var 名集 = 源码名字扫描C.扫描("枚举 颜色 { 赤, 绿 = 5, 蓝 }\n颜色 画 = 绿;\n测试输出(画);\n停止");
            记录("H68-2 高亮:枚举名归\"类型\"那一档(进结构集)、成员归\"常量\"那一档、枚举变量进变量集",
                名集.结构.Contains("颜色") && 名集.常量名.Contains("赤") && 名集.常量名.Contains("绿")
                && 名集.常量名.Contains("蓝") && 名集.变量.Contains("画"),
                $"结构=<{string.Join("/", 名集.结构)}> 常量=<{string.Join("/", 名集.常量名)}> 变量=<{string.Join("/", 名集.变量)}>");

            var 补全名 = 补全词表C.从源码收集名字("枚举 颜色 { 赤, 绿 = 5, 蓝 }\n颜色 画 = 绿;\n停止");
            记录("H68-2 补全(现场兜底那条路):枚举名与成员都进候选",
                补全名.Contains("颜色") && 补全名.Contains("赤") && 补全名.Contains("绿") && 补全名.Contains("蓝"),
                string.Join("/", 补全名));

            try
            {
                var 结果 = new 汇编器C().汇编多文件带调试([("主.hb", "枚举 颜色 { 赤, 绿 = 5, 蓝 }\n颜色 画 = 绿;\n停止")]);
                名字表C 表 = 结果.名字表;
                bool 登记对 = 表.枚举.TryGetValue("颜色", out var 成员们) && 成员们.Count == 3
                    && 表.枚举成员.GetValueOrDefault("颜色.绿") == 5;
                var 变量项 = 表.变量.FirstOrDefault(v => v.名字 == "画");
                记录("H68-2 名字表:枚举名 → 成员清单 + 成员值都登记;枚举变量记的类型名是**枚举名**(不是 整数)",
                    登记对 && 变量项 != null && 变量项.类型名 == "颜色",
                    $"枚举={表.枚举.Count} 个 / 画 的类型名=<{变量项?.类型名}>(该是 颜色)");
            }
            catch (Exception ex) { 记录异常("H68-2 名字表:枚举登记", ex); }

            // ---- ⑩ 帮助:枚举进规格,第27节写上"哪两样不做" ----
            string 速查 = 帮助文本C.中间层速查();
            记录("帮助《中间层速查》把枚举写成规格(一行写完 / 自己定值 / 当类型名 / 与 整数 同构 / 三条约束)",
                速查.Contains("枚举 颜色 { 赤, 绿, 蓝 };", StringComparison.Ordinal)
                && 速查.Contains("**枚举**:", StringComparison.Ordinal)
                && 速查.Contains("自己定值", StringComparison.Ordinal)
                && 速查.Contains("不许隐式互赋", StringComparison.Ordinal),
                "《中间层速查》数据那一节");

            string 上手 = 帮助文本C.快速上手();
            记录("帮助《第27节·还没有的写法》写明枚举哪两样不做(成员分行写 / 当数组长度)",
                上手.Contains("枚举要一行写完,还有两样不做", StringComparison.Ordinal)
                && 上手.Contains("枚举成员**不能当数组长度**", StringComparison.Ordinal),
                "硬规矩 18:用户文档只写规格");

            // ---- ⑪ 关键字与说明(加关键字必须同步加说明) ----
            记录("H68-2 `枚举`/`enum` 进关键字表,说明表也有它(自检那条\"每个关键字都有说明\"之外再钉一次)",
                中间层C.到英文关键字("枚举") == "enum"
                && 中间层C.到英文关键字("enum") == "enum"
                && 中间层指令C.说明表.ContainsKey("enum"),
                "中英切换 / 高亮 / 帮助速查都读这两张表");
        }
    }
