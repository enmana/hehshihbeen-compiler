// ============================================================
// JSON / CSV流 / NDJSON流 三个库的自检(G4 批 16)
//   —— `Sample\库\JSON.hb` · `CSV流.hb` · `NDJSON流.hb`
//
//   判据照 `基础库施工计划.md` §2 批 16 那一行:**解析 / 生成往返;流式逐条、不整份进内存**。
//   这一组七块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **JSON 整份**:路径取值(含 `记录.字段[0].成员`)/ 数字原样 / `null` / 逻辑 / 越界给默认;
//        **生成与解析进来那一串逐字节相同**(空白与转义都原样);
//     ② **JSON 坏输入**:四种坏写法都判不成立 + `错处位置` 指到出界那一点;
//     ③ **JSON 构造器**:现建一棵(对象套数组)再生成,与 C# 侧算出来的期望串逐字比;
//     ④ **CSV流 真盘**:字段级写(该转义的自己转义)再读回 —— 条数 / 段数 / 每段字数 / 引号往返;
//     ⑤ **CSV流 长跑**:真盘 2000 行 × 2 段(跨块拼行),条数与段合计逐条对;
//     ⑥ **NDJSON流 真盘**:写两条 + 一条坏行,读回来坏行跳过、序号合计对;
//     ⑦ **接线哨兵**:三个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(30 / 11 / 10)。
//
//   ⚠ 这一组**不引 `string.hb`**(JSON 那一族零依赖),HB 侧的 JSON 文本用 `拼接到` 现拼,
//     免得在 C# 字符串里叠三层转义。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void JSON与流派库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 值路径 = Path.Combine(库目录, "JSON.hb").Replace('\\', '/');
            string 表路径 = Path.Combine(库目录, "CSV流.hb").Replace('\\', '/');
            string 行路径 = Path.Combine(库目录, "NDJSON流.hb").Replace('\\', '/');
            if (!File.Exists(值路径) || !File.Exists(表路径) || !File.Exists(行路径))
            {
                跳过("JSON与流派库 定位库文件", $"找不到 {值路径} 那三个(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{值路径}\"\n包含 \"{表路径}\"\n包含 \"{行路径}\"\n";

            // HB 侧现拼 JSON 文本用的两个小帮手(避开 C# 里的三层转义)
            string 帮手 = "方法 加引(字符串 出 文, 字符串 词)\n"
                + "{\n"
                + "    字符 引 = '\"';\n"
                + "    拼接到(文, 引);\n"
                + "    拼接到(文, 词);\n"
                + "    拼接到(文, 引);\n"
                + "    返回\n"
                + "}\n"
                + "方法 加冒(字符串 出 文)\n"
                + "{\n"
                + "    拼接到(文, ':');\n"
                + "    返回\n"
                + "}\n"
                + "方法 加逗(字符串 出 文)\n"
                + "{\n"
                + "    拼接到(文, ',');\n"
                + "    返回\n"
                + "}\n";

            static string 跑(string 源, int 堆大小, int 池大小, int 软栈大小 = 32 * 1024)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 堆大小, null, 池大小,
                    虚拟机C.默认内存大小, 软栈大小);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }
            string 跑小(string 源) => 跑(源, 中间层C.默认堆大小, 中间层C.默认池大小);

            // ---- ① JSON 整份:取值 + 往返 ----
            记录("JSON库 整份解析:路径取值 / 数字原样 / null / 个数 / 生成逐字节往返",
                跑小(头 + 帮手
                    + "字符串 文 = \"\";\n"
                    + "拼接到(文, '{');\n加引(文, \"名字\");\n加冒(文);\n加引(文, \"张三\");\n加逗(文);\n"
                    + "加引(文, \"年龄\");\n加冒(文);\n拼接到(文, \"28\");\n加逗(文);\n"
                    + "加引(文, \"在职\");\n加冒(文);\n拼接到(文, \"true\");\n加逗(文);\n"
                    + "加引(文, \"零\");\n加冒(文);\n拼接到(文, \"null\");\n加逗(文);\n"
                    + "加引(文, \"爱好\");\n加冒(文);\n拼接到(文, \"[\");\n加引(文, \"读书\");\n加逗(文);\n加引(文, \"爬山\");\n拼接到(文, \"]\");\n加逗(文);\n"
                    + "加引(文, \"成绩\");\n加冒(文);\n拼接到(文, \"{\");\n加引(文, \"数学\");\n加冒(文);\n拼接到(文, \"95\");\n拼接到(文, \"}\");\n拼接到(文, \"}\");\n"
                    + "整数 根 = JSON.解析(文);\n"
                    + "字符串 值 = \"\";\n"
                    + "测试输出(JSON.种类(根, \"\"));\n"
                    + "测试输出(JSON.取整数(根, \"年龄\", 0));\n"
                    + "测试输出(JSON.取整数(根, \"成绩.数学\", 0));\n"
                    + "测试输出(JSON.取整数(根, \"没有这个\", 7));\n"
                    + "测试输出(JSON.取逻辑(根, \"在职\", 假));\n"
                    + "测试输出(JSON.是空(根, \"零\"));\n"
                    + "测试输出(JSON.个数(根, \"爱好\"));\n"
                    + "测试输出(JSON.取文本(根, \"名字\", 值));\n"
                    + "测试输出(值.长度());\n"
                    + "测试输出(JSON.取文本(根, \"爱好[1]\", 值));\n"
                    + "测试输出(值.长度());\n"
                    + "字符串 出 = \"\";\n"
                    + "测试输出(JSON.生成到(根, 出));\n"
                    + "测试输出(出 == 文);\n"
                    + "停止")
                    == "6|28|95|7|1|1|2|1|2|1|2|1|1",
                "对象 / 28 / 95(嵌套路径)/ 7(默认)/ 真 / 是空 / 2 个爱好 / 张三 2 字 / 爬山 2 字 / 生成到 真 / 逐字节相同");

            // ---- ② 坏输入 + 错处位置 ----
            记录("JSON库 坏输入四种都判不成立,错处位置指到出界那一点",
                跑小(头 + "测试输出(JSON.解析(\"\"));\n"
                    + "字符 引 = '\"';\n"
                    + "字符串 坏 = \"\";\n拼接到(坏, '{');\n拼接到(坏, 引);\n拼接到(坏, \"记录\");\n拼接到(坏, 引);\n拼接到(坏, ':');\n拼接到(坏, '}');\n"
                    + "测试输出(JSON.解析(坏));\n"
                    + "测试输出(JSON.错处位置());\n"
                    + "测试输出(JSON.解析(\"[1,2\"));\n"
                    + "字符串 尾 = \"[1,2,]\";\n"
                    + "测试输出(JSON.解析(尾));\n"
                    + "停止")
                    == "0|0|10|0|0",
                "空串 0 / 值位置是 `}` 给 0 且错处 10 / 数组没闭 0 / 尾逗号 0");

            // ---- ③ 构造器 ----
            记录("JSON库 构造器:现建对象套数组再生成,C# 侧按同一套算的期望串逐字比",
                跑小(头 + "JSON.清空();\n"
                    + "整数 根 = JSON.新建对象();\n"
                    + "测试输出(JSON.放文本(根, \"名字\", \"李四\"));\n"
                    + "测试输出(JSON.放整数(根, \"年龄\", 30));\n"
                    + "测试输出(JSON.放逻辑(根, \"在职\", 假));\n"
                    + "测试输出(JSON.放空(根, \"备注\"));\n"
                    + "整数 爱 = JSON.新建数组();\n"
                    + "测试输出(JSON.放(根, \"爱好\", 爱));\n"
                    + "测试输出(JSON.加文本(爱, \"下棋\"));\n"
                    + "测试输出(JSON.加整数(爱, 7));\n"
                    + "字符串 出 = \"\";\n"
                    + "逻辑 好 = JSON.生成到(根, 出);\n"
                    + "字符串 想 = \"\";\n"
                    + "拼接到(想, '{');\n"
                    + "字符 引 = '\"';\n"
                    + "拼接到(想, 引);\n拼接到(想, \"名字\");\n拼接到(想, 引);\n拼接到(想, ':');\n拼接到(想, 引);\n拼接到(想, \"李四\");\n拼接到(想, 引);\n拼接到(想, ',');\n"
                    + "拼接到(想, 引);\n拼接到(想, \"年龄\");\n拼接到(想, 引);\n拼接到(想, ':');\n拼接到(想, \"30\");\n拼接到(想, ',');\n"
                    + "拼接到(想, 引);\n拼接到(想, \"在职\");\n拼接到(想, 引);\n拼接到(想, ':');\n拼接到(想, \"false\");\n拼接到(想, ',');\n"
                    + "拼接到(想, 引);\n拼接到(想, \"备注\");\n拼接到(想, 引);\n拼接到(想, ':');\n拼接到(想, \"null\");\n拼接到(想, ',');\n"
                    + "拼接到(想, 引);\n拼接到(想, \"爱好\");\n拼接到(想, 引);\n拼接到(想, ':');\n拼接到(想, \"[\");\n"
                    + "拼接到(想, 引);\n拼接到(想, \"下棋\");\n拼接到(想, 引);\n拼接到(想, ',');\n拼接到(想, \"7\");\n拼接到(想, \"]\");\n拼接到(想, \"}\");\n"
                    + "测试输出(好);\n"
                    + "测试输出(出 == 想);\n"
                    + "停止")
                    == "2|3|4|5|6|7|8|1|1",
                "节点号从 2 起(根占了 1)/ 生成到 真 / 与手拼的期望串逐字节相同");

            // ---- ④⑤⑥ 真盘:CSV流 / NDJSON流 ----
            string 临时根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"JSON流自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            if (临时根.Length == 0)
            {
                跳过("JSON与流派库 真盘那一半", "不在工作副本里跑就跳过");
                return;
            }
            try
            {
                Directory.CreateDirectory(临时根);
                string 表 = 临时根 + "/表.csv";
                string 大表 = 临时根 + "/大表.csv";
                string 日志 = 临时根 + "/日志.ndjson";

                记录("CSV流库 真盘写读往返:字段级转义 + 引号往返 + 段数与字数",
                    跑小(头 + $"字符串 表 = \"{表}\";\n"
                        + "测试输出(CSV流.开写(表, \",\"));\n"
                        + "测试输出(CSV流.写字段(\"记录\"));\n"
                        + "测试输出(CSV流.写字段(\"7,5\"));\n"
                        + "测试输出(CSV流.写字段(\"说\"));\n"
                        + "测试输出(CSV流.写条尾());\n"
                        + "测试输出(CSV流.写行(\"尾,\"));\n"
                        + "测试输出(CSV流.关写());\n"
                        + "测试输出(CSV流.开读(表, \",\"));\n"
                        + "整数 条 = 0;\n"
                        + "整数 段 = 0;\n"
                        + "字符串 一 = \"\";\n"
                        + "当 (CSV流.下一条())\n"
                        + "{\n"
                        + "    条 = 条 + 1;\n"
                        + "    段 = 段 + CSV流.字段数();\n"
                        + "    整数 i = 0;\n"
                        + "    当 (i < CSV流.字段数())\n"
                        + "    {\n"
                        + "        CSV流.当前字段(i, 一);\n"
                        + "        测试输出(一.长度());\n"
                        + "        i = i + 1;\n"
                        + "    }\n"
                        + "}\n"
                        + "测试输出(条);\n"
                        + "测试输出(段);\n"
                        + "测试输出(CSV流.关读());\n"
                        + "停止")
                        == "1|1|1|1|1|1|1|1|2|3|1|1|0|2|5|1",
                    "写侧全真;读回两条:第一条 3 段(记录 2 / 7,5 3 / 说 1),第二条 2 段(尾 1 / 空 0);条 2 段 5");

                string 实长跑 = 跑小(头 + $"字符串 大表 = \"{大表}\";\n"
                        + "测试输出(CSV流.开写(大表, \",\"));\n"
                        + "字符串 空 = \"\";\n"
                        + "整数 k = 0;\n"
                        + "当 (k < 2000)\n"
                        + "{\n"
                        + "    逻辑 丢一 = CSV流.写字段(空);\n"
                        + "    逻辑 丢二 = CSV流.写字段(\"7,5\");\n"
                        + "    逻辑 丢三 = CSV流.写条尾();\n"
                        + "    k = k + 1;\n"
                        + "}\n"
                        + "测试输出(CSV流.关写());\n"
                        + "测试输出(CSV流.开读(大表, \",\"));\n"
                        + "整数 条 = 0;\n"
                        + "整数 段 = 0;\n"
                        + "当 (CSV流.下一条())\n"
                        + "{\n"
                        + "    条 = 条 + 1;\n"
                        + "    段 = 段 + CSV流.字段数();\n"
                        + "}\n"
                        + "测试输出(条);\n"
                        + "测试输出(段);\n"
                        + "测试输出(CSV流.关读());\n"
                        + "停止");
                记录("CSV流库 长跑:真盘 2000 行 × 2 段(跨块拼行),条数与段合计逐条对",
                    实长跑 == "1|1|1|2000|4000|1",
                    $"实测 {实长跑} —— 期望 1|1|1|2000|4000|1");

                string 实行 = 跑小(头 + $"字符串 日志 = \"{日志}\";\n"
                        + "测试输出(NDJSON流.开写(日志));\n"
                        + "JSON.清空();\n"
                        + "整数 一 = JSON.新建对象();\n"
                        + "整数 丢一 = JSON.放文本(一, \"级别\", \"信息\");\n"
                        + "整数 丢二 = JSON.放整数(一, \"序\", 1);\n"
                        + "测试输出(NDJSON流.写一条(一));\n"
                        + "JSON.清空();\n"
                        + "整数 二 = JSON.新建对象();\n"
                        + "整数 丢三 = JSON.放整数(二, \"序\", 2);\n"
                        + "测试输出(NDJSON流.写一条(二));\n"
                        + "测试输出(NDJSON流.写文本(\"这不是 JSON\"));\n"
                        + "测试输出(NDJSON流.关写());\n"
                        + "测试输出(NDJSON流.开读(日志));\n"
                        + "整数 条 = 0;\n"
                        + "整数 合 = 0;\n"
                        + "当 (NDJSON流.下一条())\n"
                        + "{\n"
                        + "    条 = 条 + 1;\n"
                        + "    合 = 合 + JSON.取整数(NDJSON流.当前(), \"序\", 0);\n"
                        + "}\n"
                        + "测试输出(条);\n"
                        + "测试输出(合);\n"
                        + "测试输出(NDJSON流.坏几条());\n"
                        + "测试输出(NDJSON流.关读());\n"
                        + "停止");
                记录("NDJSON流库 真盘:两条好记录 + 一条坏行,读回坏行跳过且序号合计对",
                    实行 == "1|1|1|1|1|1|2|3|1|1",
                    $"实测 {实行} —— 期望 1|1|1|1|1|1|2|3|1|1");

                // ---- ⑦ 接线哨兵 ----
                string 值文 = File.ReadAllText(值路径);
                string 表文 = File.ReadAllText(表路径);
                string 行文 = File.ReadAllText(行路径);
                记录("JSON与流派库 接线哨兵:三个库在盘上 + 头注释五段齐 + 模块名 + 公开函数数",
                    File.Exists(值路径) && File.Exists(表路径) && File.Exists(行路径)
                    && 值文.Contains("模块 JSON", StringComparison.Ordinal)
                    && 表文.Contains("模块 CSV流", StringComparison.Ordinal)
                    && 行文.Contains("模块 NDJSON流", StringComparison.Ordinal)
                    && 值文.Contains("用法:", StringComparison.Ordinal) && 值文.Contains("复杂度:", StringComparison.Ordinal)
                    && 值文.Contains("内存账", StringComparison.Ordinal) && 值文.Contains("边界(如实登记", StringComparison.Ordinal)
                    && 表文.Contains("复杂度:", StringComparison.Ordinal) && 表文.Contains("边界(如实登记", StringComparison.Ordinal)
                    && 行文.Contains("复杂度:", StringComparison.Ordinal) && 行文.Contains("边界(如实登记", StringComparison.Ordinal)
                    && 数公开方法(值文) == 30 && 数公开方法(表文) == 11 && 数公开方法(行文) == 10,
                    $"公开方法数 JSON {数公开方法(值文)} / CSV流 {数公开方法(表文)} / NDJSON流 {数公开方法(行文)}(期望 30 / 11 / 10)");
            }
            catch (Exception ex) { 记录异常("JSON与流派库 真盘那一半", ex); }
            finally
            {
                try { if (临时根.Length > 0 && Directory.Exists(临时根)) Directory.Delete(临时根, true); }
                catch { /* 临时区自清失败不判红(与别的组同一口径) */ }
            }

            // 私有:数一个库文件里"公开方法"有几个(带 `私有` 的不算)
            static int 数公开方法(string 文本)
            {
                int 个 = 0;
                foreach (var 行 in 文本.Split('\n'))
                {
                    string 净 = 行.Trim();
                    if (净.StartsWith("方法 ", StringComparison.Ordinal)) 个++;
                }
                return 个;
            }
        }
    }
}
