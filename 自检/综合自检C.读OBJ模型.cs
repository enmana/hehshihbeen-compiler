// ============================================================
// 综合自检C.读OBJ模型.cs —— R4-11:宿主能力 56 `读取模型` 的机械判据
//
//   为什么要单开一组:OBJ 导入这条链上有**三处容易错、错了又不报错**的地方 ——
//     ① 宿主侧解析(顶点数 / 面里的下标 / 边去重);② 归一化(中心与缩放);
//     ③ 参数区偏移(宿主把出口写在输入格上 ⇒ 调用方读到的条数永远是 0,**这套组合实测踩过**)。
//   上面每一条都只能靠"真读一个模型、真看数字"验出来 ⇒ 这一组就是那颗钉子。
//
//   用到的模型:`Sample\模型\球.obj`(12 经 × 6 纬的经纬球,程序生成、非版权素材)。
//   它的顶点数与边数**可以手算**:顶点 = (纬+1) × 经;边 = 经(赤道一圈) + 纬×经(竖边) + …
//   —— 这一组用的是 20 经 × 10 纬那个(220 顶点 / 620 边 / 400 面),数字在下面写成常量并注明来历
//   (⚠ 那三个数是**数出来的**,不是抄的:两极点各复制 20 份 ⇒ 边按"顶点下标对"去重正好 620)。
//   另:主力模型 `球带面.obj`(示例56 读的那一份)**顶点 / 边 / 面三样一起钉**,见下面那一条。
// ============================================================
using System;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        /// <summary> 仓库根(找不到就给 null,那一组如实跳过) </summary>
        private static string? 读OBJ模型用根()
        {
            // ⚠ **只按"程序集自己住在哪"往上找,不看 `Environment.CurrentDirectory`** ——
            // 这一条是踩出来的:第一版两个都试,单独跑这一组全绿,一进**全量自检就五条全红**
            // (指纹是"打不开文件":条数读到 0、状态码 0)。原因是全量自检会换工作目录,
            // 相对路径就算到了别处 ⇒ **自检里找仓库文件必须靠程序集位置**(`AppContext.BaseDirectory`)。
            var 目录 = new DirectoryInfo(AppContext.BaseDirectory);
            for (int i = 0; i < 10 && 目录 != null; i++)
            {
                if (File.Exists(Path.Combine(目录.FullName, "编译器CLI", "Program.cs")))
                    return 目录.FullName;
                目录 = 目录.Parent;
            }
            return null;
        }

        /// <summary>
        /// 编一段 HB 源码、**按与命令行 `--run` 同样的姿势**跑完,收回它的标准输出。
        ///
        /// ⚠ **三样一样都不能少**(这一条是踩出来的:第一版只设了输入输出,于是
        /// `读取模型` 返回假、四种输出全是 0 —— 因为**宿主调用根本没接上**):
        ///   `设内存大小` / `初值表` / **`宿主调用 = 宿主能力C.处理`**。
        /// 姿势照 `综合自检C.C后端宿主能力.cs` 那一份(它是对拍里钉住过的写法)。
        /// </summary>
        private static string 读OBJ模型跑一段(string 源, out string 跑错, int 堆字节 = 0)
        {
            跑错 = "";
            宿主能力C.清运行痕迹();
            try
            {
                // `堆字节 > 0` 就按它给堆(探针要装大一点的模型时用);不给就走默认 64KB
                var 编译结果 = 堆字节 > 0
                    ? new 汇编器C().汇编多文件带调试([("主程序.hb", 源)], 优化: true, 堆大小: 堆字节)
                    : new 汇编器C().汇编多文件带调试([("主程序.hb", 源)], 优化: true);
                var 缓冲 = new StringBuilder();
                var 机 = new 虚拟机C();
                机.设内存大小(虚拟机C.默认内存大小);
                机.初值表 = 编译结果.初值表;
                机.宿主调用 = 宿主能力C.处理;          // ⚠ 少了这一行,能力一律给假
                机.输入源 = () => null;
                机.输出目标 = b => 缓冲.Append((char)b);
                机.装载(编译结果.机器码);
                long 步 = 0;
                while (机.单步() && 步 < 20_000_000) 步++;   // 限步:别让一条坏路径把自检挂住
                return 缓冲.ToString();
            }
            catch (Exception 错)
            {
                跑错 = 错.Message;
                return "";
            }
        }

        private static void 读OBJ模型自检()
        {
            string? 根 = 读OBJ模型用根();
            if (根 == null) { 跳过("读OBJ模型", "找不到仓库根"); return; }

            string 模型 = Path.Combine(根, "Sample", "模型", "球.obj");
            if (!File.Exists(模型)) { 跳过("读OBJ模型", "找不到 Sample\\模型\\球.obj"); return; }

            // 球.obj 是 20 经 × 10 纬生成的:顶点 = 11 圈 × 20 = 220;
            // 边:每圈 20 条环边 × 11 圈 = 220,竖边 20 × 10 = 200,三角化的斜边 20 × 10 = 200 ⇒ 620。
            //   ⚠ **这不是"手抄的数"**(2026-10-12 现场核过,三个数一字不差):
            //     文件里 `v` 行 220 条、`f` 行 400 行;而**边按"顶点下标对"去重**数出来正好 620 ——
            //     关键在于这一份的**两极点各被复制了 20 份**(20 个同位置、不同下标的顶点),
            //     于是极点那一圈三角形**每片都算一条不同的边** ⇒ 比"按位置去重"多出 200 条。
            //     六端两条腿现在都是"顶点 = `v` 行、边 = 面里下标对去重"这**同一份口径**,所以 620 是对的。
            //     (示例56 读的那一份换成 `球带面.obj` 之后就**没有**这个复制了,见下面新钉的那条。)
            const int 应有顶点 = 220;
            const int 应有边 = 620;

            // 路径要按**绝对路径**给:自检的当前目录不一定是仓库根。
            string 路径 = 模型.Replace("\\", "/");
            string 源 =
                "地址 顶点块 = 申请(400 * 12);\n" +
                "地址 边块 = 申请(2000 * 8);\n" +
                "地址 面块 = 申请(900 * 12);\n" +          // R4-14:面块(每条面三个整数)
                "地址 条数块 = 申请(16);\n" +
                $"逻辑 成了 = 读取模型(\"{路径}\", 顶点块, 边块, 面块, 400, 2000, 900, 条数块);\n" +
                "如果 (成了) { 测试输出(1); } 否则 { 测试输出(0); }\n" +
                "测试输出(整数(取字(条数块, 0)));\n" +
                "测试输出(整数(取字(条数块, 4)));\n" +
                "测试输出(整数(取字(条数块, 8)));\n" +   // R4-14:第三格是**面数**
                "测试输出(整数(取字(条数块, 12)));\n" +  // 第四格是状态码
                "释放(顶点块);\n释放(边块);\n释放(面块);\n释放(条数块);\n停止\n";

            string 输出 = 读OBJ模型跑一段(源, out string 跑错);
            if (跑错.Length > 0)
            {
                记录("读OBJ模型 读球.obj:读得进来", false, $"抛异常:{跑错}");
                return;
            }

            string[] 行 = 输出.Replace("\r\n", "\n").Trim().Split('\n');
            string 首 = 行.Length > 0 ? 行[0].Trim() : "";
            string 顶点数 = 行.Length > 1 ? 行[1].Trim() : "";
            string 边数 = 行.Length > 2 ? 行[2].Trim() : "";
            string 面数 = 行.Length > 3 ? 行[3].Trim() : "";       // R4-14
            string 状态 = 行.Length > 4 ? 行[4].Trim() : "";       // R4-14:第四格往后挪了一格

            记录("读OBJ模型 读球.obj:读得进来(返回真 + 状态码 0)", 首 == "1" && 状态 == "0",
                $"返回={首} 状态码={状态}");
            记录($"读OBJ模型 顶点数对(球.obj = {应有顶点})", 顶点数 == 应有顶点.ToString(),
                $"读到 {顶点数},应有 {应有顶点}(20 经 × 10 纬 + 1 圈 = 11 × 20)");
            记录($"读OBJ模型 边数对(球.obj = {应有边},含去重)", 边数 == 应有边.ToString(),
                $"读到 {边数},应有 {应有边}(环边 220 + 竖边 200 + 斜边 200)");
            // R4-14:**面也要读出来**(这是"外部模型能实心"的前提)
            记录("读OBJ模型 面数对(球.obj = 400 —— R4-14 新加的)", 面数 == "400",
                $"读到 {面数},应有 400(20 经 × 10 纬 × 2 个三角)");

            // ⚠ 条数**不能是 0**:这正是"参数区偏移撞车"那一次的指纹
            //   (顶点数据写得对、条数永远是 0)。留一条显式钉子盯着它。
            //   ⚠ R4-14 又踩了一次(加面之后忘了把"条数块"从 24 挪到 32)⇒ 这条钉子留着值。
            记录("读OBJ模型 三个条数都不是 0(参数区输入/出口没撞车)", 顶点数 != "0" && 边数 != "0" && 面数 != "0",
                $"顶点 {顶点数} / 边 {边数} / 面 {面数} —— 三个都不是 0 才算没撞车");

            // ================= 主力模型 `球带面.obj`:三个数一起钉,期望值**现场从盘上数** =================
            //
            //   ⚠ 为什么单钉这一份:上面那三条钉的是 `球.obj`(压力测试那份),而**示例56 读的是
            //     这一份**(`Sample\模型\球带面.obj`,单极点球:20 经 × 8 纬 + 两个极点 = 142 顶点 /
            //     420 边 / 280 面)—— 它是"读模型这条路自己对不对"的**端到端读数**。
            //   ⚠ **不是手抄数字**:顶点与边由 `模型库数OBJ` 现场数出来(素材换一份,判据跟着走),
            //     三条一起比 ⇒ 顶点数对了但边去重 / 面三角化错了,这一条当场红。
            {
                string 主 = Path.Combine(根, "Sample", "模型", "球带面.obj");
                if (!File.Exists(主)) 跳过("读OBJ模型 读球带面.obj:三样一起对(142 顶点 / 420 边 / 280 面)", "找不到 Sample\\模型\\球带面.obj");
                else
                {
                    // 上限取够:142 顶点 / 420 边 / 280 面(给了余量,同时别把默认 64KB 堆撑爆)
                    string 主路径 = 主.Replace("\\", "/");
                    string 主源 =
                        "地址 顶点块 = 申请(500 * 12);\n" +
                        "地址 边块 = 申请(1500 * 8);\n" +
                        "地址 面块 = 申请(1500 * 12);\n" +
                        "地址 条数块 = 申请(16);\n" +
                        $"逻辑 成了 = 读取模型(\"{主路径}\", 顶点块, 边块, 面块, 500, 1500, 1500, 条数块);\n" +
                        "如果 (成了) { 测试输出(1); } 否则 { 测试输出(0); }\n" +
                        "测试输出(整数(取字(条数块, 0)));\n" +
                        "测试输出(整数(取字(条数块, 4)));\n" +
                        "测试输出(整数(取字(条数块, 8)));\n" +
                        "测试输出(整数(取字(条数块, 12)));\n" +
                        "释放(顶点块);\n释放(边块);\n释放(面块);\n释放(条数块);\n停止\n";
                    string 主出 = 读OBJ模型跑一段(主源, out string 主错);
                    var (主顶点, 主边, 主面) = 模型库数OBJ(主);
                    if (主错.Length > 0)
                        记录("读OBJ模型 读球带面.obj:三样一起对(142 顶点 / 420 边 / 280 面)", false, $"抛异常:{主错}");
                    else
                    {
                        string[] 行3 = 主出.Replace("\r\n", "\n").Trim().Split('\n');
                        string 值(int i) => i < 行3.Length ? 行3[i].Trim() : "?";
                        记录($"读OBJ模型 读球带面.obj:三样一起对({主顶点} 顶点 / {主边} 边 / {主面} 面 —— 期望值现场从盘上数出来)",
                            值(0) == "1" && 值(1) == 主顶点.ToString() && 值(2) == 主边.ToString()
                             && 值(3) == 主面.ToString() && 值(4) == "0",
                            $"读到 成={值(0)} 顶点={值(1)} 边={值(2)} 面={值(3)} 状态码={值(4)},盘上现数 " +
                            $"{主顶点}/{主边}/{主面}(单极点球 20 经 × 8 纬 + 两个极点 ⇒ 142 顶点 / 420 边 / 280 面)");
                    }
                }
            }

            // 打不开的那一档:给一条不存在的路径,必须返回假 + 状态码 1(不能静默当成读成功)
            string 坏源 = 源.Replace(路径, "不存在的模型文件.obj");
            string 坏输出 = 读OBJ模型跑一段(坏源, out string 坏错);
            if (坏错.Length > 0)
            {
                记录("读OBJ模型 打不开时返回假 + 状态码 1(不许静默当成功)", false, $"抛异常:{坏错}");
                return;
            }
            string[] 行2 = 坏输出.Replace("\r\n", "\n").Trim().Split('\n');
            // R4-14:状态码从第 4 格挪到第 5 格(面数插进来了)
            bool 过 = 行2.Length > 4 && 行2[0].Trim() == "0" && 行2[4].Trim() == "1";
            记录("读OBJ模型 打不开时返回假 + 状态码 1(不许静默当成功)", 过,
                $"返回={(行2.Length > 0 ? 行2[0].Trim() : "?")} 状态码={(行2.Length > 4 ? 行2[4].Trim() : "?")}");
        }
    }
