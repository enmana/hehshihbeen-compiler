        /// <summary>
        /// 装载时把内存整块清干净:数据段是"零初始化"的,不清的话上次跑剩的值会留到下一次运行
        /// (用户问"有没有内存回收/内存管理" —— 没有堆,内存就是一块固定的 64000 字节,所以谈不上回收,
        ///  但每次装载必须从干净的内存开始,这条就是在钉它)
        /// </summary>
        private static void 内存重置自检()
        {
            byte[] 码 = new 汇编器C().汇编("加载立即数 R1, 77\n存储 R1, 0x2000\n停止");
            var vm = new 虚拟机C();
            vm.运行(码);
            bool 上次留下了数据 = vm.内存[0x2000] == 77;

            vm.装载(码);
            bool 一模一样 = true;
            for (int i = 0; i < vm.内存.Length; i++)
            {
                byte 应有 = i < 码.Length ? 码[i] : (byte)0;
                if (vm.内存[i] != 应有) { 一模一样 = false; break; }
            }
            记录("虚拟机 重新装载:内存=机器码+全 0(不留上次的数据)", 一模一样,
                $"上次留下数据={上次留下了数据} 内存[{0x2000}]=0x{vm.内存[0x2000]:X2}");
        }

