        /// <summary> 从某行起向后找第一条含 R0 期望的注释行并解析 </summary>
        private static uint? 找首个期望(string[] 行表, int 起始)
        {
            for (int j = 起始; j < 行表.Length; j++)
            {
                string t = 行表[j];
                if (t.Contains("预期结果") || t.Contains("expected result") || t.Contains("expected:"))
                {
                    uint? 值 = 解析预期R0(t);
                    if (值 != null) return 值;
                }
            }
            return null;
        }

        private static uint? 解析预期R0(string 注释行)
        {
            int idx = 注释行.IndexOf("R0", StringComparison.Ordinal);
            if (idx < 0) return null;
            int eq = 注释行.IndexOf('=', idx);
            if (eq < 0) return null;
            string 剩余 = 注释行[(eq + 1)..].Trim();
            int end = 0;
            while (end < 剩余.Length && !char.IsWhiteSpace(剩余[end]) && 剩余[end] != ',' && 剩余[end] != '，') end++;
            剩余 = 剩余[..end];
            if (剩余.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
                return uint.TryParse(剩余[2..], System.Globalization.NumberStyles.HexNumber, null, out var h) ? h : null;
            return uint.TryParse(剩余, out var d) ? d : null;
        }

