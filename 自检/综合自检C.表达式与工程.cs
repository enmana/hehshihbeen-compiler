        /// <summary> 收集 "// 预期输出: a|b|c" 里的期望输出行(| 分隔多行) </summary>
        private static List<string> 解析预期输出(string[] 行表)
        {
            var 结果 = new List<string>();
            foreach (string 行 in 行表)
            {
                string t = 行.Trim();
                if (!t.StartsWith("//", StringComparison.Ordinal)) continue;
                int 位置 = t.IndexOf("预期输出", StringComparison.Ordinal);
                if (位置 < 0) continue;
                int 冒号 = t.IndexOf(':', 位置);
                if (冒号 < 0) 冒号 = t.IndexOf('：', 位置);
                if (冒号 < 0) continue;
                string 值 = t[(冒号 + 1)..].Trim();
                if (值.Length == 0) continue;
                // ⚠ 只有**格式就是 `// 预期输出: …`** 的那一行才算(头部注释里"引述格式"的行,比如
                //    ``// 判据:文件末尾那一行 `// 预期输出: …` ``,冒号前有别的内容 ⇒ 跳过)。
                //    **不能按"段里有没有反引号/省略号"来跳** —— 示例37 的期望串里就有反引号、
                //    示例35 的期望串里就有 `…`(那两处实测踩过)。
                if (t[..冒号].Trim() != "// 预期输出") continue;
                foreach (string 段 in 值.Split('|')) 结果.Add(段.Trim());
            }
            return 结果;
        }

        /// <summary>
        /// 逐行比对之后那句人话:条数不一样时**先把第一个不同的行号找出来**再报。
        /// ⚠ H82 批 4 起,带 UI 的标准工程那一行 `// 预期输出:` 里混着"窗口前那一段纯输出"与
        /// "开窗之后逐帧画出来的命令"(几千行)——只报"期望 N 行 / 实得 M 行"看不出差在哪一段,
        /// 而"第 k 行"一眼就能分清是**判据没挂呈现口**(第 k 行正好是 `打开窗口` 那条)还是**画歪了**。
        /// </summary>
        private static string 逐行差说明(string 应有, string 实得)
        {
            var 期望行 = 应有.Split('\n');
            var 实得行 = 实得.Split('\n');
            int 错行 = 0;
            if (期望行.Length == 实得行.Length)
            {
                for (int j = 0; j < 期望行.Length; j++)
                    if (期望行[j] != 实得行[j]) { 错行 = j + 1; break; }
            }
            return $"期望 {期望行.Length} 行 / 实得 {实得行.Length} 行;" +
                (错行 > 0
                    ? $"第 {错行} 行 期望[{截断(期望行[错行 - 1], 60)}] 实得[{截断(实得行[错行 - 1], 60)}]"
                    : "条数先对不上;期望头一行[" + 截断(期望行.Length > 0 ? 期望行[0] : "", 60) + "]");
        }

        /// <summary>
        /// 运行并捕获宿主输出(输出()/输出字符/输出换行 都会写到这里)。
        /// `内存大小` 是通用化第2批(可选内存模型)之后加的:标准工程按**它自己那份 `.hbp` 的 `内存`** 跑
        /// (见 `示例内存大小`),其余地方不传就是默认 1MB —— 与 `堆大小` 同一个口径。
        /// </summary>
        private static (虚拟机C 虚拟机, string 输出) 运行带输出(string 源码, string? 基目录 = null,
            int 堆大小 = 中间层C.默认堆大小, int 内存大小 = 虚拟机C.默认内存大小)
