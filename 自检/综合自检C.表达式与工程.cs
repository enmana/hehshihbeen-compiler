            var vm = new 虚拟机C
            {
                输入源 = () => null,             // 无输入 → IN 读到 EOF
                输出目标 = 解码.写,
                // P28:示例按"IDE 里跑"的口径来 —— 宿主能力(读文件/写文件/当前时间)挂上,
                // 不然 `示例12_输入输出与宿主能力` / `综合_核心与边界` 里的宿主函数一律返回假(它们在纯虚拟机上跑就是这样)
                宿主调用 = 宿主能力C.处理,
            };
            // R1-6 批 1:图形原语走**无头呈现** —— 绘制命令逐条写进同一份输出缓冲。
            // 自检就是那个"无头宿主":`示例14_图形界面` 的 `// 预期输出:` 对的就是这些行(硬规矩 6:不开窗也能验)。
            var 无头 = new StringWriter(缓冲) { NewLine = "\n" };
            图形宿主C.挂上(new 无头呈现C(无头));
            // G3 域 3:标准工程按**它自己那份 .hbp 的 `网址` 表**设网络白名单(与命令行 `-p 工程` 同口径)。
