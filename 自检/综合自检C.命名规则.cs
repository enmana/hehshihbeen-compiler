            //   · **硬判据**只留"不许撞 ISA 助记符 / 内建函数名" —— 那两类一撞就是**当场出错**(名字被顶掉),
            //     与本批 / 前后批的改名无关,判红也治得了;
            //   · **两库之间重名先只报不判**(台账 §8 第 ① 条的原话),但**实测的存量比台账写的多得多**:
            //     台账那处写"两库同名公开方法 12 个"(丙批只量了 `宽整数*` 那一族),本批把 51 个库全量了一遍,
