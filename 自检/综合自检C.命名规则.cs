            //        于是**函数体里的注释**成了射程外 —— 实测那儿躺着 38 处(`R4-13` / `第185批` / `H76` 那一族,
            //        见 `未做任务清单.md` H104 那一批)。现在**整份库文件里每一行 `//` 都扫**,报的是 `库名:行号`;
            //        代码行不扫(`0xD8` / `R0` 那种正当写法都在代码里),**正则一个字没放宽**。
            //        (`A10` / `E3` / `S6` 这种"字母+数字"的代号**仍然故意不进正则** —— `R0` / `D8` / `0xD8`
            //         全是正当的寄存器与位模式,收进来会假红一片;那一族只能靠人读。)
            var 内部编号 = new Regex(
                @"(G\d+ 域)|(H\d+(?!\d))|(\bD[1-9]\b)|(R\d-\d)|(第[一二三四五六七八九十百零两六\d]+批)|(批 ?\d+)",
                RegexOptions.Compiled);
