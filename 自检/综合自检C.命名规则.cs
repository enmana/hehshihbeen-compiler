            var 共用注释 = new List<string>();
            var 跨线注释 = new List<string>();
            foreach ((string 文件名, string 内容) in 库内容)
            {
                string[] 行们 = 内容.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
                var 用 = new Dictionary<string, List<int>>();
                for (int i = 1; i < 行们.Length; i++)
                {
                    string 净 = 行们[i].TrimStart();
                    bool 是声明 = 净.StartsWith("方法 ", StringComparison.Ordinal)
                        || 净.StartsWith("结构 ", StringComparison.Ordinal);
                    if (!是声明) continue;
                    string 上 = 行们[i - 1].Trim();
                    if (!上.StartsWith("//", StringComparison.Ordinal))
                    {
                        跨线注释.Add($"{文件名}:{i + 1}");
                        continue;
                    }
                    if (上[2..].Trim().Length == 0 || 上[2..].Trim().All(字 => 字 is '=' or '-' or '_' or '*' or ' '))
                    {
                        跨线注释.Add($"{文件名}:{i + 1}(上一行是分隔线)");
                        continue;
                    }
                    if (!用.TryGetValue(上, out var 表)) { 表 = []; 用[上] = 表; }
                    表.Add(i + 1);
                }
                foreach (var (注, 表) in 用)
                    if (表.Count >= 2) 共用注释.Add($"{文件名}:{string.Join(",", 表)}");
            }
            记录("命名 同一句作用注释不许贴到两个声明头上(那一列会印同一句话)",
                共用注释.Count == 0,
                共用注释.Count == 0 ? $"{库内容.Count} 个库里一句一用" :
                    $"{共用注释.Count} 组:{string.Join(" / ", 共用注释.Take(12))}");
            记录("命名 每个声明头上都要有自己那行作用注释(隔空行 / 只隔分隔线都算没写)",
                跨线注释.Count == 0,
                跨线注释.Count == 0 ? $"{库内容.Count} 个库的每个 `方法` / `结构` 头上都有自己那行注释" :
                    $"{跨线注释.Count} 处:{string.Join(" / ", 跨线注释.Take(12))}");

