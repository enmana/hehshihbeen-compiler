            //   ① **不许空**:第431批删掉头注释里那张「提供的函数」单子之后,约 150 条声明的作用当场变空串,
            //      用户面上印的是一排 `—`(现在逐条补齐了,这两条判据是防回潮的)。
            //   ② **同一句不许贴到两个声明头上**:同一批瘦身还把"某一句"贴满了整库(`统计.hb` 的 17 个函数
