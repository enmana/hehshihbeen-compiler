            //    判据与裸 `果` 同源(`(?<![\p{L}\p{N}_])X(?![\p{L}\p{N}_])`):`挪动` / `平移` / `粘位` / `粘入`
            //    这些**词内**用法都不算 —— 只有单独成词的那两个才红灯。
            var 裸挪粘 = new Regex(@"(?<![\p{L}\p{N}_])(挪|粘)(?![\p{L}\p{N}_])", RegexOptions.Compiled);
            var 裸挪粘违规 = new List<string>();
            foreach (string 文件 in 全仓源)
            {
                string 文本;
                try { 文本 = File.ReadAllText(文件); } catch { continue; }
                int 处 = 裸挪粘.Matches(文本).Count;
                if (处 > 0) 裸挪粘违规.Add($"{Path.GetFileName(文件)}({处} 处)");
            }
            foreach ((string 名, string 文) in new[]
                     {
                         ("快速上手", 帮助文本C.快速上手()),
                         ("指令速查", 帮助文本C.指令速查()),
                         ("中间层速查", 帮助文本C.中间层速查()),
                     })
            {
                int 处 = 裸挪粘.Matches(文).Count;
                if (处 > 0) 裸挪粘违规.Add($"{名} 正文({处} 处)");
            }
            记录("命名 全仓不许出现裸 `挪` / `粘`(Sample 下全部 .hb + 帮助三份正文;§1 禁令③)",
                裸挪粘违规.Count == 0,
                裸挪粘违规.Count == 0
                    ? $"Sample 下 {全仓源.Count} 份 .hb + 帮助三份正文:一处裸 `挪`/`粘` 都没有" +
                      "(判据按标识符边界:`粘位` / `粘入` / `平移` 不算)"
                    : $"{裸挪粘违规.Count} 处:{string.Join(" ", 裸挪粘违规.Take(8))}" +
                      "(移位那一档写 `移位量` / `粘位`;移动那一档写 `平移` / `移动`)");
        }
    }
