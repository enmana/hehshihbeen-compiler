                    for (int i = 0; i < 65; i++) 造.Append("<tr><td>").Append(i).Append("</td></tr>");
                    造.Append("</table>");
                    比行("网络与网页库 网页 拆表格 上限:65 行给假,并把上一次那一张清空(不截断、不留残值)",
                        跑行(头
                            + "字符串 页 = \"<table><tr><td>先来一张</td></tr></table>\";\n"
                            + "整数 下 = 0;\n"
                            + "测试输出(网页.取表格(页, 0, 下));\n"          // 1
                            + "输出行(网页.表行数());\n"                      // 1
                            + $"字符串 大 = \"{造}\";\n"
