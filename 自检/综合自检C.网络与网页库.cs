    public static partial class 综合自检C
    {
        private static void 网络与网页库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 网络路径 = Path.Combine(库目录, "网络.hb").Replace('\\', '/');
            string 网页路径 = Path.Combine(库目录, "网页.hb").Replace('\\', '/');
            if (!File.Exists(网络路径) || !File.Exists(网页路径))
            {
                跳过("网络与网页库 定位两个库文件", $"找不到 {网络路径} / {网页路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{网络路径}\"\n包含 \"{网页路径}\"\n";

            // 自检自己那一个端口:与几个标准工程用的 45217 / 45317 / 45321 / 45517 错开
            const int 自检口 = 45717;

            网址白名单C? 旧白名单 = 宿主能力C.网址白名单;
            void 设白名单(params string[] 项) =>
                宿主能力C.设网址白名单(网址白名单C.由文本(项));
            设白名单($"127.0.0.1:{自检口}");

            // 跑一段 HB:输出按行收(每行末尾空白去掉、首尾空行去掉)
            static List<string> 跑行(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 中间层C.默认堆大小, null,
                    中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                var 行表 = 缓冲.ToString().Replace("\r", "").Split('\n')
                    .Select(x => x.TrimEnd()).ToList();
                while (行表.Count > 0 && 行表[^1].Length == 0) 行表.RemoveAt(行表.Count - 1);
                while (行表.Count > 0 && 行表[0].Length == 0) 行表.RemoveAt(0);
                if (编译.查运行期报错(vm.内存) is { } 说明) 行表.Add($"⚠{说明}");
                return 行表;
            }

            // 一行一条地比;不齐就报第一处不一样(带行号,好查)
            void 比行(string 名, List<string> 实得, params string[] 期望行)
            {
                bool 好 = 实得.Count == 期望行.Length;
                int 第一坏 = -1;
                if (好)
                {
                    for (int i = 0; i < 期望行.Length; i++)
                        if (实得[i] != 期望行[i]) { 好 = false; 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实得.Count} 行逐行对上"
                    : $"实测 {实得.Count} 行 / 期望 {期望行.Length} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实得[第一坏]}> 期望=<{期望行[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实得)}>");
                记录(名, 好, 说明);
            }

            // 自连自收那几块共用的开头(白名单里已经放了这个端口)
            string 自连 = $"""
                整数 听 = 0;
                网络.开监听("127.0.0.1", {自检口}, 听);
                整数 客 = 0;
                网络.连上("127.0.0.1", {自检口}, 客);
                整数 服 = 0;
                网络.等连接(听, 服);
                """ + "\n";

            try
            {
                // ---- ① 按行说话 ----
                try
                {
                    宿主能力C.清句柄表();
                    比行("网络与网页库 网络 按行说话:三行连发一行一行交出来(行尾 `\\r` 去掉 / 空行给空串)",
                        跑行(头 + 自连
                            + "测试输出(网络.发一行(客, \"左\"));\n"
                            + "测试输出(网络.发一行(客, \"右\"));\n"
                            + "测试输出(网络.发一行(客, \"\"));\n"
                            + "测试输出(网络.发一行(客, \"中\\r\"));\n"
                            + "字符串 行 = \"\";\n"
                            + "测试输出(网络.收一行(服, 行));\n输出行(行);\n"
                            + "测试输出(网络.收一行(服, 行));\n输出行(行);\n"
                            + "测试输出(网络.收一行(服, 行));\n输出行(行.长度());\n"
                            + "测试输出(网络.收一行(服, 行));\n输出行(行);\n"
                            + "停止"),
                        "1", "1", "1", "1",
                        "1", "左",
                        "1", "右",
                        "1", "0",
                        "1", "中");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网络按行说话", ex); }

                // ---- ② 问答 ----
                try
                {
                    宿主能力C.清句柄表();
                    比行("网络与网页库 网络 问答:一来一回(服先把回话放出去,单线程里才不等死)",
                        跑行(头 + 自连
                            + "测试输出(网络.发一行(服, \"在\"));\n"
                            + "字符串 答 = \"\";\n"
                            + "测试输出(网络.问答(客, \"在吗\", 答));\n输出行(答);\n"
                            + "字符串 行 = \"\";\n"
                            + "测试输出(网络.收一行(服, 行));\n输出行(行);\n"
                            + "停止"),
                        "1", "1", "在", "1", "在吗");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网络问答", ex); }

                // ---- ③ 收满(跨块) ----
                try
                {
                    宿主能力C.清句柄表();
