                        "1", "1", "1",
                        "1", "独行",
                        "0", "0",
                        "0",
                        "1", "1", "1",
                        "1", "真的");

                    // 上限:64 行 / 256 格 —— 超了给假,并把**这一次**的结果清空(不截断、不留上一张)
