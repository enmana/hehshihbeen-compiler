                        + "输出行(正文.长度());\n"                             // 5000
                        + "测试输出(网页.取网页(\"http://127.0.0.1:9/\", 正文));\n"    // 0(白名单外)
                        + "测试输出(网页.上次状态());\n"                       // -1
                        + "网页.清掉();\n"
                        + "测试输出(网页.上次状态());\n"                       // 0
                        + "停止");
