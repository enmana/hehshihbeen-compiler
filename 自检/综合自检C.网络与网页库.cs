                    // "放不下"那一档由宿主能力那一组自己钉(不在这儿重复)。
                    比行("网络与网页库 网页 取(真回环):200 进变量并解出标题 / 404 给假但状态码是真的 / 档 1 也取回 5000 字节 / 白名单外连都不连",
                        实得,
                        // ⚠ 第 3 段量的是 `.长度()` —— 它数的是**文字**,不是字节(中文一个字算一个)
                        "1", "200", Encoding.UTF8.GetString(页).Length.ToString(), Encoding.UTF8.GetString(页),
