                        跑行(头
                            + "字符串 页 = \"\";\n"
                            + "拼接到(页, \"<HTML><HEAD><TITLE>批21 &amp; 网络</TITLE>\");\n"
                            + "拼接到(页, \"<style>body{color:red}</style><script>var 左=1;</script></HEAD>\");\n"
                            + "拼接到(页, \"<body><!-- 注释 --><h1>标题一</h1><p>第一段<br>换行</p>\");\n"
