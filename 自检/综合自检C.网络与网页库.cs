                        跑行(头 + 自连
                            + "字符串 大 = \"\";\n"
                            + "整数 k = 0;\n"
                            + "当 (k < 800)\n{\n    拼接到(大, \"中\");\n    k = k + 1;\n}\n"
                            + "测试输出(发送(客, 大));\n"                        // 2400
                            + "字符串 回 = \"\";\n"
                            + "测试输出(网络.收满(服, 2400, 回));\n"            // 1
                            + "测试输出(回 == 大);\n"                            // 1
                            + "测试输出(回.长度());\n"                           // 800
                            + "测试输出(网络.收满(服, 0, 回));\n"                // 1(要 0 个字节立刻成)
                            + "测试输出(回.长度());\n"                           // 0
                            + "网络.关掉(客);\n"
                            + "测试输出(网络.收满(服, 10, 回));\n"              // 0(对端关掉了)
                            + "网络.关掉(服);\n网络.关掉(听);\n"
                            + "停止"),
                        "2400", "1", "1", "800", "1", "0", "0");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网络收满", ex); }

                // ---- ④ 记账与复位 ----
                try
                {
                    宿主能力C.清句柄表();
                    比行("网络与网页库 网络 记账与复位:收到的字节数 / 发出的字节数 / 清掉",
                        跑行(头 + 自连
                            + "测试输出(网络.收到字节数());\n"                   // 0
                            + "测试输出(网络.发出字节数());\n"                   // 0
                            + "测试输出(网络.发一行(客, \"一二三\"));\n"          // 1
                            + "测试输出(网络.收到字节数() == 0);\n"              // 1(还没收)
                            + "测试输出(网络.发出字节数());\n"                   // 10(9 字节 + 换行)
                            + "字符串 行 = \"\";\n"
                            + "测试输出(网络.收一行(服, 行));\n"                 // 1
                            + "测试输出(网络.收到字节数());\n"                   // 10
                            + "测试输出(网络.发一行(客, \"四五六\"));\n"          // 1
                            + "测试输出(网络.收一行(服, 行));\n"                 // 1
                            + "输出行(行);\n"                                    // 四五六
                            + "网络.清掉();\n"
                            + "测试输出(网络.收到字节数());\n"                   // 0
                            + "测试输出(网络.发出字节数());\n"                   // 0
                            + "网络.关掉(客);\n"
                            + "测试输出(网络.收一行(服, 行));\n"                 // 0(对端关掉了)
                            + "网络.关掉(服);\n网络.关掉(听);\n"
                            + "停止"),
                        "0", "0", "1", "1", "10", "1", "10", "1", "1", "四五六", "0", "0", "0");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网络记账", ex); }

                // ---- ⑤ 失败路 ----
                try
                {
                    宿主能力C.清句柄表();
                    比行("网络与网页库 网络 失败路:白名单外的端口连都不连(假 + 句柄 -1)、坏句柄收发与关闭给假",
                        跑行(头
                            + $"整数 听 = 0;\n测试输出(网络.开监听(\"127.0.0.1\", {自检口}, 听));\n"   // 1
                            + "整数 坏 = 7;\n"
                            + "测试输出(网络.连上(\"127.0.0.1\", 9, 坏));\n"     // 0(白名单里没有 127.0.0.1:9)
                            + "测试输出(坏);\n"                                  // -1
                            + "测试输出(网络.发一行(坏, \"左\"));\n"              // 0
                            + "字符串 行 = \"\";\n"
                            + "测试输出(网络.收一行(坏, 行));\n"                 // 0
                            + "测试输出(网络.关掉(坏));\n"                       // 0(句柄不认)
                            + "输出行(网络.地址文本(\"127.0.0.1\", 9));\n"        // 127.0.0.1:9
                            + "测试输出(网络.关掉(听));\n"                       // 1
                            + "停止"),
                        "1", "0", "-1", "0", "0", "0", "127.0.0.1:9", "1");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网络失败路", ex); }

                // ---- ⑥ 网页 地址(纯文本,不动白名单) ----
                try
                {
                    比行("网络与网页库 网页 地址:拆四种写法 / 拼三种 / `是成功` 200~299",
                        跑行(头
                            + "字符串 主机 = \"\";\n整数 口 = 0;\n字符串 路径 = \"\";\n"
                            + "测试输出(网页.拆网址(\"http://127.0.0.1:8080/左?x=1\", 主机, 口, 路径));\n"
                            + "输出行(主机);\n测试输出(口);\n输出行(路径);\n"      // 127.0.0.1 / 8080 / /左?x=1
                            + "测试输出(网页.拆网址(\"https://例子.测试/\", 主机, 口, 路径));\n"
                            + "输出行(主机);\n测试输出(口);\n输出行(路径);\n"      // 例子.测试 / 443 / /
                            + "测试输出(网页.拆网址(\"http://主机\", 主机, 口, 路径));\n"
                            + "输出行(主机);\n测试输出(口);\n输出行(路径);\n"      // 主机 / 80 / /
                            + "测试输出(网页.拆网址(\"//本机:9/左\", 主机, 口, 路径));\n"
                            + "输出行(主机);\n测试输出(口);\n输出行(路径);\n"      // 本机 / 9 / /左
                            + "测试输出(网页.拆网址(\"http://\", 主机, 口, 路径));\n"   // 0(主机空)
                            + "输出行(网页.拼网址(\"127.0.0.1\", 8080, \"/左\"));\n"
                            + "输出行(网页.拼网址(\"例子.测试\", 0, \"\"));\n"
                            + "输出行(网页.拼网址(\"例子.测试\", 80, \"右\"));\n"
                            + "测试输出(网页.是成功(199));\n测试输出(网页.是成功(200));\n"
                            + "测试输出(网页.是成功(299));\n测试输出(网页.是成功(300));\n"
                            + "测试输出(网页.上次状态());\n"                    // 0(还没取过)
                            + "停止"),
                        "1", "127.0.0.1", "8080", "/左?x=1",
                        "1", "例子.测试", "443", "/",
                        "1", "主机", "80", "/",
                        "1", "本机", "9", "/左",
                        "0",
                        "http://127.0.0.1:8080/左",
