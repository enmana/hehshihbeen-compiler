                            + "字符串 短 = \"HTTP/1.1 200 OK\\n\\n左\";\n"
                            + "网页.解应答(短, 码, 头, 正文);\n"
                            + "测试输出(码);\n"                                  // 200
                            + "测试输出(头.长度());\n"                           // 0(没有头)
                            + "输出行(正文);\n"                                  // 左
                            + "字符串 乱 = \"这不是应答\";\n"
                            + "网页.解应答(乱, 码, 头, 正文);\n"
                            + "测试输出(码);\n"                                  // 0(拆不出来)
                            + "停止"),
                        "404",
                        "Content-Type: text/plain", "Content-Length: 5",
                        "4",
                        "200", "0", "左",
                        "0");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网页解应答", ex); }

                // ---- ⑨ 网页 取(真回环;不碰外网) ----
                try
                {
                    byte[] 页 = Encoding.UTF8.GetBytes(
                        "<html><head><title>回环页</title></head><body><h1>你好</h1><p>来自回环</p></body></html>");
                    byte[] 大页 = new byte[5000];
                    Array.Fill(大页, (byte)'x');
                    using var 服务器 = new 回环服务器C(请求 =>
                        请求.Contains("/missing") ? (404, Encoding.UTF8.GetBytes("没有这个"))
                        : 请求.Contains("/big") ? (200, 大页)
                        : (200, 页));
                    设白名单($"127.0.0.1:{服务器.端口}");
                    宿主能力C.清句柄表();

                    var 实得 = 跑行(头
                        + "字符串 正文 = \"\";\n"
                        + $"测试输出(网页.取网页(\"http://127.0.0.1:{服务器.端口}/ok\", 正文));\n"
                        + "测试输出(网页.上次状态());\n"
                        + "输出行(正文.长度());\n"
                        + "输出行(正文);\n"
                        + "字符串 标题 = \"\";\n"
                        + "测试输出(网页.取标题(正文, 标题));\n输出行(标题);\n"
                        + $"测试输出(网页.取网页(\"http://127.0.0.1:{服务器.端口}/missing\", 正文));\n"
                        + "测试输出(网页.上次状态());\n"
                        + "测试输出(正文.长度());\n"                          // 0(失败那一格是空的)
                        + "测试输出(网页.是成功(网页.上次状态()));\n"          // 0
