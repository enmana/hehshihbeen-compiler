                finally { 设白名单($"127.0.0.1:{自检口}"); }

                // ---- ⑩ 端到端:标准工程 示例54_网络与网页 ----
                //   走**共用那一份 `运行带输出`**:它自己认工程目录里的 `.hbp` 设网址白名单 ⇒
                //   与 `hbcc -p 工程.hbp --run` 同一条口径。
                try
                {
                    string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例54_网络与网页");
                    string? 源码路径 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                    if (源码路径 == null || !File.Exists(源码路径))
                    {
                        跳过("网络与网页库 标准工程 示例54 逐段对预期输出", $"找不到 {源码路径}(不在工作副本里跑就跳过)");
                    }
                    else
                    {
                        宿主能力C.清句柄表();
                        var 行表 = File.ReadAllLines(源码路径);
                        var 期望段 = 解析预期输出(行表);
                        var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录);
                        var 实得段 = 输出.Trim().Split('\n')
                            .Select(x => x.TrimEnd('\r').Trim()).Where(x => x.Length > 0).ToList();
                        bool 好 = 期望段.Count > 0 && 实得段.Count == 期望段.Count
                            && 实得段.Zip(期望段, (a, b) => a == b).All(x => x);
                        记录("网络与网页库 标准工程 示例54 逐段对预期输出(自连自收 / 行协议 / 收满 / 拆 HTML / 拆表格 / 拆应答 / 取网页失败路 / 带 UI 的那一帧绘制命令流)",
                            好, 好 ? $"逐段一致({期望段.Count} 段)"
                                  : $"期望 {期望段.Count} 段 / 实得 {实得段.Count} 段" +
                                    (期望段.Count > 0 && 实得段.Count > 0
                                        ? $";第 1 段 期望[{期望段[0]}] 实得[{实得段[0]}]" : ""));

                        // ⭐ 第421批:**同一行期望段,再在跨进程那条腿上对一遍** ——
                        //   那条腿才是 IDE 按 F5 走的路:`同步宿主白名单` 先把两张白名单交给宿主能力层,
                        //   `装载` 时(`跨进程虚拟机C` 那两句)再从那一份静态表里取走、带给子进程。
                        //   上面那条(进程内)过了**不等于**过线之后还对:白名单在线上少一格,
                        //   子进程就整族给状态 1(没挂能力),而示例把它折成一个 `0` ——
                        //   用户 2026-10-11 当班报的"示例54 在 IDE 里网络整族给 0"正是这个样子。
                        //   这一条把那条腿钉住:**不必再靠人按一次 F5** 才知道白名单有没有过线。
                        string? 脚本路径 = 事件脚本C.找脚本(工程目录);
                        var 跨缓冲 = new StringWriter { NewLine = "\n" };
                        var (跨输出, _, _) = 跑标准工程(工程文件C.找工程文件(工程目录)!,
                            跨进程: true, 呈现口: new 无头呈现C(跨缓冲),
                            事件脚本文本: 脚本路径 == null ? null : File.ReadAllText(脚本路径));
                        // ⚠ 跨进程那条腿上,**绘制命令不与程序输出同一条流**:程序输出回前端(`跨输出`),
                        //   绘制命令由呈现口收(`跨缓冲`)—— 所以按"这两份里各有哪些行"分开对,
                        //   而不是硬把两边合成一条。这一条正是"两条流各自都对、合起来就是那一行期望段"。
                        var 跨程序段 = 跨输出.Trim().Split('\n')
                            .Select(x => x.TrimEnd('\r').Trim()).Where(x => x.Length > 0).ToList();
                        var 跨口行 = 跨缓冲.ToString().Trim().Split('\n')
                            .Select(x => x.TrimEnd('\r').Trim()).Where(x => x.Length > 0).ToList();
                        var 跨口集 = new HashSet<string>(跨口行, StringComparer.Ordinal);
                        var 期望程序段 = 期望段.Where(x => !跨口集.Contains(x)).ToList();
                        bool 跨好 = 跨程序段.Count == 期望程序段.Count
                            && 跨程序段.Zip(期望程序段, (a, b) => a == b).All(x => x)
                            && 跨口行.Count + 跨程序段.Count == 期望段.Count;
                        记录("网络与网页库 标准工程 示例54 在**跨进程那条腿**(IDE 按 F5 走的路)上也逐段对得上" +
                            "(两张白名单过线 + 子进程照它办事 + 那一帧绘制命令流)",
                            跨好, 跨好 ? $"逐段一致(程序输出 {跨程序段.Count} 段 + 绘制命令 {跨口行.Count} 段 = {期望段.Count} 段)"
                                       : $"程序输出 {跨程序段.Count} / 期望 {期望程序段.Count};" +
                                         $"绘制命令 {跨口行.Count};合起来 {跨口行.Count + 跨程序段.Count} / 期望 {期望段.Count}。" +
                                         逐行差说明(string.Join("\n", 期望程序段), string.Join("\n", 跨程序段)));
                    }
                }
                catch (Exception ex) { 记录异常("网络与网页库 标准工程 示例54", ex); }

                // ---- ⑪ 接线哨兵 ----
                try
                {
                    var 期望模块 = new (string 路径, string 模块, int 公开)[]
                    {
                        (网络路径, "模块 网络", 13),
                        (网页路径, "模块 网页", 17),
                    };
                    var 问题 = new List<string>();
                    foreach (var (路径, 模块, 期望数) in 期望模块)
                    {
                        string 文 = File.ReadAllText(路径);
                        int 公开数 = 0;
                        foreach (var 行 in 文.Split('\n'))
                            if (行.TrimStart().StartsWith("方法 ", StringComparison.Ordinal)) 公开数++;
                        string 名 = Path.GetFileName(路径);
                        if (!文.Contains(模块, StringComparison.Ordinal)) 问题.Add($"{名}:没有 `{模块}`");
                        if (!文.Contains("用法", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `用法`");
                        if (!文.Contains("复杂度:", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `复杂度:`");
                        if (!文.Contains("内存账", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `内存账`");
                        if (!文.Contains("英文对照", StringComparison.Ordinal)) 问题.Add($"{名}:没有 `英文对照`");
                        if (公开数 != 期望数) 问题.Add($"{名}:公开函数 {公开数},期望 {期望数}");
                    }
                    记录("网络与网页库 接线哨兵:两个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(13 / 17)",
                        问题.Count == 0,
                        问题.Count == 0 ? "两个库五段齐、公开函数数对上" : string.Join(" / ", 问题));
                }
                catch (Exception ex) { 记录异常("网络与网页库 接线哨兵", ex); }
            }
            finally
            {
                宿主能力C.设网址白名单(旧白名单);
                宿主能力C.清句柄表();
            }
        }
    }
