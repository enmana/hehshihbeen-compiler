                            + "测试输出(网页.取表格(大, 0, 下二));\n"        // 0(65 行超上限)
                            + "输出行(网页.表行数());\n"                      // 0(清空)
                            + "停止"),
                        "1", "1",
                        "0", "0");
                }
                catch (Exception ex) { 记录异常("网络与网页库 网页拆表格", ex); }

                // ---- ⑧ 网页 解应答 ----
                try
                {
                    比行("网络与网页库 网页 解应答:`\\r\\n\\r\\n` 与 `\\n\\n` 两种空行、三段各归各位",
                        跑行(头
                            + "字符串 答 = \"\";\n"
                            + "拼接到(答, \"HTTP/1.1 404 Not Found\\r\\nContent-Type: text/plain\\r\\nContent-Length: 5\\r\\n\\r\\n没有这个\");\n"
                            + "整数 码 = 0;\n字符串 头 = \"\";\n字符串 正文 = \"\";\n"
                            + "网页.解应答(答, 码, 头, 正文);\n"
                            + "测试输出(码);\n"                                  // 404
                            + "输出行(头);\n"                                    // 两行头(里面带 \r\n ⇒ 两段)
