//     ⑦ **网页 拆 HTML**:`取标题` / `去标签`(样式脚本注释整段跳过、块级标签变换行)/
//        `取链接`(游标一条条走)/ `取属性`(`data-href` 里的 `href` 不算)/
//        **`取表格`(第420批:列头与数据格一样算、内层标签跳过、实体解开、越界、上限)**;
//     ⑧ **网页 解应答**:`\r\n\r\n` 与 `\n\n` 两种空行,状态码 / 头 / 正文三段;
//     ⑨ **网页 取**(真回环):对着一台**本机回环**小服务器取 200 / 404 / 白名单外 / 上限档 ——
//        正文进变量、状态码进 `上次状态()`(不碰外网);
//     ⑩ **端到端**:标准工程 **`示例54_网络与网页`** 真编真跑,与它那行 `// 预期输出:` 逐段对;
//     ⑪ **接线哨兵**:两个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(13 / 17)。
//
//   ⚠ 这一组**不引 `string.hb`**:要比就一行一个值;白名单按每一块自己那份设、跑完恢复,
