                catch (Exception ex) { 记录异常("网络与网页库 网页拆HTML", ex); }

                // ---- ⑦之二 网页 拆表格(第420批新加的 `取表格` 那一族) ----
                //   与 `Markdown.hb` 的表那一档**同一个问法**(表行数 / 行格数 / 格文本),换的是数据来源:
                //   那一边从 Markdown 的块里问,这一边从 HTML 的 `<table>` 里抠。
