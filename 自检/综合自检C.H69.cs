    /// (`挂上(null)` / `清空()`)会把另一个正开着的窗口摘掉,于是 C# 侧走"开不了窗"那一支、
    /// C 侧(另一个进程,状态互不干扰)照样开窗 ⇒ 寄存器 / 执行条数 / 内存整块分岔。
    ///
    /// **真抓到过**:`工具\临时\h69\selftest8.txt` —— 修之前连着跑 8 遍,**第 3 遍红**
    /// (示例15 C# 9442525 条 / 原生 7334 条、示例16 C# 9633 条 / 原生 44904 条,
    /// 两边输出 0 / 63 与 40 / 94 字节),别的 7 遍全绿;两次红的形状一模一样
    /// (示例16:R0 虚拟机 1 / 原生 0,R3 虚拟机 0x7851 / 原生 0x37FF3)。
    ///
    /// 这一组三条断言钉的是**三条不同的事**(互相不重复):
    ///   ① **判据还在**:图形标准工程被认出来了(名单非空、且那几个工程一个不落)——
    ///      判据坏了这条护栏就形同虚设(认不出来 ⇒ 又是并行跑);
    ///   ② **不会误伤**:非图形工程一个都没被认成图形(否则白串,那三个大的浮点 / 文本示例一慢就是几十秒);
    ///   ③ **接线在**:那条并行循环里真的有"图形工程进门 / 出门"这两句(接线哨兵 —— 按源码钉,
    ///      行为面由"修完之后连着跑 5 遍全绿"那条收口记录兜着,自检这儿不真跑并发)。
    /// </summary>
    public static partial class 综合自检C
    {
        private static void H69并发护栏自检()
        {
            // ── ① 名单:图形标准工程认得出来,且该是那几个(都在 `Sample\中间层`)──
            //   R4-10/R4-11 追加两个:`示例55_三维素体`(参数化 3D 素体)与 `示例56_读OBJ模型`(读 `.obj` 画线框)
            //   —— 它们源码里都写了 `打开窗口`,判据(看源码里写没写)本来就该把它们认进来。
            //   R4-14 追加一个:`示例58_真人头`(取件减面之后读进来的全身像)—— 同一条判据。
            //
            //   ⚠ **2026-10-12(第421批)整份名单跟进**:`H82 示例改造成带 UI` 那一线连着把
            //   `示例01`~`示例41` 那一族 + `示例54_网络与网页`(本批)+ `示例62_位图` + `预览_全身像`
            //   转成带 UI ⇒ 它们源码里**真写了 `打开窗口`**,判据本来就该把它们认进来。
            //   **名单 = 实测那一份**(用 `工具\临时` 里那趟自检的读数逐字对过),不是"照记忆补几个"。
            //   ⚠ 两条断言的名字**故意不再列示例号** —— 名字里列一遍、判断里列一遍,等于给了两份会打架的
            //   事实(本批就是这么发现它过期了两回的)。
            const string 名单断言 = "H69 图形标准工程认得出来(源码里写了 `打开窗口` 的那些一个不落)";
            try
            {
                var 工程们 = 找全部工程文件().ToList();
                if (工程们.Count == 0)
                {
                    跳过(名单断言, "找不到 Sample 目录(不在工作副本里跑)");
                    跳过("H69 非图形工程一个都没被误认", "找不到 Sample 目录");
                    跳过("H69 并发护栏 接线:并行循环里图形工程进门 / 出门成对", "找不到 Sample 目录");
                    return;
                }
                string[] 认出来的 = 工程们.Where(用图形标准工程).ToArray();
                string[] 名单 = 认出来的.Select(Path.GetFileNameWithoutExtension).OrderBy(x => x, StringComparer.Ordinal).ToArray();
                string[] 该是 =
                [
                    "示例01_类型与字面量", "示例02_表达式与运算", "示例03_流程控制", "示例04_函数与递归",
                    "示例05_结构与引用", "示例06_数组与列表", "示例07_字符串", "示例08_模块与库",
                    "示例09_堆与数据结构", "示例13_哈希表", "示例14_图形界面", "示例15_事件循环",
                    "示例16_控件库", "示例17_排序查找", "示例20_多维数组", "示例21_枚举",
                    "示例22_元组", "示例23_元组多值返回", "示例35_宽度与数字", "示例37_表达式",
                    "示例38_数组与统计", "示例39_栈与队列", "示例40_位集合与矩阵", "示例41_链表与树",
                    "示例48_JSON与窗口", "示例49_Markdown", "示例53_日志与事件", "示例54_网络与网页",
                    "示例55_三维素体", "示例56_读OBJ模型", "示例58_真人头", "示例61_斩神动作",
                    "示例62_位图", "示例63_新指令演示", "预览_全身像",
                ];
                记录(名单断言,
                    名单.SequenceEqual(该是, StringComparer.Ordinal),
                    $"{工程们.Count} 个标准工程里认出 {名单.Length} 个图形工程:" + string.Join("/", 名单) +
                    $"(该是 {string.Join("/", 该是)});判据 = 源码里写没写 `打开窗口`" +
                    " —— 判据坏了这条并发护栏就形同虚设");

                // ── ② 不误伤:认出来的必须**正好**是名单那一份(多一个就是白串一个工程)──
                const string 不误伤断言 = "H69 非图形工程一个都没被误认(认出来的正好是名单那一份)";
                string[] 多认 = 名单.Except(该是, StringComparer.Ordinal).ToArray();
                string[] 漏认 = 该是.Except(名单, StringComparer.Ordinal).ToArray();
                记录(不误伤断言, 多认.Length == 0 && 漏认.Length == 0,
                    $"多认 {多认.Length} 个" + (多认.Length > 0 ? "(" + string.Join("/", 多认) + ")" : "") +
                    $";漏认 {漏认.Length} 个" + (漏认.Length > 0 ? "(" + string.Join("/", 漏认) + ")" : "") +
                    $";共量了 {工程们.Count} 个标准工程");
            }
            catch (Exception ex)
            {
                记录异常(名单断言, ex);
                记录异常("H69 非图形工程一个都没被误认", ex);
            }

            // ── ③ 接线哨兵:并行循环里那两句(进门 / 出门)成对,而且判据就是 `用图形标准工程` ──
            // R3-6-5 批 2:给图形工程挂无头呈现的那一段现在有**两处**(解释器核那一组 + 转译产物那一组)
            // ⇒ 两处都要有这一对语句(否则有一组又会并行撞那几格进程级静态状态)。
            const string 接线断言 = "H69 并发护栏 接线:并行循环里图形工程进门 / 出门成对";
            try
            {
                string? 根 = 找仓库根目录();
                if (根 == null) { 跳过接线(接线断言, "找不到仓库根(读不到那两份自检源码)"); return; }
                var 要看的 = new[]
                {
                    System.IO.Path.Combine(根, "自检", "综合自检C.C后端解释器核.cs"),
                    System.IO.Path.Combine(根, "自检", "综合自检C.C后端全量对拍.cs"),
                };
                bool 进门 = true, 出门 = true, 判据 = true, 那把门 = false;
                var 缺 = new List<string>();
                foreach (string 一份 in 要看的)
                {
                    string 源 = File.ReadAllText(一份, Encoding.UTF8);
                    bool 这一份进门 = 源.Contains("if (图形工程) Monitor.Enter(图形对拍门);", StringComparison.Ordinal);
                    bool 这一份出门 = 源.Contains("if (图形工程) Monitor.Exit(图形对拍门);", StringComparison.Ordinal);
                    bool 这一份判据 = 源.Contains("bool 图形工程 = 用图形标准工程(路径);", StringComparison.Ordinal);
                    进门 &= 这一份进门; 出门 &= 这一份出门; 判据 &= 这一份判据;
                    if (!(这一份进门 && 这一份出门 && 这一份判据)) 缺.Add(Path.GetFileName(一份));
                    那把门 |= 源.Contains("private static readonly object 图形对拍门 = new();", StringComparison.Ordinal);
                }
                记接线(接线断言, 进门 && 出门 && 判据 && 那把门,
                    $"进门 = {进门};出门 = {出门};判据 = {判据};那把门 = {那把门}" +
                    (缺.Count > 0 ? $";缺这几份: {string.Join("/", 缺)}" : ";两处并行循环(解释器核 / 转译产物)都串上了") +
                    " —— 接线哨兵(读仓库源码文本判的),行为面看那条 8 遍复现率记录(修前 1/8 红、修后 5 遍全绿)");
            }
            catch (Exception ex) { 记录异常(接线断言, ex); }
        }
    }
