// ============================================================
// 大数库的自检(G4 批 11,第356批)
//   —— `Sample\库\大数.hb`(任意精度整数)
//
//   判据照 `基础库施工计划.md` §2 批 11 那一行:"加 / 减 / 乘 / 除余 / 比较"。
//   **对拍的那一方是 C# 的 `System.Numerics.BigInteger`** —— 语言的参考实现就在手边,
//   而且它就是"任意精度整数"这件事的标准答案(比手写一份参考实现更可信)。
//   这一组六块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **随机造数逐条对拍**:加 / 减 / 乘 / 除余 / 谁大 / 取负,每一个都拿 `BigInteger` 现算期望
//        (五位十进制到三十位十进制都造;负数也造);
//     ② **文字 ↔ 大数往返**:`从文字` 装进来、`转字符串` 送回去 —— 与 `BigInteger.Parse/ToString` 逐字对;
//        不合法文本(空串 / 只有符号 / 夹字母 / 夹空格)一律给 `假` 且置零;
//     ③ **规范形**:零只有一种写法(`用 = 0` 且 `负 = 0`);算完的高位零 limb 一定被去掉;
//     ④ **边界**:目标表太小给 `假` 且置零;除数为零给 `假`;`除余` 的余数留在被除数里;
//     ⑤ **端到端**:标准工程 **`示例43_大数`** 真编真跑,与它那行 `// 预期输出:` 逐行对;
//     ⑥ **接线哨兵**:库在盘上 + 头注释五段齐 + 公开方法个数对上(12)。
//
//   ⚠ 这一组**不引 `测试助手.hb`**:库与库之间互相引会把"谁坏了"搅浑(自检要能一眼定位)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Numerics;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 大数库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 数路径 = Path.Combine(库目录, "大数.hb").Replace('\\', '/');
            if (!File.Exists(数路径))
            {
                跳过("大数库 定位库文件", $"找不到 {数路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{数路径}\"\n";

            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // 一套"装进来 / 送出去"的 HB 夹具:一份大数用一个下标区分,数组一律放顶层(帧只有 96 字节)
            const int 份 = 4;
            const int 格数 = 24;
            var 夹具头 = new StringBuilder(头);
            for (int k = 0; k < 份; k++)
                夹具头.Append($"整数 数{k}[{格数}];\n整数 数{k}用 = 0;\n整数 数{k}负 = 0;\n");

            // ============================================================
            // ① 随机造数:加 / 减 / 乘 / 除余 / 谁大 / 取负 与 BigInteger 逐条对拍
            // ============================================================
            try
            {
                var 随机 = new Random(20261018);
                var 源 = new StringBuilder(夹具头.ToString());
                var 期望 = new StringBuilder();
                // 造 12 组数:每组的"十进制文字"由 C# 现造(位数从 5 到 30)
                var 表a = new List<string>();
                var 表b = new List<string>();
                for (int i = 0; i < 12; i++)
                {
                    int 位数a = 5 + 随机.Next(0, 26), 位数b = 1 + 随机.Next(0, 20);
                    表a.Add(造十进制(随机, 位数a, 随机.Next(0, 2) == 1));
                    表b.Add(造十进制(随机, 位数b, 随机.Next(0, 2) == 1));
                }
                for (int i = 0; i < 12; i++)
                {
                    var A = BigInteger.Parse(表a[i]);
                    var B = BigInteger.Parse(表b[i]);
                    源.Append($"输出行(大数.从文字(数0, 数0用, 数0负, \"{表a[i]}\"));\n");
                    期望.Append(表a[i] == "" ? '0' : '1').Append('|');
                    源.Append($"输出行(大数.从文字(数1, 数1用, 数1负, \"{表b[i]}\"));\n");
                    期望.Append('1').Append('|');
                    // 谁大
                    源.Append("输出行(大数.谁大(数0, 数0用, 数0负, 数1, 数1用, 数1负));\n");
                    期望.Append(A.CompareTo(B)).Append('|');
                    // 加
                    源.Append("输出行(大数.加(数2, 数2用, 数2负, 数0, 数0用, 数0负, 数1, 数1用, 数1负));\n");
                    源.Append("输出行(大数.转字符串(数2, 数2用, 数2负));\n");
                    期望.Append('1').Append('|').Append((A + B).ToString()).Append('|');
                    // 减
                    源.Append("输出行(大数.减(数2, 数2用, 数2负, 数0, 数0用, 数0负, 数1, 数1用, 数1负));\n");
                    源.Append("输出行(大数.转字符串(数2, 数2用, 数2负));\n");
                    期望.Append('1').Append('|').Append((A - B).ToString()).Append('|');
                    // 乘
                    源.Append("输出行(大数.乘(数3, 数3用, 数3负, 数0, 数0用, 数0负, 数1, 数1用, 数1负));\n");
                    源.Append("输出行(大数.转字符串(数3, 数3用, 数3负));\n");
                    期望.Append('1').Append('|').Append((A * B).ToString()).Append('|');
                    // 取负
                    源.Append("大数.取负(数2, 数2用, 数2负);\n");
                    源.Append("输出行(大数.转字符串(数2, 数2用, 数2负));\n");
                    期望.Append((-(A - B)).ToString()).Append('|');
                    // 除余(除数非零时;商写商表,余数留在被除数里)
                    if (B != 0)
                    {
                        源.Append("输出行(大数.除余(数0, 数0用, 数0负, 数1, 数1用, 数1负, 数2, 数2用, 数2负));\n");
                        源.Append("输出行(大数.转字符串(数2, 数2用, 数2负));\n");
                        源.Append("输出行(大数.转字符串(数0, 数0用, 数0负));\n");
                        var Q = BigInteger.DivRem(A, B, out var R);
                        期望.Append('1').Append('|').Append(Q.ToString()).Append('|').Append(R.ToString()).Append('|');
                    }
                    else
                    {
                        源.Append("输出行(大数.除余(数0, 数0用, 数0负, 数1, 数1用, 数1负, 数2, 数2用, 数2负));\n");
                        期望.Append('0').Append('|');
                    }
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("大数库 加 / 减 / 乘 / 除余 / 谁大 / 取负(12 组随机数,5~30 位十进制、含负数,与 C# 的 `BigInteger` 逐条对拍)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("大数库 随机对拍", ex); }

            // ============================================================
            // ② 文字 ↔ 大数往返 + 不合法文本
            // ============================================================
            try
            {
                var 随机 = new Random(20261019);
                var 源 = new StringBuilder(夹具头.ToString());
                var 期望 = new StringBuilder();
                var 样们 = new List<string> { "0", "-0", "1", "-1", "65535", "65536", "-65536", "4294967295", "4294967296" };
                for (int i = 0; i < 8; i++) 样们.Add(造十进制(随机, 1 + 随机.Next(0, 28), 随机.Next(0, 2) == 1));
                foreach (string 样 in 样们)
                {
                    源.Append($"输出行(大数.从文字(数0, 数0用, 数0负, \"{样}\"));\n");
                    源.Append("输出行(大数.转字符串(数0, 数0用, 数0负));\n");
                    源.Append("输出行(数0用);\n");
                    源.Append("输出行(数0负);\n");
                    var 值 = BigInteger.Parse(样);
                    期望.Append('1').Append('|').Append(值.ToString()).Append('|');
                    // 用:规范形下 = 有效 limb 个数 = ceil(|值| 的位数 / 16);零给 0
                    int 位 = (int)BigInteger.Abs(值).GetBitLength();
                    期望.Append(值.IsZero ? 0 : (位 + 15) / 16).Append('|');
                    期望.Append(值.Sign < 0 ? 1 : 0).Append('|');
                }
                // 不合法文本:一律给假 + 置零
                foreach (string 坏 in new[] { "", "-", "+", "12a3", " 12", "1 2", "12.", "--5", "0x10" })
                {
                    源.Append($"输出行(大数.从文字(数0, 数0用, 数0负, \"{坏}\"));\n");
                    源.Append("输出行(大数.转字符串(数0, 数0用, 数0负));\n");
                    期望.Append('0').Append('|').Append('0').Append('|');
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("大数库 文字 ↔ 大数往返(含 0 / -0 / 2⁶⁴ 附近)+ 不合法文本一律给假且置零(空串 / 只有符号 / 夹字母 / 夹空格 / 0x 写法)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("大数库 文字往返", ex); }

            // ============================================================
            // ③ 规范形 + 边界(表太小 / 除数为零 / 余数留在被除数里)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(夹具头.ToString());
                源.Append(
                    // 规范形:零只有一种写法
                    "大数.从整数(数0, 数0用, 数0负, 0);\n" +
                    "输出行(数0用);\n" +                       // 1:0
                    "输出行(数0负);\n" +                       // 2:0
                    "大数.从整数(数0, 数0用, 数0负, 0 - 7);\n" +
                    "大数.取负(数0, 数0用, 数0负);\n" +
                    "输出行(数0用);\n" +                       // 3:1
                    "输出行(数0负);\n" +                       // 4:0
                    // 高位零 limb 要去掉:65536 × 65536 = 4294967296 用 2 格;再减自己 ⇒ 回零
                    "大数.从文字(数0, 数0用, 数0负, \"4294967296\");\n" +
                    "输出行(数0用);\n" +                       // 5:2
                    "大数.从文字(数1, 数1用, 数1负, \"4294967296\");\n" +
                    "输出行(大数.减(数2, 数2用, 数2负, 数0, 数0用, 数0负, 数1, 数1用, 数1负));\n" +   // 6:1
                    "输出行(数2用);\n" +                       // 7:0
                    "输出行(数2负);\n" +                       // 8:0
                    "输出行(大数.是零(数2用));\n" +            // 9:1
                    // 除余:余数留在被除数里(100 ÷ 7)
                    "大数.从文字(数0, 数0用, 数0负, \"100\");\n" +
                    "大数.从整数(数1, 数1用, 数1负, 7);\n" +
                    "输出行(大数.除余(数0, 数0用, 数0负, 数1, 数1用, 数1负, 数3, 数3用, 数3负));\n" +   // 10:1
                    "输出行(大数.转字符串(数3, 数3用, 数3负));\n" +   // 11:14
                    "输出行(大数.转字符串(数0, 数0用, 数0负));\n" +   // 12:2(余数留在被除数里)
                    // 除数为零
                    "大数.从整数(数1, 数1用, 数1负, 0);\n" +
                    "输出行(大数.除余(数0, 数0用, 数0负, 数1, 数1用, 数1负, 数3, 数3用, 数3负));\n" +   // 13:0
                    "输出行(大数.转字符串(数0, 数0用, 数0负));\n" +   // 14:2(什么都没动)
                    // 目标表太小:乘要 2 + 20 = 22 格,而 数2 只有 24 格 —— 换一对更大的
                    "大数.从文字(数0, 数0用, 数0负, \"340282366920938463463374607431768211456\");\n" +   // 2¹²⁸,要 9 格
                    "输出行(数0用);\n" +                       // 15:9
                    "大数.从文字(数1, 数1用, 数1负, \"340282366920938463463374607431768211456\");\n" +
                    "输出行(大数.乘(数0, 数0用, 数0负, 数0, 数0用, 数0负, 数1, 数1用, 数1负));\n" +   // 16:1(2¹²⁸ × 2¹²⁸ = 2²⁵⁶,17 格,24 格放得下)
                    "输出行(数0用);\n" +                       // 17:17
                    "停止\n");
                string 期 = "0|0|1|0|3|1|0|0|1|1|14|2|0|2|9|1|17";
                string 实 = 跑(源.ToString());
                记录("大数库 规范形与边界:零只有一种写法 / 高位零 limb 去掉 / 除余的余数留在被除数里 / 除数为零给假且不动",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("大数库 规范形与边界", ex); }

            // ============================================================
            // ④ 目标表太小 ⇒ 假 + 置零
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 小[2];\n整数 小用 = 0;\n整数 小负 = 0;\n" +
                    "整数 大[8];\n整数 大用 = 0;\n整数 大负 = 0;\n" +
                    "大数.从文字(大, 大用, 大负, \"123456789012345678901234567890\");\n" +
                    "输出行(大用);\n" +                                  // 1:8
                    "输出行(大数.拷到(小, 小用, 小负, 大, 大用, 大负));\n" +   // 2:0(小装不下)
                    "输出行(小用);\n" +                                  // 3:0(置零)
                    "输出行(小负);\n" +                                  // 4:0
                    "输出行(大数.加(小, 小用, 小负, 大, 大用, 大负, 大, 大用, 大负));\n" +   // 5:0
                    "输出行(小用);\n" +                                  // 6:0
                    "停止\n");
                string 期 = "7|0|0|0|0|0", 实 = 跑(源.ToString());
                记录("大数库 目标表太小:拷到 / 加 都给假,并把目标置成零(不静默截断)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("大数库 目标表太小", ex); }

            // ============================================================
            // ⑤ 端到端:标准工程 示例43_大数
            // ============================================================
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例43_大数");
                string? 源码 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码 == null || !File.Exists(源码))
                {
                    跳过("大数库 标准工程 示例43 逐行对预期输出", $"找不到 {源码}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码);
                    var 期望行 = 解析预期输出(行表);
                    var 装载 = new List<(string, string)> { (源码, string.Join("\n", 行表)) };
                    var 编译 = new 汇编器C().汇编多文件带调试(
                        装载, true, 中间层C.默认堆大小, null, 中间层C.默认池大小,
                        虚拟机C.默认内存大小, 32 * 1024);
                    var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                    vm.设内存大小(虚拟机C.默认内存大小);
                    var 缓冲 = new StringBuilder();
                    var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                    vm.输出目标 = 解码.写;
                    vm.运行(编译);
                    解码.收尾();
                    var 实得行 = 缓冲.ToString().Trim().Split('\n').Select(x => x.TrimEnd('\r')).ToList();
                    bool 好 = 期望行.Count > 0 && 实得行.Count == 期望行.Count
                        && 实得行.Zip(期望行, (a, b) => a == b).All(x => x);
                    记录("大数库 标准工程 示例43 逐条对预期输出(30! / 2¹⁰⁰ / 负数加减与取负 / 1e21 ÷ 7 的商与余)",
                        好, 好 ? $"逐行一致({期望行.Count} 行)" : $"期望 {期望行.Count} 行 / 实得 {实得行.Count} 行;" +
                            (期望行.Count > 0 && 实得行.Count > 0
                                ? $"第 1 行 期望[{期望行[0]}] 实得[{实得行[0]}]"
                                : "条数先对不上"));
                }
            }
            catch (Exception ex) { 记录异常("大数库 标准工程 示例43", ex); }

            // ============================================================
            // ⑥ 接线哨兵
            // ============================================================
            try
            {
                string 数文 = File.ReadAllText(数路径);
                bool 头齐 = 数文.Contains("口径(2026-", StringComparison.Ordinal)
                    && 数文.Contains("提供的函数(", StringComparison.Ordinal)
                    && 数文.Contains("英文对照", StringComparison.Ordinal)
                    && 数文.Contains("复杂度", StringComparison.Ordinal)
                    && 数文.Contains("边界(如实登记", StringComparison.Ordinal);
                int 法 = 0;
                foreach (string 行 in 数文.Split('\n'))
                    if (行.StartsWith("方法 ", StringComparison.Ordinal)) 法++;
                记录("大数库 接线哨兵:库在盘上、头注释五段齐、公开方法数(12)",
                    头齐 && 数文.Contains("模块 大数", StringComparison.Ordinal) && 法 == 12,
                    $"公开方法 {法} 个");
            }
            catch (Exception ex) { 记录异常("大数库 接线哨兵", ex); }
        }

        /// <summary>造一个 `位数` 位十进制的随机数文字(首位非 0);`要负` 就带负号。自检夹具用。</summary>
        private static string 造十进制(Random 随机, int 位数, bool 要负)
        {
            var 串 = new StringBuilder();
            if (要负) 串.Append('-');
            串.Append((char)('1' + 随机.Next(0, 9)));
            for (int i = 1; i < 位数; i++) 串.Append((char)('0' + 随机.Next(0, 10)));
            return 串.ToString();
        }
    }
}
