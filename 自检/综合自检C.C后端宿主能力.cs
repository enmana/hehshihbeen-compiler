        /// <summary>
        /// 一份用宿主能力的 HB 源码,两头真跑:C# 虚拟机(挂 `宿主能力C.处理`)对 C 后端编出的原生 exe,
        /// 比寄存器 / 整块内存 / 程序输出 / 退出码 / 执行条数 / 最近路径。
        /// **两次跑之前都把 `根` 清成同一个空目录**(宿主真在动文件,起点不一样比出来的是假差异),
        /// 并且两头把钟冻在同一个秒(`冻结秒`)。
        /// </summary>
        private static void 宿主对拍(string 名, string 源码, string 根, bool 不比条数 = false)
        {
            宿主能力C.清运行痕迹();
            宿主能力C.取当前秒 = () => 冻结秒;
            try
            {
                清空目录(根);
                var 编译结果 = 编译(源码);
                string c源文本 = C后端C.转译(编译结果, 虚拟机C.默认内存大小).源码;

                // ① 虚拟机侧
                var 机 = new 虚拟机C();
                机.设内存大小(虚拟机C.默认内存大小);
                机.初值表 = 编译结果.初值表;
                机.宿主调用 = 宿主能力C.处理;
                var 出 = new MemoryStream();
                机.输出目标 = b => 出.WriteByte(b);
                string 机报错 = "";
                机.装载(编译结果.机器码);
                try { while (机.单步()) { } }
                catch (Exception ex) { 机报错 = ex.Message; }
                var 机状态 = C状态C.导出虚拟机状态(机, 出, 编译结果.代码字节数, 编译结果.数据字节数);
                机状态.退出码 = 0;

                // ② C 侧:转译 → 编 → 跑
                string 暂存 = 目录(名);
                string c源 = Path.Combine(暂存, 干净名(名) + ".c");
                string exe = Path.Combine(暂存, 干净名(名) + ".exe");
                string 状态路径 = Path.Combine(暂存, 干净名(名) + ".状态");
                File.WriteAllText(c源, c源文本, new UTF8Encoding(false));
                var 编 = C工具链C.编成exe(c源, exe, 关优化: true);
                if (!编.成功)
                {
                    记录(名, false, "C 编译器没编过:" + 截断(编.日志, 240));
                    return;
                }

                清空目录(根);       // exe 那一趟从同一个空目录开始
                var (退出码, 原生出, _) = 跑原生带状态(exe, null, 状态路径, 冻结秒);
                var 原生状态 = C状态C.读原生状态(状态路径);
                if (原生状态 == null)
                {
                    记录(名, false, "原生 exe 没落下状态转储(它自己没跑起来?)");
                    return;
                }
                var 比 = C状态C.比(机状态, 原生状态, 原生出, 退出码, 不比条数: 不比条数);
                bool 过 = 比.一致 && 机报错.Length == 0;
                // G3 流那一条:**第343批起照常逐字节比**(输出 / 寄存器 / 整块内存 / 执行条数)。
                //
                // 为什么以前不比:`读一块` 写回的那一格是"上一次 `Read` 给了几个字节",而
                // `FileStream.Read` 与 `fread` 对**同一次读**的短读切法不同(一个 8 字节可能给 2+6、
                // 另一个给 8)⇒ 那一格带出的池水位也跟着错开。**判据不该建立在这种合法差异上。**
                // 夹具因此改成"一次只读 1 个字节"(要多少给多少,直到末尾),短读那一格两边定得下来 ——
                // 于是这一条可以收紧,而且必须收紧:不收的代价实测过 —— C 后端 `开流` 多抬了一次版本
                // (末次句柄 C 侧 `2k-1` / C# 侧 `k`),这条断言看不见,是 `示例32_数据表` 的逐工程
                // 对拍把它抓出来的(口径与为什么见 `C后端\运行时.c` 流句柄表那一段)。
                if (名.Contains("流式读写", StringComparison.Ordinal))
                {
                    记录(名, 过, 过
                        ? $"退出码 {退出码};{原生出.Length} 字节输出(每次读到的字节数 / EOF / 状态码)" +
                          $" + 寄存器 + 整块内存 逐字节一致 + 执行条数 + 最近路径逐字节一致(C 源码 {c源文本.Length} 字;" +
                          $"夹具按「一次只读 1 个字节」写,`Read` 短读那一格两边定得下来)"
                        : $"不一致:{比.说明};虚拟机输出=[{Encoding.UTF8.GetString(机状态.输出).Replace("\n", "|")}]," +
                          $"原生输出=[{Encoding.UTF8.GetString(原生出).Replace("\n", "|")}];" +
                          $"虚拟机报错 = {截断(机报错, 60)},原生退出码 = {退出码}");
                    return;
                }
                记录(名, 过, 过
                    ? $"退出码 {退出码};{原生出.Length} 字节输出 + 寄存器 + 整块内存 逐字节一致" +
                      (不比条数
                          ? "(**这一档不比执行条数 / 最近路径**:它靠 `当 (任务就绪(…) == 0) { }` 等后台线程," +
                            "问了几轮由线程快慢决定 —— 拿它当判据是假判据)"
                          : " + 执行条数 + 最近路径逐字节一致") +
                      $"(C 源码 {c源文本.Length} 字)"
                    : $"不一致:{比.说明};虚拟机输出=[{Encoding.UTF8.GetString(机状态.输出).Replace("\n", "|")}]," +
                      $"原生输出=[{Encoding.UTF8.GetString(原生出).Replace("\n", "|")}];" +
                      $"虚拟机报错 = {截断(机报错, 60)},原生退出码 = {退出码}");
            }
            finally { 宿主能力C.清运行痕迹(); }         // 时钟与白名单一起还原
        }

        /// <summary>
        /// 两份程序输出"只差短读那一格"吗(留作排查用:口径与 `读一块` 那一格相同)。
        /// </summary>
        private static bool 输出只差短读那一格(byte[] 左, byte[] 右)
        {
            if (左.Length != 右.Length) return false;
            int 差 = 0;
            for (int i = 0; i < 左.Length; i++)
            {
                if (左[i] == 右[i]) continue;
                差++;
                bool 都是数字 = 左[i] is >= (byte)'0' and <= (byte)'9' && 右[i] is >= (byte)'0' and <= (byte)'9';
                if (!都是数字 || 差 > 1) return false;
            }
            return true;
        }

        /// <summary>寄存器"至多一个不同、而且两边都是小值"吗(短读带出来的那个计数寄存器)</summary>
        private static bool 至多一个寄存器差小值(IReadOnlyList<uint> 左, IReadOnlyList<uint> 右)
        {
            if (左.Count != 右.Count) return false;
            int 差 = 0;
            for (int i = 0; i < 左.Count; i++)
            {
                if (左[i] == 右[i]) continue;
                差++;
                if (差 > 1 || 左[i] > 64 || 右[i] > 64) return false;
            }
            return true;
        }

        /// <summary>
        /// G3 流那一条专用的内存比:**只放行"短读字节数"那一格**(差 1、且两边是"上一次 `Read` 给了几个字节")。
        /// 其余任何一个字节不同都照旧算不一致 —— 别把这条口子开成"内存不比了"。
        /// `允许级联` = 真时额外放行"池水位 / 缓冲指针跟着错开"那几处(短读带出来的,**值都小**)。
        /// </summary>
        internal static (bool 过, string 说明) 比内存只放行短读一格(C状态快照C 虚拟机, C状态快照C 原生,
            bool 允许级联 = false)
        {
            if (虚拟机.内存.Length != 原生.内存.Length)
                return (false, $"内存字节数 {虚拟机.内存.Length} / {原生.内存.Length}");
            int 差数 = 0, 唯一处 = -1;
            for (int i = 0; i < 虚拟机.内存.Length; i++)
            {
                if (虚拟机.内存[i] == 原生.内存[i]) continue;
                差数++;
                唯一处 = i;
            }
            if (差数 == 0) return (true, "内存一字不差");
            // 只允许**一处**、而且两边都是"小整数"(短读 1~上限):多了 / 大了说明是别的分岔,照红
            if (差数 == 1 && 虚拟机.内存[唯一处] <= 64 && 原生.内存[唯一处] <= 64)
                return (true, $"内存只差那一格(短读字节数):0x{唯一处:X}");
            if (允许级联)
            {
                // 短读带出来的那一族:值可能是"读到几个字节"(小)也可能是"池里下一块的地址"(大),
                // 但**只允许落在数据段内**(代码段 / 硬件栈上出现任何差别都照红)。
                int 出界 = 0;
                for (int i = 0; i < 虚拟机.内存.Length; i++)
                {
                    if (虚拟机.内存[i] == 原生.内存[i]) continue;
                    if (i >= 虚拟机.数据字节数) { 出界++; }
                }
                if (出界 == 0) return (true, $"内存差 {差数} 处、全落在数据段里(短读带出的计数 / 池水位 / 缓冲指针)");
                return (false, $"内存差 {差数} 处,其中 {出界} 处在数据段之外");
            }
            int 首 = -1;
            for (int i = 0; i < 虚拟机.内存.Length && 首 < 0; i++)
                if (虚拟机.内存[i] != 原生.内存[i]) 首 = i;
            if (首 < 0) return (true, "");
            return (false, $"内存差 {差数} 处,第一处 0x{首:X}(虚拟机 0x{虚拟机.内存[首]:X2} / 原生 0x{原生.内存[首]:X2})");
        }

        /// <summary>一条断言用的临时根目录(绝对路径 + 结尾 `/`,直接拼进 HB 源码里当字符串字面量)</summary>
        private static string 宿主根(string 名)
        {
            string 目录全 = Path.Combine(临时区C.基目录(), "hbcc_C后端宿主", 干净名(名)).Replace('\\', '/');
            return 目录全 + "/";
        }

        /// <summary>把那个根目录清成空目录(不存在就建出来)</summary>
        private static void 清空目录(string 路径)
        {
            try { if (Directory.Exists(路径)) Directory.Delete(路径, recursive: true); } catch { }
            try { Directory.CreateDirectory(路径); } catch { }
        }

        /// <summary>从运行期 C 源码里读一个 `#define HB_F_xxx <数字>u` 的值(没有就给 -1)</summary>
        private static int 取宏值(string 源, string 宏)
        {
            int 起 = 源.IndexOf("#define " + 宏, StringComparison.Ordinal);
            if (起 < 0) return -1;
            int 末 = 源.IndexOf('\n', 起);
            string 行 = 源[起..(末 < 0 ? 源.Length : 末)];
            Match 匹配 = Regex.Match(行, @"(\d+)u");
            return 匹配.Success ? int.Parse(匹配.Groups[1].Value, CultureInfo.InvariantCulture) : -1;
        }

        /// <summary>`needle` 在 `源` 里出现几次(数功能号那几条用)</summary>
        private static int 数出现(string 源, string needle)
        {
            int 数 = 0, 起 = 0;
            while (true)
            {
                int 处 = 源.IndexOf(needle, 起, StringComparison.Ordinal);
                if (处 < 0) break;
                数++;
                起 = 处 + needle.Length;
            }
            return 数;
        }
