        /// <summary>
        /// G3 域 1:流式读写七条真跑一遍 —— 写流(打开 / 写一块 / 定位覆盖 / 关写流)+ 读流(打开 / 连着读四块 /
        /// 关读流)+ 失败路(开不存在的文件 / 用完的句柄 / 拿读流写)。**输出全是数字或 ASCII**,
        /// 这样 C# 与原生 exe 的输出逐字可比(-1 打印成 4294967295,那是无符号十进制的口径)。
        ///
        /// ⚠ **读的次数写死,不要用"读到 0 为止"的循环当输出**:`FileStream.Read` 与 `fread` 允许
        /// "这次少给几个"(短读),于是"到末尾前读了几轮"两边可以不一样(实测:`Content-Length` 10 字节、
        /// 上限 4 时 C# 给 4+4+2、glibc 给 4+4+4) —— 那是**合法的实现差异**,拿它当对拍判据是假判据。
        /// 这里改成固定读四次,把"每次读回几个字节"逐次输出。
        /// </summary>
        private static string 宿主源_流式读写(string 根) =>
            $"字符串 目录 = \"{根}s\";\n" +
            "输出行(建目录(目录));\n" +
            $"字符串 路径 = \"{根}s/流.txt\";\n" +
            "整数 写句柄 = -1;\n" +
            "输出行(打开写流(路径, 写句柄));\n" +
            "输出行(写一块(写句柄, \"ABCDEFGH\", 0));\n" +
            "输出行(定位(写句柄, 4));\n" +
            "输出行(写一块(写句柄, \"xy\", 0));\n" +       // 从第 4 个字节起覆盖着写
            "输出行(关写流(写句柄));\n" +
            "字符串 内容 = \"\";\n" +
            "输出行(读文件(路径, 内容, 4096));\n" +
            "输出行(内容);\n" +
            "输出行(内容.长度());\n" +
            "整数 读句柄 = -1;\n" +
            "输出行(打开读流(路径, 读句柄));\n" +
            "输出行(定位(读句柄, 0));\n" +
            "字符串 块 = \"\";\n" +
            // ⚠ `读一块` 写回的那一格是"上一次 `Read` 给了几个字节";`FileStream.Read` 与 `fread`
            //    对**同一次读**的短读切法不同(一个 8 字节可能给 2+6,另一个给 8)⇒ 这一格天生不可逐字节比。
            //    所以这里**一次只读 1 个字节**:两边都必然给 1(要多少给多少,直到末尾),
            //    计数与池水位就都定了,行为和内存才都能逐字节对。
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +          // 第 9 次:0(到末尾,8 个字节已经读完)
            "输出行(块.长度());\n" +
            "输出行(定位(读句柄, 4));\n" +                 // 再定位回去,把"定位后接着读"这条也钉住
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +
            "输出行(读一块(读句柄, 块, 1));\n" +           // 第 14 次:0(又到末尾)
            "输出行(关读流(读句柄));\n" +
            "输出行(关读流(读句柄));\n" +
