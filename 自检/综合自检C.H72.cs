// ============================================================
// H72(第354批收口):**条件里的堆访问必须跟着 `&& / ||` 一起短路**
//
//   这一条是**编译器**的修复自检,所以单列一组,名字走 `H72`。
//
//   **怎么撞上的**:写 `Sample\库\树.hb` 的"中序后继"时,那一句是标准写法 ——
//   `当 (父 != 0 && 取字(父, 8) == 走)`(走到根就收手)。结果**空树 / 走到根时当场崩**:
//   `字读取越界: 0xFFFFFFFC..0xFFFFFFFF`。
//
//   **最小复现(5 行,`--no-opt` 与默认档都现)**:
//   ```
//   整数 走 = 5;
//   整数 父 = 0;
//   逻辑 果 = 假;
//   如果 (父 != 0 && 取字(父, 8) == 走) { 果 = 真; }
//   输出行(果);        // 修前:崩在 0xFFFFFFFC;修后:0
//   ```
//
//   **根因**:`中间层C.表达式工具.cs` 的 `输出条件` 一进来就调 `替换地址取用(整条条件)`,
//   而 `替换地址取用` 里第一句是 `替换堆调用` —— **按整条文本**把 `申请 / 取字 / 存字` 全展开成寄存器。
//   展开是**当场发指令**的 ⇒ 右边那半句在"左边真假还没判"的时候就已经算过了,
//   `&& / ||` 的短路(文档承诺的是"真短路:短路那一支只解析不算数")**只对它后面那层 AST 有效,
//   对"提前摊开的堆访问"无效**。`父 == 0` 时那句 `取字(父, 8)` 仍然去读 `内存[父 - 4]`(堆头检查)。
//   顺带说明"为什么别的短路还是好的":用户函数调用(`加一()`)不在这条文本展开路里,所以照旧短路。
//
//   **修法(两处,都在中间层)**:
//     ① `输出条件` 改调 **`替换地址取用跳过堆`**(只换 `地址(...)`,不碰堆调用);
//     ② `求值调用` 多一档 **`求值堆动作当值`**:AST 遇上 `申请 / 取字 / 存字 / 释放` 就懒算到
//        "轮到这一支"那一刻(实参文本走节点自己的 `显示()`,内层还嵌着堆调用时照旧走 `替换堆调用`)。
//   **ISA / 关键字 / 内建 / 机器码一个字没动**;别的表达式路径(`赋值右边` / `实参` / 老路条件)
//   仍旧走原来那条"先展开"的路,一个字没改。
//
//   ★ 这一组钉四件事(三条行为 + 一条接线哨兵):
//     ① **最小复现**:左边为假时右边的 `取字` 不许算(优化开 / 关两档都要不崩、都要给 0);
//     ② **`||` 那一半**同样短路(`父 == 0 || 取字(父, 8) == 5` 给真,不崩);
//     ③ **该算的还是要算**:左边为真时右边那个 `取字` 必须真读出来(不能为了"短路安全"把正常的也跳了);
//     ④ **接线哨兵**:那两处修复还在源码里(`替换地址取用跳过堆` / `求值堆动作当值`)。
//
//   ⚠ 为什么这条值得单列一组:`父 != 0 && 取字(父, …)` / `句柄 != 0 && 取字(句柄, …)` 是
//     **照堆写数据结构时最常见的一句护栏**(链表 / 树 / 图 / 缓冲),它一崩,整类写法都用不了。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void H72堆短路自检()
        {
            // 修前必崩的那 5 行(左边为假 ⇒ 右边那句 取字 一个字都不该发)
            const string 最小复现源 =
                "整数 走 = 5;\n" +
                "整数 父 = 0;\n" +
                "逻辑 果 = 假;\n" +
                "如果 (父 != 0 && 取字(父, 8) == 走)\n" +
                "{\n" +
                "    果 = 真;\n" +
                "}\n" +
                "输出行(果);\n" +
                "输出行(9);\n" +
                "停止\n";

            // `||` 那一半:左边为真 ⇒ 右边同样不该算
            const string 或那一半源 =
                "整数 父 = 0;\n" +
                "逻辑 果 = 假;\n" +
                "如果 (父 == 0 || 取字(父, 8) == 5)\n" +
                "{\n" +
                "    果 = 真;\n" +
                "}\n" +
                "输出行(果);\n" +
                "停止\n";

            // 该算的还是要算:左边为真 ⇒ 右边那个 取字 必须真读出来
            const string 该算还得算源 =
                "整数 块 = 申请(16);\n" +
                "存字(块, 8, 42);\n" +
                "整数 走 = 42;\n" +
                "整数 真值 = 1;\n" +
                "逻辑 果 = 假;\n" +
                "如果 (真值 != 0 && 取字(块, 8) == 走)\n" +
                "{\n" +
                "    果 = 真;\n" +
                "}\n" +
                "输出行(果);\n" +
                "输出行(取字(块, 8));\n" +
                "释放(块);\n" +
                "停止\n";

            string 跑一份(string 源, bool 优化)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, 优化,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            // ── ① 最小复现:左边为假 ⇒ 右边那句 `取字` 一个字都不许发 ──
            try
            {
                string 开 = 跑一份(最小复现源, true), 关 = 跑一份(最小复现源, false);
                bool 好 = 开 == "0|9" && 关 == "0|9";
                记录("H72 堆短路:左边为假时条件里的 `取字` 不许算(5 行最小复现,优化开/关两档;修前崩在 0xFFFFFFFC)",
                    好, $"优化开 [{开}] / 优化关 [{关}](该是 [0|9])" +
                        (好 ? ";修前这两档都是「字读取越界: 0xFFFFFFFC」" : ""));
            }
            catch (Exception ex) { 记录异常("H72 堆短路:左边为假时条件里的 `取字` 不许算(5 行最小复现,优化开/关两档)", ex); }

            // ── ② `||` 那一半同样短路 ──
            try
            {
                string 实 = 跑一份(或那一半源, true);
                记录("H72 堆短路:`||` 左边为真时右边也不许算(`父 == 0 || 取字(父, 8) == 5` 给真且不崩)",
                    实 == "1", $"实得 [{实}](该是 [1])");
            }
            catch (Exception ex) { 记录异常("H72 堆短路:`||` 左边为真时右边也不许算", ex); }

            // ── ③ 该算的还是要算(别为了"短路安全"把正常的也跳了)──
            try
            {
                string 实 = 跑一份(该算还得算源, true);
                记录("H72 堆短路:左边为真时右边那个 `取字` 必须真读出来(短的是「不该算的那一支」,不是「从此都不算」)",
                    实 == "1|42", $"实得 [{实}](该是 [1|42])");
            }
            catch (Exception ex) { 记录异常("H72 堆短路:左边为真时右边那个 `取字` 必须真读出来", ex); }

            // ── ④ 接线哨兵:两处修复还在源码里(只钉"还在不在")──
            const string 接线断言 = "H72 接线:条件那一路「只换地址、不预先展开堆调用」与「堆动作当值懒算」都还在";
            try
            {
                string? 根 = 找仓库根目录();
                if (根 == null) { 跳过(接线断言, "找不到仓库根(读不到那两份中间层源码)"); return; }
                string 表达式源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.表达式工具.cs"), Encoding.UTF8);
                string 引用源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.结构与引用.cs"), Encoding.UTF8);
                string 堆源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.堆.cs"), Encoding.UTF8);
                bool 好 = 表达式源.Contains("内容 = 替换地址取用跳过堆(内容, 行号, 原文);", StringComparison.Ordinal)
                    && 引用源.Contains("private string 替换地址取用跳过堆(string 文本, int 行号, string 原文)", StringComparison.Ordinal)
                    && 堆源.Contains("private 表达式值 求值堆动作当值(string 动作, 调用节点C 调用, int 行号, string 原文)", StringComparison.Ordinal)
                    && 表达式源.Contains("替换地址取用(内容, 行号, 原文);", StringComparison.Ordinal);   // 老路那一份照旧在
                记接线(接线断言, 好,
                    $"条件改走「跳过堆」那一份 = {表达式源.Contains("内容 = 替换地址取用跳过堆(内容, 行号, 原文);", StringComparison.Ordinal)};" +
                    $"跳过堆那一份在 = {引用源.Contains("替换地址取用跳过堆", StringComparison.Ordinal)};" +
                    $"堆动作当值在 = {堆源.Contains("求值堆动作当值", StringComparison.Ordinal)}" +
                    " —— 接线哨兵(读仓库源码文本判的),行为面看上面三条");
            }
            catch (Exception ex) { 记录异常(接线断言, ex); }
        }
    }
}
