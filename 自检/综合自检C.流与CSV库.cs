using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 流与CSV库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 流路径 = Path.Combine(库目录, "流.hb").Replace('\\', '/');
            string 迭路径 = Path.Combine(库目录, "迭代器.hb").Replace('\\', '/');
            string 大路径 = Path.Combine(库目录, "大文件工具.hb").Replace('\\', '/');
            string 表路径 = Path.Combine(库目录, "CSV.hb").Replace('\\', '/');
            string 字路径 = Path.Combine(库目录, "string.hb").Replace('\\', '/');
            if (!File.Exists(流路径) || !File.Exists(迭路径) || !File.Exists(大路径) || !File.Exists(表路径) || !File.Exists(字路径))
            {
                跳过("流与CSV库 定位库文件", $"找不到 {流路径} 那四个(不在工作副本里跑就跳过)");
                return;
            }

            string 头 = $"包含 \"{流路径}\"\n包含 \"{迭路径}\"\n包含 \"{大路径}\"\n包含 \"{表路径}\"\n包含 \"{字路径}\"\n"
                + "方法 带标(字符串 标, 字符串 值) 返回 字符串\n"
                + "{\n"
                + "    字符串 结果 = \"\";\n"
                + "    拼接到(结果, 标, 值);\n"
                + "    返回 结果;\n"
                + "}\n"
                + "方法 带标数(字符串 标, 整数 值) 返回 字符串\n"
                + "{\n"
                + "    字符串 结果 = \"\";\n"
                + "    拼接到(结果, 标);\n"
                + "    拼接到(结果, 转字符串(值));\n"
                + "    返回 结果;\n"
                + "}\n"
                + "方法 带标逻辑(字符串 标, 逻辑 值) 返回 字符串\n"
                + "{\n"
                + "    字符串 结果 = \"\";\n"
                + "    拼接到(结果, 标);\n"
                + "    如果 (值)\n"
                + "    {\n"
                + "        拼接到(结果, \"1\");\n"
                + "    }\n"
                + "    否则\n"
                + "    {\n"
                + "        拼接到(结果, \"0\");\n"
                + "    }\n"
                + "    返回 结果;\n"
                + "}\n";

            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // ============================================================
            // ① 流那一族:真盘上真跑
            // ============================================================
            string 临时根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"流库自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                string 数据路径 = 临时根 + "/数据路径.txt";
                string 源 = 头
                    + $"字符串 根 = \"{临时根}\";\n"
                    + $"字符串 数据路径 = \"{数据路径}\";\n"
                    + "输出行(带标逻辑(\"A\", 建目录(根)));\n"
                    + "整数 写句 = 流.开写(数据路径);\n"
                    + "输出行(带标逻辑(\"B\", 写句 > 0));\n"
                    + "输出行(带标数(\"C\", 流.写行(写句, \"第一行\")));\n"
                    + "输出行(带标数(\"D\", 流.写块(写句, \"接在后面\")));\n"
                    + "输出行(带标数(\"E\", 流.落盘(写句)));\n"
                    + "输出行(带标逻辑(\"F\", 流.关(写句)));\n"
                    + "输出行(带标数(\"G\", 流.写块(写句, \"作废了\")));\n"
                    + "输出行(带标逻辑(\"H\", 流.关(写句)));\n"
                    + "输出行(带标数(\"I\", 流.读块(写句)));\n"
                    + "整数 读句 = 流.开读(数据路径);\n"
                    + "输出行(带标逻辑(\"J\", 读句 > 0));\n"
                    + "输出行(带标数(\"K\", 流.读块(读句)));\n"
                    + "输出行(带标(\"L\", 流.当前块(读句)));\n"
                    + "输出行(带标数(\"M\", 流.读块(读句)));\n"
                    + "输出行(带标数(\"N\", 流.写块(读句, \"往读流里写\")));\n"
                    + "输出行(带标逻辑(\"O\", 流.关(读句)));\n"
                    + "整数 行句 = 流.开读(数据路径);\n"
                    + "当 (流.读行(行句))\n"
                    + "{\n"
                    + "    输出行(带标(\"P\", 流.当前行(行句)));\n"
                    + "}\n"
                    + "输出行(带标逻辑(\"Q\", 流.关(行句)));\n"
                    + "字符串 没有 = \"\";\n"
                    + "拼接到(没有, 根);\n"
                    + "拼接到(没有, \"/没有这个.txt\");\n"
                    + "输出行(带标数(\"R\", 流.开读(没有)));\n"
                    + "停止\n";
                var 期望段 = new List<string>
                {
                    "A1",
                    "B1",
                    "C" + Encoding.UTF8.GetByteCount("第一行\n"),
                    "D" + Encoding.UTF8.GetByteCount("接在后面"),
                    "E0",
                    "F1",
                    "G-1",
                    "H0",
                    "I-1",
                    "J1",
                    "K" + Encoding.UTF8.GetByteCount("第一行\n接在后面"),
                    "L第一行", "接在后面",
                    "M0",
                    "N-1",
                    "O1",
                    "P第一行", "P接在后面",
                    "Q1",
                    "R-1",
                };
                string 期望 = string.Join("|", 期望段);
                string 实得 = 跑(源);
                记录("流与CSV库 流那一族:开写 / 写行 / 写块 / 落盘 / 关 / 句柄作废 / 开读 / 读块 / 当前块 / " +
                    "读行 + 当前行(跨块拼行)/ 关 / 打不开 —— 真盘上真跑,逐条对 C# 侧按同一套口径算的期望",
                    期望 == 实得, 对拍说明(期望, 实得));
            }
            catch (Exception ex) { 记录异常("流与CSV库 流那一族", ex); }
            finally
            {
                try { if (临时根.Length > 0 && Directory.Exists(临时根)) Directory.Delete(临时根, true); }
                catch { /* 收尾删不掉就留给下一次扫残留 */ }
            }

            // ============================================================
            // ①之二 长跑不吃池(H83,2026-10-11 结)
            //   症状:`流.读行` / `流.写行` 长跑把字符串池吃光(实测:真盘两万行 × 61 字节,
            //     1827 万条指令 / 2.1 秒时当场停「字符串 整行 长不下了:编译器自己开的池用完了」)。
            //   根因(H84 那一条语言面口径):**函数体里"造一条新串"的局部声明,每次调用那一块都不回收** ——
            //     旧写法每读一行要造 块 / 余 / 本行 / 后半 四条、每写一行要造 整行 一条,两万行必死。
            //   修法(就地复用 + 字节区):块 / 行 / 正在吃的那一块 / 半行全是**模块级持久串**反复用,
            //     找换行与切行走模块级 `字符 区[]`(下标 O(1)),`写行` 连拼都不拼(文本与换行分两块直接写)。
            //   判据 = **同一条程序跑得完**:写得完 + 逐行读得完 + 条数与字节数都对。行故意取短
            //     (每 1000 行才夹一条 200 字节的)——"每调用一次漏一块"漏的是那几格本身、与行长无关,
            //     短行照样抓得住,而两万行 × 四五千字节那种规模光跑就要几十秒。
            // ============================================================
            string 长跑根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"流长跑自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                Directory.CreateDirectory(长跑根);
                string 长跑路 = 长跑根 + "/长跑.txt";
                string 长行字面 = new string('x', 200);
                string 源 = 头
                    + $"字符串 长跑路 = \"{长跑路}\";\n"
                    + "整数 写句 = 流.开写(长跑路);\n"
                    + "整数 i = 0;\n"
                    + "当 (i < 20000)\n"
                    + "{\n"
                    + "    如果 (i % 1000 == 0)\n"
                    + "    {\n"
                    + $"        流.写行(写句, \"{长行字面}\");\n"
                    + "    }\n"
                    + "    否则\n"
                    + "    {\n"
                    + "        流.写行(写句, \"行\");\n"
                    + "    }\n"
                    + "    i = i + 1;\n"
                    + "}\n"
                    + "输出行(带标逻辑(\"A\", 流.关(写句)));\n"
                    + "整数 读句 = 流.开读(长跑路);\n"
                    + "整数 条数 = 0;\n"
                    + "整数 合计 = 0;\n"
                    + "字符串 本行 = \"\";\n"
                    + "当 (流.读行(读句))\n"
                    + "{\n"
                    + "    条数 = 条数 + 1;\n"
                    + "    本行 = 流.当前行(读句);\n"
                    + "    合计 = 合计 + 本行.长度();\n"
                    + "}\n"
                    + "输出行(带标数(\"B\", 条数));\n"
                    + "输出行(带标数(\"C\", 合计));\n"
                    + "输出行(带标逻辑(\"D\", 流.关(读句)));\n"
                    + "停止\n";
                int 长行条数 = Enumerable.Range(0, 20000).Count(k => k % 1000 == 0);
                var 期望段 = new List<string>
                {
                    "A1",
                    "B20000",
                    "C" + (长行条数 * 200 + (20000 - 长行条数)),
                    "D1",
                };
                string 期望 = string.Join("|", 期望段);
                string 实得 = 跑(源);
                记录("流与CSV库 长跑不吃池(H83):真盘两万行(每 1000 行夹一条 200 字节的长行)" +
                    "写得完 + 逐行读得完,条数与字节数逐条对(旧写法在这儿把池吃光、当场停机)",
                    期望 == 实得, 对拍说明(期望, 实得));
            }
            catch (Exception ex) { 记录异常("流与CSV库 长跑不吃池", ex); }
            finally
            {
                try { if (长跑根.Length > 0 && Directory.Exists(长跑根)) Directory.Delete(长跑根, true); }
                catch { /* 收尾留残 */ }
            }

            // ============================================================
            // ①之三 行边界:跨三块的长行 / 空行 / `\r\n` / 末行没有换行
            //   改完 `流.hb` 的"块 + 游标 + 字节区"那一套之后,这四种形状正是游标最容易走偏的地方
            //   (块边界切在行中间、`\r\n` 跨块、连续空行、末尾那一行没有换行)。
            // ============================================================
            string 边界根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"流边界自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                Directory.CreateDirectory(边界根);
                string 边界路 = Path.Combine(边界根, "边界.txt").Replace('\\', '/');
                var 边界 = new StringBuilder();
                边界.Append("第一行\n");                    // 普通一行
                边界.Append("abc\r\n");                     // 行尾 \r 要去掉
                边界.Append('\n');                          // 空行
                边界.Append(new string('x', 12000));        // 跨三块的长行(一块 4096)
                边界.Append('\n');
                边界.Append("尾");                          // 末行没有换行
                File.WriteAllText(边界路, 边界.ToString(), new UTF8Encoding(false));
                string 源 = 头
                    + $"字符串 边界路 = \"{边界路}\";\n"
                    + "整数 句 = 流.开读(边界路);\n"
                    + "整数 序 = 0;\n"
                    + "整数 合计 = 0;\n"
                    + "当 (流.读行(句))\n"
                    + "{\n"
                    + "    字符串 本行 = 流.当前行(句);\n"
                    + "    整数 长 = 本行.长度();\n"
                    + "    合计 = 合计 + 长;\n"
                    + "    输出行(长);\n"
                    + "    如果 (序 == 3)\n"
                    + "    {\n"
                    + "        输出行(带标逻辑(\"头\", 本行[0] == 'x'));\n"
                    + "        输出行(带标逻辑(\"尾\", 本行[11999] == 'x'));\n"
                    + "    }\n"
                    + "    序 = 序 + 1;\n"
                    + "}\n"
                    + "输出行(带标数(\"条数\", 序));\n"
                    + "输出行(带标数(\"合计\", 合计));\n"
                    + "输出行(带标逻辑(\"关\", 流.关(句)));\n"
                    + "停止\n";
                var 期望段 = new List<string>
                {
                    "3",                                              // 「第一行」三个字(`长度()` 按文字算)
                    "3",                                              // 「abc」—— 行尾那个 `\r` 要去掉
                    "0",                                              // 空行
                    "12000",
                    "头1", "尾1",                                     // 长行的头尾各取一个字节认一认
                    "1",                                              // 末行「尾」—— 没有换行也算一行
                    "条数5",
                    "合计" + (3 + 3 + 0 + 12000 + 1),
                    "关1",
                };
                string 期望 = string.Join("|", 期望段);
                string 实得 = 跑(源);
                记录("流与CSV库 行边界:跨三块的长行(12000 字节)/ 空行 / `\\r\\n`(行尾 `\\r` 去掉)/ " +
                    "末行没有换行 —— 每一行的长度、条数与合计逐条对",
                    期望 == 实得, 对拍说明(期望, 实得));
            }
            catch (Exception ex) { 记录异常("流与CSV库 行边界", ex); }
            finally
            {
                try { if (边界根.Length > 0 && Directory.Exists(边界根)) Directory.Delete(边界根, true); }
                catch { /* 收尾留残 */ }
            }

            // ============================================================
            // ①之四 两条流交错着读:每格自己的进度互不串
            //   `读行` 的进度(正在吃的那一块 + 游标 + 半行)全落在格子上;扫描区与半行是"一次调用用完就走"的
            //   暂存 —— 交错这一档专门盯"暂存被另一条流冲掉"这类串味。
            // ============================================================
            string 交错根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"流交错自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                Directory.CreateDirectory(交错根);
                string 左文件路 = Path.Combine(交错根, "左文件.txt").Replace('\\', '/');
                string 右文件路 = Path.Combine(交错根, "右文件.txt").Replace('\\', '/');
                string 源 = 头
                    + $"字符串 左文件路 = \"{左文件路}\";\n"
                    + $"字符串 右文件路 = \"{右文件路}\";\n"
                    + "整数 左写句 = 流.开写(左文件路);\n"
                    + "整数 右写句 = 流.开写(右文件路);\n"
                    + "流.写行(左写句, \"1\");\n"
                    + "流.写行(左写句, \"2\");\n"
                    + "流.写行(左写句, \"3\");\n"
                    + "流.写行(左写句, \"4\");\n"
                    + "流.写行(左写句, \"5\");\n"
                    + "流.写行(右写句, \"一\");\n"
                    + "流.写行(右写句, \"二\");\n"
