//   这一组十一块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **流那一族在真盘上真跑**:开写 / 写行 / 写块 / 落盘 / 关 / 句柄作废 / 开读 / 读块 / 当前块 /
//        读行 / 当前行 / 关 —— 一整段程序的输出与 C# 侧按同一套口径算的期望逐条比(字节数逐个数);
//     ①之二 **长跑不吃池(H83,2026-10-11 结)**:真盘两万行(每 1000 行夹一条 200 字节的长行)
