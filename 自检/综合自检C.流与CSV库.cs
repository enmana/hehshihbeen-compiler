//     ①之三 **行边界**:跨三块的长行(12000 字节)/ 空行 / `\r\n`(行尾 `\r` 去掉)/ 末行没有换行;
//     ①之四 **两条流交错着读**:每格自己的进度互不串(改完 流.hb 的"块 + 游标"那一套之后钉住);
//     ② **迭代器**:按分隔 / 按行两种切法 + `剩几项` / `取前` / `跳过` / `找含子串` / `汇聚整数` / `重开`,
//        与 C# 参考实现逐条比;
//     ③ **大文件工具**:`拷到` 的字节数与内容、`数行`(末行无换行也算)、`校验`(**与 C# 的 FNV-1a 32
//        逐字节对拍**)、`读头`(短文件给全部、长文件截到 64);
//     ④ **CSV**:`字段数` / `取字段` / `是需转义` / `转义` / `生成`,与 C# 参考实现(同一套 RFC 4180 规矩)
//        逐条比 —— 引号里的分隔符 / `""` 转义 / 空字段 / 只有一段 / 空串都过一遍;
//     ⑤ **端到端**:标准工程 **`示例47_流与CSV`** 真编真跑,与它那行 `// 预期输出:` 逐行对;
//     ⑥ **接线哨兵**:四个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(10 / 10 / 4 / 5)。
//
//   ⚠ 这一组只在"给输出加非空前缀"时用一次 `拼接到`(与 `中文库` / `控制台文件时间环境库` 同一套手续)。
