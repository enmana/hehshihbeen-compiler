        /// <summary>按分隔串切段(空分隔 = 按行;与 `迭代器.建` 同一套)。</summary>
        private static List<string> 参考切段(string 源, string 分隔)
        {
            var 果 = new List<string>();
            if (源.Length == 0) return 果;
            if (分隔.Length == 0)
            {
                foreach (string 行 in 源.Split('\n'))
                {
                    string 本 = 行.EndsWith('\r') ? 行[..^1] : 行;
                    果.Add(本);
                }
                if (源.EndsWith('\n')) 果.RemoveAt(果.Count - 1);
                return 果;
            }
            var 段 = 源.Split(分隔);
            return 段.ToList();
        }

        private static int 参考整数项个数(List<string> 项们) => 项们.Count(是整数文);

        private static int 参考整数项和(List<string> 项们)
        {
            int 合 = 0;
            foreach (string 项 in 项们)
                if (int.TryParse(项, out int 值)) 合 += 值;
            return 合;
        }

        private static bool 是整数文(string 文)
        {
            if (文.Length == 0) return false;
            int i = 文[0] == '-' || 文[0] == '+' ? 1 : 0;
            if (i >= 文.Length) return false;
            for (; i < 文.Length; i++) if (文[i] < '0' || 文[i] > '9') return false;
            return true;
        }

        /// <summary>数行(`\n` 个数;末行没有换行也算一行;空串给 0)。</summary>
        private static int 参考行数(string 文)
        {
            if (文.Length == 0) return 0;
            int 换 = 文.Count(c => c == '\n');
            return 文.EndsWith('\n') ? 换 : 换 + 1;
        }

        /// <summary>FNV-1a 32(逐字节)。</summary>
        private static uint 参考FNV(string 文)
        {
            uint 值 = 2166136261;
            foreach (byte b in Encoding.UTF8.GetBytes(文))
            {
                值 ^= b;
                值 *= 16777619;
            }
            return 值;
        }

        /// <summary>逗号那一档的字段数(`string.hb.切分` 口径:空串给 1)。</summary>
        private static int 参考切分(string 行, string 分隔)
        {
            if (行.Length == 0) return 1;
            return 行.Split(分隔).Length;
        }

        /// <summary>CSV 解析(照 `CSV.hb` 头注释那套:引号只在字段开头算;`""` 是一个引号)。</summary>
        private static List<string> 参考字段们(string 行, string 分隔)
        {
            var 果 = new List<string>();
            int i = 0, 长 = 行.Length;
            while (true)
            {
                var 段 = new StringBuilder();
                if (i < 长 && 行[i] == '"')
                {
                    i++;
                    while (i < 长)
                    {
                        if (行[i] == '"')
                        {
                            if (i + 1 < 长 && 行[i + 1] == '"') { 段.Append('"'); i += 2; }
                            else { i++; break; }
                        }
                        else { 段.Append(行[i]); i++; }
                    }
                    while (i < 长 && !参考是分隔(行, i, 分隔)) i++;
                }
                else
                {
                    while (i < 长 && !参考是分隔(行, i, 分隔)) { 段.Append(行[i]); i++; }
                }
                果.Add(段.ToString());
                if (i >= 长) break;
                i += 分隔.Length;
                if (i >= 长) { 果.Add(""); break; }
            }
            return 果;
        }

        private static bool 参考是分隔(string 行, int 位, string 分隔)
        {
            if (分隔.Length == 0 || 位 + 分隔.Length > 行.Length) return false;
            return string.CompareOrdinal(行, 位, 分隔, 0, 分隔.Length) == 0;
        }

        private static bool 参考需转义(string 字段, string 分隔)
        {
            if (字段.Contains('"') || 字段.Contains('\n') || 字段.Contains('\r')) return true;
            if (分隔.Length == 0) return false;
            return 字段.Contains(分隔);
        }

        private static string 参考转义(string 字段, string 分隔)
        {
            if (!参考需转义(字段, 分隔)) return 字段;
            return "\"" + 字段.Replace("\"", "\"\"") + "\"";
        }
    }
