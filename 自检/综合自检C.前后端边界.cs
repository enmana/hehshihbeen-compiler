        /// <summary> 界面侧的文件:仓库根的 WPF 那几个 partial + 三个界面目录;`自检\` / `bin` / `obj` 不算 </summary>
        private static List<string> 界面侧源文件(string 根)
        {
            var 结果 = new List<string>();
            foreach (string 目录 in new[] { "", "界面控件", "选卡控件", "MobileIDE", "配置" })
            {
                string 全 = 目录.Length == 0 ? 根 : Path.Combine(根, 目录);
                if (!Directory.Exists(全)) continue;
                // 仓库根只取**顶层**那几个 partial(界面就在根上;递归会把 引擎\ 中间层\ hbcc\ 一起扫进来)
                var 选项 = 目录.Length == 0 ? SearchOption.TopDirectoryOnly : SearchOption.AllDirectories;
                foreach (string 文件 in Directory.EnumerateFiles(全, "*.cs", 选项))
                {
                    string 相对 = Path.GetRelativePath(根, 文件);
                    if (相对.StartsWith("自检", StringComparison.Ordinal)) continue;
                    if (相对.Contains("obj" + Path.DirectorySeparatorChar)) continue;
                    if (相对.Contains("bin" + Path.DirectorySeparatorChar)) continue;
                    结果.Add(文件);
                }
            }
            return 结果;
        }

