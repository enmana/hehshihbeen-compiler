        /// <summary>
        /// H39-2 的调试助手:同一条"编译 → 装载 → 逐步(到停机或 300 按)→ 还没停就继续"的手势,
        /// 进程内与跨进程各走一遍,把**每一按的记账签名**收下来对账(记账 = 源码行 / 调用栈深度 /
        /// 调用帧数 / 变量条数 / 调用处行数 / 寄存器说明指纹)——
        /// 一句话:两边"逐按"必须一模一样,不许"继续之后就不更新"。
        /// </summary>
        private static (int 按数, long 执行条数, int 带源码行的按, int 带变量的按, int 最深栈,
            bool 停机, double 每按微秒, string 每按签名, string 通道说明) 走一遍调试(string 源码, bool 跨进程)
        {
            var 编译 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源码)]);
            var 会话 = new 调试会话C { 调试文件表 = 编译.调试文件表, 当前文件 = "主程序.hb", 标签表 = 编译.标签表 };
            跑程序通道C? 通道 = null;
            try
            {
                if (跨进程)
                {
                    通道 = 跑程序通道C.从当前进程();          // 自检这条腿:就地再起一份自己(hbcc --跑程序服务)
                    var 机 = new 跨进程虚拟机C(通道) { 输出目标 = _ => { }, 输入源 = () => null };
                    会话.虚拟机 = 机;
                }
                else 会话.虚拟机.输出目标 = _ => { };

                会话.装载(编译);
                int 按数 = 0, 带源码行 = 0, 带变量 = 0, 最深栈 = 0;
                var 签名 = new List<string>();
                var 秒表 = System.Diagnostics.Stopwatch.StartNew();
                while (!会话.已停机 && 按数 < 300)
                {
                    var 一步 = 会话.逐步一次();
                    按数++;
                    if (一步.源码行 > 0) 带源码行++;
                    if (一步.变量.Count > 0) 带变量++;
                    最深栈 = Math.Max(最深栈, 会话.调用栈.调用处地址.Count);
                    签名.Add($"{一步.源码行}/{会话.调用栈.调用处地址.Count}/{一步.调用帧.Count}/{一步.变量.Count}/" +
                        $"{一步.调用处行.Length}/{记账指纹(一步.寄存器说明)}");
                }
                秒表.Stop();
                double 毫秒 = 秒表.Elapsed.TotalMilliseconds;
                // 还没停机就"继续"一把:这条路上是**一次过线跑掉一大段**,记账全靠带回来的表 + 尾部轨迹重放
                if (!会话.已停机)
                {
                    var 末 = 会话.继续();
                    签名.Add($"继续/{会话.调用栈.调用处地址.Count}/{末.调用帧.Count}/-/-/{记账指纹(会话.寄存器说明.全部)}");
                }
                return (按数, 会话.已执行步数, 带源码行, 带变量, 最深栈, 会话.已停机,
                    按数 > 0 ? 毫秒 * 1000 / 按数 : 0, string.Join("|", 签名), 通道?.后端说明 ?? "(进程内)");
            }
            finally { 通道?.Dispose(); }
        }

        /// <summary>
        /// H39-2:一份"寄存器说明"的短指纹(16 格里每一格的说明 / 源码行 / 变量名 / 登记时帧指针)。
        /// 自检报告里只留指纹 —— 把 16 条说明整篇灌进报告就成了"整篇 dump"。
        /// </summary>
        private static string 记账指纹(寄存器记录C?[] 说明) =>
            清单指纹(说明.Select((记, 号) => 记 == null
                ? $"{号}:"
                : $"{号}:{记.说明}/{记.源码行}/{记.变量名}/{记.登记时帧指针:X}"));
    }
