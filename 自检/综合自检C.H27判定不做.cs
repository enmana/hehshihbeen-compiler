using System;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// H27(**第301批:判定不做**)的钉子:IDE 的源码断点**不往机器码里注入 `断点` 指令**,
    /// 照旧走"断点表只记源码位置(`文件` + `行` + `条件`)+ 编译后用 `断点表C.算地址(调试文件表)` 现算地址"。
    ///
    /// 为什么留这一组(理由与实测见 `未做任务清单.md` §9 H27、`任务清单.md` 三百零一):这条待办看着只是
    /// "换个实现",实际要付三笔代价 ——
    ///   ① 下 / 取消一处断点都得**重新编译**(现在是换一张断点表就行,停机现场新加断点按「继续」照样停得住);
    ///   ② `断点` 是**代码里的指令**(P14),裸虚拟机执行到它就停(自检组 `断点指令` 钉着),
    ///      要让它服务源码断点,只能改它的语义(语言面"只加不改")或者让打包 / 执行多走一次"不带断点"的编译;
    ///   ③ 换来的收益很窄 —— 编辑器侧**已经没有汇编单步**(第158批 C23 起逐步只按源码行走),
    ///      `Sample\**` 里真写 `断点` 的地方 **0 处**(只有两处注释提到它)。
    ///
    /// 三条都钉在**行为面**(不读源码文本,按 T22 的口径不是接线哨兵)。谁真要把断点编译进机器码,
    /// 先让这三条红 —— 那时再回 `未做任务清单.md` 重新拍板,而不是"改着改着顺手换了机制"。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary> 一份够用的样本:第 2 行与第 4 行都是有指令、能下断点的行(取法同 `断点继续自检`) </summary>
        private const string H27样本源 = "var 计数 = 1;\n计数 = 计数 + 1;\nbyte n = 42;\n测试输出(计数);\n停止";

        private static void H27判定不做自检()
        {
            var 编译 = new 汇编器C().汇编多文件带调试([("主程序.hb", H27样本源)]);
            var 表 = 编译.调试文件表;

            // ① 断点**不是机器码里的一条指令**:源码里没写 `断点` 的程序,就算工程里挂着一堆断点,
            //    裸虚拟机也一路跑到停机(断点只在调试会话的地址集合里,虚拟机根本不认识它)。
            var 挂着断点 = new 断点表C();
            挂着断点.切换("主程序.hb", 2);
            挂着断点.切换("主程序.hb", 4);
            var 裸机 = new 虚拟机C();
            裸机.装载(编译.机器码);
            裸机.运行(编译.机器码);
            记录("H27 判定不做 断点不是机器码里的一条指令(挂着断点也一路跑到停机)",
                裸机.停机 && !裸机.命中断点,
                $"停机={裸机.停机} 命中={裸机.命中断点};断点表={挂着断点.摘要()} —— 虚拟机不认识断点表");

            // ② 换断点表**不用重新编译**:同一份机器码上,先后两张断点表都算得出各自的地址,
            //    而且这一路机器码一个字节没变(注入式实现会在这里红:新断点要求重编才生效)。
            var 机器码快照 = (byte[])编译.机器码.Clone();
            var 左表 = new 断点表C();
            左表.切换("主程序.hb", 2);
            int 左址 = 断点表C.算某行地址(表, "主程序.hb", 2) ?? -1;
            var 右表 = new 断点表C();
            右表.切换("主程序.hb", 4);
            int 右址 = 断点表C.算某行地址(表, "主程序.hb", 4) ?? -1;
            记录("H27 判定不做 换断点表不用重编译(同一份机器码上两张表都算得出地址)",
                左址 >= 0 && 右址 >= 0 && 左址 != 右址 && 机器码快照.SequenceEqual(编译.机器码),
                $"第2行=0x{左址:X} 第4行=0x{右址:X};机器码 {机器码快照.Length} 字节逐字节没变");

            // ③ 断点持久化**只有源码位置**:`断点.hbd` 里存的是文件 + 行 + 条件,没有地址、没有机器码 ——
            //    所以"重编之后断点还在原地"是靠"位置不变 + 地址重算"做到的,不是靠把地址写下来。
            var 存档 = new 断点表C();
            存档.切换("主程序.hb", 2);
            存档.设置条件("主程序.hb", 2, "计数 == 2");
            string 文本 = 存档.到文本();
            var 读回 = 断点表C.从文本(文本);
            记录("H27 判定不做 断点持久化只有源码位置(文件 + 行 + 条件,没有地址)",
                读回.个数 == 1 && 读回.断点[0].行 == 2 && 读回.取条件("主程序.hb", 2) == "计数 == 2"
                && !文本.Contains("地址", StringComparison.Ordinal)
                && !文本.Contains("机器码", StringComparison.Ordinal)
                && !文本.Contains("0x", StringComparison.Ordinal),
                $"存档 {文本.Replace("\r", "").Replace("\n", " ").Trim()} —— 位置存档,地址每次编译现算");
        }
    }
}
