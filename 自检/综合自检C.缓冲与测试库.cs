using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 缓冲与测试库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 缓冲路径 = Path.Combine(库目录, "缓冲.hb").Replace('\\', '/');
            string 测试路径 = Path.Combine(库目录, "测试助手.hb").Replace('\\', '/');
            string 错误路径 = Path.Combine(库目录, "错误.hb").Replace('\\', '/');
            if (!File.Exists(缓冲路径) || !File.Exists(测试路径) || !File.Exists(错误路径))
            {
                跳过("缓冲与测试库 定位 Sample\\库 下三个库", $"找不到 {缓冲路径} / {测试路径} / {错误路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{缓冲路径}\"\n包含 \"{测试路径}\"\n包含 \"{错误路径}\"\n";

            // 真编真跑:输出按 UTF-8 收、行尾换成 `|`(与别的库分组同一套跑法)
            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C();
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            // 真编真跑 + **量池水位**:池区 + 空闲区里最后一个非零字节,减掉池首 = 池用了多少字节
            static (string 输出, int 池水位) 跑看池(string 源)
            {
                int 内存 = 虚拟机C.默认内存大小;
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小, 内存, 32 * 1024);
                var vm = new 虚拟机C();
                vm.设内存大小(内存);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                var 表 = 内存布局C.算表(编译, 内存);
                var 池 = 表.First(x => x.区名 == "池");
                int 尾 = 池.起始;
                void 扫(int 起, int 止) { for (int i = 起; i < 止 && i < vm.内存.Length; i++) if (vm.内存[i] != 0) 尾 = i + 1; }
                扫(池.起始, 池.末尾);
                var 空闲 = 表.FirstOrDefault(x => x.区名 == "空闲");   // 池长大了就长进空闲区,一并扫
                if (空闲.区名 != null) 扫(空闲.起始, 空闲.末尾);
                return (缓冲.ToString().Trim().Replace("\n", "|"), 尾 - 池.起始);
            }

            // 对拍说明:哪一条对不上,一眼看得见
            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return "一字不差";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // ---- ① 缓冲:加 / 加字符 / 加整数 / 加行 / 取值 / 重置,与 .NET 算的字节数逐行对拍 ----
            try
            {
                (string 段, bool 是整数, int 值)[] 表 =
                [
                    ("左", false, 0), ("ab", false, 0), ("", false, 0), ("汉字", false, 0),
                    ("", true, 0), ("", true, 42), ("", true, -7), ("", true, 2147483647), ("", true, int.MinValue),
                    ("尾", false, 0),
                ];
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append("地址 本 = 缓冲.建(64);\n输出行(缓冲.容量(本));\n");
                期望.Append("64").Append('|');                       // 容量
                int 已用 = 0;
                int 序号 = 0;
                foreach (var (段, 是整数, 值) in 表)
                {
                    序号++;
                    string 变 = $"段{序号}";
                    源.Append($"字符串 {变} = \"{段}\";\n");
                    string 调用 = 是整数 ? $"缓冲.加整数(本, {字面(值)})" : $"缓冲.加(本, {变})";
                    源.Append($"输出行({调用});\n");
                    已用 += 是整数 ? Encoding.UTF8.GetByteCount(值.ToString()) : Encoding.UTF8.GetByteCount(段);
                    期望.Append(已用).Append('|');
                }
                源.Append("输出行(缓冲.加字符(本, 'Z'));\n");
                已用 += 1;
                期望.Append(已用).Append('|');
                源.Append("字符串 空串 = \"\";\n输出行(缓冲.加行(本, 空串));\n");
                已用 += 1;                                            // 只多一个换行
                期望.Append(已用).Append('|');
                源.Append("输出行(缓冲.字节数(本));\n输出行(缓冲.剩余(本));\n输出行(缓冲.容量(本));\n");
                期望.Append(已用).Append('|').Append(64 - 已用).Append('|').Append(64).Append('|');
                // 取值:拼出来的字节要与 C# 那边逐字节一样(逐字节比 → 转成十六进制看,免得打印控制字符)
                // `输出(文字)` 打的是**这个字本身**(而 `输出(字符)` 打的是它的码)——所以直接比"整段文字"
                源.Append("字符串 全 = 缓冲.取值(本);\n输出行(全.长度());\n输出(全);\n输出行(\"看看尾\");\n");
                string 拼出 = string.Concat(表.Select(x => x.是整数 ? x.值.ToString() : x.段)) + "Z\n";
                期望.Append(拼出.Length).Append('|').Append(拼出.Replace("\n", "|")).Append("看看尾").Append('|');
                源.Append("输出行(缓冲.重置(本));\n输出行(缓冲.字节数(本));\n停止\n");
                期望.Append("1").Append('|').Append("0");
                string 实 = 跑(源.ToString());
                string 期 = 期望.ToString();
                记录("缓冲与测试库 缓冲:加 / 加字符 / 加整数 / 加行(含 UTF-8 多字节与 32 位边界)+ 取值逐字符对拍 + 重置",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 缓冲 行为对拍", ex); }

            // ---- ② 缓冲:装不下给 -1,而且**一个字节都不写进去**;容量最小是 16 ----
            try
            {
                const string 源 = "地址 小 = 缓冲.建(4);\n" +
                    "输出行(缓冲.容量(小));\n" +
                    "字符串 十六 = \"0123456789abcdef\";\n" +
                    "输出行(缓冲.加(小, 十六));\n" +
                    "输出行(缓冲.剩余(小));\n" +
                    "字符串 内容 = \"还不下\";\n" +
                    "输出行(缓冲.加(小, 内容));\n" +
                    "输出行(缓冲.加整数(小, 7));\n" +
                    "输出行(缓冲.加字符(小, 'x'));\n" +
                    "输出行(缓冲.加行(小, 内容));\n" +
                    "输出行(缓冲.字节数(小));\n" +
                    "字符串 看 = 缓冲.取值(小);\n输出行(看);\n停止\n";
                记录("缓冲与测试库 缓冲:容量最小 16;装满后 加 / 加整数 / 加字符 / 加行 一律 -1,且盘上字节数不动",
                    跑(头 + 源) == "16|16|0|-1|-1|-1|-1|16|0123456789abcdef",
                    "期望 16|16|0|-1|-1|-1|-1|16|0123456789abcdef");
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 缓冲 装不下那一档", ex); }

            // ---- ③ **判据那一条**:缓冲治池 —— 同样拼 2000 行,量两边的池水位 ----
            try
            {
                const int 行数 = 2000;
                string 缓冲源 = 头 +
                    "地址 本 = 缓冲.建(65536);\n" +
                    "整数 i = 0;\n" +
                    "当 (i < " + 行数 + ")\n{\n" +
                    "    缓冲.加(本, \"第 \");\n" +
                    "    缓冲.加整数(本, i);\n" +
                    "    缓冲.加行(本, \" 行的内容\");\n" +
                    "    i = i + 1;\n}\n" +
                    "输出行(缓冲.字节数(本));\n停止\n";
                // 朴素那条路要 `格式化` 把数字变文字 —— 那需要 `string.hb` 的 `转字符串`(语言口径),
                // 所以这一份多包含一个 string.hb(两边都拿"正常写法",比出来才公平)
                string 朴素源 = 头 + $"包含 \"{Path.Combine(库目录, "string.hb").Replace('\\', '/')}\"\n" +
                    "字符串 结果 = \"\";\n" +
                    "整数 i = 0;\n" +
                    "当 (i < " + 行数 + ")\n{\n" +
                    "    字符串 一行 = 格式化(\"第 {0} 行的内容\\n\", i);\n" +
                    "    拼接到(结果, 一行);\n" +
                    "    i = i + 1;\n}\n" +
                    "输出行(结果.长度());\n停止\n";
                var (缓冲出, 缓冲池) = 跑看池(缓冲源);
                var (朴素出, 朴素池) = 跑看池(朴素源);
                bool 都跑完 = !缓冲出.Contains('⚠') && !朴素出.Contains('⚠');
                记录("缓冲与测试库 缓冲治池(批 2 的判据):同样拼 " + 行数 + " 行,缓冲那条路拼的过程中池几乎不动(量池水位,不与死数比)",
                    都跑完 && 缓冲池 * 2 < 朴素池,
                    $"缓冲:池水位 {缓冲池} 字节(输出 {缓冲出});每轮 `格式化` + `拼接到`:池水位 {朴素池} 字节(输出 {朴素出})");
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 缓冲治池", ex); }

            // ---- ④ 测试助手:表相等 / 表近似 / 近似 / 字符串包含 / 表文字,与 .NET 算的期望逐行比 ----
            try
            {
                int[] 表左 = [3, 1, 4, 1], 表右 = [3, 1, 4, 1], 表异 = [3, 1, 4, 2], 短 = [3, 1, 4];
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                void 表声明(string 名, int[] 值) =>
                    源.Append($"整数 {名}[{值.Length}] = [{string.Join(", ", 值.Select(字面))}];\n");
                表声明("表左", 表左); 表声明("表右", 表右); 表声明("表异", 表异); 表声明("短", 短);
                void 比(string 调用, bool 结果)
                {
                    源.Append($"输出行({调用});\n");
                    期望.Append(结果 ? 1 : 0).Append('|');
                }
                比("测试助手.表相等(表左, 表右)", 表左.SequenceEqual(表右));
                比("测试助手.表相等(表左, 表异)", 表左.SequenceEqual(表异));
                比("测试助手.表相等(表左, 短)", 表左.SequenceEqual(短));
                比("测试助手.表近似(表左, 表异, 1)", 表左.Zip(表异).All(p => Math.Abs(p.First - p.Second) <= 1));
                比("测试助手.表近似(表左, 表异, 0)", 表左.Zip(表异).All(p => Math.Abs(p.First - p.Second) <= 0));
                比("测试助手.表近似(表左, 短, 9)", false);
                比("测试助手.表近似(表左, 表异, -1)", false);
                比("测试助手.近似(10, 12, 2)", Math.Abs(10 - 12) <= 2);
                比("测试助手.近似(10, 12, 1)", Math.Abs(10 - 12) <= 1);
                比("测试助手.近似(0 - 2147483647 - 1, 2147483647, 0)", false);
                比("测试助手.字符串包含(\"报告:合计 3\", \"合计\")", true);
                比("测试助手.字符串包含(\"报告:合计 3\", \"没有\")", false);
                比("测试助手.字符串包含(\"报告\", \"\")", true);
                比("测试助手.字符串包含(\"\", \"x\")", false);
                源.Append("输出行(测试助手.表文字(表左));\n输出行(测试助手.表文字(短));\n");
                期望.Append('[').Append(string.Join(", ", 表左)).Append(']').Append('|');
                期望.Append('[').Append(string.Join(", ", 短)).Append(']');
                源.Append("停止\n");
                string 实 = 跑(源.ToString());
                string 期 = 期望.ToString();
                记录("缓冲与测试库 测试助手:表相等 / 表近似 / 近似(含负容差)/ 字符串包含(含空串)/ 表文字,与 .NET 逐点对拍",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 测试助手 对拍", ex); }

            // ---- ⑤ 错误:21 个状态码的值**逐个与 `宿主能力C` 的常量比**(真编真跑打印出来比) ----
            try
            {
                (string 名, int 值)[] 码表 =
                [
                    ("无错", 宿主能力C.状态_成功), ("没挂能力", 宿主能力C.状态_没挂能力),
                    ("打不开", 宿主能力C.状态_打不开), ("放不下", 宿主能力C.状态_放不下),
                    ("读写失败", 宿主能力C.状态_读写失败), ("参数不合法", 宿主能力C.状态_参数不合法),
                    ("不在白名单", 宿主能力C.状态_不在白名单), ("超时", 宿主能力C.状态_超时),
                    ("退出码非零", 宿主能力C.状态_退出码非零), ("目录不空", 宿主能力C.状态_目录不空),
                    ("已经存在", 宿主能力C.状态_已经存在), ("不是目录", 宿主能力C.状态_不是目录),
                    ("到末尾", 宿主能力C.状态_到末尾), ("连不上", 宿主能力C.状态_连不上),
                    ("网络超时", 宿主能力C.状态_网络超时), ("响应出错", 宿主能力C.状态_响应出错),
                    ("网址不在白名单", 宿主能力C.状态_网址不在白名单), ("协议不支持", 宿主能力C.状态_协议不支持),
                    ("句柄无效", 宿主能力C.状态_句柄无效), ("流太多", 宿主能力C.状态_流太多),
                    ("任务太多", 宿主能力C.状态_任务太多),
                ];
                var 源 = new StringBuilder(头);
                源.Append("输出行(错误.无错);\n");       // hmm:一条条打
                foreach (var (名, _) in 码表.Skip(1)) 源.Append($"输出行(错误.{名});\n");
                源.Append("输出行(错误.是否成功(0));\n输出行(错误.是否成功(2));\n");
                源.Append("输出行(错误.说明(99));\n输出行(错误.说明(0 - 5));\n");
                源.Append("输出行(错误.说明(2));\n输出行(错误.说明(0));\n");
                源.Append("停止\n");
                string 实 = 跑(源.ToString());
                string 期 = string.Join("|", 码表.Select(x => x.值))
                    + "|1|0|未知状态码(99)|未知状态码(-5)|"
                    + "打不开:文件 / 目录不在,或者路径上缺目录|成功(没有出错)";
                记录("缓冲与测试库 错误:21 个状态码逐个与 `宿主能力C` 的常量对上(真编真跑打印出来比)+ 是否成功 / 说明(含认不出的码)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 错误 状态码表", ex); }

            // ---- ⑥ 接线哨兵:三个库都在位、五段头注释齐、头注释说的函数条数对得上 ----
            try
            {
                string 缓冲源 = File.ReadAllText(缓冲路径), 测试源 = File.ReadAllText(测试路径), 错误源 = File.ReadAllText(错误路径);
                记录("缓冲与测试库 接线哨兵:三个库都在 Sample\\库 下、五段头注释齐、头注释里的函数条数与正文对得上",
                    模块名齐(缓冲源, "缓冲") && 模块名齐(测试源, "测试助手") && 模块名齐(错误源, "错误")
                    && 缓冲源.Contains("提供的函数(11 个)", StringComparison.Ordinal)
                    && 测试源.Contains("提供的函数(5 个)", StringComparison.Ordinal)
                    && 错误源.Contains("21 个公开整数 + 2 个函数", StringComparison.Ordinal)
                    && 五段齐(缓冲源) && 五段齐(测试源) && 五段齐(错误源)
                    && 方法数(缓冲源) == 11 && 方法数(测试源) == 5 && 方法数(错误源) == 2,
                    $"公开方法:缓冲 {方法数(缓冲源)} / 测试助手 {方法数(测试源)} / 错误 {方法数(错误源)}");

                static bool 模块名齐(string 源, string 名) => 源.Contains("模块 " + 名, StringComparison.Ordinal);
                static bool 五段齐(string 源) =>
                    源.Contains("口径(2026-", StringComparison.Ordinal)
                    && 源.Contains("英文对照", StringComparison.Ordinal)
                    && 源.Contains("复杂度:", StringComparison.Ordinal)
                    && 源.Contains("边界(如实登记", StringComparison.Ordinal);
                static int 方法数(string 源) =>
                    System.Text.RegularExpressions.Regex.Matches(源, @"(?m)^方法 ").Count;
            }
            catch (Exception ex) { 记录异常("缓冲与测试库 接线哨兵", ex); }
        }

        // 把 `-2147483648` 写成一条减法(字面量超出 `整数` 的正数范围)
        private static string 字面(int 数) => 数 == int.MinValue ? "(0 - 2147483647 - 1)" : 数.ToString();
    }
