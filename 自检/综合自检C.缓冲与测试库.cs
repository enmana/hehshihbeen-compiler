// 缓冲 / 测试助手 / 错误 三个库的自检(G4 批 2,第345批)
//   —— `Sample\库\缓冲.hb` · `Sample\库\测试助手.hb` · `Sample\库\错误.hb`
//
//   判据照 `基础库施工计划.md` §2 批 2 那一行:
//     "`断言相等/近似/包含` 真跑;缓冲治 32KB 池(**实测拼 N 次不炸池**)"。
//   这一组就这么验:
//     · 缓冲 / 测试助手 的期望值**由 .NET 现场算**(UTF-8 字节数、拼接结果、表比、容差),
//       真编真跑逐行比 —— 不手抄一串数当基准;
//     · **"治池"那一条是量出来的**:同样拼 2000 行,"缓冲"那条路与
//       "每轮 `格式化` 再 `拼接到`"那条路各跑一遍,拿**池水位**(池区 + 空闲区里最后一个非零字节)
//       对着比 —— 缓冲那条路拼的过程中池几乎不动,另一条一路往上涨;
//     · 错误库的 21 个状态码**逐个与 `宿主能力C` 的 常量比**(真编真跑打印出来比,不是读源码文本)。
