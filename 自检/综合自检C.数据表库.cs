// ============================================================
// 数据表库的自检(G3 域 4,第342批)—— `Sample\库\数据表.hb`
//
//   域 4 拍板取 **c**:SQL 那半(打开库 / 执行语句 / 取一行 / 事务,号段 `30~33`)**判定不做、留号**,
//   本域交付 = **文件型定长记录表**(定长记录 + 4 字节主键,只用现有文件能力与 G3 流)。
//   这一组钉的是**库本身**的行为(纯 HB,不动 ISA / 关键字 / 语言面):
//     · 建表 / 追加 / 记录数 / 总字节数;
//     · **记录长按字节算** + **长度不对就拒收**(表里不出现半条);
//     · 取记录(按序号)/ 按主键取(4 字节键,从头扫);
//     · 拉模式遍历(开始遍历 / 下一条 / 结束遍历);
//     · 字节级助手(字节长 / 取字节段 / 补足);
//     · 失败路(打不开的表 / 越界 / 键长不对 / 主键偏移越界)一律给 -1 或空串。
//
//   两条**本批实测出来**的口径也钉在这儿(它们是这一库为什么长这样):
//     · **`打开写流` 一开就把文件清空**(C# 宿主 `FileMode.Create` / C 后端 `"wb"`):
//       16 字节的文件打开写流、只写 4 字节 ⇒ 盘上只剩 4 字节,旧尾巴没了
//       ⇒ "接到表尾"只能靠 `追加写文件`(所以库的 `追加` 走它);
//     · **`.长度()` 数的是"文字"不是"字节"**:`左右ab` 的 `.长度()` 是 4,而它占 8 字节
//       ⇒ 定长记录一律按**字节**算,库自带 `字节长` / `取字节段`。
//
//   真盘那一半在 `工具\临时\数据表库自检_<Guid8>` 里真建真写真读,跑完由 C# 侧收尾删干净
//   (用 Guid 不用进程号:进程号会回收,上一趟留下的目录会被下一趟撞上)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 数据表库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 库路径 = Path.Combine(库目录, "数据表.hb").Replace('\\', '/');
            if (!File.Exists(库路径))
            {
                跳过("数据表库 定位 Sample\\库\\数据表.hb", $"找不到 {库路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{库路径}\"\n";

            // 真编真跑一趟(输出按 UTF-8 收、行尾换成 `|`,与目录库那一组同一套跑法)
            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };   // 建目录 / 追加写文件 / 打开读流 要挂宿主
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            // ---- ① 字节级助手:长度按"文字"、字节按"字节"(整库的地基) ----
            记录("数据表库 字节长 / 取字节段:`长度()` 数是文字(左右ab 给 4),字节长给 8;按字节切片对得上",
                跑(头 + "字符串 混 = \"左右ab\";\n" +
                    "输出行(数据表.字节长(混));\n" +
                    "输出行(混.长度());\n" +
                    "输出行(数据表.字节长(\"abc\"));\n" +
                    "输出行(数据表.字节长(\"\"));\n" +
                    "输出行(数据表.取字节段(\"左右ab\", 0, 3));\n" +
                    "输出行(数据表.取字节段(\"左右ab\", 3, 2));\n" +
                    "输出行(数据表.取字节段(\"左右ab\", 6, 2));\n停止")
                    == "8|4|3|0|左|右|ab",
                 "8 / 4(文字) / 3 / 0 / 左 / 右 / ab");

            // ---- ② 补足:用空格补到正好 N 个字节;超了给空串 ----
            记录("数据表库 补足:7 字节补成 8(补空格)、正好 8 给原样、超了给空串(不截断)",
                跑(头 + "字符串 补足串 = 数据表.补足(\"0004下\", 8);\n测试输出(数据表.字节长(补足串));\n" +
                    "字符串 补足串二 = 数据表.补足(\"0001左 \", 8);\n测试输出(数据表.字节长(补足串二));\n" +
                    "字符串 补足串三 = 数据表.补足(\"0001左  \", 8);\n测试输出(数据表.字节长(补足串三));\n停止")
                    == "8|8|0",
                "补成 8 / 原样 8 / 超了 空串");

            // ---- ③ 建表 + 追加 + 数数 + 总字节(真盘) ----
            string 临时根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"数据表库自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                string 表 = 临时根.Length == 0 ? "" : 临时根 + "/名单.bin";

                记录("数据表库 建表 / 追加 / 记录数 / 总字节数:空表 0 条 0 字节;三条 8 字节 ⇒ 3 条 24 字节,序号 0/1/2",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        $"输出行(建目录(\"{临时根}\"));\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.记录数(表, 8));\n" +
                        "测试输出(数据表.总字节数(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"0001左 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0002右 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0003中 \"));\n" +
                        "测试输出(数据表.记录数(表, 8));\n" +
                        "测试输出(数据表.总字节数(表));\n停止")
                        == "1|1|0|0|0|1|2|3|24",
                    "1|1|0|0|0|1|2|3|24(三条各 8 字节)");

                // ---- ④ 记录长按字节算:长度不对就拒收(不写半条) ----
                记录("数据表库 追加拒收:7 字节(-1)与 9 字节(-1)都进不去;表里仍是 3 条 24 字节(不留半条)",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"0001左 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0004下\"));\n" +      // 7 字节
                        "测试输出(数据表.追加(表, 8, \"0001左  \"));\n" +    // 9 字节
                        "测试输出(数据表.记录数(表, 8));\n" +
                        "测试输出(数据表.总字节数(表));\n停止")
                        == "1|0|-1|-1|1|8",
                    "1|0|-1|-1|1|8(只有第一条进去,盘上正好 8 字节)");

                // ---- ⑤ 取记录:按序号(返回字符串);越界 / 负数 / 记录长不是 8 给空串 ----
                记录("数据表库 取记录:第 0 条取得到、越界(4)/ 负数(-1)/ 记录长 4(本库定长是 8)一律给空串",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"0001左 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0002右 \"));\n" +
                        "输出行(数据表.取记录(表, 0, 8));\n" +
                        "输出行(数据表.取记录(表, 1, 8));\n" +
                        "字符串 越 = 数据表.取记录(表, 4, 8);\n测试输出(越.长度());\n" +
                        "字符串 负 = 数据表.取记录(表, -1, 8);\n测试输出(负.长度());\n" +
                        "字符串 零 = 数据表.取记录(表, 0, 16);\n测试输出(零.长度());\n停止")
                        == "1|0|1|0001左 |0002右 |0|0|0",
                    "1|0|1|0001左 |0002右 |0|0|0(整条 8 字节,末尾那个空格也在;后三个 0 = 空串)");

                // ---- ⑥ 按主键取:4 字节键、偏移 0 与偏移 4 两档都认;键长不对 / 偏移越界给空串 ----
                记录("数据表库 按主键取:偏移 0(前 4 字节)与偏移 4(后 4 字节)两档都找得到;没有 / 键不是 4 字节 / 偏移越界给空串",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"AAAA0001\"));\n" +
                        "测试输出(数据表.追加(表, 8, \"BBBB0002\"));\n" +
                        "输出行(数据表.按主键取(表, 8, 0, \"BBBB\"));\n" +
                        "输出行(数据表.按主键取(表, 8, 4, \"0001\"));\n" +
                        "字符串 没 = 数据表.按主键取(表, 8, 0, \"ZZZZ\");\n测试输出(没.长度());\n" +
                        "字符串 短 = 数据表.按主键取(表, 8, 0, \"AAA\");\n测试输出(短.长度());\n" +
                        "字符串 越 = 数据表.按主键取(表, 8, 6, \"AAAA\");\n测试输出(越.长度());\n停止")
                        == "1|0|1|BBBB0002|AAAA0001|0|0|0",
                    "BBBB0002 / AAAA0001 / 空 / 空 / 空");

                // ---- ⑦ 拉模式遍历:一条一条读到空串为止;结束遍历之后一律空串 ----
                记录("数据表库 遍历:开始遍历后下一条逐条给整条记录,读完给空串;结束遍历之后再问还是空串",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"0001左 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0002右 \"));\n" +
                        "测试输出(数据表.开始遍历(表) > 0);\n" +
                        "字符串 这条 = 数据表.下一条(8);\n" +
                        "当 (这条 != \"\")\n{\n    输出行(这条);\n    这条 = 数据表.下一条(8);\n}\n" +
                        "测试输出(数据表.结束遍历());\n" +
                        "字符串 完 = 数据表.下一条(8);\n测试输出(完.长度());\n停止")
                        == "1|0|1|1|0001左 |0002右 |1|0",
                    "两条按序读出 + 结束遍历 1 + 读完空串");

                // ---- ⑧ 建表 = 清空:建过的表再建一次就回到 0 条 ----
                记录("数据表库 建表即清空:写满三条再建一次表 ⇒ 记录数与总字节数都回 0",
                    临时根.Length > 0 && 跑(头 + $"字符串 表 = \"{表}\";\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.追加(表, 8, \"0001左 \"));\n" +
                        "测试输出(数据表.追加(表, 8, \"0002右 \"));\n" +
                        "测试输出(数据表.记录数(表, 8));\n" +
                        "输出行(数据表.建表(表));\n" +
                        "测试输出(数据表.记录数(表, 8));\n" +
                        "测试输出(数据表.总字节数(表));\n停止")
                        == "1|0|1|2|1|0|0",
                    "1|0|1|2|1|0|0(再建一次回到空表)");

                // ---- ⑨ 失败那条路:打不开的表一律 -1 / 空串(不报错、不停机) ----
                记录("数据表库 打不开的表:记录数 / 总字节数 给 -1,取记录 / 按主键取 给空串",
                    临时根.Length > 0 && 跑(头 + $"字符串 没有 = \"{临时根}/没有这个.bin\";\n" +
                        "测试输出(数据表.记录数(没有, 8));\n" +
                        "测试输出(数据表.总字节数(没有));\n" +
                        "字符串 取 = 数据表.取记录(没有, 0, 8);\n测试输出(取.长度());\n" +
                        "字符串 键 = 数据表.按主键取(没有, 8, 0, \"0001\");\n测试输出(键.长度());\n停止")
                        == "-1|-1|0|0",
                    "-1 / -1 / 空 / 空");

                // ---- ⑩ `打开写流` 一开就清空这件事:**真编真跑**(第343批从"按源码钉"改成真跑) ----
                //   第342批登记过一条"`打开写流` 在自检马车里不清空已存在的文件"的缺陷 ——
                //   **那是误判**:第343批照那份最小复现把两种跑法各跑了一遍,两处都是清空的
                //   (真根因是 **C 后端 `开流` 多抬了一次版本**,与宿主层 `打开写流` 无关;
                //   复现 / 定位 / 修法见 `未做任务清单.md`《◆ 已收口:`打开写流` 那条是误判…》)。
                //   既然跑法不背这个锅,这条口径就照**行为**钉住 —— 它同时是
                //   `数据表.hb` 头注释里"追加只能靠 `追加写文件`"那条设计地基的证据。
                记录("数据表库 `打开写流` 一开就把文件清空(16 字节 → 只写 4 字节 ⇒ 盘上正好剩 4 字节)",
                    临时根.Length > 0 && 跑($"字符串 数据路径 = \"{临时根}/清空.bin\";\n" +
                        $"输出行(建目录(\"{临时根}\"));\n" +
                        "整数 写 = 0;\n" +
                        "写 = 打开写流(数据路径, 写);\n" +
                        "输出行(写 > 0);\n" +
                        "输出行(写一块(写, \"AAAABBBBCCCCDDDD\", 0));\n" +
                        "输出行(关写流(写));\n" +
                        "写 = 打开写流(数据路径, 写);\n" +
                        "输出行(写 > 0);\n" +
                        "输出行(写一块(写, \"XYZW\", 0));\n" +
                        "输出行(关写流(写));\n" +
                        "字符串 全文 = \"\";\n" +
                        "输出行(读文件(数据路径, 全文, 4096));\n" +
                        "输出行(全文);\n" +
                        "输出行(全文.长度());\n停止")
                        == "1|1|16|0|1|4|0|1|XYZW|4",
                    "1|1|16|0|1|4|0|1|XYZW|4(第二次开流就把那 16 字节截成 0,只写进去的 4 字节留在盘上)");

                // ---- ⑩b 接线哨兵:库自己的写法(`追加` 走 `追加写文件`,读走 `打开读流` + `读一块(…, 8)`) ----
                string 库源 = File.ReadAllText(库路径);
                记接线("数据表库 接线哨兵:`追加` 走 `追加写文件`,读走 `打开读流` + `读一块(…, 8)`",
                    库源.Contains("追加写文件(路径, 记录)", StringComparison.Ordinal)
                    && 库源.Contains("打开读流(路径, 句柄)", StringComparison.Ordinal)
                    && 库源.Contains("读一块(句柄, 块, 8)", StringComparison.Ordinal),
                    "追加走 `追加写文件`;读走 `打开读流` + `读一块(句柄, 块, 8)`");
            }
            finally
            {
                try { if (临时根.Length > 0 && Directory.Exists(临时根)) Directory.Delete(临时根, true); }
                catch { /* 收尾失败不影响判据 */ }
            }

            // ---- ⑪ 两份示例 / 工程在盘上 + 库头注释写清了口径(改了代码忘了改说明就红灯) ----
            string 库文本 = File.ReadAllText(库路径);
            string 示例工程目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "中间层", "示例32_数据表");
            bool 工程齐 = 仓库根 != null
                && File.Exists(Path.Combine(示例工程目录, "主程序.hb"))
                && File.Exists(Path.Combine(示例工程目录, "示例32_数据表.hbp"));
            记录("数据表库 头注释与标准工程:口径(打开写流清空 / 按字节 / 256 / 4 字节主键 / 判定不做留号)写清 + 示例32 在盘上",
                库文本.Contains("文件型定长记录表", StringComparison.Ordinal)
                && 库文本.Contains("一开就把文件清空", StringComparison.Ordinal)
                && 库文本.Contains("按字节算", StringComparison.Ordinal)
                && 库文本.Contains("256", StringComparison.Ordinal)
                && 库文本.Contains("主键固定 4 字节", StringComparison.Ordinal)
                && 库文本.Contains("判定不做", StringComparison.Ordinal)
                && 库文本.Contains("30~33", StringComparison.Ordinal)
                && 工程齐,
                $"口径逐条在 = 见判据;示例32 {(工程齐 ? "齐" : "缺")}");
        }
    }
}
