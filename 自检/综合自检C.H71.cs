// ============================================================
// H71(第352批收口):**"算地址那一段会调函数"时,赋值右边算出来的值必须先落槽**
//
//   这一条是**编译器**的修复自检(不在任何库里),所以单列一组,名字走 `H71`。
//
//   **原来登记的 H71**(`未做任务清单.md` §0 六档 / §9)写的是"程序一长,前面算好的
//   '数组参数写出'结果就变了",当时**根因未定位**,只留下两件复现件;本批把根因抓出来了:
//
//     **谁**:`记录[下标] = 值` 这一条赋值(`中间层C.表达式工具.cs` 的赋值那一段)
//     **怎么坏**:右边先算进一个临时寄存器 → 再算左边的地址(下标表达式)**那一段里可能调函数**
//       → `CALL` 会把寄存器池整个冲一遍(被调方拿它们当草稿)→ 最后 `存字索引` 用的是**被冲掉之后的残值**。
//     **20 行最小复现**(修前 `--no-opt` 下**必现**,开着优化时恰好被优化器盖住):
//       ```
//       整数 表[4];
//       方法 尾(整数 首, 整数 用了, 整数 表长) 返回 整数 { 返回 首 + 用了; }
//       表[尾(0, 0, 4)] = 10;
//       输出行(表[0]);            // 修前打 0(写进去的是被冲掉的值),修后打 10
//       ```
//       更直观的一份:三个下标各写 10 / 20 / 30,修前读回来是**下标自己**(0 / 1 / 2)。
//
//     **修法**:与"二元运算右边要调函数时左边先躲进槽"**同一条尺子**(那是第97批批 13 抓的)——
//       赋值那一侧原来漏了这一句。现在:算地址那一段含调用 ⇒ 值先落临时槽,等地址算完、临到存那一步
//       再读回寄存器。三个落点各补一处:`试发存字索引` / `链写`(老路那条 `间接写` 之前) /
//       `写数组元素`。判据用**文本里有没有调用写法**(`文本含调用`,宁可多存一次,不能漏)。
//
//   ★ 这一组钉四件事(三条行为 + 一条接线哨兵):
//     ① **最小复现**:`表[尾(0,0,4)] = 10` 这一份 20 行程序,优化**开 / 关两档**都要逐条对;
//     ② **同族五个形状**:数组 + 调用下标 / 右边也是调用 / 结构里的定长数组字段 /
//        动态列表元素 / 多维数组元素 —— 每一条都真编真跑对输出;
//     ③ **优化开 / 关一致**:同一份源码两档跑出来**逐字一样**(不许"开着对、关着错");
//     ④ **接线哨兵**:那两处修复还在源码里(`算址含调用` / `链地址含调用`)——
//        只钉"还在不在",不许单独当正确性证据。
//
//   ★ **这条自检为什么能钉住它**:修前 ①②③ 全红(实测量过 —— 20 行那份在 `--no-opt` 下打 0),
//     修后全绿;`优化开/关一致` 那一条是**必须的**,因为开着优化时这个 bug 会被优化器掩盖
//     (C3 那份探针修前"只跑 --run 是绿的"),只跑默认档会漏掉。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void H71数组赋值自检()
        {
            // 修前的最小复现(20 行):三格分别写 10 / 20 / 30,读回来必须是 10 / 20 / 30
            const string 最小复现源 =
                "整数 表[4];\n" +
                "\n" +
                "方法 尾(整数 首, 整数 用了, 整数 表长) 返回 整数\n" +
                "{\n" +
                "    整数 结果 = 首 + 用了;\n" +
                "    如果 (结果 >= 表长)\n" +
                "    {\n" +
                "        结果 = 结果 - 表长;\n" +
                "    }\n" +
                "    返回 结果;\n" +
                "}\n" +
                "\n" +
                "表[尾(0, 0, 4)] = 10;\n" +
                "表[尾(0, 1, 4)] = 20;\n" +
                "表[尾(0, 2, 4)] = 30;\n" +
                "输出行(表[0]);\n" +
                "输出行(表[1]);\n" +
                "输出行(表[2]);\n" +
                "输出行(表[3]);\n" +
                "停止\n";
            const string 最小复现该是 = "10|20|30|0";

            // 同族五个形状:一条语句测一种"算地址那一段会调函数"的落点
            const string 同族源 =
                "方法 找位(整数 值) 返回 整数\n" +
                "{\n" +
                "    返回 值;\n" +
                "}\n" +
                "\n" +
                "结构 架\n" +
                "{\n" +
                "    整数 格[4];\n" +
                "}\n" +
                "\n" +
                "整数 表[4];\n" +
                "架 架子;\n" +
                "整数 袋[2][3];\n" +
                "整数 列[];\n" +
                "\n" +
                "表[找位(2)] = 11;\n" +                                  // ① 数组 + 调用下标
                "表[找位(1)] = 找位(22);\n" +                            // ② 右边也是调用
                "架子.格[找位(3)] = 33;\n" +                             // ③ 结构里的定长数组字段
                "列.添加(0);\n" +
                "列.添加(0);\n" +
                "列[找位(1)] = 44;\n" +                                  // ④ 动态列表元素
                "袋[找位(1)][找位(2)] = 55;\n" +                         // ⑤ 多维数组元素
                "输出行(表[2]);\n" +
                "输出行(表[1]);\n" +
                "输出行(架子.格[3]);\n" +
                "输出行(列[1]);\n" +
                "输出行(袋[1][2]);\n" +
                "输出行(表[0]);\n" +
                "停止\n";
            const string 同族该是 = "11|22|33|44|55|0";

            string 跑一份(string 源, bool 优化)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, 优化,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            string 说明(string 期望, string 实得)
                => 期望 == 实得 ? "一字不差" : $"期望 [{期望}] / 实得 [{实得}]";

            // ── ① 最小复现:优化开 / 关两档都要对 ──
            try
            {
                string 开 = 跑一份(最小复现源, true), 关 = 跑一份(最小复现源, false);
                bool 好 = 开 == 最小复现该是 && 关 == 最小复现该是;
                记录("H71 数组赋值:下标里的函数调用不许冲掉右边算好的值(20 行最小复现,优化开/关两档)",
                    好, $"优化开 [{开}] / 优化关 [{关}](该是 [{最小复现该是}])" +
                        (好 ? ";修前这两档分别打 0|1|2|0 与 0|1|2|0(写进去的是下标自己)" : ""));
            }
            catch (Exception ex) { 记录异常("H71 数组赋值:下标里的函数调用不许冲掉右边算好的值(20 行最小复现,优化开/关两档)", ex); }

            // ── ② 同族五个形状(数组 / 右边也调用 / 结构字段 / 列表元素 / 多维数组)──
            try
            {
                string 实得 = 跑一份(同族源, true);
                记录("H71 数组赋值 同族五个形状:数组 + 调用下标 / 右边也是调用 / 结构里的定长数组字段 / 列表元素 / 多维数组元素",
                    实得 == 同族该是, 说明(同族该是, 实得) +
                        ";这五条分别走 `试发存字索引` / `写数组元素` / `链写`(老路与多维那两条)三个落点");
            }
            catch (Exception ex) { 记录异常("H71 数组赋值 同族五个形状:数组 + 调用下标 / 右边也是调用 / 结构里的定长数组字段 / 列表元素 / 多维数组元素", ex); }

            // ── ③ 优化开 / 关一致(开着对、关着错也算没过)──
            try
            {
                string 开 = 跑一份(同族源, true), 关 = 跑一份(同族源, false);
                记录("H71 数组赋值:优化开 / 关两档逐字一致(修前的形状关掉优化就现形 —— 只跑默认档会漏)",
                    开 == 关 && 开 == 同族该是, $"优化开 [{开}] / 优化关 [{关}]");
            }
            catch (Exception ex) { 记录异常("H71 数组赋值:优化开 / 关两档逐字一致(修前的形状关掉优化就现形 —— 只跑默认档会漏)", ex); }

            // ── ④ 接线哨兵:两处修复还在源码里(只钉"还在不在")──
            const string 接线断言 = "H71 接线:赋值那一侧「算址含调用就先落槽」那三处补读还在";
            try
            {
                string? 根 = 找仓库根目录();
                if (根 == null) { 跳过(接线断言, "找不到仓库根(读不到那两份中间层源码)"); return; }
                string 赋值源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.表达式工具.cs"), Encoding.UTF8);
                string 链源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.引用链.cs"), Encoding.UTF8);
                string 数组源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.结构与引用.cs"), Encoding.UTF8);
                bool 判据 = 赋值源.Contains("算址含调用", StringComparison.Ordinal)
                    && 赋值源.Contains("值槽 = 新临时槽();", StringComparison.Ordinal)
                    && 链源.Contains("链地址含调用", StringComparison.Ordinal)
                    && 链源.Contains("if (值槽 is { } 槽) 发出读变量(源寄存器, 槽);", StringComparison.Ordinal)
                    && 数组源.Contains("地址位置? 值槽 = null", StringComparison.Ordinal);
                记接线(接线断言, 判据,
                    $"赋值那一段的判据 = {赋值源.Contains("算址含调用", StringComparison.Ordinal)};" +
                    $"落槽 = {赋值源.Contains("值槽 = 新临时槽();", StringComparison.Ordinal)};" +
                    $"链地址判据 = {链源.Contains("链地址含调用", StringComparison.Ordinal)};" +
                    $"链写补读 = {链源.Contains("if (值槽 is { } 槽) 发出读变量(源寄存器, 槽);", StringComparison.Ordinal)};" +
                    $"数组元素补读 = {数组源.Contains("地址位置? 值槽 = null", StringComparison.Ordinal)}" +
                    " —— 接线哨兵(读仓库源码文本判的),行为面看上面三条");
            }
            catch (Exception ex) { 记录异常(接线断言, ex); }
        }
    }
}
