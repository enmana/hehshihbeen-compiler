// ============================================================
// H73(第355批收口):**`存字` 的"地址那一段"会调函数时,写进去的值必须先落槽**
//
//   这一条也是**编译器**的修复自检,单列一组,名字走 `H73`。
//
//   **怎么撞上的**:写 `Sample\库\内存流.hb` 的 `写入` 时,那句是 `存字(取据(流), 到哪 * 4, 值);`
//   —— **指针那一格是个函数调用**。结果写进去的是别的数(读回来 3540,该是 333)。
//
//   **最小复现(4 行,`--no-opt` 与默认档都现)**:
//   ```
//   方法 取据(整数 流) 返回 整数 { 返回 取字(流, 0); }
//   整数 流 = 申请(16);
//   存字(流, 0, 申请(32));
//   存字(取据(流), 8, 333);
//   输出行(取字(取据(流), 8));     // 修前:3540;修后:333
//   ```
//
//   **根因**:`生成存字` 按"**值先算、地址后算**"的次序发指令(那条次序本身是对的 ——
//   值里带调用时,后算的地址不会把它冲掉),可**反过来那一半没人管**:
//   **地址里带调用**(指针写成 `取据(流)`、偏移写成 `下一个()`)时,那个 `CALL`
//   会把寄存器池整个冲一遍,值寄存器当场失效 ⇒ 存进去的是残值。
//   与 **H71**(赋值右边算好的值被"下标里的 CALL"冲掉)是**同一条尺子上的两处**。
//
//   **修法**(`中间层C.堆.cs` 的 `生成存字`):判据 `文本含调用(指针文本) || 文本含调用(偏移文本)`
//   ⇒ 值先落临时槽,等 `堆元素地址` 把地址算完、临到 `存字间接` 那一步再读回寄存器。
//   **ISA / 关键字 / 内建 / 机器码一个字没动**;别的路径(`取字` / `申请` / 赋值)一个字没改。
//
//   ★ 这一组钉三件事(两条行为 + 一条接线哨兵):
//     ① **最小复现**:指针里带调用时,写进去的必须是那个值(优化开 / 关两档都对);
//     ② **同族两处**:偏移里带调用也对;`取字` 那一侧本来就只算地址(不受影响,顺带钉住);
//     ③ **接线哨兵**:`生成存字` 里那两句还在。
//
//   ⚠ 为什么值得单列:照堆写数据结构时"指针从函数里拿"是最常见的写法
//     (`存字(取数据(流), 偏移, 值)`),它一坏,所有"自己管缓冲"的库都写不对。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void H73存字自检()
        {
            const string 最小复现源 =
                "方法 取据(整数 流) 返回 整数\n" +
                "{\n" +
                "    返回 取字(流, 0);\n" +
                "}\n" +
                "整数 流 = 申请(16);\n" +
                "存字(流, 0, 申请(32));\n" +
                "存字(取据(流), 8, 333);\n" +
                "输出行(取字(取据(流), 8));\n" +
                "停止\n";

            // 同族:偏移里带调用(值也要跨过那个 CALL);`取字` 那一侧本来就只算地址,顺带钉住
            const string 同族源 =
                "方法 取据(整数 流) 返回 整数\n" +
                "{\n" +
                "    返回 取字(流, 0);\n" +
                "}\n" +
                "方法 偏移(整数 几) 返回 整数\n" +
                "{\n" +
                "    返回 几 * 4;\n" +
                "}\n" +
                "整数 流 = 申请(16);\n" +
                "存字(流, 0, 申请(32));\n" +
                "存字(取据(流), 偏移(2), 444);\n" +
                "输出行(取字(取据(流), 8));\n" +
                "存字(取据(流), 0, 111);\n" +
                "输出行(取字(取据(流), 0));\n" +
                "停止\n";

            string 跑一份(string 源, bool 优化)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, 优化,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            // ── ① 最小复现:指针里带调用 ──
            try
            {
                string 开 = 跑一份(最小复现源, true), 关 = 跑一份(最小复现源, false);
                bool 好 = 开 == "333" && 关 == "333";
                记录("H73 存字:指针里带函数调用时,写进去的必须是那个值(指针从函数里拿那种写法)",
                    好, $"优化开 [{开}] / 优化关 [{关}](该是 [333])" + (好 ? ";修前这两档都是 3540(残值)" : ""));
            }
            catch (Exception ex) { 记录异常("H73 存字:指针里带函数调用时,写进去的必须是那个值", ex); }

            // ── ② 同族两处(偏移里带调用 / `取字` 那一侧不受影响)──
            try
            {
                string 实 = 跑一份(同族源, true);
                记录("H73 存字 同族:偏移里带调用也对,`取字` 那一侧本来就只算地址(不受影响,顺带钉住)",
                    实 == "444|111", $"实得 [{实}](该是 [444|111])");
            }
            catch (Exception ex) { 记录异常("H73 存字 同族:偏移里带调用也对", ex); }

            // ── ③ 接线哨兵 ──
            const string 接线断言 = "H73 接线:`生成存字` 里「地址含调用就先落槽、临到存再读回」那两句还在";
            try
            {
                string? 根 = 找仓库根目录();
                if (根 == null) { 跳过(接线断言, "找不到仓库根(读不到中间层源码)"); return; }
                string 堆源 = File.ReadAllText(Path.Combine(根, "中间层", "中间层C.堆.cs"), Encoding.UTF8);
                bool 判据一 = 堆源.Contains("if (文本含调用(指针文本) || 文本含调用(偏移文本))", StringComparison.Ordinal);
                bool 判据二 = 堆源.Contains("if (值槽 is { } 槽回) 发出读变量(值, 槽回);", StringComparison.Ordinal);
                bool 好 = 判据一 && 判据二;
                记接线(接线断言, 好,
                    $"地址含调用判据 = {判据一};临到存再读回 = {判据二}" +
                    " —— 接线哨兵(读仓库源码文本判的),行为面看上面两条");
            }
            catch (Exception ex) { 记录异常(接线断言, ex); }
        }
    }
}
