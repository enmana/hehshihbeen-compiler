using hehshihbeen_compiler;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 通用化(2026-10):ISA 补**硬件浮点**(单精度)—— `浮点加法`(0x38)~ `整数转浮点`(0x3F) 共 8 条,
    /// 全部借现成的「双寄存器」/「单寄存器」/「双寄存器小立即数」档(**不新加编码格式**)。
    ///
    /// **口径**:一个浮点值就是寄存器里那 32 位 IEEE754 单精度位模式 —— 与 `Sample\库\float32.hb`
    /// 完全一致(那个库一直把位模式放在 `无符号整数` 里算)⇒ 硬件指令与软件库可以互换、可以混用。
    ///
    /// 这个分组钉六件事:
    /// ① **位模式**:`1.5 + 2.25 = 3.75` 这类要**逐位**对(判据就是 IEEE754 的位模式,不是"差不多");
    /// ② **除零不报错**:IEEE754 给 ±Inf / NaN —— 与整数除零那两条(`除法` / `取余`)刻意分开;
    /// ③ **开方**:写 3D 的向量归一化 / 长度要用它(`√2.25 = 1.5`、`√(-1) = NaN`);
    /// ④ **比较**:关系码 6 档 + **无序(NaN)口径**(有序比较一律假、`!=` 给真,IEEE754);
    /// ⑤ **两个转换**:`浮点转整数` 越界 / NaN 给 `0x80000000`、`整数转浮点` 按**有符号**读;
    /// ⑥ **老 56 条一条没改**:这几条住的是空操作码 0x38~0x3F,老指令的字节一个没动。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary>
        /// 浮点自检。**每条指令都用"位模式"断言**,不用近似比较 —— 这个项目的浮点判据一直是
        /// "与 .NET 位模式逐位一致"(`float32.hb` / `float64.hb` 那两批就是这么钉的)。
        /// </summary>
        private static void 硬件浮点自检()
        {
            // 组里凡是"可能抛"的检查都走它:抛了如实记一条 FAIL,不让整组连坐(与 `跑且断言` 同一套)
            void 检查(string 名称, Func<(bool 通过, string 详情)> 试)
            {
                try
                {
                    var (通过, 详情) = 试();
                    记录(名称, 通过, 详情);
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            // 跑一段纯汇编,把 R0 拿回来(浮点指令只能在汇编这一层直接用 —— 语言层的 `浮点` 类型还没接)
            uint 算(string 汇编) => 运行(汇编).寄存器[0];

            // ---- ① 四则:位模式逐个对 ----
            // 1.5 = 0x3FC00000、2.25 = 0x40100000、3.375 = 0x40580000、-0.75 = 0xBF400000、4.5 = 0x40900000
            检查("通用化 浮点加法 1.5+2.25 = 3.75(位模式 0x40700000)", () =>
            {
                uint 值 = 算("LUI R0, 0x3FC00\nLUI R1, 0x40100\n浮点加法 R0, R1\n停止");
                return (值 == 0x40700000u, $"0x{值:X8}(期望 0x40700000)");
            });
            检查("通用化 浮点减法 1.5-2.25 = -0.75(位模式 0xBF400000)", () =>
            {
                uint 值 = 算("LUI R0, 0x3FC00\nLUI R1, 0x40100\n浮点减法 R0, R1\n停止");
                return (值 == 0xBF400000u, $"0x{值:X8}(期望 0xBF400000)");
            });
            检查("通用化 浮点乘法 1.5*2.25 = 3.375(位模式 0x40580000)", () =>
            {
                uint 值 = 算("LUI R0, 0x3FC00\nLUI R1, 0x40100\n浮点乘法 R0, R1\n停止");
                return (值 == 0x40580000u, $"0x{值:X8}(期望 0x40580000)");
            });
            检查("通用化 浮点除法 1.5/2.25 = 0.6666667(位模式 0x3F2AAAAB,与 C# 逐位一致)", () =>
            {
                uint 值 = 算("LUI R0, 0x3FC00\nLUI R1, 0x40100\n浮点除法 R0, R1\n停止");
                return (值 == 0x3F2AAAABu, $"0x{值:X8}(期望 0x3F2AAAAB)");
            });

            // ---- ② 除零照 IEEE754:给 ±Inf / NaN,**不报错**(这是与整数除零那两条的分界) ----
            检查("通用化 浮点除法 除零给 +Inf(0x7F800000)且**不停机、不报错**", () =>
            {
                var 机 = 运行("LUI R0, 0x3F800\nLUI R1, 0x0\n浮点除法 R0, R1\n停止");
                return (机.寄存器[0] == 0x7F800000u && 机.停机, $"R0=0x{机.寄存器[0]:X8} 停机={机.停机}(期望 0x7F800000)");
            });
            检查("通用化 浮点除法 0/0 给 NaN(0xFFC00000,与 C# 一致)", () =>
            {
                uint 值 = 算("LUI R0, 0x0\nLUI R1, 0x0\n浮点除法 R0, R1\n停止");
                return (值 == 0xFFC00000u, $"0x{值:X8}(期望 0xFFC00000)");
            });

            // ---- ③ 开方:3D 要用的那一条 ----
            // 2.25 = 0x40100000(注意别写成 0x40600 —— 那是 2.09375,本轮自检第一版就在这儿写错过)
            检查("通用化 浮点开方 √2.25 = 1.5(位模式 0x3FC00000,精确值)", () =>
            {
                uint 值 = 算("LUI R0, 0x40100\n浮点开方 R0\n停止");
                return (值 == 0x3FC00000u, $"0x{值:X8}(期望 0x3FC00000)");
            });
            检查("通用化 浮点开方 √(-1) 给 NaN(0xFFC00000)不报错", () =>
            {
                uint 值 = 算("LUI R0, 0xBF800\n浮点开方 R0\n停止");
                return (值 == 0xFFC00000u, $"0x{值:X8}(期望 0xFFC00000)");
            });

            // ---- ④ 比较:关系码 6 档 + 无序给 0 ----
            检查("通用化 浮点比较 关系码 6 档都对(1.5 对 2.25)", () =>
            {
                // 关系码:0 == / 1 != / 2 > / 3 < / 4 >= / 5 <=
                // 1.5 对 2.25:== 假、!= 真、> 假、< 真、>= 假、<= 真
                var 期望 = new (uint 码, uint 该给)[] { (0, 0), (1, 1), (2, 0), (3, 1), (4, 0), (5, 1) };
                foreach (var (码, 该给) in 期望)
                {
                    uint 值 = 算($"LUI R0, 0x3FC00\nLUI R1, 0x40100\n浮点比较 R0, R1, {码}\n停止");
                    if (值 != 该给) return (false, $"关系码 {码}:得 {值},该给 {该给}");
                }
                return (true, "6 档全对");
            });
            检查("通用化 浮点比较 与 NaN 比:有序比较一律 0、`!=` 给 1(IEEE754 无序口径)", () =>
            {
                // NaN = 0x7FC00000。IEEE754 对**无序**只有这一条规矩:
                //   有序比较(`==` `<` `>` `<=` `>=`)一律给假;`!=` 给**真**。
                // 这一条正好也是"硬件指令与软件库口径一致"的钉子。
                string 头 = "LUI R0, 0x3F800\nLUI R1, 0x7FC00\n";
                uint 等 = 算(头 + "浮点比较 R0, R1, 0\n停止");
                uint 不等 = 算(头 + "浮点比较 R0, R1, 1\n停止");
                uint 大 = 算(头 + "浮点比较 R0, R1, 2\n停止");
                uint 小 = 算(头 + "浮点比较 R0, R1, 3\n停止");
                uint 大等 = 算(头 + "浮点比较 R0, R1, 4\n停止");
                uint 小等 = 算(头 + "浮点比较 R0, R1, 5\n停止");
                bool 对 = 等 == 0u && 不等 == 1u && 大 == 0u && 小 == 0u && 大等 == 0u && 小等 == 0u;
                return (对, $"== {等} / != {不等}(该 1) / > {大} / < {小} / >= {大等} / <= {小等}");
            });

            // ---- ⑤ 两个转换 ----
            检查("通用化 整数转浮点 7 → 0x40E00000,且 浮点转整数 转回来还是 7(往返)", () =>
            {
                uint 值 = 算("LOAD_IMMEDIATE R0, 7\n整数转浮点 R0\n浮点转整数 R0\n停止");
                return (值 == 7u, $"得 {值}(期望 7)");
            });
            检查("通用化 浮点转整数 越界 / NaN 一律给 0x80000000(与 C# 那条判断逐字对齐)", () =>
            {
                uint 大 = 算("LUI R0, 0x60AD7\nADD_IMMEDIATE R0, 0x8EC\n浮点转整数 R0\n停止");   // 1e20f
                uint 非数 = 算("LUI R0, 0x7FC00\n浮点转整数 R0\n停止");                        // NaN
                uint 负无 = 算("LUI R0, 0xFF800\n浮点转整数 R0\n停止");                        // -Inf
                return (大 == 0x80000000u && 非数 == 0x80000000u && 负无 == 0x80000000u,
                    $"1e20→0x{大:X8} NaN→0x{非数:X8} -Inf→0x{负无:X8}(都该是 0x80000000)");
            });
        }
    }
}
