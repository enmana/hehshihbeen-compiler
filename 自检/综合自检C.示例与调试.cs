            记录("调试会话 返回后调用处清空", 返回后调用处.Count == 0, $"调用处={string.Join(",", 返回后调用处)}");
            // C15:调用链上的帧要认得出"被调的是哪个函数"(汇编标签 → 函数尾名),层号从最外层 1 起
            记录("调试会话 C15 调用帧认得出被调函数(尾名 / 层号 / 调用处行 / 文件)",
                进函数时帧.Count == 1 && 进函数时帧[0].名 == "加一" && 进函数时帧[0].层号 == 1 && 进函数时帧[0].行 == 5
                && string.Equals(进函数时帧[0].文件, "主程序.hb", StringComparison.OrdinalIgnoreCase),
