                    错.中文.Contains("a.hb", StringComparison.Ordinal) && 错.中文.Contains("第 1 行", StringComparison.Ordinal)
                    && 错.中文.Contains("模块", StringComparison.Ordinal),
                    $"报错=<{错.中文}>");
            }
        }

        /// <summary> 文本里最长的内部标签(报错时给人看看到底长成什么样了)</summary>
        private static string 最长标签段(string 文本)
        {
            string 最长 = "";
            foreach (var 词 in 文本.Split([' ', '\t', '\n', '\r', ':', '+', '(', ')'], StringSplitOptions.RemoveEmptyEntries))
                if ((词.StartsWith("_v", StringComparison.Ordinal) || 词.StartsWith("_f", StringComparison.Ordinal)) && 词.Length > 最长.Length)
                    最长 = 词;
            return 最长;
        }

        /// <summary>
        /// 用户实测的坑(F5 的语义):
        /// ① 停在断点上再按 F5 = **接着跑**,中途"新加的断点"照样要停得住(不能一路跑到停机);
        /// ② 停在断点上按 F5 不能把 PC 拉回开头(那就是"结束后重新执行"的观感);
        /// ③ 程序跑完之后重新装载,停的必须是**最早的那个断点**。
        /// </summary>
        private static void 断点继续自检()
        {
            var 文件表 = new List<(string 名称, string 内容)>
            {
                ("主程序.hb", "var 计数 = 1;\n计数 = 计数 + 1;\nbyte n = 42;\n测试输出(计数);\n测试输出(n);\n停止"),
            };
            var 编译 = new 汇编器C().汇编多文件带调试(文件表);
            var 表 = 编译.调试文件表;
            int 第一处 = 断点表C.算某行地址(表, "主程序.hb", 2) ?? -1;
            int 第二处 = 断点表C.算某行地址(表, "主程序.hb", 4) ?? -1;   // 第 3 行是 yte n = 42;:常量初值不占指令了,改用第 4 行
            记录("断点继续 两行都有能停的地址(且第 2 行在前)", 第一处 >= 0 && 第二处 >= 0 && 第一处 < 第二处,
                $"第2行=0x{第一处:X} 第4行=0x{第二处:X}");

            var 会话 = new 调试会话C { 调试文件表 = 表, 标签表 = 编译.标签表, 当前文件 = "主程序.hb", 断点地址 = [第一处] };
            会话.装载(编译);
            var 停1 = 会话.运行到断点();
            记录("断点继续 从头跑停在第 2 行", 停1.命中断点 && 停1.源码行 == 2, $"命中={停1.命中断点} 行={停1.源码行}");
            int 停1的PC = 停1.程序计数器;
            long 停1的步数 = 停1.已执行步数;

            // "用户又加了一个断点" = 界面重新算一遍地址集合(断点都在,只是多了一个)
            会话.断点地址 = [第一处, 第二处];
            var 停2 = 会话.继续();
            记录("断点继续 继续时新加的断点停得住(第 4 行),而不是一路跑到停机",
                停2.命中断点 && !停2.已停机 && 停2.源码行 == 4,
                $"命中={停2.命中断点} 停机={停2.已停机} 行={停2.源码行}");
            记录("断点继续 继续时没有把 PC 拉回开头(是接着走)", 停2.已执行步数 > 停1的步数 && 停2.程序计数器 != 0,
                $"步数 {停1的步数} → {停2.已执行步数},PC 0x{停1的PC:X} → 0x{停2.程序计数器:X}");

            var 停3 = 会话.继续();
            记录("断点继续 再继续就跑到停机", 停3.已停机 && !停3.命中断点, $"停机={停3.已停机} 行={停3.源码行}");

            // 跑完再按 F5:重新装载从头跑,应该停在第 2 行(最早的断点),不是第 3 行
            会话.装载(编译);
            var 停4 = 会话.运行到断点();
            记录("断点继续 跑完之后重新装载,停的是最早的断点(第 2 行)", 停4.命中断点 && 停4.源码行 == 2,
                $"命中={停4.命中断点} 行={停4.源码行}");

            // 源码改了(中间多一行代码)→ 后面的地址整体往后挪:断点地址必须按"新表"重算(不能拿旧表凑)
            var 改过 = new 汇编器C().汇编多文件带调试(new List<(string, string)>
            {
                ("主程序.hb", "var 计数 = 1;\n计数 = 计数 + 1;\nbyte n = 42;\nbyte 标量 = 7;\n测试输出(计数);\n停止"),
