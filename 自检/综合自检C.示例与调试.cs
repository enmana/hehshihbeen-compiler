            var 会3 = new 调试会话C { 调试文件表 = 多表, 标签表 = 多断点.标签表, 当前文件 = "主程序.hb", 断点地址 = [.. 三个] };
            会3.装载(多断点);
            var 停a = 会3.运行到断点();
            var 停b = 会3.继续();
            var 停c = 会3.继续();
            记录("断点继续 多个断点:一次停一个(2→3→4 行)",
                停a.源码行 == 2 && 停b.源码行 == 3 && 停c.源码行 == 4 && 停a.命中断点 && 停b.命中断点 && 停c.命中断点,
                $"停在第 {停a.源码行}/{停b.源码行}/{停c.源码行} 行");
            记录("断点继续 每个断点都在往前走(步数递增)",
                停a.已执行步数 < 停b.已执行步数 && 停b.已执行步数 < 停c.已执行步数,
                $"{停a.已执行步数} → {停b.已执行步数} → {停c.已执行步数}");
            记录("断点继续 最后一个断点之后再继续就停机", 会3.继续().已停机, "停机");

            // ③ 断点正好落在"程序第一条语句"(地址 0)上:再点继续必须能往下走,不能原地重置
            var 首句 = new 汇编器C().汇编多文件带调试(new List<(string, string)>
            {
                ("主程序.hb", "// 前面只有注释\n\nvar 计数 = 1;\n计数 = 计数 + 5;\n测试输出(计数);\n停止"),
            });
            var 首表 = 首句.调试文件表;
            int 首行地址 = 断点表C.算某行地址(首表, "主程序.hb", 4) ?? -1;   // 第 3 行是常量声明;第 4 行才是头一条有指令的语句
            记录("断点继续 第一条有指令的语句(第 4 行)地址就是 0", 首行地址 == 0, $"0x{首行地址:X}");
            var 会4 = new 调试会话C { 调试文件表 = 首表, 标签表 = 首句.标签表, 当前文件 = "主程序.hb", 断点地址 = [首行地址] };
            会4.装载(首句);
            var 首停 = 会4.运行到断点();
