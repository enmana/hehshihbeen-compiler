            记录("调试会话 C14 停在 `{` 行不推进 PC(下一次仍从函数体第一条指令接着说)",
                停左花括号时步数 >= 0 && 停左花括号时步数 == 报函数体时步数 && 停左花括号时PC == 报函数体时PC,
                $"`{{`行:步数={停左花括号时步数} PC={停左花括号时PC};函数体:步数={报函数体时步数} PC={报函数体时PC}");
