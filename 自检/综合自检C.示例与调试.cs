        /// <summary>
        /// 展开文本防呆(用户实测把源码覆盖成展开汇编那次):
        /// ① 唯一化必须**幂等** —— 展开文本再被当成源码编译一次,标签不能一层层长(_v0_0_0_…)`;
        /// ② 就算被覆盖了,程序行为也得跟原来一模一样(能跑、输出不变)。
        /// </summary>
        private static void 展开文本防呆自检()
        {
