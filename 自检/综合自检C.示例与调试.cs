            记录("防呆 正常源码里没有『// 来自』标记", !"var 初值 = 1;\n测试输出(初值);\n停止".Contains("// 来自", StringComparison.Ordinal), "所以能当防呆条件");

            var 又一次 = new 汇编器C().汇编多文件带调试(new List<(string, string)> { ("主程序.hb", 展开文本) });
            string 展开两次 = 又一次.调试文件表[0].展开文本;
            记录("防呆 唯一化幂等:再展开一次标签不叠加(不出现 _v0_0_)",
                !展开两次.Contains("_v0_0_", StringComparison.Ordinal) && !展开两次.Contains("_f0_0_", StringComparison.Ordinal),
                $"最长标签段={最长标签段(展开两次)}");

            // 行为一致:两份机器码跑出来的输出必须一样
            static string 跑出输出(byte[] 码)
            {
                var vm = new 虚拟机C();
                var sb = new System.Text.StringBuilder();
                vm.输出目标 = b => sb.Append((char)b);
                vm.运行(码);
                return sb.ToString();
            }
            string 输出原来 = 跑出输出(原来.机器码);
            string 输出覆盖后 = 跑出输出(又一次.机器码);
            记录("防呆 就算源码被覆盖成展开文本,程序输出也一样", 输出原来.Length > 0 && 输出原来 == 输出覆盖后,
                $"原来={输出原来.Trim()} 覆盖后={输出覆盖后.Trim()}");

            // 多文件:第94批起是**一张工程级符号表**,所以内部标签不再按文件序号唯一化
            // (重名由"重复声明"报错挡住,见下面的反面断言)
            var 多文件 = new 汇编器C().汇编多文件带调试(new List<(string, string)>
            {
                ("a.hb", "var 总值 = 1;\n测试输出(总值);\n停止"),
