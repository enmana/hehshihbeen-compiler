                string.Join(" | ", 多文件再.调试文件表.Select(段 => 最长标签段(段.展开文本))));
            期望异常("工程级 两个文件各写同名全局 → 报错(要隔离就用 `模块`)",
                () => new 汇编器C().汇编多文件带调试(new List<(string, string)>
                {
                    ("a.hb", "var 值 = 1;\n停止"),
                    ("b.hb", "var 值 = 2;\n停止"),
                }), "重复声明");
            期望异常("工程级 两个文件各写同名结构 → 报错(以前是静默覆盖)",
                () => new 汇编器C().汇编多文件带调试(new List<(string, string)>
                {
                    ("a.hb", "结构 点\n{\n整数 x;\n}\n停止\n"),
                    ("b.hb", "结构 点\n{\n整数 y;\n}\n"),
                }), "结构名冲突");
            // 报错必须**给出两处位置 + 改法**(D2):几十个文件时,只说"重复了"等于没说
