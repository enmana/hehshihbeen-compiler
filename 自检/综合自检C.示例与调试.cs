        private static void 示例回归主体()
        {
            string? 根 = 找示例目录();
            if (根 == null)
            {
                记录("定位 Sample 目录", false, AppContext.BaseDirectory);
                return;
            }
            // 递归扫描 汇编\ 与 中间层\ 下的每个示例(现在每个示例是"一个文件夹 + 工程文件 + 主程序.hb"),
            // 但排除 多文件* 的示例(那几个文件必须一起编译,单独跑不了)与 库\(库文件不是可运行示例)
            // 第434批:`列源码` 会剔掉 HB 机器码产物(IDE「只编译」落下的 `<工程名>.hb`)——
            // 不剔的话它会被当源码跑一次,多出一条"整文件不可运行"的跳过,`跳过数护栏` 跟着红。
            var 文件表 = 源码文件C.列源码(根)
                .Where(f => !f.Contains("多文件", StringComparison.Ordinal))
                .Where(f => !f.Contains($"{Path.DirectorySeparatorChar}库{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
                .OrderBy(f => f, StringComparer.Ordinal).ToArray();
            if (文件表.Length == 0)
            {
                记录("Sample 目录为空", false, 根);
                return;
            }
            // C27(2026-09-25 结案):示例回归是**按文件内容**跑的 —— 一个源文件被清成 0 字节时,它既没有
            // `// 预期输出:` 也没有停机行,于是从这个示例的"输出断言"**静默降级**成"无可回归段"
            // (跳过数 +1、断言清单基线跟着漂),屏幕上谁也看不见。这条闸就是给这种情形立的:
            // 0 字节当场红灯,并把**是谁**点名出来(标准工程 = 目录 + .hbp + 源码,三类文件一起扫)。
            var 全部源文件 = 源码文件C.列源码(根)
                .Concat(Directory.GetFiles(根, "*.hbp", SearchOption.AllDirectories)).ToArray();
            var 空文件 = 全部源文件.Where(文件 => new FileInfo(文件).Length == 0)
                .Select(文件 => Path.GetRelativePath(根, 文件)).OrderBy(名 => 名, StringComparer.Ordinal).ToArray();
            记录("C27 标准工程里的源文件一个都不是 0 字节(被清空当场红灯)", 空文件.Length == 0,
                空文件.Length == 0 ? $"扫了 {全部源文件.Length} 个 .hb / .hbp" : "0 字节:" + string.Join("、", 空文件));

            int 断言文件 = 0;
            foreach (string 文件 in 文件表)
            {
                // 名字带上文件夹(现在一堆 主程序.hb,光看文件名分不清是谁挂了)
                string 名 = Path.GetRelativePath(根, 文件);
                string[] 行表 = File.ReadAllLines(文件);
                string? 文件目录 = Path.GetDirectoryName(文件);   // 供 包含 "相对路径" 解析

                // 新式(推荐):用 输出(...) 打印结果,靠 "// 预期输出: a|b|c" 断言程序输出
                var 期望输出 = 解析预期输出(行表);
                if (期望输出.Count > 0)
                {
                    断言文件++;
                    try
                    {
                        // 标准工程按它自己目录里那份 .hbp 跑:示例09 的 `堆` 就是这么被真用上的
                        // (通用化第2批起 `内存` 也照这一套:示例60_大内存档 的那一份要 4MB)
                        var (_, 输出) = 运行带输出(string.Join("\n", 行表), 文件目录, 示例堆大小(文件目录), 示例内存大小(文件目录));
                        string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                        string 应有 = string.Join("\n", 期望输出);
                        bool 通过 = 实际 == 应有;
                        记录($"示例 {名} 输出断言", 通过, 通过 ? null : $"实际=<{实际.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
                    }
                    catch (Exception ex)
                    {
                        // ⚠ 第451批踩的坑:**名字不许把异常正文拼进去**。以前这里记的是
                        // `FAIL  示例 {名} 输出断言 => {ex.Message}`,`取行里的名` 认「=> 」切名字 ——
                        // 于是同一条断言**按失败原因换名字**(示例31 撞步数上限时叫「…=> 指令数超过上限 60000000 条…」,
                        // 跑得动时叫干净那个名)⇒ `工具\自检断言清单.txt` 这份进 git 的基线**随环境漂**
                        // (夜里巡检开着 Linux 档那一趟机器忙,那一段更容易撞上限,当场红)。
                        // 正解与上面那条同一个形状:名字写死,**原因走详情那一栏** ——
                        // ⚠ 分隔符是**两个空格 + `=> `**(`取行里的名` 认的就是 `  => `):
                        // 少一个空格,那串详情就会被当成**名字的一部分**(本批实测又踩了一次:
                        // 清单里多出一条「示例 …输出断言 => 这一趟抛了…」的假名字)。
                        R.失败++;
                        R.行.Add($"FAIL  示例 {名} 输出断言  => 这一趟抛了(没跑出输出):{ex.Message}");
                        R.异常.Add($"{名}: {ex.Message}");
                    }
                    continue;
                }

                // 老式:用 "// 预期结果: R0 = N" 断言寄存器
                // 找出全部“停机行”,按顺序编号;对第 k 个停机,运行“跳过前 k-1 个停机”的整文件变体,
                // 以还原 主程序→子程序(标签在停机之后)的完整语境,再与第 k 段期望比较。
                var 停机索引 = new List<int>();
                for (int i = 0; i < 行表.Length; i++)
                    if (行表[i].Trim() is "停止" or "HALT") 停机索引.Add(i);

                if (停机索引.Count == 0)
                {
                    // 无停机行的说明性文件:尝试整文件跑一次(若含可运行指令)
                    try
                    {
                        var vm0 = 运行(string.Join("\n", 行表), 文件目录, 示例堆大小(文件目录));
                        uint? 单值 = 找首个期望(行表, 0);
                        if (单值 != null)
                        {
                            记录($"示例 {名}(整文件无停机)", vm0.寄存器[0] == 单值.Value,
                                $"R0=0x{vm0.寄存器[0]:X} 期望0x{单值.Value:X}");
                            断言文件++;
                        }
                        else { R.跳过++; R.行.Add($"SKIP  {名} 无可回归段"); }
                    }
                    catch
                    {
                        R.跳过++; R.行.Add($"SKIP  {名}(整文件不可运行)");
                    }
                    continue;
                }

                bool 本文件有断言 = false;
                for (int k = 0; k < 停机索引.Count; k++)
                {
                    uint? 期望 = 找首个期望(行表, 停机索引[k] + 1);
                    if (期望 == null) continue; // 该段无期望 → 跳过
                    本文件有断言 = true; 断言文件++;

                    // 构造“前 k-1 个停机被注释掉”的整文件变体
                    var 变体 = (string[])行表.Clone();
                    for (int j = 0; j < k; j++) 变体[停机索引[j]] = "// 自检:跳过本停机以进入下一段";
                    try
                    {
                        var vm = 运行(string.Join("\n", 变体), 文件目录, 示例堆大小(文件目录));
                        string 详情 = $"R0=0x{vm.寄存器[0]:X} 期望0x{期望.Value:X}";
                        记录($"示例 {名} 段{k + 1}", vm.寄存器[0] == 期望.Value, 详情);
                    }
                    catch (Exception ex)
                    {
                        R.失败++;
                        R.行.Add($"FAIL  示例 {名} 段{k + 1} => {ex.Message}");
                        R.异常.Add($"{名} 段{k + 1}: {ex.Message}");
                    }
                }
                if (!本文件有断言) { R.跳过++; R.行.Add($"SKIP  {名} 无可回归段"); }
            }
        }

