        /// 变成"自检能抓"的入口(界面那边只是拿它的快照画黄条灰条)。
        /// </summary>
        private static void 调试会话自检()
        {
            string 源 = "var a = 7;\nmethod 加一(var x)  返回 整数 {\n返回 x + 1;\n}\n测试输出(加一(a));\n停止";
            var 文件表 = new List<(string 名称, string 内容)> { ("主程序.hb", 源) };
            var 编译结果 = new 汇编器C().汇编多文件带调试(文件表);
            // 调试段走**同一次编译**出来的那份(和 IDE 一样):里面才有名字表 / 函数边界(C14 靠它找 `{` `}`);
            // 标签表也要给 —— C15 靠"被调地址 → 标签 → 函数名"认出被调的是谁
            var 会话 = new 调试会话C { 调试文件表 = 编译结果.调试文件表, 标签表 = 编译结果.标签表, 当前文件 = "主程序.hb" };
            会话.装载(编译结果);

            // ① 语言单步:一次一行(相邻两次不会停在同一行),并且能一路走到停机
            var 行序列 = new List<int>();
            var 进函数时调用处 = new List<int>();
            var 返回后调用处 = new List<int>();
            long 停左花括号时步数 = -1, 报函数体时步数 = -1;
            int 停左花括号时PC = -1, 报函数体时PC = -1;
            var 进函数时帧 = new List<调用帧C>();
            for (int i = 0; i < 60 && !会话.已停机; i++)
            {
                var 步 = 会话.语言走一行();
                // "一次一行"的准确含义:每一步都真的换了位置 —— 所以相邻两步的行号不会相同
                if (步.源码行 > 0 && (行序列.Count == 0 || 行序列[^1] != 步.源码行)) 行序列.Add(步.源码行);
                if (步.源码行 == 2 && 停左花括号时步数 < 0) { 停左花括号时步数 = 步.已执行步数; 停左花括号时PC = 步.程序计数器; }
                if (步.源码行 == 3)
                {
                    进函数时调用处.AddRange(步.调用处行);
                    if (报函数体时步数 < 0)
                    {
                        报函数体时步数 = 步.已执行步数;
                        报函数体时PC = 步.程序计数器;
                        进函数时帧.AddRange(步.调用帧);
                    }
                }
                if (步.源码行 == 6) 返回后调用处.AddRange(步.调用处行);
                if (步.已停机) break;
            }
            记录("调试会话 语言单步每次真的换行(相邻不重复)",
                行序列.Count >= 4 && !行序列.Where((行, i) => i > 0 && 行 == 行序列[i - 1]).Any(),
                $"行序列={string.Join(",", 行序列)}");
            记录("调试会话 语言单步走到停机", 会话.已停机, $"共走 {会话.已执行步数} 条指令");
            // C14(2026-09-19 拍板):进函数先停在 `{` 那一行(这里 `{` 与声明同一行 = 第 2 行)、出函数停在 `}` 行(第 4 行)。
