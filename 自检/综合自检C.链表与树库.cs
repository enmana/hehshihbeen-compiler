//   —— `Sample\库\链表.hb` · `Sample\库\树.hb`
//
//   判据照 `基础库施工计划.md` §2 批 9 那一行:"**节点真申请真释放**;迭代器口径与 §8.4 拉模式同一套"。
//   这一组七块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **链表:随机前插 / 后插 / 按值删 / 按值找 / 取第几个与 C# 的 `LinkedList<int>` 逐条对拍**
//        (含越界那几档);
//     ② **树:随机插入 / 删除 / 查找 / 最小 / 最大 / 个数与 C# 的 `SortedSet<int>` 逐条对拍**;
//     ③ **树的中序不变式**:每一轮操作之后 `到数组` 出来必须**严格升序**(拉模式那一趟也对一遍);
//     ④ **节点真申请真释放(这一批的判据那一条,真量过)**:`新建 → 插 N 个 → 销毁` 连做 20 轮 ——
//        20 轮总共要 20000 个节点,而默认 64KB 堆只装得下约 5460 个(链表 12 字节)/ 4096 个(树 16 字节)
//        ⇒ **不真还回去,第几轮就当场"申请失败"停机**;两库各来一趟,还顺手把"清掉之后还能接着用"也量一下;
//     ⑤ **端到端**:标准工程 **`示例41_链表与树`** 真编真跑,与它那行 `// 预期输出:` 逐行对;
//     ⑥ **边界那一档**:空表 / 越界 / 没有那个值,逐条钉住"不报错、不停机、不动 `收值`";
//     ⑦ **接线哨兵**:两个库都在盘上 + 头注释五段齐 + 公开方法个数对上(16 / 15)。
//
//   ⚠ 这一组**不引 `测试助手.hb`**:库与库之间互相引会把"谁坏了"搅浑(自检要能一眼定位)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 链表与树库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 链路径 = Path.Combine(库目录, "链表.hb").Replace('\\', '/');
            string 树路径 = Path.Combine(库目录, "树.hb").Replace('\\', '/');
            if (!File.Exists(链路径) || !File.Exists(树路径))
            {
                跳过("链表与树库 定位两个库文件", $"找不到 {链路径} / {树路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{链路径}\"\n包含 \"{树路径}\"\n";

            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // ============================================================
            // ① 链表:随机操作与 C# 的 LinkedList<int> 逐条对拍
            // ============================================================
            try
            {
                var 随机 = new Random(20261013);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append("整数 单 = 链表.新建();\n整数 值 = -12345;\n");
                var 参考 = new LinkedList<int>();
                int 参考值 = -12345;
                for (int 轮 = 0; 轮 < 120; 轮++)
                {
                    int 动作 = 随机.Next(8);
                    int 给 = 随机.Next(-20, 21);
                    if (动作 == 0)                             // 前插
                    {
                        源.Append($"输出行(链表.前插(单, {给}));\n");
                        参考.AddFirst(给);
                        期望.Append('1').Append('|');
                    }
                    else if (动作 == 1)                        // 后插
                    {
                        源.Append($"输出行(链表.后插(单, {给}));\n");
                        参考.AddLast(给);
                        期望.Append('1').Append('|');
                    }
                    else if (动作 == 2)                        // 按值删
                    {
                        源.Append($"输出行(链表.按值删(单, {给}));\n");
                        int 删了 = 0;
                        var 走 = 参考.First;
                        while (走 != null)
                        {
                            var 下一个 = 走.Next;
                            if (走.Value == 给) { 参考.Remove(走); 删了++; }
                            走 = 下一个;
                        }
                        期望.Append(删了).Append('|');
                    }
                    else if (动作 == 3)                        // 按值找
                    {
                        源.Append($"输出行(链表.按值找(单, {给}));\n");
                        int 序号 = 0; bool 找到 = false;
                        foreach (int 一个 in 参考) { if (一个 == 给) { 找到 = true; break; } 序号++; }
                        期望.Append(找到 ? 序号 : -1).Append('|');
                    }
                    else if (动作 == 4)                        // 取第几个(含越界)
                    {
                        int 序号 = 随机.Next(-1, 参考.Count + 2);
                        源.Append($"输出行(链表.取第几个(单, {序号}, 值));\n输出行(值);\n");
                        if (序号 >= 0 && 序号 < 参考.Count) { 参考值 = 参考.ElementAt(序号); 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else if (动作 == 5)                        // 个数 / 是空
                    {
                        源.Append("输出行(链表.个数(单));\n输出行(链表.是空(单));\n");
                        期望.Append(参考.Count).Append('|').Append(参考.Count == 0 ? 1 : 0).Append('|');
                    }
                    else if (动作 == 6)                        // 正着走(拉模式)
                    {
                        源.Append($"整数 走{轮} = 链表.从头(单);\n整数 收{轮} = 0;\n当 (链表.下一项(走{轮}, 收{轮}))\n{{\n    输出行(收{轮});\n}}\n");
                        源.Append($"输出行(走{轮});\n");          // 走到头一定是 0
                        期望.Append(string.Join("|", 参考)).Append(参考.Count > 0 ? "|" : "").Append("0|");
                    }
                    else                                       // 倒着走(拉模式)
                    {
                        源.Append($"整数 回{轮} = 链表.从尾(单);\n整数 收{轮}b = 0;\n当 (链表.上一项(回{轮}, 收{轮}b))\n{{\n    输出行(收{轮}b);\n}}\n");
                        var 倒 = 参考.Reverse().ToArray();
                        源.Append($"输出行(回{轮});\n");
                        期望.Append(string.Join("|", 倒)).Append(参考.Count > 0 ? "|" : "").Append("0|");
                    }
                }
                源.Append("整数 铺[200];\n输出行(链表.到数组(单, 铺));\n");
                期望.Append(参考.Count).Append('|');
                int j = 0;
                foreach (int 一个 in 参考) { 源.Append($"输出行(铺[{j}]);\n"); 期望.Append(一个).Append('|'); j++; }
                源.Append("链表.销毁(单);\n停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("链表与树库 链表:前插 / 后插 / 按值删 / 按值找 / 取第几个 / 个数 / 正着走 / 倒着走 / 到数组(120 轮随机操作,与 C# 的 LinkedList<int> 逐条对拍;含越界那几档)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("链表与树库 链表随机对拍", ex); }

            // ============================================================
            // ② 树:随机插入 / 删除 / 查找与 C# 的 SortedSet<int> 逐条对拍
            // ============================================================
            try
            {
                var 随机 = new Random(20261014);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append("整数 根 = 树.新建();\n整数 值 = -12345;\n");
                var 参考 = new SortedSet<int>();
                int 参考值 = -12345;
                for (int 轮 = 0; 轮 < 120; 轮++)
                {
                    int 动作 = 随机.Next(7);
                    int 给 = 随机.Next(-25, 26);
                    if (动作 <= 1)                             // 插入(重复给假)
                    {
                        源.Append($"输出行(树.插入(根, {给}));\n");
                        期望.Append(参考.Add(给) ? 1 : 0).Append('|');
                    }
                    else if (动作 == 2)                        // 删除
                    {
                        源.Append($"输出行(树.删除(根, {给}));\n");
                        期望.Append(参考.Remove(给) ? 1 : 0).Append('|');
                    }
                    else if (动作 == 3)                        // 查找
                    {
                        源.Append($"输出行(树.查找(根, {给}));\n");
                        期望.Append(参考.Contains(给) ? 1 : 0).Append('|');
                    }
                    else if (动作 == 4)                        // 最小 / 最大(空树给假且不动收值)
                    {
                        源.Append("输出行(树.最小(根, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Min; 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                        源.Append("输出行(树.最大(根, 值));\n输出行(值);\n");
                        if (参考.Count > 0) { 参考值 = 参考.Max; 期望.Append('1'); } else 期望.Append('0');
                        期望.Append('|').Append(参考值).Append('|');
                    }
                    else                                       // 个数 / 是空 / 中序不变式
                    {
                        源.Append("输出行(树.个数(根));\n输出行(树.是空(根));\n");
                        期望.Append(参考.Count).Append('|').Append(参考.Count == 0 ? 1 : 0).Append('|');
                        源.Append($"整数 排{轮}[200];\n整数 铺了{轮} = 树.到数组(根, 排{轮});\n输出行(铺了{轮});\n");
                        期望.Append(参考.Count).Append('|');
                        int k = 0;
                        foreach (int 一个 in 参考) { 源.Append($"输出行(排{轮}[{k}]);\n"); 期望.Append(一个).Append('|'); k++; }
                        // 中序出来的必须是**严格升序**(这一步是 HB 侧自己扫的,不是 C# 替它判)
                        源.Append($"整数 乱{轮} = 0;\n整数 q{轮} = 1;\n当 (q{轮} < 铺了{轮})\n{{\n    如果 (排{轮}[q{轮} - 1] >= 排{轮}[q{轮}])\n    {{\n        乱{轮} = 1;\n    }}\n    q{轮} = q{轮} + 1;\n}}\n输出行(乱{轮});\n");
                        期望.Append('0').Append('|');
                    }
                }
                源.Append("树.销毁(根);\n停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                记录("链表与树库 树:插入(重复不收)/ 删除 / 查找 / 最小 / 最大 / 个数 / 中序(120 轮随机操作,与 C# 的 SortedSet<int> 逐条对拍;中序升序由 HB 侧自己扫出来)",
                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("链表与树库 树随机对拍", ex); }

            // ============================================================
            // ③ 节点真申请真释放(判据那一条:**真量过** —— 20 轮 × 1000/500 个节点,默认 64KB 堆装不下)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    // 量出来的容量边界(本批实测):链表 3000 个节点**当场申请失败**、2000 个放得下;
                    // 于是"两轮各 2000 个"这件事本身就是判据 —— 第一轮的 2000 个不真还回去,
                    // 第二轮那 2000 个就没地方放(两轮加一起 4000 > 容量),当场"申请失败"停机。
                    "整数 轮 = 0;\n" +
                    "当 (轮 < 2)\n" +
                    "{\n" +
                    "    整数 单 = 链表.新建();\n" +
                    "    整数 i = 0;\n" +
                    "    当 (i < 2000)\n" +
                    "    {\n" +
                    "        链表.后插(单, i);\n" +
                    "        i = i + 1;\n" +
                    "    }\n" +
                    "    输出行(链表.个数(单));\n" +
                    "    链表.销毁(单);\n" +
                    "    轮 = 轮 + 1;\n" +
                    "}\n" +
                    "输出行(轮);\n" +
                    // 再来一趟"清掉之后还能接着用"(控制块留着,节点还回去)
                    "整数 单2 = 链表.新建();\n" +
                    "整数 k = 0;\n" +
                    "当 (k < 2)\n" +
                    "{\n" +
                    "    整数 j = 0;\n" +
                    "    当 (j < 2000)\n" +
                    "    {\n" +
                    "        链表.后插(单2, j);\n" +
                    "        j = j + 1;\n" +
                    "    }\n" +
                    "    链表.清掉(单2);\n" +
                    "    k = k + 1;\n" +
                    "}\n" +
                    "输出行(链表.个数(单2));\n" +
                    "链表.后插(单2, 7);\n" +
                    "输出行(链表.个数(单2));\n" +
                    "链表.销毁(单2);\n");
                // 树那一半:**插入顺序由 C# 现算一份"平衡序"**(先中间、再左半、再右半 —— 高度 ≈ log2 n),
                //   不这么排的话"升序插入"会退化成一条链:`最左` / `插入` 都是 O(n) ⇒ 2000 个节点要几千万条指令,
                //   而且 `高度` 那条递归会先把软栈吃掉(实测 800 个就报"递归太深")。
                //   两轮各 2000 个节点:第一轮的 2000 个不真还回去,第二轮就没地方放(4000 > 容量)。
                var 平衡序 = new List<int>();
                void 收(int 小, int 大)
                {
                    if (小 > 大) return;
                    int 中 = (小 + 大) / 2;
                    平衡序.Add(中);
                    收(小, 中 - 1);
                    收(中 + 1, 大);
                }
                收(0, 1999);
                var 树源 = new StringBuilder();
                for (int 轮 = 0; 轮 < 2; 轮++)
                {
                    树源.Append($"整数 根{轮} = 树.新建();\n");
                    foreach (int 值 in 平衡序) 树源.Append($"树.插入(根{轮}, {值});\n");
                    树源.Append($"输出行(树.个数(根{轮}));\n");
                    树源.Append($"输出行(树.高度(根{轮}));\n");
                    树源.Append($"树.销毁(根{轮});\n");
                }
                树源.Append("整数 根9 = 树.新建();\n");
                for (int 趟 = 0; 趟 < 2; 趟++)
                {
                    foreach (int 值 in 平衡序) 树源.Append($"树.插入(根9, {值});\n");
                    树源.Append("树.清掉(根9);\n");
                }
                树源.Append("输出行(树.个数(根9));\n树.插入(根9, 7);\n输出行(树.个数(根9));\n树.销毁(根9);\n停止\n");
                源.Append(树源);
                string 期 = "2000|2000|2|0|1|2000|11|2000|11|0|1";
                string 实 = 跑(源.ToString());
                记录("链表与树库 节点真申请真释放(真量过:链表两轮各 2000 个 + 树两轮各 2000 个 —— 64KB 堆装不下,不真还回去第二轮就当场申请失败)",
                    实 == 期, 对拍说明(期, 实) + ";还量了 `清掉` 之后家还在(接着插得进)");
            }
            catch (Exception ex) { 记录异常("链表与树库 节点真申请真释放", ex); }

            // ============================================================
            // ④ 端到端:标准工程 示例41_链表与树 逐行对 `// 预期输出:`
            // ============================================================
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例41_链表与树");
                string? 源码 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码 == null || !File.Exists(源码))
                {
                    跳过("链表与树库 标准工程 示例41 逐行对预期输出", $"找不到 {源码}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码);
                    var 期望行 = 解析预期输出(行表);
                    // ⚠ 这一篇是**带 UI** 的标准工程:那一行 `// 预期输出:` 里既有窗口前那一段
                    //   `输出行`,也有开窗之后逐帧画出来的命令(H82 批 4 的口径)。
                    //   ⇒ 必须走共享帮手 `运行带输出`:它**挂无头呈现口**(绘制命令逐条进同一份输出缓冲)
                    //   并按 `基目录` 自动读工程目录那份 `事件脚本.txt`(帧数/键鼠都从那儿来)。
                    //   ⚠ 别退回"自己 new 虚拟机C"那一版:窗口开不出来 ⇒ 只跑出窗口前那一段。
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录, 示例堆大小(工程目录));
                    string 实得 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望行);
                    bool 好 = 期望行.Count > 0 && 实得 == 应有;
                    记录("链表与树库 标准工程 示例41 逐条对预期输出(两个库在真程序里的那一趟:链表名单 → 树的中序与三种删除)",
                        好, 好 ? $"逐行一致({期望行.Count} 行,含开窗那一半)" : 逐行差说明(应有, 实得));
                }
            }
            catch (Exception ex) { 记录异常("链表与树库 标准工程 示例41", ex); }

            // ============================================================
            // ⑤ 边界那一档:空表 / 越界 / 没有那个值(一律不报错、不停机、不动 `收值`)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 单 = 链表.新建();\n" +
                    "整数 值 = 99;\n" +
                    "整数 空游标 = 0;\n" +
                    "输出行(链表.是空(单));\n" +                // 1:1
                    "输出行(链表.个数(单));\n" +                // 2:0
                    "输出行(链表.按值找(单, 5));\n" +           // 3:-1
                    "输出行(链表.按值删(单, 5));\n" +           // 4:0
                    "输出行(链表.取第几个(单, 0, 值));\n" +      // 5:0
                    "输出行(值);\n" +                           // 6:99(不动)
                    "输出行(链表.从头(单));\n" +                // 7:0
                    "输出行(链表.从尾(单));\n" +                // 8:0
