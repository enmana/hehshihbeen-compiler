//        —— 只钉"还在不在",不许单独当正确性证据。
//
//   ★ **为什么数组 / 列表两条线的"多语句对拍"没进这一组 = H71**(见 `未做任务清单.md` §0 六档)
//     第351批写这一组时量出一件**编译器**的事:同一个库函数、同样的小实参,在"只跑前 12 条语句"
//     的小程序里**全对**,在一份两三百行、前后互相穿插的大程序里**结果就变了**
//     (实测:`数组.找全部(主表, -8, 出1)` 写在 `出1[0]` 里的下标,读回来是 3 而不是 0;
//     `列表.接到尾(表, 用, 7)` 在清单里跑出来是 2 而不是 -1。三档都编得过、不报运行期错、
