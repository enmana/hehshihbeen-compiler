                    实 == 期, 对拍说明(期, 实));
            }
            catch (Exception ex) { 记录异常("数组列表统计库 边界(列表)", ex); }

            // ============================================================
            // ⑤ 接线哨兵:三个库在位 + 头注释该有的几段齐 + 公开方法个数
