//     ⇒ 这一组把"数组 / 列表的多语句对拍"**留在复现件里**(`工具\临时\批6探针\H71最小复现.hb`),
//     自检只跑**形状稳定**的那几块(统计 / 不变量 / 端到端)。**哪一块稳定是量出来的,不是猜的**:
//     上面前两块与端到端那一块在"一次跑一整组"的形状下逐条对了;数组 / 列表那两块**对不上**,
//     所以它们不进判据 —— 这正是硬规矩 5 那句"接线哨兵不许单独当正确性证据"的同一条尺子:
//     **拿不稳的读数不许当判据**。H71 真修好之后,把那两块照 `工具\临时\批6探针\` 里的探针补回来。
//
//   ⚠ 这一组**不引 `测试助手.hb`**:库与库之间互相引会把"谁坏了"搅浑(自检要能一眼定位)。
