using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 数组列表统计库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 数组路径 = Path.Combine(库目录, "数组.hb").Replace('\\', '/');
            string 列表路径 = Path.Combine(库目录, "列表.hb").Replace('\\', '/');
            string 统计路径 = Path.Combine(库目录, "统计.hb").Replace('\\', '/');
            if (!File.Exists(数组路径) || !File.Exists(列表路径) || !File.Exists(统计路径))
            {
                跳过("数组列表统计库 定位三个库文件", $"找不到 {数组路径} / {列表路径} / {统计路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{数组路径}\"\n包含 \"{列表路径}\"\n包含 \"{统计路径}\"\n";

            // 真编真跑一趟(输出按 UTF-8 收、行尾换成 `|`,与 位与数学库 / 表达式库 那两组同一套跑法)
            static string 跑(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小,
                    虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }

            static string 对拍说明(string 期望, string 实得)
            {
                if (期望 == 实得) return $"一字不差({期望.Split('|').Length} 条)";
                string[] 期望段 = 期望.Split('|'), 实得段 = 实得.Split('|');
                int 少 = Math.Min(期望段.Length, 实得段.Length);
                for (int i = 0; i < 少; i++)
                    if (期望段[i] != 实得段[i])
                        return $"第 {i + 1} 个输出对不上:期望 [{期望段[i]}] / 实得 [{实得段[i]}](期望 {期望段.Length} 条 / 实得 {实得段.Length} 条)";
                return $"条数对不上:期望 {期望段.Length} 条 / 实得 {实得段.Length} 条";
            }

            // 对拍红了的时候把"这一份现场造出来的源码"落进临时区(硬规矩 15:落点走 临时区C)
            static void 落失败源(string 名字, string 文本)
            {
                try
                {
                    Directory.CreateDirectory(临时区C.基目录());
                    File.WriteAllText(Path.Combine(临时区C.基目录(), $"hb_自检_{名字}.hb"), 文本);
                }
                catch { }
            }

            static int 低32(long 和) => unchecked((int)(和 & 0xFFFFFFFFL));
            static int 参考中位数(int[] 数据表)
            {
                var 排 = 数据表.OrderBy(x => x).ToArray();
                if (排.Length == 0) return 0;
                int 中 = 排.Length / 2;
                return 排.Length % 2 == 1 ? 排[中] : (int)(((long)排[中 - 1] + 排[中]) / 2);
            }
            static int 参考众数(int[] 数据表)
            {
                if (数据表.Length == 0) return 0;
                var 排 = 数据表.OrderBy(x => x).ToArray();
                int 最多 = 0, 答案 = 排[0], i = 0;
                while (i < 排.Length)
                {
                    int j = i;
                    while (j < 排.Length && 排[j] == 排[i]) j++;
                    if (j - i > 最多) { 最多 = j - i; 答案 = 排[i]; }
                    i = j;
                }
                return 答案;
            }

            // ============================================================
            // ① 统计那一套:与 C# 的 long / double 参考实现逐条对拍
            // ============================================================
            try
            {
                var 随机 = new Random(20261005);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                for (int 轮 = 0; 轮 < 8; 轮++)
                {
                    int 长 = 1 + 随机.Next(7);
                    var 数据表 = Enumerable.Range(0, 长).Select(_ => 随机.Next(-50, 51)).ToArray();
                    源.Append($"整数 表{轮}[{长}] = [{string.Join(", ", 数据表)}];\n");
                    void 记(string 代码) { 源.Append(代码).Append('\n'); }

                    long 和64 = 数据表.Sum(x => (long)x);
                    long 积64 = 数据表.Aggregate(1L, (a, x) => a * x);
                    long 平方64 = 数据表.Sum(x => (long)x * x);
                    // 均值取整数除法,离差平方和按 64 位(与 统计.hb 的私有一致)
                    int 均 = 低32(和64) / 长;
                    long 离差 = 数据表.Sum(x => { long d = (long)x - 均; return d * d; });

                    记($"输出行(统计.个数(表{轮}));");
                    期望.Append(长).Append('|');
                    记($"输出行(统计.求和(表{轮}));");
                    期望.Append(低32(和64)).Append('|');
                    记($"输出行(统计.乘积(表{轮}));");
                    期望.Append(低32(积64)).Append('|');
                    记($"输出行(统计.平方和(表{轮}));");
                    期望.Append(低32(平方64)).Append('|');
                    记($"输出行(统计.最大(表{轮}));");
                    期望.Append(数据表.Max()).Append('|');
                    记($"输出行(统计.最小(表{轮}));");
                    期望.Append(数据表.Min()).Append('|');
                    记($"输出行(统计.极差(表{轮}));");
                    期望.Append(数据表.Max() - 数据表.Min()).Append('|');
                    记($"输出行(统计.中位数(表{轮}));");
                    期望.Append(参考中位数(数据表)).Append('|');
                    记($"输出行(统计.众数(表{轮}));");
                    期望.Append(参考众数(数据表)).Append('|');
                    int k = 1 + 随机.Next(长);
                    记($"输出行(统计.第k小(表{轮}, {k}));");
                    期望.Append(数据表.OrderBy(x => x).ElementAt(k - 1)).Append('|');
                    记($"输出行(统计.是否升序(表{轮}));");
                    期望.Append(数据表.SequenceEqual(数据表.OrderBy(x => x)) ? 1 : 0).Append('|');
                    记("输出行(统计.草稿个数());");
                    期望.Append(长).Append('|');
                    记("输出行(统计.取草稿(0));");
                    期望.Append(数据表.Min()).Append('|');

                    // 双精度三件:先落进变量,再交给 `双精度转字符串`
                    记($"双精度 均{轮} = 统计.平均值(表{轮});");
                    记($"双精度 总{轮} = 统计.总体方差(表{轮});");
                    记($"双精度 样{轮} = 统计.样本方差(表{轮});");
                    记($"双精度 标{轮} = 统计.标准差(表{轮});");
                    记($"输出行(双精度转字符串(均{轮}));");
                    期望.Append(((double)低32(和64) / 长).ToString("R", System.Globalization.CultureInfo.InvariantCulture)).Append('|');
                    记($"输出行(双精度转字符串(总{轮}));");
                    期望.Append(((double)离差 / 长).ToString("R", System.Globalization.CultureInfo.InvariantCulture)).Append('|');
                    记($"输出行(双精度转字符串(样{轮}));");
                    期望.Append(长 <= 1 ? "0" : ((double)离差 / (长 - 1)).ToString("R", System.Globalization.CultureInfo.InvariantCulture)).Append('|');
                    记($"输出行(双精度转字符串(标{轮}));");
                    期望.Append(Math.Sqrt((double)离差 / 长).ToString("R", System.Globalization.CultureInfo.InvariantCulture)).Append('|');
                }
                源.Append("停止\n");
                string 期 = 期望.ToString().TrimEnd('|'), 实 = 跑(源.ToString());
                bool 好 = 实 == 期;
                string 说明 = 好 ? $"一字不差({期.Split('|').Length} 条)" : 对拍说明(期, 实);
                if (!好)
                {
                    // 允许"只差双精度最后一位":把不同的那几条再按相对容差 1e-12 过一遍,
                    // 只要**每一条都能读成数**且都在容差里就算过(字面量那几条读不出数,自然仍算不过)。
                    string[] 期望条 = 期.Split('|'), 实得条 = 实.Split('|');
                    if (期望条.Length == 实得条.Length)
                    {
                        int 差条 = 0;
                        for (int i = 0; i < 期望条.Length; i++)
                        {
                            if (期望条[i] == 实得条[i]) continue;
                            if (!double.TryParse(期望条[i], System.Globalization.NumberStyles.Float,
                                                 System.Globalization.CultureInfo.InvariantCulture, out double 望)
                                || !double.TryParse(实得条[i], System.Globalization.NumberStyles.Float,
                                                    System.Globalization.CultureInfo.InvariantCulture, out double 得)
                                || Math.Abs(得 - 望) > 1e-12 * Math.Max(Math.Abs(望), 1.0))
                            {
                                差条 = -1;
                                break;
                            }
                            差条++;
                        }
                        if (差条 >= 0)
                        {
                            好 = true;
                            说明 = $"条数一致({期望条.Length} 条),其中 {差条} 条双精度只差最后一位(相对容差 1e-12 内)";
                        }
                    }
                }
                记录("数组列表统计库 统计:计数 / 求和 / 乘积 / 平方和 / 最大 / 最小 / 极差 / 中位数 / 众数 / 第k小 / 是否升序 / 平均值 / 样本方差 / 总体方差 / 标准差(8 张现场造的表;C# 侧用 long 累加、double 出小数)",
                    好, 说明);
            }
            catch (Exception ex) { 记录异常("数组列表统计库 统计那一套", ex); }

            // ============================================================
            // ② 三条不变量:去重必升序 / 是相同恒真 / 求和与 64 位累加一致
            // ============================================================
            try
            {
                var 随机 = new Random(20261006);
                var 源 = new StringBuilder(头);
                var 期望 = new StringBuilder();
                源.Append("整数 大[12];\n整数 收[16];\n整数 个数 = 0;\n整数 有没有乱 = 0;\n整数 k = 1;\n");
                for (int 轮 = 0; 轮 < 10; 轮++)
                {
                    var 数据表 = Enumerable.Range(0, 12).Select(_ => 随机.Next(0, 8)).ToArray();
                    for (int i = 0; i < 12; i++) 源.Append($"大[{i}] = {数据表[i]};\n");
                    源.Append("个数 = 数组.去重(大, 收);\n");
                    源.Append("输出行(个数);\n");
                    源.Append("有没有乱 = 0;\n");
                    源.Append("k = 1;\n");
                    源.Append("当 (k < 个数)\n{\n");
                    源.Append("    如果 (收[k - 1] > 收[k])\n    {\n        有没有乱 = 1;\n    }\n");
                    源.Append("    k = k + 1;\n}\n");
                    源.Append("输出行(有没有乱);\n");                 // 0:排序没乱
                    源.Append("输出行(数组.是相同(大, 大));\n");       // 1:恒真
                    // 再来一条"64 位累加"的独立核:八个 200000000 相加 = 16 亿(32 位装不下,64 位装得下)
                    源.Append("大[0] = 200000000;\n大[1] = 200000000;\n大[2] = 200000000;\n大[3] = 200000000;\n");
                    源.Append("大[4] = 200000000;\n大[5] = 200000000;\n大[6] = 200000000;\n大[7] = 200000000;\n");
                    源.Append("大[8] = 0;\n大[9] = 0;\n大[10] = 0;\n大[11] = 0;\n");
                    源.Append("输出行(统计.求和(大));\n");
                    var 独 = 数据表.Distinct().OrderBy(x => x).ToArray();
                    期望.Append(独.Length).Append('|').Append(0).Append('|').Append(1).Append('|')
                        .Append(低32(8L * 200000000)).Append('|');
                }
                源.Append("停止\n");
                string 实 = 跑(源.ToString());
                if (实 != 期望.ToString().TrimEnd('|')) 落失败源("不变量", 源.ToString());
                记录("数组列表统计库 不变量:去重出来的表必升序、`是相同(表, 表)` 恒真、`求和` 与 64 位累加一致(10 张乱序表;升序那条由 HB 侧自己扫出来,不是 C# 替它判)",
                    实 == 期望.ToString().TrimEnd('|'), 对拍说明(期望.ToString().TrimEnd('|'), 实));
            }
            catch (Exception ex) { 记录异常("数组列表统计库 三条不变量", ex); }

            // ============================================================
            // ③ 端到端:标准工程 示例38_数组与统计 的输出逐条对 `// 预期输出:`
            // ============================================================
            try
            {
                string? 工程目录 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例38_数组与统计");
                string? 源码 = 工程目录 == null ? null : Path.Combine(工程目录, "主程序.hb");
                if (源码 == null || !File.Exists(源码))
                {
                    跳过("数组列表统计库 标准工程 示例38 逐条对预期输出", $"找不到 {源码}(不在工作副本里跑就跳过)");
                }
                else
                {
                    var 行表 = File.ReadAllLines(源码);
                    var 期望行 = 解析预期输出(行表);
                    // ⚠ 这一篇是**带 UI** 的标准工程(H82 批 5):那一行 `// 预期输出:` 里既有窗口前那一段
                    //   `输出行`,也有开窗之后逐帧画出来的命令。⇒ 必须走共享帮手 `运行带输出`:
                    //   它**挂无头呈现口**(绘制命令逐条进同一份输出缓冲),并按 `基目录` 自动读工程目录
                    //   那份 `事件脚本.txt`(帧数 / 点哪儿都从那儿来)。⚠ 别退回"自己 new 虚拟机C"那一版:
                    //   没挂呈现口 ⇒ `打开窗口` 给假、窗口那一半一条命令都不出,这条断言就红得莫名其妙
                    //   (与 容器三库 / 示例39 那一处同一个口径)。
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 工程目录, 示例堆大小(工程目录));
                    string 实得 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望行);
                    bool 好 = 期望行.Count > 0 && 实得 == 应有;
                    // 报"第几行不一样"要**真去找那一行**:以前这里写死 `第 1 行`,于是红的时候打的是
                    // "第 1 行 期望[10] 实得[10]" —— 两边的第一个字一模一样,看的人只会以为判据坏了
                    // (第427批实测踩到:真正不一样的那一行在几百行后面)。
                    var 实得行 = 实得.Split('\n');
                    int 错行 = 0;
                    if (!好 && 期望行.Count == 实得行.Length)
                    {
                        for (int k = 0; k < 期望行.Count; k++)
                            if (期望行[k] != 实得行[k]) { 错行 = k + 1; break; }
                    }
                    记录("数组列表统计库 标准工程 示例38 逐条对预期输出(三个库在真程序里的那一趟:统计 → 数组 → 列表 → 报表)",
                        好, 好 ? $"逐行一致({期望行.Count} 行,含开窗那一半)"
                            : $"期望 {期望行.Count} 行 / 实得 {实得行.Length} 行;" +
                              (错行 > 0
                                  ? $"第 {错行} 行 期望[{期望行[错行 - 1]}] 实得[{实得行[错行 - 1]}]"
                                  : "条数先对不上"));
                }
            }
            catch (Exception ex) { 记录异常("数组列表统计库 标准工程 示例38", ex); }

            // ============================================================
            // ④ 边界那一档:越界 / 装不下 / 空表 / 满表(全库统一口径)
            //    每一条的期望都写在下面对应的注释里(数输出条数时对着数)
            // ============================================================
            try
            {
                var 源 = new StringBuilder(头);
                源.Append(
                    "整数 表[3] = [5, -2, 9];\n" +
                    "整数 小[2];\n" +
                    "输出行(数组.段拷(表, -5, 3, 小));\n" +          // 1:起点负当 0;目标 2 格 ⇒ 2
