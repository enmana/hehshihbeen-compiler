        /// <summary>
        /// 一个框下面挂 `条数` 个子项时**排出来的行距**(H61-1 的分档行距:子项越多行距越大)。
        /// 占高 = 子项高之和 + 行距 × (条数 − 1),把它反解出来 —— 比"看占高变大"钉得死
        /// (占高本来就跟着条数涨,那样量等于什么都没量)。
        /// </summary>
        private static double 量层行距(int 条数)
        {
            var 根 = new 导图节点C { 键 = "根", 标题 = "根", 种类 = 导图种类C.工程 };
            for (int i = 0; i < 条数; i++)
            {
                var 子 = new 导图节点C { 键 = "子" + i, 标题 = "子" + i, 种类 = "变量", 父 = 根 };
                根.子.Add(子);
            }
            根.总数 = 条数;
            导图布局C.排(根, 导图布局C.假量宽);
            if (条数 < 2) return 0;
            return (根.占高 - 根.子[0].高 * 条数) / (条数 - 1);
        }

