        /// <summary> 树里所有节点的行号(递归走一遍;自检只拿它查"有没有落到本文之外") </summary>
        private static IEnumerable<int> 全部行号(源码结构C 树)
        {
            foreach (var v in 树.变量们) yield return v.行;
            foreach (var b in 树.包含们) yield return b.行;
            foreach (var s in 树.结构们)
            {
                yield return s.行;
                foreach (var f in s.字段们) yield return f.行;
                foreach (int 行 in 方法行号们(s.方法们)) yield return 行;
            }
            foreach (int 行 in 方法行号们(树.方法们)) yield return 行;
            foreach (var t in 树.顶层语句们) yield return t.行;
            foreach (var b in 树.顶层流程块们) foreach (int 行 in 块行号们(b)) yield return 行;
        }

        private static IEnumerable<int> 方法行号们(List<方法节点C> 方法们)
        {
            foreach (var m in 方法们)
            {
                yield return m.头行;
                if (m.体起行 > 0) yield return m.体起行;
                if (m.止行 > 0) yield return m.止行;
                foreach (var p in m.参数们) yield return p.行;
                foreach (var v in m.局部们) yield return v.行;
                foreach (var t in m.语句们) yield return t.行;
                foreach (var b in m.流程块们) foreach (int 行 in 块行号们(b)) yield return 行;
                foreach (int 行 in 方法行号们(m.方法们)) yield return 行;
            }
        }

        private static IEnumerable<int> 块行号们(流程块节点C 块)
        {
            yield return 块.行;
            foreach (var v in 块.头声明们) yield return v.行;
            foreach (var v in 块.局部们) yield return v.行;
            foreach (var t in 块.里层语句们) yield return t.行;
            foreach (var c in 块.子块们) foreach (int 行 in 块行号们(c)) yield return 行;
        }

        private static int 数块(List<流程块节点C> 块们)
        {
            int 数 = 0;
            foreach (var b in 块们) 数 += 1 + 数块(b.子块们);
            return 数;
        }

        /// <summary> 一个方法这一枝有几个流程块(含成员方法里的) </summary>
        private static int 数方法块(方法节点C 方法)
        {
            int 数 = 数块(方法.流程块们);
            foreach (var 里 in 方法.方法们) 数 += 数方法块(里);
            return 数;
        }

        /// <summary> 一个方法这一枝有多少条语句(含流程块与成员方法里的) </summary>
        private static int 数方法语句(方法节点C 方法)
        {
            int 数 = 方法.语句们.Count;
            foreach (var 块 in 方法.流程块们) 数 += 数块语句(块);
            foreach (var 里 in 方法.方法们) 数 += 数方法语句(里);
            return 数;
        }

        private static int 数块语句(流程块节点C 块)
