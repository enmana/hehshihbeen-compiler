        /// <summary> 自检用的假数据源:根给 45 条;别的节点给"附加"里写的条数(默认 3)</summary>
        private static List<导图子项C> 假子项(导图节点C 节)
        {
            int 数 = 节.键 == "根" ? 45 : (节.附加 as int? ?? 3);
            var 表 = new List<导图子项C>();
            for (int i = 0; i < 数; i++)
                表.Add(new 导图子项C
                {
                    键 = 节.键 + "#" + i,
                    标题 = 节.键 == "根" ? $"文件{i}.hb" : $"子{i}",
                    说明 = "夹具",
                    种类 = "文件",
                    附加 = 3,
                });
            return 表;
        }

        private static 导图模型C 新模型() => new(
            new 导图子项C { 键 = "根", 标题 = "工程", 说明 = "夹具", 种类 = 导图种类C.工程 },
            假子项);

        /// <summary> H63-1 夹具用的一格(键 / 标题 / 文件都能指定;能往下长) </summary>
        private static 导图子项C 造项(string 键, string 标题, string 文件 = "") => new()
        {
            键 = 键, 标题 = 标题, 种类 = "方法", 文件 = 文件, 能往下长 = true,
        };

        /// <summary> H63-5 夹具用的一格(调用点那种:给键 / 标题 / 行 / 文件;不能往下长) </summary>
        private static 导图子项C 新造项(string 键, string 标题, int 行, string 文件) => new()
        {
            键 = 键, 标题 = 标题, 种类 = "调用者", 行 = 行, 文件 = 文件, 能往下长 = false,
        };

        /// <summary>
        /// H63-1 夹具:**同一个键 `K` 挂在两条枝上**(左 / 右各一个)—— 正是"跟着调用走"之后的真实形状:
        /// 本文件的方法既在**声明区**里有一个框(补红线时先建出来的那个),又在**调用链**上挂了一个框。
        /// 用来钉 `沿路找`(从根按路走)与 `找节点`(全树按键扫)在这时**给的不是同一个节点**。
        /// </summary>
        private static 导图模型C 重键模型() => new(
            new 导图子项C { 键 = "根", 标题 = "工程", 种类 = 导图种类C.工程, 文件 = "主.hb" },
            节 => 节.键 switch
            {
                "根" => [造项("左", "左框", "主.hb"), 造项("右", "右框", "主.hb")],
                "左" or "右" => [造项("K", "同一个键", "主.hb"), 造项(节.键 + "旁", "旁枝", "主.hb")],
                "K" => [造项("K2", "K 的子", "主.hb"), 造项("K2旁", "K 的另一个子", "主.hb")],
                "K2" => [造项("K3", "K2 的子", "主.hb")],
                _ => [],
            });

        /// <summary>
        /// H63-1 夹具:**同一条祖先链上出现两次"方法:左@1",但分属两份文件**(主.hb 在外、库.hb 在内)——
        /// 钉 `祖先里有(键, 文件)`:光比键会把库里那个误认成"这一枝上已经有主.hb 的那个了"。
        /// </summary>
        private static 导图模型C 同键异文件模型() => new(
            new 导图子项C { 键 = "文件:主.hb", 标题 = "主.hb", 种类 = "文件", 文件 = "主.hb" },
            节 => 节.键 switch
            {
                "文件:主.hb" => [造项("方法:左@1", "左(主.hb)", "主.hb")],
                "方法:左@1" => [造项("方法:左@1", "左(库.hb)", "库.hb")],
                _ => [],
            });

        private static int 层号(导图节点C 节)
        {
            int 层 = 0;
            for (var 父 = 节.父; 父 != null; 父 = 父.父) 层++;
            return 层;
        }

