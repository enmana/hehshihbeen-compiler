        #region 标准工程的"取值口径":按**内容**取那一样东西(行号当参照,不当地址)

        // 为什么要有这一小族(2026-10 那两批的实测教训):标准工程会被**重排 / 瘦身** ——
        //   · `Sample\中间层\示例06_数组与列表\主程序.hb`:排版器把单行块拆成多行(121 → 521 → 556 行);
        //   · `Sample\库\排序.hb`:头注释瘦身(方法行号整体前移)。
        // 那之后"第 142 行 / 第 44 行"这种按行号写死的问法会整族失效,可它要证的东西一个字没变
        // (还是"那一句语句 / 那一个变量 / 那一个方法")。所以口径改成:
        // **按内容把那一样东西取出来,再量它的行号对不对**——
        //   · 取不到、或者同名的不止一处 ⇒ 判据红(不糊);
        //   · 取到之后行号照旧逐项比(判据的强度一点没降)。
        private static 声明项C? 按名找变量(源码结构C 树, string 名)
        {
            var 命中 = 树.变量们.FindAll(v => v.名 == 名);
            return 命中.Count == 1 ? 命中[0] : null;
        }

        private static 方法节点C? 按名找方法(源码结构C 树, string 名)
        {
            var 命中 = 树.方法们.FindAll(m => m.名 == 名);
            return 命中.Count == 1 ? 命中[0] : null;
        }

        /// <summary> 一份文本里,某一行(1 基)的原样内容(去掉行尾 CR);越界给空串 </summary>
        private static string 行文(string 文本, int 行)
        {
            string[] 行集 = 文本.Split('\n');
            return 行 >= 1 && 行 <= 行集.Length ? 行集[行 - 1].TrimEnd('\r') : "";
        }

        /// <summary>
        /// 某一行"去掉行尾注释、再去掉收尾的分号"之后的样子 —— 判据用它把**写死的行号**钉到源码正文上:
        /// 行号可以随排版挪,但"第 364 行确实是 `整数 r = 0`"这件事必须当场验得出来。
        /// </summary>
        private static string 声明原文(string 文本, int 行)
        {
            string 净 = 源码声明扫描C.去行注释(行文(文本, 行)).Trim();
            return 净.EndsWith(';') ? 净[..^1].TrimEnd() : 净;
        }

        /// <summary>
        /// 一句**语句原文**(去掉行尾注释、去掉收尾分号)**现在在第几行**;找不到给 0。
        /// 排过版的那几份:H62 那批写在注释里的行号会失效,而"这一句"本身不会变。
        /// </summary>
        private static int 找原文行(string 文本, string 语句)
        {
            string 要找 = 语句.Trim().TrimEnd(';').TrimEnd();
            string[] 行集 = 文本.Split('\n');
            for (int i = 0; i < 行集.Length; i++)
                if (声明原文(文本, i + 1) == 要找) return i + 1;
            return 0;
        }

        /// <summary> 某个框的调用区里"第 行 行"那一格(没有就给 null;一格只有一个链节时才给得出链文本) </summary>
        private static 分区项C? 框内某行(框来源C? 框, int 行)
            => 框?.调用区.Find(x => x.行 == 行);

        /// <summary> 链文本的安全写法:那一格不在 / 链被 H63-6 摘空 ⇒ 给人话,不抛 </summary>
        private static string 链话(分区项C? 项)
            => 项 == null ? "(这一行不在这个框的调用区里)"
               : 项.链们.Count == 0 ? "(这一条被 H63-6 摘空了)"
               : 调用线C.链文本(项.链们[0]);

