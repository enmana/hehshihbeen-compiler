// ============================================================
// 文本处理一批的自检(R3-4 第二支,第239批)—— `Sample\库\string.hb` 第4批
//
//   纯 HB 库(不动 ISA / 关键字 / 语言面),所以这一组的钉法 = **真编真跑一段 HB 程序看输出**:
//     · 切分(每段的起 / 长写进调用方那两条数组)、段数(光数不建表)、段取(越界给空串)
//     · 连接(切分 + 连接 = 往返)、表装不下只写能放的、分隔符为空串整串一段
//     · 反转 / 重复 / 左补位 / 右补位(超宽不截断)/ 安全解析整数(越界给假且不动出参)
//     · 库文件头的口径**按源码钉住**(改了代码忘了改说明就红灯)
//
//   本批开工先量出来的三条语言边界也钉在这里(它们是"段表为什么是并排数组"的原因):
//     · **动态列表不能当参数传**(报"列表的地址不能取")、**不能当返回值**;
//     · **元素是字符串的列表不能进结构字段**(编译器拦着);
//     · **字符串参数 + 结构参数**同处一个函数头时,结构字段(列表)取下标编不过
//       (实测报"`XX` 不是字符串" / "`XX.XX` 不是列表/数组";字段名、参数名都换过,照样)。
//   要真正的"列表"那一支见 `未做任务清单.md` R3-3。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 文本处理自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 串路径 = Path.Combine(库目录, "string.hb").Replace('\\', '/');
            if (!File.Exists(串路径))
            {
                跳过("文本处理库 定位 Sample\\库\\string.hb", $"找不到 {串路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{串路径}\"\n";

            // 真编真跑一趟(与排序与查找自检同一套跑法:输出按 UTF-8 收、行尾换成 `|`)
            static string 跑(string 源, int 堆大小, int 池大小, int 软栈大小 = 32 * 1024)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 堆大小, null, 池大小,
                    虚拟机C.默认内存大小, 软栈大小);
                var vm = new 虚拟机C();
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }
            string 跑小(string 源) => 跑(源, 中间层C.默认堆大小, 中间层C.默认池大小);

            // ---- ① 切分:每段的起 / 长(含空段:下标 2 那一段长 0) ----
            记录("文本处理库 切分:把每段的「起 + 长」写进调用方那两条数组(空段也记账)",
                跑小(头 + "整数 起[8];\n整数 长[8];\n整数 个 = 切分(\"左,右,,中\", \",\", 起, 长);\n" +
                    "测试输出(个);\n整数 i = 0;\n当 (i < 个)\n{\n测试输出(起[i]);\n测试输出(长[i]);\ni = i + 1;\n}\n停止")
                    == "4|0|1|2|1|4|0|5|1",
                "4 段:(0,1)(2,1)(4,0)(5,1) —— 第 3 段是空段");

            // ---- ② 段取:按段号取回来;越界与负数给空串 ----
            记录("文本处理库 段取:首 / 尾取得到,越界(9)与负数(-1)给空串",
                跑小(头 + "整数 起[4];\n整数 长[4];\n切分(\"左,右,,中\", \",\", 起, 长);\n" +
                    "字符串 零 = 段取(\"左,右,,中\", 起, 长, 0);\n输出行(零);\n" +
                    "字符串 三 = 段取(\"左,右,,中\", 起, 长, 3);\n输出行(三);\n" +
                    "字符串 越 = 段取(\"左,右,,中\", 起, 长, 9);\n测试输出(越.长度());\n" +
                    "字符串 负 = 段取(\"左,右,,中\", 起, 长, -1);\n测试输出(负.长度());\n停止")
                    == "左|中|0|0",
                "第 0 段左 / 第 3 段中;越界与负数都是空串");

            // ---- ③ 段数:正常 / 没有分隔符 / 空串 / 分隔符为空串 ----
            记录("文本处理库 段数:4 / 1(没有分隔符)/ 1(空串也是 1 段)/ 1(分隔符为空串 ⇒ 整串一段)",
                跑小(头 + "测试输出(段数(\"左,右,,中\", \",\"));\n测试输出(段数(\"没有分隔符\", \",\"));\n" +
                    "测试输出(段数(\"\", \",\"));\n测试输出(段数(\"abc\", \"\"));\n停止")
                    == "4|1|1|1",
                "与 切分 / 取段 同一口径");

            // ---- ④ 连接:切分 + 连接 是个往返 ----
            记录("文本处理库 连接:切分 + 连接 拼回原来那条串(空段跟着分隔符一起露出来)",
                跑小(头 + "整数 起[8];\n整数 长[8];\n整数 个 = 切分(\"左,右,,中\", \",\", 起, 长);\n" +
                    "字符串 回 = 连接(\"左,右,,中\", 起, 长, 个, \"-\");\n输出行(回);\n停止")
                    == "左-右--中",
                "4 段用 `-` 拼回:左-右--中(第 3 段是空的,于是两个 `-` 挨着)");

            // ---- ⑤ 表装不下:只写能放的,返回实际写下的段数;`段数` 照旧报总数 ----
            记录("文本处理库 切分:数组只有 2 格时装不下 4 段 ⇒ 返回 2,而 段数 照旧报 4(先问一句就不会丢)",
                跑小(头 + "整数 起[2];\n整数 长[2];\n测试输出(切分(\"左,右,中,下\", \",\", 起, 长));\n" +
                    "测试输出(段数(\"左,右,中,下\", \",\"));\n停止")
                    == "2|4",
                "写下的段数 2 / 总段数 4");

            // ---- ⑥ 分隔符为空串:整串一段,长 = 主串长度 ----
            记录("文本处理库 切分:分隔符为空串 ⇒ 整串算一段(长 = 主串长度)",
                跑小(头 + "整数 起[2];\n整数 长[2];\n测试输出(切分(\"左右中\", \"\", 起, 长));\n" +
                    "测试输出(长[0]);\n停止")
                    == "1|3",
                "1 段,长 3(按文字算)");

            // ---- ⑦ 反转:按文字倒过来;空串给空串 ----
            记录("文本处理库 反转:按**文字**倒(中文一个字算一个),空串给空串",
                跑小(头 + "字符串 倒 = 反转(\"abc中\");\n输出行(倒);\n" +
                    "字符串 空 = 反转(\"\");\n测试输出(空.长度());\n停止")
                    == "中cba|0",
                "abc中 → 中cba(不是按字节倒)");

            // ---- ⑧ 重复:放 次 遍;次 <= 0 给空串 ----
            记录("文本处理库 重复:放 3 遍;0 与负数都给空串",
                跑小(头 + "字符串 三 = 重复(\"ab\", 3);\n输出行(三);\n" +
                    "字符串 零 = 重复(\"ab\", 0);\n测试输出(零.长度());\n" +
                    "字符串 负 = 重复(\"ab\", -2);\n测试输出(负.长度());\n停止")
                    == "ababab|0|0",
                "ababab / 0 / 0");

            // ---- ⑨ 补位:不足才补;够了或超了一律原样返回(不截断) ----
            记录("文本处理库 左补位 / 右补位:不足才补,超了一律原样返回(不截断)",
                跑小(头 + "字符串 补零 = 左补位(\"7\", 3, '0');\n输出行(补零);\n" +
                    "字符串 补点 = 右补位(\"7\", 3, '.');\n输出行(补点);\n" +
                    "字符串 宽了 = 左补位(\"abcd\", 2, '0');\n输出行(宽了);\n" +
                    "字符串 也宽 = 右补位(\"abcd\", 2, '.');\n输出行(也宽);\n停止")
                    == "007|7..|abcd|abcd",
                "7 → 007 / 7.. ;abcd 比宽度还长 ⇒ 原样");

            // ---- ⑩ 安全解析整数:整串必须正好合法且不越 32 位;失败不动出参 ----
            记录("文本处理库 安全解析整数:合法(含正号 / 前后空白)/ 带尾巴 / 空串 / 上界越界 / 下界边界 / 下界越界",
                跑小(头 + "整数 收 = 0;\n测试输出(安全解析整数(\"  -12 \", 收));\n测试输出(收);\n" +
                    "收 = 42;\n测试输出(安全解析整数(\"12x\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"\", 收));\n测试输出(安全解析整数(\"  \", 收));\n" +
                    "测试输出(安全解析整数(\"+7\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"2147483647\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"2147483648\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"-2147483648\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"-2147483649\", 收));\n测试输出(收);\n" +
                    "测试输出(安全解析整数(\"0x10\", 收));\n停止")
                    == "1|-12|0|42|0|0|1|7|1|2147483647|0|2147483647|1|-2147483648|0|-2147483648|0",
                "真-12 / 假不动 42 / 空串与全空白都假 / +7 真 / 上界真下界真;越界一律假且不动出参");

            // ---- ⑪ 库文件头的口径按源码钉住(改了代码忘了改说明就红灯) ----
            string 串文本 = File.ReadAllText(串路径);
            记录("文本处理库 头注释写清了口径(并排数组 / 三条语言边界 / 不截断 / 不动出参)",
                串文本.Contains("文本处理", StringComparison.Ordinal)
                && 串文本.Contains("不是列表/数组", StringComparison.Ordinal)
                && 串文本.Contains("不能当参数传", StringComparison.Ordinal)
                && 串文本.Contains("实际写下的段数", StringComparison.Ordinal)
                && 串文本.Contains("超了不截断", StringComparison.Ordinal),
                "并排数组的来由 / 三条边界原文 / 实际写下的段数 / 不截断");

            // ---- ⑫ R3-4 的验收数字:Sample\库 到 9 个库 + 示例18 标准工程在盘上 ----
            int 库数 = Directory.Exists(库目录) ? Directory.GetFiles(库目录, "*.hb").Length : 0;
            string 示例目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "中间层", "示例18_文本处理");
            bool 示例齐 = 仓库根 != null
                && File.Exists(Path.Combine(示例目录, "主程序.hb"))
                && File.Exists(Path.Combine(示例目录, "示例18_文本处理.hbp"));
            记录("基础库 Sample\\库 到 9 个库 + 示例18_文本处理 标准工程在盘上(R3-4 验收线:本批文本处理入库)",
                库数 >= 9 && 示例齐,
                $"{库数} 个 .hb(本批前是 8 个);示例18 {(示例齐 ? "齐" : "缺")}");
        }
    }
}
