using System;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// H28(2026-09-24 收口):两处**纯内部**的性能 / 结构改动 —— 行为一个字都不许变,这一组就是那句话的钉子。
    ///
    /// ① **汇编器槽表去重**(`引擎\汇编器C.cs` 的 `汇编已展开文本`):以前是
    ///    `槽序表.Any(x => x.名称 == …)` —— 每来一个槽就把已经收下的表从头扫一遍,槽多时是**槽数²**
    ///    (实测 2 万个槽 405 ms);现在换成一张 `HashSet`(`Add` 返回 false 就是有过)。
    /// ② **检查器的整词计数**(`引擎\检查器C.cs`):以前"声明了但没用到"那条规则是
    ///    **每个声明现编一个逐名字的正则、再把整份文件扫一遍**(`出现次数` 里 `new Regex(名字)`),
    ///    代价 ≈ 声明数 × 行数;现在是**全文走一遍**、边走去注释边数整词(实测 300 个声明 / 2803 行
    ///    由 75 ms 降到 4 ms)。口径不变:名字作为**整词**出现才算(`星星` 不算 `星`)。
    ///
    /// 钉的五件事:
    /// ① 数据槽仍按**声明序紧致累加**(首槽紧贴代码段末尾);
    /// ② 纯汇编那条兜底路(`_vN` 提多少次)仍**只留一格**;
    /// ③ 检查器整词口径逐条对(前缀 / 数字边界 / Unicode 数字 / 字符串 / 注释 / 多次出现);
    /// ④ 大输入(600 个声明)下「未使用」一条不少;
    /// ⑤ 「未使用」那条警告的**行列与文案**还是老样子(界面靠它画波浪线)。
    /// </summary>
    public static partial class 综合自检C
    {
        private static void 性能与结构自检()
        {
            // ---- ① 汇编器:数据槽按声明序紧致累加(去重换了实现,排布一个字没变) ----
            // 槽宽不是声明宽:`短整数` / `整数` 这种独立标量按 4 字节放(C 档宽槽,见 `中间层C.变量系统.cs`),
            // 只有 `字节` 真占 1 个字节 ⇒ 依次是 1 / 4 / 4 / 1,数据段 10 字节(实测口径,见 `任务清单.md` 第230节)。
            const string 四槽源 =
                "字节 b1 = 1;\n" +
                "短整数 s1 = 2;\n" +
                "整数 i1 = 3;\n" +
                "字节 b2 = 4;\n" +
                "停止\n";
            const string 槽排布名 = "H28 汇编器 数据槽按声明序紧致累加(1/4/4/1 挨着排,首槽紧贴代码段末尾)";
            try
            {
                var 结果 = 编译(四槽源);
                名字项C? 找(string 名) => 结果.名字表.变量.FirstOrDefault(项 => 项.是全局 && 项.名字 == 名);
                int 址(名字项C? 项) => 项 != null && 结果.标签表.TryGetValue(项.槽, out int 槽址) ? 槽址 : int.MinValue;
                var 项1 = 找("b1"); var 项2 = 找("s1"); var 项3 = 找("i1"); var 项4 = 找("b2");
                int 基 = 结果.代码字节数;
                记录(槽排布名,
                    址(项1) == 基 && 址(项2) == 基 + 1 && 址(项3) == 基 + 5 && 址(项4) == 基 + 9
                    && 结果.数据字节数 == 10,
                    $"数据段={结果.数据字节数} 字节;偏移 b1={址(项1) - 基} s1={址(项2) - 基} " +
                    $"i1={址(项3) - 基} b2={址(项4) - 基}(期望 0/1/5/9)");
            }
            catch (Exception ex) { 记录异常(槽排布名, ex); }

            // ---- ② 汇编器:同一个 `_vN` 提多少次,数据段都只留一格 ----
            const string 槽去重名 = "H28 汇编器 纯汇编里同一个 `_vN` 提一次与提三次,数据段都只留一格(4 字节)";
            try
            {
                var 一次 = new 汇编器C().汇编多文件带调试([("主程序.hb", "加载 R0, [_v1]\n停止\n")]);
                var 三次 = new 汇编器C().汇编多文件带调试(
                    [("主程序.hb", "加载 R0, [_v1]\n存储 R0, [_v1]\n加载 R1, [_v1]\n停止\n")]);
                int 格子数(汇编调试结果C 编) => 编.标签表.Count(kv => kv.Key == "_v1");
                记录(槽去重名,
                    一次.数据字节数 == 4 && 三次.数据字节数 == 4 && 格子数(一次) == 1 && 格子数(三次) == 1,
                    $"提一次:数据段 {一次.数据字节数} 字节 / `_v1` {格子数(一次)} 格;" +
                    $"提三次:数据段 {三次.数据字节数} 字节 / `_v1` {格子数(三次)} 格(期望都是 4 字节 1 格)");
            }
            catch (Exception ex) { 记录异常(槽去重名, ex); }

            // ---- ③ 检查器:整词计数的口径逐条对(老正则 `(?<![\p{L}\p{N}_])名(?![\p{L}\p{N}_])` 那一套) ----
            const string 口径名 = "H28 检查器 整词计数口径逐条对(前缀 / 数字边界 / Unicode 数字 / 字符串 / 注释)";
            try
            {
                (string 源, int[] 期望)[] 用例 =
                [
                    ("短整数 星 = 1;\n短整数 星星 = 2;\n输出行(星星);\n停止", [1]),                     // 前缀:星星 不算用到 星
                    ("短整数 ab = 1;\n输出行(ab1);\n停止", [1]),                                       // 数字边界:ab1 不算 ab
                    ("短整数 n = 1;\n输出行(n\u0662);\n停止", [1]),                                    // \p{N} 里的阿拉伯数字也算词字符
                    ("短整数 星 = 1;\n输出行(\"星\");\n停止", []),                                      // 字符串里算用到(老口径本来就把字符串留着)
                    ("短整数 星 = 1;\n// 星 只在注释里\n输出行(1);\n停止", [1]),                         // 注释里的不算
                    ("短整数 星 = 1;\n输出行(星);\n输出行(星);\n停止", []),                             // 多次出现:用到了
                ];
                var 不对 = new List<string>();
                foreach (var (源, 期望) in 用例)
                {
                    int[] 实得 = [.. 检查器C.检查(源, true).Where(x => x.规则 == "未使用").Select(x => x.行)];
                    if (!期望.SequenceEqual(实得))
                        不对.Add($"期望 [{string.Join(",", 期望)}] 实得 [{string.Join(",", 实得)}]");
                }
                记录(口径名, 不对.Count == 0,
                    不对.Count == 0 ? $"{用例.Length} 个用例全对" : string.Join(" | ", 不对));
            }
            catch (Exception ex) { 记录异常(口径名, ex); }

            // ---- ④ 检查器:名字很多时(600 个声明)一条不少 ----
            const string 大输入名 = "H28 检查器 600 个声明一次走完全文,600 条『未使用』一条不少";
            try
            {
                var 大源 = new StringBuilder();
                for (int i = 1; i <= 600; i++) 大源.Append("短整数 q").Append(i).Append(" = 1;\n");
                大源.Append("停止\n");
                var 秒 = System.Diagnostics.Stopwatch.StartNew();
                int 条数 = 检查器C.检查(大源.ToString(), true).Count(x => x.规则 == "未使用");
                秒.Stop();
                记录(大输入名, 条数 == 600, $"报出 {条数} 条(期望 600);耗时 {秒.ElapsedMilliseconds} ms");
            }
            catch (Exception ex) { 记录异常(大输入名, ex); }

            // ---- ⑤ 检查器:「未使用」那条警告的行列与文案没变(界面靠它画波浪线 / 悬停) ----
            const string 文案名 = "H28 检查器『未使用』警告的行列与文案照旧(起止列覆盖整个名字)";
            try
            {
                var 条 = 检查器C.检查("短整数 星 = 1;\n输出行(1);\n停止", true)
                    .FirstOrDefault(x => x.规则 == "未使用");
                记录(文案名,
                    条 != null && 条.行 == 1 && 条.起列 == 4 && 条.止列 == 5
                    && 条.级别 == 诊断级别.警告 && 条.文本.Contains("'星' 已声明,但整个文件中未再使用"),
                    条 == null ? "一条都没报" : $"第{条.行}行 [ {条.起列},{条.止列} ) {条.文本}");
            }
            catch (Exception ex) { 记录异常(文案名, ex); }
        }
    }
}
