using System;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 综合自检的一部分:**G3 域 2 —— HB 侧定时器库**(`Sample\库\定时.hb`)。
    ///
    /// 这一组盯的是库**自己的**四件事:
    /// ① **登记与查询**:号取最小空位、取消过的那一格会复用、`个数 / 在册 / 间隔` 说得清;
    /// ② **到点算**:每过一段的到点后自己排下一次、一次性的到点后自己摘掉;
    ///    一次跨过好几段时**只补一次**(不是"过几段补几次");
    /// ③ **回绕**(这一库最要紧的一条):`当前毫秒()` 只给低 32 位、约 49.7 天回到 0 ——
    ///    判据必须是"差值取模"(实测机器刻度已经是 3.6e7 这一量级,拿"比大小"写就是过几天必漏);
    /// ④ **确定性**:全篇喂 `推进到(刻度)`(不读机器钟)⇒ 同一份源码两次跑逐字节一致,优化开 / 关也一致。
    /// 最后是标准工程 `示例28_定时器` 那条路(自检内无头 + 命令行 `hbcc -p … --run`)逐行对 `// 预期输出:`。
    ///
    /// **零新宿主能力**:节拍就是 `当前毫秒()`(宿主功能号 55),定时表住库那边 ——
    /// 与 `基础库框架.md` 第7节写的"纯软件定时器"一字不差。
    /// </summary>
    public static partial class 综合自检C
    {
        // ================= G3 域 2:HB 侧定时器库 =================

        /// <summary>
        /// 跑一段用定时库的源码:库作为**另一个文件**内联进来(测试源码里不用写 `包含`)。
        /// 回来的是程序输出(逐行,末尾不留换行)。
        /// </summary>
        private static string 跑定时库源码(string 库文本, string 源码, bool 优化 = true)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(t => 缓冲.Append(t));
            var 编译结果 = new 汇编器C().汇编多文件带调试(
                [("定时.hb", 库文本), ("主程序.hb", 源码)], 优化);
            var vm = new 虚拟机C
            {
                输入源 = () => null,
                输出目标 = 解码.写,
                宿主调用 = 宿主能力C.处理,
                初值表 = 编译结果.初值表,
                取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址),
            };
            vm.运行(编译结果.机器码);
            解码.收尾();
            return 缓冲.ToString().Replace("\r\n", "\n").TrimEnd('\n');
        }

        private static void 定时库自检()
        {
            string? 示例 = 找示例目录();
            string? 库路径 = 示例 == null ? null : Path.Combine(示例, "库", "定时.hb");
            if (库路径 == null || !File.Exists(库路径))
            {
                跳过("定时器库 库文件落在 Sample\\库\\定时.hb(头注释就是帮助站点那一节)", $"找不到 {库路径 ?? "Sample 目录"}");
                return;
            }
            string 库文本 = File.ReadAllText(库路径);

            // ---- ① 库文件在位:头注释点了用法 / 十一个接口 / "零新宿主能力"那条口径 ----
            try
            {
                bool 有头注释 = 库文本.StartsWith("// ====", StringComparison.Ordinal)
                    && 库文本.Contains("包含 \"../../库/定时.hb\"", StringComparison.Ordinal);
                bool 接口齐 = 库文本.Contains("方法 每(") && 库文本.Contains("方法 一次(")
                    && 库文本.Contains("方法 取消(") && 库文本.Contains("方法 推进(")
                    && 库文本.Contains("方法 推进到(") && 库文本.Contains("方法 个数(")
                    && 库文本.Contains("方法 在册(") && 库文本.Contains("方法 间隔(")
                    && 库文本.Contains("方法 刻度(") && 库文本.Contains("方法 清空(");
                bool 口径在 = 库文本.Contains("当前毫秒", StringComparison.Ordinal)
                    && 库文本.Contains("单调", StringComparison.Ordinal)
                    && 库文本.Contains("回绕", StringComparison.Ordinal);
                记录("定时器库 库文件在位:头注释有用法 / 接口齐(每·一次·取消·推进·推进到·个数·在册·间隔·刻度·清空)/ " +
                    "口径写明『零新宿主能力 = 当前毫秒 + 软件定时器』",
                    有头注释 && 接口齐 && 口径在,
                    $"头注释 {有头注释};接口 {接口齐};口径 {口径在}");
            }
            catch (Exception ex) { 记录异常("定时器库 库文件与头注释", ex); }

            // ---- ② 登记 / 查询 / 取消与号复用 ----
            try
            {
                const string 源 =
                    "方法 干活(整数 号)\n{\n    返回\n}\n" +
                    "整数 每分钟号 = 定时.每(16, 地址(干活));\n" +
                    "整数 一次号 = 定时.一次(3000, 地址(干活));\n" +
                    "测试输出(每分钟号);\n测试输出(一次号);\n" +
                    "测试输出(定时.个数());\n" +
                    "测试输出(定时.间隔(每分钟号));\n" +
                    "测试输出(定时.间隔(一次号));\n" +
                    "测试输出(定时.在册(一次号));\n" +
                    "测试输出(定时.取消(一次号));\n" +
                    "测试输出(定时.取消(一次号));\n" +
                    "测试输出(定时.个数());\n" +
                    "测试输出(定时.间隔(一次号));\n" +
                    "整数 百毫秒号 = 定时.每(100, 地址(干活));\n" +
                    "测试输出(百毫秒号);\n" +
                    "测试输出(定时.取消(99));\n" +
                    "定时.清空();\n" +
                    "测试输出(定时.个数());\n" +
                    "停止\n";
                string 跑 = 跑定时库源码(库文本, 源);
                string 应有 = "0\n1\n2\n16\n3000\n1\n1\n0\n1\n-1\n1\n0\n0";
                记录("定时器库 登记 / 查询 / 取消:号取最小空位、取消过的那一格被下一个登记复用、" +
                    "取消两次给假、号越界给假、清空归零",
                    跑 == 应有,
                    跑 == 应有 ? "13 行逐行对上" : $"实际=<{跑.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("定时器库 登记与取消", ex); }

            // ---- ③ 到点算:每过一段的自己排下一次、一次性的自己摘掉、跨好几段只补一次 ----
            try
            {
                const string 源 =
                    "整数 心跳 = 0;\n整数 收手 = 0;\n" +
                    "方法 跳(整数 号)\n{\n    心跳 = 心跳 + 1;\n    返回\n}\n" +
                    "方法 收(整数 号)\n{\n    收手 = 收手 + 1;\n    返回\n}\n" +
                    "整数 心号 = 定时.每(16, 地址(跳));\n" +
                    "整数 收号 = 定时.一次(3000, 地址(收));\n" +
                    "测试输出(定时.推进到(0));\n" +
                    "测试输出(定时.推进到(15));\n" +
                    "测试输出(心跳);\n" +
                    "测试输出(定时.推进到(16));\n" +
                    "测试输出(定时.推进到(31));\n" +
                    "测试输出(定时.推进到(32));\n" +
                    "测试输出(心跳);\n" +
                    "测试输出(定时.推进到(400));\n" +
                    "测试输出(心跳);\n" +
                    "测试输出(定时.推进到(3000));\n" +
                    "测试输出(收手);\n" +
                    "测试输出(定时.推进到(3016));\n" +
                    "测试输出(收手);\n" +
                    "测试输出(定时.在册(收号));\n" +
                    "测试输出(定时.个数());\n" +
                    "测试输出(定时.刻度());\n" +
                    "停止\n";
                string 跑 = 跑定时库源码(库文本, 源);
                string 应有 = "0\n0\n0\n1\n0\n1\n2\n1\n3\n2\n0\n1\n0\n0\n1\n3016";                记录("定时器库 到点算:每 16 的按节拍走、3000 那个一次性的到点触发后就摘掉、" +
                    "一次跨过 368 个刻度也只补一次",
                    跑 == 应有,
                    跑 == 应有 ? "16 行逐行对上(心跳 16 → 32 → 400 → 3000 → 3016,共 3 次;" +
                        "3000 那一刻心跳与收手一起到,所以那一步是 2)"
                                : $"实际=<{跑.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");            }
            catch (Exception ex) { 记录异常("定时器库 到点算", ex); }

            // ---- ④ 回绕:`当前毫秒()` 只给低 32 位 —— 判据必须是"差值取模",不是"比大小" ----
            try
            {
                // 时钟跑到 4294967290(离回到 0 只差 6 个刻度),一个间隔 100 的定时器排在下一次。
                // 直接比大小:10 − 4294967290 = 负数 ⇒ 判"没到点"(得再等 49.7 天);
                // 差值取模:10 − 4294967290 = 16,没到点;到 110 那一刻 = 116 ≥ 100 ⇒ 到点。两条都要对。
                // 4294967290 写成 `0 - 6`(HB 的整数字面量是**有符号**的,直接写那个数会报越界)。
                const string 源二 =
                    "整数 次数 = 0;\n" +
                    "方法 记(整数 号)\n{\n    次数 = 次数 + 1;\n    返回\n}\n" +
                    "整数 近头 = 0 - 6;\n" +                    // = 4294967290(二进制补码)
                    "定时.每(100, 地址(记));\n" +
                    "测试输出(定时.推进到(近头));\n" +
                    "测试输出(定时.推进到(近头));\n" +
                    "测试输出(次数);\n" +
                    "测试输出(定时.推进到(10));\n" +
                    "测试输出(次数);\n" +
                    "测试输出(定时.推进到(110));\n" +
                    "测试输出(次数);\n" +
                    "停止\n";
                string 实际 = 跑定时库源码(库文本, 源二);
                string 应有 = "0\n0\n0\n0\n0\n1\n1";
                记录("定时器库 回绕:刻度从 4294967290 绕过 0 到 110 时,间隔 100 的照样到点" +
                    "(判据是『差值取模』;拿负数直接比大小就会漏,而且一漏就是一整个周期)",
                    实际 == 应有,
                    实际 == 应有 ? "围绕 0 那一圈 7 行逐行对上(绕过来之前 0 次、到 110 那一刻 1 次)"
                                  : $"实际=<{实际.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("定时器库 回绕", ex); }

            // ---- ⑤ 间隔 0:每一轮都触发(自检与"立刻做一次"用的那一档)----
            try
            {
                const string 源 =
                    "整数 次数 = 0;\n" +
                    "方法 记(整数 号)\n{\n    次数 = 次数 + 1;\n    返回\n}\n" +
                    "定时.每(0, 地址(记));\n" +
                    "测试输出(定时.推进到(5));\n" +
                    "测试输出(定时.推进到(5));\n" +
                    "测试输出(定时.推进到(5));\n" +
                    "测试输出(次数);\n" +
                    "停止\n";
                string 实际 = 跑定时库源码(库文本, 源);
                string 应有 = "1\n1\n1\n3";
                记录("定时器库 间隔 0:同一刻度喂几次就触发几次(『每一轮都做一次』那一档)",
                    实际 == 应有,
                    实际 == 应有 ? "4 行逐行对上"
                                  : $"实际=<{实际.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("定时器库 间隔 0", ex); }

            // ---- ⑥ 回调里能再登记一个(推进不是"边遍历边调")----
            try
            {
                const string 源 =
                    "整数 左走了 = 0;\n整数 右走了 = 0;\n" +
                    "方法 右(整数 号)\n{\n    右走了 = 右走了 + 1;\n    返回\n}\n" +
                    "方法 左(整数 号)\n{\n    左走了 = 左走了 + 1;\n    定时.每(50, 地址(右));\n    返回\n}\n" +
                    "定时.每(0, 地址(左));\n" +
                    "测试输出(定时.推进到(10));\n" +
                    "测试输出(定时.个数());\n" +
                    "测试输出(定时.推进到(100));\n" +
                    "测试输出(左走了);\n" +
                    "测试输出(右走了);\n" +
                    "停止\n";
                string 跑 = 跑定时库源码(库文本, 源);
                string 应有 = "1\n2\n2\n2\n1";
                记录("定时器库 回调里再登记一个:这一轮触发左(左又登记了右),下一轮右才轮到 —— " +
                    "『先挑出来再调』让表在变长时不错位",
                    跑 == 应有,
                    跑 == 应有 ? "5 行逐行对上(每 0 的左在刻度 10 / 100 各一轮 = 2 次;右登记在 100 那一刻,同刻度不再补一轮)"
                                : $"实际=<{跑.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("定时器库 回调里再登记", ex); }

            // ---- ⑦ 确定性:同一份源码两次跑逐字节一致(优化开 / 关也一致)----
            try
            {
                const string 源 =
                    "整数 次数 = 0;\n" +
                    "方法 记(整数 号)\n{\n    次数 = 次数 + 1;\n    返回\n}\n" +
                    "整数 每分钟号 = 定时.每(7, 地址(记));\n整数 一次号 = 定时.一次(30, 地址(记));\n" +
                    "整数 i = 0;\n当 (i < 40)\n{\n    测试输出(定时.推进到(i * 3));\n    i = i + 1;\n}\n" +
                    "测试输出(次数);\n测试输出(定时.个数());\n" +
                    "停止\n";
                string 一 = 跑定时库源码(库文本, 源);
                string 二 = 跑定时库源码(库文本, 源);
                string 三 = 跑定时库源码(库文本, 源, 优化: false);
                记录("定时器库 同一份源码两次跑逐字节一致(优化开 / 关也一致 —— 定时表全是确定的数据,不看机器钟)",
                    一 == 二 && 一 == 三 && 一.Length > 0,
                    $"两次输出 {一.Length} 字逐字节相同;优化关那一遍也一样(末行 = 个数 {一.Split('\n')[^1]})");
            }
            catch (Exception ex) { 记录异常("定时器库 确定性双跑", ex); }

            // ---- ⑧ 接线哨兵:库那头用的是 `当前毫秒()`(宿主功能号 55),不是 `当前时间()` ----
            try
            {
                bool 库用毫秒 = 库文本.Contains("当前毫秒()", StringComparison.Ordinal)
                    && !库文本.Contains("当前时间()", StringComparison.Ordinal);
                记录("定时器库 接线哨兵:节拍走 `当前毫秒()`(单调毫秒)、一节都不走 `当前时间()`(墙上秒)",
                    库用毫秒, 库用毫秒 ? "库源码里只有 当前毫秒()" : "库源码里出现了 当前时间() 或没有 当前毫秒()");
            }
            catch (Exception ex) { 记录异常("定时器库 接线哨兵", ex); }

            // ---- ⑨ 标准工程 示例28_定时器:自检这条路 + 命令行那条路逐行对预期输出 ----
            try
            {
                string? 文件 = 示例 == null ? null : Path.Combine(示例, "中间层", "示例28_定时器", "主程序.hb");
                if (文件 == null || !File.Exists(文件))
                {
                    跳过("定时器库 标准工程 示例28 逐行对预期输出", $"找不到 {文件 ?? "Sample 目录"}");
                    跳过("定时器库 CLI -p 示例28 --run 逐行对预期输出", "找不到标准工程");
                }
                else
                {
                    string[] 行表 = File.ReadAllLines(文件);
                    var 期望 = 解析预期输出(行表);
                    string 目录 = Path.GetDirectoryName(文件)!;
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 目录, 示例堆大小(目录));
                    string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望);
                    记录("定时器库 标准工程 示例28 逐行对预期输出(登记 / 到点 / 取消复用 / 清空;全篇喂指定刻度)",
                        实际 == 应有 && 期望.Count > 0,
                        实际 == 应有 ? $"{期望.Count} 行逐字对上"
                                      : $"实际=<{截断(实际, 200)}> 期望=<{截断(应有, 200)}>");

                    string? 编译器 = 找命令行编译器();
                    if (编译器 == null)
                        跳过("定时器库 CLI -p 示例28 --run 逐行对预期输出", "找不到 hbcc.dll(在 IDE 里跑自检时正常)");
                    else
                    {
                        var (码, 出, 误) = 跑命令行(编译器, 目录, 120_000, "-p", "示例28_定时器.hbp", "--run");
                        string 规范出 = 出.Replace("\r\n", "\n");
                        bool 过 = 码 == 0 && 规范出.Contains(应有, StringComparison.Ordinal);
                        记录("定时器库 CLI -p 示例28 --run 逐行对预期输出(命令行那条路与自检同一个入口)",
                            过, 过 ? $"退出码 0;{期望.Count} 行一行不落" : $"退出码 {码};{截断(误 + 出, 200)}");
                    }
                }
            }
            catch (Exception ex) { 记录异常("定时器库 标准工程与技术", ex); }
        }
    }
