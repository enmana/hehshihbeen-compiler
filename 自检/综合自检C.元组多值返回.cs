// 元组多值返回自检(H68-4,第321批)—— `返回 [被除 / 除数, 被除 % 除数];`
//
//   这一批只加**一处**能力:`返回` 后面直接写元组值(`[式子, 式子]`),成员按顺序算出来、
//   写进**调用方给的那块**(与结构返回同一套隐藏槽机制)。所以钉法 = 真编真跑看"读到的字段对不对":
//     · `返回 [式子, 式子]` → 调用方 `结果.项0` / `结果.项1` 读得到
//     · 元组值也认在**声明初值**(`[整数, 整数] 对 = [3 + 4, 6 * 2];`)与**整体赋值**
//       (`表[0] = [1 + 1, 2 * 2];`,含运行期下标左边)这两处 —— 三处共用同一个填块例程
//     · 成员式子里的变量 / 参数 / 别的调用结果都认(不是只收常量)
//     · 报错口径:成员个数不对 / 成员是整块(结构·数组·字符串)/ 普通结构返回仍要变量
//     · 帮助《中间层速查》把"元组值能写在哪三处"写成规格
//
//   为什么这么钉:这一批的价值全在"**不必先落一个局部变量**"—— 三个写法各来一条,
//   就说明那个填块例程在三条路上都真跑通了(与 H68-3 那条"机器码逐字节相同"互补)。
// ============================================================

using System;
using System.Linq;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 元组多值返回自检()
        {
            // ---- ① 返回 [式子, 式子] —— 调用方按字段读 ----
            跑输出断言("H68-4 多值返回:`返回 [被除 / 除数, 被除 % 除数];` 调用方按字段读得到(两个结果一份带走)",
                "方法 除法(整数 被除, 整数 除数) 返回 [整数, 整数]\n{\n返回 [被除 / 除数, 被除 % 除数];\n}\n" +
                "[整数, 整数] 结果 = 除法(9, 4);\n" +
                "测试输出(结果.项0);\n测试输出(结果.项1);\n" +
                "整数 商 = 结果.项0;\n整数 余 = 结果.项1;\n测试输出(商);\n测试输出(余);\n停止",
                "2\n1\n2\n1");

            // ---- ② 成员式子里的变量 / 参数 / 条件分支都认(不是只收常量) ----
            跑输出断言("H68-4 元组值里的成员是**任意式子**(参数运算 / 局部变量 / 分支里各返回一次)",
                "方法 换算(整数 秒) 返回 [整数, 整数]\n{\n整数 分 = 秒 / 60;\n返回 [分, 秒 % 60];\n}\n" +
                "方法 大在前(整数 左, 整数 右) 返回 [整数, 整数]\n{\n" +
                "如果 (左 > 右)\n{\n返回 [左, 右];\n}\n返回 [右, 左];\n}\n" +
                "[整数, 整数] 时分 = 换算(185);\n测试输出(时分.项0);\n测试输出(时分.项1);\n" +
                "[整数, 整数] 对 = 大在前(3, 8);\n测试输出(对.项0);\n测试输出(对.项1);\n停止",
                "3\n5\n8\n3");

            // ---- ③ 元组值在**声明初值**与**整体赋值**里也认(结构数组的元素按常量下标整体赋值也认) ----
            跑输出断言("H68-4 元组值三处共用:声明初值 / 整体赋值 / 数组元素(常量下标)整体赋值",
                "[整数, 整数] 对 = [3 + 4, 6 * 2];\n测试输出(对.项0);\n测试输出(对.项1);\n" +
                "[整数, 整数] 对二 = [0, 0];\n对二 = [对.项1 - 1, 5];\n测试输出(对二.项0);\n测试输出(对二.项1);\n" +
                "[整数, 整数] 表[2];\n表[0] = [1 + 1, 2 * 2];\n" +
                "表[1].项0 = 表[0].项0 + 1;\n表[1].项1 = 表[0].项1 + 10;\n" +
                "测试输出(表[1].项0);\n测试输出(表[1].项1);\n停止",
                "7\n12\n11\n5\n3\n14");

            // ---- ④ 报错:成员个数对不上 ----
            string 个数 = 异常文本(() => 汇编(
                "方法 少一个(整数 值) 返回 [整数, 整数]\n{\n返回 [值];\n}\n测试输出(少一个(1));\n停止"));
            记录("H68-4 元组值成员个数对不上:当场报「有 N 个成员,这里写了 M 个」+ 写法提示",
                个数.Contains("有 2 个成员,这里写了 1 个", StringComparison.Ordinal), 个数);

            // ---- ⑤ 报错:成员是整块(结构 / 数组 / 字符串)不收 ----
            string 整块成员 = 异常文本(() => 汇编(
                "结构 点\n{\n整数 x;\n整数 y;\n}\n方法 f() 返回 [点, 整数]\n{\n返回 [1, 2];\n}\n停止"));
            记录("H68-4 元组值的成员是整块时当场拦住(指路:先声明一份再对那个成员单独赋值)",
                整块成员.Contains("只收普通数值", StringComparison.Ordinal), 整块成员);

            // ---- ⑥ 普通结构返回照旧要"先算好赋给一个变量"(这一批**只**放开元组那一档) ----
            string 普通结构 = 异常文本(() => 汇编(
                "结构 点\n{\n整数 x;\n整数 y;\n}\n方法 取点() 返回 点\n{\n返回 [1, 2];\n}\n点 位置 = 取点();\n停止"));
            记录("H68-4 普通结构的返回照旧要一个同种结构的变量(元组那一档才放开字面量返回)",
                普通结构.Contains("结构必须是一个 点 变量/字段", StringComparison.Ordinal), 普通结构);

            // ---- ⑦ 帮助:《中间层速查》写明"元组值能写在哪三处" ----
            string 速查 = 帮助文本C.中间层速查();
            记录("帮助《中间层速查》写明 `返回 [式子, 式子]`(元组值三处:声明初值 / 整体赋值 / 返回)",
                速查.Contains("`返回 [被除 / 除数, 被除 % 除数];`", StringComparison.Ordinal)
                && 速查.Contains("**多值返回**:", StringComparison.Ordinal),
                "《中间层速查》数据那一节");

            // ---- ⑧ 标准工程 示例23_元组多值返回 的逐行对账:由「全示例」那三条自检统一跑
            //         (自动扫 Sample\**\*.hbp + `// 预期输出:`,本组不重复钉一遍) ----
        }
    }
}
