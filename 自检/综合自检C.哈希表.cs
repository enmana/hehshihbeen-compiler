// ============================================================
// 哈希表库自检(R1-5,第206批)—— `Sample\库\map.hb`
//
//   库是纯 HB(不动 ISA / 关键字 / 语言面),所以这一组的钉法 = **真编真跑一段 HB 程序看输出**:
//     · 哈希口径:FNV-1a 按**文字**算,几个已知值**按数钉住**(改算法就是红灯)
//     · 清空表 / 存放(只管写,不返回值;要判"新添还是改旧"先问 `有键`)/ 取出(引用参数收值)/ 有键 / 条目数 / 桶数
//     · 拉链撞冲突:两个键落同一个桶,两个都取得到;删掉一个不动另一个
//     · 桶数按需翻倍(8 → 16),翻倍之后老条目一个不丢
//     · 删除:真 / 再删假 / 有键假 / 条目数跟着掉
//     · 遍历:遍历器 + 遍历下一个(顺序确定,能写进预期)
//     · 中文键(哈希按文字算,中英混用)
//     · **一万个键**:全量取出逐个对值 + 删一半(**堆 640KB / 池 192KB** —— 一张一万条的表
//       大约要这么多地方,1MB 运行内存正好放得下;这是实测数字,见 `任务清单.md` 第206节)
//
//   为什么一万条那一条要单独给内存参数:默认堆 64KB 装不下一万条(条目三条列表 + 每个键的堆块),
//   跑出来是"堆放不下了"的**如实报错**而不是错误结果 —— 那条断言用工程里那套配(堆 640KB/池 192KB)。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 哈希表自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库路径 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库", "map.hb").Replace('\\', '/');
            if (!File.Exists(库路径))
            {
                跳过("哈希表库 定位 Sample\\库\\map.hb", $"找不到 {库路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{库路径}\"\n";

            // 真编真跑:输出按 UTF-8 收(遍历会打中文键),行尾换成 `|` 好写预期
            // 软栈给 32KB:一万条那条要 堆 640KB + 池 192KB,再用默认的 64KB 软栈就顶到 1MB 运行内存了
            static string 跑(string 源, int 堆大小, int 池大小, int 软栈大小 = 32 * 1024)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 堆大小, null, 池大小,
                    虚拟机C.默认内存大小, 软栈大小);
                var vm = new 虚拟机C();
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }
            string 跑小(string 源) => 跑(源, 中间层C.默认堆大小, 中间层C.默认池大小);

            // ---- ① 哈希口径:FNV-1a 按文字算,已知值按数钉住 ----
            记录("哈希表库 字符串哈希按文字算 FNV-1a(abc / 名字 / 空串 三个已知值)",
                跑小(头 + "无符号整数 散a = 字符串哈希(\"abc\");\n无符号整数 散b = 字符串哈希(\"名字\");\n" +
                    "无符号整数 散c = 字符串哈希(\"\");\n输出行(\"值\");\n测试输出(散a);\n测试输出(散b);\n测试输出(散c);\n停止")
                    == "值|440920331|2819865373|2166136261",
                "abc=440920331 / 名字=2819865373 / 空串=偏移基数(都用无符号变量接住再看)");

            // ---- ② 清空表 / 存放 / 有键 / 取出 / 条目数 / 桶数 ----
            //      期望串按这段源码里**8 个 `测试输出`** 逐项算出来 —— 原来盘上写的是 9 项(多了一个 `1`),
            //      `hbcc --run` 跑同一份源码给的就是下面这 8 项(批 16 复核过)。
            记录("哈希表库 清空表后是空的;存放只管写,有键问得出新添还是改旧",
                跑小(头 + "哈希表 表;\n清空表(表);\n测试输出(条目数(表));\n测试输出(桶数(表));\n" +
                    "测试输出(有键(表, \"name\"));\n存放(表, \"name\", 7);\n测试输出(有键(表, \"name\"));\n" +
                    "测试输出(有键(表, \"age\"));\n存放(表, \"age\", 42);\n" +
                    "测试输出(有键(表, \"name\"));\n存放(表, \"name\", 8);\n测试输出(条目数(表));\n测试输出(桶数(表));\n停止")
                    == "0|0|0|1|0|1|2|8",
                "空表 0 个 / 0 桶;第一次存放才开 8 个桶;有键 = 假(新添)/ 真(改旧)");
            记录("哈希表库 取出用引用参数收值;没有时给假且不动它",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"name\", 8);\n整数 收 = 1;\n" +
                    "测试输出(取出(表, \"name\", 收));\n测试输出(收);\n" +
                    "测试输出(取出(表, \"没有这个键\", 收));\n测试输出(收);\n" +
                    "测试输出(有键(表, \"name\"));\n测试输出(有键(表, \"没有这个键\"));\n停止")
                    == "1|8|0|8|1|0",
                "取到给 1 且写进 收;取不到给 0、收 不动");

            // ---- ③ 拉链撞冲突:xyz 与 id 在 8 个桶时都在 0 号桶 ----
            记录("哈希表库 撞冲突(同桶两个键)两个都取得到,删一个不动另一个",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"xyz\", 100);\n存放(表, \"id\", 200);\n" +
                    "整数 收 = 0;\n测试输出(桶数(表));\n" +
                    "测试输出(取出(表, \"xyz\", 收));\n测试输出(收);\n" +
                    "测试输出(取出(表, \"id\", 收));\n测试输出(收);\n" +
                    "测试输出(删除(表, \"xyz\"));\n测试输出(有键(表, \"xyz\"));\n" +
                    "测试输出(取出(表, \"id\", 收));\n测试输出(收);\n测试输出(条目数(表));\n停止")
                    == "8|1|100|1|200|1|0|1|200|1",
                "xyz 与 id 同落 0 号桶(哈希 %8 都是 0)");

            // ---- ④ 桶数自己翻倍(装载因子到一半),翻倍后老条目一个不丢 ----
            记录("哈希表库 装载因子到一半桶数翻倍,翻倍后老键全在",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"aa\", 0);\n存放(表, \"bb\", 1);\n" +
                    "存放(表, \"cc\", 2);\n存放(表, \"dd\", 3);\n存放(表, \"ee\", 4);\n" +
                    "测试输出(桶数(表));\n测试输出(条目数(表));\n" +
                    "整数 坏 = 0;\n整数 收 = 0;\n" +
                    "如果 (取出(表, \"aa\", 收) == 假 || 收 != 0)\n{\n坏 = 坏 + 1;\n}\n" +
                    "如果 (取出(表, \"cc\", 收) == 假 || 收 != 2)\n{\n坏 = 坏 + 1;\n}\n" +
                    "如果 (取出(表, \"ee\", 收) == 假 || 收 != 4)\n{\n坏 = 坏 + 1;\n}\n" +
                    "测试输出(坏);\n停止")
                    == "16|5|0",
                "5 条 → 桶数 8→16;老键逐个对值,坏 0");

            // ---- ⑤ 删除语义 ----
            记录("哈希表库 删除:真 / 再删假 / 有键假 / 条目数跟着掉",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"a\", 1);\n存放(表, \"b\", 2);\n" +
                    "测试输出(删除(表, \"a\"));\n测试输出(删除(表, \"a\"));\n测试输出(有键(表, \"a\"));\n" +
                    "测试输出(条目数(表));\n测试输出(删除(表, \"没有这个键\"));\n停止")
                    == "1|0|0|1|0",
                "删一次给 1,再删给 0;条目数 2→1");

            // ---- ⑥ 遍历:顺序确定(桶按号、链按挂的顺序) ----
            记录("哈希表库 遍历:遍历器 + 遍历下一个,键与值配对",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"name\", 7);\n存放(表, \"age\", 42);\n" +
                    "哈希遍历器 走;\n遍历开始(表, 走);\n当 (遍历下一个(表, 走))\n{\n" +
                    "输出行(条目键(表, 走.条目));\n测试输出(条目值(表, 走.条目));\n}\n" +
                    "测试输出(条目数(表));\n输出行(\"删一个再看\");\n删除(表, \"name\");\n" +
                    "遍历开始(表, 走);\n当 (遍历下一个(表, 走))\n{\n输出行(条目键(表, 走.条目));\n}\n停止")
                    == "age|42|name|7|2|删一个再看|age",
                "桶 6(name) 在桶 4(age) 之后 —— 顺序由桶号定");

            // ---- ⑦ 中文键(哈希按文字算) ----
            记录("哈希表库 中文键能用(与英文键混在一张表里)",
                跑小(头 + "哈希表 表;\n清空表(表);\n存放(表, \"name\", 7);\n存放(表, \"符号\", 100);\n存放(表, \"名字\", 200);\n" +
                    "整数 收 = 0;\n测试输出(取出(表, \"符号\", 收));\n测试输出(收);\n" +
                    "测试输出(取出(表, \"名字\", 收));\n测试输出(收);\n测试输出(条目数(表));\n停止")
                    == "1|100|1|200|3",
                "中英混用");

            // ---- ⑧ 一万个键:全量取出对值 + 删一半 ----
            //     键用**一个复用的字符串**拼出来(`拼接到` 到一个循环外声明的字符串):
            //     池不回收,每轮新造一个字符串会把池吃光 —— 这不是库的事,是池的口径(见 R1-2)。
            string 一万 = 头 +
                "方法 造键(字符串 出 键, 整数 号)\n{\n" +
                "字符 位3 = '0' + (号 / 1000) % 10;\n字符 位2 = '0' + (号 / 100) % 10;\n" +
                "字符 位1 = '0' + (号 / 10) % 10;\n字符 位0 = '0' + 号 % 10;\n" +
                "键.清空();\n拼接到(键, 'k');\n拼接到(键, 位3);\n拼接到(键, 位2);\n拼接到(键, 位1);\n拼接到(键, 位0);\n返回\n}\n" +
                "哈希表 表;\n清空表(表);\n字符串 键;\n整数 i = 0;\n当 (i < 10000)\n{\n造键(键, i);\n存放(表, 键, i * 3);\ni = i + 1;\n}\n" +
                "测试输出(条目数(表));\n测试输出(桶数(表));\n整数 坏 = 0;\n整数 收 = 0;\ni = 0;\n" +
                "当 (i < 10000)\n{\n造键(键, i);\n如果 (取出(表, 键, 收) == 假 || 收 != i * 3)\n{\n坏 = 坏 + 1;\n}\ni = i + 1;\n}\n" +
                "测试输出(坏);\ni = 0;\n当 (i < 10000)\n{\n造键(键, i);\n删除(表, 键);\ni = i + 2;\n}\n" +
                "测试输出(条目数(表));\n测试输出(有键(表, \"k0000\"));\n测试输出(有键(表, \"k0001\"));\n停止";
            记录("哈希表库 一万个键:全量取出对值 + 删一半(堆 640KB / 池 192KB)",
                跑(一万, 640 * 1024, 192 * 1024) == "10000|32768|0|5000|0|1",
                "条目数 10000 / 桶数 32768 / 取不出 0 / 删一半剩 5000");

            // ---- ⑨ 库文件头的口径按源码钉住(免得以后改了代码忘了改说明) ----
            string 库文本 = File.ReadAllText(库路径);
            记录("哈希表库 头注释写清了口径(拉链 / 键池只增不减 / 桶数用按位与)",
                库文本.Contains("冲突用**拉链**", StringComparison.Ordinal)
                && 库文本.Contains("键池只增不减", StringComparison.Ordinal)
                && 库文本.Contains("& (桶数 - 1)", StringComparison.Ordinal)
                && 库文本.Contains("桶数按需翻倍", StringComparison.Ordinal),
                "拉链 / 键池 / 按位与 / 翻倍 四句话都在");
        }
    }
}
