// ============================================================
// 目录库的自检(R3-4 第三支,第240批)—— `Sample\库\目录.hb`
//
//   纯 HB 库(不动 ISA / 关键字 / 语言面),所以这一组的钉法分两半:
//     · **纯函数**那一半(路径拼接 / 去尾分隔 / 取文件名 / 取目录 / 取后缀 / 是绝对路径 /
//       条目数 / 取条目 / 条目到表)= 真编真跑一段 HB 程序看输出;
//     · **真查盘**那一半(列出 / 数出 走 `列目录`)= 挂上 `宿主能力C.处理`,在
//       `工具\临时\目录库自检_<进程号>` 里真建目录 / 写文件 / 列 / 删,跑完由 C# 侧收尾删干净
//       (带进程号:R4-4 那条"两个自检同时跑会互删临时目录"的教训)。
//
//   本批开工先量出来的两条语言边界也钉在这里(它们是"列出为什么不走出参"的原因):
//     · **`引用 字符串` 编不过** —— 报"引用指向的类型不认识: '字符串'"(`引用` 只认数字类型与结构);
//     · **`列目录` 的第三个参数(上限)要编译期常量** —— 报"要写一个编译期就定下来的数字(1 ~ 1048576 字节)"
//       ⇒ 上限由库写死 65536。
//   要真正的"列表能取地址 / 能当参数传"那一支见 `未做任务清单.md` R3-3。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 目录库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 库路径 = Path.Combine(库目录, "目录.hb").Replace('\\', '/');
            if (!File.Exists(库路径))
            {
                跳过("目录库 定位 Sample\\库\\目录.hb", $"找不到 {库路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{库路径}\"\n";

            // 真编真跑一趟(与排序与查找 / 文本处理自检同一套跑法:输出按 UTF-8 收、行尾换成 `|`)
            static string 跑(string 源, int 堆大小, int 池大小, int 软栈大小 = 32 * 1024)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 堆大小, null, 池大小,
                    虚拟机C.默认内存大小, 软栈大小);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };   // 列目录 / 建目录 / 写文件 / 删文件 要挂宿主
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                string 报错 = 编译.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
            }
            string 跑小(string 源) => 跑(源, 中间层C.默认堆大小, 中间层C.默认池大小);

            // ---- ① 路径拼接:中间斜杠正好一个;名字前面带斜杠也认;空名字给原目录 ----
            记录("目录库 路径拼接:中间斜杠正好一个(名字带 / 或不带都认),名字为空给原目录",
                跑小(头 + "输出行(目录.路径拼接(\"a/b/\", \"c.txt\"));\n" +
                    "输出行(目录.路径拼接(\"a\", \"c.txt\"));\n" +
                    "输出行(目录.路径拼接(\"a/\", \"/c.txt\"));\n" +
                    "输出行(目录.路径拼接(\"a\", \"\"));\n" +
                    "输出行(目录.路径拼接(\"\", \"c.txt\"));\n停止")
                    == "a/b/c.txt|a/c.txt|a/c.txt|a|c.txt",
                "三种接法 + 两个空参数");

            // ---- ② 去尾分隔:末尾多个斜杠都去掉;整个路径都是斜杠时留一个(根) ----
            记录("目录库 去尾分隔:末尾多余的 / 与 \\ 去掉;整个路径都是分隔符时留一个(根)",
                跑小(头 + "输出行(目录.去尾分隔(\"a/b///\"));\n" +
                    "输出行(目录.去尾分隔(\"a\\\\b\\\\\"));\n" +
                    "输出行(目录.去尾分隔(\"///\"));\n" +
                    "输出行(目录.去尾分隔(\"a\"));\n停止")
                    == "a/b|a\\b|/|a",
                "两种分隔符都认;根本身不被削成空串");

            // ---- ③ 取文件名:两种分隔符都认;以分隔符结尾给空串 ----
            记录("目录库 取文件名:/ 与 \\ 都算分隔符;以分隔符结尾给空串",
                跑小(头 + "输出行(目录.取文件名(\"a/b/c.txt\"));\n" +
                    "输出行(目录.取文件名(\"a\\\\b\\\\c.txt\"));\n" +
                    "字符串 尾 = 目录.取文件名(\"a/b/\");\n测试输出(尾.长度());\n" +
                    "输出行(目录.取文件名(\"c.txt\"));\n停止")
                    == "c.txt|c.txt|0|c.txt",
                "c.txt / c.txt / 空 / c.txt");

            // ---- ④ 取目录:没有分隔符给空串;分隔符在开头给那一个(根) ----
            记录("目录库 取目录:最后一段之前的部分(没有分隔符给空串,根给那一个分隔符)",
                跑小(头 + "输出行(目录.取目录(\"a/b/c.txt\"));\n" +
                    "输出行(目录.取目录(\"/a\"));\n" +
                    "字符串 无 = 目录.取目录(\"abc\");\n测试输出(无.长度());\n" +
                    "输出行(目录.取目录(\"a/b/\"));\n停止")
                    == "a/b|/|0|a/b",
                "a/b / / / 空 / a/b");

            // ---- ⑤ 取后缀:最后一个点之后;没有点、点在头尾一律空串 ----
            记录("目录库 取后缀:最后一个 '.' 之后;没有点 / 隐藏文件(.gitignore)/ 点在末尾都给空串",
                跑小(头 + "输出行(目录.取后缀(\"a/b/c.tar.gz\"));\n" +
                    "字符串 无点 = 目录.取后缀(\"a/没有点\");\n测试输出(无点.长度());\n" +
                    "字符串 隐 = 目录.取后缀(\"a/.gitignore\");\n测试输出(隐.长度());\n" +
                    "字符串 尾 = 目录.取后缀(\"a/末尾点.\");\n测试输出(尾.长度());\n停止")
                    == "gz|0|0|0",
                "gz / 空 / 空 / 空");

            // ---- ⑥ 是绝对路径:开头分隔符,或第二个字符是 ':' ----
            记录("目录库 是绝对路径:'/' 或 '\\' 开头、第二个字符是 ':' 都算;相对路径与空串不算",
                跑小(头 + "测试输出(目录.是绝对路径(\"/x\"));\n" +
                    "测试输出(目录.是绝对路径(\"C:/x\"));\n" +
                    "测试输出(目录.是绝对路径(\"x/y\"));\n" +
                    "测试输出(目录.是绝对路径(\"\"));\n停止")
                    == "1|1|0|0",
                "1 / 1 / 0 / 0");

            // ---- ⑦ 条目数:空串给 0;末尾那个换行不算新条目 ----
            记录("目录库 条目数:空串 0、单条 1、两条 2、末尾带换行仍是 2(那个空段不算)",
                跑小(头 + "测试输出(目录.条目数(\"\"));\n" +
                    "测试输出(目录.条目数(\"a.txt\"));\n" +
                    "测试输出(目录.条目数(\"a.txt\\nb.txt\"));\n" +
                    "测试输出(目录.条目数(\"a.txt\\nb.txt\\n\"));\n停止")
                    == "0|1|2|2",
                "0 / 1 / 2 / 2");

            // ---- ⑧ 取条目:第 n 条(从 0 起);越界与负数给空串 ----
            记录("目录库 取条目:第 0 / 第 1 条取得到;越界(9)与负数(-1)给空串",
                跑小(头 + "输出行(目录.取条目(\"a.txt\\nb.txt\", 0));\n" +
                    "输出行(目录.取条目(\"a.txt\\nb.txt\", 1));\n" +
                    "字符串 越 = 目录.取条目(\"a.txt\\nb.txt\", 9);\n测试输出(越.长度());\n" +
                    "字符串 负 = 目录.取条目(\"a.txt\\nb.txt\", -1);\n测试输出(负.长度());\n停止")
                    == "a.txt|b.txt|0|0",
                "a.txt / b.txt / 空 / 空");

            // ---- ⑨ 条目到表:每条写进"起 + 长"两条并排数组,取回来对得上 ----
            记录("目录库 条目到表:每条写进调用方那两条并排数组(起 + 长),取回来与 取条目 一致",
                跑小(头 + "字符串 清单 = \"a.txt\\nb.txt\";\n整数 起[4];\n整数 长[4];\n" +
                    "整数 条 = 目录.条目到表(清单, 起, 长);\n测试输出(条);\n" +
                    "输出行(取子串(清单, 起[0], 长[0]));\n输出行(取子串(清单, 起[1], 长[1]));\n" +
                    "整数 空 = 目录.条目到表(\"\", 起, 长);\n测试输出(空);\n停止")
                    == "2|a.txt|b.txt|0",
                "2 条 + 两条文字 + 空清单给 0");

            // ---- ⑩ 真盘闭环:建目录 / 写两个文件 / 列出 / 数 / 取 / 删文件 / 删目录 ----
            // 名字用 **Guid** 而不是"进程号":进程号会**回收**,上一趟留下的目录会被下一趟撞上
            // ⑪ 那条"不存在的目录给 -1"就当场变红(2026-09-25 实测踩到:盘上留了 88 个 `..._不存在`);
            // 收尾时**两个目录都删**(`临时根` 与 ⑪ 自己造的 `临时根_不存在`)—— 硬规矩 15:自己建的要自己收。
            string 临时根 = 仓库根 == null
                ? ""
                : Path.Combine(仓库根, "工具", "临时", $"目录库自检_{Guid.NewGuid().ToString("N")[..8]}").Replace('\\', '/');
            try
            {
                记录("目录库 真盘闭环:建目录 + 写两个文件 ⇒ 列出/条目数/取条目都对;删空后 删目录 成功",
                    临时根.Length > 0 && 跑小(头 + $"字符串 临时 = \"{临时根}\";\n" +
                        "输出行(建目录(临时));\n" +
                        "字符串 左路径 = 目录.路径拼接(临时, \"a.txt\");\n字符串 右路径 = 目录.路径拼接(临时, \"b.txt\");\n" +
                        "输出行(写文件(左路径, \"左内容\"));\n输出行(写文件(右路径, \"右内容\"));\n" +
                        "字符串 清单 = 目录.列出(临时);\n测试输出(目录.条目数(清单));\n" +
                        "输出行(目录.取条目(清单, 0));\n输出行(目录.取条目(清单, 1));\n" +
                        "测试输出(目录.数出(临时));\n" +
                        "输出行(删文件(左路径));\n输出行(删文件(右路径));\n" +
                        "输出行(目录.数出(临时));\n输出行(删目录(临时));\n停止")
                        == "1|1|1|2|a.txt|b.txt|2|1|1|0|1",
                    "1|1|1|2|a.txt|b.txt|2|1|1|0|1(删空目录成功)");

                // ---- ⑪ 失败与空目录要分得开:列不成给 -1 / 空串,空目录给 0 ----
                记录("目录库 列出 / 数出:不存在的目录给空串与 -1;空目录给 0(两个口径分得开)",
                    跑小(头 + $"字符串 没有 = \"{临时根}_不存在\";\n" +
                        "测试输出(目录.数出(没有));\n" +
                        "字符串 空单 = 目录.列出(没有);\n测试输出(空单.长度());\n" +
                        "字符串 空目录 = 目录.路径拼接(没有, \"空的\");\n" +
                        "输出行(建目录(空目录));\n" +
                        "测试输出(目录.数出(空目录));\n" +
                        "输出行(删目录(空目录));\n停止")
                        == "-1|0|1|0|1",
                    "-1 / 空串 / 建目录 1 / 空目录 0 / 删目录 1");
            }
            finally
            {
                // ⑪ 自己造的那个 `_不存在` 也要收(以前只收 `临时根`,那 88 个空目录就是这么留下的)
                foreach (string 收 in new[] { 临时根, 临时根 + "_不存在" })
                {
                    try { if (收.Length > 0 && Directory.Exists(收)) Directory.Delete(收, true); }
                    catch { /* 收尾失败不影响判据 */ }
                }
            }

            // ---- ⑫ 库文件头的口径按源码钉住(改了代码忘了改说明就红灯) ----
            string 库文本 = File.ReadAllText(库路径);
            记录("目录库 头注释写清了口径(两条语言边界 / 上限 65536 / 本层不递归)",
                库文本.Contains("目录与路径库", StringComparison.Ordinal)
                && 库文本.Contains("引用指向的类型不认识", StringComparison.Ordinal)
                && 库文本.Contains("编译期常量", StringComparison.Ordinal)
                && 库文本.Contains("65536", StringComparison.Ordinal)
                && 库文本.Contains("递归", StringComparison.Ordinal),
                "两条边界原文 / 上限 / 不递归");

            // ---- ⑬ R3-4 的验收数字:Sample\库 到 10 个库 + 示例19 标准工程在盘上 ----
            int 库数 = Directory.Exists(库目录) ? Directory.GetFiles(库目录, "*.hb").Length : 0;
            string 示例目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "中间层", "示例19_目录遍历");
            bool 示例齐 = 仓库根 != null
                && File.Exists(Path.Combine(示例目录, "主程序.hb"))
                && File.Exists(Path.Combine(示例目录, "示例19_目录遍历.hbp"));
            记录("基础库 Sample\\库 到 10 个库 + 示例19_目录遍历 标准工程在盘上(R3-4 验收线:本批目录入库)",
                库数 >= 10 && 示例齐,
                $"{库数} 个 .hb(本批前是 9 个);示例19 {(示例齐 ? "齐" : "缺")}");
        }
    }
}
