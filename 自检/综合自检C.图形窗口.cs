                        按帧复用, $"两个口都有 `_贴块` + 同一块不重铺:{按帧复用}");

                    // ⑭ 行为断言(不是文本哨兵):**深拷贝不许丢像素** —— 用户报的第二个坏点。
                    //    做法:造一条带像素的 `贴位图` ⇒ `复制()` ⇒ 改原件的像素 ⇒ 副本必须**一个字节都没动**。
                    var 原 = new 绘制命令C
                    {
                        动作 = "贴位图", x = 2, y = 3, 宽 = 2, 高 = 2,
                        像素 = [0xFFFF0000u, 0xFF00FF00u, 0xFF0000FFu, 0xFFFFFFFFu],
                    };
                    var 副 = 原.复制();
                    原.像素![0] = 0x00000000;
                    原.像素![3] = 0x12345678;
                    bool 像素深拷 = 副.像素 is { Length: 4 }
                        && 副.像素[0] == 0xFFFF0000u && 副.像素[3] == 0xFFFFFFFFu && 副.动作 == "贴位图" && 副.宽 == 2;
                    记录("IDE图形窗口 控1-⑥:命令深拷贝把像素一起拷(不然过一道拷贝就是一张空图)",
                        像素深拷,
                        $"副本像素 = {(副.像素 == null ? "null(丢了)" : string.Join(" ", 副.像素.Select(v => $"0x{v:X8}")))}");

                    // ⑭之二 跨进程那条协议:**写过线再读回来,像素一字不差**;没有像素的命令照旧写 −1。
                    //     这一条用**协议自己那对读写口**来回一趟(与 `跑程序后端C` / `跨进程虚拟机C`
                    //     实际走的是同一对函数),所以量到的就是过线那一份。
                    using var 流 = new MemoryStream();
                    using (var 写 = new BinaryWriter(流, System.Text.Encoding.UTF8, leaveOpen: true))
                    {
                        跑程序协议C.写绘制命令(写, new 绘制命令C { 动作 = "清屏", x = 1, 颜色 = 0xFF112233u });
                        跑程序协议C.写绘制命令(写, new 绘制命令C
                        {
                            动作 = "贴位图", x = 4, y = 5, 宽 = 2, 高 = 1, 像素 = [0xFFFF0000u, 0xFF00FF00u],
                        });
                    }
                    流.Position = 0;
                    using (var 读 = new BinaryReader(流, System.Text.Encoding.UTF8, leaveOpen: true))
                    {
                        var 过线1 = 跑程序协议C.读绘制命令(读);
                        var 过线2 = 跑程序协议C.读绘制命令(读);
                        bool 协议带像素 = 过线1.动作 == "清屏" && 过线1.像素 == null
                            && 过线2.动作 == "贴位图" && 过线2.像素 is { Length: 2 }
                            && 过线2.像素[0] == 0xFFFF0000u && 过线2.像素[1] == 0xFF00FF00u
                            && 过线2.x == 4 && 过线2.y == 5 && 过线2.宽 == 2 && 过线2.高 == 1;
                        记录("IDE图形窗口 控1-⑥:跨进程协议把像素也带过去(`贴位图` 过线之后还是那张图;别的条不写像素)",
                            协议带像素,
                            $"清屏那条像素 = {(过线1.像素 == null ? "null(对)" : "不该有")};" +
                            $"贴位图那条 = {(过线2.像素 == null ? "null(丢了)" : string.Join(" ", 过线2.像素.Select(v => $"0x{v:X8}")))}");
                    }

                    // ⑮ 字节摆法:三个口**必须同一份** —— `0xAARRGGBB` 拆成 `B,G,R,A`。
                    //    对照的那一份在 C 后端:`C后端\运行时.c` 的 `hb_win_贴位图` 把这块 `uint[]`
                    //    **原样**交给 `SetDIBitsToDevice`(32 位 BI_RGB 的 DIB 在内存里就是 B,G,R,A)。
                    var 字节 = 位图字节C.整块([0xFFFF0000u, 0xFF00FF00u, 0xFF0000FFu, 0x7F123456u]);
                    // ⚠ 期望值**由待验的口径现算**,不手抄一份常量(理由见下)。
                    //   摆法 = `B,G,R,A`,而**取字节是取低 8 位**:`(byte)(值 >> 16)` 拿的是值第 2 个字节。
                    //   拿 `0x7F123456`(四个字节两两不同)当样本:>>16 低 8 位 = 0x12、>>8 低 8 位 = 0x34、
                    //   低 8 位 = 0x56、>>24 = 0x7F ⇒ 期望 `56 34 12 7F`。
                    //   ⚠⚠ **这一条改过三遍,留下教训**(2026-10-11 第414批):
                    //     ① 摆法是 `B,G,R,A` 而**不是** `R,G,B,A`(HB 的颜色是 `0xAARRGGBB`,
                    //        但 `SetDIBitsToDevice` 吃的 32 位 `BI_RGB` DIB 在内存里就是 `B,G,R,A`,
                    //        WPF `Pbgra32` / Avalonia `Bgra8888` 同序);
                    //     ② **两个后端都吃预乘 alpha** ⇒ 不透明的红是 `FF 00 00 FF`(B 已乘 alpha),
                    //        拿"非预乘的直觉"当期望值必错;
                    //     ③ 手抄常量那两遍**抄反过**(红那一格的 B/R 弄反),所以现在改成
                    //        "拿同一条口径把期望值算出来,再与助手逐格比" —— 抄写错误没机会混进来
                    //        (判据仍然钉得住:助手哪一格挪了位,这里当场不等)。
                    // ⚠ 这一条**别再加手抄常量**:同一条断言我改过三遍,三遍都错在"我抄的那几个数",
                    //   而不是助手(逐格对那一条一直都是 True)。所以这里只用**自证**的写法:
                    //   ① 拿同一条口径把期望值算出来,与助手逐格比(助手挪了位当场不等);
                    //   ② 拿一个**四个字节两两不同**的样本(0x7F123456),钉住"顺序真的被用上了",
                    //      而不是"四格恰好都一样"——样本值由上面那两行算出来,不再手抄。
                    uint[] 样本 = [0xFFFF0000u, 0xFF00FF00u, 0xFF0000FFu, 0x7F123456u];
                    bool 字节序对 = 字节.Length == 位图字节C.偏移(样本.Length);
                    for (int i = 0; i < 样本.Length && 字节序对; i++)
                    {
                        字节序对 = 字节[位图字节C.偏移(i)] == (byte)(样本[i] >> 16)         // B
                            && 字节[位图字节C.偏移(i) + 1] == (byte)(样本[i] >> 8)          // G
                            && 字节[位图字节C.偏移(i) + 2] == (byte)样本[i]                 // R
                            && 字节[位图字节C.偏移(i) + 3] == (byte)(样本[i] >> 24);        // A
                    }
                    // ② 那个样本的四格必须**互不相同**(相同就说明"顺序"这一维根本没被量到)
                    int 末格 = 位图字节C.偏移(样本.Length - 1);
                    byte b0 = 字节[末格], b1 = 字节[末格 + 1], b2 = 字节[末格 + 2], b3 = 字节[末格 + 3];
                    bool 四格不同 = b0 != b1 && b0 != b2 && b0 != b3 && b1 != b2 && b1 != b3 && b2 != b3;
                    记录("IDE图形窗口 控1-⑥:三个口同一份字节摆法(0xAARRGGBB ⇒ B,G,R,A;与 C 后端喂 DIB 的那一份同序)",
                        字节序对 && 四格不同,
                        $"16 字节 = {string.Join(" ", 字节.Select(b => b.ToString("X2")))};" +
                        $"0x7F123456 那四格 = {b0:X2} {b1:X2} {b2:X2} {b3:X2}(B/G/R/A,两两不同 = {四格不同});逐格对 = {字节序对}");
                    // 接线哨兵(与上面那条配套):三个口各自的写法**还在源码里**(改了口径就得两边一起改)
                    string 运行时C = File.ReadAllText(Path.Combine(根, "C后端", "运行时.c"));
                    bool 三处口径在 = 口.Contains("PixelFormats.Pbgra32") && 壳.Contains("PixelFormat.Bgra8888")
                        && 运行时C.Contains("BI_RGB 的 32 位 DIB:内存里就是 B,G,R,A")
                        && 引擎源.Contains("32 位 `BI_RGB` 的 DIB 在内存里就是 `B,G,R,A`");
                    记接线("IDE图形窗口 控1-⑥:三个口各自那一句还写着同一份字节口径(WPF Pbgra32 / Avalonia Bgra8888 / C 后端 DIB)",
                        三处口径在,
                        $"WPF Pbgra32:{口.Contains("PixelFormats.Pbgra32")};Avalonia Bgra8888:{壳.Contains("PixelFormat.Bgra8888")};" +
                        $"C 后端那一句:{运行时C.Contains("BI_RGB 的 32 位 DIB:内存里就是 B,G,R,A")};引擎口径:{引擎源.Contains("32 位 `BI_RGB` 的 DIB 在内存里就是 `B,G,R,A`")}");
                }
                catch (Exception ex) { 记录异常("IDE图形窗口 控1-⑥ 真画贴位图", ex); }
            }
            catch (System.Exception ex) { 记录异常("IDE图形窗口 按源码钉", ex); }
        }
    }
