        /// <summary> 批 19 那一块 512 字节确定性数据里的第 i 个字节(`b(i) = (i * 37 + 11) % 256`) </summary>
        private static byte 批19字节(int i) => (byte)((i * 37 + 11) % 256);

        /// <summary> C# 侧**独立**的 CRC-32(逐位,不走表;多项式 0xEDB88320 反射) </summary>
        private static uint 批19CRC32(byte[] 数据, int 个数)
        {
            uint 值 = 0xFFFFFFFFu;
            for (int i = 0; i < 个数; i++)
            {
                值 ^= 数据[i];
                for (int k = 0; k < 8; k++)
                    值 = (值 & 1) != 0 ? (值 >> 1) ^ 0xEDB88320u : 值 >> 1;
            }
            return 值 ^ 0xFFFFFFFFu;
        }

