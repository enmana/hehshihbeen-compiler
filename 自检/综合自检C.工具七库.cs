            // 跑一段 HB:输出按行收(每行末尾空白去掉、首尾空行去掉)
            static List<string> 跑行(string 源)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 源) }, true, 中间层C.默认堆大小, null,
                    中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                var 行表 = 缓冲.ToString().Replace("\r", "").Split('\n')
                    .Select(x => x.TrimEnd()).ToList();
                while (行表.Count > 0 && 行表[^1].Length == 0) 行表.RemoveAt(行表.Count - 1);
                while (行表.Count > 0 && 行表[0].Length == 0) 行表.RemoveAt(0);
                if (编译.查运行期报错(vm.内存) is { } 说明) 行表.Add($"⚠{说明}");
                return 行表;
            }

            // 一行一条地比;不齐就报第一处不一样(带行号,好查)
            void 比行(string 名, List<string> 实得, params string[] 期望行)
            {
                bool 好 = 实得.Count == 期望行.Length;
                int 第一坏 = -1;
                if (好)
                {
                    for (int i = 0; i < 期望行.Length; i++)
                        if (实得[i] != 期望行[i]) { 好 = false; 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实得.Count} 行逐行对上"
                    : $"实测 {实得.Count} 行 / 期望 {期望行.Length} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实得[第一坏]}> 期望=<{期望行[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实得)}>");
                记录(名, 好, 说明);
            }

