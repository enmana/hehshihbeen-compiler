        /// <summary> 从一行报告里取出**断言名**(`PASS 名  => 详情` / `FAIL …` / `SKIP …` 只留名)</summary>
        private static string 取行里的名(string 行)
        {
            string 名 = 行.Length > 6 ? 行[6..] : 行;        // 去掉 `PASS  ` / `FAIL  ` / `SKIP  ` 前缀
            int 箭头 = 名.IndexOf("  => ", StringComparison.Ordinal);
            return (箭头 >= 0 ? 名[..箭头] : 名).Trim();
        }

        /// <summary>
        /// 把一份自检报告里的**断言名清单**取出来(排序 + 去重;`PASS 名  => 详情` 只留名)。
