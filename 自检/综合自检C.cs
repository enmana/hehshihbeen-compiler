        /// <summary>
        /// 跑一遍综合自检。
        ///
        /// `正在更新报告` = 这一遍是 `hbcc --stats --更新报告` 拉起来的 —— 那一条命令**就是要重写
        /// `接手说明.md` §4**,所以收尾那条"§4 是不是本次运行的结果"在这一遍里**不当判据**
        /// (盘上那份正要被这一遍冲掉,拿它判等于自己判自己),只记一条说明;真判据留给下一遍
        /// (那时盘上那份已经是新的了)。别的调用方(命令行 `--selftest` / IDE 的"跑自检")一律走默认 false。
        /// </summary>
        public static 自检报告 运行(bool 正在更新报告 = false)
        {
            R = new 自检报告();
            接线按组.Clear();
            当前组名 = "";
            逐条回调 = null;                 // 上一次跑完留下的回调不许跨次活着(它攥着界面对象)

            // ---- R4-1:每组各自 try + 总耗时预算(以前是一个大 try:一组抛异常,后面 141 组全不跑) ----
            // 步数上限按**线程**挂:自检跑在这条线程上,界面线程上跑用户程序的那台机器不受影响(见 `虚拟机C.步数上限`)。
            虚拟机C.本线程默认步数上限 = 自检步数上限;
            var 总表 = System.Diagnostics.Stopwatch.StartNew();
            var 每组耗时 = new List<(long 毫秒, string 组名)>();
            int 跑过 = 0;
            // R4-11:`HB_自检只跑` 环境变量 = **只跑组名里含这个子串的那些组**。
            // 为什么加它:全量自检一轮要**几十分钟**(C 后端对拍那一组自己就占 5 分钟以上),
            // 而调一条判据的时候只想跑那一组 —— 手工去改分组表既慢又容易改坏(实测切坏过两次)。
            string 只跑 = Environment.GetEnvironmentVariable("HB_自检只跑") ?? "";
            try
            {
                foreach (var (组名, 动作) in 分组表)
                {
                    if (只跑.Length > 0 && !组名.Contains(只跑, StringComparison.Ordinal)) continue;
                    跑过++;
                    当前组号 = 跑过;
                    当前组名 = 组名;   // T22:接线哨兵按组记账(记接线 里用)
                    if (Environment.GetEnvironmentVariable("HB_自检逐组报时") == "1")
                        Console.Error.WriteLine($"  [自检 {跑过}/{分组表.Length}] {组名} …");
                    var 本组 = System.Diagnostics.Stopwatch.StartNew();
                    try
                    {
                        动作();
                    }
                    catch (Exception ex)
                    {
                        // 只算这一组自己的账:名字带上组名,后面的组照跑(收尾那两条清单断言也照常执行)
                        记录异常($"自检分组 {组名}(这一组抛了异常,后面的组照跑)", ex);
                    }
                    本组.Stop();
                    每组耗时.Add((本组.ElapsedMilliseconds, 组名));
                    if (总表.ElapsedMilliseconds > 自检总预算毫秒) break;   // 协同看门狗:撞了预算就别再往下铺
                }
            }
            finally
            {
                虚拟机C.本线程默认步数上限 = 0;
                // H44(硬规矩 15):临时区是**本次进程**自己的,跑完自己清 ——
                // C 后端全量对拍那一档实测 6.8 GB,以前跑一趟就往系统临时目录里丢一份、再不收拾。
                临时区C.清理本次遗留();
            }

            var 最慢 = 每组耗时.OrderByDescending(x => x.毫秒).Take(3)
                .Select(x => $"{x.组名} {x.毫秒} 毫秒").ToArray();
            string 最慢话 = 最慢.Length == 0 ? "没有一组跑过" : "最慢三组:" + string.Join(" / ", 最慢);

            // R4-2(2026-10):**每组耗时落盘**(只在手动要的时候写)。
            // 为什么要它:自检 200 多组,总时长里往往**一组占九成**(实测 #41「优化」17.3 秒 / 全程 22 秒),
            // 而"最慢三组"只在断言详情里、还得先把输出翻出来。设了环境变量就写一份 TSV:
            //   `序号 <TAB> 组名 <TAB> 毫秒`,按**原始顺序**写,谁想看排序自己排。
            // 不设环境变量 = 一个字都不写(正常跑与六端闸门完全不受影响)。
            string? 耗时落盘 = Environment.GetEnvironmentVariable("HB_自检耗时落盘");
            if (!string.IsNullOrWhiteSpace(耗时落盘))
            {
                try
                {
                    var 行 = 每组耗时.Select(x => $"{x.组名}\t{x.毫秒}").ToList();
                    // 序号补在最前面(组名里可能有 TAB 的可能性极小,但序号最好由外层下标给)
                    var 带号 = new List<string>();
                    for (int i = 0; i < 行.Count; i++)
                    {
                        string[] 段 = 行[i].Split('\t');
                        带号.Add($"{i + 1}\t{段[0]}\t{段[1]}");
                    }
                    File.WriteAllLines(耗时落盘, 带号, new System.Text.UTF8Encoding(false));
                }
                catch { /* 落盘失败不影响自检结论 */ }
            }

            // ⚠ 跑过几组才对:**带 `HB_自检只跑` 时**"该跑的"只有名字里含那个子串的那些组。
            //   这条断言以前拿 `跑过 == 分组表.Length` 一刀切 ⇒ **只要用了筛选就必红**
            //   (而且报的话是"总耗时撞了 600 秒预算",把"我在筛选"说成了"预算撞了" —— 当场能把人带偏)。
            //   2026-10-11 实测:只跑一组、耗时 249 毫秒,照样报"撞了 600 秒预算、剩下 241 组没跑"。
            int 应有 = 只跑.Length == 0 ? 分组表.Length : 分组表.Count(x => x.组名.Contains(只跑, StringComparison.Ordinal));
            记录("自检 每组各自 try(一组抛异常只算它自己,后面的组照跑)", 跑过 == 应有,
                跑过 == 应有
                    ? (只跑.Length == 0
                        ? $"共 {分组表.Length} 组一组不落;{最慢话}"
                        : $"筛 `{只跑}` ⇒ 该跑 {应有} 组、全跑了(另有 {分组表.Length - 应有} 组没筛上);{最慢话}")
