            try
            {
                const string 本检查 = 清单比对断言名;
                var 现清单 = 取断言清单(R).Where(x => x != 本检查).ToArray();
                string 指纹 = 清单指纹(现清单);
                string? 根 = 找示例目录();
                string? 清单路径 = 根 == null
                    ? null
                    : Path.Combine(Directory.GetParent(根)?.FullName ?? 根, "工具", "自检断言清单.txt");
                if (清单路径 == null)
                {
                    // R4-2:不在工作副本里跑 → 这条**没执行**,记跳过(以前记 FAIL,把"没跑"说成"失败")。
                    跳过(本检查, "工作副本之外跑自检,找不到 工具/自检断言清单.txt");
                }
                else if (!File.Exists(清单路径))
                {
                    记录(本检查, false, $"找不到清单文件(共 {现清单.Length} 条,指纹 {指纹});" +
                        $"跑 `hbcc --更新断言清单` 生成一份");
                }
                else
                {
                    var 基准 = File.ReadAllLines(清单路径, Encoding.UTF8)
                        .Select(x => x.Trim())
                        .Where(x => x.Length > 0 && x != 本检查)
                        .OrderBy(x => x, StringComparer.Ordinal)
                        .ToArray();
                    var 多了 = 现清单.Except(基准, StringComparer.Ordinal).Take(3).ToArray();
                    var 少了 = 基准.Except(现清单, StringComparer.Ordinal).Take(3).ToArray();
                    bool 一致 = 基准.SequenceEqual(现清单, StringComparer.Ordinal);
                    记录(本检查, 一致, 一致
                        ? $"共 {现清单.Length} 条,清单指纹 {指纹}"
                        : $"现在是 {现清单.Length} 条(指纹 {指纹}),清单文件里是 {基准.Length} 条" +
                          $"{(多了.Length > 0 ? ";新增如 " + string.Join(" / ", 多了) : "")}" +
                          $"{(少了.Length > 0 ? ";少了如 " + string.Join(" / ", 少了) : "")}" +
                          " —— 有意增删就跑 `hbcc --更新断言清单` 同步");
                }
            }
            catch (Exception ex) { 记录异常("自检 断言清单", ex); }

            return R;
        }

