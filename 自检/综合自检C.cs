        /// <summary> 自检的一条结果(自检窗口那一行;也是 `逐条回调` 的入参)</summary>
        public sealed class 自检条C
        {
            /// <summary> `PASS` / `FAIL` / `SKIP` </summary>
            public string 结果 { get; set; } = "";
            /// <summary> 这一条属于哪一组(逐条回调时就是当时那一组)</summary>
            public string 组 { get; set; } = "";
            /// <summary> 断言名</summary>
            public string 名 { get; set; } = "";
            /// <summary> 详情(名字后面那一段;没有给空串)</summary>
            public string 详情 { get; set; } = "";
        }

        /// <summary>
        /// P39:装上"每记一条就叫一下我"的钩子(自检窗口用),返回一个**注销**它的委托
        /// (窗口关掉时调一次 —— 不然那一份回调把已关的窗口钉在那儿)。
        /// `第几组` 是 1 基的组序号(配 `组名表` 用)。
        /// 注意:自检**跑在调用它的那条线程上**,界面那一侧要自己把动作派回界面线程
        /// (窗口里的用法见 `界面控件\自检窗口.xaml.cs`)。
        /// </summary>
        public static Action 装逐条回调(Action<自检条C, int> 回调)
        {
            逐条回调 = 回调;
            return () => { if (ReferenceEquals(逐条回调, 回调)) 逐条回调 = null; };
        }

        /// <summary> 把一行报告拆成三段(`PASS 名  => 详情`);拆不出详情就给空串 </summary>
        private static 自检条C 拆一条(string 行)
        {
            string 结果 = 行.StartsWith("PASS", StringComparison.Ordinal) ? "PASS"
                : 行.StartsWith("FAIL", StringComparison.Ordinal) ? "FAIL"
                : 行.StartsWith("SKIP", StringComparison.Ordinal) ? "SKIP" : "";
            string 余 = 结果.Length > 0 ? 行[结果.Length..].TrimStart() : 行;
            int 切 = 余.IndexOf("  => ", StringComparison.Ordinal);
            string 名 = 切 < 0 ? 余 : 余[..切];
            string 详情 = 切 < 0 ? "" : 余[(切 + 5)..];
            return new 自检条C { 结果 = 结果, 组 = 当前组名, 名 = 名.Trim(), 详情 = 详情.Trim() };
        }

        /// <summary> 记完一条顺手叫一下钩子(没装钩子时这一句几乎不要钱)</summary>
        private static void 报给钩子(string 行)
        {
            var 钩 = 逐条回调;
            if (钩 == null) return;
            try { 钩(拆一条(行), 当前组号); } catch { /* 钩子自己出问题不许影响自检 */ }
        }

        /// <summary>
        /// P39:给**自检窗格那一组**用的探针 —— 把一行报告按 `报给钩子` 那条路走一遍(装了什么钩子就报什么)。
        /// 它**不往报告里记任何东西**(不动通过 / 失败 / 跳过那几个数),所以拿它验钩子不会把自检的账带歪。
        /// </summary>
        public static void 探一条给钩子(string 报告行) => 报给钩子(报告行);

        /// <summary> 现在跑到第几组(1 基;给钩子报进度用)</summary>
        private static int 当前组号;

        private static void 记录(string 名称, bool 通过, string? 详情 = null)
        {
            R.行.Add((通过 ? "PASS  " : "FAIL  ") + 名称 + (详情 != null ? "  => " + 详情 : ""));
            if (通过) R.通过++; else R.失败++;
            报给钩子(R.行[^1]);
        }

        private static void 记录异常(string 名称, Exception ex)
        {
            R.失败++;
            R.行.Add($"FAIL  {名称}  => {ex.Message}");
            R.异常.Add(ex.Message);
            报给钩子(R.行[^1]);
        }

        /// <summary>
        /// 记一条**跳过**:这条断言这一次**没有执行**(不在工作副本里跑、找不到仓库根、机器上没有那份文件…)。
        ///
        /// **R4-2 的口径**:这类地方以前写的是 `记录(名, true, "…工作副本之外跑自检时跳过")` ——
        /// 记成 **PASS**,于是"通过"里混着一批**根本没跑过**的断言,而"6 跳过"这个数也是假的
        /// (实测:出了工作副本跑一次,报的是"1826 通过 / 0 跳过")。跳过就记跳过,谁也不许冒充通过。
        /// </summary>
        private static void 跳过(string 名称, string 详情)
        {
            R.跳过++;
            R.行.Add($"SKIP  {名称}  => {详情}");
            报给钩子(R.行[^1]);
        }

