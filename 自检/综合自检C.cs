        /// 为什么要有它:`示例60_大内存档` 的变量槽自己就超过 1MB,按默认 1MB 跑会当场报"装不进内存"
        /// —— 而标准工程本来就该按它自己那份工程文件跑。
        /// </summary>
        private static int 示例内存大小(string? 目录)
        {
            if (string.IsNullOrEmpty(目录)) return 虚拟机C.默认内存大小;
            try
            {
                string? 工程路径 = 工程文件C.找工程文件(目录);
