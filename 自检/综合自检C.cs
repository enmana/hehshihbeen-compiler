        }

        /// <summary>
        /// 示例(标准工程)所在目录里那份 `.hbp` 写的 **`网址` 白名单**(G3 域 3 起):与命令行
        /// `-p 工程` 那一路(`Program.取工程网址白名单`)**同一条口径** —— 整棵工程树的 `网址` 行
        /// 并起来交给 `网址白名单C.由文本`。
        ///
        /// 为什么要它:网络那一族的白名单是**工程文件给的**,自检这一路不给的话,标准工程里
        /// `监听` / `连接` / `主机解析` 永远只会走到"没挂能力"那一档(示例29 就成了一张空壳)。
        /// 没有 .hbp / 没声明 / 读不了 → null(= 这个宿主没有网络能力,与手机端 / 独立 exe 同一档)。
        /// </summary>
        private static 网址白名单C? 示例网址白名单(string? 目录)
        {
            if (string.IsNullOrEmpty(目录)) return null;
            try
            {
                string? 工程路径 = 工程文件C.找工程文件(目录);
                if (工程路径 == null) return null;
                var 行 = new List<string>();
                foreach (var 工程 in 工程文件C.读取工程树(工程路径)) 行.AddRange(工程.网址);
                var 表 = 网址白名单C.由文本(行);
                return 表.是空的 ? null : 表;
            }
            catch { return null; }
        }

