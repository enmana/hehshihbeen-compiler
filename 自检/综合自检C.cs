        /// ②自检收尾拿它跟那份清单比 —— **条数漂移必须一眼可见**(内核加固计划批 4)。
        /// 这是"**条数**";去重前那个数叫"**实例数**",见 `取断言名` / `断言实例数`。
        /// </summary>
        public static string[] 取断言清单(自检报告 报告)
            => 取断言名(报告).Distinct(StringComparer.Ordinal).OrderBy(x => x, StringComparer.Ordinal).ToArray();

