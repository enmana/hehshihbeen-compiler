        public static int 断言实例数(自检报告 报告) => 取断言名(报告).Length;

        /// <summary> 断言清单的短指纹(SHA-256 前 12 位十六进制):打印出来就能一眼看出"这次和上次不一样" </summary>
        public static string 清单指纹(IEnumerable<string> 清单)
            => Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(
                   Encoding.UTF8.GetBytes(string.Join('\n', 清单))))[..12];

        private static void 期望异常(string 名称, Action 动作, params string[] 应包含)
        {
            try
            {
                动作();
                记录(名称, false, "应当抛出异常但未抛出");
            }
            catch (Exception ex)
            {
                bool 匹配 = 应包含.All(s => ex.Message.Contains(s));
                记录(名称, 匹配, ex.Message);
                if (!匹配) R.异常.Add(ex.Message);
            }
        }

        /// <summary> 期望抛 编译异常C 且行号正好是 期望行(界面靠这个行号画红线,不能悄悄丢了)</summary>
        private static void 期望异常在第几行(string 名称, string 源码, int 期望行)
        {
            try
            {
                汇编(源码);
                记录(名称, false, "应当抛出异常但未抛出");
            }
            catch (编译异常C 错)
            {
                bool 匹配 = 错.行号 == 期望行;
                记录(名称, 匹配, $"行号={错.行号?.ToString() ?? "无"} 期望={期望行}  {错.中文}");
                if (!匹配) R.异常.Add($"行号对不上: {名称}");
            }
            catch (Exception ex)
            {
                记录(名称, false, "抛的不是编译异常C: " + ex.Message);
                R.异常.Add(ex.Message);
            }
        }

