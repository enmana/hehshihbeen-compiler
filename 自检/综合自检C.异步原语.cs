    /// <summary>
    /// G3 域 5:**异步输入输出(功能号 40 发起异步 / 41 任务就绪 / 42 取消任务)** 自检。
    ///
    /// 这一域的**路**(用户 2026-10-03 当班拍板,见 `基础库施工计划.md` §0 / §1.3):
    /// **a 宿主线程池** —— 宿主在后台线程上做真阻塞那一趟(文件 / 套接字都是真异步),
    /// VM 照旧单线程,`任务就绪` 只是"读一格状态 + 把结果搬回来"。零依赖:
    /// C# 侧 `Thread`、C 后端 `CreateThread` / `pthread_create` + 一把互斥。
    ///
    /// 六层判据(**行为断言为主**):
    ///   · **号段那半**(纯常量):`40 / 41 / 42` 三个号、与别的域一个不撞、"任务太多"是接着 22/23 的 **24**;
    ///   · **真编真跑那半**:异步写 + 异步读(内容真进那个 `字符串` 变量、字节数真对得上);
    ///   · **宿主层那半**(不起编译):任务太多(第 33 个给 -1)/ 作废号(3 与 22 分得清)/ 取消(号当场作废);
