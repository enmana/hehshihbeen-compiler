                    string 运行期 = C后端C.取运行时源码();
                    bool C同形 = 运行期.Contains("if (种类 == HB_种类_连接)", StringComparison.Ordinal)
                        && 运行期.Contains("return HB_ST_NOCAP;", StringComparison.Ordinal)
                        && 取宏值(运行期, "HB_ST_NOCAP") == 宿主能力C.状态_没挂能力;
                    记录("异步 种类 3(连接)在没白名单的宿主上:状态 1 + 任务号 -1 + **一格都不占**(C 侧同一份形状)",
                        连接状态 == 宿主能力C.状态_没挂能力 && 连接号 == 0xFFFFFFFF
                        && 后续状态 == 宿主能力C.状态_成功 && 后续 == 1 && C同形,
                        $"没白名单时:连接状态 {连接状态}(应 1)/ 号 0x{连接号:X8}(应 FFFFFFFF);" +
                        $"紧接着那个读任务拿到号 {后续}(应 1 ⇒ 第 0 格没被占,状态 {后续状态});C 侧同形 = {C同形}");
                }
                finally { 宿主能力C.设网址白名单(旧白名单); }
                清空目录(根);
            }
            catch (Exception ex) { 记录异常("异步 种类 3 的边界", ex); }
        }

        /// <summary>摆一个 `发起异步(1, 路径, …)` 的请求块(40 字节)并调它,返回任务号(排不上给 0xFFFFFFFF)</summary>
        private static uint 摆一个读任务(byte[] 内存, uint 块, string 路径, uint 头址, uint 池指针槽, uint 池末槽, out int 状态)
        {
            (uint 址, uint 长) = 放串(内存, 20000, 路径);
            写字到块(内存, 块 + 0, 宿主能力C.种类_读文件);
            写字到块(内存, 块 + 4, 址);
            写字到块(内存, 块 + 8, 长);
            写字到块(内存, 块 + 12, 0);
            写字到块(内存, 块 + 16, 0);
            写字到块(内存, 块 + 20, 64);            // 上限(读文件)
            写字到块(内存, 块 + 24, 0x77777777);
            写字到块(内存, 块 + 28, 头址);
            写字到块(内存, 块 + 32, 池指针槽);
            写字到块(内存, 块 + 36, 池末槽);
            状态 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_发起异步);
            return 读块字(内存, 块 + 24);
        }

        /// <summary>摆一个 `发起异步(3, 主机, "", 端口, …)` 的请求块(40 字节)并调它</summary>
        private static uint 摆一个连接任务(byte[] 内存, uint 块, string 主机, uint 端口, out int 状态)
        {
