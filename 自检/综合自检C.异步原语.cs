        /// <summary>摆一个 `任务就绪(号, 状态, 字节数)` 的请求块(16 字节)并调它,返回那三个值</summary>
        private static int 查一个任务(byte[] 内存, uint 块, uint 号, out int 状态, out uint 个数)
        {
            写字到块(内存, 块 + 0, 号);
            写字到块(内存, 块 + 4, 0x77777777);
            写字到块(内存, 块 + 8, 0x77777777);
            int 码 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_任务就绪);
            状态 = (int)读块字(内存, 块 + 4);
            个数 = 读块字(内存, 块 + 8);
            return 码;
        }

        /// <summary>等一个任务到"好了 / 失败 / 作废"(返回最终那个状态码;本机测试不睡眠,靠轮询真信号)</summary>
        private static int 等一个任务(byte[] 内存, uint 块, uint 号)
        {
            for (int i = 0; i < 200000; i++)
            {
                int 码 = 查一个任务(内存, 块, 号, out _, out _);
                if (码 != 0) return 码;
                Thread.Yield();
            }
            return -1;
        }
