    ///   · **接线哨兵**:三个名字进内建函数名表(中英)+ 说明表 + 帮助《第33节·异步》在,
    ///     而且 **`取消` 没被内建抢走**(`库\定时.hb` 里那个库函数照旧)。
    /// </summary>
    public static partial class 综合自检C
    {
        private static void 异步原语自检()
        {
            // ── 一、号段(纯常量):40 / 41 / 42,与别的域一个不撞 ──
            try
            {
                bool 三个号对得上 = 宿主能力C.功能_发起异步 == 40 && 宿主能力C.功能_任务就绪 == 41
                    && 宿主能力C.功能_取消任务 == 42;
                bool 号段 = 宿主能力C.异步功能号最小 == 40 && 宿主能力C.异步功能号最大 == 42;
                bool 不撞 = 宿主能力C.异步功能号最小 > 宿主能力C.网络功能号最大                 // 40 > 26
                    && 宿主能力C.异步功能号最大 < 宿主能力C.运行时功能号最小                   // 42 < 43
                    && 宿主能力C.异步功能号最大 < 宿主能力C.流功能号最小                       // 42 < 48
                    && 宿主能力C.异步功能号最大 < 宿主能力C.计时功能号最小                     // 42 < 55
                    && 宿主能力C.异步功能号最大 < 图形宿主C.图形功能号最小;                    // 42 < 60
                bool 任务太多码 = 宿主能力C.状态_任务太多 == 24 && 宿主能力C.任务表格数 == 32;
                记录("异步 号段是 40/41/42 三条(不加号),与 P28/网络/运行时/流/计时/图形一个不撞;任务太多是 24、任务表 32 格",
                    三个号对得上 && 号段 && 不撞 && 任务太多码,
                    $"发起异步 {宿主能力C.功能_发起异步} / 任务就绪 {宿主能力C.功能_任务就绪} / " +
                    $"取消任务 {宿主能力C.功能_取消任务};网络到 {宿主能力C.网络功能号最大}、" +
                    $"运行时从 {宿主能力C.运行时功能号最小} 起、流从 {宿主能力C.流功能号最小} 起;" +
                    $"任务太多 = {宿主能力C.状态_任务太多}(接着 22 / 23)、表 {宿主能力C.任务表格数} 格");
            }
            catch (Exception ex) { 记录异常("异步 号段 40/41/42", ex); }

            // ── 二、真编真跑:异步写 + 异步读(内容真进那个字符串变量) ──
            try
            {
                string 根 = 宿主根("异步真跑");
                清空目录(根);
                宿主能力C.清句柄表();       // 任务号从 (0 << 16) | 1 起(与"一个工程一个进程"同口径)
                string 源 =
                    $"字符串 目录 = \"{根}\";\n" +
                    "输出行(建目录(目录));\n" +
                    $"字符串 路径 = \"{根}数据.txt\";\n" +
                    "输出行(写文件(路径, \"异步真跑\"));\n" +
                    "整数 读任务 = 0;\n" +
                    "整数 状态 = 0;\n" +
                    "整数 个数 = 0;\n" +
                    "字符串 读回 = \"\";\n" +
                    "读任务 = 发起异步(1, 路径, 读回, 4096, 读任务);\n" +
                    "输出行(读任务);\n" +                       // 1:第一个任务的号
                    "当 (任务就绪(读任务, 状态, 个数) == 0)\n{\n}\n" +
                    "输出行(状态);\n" +                          // 0
                    "输出行(个数);\n" +                          // 12(4 个汉字 × 3 字节)
                    "输出行(读回);\n" +                          // 异步真跑
                    "整数 写任务 = 0;\n" +
                    $"写任务 = 发起异步(2, \"{根}写.txt\", \"写进去了\", 0, 写任务);\n" +
                    "当 (任务就绪(写任务, 状态, 个数) == 0)\n{\n}\n" +
                    "输出行(状态);\n" +                          // 0
                    "输出行(个数);\n" +                          // 12
                    "字符串 再读 = \"\";\n" +
                    $"输出行(读文件(\"{根}写.txt\", 再读, 4096));\n" +
                    "输出行(再读);\n" +                          // 写进去了
                    "输出行(删文件(路径));\n" +
                    $"输出行(删文件(\"{根}写.txt\"));\n" +
                    "输出行(删目录(目录));\n" +
                    "停止\n";
                var (_, 输出) = 运行带输出(源);
                string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                const string 应有 = "1\n1\n1\n0\n12\n异步真跑\n0\n12\n1\n写进去了\n1\n1\n1";
                记录("异步 真编真跑:异步写 / 异步读各一条 —— 内容真进那个 `字符串` 变量、字节数对得上、任务号从 1 起",
                    实际 == 应有,
                    实际 == 应有
                        ? "任务号 1;读回 12 字节(`异步真跑`)、写 12 字节;两条的状态都是 0"
                        : $"实际=<{实际.Replace("\n", "|")}> 期望=<{应有.Replace("\n", "|")}>");
                清空目录(根);
            }
            catch (Exception ex) { 记录异常("异步 真编真跑", ex); }

            // ── 三、宿主层:任务太多 / 作废号(3 与 22 分得清)/ 取消 ──
            try
            {
                string 根 = 宿主根("异步宿主");
                清空目录(根);
                string 没有这个 = 根 + "没有这个.txt";
                var 内存 = new byte[64 * 1024];
                uint 块 = 4096;                 // 请求块:40 字节
                uint 头址 = 8192;               // 读文件那个"收内容的头"(读到就失败,用不上,但地址得合法)
                uint 池指针槽 = 8300, 池末槽 = 8310;

                宿主能力C.清句柄表();
                var 号表 = new uint[宿主能力C.任务表格数];
                for (int i = 0; i < 号表.Length; i++)
                {
                    号表[i] = 摆一个读任务(内存, 块, 没有这个, 头址, 池指针槽, 池末槽, out int 状态);
                    if (状态 != 宿主能力C.状态_成功) throw new Exception($"第 {i} 个读任务就没排上(状态 {状态})");
                }
                uint 满了号 = 摆一个读任务(内存, 块, 没有这个, 头址, 池指针槽, 池末槽, out int 满状态);

                // 32 个格全占着 ⇒ 第 33 个给"任务太多"、任务号写 -1
                bool 太多 = 满状态 == 宿主能力C.状态_任务太多 && 满了号 == 0xFFFFFFFF;
                bool 号是错的 = 号表[0] == ((0u << 16) | 1u) && 号表[1] == ((1u << 16) | 1u);

                // 收走一个:好了之后号当场作废(再问给 3)
                int 收 = 等一个任务(内存, 块, 号表[0]);
                int 再问 = 查一个任务(内存, 块, 号表[0], out int 状态二, out uint 个数一);
                // 结构不成形的号给 22(下标越界),与"作废号"的 3 分得清
                int 太远 = 查一个任务(内存, 块, 0xFFFF0001u, out int 状态三, out uint 个数二);

                // 取消一个还没收走的:取消成功(0),再查就是 3
                写字到块(内存, 块, 号表[5]);
                int 取消 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_取消任务);
                int 取消后再查 = 查一个任务(内存, 块, 号表[5], out int 状态四, out uint 个数三);
                写字到块(内存, 块, 号表[5]);
                int 再取消 = 宿主能力C.处理(内存, 块, 宿主能力C.功能_取消任务);

                记录("异步 宿主层:32 格占满后第 33 个给「任务太多」(-1);收走 / 取消过的号给 3;下标越界给 22",
                    太多 && 号是错的 && 收 == 2 && 再问 == 3 && 太远 == 宿主能力C.状态_句柄无效
                    && 取消 == 0 && 取消后再查 == 3 && 再取消 == 3,
                    $"第 33 个:状态 {满状态}(应 24)/ 号 0x{满了号:X8};头两个任务的号 {号表[0]}/{(1u << 16) | 1u};" +
                    $"收走 {收}(这条读的是不存在的文件 ⇒ 2「这一趟失败」)→ 再问 {再问}(应 3)/ 越界号 {太远}(应 22);" +
                    $"取消 {取消}(应 0)→ 再查 {取消后再查}(应 3)→ 再取消 {再取消}(应 3);" +
                    $"收走时状态 {状态二} / 取消后状态 {状态四};越界那两格 {状态三}/{个数二}、{个数一}/{个数三}");

                // 32 个都不收走,后面的用例要干净的表
                宿主能力C.清句柄表();
                清空目录(根);
            }
            catch (Exception ex) { 记录异常("异步 宿主层", ex); }

            // ── 四、清句柄表连任务表一起清(同一个进程里连跑两个程序,第一个任务号永远一样) ──
            try
            {
                string 根 = 宿主根("异步清表");
                清空目录(根);
                string 没有这个 = 根 + "没有这个.txt";
                var 内存 = new byte[64 * 1024];
                uint 块 = 4096, 头址 = 8192, 池指针槽 = 8300, 池末槽 = 8310;

                宿主能力C.清句柄表();
                uint 首 = 摆一个读任务(内存, 块, 没有这个, 头址, 池指针槽, 池末槽, out _);
                等一个任务(内存, 块, 首);
                uint 二 = 摆一个读任务(内存, 块, 没有这个, 头址, 池指针槽, 池末槽, out _);   // 同一格复用:版本抬到 2
                等一个任务(内存, 块, 二);
                宿主能力C.清句柄表();                                                       // 压回"刚启动"
                uint 三 = 摆一个读任务(内存, 块, 没有这个, 头址, 池指针槽, 池末槽, out _);
                等一个任务(内存, 块, 三);

                记录("异步 清句柄表连任务表一起清(首号 1 → 复用后 2 → 清一次又回到 1)",
                    首 == 1 && 二 == 2 && 三 == 1,
                    $"清表后第一个任务号 {首}(应 1)/ 收走后再发起 {二}(应 2,版本抬了一格)/ 再清一次又 {三}(应 1)");
                宿主能力C.清句柄表();
                清空目录(根);
            }
            catch (Exception ex) { 记录异常("异步 清句柄表连任务表一起清", ex); }

            // ── 五、C 后端:三个功能号宏对得上 + 真开线程那一手在(纯源码,不吃 C 编译器) ──
            try
            {
                string 运行期 = C后端C.取运行时源码();
                bool 宏对 = 取宏值(运行期, "HB_F_STARTASYNC") == 宿主能力C.功能_发起异步
                    && 取宏值(运行期, "HB_F_TASKREADY") == 宿主能力C.功能_任务就绪
                    && 取宏值(运行期, "HB_F_CANCELTASK") == 宿主能力C.功能_取消任务
                    && 取宏值(运行期, "HB_ST_TASKMANY") == 宿主能力C.状态_任务太多;
                bool 有分支 = 运行期.Contains("case HB_F_STARTASYNC:", StringComparison.Ordinal)
                    && 运行期.Contains("case HB_F_TASKREADY:", StringComparison.Ordinal)
                    && 运行期.Contains("case HB_F_CANCELTASK:", StringComparison.Ordinal);
                // 零依赖的真线程:Windows `CreateThread` / POSIX `pthread_create`,再加一把互斥
                bool 真线程 = 运行期.Contains("CreateThread(", StringComparison.Ordinal)
                    && 运行期.Contains("pthread_create(", StringComparison.Ordinal)
                    && 运行期.Contains("CRITICAL_SECTION hb_任务锁;", StringComparison.Ordinal)
                    && 运行期.Contains("pthread_mutex_t hb_任务锁", StringComparison.Ordinal);
                bool 关掉连接 = 运行期.Contains("hb_host_发起异步", StringComparison.Ordinal)
                    && 运行期.Contains("hb_host_任务就绪", StringComparison.Ordinal)
                    && 运行期.Contains("hb_host_取消任务", StringComparison.Ordinal);
                记录("异步 C 后端:三个功能号宏与 C# 侧逐个对上、switch 里各有分支、真开线程(零依赖)那一手在",
                    宏对 && 有分支 && 真线程 && 关掉连接,
                    $"宏对 = {宏对} / 分支 = {有分支} / CreateThread+pthread_create+两把锁 = {真线程} / 三个处理函数在 = {关掉连接}");
            }
            catch (Exception ex) { 记录异常("异步 C 后端", ex); }

            // ── 六、接线哨兵:三个名字进表(中英)+ 说明表 + 帮助《上手》第33节;`取消` 没被内建抢走 ──
            try
            {
                var 该有 = new (string 中文, string 英文)[]
                {
                    ("发起异步", "startasync"), ("任务就绪", "taskready"), ("取消任务", "canceltask"),
                };
                var 缺 = 该有.Where(对 => !中间层指令C.内建函数名表.Any(x => x.中文 == 对.中文 && x.英文 == 对.英文)).ToArray();
                var 缺说明 = 该有.Where(对 => !中间层指令C.说明表.ContainsKey(对.英文)).ToArray();
                // `取消` / `发起` / `查就绪` 都**不许**当内建:前者是 `库\定时.hb` 里那个库函数的名字
                bool 没抢名字 = !中间层指令C.内建函数名表.Any(x => x.中文 is "取消" or "发起" or "查就绪");
                bool 帮助有 = 帮助文本C.快速上手().Contains("33,异步", StringComparison.Ordinal)
                    && 帮助文本C.快速上手().Contains("发起异步(种类, 参数一, 参数二, 参数三, 任务)", StringComparison.Ordinal);
                // 定时库那个库函数还在(源码钉:名字与它的调用点)
                string? 示例 = 找示例目录();
                bool 定时库还在 = false;
                if (示例 != null)
                {
                    string 定时 = Path.Combine(示例, "库", "定时.hb");
                    if (File.Exists(定时))
                    {
                        string 正文 = File.ReadAllText(定时, Encoding.UTF8);
                        定时库还在 = 正文.Contains("方法 取消(整数 号)", StringComparison.Ordinal);
                    }
                }
                记录("异步 三条都进了内建函数名表(中英)与说明表;帮助《第33节·异步》在;`取消` 仍归 `库\\定时.hb`(没被内建抢走)",
                    缺.Length == 0 && 缺说明.Length == 0 && 没抢名字 && 帮助有 && 定时库还在,
                    $"缺名字: {string.Join(", ", 缺.Select(x => x.中文))} / 缺说明: {string.Join(", ", 缺说明.Select(x => x.英文))}; " +
                    $"`取消` 没被抢 = {没抢名字};帮助那一段在 = {帮助有};`定时.hb` 的 `取消` 还在 = {定时库还在}");
            }
            catch (Exception ex) { 记录异常("异步 三条 接线", ex); }

            // ── 七、**种类 3(连接)这一档的边界**:两腿的可观测行为必须一样 ──
            // 事实两句(**不是**"过了校验却没实现",这一档在两腿都落到了实处):
            //   · C# 侧:带白名单(命令行 / IDE 里跑,且 `.hbp` 的 `网址` 表里有这一条)时**真异步连** ——
            //     后台线程跑那趟现成的阻塞连接,`任务就绪` 把连上的套接字装进套接字表、把句柄交出来;
            //     没挂白名单(手机端 / 独立 exe / 没给工程文件)时**当场挡掉**:状态 1、任务号 -1、**一格都不占**;
            //   · C 侧(独立 exe / 解释器核):**本宿主没有裸 socket 那一族**(G3 域 3 的 20~26 整族在那边
            //     就是"没挂能力" —— 独立 exe 带不了 `.hbp` 的 `网址` 白名单,那是 D6 拍板的老口径)
            //     ⇒ 这一档照那条老口径办:状态 1、任务号 -1、**不占格、不发线程**。
            // ⇒ 两边在"没有白名单"这个共同口径下**逐字节一样**(对拍比的就是这个);差别只在
            //   "C# 侧有白名单时能真连",与 `连到` / `监听` 那两条的老边界同一条(帮助《上手》第33节与
            //   `基础库施工计划.md` §4都写明了)。
            try
            {
                string 根 = 宿主根("异步连接边界");
                清空目录(根);
                var 内存 = new byte[64 * 1024];
                uint 块 = 4096;
                宿主能力C.清句柄表();
                网址白名单C? 旧白名单 = 宿主能力C.网址白名单;
                try
                {
                    宿主能力C.设网址白名单(null);
                    uint 连接号 = 摆一个连接任务(内存, 块, "127.0.0.1", 45321, out int 连接状态);
