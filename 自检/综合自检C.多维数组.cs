//
//   语言面新增,所以这一组的钉法 = **真编真跑看输出** + 几处"报错文案"对着钉:
//     · 二维:常量下标 / 运行期下标都读写;与"自己摊平成一维"**逐字节同构**(地址差对着算)
//     · 行优先:最后一维挨着放(地址差 = (行 × 列数 + 列) × 元素宽)
//     · `[…]` 初值**按行铺开**;三维 / 四维;结构元素(`网格[i][j].x`);元素宽 2 / 1
//     · 越界**逐维查**:编译期常量当场报(点名第几维),运行期带行号停下(同样点名第几维)
//     · 明确不做的那几样各给一条:列表的列表 / 少写一维 / 当数组参数传 / `.添加()`
//     · 硬上限:维数(硬上限C.数组维数上限)、各维乘起来(硬上限C.数组长度上限)
//     · **接线哨兵**一条:累加寄存器不许跨下标表达式活着(算完一维就落临时槽)——
//       上一版就是把累加值攥在寄存器里,示例13 / 示例16 报「临时寄存器用光了」整批撤回
//
//   ISA / 关键字 / 机器码:**一条没动**(多维数组就是"每个下标 × 步长"的线性累加,
//   全在中间层算地址;`--asm` 与 HEAD 对过:46 份标准工程逐字节相同)。
// ============================================================

