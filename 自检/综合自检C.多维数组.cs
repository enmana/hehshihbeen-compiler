        /// <summary> 跑一段 HB,返回它打出来的每一行(按 `|` 拼;编译/运行挂了返回空串) </summary>
        private static string 跑输出断言得值(string 源码)
        {
            try
            {
                var (_, 输出) = 运行带输出(源码);
                return 输出.Replace("\r\n", "\n").TrimEnd('\n').Replace("\n", "|");
            }
            catch (Exception) { return ""; }
        }

        /// <summary> 跑一段 HB 直到它**运行期报错停下**,返回人话文案(没报错返回 null)。
        /// 越界是"写错误槽 + 停机"那条路(不是抛异常),所以文案要向 `查运行期报错` 要。 </summary>
        private static string? 运行期文案(string 源码)
        {
            var 结果 = 编译(源码);
            var 机 = new 虚拟机C { 输出目标 = _ => { } };
            机.取源行号 = 地址 => 执行行映射C.查源行(结果.调试文件表, 地址);
            try { 机.运行(结果); }
            catch (运行期错误C 错) { return 错.用户文案; }
            catch (Exception) { return null; }
            return 结果.查运行期报错(机.内存);
        }
