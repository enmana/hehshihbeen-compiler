// ============================================================
// 「大内存档」自检(通用化第2批:可选内存模型 + A 路寻址;2026-10-11)
//
//   这一组盯四件事(施工图 `发展路径规划.md` §3.6 那三条判据 + 一条代价账):
//     ① **默认档零风险**:工程文件**不写** `内存` 时,汇编器**一条都不摊开**
//        (`展开行数 == 0` ⇒ 与没有这套机制的老版本走同一条编码路,机器码逐字节不变);
//     ② **两档语义一致**:同一份源码在 `1MB` 与 `4MB` 两档下编得过、跑得对、**输出逐字相同**;
//     ③ **大地址真能用**:变量槽越过 1MB(四个 65536 格数组)之后,读 / 写 / 数组元素全对
//        —— 这一条专钉"摊开时借的那个暂存寄存器不能是操作数本身"(第一版借死 R14 就栽在这儿:
//        `存字 R14, 大地址` 被摊成"把地址当地址存下去",六个大数组那份程序算出来的和是个地址);
//     ④ **池长过 1MB**:十万个整数的动态列表在 4MB 档跑得完;同一份在 1MB 档**当场报"池用完了"**
//        (这是"大内存档真买到了什么"的对照,不是缺陷)。
//
//   另外一条(接线口):C 后端**转译**这条腿也得认大内存档 —— 逐字节对拍那几组由
//   `C后端全量对拍` 覆盖(标准工程 `示例60_大内存档` 已经在那个集合里),这里只钉"转得出来"。
// ============================================================

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        /// <summary> 按指定内存档编译(返回机器码结果 + 这一趟摊开了几行) </summary>
        private static (汇编调试结果C 结果, int 展开行数) 编大内存(string 源, int 内存大小)
        {
            var 汇编器 = new 汇编器C();
            var 结果 = 汇编器.汇编多文件带调试(
                [("主程序.hb", 源)], true, 中间层C.默认堆大小, null, 中间层C.默认池大小, 内存大小);
            return (结果, 汇编器.展开行数);
        }

        /// <summary> 按指定内存档跑一遍,收输出(不挂无头呈现:这一组都是纯计算程序) </summary>
        private static string 跑大内存(string 源, int 内存大小)
        {
            var (结果, _) = 编大内存(源, 内存大小);
            var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
            vm.设内存大小(内存大小);
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
            vm.输出目标 = 解码.写;
            vm.运行(结果);
            解码.收尾();
            string 报错 = 结果.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
            return 缓冲.ToString().Trim().Replace("\n", "|") + 报错;
        }

        private static void 大内存档自检()
        {
            // ------------------------------------------------------------
            // ① 默认档(不写 `内存`)= 1MB:一条都不摊开 ⇒ 机器码逐字节不变
            //    (这里"不写内存"就是按默认 1MB 编 —— 与命令行 / 工程文件那条路同一个数)
            // ------------------------------------------------------------
            try
            {
                const string 小源 =
                    "整数 表[1000];\n整数 i = 0;\n当 (i < 1000)\n{\n表[i] = i % 7;\ni = i + 1;\n}\n" +
                    "整数 和 = 0;\ni = 0;\n当 (i < 1000)\n{\n和 = 和 + 表[i];\ni = i + 1;\n}\n" +
                    "输出行(和);\n停止\n";
                var (默认档, 默认展开) = 编大内存(小源, 虚拟机C.默认内存大小);
                var (显式档, 显式展开) = 编大内存(小源, 1024 * 1024);
                bool 同 = 默认档.机器码.SequenceEqual(显式档.机器码);
                记录("大内存档 默认档(不写 `内存`)= 显式 `1MB`:机器码逐字节相同(`展开行数 == 0` ⇒ 与老版本同一条编码路)",
                    同 && 默认展开 == 0 && 显式展开 == 0,
                    $"机器码 {默认档.机器码.Length} 字节 / 逐字节相同={同} / 展开行数 默认={默认展开} 显式={显式展开}");
            }
            catch (Exception ex) { 记录异常("大内存档 默认档零风险", ex); }

            // ------------------------------------------------------------
            // ② 同一份源码:1MB 档与 4MB 档输出逐字相同(语义不变)
            // ------------------------------------------------------------
            try
            {
                const string 源 =
                    "整数 表[1000];\n整数 i = 0;\n当 (i < 1000)\n{\n表[i] = i % 7;\ni = i + 1;\n}\n" +
                    "整数 和 = 0;\ni = 0;\n当 (i < 1000)\n{\n和 = 和 + 表[i];\ni = i + 1;\n}\n输出行(和);\n" +
                    "整数 大表[];\ni = 0;\n当 (i < 2000)\n{\n大表.添加(i % 100);\ni = i + 1;\n}\n" +
                    "输出行(大表.长度());\n输出行(大表[1999]);\n停止\n";
                string 小内存 = 跑大内存(源, 1024 * 1024);
                string 大内存 = 跑大内存(源, 4 * 1024 * 1024);
                int 期望和 = Enumerable.Range(0, 1000).Sum(i => i % 7);
                记录("大内存档 同一份源码 `1MB` 与 `4MB` 两档:编得过、跑得对、输出逐字相同",
                    小内存 == 大内存 && 小内存 == $"{期望和}|2000|99",
                    $"1MB=<{小内存}> 4MB=<{大内存}> 期望=<{期望和}|2000|99>");
            }
            catch (Exception ex) { 记录异常("大内存档 两档语义一致", ex); }

            // ------------------------------------------------------------
            // ③ 大地址真能用:变量槽越过 1MB(四个 65536 格数组)之后读 / 写 / 数组元素全对
            //    ⚠ 这条钉的是"摊开时借的暂存寄存器绝不能是本行的操作数":
            //       第一版借死 R14 ⇒ `存字 R14, 大地址` 把地址当值存了(实测:和是个地址、循环只跑 353 条)
            // ------------------------------------------------------------
            try
            {
                const string 大源 =
                    "整数 填a[65536];\n整数 填b[65536];\n整数 填c[65536];\n整数 填d[65536];\n" +
                    "整数 尾 = 5;\n整数 i = 0;\n当 (i < 3)\n{\n尾 = 尾 + 1;\ni = i + 1;\n}\n" +
                    "填a[0] = 7;\n填d[65535] = 9;\n输出行(尾);\n输出行(i);\n输出行(填a[0] + 填d[65535]);\n停止\n";
                var (结果, 展开) = 编大内存(大源, 4 * 1024 * 1024);
                var vm = new 虚拟机C();
                vm.设内存大小(4 * 1024 * 1024);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(结果);
                解码.收尾();
                string 实得 = 缓冲.ToString().Trim().Replace("\n", "|");
                // 同一份源码在 1MB 档**装不下**(变量槽自己就 1MB+)—— 顺带钉住"这是大内存档才能跑的"。
                // ⚠ 撞墙那一下发生在**装载 / 运行**时(编译期只算布局),所以要试"跑",不能只试"编"。
                // ⚠ R4-2(第429批):这里原来写的是裸 `catch { 一兆档装不下 = true; }` —— **连异常都不看**
                //   就把"试跑时抛了东西"记成"1MB 档装不下":自检自己崩 / 编译器报别的错,一样算通过,
                //   那是个**证伪不了**的假过断言(R4-2 自扫那三条正则专门逮它)。现在按仓库既有的口径
                //   (`异常与文案`)写,三个证伪点都在:
                //     ① 必须**真抛** —— 没抛说明 1MB 档居然装得下,这组"对照"本身不成立 ⇒ 当场红;
                //     ② 抛出来的文案必须是**"装不进…内存"**那一路(别的异常一律不算通过);
                //     ③ 异常原文进详情(红了当场看得见是哪一路,不用再去猜)。
                var (一兆档抛了, 一兆档文案) = 异常与文案(() => 跑大内存(大源, 1024 * 1024));
                bool 一兆档装不下 = 一兆档抛了
                    && 一兆档文案.Contains("装不进", StringComparison.Ordinal)
                    && 一兆档文案.Contains("内存", StringComparison.Ordinal);
                记录("大内存档 变量落在 1MB 之外:写 / 读 / 数组元素全对(摊开的暂存寄存器不碰操作数)",
                    实得 == "8|3|16" && 展开 > 0 && 一兆档装不下,
                    $"实得=<{实得}> 期望=<8|3|16> 展开行数={展开} 1MB 档:" +
                    (一兆档抛了
                        ? $"抛了「{截断(一兆档文案, 80)}」(要的是\"装不进内存\"这一路)"
                        : "**没抛异常** ⇒ 1MB 档装得下,对照不成立"));
            }
            catch (Exception ex) { 记录异常("大内存档 大地址读写", ex); }

            // ------------------------------------------------------------
            // ④ 池长过 1MB:十万个整数的动态列表 —— 4MB 档跑得完,1MB 档当场"池用完了"
            // ------------------------------------------------------------
            try
            {
                const string 池源 =
                    "整数 大表[];\n整数 i = 0;\n当 (i < 100000)\n{\n大表.添加(i % 100);\ni = i + 1;\n}\n" +
                    "输出行(大表.长度());\n整数 和 = 0;\ni = 0;\n当 (i < 100000)\n{\n和 = 和 + 大表[i];\ni = i + 1;\n}\n" +
                    "输出行(和);\n输出行(大表[99999]);\n停止\n";
                string 四兆 = 跑大内存(池源, 4 * 1024 * 1024);
                string 一兆 = 跑大内存(池源, 1024 * 1024);
                bool 一兆档真撞墙 = 一兆.Contains("池用完了", StringComparison.Ordinal);
                记录("大内存档 池长过 1MB:十万个整数的动态列表 4MB 档跑得完(`100000|4950000|99`)、1MB 档当场报「池用完了」",
                    四兆 == "100000|4950000|99" && 一兆档真撞墙,
                    $"4MB=<{四兆}> 1MB=<{截断(一兆, 60)}>");
            }
            catch (Exception ex) { 记录异常("大内存档 池越过 1MB", ex); }

            // ------------------------------------------------------------
            // ⑤ 接线口:C 后端**转译**这条腿也认大内存档(逐字节对拍由 `C后端全量对拍` 覆盖)
            // ------------------------------------------------------------
            try
            {
                var (结果, _) = 编大内存(
                    "整数 填a[65536];\n整数 填b[65536];\n整数 填c[65536];\n整数 填d[65536];\n" +
                    "整数 尾 = 7;\n输出行(尾);\n输出行(填d[65535]);\n停止\n", 4 * 1024 * 1024);
                string c源 = C后端C.转译(结果, 4 * 1024 * 1024).源码;
                记录("大内存档 C 后端转译不报错(4MB 档;逐字节对拍见 `C后端全量对拍` 那一组)",
                    c源.Length > 0 && c源.Contains("4194304", StringComparison.Ordinal),
                    $"C 源码 {c源.Length} 字节 / 含内存大小 4194304");
            }
            catch (Exception ex) { 记录异常("大内存档 C 后端转译", ex); }
        }
    }
}
