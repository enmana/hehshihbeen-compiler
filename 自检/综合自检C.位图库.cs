// ============================================================
// 综合自检C.位图库.cs —— 控 1-④:`Sample\库\位图.hb` 的机械判据
//
//   库本身是**纯 HB**,所以这一组走的是"真编真跑一段 HB 源码、逐行对输出"那条老路
//   (与 `界面控件库` / `模型库` 那几组同一套)。
//
//   钉的是五件事:
//     ① **建 / 尺寸 / 释放 / 旧号作废**:库把宿主那两条(`建位图` 写回句柄 + `位图尺寸`)收成一个返回值;
//     ② **画的每一档都真画上去了**:填底 / 矩形 / 空心框 / 线 / 横线 / 竖线 / 点 —— 逐格读回来对;
//     ③ **越界不报错**:画越界什么都不做、取越界给 0(与宿主那两条同口径);
//     ④ **边界**:宽高 ≤ 0 建不出(给 -1)、释放过之后句柄作废(宽给 -1、读给 0);
//     ⑤ ⭐ **一整块像素 = 一条命令**:位图这条路存在的**全部理由** —— 一帧里 `贴位图` 只出现一次,
//        与图多大无关(施工图 §1 的判据原话)。
//
//   ⚠ 这一组**不量"图上画了多少像素"**:那是宿主侧的事(位图那一组已经压着);
//     这一组只量**库**这一层有没有把宿主那八条接对。
// ============================================================
using System;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 位图库自检()
        {
            // 包含路径要**绝对**(自检不在 Sample 目录里跑 ⇒ 相对路径解析不了;与 `消息与状态机库` 同一套)
            string? 示例 = 找示例目录();
            string 库路径 = 示例 == null
                ? ""
                : System.IO.Path.Combine(System.IO.Directory.GetParent(示例)!.FullName, "Sample", "库", "位图.hb")
                    .Replace('\\', '/');
            if (库路径.Length == 0 || !System.IO.File.Exists(库路径))
            {
                跳过("位图库 定位位图.hb", $"找不到 {库路径}(不在工作副本里跑就跳过)");
                return;
            }

            // 一段把库里每一个入口都走一遍的 HB 源码 —— 每行输出后面就是"期望哪个数"
            string 源 = $"包含 \"{库路径}\"\n" +
            "// ① 建:给句柄(≥1);尺寸问得到\n" +
            "整数 图 = 位图.建(32, 24);\n" +
            "输出行(图 > 0);\n" +                                   // 1
            "输出行(位图.宽(图));\n" +                              // 32
            "输出行(位图.高(图));\n" +                              // 24
            "输出行(位图.宽(999));\n" +                             // -1 没建过的号
            "输出行(位图.建(0, 8));\n" +                            // -1 高合法、宽不合法 ⇒ 建不出
            "// ② 画:每一档都试一遍,再逐格读回来\n" +
            "位图.填底(图, 4278190080);\n" +                        // 0xFF000000
            "位图.块(图, 2, 3, 4, 5, 4294901760);\n" +              // 0xFFFF0000:x 2~5 / y 3~7
            "位图.框(图, 10, 10, 8, 6, 4278255360);\n" +            // 0xFF00FF00:四条边
            "位图.线(图, 0, 0, 5, 5, 4294967295);\n" +              // 0xFFFFFFFF:对角线
            "位图.横线(图, 20, 20, 5, 4278190335);\n" +             // 0xFF0000FF:x 20~24 / y 20
            "位图.竖线(图, 28, 16, 4, 4294901760);\n" +             // 0xFFFF0000:x 28 / y 16~19
            "位图.点(图, 31, 23, 4294967295);\n" +                  // 一个白点
            "输出行(位图.取像素(图, 0, 0));\n" +                    // -1(对角起点)
            "输出行(位图.取像素(图, 1, 1));\n" +                    // -1(对角线穿过这一格 —— 别当成"填的黑底")
            "输出行(位图.取像素(图, 2, 2));\n" +                    // -1(同上)
            "输出行(位图.取像素(图, 5, 5));\n" +                    // -1(对角终点)
            "输出行(位图.取像素(图, 6, 6));\n" +                    // -16777216(对角线外面:填的黑底)
            "输出行(位图.取像素(图, 3, 4));\n" +                    // -65536(红块里)
            "输出行(位图.取像素(图, 20, 15));\n" +                  // -16777216(空处:黑底)
            "输出行(位图.取像素(图, 10, 10));\n" +                  // -16711936(框左上角)
            "输出行(位图.取像素(图, 13, 13));\n" +                  // -16777216(框里面:空的)
            "输出行(位图.取像素(图, 22, 20));\n" +                  // -16776961(横线)
            "输出行(位图.取像素(图, 28, 18));\n" +                  // -65536(竖线)
            "输出行(位图.取像素(图, 31, 23));\n" +                  // -1(那个白点)
            "输出行(位图.取像素(图, 32, 0));\n" +                   // 0(越界读)
            "位图.点(图, 99, 99, 4294967295);\n" +                  // 越界画:什么都不做
            "位图.块(图, 40, 40, 4, 4, 4294967295);\n" +            // 整块在外面:也不做
            "输出行(位图.取像素(图, 31, 23));\n" +                  // -1(越界画没弄坏别的格子)
            "// ③ 释放与旧号\n" +
            "输出行(位图.释放(图));\n" +                            // 1
            "输出行(位图.释放(图));\n" +                            // 0(再释放一次不认)
            "输出行(位图.宽(图));\n" +                              // -1(旧号作废 —— 这一格有承诺)
            "输出行(位图.取像素(图, 0, 0));\n" +                    // 残值(句柄不认时**不做承诺**;见下面那条断言的说明)
            "整数 图二 = 位图.建(2, 2);\n" +
            "输出行(图二 > 图);\n" +                                // 1(号只增不减)
            "输出行(位图.同图(图二, 图二));\n" +                    // 1
            "输出行(位图.同图(图二, 图));\n" +                      // 0
            "位图.释放(图二);\n" +
            "// ④ 贴到窗口:一整块像素 = 一条命令(要挂呈现口才量得到)\n" +
            "整数 图三 = 位图.建(8, 6);\n" +
            "位图.填底(图三, 4278190335);\n" +
            "逻辑 开了 = 打开窗口(\"位图库\", 40, 30);\n" +
            "位图.贴(图三, 4, 4);\n" +
            "刷新();\n" +
            "位图.释放(图三);\n" +
            "关闭窗口();\n" +
            "停止\n";

            // ⭐ 贴那一小段要**挂无头呈现**才量得到命令流(与 `位图` 那一组同一套做法):
            //   挂上量完立刻清空 + 摘掉,免得别的条目看见一个开着的窗口 / 一份残留队列。
            var 无头出 = new System.IO.StringWriter();
            图形宿主C.挂上(null);
            string 跑错;
            string 输出;
            try
            {
                图形宿主C.挂上(new 无头呈现C(无头出));
                输出 = 读OBJ模型跑一段(源, out 跑错);
            }
            finally
            {
                图形宿主C.清空();
                图形宿主C.挂上(null);
            }
            if (跑错.Length > 0)
            {
                记录("位图库 建 / 画 / 取 / 释放 / 边界(真编真跑一段 HB)", false, $"抛异常:{跑错}");
                return;
            }

            string[] 行 = 输出.Replace("\r\n", "\n").Trim().Split('\n');
            string 取(int i) => i < 行.Length ? 行[i].Trim() : "(缺)";

            记录("位图库 建给句柄 + 尺寸问得到(库把写回句柄与问尺寸收成一个返回值)",
                取(0) == "1" && 取(1) == "32" && 取(2) == "24",
                $"拿到句柄={取(0)} 宽={取(1)} 高={取(2)}");
            记录("位图库 边界:没建过的号给 -1、宽高非法建不出(给 -1)、图不占运行内存",
                取(3) == "-1" && 取(4) == "-1",
                $"没建过的号 宽={取(3)};建(0, 8)={取(4)}");
            // ⚠ 颜色一律按**有符号十进制**打(`测试输出` 的口径):0xFFFFFFFF = -1、0xFFFF0000 = -65536、
            //   0xFF000000 = -16777216、0xFF00FF00 = -16711936、0xFF0000FF = -16776961。
            // ⚠⚠ 这一条**踩过一次**(第414批):`(1,1)` 我头一遍按"填的黑底"写,实际是**白** ——
            //   因为 `位图.线(图, 0, 0, 5, 5, …)` 那条**对角线正好穿过 (1,1)**。
            //   ⇒ 判据改成"**一个坐标一条期望值**"摆明写(而且 (1,1) 那一格**有意留着**当回归钉子:
            //     谁要是把 `线` 改成只画两个端点,它当场红)。坐标→颜色的对照表:
            //     (0,0) 对角起点=白 · (1,1) 对角线穿过的格子=白 · (2,2) 同上 · (5,5) 对角终点=白
            //     (6,6) 对角线**外面**=填的黑底 · (3,4) 红块里 · (20,15) 什么也没画的空处=黑底
            //     (10,10) 框左上角=绿 · (13,13) 框**里面**(空的)=黑底 · (22,20) 横线=蓝
            //     (28,18) 竖线=红 · (31,23) 白点 · (32,0) 越界(宽 32 ⇒ x 越界)给 0
            //     (31,23) 再看一次(越界画完,别的格子没被弄坏)
            (string 坐标, string 期望)[] 逐格 =
            [
                ("(0,0)", "-1"), ("(1,1)", "-1"), ("(2,2)", "-1"), ("(5,5)", "-1"), ("(6,6)", "-16777216"),
                ("(3,4)", "-65536"), ("(20,15)", "-16777216"),
                ("(10,10)", "-16711936"), ("(13,13)", "-16777216"), ("(22,20)", "-16776961"),
                ("(28,18)", "-65536"), ("(31,23)", "-1"), ("(32,0)", "0"), ("(31,23) 再看", "-1"),
            ];
            int 对得上 = 0;
            var 明细 = new System.Text.StringBuilder();
            for (int i = 0; i < 逐格.Length; i++)
            {
                string 实读 = 取(5 + i);
                if (实读 == 逐格[i].期望) 对得上++;
                else 明细.Append($"{逐格[i].坐标} 读 {实读} 期望 {逐格[i].期望};");
            }
            记录("位图库 填底 / 矩形 / 空心框 / 线 / 横线 / 竖线 / 点 —— 七档都真画上去了(14 个坐标逐格对)",
                对得上 == 逐格.Length,
                $"14 格里对 {对得上} 格" + (明细.Length == 0 ? ";" + string.Join(" ", 逐格.Select(x => x.坐标 + "=" + x.期望)) : ";不对的:" + 明细));
            // 越界那两格就在上面那张表里(`(32,0)` 给 0、越界画完 `(31,23)` 再看还是 -1)
            记录("位图库 释放:第一次成功、第二次不认、旧号当场作废(宽 -1 是**有承诺**的那一格)",
                取(19) == "1" && 取(20) == "0" && 取(21) == "-1",
                $"释放={取(19)} 再释放={取(20)} 旧号问宽={取(21)}(期望 1 / 0 / -1)");
            // ⚠⚠ **"句柄不认"与"坐标越界"分得开**(第414批实测的坑,别把它当缺陷):
            //   宿主那条 `取图像素` 走的是**纯返回值**那条路(没有写回槽),它在"句柄不认"那一路
            //   只给状态码、**不写结果** ⇒ 拿释放过的句柄去读,读回来的是**上一次的残值**
            //   (实测就是句柄自己那个数)。坐标越界那一档是**真写 0** 的,所以有承诺。
            //   ⇒ 判据写成"**要判图还在不在,就用 `宽` 那一格**" —— 那一条有承诺;并如实量一次残值。
            记录("位图库 句柄不认时:问尺寸给 -1(有承诺);取像素那一格**不做承诺**(残值,别当缺陷)",
                取(21) == "-1" && 取(22) != "(缺)",
                $"旧号问宽={取(21)}(有承诺 -1);旧号取像素={取(22)}(残值,不作判据 —— 要判就用 `宽`)");
            记录("位图库 句柄只增不减 + 同图(新号更大;同一个号是同一张,旧号不是新号)",
                取(23) == "1" && 取(24) == "1" && 取(25) == "0",
                $"新号更大={取(23)} 同图(自己,自己)={取(24)} 同图(新,旧)={取(25)}");

            // ⭐ 施工图 §1 那条判据:**一整块像素 = 一条命令**(与图多大无关)
            string 贴流 = 无头出.ToString();
            int 贴条数 = 0;
            string 贴行 = "";
            foreach (string s in 贴流.Replace("\r\n", "\n").Split('\n'))
            {
                string t = s.Trim();
                if (!t.StartsWith("贴位图", StringComparison.Ordinal)) continue;
                贴条数++;
                贴行 = t;
            }
            记录("位图库 ⭐贴:一整块像素 = 一条命令(施工图 §1 的判据;不是逐像素画矩形)",
                贴条数 == 1 && 贴行.Contains("宽=8") && 贴行.Contains("高=6"),
                $"一帧里 `贴位图` 出现 {贴条数} 次({贴行})—— 判据是 **1** 次");

            // 接线哨兵:库头那张"提供哪些函数"的清单与实际的公开方法对得上(改一个名字就红)
            string? 根 = 找仓库根目录();
            if (根 == null)
            {
                跳过接线("位图库 接线:库文件在 + 函数清单对得上", "找不到仓库根(不在工作副本里跑)");
                return;
            }
            try
            {
                string 库源 = System.IO.File.ReadAllText(System.IO.Path.Combine(根, "Sample", "库", "位图.hb"));
                // ⚠ 扫的**只算真代码行**(注释里提"平台名"是常有的事:库头就写着"两套字体栈不一样")
                string 库码 = string.Join("\n", 库源.Replace("\r\n", "\n").Split('\n')
                    .Select(x => x.Trim())
                    .Where(x => !x.StartsWith("//", StringComparison.Ordinal)));
                string[] 该有 = ["建", "释放", "宽", "高", "同图", "填底", "点", "取像素", "线", "横线", "竖线", "块", "框", "字", "字色", "贴", "字宽", "字高"];
                bool 都在 = true;
                foreach (string 名 in 该有)
                    if (!库源.Contains($"方法 {名}(", StringComparison.Ordinal)) { 都在 = false; break; }
                // 库里**不许**出现平台名(控件那一层的铁律:第 ② 层一份 HB 代码全平台共用)
                string[] 平台名 = ["Win32", "GTK", "X11", "HWND", "Avalonia", "WPF", "System.Drawing"];
                bool 干净 = true;
                foreach (string 名 in 平台名)
                    if (库码.Contains(名, StringComparison.Ordinal)) { 干净 = false; break; }
                记接线("位图库 接线:18 个入口都在 + 库里一个平台名都不出现(第 ② 层一份 HB 全平台共用)",
                    都在 && 干净, $"18 个方法都在={都在};平台名干净(只算代码行)={干净}");
            }
            catch (Exception ex) { 记录异常("位图库 接线(按源码钉)", ex); }
        }
    }
}
