using System.Text;
using hehshihbeen_compiler;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// R1-4(2026-09-22):ISA 补**间接控制转移** —— `调用寄存器`(0x35)/`跳转寄存器`(0x36),
    /// 两条都住现成的「单寄存器」档([31:24] 操作码 + [23:20] 寄存器,低 20 位保留)。
    ///
    /// 为什么加:编译器这类**分派密集**的程序要用分派表 / 跳转表(目标地址是算出来的,不是编译期常量);
    /// 没有这两条,每种分派都得写成一长串 `如果 / 否则如果`,几十条路每条都要比到命中为止。
    ///
    /// 这个分组钉五件事:
    /// ① **语义**:`调用寄存器` 与老 `调用` 同一口径(返回地址压**硬件栈**,`返回` 回得来、栈指针复原);
    ///    `跳转寄存器` 不压返回地址;
    /// ② **编码**:0x35 / 0x36 + [23:20] 寄存器,且新老两种写法(`调用 R0` 与 `调用寄存器 R0`)逐字节相同;
    /// ③ **老写法一个不破**:`调用 标签` 仍是 0x0D、`跳转 标签` 仍是 0x06;
    /// ④ **对齐**:目标在寄存器里 ⇒ 只能在运行期查,不对齐报**带行号**的运行期错误(与 R2-4 那条编译期闸一个口径);
    /// ⑤ **老 53 条机器码一字未改**:那份"每条指令各来一发"的字节流指纹与开工量底同一个数。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary> 开工量底(探针 `工具\临时\r14\探针`)对"老 53 条各编一条"这份字节流算出的指纹 </summary>
        private const string 老五十三条编码指纹 = "91A78D891D1F25F9";

        /// <summary> 示例表里那些标签要垫在前面(标签独占一行是合法写法) </summary>
        private const string 间接跳转标签垫 =
            "循环头:\n结束:\n子程序:\n相等分支:\n不等分支:\n数据区:\n左大:\n左小:\n";

        private static void 间接跳转自检()
        {
            // 组里凡是"可能抛"的检查都走它:抛了如实记一条 FAIL,不让整组连坐(与 `跑且断言` 同一套)
            void 检查(string 名称, Func<(bool 通过, string 详情)> 试)
            {
                try
                {
                    var (通过, 详情) = 试();
                    记录(名称, 通过, 详情);
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            string 四字节(byte[] 码) => 码.Length >= 4 ? Convert.ToHexString(码[..4]) : $"({码.Length} 字节)";

            // ---- ① 语义:间接调用真的调得过去、`返回` 真的回得来 ----
            const string 调用源 =
                "加载立即数 R3, 0\n" +
                "取地址 R0, 子\n" +
                "调用寄存器 R0\n" +
                "复制 R4, R1\n" +          // 回到下一条的证据:R1 是子程序写的 42
                "停止\n" +
                "子:\n" +
                "加载立即数 R1, 42\n" +
                "返回\n";
            检查("R1-4 `调用寄存器` 真的调过去、`返回` 回得来(子程序写的 42 拿到了)且返回地址压硬件栈(栈指针复原)", () =>
            {
                var 机 = 运行(调用源);
                return (机.寄存器[4] == 42 && 机.栈指针 == (uint)机.内存.Length,
                    $"R4={机.寄存器[4]}(期望 42) SP={机.栈指针} 内存={机.内存.Length}");
            });

            const string 跳转源 =
                "取地址 R0, 落点\n" +
                "跳转寄存器 R0\n" +
                "加载立即数 R1, 1\n" +        // 跳过去了就不该执行
                "停止\n" +
                "落点:\n" +
                "加载立即数 R2, 7\n" +
                "停止\n";
            检查("R1-4 `跳转寄存器` 真的跳过去(中间那条没执行)、且不压返回地址(栈指针没动过)", () =>
            {
                var 机 = 运行(跳转源);
                return (机.寄存器[2] == 7 && 机.寄存器[1] == 0 && 机.栈指针 == (uint)机.内存.Length,
                    $"R2={机.寄存器[2]}(期望 7) R1={机.寄存器[1]}(期望 0) SP={机.栈指针}");
            });

            // ---- ② 编码:0x35 / 0x36,寄存器在 [23:20];新老两种写法逐字节相同 ----
            检查("R1-4 编码:`调用寄存器 R3` = 0x35、`跳转寄存器 R3` = 0x36,寄存器在 [23:20]", () =>
            {
                byte[] 调 = 汇编("调用寄存器 R3\n停止");
                byte[] 跳 = 汇编("跳转寄存器 R3\n停止");
                return (调[..4].SequenceEqual(new byte[] { 0x00, 0x00, 0x30, 0x35 })
                    && 跳[..4].SequenceEqual(new byte[] { 0x00, 0x00, 0x30, 0x36 }),
                    $"{四字节(调)} / {四字节(跳)}(期望 00003035 / 00003036)");
            });
            检查("R1-4 老助记符的寄存器写法也认:`调用 R0` / `跳转 R0` 与正式名**逐字节相同**", () =>
            {
                byte[] 老名调 = 汇编("调用 R0\n停止");
                byte[] 正式调 = 汇编("调用寄存器 R0\n停止");
                byte[] 老名跳 = 汇编("跳转 R0\n停止");
                byte[] 正式跳 = 汇编("跳转寄存器 R0\n停止");
                return (老名调[..4].SequenceEqual(正式调[..4]) && 老名跳[..4].SequenceEqual(正式跳[..4]),
                    $"调用 R0={四字节(老名调)} vs {四字节(正式调)};跳转 R0={四字节(老名跳)} vs {四字节(正式跳)}");
            });

            // ---- ③ 老写法一个不破(只加不改) ----
            检查("R1-4 老写法一个不破:`调用 标签` 仍是 0x0D、`跳转 标签` 仍是 0x06", () =>
            {
                byte[] 老调 = 汇编("调用 子\n停止\n子:\n返回");
                byte[] 老跳 = 汇编("跳转 标\n停止\n标:\n停止");
                return (老调[3] == 0x0D && 老跳[3] == 0x06 && 老调[0] == 0x02 && 老跳[0] == 0x02,
                    $"{四字节(老调)} / {四字节(老跳)}(期望 0200000D / 02000006)");
            });

            // ---- 反汇编(反汇编窗 / 调试器看到的字) ----
            检查("R1-4 反汇编认这两条(正式名 + 寄存器都在)", () =>
            {
                byte[] 两条 = 汇编("调用寄存器 R3\n跳转寄存器 R9\n停止");
                string? 左条 = 反汇编C.反汇编一条(两条, 0, out _);
                string? 右条 = 反汇编C.反汇编一条(两条, 4, out _);
                return (左条 == "调用寄存器 R3" && 右条 == "跳转寄存器 R9", $"{左条} / {右条}");
            });
            检查("R1-4 老助记符写法反汇编成正式名(`调用 R3` → `调用寄存器 R3`)", () =>
            {
                string? 行 = 反汇编C.反汇编一条(汇编("调用 R3\n停止"), 0, out _);
                return (行 == "调用寄存器 R3", $"{行}");
            });

            // ---- ④ 对齐:目标在寄存器里 ⇒ 只能运行期查,而且要带行号 ----
            void 对齐错(string 名称, string 源)
            {
                检查(名称, () =>
                {
                    var 编译结果 = 编译(源);
                    var 机器 = new 虚拟机C();
                    机器.取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址);   // 命令行 / IDE 挂的是同一个回调
                    string 文案 = "";
                    try { 机器.运行(编译结果); }
                    catch (运行期错误C 错) { 文案 = 错.用户文案; }
                    return (文案.Contains("对齐") && 文案.StartsWith("第 3 行:")
                        && !文案.Contains("Exception") && !文案.Contains("PC="), 文案);
                });
            }
            对齐错("R1-4 间接调用目标没对齐 → 带行号的运行期错误(第 3 行那条)",
                "取地址 R0, 子\n加立即数 R0, 2\n调用寄存器 R0\n停止\n子:\n返回");
            对齐错("R1-4 间接跳转目标没对齐 → 带行号的运行期错误(第 3 行那条)",
                "取地址 R0, 落点\n加立即数 R0, 2\n跳转寄存器 R0\n停止\n落点:\n停止");

            检查("R1-4 间接跳转跳出内存 → 仍然明确报错(不静默停机)", () =>
            {
                var 编译结果 = 编译("加载立即数 R0, 0xFFFFC\n加立即数 R0, 4\n跳转寄存器 R0\n停止");
                var 机器 = new 虚拟机C();
                机器.取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址);
                string 文案 = "";
                try { 机器.运行(编译结果); }
                catch (运行期错误C 错) { 文案 = 错.用户文案; }
                return (文案.Contains("内存外面"), 文案);
            });

            // ---- ⑤ 老 53 条机器码一字未改(与开工量底同一个指纹) ----
            检查($"R1-4 老 53 条指令的机器码一字未改(开工量底指纹 {老五十三条编码指纹})", () =>
            {
                var 源 = new StringBuilder(间接跳转标签垫);
                int 收 = 0;
                foreach (var (_, 英文, 码, _) in 指令C.全部指令)
                    if (码 <= 0x34 && 指令C.取示例(英文) is { } 例) { 源.Append(例).Append('\n'); 收++; }
                源.Append("停止\n");
                string 指纹 = Convert.ToHexString(
                    System.Security.Cryptography.SHA256.HashData(汇编(源.ToString())))[..16];
                return (指纹 == 老五十三条编码指纹, $"收 {收} 条;指纹 {指纹}");
            });

            检查("R1-4 优化开/关都编得出、机器码一致", () =>
            {
                byte[] 开 = new 汇编器C().汇编多文件带调试([("主程序.hb", 调用源)], true).机器码;
                byte[] 关 = new 汇编器C().汇编多文件带调试([("主程序.hb", 调用源)], false).机器码;
                return (开.SequenceEqual(关), $"{开.Length} / {关.Length} 字节");
            });
        }
    }
}
