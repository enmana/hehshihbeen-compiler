// ============================================================
// 引用多下标自检(H3 ④,第322批)—— `表[行号].格[列号]`
//
//   H3 那条"声明期限制"的最后一件:**结构数组的元素里再取一次运行期下标**。
//   落地形态 = 把"结构里的定长数组字段"当成**下一维**挂进 `剩余维`,后面那个下标就走
//   **H68-1 多维数组那条现成的路**(下标 × 步长 线性累加)—— 一条新的地址机制都没加。
//   所以钉法分两半:
//     · **行为**:两个下标都是变量时读改对不对;第二下标之后点结构字段;字段偏移非 0;
//       与"先算地址、再按下标读写"是不是同一格;字符串数组字段;越界文案(说"字段"不说"第 2 维")
//     · **地基共用**:寄存器阈值必须与多维数组那条老路**同一个数**(3 个访问编过、4 个撞上限)——
//       这一条同时钉住"没有为它新写一套地址累加","累加值落槽 + 按段还寄存器"那条硬约束也照旧
//
//   为什么这么钉:H3 ④ 是**放开一条老限制**,不是加语法;最容易出的错是"另起一套地址算错位"、
//   或者"寄存器多占一个"—— 前者用"与手算地址读同一格"钉,后者用"与老路同阈值"钉。
// ============================================================

using System;
using System.Collections.Generic;
using System.Linq;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 引用多下标自检()
        {
            const string 头 = "结构 点\n{\n整数 x;\n整数 y;\n}\n" +
                "结构 行\n{\n整数 前;\n整数 格[4];\n点 角[2];\n}\n行 表[3];\n整数 行号 = 1;\n整数 列号 = 2;\n";

            // ---- ① 两个下标都是变量:读改 ----
            跑输出断言("H3 ④ `表[行号].格[列号]`:结构数组的元素里再取一次运行期下标,读改都对",
                头 + "表[行号].格[列号] = 7;\n测试输出(表[行号].格[列号]);\n" +
                "表[0].格[0] = 1;\n表[2].格[3] = 9;\n测试输出(表[0].格[0] * 100 + 表[2].格[3]);\n停止",
                "7\n109");

            // ---- ② 字段偏移非 0(格 前面还有 前):常量偏移照旧折进地址 ----
            跑输出断言("H3 ④ 字段偏移非 0 时也对(格 前面还有一格,常量偏移折进地址)",
                头 + "表[行号].前 = 5;\n表[行号].格[列号] = 7;\n" +
                "测试输出(表[行号].前 + 表[行号].格[列号]);\n" +
                "表[行号].格[0] = 10;\n测试输出(表[行号].格[0]);\n表[0].格[1] = 11;\n测试输出(表[0].格[1]);\n停止",
                "12\n10\n11");

            // ---- ③ 第二下标之后再点结构字段 / 再取常量下标 ----
            跑输出断言("H3 ④ 第二下标之后还能点结构字段(`表[行号].角[0].x`)",
                头 + "表[行号].角[0].x = 21;\n表[行号].角[1].y = 22;\n" +
                "测试输出(表[行号].角[0].x + 表[行号].角[1].y);\n停止",
                "43");

            // ---- ④ 与"先算地址、再按下标读写"是**同一格**(线性累加的证据) ----
            跑输出断言("H3 ④ 与\"先算地址、再按下标读写\"读改的是同一格(下标 × 步长 线性累加)",
                头 + "表[行号].格[列号] = 7;\n地址 头 = 地址(表[行号].格[0]);\n" +
                "测试输出(取字(头, 列号 * 4));\n存字(头, 列号 * 4, 66);\n" +
                "测试输出(表[行号].格[列号]);\n停止",
                "7\n66");

            // ---- ⑤ 行里放动态列表(`整数 格[];`)照旧能用(那一路本来就认两个运行期下标) ----
            跑输出断言("H3 ④ 行里放**动态列表**时两个运行期下标也认(`表[行号].数[列号]`)",
                "结构 行\n{\n整数 数[];\n}\n行 表[3];\n整数 行号 = 1;\n整数 列号 = 2;\n" +
                "表[行号].数.添加(11);\n表[行号].数.添加(22);\n表[行号].数.添加(33);\n" +
                "测试输出(表[行号].数[列号]);\n停止",
                "33");

            // ---- ⑥ 字符串数组字段:两个运行期下标取出来照样是字符串 ----
            跑输出断言("H3 ④ 字符串数组字段(`字符串 名单[3];`)两个运行期下标取出来也是字符串",
                "结构 行\n{\n字符串 名单[3];\n}\n行 表[2];\n整数 行号 = 1;\n整数 列号 = 2;\n" +
                "表[行号].名单[列号] = \"中\";\n表[行号].名单[0] = \"左\";\n" +
                "输出行(表[行号].名单[列号]);\n输出行(表[行号].名单[0]);\n停止",
                "中\n左");

            // ---- ⑦ 越界:常量下标编译期拦、运行期下标带行号停下,两处都说"字段" ----
            string 常量越界 = 异常文本(() => 汇编(
                头 + "表[行号].格[4] = 1;\n停止"));
            记录("H3 ④ 常量第二下标越界:编译期当场报,说\"字段 '格' 只有 4 个元素\"(不冒充第 2 维)",
                常量越界.Contains("下标越界", StringComparison.Ordinal)
                && 常量越界.Contains("字段 '格' 只有 4 个元素", StringComparison.Ordinal), 常量越界);

            string? 运行期越界 = 运行期文案(
                头 + "整数 列 = 4;\n表[行号].格[列] = 1;\n测试输出(1);\n停止");
            记录("H3 ④ 运行期第二下标越界:带行号停下,同一句话(字段 '格' 只有 4 个元素)",
                运行期越界 != null && 运行期越界.Contains("字段 '格' 只有 4 个元素", StringComparison.Ordinal),
                运行期越界 ?? "(没报错)");

            // ---- ⑧ 地基共用:寄存器阈值与多维数组那条老路**同一个数** ----
            static string 造源码(string 头, Func<int, string> 项, int 个数) =>
                头 + "测试输出(" + string.Join(" + ", Enumerable.Range(0, 个数).Select(项)) + ");\n停止";
            const string 头新旧 = "结构 点\n{\n整数 x;\n整数 y;\n}\n" +
                "结构 行\n{\n整数 前;\n整数 格[4];\n点 角[2];\n}\n行 表[3];\n整数 袋[3][4];\n" +
                "整数 行号 = 1;\n整数 列0 = 0;\n整数 列1 = 1;\n整数 列2 = 2;\n整数 列3 = 3;\n";
            // 形状一:第二个下标是**常量**(走"单下标"那条路)
            int 新常量 = 阈值(头新旧, i => $"表[行号].格[{i}]", 8);
            int 旧常量 = 阈值(头新旧, i => $"袋[行号][{i}]", 8);
            // 形状二:第二个下标也是**变量**(走"多维累加"那条路)
            int 新运行 = 阈值(头新旧, i => $"表[行号].格[列{i}]", 4);
            int 旧运行 = 阈值(头新旧, i => $"袋[行号][列{i}]", 4);
            记录("H3 ④ 一句里放得下的访问个数与多维数组**同一个阈值**(共用一条累加地基,没有另起一套)",
                新常量 == 旧常量 && 新运行 == 旧运行 && 新常量 >= 3 && 新运行 >= 2,
                $"常量第二下标:结构数组 {新常量} 个 / 多维数组 {旧常量} 个;" +
                $"运行期第二下标:结构数组 {新运行} 个 / 多维数组 {旧运行} 个");

            // ---- ⑨ 帮助:那条老限制撤了,《中间层速查》写成规格 ----
            string 上手 = 帮助文本C.快速上手();
            记录("帮助《第27节·还没有的写法》里那条「一条引用里的运行期下标暂时只有一个」已撤",
                !上手.Contains("一条引用里的运行期下标暂时只有一个", StringComparison.Ordinal),
                "那条限制放开之后,用户文档里不能再挂着它");

            string 速查 = 帮助文本C.中间层速查();
            记录("帮助《中间层速查》把\"结构数组的元素里再取一次下标\"写成规格",
                速查.Contains("表[行号].格[列号]", StringComparison.Ordinal)
                && 速查.Contains("再取一次下标**:", StringComparison.Ordinal),
                "《中间层速查》数据那一节");
        }

        /// <summary>
        /// 一句 `测试输出(a + b + …)` 里**最多放得下几个访问**(逐个加,第一个编不过的个数减一)。
        /// 用来比"新路"与"多维数组那条老路"的寄存器阈值 —— 两者应当同一个数。
        /// </summary>
        private static int 阈值(string 头, Func<int, string> 项, int 上限)
        {
            int 能编 = 0;
            for (int n = 1; n <= 上限; n++)
            {
                string 源 = 头 + "测试输出(" + string.Join(" + ", Enumerable.Range(0, n).Select(项)) + ");\n停止";
                try { 汇编(源); 能编 = n; }
                catch (Exception) { break; }
            }
            return 能编;
        }
    }
}
