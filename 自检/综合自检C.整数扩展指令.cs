// ============================================================
// 通用化第2批(2026-10-10):**整数扩展九条**(ISA 0x40~0x47)
//
//   用户 2026-10-10 拍板补的是 `工具\临时\通用化测量\通用化交接.md` §3 §C 那份"真缺口"的
//   **第 2、3、4 项**:
//     ② **有符号除法 / 有符号取余 / 高位乘** —— 老 `除法`/`取余` 是无符号,有符号除法一直是
//        **中间层自己展开**的一大段符号整理 ⇒ 实测"一句里两处运行期除法就把 15 个临时寄存器
//        用光"(**H88**)。有了这两条,那段展开整段删掉。
//     ③ **前导零 / 尾随零 / 数一位** —— `位.hb` 那三个是**软件循环**,压测级热点;
//        而且 C 后端要照抄一份软件版 ⇒ 两条腿各写一遍迟早漂。
//     ④ **符号扩展 / 零扩展** —— 现在靠"窄类型读 + 左移立即数 + 异或/减"凑(3 条)。
//
//   ★ 这一组钉五件事:
//     ① **语义**:九条各若干格(含**负数**、含 `0`、含 `-2^31 / -1` 那一格回绕),
//        期望值**由 C# 现算**(不手抄数当基准),判据是**逐位**相等;
//     ② **除法那两条的除零照旧报运行期错误**(与老 `除法`/`取余` 同一档,不是浮点那种 ±Inf);
//     ③ **`前导零`/`尾随零`/`数一位` 的 `0` 那一格**给 32 / 32 / 0(显式口径,不靠硬件指令的未定义行为);
//     ④ **编码**:九条的操作码落在 `0x40~0x47`、寄存器在 [23:20]、位宽在低 20 位;
//        `符号扩展`/`零扩展` 的位宽越界(>31)汇编器**当场报错**;
//     ⑤ **老 64 条一字未改**:老指令的机器码与语义照旧(那一整族由别组的"字节流指纹"盯着,
//        这里再钉一眼"新指令没有挤占老操作码")。
// ============================================================

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 整数扩展指令自检()
        {
            void 检查(string 名称, Func<(bool 通过, string 详情)> 试)
            {
                try
                {
                    var (通过, 详情) = 试();
                    记录(名称, 通过, 详情);
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            // 跑一段纯汇编,把结果按"存字"落到 0x200 起的数据区(探针那套写法的自动化版)
            //   返回:各格的 uint 值(C# 侧现算的期望值由调用方给)
            uint[] 跑格子(IReadOnlyList<string> 每格的汇编)
            {
                var 源 = new StringBuilder();
                for (int i = 0; i < 每格的汇编.Count; i++)
                {
                    源.Append(每格的汇编[i]).Append('\n');
                    源.Append($"存字 R0, 0x{0x200 + i * 4:X}\n");
                }
                源.Append("停止\n");
                var 机 = 运行(源.ToString());
                var 值 = new uint[每格的汇编.Count];
                for (int i = 0; i < 值.Length; i++)
                    值[i] = BitConverter.ToUInt32(机.内存, 0x200 + i * 4);
                return 值;
            }

            // 一格:把 32 位常量装进 R0 的汇编(小常量走 加载立即数,大的走 载入高位 + 或立即数)
            string 装0(uint 值) => $"LUI R0, 0x{值 >> 12:X}\nOR_IMMEDIATE R0, 0x{值 & 0xFFF:X}";
            string 装1(uint 值) => $"LUI R1, 0x{值 >> 12:X}\nOR_IMMEDIATE R1, 0x{值 & 0xFFF:X}";

            // ---- ① 有符号除法 / 有符号取余:含负数、含四个符号组合 ----
            检查("整数扩展 有符号除法 / 有符号取余:四个符号组合(期望值由 C# 现算,逐位比)", () =>
            {
                (int 左, int 右)[] 格 = [(7, 2), (-7, 2), (7, -2), (-7, -2), (100, 7), (-100, 7), (0, 5), (5, 100)];
                var 每格 = new List<string>();
                foreach (var (左, 右) in 格)
                {
                    每格.Add(装0(unchecked((uint)左)) + "\n" + 装1(unchecked((uint)右)) + "\n有符号除法 R0, R1");
                }
                foreach (var (左, 右) in 格)
                {
                    每格.Add(装0(unchecked((uint)左)) + "\n" + 装1(unchecked((uint)右)) + "\n有符号取余 R0, R1");
                }
                var 实得 = 跑格子(每格);
                var 期望 = new List<uint>();
                foreach (var (左, 右) in 格) 期望.Add(unchecked((uint)(左 / 右)));
                foreach (var (左, 右) in 格) 期望.Add(unchecked((uint)(左 % 右)));
                for (int i = 0; i < 期望.Count; i++)
                    if (实得[i] != 期望[i])
                        return (false, $"第 {i + 1} 格:得 0x{实得[i]:X8}({(int)实得[i]}) / 期望 0x{期望[i]:X8}({(int)期望[i]})");
                return (true, $"{格.Length} 组除法 + {格.Length} 组取余逐位对上(C# 的 `/` 与 `%` 就是判据)");
            });

            检查("整数扩展 `-2^31 / -1` 照 C 的**回绕**给 -2^31(不报错、不抛异常)", () =>
            {
                var 值 = 跑格子([
                    装0(0x80000000u) + "\n" + 装1(0xFFFFFFFFu) + "\n有符号除法 R0, R1",
                    装0(0x80000000u) + "\n" + 装1(0xFFFFFFFFu) + "\n有符号取余 R0, R1",
                ]);
                return (值[0] == 0x80000000u && 值[1] == 0u,
                    $"商 = 0x{值[0]:X8}(该 0x80000000)/ 余 = 0x{值[1]:X8}(该 0)");
            });

            // ---- ② 高位乘 ----
            检查("整数扩展 高位乘:64 位积的**高 32 位**(与 C# 的 ulong 乘法现算比)", () =>
            {
                uint[] 表左 = [0xFFFFFFFFu, 0x80000000u, 0x00010000u, 0x12345678u, 0u, 0x7FFFFFFFu];
                uint[] 表右 = [0xFFFFFFFFu, 2u, 0x00010000u, 0x9ABCDEF0u, 0xFFFFFFFFu, 0x7FFFFFFFu];
                var 每格 = new List<string>();
                for (int i = 0; i < 表左.Length; i++)
                    每格.Add(装0(表左[i]) + "\n" + 装1(表右[i]) + "\n高位乘 R0, R1");
                var 实得 = 跑格子(每格);
                for (int i = 0; i < 表左.Length; i++)
                {
                    uint 期望 = (uint)(((ulong)表左[i] * 表右[i]) >> 32);
                    if (实得[i] != 期望)
                        return (false, $"0x{表左[i]:X8} × 0x{表右[i]:X8}:得 0x{实得[i]:X8} / 期望 0x{期望:X8}");
                }
                return (true, $"{表左.Length} 格逐位对上(期望值 = C# 的 `((ulong)a * b) >> 32`)");
            });

            // ---- ③ 前导零 / 尾随零 / 数一位 ----
            检查("整数扩展 前导零 / 尾随零 / 数一位:与 C# 的 BitOperations 逐格对拍(含 0 那一格)", () =>
            {
                uint[] 值们 = [0u, 1u, 2u, 0x80000000u, 0xFFFFFFFFu, 0x00010000u, 0x00FF0000u, 0x12345678u];
                var 每格 = new List<string>();
                foreach (uint v in 值们) 每格.Add(装0(v) + "\n前导零 R0");
                foreach (uint v in 值们) 每格.Add(装0(v) + "\n尾随零 R0");
                foreach (uint v in 值们) 每格.Add(装0(v) + "\n数一位 R0");
                var 实得 = 跑格子(每格);
                for (int i = 0; i < 值们.Length; i++)
                {
                    uint 前 = 值们[i] == 0 ? 32u : (uint)System.Numerics.BitOperations.LeadingZeroCount(值们[i]);
                    uint 尾 = 值们[i] == 0 ? 32u : (uint)System.Numerics.BitOperations.TrailingZeroCount(值们[i]);
                    uint 数 = (uint)System.Numerics.BitOperations.PopCount(值们[i]);
                    if (实得[i] != 前) return (false, $"前导零(0x{值们[i]:X8}):得 {实得[i]} / 期望 {前}");
                    if (实得[值们.Length + i] != 尾) return (false, $"尾随零(0x{值们[i]:X8}):得 {实得[值们.Length + i]} / 期望 {尾}");
                    if (实得[2 * 值们.Length + i] != 数) return (false, $"数一位(0x{值们[i]:X8}):得 {实得[2 * 值们.Length + i]} / 期望 {数}");
                }
                return (true, $"{值们.Length} 个值 × 3 条逐格对上(0 那一格:32 / 32 / 0)");
            });

            // ---- ④ 符号扩展 / 零扩展 ----
            检查("整数扩展 符号扩展 / 零扩展:低 N 位那一条口径(含 0 视作整 32 位)", () =>
            {
                (uint 值, int 宽)[] 格 = [
                    (0x0000FFFFu, 16), (0x00007FFFu, 16), (0x000000FFu, 8), (0x00000080u, 8),
                    (0xFFFFFFFFu, 8), (0xFFFFFFFFu, 16), (0xFFFFFFFFu, 31),
                    (0x12345678u, 4), (0x12345678u, 12), (0x00000001u, 1), (0x80000000u, 32), (0xFFFFFFFFu, 0),
                ];
                var 每格 = new List<string>();
                foreach (var (值, 宽) in 格) 每格.Add(装0(值) + $"\n符号扩展 R0, {宽}");
                foreach (var (值, 宽) in 格) 每格.Add(装0(值) + $"\n零扩展 R0, {宽}");
                var 实得 = 跑格子(每格);
                for (int i = 0; i < 格.Length; i++)
                {
                    var (值, 宽) = 格[i];
                    uint 符 = 宽 is >= 1 and <= 31
                        ? (((值 & ((1u << 宽) - 1)) & (1u << (宽 - 1))) != 0
                            ? (值 & ((1u << 宽) - 1)) | ~((1u << 宽) - 1)
                            : 值 & ((1u << 宽) - 1))
                        : 值;
                    uint 零 = 宽 is >= 1 and <= 31 ? 值 & ((1u << 宽) - 1) : 值;
                    if (实得[i] != 符)
                        return (false, $"符号扩展(0x{值:X8}, {宽}):得 0x{实得[i]:X8} / 期望 0x{符:X8}");
                    if (实得[格.Length + i] != 零)
                        return (false, $"零扩展(0x{值:X8}, {宽}):得 0x{实得[格.Length + i]:X8} / 期望 0x{零:X8}");
                }
                return (true, $"{格.Length} 格 × 2 条逐位对上(位宽 0 = 原样那一格也在内)");
            });

            // ---- ⑤ 除零照旧报运行期错误(与老 除法/取余 同一档) ----
            void 除零错(string 名称, string 源)
            {
                检查(名称, () =>
                {
                    var 编译结果 = 编译(源);
                    var 机器 = new 虚拟机C();
                    机器.取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址);
                    string 文案 = "";
                    try { 机器.运行(编译结果); }
                    catch (运行期错误C 错) { 文案 = 错.用户文案; }
                    return (文案.Contains("除零") && 文案.StartsWith("第 3 行:"), 文案.Length == 0 ? "没报错(不该)" : 文案);
                });
            }
            除零错("整数扩展 `有符号除法` 除零 → 带行号的运行期错误(与老 `除法` 同一档)",
                "加载立即数 R0, 7\n加载立即数 R1, 0\n有符号除法 R0, R1\n停止");
            除零错("整数扩展 `有符号取余` 除零 → 带行号的运行期错误(与老 `取余` 同一档)",
                "加载立即数 R0, 7\n加载立即数 R1, 0\n有符号取余 R0, R1\n停止");

            // ---- ⑥ 编码与操作码 ----
            检查("整数扩展 编码:九条的操作码 = 0x40~0x47、寄存器在 [23:20]、位宽在低 20 位", () =>
            {
                (string 源, byte 码, byte 寄存器, uint 低20)[] 格 = [
                    ("有符号除法 R3, R5\n停止", 0x40, 3, 0),
                    ("有符号取余 R3, R5\n停止", 0x41, 3, 0),
                    ("高位乘 R3, R5\n停止", 0x42, 3, 0),
                    ("前导零 R6\n停止", 0x43, 6, 0),
                    ("尾随零 R6\n停止", 0x44, 6, 0),
                    ("数一位 R6\n停止", 0x45, 6, 0),
                    ("符号扩展 R7, 16\n停止", 0x46, 7, 16),
                    ("零扩展 R7, 8\n停止", 0x47, 7, 8),
                ];
                foreach (var (源, 码, 寄存器, 低20) in 格)
                {
                    byte[] 字节 = 汇编(源);
                    // ⚠ 机器码是**小端**:`字节[0..3]` 按小端读回来才是那条指令的 32 位
                    uint 指令 = (uint)(字节[0] | (字节[1] << 8) | (字节[2] << 16) | (字节[3] << 24));
                    uint 得码 = 指令 >> 24, 得寄存器 = (指令 >> 20) & 0xF, 得低 = 指令 & 0xFFFFF, 得源 = (指令 >> 16) & 0xF;
                    // 双寄存器那三条:低 20 位不参与(源寄存器在 [19:16]);带位宽那两条才看低 20 位
                    uint 期望低 = 码 is 0x40 or 0x41 or 0x42 ? 得低 : 低20;
                    if (得码 != 码 || 得寄存器 != 寄存器 || 得低 != 期望低)
                        return (false, $"[{源.Replace("\n", " / ")}] 字节 {string.Join(" ", 字节.Take(8).Select(x => x.ToString("X2")))} " +
                            $"→ 得 码 0x{得码:X2} 寄存器 {得寄存器} 低20 {得低}(期望 码 0x{码:X2} 寄存器 {寄存器} 低20 {期望低})");
                    if (码 is 0x40 or 0x41 or 0x42 && 得源 != 5)
                        return (false, $"[{源.Replace("\n", " / ")}] 源寄存器字段 = {得源}(期望 5)");
                }
                return (true, "八条(0x40~0x47)操作码 / 寄存器 / 位宽逐条对上;双寄存器那三条的源寄存器也在 [19:16]");
            });

            检查("整数扩展 位宽越界(>32)→ 汇编器当场报错,不静默收下", () =>
            {
                var 错们 = new List<string>();
                foreach (string 行 in new[] { "符号扩展 R0, 33\n停止", "零扩展 R0, 40\n停止" })
                    try { 汇编(行); 错们.Add($"{行.Split('\n')[0]} 竟然编过了"); }
                    catch (Exception ex) { if (!ex.Message.Contains("位宽")) 错们.Add($"{行.Split('\n')[0]} 报的不是位宽:{ex.Message}"); }
                // `32` 与 `0` 都表示"整 32 位 = 什么都不做",两个都该收下
                try { 汇编("符号扩展 R0, 32\n停止"); 汇编("零扩展 R0, 32\n停止"); }
                catch (Exception ex) { 错们.Add($"位宽 32 竟然不收:{ex.Message}"); }
                return (错们.Count == 0, 错们.Count == 0 ? "33 / 40 两条当场报错;位宽 32 与 0 都收下(都表示整 32 位)" : string.Join(" ; ", 错们));
            });

            // ---- ⑦ 反汇编认得这九条(反汇编窗 / 调试器看到的就是指令名) ----
            检查("整数扩展 反汇编认得这九条(正式名 + 操作数都在)", () =>
            {
                var 行们 = new List<string>();
                foreach (string 源 in new[] { "有符号除法 R3, R5", "有符号取余 R3, R5", "高位乘 R3, R5", "前导零 R6",
                                              "尾随零 R6", "数一位 R6", "符号扩展 R7, 16", "零扩展 R7, 8" })
                {
                    byte[] 字节 = 汇编(源 + "\n停止");
                    string? 行 = 反汇编C.反汇编一条(字节, 0, out _);
                    if (行 != 源) 行们.Add($"{源} → {行}");
                }
                return (行们.Count == 0, 行们.Count == 0 ? "八条逐条反汇编成写入时的正式名" : string.Join(" ; ", 行们));
            });

            // ---- ⑧ 新指令没有挤占老操作码(老 64 条照旧认得、老编码照旧) ----
            检查("整数扩展 只加不改:老 64 条的操作码一个没动(0x00~0x3F 逐条仍取得到)", () =>
            {
                var 缺 = new List<string>();
                for (byte 码 = 0x00; 码 <= 0x3F; 码++)
                    if (指令C.取指令中文名(码) == null) 缺.Add($"0x{码:X2}");
                return (缺.Count == 0, 缺.Count == 0
                    ? "0x00~0x3F 六十四条一条不少(新九条在 0x40~0x47)"
                    : "这几条没了:" + string.Join(",", 缺));
            });
        }
    }
