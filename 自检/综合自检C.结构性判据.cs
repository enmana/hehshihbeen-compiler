// ============================================================
// 综合自检C.结构性判据.cs —— 控 1-⑤:施工图 §4.1 那四条结构性判据
//
//   为什么单开一组:`界面控件库` / `位图库` 那两组量的是"功能对不对",这一组量的是
//   **形状对不对** —— 命令数随数据量怎么涨 / 一整块贴上去是不是只有一条命令 / 内存账动不动 /
//   UI 与业务有没有缠在一起。比值型的东西**天生会漂**,所以口径一律写成**结构性等式**:
//
//     ① `界面.重画()` 的条数随列表行数怎么涨 —— 现在是 **2 + 行数**(线性)
//        ⚠ **这一条今天红着,而且是有意的**:施工图把"不随行数涨"派给了 **控 3(虚拟化长列表)**,
//        控 1 只交**原语**。这里钉成等式 `条数 == 行数 + 2` —— 控 3 落地那天它会红,
//        提醒把它翻成"同量级"(与 F-8 当年那条反向判据同一个做法:让完成那一刻自己叫)。
//     ② 一整块像素 = **一条** `贴位图`(图多大都一样)
//     ③ 位图**不占**虚拟机那 1MB:建一张 480×520 的图、**整张填满**(≈1MB),虚拟机那边一字节不动
//     ④ `UI解耦`:界面族各库**不 包含 业务库**、**不出现平台名**、契约库零依赖
//     ⑤ 人的观感单独一条:**真开窗人看一份**(机器判据全绿 ≠ 画面能看)—— 只记"归人工",不判红绿
//
//   ⚠ §4.2 那条纪律(照 T30):**不许拿帧率 / 耗时当门槛** —— 这一组只数条数、只比等式;
//     跑一次要多久只作参考数记在详情里,不进判据。
// ============================================================
using System;
using System.IO;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        /// <summary> 库文件里的**真**包含行(整行以 `包含 ` 开头 —— 注释里的"用法"不算;`// 包含` 要跳过)</summary>
        private static bool 有真包含行(string 库文本, string 片段)
        {
            foreach (string 原行 in 库文本.Replace("\r\n", "\n").Split('\n'))
            {
                string 行 = 原行.Trim();
                if (行.StartsWith("//", StringComparison.Ordinal)) continue;
                if (行.StartsWith("包含 ", StringComparison.Ordinal) && 行.Contains(片段, StringComparison.Ordinal))
                    return true;
            }
            return false;
        }

        private static void 结构性判据自检()
        {
            string? 示例 = 找示例目录();
            if (示例 == null) { 跳过("结构性判据 定位 Sample 目录", "找不到仓库里的 Sample(不在工作副本里跑)"); return; }
            string 仓库根 = Directory.GetParent(示例)!.FullName;
            string 库目录 = Path.Combine(示例, "库");
            string 界面库 = Path.Combine(库目录, "界面.hb").Replace('\\', '/');
            string 位图库 = Path.Combine(库目录, "位图.hb").Replace('\\', '/');
            if (!File.Exists(界面库) || !File.Exists(位图库))
            {
                跳过("结构性判据 定位两个界面族库", $"找不到 {界面库} / {位图库}");
                return;
            }

            // 跑一段 HB 并按行收输出(与 `位图库` 那一组同一套:包含路径给绝对路径)
            string 跑(string 源, out string 跑错)
            {
                var 编译结果 = new 汇编器C().汇编多文件带调试(
                    [("主程序.hb", 源)], true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译结果);
                解码.收尾();
                跑错 = 编译结果.查运行期报错(vm.内存) is { } 说明 ? 说明 : "";
                return 缓冲.ToString();
            }
            string[] 行们(string 出) => 出.Replace("\r\n", "\n").Trim().Split('\n');

            // ---------- ① 命令数 vs 数据量:现在是 `2 + 行数`(线性) ----------
            try
            {
                // ⚠ `界面` 那个结构 200 字节,放不进 96 字节的帧 ⇒ 用**顶层**那一份(探针里量过)。
                //   一档一个程序:500 行那一档自己就要 400 多万条指令(实测 ~0.7 秒),别五档挤一个程序。
                const string 模板 =
                    "包含 \"{0}\"\n" +
                    "界面 面;\n" +
                    "建界面(面, 12, 12, 200, 8);\n" +
                    "整数 号 = 加列表(面, {1}, 22);\n" +
                    "整数 r = 0;\n" +
                    "当 (r < {1})\n" +
                    "{{\n" +
                    "    加列表项(面, 号, r, \"第几行\");\n" +
                    "    r = r + 1;\n" +
                    "}}\n" +
                    "标脏(面);\n" +
                    "输出行(重画(面));\n" +
                    "停止\n";
                int[] 档 = [20, 200, 500];
                var 读数 = new System.Collections.Generic.List<string>();
                bool 成立 = true;
                long 最慢毫秒 = 0;
                foreach (int 行数 in 档)
                {
                    var 表 = System.Diagnostics.Stopwatch.StartNew();
                    string 出 = 跑(string.Format(模板, 界面库, 行数), out string 错);
                    表.Stop();
                    最慢毫秒 = Math.Max(最慢毫秒, 表.ElapsedMilliseconds);
                    if (错.Length > 0) { 成立 = false; 读数.Add($"{行数} 行:抛异常 {错}"); continue; }
                    string[] 行 = 行们(出);
                    string 条 = 行.Length > 0 ? 行[0].Trim() : "(缺)";
                    读数.Add($"{行数} 行 → {条} 条");
                    // 等式:条数 == 行数 + 2(清屏 + 列表底);**线性** —— 控 3 落地那天它会红
                    if (条 != (行数 + 2).ToString()) 成立 = false;
                }
                记录("结构性 ① 重画条数 == 列表行数 + 2(现状就是**线性**;施工图把『不随行数涨』派给控 3 ⇒ 落地那天这条会红)",
                    成立,
                    string.Join(" / ", 读数) + $";等式 `条数 == 行数 + 2` = {成立};最慢一档 {最慢毫秒} 毫秒(只作参考,不进判据)");
            }
            catch (Exception ex) { 记录异常("结构性 ① 重画条数 vs 行数", ex); }

            // ---------- ② 一整块像素 = 一条 `贴位图` ----------
            try
            {
                const string 贴源 =
                    "包含 \"{0}\"\n" +
                    "整数 图 = 位图.建(96, 72);\n" +
                    "位图.填底(图, 4278190080);\n" +
                    "位图.块(图, 4, 4, 40, 30, 4294901760);\n" +
                    "逻辑 开了 = 打开窗口(\"量贴位图\", 120, 100);\n" +
                    "清屏(4278190080);\n" +
                    "位图.贴(图, 12, 12);\n" +
                    "刷新();\n" +
                    "位图.释放(图);\n" +
                    "关闭窗口();\n" +
                    "停止\n";
                var 无头出 = new StringWriter();
                图形宿主C.挂上(null);
                string 跑错;
                string 出;
                try
                {
                    图形宿主C.挂上(new 无头呈现C(无头出));
                    出 = 跑(string.Format(贴源, 位图库), out 跑错);
                }
                finally { 图形宿主C.清空(); 图形宿主C.挂上(null); }
                if (跑错.Length > 0) { 记录("结构性 ② 一整块像素 = 一条 贴位图", false, $"抛异常:{跑错}"); }
                else
                {
                    int 条数 = 0;
                    int 画矩形条数 = 0;
                    string 贴行 = "";
                    foreach (string s in 无头出.ToString().Replace("\r\n", "\n").Split('\n'))
                    {
                        string t = s.Trim();
                        if (t.StartsWith("贴位图", StringComparison.Ordinal)) { 条数++; 贴行 = t; }
                        else if (t.StartsWith("画矩形", StringComparison.Ordinal)) 画矩形条数++;
                    }
                    记录("结构性 ② 一整块像素 = 一条 `贴位图`(96×72 那张图**不是**逐像素 / 逐行画)",
                        条数 == 1 && 画矩形条数 == 0,
                        $"一帧里 `贴位图` {条数} 次({贴行})、`画矩形` {画矩形条数} 条(逐像素退化会给几千条)");
                }
            }
            catch (Exception ex) { 记录异常("结构性 ② 一整块像素 = 一条贴位图", ex); }

            // ---------- ③ 位图不占那 1MB:建一张 ≈1MB 的图并**整张填满** ----------
            try
            {
                //   480 × 520 = 249,600 格 × 4 字节 ≈ 1MB —— 与"运行内存默认 1MB"同量级。
                //   图要是在虚拟机那 1MB 里,这一步(建 + 填满 + 抽样)根本做不成 ⇒ 这是"不占"的**充分**证据。
                const string 大源 =
                    "包含 \"{0}\"\n" +
                    "整数 大 = 位图.建(480, 520);\n" +
                    "输出行(大 > 0);\n" +
                    "位图.填底(大, 4294901760);\n" +
                    "输出行(位图.取像素(大, 479, 519));\n" +       // 右下角
                    "输出行(位图.取像素(大, 240, 260));\n" +       // 正中
                    "输出行(位图.宽(大));\n" +
                    "位图.释放(大);\n" +
                    "停止\n";
                string 出 = 跑(string.Format(大源, 位图库), out string 跑错);
                if (跑错.Length > 0) { 记录("结构性 ③ 位图不占虚拟机那 1MB", false, $"抛异常:{跑错}"); }
                else
                {
                    string[] 行 = 行们(出);
                    string 取(int i) => i < 行.Length ? 行[i].Trim() : "(缺)";
                    记录("结构性 ③ 位图不占虚拟机那 1MB(建一张 ≈1MB 的图并整张填满,抽样读回两格)",
                        取(0) == "1" && 取(1) == "-65536" && 取(2) == "-65536" && 取(3) == "480",
                        $"建成={取(0)} 右下角={取(1)} 正中={取(2)} 宽={取(3)}(480×520×4 字节 ≈ 1MB;" +
                        "图要是在那 1MB 里,建完填满这一步根本做不成 —— 见 `--内存` 那张段表:建图前后一字不动)");
                }
            }
            catch (Exception ex) { 记录异常("结构性 ③ 位图不占那 1MB", ex); }

            // ---------- ④ UI解耦 ----------
            try
            {
                // 界面族这一批就两个库;以后每加一个视图型库都往这张表里挂一行
                string[] 界面族 = ["界面.hb", "位图.hb"];
                // 业务库那一族(契约 §1之3 B 级点名的那几个):界面族**一个都不许 包含**
                string[] 业务库 = ["数据表.hb", "JSON.hb", "网络.hb", "网页.hb", "文件.hb", "目录.hb",
                                   "CSV.hb", "CSV流.hb", "Markdown.hb", "日志.hb", "数据库.hb"];
                // 平台名(第 ① 层那些原语的落点):界面族**一个都不许出现**
                string[] 平台名 = ["Win32", "GTK", "X11", "HWND", "Avalonia", "WPF", "System.Drawing",
                                   "CreateWindowEx", "XCreateImage", "SetDIBitsToDevice"];

                var 缠业务 = new System.Collections.Generic.List<string>();
                var 带平台 = new System.Collections.Generic.List<string>();
                var 缺文件 = new System.Collections.Generic.List<string>();
                foreach (string 名 in 界面族)
                {
                    string 路径 = Path.Combine(库目录, 名);
                    if (!File.Exists(路径)) { 缺文件.Add(名); continue; }
                    string 文本 = File.ReadAllText(路径, Encoding.UTF8);
                    foreach (string 业 in 业务库)
                        if (有真包含行(文本, 业)) 缠业务.Add($"{名} 包含 {业}");
                    foreach (string 台 in 平台名)
                        if (文本.Contains(台, StringComparison.Ordinal)) 带平台.Add($"{名} 出现 {台}");
                    // 契约库那一档:界面族这两个**今天都是零依赖**(一条 包含 都没有)——
                    // ⚠ 判据写成"不许包含业务库"而不是"必须零依赖":以后分了小库(视图契约.hb 那类)也要放行
                }
                记录("结构性 ④a 界面族各库不 `包含` 业务库(按真包含行扫,不扫注释里的用法)",
                    缠业务.Count == 0 && 缺文件.Count == 0,
                    缠业务.Count == 0 && 缺文件.Count == 0
                        ? $"界面族 {界面族.Length} 个库 × 业务库 {业务库.Length} 个:一处都没有" +
                          "(两个库今天连一条 `包含` 都没有 ⇒ 零依赖)"
                        : string.Join(";", 缠业务) + (缺文件.Count > 0 ? ";缺文件:" + string.Join(",", 缺文件) : ""));
                记录("结构性 ④b 界面族各库源码里不出现平台名(第 ① 层那些原语的落点不许长在第 ② 层)",
                    带平台.Count == 0,
                    带平台.Count == 0
                        ? $"{界面族.Length} 个库 × {平台名.Length} 个平台名:一处都没有"
                        : string.Join(";", 带平台));

                // ④c 契约库零依赖:指的是"视图契约"那一档。**今天还没有这个库** ⇒ 这一条量的是
                //     "今天界面族连一条 `包含` 都没有"(零依赖的更强形态);那个库建起来那天,
                //     界面族那一行也要跟着长出 `包含`,那时这一条会红,提醒把它改成"契约库只许零依赖"。
                var 有包含的 = new System.Collections.Generic.List<string>();
                foreach (string 名 in 界面族)
                {
                    string 路径 = Path.Combine(库目录, 名);
                    if (!File.Exists(路径)) continue;
                    if (File.ReadAllText(路径, Encoding.UTF8)
                            .Replace("\r\n", "\n").Split('\n')
                            .Any(x => x.Trim().StartsWith("包含 ", StringComparison.Ordinal)))
                        有包含的.Add(名);
                }
                记录("结构性 ④c 契约库零依赖(今天:界面族连一条 `包含` 都没有 ⇒ 更强的零依赖)",
                    有包含的.Count == 0,
                    有包含的.Count == 0
                        ? $"{界面族.Length} 个库都没有 `包含` 行(`视图契约.hb` 那一档还没建,施工图排在控 3;" +
                          "它建起来那天这一条会红,提醒改成『契约库只许零依赖』)"
                        : $"已经有库开始 `包含` 别的东西了:{string.Join(" / ", 有包含的)} —— 请把这一条改成『契约库只许零依赖』那一档");

                // ④d **接线哨兵**:每个视图型控件都要有一条"接假数据提供者"的行为断言。
                //   ⚠ 这一条不是"做错了",是"还没轮到":今天**还没有**数据提供者契约(控件只认自己的
                //     `加列表项` 那张池子)⇒ **没有东西可接**,一条断言也挂不上;施工图 §1之3 把契约排在
                //     **控 3(虚拟化长列表)**。按 R4-2 的口径,这种"没执行"要如实记**跳过**:记红等于
                //     把"排期没到"说成"缺陷"(红是留给真缺陷的);记 PASS 更不行 —— 那就是假过断言。
                //   ★ **待绿登记**(第429批):名字与详情里写明"等控 3 落地时翻绿",并且**已经登记进**
                //     `自检\综合自检C.cs` 的 `允许跳过的前缀`(跳过数护栏那一族的第三条)。
                //     **控 3 落地、控件真接上数据提供者那天**:把这一条改回 `记录(名, <真判据>)`,
                //     同时把 `结构性 ④d` 那一条前缀从名单里**撤掉**(不撤就等于一直开着后门)。
                跳过("结构性 ④d 每个视图型控件都有一条『接假数据提供者』的断言(施工图 §1之3 B 级)",
                    "**待绿:等控 3「虚拟化长列表」落地时翻绿** —— 今天没有数据提供者契约可接" +
                    "(控件靠 `加列表项` 自己那份池子)⇒『接假数据提供者』的断言一条都挂不上;" +
                    "控件接上契约那天把这一条改回 `记录(…, 真判据)`,并从 `允许跳过的前缀` 里撤掉 `结构性 ④d`");

                // ⑤ 人的观感那一档**只写进批次记录,不占断言位**(硬规矩 6 不许自检开窗;
                //    而"跳过"要过 `跳过数护栏` 那张名单 —— 这一档**不为它**再往名单里加一条:
                //    观感本来就是人看的,不该占一条机器断言位)。
                //    —— 机器判据全绿 ≠ 画面能看。归人工那一份的跑法(写在 `任务清单.md` 那一批里):
                //       `hbcc -p Sample\中间层\示例62_位图 --run`(或 IDE 里执行)看那一屏:
                //       96×72 的图贴在 (12,12) —— 蓝框 + 红块 + 绿对角线 + 白点 + 右下角洋红块 + 两行说明字。
            }
            catch (Exception ex) { 记录异常("结构性 ④ UI解耦", ex); }
        }
    }
}
