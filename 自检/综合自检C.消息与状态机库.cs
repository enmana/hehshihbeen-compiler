// ============================================================
// 消息 / 状态机两库的自检(G4 批 22)
//   —— `Sample\库\消息.hb`(发布 / 订阅,库**真的替你调处理函数**)·
//      `Sample\库\状态机.hb`(显式状态转移表)
//
//   判据照 `基础库施工计划.md` §2 批 22 那一行:**订阅 / 发布 / 退订** + **状态转移表**;
//   不做拍板点(那一行写着"不要")。这一组十块(行为断言为主 + 一条接线哨兵;硬规矩 5 / T22):
//     ① **订阅簿**:订阅给号(0 起)、满了给 -1、`条数` / `有订阅` / `主题(号)` 对得上;
//     ② **发布真的调到**:`发布全部` 把那个主题上**每一条**都调一遍(处理函数收到的号与值都对)、
//        返回"调了几条";`发布` / `发布一个` 只调第 N 条;
//     ③ **退订之后不再调**:`退订(主题)` 撤全部、`退订一个(号)` 撤一条,撤完再发不调;
//     ④ **不报错、不停机**:没订阅过的主题 / 越界的号 / 空订阅簿,一律给确定值;
//     ⑤ **H86 那道坑的判据**:本库的**回调形参名每个函数各不相同**(`订阅_处理` / `存_处理`),
//        所以两个函数各自的形参表不会串味 —— 这条由"两种签名各自被调对"直接量到;
//     ⑥ **状态机 表**:`建` / `设转移` / `有转移` / `目标` / `清转移` 与越界;
//     ⑦ **状态机 喂**:合法转移调处理函数(实参是**旧状态、新状态**)并改当前状态;
//        没设过的格子**原地不动**(不报错);
//     ⑧ **两者接一起**:转移的一刻发消息,订阅方收到(端到端的"事件驱动骨架");
//     ⑨ **端到端**:标准工程 `示例57_消息与状态机` 真编真跑,与它那行 `// 预期输出:` 逐行对;
//     ⑩ **接线哨兵**:两个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数(12 / 11)。
//
//   ⚠ 与 `事件.hb`(批 20)的分界:**那一版库不收 `回调` 形参**(H86 的账),本批这一版收 ——
//     靠的是"每个函数的回调形参各起一个不同的名字",所以第 ⑤ 块是这一组最要紧的判据之一。
// ============================================================

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    public static partial class 综合自检C
    {
        private static void 消息与状态机库自检()
        {
            string? 示例 = 找示例目录();
            string? 仓库根 = 示例 == null ? null : Directory.GetParent(示例)?.FullName;
            string 库目录 = 仓库根 == null ? "" : Path.Combine(仓库根, "Sample", "库");
            string 消息路径 = Path.Combine(库目录, "消息.hb").Replace('\\', '/');
            string 状态机路径 = Path.Combine(库目录, "状态机.hb").Replace('\\', '/');
            if (!File.Exists(消息路径) || !File.Exists(状态机路径))
            {
                跳过("消息与状态机库 定位两个库文件", $"找不到 {消息路径} / {状态机路径}(不在工作副本里跑就跳过)");
                return;
            }
            string 头 = $"包含 \"{消息路径}\"\n包含 \"{状态机路径}\"\n";

            // 跑一段 HB:输出按行收(末尾空白去掉),行尾换 `|`(与位与数学库 / 日志与事件库那两组同一套)
            string 跑(string 源)
            {
                var 编译结果 = new 汇编器C().汇编多文件带调试(
                    [("主程序.hb", 头 + 源)], true,
                    中间层C.默认堆大小, null, 中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译结果);
                解码.收尾();
                string 报错 = 编译结果.查运行期报错(vm.内存) is { } 说明 ? $"⚠{说明}" : "";
                return string.Join("|", 缓冲.ToString().Replace("\r\n", "\n").Split('\n')
                    .Select(x => x.TrimEnd()).Where(x => x.Length > 0)) + 报错;
            }

            void 检查(string 名称, Func<(bool 通过, string 详情)> 试)
            {
                try
                {
                    var (通过, 详情) = 试();
                    记录(名称, 通过, 详情);
                }
                catch (Exception ex) { 记录异常(名称, ex); }
            }

            static string 说明(string 期望, string 实得)
                => 期望 == 实得 ? "一字不差" : $"期望 [{期望}] / 实得 [{实得}]";

            // ---- ① 订阅簿:号 / 条数 / 有订阅 / 主题 ----
            检查("消息 订阅簿:订阅给号(0 起)、条数 / 有订阅 / 主题(号) 都对得上", () =>
            {
                string 实得 = 跑("""
                    方法 左处理(整数 号, 整数 值) { 返回 }
                    方法 右处理(整数 号, 整数 值) { 返回 }
                    输出行(消息.上限());
                    输出行(消息.条数());
                    消息.清掉();
                    输出行(消息.订阅("运行", 地址(左处理)));
                    输出行(消息.订阅("运行", 地址(右处理)));
                    输出行(消息.订阅("停止", 地址(右处理)));
                    输出行(消息.条数());
                    输出行(消息.有订阅("运行"));
                    输出行(消息.有订阅("没有这个"));
                    输出行(消息.主题(0));
                    输出行(消息.主题(2));
                    输出行(消息.主题(9));
                    输出行(消息.主题(0 - 1));
                    停止
                    """);
                return (实得 == "16|0|0|1|2|3|1|0|运行|停止", 说明("16|0|0|1|2|3|1|0|运行|停止", 实得));
            });

            // ---- ② 发布真的调到 + ③ 退订之后不再调 ----
            检查("消息 发布真的调到处理函数(号与值都对),`退订` / `退订一个` 之后不再调", () =>
            {
                string 实得 = 跑("""
                    方法 左处理(整数 号, 整数 值)
                    {
                        输出行("左处理 号");
                        输出行(号);
                        输出行("左处理 值");
                        输出行(值);
                        返回
                    }
                    方法 右处理(整数 号, 整数 值)
                    {
                        输出行("右处理 号");
                        输出行(号);
                        输出行("右处理 值");
                        输出行(值);
                        返回
                    }
                    消息.清掉();
                    消息.订阅("运行", 地址(左处理));
                    消息.订阅("运行", 地址(右处理));
                    消息.订阅("停止", 地址(右处理));
                    输出行("发布全部 运行 7");
                    输出行(消息.发布全部("运行", 7));
                    输出行("发布 运行 11");
                    输出行(消息.发布("运行", 11));
                    输出行("发布一个 运行 第1条 13");
                    输出行(消息.发布一个("运行", 1, 13));
                    输出行("发布 没有 5");
                    输出行(消息.发布("没有", 5));
                    输出行("退订 运行");
                    输出行(消息.退订("运行"));
                    输出行("条数");
                    输出行(消息.条数());
                    输出行("发布全部 运行 21");
                    输出行(消息.发布全部("运行", 21));
                    输出行("退订一个 2");
                    输出行(消息.退订一个(2));
                    输出行("条数");
                    输出行(消息.条数());
                    输出行("退订一个 2 再来");
                    输出行(消息.退订一个(2));
                    停止
                    """);
                string 期望 = string.Join("|", new[]
                {
                    "发布全部 运行 7",
                    "左处理 号", "0", "左处理 值", "7", "右处理 号", "1", "右处理 值", "7", "2",
                    "发布 运行 11", "左处理 号", "0", "左处理 值", "11", "1",
                    "发布一个 运行 第1条 13", "右处理 号", "1", "右处理 值", "13", "1",
                    "发布 没有 5", "0",
                    "退订 运行", "2",
                    "条数", "1",
                    "发布全部 运行 21", "0",
                    "退订一个 2", "1",
                    "条数", "0",
                    "退订一个 2 再来", "0",
                });
                return (实得 == 期望, 说明(期望, 实得));
            });

            // ---- ④ 满了给 -1(16 格);不覆盖别人的订阅 ----
            检查("消息 订阅簿满了(16 格)再订阅给 -1,而且**不覆盖**已有订阅", () =>
            {
                string 实得 = 跑("""
                    方法 左处理(整数 号, 整数 值) { 返回 }
                    消息.清掉();
                    整数 i = 0;
                    当 (i < 16)
                    {
                        消息.订阅("主题", 地址(左处理));
                        i = i + 1;
                    }
                    输出行(消息.条数());
                    输出行(消息.订阅("主题", 地址(左处理)));
                    输出行(消息.条数());
                    输出行(消息.退订一个(3));
                    输出行(消息.条数());
                    输出行(消息.订阅("别的", 地址(左处理)));
                    输出行(消息.有订阅("别的"));
                    停止
                    """);
                return (实得 == "16|-1|16|1|15|3|1", 说明("16|-1|16|1|15|3|1", 实得));
            });

            // ---- ⑤ H86 那道坑:`订阅` 与内部存槽各自一个形参名 ⇒ 两种签名各自被调对 ----
            检查("消息 两处回调形参各用不同的名字(绕开 H86:形参表按参数名跨函数登记)", () =>
            {
                string 实得 = 跑("""
                    方法 两个参数(整数 号, 整数 值)
                    {
                        输出行(号 * 100 + 值);
                        返回
                    }
                    消息.清掉();
                    消息.订阅("左", 地址(两个参数));
                    消息.发布全部("左", 7);
                    消息.发布全部("左", 9);
                    停止
                    """);
                // 号 = 0 ⇒ 0*100+7 = 7、0*100+9 = 9;要是形参串味(第一个参数变 0 或丢),
                // 这两个数就不是 7 / 9 —— 这一条量的就是"库里那两个回调形参名不撞"。
                return (实得 == "7|9", 说明("7|9", 实得));
            });

            // ---- ⑥ 状态机:建 / 设转移 / 有转移 / 目标 / 清转移 / 越界 ----
            检查("状态机 建 / 设转移 / 有转移 / 目标 / 清转移(含越界一律给确定值)", () =>
            {
                string 实得 = 跑("""
                    方法 跑一下(整数 旧, 整数 新) { 返回 }
                    输出行(状态机.状态上限());
                    输出行(状态机.事件上限());
                    输出行(状态机.建(3, 2));
                    输出行(状态机.建(0, 2));
                    输出行(状态机.建(5, 2));
                    输出行(状态机.设转移(0, 0, 1, 地址(跑一下)));
                    输出行(状态机.设转移(1, 1, 2, 地址(跑一下)));
                    输出行(状态机.设转移(0, 9, 1, 地址(跑一下)));
                    输出行(状态机.设转移(4, 0, 1, 地址(跑一下)));
                    输出行(状态机.有转移(0, 0));
                    输出行(状态机.有转移(0, 1));
                    输出行(状态机.有转移(9, 9));
                    输出行(状态机.目标(0, 0));
                    输出行(状态机.目标(0, 1));
                    输出行(状态机.目标(9, 9));
                    输出行(状态机.清转移(1, 1));
                    输出行(状态机.有转移(1, 1));
                    输出行(状态机.清转移(9, 9));
                    输出行(状态机.当前());
                    停止
                    """);
                return (实得 == "4|4|1|0|0|1|1|0|0|1|0|0|1|0|9|1|0|0|0", 说明("4|4|1|0|0|1|1|0|0|1|0|0|1|0|9|1|0|0|0", 实得));
            });

            // ---- ⑦ 状态机 喂:合法转移调处理(实参是旧、新)并改状态;没设过的格子原地不动 ----
            检查("状态机 喂:合法转移调处理函数(实参 = 旧状态、新状态)并改当前;没设过的格子原地不动", () =>
            {
                string 实得 = 跑("""
                    方法 走(整数 旧, 整数 新)
                    {
                        输出行("走 旧");
                        输出行(旧);
                        输出行("走 新");
                        输出行(新);
                        返回
                    }
                    状态机.清掉();
                    状态机.建(3, 2);
                    状态机.设转移(0, 0, 1, 地址(走));
                    状态机.设转移(1, 1, 2, 地址(走));
                    状态机.设初始(0);
                    输出行("喂 0");
                    输出行(状态机.喂(0));
                    输出行("喂 0 再来");
                    输出行(状态机.喂(0));
                    输出行("喂 1");
                    输出行(状态机.喂(1));
                    输出行("喂 1 再来");
                    输出行(状态机.喂(1));
                    输出行("喂 9 越界");
                    输出行(状态机.喂(9));
                    输出行("设初始 9 越界");
                    输出行(状态机.设初始(9));
                    输出行("当前");
                    输出行(状态机.当前());
                    停止
                    """);
                string 期望 = string.Join("|", new[]
                {
                    "喂 0", "走 旧", "0", "走 新", "1", "1",
                    "喂 0 再来", "1",
                    "喂 1", "走 旧", "1", "走 新", "2", "2",
                    "喂 1 再来", "2",
                    "喂 9 越界", "2",
                    "设初始 9 越界", "0",
                    "当前", "2",
                });
                return (实得 == 期望, 说明(期望, 实得));
            });

            // ---- ⑧ 两者接一起:转移的一刻发消息 ----
            检查("消息 + 状态机接在一起:转移的一刻发消息,订阅方收到(号与值都对)", () =>
            {
                string 实得 = 跑("""
                    方法 收下(整数 号, 整数 值)
                    {
                        输出行("收到 号");
                        输出行(号);
                        输出行("收到 值");
                        输出行(值);
                        返回
                    }
                    方法 转移时(整数 旧, 整数 新)
                    {
                        输出行("转移");
                        输出行(旧);
                        输出行(新);
                        输出行("发布条数");
                        输出行(消息.发布全部("动", 新));
                        返回
                    }
                    消息.清掉();
                    状态机.清掉();
                    消息.订阅("动", 地址(收下));
                    状态机.建(2, 1);
                    状态机.设转移(0, 0, 1, 地址(转移时));
                    状态机.设初始(0);
                    输出行("喂");
                    输出行(状态机.喂(0));
                    输出行("当前");
                    输出行(状态机.当前());
                    停止
                    """);
                string 期望 = string.Join("|", new[]
                {
                    "喂", "转移", "0", "1", "发布条数",
                    "收到 号", "0", "收到 值", "1", "1",
                    "1",
                    "当前", "1",
                });
                return (实得 == 期望, 说明(期望, 实得));
            });

            // ---- ⑨ 端到端:标准工程 `示例57_消息与状态机` ----
            try
            {
                string? 示例目录 = 找示例目录();
                // 标准工程住在 `Sample\中间层\<工程名>\`(与 示例53 / 示例54 同一层)
                string? 工程 = 示例目录 == null ? null : Path.Combine(示例目录, "中间层", "示例57_消息与状态机", "主程序.hb");
                if (工程 == null || !File.Exists(工程))
                    跳过("消息与状态机库 端到端:标准工程 `示例57_消息与状态机` 与它那行 `// 预期输出:` 逐段对",
                        $"找不到 {工程}(不在工作副本里跑就跳过)");
                else
                {
                    // 与 `hbcc -p 工程.hbp --run` 同一条口径:按**磁盘上那份工程**真编真跑
                    // (`运行带输出(源码, 基目录)` —— 基目录要给,不然 `包含 "../../库/…"` 解析不了)
                    // ⚠ 比法是**逐段比字符串**(空段也算一段:示例里那两处空行是输出的一部分),
                    //    不是"去掉空行再比" —— 与 `示例与调试` 那一组同一把尺子。
                    string 工程目录 = Path.GetDirectoryName(工程)!;
                    var 期望 = 解析预期输出(File.ReadAllLines(工程, Encoding.UTF8));
                    var (_, 输出) = 运行带输出(File.ReadAllText(工程, Encoding.UTF8), 工程目录);
                    string 实得串 = 输出.Replace("\r\n", "\n").TrimEnd('\n').Replace("\n", "|");
                    string 期望串 = string.Join("|", 期望);
                    bool 好 = 期望.Count > 0 && 实得串 == 期望串;
                    记录("消息与状态机库 端到端:标准工程 `示例57_消息与状态机` 与它那行 `// 预期输出:` 逐段对",
                        好, 好 ? $"逐段一致({期望.Count} 段)"
                              : $"期望 {期望.Count} 段 / 实得 {实得串.Split('|').Length} 段;{说明(期望串, 实得串)}");
                }
            }
            catch (Exception ex) { 记录异常("消息与状态机库 端到端:标准工程 `示例57_消息与状态机` 与它那行 `// 预期输出:` 逐段对", ex); }

            // ---- ⑩ 接线哨兵:两个库都在盘上 + 头注释五段齐 + 模块名 + 公开函数数 ----
            const string 接线断言 = "消息与状态机库 接线:两个库文件 + 模块名 + 公开函数数(11 / 11)";
            try
            {
                string 消息源 = File.ReadAllText(消息路径, Encoding.UTF8);
                string 状态机源 = File.ReadAllText(状态机路径, Encoding.UTF8);
                int 消息公开 = 消息源.Split('\n').Count(x => x.StartsWith("方法 ", StringComparison.Ordinal) && !x.StartsWith("方法 消息_", StringComparison.Ordinal));
                int 状态机公开 = 状态机源.Split('\n').Count(x => x.StartsWith("方法 ", StringComparison.Ordinal) && !x.StartsWith("方法 状态机_", StringComparison.Ordinal));
                bool 判据 = 消息源.StartsWith("// ============================================================", StringComparison.Ordinal)
                    && 消息源.Contains("模块 消息", StringComparison.Ordinal)
                    && 状态机源.Contains("模块 状态机", StringComparison.Ordinal)
                    && 消息公开 == 11 && 状态机公开 == 11;
                记接线(接线断言, 判据,
                    $"消息 模块名 = {消息源.Contains("模块 消息", StringComparison.Ordinal)} / 公开方法 {消息公开}(该 11);" +
                    $"状态机 模块名 = {状态机源.Contains("模块 状态机", StringComparison.Ordinal)} / 公开方法 {状态机公开}(该 11)" +
                    " —— 接线哨兵(读库源码文本判的),行为面看上面那九条");
            }
            catch (Exception ex) { 记录异常(接线断言, ex); }
        }
    }
