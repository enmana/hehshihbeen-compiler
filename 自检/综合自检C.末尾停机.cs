using hehshihbeen_compiler;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// R6-6(2026-09-22 登记 / 本批收口):主程序末尾**不写 `停止`** 时,程序会**掉进编译器自己的例程**。
    ///
    /// 症状:程序正常跑完、输出也对,紧接着报一条运行期错误 ——
    /// 有函数时报「栈为空(压栈/弹栈没配对 —— 检查是不是多写了一次 弹出、少写了一次 压栈)」,
    /// **行号指向函数体里的 `返回`**(与真实病因无关);只用 `申请` 时连行号都没有。
    ///
    /// 根因(`中间层C.主流程.cs`):函数体(`_函数正文`)与内部例程(`_列表例程`:堆分配 / 列表扩容 / 打印串)
    /// 统一追加在**主程序之后**,而主程序末尾没有停机指令;平常靠"跑过代码段末尾、落进零初始化数据段的
    /// 第一个字(0x00000000 = HALT)"兜底 —— 这条兜底一旦被追加的例程挡在中间就失效,
    /// 主程序径直往下掉进例程里接着跑,撞上 `返回` 时硬件栈当然是空的。
    ///
    /// 这个分组钉五件事:
    /// ① **两条最小复现都跑得完**:末尾不带 `停止` 的**函数**工程 / **`申请`** 工程不再报运行期错误,输出也对;
    /// ② **补的是一条 `停止` 且带"编译器生成"标记**:它不算某条源码语句的行号(单步不会停在它上面),
    ///    也不撞前端那条"`停止` 之后的死代码"警告;
    /// ③ **位置对**:补出来的 `停止` 在**主程序末尾**——排在追加的函数体 / 内部例程**之前**
    ///    (所以它先停机,不会掉进那些例程);
    /// ④ **用户自己写了 `停止` 就不补**:两条路编出来的机器码**逐字节相同**(不白发一条用不上的指令);
    ///   · **T9(2026-09-27 评测整改)把前提去掉了**:有没有追加代码**都补** —— 纯主程序一样会掉进代码段后面
    ///     那块内存(`整数 数 = 0 - 1; 输出行(数);` 打完 -1 报「未知操作码: 0xFF」),那条"数据段零初始化
    ///     就是 HALT"的兜底靠的是"那块内存恰好是 0",代码/数据段长度一变就不成立。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary> 最小复现①:带函数、主程序末尾不写 `停止`(病根:函数体追加在主程序之后) </summary>
        private const string 末尾无停机函数源 =
            "方法 加(整数 x) 返回 整数\n" +
            "{\n" +
            "    返回 x + 1;\n" +
            "}\n" +
            "整数 总 = 加(41);\n" +
            "输出行(总);\n";

        /// <summary> 最小复现②:只用 `申请`、主程序末尾不写 `停止`(病根:堆分配子程序追加在主程序之后) </summary>
        private const string 末尾无停机申请源 =
            "地址 p = 申请(8);\n" +
            "输出行(1);\n";

        private static void 末尾停机自检()
        {
            // ① 两条最小复现:以前这里抛运行期错误(`跑输出断言` 会记成一条 FAIL,详情就是那条报错原文)
            跑输出断言("R6-6 末尾不写 `停止` 的函数工程跑完(不再掉进函数体报「栈为空」)",
                末尾无停机函数源, "42");
            跑输出断言("R6-6 末尾不写 `停止` 的 `申请` 工程跑完(不再掉进堆分配例程)",
                末尾无停机申请源, "1");

            // ② ③ 补的那条 `停止`:带"编译器生成"标记、位置在主程序末尾(排在函数体的 `返回` 之前)
            try
            {
                string[] 行 = 展开文本(末尾无停机函数源).Split('\n');
                int 停机行 = Array.FindIndex(行, x => x.Trim() == "停止");
                int 返回行 = Array.FindIndex(行, x => x.Trim() == "返回");
                bool 带生成标记 = 停机行 > 0 && 行[停机行 - 1].Trim() == 源行标记C.生成标记;
                bool 位置对 = 停机行 > 0 && 返回行 > 停机行;
                记录("R6-6 补出来的 `停止` 带「编译器生成」标记,且排在追加的函数体之前(先停机,掉不进去)",
                    带生成标记 && 位置对,
                    $"停机行={停机行} 标记行={停机行 - 1} 函数体 `返回` 行={返回行}");
            }
            catch (Exception ex) { 记录异常("R6-6 补出来的 `停止` 带「编译器生成」标记,且排在追加的函数体之前(先停机,掉不进去)", ex); }

            // ④ 用户自己写了 `停止` → 不再补:两条路编出来的机器码逐字节相同
            try
            {
                byte[] 没写 = 汇编(末尾无停机函数源);
                byte[] 写了 = 汇编(末尾无停机函数源 + "停止\n");
                记录("R6-6 用户自己写了 `停止` 就不再补一条(两条路机器码逐字节相同)",
                    没写.SequenceEqual(写了),
                    $"没写 {没写.Length} 字节 / 写了 {写了.Length} 字节" + (没写.SequenceEqual(写了) ? "" : " —— 多补了一条"));
            }
            catch (Exception ex) { 记录异常("R6-6 用户自己写了 `停止` 就不再补一条(两条路机器码逐字节相同)", ex); }

            // ⑤ T9(2026-09-27 评测整改):**没有追加代码的纯语句工程照样补** —— 老口径(R6-6)是"没有追加例程就不补,
            //    靠跑过代码段末尾落进零初始化数据段兜底",可实测纯主程序一样会翻:
            //    `整数 数 = 0 - 1; 输出行(数);` 打完 -1 就报「内部错误(请回报):未知操作码: 0xFF」——
    //    那条兜底靠的是"那块内存恰好是 0",代码/数据段长度一变就不成立。现在一律补,
    //    所以"明写一条 `停止`"与"不写"编出来的机器码**逐字节相同**。
            try
            {
                byte[] 纯语句 = 汇编("输出行(1);\n");
                byte[] 明写停机 = 汇编("输出行(1);\n停止\n");
                记录("T9 没有追加例程的纯语句工程也补 `停止`(与明写一条的机器码逐字节相同)",
                    纯语句.SequenceEqual(明写停机),
                    $"纯语句 {纯语句.Length} 字节 / 明写停机 {明写停机.Length} 字节");
            }
            catch (Exception ex) { 记录异常("T9 没有追加例程的纯语句工程也补 `停止`(与明写一条的机器码逐字节相同)", ex); }
        }
    }
}
