            //   ⚠ 这一条是 2026-10-11(第415批)补的钉子。以前 C# 侧借 `ObjLoader` 那份
            //     "网格加载器"的结果 —— 它按 `v/vt/vn` 组合**去重**、只留"被面引用过的角点" ⇒
            //     实测 `脸.obj` 给 **259**(文件里 **1009**)、`全身.obj` **524**(**527**)、
            //     `full.obj` **419**(**424**),而 C 侧给的就是文件里的行数 ⇒
