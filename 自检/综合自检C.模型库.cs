                        源.Append("测试输出(整数(取字(条数区, 0)));\n");
                        源.Append("测试输出(整数(取字(条数区, 8)));\n");
                    }
                    源.Append("停止\n");
                    string 输出 = 读OBJ模型跑一段(源.ToString(), out string 跑错);
                    if (跑错.Length > 0) 记录(本检查, false, $"抛异常:{跑错}");
                    else
                    {
                        string[] 行 = 输出.Replace("\r\n", "\n").Trim().Split('\n');
                        string 值(int i) => i < 行.Length ? 行[i].Trim() : "?";
                        var 差 = new List<string>();
                        var 读数 = new List<string>();
                        for (int i = 0; i < 在盘上的.Length; i++)
                        {
                            var (应顶点, _, 应面) = 模型库数OBJ(在盘上的[i].路径);
                            string 成 = 值(i * 3), 顶点 = 值(i * 3 + 1), 面 = 值(i * 3 + 2);
                            读数.Add($"{在盘上的[i].名} {顶点}/{面}");
                            if (成 != "1" || 顶点 != 应顶点.ToString() || 面 != 应面.ToString())
                                差.Add($"{在盘上的[i].名}:读回 {成}/{顶点}/{面},文件里是 1/{应顶点}/{应面}");
                        }
                        记录(本检查, 差.Count == 0, 差.Count == 0
                            ? $"8 份逐份对上(顶点/面):{string.Join(" · ", 读数)}"
                            : string.Join(";", 差));
                    }
                }
            }

            // ================= ⑤ 接线哨兵:网格那道闸 / 四档表还在源码里 =================
            {
                string 文 = File.ReadAllText(库文件);
                记录("模型库 接线:网格装不下那道闸 + 四档表还在源码里",
                    文.Contains("模型_入顶点数 > 三维网格.顶点上限()") && 文.Contains("模型_入面数 > 12000")
                    && 文.Contains("返回 300;") && 文.Contains("返回 550;") && 文.Contains("返回 1300;") && 文.Contains("返回 2600;")
                    && 文.Contains("读取模型(路径, 模型_顶点区, 模型_边区, 模型_面区, 550, 1700, 1350, 模型_条数区)")
                    && 文.Contains("模型还缓冲();\n    如果 (探查(路径) == 假)"),
                    "判据:① 网格那道闸两条;② 四档的四个顶点数;③ 二档那一句的四个字面量与宿主同口径;" +
                    "④ `装` 是**先还缓冲、再探查**(不还就换不动档 —— 实测踩过)");
            }
