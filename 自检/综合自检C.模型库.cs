//
//   为什么要单开一组:这一库治的三件事**全是静默的**,错了只会"看着像读成了" ——
//     ① **只读探查**(三个上限给 1 ⇒ 宿主先判容量、后写块 ⇒ 一个字节都不写):
//        钉两条:报回来的是**真实规模**;三个桩块**确实没被动过**;
//     ② **按规模挑档 / 换档**:同一份程序里连装几种大小不同的模型,每一趟都要挑对那一档
//        (`顶点上限()` 就是"它现在在哪一档"的指纹);
//     ③ **装不下要说清楚**:真实规模 + "大档能收多少"要一起给出来,而且**不许**因为
//        为了报它去申请大缓冲、先在 `申请` 上失败(实测踩过:真话被"堆里放不下"顶掉)。
//
//   夹具:**现造** `.obj`(在系统临时目录里写网格平面)—— 不依赖仓库里的大模型
//   (网盘素材、不进库也会变),而且顶点/边/面都能手算:
//     平面 N×N 顶点、每个格子两个三角 ⇒ 顶点 = N²,面 = 2(N−1)²。
// ============================================================
