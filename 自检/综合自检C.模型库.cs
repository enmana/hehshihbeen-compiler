        /// <summary>把一块 N×N 的网格平面写成 `.obj`(顶点带一点起伏,免得共线退化)。</summary>
        private static string 模型库造平面(string 目录, string 名, int N)
        {
            var 文 = new StringBuilder();
            文.Append("# 自检夹具:").Append(N).Append('x').Append(N).Append(" 网格平面\n");
            for (int j = 0; j < N; j++)
            {
                for (int i = 0; i < N; i++)
                {
                    double x = (i / (double)(N - 1) - 0.5) * 2.0;
                    double y = (j / (double)(N - 1) - 0.5) * 2.0;
                    double z = Math.Sin(i * 0.2) * Math.Cos(j * 0.2) * 0.15;
                    文.Append("v ").Append(x.ToString("F4", System.Globalization.CultureInfo.InvariantCulture))
                       .Append(' ').Append(y.ToString("F4", System.Globalization.CultureInfo.InvariantCulture))
                       .Append(' ').Append(z.ToString("F4", System.Globalization.CultureInfo.InvariantCulture)).Append('\n');
                }
            }
            for (int j = 0; j < N - 1; j++)
            {
                for (int i = 0; i < N - 1; i++)
                {
                    int a = j * N + i + 1, b = a + 1, c = a + N, d = c + 1;
                    文.Append("f ").Append(a).Append(' ').Append(b).Append(' ').Append(d).Append('\n');
                    文.Append("f ").Append(a).Append(' ').Append(d).Append(' ').Append(c).Append('\n');
                }
            }
            string 路径 = Path.Combine(目录, 名 + ".obj");
            File.WriteAllText(路径, 文.ToString(), new UTF8Encoding(false));
            return 路径.Replace("\\", "/");
        }

        /// <summary>
        /// 现数一份 `.obj` 的**顶点数 / 边数 / 三角面数**(与 `读取模型` 同一套认法:只看行首的 `v` 与 `f`,
        /// 顶点必须三个数齐;面里的下标 1 起数、负数从**已读到的顶点数**倒数、越界丢;
        /// 边 = **多边形**的边去重;面按扇形三角化,几个角算几个减二)。
        /// 用它算期望值 —— **不许把手抄的数字当判据**(素材换一份,判据要跟着走)。
        /// </summary>
        private static (int 顶点, int 边, int 三角面) 模型库数OBJ(string 路径)
        {
            int 顶点 = 0, 三角面 = 0;
            var 边 = new HashSet<(int, int)>();
            foreach (string 原行 in File.ReadAllText(路径).Replace("\r\n", "\n").Split('\n'))
            {
                string 行 = 原行.Trim();
                if (行.Length == 0 || 行[0] == '#') continue;
                if (行[0] == 'v' && 行.Length > 1 && (行[1] == ' ' || 行[1] == '\t'))
                {
                    var 格 = 行[1..].Split([' ', '\t', '\r', ','], StringSplitOptions.RemoveEmptyEntries);
                    if (格.Length >= 3) 顶点++;
                }
                else if (行[0] == 'f' && 行.Length > 1 && (行[1] == ' ' || 行[1] == '\t'))
                {
                    var 号 = new List<int>();
                    foreach (string 词 in 行[1..].Split([' ', '\t', '\r'], StringSplitOptions.RemoveEmptyEntries))
                    {
                        string 首 = 词.Split('/')[0];
                        if (首.Length == 0) continue;
                        if (!int.TryParse(首, System.Globalization.NumberStyles.Integer,
                                          System.Globalization.CultureInfo.InvariantCulture, out int 原号)) continue;
                        if (原号 == 0) continue;
                        int 号1 = 原号 > 0 ? 原号 - 1 : 顶点 + 原号;
                        if (号1 < 0 || 号1 >= 顶点) continue;
                        号.Add(号1);
                    }
                    if (号.Count < 3) continue;
                    for (int k = 0; k < 号.Count; k++)          // 边 = 多边形的边(不是三角化之后的)
                    {
                        int 左端 = 号[k], 右端 = 号[(k + 1) % 号.Count];
                        if (左端 == 右端) continue;
                        边.Add(左端 < 右端 ? (左端, 右端) : (右端, 左端));
                    }
                    三角面 += 号.Count - 2;
                }
            }
            return (顶点, 边.Count, 三角面);
        }

