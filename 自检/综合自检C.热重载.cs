    {
        private static void 热重载自检()
        {
            // 两版只差"循环体怎么算":声明顺序与类型宽度一个字没动 ⇒ 顶层变量槽的位置对得上
            // (语言里"常量"就是"顶层声明 + 初值是字面量"那种变量,没有单独的写法 —— 见 `源码名字扫描C.常量名`)
            const string 旧源 =
                "整数 基数 = 7;\n整数 计数 = 0;\n整数 累计 = 0;\n" +
                "当 (计数 < 10)\n{\n计数 = 计数 + 1;\n累计 = 累计 + 1;\n}\n" +
                "测试输出(基数 * 基数);\n测试输出(计数);\n测试输出(累计);\n停止\n";
            const string 新源 =
                "整数 基数 = 7;\n整数 计数 = 0;\n整数 累计 = 0;\n" +
                "当 (计数 < 10)\n{\n计数 = 计数 + 1;\n累计 = 累计 + 2;\n}\n" +
                "测试输出(基数 * 基数);\n测试输出(计数);\n测试输出(累计);\n停止\n";

            var 旧编 = 编译(旧源);
            var 新编 = 编译(新源);

            // ---- ① 保住顶层变量的值(装载 → 跑 → 重载 → 再跑,两轮的计数器接着数) ----
            try
            {
                var 机 = new 虚拟机C { 输出目标 = _ => { } };
                var 输出一 = new List<byte>();
                机.输出目标 = b => 输出一.Add(b);
                装载并备好(机, 旧编);
                机.运行(旧编);
                int 计数槽 = 槽址(旧编, "计数"), 累计槽 = 槽址(旧编, "累计");
                uint 旧计数 = 读字(机.内存, 计数槽), 旧累计 = 读字(机.内存, 累计槽);

                重载到(机, 新编, 旧编);

                uint 新计数 = 读字(机.内存, 计数槽), 新累计 = 读字(机.内存, 累计槽);
                var 输出二 = new List<byte>();
                机.输出目标 = b => 输出二.Add(b);
                机.运行(新编);
                string 一遍 = 文本(输出一), 二遍 = 文本(输出二);
                string 宽度痕 = string.Join(",", 旧编.名字表.变量.Select(x => $"{x.槽}:{x.宽度}:{x.是全局}"));
                // 第二遍:重载把初值表也换成新的那一份(与"编译后重新装载"同一套口径),所以两个计数器
                // 先回 0、再按**改过的**循环体跑 10 轮 ⇒ 累计 20 —— 钉的是"新机器码真的生效了"。
                // 而**重载那一刻**这两个格必须还是上一轮的 10:那才是"运行期数据保住了"的证据。
                bool 过 = 一遍 == "49\n10\n10" && 二遍 == "49\n10\n20"
                    && 旧计数 == 10 && 旧累计 == 10 && 新计数 == 10 && 新累计 == 10;
                记录("H13 热重载 保住顶层变量的值(改过的循环体没跑,计数与累计还是上一轮的 10)",
                    过,
                    $"第一遍 <{一遍.Replace("\n", "|")}>;装载后 计数={旧计数} 累计={旧累计};" +
                    $"重载后 计数={新计数} 累计={新累计};第二遍 <{二遍.Replace("\n", "|")}>;" +
                    $"机器码 {旧编.机器码.Length} → {新编.机器码.Length} 字节(布局真变过);" +
                    $"说明=<{string.Join(" || ", 机.上次重载诊断)}>;旧名字表=[{宽度痕}]");
            }
            catch (Exception ex) { 记录异常("H13 热重载 保住顶层变量的值", ex); }

            // ---- ② 重载后从程序开头重跑:PC = 0、寄存器全 0、停机清掉 ----
            try
            {
                var 机 = new 虚拟机C { 输出目标 = _ => { } };
                装载并备好(机, 旧编);
                机.运行(旧编);
                bool 跑完过 = 机.停机;
                重载到(机, 新编, 旧编);
                bool 寄存器全零 = 机.寄存器.All(x => x == 0);
                bool 过 = 跑完过 && 机.程序计数器 == 0 && !机.停机 && 寄存器全零;
                记录("H13 热重载 重载后从程序开头重跑(PC = 0 / 寄存器全 0 / 停机清掉 —— 旧布局的寄存器不许硬搬)",
                    过,
                    $"重载前停机={跑完过};重载后 PC={机.程序计数器} 停机={机.停机} 寄存器全零={寄存器全零}");
            }
            catch (Exception ex) { 记录异常("H13 热重载 从程序开头重跑", ex); }

            // ---- ③ 布局挪过位(前头插了一个变量)⇒ 如实说"保不住",绝不按地址硬搬 ----
            try
            {
                const string 插了新变量 =
                    "整数 基数 = 7;\n整数 占用 = 5;\n整数 计数 = 0;\n整数 累计 = 0;\n" +
                    "当 (计数 < 10)\n{\n计数 = 计数 + 1;\n累计 = 累计 + 2;\n}\n输出行(计数);\n停止\n";
                var 编3 = 编译(插了新变量);
                var 机 = new 虚拟机C { 输出目标 = _ => { } };
                装载并备好(机, 旧编);
                机.运行(旧编);
                int 旧计数槽 = 槽址(旧编, "计数"), 新计数槽 = 槽址(编3, "计数");
                重载到(机, 编3, 旧编);
                uint 搬过来的 = 读字(机.内存, 新计数槽);
                string 说明 = string.Join(" / ", 机.上次重载说明);
                bool 过 = 旧计数槽 != 新计数槽 && 搬过来的 == 0
                    && !说明.Contains("顶层变量的值", StringComparison.Ordinal);
                记录("H13 热重载 布局挪过位就如实说保不住(前头插一个变量 ⇒ 后面每一只槽都不认,不按地址硬搬)",
                    过,
                    $"旧计数槽 0x{旧计数槽:X} → 新计数槽 0x{新计数槽:X};搬过来的值={搬过来的};说明=<{说明}>");
            }
            catch (Exception ex) { 记录异常("H13 热重载 布局挪位", ex); }

            // ---- ④ 常量按声明初值恢复(上一轮跑过之后常量槽里不是出厂值,重载要把它拽回来) ----
            try
            {
                var 机 = new 虚拟机C { 输出目标 = _ => { } };
                装载并备好(机, 旧编);
                机.运行(旧编);
                int 基数槽 = 槽址(旧编, "基数");
                机.内存[基数槽] = 0x5A;                 // 人为弄脏(常量本该是 7):重载必须按初值表拽回 7
                重载到(机, 新编, 旧编);
                uint 拽回来 = 读字(机.内存, 基数槽);
                记录("H13 热重载 常量按声明的初值恢复(槽被弄脏也拽回 7,不把上一轮算过的值当常量)",
                    拽回来 == 7,
                    $"基数槽 0x{基数槽:X}:人为写 0x5A → 重载后 0x{拽回来:X}(期望 7)");
            }
            catch (Exception ex) { 记录异常("H13 热重载 常量恢复", ex); }

            // ---- ⑤ 堆里的对象不保(说清"哪一块原来装着东西"),顶层变量照旧保住 ----
            try
            {
                // 堆要**真用上**:固定个数的 `.添加()` 会被优化成静态槽(那样根本不申请堆),所以这里显式 `申请`。
                // 两份**逐字节同源** —— 布局一点没动,才验得出"堆不保"这件事本身
                const string 带列表 =
                    "整数 计数 = 0;\n地址 块 = 申请(64);\n" +
                    "当 (计数 < 3)\n{\n计数 = 计数 + 1;\n}\n测试输出(计数);\n停止\n";
                // 内存给足:默认 1MB 够,但堆那一块是 16KB —— 直接按"堆 16KB + 默认内存"编两份同源程序
                var 首编 = new 汇编器C().汇编多文件带调试([("主程序.hb", 带列表)], true, 16 * 1024);
                var 次编 = new 汇编器C().汇编多文件带调试([("主程序.hb", 带列表)], true, 16 * 1024);
                var 机 = new 虚拟机C { 输出目标 = _ => { } };
                装载并备好(机, 首编);
                机.运行(首编);
                int 计数槽 = 槽址(首编, "计数");
                重载到(机, 次编, 首编);
                string 说明 = string.Join(" / ", 机.上次重载说明);
                uint 计数保住 = 读字(机.内存, 计数槽);
                bool 提过堆 = 说明.Contains("堆里的对象不保", StringComparison.Ordinal);
                string 分区 = string.Join(",", 首编.内存分区.Select(区 => $"{区.区名}@0x{区.起始:X}+{区.大小}"));
                string 址痕 = $"首编 {旧址(首编)} / 次编 {旧址(次编)}";
                记录("H13 热重载 堆里的对象不保但要**说清**(顶层计数器照旧保住,说明里点名堆那一块)",
                    计数保住 == 3 && 提过堆,
                    $"计数={计数保住}(期望 3);分区=[{分区}];{址痕};说明=<{说明}>");
            }
            catch (Exception ex) { 记录异常("H13 热重载 堆不保要说清", ex); }

            // ---- ⑥ 跨进程那条腿:真正在跑的那台在子进程里,与进程内跑出逐行一致 ----
            try
            {
                跑程序通道C 通道;
                跨进程虚拟机C 机;
                try
                {
                    通道 = 跑程序通道C.从当前进程();
                    机 = new 跨进程虚拟机C(通道) { 输出目标 = _ => { }, 输入源 = () => null };
