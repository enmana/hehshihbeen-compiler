            //     ⚠ 版本号的来历逐版登记在 `跑程序协议C` 那个常量头上;这里钉的只是"改过就得动它":
            //     4 = H13(『重载』命令 + 『重载回执』事件);
            //     5 = 控 1-⑥(绘制命令多带一份像素 —— `贴位图` 那一块,老载荷没有这一段)。
            try
            {
                记录("H13 热重载 协议版本 = 5(『重载』那一版是 4;控 1-⑥ 给绘制命令加了像素,版本号跟着走)",
                    跑程序协议C.协议版本 == 5 && 跑程序协议C.命令_重载 == 14 && 跑程序协议C.事件_重载 == 108,
                    $"版本={跑程序协议C.协议版本} 命令_重载={跑程序协议C.命令_重载} 事件_重载={跑程序协议C.事件_重载}");
