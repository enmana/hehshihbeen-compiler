                    var 迁 = 机.上次迁移;
                    string 说明 = string.Join(" / ", 机.上次重载说明);
                    string 迁移痕 = 迁 == null ? "(没回)"
                        : $"段{迁.段.Count}说明[{string.Join("~~", 迁.说明)}]";
                    收.Clear();
                    机.运行(新编);
                    string 二遍 = 文本(收);
                    bool 过 = 一遍 == "49\n10\n10" && 二遍 == "49\n10\n20"
                        && 说明.Contains("保住 2 个顶层变量", StringComparison.Ordinal);
                    记录("H13 热重载 跨进程那条腿与进程内逐行一致(迁移表由后端判、前端照贴)",
                        过,
                        $"第一遍 <{一遍.Replace("\n", "|")}>;第二遍 <{二遍.Replace("\n", "|")}>;说明=<{说明}>;" +
                        $"迁移=[{迁移痕}];镜像旧={镜像旧};说明=<{说明}>;子进程说明=<{截断(机.通道.后端说明, 60)}>");
                }
            }
            catch (Exception ex) { 记录异常("H13 热重载 跨进程那条腿", ex); }

