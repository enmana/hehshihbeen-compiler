        // ---------------- 这一组的小工具(只服务热重载) ----------------

        /// <summary> 装载一份编译结果,顺手把"旧那一份的三张表"挂上(与 `界面契约C` 那个装载口同一个口径)</summary>
        private static void 装载并备好(虚拟机C 机, 汇编调试结果C 编)
        {
            备好新表(机, 编);
            机.装载(编);
        }

        /// <summary> 把这一份编译结果的那几张表挂到机器上(装载那一档的口径;重载那条路是**参数**传进去的)</summary>
        private static void 备好新表(虚拟机C 机, 汇编调试结果C 编)
        {
            机.标签表 = 编.标签表;
            机.内存分区 = 编.内存分区;
            机.名字表 = 编.名字表;
            机.代码字节数 = 编.代码字节数;
        }

        /// <summary> 按这一份编译结果重载(界面上 `界面契约C.热重载` 走的就是这一套参数) </summary>
        private static void 重载到(虚拟机C 机, 汇编调试结果C 编, 汇编调试结果C 旧编)
        {
            机.初值表 = 编.初值表;              // 新那一份的常量初值(重载按它把常量拽回出厂值)
            机.名字表 = 编.名字表;              // 新那一份的名字表(界面那条路也是这样:它一直挂着最新那一份)
            机.代码字节数 = 编.代码字节数;      // 新那一份的静态数据段字节数(界面的装载口也设这一格)
            机.重载(编.机器码, 旧名字表: 旧编.名字表, 新名字表: 编.名字表, 新代码字节数: 编.代码字节数,
                新标签表: 编.标签表, 新分区表: 编.内存分区);
        }

        /// <summary> 那只全局变量排在哪个字节地址(标签表里查它的槽标签;查不到就报错,别静默给 0)</summary>
        private static int 槽址(汇编调试结果C 编, string 变量名)
        {
            var 项 = 编.名字表.变量.First(x => x.是全局 && x.名字 == 变量名);
            if (!编.标签表.TryGetValue(项.槽, out int 址))
                throw new InvalidOperationException($"标签表里查不到 `{变量名}` 的槽 `{项.槽}`");
            return 址;
        }

        /// <summary> 小端读一个 32 位字(自检里量"那一格是不是这个值")</summary>
        private static uint 读字(byte[] 内存, int 址) =>
            (uint)(内存[址] | (内存[址 + 1] << 8) | (内存[址 + 2] << 16) | (内存[址 + 3] << 24));

        /// <summary> 这一份编译结果里几个槽的"槽标签@地址"(诊断用) </summary>
        private static string 旧址(汇编调试结果C 编) =>
            string.Join(",", 编.名字表.变量.Where(x => x.是全局)
                .Select(x => $"{x.槽}@0x{(编.标签表.TryGetValue(x.槽, out int 址) ? 址 : -1):X}")) +
            "|标签们=" + string.Join(",", 编.标签表.Where(kv => kv.Key.StartsWith("_v", StringComparison.Ordinal)).Select(kv => $"{kv.Key}@0x{kv.Value:X}"));

        /// <summary> 收下来的字节 → 文本(逐行对账用)</summary>
        private static string 文本(List<byte> 字节) =>
            System.Text.Encoding.UTF8.GetString([.. 字节]).Replace("\r\n", "\n").TrimEnd('\n');
    }
