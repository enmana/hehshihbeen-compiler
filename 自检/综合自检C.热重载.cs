// ============================================================
// 热重载自检(H13,第324批)—— 「改源码不重启程序就把新机器码换进去」的验收
//
//   用户 2026-10-01 拍板四点(都是推荐档):**b 档**(保布局没变的顶层变量 + 池位置大小不变时连字符串池一起保)、
//   **只手动**(编译成功且程序还在跑时按手势才换)、手势 **F6**、口径住**引擎层**(CLI / IDE / 自检共用一份)。
//
//   组里钉的是**引擎那一层的行为**(真编真跑,逐格对值),分四类:
//     ① 保住什么:顶层变量按"槽标签同名 + 宽度相同"搬,常量按声明初值回出厂值;
//     ② 保不住什么:堆、调用栈、寄存器一律不带过来 —— 重载后从程序开头重跑(PC = 0、寄存器全 0);
//     ③ 判据不许硬搬:布局挪过位(前头插了变量 / 类型宽度变了)就如实说"保不住",绝不按地址瞎搬;
//     ④ 跨进程那条腿(真正在跑的那台在子进程里)与进程内那条腿**跑出逐行一致**的结果,
//        迁移表由后端判、前端照贴(判据只有一处)。
//
//   **ISA / 语言面 / 机器码一个字节没动**:这一组全是"换进去"那一侧的事(见 `虚拟机C.重载`)。
// ============================================================

