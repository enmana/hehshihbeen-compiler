            // ---- ⑧ F6 这一条路的接线(接线哨兵:读源码文本判;行为本身由 ①~⑥ 钉住) ----
            //     为什么还要它:界面上"哪个键触发、菜单接的哪个处理函数、处理函数调的是不是契约那一格"
