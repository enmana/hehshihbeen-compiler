    public static partial class 综合自检C
    {
        private static void 出参数形状自检()
        {
            // ---------- 夹具一:出参数的八种写法(模块级只有 `槽`,不带同名那一档) ----------
            const string 出参库源 = """
                模块 出参库

                私有 字符串 槽;

                方法 一(字符串 出 文) 返回 整数
                {
                    文.清空();
                    槽.清空();
                    拼接到(槽, "项目周报");
                    拼接到(文, 槽);
                    返回 文.长度();
                }

                方法 二(字符串 出 文) 返回 整数
                {
                    文.清空();
                    整数 i = 0;
                    当 (i < 20)
                    {
                        拼接到(文, "第");
                        拼接到(文, "几段");
                        i = i + 1;
                    }
                    返回 文.长度();
                }

                方法 三(字符串 出 文) 返回 整数
                {
                    拼接到(文, "尾巴");
                    返回 文.长度();
                }

                私有 方法 内层(字符串 出 内) 返回 整数
                {
                    内.清空();
                    拼接到(内, "内层写的");
                    返回 内.长度();
                }

                方法 四(字符串 出 外) 返回 整数
                {
                    外.清空();
                    返回 内层(外);
                }

                方法 五(字符串 出 外) 返回 整数
                {
                    外.清空();
                    整数 丢 = 内层(外);
                    拼接到(外, "再接一句");
                    返回 外.长度();
                }

                方法 六(字符串 出 一, 字符串 出 二) 返回 整数
                {
                    一.清空();
                    二.清空();
                    整数 i = 0;
                    当 (i < 30)
                    {
                        拼接到(一, "左");
                        i = i + 1;
                    }
                    拼接到(二, "右");
                    整数 长一 = 一.长度();
                    整数 长二 = 二.长度();
                    返回 长一 + 长二;
                }

                私有 方法 中层(字符串 出 中) 返回 整数
                {
                    中.清空();
                    返回 内层(中);
                }

                方法 七(字符串 出 外) 返回 整数
                {
                    外.清空();
                    返回 中层(外);
                }

                方法 八(字符串 出 文) 返回 整数
                {
                    文.清空();
                    文 = "先赋值一段";
                    拼接到(文, "·再接一段");
                    返回 文.长度();
                }
                """ + "\n";

            // ---------- 夹具二:模块级变量与出参数同名 + 跨函数同名出参数 ----------
            const string 同名库源 = """
                模块 同名库

                私有 字符串 文;

                方法 同名一(字符串 出 文) 返回 整数
                {
                    文.清空();
                    拼接到(文, "撞一同名");
                    返回 文.长度();
                }

                方法 同名二(字符串 出 文) 返回 整数
                {
                    文.清空();
                    拼接到(文, "撞二");
                    返回 文.长度();
                }
                """ + "\n";

            string 临时根 = 临时区C.取目录("自检", "出参数形状");
            string 出参路径 = Path.Combine(临时根, "出参库.hb").Replace('\\', '/');
            string 同名路径 = Path.Combine(临时根, "同名库.hb").Replace('\\', '/');
            try
            {
                var 无BOM = new UTF8Encoding(false);
                File.WriteAllText(出参路径, 出参库源, 无BOM);
                File.WriteAllText(同名路径, 同名库源, 无BOM);
            }
            catch (Exception ex)
            {
                记录异常("出参数形状 写夹具(临时区里那两个模块文件)", ex);
                return;
            }

            string 头 = $"包含 \"{出参路径}\"\n包含 \"{同名路径}\"\n";

            // 跑一段 HB:输出按行收(每行末尾空白去掉、首尾空行去掉)
            List<string> 跑行(string 体)
            {
                var 编译 = new 汇编器C().汇编多文件带调试(
                    new List<(string, string)> { ("主程序.hb", 头 + 体) }, true, 中间层C.默认堆大小, null,
                    中间层C.默认池大小, 虚拟机C.默认内存大小, 32 * 1024);
                var vm = new 虚拟机C { 宿主调用 = 宿主能力C.处理 };
                vm.设内存大小(虚拟机C.默认内存大小);
                var 缓冲 = new StringBuilder();
                var 解码 = new 文字输出C(文本 => 缓冲.Append(文本));
                vm.输出目标 = 解码.写;
                vm.运行(编译);
                解码.收尾();
                var 行表 = 缓冲.ToString().Replace("\r", "").Split('\n')
                    .Select(x => x.TrimEnd()).ToList();
                while (行表.Count > 0 && 行表[^1].Length == 0) 行表.RemoveAt(行表.Count - 1);
                while (行表.Count > 0 && 行表[0].Length == 0) 行表.RemoveAt(行表.Count - 1);
                if (编译.查运行期报错(vm.内存) is { } 说明) 行表.Add($"⚠{说明}");
                return 行表;
            }

            // 一行一条地比;不齐就报第一处不一样(带行号,好查)
            void 比行(string 名, List<string> 实得, params string[] 期望行)
            {
                bool 好 = 实得.Count == 期望行.Length;
                int 第一坏 = -1;
                if (好)
                {
                    for (int i = 0; i < 期望行.Length; i++)
                        if (实得[i] != 期望行[i]) { 好 = false; 第一坏 = i; break; }
                }
                string 说明 = 好 ? $"共 {实得.Count} 行逐行对上"
                    : $"实测 {实得.Count} 行 / 期望 {期望行.Length} 行" +
                      (第一坏 >= 0 ? $";第 {第一坏 + 1} 行 实测=<{实得[第一坏]}> 期望=<{期望行[第一坏]}>"
                                   : $";实测=<{string.Join("|", 实得)}>");
                记录(名, 好, 说明);
            }

            // 每条断言都各自 try:一条炸了不挡后面九条
            void 一条(string 名, string 体, params string[] 期望行)
            {
                try { 比行(名, 跑行(体), 期望行); }
                catch (Exception ex) { 记录异常("出参数形状 " + 名, ex); }
            }

            try
            {
                一条("出参数形状 ① 清空 + 一次整串:交货的是整串,不是半截",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.一(文));\n输出行(文);\n停止",
                    "4", "项目周报");

                一条("出参数形状 ② 清空 + 循环里分段拼:20 轮每轮两次 `拼接到` 一处不落",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.二(文));\n输出行(文.长度());\n输出行(文);\n停止",
                    "60", "60", string.Concat(Enumerable.Repeat("第几段", 20)));

                一条("出参数形状 ③ 不先清空:接在调用方原有内容后面(原来的没被冲掉)",
                    "字符串 文 = \"原有\";\n" +
                    "输出行(出参库.三(文));\n输出行(文);\n停止",
                    "4", "原有尾巴");

                一条("出参数形状 ④ 转交:把调用方的 `出` 参数交给另一个 `出` 函数",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.四(文));\n输出行(文);\n停止",
                    "4", "内层写的");

                一条("出参数形状 ⑤ 转交之后再自己写一笔:两段都在",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.五(文));\n输出行(文);\n停止",
                    "8", "内层写的再接一句");

                一条("出参数形状 ⑥ 两个出参数:第一格长到 30 字之后,第二格照样对",
                    "字符串 一 = \"\";\n字符串 二 = \"\";\n" +
                    "输出行(出参库.六(一, 二));\n输出行(一.长度());\n输出行(二);\n停止",
                    "31", "30", "右");

                一条("出参数形状 ⑦ 两层转交(外 → 中 → 内)",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.七(文));\n输出行(文);\n停止",
                    "4", "内层写的");

                一条("出参数形状 ⑧ 先整串赋值、再往后拼",
                    "字符串 文 = \"\";\n" +
                    "输出行(出参库.八(文));\n输出行(文);\n停止",
                    "10", "先赋值一段·再接一段");

                一条("出参数形状 ⑨ 模块级同名 / 跨函数同名:两个同名出参数函数交替调也不串味",
                    "字符串 文 = \"\";\n" +
                    "输出行(同名库.同名一(文));\n输出行(文);\n" +
                    "输出行(同名库.同名二(文));\n输出行(文);\n" +
                    "文 = \"\";\n" +
                    "输出行(同名库.同名一(文));\n输出行(文);\n" +
                    "输出行(同名库.同名二(文));\n输出行(文);\n停止",
                    "4", "撞一同名", "2", "撞二", "4", "撞一同名", "2", "撞二");

                // ⑩ **口径钉子(反面)**:这条**不是** H85 —— 它是 `字符串[i]` 的码点性质。
                //    批 17 之所以把它记成"出参数半截串",就是这一格没有对过码点与低字节:
                //    `字符 本字 = 槽[i]` 把 `项`(U+9879 = 39033)截成 121 = `y`,四个字拼出来
                //    的字节是 `79 EE 68 A5`,按 UTF-8 解出来正是当年记的那个 `y\ufffdh?`。
                一条("出参数形状 ⑩ 口径钉子:`字符串[i]` 是码点,存进 `字符` 只剩低字节(**不是** `出` 参数的事)",
                    "字符串 槽 = \"项目周报\";\n" +
                    "整数 i = 0;\n" +
                    "当 (i < 槽.长度())\n{\n" +
                    "    整数 码 = 槽[i];\n" +
                    "    字符 本字 = ' ';\n" +
                    "    本字 = 槽[i];\n" +
                    "    整数 截后 = 本字;\n" +
                    "    输出行(码);\n    输出行(截后);\n    i = i + 1;\n}\n停止",
                    "39033", "121", "30446", "238", "21608", "104", "25253", "165");
            }
            finally
            {
                try { if (Directory.Exists(临时根)) Directory.Delete(临时根, true); } catch { }
            }
        }
    }
