using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **评测整改第 3 阶段 T18:维度组断言**(`评测整改计划.md` §4 T18)。
    ///
    /// 为什么单开一组:2026-09-27 那次评测抓到的缺陷**绝大多数落在"两个已覆盖点之间"** ——
    /// 表达式有深度护栏、语句块没有;声明处有截断检查、赋值处没有;常量下标补符号、运行期下标不补。
    /// 原来那些自检是**逐条缺陷攒出来**的:越长越密,却盖不住这些维度。这一组不再盯某一条缺陷,
    /// 改盯**不变量**:
    /// <list type="number">
    /// <item>**同一值不同写法必须同义** —— `-1` / `(0-1)` / `(2-3)` / `整数 负值 = 0-1; 负值` 四种写法
    ///   × {比较、打印、除、取余、右移、当实参} 六个用途,结果逐字节相同(判据落在 T4 修好的常量折叠上);</item>
    /// <item>**同一值七条存储路径** —— 顶层宽变量 / 顶层窄变量 / 结构字段 / 数组元素 / 列表元素 /
    ///   函数局部 / 参数 × {0x7FFF, 0x8000, 0xFFFF, 40000, -5},常量写法与运行期写法读回来都对上
    ///   "按声明宽截断、有符号的补符号位"(判据落在 T6 修好的截断三条路上),
    ///   而且**优化开/关同一答案**(`--no-opt` 只许影响指令条数)。</item>
    /// </list>
    ///
    /// **先红后绿**:这两组在 T4 / T6 修之前是红的(收口时做过一次反向实测:把两处修法临时改回去,
    /// 这两条当场 FAIL —— 证明它们不是"把当前行为抄下来")。
    /// </summary>
    public static partial class 综合自检C
    {
        /// <summary> T18「七条存储路径」用的值表:0x7FFF / 0x8000 / 0xFFFF / 40000 / -5(负常量占最后一格) </summary>
        private static readonly (string 字面, int 值)[] 维度值表 =
        [
            ("0x7FFF", 0x7FFF),
            ("0x8000", 0x8000),
            ("0xFFFF", 0xFFFF),
            ("40000", 40000),
            ("-5", -5),
        ];

        private static void 评测整改阶段三自检()
        {
            // `跑一次` 的输出是按**字节**收的(见 阶段一/阶段二那两组),要比对中文先按 UTF-8 还原一次。
            static string 还原(string 出) => Encoding.UTF8.GetString(Encoding.Latin1.GetBytes(出)).TrimEnd('\n');
            static string 跑文本(string 源, bool 优化 = true)
                => 还原(跑一次([("主程序.hb", 源)], 优化, 虚拟机C.默认内存大小).输出);

            // ================= ① 同一值不同写法必须同义(矩阵) =================
            // 三组值 × 四种写法 × 六个用途。写法里既有字面量、括号里的常量折表达式,也有"先落一个变量"那条老路
            // (T4 当年就是被它照出来的)。期望值按 C# 的 32 位补码语义算(HB 的 除/取余/右移 与它同一口径)。
            var 值组 = new (int 值, string[] 写法)[]
            {
                (-1, ["-1", "(0-1)", "(2-3)", "负值"]),
                (-3, ["-3", "(2-5)", "(0-3)", "负值二"]),
                (-10, ["-10", "(1000-2000)/100", "(0-10)", "负值三"]),
            };
            var 用途 = new (string 名, Func<string, string> 套, Func<int, int> 期望)[]
            {
                ("比较(< 0)", 写法 => $"{写法} < 0", 值 => 值 < 0 ? 1 : 0),
                ("打印", 写法 => 写法, 值 => 值),
                ("除 2", 写法 => $"{写法} / 2", 值 => 值 / 2),
                ("取余 2", 写法 => $"{写法} % 2", 值 => 值 % 2),
                ("右移 1", 写法 => $"{写法} >> 1", 值 => 值 >> 1),
                ("当实参", 写法 => $"取原({写法})", 值 => 值),
            };

            var 同义源 = new StringBuilder();
            // 变量写法要的三条声明(值的写法在 值组 里按名引用)
            同义源.Append("整数 负值 = 0-1;\n整数 负值二 = 2-5;\n整数 负值三 = (1000-2000)/100;\n");
            同义源.Append("方法 取原(整数 n) 返回 整数\n{\n返回 n;\n}\n");
            var 同义期望 = new List<string>();
            foreach (var (值, 写法们) in 值组)
                foreach (var (名, 套, 期望) in 用途)
                    foreach (string 写法 in 写法们)
                    {
                        同义源.Append($"输出行({套(写法)});\n");
                        同义期望.Add(期望(值).ToString(System.Globalization.CultureInfo.InvariantCulture));
                    }
            同义源.Append("停止\n");

            string 同义开 = 跑文本(同义源.ToString()), 同义关 = 跑文本(同义源.ToString(), 优化: false);
            string 同义期望文本 = string.Join("\n", 同义期望);
            var 同义说明 = new List<string>();
            if (同义开 != 同义期望文本 || 同义关 != 同义开)
            {
                var 实 = 同义开.Split('\n');
                int 位 = 0;
                foreach (var (值, 写法们) in 值组)
                {
                    foreach (var (名, _, _) in 用途)
                    {
                        var 这组 = 实.Skip(位).Take(写法们.Length).ToArray();
                        位 += 写法们.Length;
                        if (这组.Length != 写法们.Length || 这组.Distinct(StringComparer.Ordinal).Count() != 1)
                            同义说明.Add($"值 {值} / {名}:四种写法给出 [{string.Join("|", 这组)}]");
                    }
                }
                // 四种写法彼此一致、但整块与"算出来的期望"对不上(比如有符号除法整体坏了)—— 这一档也得说清是哪儿不一样
                if (同义开 != 同义期望文本)
                    同义说明.Insert(0, $"有整块与算出来的期望不一致:实测[{同义开.Replace("\n", "|")}](期望[{同义期望文本.Replace("\n", "|")}])");
                if (同义关 != 同义开) 同义说明.Add($"优化开关改了答案:开[{同义开.Replace("\n", "|")}] 关[{同义关.Replace("\n", "|")}]");
            }
            记录("T18 同一值不同写法必须同义(-1 / -3 / -10 各四种写法 × 比较 / 打印 / 除 / 取余 / 右移 / 当实参,逐字节相同)",
                同义说明.Count == 0,
                同义说明.Count == 0
                    ? $"{值组.Length} 组值 × {用途.Length} 个用途 × 4 种写法 = {同义期望.Count} 行,全对上;两档也相同"
                    : string.Join(" ; ", 同义说明.Take(4)));
            记录("T18 常量折叠 优化开/关同一答案(开关只许改指令条数,不许改程序输出)",
                同义关 == 同义开, $"开 {同义开.Length} 字 / 关 {同义关.Length} 字");

            // ================= ② 同一值七条存储路径(矩阵) =================
            // 七行 = 顶层宽变量(整数) + 六条**窄**路(短整数 变量 / 结构字段 / 数组元素 / 列表元素 / 函数局部 / 参数)。
            // 期望:宽那一行原样保住值;六条窄路按 16 位**有符号**读回((short)值)。
            // 两种写法各跑一遍:**字面常量**与**运行期变量**(T6 当年只治到"顶层短整数变量"那一支,这里把七条路
            // 一起摆出来,常量与运行期都不许漏)。
            var 七路期望 = new List<string>();
            foreach (var (_, 值) in 维度值表)
            {
                七路期望.Add(值.ToString(System.Globalization.CultureInfo.InvariantCulture));                 // 顶层宽变量
                for (int i = 0; i < 6; i++) 七路期望.Add(((short)值).ToString(System.Globalization.CultureInfo.InvariantCulture));
            }

            // ---- 形式 a:字面常量写进去(函数局部 / 参数各按值生成一个小方法) ----
            // **声明处**不许放超出窄类型值域的常量(T6 那条范围检查:`短整数 内 = 0x8000;` 当场报错),
            // 所以这里一律走"先声明、再**赋值**"—— 与用户拿常量写进窄槽的实际写法一致。
            var 常量源 = new StringBuilder();
            常量源.Append("结构 盒\n{\n短整数 v;\n}\n");
            for (int k = 0; k < 维度值表.Length; k++)
                常量源.Append($"方法 取局部{k}() 返回 整数\n{{\n短整数 内;\n内 = {维度值表[k].字面};\n返回 内;\n}}\n");
            for (int k = 0; k < 维度值表.Length; k++)
                常量源.Append($"方法 取参{k}(短整数 p) 返回 整数\n{{\n返回 p;\n}}\n");
            常量源.Append("整数 宽 = 0;\n短整数 窄;\n盒 盒值;\n短整数 表[2];\n短整数 列[];\n");
            for (int k = 0; k < 维度值表.Length; k++)
            {
                string v = 维度值表[k].字面;
                常量源.Append($"宽 = {v};\n输出行(宽);\n");
                常量源.Append($"窄 = {v};\n输出行(窄);\n");
                常量源.Append($"盒值.v = {v};\n输出行(盒值.v);\n");
                常量源.Append($"表[0] = {v};\n输出行(表[0]);\n");
                常量源.Append($"列.添加({v});\n输出行(列[列.长度() - 1]);\n");
                常量源.Append($"输出行(取局部{k}());\n");
                常量源.Append($"输出行(取参{k}({v}));\n");
            }
            常量源.Append("停止\n");

            // ---- 形式 b:同一个值从变量里写进去(运行期那条路) ----
            var 运行源 = new StringBuilder();
            运行源.Append("结构 盒\n{\n短整数 v;\n}\n");
            运行源.Append("方法 取局部(整数 q) 返回 整数\n{\n短整数 内;\n内 = q;\n返回 内;\n}\n");
            运行源.Append("方法 取参(短整数 p) 返回 整数\n{\n返回 p;\n}\n");
            运行源.Append("整数 宽 = 0;\n短整数 窄;\n盒 盒值;\n短整数 表[2];\n短整数 列[];\n整数 i = 0;\n");
            foreach (var (字面, _) in 维度值表)
            {
                运行源.Append($"i = {字面};\n");
                运行源.Append("宽 = i;\n输出行(宽);\n");
                运行源.Append("窄 = i;\n输出行(窄);\n");
                运行源.Append("盒值.v = i;\n输出行(盒值.v);\n");
                运行源.Append("表[0] = i;\n输出行(表[0]);\n");
                运行源.Append("列.添加(i);\n输出行(列[列.长度() - 1]);\n");
                运行源.Append("输出行(取局部(i));\n");
                运行源.Append("输出行(取参(i));\n");
            }
            运行源.Append("停止\n");

            string 期望文本 = string.Join("\n", 七路期望);
            string 常量开 = 跑文本(常量源.ToString()), 常量关 = 跑文本(常量源.ToString(), 优化: false);
            string 运行开 = 跑文本(运行源.ToString()), 运行关 = 跑文本(运行源.ToString(), 优化: false);
            记录("T18 同一值七条存储路径(常量写法):顶层宽变量原样、六条窄路按 16 位有符号读回(0x7FFF / 0x8000 / 0xFFFF / 40000 / -5)",
                常量开 == 期望文本,
                $"实测[{常量开.Replace("\n", "|")}](期望[{期望文本.Replace("\n", "|")}])");
            记录("T18 同一值七条存储路径(运行期写法):值从变量里写进去,七条路读回来与常量写法逐字节相同",
                运行开 == 常量开, $"运行期[{运行开.Replace("\n", "|")}]");
            记录("T18 七条存储路径 优化开/关两档都同一答案(常量写法 / 运行期写法各比一遍)",
                常量关 == 常量开 && 运行关 == 运行开,
                $"常量 开/关 {(常量关 == 常量开 ? "同" : "不同")};运行期 开/关 {(运行关 == 运行开 ? "同" : "不同")}");
        }
    }
}
