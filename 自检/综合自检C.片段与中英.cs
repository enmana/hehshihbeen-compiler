        private static List<string> 新列表() => [];

        /// <summary> 扫一行指令引用的第一个操作数:是 `_f…` 标签就检查它在片段或整篇里有没有定义 </summary>
        private static void 收缺标签(string 行, string 段, string 整篇, List<string> 缺)
        {
            int 注释 = 行.IndexOf("//", StringComparison.Ordinal);
            string s = (注释 >= 0 ? 行[..注释] : 行).Trim();
            if (s.Length == 0 || s.EndsWith(':')) return;
            int 冒号 = s.IndexOf(':');
            if (冒号 >= 0) { s = s[(冒号 + 1)..].Trim(); if (s.Length == 0) return; }
            int 空 = s.IndexOfAny([' ', '\t']);
            if (空 <= 0) return;
            string 首操作 = s[(空 + 1)..].Trim();
            int 止 = 首操作.IndexOfAny([' ', '\t', ',']);
            if (止 < 0) 止 = 首操作.Length;
            string 名 = 首操作[..止];
            if (!名.StartsWith("_f", StringComparison.Ordinal)) return;
            if (段.Contains("\n" + 名 + ":") || 段.StartsWith(名 + ":")) return;
            if (整篇.Contains("\n" + 名 + ":") || 整篇.StartsWith(名 + ":")) return;
            缺.Add(名);
        }

        // ================= 15.6) 中英切换(关键字 + 指令名 + 内建函数) =================
        /// <summary>
        /// 「中英切换」是**纯文本改写**:关键字(中间层指令C.关键字表)一遍、指令名(指令C.指令表)
        /// 与内建函数名(中间层指令C.内建函数名表)一遍,**注释一个字不动**。
        /// 这里盯四件事:
        /// ① 翻过去再翻回来 == 原文(可逆,不留痕迹);
        /// ② 两边各自编出来的**机器码一模一样**(切换不改语义,只改写法);
        /// ③ 三类"跟指令/类型撞名的词"各有用例:`返回`(同时是 ISA 的 RET)、
        ///    `存字`/`取字`(同时是 ISA 助记符 —— 必须翻成函数名 storeword/loadword,不是助记符)、
        ///    `地址`(是**类型名**,英文 addr,不是关键字);
        /// ④ 方法(`.长度()`/`.清空()`/`.添加()`)中英**两侧都认**(英文别名 `.length()/.clear()/.add()`,第96批),
        ///    切换**照旧不许动它们** —— 两边都能编译,不动最省心(加别名之前是"动了就变成未定义的函数")。
        /// </summary>
