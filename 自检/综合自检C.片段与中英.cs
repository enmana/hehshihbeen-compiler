        /// <summary> 验 代码解析器.取保护改写区:区间有序、互不重叠、且覆盖了注释区与字面量区各自的每一段 </summary>
        private static bool 保护改写区自洽(Func<string, List<(int 开始, int 结束)>> 取注释, Func<string, List<(int, int)>> 取串)
        {
            string 文本 = "字符串 内容 = \"含 // 与 ' 的字面量\"; // 注释里的 \"字面量\"\n整数 数 = 1;\n";
            var 注释 = 取注释(文本);
            var 字面量 = 取串(文本);
            var 保护 = 代码解析器.取保护改写区(文本);
            for (int i = 1; i < 保护.Count; i++)
                if (保护[i].开始 < 保护[i - 1].结束) return false;      // 有序且不重叠
            bool 都盖到(IEnumerable<(int 开始, int 结束)> 源) =>
                源.All(r => 保护.Any(p => p.开始 <= r.开始 && p.结束 >= r.结束));
            return 都盖到(注释) && 都盖到(字面量);
        }

        /// <summary> 头一个不一样的下标(一样就返回 -1);调试输出用 </summary>
