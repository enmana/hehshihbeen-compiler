            string 源 = string.Join('\n',
            [
                "// 注释里的 如果/返回/存字/申请 一个字都不许动",
                "结构 坐标 {",
                "    整数 横;",
                "    整数 纵;",
                "}",
                "",
                "程序集 整数 内部计数 = 1;",
                "",
                "测试 样例 {",
                "    断言 1 + 1 == 2;",
                "}",
                "",
                "方法 问好(字符串 出 结果, 字符串 称呼) 返回 逻辑 {",
                "    逻辑 好 = 假;",
                "    如果 (称呼.长度() > 0) {",
                "        拼接到(结果, \"你好,\", 称呼);",
                "        好 = 真;",
                "    } 否则 {",
                "        好 = 假;",
                "    }",
                "    返回 好;",
                "}",
                "",
                "方法 主程序() {",
                "    整数 计数 = 0;",
                "    字符串 问候 = \"\";",
                "    如果 (问好(问候, \"世界\")) { 输出行(问候); }",
                "    选择 (计数) {",
                "        情况 0 { 输出行(\"零\"); }",
                "        情况 1..3, 5 { 输出行(\"小\"); }",
                "        默认 { 输出行(\"大\"); }",
                "    }",
                "    循环 (整数 i = 0; i < 3; i = i + 1) { 如果 (i == 1) { 继续; } 输出行(i); }",
                "    当 (计数 < 2) { 计数 = 计数 + 1; }",
                "    逻辑 结 = 计数 > 0 && 计数 < 9;",
                "    测试输出(结);",
                "    短整数 短值 = -3;",
                "    无符号整数 无符号值 = 7;",
                "    文字 文字值 = 'A';",
                "    字节 字节值 = 1;",
                "    地址 地 = 申请(16);",
                "    存字(地, 0, 7);",
                "    测试输出(取字(地, 0));",
                "    释放(地);",
                "    问候.清空();",
                "    输出行(问候.长度());",
                "    输出(文字值);",
                "    输出行(\"字符串 如果 返回 存字\");",
                "    停止",
                "}",
            ]);

            string 英 = "";
            string 回 = "";
            try
            {
                英 = 中间层C.切换中英(false, 源);
                记录("中英切换 切到英文有变化", 英 != 源, $"长度 {源.Length} → {英.Length}");
                回 = 中间层C.切换中英(true, 英);
            }
            catch (Exception ex) { 记录异常("中英切换 切过去再切回来", ex); }

            // ① 可逆
            记录("中英切换 切过去再切回来 == 原文", 回 == 源,
                回 == 源 ? null : $"第 {首个不同下标(源, 回)} 个字符起不一样");

            // ② 注释一个字不动(只翻代码段)
            记录("中英切换 注释原样保留(注释里的关键字没被翻)",
                英.Contains("// 注释里的 如果/返回/存字/申请 一个字都不许动") &&
                !英.Contains("// 注释里的 if/return"),
                "注释行 " + (英.Split('\n').FirstOrDefault(x => x.Contains("注释里的")) ?? "<没找到>"));

            // ③ 三类"撞名词"各一条(都是实测踩过的形状)
            记录("中英切换 返回 → return(不是 RET,函数头与裸返回都要对)",
                英.Contains("method 问好(string result 结果, string 称呼) return logic") && 英.Contains("return 好;")
                && !英.Contains("RET 逻辑") && !英.Contains("RET 好"),
               句子含(英, "问好"));
            记录("中英切换 程序集 → internal(可见性三档里的工程档)",
                英.Contains("internal int 内部计数 = 1;") && !英.Contains("程序集"),
                句子含(英, "内部计数"));
            记录("中英切换 字符串 → string(附加类型名:类型名跟着一起切,但 字符串 不在 关键字表 里)",
                英.Contains("string 问候 = \"\";") && 英.Contains("string result 结果") && !英.Contains("字符串 问候"),
               句子含(英, "string 问候"));
            记录("中英切换 字符串/字符字面量里的词一个字不动(不许改程序的数据)",
                英.Contains("\"字符串 如果 返回 存字\"") && !英.Contains("\"string if return") && !英.Contains("\"string if")
                && 英.Contains("println(\"字符串 如果 返回 存字\");"),   // 外面那层 `输出行` 该翻成 println,里面一个字不动
               句子含(英, "println(\""));
            记录("中英切换 字符字面量与类型名不互相带跑(`字符`/`字符串` 各是各的)",
                英.Contains("rune 文字值 = 'A';"),
               句子含(英, "rune "));
            记录("切回中文时 string → 字符串(附加类型名能双向翻)",
                回.Contains("字符串 问候 = \"\";") && 回.Contains("字符串 出 结果"),
               句子含(回, "字符串 问候"));
            记录("中英切换 存字/取字 → storeword/loadword(函数调用,不是助记符 STORE_WORD/LOAD_WORD)",
                英.Contains("storeword(地, 0, 7);") && 英.Contains("loadword(地, 0)") &&
                !英.Contains("STORE_WORD(") && !英.Contains("LOAD_WORD("),
               句子含(英, "storeword"));
            记录("中英切换 地址 → addr(类型名,不是 address)",
                英.Contains("addr 地 = alloc(16);") && !英.Contains("address 地"),
               句子含(英, "addr "));
