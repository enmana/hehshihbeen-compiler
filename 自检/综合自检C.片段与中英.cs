            // ③b 同名的**汇编指令**写法(不带括号)要按指令翻,不能被当成函数调用
            //     `读取字符` 本身就是 ISA 的 IN,`存字`/`取字` 是 STORE_WORD/LOAD_WORD ——
            //     混着翻,内联汇编当场废掉。这里走**完整两步**(指令名那一步 + 关键字那一步,
            //     和编辑器/CLI 调的一模一样):少走一步就会漏掉"裸 `返回`"这种跨界情况。
            string 汇编源 = string.Join('\n',
            [
                "子程序:",
                "取地址 R15 _v1",
                "存字 R14 _v1",
                "读取字符 R13",
                "返回",
            ]);
            string 汇编英 = 中间层C.切换中英(false, 汇编源);
            string 汇编回 = 中间层C.切换中英(true, 汇编英);
