        {
            // 源里把"会撞名/会漏翻"的写法都摆上。变量名/函数名刻意避开指令名与内建函数名,
            // 这样"两边机器码一模一样"这条断言才干净(用户自己起个 `加法` 这种名字会被一致改名,
