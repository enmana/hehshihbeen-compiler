                记录("中英切换 两边机器码逐字节一致", 码中.AsSpan().SequenceEqual(码英),
                   码中.Length == 码英.Length ? $"长度一致({码中.Length}),首个不同字节 {首个不同字节(码中, 码英)}" : $"长度 {码中.Length} vs {码英.Length}");
            }
            catch (Exception ex) { 记录异常("中英切换 两边都能编译并且机器码一致", ex); }

            // ⑤ 词表只有一份:内建函数表两侧名字都能"反查回自己",说明表也不缺项
            try
