    /// <summary>
    /// 综合自检的一部分:**R1-6 批 2 —— 图形界面的输入与时钟**。
    ///
    /// 批 1 已经把"命令队列 + 无头呈现"钉住了(组 `图形界面`);这一组盯的是**输入从哪儿来、时间怎么走**:
    /// ① **键码表 / 事件类型**(`图形事件C` / `图形键C`):编号是对外接口,得钉死,而且要中英两侧都认;
    /// ② **事件脚本**(`事件脚本C`):解析口径 + 报错带行号说人话给改法;
    /// ③ **事件泵**(`图形宿主C`):第 k 帧的事件在**第 k 帧开始时**进队列;跑满 `帧数` 帧投一次关窗请求;
    ///    程序不理它 ⇒ 带行号的运行期错误(不许默默转下去);
    /// ④ **确定性**:同一份源码 + 同一份脚本两次跑逐字节一致(硬规矩 6:不开窗也能验);
    /// ⑤ **桌面壳那层隔离**:Avalonia 的键先译成 HB 键码再投(开不了窗 ⇒ 按源码钉);
    /// ⑥ **标准工程** `示例15_事件循环`:自检与 `hbcc --事件脚本` 两条路逐行对 `// 预期输出:`。
    /// </summary>
    public static partial class 综合自检C
    {
        // ================= R1-6 批 2:图形输入与时钟 =================

        /// <summary>
        /// 一段最小的即时模式事件循环:**先收事件、再刷新**(帧边界就是 `刷新()`),收不到就停不下来 ——
        /// 所以它必须配一份事件脚本跑,脚本跑满帧数之后那个关窗请求就是它的出口。
        /// 每收到一条真事件打 5 行:`当前帧号 / 类型 / 键码 / x / y`。
        /// </summary>
        private const string 事件循环源 =
            "整数 类型 = 0;\n整数 键码 = 0;\n整数 mx = 0;\n整数 my = 0;\n整数 帧 = 0;\n" +
            "如果 (打开窗口(\"脚本\", 200, 120))\n{\n" +
            "    逻辑 收手 = 假;\n" +
            "    当 (!收手)\n    {\n" +
            "        当 (取事件(类型, 键码, mx, my))\n        {\n" +
            "            如果 (类型 == 1) { 收手 = 真; }\n" +
            "            否则\n            {\n" +
            "                测试输出(帧);\n                测试输出(类型);\n                测试输出(键码);\n" +
            "                测试输出(mx);\n                测试输出(my);\n            }\n        }\n" +
            "        如果 (!收手)\n        {\n            刷新();\n            帧 = 帧 + 1;\n        }\n    }\n" +
            "    测试输出(帧);\n}\n停止\n";

        /// <summary> 上面那段程序配这份脚本跑出来的输出(帧 0/1/2 各一条事件,第 3 帧开始投关窗请求) </summary>
        private static readonly string 事件循环脚本文本 =
            "帧数 3\n" +
            "# 注释行不算(`//` 也行)\n" +
            "帧 0 按键 回车\n" +
            "帧 1 移动 7 8\n" +
            "帧 2 按下 鼠标右键 3 4\n" +
            "帧 2 抬起 鼠标右键 3 4   // 行尾注释\n";

        private const string 事件循环期望 =
            "打开窗口 标题=\"脚本\" 宽=200 高=120\n" +
            "0\n2\n13\n0\n0\n" +
            "刷新 命令=0\n" +
            "1\n3\n0\n7\n8\n" +
            "刷新 命令=0\n" +
            "2\n4\n3\n3\n4\n2\n5\n3\n3\n4\n" +
            "刷新 命令=0\n" +
            "3";

        /// <summary>
        /// 挂无头呈现 + 一份事件脚本,真跑一段源码;跑完给(程序输出, 已呈现帧数, 攒着没刷的命令, 剩事件)。
        /// 与 `跑图形源码` 的区别:这一份多一个**脚本**参数(就是"喂一份固定输入"那条路)。
        /// </summary>
        private static (string 输出, int 帧, int 攒着, int 剩事件) 跑脚本源码(string 源码, 事件脚本C? 脚本, bool 优化 = true)
        {
            var 缓冲 = new StringBuilder();
            var 解码 = new 文字输出C(t => 缓冲.Append(t));
            var 编译结果 = new 汇编器C().汇编多文件带调试([("主程序.hb", 源码)], 优化);
            var vm = new 虚拟机C
            {
                输入源 = () => null,
                输出目标 = 解码.写,
                宿主调用 = 宿主能力C.处理,
                初值表 = 编译结果.初值表,
                // 行号:宿主抛的"帧数护栏"那个运行期错误要靠它才带得上源码行(与 `hbcc --run` 同一套)
                取源行号 = 地址 => 执行行映射C.查源行(编译结果.调试文件表, 地址),
            };
            图形宿主C.清空();
            图形宿主C.挂上(new 无头呈现C(new StringWriter(缓冲) { NewLine = "\n" }));
            try
            {
                图形宿主C.挂事件脚本(脚本);
                vm.运行(编译结果.机器码);
                解码.收尾();
                return (缓冲.ToString().Replace("\r\n", "\n").TrimEnd('\n'),
                        图形宿主C.已呈现帧数, 图形宿主C.待刷新命令().Length, 图形宿主C.事件数);
            }
            finally { 图形宿主C.摘掉(); }
        }

        private static void 图形输入与时钟自检()
        {
            // ---- ① 键码表:编号是对外接口(帮助站点抄的就是它),钉死 ----
            try
            {
                bool 编号对 = 图形键C.回车 == 13 && 图形键C.退出 == 27 && 图形键C.空格 == 32
                    && 图形键C.退格 == 8 && 图形键C.制表 == 9
                    && 图形键C.上档 == 16 && 图形键C.控制 == 17 && 图形键C.替换 == 18
                    && 图形键C.左 == 37 && 图形键C.上 == 38 && 图形键C.右 == 39 && 图形键C.下 == 40
                    && 图形键C.首页 == 36 && 图形键C.末页 == 35 && 图形键C.上一页 == 33 && 图形键C.下一页 == 34
                    && 图形键C.插入 == 45 && 图形键C.删除 == 46
                    && 图形键C.鼠标左键 == 1 && 图形键C.鼠标中键 == 2 && 图形键C.鼠标右键 == 3
                    && 图形键C.字母最小 == 'A' && 图形键C.字母最大 == 'Z'
                    && 图形键C.数字最小 == '0' && 图形键C.数字最大 == '9'
                    && 图形键C.功能键(1) == 112 && 图形键C.功能键(12) == 123;
                记录("图形输入 键码表:编辑键 / 方向键取老虚拟键编号,字母数字取 ASCII,F1~F12 = 112~123",
                    编号对, $"回车 {图形键C.回车} / 退出 {图形键C.退出} / 左 {图形键C.左} / 字母A {(int)'A'} / F1 {图形键C.功能键(1)}");
            }
            catch (Exception ex) { 记录异常("图形输入 键码表", ex); }

            // ---- ② 键名的认与念:脚本里能写名字,报错文案里能念出名字 ----
            try
            {
                (string 词, int 码)[] 该认 =
                [
                    ("回车", 13), ("enter", 13), ("空格", 32), ("空格", 32),
                    ("字母A", 65), ("letterb", 66), ("a", 65), ("数字5", 53), ("digit9", 57),
                    ("F3", 114), ("f12", 123), ("鼠标左键", 1), ("mouseleft", 1),
                    ("0x0D", 13), ("13", 13), ("退出", 27), ("esc", 27), ("左", 37),
                ];
                var 不认 = 该认.Where(x => !图形键C.认键名(x.词, out int 码) || 码 != x.码).ToArray();
                // 有意为之:裸数字当**键码**,不当"数字键"(要写 `数字5`)
                bool 裸数字不成键 = !图形键C.认键名("5", out int 五) || 五 == 5;
                bool 怪词不认 = !图形键C.认键名("阿猫", out _) && !图形键C.认键名("字母α", out _);
                记录("图形输入 认键名:中文 / 英文别名 / 字母A / 数字5 / F3 / 裸数字(十进制与 0x)都认,怪词不认",
                    不认.Length == 0 && 裸数字不成键 && 怪词不认,
                    不认.Length == 0
                        ? $"认了 {该认.Length} 个写法;裸数字 5 = 键码 5(数字键要写 `数字5`)"
                        : "认不出或认错: " + string.Join(", ", 不认.Select(x => x.词)));
                记录("图形输入 键码念得出来(报错文案与诊断看它:回车 / 字母A / 数字5 / F3 / 鼠标左键)",
                    图形键C.名字(13) == "回车" && 图形键C.名字(65) == "字母A" && 图形键C.名字(53) == "数字5"
                    && 图形键C.名字(114) == "F3" && 图形键C.名字(1) == "鼠标左键" && 图形键C.名字(999) == ""
                    && 图形键C.一句话(999) == "999",
                    "回车/字母A/数字5/F3/鼠标左键 都念得出来;认不出给空串,`一句话` 退成十进制数");
            }
            catch (Exception ex) { 记录异常("图形输入 认键名", ex); }

            // ---- ③ 事件类型:五种,中英两侧都认 ----
            try
            {
                bool 编号对 = 图形事件C.关窗 == 1 && 图形事件C.按键 == 2 && 图形事件C.移动 == 3
                    && 图形事件C.按下 == 4 && 图形事件C.抬起 == 5;
                bool 中英都认 = 图形事件C.认事件名("关窗", out int 关) && 关 == 1
                    && 图形事件C.认事件名("close", out int 关2) && 关2 == 1
                    && 图形事件C.认事件名("按键", out _) && 图形事件C.认事件名("key", out _)
                    && 图形事件C.认事件名("移动", out _) && 图形事件C.认事件名("move", out _)
                    && 图形事件C.认事件名("按下", out _) && 图形事件C.认事件名("down", out _)
                    && 图形事件C.认事件名("抬起", out _) && 图形事件C.认事件名("mouseup", out _)
                    && !图形事件C.认事件名("挥手", out _);
                记录("图形输入 事件类型 1 关窗 / 2 按键 / 3 移动 / 4 按下 / 5 抬起(中英两侧都认,怪词不认)",
                    编号对 && 中英都认 && 图形事件C.名字(5) == "抬起",
                    $"编号 1~5;认得出 关窗/按键/移动/按下/抬起 与 close/key/move/down/mouseup;`抬起` 是新加的那一条(点击 = 按下 + 抬起)");
            }
            catch (Exception ex) { 记录异常("图形输入 事件类型", ex); }

            // ---- ④ 事件脚本解析:注释 / 空行 / 中英混写 / 每帧分组 ----
            try
            {
                var 脚本 = 事件脚本C.解析(事件循环脚本文本);
                bool 分组对 = 脚本.帧数 == 3 && 脚本.事件表.Count == 4
                    && 脚本.取第几帧(0).Length == 1 && 脚本.取第几帧(1).Length == 1
                    && 脚本.取第几帧(2).Length == 2 && 脚本.取第几帧(3).Length == 0;
                var 按键那条 = 脚本.取第几帧(0)[0];
                var 抬起那条 = 脚本.取第几帧(2)[1];
                bool 字段对 = 按键那条.类型 == 图形事件C.按键 && 按键那条.键码 == 图形键C.回车
                    && 按键那条.x == 0 && 按键那条.y == 0
                    && 抬起那条.类型 == 图形事件C.抬起 && 抬起那条.键码 == 图形键C.鼠标右键
                    && 抬起那条.x == 3 && 抬起那条.y == 4;
                var 混写 = 事件脚本C.解析("帧数 1\nframe 0 key enter\n");
                bool 英文也认 = 混写.帧数 == 1 && 混写.事件表.Count == 1 && 混写.事件表[0].键码 == 图形键C.回车;
                记录("图形输入 事件脚本能解析(注释 / 行尾注释 / 空行 / 中英混写 / 按帧分组 / 字段逐个对上)",
                    分组对 && 字段对 && 英文也认,
                    $"帧数 {脚本.帧数};4 条事件分成 {string.Join("/", Enumerable.Range(0, 3).Select(i => 脚本.取第几帧(i).Length))} 条;" +
                    $"第 2 帧第 2 条 = 抬起 鼠标右键 (3,4);{脚本.一句话()}");
            }
            catch (Exception ex) { 记录异常("图形输入 事件脚本解析", ex); }

            // ---- ⑤ 脚本写错了:带行号 + 说人话 + 给改法(一条不落) ----
            try
            {
                期望异常("图形输入 脚本报错 认不出的事件类型(带行号 + 列出五种写法)",
                    () => 事件脚本C.解析("帧数 1\n帧 0 挥手 1\n"), "事件脚本 第 2 行", "认不出这个事件类型", "关窗");
                期望异常("图形输入 脚本报错 认不出的键名(说清能写名字也能写数字)",
                    () => 事件脚本C.解析("帧数 1\n帧 0 按键 阿猫\n"), "事件脚本 第 2 行", "认不出这个键名", "回车");
                期望异常("图形输入 脚本报错 帧号不小于帧数(那一帧永远不会到)",
                    () => 事件脚本C.解析("帧数 1\n帧 2 按键 回车\n"), "永远不会到", "把 `帧数` 改大");
                期望异常("图形输入 脚本报错 少一行帧数(不写就不知道跑满多少帧)",
                    () => 事件脚本C.解析("帧 0 按键 回车\n"), "帧数", "跑满");
                期望异常("图形输入 脚本报错 关窗后面不用跟参数(参数个数逐条点名)",
                    () => 事件脚本C.解析("帧数 2\n帧 0 关窗 1\n"), "事件脚本 第 2 行", "不用跟参数");
                期望异常("图形输入 脚本报错 按下要键码 + 两个坐标(少一个就点名)",
                    () => 事件脚本C.解析("帧数 2\n帧 0 按下 鼠标左键 10\n"), "事件脚本 第 2 行", "要键码 + 两个坐标");
                期望异常("图形输入 脚本报错 认不出的行(说清每行该写成什么)",
                    () => 事件脚本C.解析("帧数 2\n跑快点\n"), "事件脚本 第 2 行", "认不出这一行", "帧数 N");
            }
            catch (Exception ex) { 记录异常("图形输入 脚本报错", ex); }

            // ---- ⑥ 事件泵:第 k 帧的事件在第 k 帧开始时进队列;跑满 N 帧投关窗请求 ----
            try
            {
                var 脚本 = 事件脚本C.解析(事件循环脚本文本);
                var 跑 = 跑脚本源码(事件循环源, 脚本);
                bool 过 = 跑.输出 == 事件循环期望 && 跑.帧 == 3 && 跑.剩事件 == 0 && 跑.攒着 == 0;
                记录("图形输入 事件泵:第 k 帧的事件在第 k 帧开始时投,脚本跑满 N 帧后投关窗请求(事件一条不落)",
                    过, 过 ? $"帧数 {跑.帧}(脚本写的 3);23 行输出逐行对上:{跑.输出.Replace("\n", "|")}"
                          : $"实际=<{跑.输出.Replace("\n", "|")}> 帧={跑.帧} 剩事件={跑.剩事件} 攒着={跑.攒着}");
            }
            catch (Exception ex) { 记录异常("图形输入 事件泵", ex); }

            // ---- ⑦ 关窗请求只在"跑满帧数之后"投(拿一段只刷新的程序直接问队列) ----
            try
            {
                const string 只刷新源 =
                    "整数 类型 = 0;\n整数 键码 = 0;\n整数 mx = 0;\n整数 my = 0;\n整数 i = 0;\n" +
                    "如果 (打开窗口(\"关窗请求\", 100, 80))\n{\n" +
                    "    当 (i < 2)\n    {\n        刷新();\n        i = i + 1;\n    }\n" +
                    "    如果 (取事件(类型, 键码, mx, my)) { 测试输出(类型); } 否则 { 测试输出(-1); }\n}\n停止\n";
                var 两次前 = 跑脚本源码(只刷新源, 事件脚本C.解析("帧数 2\n"));
                var 一次过 = 跑脚本源码(只刷新源, null);
                bool 过 = 两次前.输出 == "打开窗口 标题=\"关窗请求\" 宽=100 高=80\n刷新 命令=0\n刷新 命令=0\n1"
                    && 两次前.帧 == 2 && 两次前.剩事件 == 0
                    && 一次过.输出 == "打开窗口 标题=\"关窗请求\" 宽=100 高=80\n刷新 命令=0\n刷新 命令=0\n-1";
                记录("图形输入 跑满 2 帧才投关窗请求(第 2 帧之前取事件一直是假;没挂脚本就一个事件都不投)",
                    过, $"有脚本=<{两次前.输出.Replace("\n", "|")}> 没脚本=<{一次过.输出.Replace("\n", "|")}>");
            }
            catch (Exception ex) { 记录异常("图形输入 关窗请求", ex); }

            // ---- ⑧ 程序不理关窗请求 ⇒ 带行号的运行期错误(不许默默转下去) ----
            try
            {
                const string 不停源 =
                    "如果 (打开窗口(\"不停\", 100, 80))\n{\n    当 (真)\n    {\n        刷新();\n    }\n}\n停止\n";
                string 文案 = "";
                int 行号 = 0;
                try { 跑脚本源码(不停源, 事件脚本C.解析("帧数 2\n")); }
                catch (运行期错误C 错) { 文案 = 错.说明; 行号 = 错.源码行; }
                // 帧数 2 + 宽限 4 ⇒ 第 7 次刷新(第 7 帧)起报错;行号指向那条 `刷新();`(源码第 5 行)
                bool 过 = 文案.Contains("事件脚本说跑满 2 帧") && 文案.Contains("关窗请求") && 行号 == 5;
                记录("图形输入 程序不理关窗请求 ⇒ 第 帧数+4 帧起报带行号的运行期错误(说了是怎么绕、行号指 `刷新()`)",
                    过, 过 ? $"行号 {行号}:{文案}" : $"行号={行号} 说明=<{文案}>");
            }
            catch (Exception ex) { 记录异常("图形输入 帧数护栏", ex); }

            // ---- ⑨ 确定性:同一份源码 + 同一份脚本两次跑逐字节一致(优化开/关也一致) ----
            try
            {
                var 脚本 = 事件脚本C.解析(事件循环脚本文本);
                var 一 = 跑脚本源码(事件循环源, 脚本);
                var 二 = 跑脚本源码(事件循环源, 脚本);
                var 三 = 跑脚本源码(事件循环源, 脚本, 优化: false);
                记录("图形输入 同一脚本同一源码两次跑逐字节一致(优化开/关也一致 —— 事件脚本是可复现的输入)",
                    一.输出 == 二.输出 && 一.输出 == 三.输出 && 一.帧 == 二.帧 && 一.帧 == 三.帧,
                    $"两次输出 {一.输出.Length} 字逐字节相同;优化关那一遍也一样(帧数 {一.帧}/{二.帧}/{三.帧})");
            }
            catch (Exception ex) { 记录异常("图形输入 确定性双跑", ex); }

            // ---- ⑩ 桌面壳那层隔离:框架的键先译成 HB 键码再投(开不了窗 ⇒ 按源码钉) ----
            try
            {
                string? 根 = 找仓库根目录();
                if (根 == null) 跳过("图形输入 桌面壳把 Avalonia 的键 / 鼠标键译成 HB 键码再投(开不了窗,按源码钉)",
                    "找不到仓库根(不在工作副本里跑)");
                else
                {
                    string 壳 = File.ReadAllText(Path.Combine(根, "图形宿主", "桌面壳C.cs"));
                    bool 译了 = 壳.Contains("译键码") && 壳.Contains("图形键C.") && 壳.Contains("Key.A")
                        && 壳.Contains("图形键C.字母最小 + (键 - Key.A)")
                        && 壳.Contains("图形键C.功能键(键 - Key.F1 + 1)")
                        && !壳.Contains("(int)e.Key") && !壳.Contains("(int)e.GetCurrentPoint");
                    bool 抬起接了 = 壳.Contains("PointerReleased") && 壳.Contains("图形事件C.抬起")
                        && 壳.Contains("图形事件C.关窗") && 壳.Contains("图形事件C.按键");
                    记录("图形输入 桌面壳把 Avalonia 的键 / 鼠标键译成 HB 键码再投(不再把框架枚举值当对外接口)",
                        译了 && 抬起接了,
                        $"译键码 + 字母/数字/F 三族算术翻 + 鼠标抬起接线:{译了 && 抬起接了};" +
                        $"框架枚举值直投的写法 {(壳.Contains("(int)e.Key") ? "还在" : "一处不剩")}");
                }
            }
            catch (Exception ex) { 记录异常("图形输入 桌面壳键码", ex); }

            // ---- ⑪ 独立小工程的文件清单 + "跨程序集的运行期错误"这个判据(六端闸门抓到过的那两处) ----
            try
            {
                bool 判据对 = 运行期错误C.是运行期错误(new 运行期错误C("试"))
                    && !运行期错误C.是运行期错误(new IOException("试"))
                    && !运行期错误C.是运行期错误(new InvalidOperationException("试"));
                string? 根 = 找仓库根目录();
                if (根 == null)
                    跳过("图形输入 图形宿主的文件清单齐全 + 运行期错误跨程序集判得出来(六端闸门抓到的那两处)",
                        "找不到仓库根(不在工作副本里跑)");
                else
                {
                    // `图形宿主` 是独立小工程(不引用 引擎库):新加一份能力层文件而忘了列进 csproj ⇒ 这个端编不过。
                    // 六端闸门确实抓到过(批 2 实测),这儿补一条机检,免得下次还靠闸门才发现。
                    string 工程 = File.ReadAllText(Path.Combine(根, "图形宿主", "图形宿主.csproj"));
                    bool 链全 = 工程.Contains(@"..\引擎\图形宿主C.cs") && 工程.Contains(@"..\引擎\图形事件C.cs")
                        && 工程.Contains(@"..\引擎\运行期错误C.cs");
                    // T26:各端各编一份 `运行期错误C`(`图形宿主.dll` 那份是 HB宿主 也吃的唯一一份),所以
                    // 两处宿主处理必须按类型名判(否则护栏被兜底吞掉)
                    string 宿主 = File.ReadAllText(Path.Combine(根, "引擎", "宿主能力C.cs"));
                    string 图形宿主 = File.ReadAllText(Path.Combine(根, "引擎", "图形宿主C.cs"));
                    bool 都按名判 = 宿主.Contains("运行期错误C.是运行期错误(错)")
                        && 图形宿主.Contains("运行期错误C.是运行期错误(错)");
                    记录("图形输入 图形宿主的文件清单齐全 + 宿主侧的运行期错误跨程序集也判得出来(按类型名判,六端闸门抓到的那两处)",
                        判据对 && 链全 && 都按名判,
                        $"判据:{判据对};图形宿主.csproj 链了 3 份引擎文件:{链全};两处宿主处理按名判:{都按名判}");
                }
            }
            catch (Exception ex) { 记录异常("图形输入 独立小工程与跨程序集判据", ex); }

            // ---- ⑫ 标准工程 示例15_事件循环:自检这条路(工程目录里的 `事件脚本.txt` 自动喂) ----
            try
            {
                string? 根 = 找示例目录();
                string? 文件 = 根 == null ? null : Path.Combine(根, "中间层", "示例15_事件循环", "主程序.hb");
                if (文件 == null || !File.Exists(文件))
                {
                    跳过("图形输入 标准工程 示例15 逐行对预期输出(事件脚本自动喂)", $"找不到 {文件 ?? "Sample 目录"}");
                    跳过("图形输入 CLI --事件脚本 逐行对预期输出", "找不到标准工程");
                }
                else
                {
                    string[] 行表 = File.ReadAllLines(文件);
                    var 期望 = 解析预期输出(行表);
                    string 目录 = Path.GetDirectoryName(文件)!;
                    var (_, 输出) = 运行带输出(string.Join("\n", 行表), 目录, 示例堆大小(目录));
                    string 实际 = 输出.Replace("\r\n", "\n").TrimEnd('\n');
                    string 应有 = string.Join("\n", 期望);
                    记录("图形输入 标准工程 示例15 逐行对预期输出(工程目录里的 `事件脚本.txt` 被自动喂进去)",
                        实际 == 应有 && 期望.Count > 0,
                        实际 == 应有 ? $"{期望.Count} 行逐字对上(4 帧 / 5 条事件 / 收关窗请求收手)"
                                      : $"实际=<{截断(实际, 200)}> 期望=<{截断(应有, 200)}>");

                    string? 编译器 = 找命令行编译器();
                    if (编译器 == null)
                        跳过("图形输入 CLI --事件脚本 逐行对预期输出", "找不到 hbcc.dll(在 IDE 里跑自检时正常)");
                    else
                    {
                        var (码, 出, 误) = 跑命令行(编译器, 目录, 120_000, "主程序.hb", "--run", "--无头", "--事件脚本", "事件脚本.txt");
                        string 规范出 = 出.Replace("\r\n", "\n");
                        bool 过 = 码 == 0 && 规范出.Contains(应有, StringComparison.Ordinal);
                        记录("图形输入 CLI --事件脚本 逐行对预期输出(命令行那条路与自检同一种喂法)",
                            过, 过 ? $"退出码 0;{期望.Count} 行一行不落" : $"退出码 {码};{截断(误 + 出, 200)}");
                    }
                }
            }
            catch (Exception ex) { 记录异常("图形输入 标准工程与技术", ex); }
        }
