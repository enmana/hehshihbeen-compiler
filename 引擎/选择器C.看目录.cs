// 选择器C.看目录 —— `选择器C` 里**唯一依赖"工程文件"那一层**的一段,单独一个文件。
//
// 为什么要拆(2026-10-11,H92):
//   `HB宿主` 也要用 `选择器C` —— 它的 `宿主能力C.处理选文件`(功能号 83/84)先问
//   **挂着的平台选择器**(手机端 SAF),没挂才落回桌面系统对话框。
//   而 `HB宿主.csproj` 是**逐个列文件**的(`EnableDefaultCompileItems=false`)。
//   把 `看目录` 留在 `选择器C.cs` 里,链它就会顺着
//     `看目录` → `工程文件C.找工程文件` → `中间层C.默认堆大小…`
//   一路拖进**整个中间层** —— 而 `HB宿主` 的立身之本就是"不带编译器"(见它 csproj 的头注释)。
//   ⇒ 按依赖面切开:这个文件**只给带编译器的端**(引擎库 / CLI / WPF / MobileIDE)编;
//     `HB宿主` 只链 `选择器C.cs`(口子 + 同步版 + 摘要,纯 System.*)。
//   同一个格局的先例:`虚拟路径C` / `虚拟文件C` 那一对、`跑程序协议C` / `跑程序后端C` 那一对。
//
// ⚠ 往 `选择器C` 里加新方法时先问一句:**它要不要 `工程文件C` / `中间层C`?**
//   要 ⇒ 放这个文件;不要 ⇒ 放 `选择器C.cs`(否则 HB宿主 又编不过)。
// ============================================================

using System;

namespace hehshihbeen_compiler
{
    /// <summary> 看一眼"这个目录能不能当工程目录用"(D4:手机端挑完目录要立刻知道能不能开工) </summary>
    public readonly record struct 目录检查C(bool 可用, string 工程文件, string 说明);

    public static partial class 选择器C
    {
        /// <summary>
        /// 看一眼这个目录能不能当工程目录:有 `.hbp` → 直接能开工程;只有 `.hb` → 也能用(按老约定扫目录);
        /// 什么都没有 → 说清楚(免得手机端挑完目录一片空白,不知道下一步干嘛)。
        /// </summary>
        public static 目录检查C 看目录(string? 目录)
        {
            string d = (目录 ?? "").Trim();
            if (d.Length == 0) return new 目录检查C(false, "", "没有选目录");
            try
            {
                // 手机端「打开工程目录…」挑回来的是 SAF 的 `内容://…` **虚拟路径**(H64)。
                // 这一处原来拿真文件系统的 `Directory.Exists` / `Directory.EnumerateFiles` 去认 ⇒
                // **真机上挑中了也一律报"这个路径不是目录"**(第329批真机核对抓到的漏改)。
                // 判据一律走 `虚拟文件C`:虚拟路径走挂着的实现,真路径照旧走真盘(桌面 / 命令行一字不变)。
                if (!虚拟文件C.是目录(d)) return new 目录检查C(false, "", "这个路径不是目录(或者手机没给它访问权限)");
                string? 工程 = 工程文件C.找工程文件(d);
                if (工程 != null) return new 目录检查C(true, 工程, $"找到工程文件:{虚拟路径C.文件名(工程)}");
                bool 有源文件 = 虚拟文件C.列文件(d, ".hb").Count > 0;
                return 有源文件
                    ? new 目录检查C(true, "", "目录里没有 .hbp,但有 .hb 源文件(按『目录里所有 .hb 一起编译』来用)")
                    : new 目录检查C(false, "", "这个目录里既没有 .hbp 工程文件,也没有 .hb 源文件");
            }
            catch (Exception ex)
            {
                return new 目录检查C(false, "", $"看不了这个目录:{ex.Message}");
            }
        }
    }
}
