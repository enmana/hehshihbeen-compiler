        /// <summary>
        /// H13:**热重载** —— 把刚编出来的新机器码换进这台**正跑着的**虚拟机,并尽量把运行期数据带过去。
        ///
        /// **"旧那一份"的口径(踩过一次,别改回去)**:整条路一眼都不看"调用方什么时候挂的表" ——
        /// 旧值一律**按旧名字表里的槽标签从这台机器的内存里现读**(`读槽值`),旧地址就是**这台机器**
        /// 的 `标签表`(它只会在 `装载` / 重载收尾那一刻换新)。为什么不按"调用方什么时候设的标签表"判:
        /// 界面上装载 / 重载与"换表"是两个动作,`跨进程虚拟机C` 的子进程那一侧还会在装载之后再换一次表
        /// (实测:那样判出来旧标签是空的,一个变量都保不住)。
        ///
        /// **保住什么**:
        /// <list type="bullet">
        /// <item>**顶层 / 全局变量槽** —— 槽标签同名、宽度相同、而且**相对位置没挪**(见下面那段注释)
        ///   的那些,按字节搬过去;</item>
        /// <item>**字符串池** —— 这一块装的是源码里的字面量,从程序开头就是那些内容;位置、大小都没变才搬
        ///   (它在静态数据段里,代码一长一短它就跟着挪);</item>
        /// <item>**堆**:一律不保。堆里的东西全是地址,而地址在重载这一刻没有稳定含义
        ///   (调用栈与寄存器都清了、PC 回到程序开头),硬搬只会留下"指向半个对象"的野指针。
        ///   程序回到开头重跑时,`申请` 那一套会把空闲表自己重新铺一遍(它在程序开头跑)。</item>
        /// </list>
        ///
        /// **保不住 / 本来就不带过来的**:寄存器、调用栈(硬件栈与软栈)、堆里的对象、列表与字符串变量
        /// 里那些指向堆的指针(它们指向的格子在这一次重载之后是空的)。
        ///
        /// **重载之后程序从开头重跑**(PC = 0、寄存器全 0),而 `初值表` 也换成新那一份
        /// (与"编译完重新装载"同一套口径:初值就是新程序的一部分)。所以"顶层计数器保住"这件事的证据
        /// 是**重载那一刻**那一格里的值,不是重跑之后的值。
        /// </summary>
        /// <param name="旧名字表">上一次装载时的名字表(**槽标签 / 宽度 / 是不是全局**都从它来;
        /// 界面上 `名字表` 这一格不会被新那一份顶掉,所以不给就用 `_装载时名字表`)</param>
        /// <param name="旧初值表">上一次的初值表(常量槽按它恢复成出厂值)</param>
        /// <param name="旧分区表">上一次的隐藏区(池的地址与大小靠它)</param>
        /// <param name="判好的迁移">已经判好的迁移表(子进程那条腿先判、再发给前端、再拿它执行这一侧;
        /// 给了它就不再判第二遍 —— 这正是"判据只有一处"的落点)</param>
        /// <param name="新名字表">**新那一份**的名字表(不给就按现在这一份 `名字表` 判)</param>
        /// <param name="新代码字节数">新那一份的**代码段字节数**(`汇编调试结果C.代码字节数`)。
        /// 为什么要它:机器码那个数组是"代码段 + 数据段"拼起来的,数据段后面还有池 / 堆 ——
        /// 拿 `机器码.Length` 当代码段末尾会把**排在数据段里的整批变量**判成"压在代码段里"(踩过两次,
        /// 见 `任务清单.md` 第324批)。这个数只有编译器知道,必须由调用方带进来;
        /// 不给(-1)时这条判据不参与(宁可少保一只,也不许按错地址乱搬)。</param>
        public virtual void 重载(byte[] 机器码, IReadOnlyList<初值项C>? 旧初值表 = null, 名字表C? 旧名字表 = null,
            IReadOnlyList<内存分区C>? 旧分区表 = null, 重载迁移C? 判好的迁移 = null, 名字表C? 新名字表 = null,
            int 新代码字节数 = -1, IReadOnlyDictionary<string, int>? 新标签表 = null,
            IReadOnlyList<内存分区C>? 新分区表 = null)
        {
            ArgumentNullException.ThrowIfNull(机器码);
            if (机器码.Length > 内存大小)
                throw new ArgumentException($"机器码 {机器码.Length} 字节装不进这台虚拟机的内存({内存大小} 字节):把工程文件里的 `内存` 调大,或把程序拆小一点");

            // H39:子进程那一侧要**先把迁移表发给前端**(前端照它重摆镜像),所以它自己判完就交给这里执行 ——
            // 同一次重载里绝不许判两遍(两边各判一遍必然分叉)。
