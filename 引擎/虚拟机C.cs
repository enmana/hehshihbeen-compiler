        /// <summary>
        /// 这台虚拟机上**现在装的这一份**,还要不要重新装载(判据只有这一处,界面别自己另拼一套)?
        /// <list type="bullet">
        /// <item>**上一轮已经停机** → 要。程序跑完了,不重装就会"停在停机那一条指令上,一条指令都没跑" ——
