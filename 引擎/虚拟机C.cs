        /// <summary>
        /// **通用化(2026-10):硬件浮点的位模式 ↔ 单精度值**。
        /// <para>
        /// 口径与 `Sample\库\float32.hb` **完全一致** —— 一个浮点值就是寄存器里那 32 位 IEEE754 单精度位模式
        /// (那个库一直把它放在 `无符号整数` 里算)⇒ 硬件指令与软件库**可以互换、可以混用**。
        /// </para>
        /// <para>
        /// 为什么可以放心用平台的 `float`:C# 的 `float` 与 C 的 `float` 都是 IEEE754 单精度、
        /// 加减乘除开方都要求**正确舍入** ⇒ 两边逐位一致(这是 C 后端能对拍过的前提)。
        /// **唯一要守的规矩:不许重排浮点表达式**(浮点不满足结合律,换个顺序位模式就变了)。
        /// </para>
        /// </summary>
        private static float 位转浮(uint 位) => BitConverter.UInt32BitsToSingle(位);

        /// <inheritdoc cref="位转浮"/>
        private static uint 浮转位(float 值) => BitConverter.SingleToUInt32Bits(值);

        /// <summary>
        /// **这条位模式是不是非数**(指数全 1 且尾数非 0)。批 1 的 `浮点最大值` / `浮点最小值` 靠它判“要不要把这一边原样交出去”。
        /// <para>
        /// 为什么不用 `float.IsNaN`:这里要的是**位级**判断 —— 与 C 侧那几行逐字对称(那边也是 `(位 & 0x7F800000) == 0x7F800000 && (位 & 0x007FFFFF) != 0`),
        /// 而“非数的位模式”两边各写各的就会分叉(对拍判据是逐字节一致)。
        /// </para>
        /// </summary>
        private static bool 是浮点非数(uint 位) => (位 & 0x7F800000u) == 0x7F800000u && (位 & 0x007FFFFFu) != 0u;

        /// <summary>
        /// **朝 −∞ 取整**(批 1 的 `浮点向下取整` 的实现;位级算法,不用 `MathF.Floor`)。
        /// <para>
        /// 口径(与 `.NET` 的 `MathF.Floor` 逐位对拍定死,见 `ISA扩容落地台账.md` §6.5):
        /// `-0` 保号;`±∞` 与非数**原样返回**;`0.5 → +0`、`-0.5 → -1`;已经是整数的原样不动。
        /// </para>
        /// <para>
        /// 算法:`|值| < 1` 那一档显式分流(负数一律 `-1.0`,`-0` 单独保号);`|值| ≥ 1` 时清掉二进制小数点以下的尾数位得到向零截断值,
        /// **只有“负 + 原本还有小数位”才减 1.0** —— 减完不会下溢成零(`舍入值 ≥ 1.0`),所以不用碰指数。
        /// </para>
        /// </summary>
        private static uint 浮点向下取整位(uint 位)
        {
            uint 指数 = (位 >> 23) & 0xFFu;
            if (指数 == 0xFFu) return 位;                                  // ±∞ / 非数:原样
            bool 负数 = (位 & 0x80000000u) != 0u;
            if (指数 == 0u) return 负数 ? 位 : 0u;                          // 非规格化 / ±0:`-0` 与负数保号,正数给 +0
            int 移 = (int)指数 - 127;                                       // 二进制小数点在尾数里的位置
            if (移 < 0) return 负数 ? 0xBF800000u : 0u;                     // |值| < 1:负数给 -1.0,正数给 +0
            if (移 >= 23) return 位;                                        // 已经是整数
            uint 尾数 = 位 & 0x007FFFFFu;
            uint 分数掩码 = (1u << (23 - 移)) - 1u;
            if ((尾数 & 分数掩码) == 0u) return 位;                          // 已经是整数(小数位全 0)
            uint 截断 = 位 & ~分数掩码;                                      // 向零截断
            return 负数 ? 浮转位(位转浮(截断) - 1.0f) : 截断;
        }
        /// <summary>
        /// 4 位关系码判成立(批 3 的 `条件移动` / `比较并条件移动` 用)。
        /// 码的含义与 `比较取值`(0x2F)那张关系码表**同一份**:低 3 位是关系 —— `0 == / 1 != / 2 > / 3 < / 4 >= / 5 <=`,第 3 位(值 8)= 按有符号比。
        /// </summary>
        private static bool 关系成立(uint 码, uint 甲, uint 乙)
        {
            bool 有符号 = (码 & 8u) != 0u;
            int 左 = 有符号 ? (int)甲 : 0, 右 = 有符号 ? (int)乙 : 0;
            int 比 = 有符号 ? 左.CompareTo(右) : 甲.CompareTo(乙);
            return (码 & 7u) switch
            {
                0u => 比 == 0,
                1u => 比 != 0,
                2u => 比 > 0,
                3u => 比 < 0,
                4u => 比 >= 0,
                5u => 比 <= 0,
                _ => false,
            };
        }

        /// <summary>
        /// R1-4:`调用寄存器` / `跳转寄存器` 的目标是**算出来的地址**,对齐只能在运行期查。
        /// 与老 `跳转` / `调用` 的编译期检查同一个口径 —— 不对齐就从两条指令中间接着解释,
        /// 机器照跑不误、只是结果全错。报错挂回当前那条指令(PC 还没被改)。
        /// </summary>
        private void 查间接目标对齐(uint 目标, string 指令名)
        {
            if ((目标 & 0x3u) != 0)
                throw 运行期错误($"`{指令名}` 的目标地址没有 4 字节对齐:0x{目标:X}" +
                    "(指令定长 4 字节,从两条指令中间跳过去会解释出乱七八糟的字节;" +
                    "表里装的地址请用 `地址(…)` 取,别在它上面加减零头)");
        }

        /// <summary>
        /// **T11(2026-09-27 评测整改):定长栈(硬件栈)的下界** —— 内存末尾往下留给它的那一块(见 `栈顶保留`)。
        ///
        /// 以前这里只挡 `栈指针 &lt; 4`:从 `0x100000` 一路压下去,要压满 ~1MB 才拦得住,而代码段在地址 0 ——
        /// **压栈早把代码段自己写掉了**,循环指令一没,执行流撞上被清零的字节(`0x00` = HALT)就"正常停机"。
        /// 实测:循环 `入栈 R1` 262140 次 → `PC = 0x38 停机=True SP = 0x38`、程序输出**空**、**退出码 0**,
        /// 而那份程序代码段只有 236 字节。也就是说"写穿了代码与数据"这件事当时是**静默**的。
        ///
        /// 下界与池的硬顶是**同一个数**(`内存大小 − 栈顶保留`),两边口径不会各说各话。
        /// </summary>
        private uint 栈下界 => (uint)Math.Max(0, 内存大小 - 栈顶保留(内存大小));

        private void PushWord(uint value)
        {
            if (栈指针 < 栈下界 + 4)
                throw 运行期错误("栈溢出(压栈次数太多,或者压栈/弹栈没配对 —— 定长栈只占运行内存末尾那一块," +
                    "再往下写就压坏代码与数据了;调用套得太深就把递归改成循环,大数组挪到顶层)");
            栈指针 -= 4;
            内存[栈指针] = (byte)(value & 0xFF);
            内存[栈指针 + 1] = (byte)((value >> 8) & 0xFF);
            内存[栈指针 + 2] = (byte)((value >> 16) & 0xFF);
            内存[栈指针 + 3] = (byte)((value >> 24) & 0xFF);
        }

        private uint PopWord()
        {
            if (栈指针 + 4 > 内存.Length)
                throw 运行期错误("栈为空(压栈/弹栈没配对 —— 检查是不是多写了一次 弹出、少写了一次 压栈)");
            uint value = (uint)(内存[栈指针] | (内存[栈指针 + 1] << 8) | (内存[栈指针 + 2] << 16) | (内存[栈指针 + 3] << 24));
            栈指针 += 4;
            return value;
        }
