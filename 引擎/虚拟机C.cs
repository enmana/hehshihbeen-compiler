        /// </summary>
        public virtual void 同步镜像() { }

        // ---------------- H39-2:给"跑在子进程里"那一侧留的几个口子 ----------------
        // 为什么要放在基类:界面侧(以及调试会话)只认 `虚拟机C` 这一张面孔 —— 有了这几个空实现,
