        {
            var 说明 = new List<string>();
            var 搬 = new List<(int 旧起, int 新起, int 大小)>();
            var 要恢复的常量 = new List<初值项C>();
            byte[] 旧内存 = (byte[])内存.Clone();              // 旧值就地取:下面清场之后就没有了
            var 旧标签 = _装载时标签表;                        // 旧地址:装载那一刻记下的那一份
            var 旧名字 = 旧名字表 ?? _装载时名字表;
            var 旧初值 = 旧初值表 ?? _装载时初值表;
            var 旧区 = 旧分区表 ?? _装载时内存分区;              // 池的位置与大小靠它(旧那一份)
            var 新区 = 新分区表 ?? 内存分区;                     // "新的":调用方传进来那份,或现在就挂着的那份
            var 新标签 = 新标签表 ?? this.标签表;
            var 新名字 = 新名字表 ?? 名字表;
            // 代码段的末尾(判"变量槽是不是压在代码段里"必须用**代码段字节数**:
            // 机器码那个数组带着数据段尾巴、数据段后面还有池/堆,两个都不是代码段末尾 —— 见 `代码字节数` 的注释)
            int 新代码长 = 新代码字节数 >= 0 ? 新代码字节数 : -1;

            // 旧那几张表取过之后就把**新那一份**挂上(下面判的是新布局;旧值早就从 `旧内存` 快照里拍下来了,
            // 换表影响不到它)。判完无论成败都留着新那一份 —— 重载本来就是把机器换成新的那一份。
            标签表 = 新标签;
            名字表 = 新名字;
            内存分区 = 新区;

            // ① 顶层 / 全局变量槽:同名同宽 + **相对位置不变**才搬(常量槽不搬 —— 它按初值表恢复成出厂值)。
            //    为什么要"相对位置"这一条:光看"槽标签同名 + 宽度相同"不够 —— 在中间**插一个新变量**时,
            //    后面那些槽标签还是从 `_v1` 顺着发,可新旧地址错开了一格(`_v2@0x184` 在新布局里已经是
            //    `_v3@0x184`),照搬就把 计数 的值写进了 占用 那一格(实测踩到,见 `任务清单.md` 第324批)。
            //    判据 = 相邻两只匹配上的槽,**地址差与该槽宽度都逐段对得上**(整段线性搬得动才算"布局没动")。
            //    判据(**全有或全无**):把两份的全局槽各自按地址排好,然后**逐只对**——
            //      · 只数一样、槽标签逐只同名、宽度逐只相同、**地址也逐只相同** ⇒ 布局一点没动,整段一起搬;
            //      · 任何一处对不上(加了 / 删了 / 挪了 / 换了类型) ⇒ **一只都不搬**,统一报"布局变了,从 0 重新开始"。
            //    为什么不做"能对上的那几只单独搬":中间插一个新变量时,后面所有槽标签都错开一位
            //    (`_v2@0x184` 在新布局里已经是 `_v3@0x184`),逐只按"同名同宽"搬就会把 计数 的值写进 占用 那一格。
            //    "整段一起"这一条把那个窗口关死,代价是更保守(局部位移一律不保)—— 实测踩到的证据见
            //    `任务清单.md` 第324批。
            int 保住的变量 = 0, 丢掉的变量 = 0, 新变量 = 0;
            var 旧槽们 = 全局槽(旧名字).OrderBy(x => 旧标签.TryGetValue(x.槽, out int a) ? a : int.MaxValue).ToList();
            var 新槽们 = 全局槽(新名字).OrderBy(x => 新标签.TryGetValue(x.槽, out int b) ? b : int.MaxValue).ToList();
            if (新槽们.Count == 0) 新槽们 = [.. 旧槽们];
            var 旧槽序 = 旧槽们.Select(x => (x.槽, x.宽度, 址: 旧标签.TryGetValue(x.槽, out int a1) ? a1 : -1)).ToList();
            var 新槽序 = 新槽们.Select(x => (x.槽, x.宽度, 址: 新标签.TryGetValue(x.槽, out int b1) ? b1 : -1)).ToList();
            bool 布局一致 = 旧槽序.Count == 新槽序.Count;
            if (布局一致)
                for (int i = 0; i < 旧槽序.Count; i++)
                {
                    var 旧槽 = 旧槽序[i]; var 新槽 = 新槽序[i];
                    if (旧槽.槽 != 新槽.槽 || 旧槽.宽度 != 新槽.宽度 || 旧槽.址 < 0 || 新槽.址 < 0 || 旧槽.址 != 新槽.址
                        || (新代码长 > 0 && 新槽.址 < 新代码长) || 新槽.址 + 新槽.宽度 > 内存.Length)
                    { 布局一致 = false; break; }
                }
            if (!布局一致)
            {
                新变量 = Math.Max(0, 新槽序.Count - 旧槽序.Count);
                丢掉的变量 = Math.Max(旧槽序.Count, 新槽序.Count) - 新变量;
                说明.Add("这一次没有可保的顶层变量(旧新两份的全局槽布局对不上:加了 / 删了 / 挪了变量)");
            }
            else
            {
                foreach (var 项 in 新槽序)
                {
                    // 常量槽不搬运行期值(按声明的初值恢复成出厂值)
                    if (是常量槽(旧初值, 项.址, 项.宽度))
                    {
                        说明.Add($"常量 {项.槽} 按声明的初值恢复(不搬运行期值)");
                        continue;
                    }
                    if (项.址 < 0 || 项.址 + 项.宽度 > 旧内存.Length) continue;          // 旧值读不出来:不搬
                    搬.Add((项.址, 项.址, 项.宽度));                                    // 布局一致 ⇒ 旧新地址本就是同一个
                    保住的变量++;
                }
            }
            if (保住的变量 > 0) 说明.Add($"保住 {保住的变量} 个顶层变量的值");
            else 说明.Add("这一次没有可保的顶层变量(要么没有,要么旧新两份的槽位置对不上)");
            if (新变量 > 0) 说明.Add($"有 {新变量} 个顶层变量是这一次新加的,从 0 起步");
            if (丢掉的变量 > 0) 说明.Add($"有 {丢掉的变量} 个全局变量的布局变了(类型宽度变了 / 槽位挪了),它们从 0 重新开始");

            // ② 字符串池:源码里的字面量,内容从程序开头就是那些 —— 位置与大小都没变才搬
            var 旧池 = 找区(旧区, "字符串池");
            var 新池 = 找区(新区, "字符串池");
            if (旧池 is { } 旧池区 && 新池 is { } 新池区)
            {
                if (旧池区.起始 == 新池区.起始 && 旧池区.大小 == 新池区.大小)
                {
                    搬.Add((旧池区.起始, 新池区.起始, 旧池区.大小));
                    说明.Add($"字符串池原地不动({旧池区.大小} 字节),里面的字面量接着用");
                }
                else 说明.Add($"字符串池挪了位置或改了大小(旧 0x{旧池区.起始:X}+{旧池区.大小} → 新 0x{新池区.起始:X}+{新池区.大小}),这一次不保");
            }

            // ③ 堆:一律不保(理由见方法头);说清"哪一块原来装着东西" —— 空的堆不必吓人
            foreach (var 区 in 旧区)
                if (区.区名 == "堆" && 区.大小 > 0 && 堆里有东西(区))
                    说明.Add($"堆里的对象不保(堆 0x{区.起始:X}+{区.大小} 里有用过的数据):重载后程序从开头重跑,要用就重新申请");

            // ④ 真的搬:快照早就拍好了(`旧内存`),这里按新布局重摆,最后盖回要保的那几段
            Array.Clear(内存, 0, 内存.Length);
            Array.Copy(机器码, 内存, 机器码.Length);
            程序包C.应用初值(内存, 初值表);                      // 新的常量初值先落成出厂值
            foreach (var 项 in 旧初值)                             // 旧常量也回出厂值(免得把上一轮算过的值当常量)
            {
                if (项.地址 < 0 || 项.地址 + 项.宽度 > 内存.Length) continue;
                if (是常量槽(初值表, 项.地址, 项.宽度)) continue;  // 新的初值表里有它:上面那一步已经落过了
                要恢复的常量.Add(项);
            }
            程序包C.应用初值(内存, 要恢复的常量);
            foreach (var (旧起, 新起, 大小) in 搬)
            {
                if (大小 <= 0) continue;
                if (旧起 < 0 || 旧起 + 大小 > 旧内存.Length) continue;
                if (新起 < 0 || 新起 + 大小 > 内存.Length) continue;
                Array.Copy(旧内存, 旧起, 内存, 新起, 大小);
            }

            复位执行状态(机器码);
            if (说明.Count == 0) 说明.Add("这一次没有可保的运行期数据");
            上次重载说明 = 说明;
            if (收迁移表 is { } 收)
            {
                收.段.Clear();
                foreach (var 一段 in 搬) 收.段.Add(一段);
                收.旧初值表.Clear();
                foreach (var 项 in 旧初值) 收.旧初值表.Add(项);
                收.说明.Clear();
                foreach (string 一条 in 说明) 收.说明.Add(一条);
            }
        }

        /// <summary>
        /// 把**子进程那一侧**判好的迁移照搬到这一份镜像上(H39:重载的判据只有一处 —— 那边算、这边照贴,
        /// 两边各算一遍就会分叉)。`迁移` 里的地址都是**旧内存 / 新内存各自的绝对地址**。
        /// </summary>
        protected void 按迁移重摆内存(byte[] 新机器码, 重载迁移C 迁移)
        {
            ArgumentNullException.ThrowIfNull(新机器码);
            ArgumentNullException.ThrowIfNull(迁移);
            byte[] 旧内存 = (byte[])内存.Clone();
            Array.Clear(内存, 0, 内存.Length);
            Array.Copy(新机器码, 内存, Math.Min(新机器码.Length, 内存.Length));
            程序包C.应用初值(内存, 初值表);
            var 旧常量 = new List<初值项C>();
            foreach (var 项 in 迁移.旧初值表)
            {
                if (项.地址 < 0 || 项.地址 + 项.宽度 > 内存.Length) continue;
                if (是常量槽(初值表, 项.地址, 项.宽度)) continue;   // 新的初值表里有它:上面那一步已经落过了
                旧常量.Add(项);
            }
            程序包C.应用初值(内存, 旧常量);
            foreach (var (旧起, 新起, 大小) in 迁移.段)
            {
                if (大小 <= 0) continue;
                if (旧起 < 0 || 旧起 + 大小 > 旧内存.Length) continue;
                if (新起 < 0 || 新起 + 大小 > 内存.Length) continue;
                Array.Copy(旧内存, 旧起, 内存, 新起, 大小);
            }
            复位执行状态(新机器码);
            上次重载说明 = [.. 迁移.说明];
        }

        /// <summary> 旧名字表里那些"全局 / 顶层且登记了槽标签"的变量(热重载要搬的那些) </summary>
        private static IEnumerable<名字项C> 全局槽(名字表C? 表) =>
            (表?.变量 ?? []).Where(x => x.是全局 && x.槽.Length > 0);

        /// <summary> 这一格是不是**常量槽**(初值表里有它):常量不搬运行期值,按声明的初值恢复 </summary>
        private static bool 是常量槽(IReadOnlyList<初值项C>? 表, int 地址, int 宽度)
        {
            foreach (var 项 in 表 ?? [])
                if (项.地址 == 地址 && 项.宽度 == 宽度) return true;
            return false;
        }

        /// <summary> 分区表里按名字取一块(null = 这份程序没有那一块) </summary>
        private static 内存分区C? 找区(IReadOnlyList<内存分区C>? 表, string 区名)
        {
            foreach (var 区 in 表 ?? [])
                if (区.区名 == 区名) return 区;
            return null;
        }

        /// <summary> 这一块堆里有没有用过(空堆就是一片 0 —— 够用,不必去读中间层的空闲表指针)</summary>
        private bool 堆里有东西(内存分区C 区)
        {
            int 起 = Math.Max(0, 区.起始), 止 = Math.Min(内存.Length, 区.起始 + 区.大小);
            for (int i = 起; i < 止; i++) if (内存[i] != 0) return true;
            return false;
        }
