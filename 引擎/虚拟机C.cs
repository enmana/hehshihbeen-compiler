        /// (闸门 = `中断闸门C.检查间隔` 条指令一次,见 `中断闸门C`)。
        /// </summary>
        public virtual void 请求中断() => _中断请求 = true;

        /// <summary>
        /// 在闸门那一刻把"请求停下"**取走**(消费掉):返回 true = 这趟该停,并且这台机记下"我是被打断的"。
        /// 一定要取走 —— 不取走的话下一次运行刚起步就被上一次的旧请求叫停(点一下停止,后面全跑不动)。
        /// </summary>
        public virtual bool 取中断请求()
        {
            if (!_中断请求) return false;
            _中断请求 = false;
            已中断 = true;
            return true;
        }

        /// <summary> 清掉中断这一套状态(装载 / 复位时调):请求与"被打断过"一起归零 </summary>
        public virtual void 清除中断请求()
        {
            _中断请求 = false;
            已中断 = false;
        }
