        /// <summary>
        /// 默认内存容量:1 MB(1048576 字节)。
        /// 为什么是 1 MB:取地址/加载/存储这些指令的地址字段是 **20 位**,最大能寻到 0xFFFFF = 1048575,
        /// 所以 1 MB 正好是"一条指令就能指到任何地方"的上限;以前是 64000(62.5 KB),太小,帧缓冲/表都放不下。
        /// </summary>
        public const int 默认内存大小 = 1024 * 1024;

        /// <summary>
        /// 内存上限:**64 MB**(0x4000000)。
        /// <para>
        /// 为什么不再是 20 位地址字段的极限(1048576):**通用化**把这条墙拆了 ——
        /// 直接寻址仍是 20 位(老指令一条位都不动,`加载 R, [addr]` 照旧只够低 1MB),
        /// 但**地址一旦超过 20 位,由 `载入高位` + `或立即数` 拼出 32 位地址、再用间接寻址访问**
        /// (那几条指令 55 条里**本来就有**:`加载间接寻址` / `存储间接寻址` / `取字间接` / `存字间接`;
        /// 中间层也早就在这么发,见 `中间层C.结构` 那几处)。寄存器本身就是 32 位,
        /// 所以**间接寻址走满 4GB 是现成能力**,这里给的是"那块内存真开多大"的上限。
        /// </para>
        /// <para>
        /// 为什么是 64 MB 而不是 4 GB:`内存` 是**一块连续的 `byte[]`**(见构造函数),
        /// 4 GB 的托管数组分配不下来;64 MB 够装约 **130 万行**源码
        /// (实测 13,603 行 → 代码段 609,612 字节,约 45 字节/行),
        /// 比"中型程序 1~3 万行"宽两个数量级,留足了写 3D / 大表 / 大缓冲的余地。
        /// </para>
        /// </summary>
        public const int 最大内存大小 = 64 * 1024 * 1024;   // 0x4000000 = 67108864

        /// <summary> 内存下限:再小就连软栈(2112 字节)+ 代码 + 变量都装不下</summary>
        public const int 最小内存大小 = 4096;

        /// <summary>
        /// 运行内存**末尾**要给定长栈(ISA 的硬件栈:`调用/返回` 压返回地址、`入栈/出栈` 压寄存器,
        /// 它从内存末尾往下长)留的余量上限。
        /// 谁用:字符串池往上长的时候(池最多长到"内存末尾 − 这个余量"),见 `中间层C.列表.cs` 的 `池要一块`
        /// 与 `宿主能力C.写进字符串变量` —— 两边口径必须一致,所以这份常量放在虚拟机这边(宿主 exe 只链接引擎,
        /// 链不到中间层)。
        /// 为什么 16KB 够:最深的一条调用链受软栈护栏管着(软栈 4KB / 一帧 96 字节 ≈ 42 层),
        /// 一层最多几十字节;内存本身比 64KB 还小时按四分之一留(见 `栈顶保留`),免得小内存机器上一留就没了。
        /// </summary>
        public const int 硬件栈保留上限 = 16 * 1024;

        /// <summary> 这块内存的末尾要给硬件栈留多少(池能长到"内存末尾 − 它") </summary>
        public static int 栈顶保留(int 内存大小) => Math.Min(硬件栈保留上限, 内存大小 / 4);

        /// <summary>
        /// 这台虚拟机的内存容量(默认 1 MB;工程文件里写了 `内存` 就按工程来)。
        /// 改它用 <see cref="设内存大小"/>,装载时会按它重新开一块内存。
        /// </summary>
        public int 内存大小 { get; protected set; } = 默认内存大小;

        public 虚拟机C()
        {
            内存 = new byte[内存大小];
            寄存器 = new uint[寄存器C.数量]; // R0~R15(见 寄存器C,单一事实源)
            程序计数器 = 0;
            停机 = false;
            命中断点 = false;
            栈指针 = (uint)内存大小; // 从末尾开始（栈顶在最高地址+1）
            状态标志 = 0;
        }

        /// <summary>
        /// 设内存容量(字节)。下一次 装载 时按新容量重新开内存。
        /// 超范围时抛出明确错误 —— 这正是"工程文件里 `内存` 写错了"的落点。
        /// </summary>
        public virtual void 设内存大小(int 字节数)
        {
            if (字节数 < 最小内存大小 || 字节数 > 最大内存大小)
                throw new ArgumentOutOfRangeException(nameof(字节数),
                    $"内存大小须在 {最小内存大小} ~ {最大内存大小} 字节之间(可以写 1MB / 512KB / 1048576),收到 {字节数}");
            内存大小 = 字节数;
            if (内存.Length != 字节数)
            {
                内存 = new byte[字节数];
                机器码 = [];          // 换了内存:里面装着的代码也一起没了 → 界面据此重新装载
            }
            栈指针 = (uint)内存大小;
        }
