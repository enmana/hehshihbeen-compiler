        /// <summary>
        /// 连续运行的**步数上限**(0 = 不设上限,命令行 `--run` 与独立 exe 都是 0,行为一字未变)。
        ///
        /// R4-1:自检跑的是**仓库里那些示例**,示例里写一句 `当 (真) { }`,自检以前就**永远挂在那儿**
        /// (只有乱源与确定性两处自己数了步数)。现在自检给每台机器挂一个上限,撞上就抛一条说人话的
        /// 运行期错误 —— "一组卡死"变成"一条 FAIL",后面的组照跑。
        /// **不改 ISA、不改机器码**:这只是宿主侧的一道计数闸。
        /// </summary>
        public long 步数上限 { get; set; } = 本线程默认步数上限;

        /// <summary>
        /// 连续运行直到停机(或越界)。H22:每 `中断闸门C.检查间隔` 条查一次中断请求,
        /// 有请求就当场退出来(停机仍是 false —— 程序没跑完,是被人叫停的)。
        /// R4-1:另有一道**步数上限**(0 = 不设,默认就是 0;只有自检会设)—— 死循环不许把调用方挂住。
        /// H39-1 起是 `virtual`:`跨进程虚拟机C` 把它改成"先让子进程装载 → 发『跑到』→ 顺手同步镜像"
        /// (方法体一个字未改;上限那一句文案由 `步数超限说明` 统一给,免得两处各写一遍)。
        /// </summary>
        public virtual void 运行(byte[] 机器码, bool 跟踪 = false)
        {
            装载(机器码);
            long 限 = 步数上限;                  // 抬到局部:每一步只多一次比较,热循环不吃亏
            long 步 = 0;
            while (单步(跟踪))
            {
                步++;
                if (限 > 0 && 步 > 限)
                    throw 运行期错误($"指令数超过上限 {限} 条(程序多半停不下来了 —— 检查循环的退出条件" +
                        "有没有写对;自检给每段示例都设了这道护栏,免得一条死循环挂住整个自检)");
                if (中断闸门C.该检查(步) && 取中断请求()) break;
            }
        }

        /// <summary>
        /// H39-1:**这一趟"连续跑"是怎么停下来的** —— `跑到` 的返回值。
        ///
        /// 为什么要一个枚举:`运行` 那条老路只有"跑完了 / 抛异常"两种落点,而调试那条腿要区分
        /// "命中断点 / 被人叫停 / 撞了步数上限"三种"没跑完"。四种停下来路都在这儿,别在各处自己判旗标。
        /// </summary>
        public enum 停下原因C
        {
            /// <summary> 程序自己跑到 `停止`(或 BKPT 之外的静默停机)</summary>
            停机 = 0,
            /// <summary> 撞上断点(断点地址表里那一条,或者程序里那条 `断点` 指令)</summary>
            命中断点 = 1,
            /// <summary> 被「停止」叫停(`取中断请求()` 在闸门上消费掉了一个请求)</summary>
            被中断 = 2,
            /// <summary> 步数到了上限(死循环护栏;`运行` 在这个落点上抛运行期错误,`跑到` 只如实返回)</summary>
            步数上限 = 3,
            /// <summary>
            /// H39-2:程序读到没有输入、`等输入` 又开着 ⇒ **停在原地等你敲**(IDE 控制台那一档)。
            /// 与进程内那条 `while (… &amp;&amp; !机.正在等输入 …)` 是同一个退出条件,只是收进了"停下原因"这一个出口。
            /// </summary>
            在等输入 = 4,
        }

        /// <summary>
        /// `运行` 撞上步数上限时抛的那句话。**文案的唯一事实源**:
        /// `运行` 里那句字面量(= 老行为,一字未改)与 `跨进程虚拟机C.运行` 都照这一份。
        /// </summary>
        public static string 步数超限说明(long 上限) =>
            $"指令数超过上限 {上限} 条(程序多半停不下来了 —— 检查循环的退出条件" +
            "有没有写对;自检给每段示例都设了这道护栏,免得一条死循环挂住整个自检)";

        /// <summary>
        /// H39-1:**连续运行到"该停下"为止**,并说清是哪一种停下(见 `停下原因C`)。
        ///
        /// 默认实现就是 `运行` 那一圈(同一道中断闸门、同一道步数上限),只多了两档:
        /// ① **断点地址表** —— 每一条指令动手之前先看 PC 在不在表里,在就**不执行**直接返回
        ///    (这正是调试那条腿"停在断点上、现场留在原地"的语义);
        /// ② **在等输入**(H39-2)—— 程序读到没有输入、`等输入` 又开着时当场返回
        ///    (与 IDE 那条 `!机.正在等输入` 的循环条件同一个落点;`等输入` 关着时永远碰不到这一档)。
        /// 空表 + 上限 0 时与 `运行` 一字不差。
        ///
        /// 与 `运行` 唯一的有意差别:撞上限**返回** `步数上限` 而不是抛异常(`运行` 要抛,是因为它没有
        /// 第二个出口;`跑到` 的调用方要自己决定"这算失败还是算暂停")。
        /// </summary>
        public virtual 停下原因C 跑到(IReadOnlyCollection<int> 断点地址, long 上限)
        {
            long 步 = 0;
            while (true)
            {
                // 断点在**动手之前**看:停在断点上时那条指令没执行过,现场(= 断点前那一刻)留在原地
                if (断点地址.Count > 0 && 程序计数器 < 内存.Length && 断点地址.Contains((int)程序计数器))
                    return 停下原因C.命中断点;
                if (!单步()) return 命中断点 ? 停下原因C.命中断点 : 停下原因C.停机;
                步++;
                if (正在等输入) return 停下原因C.在等输入;      // 停下来等你敲:PC 原地不动,接着跑时还从这条读起
                if (上限 > 0 && 步 > 上限) return 停下原因C.步数上限;
                if (中断闸门C.该检查(步) && 取中断请求()) return 停下原因C.被中断;
            }
        }

