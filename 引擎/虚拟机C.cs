        /// <summary> 单步执行一条指令;返回是否仍在运行(true=可继续单步) </summary>
        public virtual bool 单步() => 单步(false);

        private bool 单步(bool 跟踪)
        {
            if (停机) return false;
            // R2-3:以前这里是**静默停机** —— `跳转 0x3FFFFC` 这类"PC 跑到内存外面"表现成"程序正常跑完",
            // `// 预期输出:` 断言可能因此误判通过。现在明确报错(说人话 + 给改法 + 挂回上一条指令的行号)。
            if (程序计数器 >= (uint)内存.Length - 3)
                throw 运行期错误在($"程序跑到了内存外面(执行到地址 0x{程序计数器:X},内存只有 {内存.Length} 字节)" +
                    " —— 检查跳转 / 返回的目标地址算错了没有", 上一条指令地址);
            // H39-2:没人要这一步时走原来那条最短的路(热循环一个字节都不多花)
            if (单步回调 is not { } 回调) { 执行当前指令(跟踪); return !停机; }
            int 旧PC = (int)程序计数器;
            执行当前指令(跟踪);
            回调(旧PC, (int)程序计数器);
            return !停机;
        }

        /// <summary> 调试器用:是否已结束 </summary>
        public bool 已结束 => 停机;
        #endregion

        #region 取指与指令执行(执行当前指令/操作码分派)
        private void 执行当前指令(bool 跟踪)
        {
            // R2-3:记下这一条的地址 —— 它把 PC 送出内存外面时,报错要拿它查行号(见 上一条指令地址)
            上一条指令地址 = 程序计数器;
            已执行条数++;      // R3-6-4 批 2:对拍要比"跑过的条数"(与 C 侧 `hb_steps` 同一个口径)
            _足迹[_足迹数++ & 63u] = 上一条指令地址;
            // 读取4字节指令（小端）
            uint 指令 = (uint)(内存[程序计数器] | (内存[程序计数器 + 1] << 8) | (内存[程序计数器 + 2] << 16) | (内存[程序计数器 + 3] << 24));
            byte 操作码 = (byte)((指令 >> 24) & 0xFF);
            byte 寄存器编号 = (byte)((指令 >> 20) & 0x0F);
            uint 立即数20 = 指令 & 0xFFFFF; // 低20位
            uint 地址24 = 指令 & 0xFFFFFF; // 低24位（用于J型）

            if (跟踪)
            {
                System.Diagnostics.Debug.WriteLine($"PC=0x{程序计数器:X4} OP=0x{操作码:X2} R={寄存器编号} IMM20=0x{立即数20:X5} ADDR24=0x{地址24:X6}");
            }

            try
            {
                switch (操作码)
                {
                    case 0x00: // HALT
                        停机 = true;
                        return;

                    case 0x01: // LOAD R, [addr]
                        CheckAddr(立即数20);
                        寄存器[寄存器编号] = ReadMemory(立即数20);
                        break;

                    case 0x02: // STORE R, [addr]
                        CheckAddr(立即数20);
                        WriteMemory(立即数20, (byte)(寄存器[寄存器编号] & 0xFF));
                        break;

                    case 0x03: // LOAD_IMM R, imm
                        寄存器[寄存器编号] = 立即数20;
                        break;

                    case 0x04: // ADD Rdest, Rsrc
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (寄存器[寄存器编号] + 寄存器[src]) & 0xFFFFFFFF;
                        }
                        break;

                    case 0x05: // SUB Rdest, Rsrc
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (寄存器[寄存器编号] - 寄存器[src]) & 0xFFFFFFFF;
                        }
                        break;

                    case 0x06: // JMP addr (24位左移2)
                        程序计数器 = (地址24 << 2);
                        return;

                    case 0x07: // JZ R, addr (低20位即字节地址,不左移)
                        if (寄存器[寄存器编号] == 0)
                        {
                            程序计数器 = 立即数20;
                            return;
                        }
                        break;

                    case 0x08: // CMP R1, R2
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            uint a = 寄存器[寄存器编号];
                            uint b = 寄存器[src];
                            if (a > b) 状态标志 = 1;
                            else if (a < b) 状态标志 = 2;
                            else 状态标志 = 0;
                        }
                        break;

                    case 0x09: // JG addr
                        if (状态标志 == 1)
                        {
                            程序计数器 = (地址24 << 2);
                            return;
                        }
                        break;

                    case 0x0A: // JL addr
                        if (状态标志 == 2)
                        {
                            程序计数器 = (地址24 << 2);
                            return;
                        }
                        break;

                    case 0x1B: // JEQ addr
                        if (状态标志 == 0)
                        {
                            程序计数器 = (地址24 << 2);
                            return;
                        }
                        break;

                    case 0x1C: // JNE addr
                        if (状态标志 != 0)
                        {
                            程序计数器 = (地址24 << 2);
                            return;
                        }
                        break;

                    case 0x0B: // PUSH R
                        PushWord(寄存器[寄存器编号]);
                        break;

                    case 0x0C: // POP R
                        寄存器[寄存器编号] = PopWord();
                        break;

                    case 0x0D: // CALL addr
                        PushWord(程序计数器 + 4);
                        程序计数器 = (地址24 << 2);
                        return;

                    case 0x0E: // RET
                        程序计数器 = PopWord();
                        return;

                    // ---- R1-4:间接控制转移(2026-09-22)----
                    // 目标在寄存器里(算出来的,不是编译期常量)⇒ 对齐只能在**运行期**查:
                    // 老 `跳转 标签` / `调用 标签` 是编译期查,这两条与它同一个口径(不对齐会从两条指令
                    // 中间接着解释,表现成"程序正常跑完"这类怪现象 —— 正是 R2-4 当初治的病)。
                    // 越界不在这儿查:`单步` 开头那条"跑到了内存外面"本来就兜住任何 PC。
                    case 0x35: // CALL_REG R:返回地址压**硬件栈**后 PC = R(与 0x0D `调用` 同一口径,`返回` 照样回得来)
                        {
                            uint 间接目标 = 寄存器[寄存器编号];
                            查间接目标对齐(间接目标, "调用寄存器");
                            PushWord(程序计数器 + 4);
                            程序计数器 = 间接目标;
                            return;
                        }

                    case 0x36: // JMP_REG R:PC = R(不压返回地址)
                        {
                            uint 间接目标 = 寄存器[寄存器编号];
                            查间接目标对齐(间接目标, "跳转寄存器");
                            程序计数器 = 间接目标;
                            return;
                        }

                    // ---- 通用化:大地址时代的条件跳转(2026-10)----
                    // 与上面两条同一套:目标在寄存器里 ⇒ 对齐只能在运行期查。
                    // 为什么要它:`为零跳转` 的目标字段只有 20 位,代码段一超过 1MB,指向后段的跳转全编不过
                    // (实测 40,803 行 / 1.83MB 那次:19,990 条 `为零跳转` 报「立即数/地址超出20位范围」)。
                    // 这一条把目标改成"寄存器里装着的 32 位地址",跳转范围不再受 20 位卡。
                    // **不跳时不改任何东西**(PC 照常 +4)——与 `为零跳转` 的口径一致。
                    case 0x37: // JZ_REG Rd, Rs:若 Rd == 0 → PC = Rs
                        {
                            byte 目标寄存器 = (byte)((指令 >> 16) & 0x0F);
                            if (寄存器[寄存器编号] == 0)
                            {
                                uint 间接目标 = 寄存器[目标寄存器];
                                查间接目标对齐(间接目标, "为零跳转寄存器");
                                程序计数器 = 间接目标;
                                return;
                            }
                            break;
                        }

                    // ---- 通用化:硬件浮点(单精度,2026-10)----
                    // 口径:寄存器里那 32 位就是 **IEEE754 单精度位模式**(与 `Sample\库\float32.hb` 一致)。
                    // 运算一律用平台的 `float` 做 —— C# 的 float 就是 IEEE754 单精度,
                    // 与 C 侧的 `float` 逐位一致(这也是两边对拍能过的前提);
                    // **不重排表达式**(浮点不满足结合律,重排会改位模式)。
                    // 除零**不报错**:IEEE754 给 ±Inf / NaN(整数除零那条闸在 case 0x25/0x26,与此无关)。
                    case 0x38: // FADD Rd, Rs
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = 浮转位(位转浮(寄存器[寄存器编号]) + 位转浮(寄存器[源]));
                        }
                        break;

                    case 0x39: // FSUB Rd, Rs
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = 浮转位(位转浮(寄存器[寄存器编号]) - 位转浮(寄存器[源]));
                        }
                        break;

                    case 0x3A: // FMUL Rd, Rs
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = 浮转位(位转浮(寄存器[寄存器编号]) * 位转浮(寄存器[源]));
                        }
                        break;

                    case 0x3B: // FDIV Rd, Rs(除零给 ±Inf / NaN,不报错)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = 浮转位(位转浮(寄存器[寄存器编号]) / 位转浮(寄存器[源]));
                        }
                        break;

                    case 0x3C: // FSQRT R
                        {
                            float 浮值 = 位转浮(寄存器[寄存器编号]);
                            寄存器[寄存器编号] = 浮转位(MathF.Sqrt(浮值));
                        }
                        break;

                    case 0x3D: // FCMP Rd, Rs, 关系码:Rd = (Rd 关系 Rs) ? 1 : 0(无序 → 0,与 IEEE754 一致)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            uint 码 = (指令 >> 12) & 0xF;
                            float 左 = 位转浮(寄存器[寄存器编号]);
                            float 右 = 位转浮(寄存器[源]);
                            bool 成立 = (码 & 7) switch
                            {
                                0 => 左 == 右,
                                1 => 左 != 右,
                                2 => 左 > 右,
                                3 => 左 < 右,
                                4 => 左 >= 右,
                                5 => 左 <= 右,
                                _ => false,
                            };
                            寄存器[寄存器编号] = 成立 ? 1u : 0u;
                        }
                        break;

                    case 0x3E: // F2I R:R = (整数)按零截断;越界 / NaN 给 0x80000000
                        {
                            float 浮值 = 位转浮(寄存器[寄存器编号]);
                            寄存器[寄存器编号] = (浮值 >= -2147483648f && 浮值 < 2147483648f)
                                ? unchecked((uint)(int)浮值) : 0x80000000u;
                        }
                        break;

                    case 0x3F: // I2F R:R = (浮点)(有符号读 R)
                        {
                            寄存器[寄存器编号] = 浮转位((float)unchecked((int)寄存器[寄存器编号]));
                        }
                        break;

                    // ---- 通用化第2批(2026-10):整数扩展 9 条(0x40~0x47)----
                    // 口径与 `C后端\运行时.c` 那三条 `hb_sdiv` / `hb_smod` / `hb_mulh`
                    // **一字不差**(两边靠这条"对拍逐字节一致"的判据顶着):
                    // · 除零照旧**当场报运行期错误**(与老 `除法`/`取余` 同一档,不是浮点那种 ±Inf);
                    // · `-2^31 / -1` 照 C 的**回绕**给 `-2^31`(不报错、不做饱和 —— ISA 不做溢出标志);
                    // · 取余的符号**跟被除数**(C99 截断除法口径)。
                    // 位运算那三条都是**对 32 位整体**算;`0` 的前导零/尾随零 = 32、数一位 = 0。
                    case 0x40: // SDIV Rd, Rs(有符号除法)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            if (寄存器[源] == 0) throw 运行期错误("除零(除数是 0 —— 先判断除数再除)");
                            int 被除数 = unchecked((int)寄存器[寄存器编号]), 除数 = unchecked((int)寄存器[源]);
                            // C# 的 int 除法在 `int.MinValue / -1` 上**会抛**(那正是 C 里的溢出回绕)——
                            // 所以这一格单独给:回绕成 int.MinValue(位模式 0x80000000),与 C 侧一致。
                            int 商 = (被除数 == int.MinValue && 除数 == -1) ? int.MinValue : 被除数 / 除数;
                            寄存器[寄存器编号] = unchecked((uint)商);
                        }
                        break;

                    case 0x41: // SMOD Rd, Rs(有符号取余:余数符号跟被除数)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            if (寄存器[源] == 0) throw 运行期错误("除零(取余的除数是 0 —— 先判断除数再取余)");
                            int 被除数 = unchecked((int)寄存器[寄存器编号]), 除数 = unchecked((int)寄存器[源]);
                            int 余 = (被除数 == int.MinValue && 除数 == -1) ? 0 : 被除数 % 除数;
                            寄存器[寄存器编号] = unchecked((uint)余);
                        }
                        break;

                    case 0x42: // MULH Rd, Rs(无符号 64 位积的高 32 位)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (uint)(((ulong)寄存器[寄存器编号] * 寄存器[源]) >> 32);
                        }
                        break;

                    case 0x43: // CLZ R(前导零;0 ⇒ 32)
                        {
                            uint 值 = 寄存器[寄存器编号];
                            寄存器[寄存器编号] = 值 == 0 ? 32u : (uint)System.Numerics.BitOperations.LeadingZeroCount(值);
                        }
                        break;

                    case 0x44: // CTZ R(尾随零;0 ⇒ 32)
                        {
                            uint 值 = 寄存器[寄存器编号];
                            寄存器[寄存器编号] = 值 == 0 ? 32u : (uint)System.Numerics.BitOperations.TrailingZeroCount(值);
                        }
                        break;

                    case 0x45: // POPCNT R(1 的个数)
                        {
                            寄存器[寄存器编号] = (uint)System.Numerics.BitOperations.PopCount(寄存器[寄存器编号]);
                        }
                        break;

                    case 0x46: // SIGN_EXT R, N(低 N 位按有符号扩成 32 位;N = 0 视作 32)
                        {
                            uint 位宽 = 指令 & 0xFFFFF;
                            if (位宽 is >= 1 and <= 31)
                            {
                                uint 掩码 = (1u << (int)位宽) - 1;
                                uint 低 = 寄存器[寄存器编号] & 掩码;
                                寄存器[寄存器编号] = (低 & (1u << ((int)位宽 - 1))) != 0 ? (低 | ~掩码) : 低;
                            }
                        }
                        break;

                    case 0x47: // ZERO_EXT R, N(低 N 位零扩展;N = 0 视作 32)
                        {
                            uint 位宽 = 指令 & 0xFFFFF;
                            if (位宽 is >= 1 and <= 31) 寄存器[寄存器编号] &= (1u << (int)位宽) - 1;
                        }
                        break;

                    // ---- ISA 扩容 批 1:浮点补齐(0x48~0x4B)----
                    // ⚠ 两边都走**位级算法**(不用 `MathF.Max` / `MathF.Floor`,也不用 C 的 `fmaxf` / `floorf`):
                    //   · 最大 / 最小遇**非数传播**(`MathF.Max`/`Min` 的口径,不是 C 的 `fmaxf`);
                    //   · 向下取整朝 −∞(`-0` 保号,`±∞` / `非数` 原样)—— C 侧不许用 `(int)` 截断来凑这个语义;
                    //   · 符号复制按**位级定义**,连 `-0` / 非数的符号位也照搬。
                    case 0x48: // FMAX Rd, Rs(较大者;有一边是非数就给非数)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            uint 甲 = 寄存器[寄存器编号], 乙 = 寄存器[源];
                            寄存器[寄存器编号] = 是浮点非数(甲) ? 甲 : 是浮点非数(乙) ? 乙 : (位转浮(甲) >= 位转浮(乙) ? 甲 : 乙);
                        }
                        break;

                    case 0x49: // FMIN Rd, Rs(较小者;非数同上)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            uint 甲 = 寄存器[寄存器编号], 乙 = 寄存器[源];
                            寄存器[寄存器编号] = 是浮点非数(甲) ? 甲 : 是浮点非数(乙) ? 乙 : (位转浮(甲) <= 位转浮(乙) ? 甲 : 乙);
                        }
                        break;

                    case 0x4A: // FLOOR R(朝 −∞ 取整;`-0` 保号,`±∞` / 非数原样)
                        {
                            寄存器[寄存器编号] = 浮点向下取整位(寄存器[寄存器编号]);
                        }
                        break;

                    // ---- ISA 扩容 批 3 + 批 4(0x54~0x62)----
                    // 口径:三寄存器档的字段照 `存字索引` 的惯例 —— [23:20] 基址 [19:16] 下标 [15:12] 值/目标 [11:8] 小立即数;
                    // 内存读写一律走 `ReadWord` / `WriteWord`(它们自带越界查);栈一律走 `PushWord` / `PopWord`。
                    case 0x54: // LDH_IDX Rb, Ri, Rd, 缩放(读 2 字节并零扩展)
                        {
                            uint 基 = (指令 >> 20) & 0x0Fu, 下标 = (指令 >> 16) & 0x0Fu, 目标 = (指令 >> 12) & 0x0Fu, 缩放 = (指令 >> 8) & 0x0Fu;
                            uint 址 = 寄存器[基] + (uint)(寄存器[下标] << (int)Math.Min(缩放, 31u));
                            寄存器[目标] = ReadWord(址) & 0xFFFFu;
                        }
                        break;

                    case 0x55: // STH_IDX Rb, Ri, Rs, 缩放(写 2 字节:读改写,别把高 2 字节写成 0)
                        {
                            uint 基 = (指令 >> 20) & 0x0Fu, 下标 = (指令 >> 16) & 0x0Fu, 值 = (指令 >> 12) & 0x0Fu, 缩放 = (指令 >> 8) & 0x0Fu;
                            uint 址 = 寄存器[基] + (uint)(寄存器[下标] << (int)Math.Min(缩放, 31u));
                            // ⚠ **只写 2 字节**(与 `存字节索引` 同一套读改写):第一版写成
                            // `WriteWord(址, 值 & 0xFFFF)` —— 那会把紧跟其后的 2 字节一起写成 0,
                            // 实测 `短整数 表[4]; 整数 i = 3; 表[i] = 42;` 把下标变量 `i` 抹成 0(第433批抓到)。
                            WriteWord(址, (ReadWord(址) & 0xFFFF0000u) | (寄存器[值] & 0xFFFFu));
                        }
                        break;

                    case 0x56: // STB_IDX Rb, Ri, Rs, 缩放(写 1 字节:读 4 字节、只改低字节、写回 —— 与 C 侧同办)
                        {
                            uint 基 = (指令 >> 20) & 0x0Fu, 下标 = (指令 >> 16) & 0x0Fu, 值 = (指令 >> 12) & 0x0Fu, 缩放 = (指令 >> 8) & 0x0Fu;
                            uint 址 = 寄存器[基] + (uint)(寄存器[下标] << (int)Math.Min(缩放, 31u));
                            WriteWord(址, (ReadWord(址) & 0xFFFFFF00u) | (寄存器[值] & 0xFFu));
                        }
                        break;

                    case 0x57: // MEMCOPY Rb, Ri, Rs(把 Rb 起 Ri 个字节拷到 Rs 起;第 4 位保留只许写 0)
                        {
                            uint 源 = (指令 >> 20) & 0x0Fu, 个数 = (指令 >> 16) & 0x0Fu, 目标 = (指令 >> 12) & 0x0Fu;
                            uint 起址 = 寄存器[源], 到址 = 寄存器[目标], 长 = 寄存器[个数];
                            for (uint k = 0; k < 长; k++) 内存[到址 + k] = 内存[起址 + k];
                        }
                        break;

                    case 0x58: // CMPRANGE Rb, Ri, Rs(PSW = (下界 <= 值 <= 上界) ? 0 : 2)
                        {
                            uint 下界 = (指令 >> 20) & 0x0Fu, 上界 = (指令 >> 16) & 0x0Fu, 值 = (指令 >> 12) & 0x0Fu;
                            状态标志 = (byte)((寄存器[值] >= 寄存器[下界] && 寄存器[值] <= 寄存器[上界]) ? 0u : 2u);
                        }
                        break;

                    case 0x59: // CMOV Rb, Ri, Rs, 关系码(成立则 Rd = Ri,否则 Rd = Rs)
                        {
                            uint 目标 = (指令 >> 20) & 0x0Fu, 甲 = (指令 >> 16) & 0x0Fu, 乙 = (指令 >> 12) & 0x0Fu;
                            uint 码 = (指令 >> 8) & 0x0Fu;
                            寄存器[目标] = 关系成立(码, 寄存器[甲], 寄存器[乙]) ? 寄存器[甲] : 寄存器[乙];
                        }
                        break;

                    case 0x5A: // CMPMOV Rb, Ri, Rs, 关系码(成立则 Rd = Ri,否则不动)
                        {
                            uint 目标 = (指令 >> 20) & 0x0Fu, 甲 = (指令 >> 16) & 0x0Fu, 乙 = (指令 >> 12) & 0x0Fu;
                            uint 码 = (指令 >> 8) & 0x0Fu;
                            if (关系成立(码, 寄存器[甲], 寄存器[乙])) 寄存器[目标] = 寄存器[甲];
                        }
                        break;

                    case 0x5B: // SETCC Rd(Rd = PSW 成立 ? 1 : 0;PSW 为"等于/大于"都算成立,2 = 小于算不成立)
                        {
                            寄存器[寄存器编号] = 状态标志 == 2u ? 0u : 1u;
                        }
                        break;

                    case 0x5C: // JGE 目标(PSW 为 0 或 1 ⇒ 大于等于)
                        if (状态标志 != 2u) { 程序计数器 = (指令 & 0xFFFFFFu) << 2; return; }   // ⚠ 必须 return:调用方还会 PC += 4
                        break;

                    case 0x5D: // JLE 目标(PSW 为 0 或 2 ⇒ 小于等于)
                        if (状态标志 == 0u || 状态标志 == 2u) { 程序计数器 = (指令 & 0xFFFFFFu) << 2; return; }   // 同上
                        break;

                    case 0x5E: // TAILJMP 目标(不压返回地址:栈一个字节都不动)
                        程序计数器 = (指令 & 0xFFFFFFu) << 2;
                        return;   // 尾调用:只改 PC,不压返回地址(也必须 return)

                    case 0x5F: // SADD Rd, Rs(有符号饱和加:越界夹到 ±极值,不回绕)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            long 和 = (long)(int)寄存器[寄存器编号] + (int)寄存器[源];
                            寄存器[寄存器编号] = 和 > int.MaxValue ? int.MaxValue : 和 < int.MinValue ? unchecked((uint)int.MinValue) : (uint)(int)和;
                        }
                        break;

                    case 0x60: // NOP
                        break;

                    case 0x61: // RETN 立即数(先把立即数那些字节从栈上放掉,再按 `返回` 同一条路返回)
                        for (uint 丢 = 0; 丢 < (指令 & 0xFFFFFu); 丢 += 4u) PopWord();
                        程序计数器 = PopWord();
                        return;

                    case 0x62: // GETRET Rd(Rd = 硬件栈顶那 4 字节 = 当前返回地址;只读不弹)
                        {
                            uint 顶 = PopWord();
                            寄存器[寄存器编号] = 顶;
                            PushWord(顶);
                        }
                        break;
                    // ---- ISA 扩容 批 2:位与字节(0x4C~0x53)----
                    // 八条都是**纯位运算 / 整数运算**:不碰浮点、不报运行期错误 ⇒ 与老整数那批同办。
                    case 0x4C: // UMULH Rd, Rs(无符号 64 位积的高 32 位)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (uint)(((ulong)寄存器[寄存器编号] * 寄存器[源]) >> 32);
                        }
                        break;

                    case 0x4D: // UMADD Rd, Rs(Rd = ((Rd × Rs) + Rs) >> 32)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (uint)((((ulong)寄存器[寄存器编号] * 寄存器[源]) + 寄存器[源]) >> 32);
                        }
                        break;

                    case 0x4E: // ROL Rd, Rs(循环左移,量取低 5 位)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            int n = (int)(寄存器[源] & 31u);
                            寄存器[寄存器编号] = n == 0 ? 寄存器[寄存器编号] : (寄存器[寄存器编号] << n) | (寄存器[寄存器编号] >> (32 - n));
                        }
                        break;

                    case 0x4F: // ROR Rd, Rs(循环右移,量取低 5 位)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            int n = (int)(寄存器[源] & 31u);
                            寄存器[寄存器编号] = n == 0 ? 寄存器[寄存器编号] : (寄存器[寄存器编号] >> n) | (寄存器[寄存器编号] << (32 - n));
                        }
                        break;

                    case 0x50: // BSWAP R(4 字节大端↔小端)
                        {
                            uint v = 寄存器[寄存器编号];
                            寄存器[寄存器编号] = ((v & 0x000000FFu) << 24) | ((v & 0x0000FF00u) << 8) | ((v & 0x00FF0000u) >> 8) | ((v & 0xFF000000u) >> 24);
                        }
                        break;

                    case 0x51: // GETBYTE Rd, Rs, n(取第 n 个字节,n = 0~3;闸在汇编器)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            uint n = (指令 >> 12) & 0xFu;
                            寄存器[寄存器编号] = (寄存器[源] >> (int)(8u * n)) & 0xFFu;
                        }
                        break;

                    case 0x52: // IABS R(整数的绝对值;-2^31 回绕成 -2^31)
                        {
                            int v = (int)寄存器[寄存器编号];
                            寄存器[寄存器编号] = v < 0 ? (uint)(-v) : (uint)v;
                        }
                        break;

                    case 0x53: // ADDR_IDX Rb, Ri, Rd, 缩放(只算地址,不碰内存)
                        {
                            // 字段惯例照 `存字索引`(0x33):[23:20] 基址 [19:16] 下标 [15:12] 目标 [11:8] 缩放
                            uint 基 = (指令 >> 20) & 0xFu;
                            uint 下标 = (指令 >> 16) & 0xFu;
                            uint 目标 = (指令 >> 12) & 0xFu;
                            uint 缩放 = (指令 >> 8) & 0xFu;
                            寄存器[目标] = 寄存器[基] + (寄存器[下标] << (int)缩放);
                        }
                        break;
                    case 0x4B: // FCOPYSIGN Rd, Rs(大小取 Rd、符号位取 Rs)
                        {
                            byte 源 = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (寄存器[寄存器编号] & 0x7FFFFFFFu) | (寄存器[源] & 0x80000000u);
                        }
                        break;

                    case 0x0F: // XOR Rdest, Rsrc
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] ^= 寄存器[src];
                        }
                        break;

                    case 0x10: // AND
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] &= 寄存器[src];
                        }
                        break;

                    case 0x11: // OR
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] |= 寄存器[src];
                        }
                        break;

                    case 0x12: // SHL
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] <<= (int)(寄存器[src] & 0x1F);
                            寄存器[寄存器编号] &= 0xFFFFFFFF;
                        }
                        break;

                    case 0x13: // SHR
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] >>= (int)(寄存器[src] & 0x1F);
                        }
                        break;

                    case 0x14: // ADD_IMM R, imm
                        寄存器[寄存器编号] = (寄存器[寄存器编号] + 立即数20) & 0xFFFFFFFF;
                        break;

                    case 0x15: // SUB_IMM R, imm
                        寄存器[寄存器编号] = (寄存器[寄存器编号] - 立即数20) & 0xFFFFFFFF;
                        break;

                    case 0x16: // LOAD_ADDRESS R, addr
                        寄存器[寄存器编号] = 立即数20;
                        break;

                    case 0x17: // LOAD_INDIRECT Rdest, Raddr
                        {
                            byte addrReg = (byte)((指令 >> 16) & 0x0F);
                            uint addr = 寄存器[addrReg];
                            CheckAddr(addr);
                            寄存器[寄存器编号] = ReadMemory(addr);
                        }
                        break;

                    case 0x18: // STORE_INDIRECT Rsrc, Raddr
                        {
                            byte addrReg = (byte)((指令 >> 16) & 0x0F);
                            uint addr = 寄存器[addrReg];
                            CheckAddr(addr);
                            WriteMemory(addr, (byte)(寄存器[寄存器编号] & 0xFF));
                        }
                        break;

                    case 0x19: // NOT R
                        寄存器[寄存器编号] ^= 0xFFFFFFFF;
                        break;

                    case 0x1A: // CMP_IMM R, imm
                        {
                            uint val = 寄存器[寄存器编号];
                            uint imm = 立即数20;
                            if (val > imm) 状态标志 = 1;
                            else if (val < imm) 状态标志 = 2;
                            else 状态标志 = 0;
                        }
                        break;

                    // ---- 阶段 A+B+C:复制/32位常量/字操作/乘除余 ----
                    case 0x1D: // MOV Rdest, Rsrc
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = 寄存器[src];
                        }
                        break;

                    case 0x1E: // LUI R, imm (imm << 12)
                        寄存器[寄存器编号] = (立即数20 << 12) & 0xFFFFFFFF;
                        break;

                    case 0x1F: // OR_IMMEDIATE R, imm
                        寄存器[寄存器编号] |= 立即数20;
                        break;

                    case 0x20: // LOAD_WORD R, addr
                        寄存器[寄存器编号] = ReadWord(立即数20);
                        break;

                    case 0x21: // STORE_WORD R, addr
                        WriteWord(立即数20, 寄存器[寄存器编号]);
                        break;

                    case 0x22: // LOAD_WORD_INDIRECT Rdest, Raddr
                        {
                            byte addrReg = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = ReadWord(寄存器[addrReg]);
                        }
                        break;

                    case 0x23: // STORE_WORD_INDIRECT R值, Raddr
                        {
                            byte addrReg = (byte)((指令 >> 16) & 0x0F);
                            WriteWord(寄存器[addrReg], 寄存器[寄存器编号]);
                        }
                        break;

                    case 0x24: // MUL Rdest, Rsrc (32位无符号,截断)
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            寄存器[寄存器编号] = (寄存器[寄存器编号] * 寄存器[src]) & 0xFFFFFFFF;
                        }
                        break;

                    case 0x25: // DIV Rdest, Rsrc (无符号)
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            if (寄存器[src] == 0) throw 运行期错误("除零(除数是 0 —— 先判断除数再除)");
                            寄存器[寄存器编号] = 寄存器[寄存器编号] / 寄存器[src];
                        }
                        break;

                    case 0x26: // MOD Rdest, Rsrc (无符号)
                        {
                            byte src = (byte)((指令 >> 16) & 0x0F);
                            if (寄存器[src] == 0) throw 运行期错误("除零(取余的除数是 0 —— 先判断除数再取余)");
                            寄存器[寄存器编号] = 寄存器[寄存器编号] % 寄存器[src];
                        }
                        break;

                    // ---- 阶段 D:控制台 I/O ----
                    case 0x27: // IN R (读取1字节;等输入模式下没数据就"停下来等",否则 EOF → 0xFFFFFFFF)
                        {
                            uint? 字节 = 输入源?.Invoke();
                            if (字节 == null && 等输入)
                            {
                                // 不当作 EOF:标记"正在等输入",**PC 原地不动**。
                                // R2-6(2026-09-21):以前这里写的是 `程序计数器 -= 4`,注释说"下面统一 +4 正好抵消"
                                // —— 但这是个 `return`,`+= 4` 那一句根本到不了(取指不预自增)。净效果是 PC 退到
                                // **IN 的前一条指令**上:探针实测 `读取字符` 那一段前面是 `跳转 0x2C`,
                                // 一退就整段重跑(多打印、把栈跑空),而界面表现只是"程序卡住"。
                                正在等输入 = true;
                                return;
                            }
                            寄存器[寄存器编号] = 字节 ?? 0xFFFFFFFF;
                        }
                        break;

                    case 0x28: // OUT R (输出低字节)
                        输出目标?.Invoke((byte)(寄存器[寄存器编号] & 0xFF));
                        break;

                    case 0x29: // NEWLINE (输出换行 0x0A)
                        输出目标?.Invoke(0x0A);
                        break;

                    // ---- FP + 偏移 相对寻址(局部变量/参数一条指令搞定) ----
                    case 0x2A: // LOAD_WORD_FP R, off: R = 小端 内存[FP+off]
                        寄存器[寄存器编号] = ReadWord(寄存器[寄存器C.帧指针号] + 立即数20);
                        break;

                    case 0x2B: // STORE_WORD_FP R, off: 内存[FP+off] = R
                        WriteWord(寄存器[寄存器C.帧指针号] + 立即数20, 寄存器[寄存器编号]);
                        break;

                    case 0x2C: // LOAD_ADDRESS_FP R, off: R = FP + off
                        寄存器[寄存器编号] = 寄存器[寄存器C.帧指针号] + 立即数20;
                        break;

                    // ---- P11:立即数移位与掩码(移位量取低 5 位,与 `左移` 同一口径) ----
                    case 0x2D: // SHL_IMMEDIATE R, imm: R = R << (imm & 0x1F)
                        寄存器[寄存器编号] = (寄存器[寄存器编号] << (int)(立即数20 & 0x1F)) & 0xFFFFFFFF;
                        break;

                    case 0x2E: // AND_IMMEDIATE R, imm: R = R & imm
                        寄存器[寄存器编号] &= 立即数20;
                        break;

                    // ---- A9:立即数逻辑右移(第108批;移位量取低 5 位,与 `右移` 同一口径) ----
                    case 0x34: // SHR_IMMEDIATE R, imm: R = R >> (imm & 0x1F)(**逻辑**右移,高位补 0)
                        寄存器[寄存器编号] >>= (int)(立即数20 & 0x1F);
                        break;

                    // ---- P13:比较结果进寄存器(第 4 个操作数是关系码:低 3 位关系,第 3 位 = 有符号) ----
                    case 0x2F: // CMP_SET Rd, Rs, 码: Rd = (Rd 关系 Rs) ? 1 : 0
                        {
                            byte 源2 = (byte)((指令 >> 16) & 0x0F);
                            uint 码 = (指令 >> 12) & 0xF;
                            uint 左 = 寄存器[寄存器编号], 右 = 寄存器[源2];
                            bool 成立;
                            if ((码 & 8) != 0)
                            {
                                int a = (int)左, b = (int)右;
                                成立 = (码 & 7) switch
                                {
                                    0 => a == b, 1 => a != b, 2 => a > b, 3 => a < b, 4 => a >= b, 5 => a <= b,
                                    _ => false
                                };
                            }
                            else
                            {
                                成立 = (码 & 7) switch
                                {
                                    0 => 左 == 右, 1 => 左 != 右, 2 => 左 > 右, 3 => 左 < 右, 4 => 左 >= 右, 5 => 左 <= 右,
                                    _ => false
                                };
                            }
                            寄存器[寄存器编号] = 成立 ? 1u : 0u;
                        }
                        break;

                    // ---- P14:断点指令 ----
                    case 0x30: // BKPT:停下,并标记"这是断点命中"(调试器据此改说法)
                        命中断点 = true;
                        停机 = true;
                        return;

                    // ---- P28:宿主调用 ----
                    case 0x31: // HOST_CALL Rd, 功能号:Rd 进 = 参数区地址,出 = 状态码(0 = 成功)
                        {
                            uint 参数区 = 寄存器[寄存器编号];
                            int 状态 = 1;                                   // 没挂宿主能力 → 失败(不崩)
                            if (宿主调用 != null)
                            {
                                // R1-6 批 2:宿主自己抛的**运行期错误**(图形帧数护栏那一条)在宿主里没有行号,
                                // 在这儿补上 —— 报错必须带行号,而且行号只可能由虚拟机查(它才知道当前 PC)
                                try { 状态 = 宿主调用(内存, 参数区, (int)立即数20); }
                                catch (运行期错误C 错) when (错.源码行 == 0)
                                { throw 运行期错误在(错.说明, 程序计数器); }
                            }
                            寄存器[寄存器编号] = (uint)状态;
                        }
                        break;

                    // ---- P12:索引寻址(读)----
                    case 0x32: // LOAD_WORD_INDEX Rd, Ri, 缩放: Rd = 小端 内存[Rd + (Ri << 缩放)]
                        {
                            byte 下标寄存器 = (byte)((指令 >> 16) & 0x0F);
                            uint 缩放 = (指令 >> 12) & 0x0F;
                            uint 地址 = 寄存器[寄存器编号] + (寄存器[下标寄存器] << (int)Math.Min(缩放, 31u));
                            CheckAddr(地址);
                            寄存器[寄存器编号] = ReadWord(地址);
                        }
                        break;

                    // ---- A3:索引寻址(写)----
                    case 0x33: // STORE_WORD_INDEX Rb, Ri, Rs, 缩放: 小端 内存[Rb + (Ri << 缩放)] = Rs
                        {
                            byte 下标寄存器 = (byte)((指令 >> 16) & 0x0F);
                            byte 值寄存器 = (byte)((指令 >> 12) & 0x0F);
                            uint 缩放 = (指令 >> 8) & 0x0F;
                            uint 地址 = 寄存器[寄存器编号] + (寄存器[下标寄存器] << (int)Math.Min(缩放, 31u));
                            WriteWord(地址, 寄存器[值寄存器]);
                        }
                        break;

                    default:
                        // R4-10:报错时**把那一格的原始字节一起带上** —— 这一条以前只说操作码,
                        // 出了"PC 指着中间"这类事就没法判(操作码与内存里那四个字节对不上时,
                        // 一眼看得出是取指错位还是内存被写过)。
                        {
                            int 址 = (int)程序计数器;
                            string 原样 = 址 >= 0 && 址 + 4 <= 内存.Length
                                ? $"{内存[址]:X2} {内存[址 + 1]:X2} {内存[址 + 2]:X2} {内存[址 + 3]:X2}"
                                : "(越界,读不到)";
                            throw new Exception(
                                $"未知操作码: 0x{操作码:X2} (PC=0x{程序计数器:X4};那一格原样 = {原样}," +
                                $"上一条执行过的 = 0x{上一条指令地址:X4})");
                        }
                }

                // 若未跳转，前进到下一条指令
                程序计数器 += 4;
            }
            catch (运行期错误C)
            {
                // **运行期错误原样抛**:它自己带着"说人话的说明 + 源码行号",
                // 再套一层 `执行错误 (PC=0x…)` 反而把行号盖掉、还把机器层地址漏给用户(见 运行期错误C)
                throw;
            }
            catch (Exception ex)
            {
                throw new Exception($"执行错误 (PC=0x{程序计数器:X4}): {ex.Message}", ex);
            }
        }
        #endregion
    }
