        // ---- 32 位字读写(小端,4 字节对齐非强制) ----
        #region 32 位字读写(小端)
        private uint ReadWord(uint addr)
        {
            if (addr > (uint)内存.Length - 4)
                throw 运行期错误($"字读取越界: 0x{addr:X}..0x{addr + 3:X} 超出内存(共 {内存.Length} 字节)—— 检查下标 / 地址是不是算错了");
            return (uint)(内存[addr]
                | (内存[addr + 1] << 8)
                | (内存[addr + 2] << 16)
                | (内存[addr + 3] << 24));
        }

        private void WriteWord(uint addr, uint value)
        {
            if (addr > (uint)内存.Length - 4)
                throw 运行期错误($"字写入越界: 0x{addr:X}..0x{addr + 3:X} 超出内存(共 {内存.Length} 字节)—— 检查下标 / 地址是不是算错了");
            内存[addr] = (byte)(value & 0xFF);
            内存[addr + 1] = (byte)((value >> 8) & 0xFF);
            内存[addr + 2] = (byte)((value >> 16) & 0xFF);
            内存[addr + 3] = (byte)((value >> 24) & 0xFF);
        }
        #endregion

