        /// <summary>
        /// R3-6-4 批 2(全量对拍):把**这一刻的整机状态**写成一份文本 ——
        /// `PC` / `LAST_ADDR` / `MEM` / `CODE_BYTES` / `DATA_BYTES` 五行,随后 `R0`~`R15`,
        /// 再往后是**整块内存的十六进制**(每行 32 字节,不带走首地址)。
        ///
        /// 为什么要它:C# 虚拟机与 C 后端编出的原生 exe 是**两份实现**,只比程序输出等于只比了个尾巴;
        /// 这里落的是"跑完之后机器里到底是什么",好让两边**逐字节**对账
        /// (判据在 `C后端\C状态C.cs`,同一份格式的另一半在 `C后端\运行时.c` 的 `hb_dump_state`)。
        ///
        /// `PC` 那一行两边**约定不一样**(虚拟机跑到 `停止` 时已经 +4,C 侧停在那一条上),
        /// 所以对拍比的是 `LAST_ADDR`(虚拟机 = 上一条真执行过的指令地址;C 侧 = `hb_pc`,
        /// 它本来就停在那条指令上)—— 这两样是同一个东西。
        ///
        /// **格式必须与 C 侧一字不差** —— 改这边就得同时改那边(自检那条"两侧格式"的断言盯着)。
        /// 一份 1MB 内存的转储约 2.3MB 文本,只在自检 / 探针里落盘,不进任何用户路径。
        /// </summary>
        public void 导出状态(TextWriter 出, int 代码字节数, int 数据字节数)
        {
            ArgumentNullException.ThrowIfNull(出);
            写一行(出, "PC", 程序计数器);
            写一行(出, "LAST_ADDR", 上一条指令地址);
            写一行(出, "STEPS", 已执行条数);
            写一行(出, "MEM", (uint)内存.Length);
            写一行(出, "CODE_BYTES", (uint)Math.Max(0, 代码字节数));
            写一行(出, "DATA_BYTES", (uint)Math.Max(0, 数据字节数));
            for (int i = 0; i < 寄存器.Length; i++) 写一行(出, "R" + i.ToString(System.Globalization.CultureInfo.InvariantCulture), 寄存器[i]);
            for (int 基 = 0; 基 < 内存.Length; 基 += 32)
            {
                for (int k = 基; k < Math.Min(基 + 32, 内存.Length); k++)
                    出.Write(内存[k].ToString("X2", System.Globalization.CultureInfo.InvariantCulture));
                出.Write('\n');
            }
            // 最近跑过的指令地址(从旧到新;与 C 侧那一串 `T` 行对应)
            foreach (uint 一步 in 最近足迹()) 写一行(出, "T", 一步);
        }

        /// <summary>`<标签> <8 位十六进制>` 一行(与 C 侧 `hb_dump_line` 同一个拼法)</summary>
        private static void 写一行(TextWriter 出, string 标签, uint 值)
        {
            出.Write(标签);
            出.Write(' ');
            出.Write(值.ToString("X8", System.Globalization.CultureInfo.InvariantCulture));
            出.Write('\n');
        }

