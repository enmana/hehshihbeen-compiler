        /// 那次判定不能走 `重载`(那个入口见到"判好的迁移"就早退),所以判据留这么一个受保护的口子。
        /// `收迁移表` 给了就把判出来的段 / 旧初值 / 说明一并抄进去(子进程照它照贴)。
