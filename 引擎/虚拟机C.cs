        /// <summary>
        /// **最近 64 条执行过的指令地址**(环;R3-6-4 批 2 定位用,与 C 侧的 `hb_trace` 同一个口径)。
        /// 条数对不上时,拿两边这份尾巴一对,分岔点直接看得见。
        /// </summary>
        private readonly uint[] _足迹 = new uint[64];
        private uint _足迹数;

        /// <summary>把最近执行过的指令地址按**从旧到新**抄出来(定位"两条路在哪儿分岔"用)</summary>
        public uint[] 最近足迹()
        {
            uint 起 = _足迹数 > 64 ? _足迹数 - 64 : 0;
            var 出 = new uint[_足迹数 - 起];
            for (uint i = 起; i < _足迹数; i++) 出[i - 起] = _足迹[i & 63u];
            return 出;
        }

        private void CheckAddr(uint addr)
        {
            if (addr >= 内存.Length)
                throw 运行期错误($"内存越界: 0x{addr:X} 超出内存(共 {内存.Length} 字节)—— 检查下标 / 地址是不是算错了");
        }

        private byte ReadMemory(uint addr)
        {
            CheckAddr(addr);
            return 内存[addr];
        }

        private void WriteMemory(uint addr, byte value)
        {
            CheckAddr(addr);
            内存[addr] = value;
        }
