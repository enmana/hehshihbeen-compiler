namespace hehshihbeen_compiler
{
    /// <summary> 执行行(调试黄条)该不该滚、往哪滚 </summary>
    public enum 滚动方式C
    {
        /// <summary> 在视口里、离底边还有余地 → **一动不动**(别行行跳) </summary>
        不动 = 0,
        /// <summary> 落到底边附近(或更靠下)→ 挪到视口**中央** </summary>
        居中 = 1,
        /// <summary> 跑到视口**上面**去了 → 挪回来,放在视口上三分之一处(留出上下文) </summary>
        靠上 = 2,
    }

    /// <summary>
    /// "执行行(调试黄条)要不要滚动"的判定 —— **纯逻辑**,所以能在自检里逐条钉住(不用开界面)。
    ///
    /// 用户实测(2026-09-19):"单步黄条始终保持在编辑器中央,修改为黄条离编辑器底边还有一两行时
    /// 再挪到中央(不然观感太跳了)" —— 以前每标一行都滚一下,单步一行行走时整屏内容一直在挪,
    /// 眼睛得跟着找黄条。现在的规矩:
    ///   ① 行号在视口里、**离底边还有 3 行以上** → 不动(黄条自己往下走,屏幕别动);
    ///   ② 离底边只剩 `留边行数` 行(默认 2)或更靠下 → **居中**(把下面腾出来);
    ///   ③ 跑到视口上面去了 → **靠上**(放回上三分之一,不然黄条看不见了)。
    /// </summary>
    public static class 执行行滚动C
    {
        /// <summary> 离底边留几行就提前居中(默认 2:黄条下面还能看见两行) </summary>
        public const int 默认留边行数 = 2;

        /// <summary>
        /// 定"要不要滚、往哪滚"。参数都是**文档行号**(1 基),`首可见行`/`末可见行` = 编辑器视口里
        /// 当前看得见的第一行/最后一行(拿 `TextView.VisualLines` 的首尾就能算出来)。
        /// 参数明显不对(行号 0、可视范围反了)一律 `不动`:宁可不滚,也不要把视口滚到奇怪的地方。
        /// </summary>
        public static 滚动方式C 定(int 行号, int 首可见行, int 末可见行, int 留边行数 = 默认留边行数)
        {
            if (行号 <= 0 || 首可见行 <= 0 || 末可见行 < 首可见行) return 滚动方式C.不动;
            if (留边行数 < 0) 留边行数 = 0;
            if (行号 < 首可见行) return 滚动方式C.靠上;
            if (行号 >= 末可见行 - 留边行数) return 滚动方式C.居中;
            return 滚动方式C.不动;
        }

        /// <summary> 给人看的一行(自检详情 / 排查用) </summary>
        public static string 说明(滚动方式C 方式) => 方式 switch
        {
            滚动方式C.不动 => "视口里,离底边还有余地 → 不滚",
            滚动方式C.居中 => "到底边了 → 挪到中央",
            滚动方式C.靠上 => "跑到视口上面了 → 放回上三分之一",
            _ => "未知",
        };
    }
}
