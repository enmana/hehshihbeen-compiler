        /// <summary>
        /// 这条指令携带的是不是**要跳过去的字节地址**?跳转 / 调用 / 条件跳转(编码格式 = `跳转地址`)都算,
        /// 另外 **`为零跳转`**(0x07)也算 —— 它借的是"寄存器地址"格式,只有它的第二操作数是跳转目标。
        /// 汇编器据此查 4 字节对齐:地址不对齐就会从一条指令的中间接着解释
        /// (R2-4 实测:`为零跳转 R0, 6` 以前编得过、而且真的跳,最后表现成"程序正常跑完")。
        /// </summary>
        public static bool 带跳转目标(byte 操作码) =>
            操作码 == 0x07 || 取格式(操作码) == 指令格式.跳转地址;

        /// <summary>
        /// `比较取值` 的关系码(4 位)合法不合法:低 3 位是关系(0~5),第 3 位(值 8)= 按有符号比
        /// ⇒ 合法的只有 **0~5 与 8~13**。6/7/14/15 以前会被静默收下、在 VM 里落到 `_ => false`
        /// (结果恒 0),属于"编出来的机器码与源码字面不符"。
        /// </summary>
        public static bool 是有效关系码(long 码) => (码 & ~0xFL) == 0 && (码 & 7) <= 5;

