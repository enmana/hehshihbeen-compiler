            // 它借的就是同一套判据(整行两个记号 + 第二操作数是寄存器名 + 不是标签),
            // 所以 `为零跳转 R1, R2` 从此走 0x37 这条间接路;老写法(标签 / 数值)一个字不破。
            ("为零跳转", "为零跳转寄存器"), ("JZ", "JZ_REG"),
        ];

