        /// <summary>
        /// `比较取值` 的关系码(第 4 个操作数,4 位):低 3 位是关系,第 3 位(值 8)= **按有符号比**。
        /// 中英两边都用这张表,别再各抄一份。
        /// </summary>
        public static readonly IReadOnlyDictionary<string, uint> 关系码表 = new Dictionary<string, uint>(StringComparer.Ordinal)
        {
            ["=="] = 0, ["!="] = 1, [">"] = 2, ["<"] = 3, [">="] = 4, ["<="] = 5,
        };

        /// <summary> 关系记号 + 是不是有符号 → 关系码(不认识的记号返回 null,交给老路去报错) </summary>
        public static uint? 取关系码(string 关系符, bool 有符号)
            => 关系码表.TryGetValue(关系符, out uint 码) ? 码 | (有符号 ? 8u : 0u) : null;

        /// <summary> 关系码 → 中文说明(反汇编/帮助/寄存器说明用) </summary>
        public static string 关系码说明(uint 码)
        {
            string 关系 = (码 & 7) switch
            {
                0 => "相等", 1 => "不相等", 2 => "大于", 3 => "小于", 4 => "大于等于", 5 => "小于等于",
                _ => "?"
            };
            return (码 & 8) != 0 ? $"{关系}(有符号)" : $"{关系}(无符号)";
        }

