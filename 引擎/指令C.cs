        #region 指令名语言切换(注释感知替换)
        /// <summary> 内建函数英文名 → 中文名(切回中文用;`storeword` → `存字`)。表在 中间层指令C.内建函数名表 </summary>
        private static string 内建函数中文名(string 英文名) =>
            中间层指令C.到内建函数中文名(英文名) ?? 英文名;

        public static string 切换指令名语言(bool 使用中文, string 代码)
        {
            // 准备正则，按长度降序以避免部分匹配问题
            // 除了 ISA 指令名,**语言级内建函数名也要进来**(`申请`/`释放`/`读取行`/`存字`…):
            // 它们不在 关键字表 里(是表达式里的函数名,不是语句开头那个词),不列进来就永远翻不到。
            var 所有指令 = 取全部指令名()
                .Concat(中间层指令C.内建函数名表.SelectMany(x => new[] { x.中文, x.英文 }))
                // 附加类型名(`字符串`/`string`):它们不在 关键字表 里(不是基本类型,见 中间层指令C.附加类型名表),
                // 但也得跟着整体切换 —— 不列进来,"切到英文"之后代码里还留着 `字符串`,跟其它类型名不一致。
                .Concat(中间层指令C.附加类型名表.SelectMany(x => new[] { x.中文, x.英文 }))
                .Distinct(StringComparer.Ordinal)
                .OrderByDescending(s => s.Length)
                .ToArray();
            if (所有指令.Length == 0)
            {
                return 代码;
            }
            string pattern = string.Join("|", 所有指令.Select(Regex.Escape));
            // 使用 Unicode 字母/数字类作为边界判断（避免中文与字母数字粘连时误匹配）
            var 指令正则 = new Regex($"(?<![\\p{{L}}\\p{{N}}])(?:{pattern})(?![\\p{{L}}\\p{{N}}])", RegexOptions.Compiled);

            string 局部替换(string 段)
            {
                return 指令正则.Replace(段, m =>
                {
                    string token = m.Value;
                    try
                    {
                        // **语言关键字优先**:像 `返回` 这种既是 ISA 助记符(RET)又是语言关键字的词,
                        // 中英切换必须交给语言那一层(`返回` ↔ `return`),不能翻成 `RET`
                        // —— 翻成 `RET` 就把 `函数 f() 返回 整数` 和 `返回 值` 一起弄坏了(实测踩到)。
                        // 方向相反的那一半(`RET` → 中文)也跳过:它是**汇编层**的助记符,中文名仍是 `RET`。
                        // **例外:裸 `返回`**(整行只有它)= 汇编 RET,要按指令名翻成 `RET`
                        // (关键字那一层已经把它让出来了,见 中间层指令C.切换关键字语言)。
                        if (token == "返回" && 中间层指令C.是裸返回(段, m.Index + m.Length))
                            return 使用中文 ? token : 到英文指令名("返回");
                        if (中间层指令C.到英文关键字(token) is not null) return token;
                        // ⚠ **带点的方法名一个字都不许动**(2026-10-10):`位.数一位(…)` 里的 `数一位`
                        // 与 ISA 新加的那条指令**同名** —— 不拦的话"切到英文"会把它翻成 `位.POPCNT`,
                        // 而库方法并没有英文别名 ⇒ 切完当场编不过(实测:示例33 报 7 处"未定义的函数")。
                        // 判据只认"紧挨着前面那个字符是不是 `.`":是 ⇒ 这一段是**成员访问**的一部分
                        // (库方法 / 结构字段 / 模块名),照旧原样留着(与下面那条"切换不动方法名"同一个口径)。
                        if (m.Index > 0 && 段[m.Index - 1] == '.') return token;
                        // **语言级内建函数**:只翻"函数调用"那一种写法(后面跟 `(`)。
                        // `存字(地, 0, 7)` 是堆写(英文 `storeword`),`存字 R14 _v4` 是**汇编指令**
                        // —— 后者要按下面的指令名分支翻成助记符;混在一起翻,内联汇编当场废掉(实测踩到)。
                        if (是调用写法(段, m.Index + m.Length) && 中间层指令C.到内建函数英文名(token) is { } 函数英文名)
                            return 使用中文 ? 内建函数中文名(函数英文名) : 函数英文名;
                        // **附加类型名**(`字符串` ↔ `string`):按类型名翻,跟有没有括号无关
                        // (类型名出现在声明/参数表里,永远不带括号)。它不是 ISA 助记符也不是关键字,不会跟别人撞。
                        if (中间层指令C.到附加类型英文名(token) is { } 类型英文名)
                            return 使用中文 ? 中间层指令C.到附加类型中文名(类型英文名) ?? token : 类型英文名;
                        // 带点的"方法"(`.长度()` / `.length()`)中英**两侧都认**(第96批),所以这里**一个字都不动**:
                        // 翻不翻都能编译,少一层"切一下就编不过"的风险。它们不在上面的名字表里,走不到这儿。
                        // 说明:在加英文别名之前,翻成 `length()` 会当场变成"未定义的函数"(实测踩到)——
                        // 现在这个坑已经不存在了,但"切换不动方法名"这条口径保持不变。
                        if (使用中文)
                        {
                            if (是中文指令名(token)) return token;
                            return 到中文指令名(token);
                        }
                        else
                        {
                            if (是英文指令名(token)) return token;
                            return 到英文指令名(token);
                        }
                    }
                    catch
                    {
                        // 若转换失败，保持原样
                        return token;
                    }
                });
            }

            // 只替换代码段:注释与**字符串/字符字面量**原样保留
            // (字面量里也常写着 `字符串`/`如果` 这种词,改了就是偷偷改了程序的数据)
            var 结果 = new StringBuilder();
            var 保护区表 = 代码解析器.取保护改写区(代码);
            int 位置 = 0;
            foreach (var (开始, 结束) in 保护区表)
            {
                结果.Append(局部替换(代码[位置..开始]));
                结果.Append(代码, 开始, 结束 - 开始);
                位置 = 结束;
            }
            if (位置 < 代码.Length) 结果.Append(局部替换(代码[位置..]));
            return 结果.ToString();
        }

        /// <summary>
        /// 这个词后面(跳过空格/制表符)是不是紧跟一个 `(` —— 用来区分"函数调用"与"汇编指令"。
        /// `存字(地, 0, 7)` 是调用,`存字 R14 _v4` 是指令,两者中英切换的去向不一样。
        /// </summary>
        private static bool 是调用写法(string 段, int 从哪)
        {
            for (int i = 从哪; i < 段.Length; i++)
            {
                char c = 段[i];
                if (c is ' ' or '\t') continue;
                return c == '(';
            }
            return false;
        }
