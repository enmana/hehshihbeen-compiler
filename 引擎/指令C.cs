        #region 老助记符的寄存器写法(R1-4)
        /// <summary>
        /// `调用 R0` / `跳转 R0`(第二操作数写的是寄存器)与 `调用寄存器 R0` / `跳转寄存器 R0` 等价 ——
        /// 老助记符在"操作数是编译期常量标签"时走老那条路(`调用` = 0x0D / `跳转` = 0x06),
        /// 写成寄存器时改走间接那条。**这是"只加不改"**:老写法一个字不破,只是多收一种写法。
        /// 放在这张表里(而不是在汇编器里写死 `if`)是为了:中英两边共用、以后加同类指令只改一处。
        /// </summary>
