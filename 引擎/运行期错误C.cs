using System;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **运行期错误**:由虚拟机在执行中发现、编译期查不出来的错(除零、栈溢出这类)。
    ///
    /// 为什么不直接抛 `InvalidOperationException`:那样用户看到的是 .NET 异常的 Message ——
    /// 实测就是 `执行错误 (PC=0x03D8): 除零错误 (DIV)`:`DIV` 是**内部指令助记符**、`PC=0x…` 是**机器层地址**,
    /// 两个都不该漏给写高级语言的用户,而且**没有行号** —— 与"报错必须带行号 + 说人话"这条规矩不符。
    ///
    /// 现在统一成:**说人话的说明 + 源码行号(查得到就给)+ 程序计数器(调试/汇编层用)**。
    /// 行号靠 `虚拟机C.取源行号` 这个回调查(命令行/IDE 都从 `执行行映射C` 那张表来;
    /// 没挂回调的程序 —— 比如贴了程序包的独立 exe、手写汇编 —— 就没有行号,只报说明)。
    /// `用户文案` 刻意做成和"错误槽那套"(列表满/越界/断言失败)同一副面孔:`第 N 行:说明`。
    /// </summary>
    public sealed class 运行期错误C : Exception
    {
        /// <summary> 说人话的一句话(不含行号、不含内部指令名) </summary>
        public string 说明 { get; }

        /// <summary> 出错那条指令对应的**源码行号**(0 = 查不到;比如独立的 exe 里没有源码信息) </summary>
        public int 源码行 { get; }

        /// <summary> 出错时的程序计数器(字节地址;调试/汇编层定位用,不往用户文案里塞) </summary>
        public uint 程序计数器 { get; }

        /// <summary>
        /// 出错处的**位置串**(H7):`目录.hb 第 12 行` / `第 12 行`;空 = 查不到(独立 exe 的老包 / 手写汇编)。
        /// 有它就用它(多文件的独立 exe 里,光有行号分不出是哪一份文件)。
        /// </summary>
        public string 位置 { get; }

        public 运行期错误C(string 说明, int 源码行 = 0, uint 程序计数器 = 0, string 位置 = "")
            : base(位置.Length > 0 ? $"{位置}:{说明}" : (源码行 > 0 ? $"第 {源码行} 行:{说明}" : 说明))
        {
            this.说明 = 说明;
            this.源码行 = 源码行;
            this.程序计数器 = 程序计数器;
            this.位置 = 位置;
        }

        /// <summary>
        /// 这个异常是不是"运行期错误"(宿主里的兜底 catch 要用;T26 之前还得靠它跨程序集认亲)。
        ///
        /// **为什么按类型名判、不写 `错 is 运行期错误C`**:这个类型在几个端里由不同工程编出来
        /// (`引擎库` / `编译器CLI` / WPF 主程序 / `图形宿主` 各有一份,而 `HB宿主` 吃的是 `图形宿主.dll`
        /// 那一份 —— T26 之后它不再自编了)。同名却是**两个类型**的地方仍然存在:`宿主能力C` 里
        /// catch 上来的异常可能来自另一个程序集,`is` 在那个方向上判不出来。
        /// 判不出来的后果是"护栏抛了却被兜底 `catch (Exception)` 吞成状态码"(程序一直转、人看不见为什么),
        /// 正是不久前刚修掉的那个坑(见 `宿主能力C.处理` 的注释)。按名字判,哪一份都认。
        /// </summary>
        public static bool 是运行期错误(Exception 错) => 错.GetType().Name == nameof(运行期错误C);

        /// <summary>
        /// 给用户看的那一句(和"错误槽那套"一个格式:`第 N 行:说明`)。
        /// **注意 `Message` 就是它** —— 各处界面都是直接打 `ex.Message`,
        /// 这样"忘了用 用户文案"的地方也不会漏掉行号(实测踩过:界面那两处 catch 打的就是 Message)。
        /// </summary>
        public string 用户文案 => Message;

        /// <summary>
        /// T8(2026-09-27 评测整改):**"错误槽那套"运行期报错的统一抬头** —— `第 N 行:说明`。
        ///
        /// 背景:`中间层C.列表.cs` 的 `记运行期错误(行号, 说明, 停机)` 一直收着行号,**却把它丢了**
        /// (`_错误表` 只存 `号 + 说明`)⇒ 下标越界 / 递归太深 / 列表满 / 池用完 / 断言失败这些
        /// 命令行与 IDE 都只打一句没有行号的说明(同一批里只有"堆"那几条自己把行号写进了说明,
        /// 于是同一个程序里两种面孔 —— 用户实测报的就是这条)。
        ///
        /// 现在统一在**记的时候**就拼好:错误号 → 说明这份表同时喂给四条腿 ——
        /// 命令行 `--run`、IDE、独立 exe(`程序包C` 的**消息区**)、C 后端(`运行时.c` 的 `hb_errs`)。
        /// 在这儿拼一次,四条腿自然一致(在各自的打印处拼就得改四处,迟早有一处漏掉)。
        ///
        /// `说明` 自己**已经带同一个 `第 N 行:` 抬头**的原样返回 —— "堆"那几条的文案
        /// (`堆.cs` / `串写入.cs`)一个字都不动(判据里是逐字比对)。`行号 &lt;= 0` 也不加:
        /// 生成代码里的报错(例如 `读取数字` 例程)本来就没有对应的源码行,编一个假行号更坏。
        /// </summary>
        public static string 带行号(int 行号, string 说明)
        {
            if (行号 <= 0 || 说明.StartsWith($"第 {行号} 行:", StringComparison.Ordinal)) return 说明;
            return $"第 {行号} 行:{说明}";
        }
    }
}
