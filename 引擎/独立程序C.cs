using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary> 见文件头:「在控制台窗口里跑」要起的那一份(路径 / 工作目录 / 起不了时的说明) </summary>
    public static class 独立程序C
    {
        /// <summary>
        /// `项目` 按当前打包规格该起哪一个文件。三类结果:
        ///   · **起得了** —— 路径 + 工作目录(**标准示例站仓库根**、仓库外的工程站工程目录,
        ///     见 `工作目录取`),说明为空;
        ///   · **「只编译」那档** —— 路径为空 + 一句人话(交的是 C 源码 / `.hb`,没有独立程序);
        ///   · **没目录 / 没名字** —— 路径为空 + 一句人话。
        /// </summary>
        public static (string 路径, string 工作目录, string 说明) 取(项目项C? 项目, string 规格)
        {
            string 目录 = 项目?.目录 ?? "";
            string 名称 = 项目?.名称 ?? "";
            if (目录.Length == 0) return ("", "", "这个项目还没有目录(工程文件没落盘?):先保存一次再跑。");
            if (名称.Length == 0) return ("", 目录, "这个项目没有名字:起不了独立程序。");
            if (打包规格C.是只编译(规格))
                return ("", 目录, "「只编译」这一档不产独立程序 —— 交的是 C 源码 / `.hb`," +
                    "落在工程目录下的 `bin\\` 里(H103:那两样与源码同后缀,落工程目录会把工作树弄脏)。" +
                    "要看控制台窗口,把工具栏『打包:』换成「原生 C」或「自带运行时·单文件」,再编译一次。");
            return (Path.Combine(目录, 名称 + ".exe"), 工作目录取(目录), "");
        }

        /// <summary>
        /// **起这一份时该站在哪一层**(第415批统一,用户当班拍板取 b):
        ///   · 工程**在仓库里**(往上找得到"同时有 `引擎` 与 `Sample`"的那一层)⇒ **仓库根**;
        ///   · 否则(别人的工程 / 仓库外)⇒ **工程目录**(老行为,一个字不变)。
        ///
        /// **为什么统一**:标准示例的数据路径**一律照仓库根写**(`引擎\仓库根C.cs` 文件头那条口径 ——
        /// `Sample/模型/…`、`工具/临时/…`、`Sample/库/排序.hb`),而 IDE 那条腿(H90)与命令行那条腿
        /// 本来就站仓库根,**只有"在控制台窗口里跑"这一档站在工程目录** ⇒ 同一个工程换个入口跑,
        /// 读数据文件的结果就不一样(实测:示例56/58/预览_全身像 在这一档上模型一个顶点都读不到,
        /// 窗口里空无一物)。**唯一口径仍然只有一处**:`仓库根C`。
        /// </summary>
        public static string 工作目录取(string 目录) => 仓库根C.找(目录) ?? 目录;
    }
}
