namespace hehshihbeen_compiler
{
    /// <summary>
    /// **缩进导引线**(C16-3,用户 2026-09-19 追加,原话:"展开/收缩的对齐线能对齐大括号吗?
    /// 而不是全部都挤在单独的一列里面")。
    ///
    /// 规则:每一对**跨行的** `{ … }` 在**它自己那个 `}` 的列**上画一条竖线 ——
    /// (用户 2026-09-21 定版:"彩虹对齐线以**大括号结束符**为基准";老写法 `结构 点 {` 里 `{` 在第 5 列、
    /// `}` 在第 0 列,线画**第 0 列** —— 新写法 `{` 与 `}` 同列,两种写法画出来一样)
    /// 开括号那一行从下半行起、中间每一行整行;**收尾那一行不画**(线在 `}` 的**上方**就结束,
    /// 用户 2026-09-20 看过实际效果:"彩虹折叠线往下延申过长,在 `}` 上方结束");
    /// 单行 `{ … }` 没有"里面",不画。
    ///
    /// **这一列上站着字的那一行不画**(用户 2026-09-21 补的一条:"本应该画对齐线的位置有字符,
    /// 那个位置就不画对齐线,不然会和字符重叠不好看")—— 判据是**这一个字符是不是空白**
    /// (空格 / 制表符照画,`结构 点 {` 那种老写法下第 5 列正压在 `数` 上,那一段就跳过)。
    /// 于是外层线贴外层 `}`、内层线贴内层 `}`,一眼看出哪几行属于哪一层(而不是所有线挤在同一个列上)。
    ///
    /// **第 1 层也画**(用户当初画的那张示意图里,最外层 `{` 与 `}` 之间就有两条 `|`)——
    /// 左边那条"折叠符那一栏"的灰线**不是这里画的**(那是 AvalonEdit 折叠边距自己的范围线,
    /// 第152批用 `无连线折叠边距` 去掉了)。
    ///
    /// **颜色跟着括号那一层的彩虹色**(第151批,用户原话:"不是跟随括号颜色么" ——
    /// 第一版是一条半透明灰,用户说太淡)。每条线段都带**层号**,界面按 `花括号层号C.取色(取色档(层号))` 取色,
    /// 再按 `花括号层号C.导引线透明度` 压一点透明度(别把代码盖住)。
    ///
    /// **为什么放引擎**:与 `折叠区C` / `花括号层号C` 同一个理由 —— "哪一行该画哪几条线、什么颜色"是**规则**,
    /// 规则要能被自检直接喂源码钉住;界面那个 `IBackgroundRenderer` 只负责把列号换算成像素画出来。
    ///
    /// 扫描口径与 `花括号层号C` / `折叠区C` 一致:注释区 ∪ 字符串/字符字面量走 `代码解析器.取保护改写区`,
    /// 里面的 `{}` 一律不算(`输出行("{")` 不该拉出一条线)。纯函数 + 一次扫完,
    /// 界面按**文档版本**缓存这张表(与逐行高亮同一条路),只查看得见的那几十行。
    /// </summary>
    public static class 缩进导引线C
    {
        /// <summary>
        /// 一行上的一小段竖线:**列号**(0 基)+ **它在第几层**(1 基,与 `花括号层号C` 同口径)
        /// + 上下端在行高里的比例(0 = 行顶,1 = 行底)。层号给界面挑颜色用(跟着括号那一层的彩虹色)。
        /// </summary>
        public readonly record struct 导引段C(int 列, int 层号, double 起比例, double 止比例);

        /// <summary> `{` 自己那一行只画下半行(竖线接在括号下面,不从括号身上穿过去) </summary>
        public const double 括号行半高 = 0.5;

        /// <summary>
        /// 算一遍正文:行号(1 基)→ 这一行要画的竖线段(按列号 / 层号排好序)。算不出来返回空表,绝不抛异常
        /// (导引线只是观感,出错就当没有)。
        /// </summary>
        public static IReadOnlyDictionary<int, List<导引段C>> 算(string? 正文)
        {
            var 结果 = new Dictionary<int, List<导引段C>>();
            string 文本 = 正文 ?? "";
            if (文本.Length == 0) return 结果;
            try
            {
                List<(int 开始, int 结束)> 保护;
                try { 保护 = 代码解析器.取保护改写区(文本); }
                catch { 保护 = []; }

                var 栈 = new Stack<(int 行, int 列, int 层)>();
                string[] 行表 = 文本.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
                int 行号 = 1, 列 = 0, 保护号 = 0, 层 = 1;      // 层 = 当前开着几层(1 基,与 `花括号层号C` 同一套)
                for (int 位 = 0; 位 < 文本.Length; 位++)
                {
                    char c = 文本[位];
                    if (c == '\n') { 行号++; 列 = 0; continue; }
                    if (c == '\r') continue;                     // `\r\n` 与单个 `\r` 都不算列

                    while (保护号 < 保护.Count && 位 >= 保护[保护号].结束) 保护号++;
                    if (保护号 < 保护.Count && 位 >= 保护[保护号].开始) { 列++; continue; }

                    if (c == '{') 栈.Push((行号, 列, 层++));      // `{` 自己占"遇到它之前已开层数 + 1"
                    else if (c == '}' && 栈.Count > 0)
                    {
                        int 收列 = 列;                            // 用户 2026-09-21:竖线以**结束符那一列**为基准
                        var 开 = 栈.Pop();
                        层 = Math.Max(1, 层 - 1);                // `}` 与它配对的 `{` 同层(先减再记)
                        if (开.行 < 行号)                        // 单行 `{ … }` 没有"里面",不画
                        {
                            填(结果, 行表, 开.行, 收列, 开.层, 括号行半高, 1.0);
                            for (int 中 = 开.行 + 1; 中 < 行号; 中++) 填(结果, 行表, 中, 收列, 开.层, 0.0, 1.0);
                            // 收尾那一行**不画** —— 线在 `}` 上方就结束(用户点名:别往下延申过长)
                        }
                    }
                    列++;
                }
                // 同一行上外层线比内层线长,先画谁无所谓;排个序只为"同一份输入永远给同一份输出"(自检好钉)
                foreach (var 一位 in 结果.Values)
                    一位.Sort((a, b) => a.列 != b.列 ? a.列.CompareTo(b.列)
                        : a.层号 != b.层号 ? a.层号.CompareTo(b.层号)
                        : a.起比例 != b.起比例 ? a.起比例.CompareTo(b.起比例)
                        : a.止比例.CompareTo(b.止比例));
            }
            catch { 结果.Clear(); }
            return 结果;
        }

        /// <summary> 第 `行号`(1 基)该画的竖线段(没有就返回空表,不返回 null) </summary>
        public static List<导引段C> 取行段(IReadOnlyDictionary<int, List<导引段C>>? 表, int 行号)
        {
            if (表 != null && 表.TryGetValue(行号, out var 一位)) return 一位;
            return [];
        }

        private static void 填(Dictionary<int, List<导引段C>> 结果, string[] 行表, int 行号, int 列, int 层号,
            double 起比例, double 止比例)
        {
            if (止比例 <= 起比例) return;
            // 这一列上站着字(不是空白)就不画这一段 —— 画了就压在字上(用户 2026-09-21 点名)
            if (行号 - 1 < 行表.Length && 列 < 行表[行号 - 1].Length
                && !char.IsWhiteSpace(行表[行号 - 1][列])) return;
            if (!结果.TryGetValue(行号, out var 一位)) { 一位 = []; 结果[行号] = 一位; }
            var 段 = new 导引段C(列, 层号, 起比例, 止比例);
            if (!一位.Contains(段)) 一位.Add(段);
        }
    }
}
