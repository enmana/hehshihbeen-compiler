using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Text;
using System.Threading;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **H39-1:前端这一侧的跑程序通道** —— 起一个子进程(默认就是"再起一份自己",见 `从当前进程`),
    /// 用**标准输入输出管道**把命令送过去、按帧收消息。
    ///
    /// <para>**为什么是标准输入输出管道**:最土、零依赖、天然只在本机(不用监听端口);量出来的往返
    /// 是 12 ~ 31 微秒一跳(见 `未做任务清单.md` §24 H39),人按 F10 那种手感有二十倍以上余量。</para>
    ///
    /// <para>**标准错误不并进协议**:子进程崩了要看得到"为什么会崩",`标准错误` 由另一条线程收着,
    /// 出事时把尾巴几行拼进 `死因`(这就是验收①那句"说得清"的来源);H39-4 起**先等它把最后几行收进队列**
    /// 再定稿,而且死因里带上**进程号**(谁没了,任务管理器里对得上号)。</para>
    ///
    /// <para>**死的判据**:读帧读到管道末尾(子进程退出/崩了)⇒ `活着` 变 false、`死因` 记下来,
    /// 所有在等状态的地方当场抛 `跑程序通道错误C` —— **不许静默当成"程序跑完了"**。</para>
    /// </summary>
    public sealed class 跑程序通道C : IDisposable
    {
        private const int 标准错误留几行 = 8;

        private readonly object _写锁 = new();          // 多线程写同一条管道:加锁(后面还会有别的线程发"中断")
        private readonly object _等锁 = new();          // "状态"帧到了没有
        private readonly object _等重载锁 = new();      // H13:"重载回执"帧到了没有(它不走状态帧那条路)
        private readonly object _命令锁 = new();        // 一次只许有一条命令在路上(命令 ↔ 状态 一一对应)
        private readonly object _标准错误锁 = new();
        private readonly Queue<string> _标准错误 = new();

        private Process? _进程;
        private Stream? _写入;                          // 前端 → 后端(子进程的标准输入)
        private Stream? _读出;                          // 后端 → 前端(子进程的标准输出)
        private Thread? _泵线程;
        private Thread? _标准错误线程;
        private volatile bool _活着;
        private string? _死因;
        private bool _已请求结束;
        private 跑程序协议C.跑程序状态C? _状态;
        private 虚拟机C.重载迁移C? _重载迁移;      // H13:最近一条"重载回执"带回来的迁移表(发重载那条线程取走)

        /// <summary> 前端这一侧的输入源(收到"请求输入"帧就调它:返回值 = 一个字节,null = 没有输入了) </summary>
        public Func<uint?>? 输入源 { get; set; }

        /// <summary> 前端这一侧的输出目标(收到"输出"帧就按字节喂给它 —— 与进程内同一套注入口径) </summary>
        public Action<byte>? 输出目标 { get; set; }

        /// <summary> 前端本地那个画图的口子(收到"图形命令"帧就回放给它);null = 这一侧没有图形能力 </summary>
        public 图形呈现口C? 呈现口 { get; set; }

        /// <summary> 收到"内存增量"帧(跨进程虚拟机拿它贴自己的镜像内存) </summary>
        public Action<IReadOnlyList<(int 起址, byte[] 字节)>>? 收到内存增量 { get; set; }

        /// <summary> 子进程自报的那一行(`构建=…`),出事时给人看</summary>
        public string 后端说明 { get; private set; } = "";

        /// <summary> 通道还活着吗(子进程起不来 / 半路退出 / 协议对不上都算不活)</summary>
        public bool 活着 => _活着;

        /// <summary>
        /// **运行监视(H100 第一步)**:这条通道那个子进程用掉了多少 CPU 与物理内存。
        /// `处理器秒` 是累计处理器时间(采两次求差就是占用率),`物理字节` 是工作集。
        /// 走 OS 读数 —— **不占协议、不问后端**,所以程序跑到一半也读得到。
        /// 拿不到(还没起来 / 已退出 / 读数抛错)一律给 **null**:调用方照"没有这一项"显示,绝不编数。
        /// </summary>
        public (double 处理器秒, long 物理字节)? 进程用量()
        {
            var 子 = _进程;
            if (子 == null) return null;
            try
            {
                子.Refresh();
                if (子.HasExited) return null;
                return (子.TotalProcessorTime.TotalSeconds, 子.WorkingSet64);
            }
            catch { return null; }        // 刚退出那一瞬间读数会抛:照"没有"处理,不往上冒
        }

        /// <summary>
        /// 通道死了的原因(活得好好的是 null)。**必须能说人话**:ExitCode + 标准错误尾巴。
        /// H39-4:尾巴是**读的时候现拼**的 —— 子进程最后那几行有时比"它退出了"晚一步到,
        /// 在记死因那一刻拼死了,`标准错误末尾` 就永远是空的(踩过)。
        /// </summary>
        public string? 死因
        {
            get
            {
                lock (_等锁)
                {
                    if (_死因 == null) return null;
                    return _死因 + 标准错误尾巴();
                }
            }
        }

        /// <summary>
        /// 起一条通道:跑 `可执行` + `参数`(子进程的入/出被重定向成协议管道)。
        /// **起不来不抛异常** —— 记进 `死因`、`活着 = false`,等真要用它的时候如实报(自检与界面都要能"先看死因")。
        /// </summary>
        public 跑程序通道C(string 可执行, IEnumerable<string>? 参数 = null, string? 工作目录 = null)
        {
            起(可执行, 参数, 工作目录);
        }

        /// <summary>
        /// **就地在起一份自己**当子进程(自检 / `hbcc --跨进程` 走这条;不必先编出 `HB宿主`)。
        /// 认两种跑法:`dotnet hbcc.dll …`(ProcessPath 是 dotnet.exe,得把那份 dll 当第一个参数带上)与
        /// 直接跑 apphost(hbcc.exe 自己就是那一份程序)。
        /// </summary>
        public static 跑程序通道C 从当前进程()
        {
            string 可执行 = Environment.ProcessPath ?? Environment.GetCommandLineArgs()[0];
            var 参数 = new List<string>();
            string[] 命令行 = Environment.GetCommandLineArgs();
            string 首 = 命令行.Length > 0 ? 命令行[0] : "";
            if (首.Length > 0 && 首.EndsWith(".dll", StringComparison.OrdinalIgnoreCase)
                && Path.GetFileName(可执行).StartsWith("dotnet", StringComparison.OrdinalIgnoreCase))
            {
                try { 参数.Add(Path.GetFullPath(首)); } catch { 参数.Add(首); }
            }
            参数.Add(跑程序协议C.服务参数);
            return new 跑程序通道C(可执行, 参数);
        }

        private void 起(string 可执行, IEnumerable<string>? 参数, string? 工作目录)
        {
            记住命令行(可执行, 参数, 工作目录);
            lock (_等锁) { _死因 = null; _状态 = null; }
            _已请求结束 = false;
            lock (_标准错误锁) _标准错误.Clear();
            try
            {
                var 信息 = new ProcessStartInfo(可执行)
                {
                    RedirectStandardInput = true,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,          // 不并进协议:崩了拿它的尾巴说人话
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    StandardErrorEncoding = new UTF8Encoding(false),
                };
                if (!string.IsNullOrEmpty(工作目录)) 信息.WorkingDirectory = 工作目录;
                // H91:子进程那份"准不准弹窗"由**环境变量**过线(协议一个字不动)。
                // 为什么必须过线:程序跑在子进程里,而"弹不弹"是那个进程的静态状态 ——
                // 界面这一侧设了不算。环境变量在子进程启动那一刻读一次,下一次起就是新值。
                信息.Environment[宿主弹窗C.环境变量名] = 宿主弹窗C.允许弹窗 ? "1" : "0";
                foreach (string 一个 in 参数 ?? []) 信息.ArgumentList.Add(一个);

                var 进程 = Process.Start(信息) ?? throw new InvalidOperationException("Process.Start 没给出进程");
                _进程 = 进程;
                _写入 = 进程.StandardInput.BaseStream;     // **走字节流**:不经过任何编码转换(协议是二进制)
                _读出 = 进程.StandardOutput.BaseStream;
                _活着 = true;

                _标准错误线程 = new Thread(收标准错误) { IsBackground = true, Name = "跑程序通道 标准错误" };
                _标准错误线程.Start();
                _泵线程 = new Thread(泵循环) { IsBackground = true, Name = "跑程序通道 读帧" };
                _泵线程.Start();

                // 先把本端版本报过去(对面也会主动报它的;两边对不上就有一边当场说"版本对不上")。
                // 起不来 / 半路断在这儿都不许把构造搞成抛异常:死因已经记下了,谁要用谁去读。
                try { 发命令(跑程序协议C.命令_问候, 写 => 写.Write(跑程序协议C.协议版本)); }
                catch (跑程序通道错误C) { }
            }
            catch (System.ComponentModel.Win32Exception 错)
            {
                // 最常见的一档:路径写错 / 那个 exe 根本不在。系统那句是英文的,放后面当佐证,抬头仍说中文
                记死因($"子进程起不来:可执行文件 `{可执行}` 起不动(系统说:{错.Message})");
            }
            catch (Exception 错)
            {
                记死因($"子进程起不来:{错.Message}(可执行 = {可执行})");
            }
        }

        /// <summary> 再起一份(旧的先体面收场)。"能重连"就靠它(验收①)。 </summary>
        public void 重开()
        {
            结束();
            停旧进程();
            string 可执行 = _上次可执行 ?? Environment.ProcessPath ?? "";
            起(可执行, _上次参数, _上次工作目录);
        }

        private string? _上次可执行;
        private string[]? _上次参数;
        private string? _上次工作目录;
        private void 记住命令行(string 可执行, IEnumerable<string>? 参数, string? 工作目录)
        {
            _上次可执行 = 可执行;
            _上次参数 = 参数 == null ? [] : [.. 参数];
            _上次工作目录 = 工作目录;
        }

        // ===================================================================
        // 发命令 / 等状态
        // ===================================================================

        /// <summary>
        /// 发一条**只发不收**的命令(中断请求 / 清除… / 输入应答 / 图形事件):写完就返回,不等状态。
        /// 通道断了就抛 —— 调用方要给用户一个说法,不许当成"发过了"。
        /// </summary>
        public void 发命令(byte 消息号, Action<BinaryWriter>? 写载荷 = null)
        {
            if (!_活着 || _写入 == null) throw new 跑程序通道错误C("跑程序通道已经断了:" + 死因话());
            try
            {
                跑程序协议C.写帧(_写入, _写锁, 消息号, 写载荷);
            }
            catch (Exception 错)
            {
                记死因("往子进程写不出去:" + 错.Message);
                throw new 跑程序通道错误C("跑程序通道写不出去:" + 错.Message, 错);
            }
        }

        /// <summary>
        /// 发一条**要回执**的命令,并等它那条"状态"帧(命令 ↔ 状态 一一对应)。
        /// 通道断了 / 子进程半路没了 → 抛 `跑程序通道错误C`(带上死因与标准错误尾巴)。
        /// </summary>
        public 跑程序协议C.跑程序状态C 发命令并等状态(byte 消息号, Action<BinaryWriter>? 写载荷 = null)
        {
            lock (_命令锁)
            {
                lock (_等锁) _状态 = null;
                发命令(消息号, 写载荷);
                lock (_等锁)
                {
                    while (_状态 == null)
                    {
                        if (!_活着) throw new 跑程序通道错误C("跑程序通道已经断了:" + 死因话());
                        Monitor.Wait(_等锁);
                    }
                    var 状态 = _状态;
                    _状态 = null;
                    return 状态;
                }
            }
        }

        /// <summary>
        /// H13:发一条"要**重载回执**"的命令(只有 `命令_重载` 走它)并等那条 `事件_重载`。
        ///
        /// 为什么单独一条路:重载的应答**不走状态帧**(状态帧是"命令 ↔ 状态"一一对应的那一套,
        /// 而重载要带回一张迁移表)—— 与图形回执同一个理由:**由读帧线程收**,因为发重载的这条线程
        /// 正卡在等它(塞进命令队列会自己锁死自己)。
        /// </summary>
        public 虚拟机C.重载迁移C 发命令并等重载(byte 消息号, Action<BinaryWriter>? 写载荷 = null)
        {
            lock (_命令锁)
            {
                lock (_等重载锁) _重载迁移 = null;
                发命令(消息号, 写载荷);
                lock (_等重载锁)
                {
                    while (_重载迁移 == null)
                    {
                        if (!_活着) throw new 跑程序通道错误C("跑程序通道已经断了:" + 死因话());
                        Monitor.Wait(_等重载锁);
                    }
                    var 迁移 = _重载迁移;
                    _重载迁移 = null;
                    return 迁移;
                }
            }
        }

        /// <summary>
        /// 现在有没有一条"要等回执"的命令在路上(界面线程据此判断"能不能顺手要一份镜像")。
        ///
        /// 为什么要有它:「跑到」可能跑好几分钟,而**变量面板 / 取快照随时可能被界面线程调到** ——
        /// 那时候跟着发一条"读内存"并等回执,就会一直等到那一趟跑完(界面看着就是冻住)。
        /// 所以"要镜像"这件事在忙的时候**放过这一次**:状态本来就是旧的那一份,等那一趟回来自然就新了。
        /// </summary>
        public bool 有命令在跑
        {
            get
            {
                if (Monitor.TryEnter(_命令锁)) { Monitor.Exit(_命令锁); return false; }
                return true;
            }
        }

        /// <summary> 投一个图形事件给子进程(类型 / 键码 / x / y;口径与 `图形宿主C.投事件` 一字不差)</summary>
        public void 送图形事件(int 类型, int 键码, int x, int y) =>            发命令(跑程序协议C.命令_图形事件, 写 =>
            {
                写.Write(类型);
                写.Write(键码);
                写.Write(x);
                写.Write(y);
            });

        // ===================================================================
        // 收帧(泵线程)
        // ===================================================================

        private void 泵循环()
        {
            try
            {
                while (true)
                {
                    var 帧 = 跑程序协议C.读帧(_读出!);
                    if (帧 == null) { 记子进程退出(); return; }
                    var (消息号, 载荷) = 帧.Value;
                    switch (消息号)
                    {
                        case 跑程序协议C.事件_问候:
                            using (var 读 = 跑程序协议C.开读(载荷))
                            {
                                int 版本 = 读.ReadInt32();
                                后端说明 = 读.ReadString();
                                if (版本 != 跑程序协议C.协议版本)
                                    记死因($"协议版本对不上:子进程说 {版本},这一侧是 {跑程序协议C.协议版本}" +
                                        "(两边必须用同一份 `跑程序协议C`)");
                            }
                            break;
                        case 跑程序协议C.事件_输出:
                            using (var 读 = 跑程序协议C.开读(载荷))
                                foreach (byte 一个 in 跑程序协议C.读块(读)) 输出目标?.Invoke(一个);
                            break;
                        case 跑程序协议C.事件_请求输入: 回答输入(); break;
                        case 跑程序协议C.事件_内存增量:
                            using (var 读 = 跑程序协议C.开读(载荷))
                                收到内存增量?.Invoke(跑程序协议C.读内存增量(读));
                            break;
                        case 跑程序协议C.事件_图形命令: 回放图形命令(载荷); break;
                        case 跑程序协议C.事件_状态:
                            using (var 读 = 跑程序协议C.开读(载荷))
                            {
                                var 状态 = 跑程序协议C.读状态(读);
                                lock (_等锁) { _状态 = 状态; Monitor.PulseAll(_等锁); }
                            }
                            break;
                        case 跑程序协议C.事件_重载:
                            using (var 读 = 跑程序协议C.开读(载荷))
                            {
                                var 迁移 = 跑程序协议C.读迁移(读);
                                lock (_等重载锁) { _重载迁移 = 迁移; Monitor.PulseAll(_等重载锁); }
                            }
                            break;
                        case 跑程序协议C.事件_致命错误:
                            using (var 读 = 跑程序协议C.开读(载荷))
                                记死因("子进程报致命错误:" + 读.ReadString());
                            break;
                        default:
                            记死因($"认不出的消息号 {消息号}(两边协议版本对不上?)");
                            break;
                    }
                }
            }
            catch (Exception 错)
            {
                记死因("读帧出错:" + 错.Message);
            }
        }

        /// <summary>
        /// 子进程要输入:调前端自己身上的 `输入源`(与进程内同一套注入口径 —— IDE 的字节队列 / 命令行的
        /// 标准输入都照旧),再把结果当"输入应答"发回去。这里是**泵线程**,前端那条主线程还在等状态帧。
        /// </summary>
        private void 回答输入()
        {
            // 前端没有输入 / 输入源抛了 ⇒ 如实当"没有输入了"(子进程那边按 `等输入` 那一档决定停不停)
            bool 有 = false;
            byte 值 = 0;
            try
            {
                if (输入源?.Invoke() is uint 一个) { 有 = true; 值 = (byte)一个; }
            }
            catch { 有 = false; }
            try
            {
                发命令(跑程序协议C.命令_输入应答, 写 =>
                {
                    写.Write(有 ? 跑程序协议C.输入_有字节 : 跑程序协议C.输入_没有);
                    if (有) 写.Write(值);
                });
            }
            catch (跑程序通道错误C) { /* 通道已经断了:子进程那边会因为读不到应答而收摊 */ }
        }

        /// <summary>
        /// 收到"图形命令"就回放给**前端本地**的呈现口(口径 a:窗口在前端进程里画),
        /// 再把结果回一条**图形回执**给子进程(H39-3)。
        /// 注意"等待"那一档:子进程已经真睡过了,这一侧**不再重睡**(两边各睡一次 = 帧节拍只剩一半)。
        ///
        /// **回放失败也照旧回执**(不是记一句就完):子进程那一侧在等这一条 —— 不回它就得等到超时。
        /// 前端画不出来(呈现口抛了 / 这一侧没挂呈现口)⇒ 回"失败"⇒ 子进程让程序拿到
        /// `状态_开不了窗口`,与进程内"呈现口抛异常"**同一个出口**。
        /// </summary>
        private void 回放图形命令(byte[] 载荷)
        {
            var 口 = 呈现口;
            uint 序号 = 0;
            byte 种类 = 0;
            bool 成功 = false;
            string 说明 = "";
            try
            {
                using var 读 = 跑程序协议C.开读(载荷);
                序号 = 读.ReadUInt32();
                if (口 == null)
                {
                    // 这一侧没有图形能力:与其抛,不如如实回"画不了"(与"没挂呈现口"同口径)
                    说明 = "这一侧的跑程序前端没有挂呈现口(没有窗口可画)";
                }
                else
                {
                    种类 = 读.ReadByte();
                    switch (种类)
                    {
                        case 跑程序协议C.图形_打开窗口:
                        {
                            string 标题 = 读.ReadString();
                            int 宽 = 读.ReadInt32(), 高 = 读.ReadInt32();
                            口.打开窗口(标题, 宽, 高);
                            break;
                        }
                        case 跑程序协议C.图形_关闭窗口: 口.关闭窗口(); break;
                        case 跑程序协议C.图形_呈现:
                        {
                            int 条数 = 读.ReadInt32();
                            var 一帧 = new List<绘制命令C>(Math.Max(0, 条数));
                            for (int i = 0; i < 条数; i++) 一帧.Add(跑程序协议C.读绘制命令(读));
                            口.呈现(一帧);
                            break;
                        }
                        case 跑程序协议C.图形_等待: _ = 读.ReadInt32(); break;   // 已经睡过:照样读掉字段,不重睡
                    }
                    成功 = true;
                }
            }
            catch (Exception 错)
            {
                成功 = false;
                说明 = $"回放图形命令(种类 {种类})时出错:{错.Message}";
            }
            if (!成功) 图形口问题 = 说明;
            回图形回执(序号, 成功, 说明);
        }

        /// <summary>
        /// H39-3:把这一条图形命令的结果回给子进程(**成功 / 失败都要回** —— 不回它就得等到超时)。
        /// 通道已经断了就吞掉:那种情况下子进程那边马上就看得见"前端走了",不必在这儿再报一遍。
        /// </summary>
        private void 回图形回执(uint 序号, bool 成功, string 说明)
        {
            try
            {
                发命令(跑程序协议C.命令_图形回执, 写 =>
                {
                    写.Write(序号);
                    写.Write(成功 ? 跑程序协议C.图形回执_好 : 跑程序协议C.图形回执_失败);
                    写.Write(说明 ?? "");
                });
            }
            catch (跑程序通道错误C) { }
        }

        /// <summary>
        /// 回放图形命令时出错的那一句(**null = 没出过错**)。留给前端(IDE)显示"窗口这一侧没画成";
        /// H39-3 起它也记"这一侧压根没挂呈现口"那一档。**它不影响"跑程序"本身**:程序照跑,通道照活。
        /// </summary>
        public string? 图形口问题 { get; private set; }

        // ===================================================================
        // 标准错误 / 死因 / 收摊
        // ===================================================================

        private void 收标准错误()
        {
            try
            {
                while (_进程?.StandardError.ReadLine() is { } 行)
                    lock (_标准错误锁)
                    {
                        _标准错误.Enqueue(行);
                        while (_标准错误.Count > 标准错误留几行) _标准错误.Dequeue();
                    }
            }
            catch { /* 进程没了:收工 */ }
        }

        private void 记子进程退出()
        {
            // 前端主动发过"结束"的,是**体面收场**,不是死因(通道不再可用,但没什么可说的)
            if (_已请求结束)
            {
                lock (_等锁) { _活着 = false; Monitor.PulseAll(_等锁); }
                return;
            }
            int? 码 = null;
            try { if (_进程 != null && _进程.WaitForExit(1000)) 码 = _进程.ExitCode; } catch { }
            // H39-4:尾巴那几行是"说得清"的一半 —— 先把收标准错误那条线程等一会儿(它读到管道末尾就收工),
            // 别在它把子进程最后的脚印写进队列之前就把死因定稿(不然 `标准错误末尾` 老是空的)。
            等标准错误收尾();
            记死因(码 switch
            {
                // -1 = TerminateProcess 那一档(被 `Process.Kill` / 任务管理器强行终止):如实说清是被打死的,
                // 别糊成"退出码没取到"(那是另一回事:管道末尾到了、进程对象还没落定)
                -1 => $"子进程{进程号话()}被强行终止(退出码 -1)",
                int 值 => $"子进程{进程号话()}已退出,退出码 {值}",
                null => $"子进程{进程号话()}的标准输出到了末尾(它退出了,退出码没来得及取到)",
            });
        }

        /// <summary> H39-4:等收标准错误那条线程收工最多这么久(子进程已经没了,它读得到管道末尾) </summary>
        private const int 等标准错误毫秒 = 300;
        private void 等标准错误收尾()
        {
            try { _标准错误线程?.Join(等标准错误毫秒); } catch { }
        }

        /// <summary>
        /// H39-4:子进程号(还没起 / 已经收场就是 null)。给人看的那句话里带上它 ——
        /// "是哪个进程没了"在任务管理器里对得上号;自检也拿它去**故意打死子进程**(钉"崩了能重连")。
        /// </summary>
        public int? 子进程号
        {
            get { try { return _进程?.Id; } catch { return null; } }
        }

        private string 进程号话() => 子进程号 is int 号 ? $"(进程号 {号})" : "";

        private void 记死因(string 原因)
        {
            lock (_等锁)
            {
                _死因 ??= 原因;                          // 只留**抬头**那一句;标准错误尾巴由 `死因` 现拼(见它的注释)
                _活着 = false;
                Monitor.PulseAll(_等锁);                  // 在等状态的人当场醒过来抛"通道断了"
            }
        }

        private string 标准错误尾巴()
        {
            string[] 行;
            lock (_标准错误锁) 行 = [.. _标准错误];
            return 行.Length == 0 ? "" : ";标准错误末尾:" + string.Join(" | ", 行);
        }

        /// <summary> 死因那一句(没死就说"通道还活着"——调用方只在断了之后才该问它)</summary>
        private string 死因话() => 死因 ?? "子进程没声了(没记下具体原因)";

        /// <summary> 体面收场:发一条"结束"让子进程自己退(它那边会先叫停长跑)</summary>
        public void 结束()
        {
            if (!_活着) return;
            _已请求结束 = true;
            try { 发命令(跑程序协议C.命令_结束); } catch (跑程序通道错误C) { }
        }

        private void 停旧进程()
        {
            try
            {
                if (_进程 != null && !_进程.HasExited)
                {
                    _进程.WaitForExit(1500);              // 给它 1.5 秒体面退出(结束帧 + 长跑被叫停)
                    if (!_进程.HasExited) _进程.Kill(entireProcessTree: true);
                }
            }
            catch { }
            try { _进程?.Dispose(); } catch { }
            _进程 = null;
            _写入 = null;
            _读出 = null;
        }

        public void Dispose()
        {
            结束();
            停旧进程();
        }
    }

    /// <summary>
    /// **H39-1:跨进程的虚拟机** —— 与 <see cref="虚拟机C"/> 同一个面孔(装载 / 单步 / 运行 / 中断 / 图形…),
    /// 但真跑程序的那台机器住在子进程里,这一份只是**镜像 + 通道**。
    ///
    /// <para>**口径 c(状态住后端、前端只拿小增量与快照)**:前端留着**镜像内存与镜像寄存器** ——
    /// 状态帧里的 PC / 寄存器 / 栈指针 / 旗标直接更新镜像,内存靠"内存增量"贴。
    /// `单步()` 只更新状态(**不发内存增量**,每步要小);前端要读内存之前调一次 `同步镜像()`。</para>
    ///
    /// <para>**为什么 `装载` 帧要带上初值表 / 源行表 / 白名单**:这三样都是"跑程序要用、但只在前端手里"的东西
    /// (初值随编译结果来、源行表给报错带行号、白名单从工程文件来)。带过去之后,进程内那一条路上的
    /// catch(`运行期错误C`)与注入口径(输入源 / 输出目标)在跨进程这条路上**一个字不用改**。</para>
    /// </summary>
    public sealed class 跨进程虚拟机C : 虚拟机C
    {
        /// <summary> 这条虚拟机住哪条通道里(命令 / 状态 / 图形 / 内存增量都从它过)</summary>
        public 跑程序通道C 通道 { get; }

        /// <summary>
        /// 装载帧里带给子进程的源行表(与进程内的 `取源位置` 同一个用途:运行期报错带文件 + 行号)。
        /// 前端这一侧也用它 —— `运行` 撞步数上限时那一句错误文案要按它查行号(与进程内一字不差)。
        /// </summary>
        public 源行表C? 源行表 { get; set; }

        /// <summary>
        /// H39-2:这一侧的图形呈现口 —— **子进程把绘制命令打成帧、这一侧回放给谁**就是它
        /// (口径 a:窗口在前端进程里画)。基类那个同名属性对进程内那台是"没这回事"。
        /// </summary>
        public override 图形呈现口C? 图形呈现口
        {
            get => 通道.呈现口;
            set => 通道.呈现口 = value;
        }

        /// <summary>
        /// H39-3:`--事件脚本` 那份脚本的**原文** —— 随装载帧带给子进程,由**子进程那一侧的 `图形宿主C` 挂上**。
        ///
        /// 为什么脚本要过线而不是由前端按帧喂:帧号口径(打开窗口 = 第 0 帧 / 每 `刷新()` 进下一帧)、
        /// 跑满帧数投关窗请求、帧数宽限那道"程序不理关窗请求就报错"的护栏,全都在 `图形宿主C` 里、
        /// 而它跑在子进程 —— 原文过去、那边用**同一个解析器**再解一遍,两套跑法就只有一份语义实现。
        /// null / 空串 = 这一趟没有脚本。
        /// </summary>
        public string? 事件脚本文本 { get; set; }

        /// <summary> H39-2:账记在子进程那一侧(见 `虚拟机C.要记账` / `上次记账`) </summary>
        public override bool 要记账 { get; set; }

        /// <summary> H39-2:上一条命令带回来的记账(装载 / 单步 / 跑到之后就是新的;前端拿它复原调用栈 + 重放寄存器说明) </summary>
        public override 跑程序协议C.跑程序记账C? 上次记账 { get; set; }

        /// <summary> H39-2:这条通道还接得上吗(断了 ⇒ 下一次"执行"要换一条新的,见 `虚拟机C.通道可用`) </summary>
        public override bool 通道可用 => 通道.活着;

        /// <summary> H39-2:把一个图形事件送回子进程那台虚拟机(桌面壳的键盘 / 鼠标走这条) </summary>
        public override void 送图形事件(int 类型, int 键码, int x, int y)
        {
            try { 通道.送图形事件(类型, 键码, x, y); } catch (跑程序通道错误C) { /* 通道断了:下一次装载会如实报 */ }
        }

        /// <summary> 回放图形命令时出错的那一句(null = 没出过错;见 `跑程序通道C.图形口问题`) </summary>
        public string? 图形口问题 => 通道.图形口问题;

        public 跨进程虚拟机C(跑程序通道C 通道)
        {
            this.通道 = 通道 ?? throw new ArgumentNullException(nameof(通道));
            // 输入 / 输出走**前端自己身上**那两个回调(与进程内同一套注入口径,IDE 与 CLI 都不用改代码):
            // 通道那头调的是这条 lambda,它每次现读本对象的属性 —— 于是调用方后面再赋值也照样生效。
            通道.输入源 = () => 输入源?.Invoke();
            通道.输出目标 = b => 输出目标?.Invoke(b);
            通道.收到内存增量 = 贴增量;
        }

        /// <summary> 自检 / `hbcc --跨进程` 用:就地在起一份自己当子进程 </summary>
        public static 跨进程虚拟机C 从当前进程() => new(跑程序通道C.从当前进程());

        /// <summary>
        /// **H39-4:崩了能重连** —— 同一条机器(同一个 `调试会话`、断点表、镜像这几张面孔都还在这份对象上)
        /// 换一条新的通道。子进程那台机器是**全新的**(内存全 0、PC = 0),所以重连之后必须**重新装载**:
        /// 这一格立起来给 `需要重新装载` 认(重连那一刻"停机 = false 且机器码还是同一份"完全可能,
        /// 只看基类那三条判据会漏掉这一档 —— 那就成了"跑在一台空内存上"的静默错)。
        /// 返回 false = 新的子进程也没起来(原因在 `通道.死因`,调用方如实念给用户听)。
        /// </summary>
        public bool 重连()
        {
            通道.重开();
            上次记账 = null;
            _重连过 = true;
            return 通道.活着;
        }

        /// <summary> H39-4:重连过还没重新装载(装一次就复位) </summary>
        private bool _重连过;

        // ---------------- 一次命令(发出去 + 等状态 + 更新镜像) ----------------

        /// <summary>
        /// 走一趟命令:发 → 等状态 → 更新镜像 → 该抛的抛。
        /// 结果码为"运行期错误"时抛 `运行期错误C`(**说明 / 源码行 / 位置 / PC 都用子进程给的那一份**,
        /// 一个字不另编 —— 于是进程内那些 `catch (运行期错误C)` 一个字不用改)。
        /// </summary>
        private 跑程序协议C.跑程序状态C 走一趟(byte 消息号, Action<BinaryWriter>? 写载荷 = null)
        {
            上次记账 = null;                       // 这一趟的账要现收:上一趟的不能留(不然会重复重放)
            var 状态 = 通道.发命令并等状态(消息号, 写载荷);
            应用状态(状态);
            上次记账 = 状态.记账;
            if (状态.结果码 == 跑程序协议C.结果_运行期错误)
                throw new 运行期错误C(状态.说明, 状态.源码行, 状态.程序计数器, 状态.位置);
            if (状态.结果码 != 跑程序协议C.结果_正常)
                throw new 跑程序通道错误C($"子进程报『{状态.说明}』(结果码 {状态.结果码})");
            return 状态;
        }

        /// <summary> 把状态帧里的整机小快照贴进这一份镜像(内存不在里面:它在增量帧里) </summary>
        private void 应用状态(跑程序协议C.跑程序状态C 状态)
        {
            程序计数器 = 状态.程序计数器;
            for (int i = 0; i < 寄存器.Length && i < 状态.寄存器.Length; i++) 寄存器[i] = 状态.寄存器[i];
            栈指针 = 状态.栈指针;
            状态标志 = 状态.状态标志;
            停机 = 状态.停机;
            命中断点 = 状态.命中断点;
            已中断 = 状态.已中断;
            正在等输入 = 状态.正在等输入;
            上一条指令地址 = 状态.上一条指令地址;
            已执行条数 = 状态.已执行条数;
        }

        private void 贴增量(IReadOnlyList<(int 起址, byte[] 字节)> 段们)
        {
            if (内存.Length == 0) return;
            跑程序协议C.贴内存增量(内存, 段们);
        }

        // ---------------- `虚拟机C` 那些口子(全部改成走通道) ----------------

        /// <summary>
        /// 装载:先让**这一份镜像**按同一套规矩复位(校验、清内存、PC = 0、寄存器归零 —— 复用的就是基类
        /// 那个方法体,一个字没改),再把同一份东西装进子进程那一台。
        /// 内存容量随这一帧带过去(没有单独一条"设内存大小"的消息:容量只在装载那一刻有意义)。
        /// </summary>
        public override void 装载(byte[] 机器码)
        {
            base.装载(机器码);
            走一趟(跑程序协议C.命令_装载, 写 =>
            {
                写.Write(内存大小);
                跑程序协议C.写块(写, 机器码);
                跑程序协议C.写初值表(写, 初值表);
                跑程序协议C.写源行表(写, 源行表);
                // 白名单在**发送这一刻**从宿主能力那一份静态表里读:调用方(IDE / CLI)本来就会在跑之前
                // `宿主能力C.设可执行白名单(…)`,于是"声明过什么"这件事不用再让调用方重设一遍
                跑程序协议C.写可执行白名单(写, 宿主能力C.可执行白名单);
                跑程序协议C.写网址白名单(写, 宿主能力C.网址白名单);
                写.Write(图形呈现口 != null);   // 这一侧有图形口 ⇒ 子进程才挂"转发呈现口"
                写.Write(等输入);
                写.Write(要记账);               // H39-2:调试那条腿要账(单步 / 跑到也各带一次,怕中途改主意)
                写.Write(事件脚本文本 ?? "");    // H39-3:脚本在**真正跑程序的那一侧**按帧喂(空 = 没有脚本)
                // H13:热重载要用的几张表 —— 子进程把这一份记下来,等 `命令_重载` 时判"旧那一份是什么样"
                跑程序协议C.写全局槽(写, 名字表);
                跑程序协议C.写分区表(写, 内存分区);
                跑程序协议C.写标签表(写, 标签表);
                跑程序协议C.写代码字节数(写, 代码字节数);
            });
            _重连过 = false;                     // H39-4:新通道那台机器已经装上了,重连那一档的账结掉
        }

        /// <summary> 单步(只更新状态,不发内存增量:每步要小)。撞上运行期错误照原样抛。 </summary>
        public override bool 单步()
        {
            走一趟(跑程序协议C.命令_单步, 写 =>
            {
                写.Write(等输入);
                写.Write(要记账);
            });
            return !停机;
        }

        /// <summary> 跑到:断点地址表 + 步数上限都过线,回来的"停下原因"直接就是基类那个枚举 </summary>
        public override 停下原因C 跑到(IReadOnlyCollection<int> 断点地址, long 上限)
        {
            var 状态 = 走一趟(跑程序协议C.命令_跑到, 写 =>
            {
                写.Write(断点地址.Count);
                foreach (int 地址 in 断点地址) 写.Write(地址);
                写.Write(上限);
                写.Write(等输入);
                写.Write(要记账);
            });
            return 状态.停下 == 跑程序协议C.停_没有 ? 停下原因C.停机 : (停下原因C)状态.停下;
        }

        /// <summary>
        /// 整程序跑:装载 → "跑到"(无断点、上限 = 步数上限)→ 顺手同步镜像(前端跑完要读内存查运行期报错)。
        /// 撞上限抛的**是同一句话**(文案的唯一事实源在 `虚拟机C.步数超限说明`),行号按这一侧的源行表查。
        /// `跟踪` 这一档在跨进程这条路上没有落点(子进程不在这个控制台里),与进程内不同,如实记在这儿。
        /// </summary>
        public override void 运行(byte[] 机器码, bool 跟踪 = false)
        {
            装载(机器码);
            var 原因 = 跑到([], 步数上限);
            同步镜像();
            if (原因 != 停下原因C.步数上限) return;

            string 位置 = "";
            try { 位置 = 源行表?.查位置(程序计数器) ?? ""; } catch { 位置 = ""; }
            int 行 = 位置.Length > 0 ? 0 : (源行表?.查行号(程序计数器) ?? 0);
            throw new 运行期错误C(虚拟机C.步数超限说明(步数上限), 行, 程序计数器, 位置);
        }

        /// <summary> 内存容量:这一份镜像按新容量重开(校验也走基类那一个);大小随下一次"装载"带过去 </summary>
        public override void 设内存大小(int 字节数) => base.设内存大小(字节数);

        /// <summary>
        /// H13:**热重载** —— 真正在跑的那一台在子进程里,所以这一侧**先判一次**(判据 = `虚拟机C.重载`),
        /// 判出来的迁移表既落在这一份镜像上、又原样发给子进程**照贴**(子进程这一趟一个判据都不跑)。
        ///
        /// 为什么不让子进程自己判:它那边"上一份表"的挂表时机与这一侧不同(装载帧到重载帧之间还会换一次),
        /// 各判一遍必然分叉 —— 实测过,子进程自己判时一只变量都保不住(见 `任务清单.md` 第324批)。
        /// </summary>
        public override void 重载(byte[] 机器码, IReadOnlyList<初值项C>? 旧初值表 = null, 名字表C? 旧名字表 = null,
            IReadOnlyList<内存分区C>? 旧分区表 = null, 虚拟机C.重载迁移C? 判好的迁移 = null, 名字表C? 新名字表 = null,
            int 新代码字节数 = -1, IReadOnlyDictionary<string, int>? 新标签表 = null,
            IReadOnlyList<内存分区C>? 新分区表 = null)
        {
            ArgumentNullException.ThrowIfNull(机器码);
            var 给名字表 = 新名字表 ?? 名字表;
            var 给标签表 = 新标签表 ?? this.标签表;
            var 给分区表 = 新分区表 ?? 内存分区;
            int 给代码长 = 新代码字节数 >= 0 ? 新代码字节数 : 代码字节数;

            // ① 先在这一份镜像上判一遍(判据 = 基类 `虚拟机C.重载`),判完的迁移表再发给子进程照贴。
            //    注意第 5 个参数**必须显式传 null**:那一格是"已经判好的迁移",给非空值基类就会早退、
            //    一个判据都不跑(踩过 —— 判据次数 0、迁移表空,子进程那边跟着一起什么都没有)。
            var 迁移 = new 虚拟机C.重载迁移C();
            if (判好的迁移 is { } 现成)
            {
                按迁移重摆内存(机器码, 现成);
                迁移 = 现成;
            }
            else
            {
                // 判据走 `判迁移并重摆`(不能走 `重载`:那个入口见到"判好的迁移"就早退),
                // 判出来的段 / 旧初值 / 说明一并抄进 `迁移`,下面原样发给子进程照贴。
                判迁移并重摆(机器码, 旧初值表 ?? 装载时初值表, 旧名字表 ?? 装载时名字表,
                    旧分区表 ?? 装载时内存分区, 给名字表, 给代码长, 给标签表, 给分区表, 迁移);
            }
            // 迁移表里要带上"旧常量"(子进程照它把旧常量拽回出厂值)与给人看的说明
            抄旧初值(迁移);
            foreach (string 一条 in 上次重载说明) if (!迁移.说明.Contains(一条)) 迁移.说明.Add(一条);

            // ② 发给子进程照贴(它这一趟一个判据都不跑;这一帧只带"新机器码 + 判好的迁移")
            通道.发命令并等重载(跑程序协议C.命令_重载, 写 =>
            {
                写.Write(内存大小);
                跑程序协议C.写块(写, 机器码);
                跑程序协议C.写初值表(写, 初值表);
                写.Write(给代码长);
                跑程序协议C.写迁移(写, 迁移);
            });
            上次迁移 = 迁移;
            _重连过 = false;
        }

        /// <summary> H13:最近一次重载后端判出来的迁移表(自检量用;null = 还没重载过) </summary>
        public 虚拟机C.重载迁移C? 上次迁移 { get; private set; }

        /// <summary> 要不要重新装载:基类那三条判据照旧,再加两条 ——**通道死了就必须重来**(子进程里那台机器没了)、
        /// **重连过还没重新装载**也必须重来(H39-4:新子进程那台是空内存,不重装就是静默跑空) </summary>
        public override bool 需要重新装载(byte[] 机器码) => _重连过 || base.需要重新装载(机器码) || !通道.活着;

        /// <summary>
        /// 请求停下:本端那面旗先立起来(界面靠 `有中断请求` 说一句"正在停止…"),再**原样送到子进程**。
        /// 只发不收:等到下一道闸门自然会从状态帧的旗标上看到"已中断"(同步等会把自己锁死)。
        /// </summary>
        public override void 请求中断()
        {
            base.请求中断();
            try { 通道.发命令(跑程序协议C.命令_中断请求); }
            catch (跑程序通道错误C) { /* 本端的旗已经立了;真要紧的是下一次装载会如实报"通道断了" */ }
        }

        /// <summary>
        /// 取中断请求:子进程那一侧说了算(它才是真正会停下来的那一台);本端那面旗顺手消费掉
        /// (不消费的话 `有中断请求` 永远是真,界面一直显示"正在停止")。
        /// </summary>
        public override bool 取中断请求()
        {
            var 状态 = 走一趟(跑程序协议C.命令_取中断请求);
            base.取中断请求();
            return 状态.有中断请求;
        }

        /// <summary>
        /// **运行监视(H100 第一步)**:子进程那台真机用掉了多少 CPU 与物理内存。
        /// 真正的读数在**通道**那一侧(它是 `Process` 的主人,见 `跑程序通道C.进程用量`);
        /// 这一层只转发 —— 走 OS 读数,**不占协议、不问后端**,所以跑到一半也读得到。
        /// 拿不到(还没起来 / 已经退出 / 读数抛错)一律给 **null**:界面照"没有这一项"显示,绝不编数。
        /// </summary>
        public override (double 处理器秒, long 物理字节)? 进程用量() => 通道.进程用量();

        public override void 清除中断请求()
        {
            base.清除中断请求();
            try { 通道.发命令(跑程序协议C.命令_清除中断请求); } catch (跑程序通道错误C) { }
        }

        /// <summary> 清"正在等输入":本端镜像先清,子进程那一侧也要清(不然接着跑时它一步都不动 —— R2-6 那个坑)</summary>
        public override void 清除等待输入()
        {
            base.清除等待输入();
            try { 通道.发命令(跑程序协议C.命令_清除等待输入); } catch (跑程序通道错误C) { }
        }

        /// <summary>
        /// 把内存增量要过来贴上(前端要读内存 / 查运行期报错之前调一次;单步不走这一步)。
        /// **另一条命令还在路上时不干等**(见 `跑程序通道C.有命令在跑`):宁可这一趟看旧镜像,也别把界面冻住。
        /// </summary>
        public override void 同步镜像()
        {
            if (通道.有命令在跑) return;
            走一趟(跑程序协议C.命令_读内存);
        }
    }
