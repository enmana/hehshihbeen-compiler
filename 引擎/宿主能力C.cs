        /// <summary>
        /// 这段机器码**最多用到几号宿主能力**(扫 `宿主调用` 0x31 的 20 位立即数;一个都没用到给 0)。
        ///
        /// 用途:宿主是旧的那一版时判"这个程序用得到它没有的能力吗" —— 用得到就**不产这一份 exe**
        /// (产出来必然是"打开窗口给 假"那种骗人的产物),用不到就照产、但如实说清。
        /// </summary>
        public static int 这段机器码要的功能号上限(byte[] 机器码)
        {
            int 上限 = 0;
            for (int i = 0; i + 3 < 机器码.Length; i += 4)
            {
                uint 指令 = (uint)(机器码[i] | (机器码[i + 1] << 8) | (机器码[i + 2] << 16) | (机器码[i + 3] << 24));
                if ((指令 >> 24) != 0x31) continue;                 // 0x31 = `宿主调用`
                int 功能号 = (int)(指令 & 0xFFFFF);
                if (功能号 > 上限) 上限 = 功能号;
            }
            return 上限;
        }

        /// <summary>
        /// 解析"问一句 `--能力`"的答案(**纯函数**:自检拿假的输出与退出码就能钉它,不必真起进程)。
        /// 判"够新"三条:① 输出里有能力标记 ② 自报的最大功能号 ≥ `该到几号`(缺省 = 当前最大功能号)
        /// ③ 自报的包格式 ≥ `该到包格式`(`该到包格式` = 0 = 这次不看这一条)。
        /// 差一条就给一句**说人话的为什么**(`陈旧`),调用方照"假自包含"那套**如实说清 + 后台重发**。
        /// </summary>
        public static 宿主能力种C 解析能力清单(string? 标准输出, int 退出码, int 该到几号 = 0, int 该到包格式 = 0)
        {
            if (该到几号 <= 0) 该到几号 = 当前最大功能号;
            string 文 = 标准输出 ?? "";
            if (!文.Contains(能力标记, StringComparison.Ordinal))
                return new 宿主能力种C
                {
                    会自报 = false,
                    最大功能号 = 0,
                    陈旧 = 退出码 == 0
                        ? $"它没打能力标记(`{能力标记}` 那一行),认不出是哪一版"
                        : $"它不认 `{能力请求参数}`(问它一句,退出码 {退出码},输出里也没有 `{能力标记}` 那一行)—— 比会自报能力的这一版还老",
                };

            int 号 = 0;
            int 包 = 0;
            int 集 = 0;
            // ⚠ 三条判据各自独立、**一律不许 `continue`**:清单里"最大功能号"那一行排在最前面,
            //   一写 `continue` 就把后面那两行(包格式 / 指令集)整段跳过(F-4 实测踩到:指令集恒 0,
            //   于是连当前这一版都被判陈旧)。
            foreach (string 行 in 文.Replace("\r\n", "\n").Split('\n'))
            {
                string 净 = 行.Trim();
                int 等号 = 净.IndexOf('=');
                if (等号 < 0) continue;
                string 值 = 净[(等号 + 1)..].Trim();
                if (号 == 0 && 净.StartsWith(能力行最大功能号, StringComparison.Ordinal))
                {
                    if (int.TryParse(值, out int 数)) 号 = 数;
                    continue;
                }
                if (包 == 0 && 净.StartsWith(能力行包格式, StringComparison.Ordinal))
                {
                    if (int.TryParse(值, out int 数)) 包 = 数;
                    continue;
                }
                // F-4:指令集上界(报的是 `0xNN` 这种十六进制写法;**认不出的写法一律当作"没报"** ——
                // 静默收下一个 0 会把"老宿主"误判成"够新",那正是这一条要治的毛病)
                if (集 == 0 && 净.StartsWith(能力行指令集, StringComparison.Ordinal))
                {
                    // ⚠ `int.TryParse` 带 `NumberStyles.HexNumber` **不认 `0x` 前缀**
                    //   (实测:喂 `0x62` 直接返回 false ⇒ 恒读成"没报",连当前那一版都被判陈旧)⇒ 前缀自己剥。
                    string 十六进制 = 值.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? 值[2..] : 值;
                    if (int.TryParse(十六进制, System.Globalization.NumberStyles.HexNumber,
                            System.Globalization.CultureInfo.InvariantCulture, out int 数))
                        集 = 数;
                }
            }
            if (号 <= 0)
                return new 宿主能力种C { 会自报 = true, 最大功能号 = 0, 包格式 = 包, 指令集上界 = 集, 陈旧 = "它会自报能力,却没写清最大功能号" };
            if (号 < 该到几号)
                return new 宿主能力种C
                {
                    会自报 = true,
                    最大功能号 = 号,
                    包格式 = 包,
                    指令集上界 = 集,
                    陈旧 = 缺哪一档文本(号, 该到几号),
                };
            if (集 < 当前指令集上界)
                return new 宿主能力种C
                {
                    会自报 = true,
                    最大功能号 = 号,
                    包格式 = 包,
                    指令集上界 = 集,
                    陈旧 = 指令集原因(集),
                };
            if (该到包格式 > 0 && 包 < 该到包格式)
                return new 宿主能力种C { 会自报 = true, 最大功能号 = 号, 包格式 = 包, 指令集上界 = 集, 陈旧 = 包格式原因(包, 该到包格式) };
            return new 宿主能力种C { 会自报 = true, 最大功能号 = 号, 包格式 = 包, 指令集上界 = 集, 陈旧 = null };
        }

        /// <summary>
        /// "它缺的是哪一档能力"这句**说人话的为什么**(G3 流加入后补的一刀,界面那一档落地时改成"点名每一段",
        /// G3 网络那一档再加一段,G3 异步那一档再加一段;位图与剪贴板/弹窗两族同理补上):缺的那一段里
        /// **碰上了**哪一档就点哪一档(网络 20~26 / 异步 40~42 / 流 48~54 / 计时 55 / 图形 60~69 /
        /// 位图 70~77 / 弹窗 80~85),一段都没碰上就照实说号 ——
        /// 别把"缺流能力"说成"缺图形能力",也别漏说。
        /// </summary>
        private static string 缺哪一档文本(int 号, int 该到)
        {
            int 起到 = 号 + 1;
            var 点名的 = new List<string>();
            if (起到 <= 网络功能号最大 && 该到 >= 网络功能号最小)
                点名的.Add($"{网络功能号最小}~{网络功能号最大} 是后加的**网络**(裸 TCP:连到 / 发送 / 发送块 / 接收 / 接收块 / 监听 / 接受 / 主机解析)");
            if (起到 <= 异步功能号最大 && 该到 >= 异步功能号最小)
                点名的.Add($"{异步功能号最小}~{异步功能号最大} 是后加的**异步输入输出**(发起异步 / 任务就绪 / 取消任务)");
            if (起到 <= 流功能号最大 && 该到 >= 流功能号最小)
                点名的.Add($"{流功能号最小}~{流功能号最大} 是后加的**流式读写**(大文件分块进出)");
            if (起到 <= 计时功能号最大 && 该到 >= 计时功能号最小)
                点名的.Add($"{计时功能号最小} 是后加的**当前毫秒**(界面 / 定时器要的毫秒级节拍)");
            if (起到 <= 图形宿主C.图形功能号最大 && 该到 >= 图形宿主C.图形功能号最小)
                点名的.Add($"{图形宿主C.图形功能号最小}~{图形宿主C.图形功能号最大} 是后加的**图形界面**" +
                    $"(开窗口 / 画一屏 / 取事件那一族)");
            if (起到 <= 图形宿主C.位图功能号最大 && 该到 >= 图形宿主C.位图功能号最小)
                点名的.Add($"{图形宿主C.位图功能号最小}~{图形宿主C.位图功能号最大} 是后加的**位图**" +
                    $"(离屏画布:建位图 / 画点到图 / 贴位图那一族)");
            if (起到 <= 弹窗功能号最大 && 该到 >= 弹窗功能号最小)
                点名的.Add($"{弹窗功能号最小}~{弹窗功能号最大} 是后加的**剪贴板与弹窗**" +
                    $"(读剪贴板 / 写剪贴板 / 清空剪贴板 / 提示框 / 选文件 / 另存文件)");
            if (点名的.Count == 0) return $"它的能力只到功能号 {号},缺到 {该到}";
            return $"它的能力只到功能号 {号},缺 {起到}~{该到} —— 其中 {string.Join(";", 点名的)}";
        }

        /// <summary>"它读不了新包"那句**说人话的为什么**(包格式那一档)</summary>
        private static string 包格式原因(int 它, int 该到) => 它 switch
        {
            0 => $"它不认「{能力行包格式}」这一行(比会读段式初值包的那一版还老)",
            程序包C.包格式_逐条初值 => $"它只会读逐条初值的包(包格式 {它}),读不了这一版写的**段式初值包**(要 {该到})",
            程序包C.包格式_段初值 => $"它只会读段式初值的包(包格式 {它}),读不了这一版写的**带源行表的包**" +
                $"(要 {该到};那张表就是独立 exe 运行期报错能带行号的依据)",
            _ => $"它的读包能力只到包格式 {它},要 {该到}",
        };

        /// <summary>
        /// "它不认识这一版指令集"那句**说人话的为什么**(指令集那一档;**F-4** 加的)。
        ///
        /// 为什么这一刀非有不可(2026-10-16 用户实测报的示例63):`最大功能号` 与 `包格式` 这两条
        /// **都盯着宿主能力与包格式**,而 ISA 扩容只往虚拟机里加 `case`(指令表 + 虚拟机 + C 运行时的
        /// 指令语义),宿主能力一个号都没动 ⇒ 一份 **ISA 扩容前一天编的宿主**在这两条上**报得跟当前代码
        /// 一模一样**(实测:那份 10-12 的 `HB宿主.exe` 报 `最大功能号=85`、`包格式=4`,两项都"够新"),
        /// 于是被判"够新"照用;它把 `0x4E`(`循环左移`)当未知操作码,而报错出来的是**子进程里的异常**
        /// ⇒ 用户看到的是"跑程序通道错误:子进程报『未知操作码』"这种像通道坏了的说法,
        /// 真因却是"壳比机器码旧"。
        /// </summary>
        private static string 指令集原因(int 它) => 它 <= 0
            ? $"它不认「{能力行指令集}」这一行 —— 比会把指令集版本报出来的那一版还老" +
              $"(这条问话能问出功能号与包格式,却问不出「认不认识 0x{当前指令集上界:X2} 这一档新指令」)"
            : $"它的指令集只到 0x{它:X2},当前是 0x{当前指令集上界:X2} —— " +
              $"这一版机器码里 `0x{它 + 1:X2}~0x{当前指令集上界:X2}` 那些指令它不认识" +
              "(跑起来会报「未知操作码」;`指令集说明.md` §3 有那一段的逐条清单)";

        // 问过的宿主记在这儿:同一个文件(路径 + 大小 + 最后写时间都没变)只问一次。
        // 为什么非要缓存:问一句 = 起一个七十多 MB 的 exe,而这条路是在**界面线程**上走的,
        // 每次编译都问一遍会让"编译"按钮明显发顿。
        private static readonly object _能力缓存锁 = new();
        private static readonly Dictionary<string, (long 长, DateTime 时, int 该到, int 该到包, 宿主能力种C 果)> _能力缓存 = new(StringComparer.OrdinalIgnoreCase);

        /// <summary>
        /// 问一份宿主 exe"你是哪一版":带 `--能力` 起它一次,看它报不报得出能力清单。
        /// **同一个文件只问一次**(见 `_能力缓存`);文件不在 / 起不来 / 超时一律算**答不上来**。
        /// `该到包格式` = 这一次要它读得动到第几档包(0 = 不看这一条)。
        /// </summary>
        public static 宿主能力种C 问能力(string 可执行路径, int 该到几号 = 0, int 该到包格式 = 0)
        {
            string 全;
            try { 全 = Path.GetFullPath(可执行路径); } catch { 全 = 可执行路径; }
            long 长 = -1;
            DateTime 时 = default;
            try
            {
                var 文 = new FileInfo(全);
                if (文.Exists) { 长 = 文.Length; 时 = 文.LastWriteTimeUtc; }
            }
            catch { }
            lock (_能力缓存锁)
                if (_能力缓存.TryGetValue(全, out var 记) && 记.长 == 长 && 记.时 == 时 && 记.该到 == 该到几号 && 记.该到包 == 该到包格式)
                    return 记.果;

            var 果 = 长 < 0
                ? new 宿主能力种C { 陈旧 = "文件不在" }
                : 真问能力(全, 该到几号, 该到包格式);
            lock (_能力缓存锁) _能力缓存[全] = (长, 时, 该到几号, 该到包格式, 果);
            return 果;
        }

        /// <summary>这一份宿主**比当前代码旧**吗(null = 够新;不是 null = 一句**为什么**)</summary>
        public static string? 陈旧原因(string 可执行路径, int 该到几号 = 0, int 该到包格式 = 0)
            => 问能力(可执行路径, 该到几号, 该到包格式).陈旧;

        /// <summary>
        /// 说清"它支持到几号能力"(报错 / 提醒里那句):会自报就给号,不认这句问话的老宿主**如实说它不说**
        /// —— 写成"它只到 0"是把话说岔了(它其实是不会自报,不是一号能力都没有)。
        /// </summary>
        public static string 能力上限文本(宿主能力种C 能力)
            => 能力.会自报 ? $"它只到功能号 {能力.最大功能号}" : "它老到不会自报能力(问它一句只会报「里面没有贴程序」)";

        /// <summary>说清"它读得动哪一档包"(与 `能力上限文本` 同一路数,措辞不夸大)</summary>
        public static string 包格式上限文本(宿主能力种C 能力)
            => 能力.包格式 > 0 ? $"它只到包格式 {能力.包格式}" : $"它老到不认「{能力行包格式}」这一行(只会报功能号)";

        /// <summary>
        /// 说清"它认到哪一版指令集"(与前两条同一路数,措辞不夸大):会自报就给上界,
        /// 不认那一行的老宿主**如实说它不说** —— 而"功能号与包格式都够新"说明不了这件事(F-4)。
        /// </summary>
        public static string 指令集上限文本(宿主能力种C 能力)
            => 能力.指令集上界 > 0
                ? $"它的指令集只到 0x{能力.指令集上界:X2}"
                : $"它老到不认「{能力行指令集}」这一行(只会报功能号与包格式——" +
                  $"这两样都够新也说明不了它认识 0x{当前指令集上界:X2} 这一档新指令)";

        /// <summary>真起一次那个 exe(读法与 `处理运行进程` 同一套:先挂异步读、再等退出,超时杀进程树)</summary>
        private static 宿主能力种C 真问能力(string 全, int 该到几号, int 该到包格式)
        {
            System.Diagnostics.Process? 进程 = null;
            try
            {
                var 起 = new System.Diagnostics.ProcessStartInfo
                {
                    FileName = 全,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    RedirectStandardInput = true,               // 它要读输入就给 EOF,别让它挂在等输入上
                    StandardOutputEncoding = new UTF8Encoding(false),
                    StandardErrorEncoding = new UTF8Encoding(false),
                };
                起.ArgumentList.Add(能力请求参数);
                进程 = System.Diagnostics.Process.Start(起);
                if (进程 == null) return new 宿主能力种C { 陈旧 = "起不来(Process.Start 给了 null)" };
                try { 进程.StandardInput.Close(); } catch { }
                var 出任务 = 读全部字节(进程.StandardOutput.BaseStream);
                var 错任务 = 读全部字节(进程.StandardError.BaseStream);
                if (!进程.WaitForExit(能力探测超时毫秒))
                {
                    try { 进程.Kill(entireProcessTree: true); } catch { }
                    try { 进程.WaitForExit(2000); } catch { }
                    return new 宿主能力种C { 陈旧 = $"问它一句 `{能力请求参数}`,{能力探测超时毫秒 / 1000} 秒都没答上来" };
                }
                进程.WaitForExit();
                string 出 = 出任务.Wait(2000) ? 解码输出(出任务.Result) : "";
                string 错 = 错任务.Wait(2000) ? 解码输出(错任务.Result) : "";
                // 老宿主不会答这句问话:它把 `--能力` 当程序文件,用法提示打在**标准错误**上(退出码 2)⇒ 一起收
                return 解析能力清单(出.Trim().Length > 0 ? 出 : 错, 进程.ExitCode, 该到几号, 该到包格式);
            }
            catch (Exception 异)
            {
                return new 宿主能力种C { 陈旧 = $"问不出来({异.GetType().Name}:{异.Message})" };
            }
            finally { try { 进程?.Dispose(); } catch { } }
        }
    }
