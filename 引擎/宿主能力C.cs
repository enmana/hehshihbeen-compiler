        public const int 功能_追加写文件 = 4;

        /// <summary> 建目录(批 9):`参数1` 路径址、`参数2` 路径长。**已存在也算成功**(幂等 —— 同一段程序跑第二遍不该失败)。 </summary>
        public const int 功能_建目录 = 5;

