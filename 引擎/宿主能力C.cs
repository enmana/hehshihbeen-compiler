        // ================= D1:运行进程(白名单 + 同步等待 + 超时杀进程树) =================

        /// <summary> 把一个流读成字节(异步;子进程被超时杀掉时流会关,任务随即结束) </summary>
        private static async Task<byte[]> 读全部字节(Stream 流)
        {
            using var 缓冲 = new MemoryStream();
            await 流.CopyToAsync(缓冲).ConfigureAwait(false);
            return 缓冲.ToArray();
        }

        /// <summary>
        /// 子进程输出怎么解码:按候选顺序试,**取第一个解出来不含替换符(U+FFFD)的**。
        /// 候选:① 严格 UTF-8(现代工具多半吐这个)② 系统 OEM / ANSI 代码页(中文 Windows = 936/GBK,
        /// `cmd` 与老工具吐的是它)③ 当前控制台编码。为什么不能只认一种:只认 UTF-8 时 `cmd` 的中文全乱码,
        /// 只认代码页时 UTF-8 工具又乱码(踩过)。
        /// </summary>
        public static string 解码输出(byte[] 字节)
        {
            if (字节 == null || 字节.Length == 0) return "";
            if (字节.All(b => b < 0x80)) return Encoding.ASCII.GetString(字节);      // 纯 ASCII:谁解都一样
            foreach (Encoding 候选 in 候选解码器())
            {
                string 试;
                try { 试 = 候选.GetString(字节); }
                catch (DecoderFallbackException) { continue; }                        // 严格 UTF-8 碰上非法字节就走下一个
                catch { continue; }
                if (!试.Contains('\uFFFD')) return 试;
            }
            return Encoding.UTF8.GetString(字节);                                     // 兜底:总得给点什么
        }

        private static IEnumerable<Encoding> 候选解码器()
        {
            yield return new UTF8Encoding(false, throwOnInvalidBytes: true);
            // 系统代码页(OEM = 中文 Windows 的 936)要先登记 CodePages 提供程序 —— .NET Core 起非 Unicode 代码页
            // 默认不认(`Encoding.GetEncoding(936)` 会抛)。这个程序集在共享框架里,不用额外包。
            try { Encoding.RegisterProvider(System.Text.CodePagesEncodingProvider.Instance); } catch { }
            foreach (int 码页 in new[] { System.Globalization.CultureInfo.CurrentCulture.TextInfo.OEMCodePage,
                                        System.Globalization.CultureInfo.CurrentCulture.TextInfo.ANSICodePage })
            {
                Encoding? 编码 = null;
                try { 编码 = Encoding.GetEncoding(码页); } catch { }
                if (编码 != null) yield return 编码;
            }
            yield return Console.OutputEncoding;
        }

        /// <summary>
        /// 请求块(10 个字,40 字节):**+0** 名字址、**+4** 名字长、**+8** 输出串头址、**+12** 池指针槽、**+16** 池末槽、
        /// **+20** 参数址、**+24** 参数长、**+28** 超时毫秒、**+32**(写回)退出码、**+36** 状态。
        /// 前三样与 `读文件` 那条**故意同形**(+8/+12/+16 就是"头址/池指针槽/池末槽"),
        /// 这样"输出写进字符串变量"能直接复用 `写进字符串变量`(换块扩容那套一个字都不用重写)。
        /// </summary>
        private static int 处理运行进程(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 40)) return 状态_参数不合法;
            上次退出码 = 0xFFFFFFFF;                       // 这一趟没跑成的话,取退出码() 就该给"没有"
            写字(内存, 参数区 + 32, 0xFFFFFFFF);

            var 表 = 可执行白名单;
            if (表 == null) return 状态_没挂能力;            // 这个宿主没挂(手机端 / 独立 exe / 没给工程文件)

            var (名字, 错1) = 取参数串(内存, 参数区, 0);
            if (名字 == null) return 错1;
            uint 参数址 = 读字(内存, 参数区 + 20);
            uint 参数长 = 读字(内存, 参数区 + 24);
            if (!放得下(内存, 参数址, 参数长)) return 状态_参数不合法;
            string 参数串 = Encoding.UTF8.GetString(内存, (int)参数址, (int)参数长);
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            uint 超时 = 读字(内存, 参数区 + 28);
            if (超时 == 0) 超时 = 默认进程超时毫秒;
            if (超时 > 3600_000) 超时 = 3600_000;           // 上限 1 小时:防止 HB 侧写个天文数字把 IDE 挂住

            if (名字.Trim().Length == 0) return 状态_参数不合法;
            if (!表.TryGetValue(名字.Trim(), out string? 路径) || 路径.Trim().Length == 0) return 状态_不在白名单;
            if (!File.Exists(路径)) return 状态_打不开;

            // 参数**每行一个**,原样进 argv —— 不过 shell、不做引号/转义解析(转义那口锅就不存在了)
            var 参数表 = new List<string>();
            foreach (string 行 in 参数串.Replace("\r\n", "\n").Split('\n'))
                if (行.Length > 0) 参数表.Add(行);

            var 起 = new System.Diagnostics.ProcessStartInfo
            {
                FileName = 路径,
                UseShellExecute = false,                    // 不经过 shell:参数原样给子进程
                CreateNoWindow = true,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                RedirectStandardInput = true,               // 子进程要读输入就给 EOF,别让它挂在等输入上
                StandardOutputEncoding = new UTF8Encoding(false),
                StandardErrorEncoding = new UTF8Encoding(false),
            };
            foreach (string 一个 in 参数表) 起.ArgumentList.Add(一个);

            System.Diagnostics.Process? 进程 = null;
            try
            {
                进程 = System.Diagnostics.Process.Start(起);
                if (进程 == null) return 状态_打不开;
                try { 进程.StandardInput.Close(); } catch { }
                // **先挂上异步读**,再去等退出 —— 反过来(先 ReadToEnd 再等)会在"子进程一直输出/不输出也不退"时
                // 卡死在读上:超时形同虚设(踩过:自检卡到超时)。读是后台任务,超时时把进程树杀掉、流一关它就收尾。
                // 读的是**原始字节**(不走 StreamReader 的解码):解编码在下面按"先严 UTF-8、再控制台代码页"来,
                // 这样 UTF-8 的工具与中文 Windows 控制台(GBK)的输出都能看对。
                var 出任务 = 读全部字节(进程.StandardOutput.BaseStream);
                var 错任务 = 读全部字节(进程.StandardError.BaseStream);
                if (!进程.WaitForExit((int)超时))
                {
                    try { 进程.Kill(entireProcessTree: true); } catch { }
                    try { 进程.WaitForExit(2000); } catch { }
                    try { Task.WaitAll(new Task[] { 出任务, 错任务 }, 1000); } catch { }
                    return 状态_超时;
                }
                进程.WaitForExit();
                string 标准输出 = 出任务.Wait(2000) ? 解码输出(出任务.Result) : "";
                string 标准错误 = 错任务.Wait(2000) ? 解码输出(错任务.Result) : "";

                // 输出:先 stdout 后 stderr(文档写明;要分开看就自己让工具往文件里写)
                string 全输出 = 标准输出;
                if (标准错误.Length > 0) 全输出 += (全输出.Length > 0 && !全输出.EndsWith("\n") ? "\n" : "") + 标准错误;
                int 写状态 = 写进字符串变量(内存, 参数区, 头址, Encoding.UTF8.GetBytes(全输出));
                if (写状态 != 状态_成功) return 写状态;      // 放不下就按"放不下"报,退出码已经写好了

                上次退出码 = (uint)进程.ExitCode;
                写字(内存, 参数区 + 32, 上次退出码);
                return 进程.ExitCode == 0 ? 状态_成功 : 状态_退出码非零;
            }
            catch (System.ComponentModel.Win32Exception) { return 状态_打不开; }
            catch (InvalidOperationException) { return 状态_打不开; }
            catch (IOException) { return 状态_读写失败; }
            catch (Exception) { return 状态_读写失败; }
            finally { try { 进程?.Dispose(); } catch { } }
        }

        // ================= D5:取网址(白名单 + 同步一次性 GET + 超时 + 上限) =================

        /// <summary>
        /// 请求块(9 个字,36 字节):**+0** 网址址、**+4** 网址长、**+8** 输出串头址、**+12** 池指针槽、
        /// **+16** 池末槽、**+20** 超时毫秒、**+24** 响应体上限字节、**+28**(写回)HTTP 状态码、**+32** 状态。
        /// 前三样与 `读文件` **故意同形**(+8/+12/+16 就是"头址/池指针槽/池末槽"),于是"响应体写进字符串变量"
        /// 直接复用 `写进字符串变量`(换块扩容那套一个字不用重写)。
        /// **顺序也是安全边界**:先查白名单、再发请求 —— 不在表里连 DNS 都不做。
        /// </summary>
        private static int 处理取网址(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 36)) return 状态_参数不合法;
            上次网址状态码 = -1;
            写字(内存, 参数区 + 28, 0xFFFFFFFF);

            var 白名单 = 网址白名单;
            if (白名单 == null) return 状态_没挂能力;        // 独立 exe / 手机 IDE / 没给工程文件

            var (网址文本, 错) = 取参数串(内存, 参数区, 0);
            if (网址文本 == null) return 错;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;

            if (!Uri.TryCreate(网址文本.Trim(), UriKind.Absolute, out Uri? 网址) || 网址.Host.Length == 0)
                return 状态_参数不合法;
            if (网址白名单项C.协议默认端口(网址.Scheme) < 0) return 状态_协议不支持;
            if (!白名单.允许(网址, out _)) return 状态_网址不在白名单;

            uint 超时 = 读字(内存, 参数区 + 20);
            if (超时 == 0) 超时 = 网络能力C.默认超时毫秒;
            if (超时 > 网络能力C.最大超时毫秒) 超时 = (uint)网络能力C.最大超时毫秒;
            uint 上限 = 读字(内存, 参数区 + 24);
            if (上限 == 0) 上限 = 网络能力C.默认上限字节;
            if (上限 > 网络能力C.最大上限字节) 上限 = (uint)网络能力C.最大上限字节;

            var 应答 = 网络能力C.取(new 网络请求C
            {
                网址 = 网址,
                超时毫秒 = (int)超时,
                上限字节 = (int)上限,
            });
            if (应答.HTTP状态码 > 0)
            {
                上次网址状态码 = 应答.HTTP状态码;
                写字(内存, 参数区 + 28, (uint)上次网址状态码);
            }
            if (!应答.成功) return 应答.状态;
            return 写进字符串变量(内存, 参数区, 头址, 应答.内容);
        }

