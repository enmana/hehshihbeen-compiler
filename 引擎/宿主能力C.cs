        public const int 功能_取网址状态码 = 16;

        // ================= G3 流式读写(域 1:流 48~54)=================
        //
        // 为什么要有这一域:内存只有 1MB,而"读文件 / 写文件"是**整份进出**的 —— 大文件只能靠
        // `读文件块`(它每次都要按路径重新开一次文件、还要自己数偏移)。流把"打开一次、要几块读几块"
        // 这条路铺平,顺带成了 `CSV流` / `NDJSON流` 的地基(见 `基础库框架.md` §7)。
        //
        // 句柄 = **整数**(`(表下标 << 16) | 版本`)—— 不把指针暴露给用户;表由宿主维护,一个程序跑完就清。
        // 返回值照用户的拍板(2026-10-02):`读一块` / `写一块` 给**字节数**,失败给 **-1**,
        // `读一块` 读到末尾给 **0**;`打开*` 给句柄(失败 -1);`定位` / `关*` 给状态码(0 = 成功)。

        /// <summary> **打开读流**(G3 流):`参数1/2` 路径(与 `读文件` 同形),`参数3` 写回 = 句柄。
        /// 表满 / 打不开 / 系统目录那一档(虚拟路径)不支持 → 句柄写 -1,返回对应状态码。 </summary>
        public const int 功能_打开读流 = 48;

        /// <summary> **读一块**(G3 流):`参数1` 句柄、`参数2` 内容变量头地址、`参数3/4` 池指针槽 / 池末槽、
        /// `参数5` 上限(最多读多少字节,0 = 4096 兜底);`参数6` 写回 = **读到的字节数**
        /// (0 = 已到末尾,这时内容变量清空)。 </summary>
        public const int 功能_读一块 = 49;

        /// <summary> **定位**(G3 流):`参数1` 句柄、`参数2` 目标偏移(从文件开头算的**绝对**字节位置)。
        /// 读流 / 写流都能定位(写流定位过再写 = 从那个位置覆盖)。 </summary>
        public const int 功能_定位 = 50;

        /// <summary> **关闭读流**(G3 流):`参数1` 句柄。关掉之后那个句柄一律作废(状态 22)。 </summary>
        public const int 功能_关读流 = 51;

        /// <summary> **打开写流**(G3 流):`参数1/2` 路径,`参数3` 写回 = 句柄。
        /// **覆盖写**:文件不存在就新建、存在就从头写起(要接着写先用 `追加写文件` 或自己 `定位`)。 </summary>
        public const int 功能_打开写流 = 52;

        /// <summary> **写一块**(G3 流):`参数1` 句柄、`参数2` 数据地址、`参数3` 字节数;
        /// `参数4` 写回 = **真写下去的字节数**。到这儿还**没落盘** —— 落盘在 `关写流`(它会冲刷)。 </summary>
        public const int 功能_写一块 = 53;

        /// <summary> **关闭写流**(G3 流):`参数1` 句柄。**先把缓冲冲刷到盘上再关**(G3 定:关写流并冲刷)。 </summary>
        public const int 功能_关写流 = 54;

        /// <summary> G3 流那一域的最小 / 最大功能号(自检与"参数区字节数"表共用一处) </summary>
        public const int 流功能号最小 = 功能_打开读流;
        public const int 流功能号最大 = 功能_关写流;

        // ---- G3 域 2:界面那一域的**节拍**(`基础库框架.md` §7 的"运行时"那几行里,
        //      `当前毫秒` 是"界面 / 定时"这一域唯一还缺的宿主能力;接口那一族十条在 `图形宿主C` 的 60~69)----

        /// <summary> **当前毫秒**(G3 域 2):无参数;把**单调时钟**的毫秒数写进 `参数1` 那个字(低 32 位)。
        ///
        /// 为什么要它:`Sample\库\定时.hb`(软件定时器)与"界面主循环算两帧差多久"都要一个**毫秒级**的钟,
        /// 而 `当前时间()` 只有秒(`当前时间()*1000` 那种凑法在两帧之间永远是 0,定时器就没法定时)。
        ///
        /// 口径三条:
        /// ① **单调**:不受用户改系统时间影响(Windows `GetTickCount64` / POSIX `CLOCK_MONOTONIC`,
        ///    .NET 侧 `Environment.TickCount64`)—— 定时器最怕的就是"时间往回跳";
        /// ② **给 32 位、会回绕**:`宿主调用` 的写回槽就一个字(4 字节),所以回到 0 是**定下的口径**,
        ///    周期约 49.7 天。**差值照旧对**(模 2^32 减法),只是"两个时刻谁大谁小"不能直接比 ——
        ///    程序别把它当绝对时刻存,只拿它算差(定时库就是这么用的);
        /// ③ **起点无所谓**:它不是一个"公元多少年"的时间,只是同一个宿主里的一个连续刻度。 </summary>
        public const int 功能_当前毫秒 = 55;

        /// <summary> 界面那一域用到的节拍能力的最小 / 最大功能号(当前只有 `当前毫秒` 一条;给自检与清单指路)</summary>
        public const int 计时功能号最小 = 功能_当前毫秒;
        public const int 计时功能号最大 = 功能_当前毫秒;

