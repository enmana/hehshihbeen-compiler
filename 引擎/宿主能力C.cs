        }

        /// <summary>
        /// **主机解析**:把第一个解析出来的地址写进那个字符串(优先 IPv4 —— 4 字节定长地址最省事)。
        /// 两关:① 这台主机**得在 `网址` 表里出现过**(带端口那一式);② 解析不出来给状态 17。
        /// </summary>
        private static int 处理主机解析(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 24)) return 状态_参数不合法;
            if (网址白名单 == null) return 状态_没挂能力;

            var (主机, 错) = 取参数串(内存, 参数区, 0);
            if (主机 == null) return 错;
            主机 = 主机.Trim();
            if (主机.Length == 0) return 状态_参数不合法;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            if (!网址白名单.有主机(主机)) return 状态_网址不在白名单;

