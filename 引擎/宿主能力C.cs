        /// 自检在对拍"会用句柄的工程"之前调这一条把版本压回起点,就与"一个工程一个进程"逐字对齐;
        /// 那些工程还要**一个一个跑**(见自检里的 `句柄对拍门`:两张表是进程级静态的)。
