        // ================= G3 流句柄表(唯一一处;一个程序跑完 `清运行痕迹` 就清空)=================

        /// <summary> 一格流(`流.C` 非 null = 这一格在用) </summary>
        private sealed class 流格C
        {
            public FileStream? 流;
            public int 版本 = 1;
            public bool 是写;
        }

        /// <summary> 同时能开几个流(表满给状态 23;够"同时读几份 + 写几份"用) </summary>
        public const int 流表格数 = 64;

        private static readonly object _流锁 = new();
        private static readonly 流格C[] _流表 = new 流格C[流表格数];

        /// <summary> 句柄 = `(表下标 << 16) | 版本`(版本从 1 起、每复用一格 +1 ⇒ 老句柄不会撞上新流) </summary>
        private static uint 拼句柄(int 下标, int 版本) => ((uint)下标 << 16) | (uint)版本;

        private static void 清流()
        {
            lock (_流锁)
            {
                for (int i = 0; i < _流表.Length; i++)
                {
                    var 格 = _流表[i];
                    if (格 == null) continue;
                    try { 格.流?.Dispose(); } catch { }
                    格.流 = null;
                    格.版本 = 1;
                    格.是写 = false;
                }
            }
        }

        /// <summary> 按句柄取那一格(认不出给 null:没开过 / 已经关了) </summary>
        private static 流格C? 取流格(uint 句柄)
        {
            int 下标 = (int)(句柄 >> 16);
            int 版本 = (int)(句柄 & 0xFFFF);
            if (下标 < 0 || 下标 >= _流表.Length || 版本 == 0) return null;
            var 格 = _流表[下标];
            return 格 is { 流: not null } && 格.版本 == 版本 ? 格 : null;
        }

        /// <summary> 开一条流并给它一个句柄(表满 / 开不出来给 null + 状态码) </summary>
        private static (uint 句柄, int 状态) 开流(string 路径, bool 写)
        {
            // 系统目录那一档(手机端 SAF)走的是抽象路径,这里开不了真文件流 —— 如实说"没挂能力"
            if (虚拟路径C.是虚拟(路径)) return (0, 状态_没挂能力);
            lock (_流锁)
            {
                int 空 = -1;
                for (int i = 0; i < _流表.Length; i++)
                    if (_流表[i] is not { 流: not null }) { 空 = i; break; }
                if (空 < 0) return (0, 状态_流太多);

                var 格 = _流表[空] ??= new 流格C();
                try { 格.流 = new FileStream(路径, 写 ? FileMode.Create : FileMode.Open, 写 ? FileAccess.Write : FileAccess.Read, FileShare.Read); }
                catch (FileNotFoundException) { 格.流 = null; return (0, 状态_打不开); }
                catch (DirectoryNotFoundException) { 格.流 = null; return (0, 状态_打不开); }
                catch (IOException) { 格.流 = null; return (0, 状态_读写失败); }
                catch (UnauthorizedAccessException) { 格.流 = null; return (0, 状态_打不开); }
                if (格.流 == null) return (0, 状态_读写失败);
                格.是写 = 写;
                return (拼句柄(空, 格.版本), 状态_成功);
            }
        }

        /// <summary> 关掉一条流(句柄作废;关之前把缓冲冲刷下去 —— `关写流` 的口径) </summary>
        private static bool 关流(uint 句柄, bool 要冲刷)
        {
            lock (_流锁)
            {
                var 格 = 取流格(句柄);
                if (格 == null) return false;
                try
                {
                    if (要冲刷) 格.流!.Flush(flushToDisk: true);
                    格.流!.Dispose();
                }
                catch { 格.流 = null; 格.版本++; return false; }
                格.流 = null;
                格.版本++;                     // 复用这一格时给一个新句柄(老句柄从此认不出)
                return true;
            }
        }

        // ================= G3 网络:套接字句柄表(唯一一处;`清运行痕迹` 把还开着的全部关掉)=================

        /// <summary> 一格套接字(`套接字` 非 null = 这一格在用) </summary>
        private sealed class 套接字格C
        {
            public Socket? 套接字;
            public int 版本 = 1;
            public bool 是监听;
        }

        private static readonly object _套接字锁 = new();
        private static readonly 套接字格C[] _套接字表 = new 套接字格C[套接字表格数];

        /// <summary>
        /// 套接字的句柄 = `((表下标 + 流表格数) &lt;&lt; 16) | 版本`。
        /// **为什么加这个偏移**:流与套接字是两张表,而句柄都长成 `(下标 &lt;&lt; 16) | 版本` ——
        /// 不加偏移,一个流句柄 `65536` 拿去 `接收` 就会正好落在套接字表第 0 格里(那不是"句柄无效",
        /// 是**误读另一张表**)。加一个 `流表格数` 的偏移之后,两张表的句柄**永远撞不上**:
        /// 拿流句柄调网络原语一律落到"下标 &lt; 64 ⇒ 没有这一格"⇒ 状态 22。
        /// </summary>
        private static uint 拼套接字句柄(int 下标, int 版本) => (((uint)下标 + 流表格数) << 16) | (uint)版本;

        /// <summary> 按句柄取那一格(认不出给 null:没开过 / 已经关了 / 是流那边开出来的句柄) </summary>
        private static 套接字格C? 取套接字格(uint 句柄)
        {
            int 下标 = (int)(句柄 >> 16) - 流表格数;              // 减掉偏移:只有网络开的句柄才落在 0..套接字表格数-1
            int 版本 = (int)(句柄 & 0xFFFF);
            if (下标 < 0 || 下标 >= _套接字表.Length || 版本 == 0) return null;
            var 格 = _套接字表[下标];
            return 格 is { 套接字: not null } && 格.版本 == 版本 ? 格 : null;
        }

        /// <summary> 把还开着的套接字全关掉(宿主跑完一个程序就清:句柄从头再来) </summary>
        private static void 清套接字()
        {
            lock (_套接字锁)
            {
                for (int i = 0; i < _套接字表.Length; i++)
                {
                    var 格 = _套接字表[i];
                    if (格 == null) continue;
                    try { 格.套接字?.Dispose(); } catch { }
                    格.套接字 = null;
                    格.版本 = 1;
                    格.是监听 = false;
                }
            }
        }

        private static int 找空套接字格()
        {
            for (int i = 0; i < _套接字表.Length; i++)
                if (_套接字表[i] is not { 套接字: not null }) return i;
            return -1;
        }

        /// <summary>
        /// 开一条套接字并给它一个句柄(表满 / 连不上 / 绑不上给 null + 状态码)。
        /// **锁只护表那一小段**:连接会阻塞到最多 `默认连接超时毫秒`,套着锁做会把别的程序一起卡住
        /// (自检是 4 路并行跑标准工程)。
        /// </summary>
        private static (uint 句柄, int 状态) 开套接字(string 主机, int 端口, bool 监听)
        {
            int 空;
            套接字格C 格;
            lock (_套接字锁)
            {
                空 = 找空套接字格();
                if (空 < 0) return (0, 状态_流太多);
                格 = _套接字表[空] ??= new 套接字格C();
            }

            var 新 = new Socket(AddressFamily.InterNetwork, SocketType.Stream, ProtocolType.Tcp);
            try
            {
                // 监听那一侧允许"上一趟刚关、端口还在 TIME_WAIT 里"再绑回来(示例与自检都要跑很多遍)
                新.SetSocketOption(SocketOptionLevel.Socket, SocketOptionName.ReuseAddress, true);
                if (监听)
                {
                    // 绑哪块网卡必须是 IP 字面量:主机名要先解析,而"监听"这一侧解析出来的地址
                    // 未必是本机网卡上的那一个 —— 与其猜,不如让用户写清(帮助里写死了这条口径)。
                    if (!IPAddress.TryParse(主机, out IPAddress? 绑址)) { 新.Dispose(); return (0, 状态_参数不合法); }
                    新.Bind(new IPEndPoint(绑址, 端口));
                    新.Listen(8);
                }
                else
                {
                    using var 等 = 新.ConnectAsync(主机, 端口);
                    if (!等.Wait(默认连接超时毫秒)) { 新.Dispose(); return (0, 状态_网络超时); }
                }
            }
            catch (SocketException) { 新.Dispose(); return (0, 状态_连不上); }
            catch (ObjectDisposedException) { 新.Dispose(); return (0, 状态_连不上); }
            catch (Exception) { 新.Dispose(); return (0, 状态_连不上); }

            lock (_套接字锁)
            {
                格.套接字 = 新;
                格.是监听 = 监听;
                return (拼套接字句柄(空, 格.版本), 状态_成功);
            }
        }

        /// <summary> 关掉一条套接字(句柄作废;版本 +1 ⇒ 老句柄从此认不出) </summary>
        private static bool 关套接字(uint 句柄)
        {
            lock (_套接字锁)
            {
                var 格 = 取套接字格(句柄);
                if (格 == null) return false;
                try { 格.套接字!.Shutdown(SocketShutdown.Both); } catch { }   // 监听句柄上 Shutdown 会抛,忽略
                try { 格.套接字!.Dispose(); } catch { }
                格.套接字 = null;
                格.是监听 = false;
                格.版本++;
                return true;
            }
        }


        // ================= G3 域 5:异步任务表 + 后台线程池(唯一一处;`清句柄表` 连它一起清)=================

        /// <summary>
        /// 一格任务。**状态机只有三个位置**:空(没占)/ 在跑 / 好了(结果放着等收走)。
        ///
        /// `在用 = true` 从 `发起` 一直占 `收走` 或 `取消` 为止 —— **跑完不会自己放格子**,
        /// 因为结果要等人来取。于是"32 格全占着"是**确定的**(与线程快慢无关):
        /// 发起 32 个不查就绪,第 33 个必然给 -1(标准工程的"任务太多"那条失败路就靠这条)。
        ///
        /// **后台线程一个字节都不许碰 VM 的内存**(`byte[] 内存` 是主线程的):它只往自己这一格里写
        /// 字符串 / 字节数组这种托管对象,VM 内存的搬运全部发生在 `处理任务就绪`(主线程)里。
        /// </summary>
        private sealed class 任务格C
        {
            /// <summary>版本(从 1 起;`收走` / `取消` 各 +1 ⇒ 旧号当场作废)</summary>
            public int 版本 = 1;
            /// <summary>这一格被一个任务占着(在跑,或者结果放着等收走)</summary>
            public bool 在用;
            /// <summary>后台那一趟还没回来</summary>
            public bool 在跑;
            /// <summary>取消过了:回来时把结果丢掉、把格子还掉(尽力取消)</summary>
            public bool 要取消;
            /// <summary>种类(1 读文件 / 2 写文件 / 3 连接)</summary>
            public int 种类;
            /// <summary>这一趟的结果状态(0 = 成了;别的见 `说明`)</summary>
            public int 结果状态;
            /// <summary>结果数字:读 / 写 = 字节数;连接 = 新连接的句柄(没成给 0 —— 真实的句柄恒大于 0)</summary>
            public uint 结果数字 = 0;
            /// <summary>读文件那一趟读到的字节(别的种类为空)</summary>
            public byte[] 结果数据 = [];
            /// <summary>连接那一趟连上的套接字(**还没交给 `套接字表`**;交出去或丢掉都在这条线程之外)</summary>
            public Socket? 连接;
            /// <summary>读文件:收内容那个 `字符串` 变量的头地址 + 池那一对槽(从 `发起` 的请求块抄下来)</summary>
            public uint 头址, 池指针槽, 池末槽, 上限;
        }

        private static readonly object _任务锁 = new();
        private static readonly 任务格C[] _任务表 = new 任务格C[任务表格数];

        /// <summary>任务号 = `(下标 &lt;&lt; 16) | 版本`(与流 / 套接字那两张表同一套写法) </summary>
        private static uint 拼任务号(int 下标, int 版本) => ((uint)下标 << 16) | (uint)版本;

        /// <summary>
        /// 按任务号取那一格。三种结局分得清(自检与报错文案都要这一层):
        /// `号非法`(下标越界 / 版本 0 → 状态 22)、`作废`(版本对不上,或者这一格空着 → 状态 3)、`找到`。
        /// </summary>
        private static 任务格C? 取任务格(uint 号, out bool 号非法)
        {
            int 下标 = (int)(号 >> 16);
            int 版本 = (int)(号 & 0xFFFF);
            号非法 = 下标 < 0 || 下标 >= _任务表.Length || 版本 == 0;
            if (号非法) return null;
            var 格 = _任务表[下标];
            return 格 is { 在用: true } && 格.版本 == 版本 ? 格 : null;
        }

        /// <summary>把任务表压回"刚启动":让还开着的套接字先关掉、再清格子(跑着的线程回来时只往自己那格里写,写不到已清的表上)</summary>
        private static void 清任务()
        {
            List<Socket> 待关 = [];
            lock (_任务锁)
            {
                for (int i = 0; i < _任务表.Length; i++)
                {
                    var 格 = _任务表[i];
                    if (格 == null) continue;
                    if (格.连接 != null) 待关.Add(格.连接);      // 连上了却还没交出去:别漏掉那只套接字
                    _任务表[i] = null;                          // 整格丢掉:跑着的那条线程拿到的是**旧对象**,写进来也没人认
                }
            }
            // 关套接字放到锁外面:关的时候可能阻塞(与 `开套接字` 那段"锁只护表"同一条口径)
            foreach (var 只 in 待关) { try { 只.Dispose(); } catch { } }
        }

        /// <summary>
        /// **发起异步**的宿主那一半(主线程):验参数 → 找空位 → 把这一趟要用的东西抄成托管对象 → 起后台线程。
        /// 与 C 侧 `hb_host_发起异步` **逐条对齐**(对拍比的就是"谁在第几格、任务号是多少")。
        /// </summary>
        private static int 处理发起异步(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 40)) return 状态_参数不合法;
            uint 任务槽 = 参数区 + 24;
            写字(内存, 任务槽, 0xFFFFFFFF);                     // 排不上就留 -1(与网络那一族"先写 -1"同一套写法)

            uint 种类 = 读字(内存, 参数区);
            if (种类 is not (种类_读文件 or 种类_写文件 or 种类_连接)) return 状态_参数不合法;
            var (参数一, 错) = 取参数串(内存, 参数区, 1);
            if (参数一 == null) return 错;
            var (参数二, 错二) = 取参数串(内存, 参数区, 3);
            if (参数二 == null) return 错二;
            uint 参数三 = 读字(内存, 参数区 + 20);
            byte[] 写字节 = [];

            if (种类 == 种类_读文件)
            {
                uint 头址 = 读字(内存, 参数区 + 28);
                if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
                if (参数三 == 0) 参数三 = 4096;                          // 兜底:不给上限就一块 4KB(与 `读一块` 同)
                if (参数三 > 1024u * 1024u) return 状态_参数不合法;
            }
            else if (种类 == 种类_写文件)
            {
                if (参数三 > 1024u * 1024u) return 状态_参数不合法;
                byte[] 全 = Encoding.UTF8.GetBytes(参数二);
                if (参数三 == 0) 参数三 = (uint)全.Length;               // 0 = 整段都写(与 `写一块` 同)
                int 要 = (int)Math.Min(参数三, (uint)全.Length);      // ⚠ 按**字节**截:再解回字符串会碰上半个汉字
                写字节 = 要 == 全.Length ? 全 : 全[..要];
            }
            else
            {
                // 连接:白名单那一关在**最前面**(不在 `网址` 表里连 DNS 都不做,与 `连到` 同一套)
                if (网址白名单 == null) return 状态_没挂能力;
                参数一 = 参数一.Trim();
                if (参数一.Length == 0 || 参数三 < 1 || 参数三 > 65535) return 状态_参数不合法;
                if (!网址白名单.允许主机端口(参数一, (int)参数三, out _)) return 状态_网址不在白名单;
            }

            int 空;
            任务格C 格;
            lock (_任务锁)
            {
                空 = -1;
                for (int i = 0; i < _任务表.Length; i++)
                    if (_任务表[i] is not { 在用: true }) { 空 = i; break; }
                if (空 < 0) return 状态_任务太多;
                格 = _任务表[空] ??= new 任务格C();
                格.在用 = true;
                格.在跑 = true;
                格.要取消 = false;
                格.种类 = (int)种类;
                格.结果状态 = 状态_成功;
                格.结果数字 = 0;
                格.结果数据 = [];
                格.连接 = null;
                格.头址 = 读字(内存, 参数区 + 28);
                格.池指针槽 = 读字(内存, 参数区 + 32);
                格.池末槽 = 读字(内存, 参数区 + 36);
                格.上限 = 参数三;
                写字(内存, 任务槽, 拼任务号(空, 格.版本));
            }

            // 输入**全部抄成托管对象**再交出去:后台线程一个字节都不许碰 `内存`
            int 种类号 = (int)种类;
            string 路径或主机 = 解析路径(参数一);
            byte[] 写内容 = 写字节;
            int 端口 = (int)参数三;
            uint 读上限 = 参数三;

            var 线程 = new Thread(() =>
            {
                try
                {
                    if (种类号 == 种类_读文件)
                    {
                        if (虚拟路径C.是虚拟(路径或主机)) { 收尾(格, 状态_没挂能力, 0, []); return; }
                        if (!虚拟文件C.存在(路径或主机)) { 收尾(格, 状态_打不开, 0, []); return; }
                        byte[] 块 = 虚拟文件C.读字节块(路径或主机, 0, (int)读上限);
                        收尾(格, 状态_成功, (uint)块.Length, 块);
                    }
                    else if (种类号 == 种类_写文件)
                    {
                        if (虚拟路径C.是虚拟(路径或主机)) { 收尾(格, 状态_没挂能力, 0, []); return; }
                        虚拟文件C.写字节(路径或主机, 写内容);
                        收尾(格, 状态_成功, (uint)写内容.Length, []);
                    }
                    else
                    {
                        var 新 = new Socket(AddressFamily.InterNetwork, SocketType.Stream, ProtocolType.Tcp);
                        try
                        {
                            using var 等 = 新.ConnectAsync(路径或主机, 端口);
                            if (!等.Wait(默认连接超时毫秒)) { 新.Dispose(); 收尾(格, 状态_网络超时, 0, []); return; }
                        }
                        catch (SocketException) { 新.Dispose(); 收尾(格, 状态_连不上, 0, []); return; }
                        catch (ObjectDisposedException) { 新.Dispose(); 收尾(格, 状态_连不上, 0, []); return; }
                        catch (Exception) { 新.Dispose(); 收尾(格, 状态_连不上, 0, []); return; }
                        lock (_任务锁)
                        {
                            if (格.要取消 || !格.在用) { try { 新.Dispose(); } catch { } 格.在跑 = false; 格.在用 = false; return; }
                            格.连接 = 新;
                            格.结果状态 = 状态_成功;
                            格.结果数字 = 0;   // 句柄由 `任务就绪` 装进套接字表之后再填
                            格.在跑 = false;
                        }
                    }
                }
                catch (IOException) { 收尾(格, 状态_读写失败, 0, []); }
                catch (UnauthorizedAccessException) { 收尾(格, 状态_打不开, 0, []); }
                catch (Exception) { 收尾(格, 状态_读写失败, 0, []); }
            })
            { IsBackground = true, Name = $"HB任务{空}" };
            线程.Start();
            return 状态_成功;
        }

        /// <summary>后台线程收尾:把结果放进格子(取消过 / 格子已经被清掉就丢掉)</summary>
        private static void 收尾(任务格C 格, int 状态, uint 数字, byte[] 数据)
        {
            lock (_任务锁)
            {
                if (格.要取消 || !格.在用) { 格.在跑 = false; 格.在用 = false; return; }
                格.结果状态 = 状态;
                格.结果数字 = 数字;
                格.结果数据 = 数据;
                格.在跑 = false;
            }
        }

        /// <summary>
        /// **任务就绪**的宿主那一半(主线程):读一格状态 + 把结果搬进请求块,好了就**收走**(版本 +1)。
        ///
        /// 写回次序(**内容先、两个标量后**):读文件那一趟要把字节写进那个 `字符串` 变量,
        /// 而 `写进字符串变量` 会在池里换块搬数据 —— 两个标量放最后写,才不会被它盖掉。
        /// </summary>
        private static int 处理任务就绪(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 16)) return 状态_参数不合法;
            uint 状态槽 = 参数区 + 4, 字节数槽 = 参数区 + 8;
            写字(内存, 状态槽, 0xFFFFFFFF);                     // 作废 / 号非法时两格都是 -1(确定值,便于对拍)
            写字(内存, 字节数槽, 0xFFFFFFFF);

            uint 号 = 读字(内存, 参数区);
            var 格 = 取任务格(号, out bool 号非法);
            if (号非法) return 状态_句柄无效;                     // 22:这个号根本不成形
            if (格 == null) return 3;                             // 3:作废过(取消 / 收走)或者从来没用过

            lock (_任务锁)
            {
                if (格.在跑) { 写字(内存, 状态槽, 0); 写字(内存, 字节数槽, 0); return 0; }   // 0:还没好
                if (格.要取消) return 3;

                int 状态 = 格.结果状态;
                uint 数字 = 格.结果数字;
                byte[] 数据 = 格.结果数据;
                var 套接字 = 格.连接;
                格.连接 = null;

                // 内容先写:读文件那一趟把字节搬进那个字符串变量(与 `读文件` / `读一块` 同一条路)
                if (状态 == 状态_成功 && 套接字 == null && 格.种类 == 种类_读文件)
                {
                    int 写状态 = 写进字符串变量(内存, 格.头址, 格.池指针槽, 格.池末槽, 数据, 格.上限);
                    if (写状态 != 状态_成功) 状态 = 写状态;
                }

                // 连接那一趟:把连上的套接字**装进套接字表**再给句柄(装不下就是"流太多")
                if (套接字 != null)
                {
                    int 空;
                    lock (_套接字锁)
                    {
                        空 = 找空套接字格();
                        if (空 >= 0)
                        {
                            var 新格 = _套接字表[空] ??= new 套接字格C();
                            新格.套接字 = 套接字;
                            新格.是监听 = false;
                            数字 = 拼套接字句柄(空, 新格.版本);
                        }
                    }
                    if (空 < 0)
                    {
                        try { 套接字.Dispose(); } catch { }
                        状态 = 状态_流太多;
                        数字 = 0;
                    }
                }

                格.版本++;                                        // 收走:这个号当场作废
                格.在用 = false;
                格.结果数据 = [];
                写字(内存, 状态槽, 状态 < 0 ? 0xFFFFFFFF : (uint)状态);
                写字(内存, 字节数槽, 数字);
                return 状态 == 状态_成功 ? 1 : 2;                  // 1 = 好了;2 = 这一趟失败(具体见"状态"那一格)
            }
        }

        /// <summary>**取消任务**的宿主那一半:号当场作废(版本 +1),已经在跑的那一趟拦不住、结果丢掉</summary>
        private static int 处理取消任务(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 8)) return 状态_参数不合法;
            uint 号 = 读字(内存, 参数区);
            var 格 = 取任务格(号, out bool 号非法);
            if (号非法) return 状态_句柄无效;
            if (格 == null) return 3;
            Socket? 待关 = null;
            lock (_任务锁)
            {
                格.要取消 = true;
                格.版本++;                                         // 旧号当场作废(与"收走"同一条)
                if (!格.在跑)
                {
                    待关 = 格.连接;
                    格.连接 = null;
                    格.在用 = false;
                    格.结果数据 = [];
                }
            }
            if (待关 != null) { try { 待关.Dispose(); } catch { } }
            return 状态_成功;
        }


        /// <summary> 一个功能号要读 / 写几个字节的参数区(`处理` 开头的越界闸;各能力表不止 16 字节) </summary>
        private static int 参数区字节数(int 功能号) => 功能号 switch
        {
            功能_打开读流 or 功能_打开写流 => 16,      // 路径址 / 路径长 / 句柄(写回)/ 空
            功能_读一块 => 28,                          // 句柄 / 头址 / 池指针槽 / 池末槽 / 上限 / 字节数(写回)/ 空
            功能_定位 => 12,                            // 句柄 / 偏移 / 空
            功能_关读流 or 功能_关写流 => 8,            // 句柄 / 空
            功能_写一块 => 16,                          // 句柄 / 数据址 / 字节数 / 写回
            功能_当前毫秒 => 4,                         // (无参数)结果写回这一个字
            功能_连接 or 功能_监听 => 16,               // 主机址 / 主机长 / 端口 / 句柄(写回)
            功能_接受 => 12,                            // 监听句柄 / 空 / 句柄(写回)
            功能_发送 => 16,                            // 句柄 / 数据址 / 字节数 / 字节数(写回)
            功能_接收 => 28,                            // 与 `读一块` 逐字节同形(句柄 / 空 / 头址 / 池指针槽 / 池末槽 / 上限 / 字节数)
            功能_发送块 => 16,                          // 句柄 / 块址 / 字节数 / 字节数(写回)
            功能_接收块 => 24,                          // 句柄 / 空 / 块址 / 容量 / 空 / 字节数(写回)
            功能_关闭 => 8,                             // 句柄 / 空
            功能_主机解析 => 24,                        // 主机址 / 主机长 / 头址 / 池指针槽 / 池末槽 / 空
            功能_睡眠 => 4,                             // 毫秒
            功能_冲刷 => 8,                             // 句柄 / 空
            功能_改名 => 16,                            // 旧路径址 / 旧路径长 / 新路径址 / 新路径长
            功能_临时目录 => 28,                        // 空 / 空 / 头址 / 池指针槽 / 池末槽 / 上限 / 状态
            功能_发起异步 => 40,                        // 种类 / 参数一址 / 参数一长 / 参数二址 / 参数二长 / 参数三 / 任务号 / 头址 / 池指针槽 / 池末槽
            功能_任务就绪 => 16,                        // 任务号 / 状态(写回)/ 字节数(写回)/ 空
            功能_取消任务 => 8,                         // 任务号 / 空
            // G4 批 23:剪贴板 / 提示框 / 选文件(请求块形状见各处理函数头上的说明)
            功能_读剪贴板 or 功能_写剪贴板 or 功能_提示框 => 28,   // 与 `读文件` 前三格同形
            功能_选文件 or 功能_另存文件 => 36,                   // 头址 / 池两槽 / 预填名址 + 长
            _ => 16,                                   // P28 那 16 条一律先要 16 字节
        };

        /// <summary> 给虚拟机挂的处理器(见 `虚拟机C.宿主调用`) </summary>
        public static int 处理(byte[] 内存, uint 参数区, int 功能号)
        {
            try
            {
                // 图形能力(R1-6 批 1)与流能力(G3)的参数区大小各异,按各能力的表算;P28 那 16 条一律先要 16 字节
                int 需要 = 图形宿主C.是图形功能号(功能号) ? 图形宿主C.参数区字节数(功能号) : 参数区字节数(功能号);
                if (!放得下(内存, 参数区, 需要)) return 状态_参数不合法;
                switch (功能号)
                {
