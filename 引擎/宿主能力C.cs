        private static int 处理列目录(byte[] 内存, uint 参数区)
        {
            var (路径, 错) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            if (!虚拟文件C.是目录(路径)) return 状态_打不开;
            // 排序 ⇒ 结果稳定(同一目录两次跑出来的字符串一样;自检的"双跑一致"也靠它)
            var 名字 = 虚拟文件C.列名字(路径);
            return 写进字符串变量(内存, 参数区, 头址, Encoding.UTF8.GetBytes(string.Join("\n", 名字)), 读字(内存, 参数区 + 20));
        }

        private static int 处理环境变量(byte[] 内存, uint 参数区)
        {
            var (名, 错) = 取参数串(内存, 参数区, 0);
            if (名 == null) return 错;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            string? 值 = Environment.GetEnvironmentVariable(名);
            if (值 == null) return 状态_打不开;
            return 写进字符串变量(内存, 参数区, 头址, Encoding.UTF8.GetBytes(值), 读字(内存, 参数区 + 20));
        }

