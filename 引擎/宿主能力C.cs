        /// <summary> **写剪贴板**(81):`参数1` 内容址、`参数2` 内容长。覆盖原来的内容。 </summary>
        public const int 功能_写剪贴板 = 81;

        /// <summary> **提示框**(82):`参数1/2` 标题、`参数3/4` 正文、`参数5` 按钮(见 `按钮_*`);
        /// `参数6`(写回)= 答案(见 `答_*`;没弹成给 0xFFFFFFFF)。**阻塞**到用户点了为止。 </summary>
        public const int 功能_提示框 = 82;

        /// <summary> **选文件**(83):`参数1/2` 标题、`参数3/4` 后缀表(分号分隔,例 `".hb;.hbp"`)、
