        /// <summary> 移动文件或目录(目标已存在 → 14;旧路径不存在 → 2)</summary>
        private static int 处理移动到(byte[] 内存, uint 参数区)
        {
            var (旧路径, 错1) = 取路径参数(内存, 参数区, 0);
            if (旧路径 == null) return 错1;
            uint 新址 = 读字(内存, 参数区 + 8);
            uint 新长 = 读字(内存, 参数区 + 12);
            if (!放得下(内存, 新址, 新长)) return 状态_参数不合法;
            string 新路径 = 解析路径(Encoding.UTF8.GetString(内存, (int)新址, (int)新长));

            // H64:两头都可能落在系统目录那一档(虚拟路径)⇒ 一律走 `虚拟文件C`(老口径"不覆盖"没变)
            if (虚拟文件C.存在(新路径)) return 状态_已经存在;
            if (!虚拟文件C.存在(旧路径)) return 状态_打不开;
            虚拟文件C.移动(旧路径, 新路径);
            return 状态_成功;
        }

        /// <summary> 复制文件(照抄内容)或**整棵目录**(目标已存在 → 14,不合并不覆盖)</summary>
        private static int 处理复制到(byte[] 内存, uint 参数区)
        {
            var (源路径, 错1) = 取路径参数(内存, 参数区, 0);
            if (源路径 == null) return 错1;
            uint 目址 = 读字(内存, 参数区 + 8);
            uint 目长 = 读字(内存, 参数区 + 12);
            if (!放得下(内存, 目址, 目长)) return 状态_参数不合法;
            string 目标路径 = 解析路径(Encoding.UTF8.GetString(内存, (int)目址, (int)目长));

            // H64:同 `移动到` —— 问在不在、真搬那一下都走 `虚拟文件C`(目录整棵复制的老口径不变)
            if (虚拟文件C.存在(目标路径)) return 状态_已经存在;
            if (!虚拟文件C.存在(源路径)) return 状态_打不开;
            虚拟文件C.复制(源路径, 目标路径);
            return 状态_成功;
        }

        // ================= G3 域 6:运行时(睡眠 / 冲刷 / 改名 / 临时目录) =================

        /// <summary> 睡 `参数1` 毫秒(**阻塞**)。负数给状态 9 —— 不把它静默当 0 睡,
        /// "写错了参数却一路看上去正常"是最难查的一类 (口径见 `功能_睡眠` 那段注释) </summary>
        private static int 处理睡眠(byte[] 内存, uint 参数区)
        {
            uint 毫秒 = 读字(内存, 参数区);
            if (毫秒 > int.MaxValue) return 状态_参数不合法;
            int 要睡 = (int)毫秒;
            if (要睡 < 0) return 状态_参数不合法;
            Thread.Sleep(要睡);
            return 状态_成功;
        }

        /// <summary> 把一条**写流**的缓冲推下去并落盘(流还开着)。读流给状态 9:
        /// 它没有"要落盘的写缓冲",而 `FileStream.Flush` 会把预读丢掉 —— 那不是用户要的 </summary>
        private static int 处理冲刷(byte[] 内存, uint 参数区)
        {
            uint 句柄 = 读字(内存, 参数区);
            lock (_流锁)
            {
                var 格 = 取流格(句柄);
                if (格 == null) return 状态_句柄无效;
                if (!格.是写) return 状态_参数不合法;
                try { 格.流!.Flush(flushToDisk: true); return 状态_成功; }
                catch (IOException) { return 状态_读写失败; }
                catch (ObjectDisposedException) { return 状态_句柄无效; }
            }
        }

        /// <summary> 改名 / **覆盖式替换**(`移动到` 是"不覆盖"那一档,这一条给原子写用)。
        /// 旧路径不存在 → 2;目录碰上已存在的目标 → 14(目录不替换,口径见 `功能_改名`) </summary>
        private static int 处理改名(byte[] 内存, uint 参数区)
        {
            var (旧路径, 错) = 取路径参数(内存, 参数区, 0);
            if (旧路径 == null) return 错;
            uint 新址 = 读字(内存, 参数区 + 8);
            uint 新长 = 读字(内存, 参数区 + 12);
            if (!放得下(内存, 新址, 新长)) return 状态_参数不合法;
            string 新路径 = 解析路径(Encoding.UTF8.GetString(内存, (int)新址, (int)新长));

            if (!虚拟文件C.存在(旧路径)) return 状态_打不开;
            if (虚拟文件C.存在(新路径) && (虚拟文件C.是目录(旧路径) || 虚拟文件C.是目录(新路径)))
                return 状态_已经存在;
            虚拟文件C.改名(旧路径, 新路径);
            return 状态_成功;
        }

        /// <summary> 把本机临时目录写进那个字符串变量。**尾分隔符去掉**:
        /// .NET 的 `Path.GetTempPath()` 带尾 `\`、C 那边 `getenv("TEMP")` 不带 ⇒ 不去掉,
        /// C# 与 C 两条腿写进变量的字节就不一样(对拍会比出一处"莫名其妙的差") </summary>
        private static int 处理临时目录(byte[] 内存, uint 参数区)
        {
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            return 写进字符串变量(内存, 参数区, 头址, Encoding.UTF8.GetBytes(临时目录文本()), 读字(内存, 参数区 + 20));
        }

        /// <summary> 本机临时目录(尾分隔符去掉;取不到给空串 —— "这台机器没有临时目录"是合法结果,不是失败)。
        /// **至少留一个字符**:`/` 这种"根目录本身就是临时目录"的写法不能被削成空串
        /// (C 后端那一份(`hb_host_临时目录`)同一条口径,两边写进变量的字节必须一样)。 </summary>
        internal static string 临时目录文本()
        {
            try
            {
                string 目录 = Path.GetTempPath();
                string 净 = 目录.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                return 净.Length > 0 ? 净 : 目录;
            }
            catch { return ""; }
        }

        // ================= D3:分块读文件(大文件别一次吃满内存) =================

        /// <summary>
        /// 从 `偏移` 起读**最多** `上限` 字节进那个字符串变量;到头了(或文件空)→ 状态 16 并把变量清空。
        /// 用 `FileStream` 只读这一块(**不 `ReadAllBytes`**)—— 不然"分块"是假的:每次调用还是把整文件读一遍。
        /// 请求块(32 字节):+0 路径址 / +4 路径长 / +8 头址 / +12 池指针槽 / +16 池末槽 / +20 偏移 / +24 上限 / +28 状态。
        /// </summary>
        private static int 处理读文件块(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 28)) return 状态_参数不合法;
            var (路径, 错) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            uint 偏移 = 读字(内存, 参数区 + 20);
            uint 上限 = 读字(内存, 参数区 + 24);
            if (上限 == 0) 上限 = 4096;                     // 兜底:不给上限就一块 4KB

            if (!虚拟文件C.存在(路径)) return 状态_打不开;
            // H64:块读走 `虚拟文件C.读字节块` —— 真路径那份是 `FileStream.Seek`(与老代码一样**不 ReadAllBytes**),
            // 系统目录那一份在流上跳过偏移再读。偏移到末尾(或文件本来就是空的)给空数组
            // ⇒ 状态 16("到末尾了")并把变量清空,调用方看返回值就该停。
            int 上限块 = 上限 > int.MaxValue ? int.MaxValue : (int)上限;
            byte[] 块 = 虚拟文件C.读字节块(路径, 偏移, 上限块);
            if (块.Length == 0)
            {
                写进字符串变量(内存, 参数区, 头址, []);     // 清空:别留着上一块
                return 状态_到末尾;
            }
            return 写进字符串变量(内存, 参数区, 头址, 块);
        }

        // ================= R4-10:3D 模型(`.obj`)=================

        /// <summary>
        /// **读取模型(.obj)**:`参数1/2` 路径、`参数3` 顶点块地址、`参数4` 顶点容量、
        /// `参数5` 边块地址、`参数6` 边容量;写回 `参数7` 顶点数、`参数8` 边数、`参数9` 状态码。
        ///
        /// <para>**只认 `v` 与 `f`**:法线 / 纹理坐标 / 材质 / 分组一律跳过。
        /// 面按多边形处理(扇形三角化),边**去重**(同两个顶点只留一条)。
        /// 面里的下标按 OBJ 规矩:1 起数,**负数 = 从末尾倒数**。</para>
        ///
        /// <para>**读进来之后做一次归一化**(这一步很要紧):把模型**按最长边缩到 2 个单位**、
        /// 再把包围盒中心挪到原点。为什么必须做:不同来源的 OBJ 单位差别极大
        /// (毫米 / 厘米 / 米,还有 0.01 的怪尺度)⇒ 不归一化的话,调用方每换一个模型都要重新配相机。
        /// 归一化之后:**相机口径可以直接用 `眼距 3.2 / 焦距 620` 那一套**(`三维网格.hb` 里注释掉的那档)。</para>
        ///
        /// <para>状态码:0 成功 / 1 打不开 / 2 不是 OBJ(没有顶点)/ 3 装不下(顶点或边超容量)。</para>
        /// </summary>
        private static int 处理读取模型(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 44)) return 状态_参数不合法;
            var (路径, 错) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错;
            uint 顶点址 = 读字(内存, 参数区 + 8);
            uint 顶点容量 = 读字(内存, 参数区 + 12);
            uint 边址 = 读字(内存, 参数区 + 16);
            uint 边容量 = 读字(内存, 参数区 + 20);
            // R4-14:**面块**(可选)。`面容量 = 0` 表示调用方不要面(与老口径完全兼容);
            //   要面就给"面址 + 面容量"(每条面三个整数 = 12 字节,与顶点块一样是紧排)。
            uint 面址 = 读字(内存, 参数区 + 24);
            uint 面容量 = 读字(内存, 参数区 + 28);

            // 出口先按"打不开"写一遍(成功 / 不是 OBJ / 装不下那几路各自再写一次)——
            // **每一条返回路径都要写**:块不是零初始化的,不写调用方读到的是垃圾。
            // ⚠ **参数区偏移千万别和输入撞车**(R4-14 扩到 44 字节之后的新布局):
            //   0/4 路径址/长 · 8/12 顶点址/容量 · 16/20 边址/容量 · 24/28 面址/容量
            //   · **32 = 条数块地址**(输入)· 出口 40/44/48/52。
            //   第一版把出口写在输入那几格上 ⇒ 调用方读到的条数永远是 0(实测踩过两次:
            //   一次是 24/28/32,一次是加面之后忘了把条数块从 24 挪到 32)。
            uint 条数块址 = 读字(内存, 参数区 + 32);

            if (!虚拟文件C.存在(路径))
            {
                写出口(内存, 参数区, 条数块址, 0, 0, 0, 1);   // ⚠ 出口**必须先写**:见 `写出口` 的说明
                return 状态_打不开;
            }

            string 文本;
            try { 文本 = 虚拟文件C.读文本(路径); }
            catch
            {
                写出口(内存, 参数区, 条数块址, 0, 0, 0, 1);
                return 状态_打不开;
            }

            // **逐行真解**(与 `C后端\运行时.c` 的 `hb_host_读取模型` **逐条同口径**)——
            // ⚠ 这一处是 2026-10-11(第415批)纠的:以前借 `ObjLoader` 那份"网格加载器"的结果,
            //   而它是按 `v/vt/vn` 组合**去重**、只留"被面引用过的角点" ⇒ 顶点数 / 顺序都不是文件里那一份。
            //   **实测(同一份 .obj,两条腿各读一遍,那一批当时的素材)**:`脸.obj` C# 给 **259** / C 给 **1009**、
            //   `全身.obj` **524 / 527**、`full.obj` **419 / 424**、`球.obj` 两边都是 220 ——
            //   于是那三个读 OBJ 的标准工程在 `C后端 解释器核` / `全量对拍` 里**永远差一截**(台账 H94),
            //   `模型库 换档` 那两条(钉的就是"文件里 527")也一直红。**契约定的是**:
            //     · 顶点 = 文件里的 `v` 行(**文件序**,不去重、不引用也留着);
            //     · 面   = 按 OBJ 规矩(1 起数 / 负数从**已读到的顶点数**倒数 / 越界丢),扇形三角化;
            //     · 边   = **面(多边形)的边**去重,输出**按 (左端,右端) 升序**(C 那边是插排去重 ⇒ 天然有序,
            //              这一侧必须自己排,否则内存逐字节比一样对不上)。
            var 点 = new List<(float x, float y, float z)>();
            var 边 = new HashSet<(int 左端, int 右端)>();
            var 三角面 = new List<(int 顶点0, int 顶点1, int 顶点2)>();
            try
            {
                foreach (string 原行 in 文本.Replace("\r\n", "\n").Split('\n'))
                {
                    string 行 = 原行.Trim();
                    if (行.Length == 0 || 行[0] == '#') continue;
                    if (行[0] == 'v' && 行.Length > 1 && (行[1] == ' ' || 行[1] == '\t'))
                    {
                        string[] 格 = 行[1..].Split([' ', '\t', '\r', ','], StringSplitOptions.RemoveEmptyEntries);
                        if (格.Length < 3) continue;                       // 只有三个数齐了才算一个顶点
                        if (float.TryParse(格[0], NumberStyles.Float, CultureInfo.InvariantCulture, out float x)
                            && float.TryParse(格[1], NumberStyles.Float, CultureInfo.InvariantCulture, out float y)
                            && float.TryParse(格[2], NumberStyles.Float, CultureInfo.InvariantCulture, out float z))
                        {
                            点.Add((x, y, z));
                        }
                        continue;
                    }
                    if (!(行[0] == 'f' && 行.Length > 1 && (行[1] == ' ' || 行[1] == '\t'))) continue;
                    var 号 = new List<int>();
                    foreach (string 词 in 行[1..].Split([' ', '\t', '\r'], StringSplitOptions.RemoveEmptyEntries))
                    {
                        string 首 = 词.Split('/')[0];
                        if (首.Length == 0) continue;
                        if (!int.TryParse(首, NumberStyles.Integer, CultureInfo.InvariantCulture, out int 原号)) continue;
                        if (原号 == 0) continue;
                        int 号1 = 原号 > 0 ? 原号 - 1 : 点.Count + 原号;     // 负数 = 从**已读到的顶点数**倒数
                        if (号1 < 0 || 号1 >= 点.Count) continue;            // 越界的面整个丢掉(与 C 那边一致)
                        号.Add(号1);
                    }
                    if (号.Count < 3) continue;
                    for (int k = 0; k < 号.Count; k++)                       // 边 = **多边形**的边(不是三角化后的)
                    {
                        int 左端 = 号[k], 右端 = 号[(k + 1) % 号.Count];
                        if (左端 == 右端) continue;
                        边.Add(左端 < 右端 ? (左端, 右端) : (右端, 左端));
                    }
                    for (int k = 1; k + 1 < 号.Count; k++)                   // 面 = 扇形三角化(绕向照 OBJ 原样)
                    {
                        if (号[0] == 号[k] || 号[k] == 号[k + 1] || 号[0] == 号[k + 1]) continue;
                        三角面.Add((号[0], 号[k], 号[k + 1]));
                    }
                }
            }
            catch
            {
                写出口(内存, 参数区, 条数块址, 0, 0, 0, 1);
                return 状态_打不开;
            }

            if (点.Count == 0)
            {
                写出口(内存, 参数区, 条数块址, 0, 0, 0, 2);          // 不是 OBJ
                return 状态_成功;
            }
            if (点.Count > 顶点容量 || 边.Count > 边容量 || (面容量 > 0 && 三角面.Count > 面容量))
            {
                写出口(内存, 参数区, 条数块址,
                    (uint)Math.Min(点.Count, int.MaxValue),
                    (uint)Math.Min(边.Count, int.MaxValue),
                    (uint)Math.Min(三角面.Count, int.MaxValue), 3);   // 装不下(如实报条数,好让调用方把上限调大)
                return 状态_成功;
            }

            // ---- 归一化:包围盒中心挪到原点,最长边缩到 2 个单位 ----
            float 小x = 点[0].x, 大x = 点[0].x;
            float 小y = 点[0].y, 大y = 点[0].y;
            float 小z = 点[0].z, 大z = 点[0].z;
            foreach (var p in 点)
            {
                if (p.x < 小x) 小x = p.x; else if (p.x > 大x) 大x = p.x;
                if (p.y < 小y) 小y = p.y; else if (p.y > 大y) 大y = p.y;
                if (p.z < 小z) 小z = p.z; else if (p.z > 大z) 大z = p.z;
            }
            float 宽x = 大x - 小x, 宽y = 大y - 小y, 宽z = 大z - 小z;
            float 最长 = MathF.Max(宽x, MathF.Max(宽y, 宽z));
            float 倍 = 最长 > 1e-9f ? 2.0f / 最长 : 1.0f;
            float 中x = (小x + 大x) * 0.5f, 中y = (小y + 大y) * 0.5f, 中z = (小z + 大z) * 0.5f;

            // ---- 写顶点(紧排 x,y,z 三个单精度)----
            for (int i = 0; i < 点.Count; i++)
            {
                uint 基 = 顶点址 + (uint)(i * 12);
                if (基 + 12 > 内存.Length) return 状态_参数不合法;
                写浮点(内存, 基, (点[i].x - 中x) * 倍);
                写浮点(内存, 基 + 4, (点[i].y - 中y) * 倍);
                写浮点(内存, 基 + 8, (点[i].z - 中z) * 倍);
            }
            // ---- 写边(每条两个 32 位整数下标)**按 (左端,右端) 升序** ----
            // ⚠ 顺序是契约的一部分:C 那边 `hb_obj_e` 的去重是"二分找位 + 插入" ⇒ 出来天然有序;
            //   这一侧交的是 `HashSet`,不排就是随机序 ⇒ 内存逐字节比对不上(H94 那三个工程里也有这一笔)。
            var 边序 = new List<(int 左端, int 右端)>(边);
            边序.Sort((a, b) => a.左端 != b.左端 ? a.左端 - b.左端 : a.右端 - b.右端);
            int 第 = 0;
            foreach (var (左端, 右端) in 边序)
            {
                uint 基 = 边址 + (uint)(第 * 8);
                if (基 + 8 > 内存.Length) return 状态_参数不合法;
                写字(内存, 基, (uint)左端);
                写字(内存, 基 + 4, (uint)右端);
                第++;
            }

            // ---- 出口:统一走 `写出口`(参数区 + 调用方那块都写)----
            // ---- 写面(每条三个整数下标;调用方不要面(`面容量 = 0`)就跳过) ----
            if (面容量 > 0 && 面址 != 0)
            {
                for (int i = 0; i < 三角面.Count; i++)
                {
                    uint 基 = 面址 + (uint)(i * 12);
                    if (基 + 12 > 内存.Length) return 状态_参数不合法;
                    写字(内存, 基, (uint)三角面[i].顶点0);
                    写字(内存, 基 + 4, (uint)三角面[i].顶点1);
                    写字(内存, 基 + 8, (uint)三角面[i].顶点2);
                }
            }

            写出口(内存, 参数区, 条数块址, (uint)点.Count, (uint)边.Count, (uint)三角面.Count, 0);   // 成功
            return 状态_成功;
        }

        /// <summary>
        /// **写三个出口**(顶点数 / 边数 / 状态码),同时写进参数区与调用方给的条数块。
        ///
        /// ⚠ **每一条返回路径都得调它,包括"打不开"那条**(这一条是踩出来的):
        /// 第一版只在成功那一路写出口,文件不存在时**直接返回** —— 调用方读到的就是
        /// `申请` 下来那块里的**垃圾值**(自检里表现为"返回假、状态码 0",
        /// 而它本该是状态码 1)。**块不是零初始化的** ⇒ 出口要么写、要么调用方无从判断。
        /// </summary>
        private static void 写出口(byte[] 内存, uint 参数区, uint 条数块址, uint 顶点数, uint 边数, uint 面数, uint 状态)
        {
            // ⚠ 参数区布局(R4-14 扩到 44 字节 = 11 格):
            //   0~7   路径址/长
            //   8~11  顶点址 / 12~15 顶点容量
            //   16~19 边址   / 20~23 边容量
            //   24~27 面址   / 28~31 面容量      ← R4-14 新增(**面容量 = 0 = 不要面**)
            //   32~39 **条数块地址**(输入;那块里三格:顶点数 / 边数 / 面数)
            //   出口:40 顶点数 · 44 边数 · 48 面数 · 52 状态 —— ⚠ **别再和输入撞车**(第一版撞过)
            写字(内存, 参数区 + 40, 顶点数);
            写字(内存, 参数区 + 44, 边数);
            写字(内存, 参数区 + 48, 面数);
            写字(内存, 参数区 + 52, 状态);
            if (条数块址 != 0 && 条数块址 + 16 <= 内存.Length)
            {
                写字(内存, 条数块址, 顶点数);
                写字(内存, 条数块址 + 4, 边数);
                写字(内存, 条数块址 + 8, 面数);
                写字(内存, 条数块址 + 12, 状态);
            }
        }

        /// <summary> 往内存里写一个单精度浮点(位模式小端;与 ISA 的口径一致) </summary>
        private static void 写浮点(byte[] 内存, uint 址, float 值)
        {
            uint 位 = (uint)BitConverter.SingleToInt32Bits(值);
            写字(内存, 址, 位);
        }

        // ================= G3:流式读写(域 1:流 48~54)=================

        /// <summary>
        /// **打开读流 / 打开写流**:`参数1/2` 路径、`参数3` 写回 = 句柄(失败写 -1)。
        /// 读流走 `FileMode.Open`(**文件必须在**;不存在给状态 2)、写流走 `FileMode.Create`(不存在就新建、存在就从头写起)。
        /// 都只 `FileShare.Read`(同一个文件同时开写流两份会互相踩)。
        /// </summary>
        private static int 处理打开流(byte[] 内存, uint 参数区, bool 写)
        {
            var (路径, 错) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错;
            uint 句柄槽 = 参数区 + 8;
            var (句柄, 状态) = 开流(路径, 写);
            写字(内存, 句柄槽, 状态 == 状态_成功 ? 句柄 : 0xFFFFFFFF);
            return 状态;
        }

        /// <summary>
        /// **读一块**:请求块与 `读文件块` **同形**(+8 头址 / +12 池指针槽 / +16 池末槽 / +20 上限),
        /// 只把"+0 路径址 +4 路径长"换成"+0 句柄",写回改成"+24 读到的字节数"(失败 -1)。
        /// **只有句柄无效或参数不合法才给 -1**:读到末尾给 0(而"读到一半出错"为了不退化成死循环,
        /// 也当末尾给 0 —— 调用方看 `块.长度()` 就知道这一轮拿到没有)。
        /// </summary>
        private static int 处理读一块(byte[] 内存, uint 参数区)
        {
            uint 头址 = 读字(内存, 参数区 + 8);
            uint 句柄 = 读字(内存, 参数区);
            uint 字节数槽 = 参数区 + 24;
            int 状态 = 状态_句柄无效;
            if (!放得下(内存, 头址, 12)) { 写字(内存, 字节数槽, 0xFFFFFFFF); return 状态_参数不合法; }
            lock (_流锁)
            {
                var 格 = 取流格(句柄);
                if (格 != null)
                {
                    uint 上限 = 读字(内存, 参数区 + 20);
                    if (上限 == 0) 上限 = 4096;                       // 兜底:不给上限就一块 4KB
                    byte[] 块 = [];
                    int 结果;
                    try
                    {
                        // 上限不由调用方信任:最多读到内存装得下的一小块(防止"上限给了 1MB、内存只有 64KB")
                        int 要 = (int)Math.Min(上限, 1024u * 1024u);
                        块 = new byte[要];
                        int 收 = 0, 读;
                        while (收 < 要 && (读 = 格.流!.Read(块, 收, 要 - 收)) > 0) 收 += 读;
                        if (收 != 要) Array.Resize(ref 块, 收);
                        结果 = 收;
                        状态 = 状态_成功;
                    }
                    catch (IOException) { 结果 = 0; 状态 = 状态_成功; }   // 读到一半出错:当末尾(见上面那段口径)
                    catch (ObjectDisposedException) { 结果 = -1; 状态 = 状态_句柄无效; }
                    // ⚠ **字节数先写回**:`写进字符串变量` 会在池里换块 / 搬数据,而池块完全可能盖住请求块自己
                    //   (实测:先写内容再写字节数,`块.长度()` 读到 0 —— 那 4 字节被字符串的数据盖掉了)
                    写字(内存, 字节数槽, 结果 < 0 ? 0xFFFFFFFF : (uint)结果);
                    if (状态 == 状态_成功)
                    {
                        int 写状态 = 写进字符串变量(内存, 参数区, 头址, 块);
                        if (写状态 != 状态_成功) { 写字(内存, 字节数槽, 0xFFFFFFFF); return 写状态; }
                    }
                    return 状态;
                }
            }
            写字(内存, 字节数槽, 0xFFFFFFFF);
            return 状态;
        }

        /// <summary> **写一块**:`参数1` 句柄、`参数2` 数据址、`参数3` 字节数;`参数4` 写回 = 真写下去几个字节(失败 -1)。
        /// 到这儿**还没落盘**(盘上见不见得到由 `关写流` 的冲刷说了算)。 </summary>
        private static int 处理写一块(byte[] 内存, uint 参数区)
        {
            uint 句柄 = 读字(内存, 参数区);
            uint 数据址 = 读字(内存, 参数区 + 4);
            uint 字节数 = 读字(内存, 参数区 + 8);
            uint 写回槽 = 参数区 + 12;
            int 结果 = -1;
            int 状态 = 状态_句柄无效;
            lock (_流锁)
            {
                var 格 = 取流格(句柄);
                if (格 != null && (!放得下(内存, 数据址, 字节数) || !格.是写)) { 状态 = 状态_参数不合法; }
                else if (格 != null)
                {
                    byte[] 数据 = new byte[字节数];
                    Array.Copy(内存, (int)数据址, 数据, 0, (int)字节数);
                    try
                    {
                        格.流!.Write(数据, 0, 数据.Length);
                        格.流.Flush();
                        结果 = 数据.Length;
                        状态 = 状态_成功;
                    }
                    catch (IOException) { 结果 = -1; 状态 = 状态_读写失败; }
                    catch (ObjectDisposedException) { 结果 = -1; 状态 = 状态_句柄无效; }
                }
            }
            写字(内存, 写回槽, 结果 < 0 ? 0xFFFFFFFF : (uint)结果);
            return 状态;
        }

        /// <summary> **定位**:`参数1` 句柄、`参数2` 绝对偏移(从文件开头算);读流 / 写流都能定(写流定位过再写 = 覆盖)。 </summary>
        private static int 处理定位(byte[] 内存, uint 参数区)
        {
            uint 句柄 = 读字(内存, 参数区);
            uint 偏移 = 读字(内存, 参数区 + 4);
            lock (_流锁)
            {
                var 格 = 取流格(句柄);
                if (格 == null) return 状态_句柄无效;
                try { 格.流!.Seek(偏移, SeekOrigin.Begin); return 状态_成功; }
                catch (IOException) { return 状态_读写失败; }
                catch (ObjectDisposedException) { return 状态_句柄无效; }
            }
        }

        // ================= G3 域 3:网络(裸 socket)的七个处理函数 =================
        //
        // 请求块布局(与中间层 `求值网络` 一一对应):
        //   连接 / 监听  16 字节:+0 主机址 / +4 主机长 / +8 端口 / +12 句柄(写回,-1 = 失败)
        //   接受         12 字节:+0 监听句柄 / +4(空)/ +8 句柄(写回)
        //   发送         16 字节:+0 句柄 / +4 数据址 / +8 字节数 / +12 真发出去几个字节(写回)
        //   接收         28 字节:+0 句柄 / +4(空)/ +8 头址 / +12 池指针槽 / +16 池末槽 / +20 上限 / +24 收到几个字节
        //   关闭          8 字节:+0 句柄 / +4(空)
        //   主机解析     24 字节:+0 主机址 / +4 主机长 / +8 头址 / +12 池指针槽 / +16 池末槽 / +20(空)
        //
        // **写回槽在"没挂能力"时也要写 -1**:C 后端(独立 exe / 解释器核)对整族一律状态 1,
        // 两边逐字节对拍靠的就是"先写 -1、再返回状态码"这一个次序(与 `处理运行进程` 同一条口径)。

        /// <summary>
        /// **连接 / 监听**:白名单那一关在**最前面**(不在 `网址` 表里连 DNS 都不做)。
        /// 失败一律把 -1 写进句柄槽 —— 调用方看 -1 就知道"这一条没开成"(具体是哪一种失败见 `说明`)。
        /// </summary>
        private static int 处理连接或监听(byte[] 内存, uint 参数区, bool 监听)
        {
            if (!放得下(内存, 参数区, 16)) return 状态_参数不合法;
            uint 句柄槽 = 参数区 + 12;
            写字(内存, 句柄槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;                 // 手机端 / 独立 exe / 没给工程文件

            var (主机, 错) = 取参数串(内存, 参数区, 0);
            if (主机 == null) return 错;
            主机 = 主机.Trim();
            if (主机.Length == 0) return 状态_参数不合法;
            uint 端口 = 读字(内存, 参数区 + 8);
            if (端口 < 1 || 端口 > 65535) return 状态_参数不合法;
            if (!网址白名单.允许主机端口(主机, (int)端口, out _)) return 状态_网址不在白名单;

            var (句柄, 状态) = 开套接字(主机, (int)端口, 监听);
            if (状态 == 状态_成功) 写字(内存, 句柄槽, 句柄);
            return 状态;
        }

        /// <summary> **接受**:从监听句柄上收一个新连接(`Accept` **同步阻塞**;表满给状态 23)。 </summary>
        private static int 处理接受(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 12)) return 状态_参数不合法;
            uint 句柄槽 = 参数区 + 8;
            写字(内存, 句柄槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;

            套接字格C? 听格;
            int 空;
            lock (_套接字锁)
            {
                听格 = 取套接字格(读字(内存, 参数区));
                if (听格 == null || !听格.是监听) return 状态_句柄无效;
                空 = 找空套接字格();
                if (空 < 0) return 状态_流太多;                            // 先找位再接受:表满时不去惊动内核
            }

            Socket? 新连;
            try { 新连 = 听格.套接字!.Accept(); }                          // 无锁等(见 `开套接字` 那段说明)
            catch (SocketException) { return 状态_连不上; }
            catch (ObjectDisposedException) { return 状态_句柄无效; }
            catch (Exception) { return 状态_连不上; }

            lock (_套接字锁)
            {
                var 新格 = _套接字表[空] ??= new 套接字格C();
                if (新格.套接字 != null) { try { 新连.Dispose(); } catch { } return 状态_流太多; }
                新格.套接字 = 新连;
                新格.是监听 = false;
                写字(内存, 句柄槽, 拼套接字句柄(空, 新格.版本));
                return 状态_成功;
            }
        }

        /// <summary> **发送**:把内存里那一段字节发出去(一路 `Send` 到发完;半路发不动给状态 4)。 </summary>
        private static int 处理发送(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 16)) return 状态_参数不合法;
            uint 写回槽 = 参数区 + 12;
            写字(内存, 写回槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;

            uint 数据址 = 读字(内存, 参数区 + 4);
            uint 字节数 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 数据址, 字节数)) return 状态_参数不合法;
            var 格 = 取套接字格(读字(内存, 参数区));
            if (格 == null || 格.是监听) return 状态_句柄无效;               // 监听句柄只能 `接受`,不能收发

            byte[] 数据 = new byte[字节数];
            Array.Copy(内存, (int)数据址, 数据, 0, (int)字节数);
            int 总 = 0;
            try
            {
                while (总 < 数据.Length)
                {
                    int 发 = 格.套接字!.Send(数据, 总, 数据.Length - 总, SocketFlags.None);
                    if (发 <= 0) break;
                    总 += 发;
                }
            }
            catch (SocketException) { 写字(内存, 写回槽, (uint)总); return 状态_读写失败; }
            catch (ObjectDisposedException) { return 状态_句柄无效; }
            写字(内存, 写回槽, (uint)总);
            return 总 == 数据.Length ? 状态_成功 : 状态_读写失败;
        }

        /// <summary>
        /// **接收**:请求块与 `读一块` **逐字节同形**(+8 头址 / +12 池指针槽 / +16 池末槽 / +20 上限),
        /// 只把"+0 路径址 +4 路径长"换成"+0 句柄"、写回挪到"+24 收到几个字节"。
        /// **收到 0 字节 = 对端关掉了**(这时内容变量清空,与 `读一块` 的"到末尾"同一套写法);
        /// 半路出错也当 0(不退化成死循环)。只有句柄无效 / 参数不合法才给 -1。
        /// </summary>
        private static int 处理接收(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 28)) return 状态_参数不合法;
            uint 字节数槽 = 参数区 + 24;
            写字(内存, 字节数槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;

            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;
            var 格 = 取套接字格(读字(内存, 参数区));
            if (格 == null || 格.是监听) return 状态_句柄无效;

            uint 上限 = 读字(内存, 参数区 + 20);
            if (上限 == 0) 上限 = 4096;                                    // 兜底:不给上限就一块 4KB
            int 要 = (int)Math.Min(上限, 1024u * 1024u);                   // 上限不由调用方信任(与 `读一块` 同)
            byte[] 块 = new byte[要];
            int 收;
            int 状态;
            try
            {
                收 = 格.套接字!.Receive(块, 0, 要, SocketFlags.None);
                状态 = 状态_成功;
            }
            catch (SocketException) { 收 = 0; 状态 = 状态_成功; }          // 对端断了:当"不给了"(见上面那段口径)
            catch (ObjectDisposedException) { 收 = -1; 状态 = 状态_句柄无效; }

            if (收 <= 0) 块 = [];
            else if (收 < 要) Array.Resize(ref 块, 收);
            // ⚠ 字节数**先**写回、再写字符串:池里换块搬数据完全可能盖住请求块自己(与 `读一块` 那个坑同一个)
            写字(内存, 字节数槽, 收 < 0 ? 0xFFFFFFFF : (uint)收);
            if (状态 == 状态_成功)
            {
                int 写状态 = 写进字符串变量(内存, 参数区, 头址, 块);
                if (写状态 != 状态_成功) { 写字(内存, 字节数槽, 0xFFFFFFFF); return 写状态; }
            }
            return 状态;
        }

        /// <summary>
        /// **发送块**(2026-10-06 加):与 `处理发送` 逐条同口径,只差一点 ——
        /// 这一条收的是**块地址 + 显式字节数**,不看字符串头、也不扫 0
        /// ⇒ 报文里有 `00` 字节照样发得出去。
        /// 直接从虚拟机内存那一格发(`Socket.Send(内存, 址, 长, …)`),连一次拷贝都省了。
        /// </summary>
        private static int 处理发送块(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 16)) return 状态_参数不合法;
            uint 写回槽 = 参数区 + 12;
            写字(内存, 写回槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;

            uint 数据址 = 读字(内存, 参数区 + 4);
            uint 字节数 = 读字(内存, 参数区 + 8);
            if (字节数 > 0 && !放得下(内存, 数据址, 字节数)) return 状态_参数不合法;
            var 格 = 取套接字格(读字(内存, 参数区));
            if (格 == null || 格.是监听) return 状态_句柄无效;               // 监听句柄只能 `接受`,不能收发

            int 总 = 0;
            try
            {
                while (总 < (int)字节数)
                {
                    int 发 = 格.套接字!.Send(内存, (int)数据址 + 总, (int)字节数 - 总, SocketFlags.None);
                    if (发 <= 0) break;
                    总 += 发;
                }
            }
            catch (SocketException) { 写字(内存, 写回槽, (uint)总); return 状态_读写失败; }
            catch (ObjectDisposedException) { return 状态_句柄无效; }
            写字(内存, 写回槽, (uint)总);
            return 总 == (int)字节数 ? 状态_成功 : 状态_读写失败;
        }

        /// <summary>
        /// **接收块**(2026-10-06 加):与 `处理接收` 逐条同口径,只差"往哪写" ——
        /// 直接收进调用方给的**块地址**(按 `容量` 封顶),**不碰字符串头、不碰池**。
        /// 于是 `取字` / `存字` 逐字节都读得回来 —— 帧头那种"里面有任意字节"的东西这才收得了。
        /// 参数区:`+0` 句柄 / `+4`(空)/ `+8` 块址 / `+12` 容量 / `+16`(空)/ `+20` 字节数(写回)。
        /// **收到 0 字节 = 对端关掉了**(与 `接收` / `读一块` 同一套写法);半路出错也当 0。
        /// </summary>
        private static int 处理接收块(byte[] 内存, uint 参数区)
        {
            if (!放得下(内存, 参数区, 24)) return 状态_参数不合法;
            uint 字节数槽 = 参数区 + 20;
            写字(内存, 字节数槽, 0xFFFFFFFF);
            if (网址白名单 == null) return 状态_没挂能力;

            uint 块址 = 读字(内存, 参数区 + 8);
            uint 容量 = 读字(内存, 参数区 + 12);
            if (容量 == 0) 容量 = 4096;                                    // 兜底:不给容量就一块 4KB
            if (容量 > 1024u * 1024u) 容量 = 1024u * 1024u;                // 容量不由调用方信任(与 `接收` 同)
            if (!放得下(内存, 块址, 容量)) return 状态_参数不合法;

            var 格 = 取套接字格(读字(内存, 参数区));
            if (格 == null || 格.是监听) return 状态_句柄无效;

            int 收;
            int 状态;
            try
            {
                收 = 格.套接字!.Receive(内存, (int)块址, (int)容量, SocketFlags.None);
                状态 = 状态_成功;
            }
            catch (SocketException) { 收 = 0; 状态 = 状态_成功; }          // 对端断了:当"不给了"(与 `处理接收` 同)
            catch (ObjectDisposedException) { 收 = 0; 状态 = 状态_句柄无效; }

            if (收 < 0) 收 = 0;
            写字(内存, 字节数槽, (uint)收);
            return 状态;
        }

