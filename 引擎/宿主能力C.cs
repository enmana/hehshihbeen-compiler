        private static uint 读字(byte[] 内存, uint 地址)
            => (uint)(内存[地址] | (内存[地址 + 1] << 8) | (内存[地址 + 2] << 16) | (内存[地址 + 3] << 24));

        private static void 写字(byte[] 内存, uint 地址, uint 值)
        {
            内存[地址] = (byte)(值 & 0xFF);
            内存[地址 + 1] = (byte)((值 >> 8) & 0xFF);
            内存[地址 + 2] = (byte)((值 >> 16) & 0xFF);
            内存[地址 + 3] = (byte)((值 >> 24) & 0xFF);
        }

        private static bool 放得下(byte[] 内存, uint 地址, long 长度)
            => 地址 <= (uint)内存.Length && 长度 >= 0 && 地址 + (uint)长度 <= (uint)内存.Length;

        private static int 处理读文件(byte[] 内存, uint 参数区)
        {
            var (路径, 错) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错;
            uint 头址 = 读字(内存, 参数区 + 8);
            if (!放得下(内存, 头址, 12)) return 状态_参数不合法;

            if (!虚拟文件C.存在(路径)) return 状态_打不开;
            // 上限(参数区 +20)是**硬上限**:要读大的就用 `读文件块` 分块(以前这里把"上限"当摆设,文件多大读多大)
            // H64:读字节走 `虚拟文件C`(系统目录那一档由挂上的实现去读)
            return 写进字符串变量(内存, 参数区, 头址, 虚拟文件C.读字节(路径), 读字(内存, 参数区 + 20));
        }

        /// <summary>
        /// 把一段字节写进"参数 3 那个字符串头"指向的字符串变量(读文件 / 列目录 / 环境变量 三条共用)。
        /// 装不下就按 ×2 从池里换一块(与"赋值/拼接到"同一套口径),末尾补一个 0 字节。
        /// 池指针槽 / 池末槽的地址由中间层随请求块递进来(参数 4 / 参数 5)。
        ///
        /// **R1-2:池会自己长大** —— 装不下时先按 ×2 把"池末"往上抬(`池末*2`),最多抬到
        /// **运行内存末尾 − 给硬件栈留的余量**(与 `虚拟机C.栈顶保留` 同一个口径;这儿能直接从内存数组长度
        /// 读出运行内存有多大,不用编译期把 `内存` 递进来)。抬到顶还装不下才返回"放不下"。
        /// 生成代码那一侧(中间层 `池要一块`)抬的是同一个"池末槽",两边口径一致。
        ///
        /// ⚠⚠ **这个重载只认"六格请求块"**:池两槽的**地址**是从 `参数区 +12 / +16` 读的 ——
        /// 那是 `读文件` / `取网址` / `运行进程` 那种"路径(两格)+ 头址 + 池槽 ×2 + …"的布局。
        /// 请求块**不是**那个形状的(例如 G4 批 23 的 `读剪贴板`:四格 = 头址 / 池指针槽 / 池末槽 / 状态)
        /// **必须调下面那个"池两格直接给"的重载** —— 否则 +12 / +16 落在**别人家的内存**上,
        /// 池指针被写成垃圾,最后以状态 3("放不下")收场,而真正的内容一个字都没问题(实测踩过)。
        /// </summary>
        private static int 写进字符串变量(byte[] 内存, uint 参数区, uint 头址, byte[] 内容, uint 上限 = 0)
        {
            // D3:上限真生效(以前 `读文件` 的"上限"只是个摆设,文件多大就全读进来)
            if (上限 > 0 && 内容.Length > 上限) 内容 = 内容[..(int)上限];
            uint 池指针槽 = 读字(内存, 参数区 + 12);
            uint 池末槽 = 读字(内存, 参数区 + 16);
            return 写进字符串变量(内存, 头址, 池指针槽, 池末槽, 内容, 上限);
        }

        /// <summary>
        /// 同上,但**池那两格直接给**(G3 域 5 的异步读要用):`任务就绪` 手上只有任务格里抄下来的
        /// 头地址与两个槽地址,没有"请求块"(内容是从**上一次** `发起异步` 的请求块里抄下来的),
        /// 所以把真正干活的那一半单独拿出来。
        /// **上限这里不再截**:调用方(异步读)在发起那一刻就按上限读完了。
        /// </summary>
        private static int 写进字符串变量(byte[] 内存, uint 头址, uint 池指针槽, uint 池末槽, byte[] 内容, uint 上限 = 0)
        {
            if (上限 > 0 && 内容.Length > 上限) 内容 = 内容[..(int)上限];

            uint 数据址 = 读字(内存, 头址);
            uint 容量 = 读字(内存, 头址 + 8);
            if (内容.Length + 1 > 容量)
            {
                // 装不下:按 ×2 从池里换一块(与"赋值/拼接到"同一套口径)
                //   —— 池是编译器管的:池指针槽/池末槽的地址由中间层随请求块一起递进来
                if (!放得下(内存, 池指针槽, 8) || !放得下(内存, 池末槽, 4)) return 状态_参数不合法;
                uint 新容量 = Math.Max((uint)(内容.Length + 1), 容量 * 2);
                uint 池指针 = 读字(内存, 池指针槽);
                uint 池末 = 读字(内存, 池末槽);
                if (池指针 + 新容量 > 池末)
                {
                    // R1-2:池自己长大 —— 池末 ×2 往上抬,最多抬到硬顶
                    int 余量 = 虚拟机C.栈顶保留(内存.Length);
                    uint 硬顶 = 内存.Length > 余量 ? (uint)(内存.Length - 余量) : 0;
                    while (池末 < 硬顶 && 池指针 + 新容量 > 池末)
                    {
                        uint 抬到 = Math.Min(池末 * 2, 硬顶);
                        if (抬到 <= 池末) break;
                        池末 = 抬到;
                        写字(内存, 池末槽, 池末);
                    }
                }
                if (池指针 + 新容量 > 池末) return 状态_放不下;
                uint 新块 = 池指针;
                if (!放得下(内存, 新块, 新容量 + 1)) return 状态_参数不合法;
                // 老内容搬到新块(源与目标可能重叠,但新块在池尾、旧块在池里更靠前 → 从前往后拷是安全的)
                uint 旧长 = 读字(内存, 头址 + 4);
                if (旧长 > 0 && 放得下(内存, 数据址, 旧长))
                    Array.Copy(内存, (int)数据址, 内存, (int)新块, (int)旧长);
                写字(内存, 头址, 新块);            // 头里的数据地址
                写字(内存, 头址 + 8, 新容量);      // 头里的容量
                写字(内存, 池指针槽, 池指针 + 新容量);   // 池指针往前挪
                数据址 = 新块;
                容量 = 新容量;
            }
            if (!放得下(内存, 数据址, 内容.Length + 1)) return 状态_参数不合法;

            Array.Copy(内容, 0, 内存, (int)数据址, 内容.Length);
            内存[数据址 + 内容.Length] = 0;
            写字(内存, 头址 + 4, (uint)内容.Length);                        // 长度写回头里
            return 状态_成功;
        }

        /// <summary> 取"参数1/参数2"那对(数据地址, 长度)对应的字符串;不合法时返回 (null, 状态码) </summary>
        private static (string? 文本, int 状态) 取参数串(byte[] 内存, uint 参数区, uint 参数下标)
        {
            uint 址 = 读字(内存, 参数区 + 参数下标 * 4);
            uint 长 = 读字(内存, 参数区 + 参数下标 * 4 + 4);
            if (!放得下(内存, 址, 长)) return (null, 状态_参数不合法);
            return (Encoding.UTF8.GetString(内存, (int)址, (int)长), 状态_成功);
        }

        private static int 处理追加写文件(byte[] 内存, uint 参数区) => 写字到文件(内存, 参数区, 追加: true);

        private static int 处理写文件(byte[] 内存, uint 参数区) => 写字到文件(内存, 参数区, 追加: false);

        /// <summary> 写 / 追加写:路径(参数1、2)+ 内容(参数3、4);两种只差打开方式 </summary>
        private static int 写字到文件(byte[] 内存, uint 参数区, bool 追加)
        {
            var (路径, 错1) = 取路径参数(内存, 参数区, 0);
            if (路径 == null) return 错1;
            uint 内容址 = 读字(内存, 参数区 + 8);
            uint 内容长 = 读字(内存, 参数区 + 12);
            if (!放得下(内存, 内容址, 内容长)) return 状态_参数不合法;

            byte[] 内容 = new byte[内容长];
            Array.Copy(内存, (int)内容址, 内容, 0, (int)内容长);
            // 缺的目录先建出来:相对路径是相对"程序运行时的工作目录"的(手机端是 H10 那个**基准目录**),
            // 不建的话换个目录跑就写不进去(用户实测:示例在 IDE 里跑 → 工作目录不是仓库根 → 写文件一路失败)
            // H64:写盘走 `虚拟文件C`(真路径那份实现与老代码一样会先建缺的目录)
            if (追加) 虚拟文件C.追加字节(路径, 内容);
            else 虚拟文件C.写字节(路径, 内容);
            return 状态_成功;
        }

        private static int 处理建目录(byte[] 内存, uint 参数区)
