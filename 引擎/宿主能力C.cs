        /// <summary> 取退出码(D1):无参数;把**上一次** `运行进程` 的退出码写进 `参数1` 那个字(还没跑过给 0xFFFFFFFF)。 </summary>
        public const int 功能_取退出码 = 10;

        /// <summary>
        /// 删目录(D2):`参数1` 路径址、`参数2` 路径长。**只删空目录** —— 目录不空给状态 13,
