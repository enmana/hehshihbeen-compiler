        /// `参数4/5` 池指针槽/池末槽、`参数6` 超时毫秒(0 = 默认 10000)、`参数7` 响应体上限字节、
        /// `参数8`(写回)= HTTP 状态码。**只做同步一次性 GET**,不跟跳转、不做长连接。
