        //  ② **自检一条窗口都不开**(硬规矩 6):本族的判据只钉"参数区形状 / 状态码 / 取消与不支持要分得开",
        //     真弹窗 / 真挑文件**只由人点**(库与示例那一侧给人用);
        //  ③ **文本只有 `字符串` 一种**(HB 没有剪贴板格式协商、也没有图片):图片要等位图那一族与平台
        //     剪贴板格式对上号(那是后面的事,现在如实只做文本)。

        /// <summary> **读剪贴板**(80):`参数1` 输出串头址、`参数2` 池指针槽、`参数3` 池末槽;
        /// `参数4`(写回)状态。剪贴板里没有文本 ⇒ 成功且给空串。 </summary>
