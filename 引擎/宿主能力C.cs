        /// <summary>
        /// H10:把 HB 侧写的路径解析成真路径(**唯一一处**,别在别处再拼一次)。
        /// 没设基准目录 ⇒ 原样返回;解析不出来(怪字符之类)也原样返回 —— 让下层照旧报"打不开",
        /// 别在这里把一条路径错误变成一次崩溃。
        /// </summary>
        public static string 解析路径(string 路径)
        {
            if (string.IsNullOrEmpty(路径)) return 路径;
            string? 基准 = 基准目录;
            if (基准 == null) return 路径;
            try
            {
                // H64:基准目录或路径本身落在"系统目录那一档"(虚拟路径)时,只做字符串拼接 ——
                // `Path.GetFullPath` 会把 `内容://…` 算成一个谁都不认识的名字
                if (虚拟路径C.是虚拟(基准) || 虚拟路径C.是虚拟(路径))
                    return 虚拟路径C.收正(虚拟路径C.拼接(基准, 路径));
                return Path.IsPathRooted(路径) ? 路径 : Path.GetFullPath(Path.Combine(基准, 路径));
            }
            catch { return 路径; }
        }

        /// <summary> 取"参数1/参数2"那对并按 H10 的基准目录解析成真路径(路径型能力的一号参数专用) </summary>
        private static (string? 路径, int 状态) 取路径参数(byte[] 内存, uint 参数区, uint 参数下标)
        {
            var (文本, 状态) = 取参数串(内存, 参数区, 参数下标);
            return 文本 == null ? (null, 状态) : (解析路径(文本), 状态);
        }

        /// <summary> 这一份实现取的"现在"(Unix 秒);换掉它就等于把钟停住 </summary>
