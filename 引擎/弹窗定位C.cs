using System;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 弹窗(智能补全的候选框等)该落在哪儿 —— **纯计算,不碰界面**,自检直接喂数。
    ///
    /// 为什么单独拿出来(第144批,用户实测报的 bug):候选框原来只算"光标下面一行再往下 4 像素",
    /// 没有任何"下面放不下"的处置。光标越靠近编辑器底边,算出来的落点就越把整个框推到编辑器**外面**;
    /// WPF 的弹窗一旦越出屏幕底边,就按它的"贴边"规则把整个框重新对齐到**屏幕底边** ——
    /// 界面表现就是"补全框跑到 Windows 任务栏上、底边贴着屏幕底边"(用户原话)。
    ///
    /// 现在的口径:优先放到**光标下面**(与 VS 一致);下面放不下就翻到**光标上面**;
    /// 上下都放不下(框比编辑区还高)才贴着编辑区底边、宁可盖住几行代码 —— 总之**绝不出编辑区**。
    /// </summary>
    public static class 弹窗定位C
    {
        /// <summary> 光标与弹窗之间留的缝(像素) </summary>
        public const double 间距 = 4;

        /// <summary>
        /// 算落点。所有坐标都是**相对容器(编辑器)左上角**的像素。
        /// </summary>
        /// <param name="光标X">光标左边缘在容器里的横坐标</param>
        /// <param name="光标Y">光标所在行的上边缘在容器里的纵坐标</param>
        /// <param name="行高">光标那一行的高度(算"下一行"用)</param>
        /// <param name="弹窗宽">弹窗量出来的宽</param>
        /// <param name="弹窗高">弹窗量出来的高</param>
        /// <param name="容器宽">容器(编辑器可视区)的宽</param>
        /// <param name="容器高">容器(编辑器可视区)的高</param>
        public static (double X, double Y) 算(
            double 光标X, double 光标Y, double 行高,
            double 弹窗宽, double 弹窗高, double 容器宽, double 容器高)
        {
            double 下 = 光标Y + 行高 + 间距;
            double y;
            if (下 + 弹窗高 <= 容器高) y = 下;                 // ① 下面放得下:就在光标下面
            else if (光标Y - 弹窗高 - 间距 >= 0) y = 光标Y - 弹窗高 - 间距;   // ② 下面放不下、上面放得下:翻到光标上面
            else y = 容器高 - 弹窗高;                          // ③ 上下都放不下(框比编辑区还高):贴底

            // 兜底再夹一次:上面三条都建立在"光标在可视区里"这个前提上,而滚动/换行的一瞬间光标可能在区外 ——
            // 落点无论如何都不许出容器(出了容器就可能被 WPF 的屏幕贴边规则甩到任务栏去)。
            y = Math.Clamp(y, 0, Math.Max(0, 容器高 - 弹窗高));

            double x = 光标X;
            if (x + 弹窗宽 > 容器宽) x = 容器宽 - 弹窗宽 - 间距;   // 右边放不下就往左收
            x = Math.Clamp(x, 0, Math.Max(0, 容器宽 - 弹窗宽));
            return (x, y);
        }
    }
}
