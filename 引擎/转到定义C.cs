using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary> 导航到的一个**去处**:哪个文件、第几行,外加一句给人看的说明(行号 0 = 行号不可考,说明里会写为什么)。 </summary>
    public sealed class 去处C
    {
        /// <summary> 文件(工程文件表口径的名字;可能是空串 = 当前文件) </summary>
        public string 文件 = "";

        /// <summary> 行号(1 基;0 = 行号不可考,见 说明) </summary>
        public int 行;

        /// <summary> 一句说明(为什么跳这儿 / 是谁调用的 / 是不是库行)</summary>
        public string 说明 = "";

        public override string ToString()
        {
            string 名 = 文件.Length > 0 ? Path.GetFileName(文件) : "(当前文件)";
            if (行 > 0) return $"{名}:{行}" + (说明.Length > 0 ? $"  {说明}" : "");
            return 说明.Length > 0 ? $"{名}  {说明}" : 名;
        }
    }

    /// <summary>
    /// "转到定义 / 查找引用"算出来的东西:**定义处 + 引用处 + 类别 + 一句人话说明**。
    /// 关键口径:**认不出来也要说话** —— 内建函数 / 宿主能力 / 汇编指令 / 结构 / 未定义 / 还没编译过,
    /// 各有各的说明(不是静默没反应),见 `转到定义C` 的类注释。
    /// </summary>
    public sealed class 导航结果C
    {
        /// <summary> 定义处(null = 这一类名字没有源码定义可跳,原因写在 说明 里)</summary>
        public 去处C? 定义;

        /// <summary> 引用处(调用点 / 同名文字;按 文件 → 行 排好)</summary>
        public List<去处C> 引用 { get; } = [];

        /// <summary> 认出来的类别:用户函数 / 变量 / 结构 / 内建函数 / 宿主能力 / 汇编指令 / 语句 / 类型 / 未定义 / 还没有编译 / 没有词 </summary>
        public string 类别 = "未定义";

        /// <summary> 一句人话(给输出框 / 弹框用)</summary>
        public string 说明 = "";

        public bool 有定义 => 定义 != null;
        public int 引用数 => 引用.Count;

        public override string ToString() =>
            (定义 != null ? $"定义 {定义}" : $"没有可跳的定义({类别})") + (引用.Count > 0 ? $";引用 {引用.Count} 处" : "");
    }

    /// <summary>
    /// **转到定义 / 查找引用计算器**(P22,语义版):给"光标下的词 + 当前文件 + 一次编译的名字表 + 调用关系表
    /// (+ 可选源码文件表)",算出该跳到哪儿、还有谁用到它。只算不写:不写盘、不碰编辑器、不改编译器状态。
    ///
    /// 判据(与 `重命名C` 的"尾名相等"同一口径 —— 模块里裸写的 `求和` 也要能对上 `数学.求和`):
    ///   ① **用户函数**:`名字表C.函数范围` 里**尾名相等**的条目(多个同名时优先**同一个文件**那个)。
    ///      定义行 = 那个函数的定义行;引用 = `调用关系表C.谁调用了(定义名)` 的调用点。
    ///   ② **变量**:`名字表C.变量` 里名字相等(或尾名相等)的条目(同样优先同一个文件)。
    ///      变量没有"调用边",引用按**文本**找(整词),说明里写明这是文本口径。
    ///   ③ **结构**:`名字表C.结构` 里有这个名字 → 没有单一"定义行"可跳(字段表在调试面板),
    ///      说明里写清 + 按文本给出用到它的地方。
    ///   ④ **内建函数 / 宿主能力 / 汇编指令 / 语句 / 类型**(`补全词表C.查种类` 认得出来的):
    ///      由引擎或编辑器实现,**没有源码定义**,说明里点名是哪一类。
    ///   ⑤ **没有编译结果**(名字表与调用关系表都没给):说明"先编译一次才能按语义跳";
    ///      **没有源码文件表**:说明"没有源码可查文本"。
    ///   ⑥ 其余 = **未定义**:按文本找同名文字当线索(可能是敲错了,或者来自没 包含 进来的库)。
    ///
    /// 注意:一次编译只给"这一个文件 + 它包含的东西"的调试信息时,跨文件跳转自然只在这些文件里成立;
    /// 工程级编译(`-p` / IDE 打开工程)时 `函数范围` 的每一项都带**自己的文件**,所以跨文件跳转是真的跨文件。
    /// </summary>
    public static class 转到定义C
    {
        private const int 文本线索上限 = 200;

        /// <summary> 算一次导航结果(见类注释的六条判据) </summary>
        public static 导航结果C 计算(string? 词原, string? 光标文件, 名字表C? 名字表, 调用关系表C? 调用表,
            IReadOnlyList<(string 名称, string 内容)>? 文件表 = null, string? 光标函数 = null)
        {
            var 结果 = new 导航结果C();
            string 词 = (词原 ?? "").Trim();

            if (词.Length == 0)
            {
                结果.类别 = "没有词";
                结果.说明 = "光标下面没有名字 —— 把光标放进函数名 / 变量名里(别停在空白或标点上),再试一次。";
                return 结果;
            }

            // ④ 不是用户起的名字:内建 / 宿主 / 汇编指令 / 语句 / 类型
            //    (那一句人话与 H60-9 的 `声明线C` **共用一份口径**:`补全词表C.没有源码定义说明`)
            if (补全词表C.查种类(词) is { } 种类)
            {
                结果.类别 = 种类;
                结果.说明 = 补全词表C.没有源码定义说明(词, 种类);
                return 结果;
            }

            if (名字表 != null)
            {
                // ① 用户函数(尾名相等;多个同名优先同一个文件)
                var 函数们 = new List<(string 函数, int 起, int 止, string 文件)>();
                foreach (var 条 in 名字表.函数范围)
                    if (名相符(条.函数, 词)) 函数们.Add(条);
                if (函数们.Count > 0)
                {
                    结果.类别 = "用户函数";
                    var 取 = 挑一个(函数们, 光标文件);
                    结果.定义 = new 去处C
                    {
                        文件 = 取.文件.Length > 0 ? 取.文件 : (光标文件 ?? ""),
                        行 = 取.起,
                        说明 = $"方法 `{取.函数}` 的定义({取.起}~{取.止})",
                    };
                    if (函数们.Count > 1)
                        结果.说明 = $"工程里有 {函数们.Count} 个尾名一样的函数:" +
                            string.Join(" / ", 函数们.Select(x => x.函数)) + $" —— 这里跳的是 `{取.函数}`(同文件的优先)。";
                    收调用引用(结果, 调用表, 取.函数);
                    if (结果.引用.Count == 0)
                    {
                        if (调用表 == null)
                            结果.说明 += "还没有可用的调用关系(先编译一次),所以只给了定义处。";
                        else
                            结果.说明 += "没有找到调用它的地方(可能是别处递归调用自己,或者它还没被用到)。";
                    }
                    return 结果;
                }

                // ② 变量
                var 变量们 = new List<名字项C>();
                foreach (var 项 in 名字表.变量)
                    if (名相符(项.名字, 词)) 变量们.Add(项);
                if (变量们.Count > 0)
                {
                    结果.类别 = "变量";
                    var 取 = 挑一个变量(变量们, 光标文件);
                    结果.定义 = new 去处C
                    {
                        文件 = 取.声明文件.Length > 0 ? 取.声明文件 : (光标文件 ?? ""),
                        行 = 取.声明行,
                        说明 = $"变量 `{取.名字}`({名字表C.显示类型名(取.类型名)};{(取.是全局 ? "全局" : "局部/参数")}" +
                            (取.所属函数.Length > 0 ? $",属于 {取.所属函数}" : "") + ")",
                    };
                    if (变量们.Count > 1)
                        结果.说明 = $"有 {变量们.Count} 个同名的变量/参数(不同函数里的局部同名很常见)—— 这里跳的是" +
                            (取.是全局 ? "全局那一个" : $"`{取.所属函数}` 里那一个") + "。";
                    结果.说明 += 找文本引用(结果, 文件表, 取.名字, "变量没有调用边,引用是按**文本**找的(整词)");
                    return 结果;
                }

                // ③ 结构(没有单一声明行)
                if (名字表.结构.ContainsKey(词))
                {
                    结果.类别 = "结构";
                    结果.说明 = $"`{词}` 是一个**结构** —— 结构没有单独的声明行可跳(它的字段表在调试面板的『结构』里);" +
                        找文本引用(结果, 文件表, 词, "下面按**文本**列出用到它的地方");
                    return 结果;
                }
            }

            // ⑤ 没有编译结果 / 没有源码
            if (名字表 == null && 调用表 == null)
            {
                结果.类别 = "还没有编译";
                结果.说明 = "还没有可用的编译结果 —— **先编译一次**(运行菜单 → 编译,或按 F5),才能按语义跳到定义。" +
                    找文本引用(结果, 文件表, 词, "现在先按**文本**给你几处同名的地方当线索");
                return 结果;
            }
            if (文件表 == null)
            {
                结果.类别 = "未定义";
                结果.说明 = $"`{词}` 在名字表里找不到,也没有源码可以查文本 —— 可能是敲错了,或者它来自**没 包含 进来**的库文件。";
                return 结果;
            }

            // ⑥ 未定义(有名字表也有源码:给文本线索)
            结果.类别 = "未定义";
            string 线索 = 找文本引用(结果, 文件表, 词, "它没有定义,下面只是**文本**上的同名处");
            结果.说明 = 结果.引用.Count > 0
                ? $"`{词}` 在名字表里**没有定义** —— " + 线索 + "(可能是注释/字符串里的字,或者来自没 包含 进来的库)。"
                : $"`{词}` 在工程里一个都没找到 —— 大概是敲错了。";
            return 结果;
        }

        /// <summary> 便捷重载:直接吃一次编译的 `汇编调试结果C`(内部现算调用关系表;不改这份结果) </summary>
        public static 导航结果C 计算(string? 词, string? 光标文件, 汇编调试结果C? 编译结果,
            IReadOnlyList<(string 名称, string 内容)>? 文件表 = null)
            => 计算(词, 光标文件, 编译结果?.名字表, 编译结果 == null ? null : 调用关系扫描C.扫描(编译结果), 文件表);

        // ---------------- 内部实现 ----------------

        /// <summary> 尾名相等就算(模块里裸写的 `求和` 能对上 `数学.求和`;完全相等当然也算)</summary>
        private static bool 名相符(string 定义名, string 词)
            => string.Equals(定义名, 词, StringComparison.OrdinalIgnoreCase)
               || string.Equals(尾段(定义名), 词, StringComparison.OrdinalIgnoreCase);

        private static string 尾段(string 名)
        {
            int 点 = 名.LastIndexOf('.');
            return 点 < 0 ? 名 : 名[(点 + 1)..];
        }

        /// <summary> 多个同名:优先**同一个文件**那一个;都没有就取第一个(函数范围/变量表的顺序是稳定的)</summary>
        private static (string 函数, int 起, int 止, string 文件) 挑一个(
            List<(string 函数, int 起, int 止, string 文件)> 们, string? 光标文件)
        {
            foreach (var 条 in 们) if (文件判定C.同文件(条.文件, 光标文件)) return 条;
            return 们[0];
        }

        private static 名字项C 挑一个变量(List<名字项C> 们, string? 光标文件)
        {
            foreach (var 项 in 们) if (文件判定C.同文件(项.声明文件, 光标文件)) return 项;
            return 们[0];
        }

        /// <summary> 引用 = 调用边表里"谁调用了这个定义名"的调用点(按 文件 → 行 排好)</summary>
        private static void 收调用引用(导航结果C 结果, 调用关系表C? 调用表, string 定义名)
        {
            if (调用表 == null) return;
            foreach (var 边 in 调用表.谁调用了(定义名))
                结果.引用.Add(new 去处C
                {
                    文件 = 边.调用点文件,
                    行 = 边.调用点行,
                    说明 = $"被 {边.调用者显示} 调用" + (边.调用点行 == 0 ? "(包含进来的文件,行号不可考)" : ""),
                });
            排好(结果);
        }

        /// <summary> 按文本找回引用(整词;注释与字符串里的也算,说明里会写明这是文本口径);返回一句说明(可能是空串)</summary>
        private static string 找文本引用(导航结果C 结果, IReadOnlyList<(string 名称, string 内容)>? 文件表,
            string 词, string? 开头)
        {
            if (文件表 == null || 文件表.Count == 0) return "没给源码,连文本线索也查不了";
            var 设置 = new 查找设置C { 整词 = true, 保护注释与字符串 = false };   // 线索:连注释/字符串里的也算,免得漏
            int 共 = 0;
            foreach (var (名称, 内容) in 文件表)
                foreach (var 处 in 查找替换C.查找(内容, 词, 设置))
                {
                    if (结果.引用.Count >= 文本线索上限) break;
                    结果.引用.Add(new 去处C { 文件 = 名称, 行 = 处.行号, 说明 = "文本命中(整词)" });
                    共++;
                }
            排好(结果);
            if (共 == 0) return "文本上一个同名也没找到";
            return (开头 != null ? 开头 + ":" : "") + $"共 {共} 处" + (共 >= 文本线索上限 ? "(只列前 " + 文本线索上限 + " 处)" : "");
        }

        private static void 排好(导航结果C 结果) => 结果.引用.Sort((a, b) =>
        {
            int 比 = string.CompareOrdinal(a.文件, b.文件);
            if (比 != 0) return 比;
            比 = a.行.CompareTo(b.行);
            return 比 != 0 ? 比 : string.CompareOrdinal(a.说明, b.说明);
        });
    }
}
