using System;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// C28:把代码片段插进"某份文档的某个位置"到底要**删什么、插什么** —— 纯函数(自检直接喂文本,不开窗口)。
    ///
    /// 为什么要抽出来:菜单『编辑 → 插入代码片段』与**智能补全里选中那条片段候选**必须插出**同一份**文本
    /// (用户验收原话:"插入结果与走菜单插入逐字节相同")。以前缩进 + 展开这套算在界面 `编辑器.插入片段` 里,
    /// 自检够不着;现在收进引擎,两条路都调这一个入口,验收就能直接比字符串。
    ///
    /// 两件事在这里定死:
    ///   · **缩进** —— 光标前那一段是本行前导空白时按"当前层级"算(`代码排版C.回车后的缩进`),
    ///     否则跟着这一行的前导空白(与界面上一直以来的口径一致);
    ///   · **缩写** —— 补全那条路是先打了两三个字母再选候选的,那几个字母要**先删掉**;
    ///     缩进按"删掉之后"的文本算,所以 `算插入(含缩写的文档, …)` 与
    ///     `算插入(把缩写删掉的文档, …)` 结果**逐字节相同**(自检钉的就是这一条)。
    /// </summary>
    public static class 片段插入C
    {
        /// <summary>
        /// 算好的插入动作:`起点` 起删掉 `删除长度` 个字,插入 `文本`;
        /// `光标` 是**改完之后文档里**光标该落的位置(= 起点 + `文本` 里那一位)——
        /// 要跟 `文本` 里的下标比,先减掉 `起点`。
        /// </summary>
        public readonly record struct 动作C(int 起点, int 删除长度, string 文本, int 光标);

        /// <summary>
        /// 算一次片段插入。`位置` = 光标(0 基,超出文档长度按文档末尾算);
        /// `缩写长度` = 光标前那个词有几个字符(菜单那条路传 0,补全那条路传打进去的那几个字母有几个)。
        /// </summary>
        public static 动作C 算插入(string? 文档文本, int 位置, int 缩写长度, 片段项C? 项, 排版设置C? 设置 = null)
        {
            string 全文 = 文档文本 ?? "";
            位置 = Math.Clamp(位置, 0, 全文.Length);
            缩写长度 = 缩写长度 > 0 ? Math.Min(缩写长度, 位置) : 0;
            int 起点 = 位置 - 缩写长度;
            if (项 == null) return new 动作C(起点, 缩写长度, "", 起点);

            // 缩进按"缩写已经删掉"的那份文本算 —— 这样菜单那条路(本来就传 0)
            // 与补全那条路(先删缩写)算出来一模一样,不会因为"光标这一行还剩几个字母"而差一档。
            string 去缩写 = 缩写长度 > 0 ? 全文.Remove(起点, 缩写长度) : 全文;
            string 缩进 = 算缩进(去缩写, 起点, 设置);
            string 文本 = 片段表C.展开(项, 缩进, out int 光标偏移);
            string 换行 = 取换行(去缩写);
            if (换行 != "\n") 文本 = 文本.Replace("\n", 换行);
            return new 动作C(起点, 缩写长度, 文本, 起点 + 光标偏移);
        }

        /// <summary>
        /// `位置` 之前那一段定出来的缩进:这一行(光标前)只有空白 → 按**当前层级**算
        /// (`代码排版C.回车后的缩进`);有内容 → 跟着这一行的前导空白。
        /// </summary>
        public static string 算缩进(string? 文档文本, int 位置, 排版设置C? 设置 = null)
        {
            string 全文 = 文档文本 ?? "";
            位置 = Math.Clamp(位置, 0, 全文.Length);
            int 行首 = 0;
            if (位置 > 0)
            {
                int 换行位 = 全文.LastIndexOf('\n', 位置 - 1);
                行首 = 换行位 < 0 ? 0 : 换行位 + 1;
            }
            string 行内 = 全文[行首..位置];
            if (行内.Trim().Length > 0)
                return 行内[..(行内.Length - 行内.TrimStart(' ', '\t').Length)];

            int 行号 = 1;
            for (int i = 0; i < 行首; i++) if (全文[i] == '\n') 行号++;
            return 代码排版C.回车后的缩进(全文, 行号, 设置);
        }

        /// <summary>
        /// 这份文档用哪种换行(看开头一段就够;没有换行就用 `\n`)——
        /// 与界面 `编辑器.取文档换行` 同一份口径(CRLF 的文档里插 CRLF,免得插一段就多出一片混行尾)。
        /// </summary>
        public static string 取换行(string? 文档文本)
        {
            string 全文 = 文档文本 ?? "";
            string 头 = 全文.Length <= 4000 ? 全文 : 全文[..4000];
            return 头.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        }
    }
}
