        #region 生成整份表(纯函数:给一段文档全文 + 一个"文件在不在"的探针,产出整份文本)
        /// <summary>
        /// 生成整份真值源文本(**纯函数**,不碰盘 —— 自检要能拿它跟盘上那份逐字节比)。
        /// </summary>
        /// <param name="文档全文">`指令集说明.md` 的全文;null = 读不到(表里如实写"读不到",不静默编造)。</param>
        /// <param name="文件存在">相对仓库根的路径 → 在不在(自检真查盘,命令行那条路也真查)。</param>
        public static string 生成(string? 文档全文, Func<string, bool> 文件存在)
        {
            var 表 = 指令C.全部指令;
            var 语义 = new Dictionary<byte, string>();
            if (文档全文 != null)
                foreach (string 行 in 读文档语义行(文档全文))
                {
                    var 格 = 拆文档表行(行);
                    if (格 == null) continue;
                    if (格[0].StartsWith("0x", StringComparison.OrdinalIgnoreCase)
                        && byte.TryParse(格[0][2..], System.Globalization.NumberStyles.HexNumber, null, out byte 码))
                        语义[码] = 格[4];
                }

            var 文 = new StringBuilder();
            文.Append("# HB 指令集真值源(R3-6-1)——ISA 的**机器可读**冻结表\n");
            文.Append("#\n");
            文.Append("# 这份文件是**生成**出来的,别手改:跑 `hbcc --更新指令集` 重写它。\n");
            文.Append("# 生成器 = 引擎\\指令集真值源C.cs;自检每次运行都重新生成一遍与盘上这份逐字节比。\n");
            文.Append("# 为什么要有它:换核(C 解释器 / 转译器,R3-6-2)要先有一个**与 C# 无关**的真值源。\n");
            文.Append("#\n");
            文.Append("# 格式:`#` 开头是注释、空行忽略、一条记录一行、列之间**一个 TAB**、非注释行不许有尾随空白。\n");
            文.Append($"# 表格行数与上面各段声明的条数必须一致;这份文件**逐字节可复现**(不带时间戳)。\n");
            文.Append($"#\n# 条数:指令 {表.Count} 条(操作码 0x{表.Min(x => x.操作码):X2}~0x{表.Max(x => x.操作码):X2})" +
                      $" / 编码格式 {Enum.GetValues<指令格式>().Length} 种 / 关系码 {指令C.关系码表.Count} 条" +
                      $" / 语义说明 {语义.Count} 条" +
                      (文档全文 == null ? "(读不到 指令集说明.md,语义那一段为空)" : "") + "\n");
            文.Append("#\n");

            // ---- 段一:编码格式 ----
            文.Append("# ==== 编码格式(每条指令固定 4 字节;操作码在最高字节,即机器码的 地址+3 那个字节)====\n");
            文.Append("# 列:格式名\t操作数写法\t位布局\n");
            foreach (var 格 in Enum.GetValues<指令格式>())
                文.Append($"格式\t{格}\t{指令C.操作数写法(格)}\t{指令C.格式位布局(格)}\n");

            // ---- 段二:操作码表 ----
            文.Append($"\n# ==== 操作码表({指令C.全部指令.Count} 条;「带跳转目标」那一列是真的要落成跳转地址的那些,自检按 指令C.带跳转目标 逐条复算)====\n");
            文.Append("# 列:指令\t操作码\t中文\t英文\t格式\t操作数写法\t带跳转目标\t写法示例\n");
            foreach (var (中文, 英文, 码, 格) in 表.OrderBy(x => x.操作码))
                文.Append($"指令\t0x{码:X2}\t{中文}\t{英文}\t{格}\t{指令C.操作数写法(格)}\t" +
                          $"{(指令C.带跳转目标(码) ? "是" : "否")}\t{指令C.取示例(英文) ?? "—"}\n");

            // ---- 段三:关系码(比较取值 的第 4 个操作数) ----
            文.Append("\n# ==== 关系码(只有 `比较取值` 用;低 3 位是关系,第 3 位 8 = 按有符号比)====\n");
            文.Append("# 列:关系码\t记号\t数值\t带符号版本\t说明\n");
            foreach (var (记号, 值) in 指令C.关系码表.OrderBy(x => x.Value))
                文.Append($"关系码\t{记号}\t{值}\t{值 | 8}\t{指令C.关系码说明(值)}\n");

            // ---- 段四:语义说明 + 语义落点 ----
            文.Append("\n# ==== 语义说明(逐条搬运 指令集说明.md §3 操作码表 —— 文档是 ISA 语义的唯一事实源)====\n");
            文.Append("# 列:语义\t操作码\t中文\t说明\t语义落点\n");
            文.Append("# 「语义落点」= 这条指令照哪一份实现抄(给 R3-6-2 当施工路线);`@` 后面是那个文件里的定位。\n");
            foreach (var (中文, 英文, 码, _) in 表.OrderBy(x => x.操作码))
                文.Append($"语义\t0x{码:X2}\t{中文}\t{(语义.TryGetValue(码, out string? 说) ? 说 : "—")}\t" +
                          $"{取语义落点(码) ?? "—"}\n");

            // ---- 段五:落点文件清单(自检逐条查"在不在") ----
            var 落点 = 表.Select(x => 取语义落点(x.操作码)).Where(x => !string.IsNullOrEmpty(x))
                          .Select(x => x!.Split('@')[0]).Distinct(StringComparer.Ordinal).OrderBy(x => x, StringComparer.Ordinal).ToArray();
            文.Append("\n# ==== 语义落点涉及的文件(自检逐条查它在不在仓库里;`@` 后面是定位,不单独校)====\n");
            文.Append("# 列:落点文件\t在不在\n");
            foreach (string f in 落点)
                文.Append($"落点文件\t{f}\t{(文件存在(f) ? "在" : "不在")}\n");

            // 这份文件**逐字节可复现**:不带时间戳、不带生成机器信息 —— 同一份指令表 + 同一份文档,
            // 生成出来的字节一个不差(自检拿"重新生成逐字节相同"当判据,与帮助站点同一口径)。
            // 想知道这份是什么时候生的,看文件的修改时间,别在正文里塞会漂的东西。
            return 文.ToString();
        }
