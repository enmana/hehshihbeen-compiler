        #region 文档里那段操作码表 → 语义说明(搬运,不重写)
        /// <summary>
        /// `指令集说明.md §3 操作码表` 的**表体行**(跳过大标题那两行与表头分隔行):
        /// 列 = `操作码 | 中文指令 | 英文指令 | 格式 | 说明`。
        /// 返回空数组 = 那段表没找到 / 行不像表(自检据此报"文档里那段操作码表找不到",而不是静默给空表)。
        /// </summary>
        public static string[] 读文档语义行(string 文档全文)
        {
            var 行们 = 文档全文.Replace("\r\n", "\n").Split('\n');
            int 起 = Array.FindIndex(行们, x => x.Trim() == 语义文档节标题);
            if (起 < 0) return [];
            var 收 = new List<string>();
            bool 见表头 = false;
            for (int i = 起 + 1; i < 行们.Length; i++)
            {
                string 行 = 行们[i].Trim();
                if (行.Length == 0) { if (见表头) break; else continue; }        // 表后第一段空行 = 表结束
                if (!行.StartsWith('|')) { if (见表头) break; else continue; }
                if (行.StartsWith("|---") || 行.StartsWith("| ---")) continue;    // 分隔行
                if (!见表头)
                {
                    // 表头行:`| 操作码 | 中文指令 | … |` —— 认它才算进了表体(免得把上面别的表吃进来)
                    见表头 = 行.Contains("操作码") && 行.Contains("中文指令");
                    continue;
                }
                收.Add(行);
            }
            return [.. 收];
        }

        /// <summary>
        /// 把一行文档表体拆成五格(去掉首尾 `|`、每格去空白);格数不是 5 返回 null。
        /// **转义处理**:文档里 `\|` 是"表里真的写一个竖线"(如 `或` 那条的 `Rdest = Rdest \| Rsrc`),
        /// 拆格时先按 `\|` 占位再拆,最后还原 —— 不这么办,那一行的"说明"会被拆成两格。
        /// </summary>
        public static string[]? 拆文档表行(string 行)
        {
            const string 占位 = "\u0001";
            string 整 = 行.Replace("\\|", 占位).Trim();
            if (整.StartsWith('|')) 整 = 整[1..];
            if (整.EndsWith('|')) 整 = 整[..^1];
            var 格 = 整.Split('|').Select(x => x.Replace(占位, "|").Trim()).ToArray();
            return 格.Length == 5 ? 格 : null;
        }
