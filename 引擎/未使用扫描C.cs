using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// "这个函数没人调用"的归类。**只是给人看的旁路分类**:不参与汇编、不影响机器码,
    /// 也不会被编译器读回去(和 `调用关系扫描C` 同一档)。
    /// </summary>
    public enum 未使用归类C
    {
        /// <summary> 调用边表里**一条入边都没有**:整个工程(含顶层程序段与 `测试` 块)都没调用它 </summary>
        完全没人调,

        /// <summary> 有入边,但**全部来自它自己**(自己递归自己)—— 外面没有任何地方调用它 </summary>
        递归孤岛,

        /// <summary> 没人调用(或只自己调),但看起来是**给别人用的**。措辞要克制:只提醒,不建议删 </summary>
        对外接口,
    }

    /// <summary>
    /// 一个"没人调用"的函数:定义名 + 声明在哪个文件、哪几行 + 为什么算没人调用。
    /// 行号是**该文件自己的行号**(1 基),与调试信息里的口径一致。
    /// </summary>
    public sealed class 未使用项C
    {
        /// <summary> 函数定义名(模块/容器成员带点:`数学.求和`) </summary>
        public string 函数 = "";

        /// <summary> 声明所在的源文件(工程文件表里的那个名字) </summary>
        public string 声明文件 = "";

        /// <summary> 声明首行(1 基;`函数` 那一行) </summary>
        public int 起行 = 1;

        /// <summary> 声明止行(1 基;函数体最后一个 `}` 那一行) </summary>
        public int 止行;

        /// <summary> 归在哪一栏 </summary>
        public 未使用归类C 归类;

        /// <summary> 为什么算"没人用"(判据 + 建议改法,一句话说清) </summary>
        public string 为什么 = "";

        /// <summary> 汇编里的标签(`数学.求和` → `数学_求和`) </summary>
        public string 标签 => 函数.Replace('.', '_');

        /// <summary> 名字带模块/容器前缀(`模块.名` 或 `容器.方法`) </summary>
        public bool 带模块前缀 => 函数.Contains('.');

        /// <summary> 只留文件名,给人看 </summary>
        public string 文件名 => 声明文件.Length > 0 ? Path.GetFileName(声明文件) : "(未知文件)";

        /// <summary> 归类给人看的样子 </summary>
        public string 归类名 => 归类 switch
        {
            未使用归类C.完全没人调 => "完全没人调",
            未使用归类C.递归孤岛 => "递归孤岛(只被自己调用)",
            _ => "对外接口(可能是给别人用的)",
        };

        /// <summary> `文件:起-止` </summary>
        public string 位置显示 => $"{文件名}:{起行}-{止行}";

        /// <summary> 给自检/面板用的一行文本 </summary>
        public override string ToString() => $"{函数} @{位置显示} [{归类名}] {为什么}";
    }

    /// <summary>
    /// 一次"未使用函数"扫描的结果。三栏**互不重叠**(一个函数只出现在一栏里):
    /// `完全没人调` / `递归孤岛` / `对外接口`;想看合计用 `全部`。
    /// 每栏内部按"文件 → 起行 → 函数名"排好序,**顺序确定**(自检与显示都靠它)。
    /// </summary>
    public sealed class 未使用报告C
    {
        /// <summary> 完全没人调的函数(调用边表里连入边都没有) </summary>
        public List<未使用项C> 完全没人调 { get; } = [];

        /// <summary> 递归孤岛:只有它自己在调自己 </summary>
        public List<未使用项C> 递归孤岛 { get; } = [];

        /// <summary> 看起来是给别人用的(模块前缀 / 写了 `程序集` …):**只提醒,不建议删** </summary>
        public List<未使用项C> 对外接口 { get; } = [];

        /// <summary> 三栏合起来(顺序同各栏:文件 → 起行 → 函数名) </summary>
        public IReadOnlyList<未使用项C> 全部 =>
            [.. 完全没人调, .. 递归孤岛, .. 对外接口];

        /// <summary> 一共扫出几个没人调用的函数 </summary>
        public int 条数 => 完全没人调.Count + 递归孤岛.Count + 对外接口.Count;

        /// <summary> 一个都没扫出来 </summary>
        public bool 空 => 条数 == 0;

        /// <summary> 按定义名找一个(不在报告里返回 null) </summary>
        public 未使用项C? 找(string 定义名)
        {
            foreach (var 项 in 全部)
                if (string.Equals(项.函数, 定义名, StringComparison.OrdinalIgnoreCase)) return 项;
            return null;
        }

        /// <summary> 收一项(只给本文件的扫描器用) </summary>
        internal void 收(未使用项C 项)
        {
            switch (项.归类)
            {
                case 未使用归类C.递归孤岛: 递归孤岛.Add(项); break;
                case 未使用归类C.对外接口: 对外接口.Add(项); break;
                default: 完全没人调.Add(项); break;
            }
        }
    }

    /// <summary>
    /// **未使用函数扫描器**:从"函数范围"(工程级 `名字表C`)与"调用边表"(`调用关系表C`,Q3 那件)
    /// 算出**没人调用的函数**,并把"对外接口"单独分一栏。
    ///
    /// **纯函数**:只读入参、只出报告,不改编译器状态、不写盘、不碰编辑器;给同样的输入必给同样的报告
    /// (`字段顺序 → 排序` 全部定死)。
    ///
    /// 判据(只看调用边表的**入边**,不重算一遍调用关系):
    ///   · 一个函数"被用过" = 入边表里**存在一条不是它自己发的**入边。顶层程序段与 `测试` 块的调用
    ///     记在空串键(`调用者 == ""`)上,所以它们调的函数**算被用过**(`测试` 块写在函数外面)。
    ///   · 入边**一条都没有** → `完全没人调`。
    ///   · 入边**全部来自它自己**(自己递归自己)→ `递归孤岛`,单独一栏,不和"完全没人调"混。
    ///   · 上面两种里,凡是**看起来给别人用**的 → 改归 `对外接口`,提示措辞克制。
    ///
    /// "看起来是给别人用的"三条证据(任一条成立;写了 `私有`/`private` 则**一票否决** —— 它明确是模块内部的):
    ///   ① 声明前面写了 `程序集`(英文 `internal`)—— 同工程可用,很可能就是给别的文件调的;
    ///   ② 名字带模块/容器前缀(`数学.求和`、`棋盘.面积`)—— 命名上就是留给外面用的;
    ///   ③ 声明前面写了 `公共`/`public`(H2 起这个前缀**真能写**了 —— 与"不写"同义,
    ///      写出来就是明说"这是留给外面用的"),或者调用方打开了 `无前缀也算对外接口` 开关。
    ///
    /// **默认口径与取舍(说清楚,免得猜)**:
    ///   · HB 里"不写可见性前缀"就是 `公共`,可**编译调试信息里没有导出清单**。若把默认公共一律算对外接口,
    ///     普通工程里任何一个没人调的函数都会被归进"对外接口",未使用检测就等于永不报警 ——
    ///     与这件交付物的目的冲突。所以 `无前缀也算对外接口` **默认关**:只认**明确写出来的** `程序集`
    ///     与**名字带前缀**的;没写前缀的照实报"没人调用"(措辞克制:说"没人调用",不说"删掉")。
    ///   · 要给"库作者"口径(默认公共也算对外)时,调用方把这个开关打开即可 —— 两种口径都有自检钉住。
    ///   · 没给源码(只给 `名字表C` + `调用关系表C`)时看不到声明行:**带前缀的名字仍算对外接口**,
    ///     不带前缀的按普通函数报。也就是说,`私有` 的模块函数在这种输入下会被保守地当成对外接口
    ///     (宁可少报死代码,也不劝人删库的对外函数)。要判准就把工程源码(文件表)一起传进来。
    ///
    /// **边界(如实记下)**:
    ///   · 只按"有没有直接的调用边"判,**不做可达性传播** —— 只在另一个没人调用的函数里被调用的函数,
    ///     这里**不会**报(它确实有入边)。要"整片死代码"得另做可达性分析,本件不做。
    ///   · 只认 `调用关系表C` 认得出来的直接调用(HB 没有函数指针/间接调用);内联汇编里手写的 `CALL 标签`
    ///     若真发出机器码,`调用关系扫描C` 也能扫到,不受影响。
    /// </summary>
    public static class 未使用扫描C
    {
        /// <summary>
        /// 扫一次(推荐口径):`名字表C`(函数范围,可从 `汇编调试结果C.名字表` 来)+ `调用关系表C`。
        /// `文件表` 只用来**看声明行上的可见性前缀**(不给也能扫,只是 `私有` 判不准,见类注释)。
        /// </summary>
        public static 未使用报告C 扫描(名字表C? 名字表, 调用关系表C? 调用关系表,
            IReadOnlyList<(string 名称, string 内容)>? 文件表 = null, bool 无前缀也算对外接口 = false)
            => 扫描(名字表?.函数范围, 调用关系表, 文件表, 无前缀也算对外接口);

        /// <summary>
        /// 便捷重载:直接吃一次编译的 `汇编调试结果C`(内部现算一张调用关系表;不会改这份编译结果)。
        /// </summary>
        public static 未使用报告C 扫描(汇编调试结果C? 编译结果,
            IReadOnlyList<(string 名称, string 内容)>? 文件表 = null, bool 无前缀也算对外接口 = false)
        {
            if (编译结果 == null) return new 未使用报告C();

            // 名字表优先用工程级那份;它没登记函数范围时(老口径/只给调试段)退回逐段收一遍。
            var 范围 = new List<(string 函数, int 起, int 止, string 文件)>();
            if (编译结果.名字表 != null) 范围.AddRange(编译结果.名字表.函数范围);
            if (范围.Count == 0 && 编译结果.调试文件表 != null)
                foreach (var 段 in 编译结果.调试文件表)
                    if (段.名字表 != null) 范围.AddRange(段.名字表.函数范围);
            return 扫描(范围, 调用关系扫描C.扫描(编译结果), 文件表, 无前缀也算对外接口);
        }

        /// <summary> 核心:给一张函数范围表就能扫(自检/别的调用方要手造范围时也走这里) </summary>
        public static 未使用报告C 扫描(IReadOnlyList<(string 函数, int 起, int 止, string 文件)>? 函数范围,
            调用关系表C? 调用关系表, IReadOnlyList<(string 名称, string 内容)>? 文件表 = null,
            bool 无前缀也算对外接口 = false)
        {
            var 报告 = new 未使用报告C();
            if (函数范围 == null || 函数范围.Count == 0) return 报告;

            // 去重(段名字表与工程级名字表可能都登记过同一条)+ **输出顺序定死**:文件 → 起行 → 函数名。
            var 去过重 = new HashSet<string>(StringComparer.Ordinal);
            var 清单 = new List<(string 函数, int 起, int 止, string 文件)>();
            foreach (var (函数, 起, 止, 文件) in 函数范围)
            {
                if (string.IsNullOrWhiteSpace(函数)) continue;
                if (去过重.Add($"{函数}\u0001{文件}\u0001{起}")) 清单.Add((函数, 起, 止, 文件 ?? ""));
            }
            清单.Sort((a, b) =>
            {
                int 比 = string.CompareOrdinal(a.文件, b.文件);
                if (比 != 0) return 比;
                比 = a.起.CompareTo(b.起);
                return 比 != 0 ? 比 : string.CompareOrdinal(a.函数, b.函数);
            });

            foreach (var (函数, 起, 止, 文件) in 清单)
            {
                string 标签 = 函数.Replace('.', '_');
                var 入边 = 取入边(调用关系表, 函数, 标签);
                bool 自己调过 = 入边.Any(e => 是调用者自己(e, 函数, 标签));
                bool 别人调过 = 入边.Any(e => !是调用者自己(e, 函数, 标签));
                if (别人调过) continue;                                  // 有别人调用 = 用过了,不报

                未使用归类C 归类 = 入边.Count == 0 ? 未使用归类C.完全没人调 : 未使用归类C.递归孤岛;
                string? 理由 = 对外理由(函数, 文件, 起, 文件表, 无前缀也算对外接口);
                string 为什么;
                if (理由 != null)
                {
                    归类 = 未使用归类C.对外接口;
                    为什么 = $"当前这一份代码里没人调用它,但它看起来是对外接口({理由})。" +
                             $"给别的文件 / 别的工程用的函数留着是正常的 —— 这里只做提醒,不建议删掉库的对外函数;" +
                             $"要确认就把整个工程(含子工程)一起看一遍。";
                }
                else if (归类 == 未使用归类C.完全没人调)
                {
                    为什么 = "调用边表里一条入边都没有:整个工程(顶层程序段与 `测试` 块都算过)没有任何地方调用它。" +
                             "确认没用就删掉它;只是先留着用不到的实现也可以不管 —— 这条提示不影响编译。";
                }
                else
                {
                    为什么 = "调用了它的边只有它自己发的递归调用(递归孤岛),外面没有任何地方调用它。" +
                             "要么把外面的调用接上,要么删掉它。";
                }

                报告.收(new 未使用项C
                {
                    函数 = 函数,
                    声明文件 = 文件,
                    起行 = 起,
                    止行 = 止,
                    归类 = 归类,
                    为什么 = 为什么,
                });
            }
            return 报告;
        }

        // ---------------- 内部实现 ----------------

        /// <summary>
        /// 取某个函数的全部入边:定义名一份、汇编标签一份(直接写标签调用时按标签进表),按
        /// `调用者/文件/行/被调标签` 去重 —— 名字不带点时两次查的是同一张表,不去重会重复计数。
        /// </summary>
        private static List<调用边C> 取入边(调用关系表C? 表, string 函数, string 标签)
        {
            var 结果 = new List<调用边C>();
            if (表 == null) return 结果;
            var 去过重 = new HashSet<string>(StringComparer.Ordinal);
            foreach (string 键 in 函数 == 标签 ? new[] { 函数 } : new[] { 函数, 标签 })
                foreach (var 边 in 表.谁调用了(键))
                    if (去过重.Add($"{边.调用者}\u0001{边.调用点文件}\u0001{边.调用点行}\u0001{边.被调标签}"))
                        结果.Add(边);
            return 结果;
        }

        /// <summary> 这条边的调用者是不是"这个函数自己"(调用者记的是定义名;标签写法兜底) </summary>
        private static bool 是调用者自己(调用边C 边, string 函数, string 标签)
            => string.Equals(边.调用者, 函数, StringComparison.OrdinalIgnoreCase)
            || string.Equals(边.调用者, 标签, StringComparison.OrdinalIgnoreCase);

        /// <summary>
        /// 这个函数"看起来是给别人用的"吗?返回理由(给人看的一句话)或 null。
        /// 判据见类注释;`私有`/`private` 一票否决(明确写了"只有本模块能用")。
        /// </summary>
        private static string? 对外理由(string 函数, string 文件, int 起行,
            IReadOnlyList<(string 名称, string 内容)>? 文件表, bool 无前缀也算对外接口)
        {
            string 声明行 = 取声明行(文件, 起行, 文件表) ?? "";
            bool 有源码 = 声明行.Length > 0;
            string 首词 = 有源码 ? 代码解析器.取首词(声明行) : "";

            if (首词 is "私有" or "private") return null;                 // 明确模块内部用 → 不是对外接口

            if (首词 is "程序集" or "internal")
                return "声明前面写了 `程序集`(英文 `internal`)—— 同一个 .hbp 工程里可用,很可能就是给别的文件调的";
            if (函数.Contains('.'))
                return $"名字带模块/容器前缀(定义名 `{函数}`)—— 这种命名通常就是留给外面用的";
            if (首词 is "公共" or "public") return "声明前面写了 `公共`";
            if (!有源码)
                return 无前缀也算对外接口
                    ? "没给源码,看不到它的声明行;按『不写就是 公共』的默认算对外"
                    : null;
            return 无前缀也算对外接口 ? "没有写可见性前缀 —— HB 里不写就是 `公共`(谁都能用)" : null;
        }

        /// <summary> 取某文件第 N 行(1 基)去掉行尾注释后的原文;文件对不上/行号越界返回 null </summary>
        private static string? 取声明行(string 文件, int 行号,
            IReadOnlyList<(string 名称, string 内容)>? 文件表)
        {
            if (文件表 == null || 文件表.Count == 0 || 行号 < 1) return null;
            string? 内容 = null;
            foreach (var (名称, 文本) in 文件表)
                if (string.Equals(名称, 文件, StringComparison.OrdinalIgnoreCase)) { 内容 = 文本; break; }
            if (内容 == null)
            {
                string 短名 = Path.GetFileName(文件);
                foreach (var (名称, 文本) in 文件表)
                    if (string.Equals(Path.GetFileName(名称), 短名, StringComparison.OrdinalIgnoreCase)) { 内容 = 文本; break; }
            }
            if (内容 == null) return null;

            string[] 行表 = 内容.Replace("\r\n", "\n").Split('\n');
            if (行号 > 行表.Length) return null;
            string 行 = 代码解析器.去注释(行表[行号 - 1]).Trim();
            return 行.Length > 0 ? 行 : null;
        }
    }

    /// <summary>
    /// **未使用报告 → 编辑器诊断项**的纯映射(给 IDE 的波浪下划线与底部『问题』页用)。
    ///
    /// 这一层单独拆出来的原因:它是这件交付物里**唯一能用自检钉住**的部分 ——
    /// "界面怎么显示"没法自动验证,"哪一条该报成什么级别、写什么话"可以。
    ///
    /// 口径(说清楚,免得猜):
    ///   · `完全没人调` 与 `递归孤岛` → 默认 `警告`(与 `检查器C` 的"声明了没用的变量"同一档:
    ///     都是"大概是死代码,但不影响编译"),文案里带函数名与一句改法。
    ///   · `对外接口` **默认不报**。理由:HB 里带模块前缀的名字一律算对外接口,而模块写法很常用 ——
    ///     全报出来的话,一个正常工程的问题页会被"这可能是给别人用的函数"刷满,反而把真正的死代码淹掉;
    ///     要看这一栏就把 `报对外接口` 打开,那时按 `提示`(最轻的一档)报。
    ///   · 行号一律用报告里的 `起行`(= 声明那一行),起列/止列留 0 = 按整行画线。
    ///   · 文案克制:**不用感叹号**,不说"删掉",只说"可以考虑";改动建议跟着判据走。
    ///
    /// **纯函数**:只读入参、只出列表;`报告` 为 null 或空报告都返回空列表(不炸)。
    /// 输出顺序 = `未使用报告C.全部` 的顺序(完全没人调 → 递归孤岛 → 对外接口,各栏自带确定顺序)。
    /// </summary>
    public static class 未使用诊断C
    {
        /// <summary> 诊断项上的规则名(自检与"关过哪一处"的记忆都按它区分)</summary>
        public const string 规则名 = "未使用函数";

        /// <summary>
        /// 映射一次。`级别` 只管 `完全没人调` 与 `递归孤岛` 两栏;`对外接口` 固定用 `提示`(见类注释)。
        /// </summary>
        public static List<诊断项C> 映射(未使用报告C? 报告, 诊断级别 级别 = 诊断级别.警告,
            bool 报对外接口 = false)
        {
            var 结果 = new List<诊断项C>();
            if (报告 == null) return 结果;
            foreach (var 项 in 报告.完全没人调) 结果.Add(造(项, 级别));
            foreach (var 项 in 报告.递归孤岛) 结果.Add(造(项, 级别));
            if (报对外接口)
                foreach (var 项 in 报告.对外接口) 结果.Add(造(项, 诊断级别.提示));
            return 结果;
        }

        /// <summary> 一条报告项 → 一条诊断项(说人话 + 给改法;函数名一定在文案里)</summary>
        private static 诊断项C 造(未使用项C 项, 诊断级别 级别) => new()
        {
            行 = 项.起行 > 0 ? 项.起行 : 1,
            起列 = 0,
            止列 = 0,
            级别 = 级别,
            规则 = 规则名,
            文件 = 项.声明文件,
            文本 = 文案(项),
        };

        /// <summary>
        /// 三栏各一句话。措辞克制:说"没有被调用"、给两个方向(删掉 / 它本来是给别的工程用的),
        /// 不说"死代码该删";递归孤岛点明"可能是漏了调用点";对外接口明确"留着是正常的"。
        /// </summary>
        private static string 文案(未使用项C 项) => 项.归类 switch
        {
            未使用归类C.递归孤岛 =>
                $"方法 '{项.函数}' 只被它自己调用(递归孤岛,可能是漏了调用点):外面没有任何地方调用它," +
                "要么把外面的调用接上,要么删掉它。",
            未使用归类C.对外接口 =>
                $"方法 '{项.函数}' 在当前这一份代码里没有被调用;它看起来是对外接口({对外理由一句话(项.为什么)})," +
                "给别的文件或别的工程用的函数留着是正常的 —— 这里只做提醒,不建议删掉库的对外函数。",
            _ =>
                $"方法 '{项.函数}' 没有被任何地方调用(可以考虑删掉,或者它本来是给别的工程用的)。",
        };

        /// <summary>
        /// 从报告那句长理由里把"为什么算对外接口"抠出来:理由的写法是
        /// `……但它看起来是对外接口(<判据>)。……`,这里取**括号里那一层**(按括号配对,判据自身还可能带括号)。
        /// </summary>
        private static string 对外理由一句话(string 为什么)
        {
            string 文 = 为什么 ?? "";
            int 起 = 文.IndexOf('(');
            if (起 < 0) return "名字带模块前缀,或者声明写了 `程序集`";
            int 深度 = 0;
            for (int i = 起; i < 文.Length; i++)
            {
                if (文[i] == '(') 深度++;
                else if (文[i] == ')')
                {
                    深度--;
                    if (深度 == 0)
                    {
                        string 判据 = 文[(起 + 1)..i].Trim();
                        return 判据.Length > 0 ? 判据 : "名字带模块前缀,或者声明写了 `程序集`";
                    }
                }
            }
            return "名字带模块前缀,或者声明写了 `程序集`";
        }
    }
