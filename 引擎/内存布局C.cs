using System;
using System.Collections.Generic;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 运行内存的**分区明细**(R1-3,第207批)。
    ///
    /// 这一条治的是"1MB 是多大、被谁占了、还剩多少"看不见的问题:以前只知道
    /// "代码 + 静态数据 = 多少字节"一个总数,而 `堆` / `池` / `软栈` 三块**都在静态数据段里面**,
    /// 池还会自己往上涨 —— 用户撞上"池用完了"时看不出到底还有没有余地。
    ///
    /// **口径(与运行期那套同一个事实源,不另立一份)**:
    /// <list type="bullet">
    /// <item>代码段从 0 开始(一条指令 4 字节),静态数据段紧跟其后(见 `汇编器C.汇编已展开文本`);</item>
    /// <item>隐藏区(堆 / 池 / 软栈 / 垫子)的位置**由中间层登记、汇编器翻成地址**(见 <see cref="内存分区C"/>),
    ///   这里只按地址排序、把缝隙补成"变量槽",**不猜**它们的排布;</item>
    /// <item>池能长到哪儿,与运行期 `池要一块` / `宿主能力C` 同一个判据:**运行内存末尾 − `虚拟机C.栈顶保留`**;</item>
    /// <item>末尾那一小块是 ISA 定长栈(硬件栈)的保留区,`调用/返回` 与 `入栈/出栈` 从内存末尾往下长。</item>
    /// </list>
    ///
    /// 为什么要有这一条:自举的编译器要同时装"源码的字 + 符号表 + 中间表示 + 输出机器码",
    /// 1MB 是双重天花板(R1-3 拍板走"按文件流式编译",不动 ISA);这份表就是"到底还有多少余地"的账本 ——
    /// **它不是扩容**,是把现有 1MB 用到看得见。详见 `任务清单.md` 第207节。
    /// </summary>
    public static class 内存布局C
    {
        /// <summary> 池能长到的最高地址(与运行期同一个判据:运行内存末尾减硬件栈保留) </summary>
        public static int 池硬顶(int 内存大小) => Math.Max(0, 内存大小 - 虚拟机C.栈顶保留(内存大小));

        /// <summary>
        /// 整张分区表(按地址升序,首尾相接,**正好铺满** [0, 内存大小))。
        /// 表里可能出现两段"变量槽" —— 隐藏区夹在用户变量中间时本来就是两截,如实分两行写。
        /// </summary>
        public static IReadOnlyList<内存分区C> 算表(汇编调试结果C 编译, int 内存大小)
        {
            var 区们 = new List<内存分区C>();
            int 代码 = Math.Max(0, 编译.代码字节数);
            int 数据末尾 = Math.Max(代码, 编译.代码字节数 + 编译.数据字节数);
            int 硬顶 = 池硬顶(内存大小);

            if (代码 > 0) 区们.Add(new 内存分区C("代码段", 0, 代码, "指令,一条 4 字节;从 0 开始"));

            // 隐藏区:只认"落在内存里、且不与前一块重叠"的那些 —— 表是给人看的账本,宁可少写一行也不许算歪
            var 隐藏 = 编译.内存分区
                .Where(x => x.大小 > 0 && x.起始 >= 0 && x.起始 + x.大小 <= 内存大小)
                .OrderBy(x => x.起始)
                .ToList();
            int 游标 = 代码;
            int 第几段 = 0;
            foreach (var 区 in 隐藏)
            {
                if (区.起始 < 游标) continue;                       // 与前一块重叠:丢掉(正常不会发生)
                if (区.起始 > 游标)
                {
                    第几段++;
                    区们.Add(new 内存分区C(第几段 == 1 ? "变量槽" : $"变量槽 {第几段}",
                        游标, 区.起始 - 游标, "顶层变量 / 全局变量,按声明序紧致排布"));
                }
                区们.Add(区);
                游标 = 区.起始 + 区.大小;
            }
            if (数据末尾 > 游标)
            {
                第几段++;
                区们.Add(new 内存分区C(第几段 == 1 ? "变量槽" : $"变量槽 {第几段}",
                    游标, 数据末尾 - 游标, "顶层变量 / 全局变量,按声明序紧致排布"));
                游标 = 数据末尾;
            }

            int 空闲起 = Math.Max(游标, 数据末尾);
            if (硬顶 > 空闲起)
                区们.Add(new 内存分区C("空闲", 空闲起, 硬顶 - 空闲起,
                    "池不够就从这儿往上长;这块越大,池能长的余地越大"));
            if (内存大小 > 硬顶)
                区们.Add(new 内存分区C("硬件栈", 硬顶, 内存大小 - 硬顶,
                    "定长栈从内存末尾往下长(调用压返回地址、入栈/出栈)"));
            return 区们;
        }

        /// <summary>
        /// 给人看的分区明细(`hbcc --run` 打的就是这几行)。**数字都是现场算的**,不手抄。
        /// 装不下(代码 + 静态数据已经超过内存)时如实说清"装不下",不假装还有空闲。
        /// </summary>
        public static IReadOnlyList<string> 文本行(汇编调试结果C 编译, int 内存大小)
        {
            var 行 = new List<string>();
            int 硬顶 = 池硬顶(内存大小);
            int 占死 = Math.Max(0, 编译.代码字节数 + 编译.数据字节数);
            行.Add($"内存布局:运行内存 {工程文件C.大小文本(内存大小)}({内存大小} 字节)," +
                $"给硬件栈留 {工程文件C.大小文本(虚拟机C.栈顶保留(内存大小))}(池最多长到 0x{硬顶:X})");
            foreach (var 区 in 算表(编译, 内存大小))
                行.Add($"  0x{区.起始:X6} ~ 0x{区.末尾:X6}  {区.区名}:{工程文件C.大小文本(区.大小)} —— {区.说明}");
            行.Add(硬顶 > 占死
                ? $"  说明:代码 + 静态数据 {占死} 字节;池能从上面的\"空闲\"往上长,最多再用 {硬顶 - 占死} 字节"
                : $"  说明:代码 + 静态数据 {占死} 字节,**已经装不进运行内存** —— 请把工程文件里的 `内存` 调大(最大 {工程文件C.大小文本(虚拟机C.最大内存大小)})," +
                  "或者把 `堆` / `软栈` / 大数组改小");
            return 行;
        }
    }
}
