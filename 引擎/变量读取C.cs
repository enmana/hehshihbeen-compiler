namespace hehshihbeen_compiler
{
    /// <summary> 调试面板上"一个变量现在是多少"的一行(结构变量会展开成 变量.字段 多行) </summary>
    public sealed class 变量读数C
    {
        public string 名字 = "";
        public string 类型名 = "";
        /// <summary> 给人看的值:"65" / "65 ('A')" / "真" / "[4 个] 首元素=1" </summary>
        public string 值文本 = "";
        /// <summary> 原始值(读不到时无意义) </summary>
        public uint 值;
        /// <summary> false = 现在读不到它的值(比如函数还没进来 / 标签对不上),值文本会是"?" —— 绝不错读一段别处的内存冒充它的值 </summary>
        public bool 可读;
        /// <summary> 它在哪儿(说明):"全局" / "方法 f 的局部(帧内 +8)" </summary>
        public string 位置文本 = "";
        /// <summary> 缩进层级(结构字段比它所属的结构低一级,显示时缩进) </summary>
        public int 层级;
    }

    /// <summary>
    /// "停在这一行时,我能看见哪些变量、各自现在是多少" —— 纯函数,不碰界面、不碰虚拟机。
    /// 全局变量按 槽标签 → 数据段地址 读;局部/参数按 **帧指针(R15) + 帧内偏移** 读。
    /// 读不到就标 可读=false(显示 "?"),不猜 —— 调试器骗人比不显示更糟。
    /// </summary>
    public static class 变量读取C
    {
        /// <summary>
        /// 取"第 行"能看见的变量读数。
        /// </summary>
        /// <param name="名字表">这个文件的调试名字表(见 名字表C);null = 没有调试信息,返回空</param>
        /// <param name="标签表">汇编器的"标签名 → 字节地址"(全局变量槽靠它定位)</param>
        /// <param name="内存">虚拟机的内存(读值用)</param>
        /// <param name="帧指针">当前帧指针(= R15);不在任何函数里时它的值无意义,不会有人去读</param>
        /// <param name="行">当前源码行(决定"哪些变量可见"与"是哪个函数的帧")</param>
        public static List<变量读数C> 取可见变量(名字表C? 名字表, IReadOnlyDictionary<string, int>? 标签表,
            byte[]? 内存, uint 帧指针, int 行)
        {
            var 结果 = new List<变量读数C>();
            if (名字表 == null || 内存 == null) return 结果;
            var 标签 = 标签表 ?? new Dictionary<string, int>();
            string? 当前函数 = 名字表.行所属函数(行);

            foreach (var 项 in 名字表.可见变量(行, 当前函数))
            {
                结果.Add(读一个(名字表, 标签, 内存, 帧指针, 项, 0));
                // 结构变量顺手把字段接在后面(缩进显示),这样"我的点.x 是多少"不用去翻内存
                结果.AddRange(取字段读数(名字表, 标签, 内存, 帧指针, 项));
            }
            return 结果;
        }

        private static 变量读数C 读一个(名字表C 名字表, IReadOnlyDictionary<string, int> 标签,
            byte[] 内存, uint 帧指针, 名字项C 项, int 层级)
        {
            var 读数 = new 变量读数C
            {
                名字 = 项.名字,
                类型名 = 项.是引用
                    ? $"引用({名字表C.显示类型名(项.指向类型名)})"
                    : 项.是列表
                    ? (项.元素个数 > 0 ? $"列表[最多 {项.元素个数}]({名字表C.显示类型名(项.类型名)})" : $"列表({名字表C.显示类型名(项.类型名)})")
                    : 项.是数组 ? $"数组[{项.元素个数}]({名字表C.显示类型名(项.类型名)})"
                    : 名字表C.显示类型名(项.类型名),
                位置文本 = 项.是全局 ? "全局" : $"方法 {项.所属函数} 的局部(帧内 +{项.帧偏移})",
                层级 = 层级,
            };

            // 列表:值就是"现在几个 / 最多几个"(长度存在长度槽里,槽标签就是 项.槽;数据本身可能还在池里)
            if (项.是列表)
            {
                if (项.槽.Length == 0 || !标签.TryGetValue(项.槽, out int 长度地址) || 长度地址 < 0 || 长度地址 + 4 > 内存.Length) return 读数;
                读数.可读 = true;
                读数.值 = 读数值(内存, 长度地址, 4);
                读数.值文本 = 项.元素个数 > 0 ? $"[现在 {读数.值} 个 / 最多 {项.元素个数} 个]" : $"[现在 {读数.值} 个]";
                return 读数;
            }

            int 地址;
            if (项.是全局)
            {
                if (项.槽.Length == 0 || !标签.TryGetValue(项.槽, out 地址)) return 读数;   // 读不到
            }
            else
            {
                地址 = (int)帧指针 + 项.帧偏移;
            }

            if (地址 < 0 || 地址 + 项.宽度 > 内存.Length) return 读数;   // 越界:老实说读不到
            if (项.宽度 <= 0) { 读数.可读 = true; 读数.值文本 = "(空)"; return 读数; }

            // 引用:槽里装的是地址 —— 先给"指向哪儿";标量顺手把指向的值也读出来(改的是同一个地方),
            // 结构只报指向(真正的值在它下面那些字段行里,由 取字段读数 解完引用再展开)。
            if (项.是引用)
            {
                读数.值 = 读数值(内存, 地址, 4);
                读数.可读 = true;
                int 指向 = (int)读数.值;
                if (指向 == 0) { 读数.值文本 = "→ 空(还没指向谁)"; return 读数; }
                if (!名字表.结构.ContainsKey(项.指向类型名) && 项.指向宽 > 0 && 指向 + 项.指向宽 <= 内存.Length)
                    读数.值文本 = $"→ 0x{指向:X} 现在是 {格式化(项.指向类型名, 读数值(内存, 指向, 项.指向宽), 项.指向宽)}";
                else
                    读数.值文本 = $"→ 0x{指向:X}({名字表C.显示类型名(项.指向类型名)})";
                return 读数;
            }

            if (项.是数组)
            {
                // `字符串 名单[N]`:显示个数与第一个元素的**内容** —— 不看堆地址(数据地址是分配器的家事,
                // 还会随优化/分配顺序变:自检 `优化 双跑一致` 比的是命名变量的值,显示成裸地址就被它误判)。
                if (名字表C.显示类型名(项.类型名) == "字符串")
                {
                    读数.可读 = true;
                    读数.值 = 读数值(内存, 地址, 4);
                    读数.值文本 = $"[{项.元素个数} 个] 首元素 = {堆串文本(内存, 地址)}";
                    return 读数;
                }
                uint 首 = 读数值(内存, 地址, 项.元素宽);
                读数.可读 = true;
                读数.值 = 首;
                读数.值文本 = $"[{项.元素个数} 个] 首元素 = {格式化(项.类型名, 首, 项.元素宽)}";
                return 读数;
            }

            读数.值 = 读数值(内存, 地址, 项.宽度);
            读数.可读 = true;
            读数.值文本 = 格式化(项.类型名, 读数.值, 项.宽度);

            // 结构变量:值文本改成"结构"两字(真正的值在它下面那些字段行里)
            if (名字表.结构.ContainsKey(项.类型名))
            {
                读数.值文本 = "结构";
                读数.可读 = true;
            }
            return 读数;
        }

        /// <summary> 结构变量的字段读数(面板把它接在结构那一行后面显示;嵌套结构会一层层展开)</summary>
        public static List<变量读数C> 取字段读数(名字表C? 名字表, IReadOnlyDictionary<string, int>? 标签表,
            byte[]? 内存, uint 帧指针, 名字项C 项)
        {
            var 结果 = new List<变量读数C>();
            if (名字表 == null || 内存 == null) return 结果;
            if (!名字表.结构.ContainsKey(项.类型名)) return 结果;
            int 基址;
            string 位置文本;
            if (项.是引用)
            {
                // 引用:先读出槽里的地址,再从那个地址展开字段 —— 不然就会把"地址本身"当结构内容读(骗人)
                if (项.是全局)
                {
                    if (项.槽.Length == 0 || !(标签表 ?? new Dictionary<string, int>()).TryGetValue(项.槽, out int 槽地址)) return 结果;
                    基址 = 读引用基址(名字表, 内存, 槽地址, 项);
                }
                else 基址 = 读引用基址(名字表, 内存, (int)帧指针 + 项.帧偏移, 项);
                if (基址 <= 0) return 结果;
                位置文本 = $"引用 {项.名字} 指向的地方";
            }
            else
            {
                if (项.是全局)
                {
                    if (项.槽.Length == 0 || !(标签表 ?? new Dictionary<string, int>()).TryGetValue(项.槽, out 基址)) return 结果;
                }
                else 基址 = (int)帧指针 + 项.帧偏移;
                位置文本 = 项.是全局 ? "全局" : $"方法 {项.所属函数} 的局部";
            }
            展开字段(名字表, 内存, 项.名字, 项.类型名, 基址, 位置文本, 1, 结果);
            return 结果;
        }

        /// <summary> 从引用变量的槽里读出它指向的地址;读不到(越界/指空)返回 0 </summary>
        private static int 读引用基址(名字表C 名字表, byte[] 内存, int 槽地址, 名字项C 项)
        {
            if (槽地址 < 0 || 槽地址 + 4 > 内存.Length) return 0;
            int 指向 = (int)读数值(内存, 槽地址, 4);
            if (指向 <= 0) return 0;
            int 总宽 = 名字表.结构.TryGetValue(项.类型名, out var 字段表) && 字段表.Count > 0
                ? 字段表.Max(f => f.偏移 + f.宽度) : 0;
            return 总宽 > 0 && 指向 + 总宽 > 内存.Length ? 0 : 指向;
        }

        /// <summary> 一层层把结构字段摊开(嵌套结构继续往下);地址全在编译期算好,这里只是读内存</summary>
        private static void 展开字段(名字表C 名字表, byte[] 内存, string 前缀, string 结构名, int 基址, string 位置文本,
            int 层级, List<变量读数C> 结果)
        {
            if (!名字表.结构.TryGetValue(结构名, out var 字段表)) return;
            foreach (var 字段 in 字段表)
            {
                int 地址 = 基址 + 字段.偏移;
                var 行 = new 变量读数C
                {
                    名字 = $"{前缀}.{字段.名字}",
                    类型名 = 字段.是列表 ? $"列表({名字表C.显示类型名(字段.类型名)})"
                        : 字段.是数组 ? $"数组[{字段.元素个数}]({名字表C.显示类型名(字段.类型名)})" : 字段.类型名,
                    层级 = 层级,
                    位置文本 = 位置文本,
                };
                if (地址 >= 0 && 地址 + 字段.宽度 <= 内存.Length)
                {
                    行.可读 = true;
                    if (字段.是列表)
                    {
                        // 动态列表字段(头 12 字节):显示"现在几个",**不显示数据地址** ——
                        // 地址是分配器的家事,会随优化/分配顺序变(与 `字符串` 字段同一个理由)
                        uint 个数 = 读数值(内存, 地址 + 4, 4);
                        行.值 = 个数;
                        行.值文本 = $"列表[{个数} 个]({名字表C.显示类型名(字段.类型名)})";
                    }
                    else if (字段.是字符串)
                    {
                        // `字符串` 字段:显示**内容**(不看堆地址 —— 地址是分配器的家事,还会随优化/分配顺序变)
                        行.值文本 = 堆串文本(内存, 地址);
                    }
                    else if (字段.元素是字符串)
                    {
                        // `字符串 名单[N]`:显示个数与第一个元素的内容
                        行.值文本 = $"[{字段.元素个数} 个] 首元素 = {堆串文本(内存, 地址)}";
                    }
                    else if (字段.是数组)
                    {
                        uint 首 = 读数值(内存, 地址, 字段.元素宽);
                        行.值 = 首;
                        行.值文本 = $"[{字段.元素个数} 个] 首元素 = {格式化(字段.类型名, 首, 字段.元素宽)}";
                    }
                    else if (字段.是结构)
                    {
                        行.值文本 = "结构";     // 里面的字段下一层继续展开
                    }
                    else
                    {
                        行.值 = 读数值(内存, 地址, 字段.宽度);
                        行.值文本 = 格式化(字段.类型名, 行.值, 字段.宽度);
                    }
                }
                结果.Add(行);
                if (字段.是结构) 展开字段(名字表, 内存, 行.名字, 字段.类型名, 地址, 位置文本, 层级 + 1, 结果);
            }
        }

        /// <summary> 小端读 1/2/4 字节 </summary>
        public static uint 读数值(byte[] 内存, int 地址, int 宽)
        {
            uint 值 = 0;
            for (int i = 0; i < 宽 && 地址 + i < 内存.Length; i++) 值 |= (uint)内存[地址 + i] << (8 * i);
            return 值;
        }

        /// <summary>
        /// `字符串` 字段 / 字符串数组元素的显示文本:字段里是"数据地址 + 容量",真正的字节在堆里(0 结尾)。
        /// 地址为 0 就是空串(没分配过);读的时候**按容量封顶**,堆里的内容坏了也不会一路读到别的块上。
        /// </summary>
        private static string 堆串文本(byte[] 内存, int 字地址)
        {
            if (字地址 < 0 || 字地址 + 8 > 内存.Length) return "?";
            uint 数据 = 读数值(内存, 字地址, 4);
            uint 容量 = 读数值(内存, 字地址 + 4, 4);
            if (数据 == 0 || 容量 == 0) return "空串";
            int 起点 = (int)数据;
            int 上限 = Math.Min(内存.Length, 起点 + (int)容量);
            var 字节 = new List<byte>();
            for (int i = 起点; i < 上限; i++)
            {
                if (内存[i] == 0) break;
                字节.Add(内存[i]);
                if (字节.Count >= 64) break;             // 太长的只显示前 64 字节,免得面板被一屏字占满
            }
            string 内容 = System.Text.Encoding.UTF8.GetString([.. 字节]);
            return $"\"{内容}\"" + (字节.Count >= 64 ? "…" : "");
        }

        /// <summary> 按类型把数字写成人看得懂的样子:字符给字母,逻辑给 真/假,其余给十进制 </summary>
        public static string 格式化(string 类型名, uint 值, int 宽)
        {
            switch (类型名)
            {
                case "字符":
                    return 值 is >= 32 and < 127 ? $"{值} ({(char)值})" : $"{值}";
                case "逻辑":
                    return 值 == 0 ? "假" : "真";
            }
            // 有符号类型(整数/短整数):按**声明类型的宽度**解释符号位再显示。
            // 为什么不能直接看槽宽:C 档下 `短整数` 变量放在 4 字节宽槽里(存的是符号扩展后的值),
            // 直接按 4 字节显示会把 -15 显示成 4294967281。
            if (类型C.解析(类型名) is { } 类型 && 类型.有符号)
                return 类型C.看成有符号(值, 类型.宽度).ToString();
            return 值.ToString();
        }
    }
