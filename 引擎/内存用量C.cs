using System;
using System.Collections.Generic;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// H100 第二步(2026-10-15,第442批):**运行监视要的那三个数** —— 池 / 堆 / 软栈各用了多少。
    ///
    /// <para><b>为什么要有它</b>:第一步(2026-10-11)那条监视条只报得出状态 / PC / 条数 / 条频 / 子进程 CPU 与内存;
    /// "池涨到哪、堆用了多少、软栈用了多少"这三个数**状态帧里没有**,而它们恰恰是这门语言最会咬人的地方
    /// (池用完 / 递归太深 / 堆漏)。这三个数**不用新加计数器** —— 运行期本来就把账记在几个隐藏槽里:</para>
    /// <list type="bullet">
    /// <item><b>池</b>:`池指针`(下一个空位)/ `池末`(现在能用到哪儿,不够会自己 ×2 往上抬)—— 见 `中间层C.列表.cs`;</item>
    /// <item><b>堆</b>:堆区是**空闲链表 + 块头**([+0] 下一空闲块 / [+4] 本块大小 / [+8] 空闲标志,见 `中间层C.堆.cs` 的 `确保堆`)
    ///   ⇒ 用了多少 = 堆区大小 − 空闲块大小之和(走一遍空闲表);</item>
    /// <item><b>软栈</b>:帧指针(ISA 的 R15)从软栈底往上长 ⇒ 用了多少 = 帧指针 − 软栈底
    ///   (程序开头那条 `取地址 R15 软栈槽` 定的基准,见 `中间层C.主流程.cs`)。</item>
    /// </list>
    ///
    /// <para><b>口径一处</b>:槽的绝对地址由汇编器翻好(`汇编调试结果C.内部槽地址`,角色名 = `池指针` / `池末` /
    /// `堆首` / `堆末` / `空闲表头` / `软栈`),这里只负责"读出来、减出用量"。**缺角色 = 这项没有**
    /// (没用到堆的程序就不该编出堆来),那一项如实给 0 —— 绝不编数(与监视条第一步同一条口径)。</para>
    ///
    /// <para><b>读的是哪一份内存</b>:前端传进来的那一份(进程内就是那台机的内存;跨进程是**镜像内存**,
    /// 由 `跨进程虚拟机C.同步镜像()` 拉过增量再算)—— 所以这条路**不用动协议**。</para>
    /// </summary>
    public readonly record struct 内存用量C(int 池用, int 池顶, int 堆用, int 堆共, int 软栈用, int 软栈共)
    {
        /// <summary> 没有任何一项算得出来(装载之前 / 拿不到槽地址)—— 监视条据此**不显示**那几项 </summary>
        public bool 全零 => 池顶 == 0 && 堆共 == 0 && 软栈共 == 0;

        /// <summary> 空闲链表的走表上限:链表坏掉(环)时不许把界面挂死 </summary>
        private const int 走表上限 = 4096;

        /// <summary>
        /// 算三个数。**任何一项算不出来就给 0**(槽地址缺 / 越界 / 内存还没装载)——
        /// 监视条那边"全 0 就不显示",不拿 0 冒充"用量是 0"。
        /// </summary>
        public static 内存用量C 算(byte[]? 内存, IReadOnlyList<内存分区C>? 分区表, IReadOnlyDictionary<string, int>? 内部槽地址, uint 帧指针)
        {
            if (内存 == null || 内存.Length == 0 || 分区表 == null || 内部槽地址 == null) return default;

            // ---- 池 ----
            int 池用 = 0, 池顶 = 0;
            if (取区(分区表, "池") is { } 池区 && 取址(内部槽地址, "池指针") is { } 池指针址 && 取址(内部槽地址, "池末") is { } 池末址)
            {
                long 指针 = 读字(内存, 池指针址);
                long 末 = 读字(内存, 池末址);
                池用 = (int)Math.Clamp(指针 - 池区.起始, 0, Math.Max(0, 池区.大小));
                池顶 = 末 > 0 ? (int)Math.Clamp(末 - 池区.起始, 0, Math.Max(0, 池区.大小)) : 池区.大小;
            }

            // ---- 堆:堆区大小 − 空闲块大小之和 ----
            int 堆用 = 0, 堆共 = 0;
            if (取区(分区表, "堆") is { } 堆区 && 取址(内部槽地址, "空闲表头") is { } 表头址)
            {
                堆共 = Math.Max(0, 堆区.大小);
                long 空闲 = 0;
                long 块 = 读字(内存, 表头址);
                for (int i = 0; i < 走表上限 && 块 > 0; i++)
                {
                    if (块 + 8 > 内存.Length) break;                       // 越界 = 链表坏了,不再往下走
                    long 大小 = 读字(内存, (int)块 + 4);
                    if (大小 <= 0) break;
                    空闲 += 大小;
                    块 = 读字(内存, (int)块);
                }
                堆用 = (int)Math.Clamp(堆共 - 空闲, 0, 堆共);
            }

            // ---- 软栈:帧指针 − 软栈底 ----
            int 软栈用 = 0, 软栈共 = 0;
            if (取区(分区表, "软栈") is { } 软栈区)
            {
                软栈共 = Math.Max(0, 软栈区.大小);
                if (帧指针 > 0)
                    软栈用 = (int)Math.Clamp((long)帧指针 - 软栈区.起始, 0, 软栈共);
            }

            return new 内存用量C(池用, 池顶, 堆用, 堆共, 软栈用, 软栈共);
        }

        private static 内存分区C? 取区(IReadOnlyList<内存分区C> 表, string 区名)
        {
            foreach (var 区 in 表) if (区.区名 == 区名) return 区;
            return null;
        }

        private static int? 取址(IReadOnlyDictionary<string, int> 表, string 角色)
            => 表.TryGetValue(角色, out int 址) ? 址 : null;

        /// <summary> 读一个字(4 字节小端)。越界给 0(监视这条路**只读不报错** —— 它是给人看的,不该把界面搞崩) </summary>
        private static long 读字(byte[] 内存, int 地址)
        {
            if (地址 < 0 || 地址 + 4 > 内存.Length) return 0;
            return (uint)(内存[地址] | (内存[地址 + 1] << 8) | (内存[地址 + 2] << 16) | (内存[地址 + 3] << 24));
        }
    }
}
