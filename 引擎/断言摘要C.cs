namespace hehshihbeen_compiler
{
    /// <summary>
    /// 「输出断言」那一行的收口(H31,2026-09-20):**一行里每边最多显示 200 字,绝不整篇回显**。
    ///
    /// 为什么要它:H22 那批的探针量到"输出上百万字符时「输出」页那段程序输出变成**两份**"。
    /// 根因就是这里 —— 断言那一行原来把**整篇程序输出**当字符串拼进 `实际 &lt;…&gt;` 里,
    /// 再 `输出框.AppendText(断言)`,于是本页上面已经刷过一遍的输出被原样贴了第二遍
    /// (H31 探针实测:一次 `TextChanged` 从 1176490 字涨到 2352989 字,增 1176499;
    /// 控制台页与 `本次程序输出` 都是一份 ⇒ 问题只在"断言回显"这一处,不在追加那条路、更不是 WPF)。
    ///
    /// 口径:程序自己的输出本来就在「输出」页上面一行行刷着,断言这一行只需要够看出
    /// **哪儿不一样**;超过上限就只留头 200 字 + 一句"共几个字",并另起一行说清完整输出在哪。
    /// </summary>
    public static class 断言摘要C
    {
        /// <summary> 一行里每边最多显示多少字(超了就只留头一段并注明共几个字)</summary>
        public const int 每边上限 = 200;

        /// <summary> 收过口时那句说明:说清"完整输出在哪儿",不是干巴巴一句"太长" </summary>
        public const string 收口说明 =
            "(某一侧只显示了头 200 字:完整程序输出就在本页上面刷着呢;要逐字比,可用命令行 `hbcc --run`,或把 `// 预期输出:` 写短些)";

        /// <summary> 把一段输出收成"一行":换行换成竖线;超过上限就只留头一段并注明共几个字 </summary>
        public static string 一行(string 文本)
        {
            string 单行 = 成一行(文本);
            if (单行.Length <= 每边上限) return 单行;
            return 单行[..每边上限] + "…(共 " + 单行.Length + " 字)";
        }

        /// <summary> 这一段是不是被收过口了(收过口就另起一行说清完整输出在哪) </summary>
        public static bool 收过口(string 文本) => 成一行(文本).Length > 每边上限;

        /// <summary> 断言那一整行(通过 / 失败都在这一处拼,免得两条路各写一份文案) </summary>
        public static string 输出断言(string 期望输出, string 实际输出, bool 通过) =>
            $"输出断言: 期望 <{一行(期望输出)}>, 实际 <{一行(实际输出)}> → {(通过 ? "通过" : "失败")}";

        /// <summary> 换行统一成竖线(`\r\n` 与 `\n` 都只算一处) </summary>
        private static string 成一行(string 文本) => 文本.Replace("\r\n", "\n").Replace('\n', '|');
    }
}
