using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **H39-1:跑程序的后端** —— 住在一个子进程里,把"虚拟机 + 宿主能力 + 图形宿主"整块接过来
    /// (它就是这个子进程的 `跑程序服务` 那一档,见 `HB宿主\Program.cs` 与 `编译器CLI\Program.cs`)。
    ///
    /// <para>**为什么要有它**:一次未处理异常 / 一次宿主崩就会带走整个 IDE。把"跑程序"放进子进程之后,
    /// 前端只拿小增量与快照(口径 c),崩的是子进程、IDE 还在、还能重连。</para>
    ///
    /// <para>**线程分工**(两条,别把长跑塞进读帧线程 —— 那样中断与输入都收不到):
    /// ① **读帧线程**:只做"当场就能做完"的三件事 —— `中断请求` → `机.请求中断()`,
    ///    `输入应答` → 投给输入源,`图形事件` → `图形宿主C.投事件`;`结束` 就置停止旗标 + 唤醒输入等待。
    ///    别的命令一律**塞进队列**;
    /// ② **主线程**(= `跑()` 那条):一条一条取命令来执行(装载 / 单步 / 跑到 / 读内存…),长跑在这儿。</para>
    ///
    /// <para>**出口**:`跑()` 返回进程退出码(0 = 正常收摊;3 = 协议对不上这类"不得不收摊")。</para>
    /// </summary>
    public sealed class 跑程序后端C
    {
        /// <summary> 输入(前端 → 这一侧)</summary>
        private readonly Stream _入;
        /// <summary> 输出(这一侧 → 前端;协议通道,不许写别的东西)</summary>
        private readonly Stream _出;

        /// <summary> 写帧要用的锁:主线程(命令回复 / 图形命令)与读帧线程(输入应答)都会写</summary>
        private readonly object _写锁 = new();

        /// <summary> 攒着还没发出去的输出字节(≥256 字节 / 每条命令结尾 / 发"请求输入"之前冲刷)</summary>
        private readonly List<byte> _输出缓冲 = [];
        private readonly object _输出锁 = new();

        /// <summary> 读帧线程塞进来的命令(主线程取)</summary>
        private readonly System.Collections.Concurrent.BlockingCollection<(byte 消息号, byte[] 载荷)> _命令队列 = [];

        /// <summary> "前端送来的输入应答"那把锁(输入源在它上面等)</summary>
        private readonly object _输入锁 = new();
        /// <summary> 等着的输入应答:**null = 还没来**;`(false, 0)` = 前端说"没有输入 / 我走了" </summary>
        private (bool 有字节, byte 值)? _输入应答;

        /// <summary> 真跑程序的那台虚拟机(这一侧唯一的一台;装载时按前端给的容量与内容重置)</summary>
        private readonly 虚拟机C _机 = new();

        /// <summary> 上一次**已经发给前端**的内存镜像(比"变没变"用它,只发差量)</summary>
        private byte[]? _上次镜像;

        /// <summary> 图形命令往哪儿去(子进程里那块"画在哪儿"的接口就是"打包成帧发给前端")</summary>
        private readonly 转发呈现口C _转发呈现口;

        // ---------------- H39-3:图形回执(前端那一侧到底画成了没有) ----------------
        /// <summary> 等"图形回执"那把锁:回执由**读帧线程**收,主线程在呈现口那一趟里等它</summary>
        private readonly object _图形锁 = new();
        /// <summary> 收到的那一条图形回执(**null = 还没来**);序号对不上(迟到的旧回执)就丢掉</summary>
        private (uint 序号, bool 成功, string 说明)? _图形回执;
        /// <summary> 图形命令的序号(每发一条 +1;只有发命令那条线程动它,不用锁)</summary>
        private uint _图形序号;

        /// <summary>
        /// 等一条图形回执最多多久(毫秒)。**给得宽**:前端那一侧的 `打开窗口` 自己最多等首帧 3 秒,
        /// 界面线程被人占着也可能拖几秒;而**超时只当"这一条没画成"(程序拿到 `状态_开不了窗口`),
        /// 不判通道死** —— 慢不等于崩,这一条与 H39 验收①那条"崩了要说得清"分得开。
        /// </summary>
        private const int 图形回执超时毫秒 = 30_000;

        // ---- H13:热重载要问"旧那一份长什么样"(子进程手里攥着的上一份编译产物) ----
        /// <summary> 现在装着的机器码(装载 / 重载时换;判"旧的这一格在不在数据段里"靠它)</summary>
        private byte[] _机器码 = [];
        /// <summary> 现在这一份的初值表(重载时前半是"旧常量也回出厂值"的依据)</summary>
        private IReadOnlyList<初值项C> _初值表 = [];
        /// <summary> 现在这一份的隐藏区(字符串池的位置与大小靠它)</summary>
        private IReadOnlyList<内存分区C> _分区表 = [];
        /// <summary> 现在这一份的全局槽(槽标签 / 宽度 / 名字;重载要判"同名同宽才搬")</summary>
        private 名字表C _名字表 = new();
        /// <summary> 现在这一份的"槽标签 → 地址"表(旧地址只有它能给)</summary>
        private IReadOnlyDictionary<string, int> _标签表 = new Dictionary<string, int>(StringComparer.Ordinal);
        /// <summary> 现在这一份的代码段字节数(判"变量槽有没有压在代码段里")</summary>
        private int _代码字节数 = -1;

        // ---------------- H39-2:记账(调用栈标记 + 尾部轨迹) ----------------
        // 为什么账记在这一侧:"跑到断点"是**一次过线跑掉几十万条** —— 前端拿不到中间每一步,
        // 只能由真正执行的那一侧逐条记下来、随状态帧整份带回去(见 `跑程序协议C.跑程序记账C`)。
        /// <summary> 调用处记帐(与 `调试会话C` 里那一份同一个类、同一套"进出"口径)</summary>
        private readonly 调用栈标记C _调用栈 = new();
        /// <summary> 尾部轨迹环(装 (指令地址, 当时的 R15));每条命令开头清掉,于是"这一趟新产生的"就是全部</summary>
        private readonly 轨迹环C _轨迹 = new(跑程序协议C.轨迹上限);
        /// <summary> 这一趟要不要记账(前端随命令带过来;关着时连钩子都不装,一分钱不多花)</summary>
        private bool _要记账;

        private volatile bool _停止;
        private bool _前端走了;
        private volatile int _退出码;

        public 跑程序后端C(Stream 入, Stream 出)
        {
            _入 = 入 ?? throw new ArgumentNullException(nameof(入));
            _出 = 出 ?? throw new ArgumentNullException(nameof(出));
            _转发呈现口 = new 转发呈现口C(this);
        }

        /// <summary> 主循环:发问候 → 起读帧线程 → 一条一条做命令。返回进程退出码。 </summary>
        public int 跑()
        {
            _机.宿主调用 = 宿主能力C.处理;      // P28:读文件 / 写文件 / 当前时间(与进程内同一套)
            发帧(跑程序协议C.事件_问候, 写 =>
            {
                写.Write(跑程序协议C.协议版本);
                写.Write($"构建={System.Runtime.InteropServices.RuntimeInformation.FrameworkDescription}" +
                    $" / {System.Runtime.InteropServices.RuntimeInformation.RuntimeIdentifier}");
            });

            var 读帧线程 = new Thread(读帧循环) { IsBackground = true, Name = "跑程序后端 读帧" };
            读帧线程.Start();

            while (!_停止)
            {
                if (!_命令队列.TryTake(out var 命令, Timeout.Infinite)) break;
                执行命令(命令.消息号, 命令.载荷);
            }
            return _退出码;
        }

        // ===================================================================
        // 读帧线程:只做"当场能做完"的三件事 + 结束
        // ===================================================================

        private void 读帧循环()
        {
            try
            {
                while (true)
                {
                    var 帧 = 跑程序协议C.读帧(_入);
                    if (帧 == null) { 前端走了(); return; }        // 管道到了末尾:前端退出了 / 关掉了这一端
                    var (消息号, 载荷) = 帧.Value;
                    switch (消息号)
                    {
                        case 跑程序协议C.命令_问候: 处理问候(载荷); break;
                        case 跑程序协议C.命令_中断请求:
                            _机.请求中断();          // 长跑会在下一道闸门上退出来(闸门口径见 `中断闸门C`)
                            break;
                        case 跑程序协议C.命令_输入应答: 处理输入应答(载荷); break;
                        case 跑程序协议C.命令_图形事件: 处理图形事件(载荷); break;
                        case 跑程序协议C.命令_图形回执: 处理图形回执(载荷); break;
                        case 跑程序协议C.命令_结束:
                            // 长跑要先**叫停**再收摊:否则主线程还卡在"跑到"里,`_停止` 没人看
                            _机.请求中断();
                            前端走了();
                            return;
                        default:
                            _命令队列.Add((消息号, 载荷));
                            break;
                    }
                }
            }
            catch (Exception)
            {
                // 读帧出错(帧被读偏了 / 半路断掉):这一侧没法回话,如实收摊
                前端走了();
            }
        }

        /// <summary> 前端发来的协议版本:对不上就如实收摊(不许硬接着读载荷 —— 布局可能已经变了)</summary>
        private void 处理问候(byte[] 载荷)
        {
            using var 读 = 跑程序协议C.开读(载荷);
            int 它的 = 读.ReadInt32();
            if (它的 == 跑程序协议C.协议版本) return;
            发帧(跑程序协议C.事件_致命错误, 写 =>
                写.Write($"协议版本对不上:前端说 {它的},这一端是 {跑程序协议C.协议版本} —— " +
                    "两边必须用同一份 `跑程序协议C`(把两个东西都重新编一遍)"));
            _退出码 = 3;
            收摊();
        }

        private void 处理输入应答(byte[] 载荷)
        {
            using var 读 = 跑程序协议C.开读(载荷);
            byte 种类 = 读.ReadByte();
            (bool, byte) 应答 = 种类 == 跑程序协议C.输入_有字节 ? (true, 读.ReadByte()) : (false, (byte)0);
            lock (_输入锁)
            {
                _输入应答 = 应答;
                Monitor.PulseAll(_输入锁);
            }
        }

        /// <summary> 图形事件在**读帧这一条线程上**直接进队列(事件本来就是队列,不用等主线程)</summary>
        private static void 处理图形事件(byte[] 载荷)
        {
            using var 读 = 跑程序协议C.开读(载荷);
            图形宿主C.投事件(读.ReadInt32(), 读.ReadInt32(), 读.ReadInt32(), 读.ReadInt32());
        }

        /// <summary>
        /// H39-3:前端那一侧把一条图形命令做完了(或做不了)。**必须由读帧线程收**:
        /// 主线程这会儿正卡在"等这一条回执"里(它就是发那条命令的人),塞进命令队列会自己把自己锁死。
        /// </summary>
        private void 处理图形回执(byte[] 载荷)
        {
            using var 读 = 跑程序协议C.开读(载荷);
            uint 序号 = 读.ReadUInt32();
            bool 成功 = 读.ReadByte() == 跑程序协议C.图形回执_好;
            string 说明 = 读.ReadString();
            lock (_图形锁)
            {
                _图形回执 = (序号, 成功, 说明);
                Monitor.PulseAll(_图形锁);
            }
        }

        /// <summary>
        /// 前端走了 / 不得不收摊:置停止旗标、唤醒等输入的线程、把命令队列关掉。
        /// 为什么收摊写在各自的调用点上 —— 这一侧**没有第二条路**能把原因说出去(管道已经断了)。
        /// </summary>
        private void 前端走了()
        {
            _前端走了 = true;
            收摊();
        }

        private void 收摊()
        {
            _停止 = true;
            lock (_输入锁) Monitor.PulseAll(_输入锁);
            lock (_图形锁) Monitor.PulseAll(_图形锁);        // H39-3:等图形回执的线程当场醒过来(程序那边如实拿到"画不了")
            _命令队列.CompleteAdding();
        }

        // ===================================================================
        // 主线程:一条一条做命令(每条命令回一帧"状态")
        // ===================================================================

        private void 执行命令(byte 消息号, byte[] 载荷)
        {
            try
            {
                switch (消息号)
                {
                    case 跑程序协议C.命令_装载: 处理装载(载荷); break;
                    case 跑程序协议C.命令_单步: 处理单步(载荷); break;
                    case 跑程序协议C.命令_跑到: 处理跑到(载荷); break;
                    case 跑程序协议C.命令_读内存: 发内存增量(); 回状态(跑程序协议C.结果_正常); break;
                    case 跑程序协议C.命令_取中断请求:
                        {
                            bool 有 = _机.取中断请求();
                            回状态(跑程序协议C.结果_正常, null, 跑程序协议C.停_没有, 有);
                            break;
                        }
                    case 跑程序协议C.命令_清除中断请求: _机.清除中断请求(); break;
                    case 跑程序协议C.命令_清除等待输入: _机.清除等待输入(); break;
                    case 跑程序协议C.命令_重载: 处理重载(载荷); break;
                    default:
                        发帧(跑程序协议C.事件_致命错误, 写 => 写.Write($"认不出的消息号 {消息号}(两边协议版本对不上?)"));
                        _退出码 = 3;
                        收摊();
                        break;
                }
            }
            catch (跑程序通道错误C 错)
            {
                // 载荷读不成(帧被读偏了 / 块长度不像话):如实回一条"内部错误",前端在等状态,不回就挂住了
                try { 冲刷输出(); 回状态(跑程序协议C.结果_内部错误, null, null, false, 错.Message); }
                catch (Exception) { 前端走了(); }        // 连回话都发不出去 = 管道没了
            }
            catch (Exception 错)
            {
                try { 冲刷输出(); 回状态(跑程序协议C.结果_内部错误, null, null, false, 错.Message); }
                catch (Exception) { 前端走了(); }
            }
        }

        private void 处理装载(byte[] 载荷)
        {
            using var 读 = 跑程序协议C.开读(载荷);
            int 内存大小 = 读.ReadInt32();
            byte[] 机器码 = 跑程序协议C.读块(读);
            var 初值表 = 跑程序协议C.读初值表(读);
            var 源行表 = 跑程序协议C.读源行表(读);
            var 可执行 = 跑程序协议C.读可执行白名单(读);
            var 网址 = 跑程序协议C.读网址白名单(读);
            bool 有图形口 = 读.ReadBoolean();
            bool 等输入 = 读.ReadBoolean();
            _要记账 = 读.ReadBoolean();
            string 脚本文本 = 读.ReadString();        // H39-3:`--事件脚本` 那份脚本的原文(空串 = 这一趟没有脚本)
            _名字表 = 跑程序协议C.读全局槽(读);        // H13:热重载要判"同名同宽才搬"
            _分区表 = 跑程序协议C.读分区表(读);         // H13:热重载要判"字符串池能不能原地保"
            _标签表 = 跑程序协议C.读标签表(读);         // H13:旧那一格排在哪(旧地址只有它能给)
            _代码字节数 = 跑程序协议C.读代码字节数(读);  // H13:代码段多长(判"槽有没有压在代码段里")

            // 白名单:空 = 没这个能力(与进程内同一套口径);每次装载都重设一次,免得串到上一个程序
            宿主能力C.设可执行白名单(可执行);
            宿主能力C.设网址白名单(网址);
            if (有图形口) 图形宿主C.挂上(_转发呈现口);
            else 图形宿主C.摘掉();
            图形宿主C.清空();                    // 一个程序一个宿主:上一轮没刷的命令 / 旧事件不带过来
            // R4-12 补缀(2026-10-13):位图仓也是"一个程序一个宿主"那一族,原先漏了它 ⇒
            //   同一个宿主进程连跑两个程序时,上一个程序的图留着、句柄接着涨(实测 **1 → 2**),
            //   而 C 后端那条腿每个程序都是新进程(`hb_boot` 一次、`hb_bmp_下一号` 从 1 起)——
            //   于是"整数 图 = 位图.建(…)"写进运行内存的那几个字节两边对不上(全量对拍逐字节比)。
            //   `清光` 连号一起压回 1(见 `引擎\位图仓C.cs`),与 `hb_boot` 里那句 `hb_bmp_清光()` 同档。
            位图仓C.清光();
            // H39-3:脚本挂**这一侧**(真正跑程序的那一侧)—— 帧 0 投放 / 跑满帧数投关窗请求 /
            // 帧数宽限那道护栏全在 `图形宿主C` 里,于是跨进程与进程内是同一套语义;
            // 必须在 `挂上 / 摘掉` 之后(那两处会把脚本清掉)。
            图形宿主C.挂事件脚本(string.IsNullOrEmpty(脚本文本) ? null : 事件脚本C.解析(脚本文本));

            _机.设内存大小(内存大小);
            _机.初值表 = 初值表;
            // 运行期报错带行号:与 `HB宿主\Program.cs` 那条老口径同一个写法(挂 `取源位置`,没有表就不挂)
            _机.取源位置 = null;
            if (!源行表.空) _机.取源位置 = 地址 => 源行表.查位置(地址);
            _机.取源行号 = null;
            _机.等输入 = 等输入;
            _机.输入源 = 取输入字节;
            _机.输出目标 = 收输出字节;
            _机.装载(机器码);
            _机器码 = 机器码;                            // H13:这一份就是下一次重载眼里的"旧"
            _初值表 = 初值表;
            // H13:这一份的几张表也挂到机器上,再记快照 —— 快照是"下一次重载眼里的旧那一份",
            // 不挂上去的话快照里是空表(踩过:跨进程那条腿一只变量都保不住)
            _机.名字表 = _名字表;
            _机.标签表 = _标签表;
            _机.内存分区 = _分区表;
            _机.代码字节数 = _代码字节数;
            _机.记下装载快照();                          // H13:装载之后这一份就是下一次重载眼里的"旧那一份"
            _上次镜像 = new byte[_机.内存.Length];  // 前端手里那份镜像就是全 0(装载刚清过),对齐
            // H39-2:装载 = 新的一轮:调用栈与尾部轨迹都从头来;要记账才把钩子挂上(不挂 = 热循环一个字节不多花)
            _调用栈.清空();
            _轨迹.清空();
            _机.单步回调 = _要记账 ? 记一步账 : null;
            回状态(跑程序协议C.结果_正常);
        }

        /// <summary>
        /// H13:**热重载(后端这一侧)** —— 这一台才是真正在跑的那台,所以**判据在这儿**:
        /// 拿"现在装着的这一份"(机器码 / 初值表 / 分区表,顺手从 `_机` 新机器码上取)跟新的一份比,
        /// 判出"哪些格能保",判完**先回一条 `事件_重载`**(前端照它重摆镜像),再拿判好的那份执行自己这一侧。
        ///
        /// 为什么先回执再自己换:前端那条线程卡在等这一条回执上,而这一条命令是**串行队列**里轮到的
        /// (跑到 / 单步都在它前面),所以这一刻没有别的命令在路上,发帧不会与谁抢。
        /// </summary>
        private void 处理重载(byte[] 载荷)
        {
            int 内存大小;
            byte[] 机器码;
            List<初值项C> 新初值表;
            int 代码字节数;
            虚拟机C.重载迁移C 迁移;
            using (var 读 = 跑程序协议C.开读(载荷))
            {
                内存大小 = 读.ReadInt32();
                机器码 = 跑程序协议C.读块(读);
                新初值表 = 跑程序协议C.读初值表(读);
                代码字节数 = 读.ReadInt32();
                迁移 = 跑程序协议C.读迁移(读);              // **判好的迁移**(前端判的:这一侧一个判据都不跑)
            }

            _机.设内存大小(内存大小);
            _机.初值表 = 新初值表;
            _机.代码字节数 = 代码字节数;
            _机.重载(机器码, 判好的迁移: 迁移);            // 照贴:地址 / 旧初值 / 说明全是前端那一份原文
            _机.记下装载快照();                          // 换完这一份就是新的"旧那一份"(下一次重载接着用)

            // 回执:同一份迁移表交回前端当账(内容一字不改)
            发帧(跑程序协议C.事件_重载, 写 => 跑程序协议C.写迁移(写, 迁移));

            _机器码 = 机器码;
            _初值表 = 新初值表;
            _代码字节数 = 代码字节数;
            _上次镜像 = new byte[_机.内存.Length];      // 前端那份镜像刚被它自己重摆过(不是全 0);下一次"读内存"会把差量补齐
            _调用栈.清空();                             // 新的一轮:上一轮的调用栈属于旧机器码
            _轨迹.清空();
            _机.单步回调 = _要记账 ? 记一步账 : null;
            冲刷输出();
        }

        /// <summary>
        /// H39-2:**每走完一条指令记一笔账**(调用栈那两下与 `调试会话C.走一条` 一模一样;
        /// 轨迹多存一列"当时的 R15",好让前端把寄存器说明重放出来)。
        /// </summary>
        private void 记一步账(int 旧PC, int 新PC)
        {
            _调用栈.记一步(旧PC, 新PC, 虚拟机C.是调用指令(_机.机器码, 旧PC));
            _轨迹.记(旧PC, _机.寄存器[寄存器C.帧指针号]);
        }

        private void 处理单步(byte[] 载荷)
        {
            using (var 读 = 跑程序协议C.开读(载荷))
            {
                _机.等输入 = 读.ReadBoolean();
                _要记账 = 读.ReadBoolean();
            }
            _轨迹.清空();                     // 这一趟只带"这一条命令里新产生的"轨迹(单步就是 1 条)
            try
            {
                _机.单步();
                冲刷输出();
                回状态(跑程序协议C.结果_正常);
            }
            catch (运行期错误C 错) { 冲刷输出(); 回状态(跑程序协议C.结果_运行期错误, 错); }
            catch (Exception 错) { 冲刷输出(); 回状态(跑程序协议C.结果_内部错误, null, null, false, 错.Message); }
        }

        private void 处理跑到(byte[] 载荷)
        {
            List<int> 断点;
            long 上限;
            using (var 读 = 跑程序协议C.开读(载荷))
            {
                int 条数 = 读.ReadInt32();
                if (条数 < 0 || 条数 > 1_000_000) throw new 跑程序通道错误C($"断点地址表 {条数} 条不像话");
                断点 = new List<int>(条数);
                for (int i = 0; i < 条数; i++) 断点.Add(读.ReadInt32());
                上限 = 读.ReadInt64();
                _机.等输入 = 读.ReadBoolean();
                _要记账 = 读.ReadBoolean();
            }
            _轨迹.清空();                     // 同上:一趟最多带满 512 条(轨迹环自己的容量)
            try
            {
                var 原因 = _机.跑到(断点, 上限);
                冲刷输出();
                回状态(跑程序协议C.结果_正常, null, (byte)原因);
            }
            catch (运行期错误C 错) { 冲刷输出(); 回状态(跑程序协议C.结果_运行期错误, 错); }
            catch (Exception 错) { 冲刷输出(); 回状态(跑程序协议C.结果_内部错误, null, null, false, 错.Message); }
        }

        /// <summary> 回一条"命令结束"的状态帧(带上这一刻的整机小快照 + 这一趟的记账) </summary>
        private void 回状态(byte 结果码, 运行期错误C? 错 = null, byte? 停下 = null, bool 有中断请求 = false,
            string 内部说明 = "")
        {
            发帧(跑程序协议C.事件_状态, 写 => 跑程序协议C.写状态(写, new 跑程序协议C.跑程序状态C
            {
                结果码 = 结果码,
                停下 = 停下 ?? 跑程序协议C.停_没有,
                程序计数器 = _机.程序计数器,
                寄存器 = _机.寄存器,
                栈指针 = _机.栈指针,
                状态标志 = _机.状态标志,
                停机 = _机.停机,
                命中断点 = _机.命中断点,
                已中断 = _机.已中断,
                正在等输入 = _机.正在等输入,
                上一条指令地址 = _机.上一条指令地址,
                已执行条数 = _机.已执行条数,
                // 运行期错误**拆成"说明 + 源码行 + 位置"三件发**:前端照原样重建 `运行期错误C`,
                // `Message` 就与进程内那条一模一样("第 N 行:说明" / "文件 第 N 行:说明")
                说明 = 错?.说明 ?? 内部说明,
                源码行 = 错?.源码行 ?? 0,
                位置 = 错?.位置 ?? "",
                有中断请求 = 有中断请求,
                // H39-2:账随这条命令一起回去(没要记账就是 null —— 状态帧里一个字节都不多)
                记账 = _要记账 ? new 跑程序协议C.跑程序记账C
                {
                    调用处 = [.. _调用栈.调用处地址],
                    被调 = [.. _调用栈.被调地址],
                    轨迹 = _轨迹.取全部(),
                } : null,
            }));
        }

        // ===================================================================
        // 输出 / 输入
        // ===================================================================

        private void 收输出字节(byte 字节)
        {
            bool 该冲;
            lock (_输出锁)
            {
                _输出缓冲.Add(字节);
                该冲 = _输出缓冲.Count >= 256;      // 攒够 256 字节就冲刷(别一个字节一帧地过管道)
            }
            if (该冲) 冲刷输出();
        }

        private void 冲刷输出()
        {
            byte[]? 块 = null;
            lock (_输出锁)
            {
                if (_输出缓冲.Count > 0) { 块 = [.. _输出缓冲]; _输出缓冲.Clear(); }
            }
            if (块 != null) 发帧(跑程序协议C.事件_输出, 写 => 跑程序协议C.写块(写, 块));
        }

        /// <summary>
        /// 给虚拟机挂的输入源:没有输入就发一次"请求输入"帧,**阻塞等**前端送"输入应答"。
        /// 前端走了 = 没有输入了(EOF → null)。等之前先把输出冲刷掉(提示语要排在"等你输入"之前)。
        /// </summary>
        private uint? 取输入字节()
        {
            if (_前端走了) return null;
            冲刷输出();
            发帧(跑程序协议C.事件_请求输入);
            lock (_输入锁)
            {
                while (_输入应答 == null && !_前端走了) Monitor.Wait(_输入锁);
                var 应答 = _输入应答;
                _输入应答 = null;
                if (应答 == null || !应答.Value.有字节) return null;   // 前端没有输入 / 前端走了 ⇒ 按"没有输入了"处理
                return 应答.Value.值;
            }
        }

        // ===================================================================
        // 内存增量 与 发帧
        // ===================================================================

        /// <summary>
        /// 与"上一次发给前端的镜像"比一次,变过的连续段当"内存增量"发出去。
        /// **每条要发内存的命令结尾调一次**(单步不调:每一步都过一遍管道会把 F10 的手感吃掉)。
        /// </summary>
        private void 发内存增量()
        {
            var 现在 = _机.内存;
            var 差量 = 跑程序协议C.比较内存(现在, _上次镜像);
            _上次镜像 = (byte[])现在.Clone();          // 记下"已经发到哪儿了"(差量为空也要记:镜像得跟上这一刻)
            if (差量.Count > 0) 发帧(跑程序协议C.事件_内存增量, 写 => 跑程序协议C.写内存增量(写, 差量));
        }

        private void 发帧(byte 消息号, Action<BinaryWriter>? 写载荷 = null)
        {
            跑程序协议C.写帧(_出, _写锁, 消息号, 写载荷);
        }

        // ===================================================================
        // H39-3:图形命令过线(发一条 + 等一条回执)
        // ===================================================================

        /// <summary>
        /// 把一条图形命令发给前端,并**等它回执**(序号对上才算这一条的回执;迟到的旧回执丢掉)。
        ///
        /// 返回 false = 这一条没画成(前端那一侧抛了 / 没挂呈现口 / 超时 / 前端走了),`说明` 是给人看的那句;
        /// 转发呈现口据此抛异常,能力层兜底 catch 转成 `状态_开不了窗口` 交回给程序 ——
        /// **程序这一侧"打开了窗口"这件事不许假装成功**(H39-2 只发不收,前端画不出来时程序还以为画成了)。
        ///
        /// 等的时候**绝不能占着读帧线程**(回执由它收),睡(让出一帧)也睡在**这一侧**
        /// (前端收到"等待"帧不再重睡 —— 两边各睡一次 = 帧节拍只剩一半,与 H39-2 同一条口径)。
        /// </summary>
        private bool 过一条图形命令(Action<BinaryWriter> 写种类, int 睡毫秒, out string 说明)
        {
            冲刷输出();          // 输出与绘制同一条管道、同一个顺序:先把攒着的输出推出去再发绘制
            uint 序号 = ++_图形序号;
            lock (_图形锁) _图形回执 = null;
            发帧(跑程序协议C.事件_图形命令, 写 =>
            {
                写.Write(序号);
                写种类(写);
            });
            if (睡毫秒 > 0) Thread.Sleep(睡毫秒);
            return 等图形回执(序号, out 说明);
        }

        /// <summary> 等序号对得上的那一条回执(**读帧线程**收回来);前端走了 / 超时都给 false </summary>
        private bool 等图形回执(uint 序号, out string 说明)
        {
            说明 = "";
            long 期限 = Environment.TickCount64 + 图形回执超时毫秒;
            lock (_图形锁)
            {
                while (true)
                {
                    if (_图形回执 is { } 到)
                    {
                        _图形回执 = null;
                        if (到.序号 == 序号) { 说明 = 到.说明; return 到.成功; }
                        // 迟到的旧回执(上一趟等到超时之后才回来):丢掉,接着等这一条
                    }
                    if (_前端走了) { 说明 = "前端已经走了,这一条没人画"; return false; }
                    long 剩 = 期限 - Environment.TickCount64;
                    if (剩 <= 0) { 说明 = $"前端 {图形回执超时毫秒 / 1000} 秒没回话"; return false; }
                    Monitor.Wait(_图形锁, (int)Math.Min(剩, 200));
                }
            }
        }

        /// <summary>
        /// **图形命令的转发口**:能力层(`图形宿主C`)把"打开窗口 / 关闭窗口 / 呈现 / 等待"交给它,
        /// 它原样打成"图形命令"帧发给前端 —— 真窗口在前端进程里画(口径 a),这一侧一个窗口都不开。
        ///
        /// **H39-3 起每一条都等回执**:前端说画不了(呈现口抛了 / 没挂 / 超时)就抛
        /// `图形过线失败C`,能力层如实给程序 `状态_开不了窗口`(与进程内"呈现口抛异常"同一个出口)。
        /// </summary>
        private sealed class 转发呈现口C(跑程序后端C 后端) : 图形呈现口C
        {
            private readonly 跑程序后端C _后端 = 后端;

            public void 打开窗口(string 标题, int 宽, int 高) => 过线(写 =>
            {
                写.Write(跑程序协议C.图形_打开窗口);
                写.Write(标题 ?? "");
                写.Write(宽);
                写.Write(高);
            });

            public void 关闭窗口() => 过线(写 => 写.Write(跑程序协议C.图形_关闭窗口));

            public void 呈现(IReadOnlyList<绘制命令C> 命令) => 过线(写 =>
            {
                写.Write(跑程序协议C.图形_呈现);
                写.Write(命令.Count);
                foreach (var 条 in 命令) 跑程序协议C.写绘制命令(写, 条);
            });

            /// <summary>
            /// 让出一帧:**睡在这一侧**(程序那半在这儿),前端收到这一帧只回执、不再重睡。
            /// </summary>
            public void 等待(int 毫秒) => 过线(
                写 => { 写.Write(跑程序协议C.图形_等待); 写.Write(毫秒); }, 睡毫秒: 毫秒);

            /// <summary>
            /// **跨进程这条腿画不了字进像素**(控 1-① 的号 78):如实给**假**。
            ///
            /// <para>为什么不做:字形光栅化在**前端**(真窗口 / WPF / Avalonia 那一侧),
            /// 而位图(`位图仓C`)住在**子进程**里 —— 要让它成,得把整块像素按 `图形命令` 帧发过去、
            /// 画完再发回来(协议版本 / 帧大小 / 回执全要跟着改),而那一帧的意义只是"给一张离屏图写字"。
            /// 这一档今天**没有调用方**(程序跑在子进程里时,`贴文字到位图` 直接给"没挂能力")。</para>
            ///
            /// <para>⚠ 如实登记:进程内那条腿(IDE 的 WPF 口 / 独立 exe 的 Avalonia 口)**能用**,
            /// 跨进程这条腿**不能用** —— 与"没挂呈现口"同一个状态码(状态 1),程序侧分不出来,
            /// 所以写进这条注释与 `未做任务清单.md`。</para>
            /// </summary>
            public bool 把文字画进像素(int x, int y, string 文本, uint 字色, int 字号, uint[] 像素, int 宽, int 高) => false;

            /// <summary> 发一条图形命令并等回执;没画成就抛(能力层兜底 catch ⇒ `状态_开不了窗口`) </summary>
            private void 过线(Action<BinaryWriter> 写种类, int 睡毫秒 = 0)
            {
                if (!_后端.过一条图形命令(写种类, 睡毫秒, out string 说明))
                    throw new 图形过线失败C(说明);
            }
        }
    }

    /// <summary>
    /// **H39-3:一条图形命令在前端那一侧没画成**(呈现口抛了 / 前端没挂呈现口 / 等回执超时)。
    ///
    /// 为什么不复用 `跑程序通道错误C`:那是"通道本身出事了"(子进程起不来 / 半路退出),
    /// 前端必须如实说清、界面还要提示重连;这一条只是**这一条绘制命令画不成**——
    /// 通道好好的、程序照跑,能力层(`图形宿主C.处理` 的兜底 catch)把它转成 `状态_开不了窗口` 就够了。
    /// </summary>
    internal sealed class 图形过线失败C(string 说明) : Exception(说明)
    {
    }

    /// <summary>
    /// H39-2:**尾部轨迹环** —— 只留最近 `容量` 条 `(指令地址, 当时的 R15)`。
    ///
    /// 为什么只要"最近这么点":状态帧里带它是为了让前端把**寄存器说明**补回来(见
    /// `寄存器信息管理器C`),而"哪一格现在装着谁的值"只与最近这几步有关;跑到断点一口气跑掉几十万条时,
    /// 前面那些早就被后来的覆盖了 —— 带 512 条与带全部,重放出来的结果一样。
    /// 每条命令开头 `清空()`,于是"取全部()"给的是**这一趟新产生的**(单步 1 条、跑到最多 512 条)。
    /// </summary>
    internal sealed class 轨迹环C(int 容量)
    {
        private readonly (int 地址, uint 帧指针)[] _环 = new (int, uint)[Math.Max(1, 容量)];
        private int _写位置;

        public void 记(int 地址, uint 帧指针) => _环[_写位置++ % _环.Length] = (地址, 帧指针);

        public void 清空() => _写位置 = 0;

        /// <summary> 这一趟记下的那些条(从旧到新;最多一个环的容量) </summary>
        public (int 地址, uint 帧指针)[] 取全部()
        {
            int 条数 = Math.Min(_写位置, _环.Length);
            var 出 = new (int, uint)[条数];
            int 起 = _写位置 - 条数;
            for (int i = 0; i < 条数; i++) 出[i] = _环[(起 + i) % _环.Length];
            return 出;
        }
    }
