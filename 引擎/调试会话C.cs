    /// <summary> 调用链上的一帧(单步叠灰用):调用处落在哪(文件 + 行)、被调的是哪个函数、它在链上算第几层 </summary>
    public sealed class 调用帧C
    {
        /// <summary> 调用处所在文件 </summary>
        public string 文件 = "";
        /// <summary> 调用处行号(1 基) </summary>
        public int 行;
        /// <summary> 被调函数的**尾名**(`棋盘.面积` → `面积`):界面上拿它去那一行里找对应的那段调用 </summary>
        public string 名 = "";
        /// <summary> 在调用链上的层号(1 基,最外层 = 1)。跨文件也算,编译器内部例程不算 </summary>
        public int 层号;
    }

    /// <summary> 单步走一步之后的状态快照(**纯数据**):界面只照它画黄条、灰条、滚过去 </summary>
    public sealed class 调试步进结果C
    {
        /// <summary> 当前 PC(字节地址) </summary>
        public int 程序计数器;
        public bool 已停机;
        public long 已执行步数;
        /// <summary> PC 落在哪个文件的代码段里(null = 不在任何文件的代码段里) </summary>
        public string? 文件;
        /// <summary> 源码第几行(0 = 这一段没有对应源码行,是编译器生成出来的) </summary>
        public int 源码行;
        /// <summary> 汇编单步时编辑器里那一行(0 = 查不到) </summary>
        public int 显示行;
        /// <summary> 该标淡灰的"调用处"行(已经按"当前看的文件"过滤过) </summary>
        public int[] 调用处行 = [];
        /// <summary>
        /// 调用链上的每一帧(从最外层到当前这一层;只含**认得出是用户函数**的那些)——
        /// C15 按层叠灰用。别的文件的帧也在表里(带了文件),界面只画当前文件的那几帧、深度照整条链算。
        /// </summary>
        public List<调用帧C> 调用帧 = [];
        /// <summary> 这一步是不是"调用跳出去" </summary>
        public bool 这一步跳出去;
        /// <summary> 这一步是不是"停在断点上"(运行到断点那个入口才会置) </summary>
        public bool 命中断点;
        /// <summary>
        /// H22:这一趟是不是被**「停止」**打断的(既不是停机、也不是命中断点)——
        /// 界面据此走"已停止"那一支(不做断言、也不当成"跑了步数上限")。
        /// 只按**这一趟**算(取快照时不从虚拟机那个"被打断过"的记号上抄,免得下一步还报已停止)。
        /// </summary>
        public bool 已中断;
        /// <summary> 当前指令的反汇编文本(调试台显示用) </summary>
        public string 指令文本 = "";
        /// <summary> 这一步之后"我能看见的变量各自是多少"(名字/类型/值;结构变量会展开字段) </summary>
        public List<变量读数C> 变量 = [];
        /// <summary> 每个寄存器现在装着什么的说明(下标 = 寄存器编号;没说明的位置是 null) </summary>
        public 寄存器记录C?[] 寄存器说明 = new 寄存器记录C?[寄存器C.数量];
    }

    /// <summary>
    /// 调试会话:把"机器码 + 虚拟机 + 单步状态"整个从窗口里搬出来,做成一个**零界面依赖**的纯对象。
    /// 命令行(`hbcc --debug-steps/--debug-asm`)和自检直接用它驱动;界面只做两件事:
    /// 「按一下按钮 → 调一次会话 → 拿返回的快照去画」。
    ///
    /// 这样"单步映射""调用处记帐"这些容易错的东西都能被自检抓住,不用再靠人眼。
    /// </summary>
    public sealed class 调试会话C
    {
        /// <summary> 正在调试的机器码 </summary>
        public byte[] 机器码 { get; private set; } = [];

        /// <summary>
        /// 真正跑代码的虚拟机(和界面上"执行"用的不是同一个实例)。
        /// **H39-2 起可换**:界面可以把它换成"跑在子进程里"的那一台(`跨进程虚拟机C`)——
        /// 这一整个类(单步 / 走到断点 / 变量 / 寄存器说明)对它毫无察觉,因为记账那两样
        /// (调用栈 / 寄存器说明)要么自己记、要么从那一侧整份收回来(见 `走一条`)。
        /// </summary>
        public 虚拟机C 虚拟机 { get; set; } = new();

        public long 已执行步数 { get; private set; }

        public bool 已停机 => 机器码.Length == 0 || 虚拟机.已结束;

        public bool 有机器码 => 机器码.Length > 0;

        /// <summary> true = 汇编单步(按指令走);false = 语言单步(按行走)。只影响快照里用哪张表换算行号 </summary>
        public bool 汇编模式 { get; set; } = true;

        /// <summary> 每个文件一段调试信息(编译时建好;见 执行行映射C.建全表) </summary>
        public List<文件映射C> 调试文件表 { get; set; } = [];

        /// <summary> 界面上正在看的那个文件(算"显示行""调用处灰条"时只认它,不然会标到别的文件的行号上) </summary>
        public string? 当前文件 { get; set; }

        /// <summary> 调用处记帐(跳走了记着,回来了撤掉) </summary>
        public 调用栈标记C 调用栈 { get; } = new();

        /// <summary> 断点落在哪些机器码地址上(编译后由 断点表C.算地址() 填) </summary>
        public HashSet<int> 断点地址 { get; set; } = [];

        /// <summary> 现在是不是"停在断点上等着"(再点执行/继续就从这儿接着跑,不该重新装载) </summary>
        public bool 已暂停在断点 { get; private set; }

        /// <summary> 汇编器的标签表(标签名 → 字节地址):全局变量槽靠它定位,再配上名字表就能显示"变量 初值 = 65" </summary>
        public Dictionary<string, int> 标签表
        {
            get => _标签表;
            set { _标签表 = value ?? []; _标签反查 = null; }
        }

        private Dictionary<string, int> _标签表 = [];
        private Dictionary<int, string>? _标签反查;

        /// <summary>
        /// H100 第二步:运行期那几个**账本槽**的绝对地址(角色 → 地址:`池指针` / `池末` / `堆首` / `堆末` /
        /// `空闲表头` / `软栈`)—— 与 `标签表` **同一次编译**出来的(见 `汇编调试结果C.内部槽地址`);
        /// 运行监视拿它 + 镜像内存算"池 / 堆 / 软栈各用了多少"(口径见 `引擎\内存用量C.cs`)。
        /// </summary>
        public Dictionary<string, int> 内部槽地址 { get; set; } = new(StringComparer.Ordinal);

        /// <summary> 这台调试虚拟机开多大内存(默认 1 MB;工程文件写了 `内存` 就按工程来);装载时生效 </summary>
        public int 内存大小 { get; set; } = 虚拟机C.默认内存大小;

        /// <summary> 寄存器信息管理器:每走一步记一笔账,面板上就能说清"这一格现在装的是谁的值" </summary>
        public 寄存器信息管理器C 寄存器说明 { get; } = new();

        /// <summary>
        /// **条件断点的接口(C4 第121批已接)**:断点命中时问一句,返回 false = 这次不算命中、继续跑。
        /// 条件怎么算在 `引擎\断点条件C.cs`(`变量 运算符 常量`;判不了就返回 null + 一句说明,绝不猜);
        /// 界面在 `MainWindow.调试与断点.cs` 里把它挂上,这里只留这一个口子,别的地方不用动。
        /// </summary>
        public Func<int, bool>? 断点命中判断 { get; set; }

        /// <summary> 这个地址算不算命中(在断点集合里,且条件判断放行) </summary>
        public bool 命中断点(int 地址) =>
            断点地址.Contains(地址) && (断点命中判断?.Invoke(地址) ?? true);

        /// <summary> 界面正在看的那个文件的调试段(不在工程里就返回 null) </summary>
        public 文件映射C? 当前文件段 =>
            string.IsNullOrWhiteSpace(当前文件)
                ? null
                : 调试文件表.FirstOrDefault(段 => string.Equals(段.文件, 当前文件, StringComparison.OrdinalIgnoreCase));

        /// <summary> 装机器码并复位:步数清零、调用栈清空 </summary>
        public void 装载(byte[] 机器码)
        {
            this.机器码 = 机器码 ?? [];
            虚拟机.设内存大小(内存大小);      // 工程文件里的 `内存` 在这里生效(不合法会抛出明确错误)
            // 运行期错误(除零/栈溢出)带行号:用调试那张"地址 → 源码行"表 —— 和单步黄条同一份数据
            虚拟机.取源行号 = 地址 => 执行行映射C.查源行(调试文件表, 地址);
            // H65:同一个地址也挂一份"给人看的位置串" —— 多文件程序报 `工具.hb 第 3 行`
            // (单文件程序照旧只报 `第 3 行`;判据与独立 exe / 跨进程那条腿同源,见 `执行行映射C.查位置`)
            虚拟机.取源位置 = 地址 => 执行行映射C.查位置(调试文件表, 地址);
            // H39-2:调试那条腿要"账"(调用栈 + 尾部轨迹)—— 子进程那台随状态帧带回来,进程内这台自己记
            虚拟机.要记账 = true;
            虚拟机.装载(this.机器码);
            已执行步数 = 0;
            已暂停在断点 = false;
            调用栈.清空();
            虚拟机.上次记账 = null;
            寄存器说明.标签表 = 标签表;
            寄存器说明.名字表 = 调试文件表.FirstOrDefault()?.名字表;
            寄存器说明.清空();
            _上次段 = null;
            _上次行 = 0;
            _待报行 = 0;
        }

        // 变量面板的"记忆":编译器生成的指令没有源码行,这时候沿用上一次有源码行的位置,
        // 免得走到序言/收尾那几步时,变量列表闪一下空。
        private 文件映射C? _上次段;
        private int _上次行;

        /// <summary>
        /// C14:下一次 `语言走一行()` 要先报的那一行(0 = 没有)。
        /// 进函数报 `{` 那一行、出函数报 `}` 那一行时,顺手把"本该报的函数体第一行 / 调用方那一行"记在这儿 ——
        /// 这样既不丢行、又不用让 PC 真的停在 `{` / `}` 上(它们没有指令)。
        /// </summary>
        private int _待报行;

        /// <summary> 整个清空(没有可调试的东西了) </summary>
        public void 清空()
        {
            机器码 = [];
            已执行步数 = 0;
            调试文件表 = [];
            当前文件 = null;
            断点地址 = [];
            已暂停在断点 = false;
            调用栈.清空();
            标签表 = [];
            寄存器说明.名字表 = null;
            寄存器说明.清空();
            _上次段 = null;
            _上次行 = 0;
            _待报行 = 0;
        }

        // ---------------- 三种走法:都返回"走完之后的快照" ----------------

        /// <summary> 汇编单步:走一条指令(行号按**展开文本行号**给;CLI 的 `--debug-asm` 用它) </summary>
        public 调试步进结果C 汇编单步一次()
        {
            汇编模式 = true;
            bool 跳出去 = 走一条();
            return 取快照(跳出去);
        }

        /// <summary>
        /// 逐步(第158批把原「逐汇编 / 逐语句」合并成一档;第160批按用户实测**定了粒度**):
        /// **一下一步 = 一条源码行**。
        ///
        /// 为什么不是"一条机器指令一步"(第158批原本那么写的):编辑器不再换成展开汇编,
        /// 所以"走了几条指令"在界面上**看不见**。用户实测:「逐步」按下去底部面板出来了、但看着没往前走 ——
        /// 量出来是这个原因:程序开头一大段是**编译器生成**的指令(顶层字符串 / 列表初值那些),
        /// 示例 61 要走到**第 95 条指令**才落到 `主程序.hb` 第 11 行 ⇒ 按一条指令一步得按 95 下才看见黄条动。
        /// 所以这里直接走**源码行**那一档(`取位置` 变了才停,见 `语言走一行`):编译器生成的序言 / 收尾 /
        /// 函数出入口一口气跑过,进 / 出函数仍按 C14 在 `{` / `}` 上停一行。
        /// 想看"一条机器指令一步"的老路照旧在:CLI `--debug-asm`(`汇编单步一次()`)。
        /// </summary>
        public 调试步进结果C 逐步一次()
        {
            汇编模式 = false;
            return 语言走一行();
        }

        /// <summary>
        /// 语言单步:按"行"走 —— 同一行展开出来的多条指令一次走完,直到源码位置真的变了(或停机)。
        /// 这样一次点击就前进一行,不会"点很多下才动一下"。
        ///
        /// **C14(2026-09-19 用户拍板)**:进函数那一步黄条先落在 `{` 那一行、出函数落在 `}` 那一行。
        /// `{` / `}` 本身**没有指令**,所以这里给"进/出一个函数"各补一个**不推进 PC 的停点**:
        /// 进函数时先报 `{` 行,把"接下来该报的函数体第一行"记进 `_待报行`;下一次调用再把那一行报出来。
        /// 进出靠**调用栈深度**判(进了会多一层、出了会少一层),不靠"上一条是不是 调用"——
        /// 函数序言有好几条指令,等落到函数体第一行时"上一条是 调用"早就不成立了。
        /// 只对**函数**这么做:`如果` / `当` / `自成一段` 这些块不额外停一步(拍板第 ② 条)。
        /// 逐汇编那一档一个字都不动(拍板第 ① 条:`{` / `}` 没有对应指令)。
        /// </summary>
        public 调试步进结果C 语言走一行()
        {
            汇编模式 = false;
            if (_待报行 > 0)                        // 上一步是"进/出函数":这一步把 `{` / `}` 那一行报出来
            {
                int 该报 = _待报行;
                _待报行 = 0;
                var 补 = 取快照();
                补.源码行 = 该报;                    // 只改黄条落在哪一行,PC 一动不动(下一次才真正往下走)
                return 补;
            }
            int 起点PC = (int)虚拟机.程序计数器;
            var 起点 = 取位置(起点PC);
            string? 起函数 = 段里函数(找段(起点PC), 起点?.行 ?? 0);
            int 起层数 = 调用栈.调用处地址.Count;
            const int 上限 = 100_000;
            int 走了 = 0;
            bool 跳出 = false;
            while (!已停机 && 走了 < 上限)
            {
                跳出 |= 走一条();
                走了++;
                int 现在PC = (int)虚拟机.程序计数器;
                var 现在 = 取位置(现在PC);
                if (现在 == null || 现在 == 起点) continue;      // 停到"新的、有源码行的那一步"才算换行
                int 现在行 = 现在.Value.行;
                // C14:这一步跨了函数边界(多一层 = 进去了,少一层 = 出来了)就多停一行
                int 现在层数 = 调用栈.调用处地址.Count;
                if (现在层数 != 起层数)
                {
                    int 停行 = 0;
                    if (现在层数 > 起层数)
                    {
                        string? 新函数 = 段里函数(找段(现在PC), 现在行);
                        if (!string.Equals(起函数, 新函数, StringComparison.Ordinal))
                            停行 = 找段(现在PC)?.名字表.花括号行(新函数)?.左行 ?? 0;
                    }
                    else
                    {
                        停行 = 找段(起点PC)?.名字表.花括号行(起函数)?.右行 ?? 0;
                    }
                    if (停行 > 0)
                    {
                        _待报行 = 现在行;
                        var 快 = 取快照(跳出);
                        快.源码行 = 停行;
                        return 快;
                    }
                }
                break;
            }
            return 取快照(跳出);
        }

        /// <summary>
        /// **运行到断点**(没断点就是跑到停机):一直走,走到断点上停下、或者停机、或者到步数上限。
        ///
        /// 关键一步:先"离开当前这一条"再判断,否则刚停下的那个断点会立刻又命中(原地打转)。
        /// 这里**不能只看步数** —— 停在"程序第一条语句"的断点上时,已执行步数还是 0(一条都还没走),
        /// 只看步数就不会往前迈,于是再点执行永远停在原地(用户实测:"F5 只到第一个断点,然后再点没反应")。
        /// 所以用 `已暂停在断点` 来判断"我现在正踩在一个断点上"。
        ///
        /// **H39-2 改法**:那"一口气跑掉几十万条"的一段交给 `虚拟机C.跑到(断点地址表, 上限)` ——
        /// 进程内那台就是原来那一圈(一个字节没改),子进程那台变成**一条命令**。
        /// 循环口径与老那条**逐条**循环一致:每命中一个候选地址就问一次条件(条件求值留在前端,
        /// 它要用前端那份名字表);条件为假就踏过这一条、再接着跑。
        /// 记账(调用栈 / 寄存器说明)在这一趟结束时从那一侧整份收回来(见 `收后端账`)。
        /// </summary>
        public 调试步进结果C 运行到断点(long 上限 = 5_000_000)
        {
            bool 跳出 = false;
            bool 这趟被停 = false;
            if (已执行步数 > 0 || 已暂停在断点) 跳出 |= 走一条();   // 从"停着的那一条"往下走一条
            var 断点们 = new List<int>(断点地址);
            while (!已停机 && 已执行步数 < 上限)
            {
                int 现在 = (int)虚拟机.程序计数器;
                if (断点地址.Count > 0 && 断点地址.Contains(现在))
                {
                    if (问命中(现在)) break;                 // 条件成立(或没条件):就停在这儿
                    跳出 |= 走一条();                          // 条件不成立:踏过这一条,接着跑
                    continue;
                }
                // 一次过线:跑到"表里任一地址 / 停机 / 被叫停 / 在等输入 / 步数到顶"为止
                long 前条数 = 虚拟机.已执行条数;
                var 原因 = 虚拟机.跑到(断点们, 上限 - 已执行步数);
                已执行步数 += 虚拟机.已执行条数 - 前条数;
                if (虚拟机.上次记账 is { } 账) 收后端账(账);
                if (原因 == 虚拟机C.停下原因C.被中断) { 这趟被停 = true; break; }
                if (原因 == 虚拟机C.停下原因C.在等输入) break;
                if (原因 == 虚拟机C.停下原因C.步数上限) break;
                // 其余落点(停机 / 命中断点 / 程序里那条 `断点` 指令)回到循环头再看一眼:
                // 停机那条由 `while` 条件收口,命中断点那条由上面那一格问条件
            }
            var 结果 = 取快照(跳出);
            结果.已中断 = 这趟被停;
            // 命中来源有两种:①IDE 设的断点(地址集合)②程序里的 `断点` 指令(P14:虚拟机自己停下并标记,取快照时已经带上)
            结果.命中断点 = 结果.命中断点 || (!结果.已停机 && 问命中(结果.程序计数器));
            已暂停在断点 = 结果.命中断点;
            return 结果;
        }

        /// <summary>
        /// 问一句"这个地址算不算命中"。
        /// **条件要读变量 ⇒ 先把内存镜像要过来**(跨进程那台;进程内是空操作)——
        /// 不这么做,条件断点会拿着"跑到之前那一刻"的内存去判,判出来的结论是假的。
        /// </summary>
        private bool 问命中(int 地址)
        {
            if (断点地址.Contains(地址) && 断点命中判断 != null) 虚拟机.同步镜像();
            return 命中断点(地址);
        }

        /// <summary> 继续:和"运行到断点"同一件事(有断点就停在断点,没断点就跑到停机) </summary>
        public 调试步进结果C 继续(long 上限 = 5_000_000) => 运行到断点(上限);

        /// <summary> 走一条指令,并顺手记调用处(跳出去=记,回到调用处下一条=撤) </summary>
        private bool 走一条()
        {
            if (已停机) return false;
            int 旧PC = (int)虚拟机.程序计数器;
            bool 是调用 = 虚拟机C.是调用指令(机器码, 旧PC);
            虚拟机.单步();
            已执行步数++;
            int 新PC = (int)虚拟机.程序计数器;
            // H39-2:账记在**真正执行的那一侧**。子进程那台把调用栈两张表与尾部轨迹随状态帧带回来,
            // 这一侧整份复原 + 逐条重放(名字表 / 机器码都是这一份 ⇒ 与进程内那条路同源同口径);
            // 进程内这台 `上次记账` 恒为 null,照旧自己一条一条记。
            if (虚拟机.上次记账 is { } 账) 收后端账(账);
            else { 记寄存器(旧PC); 调用栈.记一步(旧PC, 新PC, 是调用); }
            return 是调用 && 新PC != 旧PC + 4;
        }

        /// <summary>
        /// H39-2:把"跑程序那一侧"带回来的账摊进这一侧 ——
        /// ① 调用栈两张表**整份复原**(那一侧一直在记,口径与 `走一条` 里那两句完全一样);
        /// ② 尾部轨迹**逐条重放**进寄存器说明(每一条都用**它自己那一刻的帧指针**,
        ///    换过帧的旧账才不会记错;行号查法与进程内那句一字不差)。
        /// </summary>
        private void 收后端账(跑程序协议C.跑程序记账C 账)
        {
            调用栈.复原(账.调用处, 账.被调);
            foreach (var (地址, 帧指针) in 账.轨迹) 记寄存器(地址, 帧指针);
        }

        /// <summary> 把"这一步写到哪个寄存器、写进去的是谁的值"记进寄存器管理器(纯登记,不改任何东西) </summary>
        private void 记寄存器(int 指令地址) => 记寄存器(指令地址, 虚拟机.寄存器[寄存器C.帧指针号]);

        /// <summary>
        /// 同上,但帧指针由调用方给(H39-2:重放尾部轨迹时用**当时**的 R15)。
        /// 行号口径:这条指令自己查得到源码行就用它,查不到沿用"上一次有源码行的那一行"(与老代码一致)。
        /// </summary>
        private void 记寄存器(int 指令地址, uint 帧指针)
        {
            var 段 = 找段(指令地址);
            寄存器说明.标签表 = 标签表;
            寄存器说明.名字表 = 段?.名字表;
            int 行 = 段 != null && 段.地址到源行.TryGetValue(指令地址, out int n) ? n : _上次行;
            寄存器说明.登记(指令地址, 机器码, 帧指针, 行);
        }

