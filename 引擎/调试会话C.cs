        /// <summary> 当前状态(不往前走) </summary>
        public 调试步进结果C 取快照(bool 这一步跳出去 = false)
        {
            // H39-2:变量面板要读内存 ⇒ 先把内存镜像要过来(跨进程那台;进程内是空操作)。
            // 一次 ~30 微秒(量出来的),够"人按 F10 无感"。
            虚拟机.同步镜像();
            var 结果 = new 调试步进结果C
            {
                程序计数器 = (int)虚拟机.程序计数器,
                已停机 = 已停机,
                命中断点 = 虚拟机.命中断点,        // P14:程序里写了 `断点` 指令 → 虚拟机自己停下并标记
                已执行步数 = 已执行步数,
                这一步跳出去 = 这一步跳出去,
            };
            var 段 = 找段(结果.程序计数器);
            结果.文件 = 段?.文件;
            if (段 != null)
            {
                // 表里的键就是绝对地址(第93批),直接用 PC 查
                if (段.地址到源行.TryGetValue(结果.程序计数器, out int 行)) 结果.源码行 = 行;
                if (段.地址到显示行.TryGetValue(结果.程序计数器, out int 展开行)) 结果.显示行 = 展开行;
            }

            // 变量面板:停在这一行能看见哪些变量、各自现在是多少(编译器生成的步骤沿用上一次的位置)
            if (结果.源码行 > 0 && 段 != null) { _上次段 = 段; _上次行 = 结果.源码行; }
            var 变量段 = 段 ?? _上次段;
            int 变量行 = 结果.源码行 > 0 ? 结果.源码行 : _上次行;
            if (变量段 != null && 变量行 > 0)
                结果.变量 = 变量读取C.取可见变量(变量段.名字表, 标签表, 虚拟机.内存, 虚拟机.寄存器[15], 变量行);

            // 寄存器说明:照最新那笔账给每个寄存器配一句说明
            Array.Copy(寄存器说明.全部, 结果.寄存器说明, 结果.寄存器说明.Length);

            // 调用处灰条:只给"界面上正在看的那个文件"里显示得出来的行
            var 行表 = new List<int>();
            foreach (int 地址 in 调用栈.调用处地址)
            {
                var 调用段 = 找段(地址);
                if (调用段 == null) continue;
                if (!string.IsNullOrWhiteSpace(当前文件) &&
                    !string.Equals(调用段.文件, 当前文件, StringComparison.OrdinalIgnoreCase)) continue;
                int 行 = 汇编模式
                    ? (调用段.地址到显示行.TryGetValue(地址, out int 展开行) ? 展开行 : 0)
                    : (调用段.地址到源行.TryGetValue(地址, out int 源码行) ? 源码行 : 0);
                if (行 > 0 && !行表.Contains(行)) 行表.Add(行);
            }
            结果.调用处行 = [.. 行表];

            // C15:调用链上的每一帧(含别的文件的),给界面"按层叠灰"用。层号只数**认得出的用户函数**:
            // 编译器内部例程(打印串 / 池与列表扩容那些 `_f…`)不算一层,否则"第几层"会被它们搅乱。
            var 帧表 = new List<调用帧C>();
            int 层 = 0;
            for (int i = 0; i < 调用栈.调用处地址.Count; i++)
            {
                int 地址 = 调用栈.调用处地址[i];
                var 调用段 = 找段(地址);
                if (调用段 == null) continue;
                int 行 = 汇编模式
                    ? (调用段.地址到显示行.TryGetValue(地址, out int 展开行) ? 展开行 : 0)
                    : (调用段.地址到源行.TryGetValue(地址, out int 源码行) ? 源码行 : 0);
                if (行 <= 0) continue;
                int 被调 = i < 调用栈.被调地址.Count ? 调用栈.被调地址[i] : 0;
                string 名 = 被调名(被调);
                if (名.Length == 0) continue;
                帧表.Add(new 调用帧C { 文件 = 调用段.文件, 行 = 行, 名 = 名, 层号 = ++层 });
            }
            结果.调用帧 = 帧表;

            try { 结果.指令文本 = 反汇编C.反汇编一条(机器码, (uint)结果.程序计数器, out _) ?? ""; }
            catch { 结果.指令文本 = ""; }
            return 结果;
        }

        /// <summary> 某个地址落在哪个函数里(查不到返回 null:编译器生成的代码、或者名字表里没有这个位置) </summary>
        private static string? 段里函数(文件映射C? 段, int 行) =>
            段 == null || 行 <= 0 ? null : 段.名字表.行所属函数(行);

        /// <summary>
        /// 被调方入口地址 → 它在源码里叫什么(`棋盘.面积` 的**尾名** `面积`)。
        /// 只认得出**用户函数**:按"函数边界里的定义名把点换成下划线"去对汇编标签,对不上就返回空
        /// (编译器内部例程 `_f打印串1` 这类就是这种情况 —— 它们不该被算成一层调用)。
        /// </summary>
        private string 被调名(int 被调地址)
        {
            if (被调地址 <= 0 || _标签表.Count == 0) return "";
            _标签反查 ??= 建标签反查();
            if (!_标签反查.TryGetValue(被调地址, out string? 标签) || string.IsNullOrEmpty(标签)) return "";
            var 段 = 找段(被调地址);
            if (段 != null)
                foreach (var (函数, _, _, _) in 段.名字表.函数边界)
                    if (string.Equals(函数.Replace('.', '_'), 标签, StringComparison.Ordinal)) return 尾名(函数);
            return "";
        }

        private Dictionary<int, string> 建标签反查()
        {
            var 反查 = new Dictionary<int, string>(_标签表.Count);
            foreach (var (名, 址) in _标签表) 反查.TryAdd(址, 名);
            return 反查;
        }

        /// <summary> 名字的最后一段(`棋盘.面积` → `面积`;没有点就是它自己) </summary>
        private static string 尾名(string 名)
        {
            int 点 = 名.LastIndexOf('.');
            return 点 >= 0 && 点 + 1 < 名.Length ? 名[(点 + 1)..] : 名;
        }

        /// <summary> PC → (文件, 源码行)。查不到返回 null:那一段是编译器生成的代码(序言/收尾之类),没有对应源码行 </summary>
        public (string 文件, int 行)? 取位置(int 地址)
        {
            var 段 = 找段(地址);
            if (段 == null) return null;
            return 段.地址到源行.TryGetValue(地址, out int 行) ? (段.文件, 行) : null;
        }

        private 文件映射C? 找段(int 地址) => 调试文件表.FirstOrDefault(段 => 段.含地址(地址));
    }
