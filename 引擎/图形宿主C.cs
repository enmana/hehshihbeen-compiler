    ///
    /// 「一条命令」= 画什么 + 几个整数 + 一段文字 + 一个颜色;`刷新` 那条只是帧边界,不进这个类型
    /// (它是 `刷新 命令=N` 那一行,由 `图形呈现口C.呈现` 收到整批时打)。
    /// </summary>
    public sealed class 绘制命令C
    {
        /// <summary> 动作名:`清屏` / `画文字` / `画矩形` / `画线`(=`图形宿主C` 里那几条原语的中文名) </summary>
        public string 动作 { get; set; } = "";

        public int x { get; set; }
        public int y { get; set; }
        public int 宽 { get; set; }
        public int 高 { get; set; }
        public int x2 { get; set; }
        public int y2 { get; set; }
        public string 文本 { get; set; } = "";
        public uint 颜色 { get; set; }

        /// <summary>
        /// **贴位图那一条专用**:要贴上去的那块像素(行优先、`0xAARRGGBB`、紧排)。
        ///
        /// 为什么是**快照**而不是句柄:命令表要能跨进程送给另开的那台虚拟机跑
        /// (`跑程序协议C` 把整批命令序列化过去),句柄在那一侧没有意义;
        /// 而"一次贴一整块"的判据本来就是**字节**,不是句柄。
        /// ⚠ 只有 `动作 = "贴位图"` 这一条会带它(别的条一律 null)。
        /// </summary>
        public uint[]? 像素 { get; set; }

        /// <summary>
        /// **命令的文本形态**(无头呈现 / 自检 / 命令行都吃这一行)。
        ///
        /// 只有这一处是格式的事实源:改格式就改这里,`无头呈现C` 与自检逐字口径一起动。
        /// 文字一律加引号(里面有空格也一眼看得出边界),`\\` 与 `"` 反斜杠转义。
        /// 颜色按 8 位十六进制打(`0xFF2A6EF0`),与 HB 源码里的写法一致。
        /// </summary>
        public string 一句话() => 动作 switch
        {
            "清屏" => $"清屏 颜色=0x{颜色:X8}",
            "画文字" => $"画文字 x={x} y={y} 文本={带引号(文本)} 颜色=0x{颜色:X8}",
            "画矩形" => $"画矩形 x={x} y={y} 宽={宽} 高={高} 颜色=0x{颜色:X8}",
            "画线" => $"画线 x1={x} y1={y} x2={x2} y2={y2} 颜色=0x{颜色:X8}",
            // R4-12:**贴位图**那一行只报"贴了多大一块",**不把像素倒出来**
            //   —— 一块 480×520 的图有 249,600 个数,打进文字里既没用又淹没输出。
            "贴位图" => $"贴位图 x={x} y={y} 宽={宽} 高={高}",
            _ => 动作,
        };

        /// <summary> 把一段文字包成 `"…"`(反斜杠与引号转义),给 `一句话()` 用 </summary>
        public static string 带引号(string 文本) =>
            "\"" + 文本.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        /// <summary>
        /// 深拷贝一帧里的这一条(两个呈现口跨界之前都要拷一份 —— 能力层那张表是真源,界面侧不许碰它)。
        ///
        /// ⚠ **像素也要真拷**(控 1-⑥,2026-10-11 第414批):这个方法是照着字段序列手写的,
        /// 而 `像素` 是后加的字段 —— 漏掉它的话,`贴位图` 那条命令**过一道拷贝就变成一张空图**:
        /// 两个呈现口(IDE 的 WPF 画布 / 独立 exe 的 Avalonia 画布)拿到的 `像素` 是 `null`,
        /// 于是"命令攒进了窗口队列、`一句话()` 也打得出那一行,**真窗口上一个像素都不出**"。
        /// 症状与"没写 `case \"贴位图\"`"**一模一样**,查的时候要一起看这两处。
        /// </summary>
        public 绘制命令C 复制() => new()
        {
            动作 = 动作, x = x, y = y, 宽 = 宽, 高 = 高, x2 = x2, y2 = y2, 文本 = 文本, 颜色 = 颜色,
            像素 = 像素?.Clone() as uint[],
        };
    }

    /// <summary>
    /// **一块位图像素的字节摆法**(控 1-⑥):`0xAARRGGBB` 的 `uint[]` ⇒ `B,G,R,A` 的字节序。
    ///
    /// <para>这是**三条腿共用的那一份口径**,别再各写各的:</para>
    /// · C 后端(`C后端\运行时.c` 的 `hb_win_贴位图`)把 `uint[]` **原样**交给 `SetDIBitsToDevice` ——
    ///   32 位 `BI_RGB` 的 DIB 在内存里就是 `B,G,R,A`,与 `0xAARRGGBB` 那个整数**同序**;
    /// · WPF 画布用 `PixelFormats.Pbgra32`(字节序同样是 `B,G,R,A`);
    /// · Avalonia 画布用 `PixelFormat.Bgra8888` + `AlphaFormat.Premul`。
    ///
    /// <para>⇒ 三个口喂进渲染后端的**字节逐字节一样**:"位图贴到窗口上"这件事在
    /// `C后端图形窗口` 那一组能用 `GetPixel` 读回来对,在这里也就有了一份可对照的口径。</para>
    ///
    /// <para>**为什么放在引擎这一层**:它只谈字节,**不碰任何一种 UI 框架** —— 引擎库是 `net10.0`
    /// (没有 WPF / Avalonia / `System.Drawing`),框架相关的部分一个字节都不许长在这里。
    /// 呈现口那边只做"把这块字节喂给自己那套位图类型"。</para>
    /// </summary>
    public static class 位图字节C
    {
        /// <summary> 一个像素 4 个字节(`B,G,R,A`)</summary>
        public const int 每像素字节数 = 4;

        /// <summary> 第 `i` 个像素在字节数组里的起点(凸出来只为让两条腿按**同一个偏移式**走)</summary>
        public static int 偏移(int i) => i * 每像素字节数;

        /// <summary> 把 `[起, 起+个数)` 这些像素铺进 `目标`(每像素 4 字节,`B,G,R,A`);不够长就抛</summary>
        public static void 铺进(byte[] 目标, int 起, uint[] 像素, int 个数)
        {
            if (像素 == null) throw new ArgumentNullException(nameof(像素));
            if (个数 < 0 || 起 < 0 || 起 + 个数 > 像素.Length || 偏移(起 + 个数) > 目标.Length)
                throw new ArgumentOutOfRangeException(nameof(个数), $"像素区间 [{起}, {起 + 个数}) 越界(像素 {像素.Length} 格 / 目标 {目标.Length} 字节)");
            for (int i = 0; i < 个数; i++)
            {
                uint 值 = 像素[起 + i];
                int 落 = 偏移(i);
                目标[落] = (byte)(值 >> 16);            // B
                目标[落 + 1] = (byte)(值 >> 8);         // G
                目标[落 + 2] = (byte)值;                // R
                目标[落 + 3] = (byte)(值 >> 24);        // A
            }
        }

        /// <summary> 一整块(建一份新数组;自检与"按帧复用"那两条路共用同一份口径)</summary>
        public static byte[] 整块(uint[] 像素)
        {
            var 出 = new byte[偏移(像素.Length)];
            铺进(出, 0, 像素, 像素.Length);
            return 出;
        }
    }

    /// <summary>
    /// **呈现接口**:能力层只管"攒命令 + 收事件",真画在哪儿由这一个口子决定。
    ///
    /// 批 1 有三个实现:`无头呈现C`(逐条 dump,自检与命令行走它)、桌面壳 `图形宿主\桌面壳C`
    /// (Avalonia,真窗口)、批 5 才有的手机端。
    /// **没挂口子 = 没这个能力**(与 `可执行白名单 == null` 同一套口径,见 `宿主能力C`)。
    /// </summary>
    public interface 图形呈现口C
    {
        /// <summary> 开一个窗口(批 1 只认一个窗口)。抛异常 = 开不出来(能力层会转成状态码,不让程序崩) </summary>
        void 打开窗口(string 标题, int 宽, int 高);

        /// <summary> 关掉窗口,程序继续跑(不结束进程) </summary>
        void 关闭窗口();

        /// <summary>
        /// 提交一帧:这一批命令按顺序画上去。命令表是**只读快照**,呈现口不该改它。
        ///
        /// **空的一帧(0 条命令)不是"把屏擦空"**(第236批 H40):干净的一帧照样要 `刷新()`
        /// (帧节拍挂在刷新上),只是这一帧没有新画面 —— 真窗口那两个口这时**原样留着上一帧**
        /// (动一下画布就把上一帧擦成黑底);无头呈现照旧打 `刷新 命令=0`(示例的预期输出对的就是那一行)。
        /// </summary>
        void 呈现(IReadOnlyList<绘制命令C> 命令);

        /// <summary> 让出一帧(毫秒)。无头呈现**不真睡**(自检要确定、要快),桌面壳睡 </summary>
        void 等待(int 毫秒);

        /// <summary>
        /// **把一段文字画进一块像素**(控 1-①,号 78 —— `贴文字到位图`)。
        ///
        /// <para>**为什么要有这一口**:引擎库的目标框架是 `net10.0` —— 没有 WPF、没有 Avalonia、
        /// 没有 `System.Drawing`,**引擎里没有任何字体光栅化能力**;而 `画文字` 只把文本攒进
        /// **窗口**那条命令队列,一个像素都不落。位图要的是像素(`取图像素` 要进寄存器)
        /// ⇒ "字从哪儿来"只能问平台要(拍板 A)。</para>
        ///
        /// <para>**契约(两边都按这几条实现,谁改谁负责对齐)**:</para>
        /// <list type="number">
        /// <item><description>`像素` 是 `0xAARRGGBB`、**行优先、紧排**、长 `宽 × 高` 的那一块;
        /// 呈现口把**字形覆盖到的像素**写进去(**整块盖掉**,含 alpha —— 与"画上去"同义)。</description></item>
        /// <item><description>**只许写 `[0, 宽×高)` 这一段**(界外一个字都不许碰):裁剪就靠这一条 ——
        /// 文字超出这块图时,超出的部分自然落不进来,不必另立"裁剪区"。</description></item>
        /// <item><description>(x, y) 是**这块图内部**的落点(不是窗口坐标;调用方已经把它减过了)。</description></item>
        /// <item><description>字形画不出来 / 这个呈现口没有字(无头就是这一档)⇒ 返回 **假**,
        /// **不许动 `像素` 一个格子** —— 调用方据此如实给状态,而不是"悄悄画了一块空白"。</description></item>
        /// </list>
        ///
        /// <para>⚠ **字体栈不保证跨口一致**:C# 那两个口(WPF / Avalonia)各有各的字体栈,
        /// 同一行字的光栅化结果**不保证逐字节相同** ⇒ 跨腿判据对"文字像素"只能做到
        /// **形状级**(同位置同色 / 覆盖率),这一条是拍板 A 明确接受的降档(写进台账)。</para>
        /// </summary>
        /// <returns>真 = 真画进去了(像素被改过);假 = 这个口画不了字(像素一个格子都没动)</returns>
        bool 把文字画进像素(int x, int y, string 文本, uint 颜色, int 字号, uint[] 像素, int 宽, int 高);
    }

