    /// <summary>
    /// **无头呈现**:把每一条绘制命令按同一份格式**逐条打出来**,不开窗口。
    ///
    /// 这是"不开窗也能验"的前提(硬规矩 6):自检与 `hbcc --run` 都走它,`示例14_图形界面`
    /// 那句 `// 预期输出:` 对的就是这些行。
    /// </summary>
    public sealed class 无头呈现C : 图形呈现口C
    {
        private readonly TextWriter _出;

        public 无头呈现C(TextWriter 出) => _出 = 出;

        public void 打开窗口(string 标题, int 宽, int 高) =>
            _出.WriteLine($"打开窗口 标题={绘制命令C.带引号(标题)} 宽={宽} 高={高}");

        public void 关闭窗口() => _出.WriteLine("关闭窗口");

        public void 呈现(IReadOnlyList<绘制命令C> 命令)
        {
            foreach (var 条 in 命令) _出.WriteLine(条.一句话());
            _出.WriteLine($"刷新 命令={命令.Count}");
        }

        public void 等待(int 毫秒) { }      // 无头不睡:自检要的是确定与快,不是真等

        /// <summary>
        /// **无头这一档画不了字**(控 1-①):这是**如实**的边界,不是没做 ——
        /// 无头呈现的意义正是"**不开窗、不落像素**,把命令逐条打成文本",而画字要光栅化器。
        /// ⇒ 返回 **假**,一个格子都不动;调用方(`处理贴文字到位图`)据此给状态码。
        /// </summary>
        public bool 把文字画进像素(int x, int y, string 文本, uint 颜色, int 字号, uint[] 像素, int 宽, int 高) => false;
    }

