        /// <summary> 挂着的事件脚本(**null = 没有脚本**:事件只能由宿主真投,比如桌面壳的键盘 / 鼠标)</summary>
        public static 事件脚本C? 事件脚本 { get { lock (_锁) return _脚本; } }

        /// <summary> 已经 `刷新` 过几帧(= 当前在第几帧)。脚本的"第 k 帧"就按它算 </summary>
        public static int 已呈现帧数 { get { lock (_锁) return _已呈现帧数; } }

        /// <summary>
        /// 挂上一份事件脚本(null = 摘掉)。**只在"确定性测试"这条路用**:
        /// 自检、`hbcc --事件脚本`,以及桌面上想看固定输入的人。挂上之后:
        /// ① `打开窗口` = 第 0 帧开始 ⇒ 投脚本里 `帧 0` 的事件;
        /// ② 每 `刷新` 一次提交一帧、进下一帧 ⇒ 投那一帧的事件;
        /// ③ 第 `帧数` 帧开始时投**一个「关窗请求」**(程序该在这一帧之后收手);
        /// ④ 再往后还刷 `帧数宽限` 帧 ⇒ 报带行号的运行期错误(见 `处理刷新`)。
        /// </summary>
        public static void 挂事件脚本(事件脚本C? 脚本)
        {
            lock (_锁)
            {
                _脚本 = 脚本;
                _已呈现帧数 = 0;
                _关窗请求投过 = false;
            }
        }

        /// <summary>
        /// 进入第 `帧号` 帧:把脚本里排在这一帧的事件投进队列;帧数用尽之后改投**关窗请求**(只投一次)。
        /// **调用方要持有 `_锁`**(它是 `打开窗口` / `刷新` 里顺带做的一步,不是独立动作)。
        /// </summary>
        private static void 投放第几帧(int 帧号)
        {
            if (_脚本 == null) return;
            if (帧号 < _脚本.帧数)
            {
                foreach (var 条 in _脚本.取第几帧(帧号))
                    _事件.Enqueue((条.类型, 条.键码, 条.x, 条.y));
                return;
            }
            if (_关窗请求投过) return;
            _关窗请求投过 = true;
            _事件.Enqueue((图形事件C.关窗, 0, 0, 0));
        }

        /// <summary> 当前攒着、还没 `刷新` 的命令(自检看它;拷一份出去,免得调用方改到内部状态) </summary>
        public static 绘制命令C[] 待刷新命令()
        {
            lock (_锁) return [.. _命令.Select(x => x.复制())];
        }

        /// <summary> 队列里有几个事件(自检看它)</summary>
        public static int 事件数 { get { lock (_锁) return _事件.Count; } }

        /// <summary>
        /// **H39-2:事件出口** —— 挂了就往它转(跨进程那条路:窗口画在前端,事件要送回**子进程那台虚拟机**),
        /// 没挂照旧进本地队列(进程内那条路 / 自检的事件脚本 / 桌面壳都走本地队列,一个字没变)。
        /// 为什么在这儿开口子:`图形窗口呈现C` 那几处投事件的地方**一个字都不用改** ——
        /// "事件去哪儿"是宿主接线的事,不是窗口的事。
        /// </summary>
        public static Action<int, int, int, int>? 事件出口 { get; set; }

        /// <summary>
        /// **投一个事件**(宿主侧调:桌面壳把键盘 / 鼠标 / 关窗请求塞进来,自检拿脚本塞)。
        /// 事件是**队列**:一次 `取事件` 取一个,取空了给"没有事件"。
        /// 挂了出口(跨进程那条路)就整个转出去,不入本地队列 —— 两处都收会变成"事件跑两遍"。
        /// </summary>
        public static void 投事件(int 类型, int 键码, int x, int y)
        {
            if (事件出口 is { } 出口) { 出口(类型, 键码, x, y); return; }
            lock (_锁) _事件.Enqueue((类型, 键码, x, y));
        }

        /// <summary> 这个功能号是图形能力吗(宿主能力C 分派、机器码扫描都用它) </summary>
        public static bool 是图形功能号(int 功能号) => 功能号 is >= 图形功能号最小 and <= 图形功能号最大;

        /// <summary>
        /// 这段机器码用没用图形能力(扫 `宿主调用` 0x31 的 20 位立即数)。
        ///
        /// 为什么要它:独立 exe 的宿主(HB宿主)在**挂不挂桌面壳**之间选 —— 不挂就还是纯控制台,
        /// 挂上就把 Avalonia 拉进来。机器码是现成的事实源,不必给程序包加字段。
        /// </summary>
        public static bool 这段机器码用图形(byte[] 机器码)
        {
            for (int i = 0; i + 3 < 机器码.Length; i += 4)
            {
                uint 指令 = (uint)(机器码[i] | (机器码[i + 1] << 8) | (机器码[i + 2] << 16) | (机器码[i + 3] << 24));
                if ((指令 >> 24) != 0x31) continue;                 // 只看 `宿主调用`
                if (是图形功能号((int)(指令 & 0xFFFFF))) return true;
            }
            return false;
        }

