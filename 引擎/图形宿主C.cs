        /// <summary> `取文字宽度` 的等宽口径:ASCII 1 格、汉字(全角)2 格;换行 / 制表按 1 格 </summary>
        public static int 量文字宽度(string 文本)
        {
            int 宽 = 0;
            foreach (char 字 in 文本) 宽 += 是宽字(字) ? 中文字宽 : 1;
            return 宽;
        }

        /// <summary>
        /// 这个字符算不算"两格宽"。用码点区间判:CJK / 全角标点 / 韩文 / 中日韩兼容,与
        /// 项目里"输出对齐"那条口径同一套(不引字体、不量像素 —— 等宽假设是拍板定下的档位)。
        /// </summary>
        private static bool 是宽字(char 字) => 字 switch
        {
            >= '\u1100' and <= '\u115F' => true,      // 韩文字母
            >= '\u2E80' and <= '\u303E' => true,      // 中日韩部首 / 标点
            >= '\u3041' and <= '\u33FF' => true,      // 假名 / 注音 / 兼容字
            >= '\u3400' and <= '\u4DBF' => true,      // 扩展 A
            >= '\u4E00' and <= '\u9FFF' => true,      // 基本汉字
            >= '\uA000' and <= '\uA4CF' => true,      // 彝文
            >= '\uAC00' and <= '\uD7A3' => true,      // 韩文音节
            >= '\uF900' and <= '\uFAFF' => true,      // 兼容汉字
            >= '\uFE30' and <= '\uFE4F' => true,      // 兼容标点
            >= '\uFF00' and <= '\uFF60' => true,      // 全角
            >= '\uFFE0' and <= '\uFFE6' => true,      // 全角符号
            _ => false,
        };

        // ---------------- 能力处理 ----------------

        /// <summary> 给虚拟机挂的处理器(见 `宿主能力C.处理` 末尾那一段分派) </summary>
        public static int 处理(byte[] 内存, uint 参数区, int 功能号)
        {
            try
            {
                // 取文字宽度**是纯计算**(排版要用,不该因为"没开窗"就不给)—— 别的都要呈现口
                if (功能号 == 功能_取文字宽度) return 处理取文字宽度(内存, 参数区);
                // R4-12:位图那一族也**不要呈现口** —— 它是**离屏**的(建一张图、往上画点),
                // 与"窗口开没开"无关。放到这一行下面就会被"没挂能力"拦掉,所以必须在这之前。
                if (功能号 is >= 位图功能号最小 and <= 位图功能号最大)
                {
                    switch (功能号)
                    {
                        case 功能_建位图: return 处理建位图(内存, 参数区);
                        case 功能_释放位图: return 位图仓C.释放((int)读字(内存, 参数区)) ? 状态_成功 : 状态_句柄无效;
                        case 功能_位图尺寸: return 处理位图尺寸(内存, 参数区);
                        case 功能_画点到图: return 处理画点到图(内存, 参数区);
                        case 功能_取图像素: return 处理取图像素(内存, 参数区);
                        // ⚠⚠ **F-8 的真根因就在这两行有没有**(2026-10-11 定位并修):
                        //   `画线到图` / `画矩形到图` 与 `画点到图` 是**同一档** —— 都只往
                        //   `位图仓C` 那张离屏图上写像素,**不需要呈现口**。原先它俩漏在上面那个 switch 之外,
                        //   于是往下走到 `呈现口 == null` 那一句 ⇒ 在**没挂呈现口**的环境里
                        //   (自检的 in-process 那台虚拟机、命令行那条腿)一律被"没挂能力"拦掉:
                        //   状态给 1、**一个像素都没画**,而 `画点到图` 照画 ⇒ 症状就是
                        //   "自检里 `画线到图` / `画矩形到图` 读回 0,命令行那条腿却全对"(F-8 / R4-12)。
                        case 功能_画线到图: return 处理画线到图(内存, 参数区);
                        case 功能_画矩形到图: return 处理画矩形到图(内存, 参数区);
                        // `贴位图` **要**呈现口(它得把一整块贴到窗口上,命令进的是窗口那条队列)
                        //   ⇒ 它留在下面那个 switch 里,这里不接。
                        // ⚠ 号 78 `贴文字到位图` 也**要**呈现口(字形光栅化只有平台有),由它自己判
                        //   (`处理贴文字到位图` 里那一句 `呈现口 == null` ⇒ 状态 1):**不能**把它挪到
                        //   下面去 —— 那样在"没挂呈现口"时给的状态码虽然一样,但"句柄不认"那一档
                        //   就永远轮不到(先撞没挂能力),判据分不开这两件事。
                        case 功能_贴文字到位图: return 处理贴文字到位图(内存, 参数区);
                    }
                }
                if (呈现口 == null) return 状态_没挂能力;

                switch (功能号)
                {
                    case 功能_打开窗口: return 处理打开窗口(内存, 参数区);
                    case 功能_关闭窗口: return 处理关闭窗口();
                    case 功能_清屏: return 攒一条(new 绘制命令C { 动作 = "清屏", 颜色 = 读字(内存, 参数区) });
                    case 功能_画文字: return 画文字(内存, 参数区);
                    case 功能_画矩形:
                        return 攒一条(new 绘制命令C
                        {
                            动作 = "画矩形",
                            x = (int)读字(内存, 参数区),
                            y = (int)读字(内存, 参数区 + 4),
                            宽 = (int)读字(内存, 参数区 + 8),
                            高 = (int)读字(内存, 参数区 + 12),
                            颜色 = 读字(内存, 参数区 + 16),
                        });
                    case 功能_画线:
                        return 攒一条(new 绘制命令C
                        {
                            动作 = "画线",
                            x = (int)读字(内存, 参数区),
                            y = (int)读字(内存, 参数区 + 4),
                            x2 = (int)读字(内存, 参数区 + 8),
                            y2 = (int)读字(内存, 参数区 + 12),
                            颜色 = 读字(内存, 参数区 + 16),
                        });
                    case 功能_刷新: return 处理刷新();
                    case 功能_取事件: return 处理取事件(内存, 参数区);
                    case 功能_等待:
                        呈现口!.等待((int)读字(内存, 参数区));
                        return 状态_成功;
                    // ---- R4-12:位图那一族(上面那段已经拦过;这里留着只为"万一走到"给对状态码)----
                    case 功能_建位图: return 处理建位图(内存, 参数区);
                    case 功能_释放位图: return 位图仓C.释放((int)读字(内存, 参数区)) ? 状态_成功 : 状态_句柄无效;
                    case 功能_位图尺寸: return 处理位图尺寸(内存, 参数区);
                    case 功能_画点到图: return 处理画点到图(内存, 参数区);
                    case 功能_取图像素: return 处理取图像素(内存, 参数区);
                    case 功能_贴位图: return 处理贴位图(内存, 参数区);
                    case 功能_画线到图: return 处理画线到图(内存, 参数区);
                    case 功能_画矩形到图: return 处理画矩形到图(内存, 参数区);
                    default: return 状态_参数不合法;
                }
            }
            catch (Exception 错) when (运行期错误C.是运行期错误(错)) { throw; }   // 帧数护栏:如实往上报,别吞成状态码
            catch (Exception 错)
            {
                // R4-10:**取证** —— 以前这里静默吞成状态码,于是"独立 exe 里 `打开窗口` 恒失败、
                // 还卡 15 秒"这件事查不到任何线索。设了这一个环境变量就把异常原样报出来(只在排查时设)。
                if (Environment.GetEnvironmentVariable("HB_图形报错") is { Length: > 0 })
                {
                    Console.Error.WriteLine($"图形层异常[{功能号}]:{错.GetType().Name}: {错.Message}");
                    Console.Error.WriteLine(错.StackTrace);
                }
                return 状态_开不了窗口;   // 呈现口抛了:如实说"开不出来",不让程序崩
            }
        }

        /// <summary> 攒一条绘制命令(没开窗口就是"没有窗口"—— 这条边界不能静默)</summary>
        private static int 攒一条(绘制命令C 命令)
        {
            lock (_锁)
            {
                if (!_窗口开着) return 状态_没有窗口;
                _命令.Add(命令);
                return 状态_成功;
            }
        }

        private static int 处理打开窗口(byte[] 内存, uint 参数区)
        {
            uint 标题址 = 读字(内存, 参数区);
            uint 标题长 = 读字(内存, 参数区 + 4);
            int 宽 = (int)读字(内存, 参数区 + 8);
            int 高 = (int)读字(内存, 参数区 + 12);
            string 标题 = Encoding.UTF8.GetString(内存, (int)标题址, (int)标题长);

            lock (_锁)
            {
                if (_窗口开着) return 状态_窗口已经开着;
                _命令.Clear();                  // 开窗是新的开始:上一轮没刷的命令不带过来
                _窗口开着 = true;
                _窗口宽 = 宽;
                _窗口高 = 高;
                窗口标题 = 标题;
                _已呈现帧数 = 0;                // 打开窗口 = 第 0 帧开始(R1-6 批 2 的时调节拍)
                _关窗请求投过 = false;
                投放第几帧(0);
            }
            // 呈现口在锁外调:开窗可能要等界面线程好几毫秒,别攥着锁(它会回调 投事件)
            呈现口!.打开窗口(标题, 宽, 高);
            return 状态_成功;
        }

        private static int 处理关闭窗口()
        {
            lock (_锁)
            {
                if (!_窗口开着) return 状态_没有窗口;
                _命令.Clear();                  // 没刷的命令随窗口一起去:关了就没人接了
                _窗口开着 = false;
                _窗口宽 = 0;
                _窗口高 = 0;
            }
            呈现口!.关闭窗口();
            return 状态_成功;
        }

        private static int 处理刷新()
        {
            绘制命令C[] 一帧;
            int 帧号;
            int 限 = 0;
            bool 超了;
            lock (_锁)
            {
                if (!_窗口开着) return 状态_没有窗口;
                一帧 = [.. _命令.Select(x => x.复制())];
                _命令.Clear();
                _已呈现帧数++;                    // 提交了第 k 帧 ⇒ 从这一帧起进第 k+1 帧
                帧号 = _已呈现帧数;
                限 = _脚本?.帧数 ?? 0;
                // 脚本说跑满 N 帧:第 N 帧开始时投一个「关窗请求」;程序要是不理它、接着刷,
                // 再给 `帧数宽限` 帧就不客气了 —— 确定性测试里"跑不完"必须是能被看见的错,不能默默转下去
                超了 = _脚本 != null && 帧号 > _脚本.帧数 + 事件脚本C.帧数宽限;
                if (!超了) 投放第几帧(帧号);
            }
            呈现口!.呈现(一帧);          // 呈现口在锁外调:它可能要等界面线程,别攥着锁
            if (超了)
                throw new 运行期错误C($"事件脚本说跑满 {限} 帧,程序到第 {帧号} 帧还在刷新 —— " +
                    $"多半是没理那个「关窗请求」(类型 1)。" +
                    $"办法:主循环里 `如果 (取事件(类型, 键码, x, y)) {{ 如果 (类型 == 1) {{ 跳出; }} }}`," +
                    $"或者在 `帧数` 那一行写大一点");
            return 状态_成功;
        }

        /// <summary>
        /// 画文字:x / y / 文本址 / 文本长 / 颜色。文字**按 UTF-8 取出来**(与字符串一致),
        /// 超出窗口由呈现口裁掉(不报错 —— 这是画布的常态)。
        /// </summary>
        private static int 画文字(byte[] 内存, uint 参数区)
        {
            uint 文本址 = 读字(内存, 参数区 + 8);
            uint 文本长 = 读字(内存, 参数区 + 12);
            string 文本 = Encoding.UTF8.GetString(内存, (int)文本址, (int)文本长);
            return 攒一条(new 绘制命令C
            {
                动作 = "画文字",
                x = (int)读字(内存, 参数区),
                y = (int)读字(内存, 参数区 + 4),
                文本 = 文本,
                颜色 = 读字(内存, 参数区 + 16),
            });
        }

        /// <summary>
        /// **贴文字到位图**(号 78,控 1-①):`参数1` 句柄、`参数2/3` 落点、`参数4/5` 文本址长、`参数6` 颜色。
        ///
        /// <para>**要呈现口**(这一条是位图那一族里**唯一**要它的):字形光栅化只有平台有 ——
        /// 引擎库是 `net10.0`,没有 WPF / Avalonia / `System.Drawing`。没挂呈现口给"没挂能力",
        /// 图一个像素都不动(与 `贴位图` 那条"要窗口"同一类边界)。</para>
        ///
        /// <para>**拷贝那一趟是必须的**:呈现口拿到的是**它自己那份数组**(`像素` 参数),
        /// 画完再拷回 `位图C.像素` —— 不这么做就等于把库内部那块交给外部随便改。</para>
        ///
        /// <para>⚠ **跨腿口径**:C 后端那边到今天**还没实现这一条**(Linux/Win32 两套字形都得另写),
        /// 它如实给"没挂能力"。⇒ 这一档的跨腿判据只有 **形状级**(见接口上那段说明)。</para>
        /// </summary>
        private static int 处理贴文字到位图(byte[] 内存, uint 参数区)
        {
            var 口 = 呈现口;
            if (口 == null) return 状态_没挂能力;
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            uint 文本址 = 读字(内存, 参数区 + 12);
            uint 文本长 = 读字(内存, 参数区 + 16);
            string 文本 = Encoding.UTF8.GetString(内存, (int)文本址, (int)文本长);
            if (文本.Length == 0) return 状态_成功;      // 空串:没什么可画(不算失败)
            var 拷 = (uint[])图.像素.Clone();
            bool 画了 = 口.把文字画进像素((int)读字(内存, 参数区 + 4), (int)读字(内存, 参数区 + 8),
                文本, 读字(内存, 参数区 + 20), 图形规格C.默认字号, 拷, 图.宽, 图.高);
            if (!画了) return 状态_没挂能力;            // 这个口画不了字(无头就是这一档),图一个格子没动
            Array.Copy(拷, 图.像素, 图.像素.Length);
            return 状态_成功;
        }

        /// <summary> 取事件:有就给真(四个出参写进参数区),没有给"没有事件"(中间层转成 假) </summary>
        private static int 处理取事件(byte[] 内存, uint 参数区)
        {
            lock (_锁)
            {
                if (_事件.Count == 0) return 状态_没有事件;
                var (类型, 键码, x, y) = _事件.Dequeue();
                写字(内存, 参数区, (uint)类型);
                写字(内存, 参数区 + 4, (uint)键码);
                写字(内存, 参数区 + 8, (uint)x);
                写字(内存, 参数区 + 12, (uint)y);
                return 状态_成功;
            }
        }

        private static int 处理取文字宽度(byte[] 内存, uint 参数区)
        {
            uint 文本址 = 读字(内存, 参数区);
            uint 文本长 = 读字(内存, 参数区 + 4);
            string 文本 = Encoding.UTF8.GetString(内存, (int)文本址, (int)文本长);
            写字(内存, 参数区 + 8, (uint)量文字宽度(文本));
            return 状态_成功;
        }

        // ---------------- 内存读写(与 `宿主能力C` 同一套口径:小端) ----------------

        private static uint 读字(byte[] 内存, uint 地址)
            => (uint)(内存[地址] | (内存[地址 + 1] << 8) | (内存[地址 + 2] << 16) | (内存[地址 + 3] << 24));

        private static void 写字(byte[] 内存, uint 地址, uint 值)
        {
            内存[地址] = (byte)(值 & 0xFF);
            内存[地址 + 1] = (byte)((值 >> 8) & 0xFF);
            内存[地址 + 2] = (byte)((值 >> 16) & 0xFF);
            内存[地址 + 3] = (byte)((值 >> 24) & 0xFF);
        }

        // ================= R4-12:位图那一族(70~74)的五个处理 =================

        /// <summary>
        /// **建位图**:`参数1` **出句柄的槽地址**(调用方那个整数变量在哪)、`参数2/3` 宽高。
        /// 宽高不合法(≤0 / 太大 / 总格数过线)给状态 9,句柄槽写 **-1**。
        ///
        /// ⚠ **参数1 是"地址"而不是"句柄"**(与别的条不一样,写在这儿免得下一班再踩):
        /// 宿主得知道"把句柄写回哪儿"。位图还不存在,这一格不可能是句柄本身。
        /// </summary>
        private static int 处理建位图(byte[] 内存, uint 参数区)
        {
            uint 句柄址 = 读字(内存, 参数区);
            int 宽 = (int)读字(内存, 参数区 + 4);
            int 高 = (int)读字(内存, 参数区 + 8);
            int 号 = 位图仓C.建并取号(宽, 高, out _);
            if (号 < 0)
            {
                if (句柄址 + 4 <= 内存.Length) 写字(内存, 句柄址, 0xFFFFFFFFu);
                return 状态_参数不合法;
            }
            if (句柄址 + 4 > 内存.Length) return 状态_参数不合法;
            写字(内存, 句柄址, (uint)号);
            return 状态_成功;
        }

        /// <summary>**位图尺寸**:`参数1` 句柄、`参数2/3` 写回宽高;句柄不认给假(两个写回槽不动)</summary>
        private static int 处理位图尺寸(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            uint 宽址 = 读字(内存, 参数区 + 4);
            uint 高址 = 读字(内存, 参数区 + 8);
            if (宽址 + 4 > 内存.Length || 高址 + 4 > 内存.Length) return 状态_参数不合法;
            写字(内存, 宽址, (uint)图.宽);
            写字(内存, 高址, (uint)图.高);
            return 状态_成功;
        }

        /// <summary>**画点到图**:`参数1` 句柄、`参数2/3` x/y、`参数4` 颜色。越界**不报错**(什么都不做)——
        /// 绘制代码不该为每个点自己判边界(`位图C.画` 里判了)。</summary>
        private static int 处理画点到图(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            图.画((int)读字(内存, 参数区 + 4), (int)读字(内存, 参数区 + 8), 读字(内存, 参数区 + 12));
            return 状态_成功;
        }

        /// <summary>
        /// **取图像素**:`参数1` 句柄、`参数2/3` x/y、`参数4`(写回)= 颜色。越界给 0。
        ///
        /// ⚠ **结果写在 `参数4`(= +12)那一格**(与"取文字宽度把结果写在 +8"同一个格局):
        /// 调用方把那一格的**地址**当"写回槽"给过来,值就落回参数块里 ——
        /// 这样这一条既能当**表达式**用(`输出行(取图像素(图, x, y))`),不必再多要一个"出参变量"。
        /// </summary>
        private static int 处理取图像素(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            写字(内存, 参数区 + 12, 图.取((int)读字(内存, 参数区 + 4), (int)读字(内存, 参数区 + 8)));
            return 状态_成功;
        }

        /// <summary>
        /// **贴位图**(R4-12):`参数1` 句柄、`参数2/3` 贴到窗口的哪个位置。
        ///
        /// <para>**这是位图那条路的出口**,也是"帧数不再随画了多少东西涨"的那一条:
        /// 一整块像素**攒成一条命令**发出去,而不是几万条 `画矩形`。施工图的判据就是它
        /// ("只提交 1 次贴位图")。</para>
        ///
        /// <para>**命令里带的是像素快照,不是句柄**:命令表要能跨进程送给另开的那台虚拟机
        /// (`跑程序协议C` 序列化整批命令),句柄在那一侧没有意义。快照的成本是复制一块 ——
        /// 与"省下的几万次往返"比可以忽略。</para>
        /// </summary>
        private static int 处理贴位图(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            return 攒一条(new 绘制命令C
            {
                动作 = "贴位图",
                x = (int)读字(内存, 参数区 + 4),
                y = (int)读字(内存, 参数区 + 8),
                宽 = 图.宽,
                高 = 图.高,
                像素 = (uint[])图.像素.Clone(),   // 快照:命令交出去之后程序还会接着画那张图
            });
        }

        /// <summary>
        /// **画线到位图**(R4-12):`参数1` 句柄、`参数2..5` 两端点、`参数6` 颜色。
        ///
        /// <para>与 `画线`(画到窗口那条)**同一套口径**,只是画到**离屏**;算法在宿主侧
        /// (Bresenham,整数)。**一条命令画一整条线** —— 这正是位图这条路省往返的地方:
        /// 画一条 200 像素的线是**一次**调用,而不是 200 次 `画点到图`。</para>
        /// </summary>
        private static int 处理画线到图(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            图.画线((int)读字(内存, 参数区 + 4), (int)读字(内存, 参数区 + 8),
                    (int)读字(内存, 参数区 + 12), (int)读字(内存, 参数区 + 16),
                    读字(内存, 参数区 + 20));
            return 状态_成功;
        }

        /// <summary> **画矩形到位图**(R4-12):`参数1` 句柄、`参数2/3` 左上角、`参数4/5` 宽高、`参数6` 颜色。
        /// 实心、闭区间;宽高 ≤ 0 什么都不做(与画到窗口那条 `画矩形` 同口径)。</summary>
        private static int 处理画矩形到图(byte[] 内存, uint 参数区)
        {
            var 图 = 位图仓C.取((int)读字(内存, 参数区));
            if (图 == null) return 状态_句柄无效;
            图.画矩形((int)读字(内存, 参数区 + 4), (int)读字(内存, 参数区 + 8),
                      (int)读字(内存, 参数区 + 12), (int)读字(内存, 参数区 + 16),
                      读字(内存, 参数区 + 20));
            return 状态_成功;
        }
    }
