using System.IO;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **一样东西声明在哪儿** —— H60-9(思维导图 2.0 的"声明线";出处条目 = §9 H53 步 2)。
    ///
    /// 用户口径(2026-09-26):「`测试输出` 点击会出现两条线:一条指向他的**声明**,另一条指向他**调用其他**」
    /// —— 这一层只答"指向声明"那一半("调用其他"那一半是 H60-10)。
    ///
    /// **一条铁律**:`行 = 0` 一律表示**没有源码定义**(内建函数 / 宿主能力 / 关键字 / 类型 / 汇编指令),
    /// 这时 `说明` 里如实写清为什么 —— **绝不编一个假位置**(施工图口径:"内建 / 宿主 / 关键字认得出但
    /// 没有源码定义,如实说清,不编一个假位置")。
    /// </summary>
    public sealed class 声明处C
    {
        /// <summary> 查它时用的那个名字(可能是尾名:`求和` 查到的是 `数学.求和`)</summary>
        public string 名 = "";

        /// <summary> 声明处登记的全名(带模块前缀;与 `名` 一样时就是它自己)</summary>
        public string 全名 = "";

        /// <summary>
        /// 变量 / 常量 / 参数 / 局部 / 字段 / 结构 / 结构方法 / 成员方法 / 方法 / 方法容器 /
        /// 内建函数 / 类型 / 语句 / 字面量 / 指令(后五种**没有源码定义**)
        /// </summary>
        public string 种类 = "";

        /// <summary> 声明在哪一份源文件(空 = 这份文本自己没有文件名 / 只有一份文件)</summary>
        public string 文件 = "";

        /// <summary> 声明行(1 基;**0 = 行号不可考或没有源码定义**,原因写在 `说明` 里)</summary>
        public int 行;

        /// <summary> 有没有源码里的位置(`行 > 0` 就是有)</summary>
        public bool 是源码声明;

        /// <summary> 类型词(变量 / 参数 / 字段有;方法 / 结构没有就是空串)</summary>
        public string 类型词 = "";

        /// <summary> 它所在的那一层(`方法 求和` / `流程块 循环` / `结构 点`;顶层就是空串)—— 给人看的</summary>
        public string 所在 = "";

        /// <summary> 一句人话(行号不可考 / 没有源码定义时说清为什么)</summary>
        public string 说明 = "";

        /// <summary> 它的作用域区间(行号,1 基)—— 按出现处挑"最近的那一个"用</summary>
        public int 作用域起 = 1;
        public int 作用域止 = int.MaxValue;

        /// <summary> 这一行落不落在它的作用域里(`行 <= 0` = 不问作用域,一律算落) </summary>
        public bool 含(int 行) => 行 <= 0 || (行 >= 作用域起 && 行 <= 作用域止);

        public override string ToString()
        {
            if (是源码声明)
            {
                string 文件名 = 文件.Length > 0 ? Path.GetFileName(文件) : "(本文)";
                string 尾 = 种类
                    + (类型词.Length > 0 ? " " + 类型词 : "")
                    + (所在.Length > 0 ? "," + 所在 : "");
                return $"{文件名} 第 {行} 行({尾})";
            }
            return 说明.Length > 0 ? 说明 : $"没有源码定义({种类})";
        }
    }

    /// <summary>
    /// **声明线的那张表**(H60-9):名字 → 它声明在哪儿。
    ///
    /// 三档来源(施工图口径):
    ///   ① **本文件(或多份文件)的源码结构树**(`源码声明扫描C.扫结构`)—— 行号最全,
    ///      参数 / 局部 / 流程块头的 `k` / 字段都有自己那一行;
    ///   ② **一次编译的 `名字表C`**(`函数范围` / `变量` / `结构`)—— 补上"这份文件没扫过的那几份";
    ///   ③ **`补全词表C.查种类`** —— 内建 / 宿主 / 关键字 / 指令,**如实说"没有源码定义"**
    ///      (只在 ①② 都找不到时才问它,问出来的 `行 = 0`)。
    ///
    /// 挑法(`查(名, 行, 文件)`):**同文件 → 有源码行 → 作用域含这一行 → 作用域窄 → 行号靠后(就近)**。
    /// 这样"两个方法里各有一个同名局部"才会各指各的,而"顶层那个同名变量"只在方法外才被指到。
    /// </summary>
    public sealed class 声明索引C
    {
        /// <summary> 这张索引是给哪一份文件用的(空 = 不按文件挑) </summary>
        public string 本文件 = "";

        private readonly List<声明处C> _表 = [];

        /// <summary> 全部登记项(按登记顺序;同一个名字会有好几条) </summary>
        public IReadOnlyList<声明处C> 表 => _表;

        /// <summary> 登记了几条 </summary>
        public int 计数 => _表.Count;

        /// <summary>
        /// 登记一条(**自动去重**):同一个 (名字, 文件, 行号) 只留第一条(源码树排在编译结果前面 ⇒
        /// 留下的是"种类更细"的那一条 —— 参数 / 局部 / 结构方法 这些细分只有源码树说得出来)。
        /// 另外:`行 = 0` 的那一条(编译结果里认得、但没有行号)碰到"同名同文件且**有**行号"的那条就不登记。
        /// </summary>
        public void 加(声明处C 处)
        {
            foreach (var 有 in _表)
            {
                if (!string.Equals(有.名, 处.名, StringComparison.OrdinalIgnoreCase)) continue;
                if (处.行 > 0 && 有.行 == 处.行 && 文件判定C.同文件(有.文件, 处.文件)) return;
                if (处.行 <= 0 && 有.行 > 0 && 文件判定C.同文件(有.文件, 处.文件)) return;
                if (处.行 <= 0 && 有.行 <= 0 && string.Equals(有.种类, 处.种类, StringComparison.OrdinalIgnoreCase)) return;
            }
            _表.Add(处);
        }

        /// <summary> 这个名字登记的全部声明处(按名字精确对,不分大小写;没有就是空表)</summary>
        public List<声明处C> 查全部(string? 名原)
        {
            var 果 = new List<声明处C>();
            string 名 = (名原 ?? "").Trim();
            if (名.Length == 0) return 果;
            foreach (var 处 in _表)
                if (string.Equals(处.名, 名, StringComparison.OrdinalIgnoreCase)) 果.Add(处);
            return 果;
        }

        /// <summary>
        /// 这个名字**声明在哪儿**(找不到源码声明时问 `补全词表C.查种类`,那一档 `行 = 0` + 说明;
        /// 连它也不认识 ⇒ null = **没这个词**,不硬猜)。
        /// `行` / `文件` = 出现的那一处(用来在好几个同名里挑最近的那一个;不传就是不问作用域)。
        /// </summary>
        public 声明处C? 查(string? 名原, int 行 = 0, string 文件 = "")
        {
            string 名 = (名原 ?? "").Trim();
            if (名.Length == 0) return null;

            var 候选 = 查全部(名);
            if (候选.Count > 0)
            {
                声明处C 最好 = 候选[0];
                for (int i = 1; i < 候选.Count; i++)
                    if (比(候选[i], 最好, 行, 文件) < 0) 最好 = 候选[i];
                return 最好;
            }

            if (补全词表C.查种类(名) is { } 种类)
                return new 声明处C
                {
                    名 = 名,
                    全名 = 名,
                    种类 = 种类,
                    行 = 0,
                    是源码声明 = false,
                    说明 = 补全词表C.没有源码定义说明(名, 种类),
                };
            return null;
        }

        /// <summary> 挑法(见类注释):同文件 → 有源码行 → 作用域含这一行 → 作用域窄 → 行号靠后 </summary>
        private static int 比(声明处C 左, 声明处C 右, int 行, string 文件)
        {
            int 左同 = 同文件优先(左.文件, 文件) ? 0 : 1;
            int 右同 = 同文件优先(右.文件, 文件) ? 0 : 1;
            if (左同 != 右同) return 左同 - 右同;

            if (左.是源码声明 != 右.是源码声明) return 左.是源码声明 ? -1 : 1;

            int 左含 = 左.含(行) ? 0 : 1, 右含 = 右.含(行) ? 0 : 1;
            if (左含 != 右含) return 左含 - 右含;

            int 宽左 = 左.作用域止 - 左.作用域起, 宽右 = 右.作用域止 - 右.作用域起;
            if (宽左 != 宽右) return 宽左 - 宽右;

            return 右.行.CompareTo(左.行);
        }

        /// <summary> 给的这一份"是不是同一份文件"—— 有一边说不上(空串)就不给这一档加分 </summary>
        private static bool 同文件优先(string 左, string 右)
            => 左.Length > 0 && 右.Length > 0 && 文件判定C.同文件(左, 右);
    }

    /// <summary>
    /// **声明线**(H60-9):把"文件名 → 它的结构树"与一次编译的 `名字表C` **并成一张声明索引**。
    /// 纯函数:不读盘、不吃编译结果以外的状态、不碰界面、不动机器码。
    ///
    /// 用法(思维导图 2.0 后面几步都从这儿拿"这个名字声明在哪儿"):
    /// <code>
    /// var 索引 = 声明线C.建(源码声明扫描C.扫结构(文本, 文件), 编译结果?.名字表);
    /// var 处 = 索引.查("测试输出", 12, 文件);   // ⇒ 种类 = 内建函数、行 = 0、说明 = "…没有源码定义…"
    /// var 处2 = 索引.查("k", 103, 文件);        // ⇒ 流程块头里的那个 k,行 = 101
    /// </code>
    /// </summary>
    public static class 声明线C
    {
        /// <summary> 一份文件的结构树(+ 可选的编译结果)→ 一张声明索引 </summary>
        public static 声明索引C 建(源码结构C 本文件, 名字表C? 表 = null)
        {
            var 索引 = new 声明索引C { 本文件 = 本文件?.文件 ?? "" };
            if (本文件 != null) 收(索引, 本文件);
            if (表 != null) 收表(索引, 表);
            return 索引;
        }

        /// <summary> 工程级:几份文件的结构树(+ 可选的编译结果)→ 一张声明索引(跨文件也指得到) </summary>
        public static 声明索引C 建(IReadOnlyList<源码结构C> 各文件, 名字表C? 表 = null)
        {
            var 索引 = new 声明索引C();
            if (各文件 != null)
                foreach (var 树 in 各文件) 收(索引, 树);
            if (表 != null) 收表(索引, 表);
            return 索引;
        }

        // ---------------- ① 源码结构树 ----------------

        /// <summary> 把一份文件的"自然结构"收进索引(顶级:变量 / 常量 / 结构 / 方法;往下:字段 / 参数 / 局部 / 流程块) </summary>
        public static void 收(声明索引C 索引, 源码结构C 树)
        {
            if (树 == null) return;
            string 文件 = 树.文件 ?? "";
            int 总止 = 树.行数 > 0 ? 树.行数 : int.MaxValue;

            foreach (var 变 in 树.变量们)
                加名(索引, 文件, 变.名, 变.是常量 ? "常量" : "变量", 变.行, 变.类型词, "", 1, 总止);

            for (int i = 0; i < 树.结构们.Count; i++)
            {
                var 结 = 树.结构们[i];
                int 止 = i + 1 < 树.结构们.Count ? 树.结构们[i + 1].行 - 1 : 总止;
                加名(索引, 文件, 结.名, "结构", 结.行, "", "", 结.行, 止);
                foreach (var 字 in 结.字段们)
                    加名(索引, 文件, 字.名, "字段", 字.行, 字.类型词, $"结构 {结.名}", 结.行, 止);
                收方法们(索引, 文件, 结.方法们, "结构方法", 止);
            }

            收方法们(索引, 文件, 树.方法们, "方法", 总止);
            收块们(索引, 文件, 树.顶层流程块们, 总止);
        }

        /// <summary>
        /// 收方法(容器里的成员方法也走它:种类写 `成员方法`)。
        /// `深` 是 T3(2026-09-27 评测整改)加的**嵌套计数**:方法套方法 / 块套块一路递归下去,
        /// 撞 `硬上限C.语句块嵌套上限` 就抛带行号的编译错误 —— 不然嵌套 5000 层的文件一开思维导图,
        /// IDE 进程会被栈溢出当场打死(这条路上只有 `catch (Exception)`,接不住)。
        /// </summary>
        private static void 收方法们(声明索引C 索引, string 文件, List<方法节点C> 方法们, string 种类, int 宿主止, int 深 = 0)
        {
            if (深 > 硬上限C.语句块嵌套上限)
                throw 硬上限C.嵌套太深的错误("思维导图:收声明处", 方法们.Count > 0 ? 方法们[0].头行 : 0, 文件);
            for (int i = 0; i < 方法们.Count; i++)
            {
                var 方 = 方法们[i];
                int 止 = 方.止行 > 0 ? Math.Min(方.止行, 宿主止) : 宿主止;
                int 体起 = 方.体起行 > 0 ? 方.体起行 : 方.头行;
                加名(索引, 文件, 方.名, 种类, 方.头行, 方.返回类型词, "", 方.头行, 止);
                foreach (var 参 in 方.参数们)
                    加名(索引, 文件, 参.名, "参数", 参.行, 参.类型词, $"方法 {方.名}", 方.头行, 止);
                foreach (var 局 in 方.局部们)
                    加名(索引, 文件, 局.名, "局部", 局.行, 局.类型词, $"方法 {方.名}", 体起, 止);
                收块们(索引, 文件, 方.流程块们, 止, 深 + 1);
                收方法们(索引, 文件, 方.方法们, 种类 == "方法" ? "成员方法" : 种类, 止, 深 + 1);
            }
        }

        /// <summary> 收"流程块"这一族:块头声明的(`循环 (var k = …)`)与块体里声明的都算**它自己的局部**(`深` 见 收方法们) </summary>
        private static void 收块们(声明索引C 索引, string 文件, List<流程块节点C> 块们, int 宿主止, int 深 = 0)
        {
            if (深 > 硬上限C.语句块嵌套上限)
                throw 硬上限C.嵌套太深的错误("思维导图:收声明处", 块们.Count > 0 ? 块们[0].行 : 宿主止, 文件);
            for (int i = 0; i < 块们.Count; i++)
            {
                var 块 = 块们[i];
                int 止 = i + 1 < 块们.Count ? Math.Min(块们[i + 1].行 - 1, 宿主止) : 宿主止;
                int 起 = Math.Max(1, 块.行);
                string 这块 = $"流程块 {块.词}";
                foreach (var 头 in 块.头声明们)
                    加名(索引, 文件, 头.名, "局部", 头.行, 头.类型词, 这块, 起, 止);
                foreach (var 局 in 块.局部们)
                    加名(索引, 文件, 局.名, "局部", 局.行, 局.类型词, 这块, 起, 止);
                收块们(索引, 文件, 块.子块们, 止, 深 + 1);
            }
        }

        /// <summary> 登记一条源码里的声明(空名字直接丢掉)</summary>
        private static void 加名(声明索引C 索引, string 文件, string 名, string 种类, int 行,
            string 类型词, string 所在, int 起, int 止)
        {
            if (名.Length == 0) return;
            索引.加(new 声明处C
            {
                名 = 名,
                全名 = 名,
                种类 = 种类,
                文件 = 文件,
                行 = 行,
                是源码声明 = 行 > 0,
                类型词 = 类型词,
                所在 = 所在,
                作用域起 = Math.Max(1, Math.Min(起, 止)),
                作用域止 = Math.Max(1, Math.Max(起, 止)),
            });
        }

        // ---------------- ② 一次编译的 `名字表C` ----------------

        /// <summary>
        /// 把一次编译的名字表收进索引(`函数范围` / `变量` / `结构`;施工图点名的三样)。
        /// 这份文件已经扫过源码树的那些名字**不会重复登记**(源码树那一条种类更细)。
        /// </summary>
        public static void 收表(声明索引C 索引, 名字表C 表)
        {
            if (表 == null) return;

            // 结构自己的方法(`点.到原点`):种类要跟别的方法分开
            var 结构方法名 = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (var (_, 名单) in 表.结构方法)
                foreach (string 名 in 名单) 结构方法名.Add(名);

            foreach (var (函数, 起, 止, 文件) in 表.函数范围)
            {
                if (函数.Length == 0) continue;
                收一条(索引, new 声明处C
                {
                    名 = 函数,
                    全名 = 函数,
                    种类 = 结构方法名.Contains(函数) ? "结构方法" : "方法",
                    文件 = 文件 ?? "",
                    行 = 起,
                    是源码声明 = 起 > 0,
                    作用域起 = Math.Max(1, 起),
                    作用域止 = Math.Max(起, 止),
                }, 要尾名: true);
            }

            foreach (var 项 in 表.变量)
            {
                if (项.名字.Length == 0) continue;
                收一条(索引, new 声明处C
                {
                    名 = 项.名字,
                    全名 = 项.名字,
                    种类 = 项.是全局 ? "变量" : "局部",
                    文件 = 项.声明文件 ?? "",
                    行 = 项.声明行,
                    是源码声明 = 项.声明行 > 0,
                    类型词 = 名字表C.显示类型名(项.类型名),
                    所在 = 项.所属函数.Length > 0 ? $"方法 {项.所属函数}" : "",
                    说明 = "来自编译结果的名字表(这份文件的源码树没扫过它)",
                    作用域起 = 项.区间?.起 ?? 1,
                    作用域止 = 项.区间?.止 ?? int.MaxValue,
                }, 要尾名: false);
            }

            foreach (var (结构名, _) in 表.结构)
            {
                if (结构名.Length == 0) continue;
                bool 是容器 = 表.容器类型.Contains(结构名) || 结构名.StartsWith("_方法_", StringComparison.Ordinal);
                string 文件 = 表.查可见性(结构名)?.声明文件 ?? "";
                收一条(索引, new 声明处C
                {
                    名 = 名字表C.显示类型名(结构名),
                    全名 = 结构名,
                    种类 = 是容器 ? "方法容器" : "结构",
                    文件 = 文件,
                    行 = 0,
                    是源码声明 = false,
                    说明 = $"编译结果里认得这个{(是容器 ? "方法容器" : "结构")},但它**没有单独的声明行**"
                           + (文件.Length > 0
                                ? $"(声明在 {Path.GetFileName(文件)};行号看源码树那一档)"
                                : "(行号看源码树那一档)"),
                }, 要尾名: false);
            }
        }

        /// <summary> 收一条编译结果里的登记项;`要尾名` 为真时**再收一条尾名**(`数学.求和` → `求和`)</summary>
        private static void 收一条(声明索引C 索引, 声明处C 处, bool 要尾名)
        {
            索引.加(处);
            if (!要尾名) return;
            string 尾 = 源码声明扫描C.尾名(处.全名);
            if (尾.Length == 0 || string.Equals(尾, 处.全名, StringComparison.OrdinalIgnoreCase)) return;
            索引.加(new 声明处C
            {
                名 = 尾,
                全名 = 处.全名,
                种类 = 处.种类,
                文件 = 处.文件,
                行 = 处.行,
                是源码声明 = 处.是源码声明,
                类型词 = 处.类型词,
                所在 = 处.所在,
                说明 = 处.说明,
                作用域起 = 处.作用域起,
                作用域止 = 处.作用域止,
            });
        }
    }
}
