namespace hehshihbeen_compiler
{
    /// <summary>
    /// 一个寄存器"现在装着什么"的说明(靠登记得来,不是猜)。
    /// 寄存器里的数字对人没意义,配上这个说明才看得懂:这一格装的是"变量 字(字符) 的值",还是"刚算出的中间结果"。
    /// </summary>
    public sealed class 寄存器记录C
    {
        public int 编号;
        /// <summary> 说明,如 "变量 字(字符) 的值" / "刚算出的结果(第 12 行 加法)" </summary>
        public string 说明 = "";
        /// <summary> 这个说明来自哪一步(源码行;0 = 编译器生成的一步,没有对应源码行) </summary>
        public int 源码行;
        /// <summary> 里面装的是哪个变量的值/地址(null = 不是某个变量) </summary>
        public string? 变量名;
        /// <summary> 装的是变量时的类型名(面板上"谁的"那一列直接用它,不去猜文本) </summary>
        public string 类型名 = "";
        public bool 是地址;
        /// <summary> 装的如果是"帧内某偏移的地址",这里是那个偏移(局部变量就是靠它定位的) </summary>
        public int? 帧偏移;
        /// <summary>
        /// 记这笔账的时候帧指针(FP/R15)是多少。
        /// 用途:进函数/出函数都会换帧,换过帧以后"上一层留下的变量说明"就不算数了 ——
        /// 界面靠比这个值,把过期的说明丢掉,免得指着一个早就不在那个寄存器里的变量。
        /// </summary>
        public uint 登记时帧指针;
    }

    /// <summary>
    /// 寄存器信息管理器:每执行一条指令,就把"这条指令写了哪个寄存器、写进去的是什么"记成一笔账。
    /// 靠的是**操作码 + 编码格式**解码(见 指令C.取格式),再拿 名字表C + 标签表 把地址翻成变量名 ——
    /// 所以面板上显示的是"变量 字(字符) 的值",而不是"地址 0x30"。
    ///
    /// 它只**登记**,一个字节都不改:没有名字可查时就老实写"刚算出的结果(第 N 行 加法)",绝不瞎猜。
    /// </summary>
    public sealed class 寄存器信息管理器C
    {
        private readonly 寄存器记录C?[] _记录 = new 寄存器记录C?[寄存器C.数量];
        private 名字表C? _名字表;
        private Dictionary<string, int> _标签表 = [];
        /// <summary> 全局变量:数据段地址 → 名字项(读数/反查用) </summary>
        private readonly Dictionary<int, 名字项C> _地址到全局 = [];

        public 寄存器信息管理器C() => 清空();

        /// <summary> 调试名字表(编译期导出;换工程时重设) </summary>
        public 名字表C? 名字表
        {
            get => _名字表;
            set { _名字表 = value; 重建反查表(); }
        }

        /// <summary> 标签表(汇编器给的"标签名 → 字节地址";换工程时重设) </summary>
        public Dictionary<string, int> 标签表
        {
            get => _标签表;
            set { _标签表 = value ?? []; 重建反查表(); }
        }

        /// <summary> 清空登记(每个寄存器都回到"没有说明") </summary>
        public void 清空()
        {
            for (int i = 0; i < _记录.Length; i++) _记录[i] = null;
            // R15 是编译器保留的帧指针:它一格一格装着"当前函数的帧在哪",局部变量就是 FP + 偏移
            注明(15, "帧指针(FP):指向当前函数的帧,局部变量都依据它 + 偏移定位", 0,
                变量名: null, 是地址: true, 帧偏移: 0);
        }

        /// <summary> 取某个寄存器的说明(没有就是 null) </summary>
        public 寄存器记录C? 取(int 编号) => 编号 >= 0 && 编号 < _记录.Length ? _记录[编号] : null;

        /// <summary> 全部说明(按下标 = 寄存器编号;没说明的位置是 null) </summary>
        public 寄存器记录C?[] 全部 => _记录;

        /// <summary> 这个寄存器的固定角色(R0 = 返回值/表达式结果,R15 = 帧指针,其余 = 临时寄存器) </summary>
        public static string 角色说明(int 编号) => 编号 switch
        {
            0 => "返回值 / 表达式结果",
            15 => "帧指针(FP)",
            _ => "临时寄存器",
        };

        private void 重建反查表()
        {
            _地址到全局.Clear();
            if (_名字表 == null) return;
            foreach (var 项 in _名字表.变量)
            {
                if (!项.是全局 || 项.槽.Length == 0) continue;
                if (_标签表.TryGetValue(项.槽, out int 地址)) _地址到全局[地址] = 项;
            }
        }

        private void 注明(int 号, string 说明, int 源码行, string? 变量名 = null, bool 是地址 = false, int? 帧偏移 = null,
            string 类型名 = "")
        {
            if (号 is < 0 or >= 寄存器C.数量) return;
            // R15 是编译器保留的帧指针:它里面装的永远是"当前函数帧的地址"(帧基),
            // 局部 / 参数都依据它 + 偏移定位 —— 所以它一律记成"地址、帧内偏移 0",这条谁写都改不掉。
            if (号 == 15) { 是地址 = true; 帧偏移 ??= 0; 变量名 = null; 类型名 = ""; }
            _记录[号] = new 寄存器记录C
            {
                编号 = 号, 说明 = 说明, 源码行 = 源码行,
                变量名 = 变量名, 类型名 = 类型名, 是地址 = 是地址, 帧偏移 = 帧偏移,
                登记时帧指针 = _当前帧指针,
            };
        }

        /// <summary>
        /// 变量名 → 哪些寄存器里现在是它的值/地址(界面"变量 ↔ 寄存器"那一列的靠山)。
        /// 只认真认出来的(记录里带变量名的),不猜;
        /// 给了 当前帧指针 就把"上一层函数帧里留下的说明"滤掉(换了帧,那些早就不能作数了)。
        /// </summary>
        public static Dictionary<string, List<int>> 变量到寄存器(IReadOnlyList<寄存器记录C?> 说明, uint? 当前帧指针 = null)
        {
            var 表 = new Dictionary<string, List<int>>(StringComparer.OrdinalIgnoreCase);
            for (int 号 = 0; 号 < 说明.Count; 号++)
            {
                var 笔 = 说明[号];
                if (笔?.变量名 is not { Length: > 0 } 名) continue;
                if (当前帧指针 is { } 帧 && 笔.登记时帧指针 != 帧) continue;      // 换过帧了:这笔账过期
                if (!表.TryGetValue(名, out var 列)) 表[名] = 列 = [];
                if (!列.Contains(号)) 列.Add(号);
            }
            return 表;
        }

        /// <summary> 这几行后面要写"第 N 行" —— 编译器生成的一步(源码行 0)就只说指令名 </summary>
        private static string 哪一行(int 源码行, string 后缀) =>
            源码行 > 0 ? $"刚算出的结果(第 {源码行} 行 {后缀})" : $"刚算出的结果({后缀})";

        /// <summary>
        /// 登记:PC 处那条指令执行**之后**调一次(虚拟机已经走完了)。
        /// 地址 = 这条指令的地址,机器码 = 正在调试的整段机器码,源码行 = 它来自源码第几行(0 = 编译器生成的)。
        /// </summary>
        public void 登记(int 地址, byte[]? 机器码, 虚拟机C 虚拟机, int 源码行)
        {
            ArgumentNullException.ThrowIfNull(虚拟机);
            登记(地址, 机器码, 虚拟机.寄存器[15], 源码行);
        }

        /// <summary>
        /// H39-2:同上,但**帧指针由调用方给** —— 跨进程那条腿重放"尾部轨迹"时要用**当时**的 R15
        /// (轨迹里每一条都带了自己那一刻的帧指针;拿现在这一格去登记,换过帧的那些账全会记错)。
        /// </summary>
        public void 登记(int 地址, byte[]? 机器码, uint 帧指针, int 源码行)
        {
            if (机器码 == null || 地址 < 0 || 地址 + 3 >= 机器码.Length) return;
            当前源码行 = 源码行;
            _当前帧指针 = 帧指针;      // 记下"这笔账是在哪一层帧上写的"(换过帧就过期)
            uint 码 = (uint)(机器码[地址] | (机器码[地址 + 1] << 8) | (机器码[地址 + 2] << 16) | (机器码[地址 + 3] << 24));
            byte 操作码 = (byte)(码 >> 24);
            int 目标 = (int)((码 >> 20) & 0xF);
            int 源 = (int)((码 >> 16) & 0xF);
            uint 立即 = 码 & 0xFFFFF;
            string 指令 = 指令C.取指令中文名(操作码) ?? "未知指令";

            switch (操作码)
            {
                // ---- 直接按地址读写:地址字段能反查出变量名 ----
                case 0x01:   // 加载(1 字节)
                case 0x20:   // 取字(4 字节)
                case 0x02:   // 存储
                case 0x21:   // 存字
                case 0x16:   // 取地址
                {
                    bool 取地址 = 操作码 == 0x16;
                    bool 写入 = 操作码 is 0x01 or 0x20 or 0x16;
                    if (!写入) return;                                   // 存储不改寄存器
                    if (目标 == 15)
                    {
                        // 程序开头 `取地址 R15 软栈槽`:把帧指针摆到软栈底(局部变量全靠它)
                        注明(15, "帧指针(FP):指向当前函数的帧,局部变量都依据它 + 偏移定位", 源码行);
                        return;
                    }
                    var 命中 = 反查地址(立即, 4);
                    string 说明 = 命中 == null
                        ? (取地址 ? $"0x{立即:X} 这个地址" : $"内存 0x{立即:X} 处的值")
                        : (取地址 ? $"{命中.Value.文本} 的地址" : $"{命中.Value.文本} 的值");
                    注明(目标, 说明, 源码行, 命中?.项.名字, 是地址: 取地址, 类型名: 命中 == null ? "" : 显示类型(命中.Value.项));
                    return;
                }
                case 0x03:   // 加载立即数
                    注明(目标, $"立即数 {立即}", 源码行);
                    return;
                case 0x1E:   // 载入高位(LUI):imm20 << 12
                    注明(目标, $"高位立即数 0x{立即 << 12:X}", 源码行);
                    return;
                case 0x1F:   // 或立即数(拼 32 位常量)
                    注明(目标, 哪一行(源码行, "拼 32 位常量"), 源码行);
                    return;

                // ---- 运算:结果就是"刚算出来的" ----
                case 0x04: case 0x05: case 0x0F: case 0x10: case 0x11:
                case 0x12: case 0x13: case 0x19: case 0x24: case 0x25: case 0x26:
                    注明(目标, 哪一行(源码行, 指令), 源码行);
                    return;

                // ---- 加/减立即数:常见用途是"从帧指针/变量地址上加个偏移",跟着上一笔账走 ----
                case 0x14: case 0x15:
                {
                    long 差 = 操作码 == 0x14 ? 立即 : -(long)立即;
                    var 旧 = 取(目标);
                    if (旧 is { 是地址: true } && 旧.帧偏移 is { } 旧偏移)
                    {
                        int 新偏移 = (int)(旧偏移 + 差);
                        var 指到的 = 反查局部(新偏移);      // 加完偏移正好是某个局部变量 → 连名字一起记上(界面就认得出)
                        注明(目标, 指到的 == null ? 帧内偏移说明(新偏移) : $"{描述(指到的)} 的地址", 源码行,
                            指到的?.名字 ?? 旧.变量名, 是地址: true, 帧偏移: 新偏移,
                            类型名: 指到的 == null ? 旧.类型名 : 显示类型(指到的));
                        return;
                    }
                    if (旧 is { 是地址: true } && 旧.变量名 != null)
                    {
                        注明(目标, $"{旧.变量名} 附近 +{差} 的地址", 源码行, 旧.变量名, 是地址: true, 帧偏移: null, 类型名: 旧.类型名);
                        return;
                    }
                    注明(目标, 哪一行(源码行, 指令), 源码行);
                    return;
                }

                // ---- 复制:说明跟着值一起搬过去(谁的值搬过来,新寄存器就还是谁的值) ----
                case 0x1D:   // 复制
                {
                    var 旧 = 取(源);
                    // 说明跟着值一起搬(变量名/是不是地址/帧内偏移都跟着);"(从 Rx 复制)"只标一次,免得 R1←R2←R3 越串越长
                    string 说明 = 旧 == null
                        ? $"从 {寄存器C.名称(源)} 复制来的值"
                        : 旧.说明.Contains("(从 ", StringComparison.Ordinal) ? 旧.说明 : $"{旧.说明}(从 {寄存器C.名称(源)} 复制)";
                    注明(目标, 说明, 源码行, 旧?.变量名, 旧?.是地址 ?? false, 旧?.帧偏移, 旧?.类型名 ?? "");
                    return;
                }

                // ---- 间接读写:地址在另一个寄存器里(局部变量走的正是这条路) ----
                case 0x17:   // 加载间(1 字节)
                case 0x22:   // 取字间(4 字节)
                {
                    var 读到的 = 间接说明(源);
                    注明(目标, 读到的.文本, 源码行, 读到的.项?.名字, 类型名: 读到的.项 == null ? "" : 显示类型(读到的.项));
                    return;
                }
                case 0x18:   // 存储间
                case 0x23:   // 存字间
                case 0x33:   // 存字索引(A3):只写内存,不改寄存器
                    return;

                // ---- 帧相对寻址(FP+偏移):一条指令就把局部/参数读到或取到地址 ----
                case 0x2A:   // 取字帧:R = 内存[FP+偏移]
                {
                    var 局部 = 反查局部((int)立即);
                    注明(目标, 局部 == null ? $"帧内偏移 {立即} 处的值" : $"{描述(局部)} 的值", 源码行,
                        局部?.名字, 类型名: 局部 == null ? "" : 显示类型(局部));
                    return;
                }
                case 0x2B:   // 存字帧:只写内存,不改寄存器
                    return;
                case 0x2C:   // 取地址帧:R = FP + 偏移(把局部/参数的地址递出去)
                {
                    var 指到的 = 反查局部((int)立即);
                    注明(目标, 指到的 == null ? 帧内偏移说明((int)立即) : $"{描述(指到的)} 的地址", 源码行,
                        指到的?.名字, 是地址: true, 帧偏移: (int)立即,
                        类型名: 指到的 == null ? "" : 显示类型(指到的));
                    return;
                }

                // ---- R1-4:间接控制转移(寄存器里装的是**目标地址**,寄存器本身没被改) ----
                case 0x35:   // 调用寄存器
                case 0x36:   // 跳转寄存器
                    注明(目标, $"跳转目标地址({指令})", 源码行, 是地址: true);
                    return;

                // ---- P11:立即数移位/掩码(寄存器里的值变了 → 说明重标成"刚算出的结果") ----
                case 0x2D:   // 左移立即数
                case 0x2E:   // 与立即数
                case 0x34:   // 右移立即数(A9):同样是"刚算出的结果"
                    注明(目标, 哪一行(源码行, 指令), 源码行);
                    return;

                // ---- P13:比较取值把一个 0/1 写进寄存器(说明重标) ----
                case 0x2F:   // 比较取值
                    注明(目标, "刚算出的比较结果(0/1)", 源码行);
                    return;

                // ---- P12:取字索引把"基址+下标×宽"那个字读进寄存器(说明重标) ----
                case 0x32:   // 取字索引
                    注明(目标, 哪一行(源码行, 指令), 源码行);
                    return;

                case 0x0C:   // 出栈
                    注明(目标, "刚出栈取回的值", 源码行);
                    return;
                case 0x27:   // 读取字符
                    注明(目标, "刚读入的字符(来自输入)", 源码行);
                    return;
                default:
                    return;   // 跳转/比较/入栈/停机之类不改寄存器
            }
        }

        /// <summary> 间接访问:地址寄存器如果指着帧内某个偏移,就翻成"局部变量 数(短整数) 的值"(连名字一起给出来) </summary>
        private (string 文本, 名字项C? 项) 间接说明(int 地址寄存器)
        {
            var 指针 = 取(地址寄存器);
            if (指针 is { 是地址: true, 帧偏移: { } 偏移 })
            {
                var 局部 = 反查局部(偏移);
                if (局部 != null) return ($"{描述(局部)} 的值", 局部);
                return ($"帧内偏移 {偏移} 处的值", null);
            }
            return ($"从 [{寄存器C.名称(地址寄存器)}] 指向的内存读来的值", null);
        }

        /// <summary> 地址 → 全局变量(含"结构字段/数组元素"),查不到返回 null </summary>
        private (string 文本, 名字项C 项)? 反查地址(uint 地址值, int 宽)
        {
            int 地址 = (int)地址值;
            if (_地址到全局.TryGetValue(地址, out var 精确)) return (描述(精确), 精确);
            foreach (var (基址, 项) in _地址到全局)
            {
                int 终点 = 基址 + 项.宽度;
                if (地址 <= 基址 || 地址 >= 终点) continue;
                int 偏移 = 地址 - 基址;
                if (项.是数组 && 项.元素宽 > 0)
                {
                    int 第几个 = 偏移 / 项.元素宽;
                    return ($"{项.名字}[{第几个}]({名字表C.显示类型名(项.类型名)})", 项);
                }
                if (_名字表 != null && _名字表.结构.TryGetValue(项.类型名, out var 字段表))
                {
                    foreach (var 字段 in 字段表)
                        if (偏移 >= 字段.偏移 && 偏移 < 字段.偏移 + 字段.宽度)
                            return ($"{项.名字}.{字段.名字}({字段.类型名})", 项);
                }
                return ($"{项.名字} 里的第 {偏移} 个字节", 项);
            }
            return null;
        }

        /// <summary> 帧内偏移 → 局部变量(要靠"第几行落在哪个函数里"确定是哪个函数的帧) </summary>
        private 名字项C? 反查局部(int 偏移)
        {
            if (_名字表 == null) return null;
            var 当前 = _名字表.行所属函数(当前源码行);
            foreach (var 项 in _名字表.变量)
            {
                if (项.是全局 || 项.帧偏移 != 偏移) continue;
                if (当前 != null && !string.Equals(项.所属函数, 当前, StringComparison.OrdinalIgnoreCase)) continue;
                return 项;
            }
            return null;
        }

        /// <summary> 当前正在算的那一行(登记时顺手记下,给"帧内偏移反查局部变量"用) </summary>
        public int 当前源码行 { get; set; }

        /// <summary> 记最近一笔账时的帧指针(写进记录里,界面靠它丢过期说明) </summary>
        private uint _当前帧指针;

        /// <summary> "变量 字(字符)" 这种给人看的描述 </summary>
        internal static string 描述(名字项C 项) =>
            $"变量 {项.名字}({显示类型(项)})";

        /// <summary> 变量的类型名(给人看的样子:数组写成"数组[4](短整数)",引用写成"引用(点)",静态方法容器的内部名字换成人能看懂的那个) </summary>
        internal static string 显示类型(名字项C 项) =>
            项.是引用 ? $"引用({名字表C.显示类型名(项.指向类型名)})"
            : 项.是数组 ? $"数组[{项.元素个数}]({名字表C.显示类型名(项.类型名)})" : 名字表C.显示类型名(项.类型名);

        private static string 帧内偏移说明(int 偏移) => $"指向帧内偏移 {偏移} 的地址";
    }
