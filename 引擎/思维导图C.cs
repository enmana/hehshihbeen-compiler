    /// <summary>
    /// **思维导图的形状**(纯逻辑,不吃界面、不碰编译):展开 / 截断 / 追溯 / **视野**。
    ///
    /// 三条口径:
    ///   · **一次长一层,长过的仍在树上**(展开仍是追加,已经长出来的子节点一个不动)——
    ///     但**"这一屏画什么"由视野说了算**(H63-2 `算可见`:默认只画当前那一格的**父链 + 自己 + 直接子**,
    ///     兄弟枝与走过的旁支**隐藏**;顶上那个"全集图"开关才看全)。**H33 那条"只追加不清除"的口径
    ///     就此作废**:不清除的是**数据**,不是画面(硬规矩 16 —— 不留"两套增长策略并存"的半套);
    ///   · **一层最多先长 20 个**,还有剩就挂一条"…"(点它才全部长出来;长完"…"自己消失);
    ///   · **同一个节点点第二次不再长**(幂等),想全要就点"…"。
    /// </summary>
    public sealed class 导图模型C
    {
        /// <summary> 第一次展开一层最多长几个(用户 2026-09-25 拍板:20 个 + 一条"…") </summary>
        public const int 一屏子项 = 20;

        /// <summary> 那条"…"的键(在它父节点的子表里唯一) </summary>
        public const string 更多键 = "\u0001更多";

        private readonly 取子项委托 _取子项;
        private readonly List<导图节点C> _追溯 = [];

        /// <summary> 全部节点(**按长出来的先后**;界面照这个顺序画 —— H63-2 起还要再过一个"视野"筛子) </summary>
        public List<导图节点C> 节点表 { get; } = [];

        /// <summary>
        /// **回连线那一张表**(H61-2):每条 = 一个框**指回**声明区某一项。
        /// 与父子边分开存:父子边一个父只连自己的子,回连线可以横跨半棵树(链节框在很深的调用区,
        /// 目标在文件框的声明区)。谁记谁清:`加回连` 记、`收起` 时 `清悬空回连` 清。
        /// </summary>
        public List<回连线C> 回连线 { get; } = [];

        /// <summary> 根节点(它一定在 `节点表` 的第一位) </summary>
        public 导图节点C 根 { get; }

        public 导图模型C(导图子项C 根项, 取子项委托 取子项)
        {
            ArgumentNullException.ThrowIfNull(根项);
            _取子项 = 取子项 ?? (_ => []);
            根 = 新节点(根项, null);
            节点表.Add(根);
            _追溯.Add(根);
        }

        /// <summary> 追溯栈现在有几步 </summary>
        public int 追溯步数 => _追溯.Count;

        /// <summary> 追溯栈现在站在第几步(0 基;栈空 = -1) </summary>
        public int 追溯位 { get; private set; }

        /// <summary> 现在站在哪(栈空 = null) </summary>
        public 导图节点C? 当前追溯 => 追溯位 >= 0 && 追溯位 < _追溯.Count ? _追溯[追溯位] : null;

        private 导图节点C 新节点(导图子项C 项, 导图节点C? 父) => new()
        {
            键 = 项.键,
            标题 = 项.标题,
            说明 = 项.说明 ?? "",
            小字 = 项.小字 ?? "",
            提示 = 项.提示 ?? "",
            悬停 = 项.悬停 ?? "",
            种类 = 项.种类,
            行 = 项.行,
            文件 = 项.文件,
            声明边 = 项.声明边,
            竖排 = 项.竖排,
            竖排字 = 项.竖排字,
            能往下长 = 项.能往下长,
            附加 = 项.附加,
            父 = 父,
        };

        /// <summary>
        /// **长一层**(点一个框走这条)。已经长过就**什么都不做**(幂等,返回假)——
        /// 想接着要剩下的那条"…"的分支见 `展开全部`。
        /// </summary>
        public bool 展开一层(导图节点C 节点) => 节点 is { 已展开: false, 能往下长: true } && 长(节点, 全部: false);

        /// <summary> **这一层全要**(点"…"走这条;已经全在树上就返回假) </summary>
        public bool 展开全部(导图节点C 节点)
        {
            if (节点 == null || !节点.能往下长) return false;
            if (节点.已展开 && !节点.还能长) return false;
            return 长(节点, 全部: true);
        }

        private bool 长(导图节点C 节点, bool 全部)
        {
            节点.全量 ??= _取子项(节点) ?? [];
            节点.总数 = 节点.全量.Count;
            int 到 = 全部 ? 节点.全量.Count : Math.Min(节点.全量.Count, 节点.已生成 + 一屏子项);
            if (到 <= 节点.已生成 && 节点.已展开) return false;

            去掉更多(节点);
            for (int i = 节点.已生成; i < 到; i++)
            {
                var 子 = 新节点(节点.全量[i], 节点);
                节点.子.Add(子);
                节点表.Add(子);
            }
            节点.已生成 = 到;
            节点.已展开 = true;
            if (节点.已生成 < 节点.总数) 加更多(节点);
            记追溯(节点);
            return true;
        }

        private void 加更多(导图节点C 父)
        {
            var 条 = new 导图节点C
            {
                键 = 更多键,
                标题 = "…",
                说明 = $"还有 {父.总数 - 父.已生成} 条",
                提示 = "点这里全部生成",
                种类 = 导图种类C.更多,
                能往下长 = false,
                父 = 父,
            };
            父.子.Add(条);
            节点表.Add(条);
        }

        private void 去掉更多(导图节点C 父)
        {
            父.子.RemoveAll(x => x.种类 == 导图种类C.更多);
            节点表.RemoveAll(x => x.种类 == 导图种类C.更多 && ReferenceEquals(x.父, 父));
        }

        /// <summary>
        /// **收起这一枝**(右键菜单里的那条):把这一枝长出来的后代全收掉,自己回到"没长过"的样子。
        /// 收掉的是**这一枝自己长出来的**,别的枝一个不动 —— "以前生成的不清除"那条只约束展开,不约束收起。
        /// `全量` 缓存也一起丢掉:收回之后再点,数据可能已经变了(改了代码、又编了一次)。
        /// </summary>
        public bool 收起(导图节点C 节点)
        {
            if (节点 == null || 节点.子.Count == 0) return false;
            var 要收 = new List<导图节点C>();
            攒后代(节点, 要收);
            foreach (var 节 in 要收) 节点表.Remove(节);
            节点.子.Clear();
            节点.已展开 = false;
            节点.已生成 = 0;
            节点.总数 = 0;
            节点.全量 = null;
            清悬空回连();       // H61-2:落在收掉的那些节点上的回连线一起走,不许留悬空
            // 追溯栈里被收掉的那些再也点不到,整条栈跟着清到"现在这个"为止
            if (追溯位 >= 0 && 追溯位 < _追溯.Count - 1) _追溯.RemoveRange(追溯位 + 1, _追溯.Count - 追溯位 - 1);
            return true;
        }

        private static void 攒后代(导图节点C 节点, List<导图节点C> 结果)
        {
            foreach (var 子 in 节点.子)
            {
                结果.Add(子);
                攒后代(子, 结果);
            }
        }

        // ---------------- 回连线(H61-2:链节 → 声明区那一项) ----------------

        /// <summary>
        /// **把一条键路铺出来**(H61-2 的"自动展开";口径 ⑤"目标没展开就自动展开")。
        /// 从根出发沿着一格一格的**节点键**往下走;哪一格还没生成,就先 `展开全部` 那个父节点再找
        /// (声明区里有几百条时也一步走到目标 —— `展开一层` 只出 20 条,不够用)。
        ///
        /// `键路` 从**文件框**起(第一格允许是根的后代:工程根下面就是文件框那一层);
        /// 根自己出现在哪一格就从它的下一格接(起点是方法框时也一样走得通)。
        /// 走不通(代码改了 / 这条根本不在)给 `null` —— 界面照旧说人话,不抛。
        /// </summary>
        public 导图节点C? 铺到(IReadOnlyList<string>? 键路)
        {
            if (键路 == null || 键路.Count == 0) return null;
            var 节 = 根;
            int 起 = 0;
            for (int i = 0; i < 键路.Count; i++)
                if (string.Equals(键路[i], 根.键, StringComparison.Ordinal)) 起 = i + 1;
            for (int i = 起; i < 键路.Count; i++)
            {
                var 子 = 找子(节, 键路[i]);
                if (子 == null)
                {
                    展开全部(节);                  // 这一层可能只长了头 20 条
                    子 = 找子(节, 键路[i]);
                }
                if (子 == null) return null;
                节 = 子;
            }
            return 节;
        }

        /// <summary> 直接子节点里按 `键` 找一个(H61-2;不递归 —— 递归那件事由 `铺到` 一格一格做) </summary>
        private static 导图节点C? 找子(导图节点C 节, string 键)
        {
            foreach (var 子 in 节.子)
                if (string.Equals(子.键, 键, StringComparison.Ordinal)) return 子;
            return null;
        }

        /// <summary> 整棵树里按 `键` 找一个节点(还没生成出来给 null;H61-2 补线时"目标已经在树上就接上") </summary>
        public 导图节点C? 找节点(string? 键)
        {
            if (string.IsNullOrEmpty(键)) return null;
            foreach (var 节 in 节点表)
                if (string.Equals(节.键, 键, StringComparison.Ordinal)) return 节;
            return null;
        }

        /// <summary>
        /// **按一条键路找"现在已经在树上"的那一格**(H63-1;不展开、不新建)。
        ///
        /// 与 `铺到` 的分工:那个走不通会顺手把那一层**展开**;这个只看现在这棵树,一步不展开。
        /// 为什么不接着用 `找节点`(全树按键扫):H63-1 之后**同一个键可以在树上出现两次** ——
        /// 本文件的方法**既**在文件框的声明区里有一个框,**又**在调用链上"跟着调用走"挂了一个框;
        /// 全树扫会拿到先建出来的那一个,红线就指到了另一个枝上 ⇒ 补线必须**从根一格一格走**。
        /// 走不通给 null(代码改了 / 这一格还没生成 —— 那件事归 `铺到`,这里不硬猜)。
        /// </summary>
        public 导图节点C? 沿路找(IReadOnlyList<string>? 键路)
        {
            if (键路 == null || 键路.Count == 0) return null;
            var 节 = 根;
            int 起 = 0;
            for (int i = 0; i < 键路.Count; i++)
                if (string.Equals(键路[i], 根.键, StringComparison.Ordinal)) 起 = i + 1;
            for (int i = 起; i < 键路.Count; i++)
            {
                节 = 找子(节, 键路[i]);
                if (节 == null) return null;
            }
            return 节;
        }

        /// <summary>
        /// **H63-5:当场把一组"现成的子项"挂到某一格下面**(方法框右键「看谁调用它」走这条)。
        ///
        /// 与 `取子项` 那条路**分开走**:那条答的是"这个框**本来长什么**"(声明区 / 调用区 / 调用链),
        /// 这一组是**当场问 IDE 要来的另一份数据**(工程级调用边表里的调用者)—— 数据源不同,
        /// 所以**不进 `全量` 缓存**(混进去之后"再点一下展开"就会把它当成这个框自己那一层)。
        /// 挂上去的排在同一层**最前面**(用户刚点了「看谁调用它」,要看的就是这一段);
        /// 同一个键不重复挂(再点一次不会翻倍);`收起` 那一枝时它跟普通子项一样一起走。
        /// 返回**这一次真挂了几条**(0 = 重复 / 空表)。
        /// </summary>
        public int 挂子项(导图节点C 父, IReadOnlyList<导图子项C>? 项们)
        {
            if (父 == null || 项们 == null || 项们.Count == 0) return 0;
            var 新 = new List<导图节点C>();
            foreach (var 项 in 项们)
            {
                if (父.子.Any(x => string.Equals(x.键, 项.键, StringComparison.Ordinal))) continue;
                新.Add(新节点(项, 父));
            }
            if (新.Count == 0) return 0;
            父.子.InsertRange(0, 新);
            节点表.AddRange(新);
            return 新.Count;
        }

        /// <summary>
        /// **H63-2 的视野**(纯函数,不碰界面):给"当前站在哪一格",算出**这一屏要画哪些框**。
        ///
        /// 用户 2026-09-26 的原话:「**只显示三层**:父级,自己,子级 …… 红线连过去的地方**也只展示
        /// 声明处和声明处的父级**,意思就是**只展示相关的,无关的不展示**」+ 当班拍板的两条口径:
        /// ① **父链全留、只收掉兄弟枝**(不是严格三层 —— "不丢线索"靠的正是父链,"无关的不展示"靠的是
        /// 收掉别的枝);② **视野模型做默认 + 全集图开关**(全集图 = 旧那一套"长过的全都画")。
        ///
        /// 于是这一屏 = 当前那一格的**父链(含自己)+ 它的直接子**,**再加"这一屏里看得见的那些链节"
        /// 拉出来的红线那一头** —— 红线那头按口径**只给"声明处 + 它的父链"**(不给它的兄弟枝、
        /// 也不给它的子)。**别枝上早先拉过的红线不算**:那些链节这一屏根本没画,
        /// 把它们的声明区拖进来只会让画面越点越大(实测:不筛这一条,示例06 点到第 9 轮就涨到 2998×4862,
        /// 比"长的全都画"还大 —— 探针 `工具\临时\h284` 量出来的)。
        /// **必须是从根连下来的一棵闭子树** —— 可见的框,它的父一定也可见,不然布局那一层会把这个框
        /// 挂到不存在的父旁边(见 `导图布局C.排` 的 `可见`)。
        ///
        /// `当前` 给 null ⇒ 按**根**算(还没点过任何框的第一屏);`全集图` 为真 ⇒ 全都画(旧行为,保留)。
        /// </summary>
        public HashSet<导图节点C> 算可见(导图节点C? 当前, bool 全集图)
        {
            if (全集图) return new HashSet<导图节点C>(节点表);
            var 可见 = new HashSet<导图节点C>();
            var 起 = 当前 ?? 根;
            for (var 节 = 起; 节 != null; 节 = 节.父) 可见.Add(节);
            foreach (var 子 in 起.子) 可见.Add(子);
            // 红线:只认"这一屏里已经看得见的链节"拉出来的那些线;声明处那一头只往上带父链。
            // 几轮就够(带上来的父链通常不会再引出新的链节),但写成到不动点为止,免得漏。
            for (int 轮 = 0; 轮 < 4; 轮++)
            {
                bool 又加了 = false;
                foreach (var 边 in 回连线)
                {
                    if (!可见.Contains(边.从)) continue;
                    for (var 节 = 边.到; 节 != null; 节 = 节.父) 又加了 |= 可见.Add(节);
                }
                if (!又加了) break;
            }
            return 可见;
        }

        /// <summary>
        /// **记一条回连线**(H61-2):两头都必须在**现在这棵树上**(不然就是悬空),同一条线不记第二遍。
        /// 返回真 = 这一次真记上了(自检与探针拿它数"拉了几条红线")。
        /// </summary>
        public bool 加回连(导图节点C? 从, 导图节点C? 到)
        {
            if (从 == null || 到 == null) return false;
            if (!节点表.Contains(从) || !节点表.Contains(到)) return false;
            foreach (var 边 in 回连线)
                if (ReferenceEquals(边.从, 从) && ReferenceEquals(边.到, 到)) return false;
            回连线.Add(new 回连线C { 从 = 从, 到 = 到 });
            return true;
        }

        /// <summary>
        /// 把落在"已经不在树上"的节点上的回连线**一起清掉**(H61-2 ③:收枝之后不许留悬空)。
        /// 收起 / 收起全部那一族动完树必调它。
        /// </summary>
        private void 清悬空回连()
        {
            if (回连线.Count == 0) return;
            var 在 = new HashSet<导图节点C>(节点表);
            回连线.RemoveAll(边 => !在.Contains(边.从) || !在.Contains(边.到));
        }

        /// <summary> 展开成功就把"我点到这儿了"压进追溯栈(后面的重做一律丢掉 —— 与编辑器撤销同一套口径) </summary>
        private void 记追溯(导图节点C 节点)
        {
            if (追溯位 >= 0 && 追溯位 < _追溯.Count - 1) _追溯.RemoveRange(追溯位 + 1, _追溯.Count - 追溯位 - 1);
            if (_追溯.Count == 0 || !ReferenceEquals(_追溯[^1], 节点)) _追溯.Add(节点);
            追溯位 = _追溯.Count - 1;
        }

        /// <summary> 往前一步(上一个我点过的框);到头了给 null </summary>
        public 导图节点C? 后退()
        {
            if (追溯位 <= 0) return null;
            追溯位--;
            return _追溯[追溯位];
        }

        /// <summary> 往后一步;到头了给 null </summary>
        public 导图节点C? 前进()
        {
            if (追溯位 < 0 || 追溯位 >= _追溯.Count - 1) return null;
            追溯位++;
            return _追溯[追溯位];
        }

        /// <summary> 状态行那一句:"第 3 / 7 步:数学.求和" </summary>
        public string 追溯说明()
        {
            var 节点 = 当前追溯;
            if (节点 == null) return "还没有展开过任何一层";
            return $"第 {追溯位 + 1} / {追溯步数} 步:{节点.标题}";
        }
    }

    /// <summary>
    /// 排版的间距参数(都在这儿,想调只改这一处)。
    ///
    /// **H60-14 把框整体放大了**(用户口径 ⑧「导图框整体放大(尺寸 / 字号 / 内边距)」):
    /// 框里那三行字号 12 / 11 / 10.5 → **14 / 12.5 / 11.5**,内边距 (12,6,12,6) → **(16,10,16,10)**,
