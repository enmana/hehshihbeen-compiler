    /// <summary>
    /// **导图的缩放**(H63-3;纯函数,不碰界面):算"适应窗口"那个比例、以及"滚到某一格"该给多少滚动偏移。
    ///
    /// 为什么单独摆在这儿:两处都要按**缩放比例**换算(`滚到` 与双击之后的高亮),算错了就是
    /// "点了适应窗口之后滚到别处去了" —— 钉在自检里比在窗口里肉眼看稳。
    /// 窗口那一侧只做三件:把比例塞进 `ScaleTransform`、把偏移塞进 `ScrollViewer`、把光标底下那个点留住。
    /// </summary>
    public static class 导图缩放C
    {
        /// <summary> 缩放下限(5% —— 示例06 全量视图 6854 高,要塞进 680 的窗口要 ~0.099,别卡在这儿) </summary>
        public const double 最小 = 0.05;

        /// <summary> 缩放上限(300%) </summary>
        public const double 最大 = 3.0;

        /// <summary>
        /// **「适应窗口」那个比例**:让整张画布进视口(四周留一点边:`留边` 0.98),
        /// 再夹进 [`最小`, `最大`]。画布 / 视口尺寸有一个说不上(≤0)就给 1(不缩放,照旧)。
        /// </summary>
        public static double 适应比例(double 画布宽, double 画布高, double 视口宽, double 视口高, double 留边 = 0.98)
            => 画布宽 <= 0 || 画布高 <= 0 || 视口宽 <= 0 || 视口高 <= 0
                ? 1.0
                : Math.Clamp(Math.Min(视口宽 / 画布宽, 视口高 / 画布高) * 留边, 最小, 最大);

        /// <summary> 再夹一次(滚轮 / 滑条来的比例都要过它) </summary>
        public static double 夹比例(double 比例) => Math.Clamp(比例, 最小, 最大);

        /// <summary>
        /// **要把这一格滚到视口中间时,`ScrollViewer` 该给的偏移**(画布坐标 → 滚动偏移):
        /// 中心 = (坐标 + 框长 / 2) × 比例,再减视口的一半;负的夹到 0(到头了)。
        /// </summary>
        public static double 居中偏移(double 坐标, double 框长, double 视口长, double 比例)
            => Math.Max(0, (坐标 + 框长 / 2) * 比例 - 视口长 / 2);

        /// <summary> 从视口左上角那一格起(往回滚到最前):给 0 就行;留这个口子只为把"两处都走同一个换算"写明</summary>
        public static double 起点偏移(double 坐标, double 比例) => Math.Max(0, 坐标 * 比例);
    }

    /// <summary>
    /// **思维导图的排版**(纯函数:给一棵树 + 一个"量字宽"的口子,把每个框的 x/y/宽/高填好)。
    /// 左 → 右一层一列;父节点在自己那几枝的**竖直中点**上,所以连线是发散出去的。
    ///
    /// 为什么"量宽"要传进来:`FormattedText` 要 WPF 那一套,自检里不想要 ——
    /// 自检喂一个"每字 8 像素"的假量法,算出来的坐标照样能钉(不重叠 / 列递增 / 空树不炸)。
    /// </summary>
    public static class 导图布局C
    {
        /// <summary> 量一行字有多宽(界面传 FormattedText 那份;自检传固定字宽那份) </summary>
        public delegate double 量宽委托(string 文本);

        /// <summary> 自检 / 没装字体时的兜底量法:每个字符 8.4 像素 </summary>
        public static double 假量宽(string 文本) => (文本 ?? "").Length * 8.4;

        /// <summary>
        /// **子项多就把层间距拉开**(H61-1 口径 ⑥;用户原话「当一个项的子项过多时,可以适当的把项与子项的距离拉开一些」):
        /// 按一个框的**子项数**分三档加行距 —— ≥8 ×1.3 / ≥15 ×1.7 / ≥25 ×2.2,不到 8 条就是原来的 1.0。
        /// **只加行距,框宽不动**(框宽仍由字数决定,见 `排` 的第 ① 步)。
        ///
        /// 怎么数:取 `节点.子.Count` 与 `节点.总数` 里大的那个 —— 一层先长 20 条的截断不该让间距忽大忽小
        /// (点了「…」全部生成之后,同一层的间距与之前一致)。
        /// </summary>
        public static double 行距倍数(int 子项数)
            => 子项数 >= 25 ? 2.2 : 子项数 >= 15 ? 1.7 : 子项数 >= 8 ? 1.3 : 1.0;

        /// <summary> 这个框这一层的行距(倍数 × `参数.行间距`;
        /// **H63-2 起按"看得见的子项数"算** —— 视野里兄弟枝收起来之后,别拿全量的条数去撑间距) </summary>
        private static double 这一层的行距(int 子项数, int 总数, 导图布局参数C 参)
            => 参.行间距 * 行距倍数(Math.Max(子项数, 总数));

        /// <summary>
        /// 排一遍;返回画布要多大(宽, 高)。
        ///
        /// **H63-2 多一格 `可见`**:给了它就**只排看得见的那些框**(视野模型;`null` = 全都排,老口径)。
        /// 传进来的必须是"父在、子才在"的闭集(见 `导图模型C.算可见`)—— 不然子框会挂到不存在的位置上;
        /// 这个口子**不改树**:看不见的框只是不排(它们的 `X/Y/宽/高` 停在上一回算出来的数上,不拿来画)。
        /// </summary>
        public static (double 宽, double 高) 排(导图节点C 根, 量宽委托? 量宽 = null, 导图布局参数C? 参数 = null,
            IReadOnlySet<导图节点C>? 可见 = null)
        {
            var 参 = 参数 ?? new 导图布局参数C();
            if (根 == null) return (0, 0);
            量宽 ??= 假量宽;

            var 层 = new List<List<导图节点C>>();
            收集(根, 0, 层, 可见);

            // ① 量框:宽 = 最长那一行文字 + 两侧内边距(夹在最小 / 最大之间);高 = 行数 × 行高 + 上下内边距
            //    (只量看得见的 —— 看不见的那些这一回不画)
            foreach (var 一层的 in 层)
                foreach (var 节 in 一层的)
                {
                    double 文字宽 = 量宽(节.标题);
                    if (节.小字.Length > 0) 文字宽 = Math.Max(文字宽, 量宽(节.小字) + 4);
                    if (节.说明.Length > 0) 文字宽 = Math.Max(文字宽, 量宽(节.说明) + 4);
                    if (节.提示.Length > 0) 文字宽 = Math.Max(文字宽, 量宽(节.提示) + 4);
                    double 竖排占 = 节.竖排 ? 参.竖排宽 : 0;      // H61-1:左边那条竖排种类标签的位置
                    节.宽 = Math.Clamp(文字宽 + 参.横内边距 * 2 + 竖排占, 参.最小宽, 参.最大宽);
                    int 行数 = 1 + (节.小字.Length > 0 ? 1 : 0) + (节.说明.Length > 0 ? 1 : 0)
                        + (节.提示.Length > 0 ? 1 : 0);
                    节.高 = 行数 * 参.行高 + 参.纵内边距 * 2;
                }

            // ② 列位置:每一列多宽 = 这一层最宽那个框;列与列之间留 `列间距`
            double 累 = 参.左右留白;
            foreach (var 一层的 in 层)
            {
                double 最宽 = 一层的.Count == 0 ? 0 : 一层的.Max(x => x.宽);
                foreach (var 节 in 一层的) 节.X = 累;
                累 += 最宽 + 参.列间距;
            }
            double 总宽 = Math.Max(0, 累 - 参.列间距 + 参.左右留白);

            // ③ 行位置:后序 —— 先算每一枝要占多高,再从上往下落位(父节点落在子节点的中点)
            占(根, 参, 可见);
            落位(根, 参.上下留白, 参, 可见);
            return (总宽, 根.占高 + 参.上下留白 * 2);
        }

        /// <summary> 看得见这个子框吗(`可见` 为 null = 全都排,老口径)</summary>
        private static bool 看得见(IReadOnlySet<导图节点C>? 可见, 导图节点C 节) => 可见 == null || 可见.Contains(节);

        /// <summary> 按层收节点(顺序稳定:先来先放,子节点按数据顺序;看不见的子框连它的后代一起跳掉)</summary>
        private static void 收集(导图节点C 节, int 层号, List<List<导图节点C>> 层, IReadOnlySet<导图节点C>? 可见)
        {
            while (层.Count <= 层号) 层.Add([]);
            层[层号].Add(节);
            foreach (var 子 in 节.子)
                if (看得见(可见, 子)) 收集(子, 层号 + 1, 层, 可见);
        }

        private static double 占(导图节点C 节, 导图布局参数C 参, IReadOnlySet<导图节点C>? 可见)
        {
            int 子数 = 0;
            foreach (var 子 in 节.子) if (看得见(可见, 子)) 子数++;
            if (子数 == 0) { 节.占高 = 节.高; return 节.占高; }
            double 和 = 0;
            foreach (var 子 in 节.子)
            {
                if (!看得见(可见, 子)) continue;
                和 += 占(子, 参, 可见);
            }
            和 += 这一层的行距(子数, 节.总数, 参) * (子数 - 1);
            节.占高 = Math.Max(节.高, 和);
            return 节.占高;
        }

        private static void 落位(导图节点C 节, double 顶, 导图布局参数C 参, IReadOnlySet<导图节点C>? 可见)
        {
            导图节点C? 首 = null, 尾 = null;
            int 子数 = 0;
            foreach (var 子 in 节.子)
                if (看得见(可见, 子)) { 首 ??= 子; 尾 = 子; 子数++; }
            if (首 == null) { 节.Y = 顶; return; }

            double 起 = 顶, 这层行距 = 这一层的行距(子数, 节.总数, 参);
            foreach (var 子 in 节.子)
            {
                if (!看得见(可见, 子)) continue;
                落位(子, 起, 参, 可见);
                起 += 子.占高 + 这层行距;
            }
            double 中点 = (首.Y + 尾!.Y + 尾.高) / 2 - 节.高 / 2;
            double 上界 = 顶 + Math.Max(0, 节.占高 - 节.高);
            节.Y = Math.Clamp(中点, 顶, 上界);
        }
    }
