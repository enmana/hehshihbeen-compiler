        /// <summary> 从根到这里的唯一路径(追溯与"环护栏"都看它) </summary>
        public string 路径键 => 父 == null ? 键 : 父.路径键 + "\u0001" + 键;

        /// <summary>
        /// 本节点这一路上(含自己)有没有出现过这个名字 —— 递归调用靠它截断。
        ///
        /// **H63-1 起多一格 `文件`**:给了文件就要求"键与文件都对上"才算 —— 跟着调用走之后,
        /// **同一棵树里会同时挂着好几个文件的框**(本文件的方法既在声明区里有一个框,又可能被
        /// 别的文件的调用链挂一个框),而框键(`方法:名@头行`)**不带文件名**,
        /// 光比键会把"另一个文件里同名同行的方法"误认成这一枝上出现过。
        /// 不给文件 = 老口径(只比键);给了文件而有一边说不上(空串)也算对上 —— 宁可截断,不许打转。
        /// </summary>
        public bool 祖先里有(string 名, string 文件 = "")
        {
            for (var 节 = this; 节 != null; 节 = 节.父)
            {
                if (!string.Equals(节.键, 名, StringComparison.Ordinal)) continue;
                if (文件.Length == 0 || 节.文件.Length == 0 || 文件判定C.同文件(节.文件, 文件)) return true;
            }
            return false;
        }

        public override string ToString() => $"{标题}{(说明.Length > 0 ? "(" + 说明 + ")" : "")}";
    }

