            15,编成独立 exe:三档打包方式
              **编译一次就自动生成**(运行→编译,或 F5):产物出现在**项目目录里**(名字 = 项目名)。**打成什么,由工具栏那个「打包:」下拉说话**;命令行
              同一个词:`--打包 native_c` / `--打包 host_self` / `--打包 source_only`(也可以写三个正式名:原生 C / 自带运行时·单文件 / 只编译)。
              · **原生 C**(缺省;`hbcc 程序.hb --exe 程序.exe --方式 C` 或 `--打包 native_c`):机器码先转成 C 源码,再交本机 C 编译器(clang / gcc /
                cl)编。**产物几十~几百 KB、不带 .NET**,拷到任何 Windows 机器上双击就跑,编这一份也最快。代价:**编这一份的那台机器**要有 C 编译器
                (开发机装一次,拿到 exe 的机器都不用装);本机没有就换成下一档,或者 `--打包 只编译` 只交 C 源码
              · **自带运行时·单文件**(老那条;`--打包 host_self`):复制一份**自包含的 HB 宿主** + 贴机器码。**产物几十 MB**(实测约 70 MB),但
                **目标机器什么都不用装**。宿主第一次用会**在后台自动发布**(约一分钟,只做一次);手动发布:`dotnet publish HB宿主\\HB宿主.csproj
                -c Release -r win-x64 --self-contained -p:PublishSingleFile=true`。这一档还会**问宿主一句"你是哪一版"**(宿主带 `--能力` 报出自己
                支持到几号功能、读得动哪一档程序包):比当前代码旧的那份判**陈旧** —— 程序用到了它没有的能力(例如图形)、或者程序带顶层常量初值而它
                读不了新包、**或者程序有源码位置而它读不了"带源行表的包"**,就**这一轮不产 exe**,如实说清 + 后台重新发布;用不到的照常产,但在编译页
                写明"这份宿主比代码旧"。它还会校验宿主是不是真自包含,不是(例如盘上只有那份 0.18 MB 的框架依赖版)就**如实告诉你 + 后台重新发布**
              · **独立 exe 的运行期报错带行号**:贴尾巴时连一张"**地址 → 源码位置**"表一起带上(包格式 `HBE4`)—— 除零 / 栈溢出 / 间接跳转没对齐这类
                **运行期**错误,exe 里报的就是 `⚠ 运行停下:第 3 行:除零(除数是 0)`,多文件程序还带**文件名**(`目录.hb 第 57 行`)。**手写汇编(`.hba`)那一份同样带它自己的文件 + 行号**(`热路径.hba 第 8 行`);老包照旧只报说明
              · **只编译**(`--打包 source_only`):**一个 exe 都不产** —— 走「原生 C」那条路就交一份 **C 源码**(`.c`),走宿主那条路就交一份
                **`.hb`**(4 字节头 + 机器码);让**没有 C 编译器的机器照样用得上 C 后端**。**IDE 里它落 `<工程目录>\bin\`**
                (那两样与源码同后缀,落工程目录会把工作树弄脏;`bin/` 本来就不进版本库);命令行那条腿照旧**你 `-o` 指哪写哪**
              三档共有口径:生成的是**控制台程序**(双击打开一个控制台窗口,跑完**停住等你按任意键**);输入输出直连终端;`程序.exe < 输入.txt` 重定向
              输入;退出码 0 = 正常,1 = 运行期出错。**IDE 里一键在控制台窗口里跑**:运行 → 在控制台窗口里跑(`Ctrl+F5`)—— 编译(没编就编)后把刚生成的
              独立程序在**它自己的控制台窗口**里跑起来(退出码回写「输出」页)。与 F5 的分工:F5 跑在「输出」页里(能单步 / 断点 / 断言),这一条是**真终端**。
              **顶层常量的初值跟着程序包走**:`整数 初值 = 7;` / `短整数 表[3] = [1,2,3]` 这类初值不再编成"程序开头一串存储指令",而是随包带给宿主,
              装载时直接写进内存(代码段因此更短);初值区按**地址连续的段**合并;带初值的包用标记 `HBE3`,更早的 `HBE2`(逐条记)与没有初值的 `HBEX`
              **也照样能跑**。中文:控制台里手打中文没问题;**重定向的输入文件请存成 UTF-8**(存成 GBK 会乱码);上次选的哪一档记在**本机**(IDE 安装
              目录里的 `打包方式.json`),不进工程文件 —— 换台机器各选各的。**独立 exe 里没有 `运行进程` / `取网址`**:这两个能力靠工程文件 `.hbp` 里的
              白名单(`可执行文件` / `网址`),而独立 exe **没有工程文件** —— 与手机端同一条口径:调用一律返回 假,`取退出码()` / `取网址状态码()` 给
              `0xFFFFFFFF`,程序照常跑、不崩;要用它们就在工程里跑(WPF IDE 按 F5,或 `hbcc -p 工程.hbp --run`)

