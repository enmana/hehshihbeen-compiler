                指令),标签与源码**全局共用**(互相 `调用` / `跳转` 都行)。默认一个都不列;平时不用手改 JSON:打开 `.hba` 后勾「运行 → 汇编源码
                参与编译」。自动生成的 `<启动文件名>_ASM.hba` 是**整篇展开**,整个勾进来会和源码撞标签(见第23节)
              · 内存:可写 1MB / 512KB / 1048576,不写 = 1MB(写错了编译时直接告诉你);堆:64KB / 128KB / 131072,不写 = 64KB,不能比 `内存` 大;
                池:**一开始**多大,32KB / 256KB / 131072,不写 = 32KB,不能比 `内存` 大;软栈:64KB / 128KB / 65536,不写 = min(64KB, 内存 ÷ 4),
                上限 256KB;帧:**函数帧多大**,128 / 256 / 4096,不写 = **96 字节**,范围 96 ~ 4096、必须是 **4 的倍数**、不能比 `软栈` 大
              · 边界(可选):运行期下标越界检查。**不写 = 查**;`"开"` 也是查;`"关"` = 一次下标访问省 2~3 条指令,但**越界不再拦**(见第8节);
                编译期算得出的常量越界**照旧报错**;字符串取字(`名字[0]`)的检查不归它管
              · 子工程:打开项目时按这里的路径一起读出来(同一个工程只读一次,循环引用不会死循环)
              · 菜单:文件 → 新建项目 / 打开项目… / 生成工程文件(按目录内容自动生成一份);命令行:`hbcc -p 工程.hbp --run`(没给 `--in` 就用
                第一个资源当输入)。要控制编译顺序 / 多入口 / 带输入数据,或者想用 CLI 精确复现 IDE 的编译,就用它

            10,多文件与复用怎么选
              工程文件管"编译哪几个文件、什么顺序",**同时就是名字共享的范围**:**函数 / 结构类型 / 顶层全局变量**整个工程里随便用,哪个文件声明的
              都行,"先用、后声明"也行(编译器先把函数签名、结构定义、全局名字与数据槽收齐;只有全局 `引用` 是例外,它登记时要算目标地址,仍要声明
              在前)。**初始化代码仍然跟着声明那一句走**:`整数 计数 = 41;` 写在最后一个文件里,前面的文件执行到那一句之前读到的是 0。**同名会报
              错**,要隔离就给文件加一行 `模块 名字`(见下)。`包含 "路径"` 仍然管用(编译期内联),每个文件各自"只包含一次"。

            11,模块(把库的名字圈起来;两个库可以同名)
              两个库都写 `函数 求和` 就冲突。在库文件的**第一条**写一行 `模块 名字` 就解决了:
                模块 数学              // 库/数学.hb 的第一条(英文 module)
                私有 整数 调用次数 = 0;   // 私有:只有本模块能用
                程序集 整数 内部缓存 = 0; // 程序集:本工程里能用,别的工程用不了
                整数 累加器 = 0;         // 公开(不写 私有 / 程序集 就是公开)
                结构 结果 { 整数 和; 整数 个数; }
                方法 求和(整数 表[]) 返回 整数 { … }
                私有 方法 记一次() { 调用次数 = 调用次数 + 1; }
              · 这个文件里的**函数 / 结构 / 全局变量都自动带 `数学.` 前缀**(定义 `函数 求和` → `数学.求和`);外面写 `数学.求和(数据)`、
                `数学.结果 得分;`、`数学.累加器 = 5;`;于是**两个库都写 `求和` 也不打架**(标准工程 示例08_模块与库);模块**内部**写裸名字就行(`平均` 里直接写 `求和(表)`;
                先按全局找,找不到再用本模块的)
              · 可见性三档(写在**声明**前面,一个声明只写一个;写在**结构的字段**上也行):`公共`(默认,不写)—— 谁都能用;`程序集`(英文别名
                `internal`)—— 只在**同一个 `.hbp` 工程**里能用;`私有`(英文别名 `private`)—— 只在**同一个 `模块`** 里能用
              · `程序集` 覆盖 函数 / 结构 / 全局变量 / 列表(与 `私有` 同口径):`程序集 方法 f(…)` / `程序集 结构 点`(块头一行、`{` 另起一行)/
                `程序集 整数 计数 = 0;`
              · `程序集` 的**边界 = 单个 `.hbp` 工程**:子工程各算一个,子工程 A 的程序集成员子工程 B 用不了;别的工程引用它会当场报错并告诉你
                怎么办(去掉 `程序集`,或者加一个公开函数把它取出来)。**普通工程(没有子工程)里 `程序集` 与 `公共` 完全等价** —— 它是抓"意外
                耦合"的编译期纪律工具
              · `私有` 加在声明前面(函数 / 结构 / 全局变量 / 列表 / 字符串都行):**只有本模块能用**,外面引用它会当场报错并告诉你怎么办 —— 库的
                内部数据、内部助手用它挡起来
              · 可见性加在**结构的字段**上:`结构 账户` 里写 `私有 整数 余额;` 与 `整数 编号;` —— `余额` 只有声明它的模块能用,外面写 `账户.余额`
                (读 / 写 / 取地址 / 字面量初值 `[…]`)都会当场报错并给改法;`编号` 这种没标的前缀照旧公开(整个结构标 `私有` 也行,那是"结构本身
                不公开")
              · `模块` 必须是文件第一条(前面只能有空行和注释);同一个模块名不许声明两次(报重复定义)
              · **不写 `模块` 的文件语义一个字不变**(名字还是全全局)—— 老库、老程序照旧能编,两种写法可以混用

            12,编译期优化(默认开,平时不用管)
              编译器会把"生成的冗余指令"省掉:一条赋值少一条 MOV;循环里"每轮都重读但不会变"的变量/常量提到循环外面只读一次。**纯编译期的事:ISA
              一个字不改、程序结果一模一样**(自检"双跑对比"拿全部示例逐个验证:优化开/关跑出来必须完全一致)。编译页会写一行"优化:省掉 N 条冗余
              指令;把 K 个循环不变量提到循环外面;M 个数组的取址改成指针步进"。想对着"原样展开"查错:输出框写 优化="关"(命令行 `--no-opt`),
              写 优化="开" 恢复。
              不做提升的情况(循环体内含 函数调用 / 取地址 / 引用 / 间接写 / 列表添加 / **自己写的寄存器名**)—— 这几样一出现,编译器不敢断定那一格
              没被改过 ⇒ 那一段一律照原样展开,宁可少省几条,不许提错。序言也按需发:**只有"能顺着调用回到自己"的函数**才在入口查递归深度,叶子
              函数一条都不发;整篇没有递归时连那个隐藏槽和报错话都不生成。顶层常量的初值不编成代码了:随编译结果 / 程序包带给装载方,装载时直接写进
              内存(函数帧与循环体里的初值照旧现场写)。循环条件里的偏置掩码与"偏置后的界"都是编译期常量,提到循环外各占一个常驻寄存器,每轮少 4 条;
              有符号的 `x / 10`、`x % 10`(除数是正数常量)走短路径,同一次除法少 11 条(负数除法/取余都对)。**数组地址增量**:`循环 (整数 i = 0;
              i < n; i = i + 1)` 的体里读 `表[i]`(`表` 是定长数组)、体里没写过它时,元素地址提成**一个指针**,每轮只在**步进那一步**加立即数,
              一次访问少 3 条。**越界检查一条不少**,越界照样当场停下;写数组、下标不是那个**归纳变量**、体里又改归纳变量、计数器会回绕、嵌套循环这
              几种一律不提。

