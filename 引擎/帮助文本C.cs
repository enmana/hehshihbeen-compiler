                `等待(毫秒)` / `关闭窗口()` / `刷新()`;**有返回值那一档**:`打开窗口` 与 `取事件` 返回 `逻辑`,`取文字宽度(文本)` 返回 `整数`(等宽口径:ASCII 1 格、
                汉字 2 格)
              · `取事件` 的四个实参要写**变量名**(事件的值写回它们);**类型**五种:1 关窗 / 2 按键 / 3 移动 / 4 按下 / 5 抬起(同一个键码凑成一次"点一下")。
