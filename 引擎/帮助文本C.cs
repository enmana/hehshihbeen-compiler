            8,数据放哪儿、内存有多大
              变量槽紧跟代码之后,代码长了地址就大;写内存示例请从 0x2000 起,不要用 0x100 这类低地址(否则程序一大就会把自己的指令覆盖掉 ——
              自修改代码)。运行内存**默认 1MB**(1048576 字节;够写约 2 万行),上限 **64MB**(够约 130 万行);代码段 + 变量数据段从 0 往上排,
              栈从内存末尾往下长。想改:工程文件里写 `"内存": "512KB"`(也支持 `1MB` / 直接写字节数 `1048576`),最大 **64MB**。
              · 直接寻址仍是 20 位(前 1MB),但**地址一旦超过 20 位,编译器自己改走"载入高位 + 间接寻址"**(数据访问与代码跳转都算);**代价如实
                说**:摊开是"一条变几条" —— `取地址` / 大常量 **1 → 2 条**、`加载` / `取字` **1 → 3 条**、`存储` / `存字` / `比较立即数` **1 → 5 条**
                (后两档要借一个暂存寄存器,借之前先 `入栈` 护住);只在**地址真的超过 1MB** 时才摊,**1MB 档(不写 `内存`)一条都不摊**(标准工程 `示例60_大内存档` 是 4MB 档)
              · 堆区(`申请` 那块)**默认 64KB**;字符串池(运行期的字符串与动态列表住的那块)**一开始 32KB**,**池会自己长大**(不够就按倍增往上
                长,长到头才报错停机);软栈(函数调用/递归那块)**默认按运行内存算** = min(64KB, 内存 ÷ 4)(上限 256KB):默认一帧 96 字节、用到
                八成算太深 ⇒ 默认 64KB ≈ 546 层;函数帧(参数 + 局部变量 + 表达式临时槽共用)**默认 96 字节**,范围 96 ~ 4096、必须是 **4 的倍数**、
                不能比 `软栈` 大,撞上「帧超出」就调大(代价是同样的软栈能装的层数变少)。四处都在工程文件里改,见第9节
              · 编译完"编译"页会报代码 / 变量 / 剩余各多少字节与这次的堆、软栈大小;想看分区明细(代码段 / 变量槽 / 堆 / 池 / 软栈 / 空闲 / 给硬件栈
                留的那一块)就跑 `hbcc --run 主程序.hb`;池是从"空闲"那段往上长的 ⇒ 撞上"池用完了"先看这一行
              程序能写多大**不是无限的**:几条悬崖式硬上限在帮助站点左边「硬上限」一节里逐条列着 —— {{硬上限C.一句话()}}。每条的"什么写法会撞上 /
              撞上了怎么绕"也都在那一节里;撞上时编译器当场报错并说清上限。
              数组还是列表?个数**写得出**就用数组(`短整数 表[8]`);**写不出/会变**就用列表(`短整数 分数[]`);列表个数编译器先算(数你
              `.添加()` 几次),算不出(在循环里加)就自动长大。**下标越界一律当场拦住**:每次下标访问都比一下上界(热路径多 2~3 条指令),越界就停下
              并说清"只有几个、下标从 0 起";真在乎那几条指令、且自己保证不越界,可以在工程文件里写 `"边界": "关"` 关掉(见第9节);编译期算得出的
              常量越界**照旧报错**。**两个括号各管一件事**:`[ … ]` = 数组 / 列表的初值与整体赋值(`短整数 表[5] = [10, 20];`);`{ … }` = 语句块
              —— 不混用,老写法 `= {1, 2, 3}` 当场报错并指到 `[…]`。

