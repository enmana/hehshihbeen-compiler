            31,网络:自己连一台主机、或者当一个小服务端
                《30》那条是"**宿主替你把 HTTP 取回来**"(`取网址`,同步一次性 GET);这一节是**裸 TCP**(与前面那些宿主能力同一档):
                    听 = 监听("127.0.0.1", 8080, 听);            // 绑哪块网卡(写 IP)+ 端口;用不了给 -1
                    客 = 接受(听, 客);                            // **同步阻塞**:有人来连才往下走
                    整数 块长 = 接收(客, 块, 4096);                // 收到几个字节;0 = 对端关掉了;-1 = 出错
                    发送(客, "你好");                             // 返回真发出去的字节数
                    关闭(客);                                      // 关连接 / 关监听都是它(0 = 成功)
                    连 = 连到("例子.测试", 8080, 连);               // 客户端这一侧;同步,连不上给 -1
                    如果 (主机解析("例子.测试", 地址)) { 输出行(地址); }   // 主机名 → 地址(写进那个字符串变量)
              · **主机 + 端口必须先声明**:在工程文件 `.hbp` 里加一条 `"网址": [ "127.0.0.1:8080" ]`。这一节的原语与 `取网址` 共用那张表,但**裸 socket 只认写到端口的
                声明**(不带端口那一式管的是 http / https 的默认端口)—— 不在表里的**连试都不试**:`连到` / `监听` / `接受` 给 -1,主机解析给 假
              · **这一族全同步阻塞**:连接要等连上(最多 5 秒,到点给状态 18)、`接受` 要等人来、收发要等数据到;要"别堵在这儿"看第33节。**句柄**是一个 `整数` 变量接
                的值(与流的句柄同一套写法,但**两张表的号互不相干**):监听句柄只能 `接受`(收发会给 -1);连接句柄收发都行;`关闭` 之后那个句柄一律作废(状态 22);
                同时最多开 32 条连接 / 监听(表满给状态 23)
              · **返回值分四档**:`连到` / `监听` / `接受` 给**句柄**(失败 -1);`发送` 给**真发出去的字节数**;`接收` 给**收到的字节数**(`0` = 对端关掉了,这时那个字符串
                变量被清空);`关闭` 给**状态码**(0 = 成功)
              · `接收(句柄, 数据变量, 上限)` 的 `上限` 是**编译期数字**(1 ~ 1048576);一次真能收到几个字节由网络说了算,所以按"还差几个字节"循环收:
                  当 (已收 < 要收的数 && 块长 > 0) { 块长 = 接收(句柄, 块, 64); 如果 (块长 > 0) { 拼接到(全文, 块); 已收 = 已收 + 块长; } }
              · `监听` 的"网卡地址"要写 **IP 字面量**(`127.0.0.1` 只收本机、`0.0.0.0` 哪块网卡都收)—— 不认主机名;写别的给状态 9。**手机端与独立 exe 没有这一族能力**:
                它们带不了白名单,整族一律给 -1 / 假
              · **二进制报文用带"块"的那两条**:`发送块(句柄, 块地址, 字节数)` / `接收块(句柄, 块地址, 容量)` —— 与 `发送` / `接收` 走同一条路,差别只在**数据住在哪**。
                为什么要它们:`字符串` 是**文本**容器 —— `.长度()` 数的是**文字**、`名字[下标]` 给的是**解码后的码点**,而 `拼接到(串, 字节变量)` 写进去的也是**码点**
                (`字节 200` 存成 `U+0200` 两个字节)⇒ 帧头 / 协议包 / 机器码这类"里面有任意字节"的东西,用 `发送` / `接收` **做不了**(`0x81` 收下来读不回来,
                `0x00` 也发不出去)。带"块"的那两条把字节摆进 `申请` 回来的内存里,`取字` / `存字` 逐字节读写:
                    地址 帧 = 申请(64);
                    存字(帧, 0, 0xC8007E81);                      // 字节 81 7E 00 C8(小端)
                    发送块(客, 帧, 4);                             // 发 4 个字节,含 0x00 也照发
                    整数 收到 = 接收块(客, 帧, 64);                // 收进那块内存,返回收到的字节数
                    整数 首字节 = 取字(帧, 0) & 255;               // 129 —— 这一格 `接收` 给不了你
                    释放(帧);
                `发送块` 的字节数是**显式给的**(数字或变量,**不认字符串头、也不扫 0**);`接收块` 的容量由调用方保证。标准工程 示例29_网络 有全套例子。**`连到` 不叫
                `连接`**:`连接`(英文 `connect`)是 `库\string.hb` 里"把几段拼成一条"那个库函数的名字(`出` 的英文别名 `result` 同理)

