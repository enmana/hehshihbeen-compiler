                  逻辑 开 = 打开窗口("HB 图形演示", 320, 200);
                  如果 (开) { 当 (真) {
                      清屏(0xFF101018);                      // 整窗铺一个底色(命令,没有返回值)
                      画矩形(10, 10, 120, 40, 0xFF2A6EF0);    // 填充矩形
                      画文字(16, 24, "你好,HB", 0xFFFFFFFF);   // 等宽单行
                      画线(0, 60, 319, 60, 0xFF3C3C46);
                      刷新();                                // 不刷新就一直不显示
                      等待(16);                              // 让出一帧,别把 CPU 烧满
                      整数 类型;  整数 键码;  整数 x;  整数 y;
                      如果 (取事件(类型, 键码, x, y)) { 如果 (类型 == 1) { 跳出; } }   // 1 = 关窗;不阻塞
                  } 关闭窗口(); }
