            17,断点与单步(调试)
              断点:调试菜单 → 切换断点(F9),也可以**点行号左边的空白处**一下(红点 = 有断点);断点跟着工程走(项目目录的 `断点.hbd`);调试菜单 →
              清除所有断点一次全清。**断点条件**(调试菜单或编辑器右键):给光标那一行已经下好的断点写条件,三样都留空 = 不管 —— · **命中条件**
              `变量 运算符 值`(计数 == 5、开关 != 真、c == 'A';右边也可以写另一个变量);只写一个变量名 = 非 0 就停;**条件为假就当没命中、接着跑**;
              · **命中次数** `5` = 第 5 次经过时停一次;`%5` = 每 5 次停一次;`>=5` = 第 5 次起每次都停;· **日志** 填了它就成**日志断点**:命中时把这一行
              打进「输出」页、**程序不停**,`{变量}` 换成那个变量**这一刻**的值,还认 `{行}` / `{文件}`。三样都在对话框里**边打边判**;带这三样的断点
              画成**空心红圈**(普通断点是实心点),全都跟着工程存进 `断点.hbd`。变量要在这一行看得见;字符串 / 结构 / 数组比不了、变量又读不到 ——
              这类情况会**明确说清并按『停』处理**。
              **监视表达式**(调试菜单或编辑器右键,默认键 **Ctrl+Alt+W**):把**光标下的名字**加进底部『监视』页,停一次、走一步就重算一次,值变过会在
              「变化」那一列留下 `1 → 2 → 3`;写法与条件断点**同一套**;底部『监视』页里**也能直接加**。**自动切页**:停在断点上时**自动切到断点所在的
              文件标签页**。
              **执行(F5 = 编译 + 执行)**:有改过没保存的文件先自动存盘;源码跟上一次编译的不一样就**自动重新编译、从头开始跑**;源码没变、上次又停在断点
              上就**接着跑**;跑完再按 F5 才从头跑。**程序还在跑的时候按 F5 = 重新执行**:先把这一趟停掉(与「停止」同一套:停在原地、这一次不做断言),
              **等它收工**(图形窗口跟着收掉)再从程序开头跑一遍 —— 想再看一遍直接**再按一次 F5**。**跑程序这一步在子进程里**:引擎 / 宿主那一侧崩了
              **带不走这个界面**(输出页写明"跑程序子进程没了 + 进程号 + 退出码 + 标准错误末尾几行",这一趟不做断言),下一次「执行」自动重连。
              **停止(Shift+F5)**:跑死循环时**不用再杀进程** —— 程序**停在原地**(PC / 寄存器 / 变量都留着,底部『变量/调试』两页看现场),输出页写
              「已停止」,这一次**不做断言**;再按「执行」**从头跑**,想接着往下走就按「继续」(有断点停断点,没断点跑到停机)。
              **展开到汇编**(工具栏那个 `</>` 按钮):把**当前文件**整篇展开成汇编,在**新标签页**里打开(可编辑、可保存,存成「被展开文件名 +
              _ASM.hba」)。展开文本带源行标记 `// 来自[文件K]第 N 行[ 到 M 行][ 库]`(尾巴 `库` = 被 `包含` 进来的文件)。它默认**不参与编译**;
              编译/执行读的**始终是源码**。**一条 `.hba` 有两个来处**:① 点菜单「运行 → 编译(启动项目)」编完 → 这一次的**整个工程**展开自动在编辑器新开
              一页(**只有菜单这一条会开页**;F5 / 逐步 / 继续 / 展开到汇编顺带跑的那次编译,以及资源管理器右键的「编译」,都不抢页),落点 = **项目目录里
              的 `<启动文件名>_ASM.hba`**;② 点工具栏「展开到汇编」→ **当前这一个文件**的那一段展开在新页里打开,落点 = **`<被展开文件名>_ASM.hba`**。
              两页都**能改能存**(Ctrl+S);`.hba` **默认不参与编译**;不是**参与编译**的那一份里**不能下断点**。
              **代码折叠**:行号右边的小三角(块 `{ … }`、连着两行以上的 `//` 注释块、跨行的 `/* … */`),**纯折叠,不动源码**;只折**跨行**的块;字符串与
              注释里的 `{}` 不算块括号;花括号另起一行时折叠标记落在 `当 (…)` / 函数签名那一行(**对齐的是语句那一行,不是 `{` 那一行**)。按层的**缩进导引
              线**:每一对跨行 `{}` 在它那个 **`}` 的列**上有一条竖线;**线到 `}` 的上方就结束**;**这一列上站着字的那一行不画**;选项页《外观与主题》里能关(`缩进导引线`)。
              **单步**:逐步(F10) 一次走**一条源码行**(原来的「逐汇编 / 逐语句」合并成这一档;编译器生成的序言 / 收尾一口气跑过),编辑器里始终是你的**语言
              源码**,黄条落在"当前执行到的那一行"上;想看**一条机器指令一步**用 `hbcc --debug-asm`。继续(F7) 往下跑:有断点停在断点,没有就跑到停机。
              停止(Shift+F5) 停在原地、不做断言。复位(F8) 回到起点(同时退出单步模式)。逐步 / 继续 / 停止 / 复位 / 断点这几条都在**「调试」菜单**里
              (工具栏上只有「执行」与「停止」);编辑器右键菜单里也有「切换断点 / 断点条件 / 删除全部断点」。**快捷键**:F5 执行 / Shift+F5 停止 / F10 逐步 /
              F8 复位 / F7 继续 / F9 切换断点 / Ctrl+Alt+W 加监视表达式。
              **调试窗就在主窗口底部**,平时收起,只在**单步**和**停在断点上**时出现两页:① 变量(名字 | 值 | 类型 | 在哪 | 寄存器)—— 停在这一行看得见的
              变量都在(全局按数据段读,局部按帧指针 + 偏移读);结构变量展开成"原点.x = 3";出了代码块 / 出了函数的局部自动消失;读不到就写"?(现在读不到)",
              不做推测。② 调试:三栏并排(指令 / 内存 / 寄存器)。单步时跳走会自动滚动跟过去;同一行里层层往外调时那一行会**按调用层叠色**(赤橙黄绿青蓝紫
              七档),越内层颜色越深。

            18,条件的逻辑运算(&& / || / !)与三目
                如果 (a > 0 && b < 10)      // 两边都真才进去;a 不成立,b 那边看都不看(**短路**)
                如果 (a == 0 || b == 0)     // 有一个真就进去;a 成立就不再算 b
                如果 (!标志)                  // 取反;可以连着写 !!x
                当 (继续跑 && 计数 < 100) { ... }
              · **只用符号 && || !**(和 C 一样,前后不用留空格)—— 没有中文的 且/或/非 写法;优先级:! > && > ||,不确定时请加括号
              三目(一句话里二选一):`条件 ? a : b` —— `输出行(x > 0 ? 100 : 200)` / `最大 = a > b ? a : b`;只算被选中的那一支(和 && / || 一样是短路),
              所以 `x != 0 ? 100 / x : 0` 不会除以 0;可以套。这些全是**编译期**展开成跳转的 —— ISA 一个字不改;`&& / ||` 短路的地方,右边的函数**根本
              不会被调用**。跳出 / 继续 的层数:`跳出 2;` = 一次跳出**两层**(循环与 选择 都算一层,和 C 的 break 一致);`继续 2;` = 直接进"外面第 2 层循环"
              的下一次(只数循环,选择不算);不写数字就是 1 层;层数越界会明确报错。选择 的分支:`情况 1, 2, 5`(一个分支收多个值,逗号/中文逗号/顿号都认)/
              `情况 10..20`(闭区间)/ `情况 -5..-1`(有符号)

            19,字符串放进结构 / 数组
              【一】结构字段写 `字符串 名字;` —— 字段里只放**数据地址 + 容量**(8 字节),真正的字**在堆里**(堆默认 64KB,可在工程文件里写 `"堆": "128KB"`
                调大):
                  结构 人 { 字符串 名字; 短整数 岁数; }
                  人 成员;
                  成员.名字 = "张三";         // 整份赋值:装不下会自动 申请 一块更大的,旧的还回堆里
                  输出行(成员.名字);          // 打到第一个 0 为止
                  成员.名字.长度();           // 按**文字**数(中文一个字算一个)
                  成员.名字 == "张三"          // 按 UTF-8 字节比(和普通字符串一个口径)
                  拼接到(成员.名字, "丰");    // 接在原有内容后面(不够就换块)
                  释放(成员.名字);            // 还回堆里,字段当场清成空串
                · 字段当**值**用就是它存的数据地址:`地址 p = 成员.名字;`;`成员.名字 = 0;` = 清成空串(堆里那块**先还回去**);`成员 = 0;` 整块清 0 时,
                  结构里的字符串块也一样还回堆里;`成员.名字[下标]` 按**文字**读改一个字(要按**字节**看才先 `地址 p = 成员.名字;` 再 取字/存字);也不能把
                  整个字符串数组 `副本 = 成员`(两边会共用堆里同一块,所以直接拦住)
              【二】`字符 名字[16]` 这种**定长缓冲**也当字符串用 —— 内联在结构里(容量固定),末尾的 0 定长度:
                  结构 人 { 字符 代号[8]; }
                  人 成员;
                  成员.代号 = "ZS";           // 容量 8 → 最多装 7 字节内容(末尾留一个 0)
                  拼接到(成员.代号, "X");
                  输出行(成员.代号);          // ZSX
                · 放不下**当场拦住**:字面量太长是编译期就报错(报出容量与这次要写多少),运行期才知道多长就停机并说清改法;列表(`字符 缓冲[]`,个数会变的
                  那种)不按定长缓冲办 —— 它的容量是运行期的
              【三】`字符串 名单[3]` 字符串数组 —— 每个元素 8 字节(地址 + 容量),数据同样在堆里:
                  字符串 名单[3];
                  名单[0] = "张三";
                  名单[i] = "李四";           // 运行期下标也行
                · 个数不定的列表 `字符串 名单[]` 也通了:`名单.添加("张三");` 一个个加,下标读 `名单[0]`、长度 `名单.长度()`、`名单.清空()`;数据同样在堆里,
                  用完记得 `释放`
                · **结构字段里也能放列表**:`结构 筐` 里写 `整数 数[];` —— `成员.数.添加(3)` / `成员.数[0]` / `成员.数.长度()` 与顶层列表一个用法,数据住
                  **堆**里;结构数组元素里各有一份(`表[1].数`),整体赋值(`副本 = 成员;`)深拷贝,`成员 = 0;` 把块还回堆。字段里的列表**元素**暂时只收
                  "没有堆块"的类型:放 `字符串` 元素、或放带 `字符串`/列表字段的结构会当场报错并给改法
              【四条硬规矩】· **赋值 = 各有一份**:结构整体赋值、函数返回结构、结构进列表时,里面的字符串字段都**深拷贝**,改一份不影响另一份 · 用完的块记得
                `释放`(堆是固定的,不会自己变大);释放之后别再读写它(会当场停下并说明) · 函数里的 `字符串 名字;`(变量)数据在**池**里,由编译器管;结构字段 /
                数组元素里的 `字符串` 数据在**堆**里,要自己管 · 调试面板里,字符串字段直接显示**内容**(不是堆地址)。标准工程 示例07_字符串 有全套例子

            20,可写回的字符串参数 `出` 与"返回串直接进表达式"
              字符串参数**默认是只读的**(函数里改它会当场报错)。想让它能改,参数前面多写一个 `出`(英文别名 `result` —— 不叫 `out`,那是 ISA 的 OUT 指令
              助记符):
                方法 取全名(字符串 出 结果, 字符串 姓, 字符串 名)
                {
                    结果 = 姓;              // 里面一赋值,外面那变量当场就变了
                    拼接到(结果, "·", 名);   // 接多长都行:装不下连调用方的容量一起长大
                    返回 结果;               // 也能当返回值(整份拷给调用方)
                }
                字符串 全名;  取全名(全名, "张", "三");  输出行(全名);   // 张·三
              · 传的是"调用方那个字符串的**头**"(数据地址 + 容量,一共两个字 / 8 字节;当**参数**传的是"数据地址 + 长度"),没有"返回时回拷"这一步;
                **`出` 只给字符串参数用**:`整数 出 结果` / `点 出 p` 都会当场报错并给改法 —— 基础类型要写回就写 `引用 整数 结果`;结构参数**本来就是按地址
                传**(改了就是改调用方那份)
              · 进函数先读它,读到的是**调用方当前的内容**;`出` 参数还能**转发**给另一个函数的 `出` 参数;实参只能是**字符串变量**(或本函数自己的 `出`
                参数):字面量、结构里的字符串字段、`字符 名字[16]` 缓冲都没有"可写的头",当场报错并给改法;不写 `出` 的参数照旧只读,改它会报错并提醒你写 `出`
              **`返回 字符串` 的函数调用能直接写进表达式**:`输出行(取名字(1));`(当输出参数)、`拼接到(汇总, 取名字(1), 取名字(2));`(当拼接段,每个调用只调
              一次)、`如果 (取名字(1) == "张三")`(当比较的一侧)、`成员.名字 = 取名字(1);`(写进结构里的字符串字段,深拷贝)。编译器在**每个调用点**开一个隐藏
              的临时串(函数里开在帧里 —— 每层调用各一份,递归也安全;顶层开在数据段),把返回值接住再当普通字符串用。

            21,程序自带的测试:`测试` / `断言`(英文别名 `test` / `assert`)
              `// 预期输出:` 管的是"**整个程序**输出对不对";`测试` 管的是"程序里**每一小块**对不对" —— 一个程序里可以写好几个块,哪一行、哪个条件不成立直接说出来,
              而且失败**不打断**:一次看全所有不成立的断言。
                测试 加法 { 断言 1 + 1 == 2; 断言 2 * 3 == 6; }
                测试 字符串
                {
                    字符串 姓名 = "张三";
                    断言 姓名.长度() == 2;
                    断言 姓名 == "李四", "名字应该是李四";     // 逗号后面跟一句说明(可省)
                }
              · `测试 名字` 只能写在**函数外面**(程序级别);块不能嵌套,名字后面必须跟 `{`(另起一行)
              · `断言 条件;` / `断言 条件, "说明";` —— 条件随便写:数字比较、字符串比较、`&&`/`||`、函数调用都行
              · 不成立时打印 `第 N 行:断言失败:<条件原文>(说明)`,然后**接着往下跑**(循环里也能写断言);每个块跑完打印一行汇总:
                `测试 名字:共 N 条断言,失败 M 条`
              · 有失败的块会把这次失败记进"错误槽"(只记不停):程序本身**照常跑完**,但命令行会多打一行 `⚠ 运行停下: 测试 名字 里有断言不成立…`;
                测试块写在哪儿就**在哪儿跑**;函数里不能写 `测试`,块外不能写 `断言`

            22,宿主能力:文件、目录、环境变量与时间
              要碰"文件、目录、环境变量、时间"这些**只有宿主(命令行 / IDE)才知道的事**,用这**四十个**内建函数(不是关键字,和 `申请`/`读取行` 同一档;
              中英可整体切换。这一节数的只是**与宿主打交道的那一批**,**内建函数一共 59 个**,另外那些是输入输出与内存那一族,见 `hbcc --help-text` 的
              【内建函数】):读文件 / 写文件 / 追加写文件 / 读文件块 / 建目录 / 删文件 / 删目录 / 列目录 / 环境变量 / 当前时间 / **当前毫秒** / 移动到 /
              复制到 / 运行进程 / 取退出码 / 取网址 / 取网址状态码 / **打开读流 / 读一块 / 定位 / 关读流 / 打开写流 / 写一块 / 关写流**(流式读写,见第30节)/
              **连到 / 发送 / 发送块 / 接收 / 接收块 / 关闭 / 监听 / 接受 / 主机解析**(网络,见第31节)/ **睡眠 / 冲刷 / 改名 / 临时目录**(运行时,见第32节)/
              **发起异步 / 任务就绪 / 取消任务**(异步,见第33节)。最后那四个(`运行进程` / `取退出码` / `取网址` / `取网址状态码`)要工程文件里声明白名单(见下);
              **网络那七个也一样要白名单**(而且必须写到端口),见第31节
                字符串 路径 = "数据/名单.txt";
                如果 (写文件(路径, "张三,李四")) { 输出行("写好了"); }
                字符串 读回;
                如果 (读文件(路径, 读回, 4096)) { 输出行(读回); }
                整数 秒 = 当前时间();          // Unix 秒(1970-01-01 00:00:00 UTC 起);失败给 0
              · `写文件(路径, 内容) 返回 逻辑` —— **覆盖写**(文件不存在就新建);**路径上缺的目录会顺手建出来**(相对路径是相对"程序运行时的工作目录"的);
                `追加写文件(路径, 内容)` 接在**文件末尾**(不存在就新建)
              · `读文件(路径, 内容变量, 上限) 返回 逻辑` —— `上限` 是编译期数字,**而且是硬上限**:文件比它大就只读这么多;`读文件块(路径, 偏移, 内容变量, 上限)`
                **从第 `偏移` 字节起读一块**(最多 `上限` 字节):读到了给 真、内容进那个字符串变量;**读到文件末尾(或文件是空的)给 假**并把变量清空 —— 于是
                循环头写成 `当 (读文件块(路径, 偏移, 块, 4096))`、体里把 `偏移` 往后挪就能自然收尾(`块.长度()` 数的是**文字**:一个汉字算一个、占 3 字节)
              · `建目录(路径) 返回 逻辑` —— **已存在也算成功**;`列目录(路径, 内容变量, 上限)` 把目录里的**名字**按行写进那个字符串变量(只列本层、不递归、按名字
                排序);目录不存在 → 假
              · `删文件(路径) 返回 逻辑` —— 文件**不存在给 假**(不静默当成功);`删目录(路径)` **只删空目录**,里面还有东西 → 假,**递归删故意不提供**
              · `移动到(旧路径, 新路径) 返回 逻辑` —— 文件或**整个目录**换个位置;新路径上缺的目录会顺手建出来;**目标已存在 → 假(不覆盖)**;`复制到(源路径,
                目标路径)` 文件照抄内容、**目录整棵复制**,**目标已存在 → 假**(注意:`复制` 是汇编指令 MOV 的中文名);`环境变量(名字, 内容变量, 上限) 返回 逻辑`
                —— 没有这个变量 → 假
              · 上面这一串里**返回 `逻辑`** 的那几条:真 = 成功,假 = 失败(**不抛异常、不停机**),所以要用 `如果/否则` 看结果;另外三个返回数字(`当前时间()` 是
                Unix 秒,`取退出码()` / `取网址状态码()` 是上一次调用的结果码);**失败不写错误槽**。相对路径是相对**程序运行时**的当前目录;手机上跑时由手机 IDE 决定能碰哪些目录(标准工程 示例12_输入输出与宿主能力 有全套例子)
              · ISA 那边**只多了一条** `宿主调用`(参数区 + 功能号):**能力是宿主注入的**,没注入时这些函数一律返回 假(程序照常跑,不崩)
              运行外部程序(默认没有这个能力,要在工程文件里声明才用得上)
                如果 (运行进程("ffmpeg", "-i\\n输入.mp4\\n输出.mp3", 输出, 10000)) { 输出行(输出); }
              · **安全边界(这条最要紧)**:HB 侧**给不了可执行文件路径** —— 只能写工程文件 `.hbp` 里`可执行文件`表声明过的**名字**(如 `"可执行文件":
                { "ffmpeg": "C:/tools/ffmpeg/bin/ffmpeg.exe" }`);表里没有的名字 → 直接拒绝(返回 假);**表是空的 / 没给工程文件 → 这个宿主就没有这个能力**
                (手机端、`hbcc --exe` 生成的独立 exe 就是这种:调了给 假,程序照常跑)
              · `运行进程(名字, 参数, 输出变量, 超时毫秒) 返回 逻辑`:参数是一个字符串、**每行一个参数**,原样进 argv —— **不经过 shell**;子进程的标准输出与
                标准错误**都写进**那个 `字符串` 变量;输出按**先严 UTF-8、再系统代码页**的顺序解
              · **同步**:跑完才返回。`超时毫秒` 写 0 = 默认 10000(上限 1 小时);超时会**杀掉整个进程树**,给 假,退出码记 `0xFFFFFFFF`;`取退出码()` 给上一次
                的退出码(0 → 给 **真**,非 0 → 给 **假**);WPF IDE 与 `hbcc -p 工程.hbp --run` 按**当前工程**设这张表;手机端与独立 exe **没有**这个能力
              连网址(默认没有这个能力,要在工程文件里声明才用得上)
                如果 (取网址("http://127.0.0.1:8080/状态", 回应, 65536, 5000)) { 输出行(回应); }
              · `取网址(网址, 内容变量, 上限, 超时毫秒) 返回 逻辑` —— **同步 GET 一次**:`网址` 要写全(`http://主机:端口/路径`);响应体写进那个 `字符串` 变量;
                `上限` 是响应体最多多少字节(编译期数字,超了给 假 —— **不截断**);`超时毫秒` 写 0 = 默认 10000
              · **安全边界**:HB 侧**给不了任意网址** —— 只能连工程文件 `.hbp` 里 `网址` 表声明过的**主机 + 端口**;不在表里的主机/端口 → 直接拒绝(返回 假),
                **连都不连**;表是空的 / 没给工程文件 → 没有这个能力(手机 IDE 就是这种:它编的是编辑器里那一份源码,没有 `.hbp` 可读;`hbcc --exe` 生成的**独立 exe** 也是这种 —— 见第15节三档共有口径里那一条)
              · 只做**一次性 GET**:不跟跳转(3xx 也算失败)、不做长连接、不做上传;HTTP 2xx 给 **真**,别的给 **假**(真实状态码用 `取网址状态码()` 看);响应体的
                编码按 `Content-Type` 的 charset 解,没写就按**先严 UTF-8、再系统代码页**猜;图片/压缩包这类二进制**一个字节都不动**

            23,汇编源码(.hba)与"参与编译"
              · 点「运行 → 编译」成功后,IDE 把这一整篇展开的汇编写进**项目目录里的 `<启动文件名>_ASM.hba`** 并在编辑器里开一页(**只有点这一条会自动开这一页**;
