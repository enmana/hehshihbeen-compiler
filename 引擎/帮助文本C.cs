                回车 13 / Esc 27 / 空格 32 / 退格 8 / 制表 9 / Shift 16 / Ctrl 17 / Alt 18 / 左 37 / 上 38 / 右 39 / 下 40 / 首页 36 / 末页 35 / 上一页 33 /
                下一页 34 / 插入 45 / 删除 46 / 鼠标左键 1 / 中键 2 / 右键 3
              · **时钟**:`等待(毫秒)` 就是"让出一帧"(即时模式的主循环里每帧调一次);桌面壳上它**真睡**这么久;无头呈现(`hbcc --run` / 自检)**不真等**。要算"两帧
                之间过了多久"用 **`当前毫秒()`** —— **单调钟**的毫秒刻度,**低 32 位、约 49.7 天回到 0**(别拿它当绝对时刻比大小,只拿它**算差**)
              · **定时器**用标准库 **`Sample\库\定时.hb`**:开头 `包含 "../../库/定时.hb"`,主循环里每轮 `定时.推进()`,登记写 `定时.每(16, 地址(动一下));` /
