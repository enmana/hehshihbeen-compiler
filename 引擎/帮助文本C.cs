            25,图形界面:开一个窗口、画一屏
              · 这一门语言**不做控件库**:窗口、像素、输入是宿主给的,控件(按钮 / 文本框 / 列表 / 布局)由 HB 自己写 —— 每帧重画一遍(即时模式),状态就是普通变量。
