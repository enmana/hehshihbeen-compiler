            33,异步:别让一次阻塞调用把整帧卡住
                前面那几节(`读文件` / `读一块` / `接收`)都是**全同步**的:调用一次,程序就停在那儿等它回来。界面程序里这会**把整帧卡住**。这一节的三个函数把"等"这件事
                挪到**宿主后台线程**上去 —— 发起那一刻就回来,程序自己隔一会儿问一句"好了没有":
                    任务 = 发起异步(1, "数据/大.txt", 内容, 4096, 任务);  // 1 = 读文件;立刻给任务号
                    当 (任务就绪(任务, 状态, 个数) == 0) { }              // 0 = 还没好
                    如果 (状态 == 0) { 输出行(内容); }                    // 0 = 这一趟成了;内容就在这个变量里
                    任务 = 发起异步(2, "数据/新.txt", "一段文字", 0, 任务); // 2 = 写文件(字节数 0 = 整段都写)
                    任务 = 发起异步(3, "127.0.0.1", "", 8080, 任务);        // 3 = 连接(第二格不用,写 "")
                    取消任务(任务);                                         // 不再等它(结果丢掉)
                · **`发起异步(种类, 参数一, 参数二, 参数三, 任务)`** 把一件事交出去、**立刻**返回任务号(排不上给 -1);`任务` 要写**一个 `整数` 变量的名字**
                  (与 `打开读流(路径, 句柄)` 的第二个实参同一个写法)。四个数据实参按 `种类` 解释:种类 `1` 读文件:参数一 = 路径,**参数二 = 收内容的 `字符串` 变量**,
                  参数三 = 上限字节数(0 = 4096 兜底);种类 `2` 写文件:参数一 = 路径,参数二 = 要写的串,参数三 = 要写的字节数(0 = 整段都写);种类 `3` 连接:参数一 =
                  主机,参数二 = 不用(写 `""`),参数三 = 端口
                · **`任务就绪(任务号, 状态, 字节数)`** 问一句"那一趟好了没有":**返回值**就是这一轮的状态码 —— `0` 还没好 · `1` 好了 · `2` 这一趟失败 · `3` 任务号作废
                  (取消过 / 收走过)· `22` 任务号不成形。返回 `1` 那一刻结果搬进那两个 `整数` 变量、**任务号当场作废**(结果只收得到一次):`状态` 给这一趟的结果状态
                  (`0` = 成了;失败给具体状态码:2 打不开 / 4 读写失败 / 17 连不上…);`字节数` 给结果数字 —— 读 / 写是"做了几个字节",**连接那一趟放的是新连接的句柄**
                  (拿它去 `发送` / `接收` / `关闭`);失败时那一格是 0。**读文件的内容不进这两个变量**:它在说"好了"那一刻直接写进 `发起异步` 指定的那个 `字符串` 变量
                · **等就绪照上面那样写成 `当 (任务就绪(…, 状态, 字节数) == 0) { }`** —— 别用 `睡眠` 去"等一会儿再看":睡多久都是猜。**`取消任务(任务号)`** 是**尽力而
                  为**:已经在跑的那一趟拦不住(它跑完自己把格子还回来),但结果**不会再交出来**,而且任务号当场作废(0 = 取消了;3 = 已经作废;22 = 号不成形)
                · **同时最多占 32 个任务** —— "在跑的"与"结果还没收走的"都算;满了 `发起异步` 给 -1,先 `任务就绪` 把结果收走、或者 `取消任务` 掉几个,再发起(一格从
                  `发起` 占到最后一次 `任务就绪`,**跑完不自己放格子**)
                · **这一族每个宿主都有**(手机端 / 独立 exe 也一样);但**只 `种类 3 连接` 这一档看白名单**:**主机 + 端口要先写进工程文件 `.hbp` 的 `网址` 表**(而且必须
                  写到端口);不在表里给 `20`(网址不在白名单);而**带不了白名单的那几个宿主**(手机端 / 独立 exe)一律**当场挡掉**:给状态 `1`、任务号写 `-1`,**不占任务格、
                  也不起线程**(与 `连到` / `监听` 那两条是同一条老边界)。`种类 1` / `种类 2` 不要白名单
                · **三个名字为什么长这样**:`发起异步` 不叫 `发起`、`取消任务` 不叫 `取消` —— `取消` 是 `库\定时.hb` 里那个库函数的名字(`定时.取消(号)`),而语言内建名
                  **优先于用户函数**,内建叫 `取消` 会把那个库打断。标准工程 示例31_异步 有全套例子

