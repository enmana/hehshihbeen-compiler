                    写句柄 = 打开写流("数据/新.txt", 写句柄);        // 不存在就新建;**已存在就从头写起**
                    写一块(写句柄, "第一行\\n", 0);                  // 返回真写下去的字节数
                    定位(写句柄, 0);                                // 挪到第 0 个字节,再写就是**覆盖**
                    关写流(写句柄);                                 // **先把缓冲冲刷到盘上**再关
