            27,还没有的写法(逐条真编核对过,别一条条撞上去)
              · **多维数组是规格了,但还有几样不做**:`整数 表[][3];` / `整数 表[3][];` / `整数 表[][];`(列表的列表 —— 每一维都得写长度)不收;**当数组参数传**、
                **取地址**、**整块赋值**、**当值整个读**这几样多维数组一律不做。那怎么办:要整块用就摊平成一维(`整数 袋[12];`,自己按下标算),或写成结构数组
              · **枚举要一行写完,还有两样不做**:`枚举 颜色 {` 之后每个成员一行那种写法不收 —— 成员之间用逗号隔开、一行写完就行(`枚举 颜色 { 赤, 绿, 蓝 }`);
                枚举成员**不能当数组长度**(`整数 表[赤];` 报错)。那怎么办:枚举当**类型与常量表**用(声明变量 / 比较 / `情况` / 传给方法都行),要"按枚举个数定长"
                就把那个数写出来
              · **元组有三样不做**:①**拆包**不收(`[整数 商, 整数 余] = 除法(9, 4);` 写不了 —— 要拆就一个成员一个成员取:`整数 商 = 结果.项0;`);②元素是 `字符串`
                的元组不收;③**空元组 `[]` 不收**。那怎么办:字符串与整块数据放结构里(`结构 卡片 { 字符串 名字; 整数 号; }`),元组留给"几个小值捆一起"
              · **`引用` 不能指向数组 / 列表**:`引用 整数 表 = 某数组` 报错。那怎么办:①要一个稳定地址就用**定长数组**;②只是按下标读改就照旧 `表[i]`;③要几处共享
                一份可改的数据,就用一个普通变量 + `引用` 指它
              · **字符串数组 / 字符串列表的初值写不了**:`字符串 名单[3] = ["张三", "李四"];` 不收(每个元素都要在堆里要一块)。那怎么办:声明完再一个个赋值或 `添加`
              · **字符串数组的整块赋值也写不了**(那要运行期挨个深拷贝)。那怎么办:一个元素一个元素赋值
              · **动态列表的整块操作写不了**(`成员 = 副本` 那种整体赋值)。那怎么办:循环逐个 `添加` 过去
              · **结构 / 数组的字面量初值只收普通数值**:`整数 表[3] = [1, 2, 3];` 可以;数组 / 字符串 / 结构 / 列表这几种**字段**不能进字面量初值(塞进去的只会是一串
                假地址)。那怎么办:先整块清 0,再对那个字段分别赋值
              · **结构字段的默认值只认常量字面量**:`结构 点 { 整数 x = 5; }` 可以,`整数 x = 5 + 1;` 不行(编译器算不出来)。那怎么办:写死一个字面量,或者先算进
                一个变量再转过去
              · **方法容器 / 结构里没有构造函数那种东西**:声明一份就要自己初始化。那怎么办:给结构写一个 `方法 初始化()` 自己挨个字段赋值,声明完立刻调一次
              · 两条**早就不成立**的老说法(别再照老笔记绕):① 方法容器的字段**早就支持数组**(与结构字段同一把尺子);② 字符串数组的**元素早就能放 `字符串`**

            28,错误怎么传(没有异常,失败一律靠返回值)
              · 三类,只有第三类要你自己写代码处理:① **编译期的毛病**:当场报错,报错带**行号 + 说明 + 改法**;② **运行期的守卫**:下标越界 / 定长列表满了 / 池用完 /
                软栈溢出 / `断言` 不成立 —— 虚拟机自己拦下(把号写进"错误槽"):命令行退出码非 0、IDE 也报出来,程序**不会带着错数据往下跑**;其中 `断言` 与
                `测试` 那一档是**只记不停**(跑完给汇总),其余几种当场停机;③ **"失败也算正常结果"的那一类**(宿主能力、你自己写的函数):**靠返回值传**
              · **语言里没有异常** —— 没有"抛出 / 接住"那种写法:加异常要动 ISA 与虚拟机语义,与"语言面只加不改"冲突。要"把失败一层层往上穿"就用**标准结果形状** =
                一个"成不成 + 值"的小捆,缺省用**元组**:
                  方法 取一半(整数 数) 返回 [逻辑, 整数]
                  {
                      如果 (数 < 0) { 返回 [假, 0]; }   // 失败:第二个成员给一个"不用看"的 0
                      返回 [真, 数 / 2];                // 成功
                  }
                调用方:`[逻辑, 整数] 结果 = 取一半(10);` 然后 `如果 (结果.项0) { 用(结果.项1); } 否则 { 说一句(); }` —— 拿到"成不成"就能当场分岔;要一层层往上穿时,
                把结果形状原样 `返回` 给上一层
              · **要错误码 / 说明就换成结构**(字段随自己定、起真名字;字符串字段也放得下):`结构 取数结果 { 逻辑 成; 整数 值; 整数 错误码; 字符串 说明; }` —— 结构与元组
                **是同一件事的两种写法**
              · **宿主能力**(第22节那一族)是**老约定**:返回 `逻辑`(真 = 成功、假 = 失败),**失败不停机、不写错误槽** —— 目标内容 / 清单走那个"出参"变量。
                `如果 (读文件("数据.txt", 内容, 4096)) { 用(内容); }`;`取网址` 那一档同理,状态码另问 `取网址状态码()`(没取到给 0xFFFFFFFF)
              · **哨兵值(失败返回 -1 / 0 / 空串)能用,但要知道代价**:它和合法值会撞车 —— `取一半(-2)` 给 -1,调用方分不清"失败了"还是"确实算出 -1"。只在**合法值里
                根本不可能出现那个数**时才用它
              · **不做的**:异常(抛出 / 接住)、`结果<值, 错误>` 那种**泛型**结果类型(HB 不加泛型)、改宿主能力的老返回口径

