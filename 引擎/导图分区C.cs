    /// <summary>
    /// **一个分区里的一条子项**(H60-11;施工图 = `未做任务清单.md` §9 H53 的"施工图 · 步 4")。
    ///
    /// 用户 2026-09-26 的口径(已定口径 ③):「点开都分两个区,一个声明区,一个调用区」——
    /// 这一层就是那两个区里装的东西:
    ///   · **声明区**的子项 = 这个框**自己声明**的东西(文件框:变量 / 常量 / 结构 / 方法 / 包含;
    ///     结构框:字段 / 结构方法;方法框:参数 / 局部;流程块框:头声明 / 局部);
    ///   · **调用区**的子项 = 这个框里**直接挂着的语句**(`种类 = 语句`),每条语句自己的调用链挂在
    ///     `链们` 那一格(`调用线C.拆` 长的 —— 用户要的"语句与它调用的东西"就是这个形状)。
    ///
    /// `声明` 那一格是 H60-9 的**声明线**(点开画出虚线的那一条);调用区里那个链节自己的 `声明`
    /// 也一样填(H60-10 已经拼好了,这一层只是照搬)。
    /// </summary>
    public sealed class 分区项C
    {
        /// <summary> 这棵树里唯一(`声明:名@行` / `语句:行` / `包含:路径@行`;H60-12 排序、H60-14 双击都按它找)</summary>
        public string 键 = "";

        /// <summary> 显示的那个名字(声明 = 名字;语句 = 那一行原文)</summary>
        public string 名 = "";

        /// <summary>
        /// 种类**直接用 `声明线C` 查出来的那一档**(用户方法 / 结构 / 结构方法 / 成员方法 / 变量 / 常量 /
        /// 参数 / 局部 / 字段);语句那一档写 `语句`,包含那一档写 `包含`。
        /// </summary>
        public string 种类 = "";

        /// <summary> 声明行 / 语句行(1 基)</summary>
        public int 行;

        /// <summary> 类型词(变量 / 常量 / 参数 / 局部 / 字段有;方法 / 结构 / 语句 / 包含没有就是空串)</summary>
        public string 类型词 = "";

        /// <summary> 一句人话(「第 N 行声明」/「第 N 行语句」/「第 N 行:包含 "…"」)</summary>
        public string 说明 = "";

        /// <summary> 声明线:这一项声明在哪儿(H60-9 的 `声明处C`;语句项自己那一格是 null)</summary>
        public 声明处C? 声明;

        /// <summary> 调用线:这条**语句**里直接调用的那些链节(H60-10 的 `调用线C.拆`;声明项一律空)</summary>
        public List<调用链节C> 链们 { get; } = [];

        public override string ToString()
            => $"{名}{(类型词.Length > 0 ? " " + 类型词 : "")}[{种类}]@{行}";
    }

    /// <summary>
    /// **一个框**(H60-11):文件 / 结构 / 方法 / 流程块,都是同一个形状 —— **两个分区 + 自己的子框**。
    ///
    /// 为什么连"文件"也是一个框:用户 2026-09-26 的原话「以我们的设定,一个文件就相当于一个大的方法(类)」——
    /// 文件 = 类,类里有变量 / 常量 / 结构 / 方法;方法体里又有流程块(用户:「`循环 (var k = 1; …)`
    /// 按照方法处理,`k` 就是它自己的局部变量」)。于是整棵树只有一种节点:**有声明区、有调用区、有子框**。
    ///
    /// `种类` 只有四样(**文件 / 结构 / 方法 / 流程块**)—— H60-13 的配色与 H60-14 的弧线都按它走
    /// (施工图说"三样":文件 / 方法 / 流程块;③⑤ 又明写"结构框 = 字段们 + 方法们""键建议 `结构:名@行`"
    /// ⇒ 结构也是框,如实记进本批记录)。
    /// </summary>
    public sealed class 框来源C
    {
        /// <summary> 这棵树里唯一(`文件:` / `结构:名@行` / `方法:名@头行` / `流程块:词@行`)</summary>
        public string 键 = "";

        /// <summary> 显示的名字(文件 = 文件名;别的 = 它自己的名字;流程块 = 那个词)</summary>
        public string 标题 = "";

        /// <summary> 文件 / 结构 / 方法 / 流程块</summary>
        public string 种类 = "";

        /// <summary> 头一行(文件框恒为 1;1 基)</summary>
        public int 行;

        /// <summary> 收到哪一行(文件 = 本文行数;方法 = 收尾 `}`;结构 / 流程块 = 下一个同层块起行 − 1)</summary>
        public int 止行;

        /// <summary> **声明区**:这个框自己声明的东西(见 `分区项C` 的注释)</summary>
        public List<分区项C> 声明区 { get; } = [];

        /// <summary> **调用区**:这个框里直接挂着的语句(每条语句一个子项,它自己的调用链在 `分区项C.链们` 里)</summary>
        public List<分区项C> 调用区 { get; } = [];

        /// <summary> 子框:结构 / 方法 / 流程块(按顺序挂,谁也别挤掉谁)</summary>
        public List<框来源C> 子框们 { get; } = [];

        /// <summary> 一句人话(「第 N 行声明」/「第 N 行:循环块」;文件框 = 那份文件的全称)</summary>
        public string 说明 = "";

        public override string ToString()
            => $"{种类} {标题}@{行}~{止行}(声明 {声明区.Count} / 调用 {调用区.Count} / 子框 {子框们.Count})";
    }

    /// <summary>
    /// **导图分区**(H60-11 建、H60-12 排序;施工图 = `未做任务清单.md` §9 H53 的"施工图 · 步 4 / 步 5")——
    /// 思维导图 2.0 的第四 / 第五步:把 H60-8 那棵"文件 = 类"的树 **+** H60-9 那张声明索引,
    /// 变成**每个框点开都有的两个区**(声明区 / 调用区)+ 流程块自己的框,
    /// 再让**每个框的三个表都按行号排**(用户 2026-09-26 的口径「所有顺序按照行号排序」)。
    ///
    /// 用户口径:**两条线** —— 声明线(虚线,`分区项C.声明` 那一格,H60-9)+ 调用线(实线,`分区项C.链们`
    /// 那一串,H60-10);这一步只是把两者按框归好类(画出来是 H60-14)。
    ///
    /// **纯函数**:喂一棵树 + 一张索引就出框树 —— 不读盘、不吃编译结果、不碰界面、不动机器码
    /// (与 H60-8 / H60-9 / H60-10 同一个节奏)。
    ///
    /// **一条铁律**:哪个名字归哪个框,**H60-9 的 `声明索引C` 已经按 `所在`(方法 X / 流程块 循环)
    /// 分好了** —— 这一层只做"按框归类",**不写第二套作用域推断**(两套口径迟早打架;施工图 ③)。
    /// 于是 `局部` 这个名字在这里只问 `索引.查(名, 行, 文件)` 要种类与声明处,绝不自己算区间。
    ///
    /// **按行号排**(H60-12):每个框的 `声明区` / `调用区` / `子框们` 一律按 `行` 升序;
    /// 用户 2026-09-26 的原话是「所有顺序按照行号排序」。`工程 → 文件` 那一层**不归这一步**
    /// (文件本身没有行号,按 `.hbp` 的文件表顺序),它在界面侧 `MainWindow.思维导图.cs`。
    ///
    /// 用法(H60-12 / H60-13 / H60-14 都从这儿拿框):
    /// <code>
    /// var 树 = 源码声明扫描C.扫结构(文本, 文件);
    /// var 索引 = 声明线C.建(树);
    /// var 根 = 导图分区C.建(树, 索引);           // ⇒ 根 = 文件框,两个区 + 子框都在
    /// var 块 = 导图分区C.找框(根, "流程块:循环@101");
    /// </code>
    /// </summary>
    public static class 导图分区C
    {
        public const string 种类文件 = "文件";
        public const string 种类结构 = "结构";
        public const string 种类方法 = "方法";
        public const string 种类流程块 = "流程块";

        /// <summary>
        /// 一棵"文件 = 类"的树(+ H60-9 的声明索引)→ **根框 = 文件框**。
        ///
        /// 每个框**先出两个区**(施工图 ③):
        ///   · 文件框:声明区 = 顶层 `变量们`(按 `是常量` 分常量 / 变量)+ `结构们` + `方法们` + `包含们`;
        ///     调用区 = `顶层语句们`;
        ///   · 结构框:声明区 = `字段们` + `方法们`(结构方法;每个再另起一个方法框挂在结构框下);
        ///   · 方法框:声明区 = `参数们` + `局部们`;调用区 = `语句们`;
        ///   · 流程块框:声明区 = `头声明们` + `局部们`;调用区 = `里层语句们`。
        ///
        /// **两处不收就丢内容**(施工图 ⑦,照 H60-8 的前例):① **顶层流程块**挂到文件框下
        /// (H60-8 为此在根上多收了 `顶层流程块们`);② **容器的裸成员头**(`累加(整数 n)`)在树里是
        /// `方法节点C.方法们` ⇒ 归到那个容器框(也是方法框)下面当方法框。
        /// </summary>
        public static 框来源C 建(源码结构C? 树, 声明索引C? 索引 = null)
        {
            string 文件 = 树?.文件 ?? "";
            var 根 = new 框来源C
            {
                键 = "文件:" + 文件,
                标题 = 文件.Length > 0 ? Path.GetFileName(文件) : "(本文)",
                种类 = 种类文件,
                行 = 1,
                止行 = 树?.行数 ?? 0,
                说明 = 文件.Length > 0 ? 文件 : "这一份源码文本",
            };
            if (树 == null) return 根;

            int 总止 = 树.行数 > 0 ? 树.行数 : int.MaxValue;

            // ---- 文件框的声明区:变量 / 常量 / 结构 / 方法 / 包含 ----
            foreach (var 变 in 树.变量们)
                根.声明区.Add(声明项(索引, 文件, 变.名, 变.行, 变.是常量 ? "常量" : "变量", 变.类型词));
            foreach (var 结 in 树.结构们)
                根.声明区.Add(声明项(索引, 文件, 结.名, 结.行, 种类结构));
            foreach (var 方 in 树.方法们)
                根.声明区.Add(声明项(索引, 文件, 方.名, 方.头行, "方法"));
            foreach (var (路径, 行) in 树.包含们)
                根.声明区.Add(new 分区项C
                {
                    键 = $"包含:{路径}@{行}",
                    名 = 路径,
                    种类 = "包含",
                    行 = 行,
                    说明 = $"第 {行} 行:包含 \"{路径}\"",
                });

            // ---- 文件框的调用区:顶层直接挂着的语句 ----
            加语句们(根.调用区, 树.顶层语句们, 文件, 索引);

            // ---- 文件框的子框:结构 + 方法 + 顶层流程块 ----
            for (int i = 0; i < 树.结构们.Count; i++)
            {
                int 止 = i + 1 < 树.结构们.Count ? 树.结构们[i + 1].行 - 1 : 总止;
                根.子框们.Add(长结构(树.结构们[i], 文件, 索引, 止));
            }
            foreach (var 方 in 树.方法们) 根.子框们.Add(长方法(方, 文件, 索引));
            加流程块们(根.子框们, 树.顶层流程块们, 文件, 索引, 总止);

            按行排一棵树(根);   // H60-12:每个框的三个表都按行号排(同号按原来出现的顺序)

            return 根;
        }

        /// <summary>
        /// 一棵框树里**所有框**(先自己、后子框,按顺序)。
        /// `深` 是 T3(2026-09-27 评测整改)加的嵌套计数:框套框一路递归,撞 `硬上限C.语句块嵌套上限`
        /// 抛带行号的编译错误 —— 不然嵌套 5000 层的文件一开导图,栈溢出会当场把 IDE 进程打死。
        /// </summary>
        public static IEnumerable<框来源C> 全部框(框来源C? 框, int 深 = 0)
        {
            if (框 == null) yield break;
            if (深 > 硬上限C.语句块嵌套上限) throw 硬上限C.嵌套太深的错误("思维导图:取框树", 框.行);
            yield return 框;
            foreach (var 子 in 框.子框们)
                foreach (var 孙 in 全部框(子, 深 + 1)) yield return 孙;
        }

        /// <summary> 一棵框树里**所有子项**(每个框先声明区、后调用区;递归走一遍) </summary>
        public static IEnumerable<分区项C> 全部项(框来源C? 框)
        {
            foreach (var 一框 in 全部框(框))
            {
                foreach (var 项 in 一框.声明区) yield return 项;
                foreach (var 项 in 一框.调用区) yield return 项;
            }
        }

        /// <summary> 按 `键` 找框(找不到给 null = 不硬猜) </summary>
        public static 框来源C? 找框(框来源C? 框, string 键)
        {
            foreach (var 一框 in 全部框(框))
                if (string.Equals(一框.键, 键, StringComparison.Ordinal)) return 一框;
            return null;
        }

        /// <summary>
        /// 框树里**头行正好是这一行**的那个方法框(H63-1「跟着调用走」按声明行认被调方法)。
        ///
        /// 为什么不复用界面那侧按"行落在区间里"认的口子(`MainWindow.找框含行`,编辑器光标那一档):
        /// 那个会被**外面那个容器框**先接住(容器框的 `止行` 盖住它里面的成员方法);
        /// 这里要的是"声明行 = 头行"的那一个,自己一层层往下找就行 —— 容器里的成员方法也认得出。
        /// 找不到给 null(不硬猜)。
        /// </summary>
        public static 框来源C? 找方法框(框来源C? 框, int 行, int 深 = 0)
        {
            if (框 == null) return null;
            if (深 > 硬上限C.语句块嵌套上限) throw 硬上限C.嵌套太深的错误("思维导图:找方法框", 框.行);
            if (框.种类 == 种类方法 && 框.行 == 行) return 框;
            foreach (var 子 in 框.子框们)
                if (找方法框(子, 行, 深 + 1) is { } 中) return 中;
            return null;
        }

        /// <summary>
        /// **H63-1:这条声明能不能"跟着调用走"钻到它的框** —— 是源码里定义的方法那一档。
        /// 三样缺一不可:① 有源码行(`是源码声明` + `行 &gt; 0`);② 知道在哪一份文件;
        /// ③ 种类是 方法 / 结构方法 / 成员方法(变量 / 常量 / 参数 / 局部 / 字段 / 类型 / 方法容器
        /// 不往里钻 —— 它们不是"被调用的方法",硬钻只会钻到一张不是它的框上)。
        /// `null`(根本没查到声明)照旧给假。
        /// </summary>
        public static bool 能钻到方法框(声明处C? 处)
            => 处 is { 是源码声明: true, 行: > 0 }
            && 处.文件.Length > 0
            && 处.种类 is "方法" or "结构方法" or "成员方法";

        /// <summary>
        /// **按行号排一串子项**(H60-12;施工图 = `未做任务清单.md` §9 H53 的"施工图 · 步 5")。
        ///
        /// 用户 2026-09-26 的口径:「所有顺序按照行号排序」—— `OrderBy` 是**稳定排序**,
        /// 所以**同号的两项按原来出现的顺序**留着(这一条不许换成人肉快排:`List.Sort` 不稳定,
        /// 同号会乱)。**只换顺序**:`键` / `行` / `种类` / `声明` / `链们` 一个字段都不动
        /// (H60-13 的配色靠 `种类`、H60-14 的双击跳转靠 `行`)。
        /// </summary>
        public static List<分区项C> 按行排(IEnumerable<分区项C>? 项们)
            => 项们 == null ? [] : 项们.OrderBy(项 => 项.行).ToList();

        /// <summary> 一套手势两处共用:框也按 `行` 排(同号按原来出现的顺序 —— `OrderBy` 是稳定排序)</summary>
        public static List<框来源C> 按行排(IEnumerable<框来源C>? 框们)
            => 框们 == null ? [] : 框们.OrderBy(框 => 框.行).ToList();

        // ---------------- 往下都是"按框归类"这一层自己 ----------------

        /// <summary>
        /// 每个框的 `声明区` / `调用区` / `子框们` 都排一遍,再递归往下排(施工图 ② 排三样)。
        /// `深` 是 T3 的嵌套计数(见 `全部框`;这里同样是一路递归)。
        ///
        /// 为什么连 `调用区` 也排(它本来就是树里的源码顺序):**护栏** —— 以后谁往调用区里插一条,
        /// 排一遍就还是行号序,不必再靠"插的时候记得插对地方"。
        /// **子框们**这一步是真的会变:文件框原来是"结构们 → 方法们 → 顶层流程块们"三组接着摆,
        /// 排完才是按源码顺序混着走(结构 / 方法 / 流程块按各自的行号)。
        /// </summary>
        private static void 按行排一棵树(框来源C 框, int 深 = 0)
        {
            if (深 > 硬上限C.语句块嵌套上限) throw 硬上限C.嵌套太深的错误("思维导图:按行排框树", 框.行);
            替换(框.声明区, 按行排(框.声明区));
            替换(框.调用区, 按行排(框.调用区));
            替换(框.子框们, 按行排(框.子框们));
            foreach (var 子 in 框.子框们) 按行排一棵树(子, 深 + 1);
        }

        /// <summary> 原地换掉一张表的内容(表本身是 `{ get; }` 的只读属性,只能清空再装) </summary>
        private static void 替换<T>(List<T> 原表, List<T> 排好)
        {
            原表.Clear();
            原表.AddRange(排好);
        }

        /// <summary> 一个结构框:字段进声明区,结构方法**两头都要** —— 声明区里一条(它是个名字)+ 下面一个方法框 </summary>
        private static 框来源C 长结构(结构节点C 结, string 文件, 声明索引C? 索引, int 止)
        {
            var 框 = new 框来源C
            {
                键 = $"结构:{结.名}@{结.行}",
                标题 = 结.名,
                种类 = 种类结构,
                行 = 结.行,
                止行 = 止,
                说明 = $"第 {结.行} 行声明",
            };
            foreach (var 字 in 结.字段们)
                框.声明区.Add(声明项(索引, 文件, 字.名, 字.行, "字段", 字.类型词));
            foreach (var 方 in 结.方法们)
            {
                框.声明区.Add(声明项(索引, 文件, 方.名, 方.头行, "结构方法"));
                框.子框们.Add(长方法(方, 文件, 索引));
            }
            return 框;
        }

        /// <summary>
        /// 一个方法框(**容器自己也是方法框** —— 它就是个 `静态 方法 名(…){…}`)。
        /// 容器的裸成员头(`方法节点C.方法们`)照旧挂在它下面(`子框们`),与普通方法体里的结构一样处理。
        /// </summary>
        private static 框来源C 长方法(方法节点C 方, string 文件, 声明索引C? 索引, int 深 = 0)
        {
            if (深 > 硬上限C.语句块嵌套上限) throw 硬上限C.嵌套太深的错误("思维导图:长方法框", 方.头行);
            var 框 = new 框来源C
            {
                键 = $"方法:{方.名}@{方.头行}",
                标题 = 方.名,
                种类 = 种类方法,
                行 = 方.头行,
                止行 = 方.止行 > 0 ? 方.止行 : 0,
                说明 = $"第 {方.头行} 行声明",
            };
            foreach (var 参 in 方.参数们)
                框.声明区.Add(声明项(索引, 文件, 参.名, 参.行, "参数", 参.类型词));
            foreach (var 局 in 方.局部们)
                框.声明区.Add(声明项(索引, 文件, 局.名, 局.行, "局部", 局.类型词));
            加语句们(框.调用区, 方.语句们, 文件, 索引);
            加流程块们(框.子框们, 方.流程块们, 文件, 索引, 方.止行 > 0 ? 方.止行 : int.MaxValue, 深);
            foreach (var 内 in 方.方法们) 框.子框们.Add(长方法(内, 文件, 索引, 深 + 1));
            return 框;
        }

        /// <summary> 一串同层的流程块 → 框(收尾行按"下一个同层块的起行 − 1"推,与 `声明线C` 同一套手势;`深` 见 `全部框`) </summary>
        private static void 加流程块们(List<框来源C> 收, List<流程块节点C> 块们, string 文件, 声明索引C? 索引, int 宿主止, int 深 = 0)
        {
            if (深 > 硬上限C.语句块嵌套上限)
                throw 硬上限C.嵌套太深的错误("思维导图:长流程块框", 块们.Count > 0 ? 块们[0].行 : 宿主止);
            for (int i = 0; i < 块们.Count; i++)
            {
                int 止 = i + 1 < 块们.Count ? 块们[i + 1].行 - 1 : 宿主止;
                收.Add(长流程块(块们[i], 文件, 索引, 止, 深 + 1));
            }
        }

        /// <summary> 一个流程块框:头里 `var k = …` 与体里声明的**都是它自己的局部**(用户点名的那一条) </summary>
        private static 框来源C 长流程块(流程块节点C 块, string 文件, 声明索引C? 索引, int 止, int 深 = 0)
        {
            var 框 = new 框来源C
            {
                键 = $"流程块:{块.词}@{块.行}",
                标题 = 块.词,
                种类 = 种类流程块,
                行 = 块.行,
                止行 = 止,
                说明 = $"第 {块.行} 行:{块.词}块",
            };
            foreach (var 头 in 块.头声明们)
                框.声明区.Add(声明项(索引, 文件, 头.名, 头.行, "局部", 头.类型词));
            foreach (var 局 in 块.局部们)
                框.声明区.Add(声明项(索引, 文件, 局.名, 局.行, "局部", 局.类型词));
            加语句们(框.调用区, 块.里层语句们, 文件, 索引);
            加流程块们(框.子框们, 块.子块们, 文件, 索引, 止, 深);
            return 框;
        }

        /// <summary>
        /// 这一层的语句 → 调用区的一条条子项(每条语句自己的调用链挂在它下面)。
        ///
        /// **H63-6(B 档口径)**:同一个**框**里**同名的链节只建一次** —— 用户原话「变量在同作用域里被调用,
        /// 只需一次 …… `a=a+1;` 就列一个 `a` 出来就好;这个 `a` 在同作用域被不同语句(赋值等)用到,也只列一次」。
        /// 挂在这个框里**第一次**出现的那条语句下面;后面出现的行号追加进第1节的 `也在行`
        /// (界面写进提示 —— "这一行用了谁"照样看得见,只是不再重复画一格)。
        /// **粒度是"框 + 名字"**:两个方法里各有一个 `i` 是两份声明,各列各的(与 H60-9 的声明索引同一套口径)。
        /// 重复的那一节**就地摘掉、把它的子们接上来**(`函数(b)` 里的 `b` 是另一个名字,还得按名字管)——
        /// 连子树一起丢掉会把"这个框里还用到 `b`"丢没。
        /// </summary>
        private static void 加语句们(List<分区项C> 收, List<语句C> 语句们, string 文件, 声明索引C? 索引)
        {
            var 见过 = new Dictionary<string, 调用链节C>(StringComparer.OrdinalIgnoreCase);
            foreach (var 句 in 语句们)
            {
                var 项 = new 分区项C
                {
                    键 = $"语句:{句.行}",
                    名 = 句.原文,
                    种类 = "语句",
                    行 = 句.行,
                    说明 = $"第 {句.行} 行语句",
                };
                // 第281批:语句级**连变量名一起收**(只要调用: 假)—— 用户「变量要有回调线」:
                // `i = i + 1;` 这种赋值以前一个链节都没有,`i` 自然没有回连线。
                项.链们.AddRange(调用线C.拆(句.原文, 句.行, 文件, 索引, 只要调用: false));
                按名去重(项.链们, 见过);        // H63-6:同一个框里同名只留第一处
                收.Add(项);
            }
        }

        /// <summary>
        /// **H63-6:一层链节按名字去重**(先序:同一个框里第一次出现的那一处留下,后面的摘掉)。
        /// 摘掉的那一节**把子们就地接上来** —— 子们是别的名字,还要照旧按名字管;
        /// 摘掉之后把它的行号记进第一个那节的 `也在行`(同一行重复出现只记一次)。
        /// </summary>
        private static void 按名去重(List<调用链节C> 链们, Dictionary<string, 调用链节C> 见过)
        {
            for (int i = 0; i < 链们.Count;)
            {
                var 节 = 链们[i];
                if (节.名.Length > 0 && 见过.TryGetValue(节.名, out var 首))
                {
                    if (首.行 != 节.行 && !首.也在行.Contains(节.行)) 首.也在行.Add(节.行);
                    链们.RemoveAt(i);
                    链们.InsertRange(i, 节.子们);
                    continue;                       // 接着看这一位上接上来的第一个
                }
                if (节.名.Length > 0) 见过[节.名] = 节;
                i++;
                按名去重(节.子们, 见过);
            }
        }

        /// <summary>
        /// 一条**声明项**:种类与声明处照 **H60-9 的 `声明索引C`** 那一档拿(施工图 ③"不许再写一套作用域推断")。
        /// 索引给不出来(或它挑中的不是这一行)时按树的形状**兜一个种类** —— 位置本来就是我们自己这棵树上的,
        /// 不编假东西,只是不硬猜"它属于哪一层"。
        /// </summary>
        private static 分区项C 声明项(声明索引C? 索引, string 文件, string 名, int 行, string 兜底种类, string 类型词 = "")
        {
            var 处 = 行 > 0 ? 索引?.查(名, 行, 文件) : null;
            if (处 == null || 处.行 != 行)
                处 = new 声明处C
                {
                    名 = 名,
                    全名 = 名,
                    种类 = 兜底种类,
                    文件 = 文件,
                    行 = 行,
                    是源码声明 = 行 > 0,
                    类型词 = 类型词,
                };
            return new 分区项C
            {
                键 = $"声明:{名}@{行}",
                名 = 名,
                种类 = 处.种类,
                行 = 行,
                类型词 = 类型词.Length > 0 ? 类型词 : 处.类型词,
                说明 = $"第 {行} 行声明",
                声明 = 处,
            };
        }
    }
