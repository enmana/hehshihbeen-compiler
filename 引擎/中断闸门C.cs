namespace hehshihbeen_compiler
{
    /// <summary>
    /// H22(2026-09-20):**长跑闸门** —— "跑多少条指令问一次『要不要停下』"的唯一口径。
    ///
    /// 为什么要有它:虚拟机跑一个死循环时,界面不能一直干等,得能被打断;但"每条指令都问一次"
    /// 会让最内层的循环多一次内存读(Release 实测 107 M 条/秒,那是一年年抠出来的)。折中 =
    /// **每 4096 条问一次**:Release 下约 38 微秒一次、Debug 下约 0.4 毫秒一次 ——
    /// 用户点「停止」几乎立刻见效,虚拟机那一趟也几乎不掉速度。
    ///
    /// 纯函数 + 常量(不碰线程、不碰界面):命令行自检直接喂数比。
    /// </summary>
    public static class 中断闸门C
    {
        /// <summary> 每跑这么多条指令查一次中断请求(2 的幂,取模就是按位与)</summary>
        public const int 检查间隔 = 4096;

        /// <summary> 走到第 `步数` 条时该不该查一次(步数从 1 数起:第 1 条不查,第 4096 条查)</summary>
        public static bool 该检查(long 步数) => 步数 > 0 && (步数 & (检查间隔 - 1)) == 0;
    }
}
