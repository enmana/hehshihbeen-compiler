        /// <summary> 按名字取一条(找不到给 null) </summary>
        public static 硬上限项? 取(string 名) =>
            表.FirstOrDefault(x => string.Equals(x.名, 名, System.StringComparison.Ordinal));

        /// <summary>
        /// T3(2026-09-27 评测整改):**"这棵树太深了,不往下走"** 那一条错误 —— 声明线 / 导图分区
        /// 那几处"照嵌套递归"的地方共用同一句话、同一个上限(`语句块嵌套上限`)。
        ///
        /// 为什么不各写一句:这几处递归都长在**界面的那条路**上(思维导图取框树 / 导图搜索),
        /// 栈溢出**不是可捕获异常**(`catch (Exception)` 接不住,`异常收集C` 也接不住)⇒ 以前嵌套 5000 层
        /// 一开导图,IDE 进程当场消失、没存的东西一起丢。现在撞上限就抛这条**带行号的编译异常C**,
        /// 界面按普通错误路径提示(用户看到的是人话,不是进程没了)。
        /// </summary>
        public static 编译异常C 嵌套太深的错误(string 谁, int 行, string? 文件 = null) =>
            new($"{谁}:这份文件嵌套太深(超过 {语句块嵌套上限} 层),不往下展开了 —— " +
                $"再往里递归会把 IDE 进程直接打死(栈溢出接不住,没保存的内容可能一起丢)。" +
                $"把最里面那半段提成一个 `方法`,或者用 `搜索` 直接定位名字",
                $"nesting too deep for {谁}", 行 > 0 ? 行 : null, null, 文件);

        /// <summary> 一行话把每条的上限串起来 —— 帮助文本《八、数据放哪儿、内存有多大》指路用(数字不手抄) </summary>
        public static string 一句话() => string.Join("、", 表.Select(x => $"{x.名} {x.值}").ToList());
    }
