                "不写数字就是列表 `整数 表[]`,个数自己长(受运行内存上限管);特别大又不改的可以分块"),

            new("字符串数组长度",
                $"{字符串数组长度上限} 个元素",
                $"`字符串 表[{字符串数组长度上限}];` —— 一个元素 {字符串元素宽} 字节(数据地址 + 容量)," +
                $"字符串数组的整块也封在 {数组长度上限} 字节里(实测 {字符串数组长度上限} 能编过、{字符串数组长度上限 + 1} 拦下)",
                "要更多就用字符串列表 `字符串 表[]`(元素同样 8 字节,字住在堆里、装不下自己换块)"),

