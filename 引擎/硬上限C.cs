    /// <summary>
    /// 一条**悬崖式硬上限**:撞上去是当场报错(不是慢慢变慢)。四个字段就是帮助站点那一节要说的全部 ——
    /// 名(查得到)/ 值(上限到底是多少)/ 在哪(什么写法会撞)/ 怎么绕(撞上了改成怎么写)。
    /// </summary>
    public sealed class 硬上限项
    {
        public 硬上限项(string 名, string 值, string 在哪, string 怎么绕)
        {
            this.名 = 名;
            this.值 = 值;
            this.在哪 = 在哪;
            this.怎么绕 = 怎么绕;
        }

        /// <summary> 上限的名字(帮助站点里那一条的标题,自检按它查) </summary>
        public string 名 { get; }
        /// <summary> 上限的值(用 `硬上限C` 里的常量拼出来,不手抄数字) </summary>
        public string 值 { get; }
        /// <summary> 什么写法会撞上(带实测到的形状) </summary>
        public string 在哪 { get; }
        /// <summary> 撞上了怎么绕(报错文案里那句"办法"与它同一个口径) </summary>
        public string 怎么绕 { get; }
    }

    /// <summary>
    /// R3-2(第184批):**悬崖式硬上限的唯一事实源**。
    /// <para>
    /// 第184批之前,这些数字只写在代码里(数组 65536 / 情况常量 32 位 / 表达式临时寄存器 15 /
    /// `包含` 深度 16),用户**撞上才知道**,而且四条报错各说各的(两条连上限都不说)。现在三处都吃这一份:
    /// </para>
    /// <list type="number">
    /// <item>编译器各处的**检查**用这里的常量(不再各写一个 `0x10000`);</item>
    /// <item>**报错文案**用这里的常量(数字不会再漂)+ 同一句"怎么绕";</item>
    /// <item>帮助站点的**「硬上限」一节从 `表` 生成** —— 表里加一条,站点就多一条
    ///   (自检拿假表钉住这条,与类型 / 指令 / 关键字那几节同一套办法)。</item>
    /// </list>
    /// <para>
    /// **评估结论:一条都不放大**(R3-2 要求"按自举会不会撞到一条条评估",四条都量过):
    /// ① **表达式临时寄存器 15 个** —— 受 ISA 管:寄存器就 R0~R15,R15 留给帧指针,加不了;
    /// ② **数组长度 65536**、**字符串数组 8192** —— 受 1MB 运行内存管(65536 个 4 字节元素 = 256KB,
    ///    已经是 1/4);真放大要跟 R1-3(总内存 1MB)一起拍板,本批只把它写清楚;
    /// ③ **情况常量 32 位** —— 受语言事实管:HB 的值最宽就是 32 位(`整数` / `无符号整数` 都 4 字节),
    ///    再大的常量没有任何值能匹配上;
    /// ④ **包含深度 16** —— 编译期自己的递归预算,16 层嵌套包含已经远比真实工程深(实测 16 层能编、17 层拦下)。
    /// </para>
    /// </summary>
    public static class 硬上限C
    {
        /// <summary> 写了数字的数组最多几个元素(`整数 表[65536]` 静态数据 256KB) </summary>
        public const int 数组长度上限 = 0x10000;

        /// <summary> 一个字符串元素占几字节(数据地址 + 容量),也是字符串数组封顶的依据 </summary>
        public const int 字符串元素宽 = 8;

        /// <summary> 字符串数组最多几个元素(整块封在 65536 字节里 ⇒ 8192 个) </summary>
        public const int 字符串数组长度上限 = 数组长度上限 / 字符串元素宽;

        /// <summary> 定长数组最多几维(H68-1 多维数组:2~4 维够用,再深地址累加与报错文案都不划算) </summary>
        public const int 数组维数上限 = 4;

        /// <summary> `情况` 常量的上限(按绝对值看;值本身最宽就是 32 位) </summary>
        public const ulong 情况常量上限 = 0xFFFFFFFF;

        /// <summary> 一句表达式能同时用几个临时寄存器(R0~R14;R15 是帧指针) </summary>
        public const int 临时寄存器数 = 15;

        /// <summary> `包含` 最多嵌几层(同一份文件只展开一次,所以这不是"防死循环"的闸) </summary>
        public const int 包含深度上限 = 16;

        /// <summary>
        /// **语句块**最多嵌几层(T2,2026-09-27 评测整改):`如果` / `选择` / `当` / `循环` / `遍历` 的
        /// `{ }` 每进一层算一层,函数体那一层也算。
        ///
        /// 为什么必须有一道上限(与 `表达式语法C.最大深度` 同一个病因):编译器的 `处理块 → 处理语句 → 处理块`
        /// 是**照嵌套递归**下去的,而 .NET 的栈溢出(`0xC00000FD`)**接不住** —— 进程当场没, stdout 零字节,
        /// stderr 只剩一段 .NET 裸栈,连一句行号都给不出(实测 Debug 档嵌套 `如果` 300 层还能编、450 层就死;
        /// `当` / `选择` 300 层能编、500 层就死;Release 档 1000 层死)。
        ///
        /// 128 是照"编译器能安全递归的深度"取的(离实测极限一倍以上余量,和表达式那道 128 层同一个口径),
        /// 不是"刚好够现有示例"。超限在 `处理块` 里当场抛**带行号的编译错误**,而不是编译器自己崩掉。
        /// </summary>
        public const int 语句块嵌套上限 = 128;

        /// <summary>
        /// 一个函数的帧多大(参数 + 局部变量 + 表达式临时槽**共用**的一块)。
        /// **H34 起它是可配的**:默认 `中间层C.默认帧大小`(96 字节),工程文件里写 `帧` 能在
        /// `最小帧大小` ~ `最大帧大小`(96 ~ 4096)之间调 —— 所以这条"硬上限"说的是**上限那一头**,
        /// 真编的时候按用户配的值来(自检拿编译提示里的"最大用量 / N"对着配的值钉)。
        /// </summary>
        public const int 帧字节上限 = 中间层C.最大帧大小;

        /// <summary>
        /// 全部硬上限(帮助站点的「硬上限」一节逐条读它;顺序 = R3-2 评估的顺序 + 帧)。
