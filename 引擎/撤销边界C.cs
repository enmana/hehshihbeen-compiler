namespace hehshihbeen_compiler
{
    /// <summary>
    /// 撤销的边界(C29,用户 2026-09-20 报的):**载入完成后才开始算撤销** ——
    /// 用户原话"撤销不能撤得太彻底,最后一个撤销会撤出来一个空白页(应该从代码载入完成后才开始算撤销)"。
    ///
    /// 为什么会有这个 bug:`界面控件\编辑器.xaml.cs` 的 `推送绑定内容到编辑器` 对**同一个** `TextDocument`
    /// 做一次 `Replace`(C10 有意为之:`TextEditor.Text = 文本` 会换掉整个文档、把撤销栈一起丢掉)。
    /// 可**载入文件**走的也是这条同一条路:页模型给内容 → 编辑器 `Replace("" → 全文)`
    /// ⇒ 栈底多了一条"把整篇删掉"的撤销单元,再按一次 `Ctrl+Z` 得到的就是空文档。
    ///
    /// 口径(只在这一处判,界面别各写一遍):**"载入"不进撤销栈,"用户动作"留一个撤销单元**。
    /// 判据两条,满足其一就是载入:
    /// <list type="bullet">
    /// <item>**换了页**:编辑器换到另一个标签页那份内容上(编辑器控件是各页共用的一个 `TextDocument`,
    ///       不清栈的话 `Ctrl+Z` 能一路撤回**上一个文件**的正文 —— 帮助里"撤销栈是每个文件自己的"就不成立了);</item>
    /// <item>**页上标着载入**:这一份内容来自磁盘 / 新建页 / 装载工程(页模型在载入那一刻标一下,
    ///       编辑器读走就复位)。</item>
    /// </list>
    /// 替换 / 格式化 / 改名 / 中英切换 / 全工程替换这些**用户动作**两条都不满足 ⇒ 照旧留一个撤销单元(C10 的成果不破)。
    ///
    /// 纯计算、不碰界面,自检直接喂参数钉真值表(见 `自检\综合自检C.多文件与自举.cs` 的 `撤销边界自检()`)。
    /// </summary>
    public static class 撤销边界C
    {
        /// <summary> 这一次"整篇推文本"算不算**载入**(载入要清空撤销栈;用户动作不清) </summary>
        /// <param name="换了页">编辑器这次的绑定源换成了另一个标签页(页对象不是上一次那个)</param>
        /// <param name="页上标着载入">页模型上那面"这一份是载入进来的"旗子(读走即复位)</param>
        public static bool 算载入(bool 换了页, bool 页上标着载入) => 换了页 || 页上标着载入;
    }
}
