using System.IO;
using System.Windows;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 主窗口的一部分(H39-2):**把"跑程序"接到子进程那条通道上**。
    ///
    /// 这一份只管三件事,而且**都只有这一处口径**:
    /// ① **子进程壳在哪儿**(`找跑程序壳`:IDE 旁边 → 开发构建 → 老 publish 路径 → dll + dotnet);
    /// ② **两台机器按需创建与重连**(`确保跑程序机` / `确保调试机`:通道死了就**就地重连** ——
    /// 同一条机器换一条新通道,重连过 ⇒ 下一次装载从头装一遍;H39-4);
    /// ③ **崩了如实说清**(`报跑程序故障`:退出码 + 标准错误尾巴 + "界面还在",绝不当成"程序跑完")。
    ///
    /// 界面上别的地方(执行 / 逐步 / 继续 / 断点 / 控制台)照旧只认 `前端契约C.服务.调试.机器` 与 `前端契约C.服务.调试.会话机器`
    /// 这两张老面孔 —— 于是"把跑程序挪出 IDE"这一步对它们**一个字都不用改**。
    /// </summary>
    public partial class MainWindow : Window
    {
        /// <summary> 子进程壳找不到 / 起不来时那句人话(null = 一路正常) </summary>
        private string? _跑程序不可用;

        /// <summary>
        /// **H90:子进程的当前目录 —— 必须钉在仓库根,不许跟着界面进程走**。
        ///
        /// 为什么要钉(用户 2026-10-11 当班实测报的缺陷):标准示例里的数据路径**一律照仓库根写**
        /// (`Sample/模型/人头肩/头肩.obj` / `工具/临时/示例30/主文件.txt` / `Sample/库/排序.hb`…),
        /// 而子进程若不指定当前目录就**继承界面进程的**那一份 —— 界面是从
        /// `bin\Debug\net10.0-windows\` 起的,于是"盘上明明有这份模型"却报
        /// `打不开这个文件(路径对不对?盘上有没有?)`(示例58 就是这么翻的车)。
        /// 命令行那条腿不踩它:`hbcc` 是在仓库根敲的,当前目录本来就是对的。
        ///
        /// 判据与实现收在 **`引擎\仓库根C.cs`**(唯一一处;那里也写着为什么起点必须是
        /// `AppContext.BaseDirectory` 而不是当前目录)。找不到 ⇒ null = 保持老行为。
        /// </summary>
        private static string? 跑程序工作目录() => 仓库根C.程序运行目录();

        /// <summary>
        /// H39-2:**子进程壳候选**(界面里只此一处,别在各处各拼一遍)。按优先级四档:
        /// ① IDE 旁边那份 `HB宿主.exe`(自包含发布/拷贝过去的那一份);
        /// ② 仓库里的开发构建 `HB宿主\bin\{Release,Debug}\net10.0\HB宿主.exe`(**先 Release**:快);
        /// ③ 老那套发布路径(`列宿主候选()`;贴独立 exe 那条路一直用它);
        /// ④ 同一层的 `HB宿主.dll` ⇒ 用 `dotnet &lt;dll&gt; --跑程序服务` 起。
        /// </summary>
        private static List<(string 可执行, string[] 参数, string 说明)> 跑程序壳候选()
        {
            var 表 = new List<(string 可执行, string[] 参数, string 说明)>();
            string 旁边 = Path.Combine(AppContext.BaseDirectory, "HB宿主.exe");
            if (File.Exists(旁边)) 表.Add((旁边, [跑程序协议C.服务参数], "界面旁边那份 HB宿主.exe"));

            var 目录 = new DirectoryInfo(AppContext.BaseDirectory);
            for (int 上 = 0; 上 < 6 && 目录?.Parent != null; 上++)
            {
                目录 = 目录.Parent;
                foreach (string 配置 in new[] { "Release", "Debug" })
                {
                    string 基 = Path.Combine(目录.FullName, "HB宿主", "bin", 配置, "net10.0");
                    string exe = Path.Combine(基, "HB宿主.exe");
                    if (File.Exists(exe)) 表.Add((exe, [跑程序协议C.服务参数], $"开发构建({配置})的 HB宿主.exe"));
                    string dll = Path.Combine(基, "HB宿主.dll");
                    if (File.Exists(dll)) 表.Add(("dotnet", [dll, 跑程序协议C.服务参数], $"开发构建({配置})的 HB宿主.dll"));
                }
            }
            foreach (string 发布 in 列宿主候选())
                if (File.Exists(发布)) 表.Add((发布, [跑程序协议C.服务参数], "老发布路径那份 HB宿主.exe"));
            return 表;
        }

        /// <summary>
        /// H39-2 + **H92**:从候选里挑**第一个够新的**壳;一个都没有给 null(`为什么` 里说明原因,
        /// 调用方用它区分"比当前代码旧"与"根本找不到")。
        ///
        /// ⚠ **为什么非问一句"你是哪一版"不可**(2026-10-11 用户实测报的 `示例59_剪贴板与弹窗`):
        /// 老口径只判"文件在不在" ⇒ 盘上那份 `HB宿主.exe` 是当天 14:40 编的,而剪贴板 / 提示框 /
        /// 选文件那一族(功能号 **80~85**)17:29 才落地 —— 界面照旧拿它跑,`复制` 给 0、提示框读回
        /// **没人写过的**垃圾值(库把按钮号当成了答案),程序跑完、输出全错、界面一句提示都没有。
        /// 更糟的是候选①(界面旁边那份)常常是更老的**发布版**,一撞上就永远轮不到后面那份新构建。
        /// ⇒ 逐个问 `--能力`(H35 那套;问过的按 路径 + 大小 + 时间 缓存,不会每次编译都问一遍),
        /// 取第一个够新的;都不够新就**如实说清 + 不跑**(绝不拿旧的凑合)。
        ///
        /// `dotnet &lt;dll&gt;` 那一档**问不了**(`问能力` 只认 exe)⇒ 留作最后一档直接信它 ——
        /// 它是刚编出来的开发构建。
        /// </summary>
        private static (string 可执行, string[] 参数)? 找跑程序壳(out string 为什么)
        {
            为什么 = "";
            var 旧说法 = new List<string>();
            foreach ((string 可执行, string[] 参数, string 说明) in 跑程序壳候选())
            {
                if (可执行.Equals("dotnet", StringComparison.OrdinalIgnoreCase)) return (可执行, 参数);
                string? 旧 = 前端契约C.服务.宿主.陈旧原因(可执行);
                if (旧 == null) return (可执行, 参数);
                旧说法.Add($"{说明}({旧})");
            }
            if (旧说法.Count > 0) 为什么 = string.Join(";", 旧说法);
            return null;
        }

        /// <summary>壳不能用时那句人话(H92:**"比当前代码旧"与"根本找不到"要分开说** —— 两句的下一步不一样)</summary>
        private static string 壳不可用说明(string 壳旧, string 下一步)
            => 壳旧.Length > 0
                ? $"跑程序用的那个 HB宿主 比当前代码旧,已拒绝用它 —— {壳旧}。" +
                  "⚠ 它没有的能力**不报错**,而是**静默给错结果**(2026-10-11 实测:`复制` 给 0、" +
                  $"提示框读回没人写过的值)⇒ 先重建:`dotnet build HB宿主\\HB宿主.csproj`(或跑 `工具\\五端构建.ps1`),再{下一步}。"
                : $"找不到 HB宿主.exe —— 先构建 HB宿主\\HB宿主.csproj(或跑 工具\\五端构建.ps1),再{下一步}。";

        /// <summary>
        /// H39-2:保证"执行"那台虚拟机是**住在子进程里**的那一台。
        /// H39-4:通道死过 ⇒ **就地重连**(同一条机器 / 断点表 / 记账面孔都在,只换一条新通道),
        /// 连不上才说"跑不成"(原因记在 `_跑程序不可用`,调用方念给用户听)。
        /// </summary>
        private bool 确保跑程序机()
        {
            if (前端契约C.服务.调试.机器 is 跨进程虚拟机C 现成)
            {
                if (现成.通道可用) { 接上跑程序回调(会话机: false); return true; }
                if (现成.重连()) { 接上跑程序回调(会话机: false); _跑程序不可用 = null; return true; }
                _跑程序不可用 = $"跑程序子进程起不来:{现成.通道.死因}";
                return false;
            }
            var 壳 = 找跑程序壳(out string 壳旧);
            if (壳 == null)
            {
                _跑程序不可用 = 壳不可用说明(壳旧, "执行");
                return false;
            }
            var 通道 = new 跑程序通道C(壳.Value.可执行, 壳.Value.参数, 跑程序工作目录());
            if (!通道.活着)
            {
                _跑程序不可用 = $"跑程序子进程起不来:{通道.死因}";
                return false;
            }
            // H38-2:先把新机器交给契约,再按"哪一台"接回调 —— 界面不再攥着这台机器(参数只传一个 bool)
            前端契约C.服务.调试.机器 = new 跨进程虚拟机C(通道);
            接上跑程序回调(会话机: false);
            _跑程序不可用 = null;
            return true;
        }

        /// <summary>
        /// 同上,给**调试会话**那一台(与"执行"那台各是各的通道:两边各有自己的 PC / 内存 / 等输入状态)。
        /// 换了机器 / 重连过 = 机器码得重装一遍,判据在 `需要重新装载()` 里(基类那三条 + 重连那一档)。
        /// </summary>
        private bool 确保调试机()
        {
            if (前端契约C.服务.调试.会话机器 is 跨进程虚拟机C 现成)
            {
                if (现成.通道可用) { 接上跑程序回调(会话机: true); return true; }
                if (现成.重连()) { 接上跑程序回调(会话机: true); _跑程序不可用 = null; return true; }
                _跑程序不可用 = $"跑程序子进程起不来:{现成.通道.死因}";
                return false;
            }
            var 壳 = 找跑程序壳(out string 壳旧);
            if (壳 == null)
            {
                _跑程序不可用 = 壳不可用说明(壳旧, "逐步调试");
                return false;
            }
            var 通道 = new 跑程序通道C(壳.Value.可执行, 壳.Value.参数, 跑程序工作目录());
            if (!通道.活着)
            {
                _跑程序不可用 = $"跑程序子进程起不来:{通道.死因}";
                return false;
            }
            前端契约C.服务.调试.会话机器 = new 跨进程虚拟机C(通道);
            接上跑程序回调(会话机: true);
            _跑程序不可用 = null;
            return true;
        }

        /// <summary>
        /// 把那几个"程序 ↔ 界面"的注入口径接到**这一台**机器上 —— 与 H22 那条进程内老口径**一字不差**的四个回调
        /// (程序输出 / 程序输入 / 等输入 / 宿主调用)。图形那两样(呈现口 / 事件出口)在 `同步图形呈现()` 里接。
        /// H38-2:参数是"哪一台"(会话机 / 执行机),机器本身问契约要 —— 界面不再存引擎对象。
        /// </summary>
        private void 接上跑程序回调(bool 会话机)
        {
            var 机 = 前端契约C.服务.调试.取机器(会话机);
            机.输出目标 = b => 控制台吐字节(b);
            机.输入源 = 取一个输入字节;
            机.等输入 = true;                  // IDE 里读输入而没数据 → 停下来等你敲,而不是当"没有输入了"
            机.宿主调用 = 前端契约C.服务.宿主.处理;        // P28:读文件 / 写文件 / 当前时间(相对路径按 IDE 的当前目录算)
        }

        /// <summary>
        /// H39-2:跑程序那条腿出的事**如实说清**。返回 true = 这确实是"子进程 / 通道"的事
        /// (调用方别再补一句别的),并且已经把这个说法写进了输出页。
        ///
        /// 三条口径:① **绝不当成"程序跑完"**(断言那一支根本不进);② 说清是**子进程没了**、
        /// 界面还在、下次自动换新通道;③ 退出码 / 标准错误尾巴都在 `异常.Message` 里(见 `跑程序通道C.死因`)。
        /// </summary>
        private bool 报跑程序故障(Exception 异常)
        {
            if (异常 is not 跑程序通道错误C) return false;
            输出框.AppendText("\n⚠ 跑程序子进程没了:" + 异常.Message + "\n" +
                "   引擎 / 宿主那一侧崩了,带不走这个界面 —— 下一次「执行」/「逐步」会自动重连,从头再跑一遍。\n" +
                "   这一趟没跑完:下面不做输出断言(免得把半截输出当成结果)。\n");
            切到底部输出();
            return true;
        }

        /// <summary> 壳找不到 / 起不来时念一句人话(跑不成,也别让人对着"什么都没发生"发愣)</summary>
        private void 报跑程序不可用()
        {
            输出框.AppendText("\n⚠ " + (_跑程序不可用 ?? "跑程序子进程不可用") + "\n");
            切到底部输出();
            记异常框(_跑程序不可用 ?? "跑程序子进程不可用");
        }
    }
}
