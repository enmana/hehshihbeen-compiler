using System.Linq;
using System.Windows.Threading;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **运行监视条(H100 第一步)** —— 执行 / 调试的时候,窗口最底下一行实时报:
    /// `状态 · PC · 已执行条数 · 条每秒 · 子进程 CPU · 子进程物理内存`。
    ///
    /// **口径(为什么这块不用改协议、不用改虚拟机)**:
    /// · **状态 / PC / 已执行条数**:执行是**分块驱动**的(`跑一遍` 里一块 `机.跑到([], 每块步数)`,
    ///   一块 `每块步数` 条),每块收尾那一帧状态就会把 PC / 条数刷进前端这面镜像 ⇒ 每 400 ms 采一次样,
    ///   读到的就是"上一块跑完时"的真实值(不是猜的)。
    /// · **子进程 CPU / 物理内存**:走**契约取到的那台机**(`前端契约C.服务.调试.取机器(…)`)的
    ///   `进程用量()` —— 只有跨进程那台给得出(子进程才是真正在烧 CPU 的那一台)。**拿不到就不显示**,
    ///   绝不编一个数。
    ///   ⚠ 这一行**不点名引擎类型**(连注释里也不点):`前后端边界` 那条棘轮按**源码文本**数"界面侧
    ///   直接摸引擎的处数",在注释里写一句引擎类型名照样把读数抬上去(第429批实测:它把上限 1 顶穿,
    ///   而真调用点一个都没有 —— 那一处是**假红**)。
    /// · **条每秒**由两次采样的条数差算;取最近 5 次的中位数(一块跑完的瞬间会跳一下,平滑掉好看)。
    /// · 装着的那台**停机了 / 还没装载**:显示"就绪" + 工程配的运行内存档,不显示会误导的 0。
    ///
    /// **第二步(2026-10-15 第442批,已做)**:池 / 堆 / 软栈三个实时用量也上了这一行 ——
    /// `池 已用/能长到 · 堆 已用/整块 · 软栈 帧指针走到哪/整块`。**没有动协议**:这三个数运行期本来就
    /// 记在几个账本槽里(池指针 / 池末 / 空闲表头 / 堆末 / 软栈底),汇编器把槽地址翻好、引擎侧算成用量
    /// (**口径只有一处**,不在这边);界面只拿数(走契约那一格 `内存用量`)。
    /// **拿不到就不显示那一项**(绝不编数);读的是**镜像内存**,比 PC 略滞后一帧。
    /// </summary>
    public partial class MainWindow
    {
        private DispatcherTimer? _运行监视计时器;

        /// <summary>
        /// H100 第二步(2026-10-15 第442批):「执行」那条腿**一块多少条**。
        /// 为什么要有它:"跑到"一条命令**只回状态、不带内存增量**(每步要小那条口径)⇒ 块太大的话
        /// 监视条上的池 / 堆 / 软栈一整块里都停在开跑前那份。200 万条一块(这台机器上大约 20~200 毫秒一块)
        /// ⇒ 每 400 ms 采样一次看到的就是真数。**闸门与步数上限仍在引擎那一处**,这只是分几趟走。
        /// </summary>
        private const long 每块步数 = 2_000_000;

        /// <summary> 一次「执行」最多走多少条(与 H39-2 那条口径同一个数:撞了当"疑似死循环"报) </summary>
        private const long 总步数上限 = 20_000_000;

        // ---- 采样用的一格状态(只在界面线程碰,不用锁) ----
        private long _监视上次条数;
        private TimeSpan _监视上次处理器;
        private DateTime _监视上次时刻 = DateTime.MinValue;
        private readonly double[] _监视条频 = new double[5];
        private int _监视条频位;
        private int _监视条频个数;

        /// <summary> 起运行监视(窗口起来时调一次;重复调是空操作) </summary>
        private void 起运行监视()
        {
            if (_运行监视计时器 != null) return;
            _运行监视计时器 = new DispatcherTimer(DispatcherPriority.Background, Dispatcher)
            {
                Interval = TimeSpan.FromMilliseconds(400),
            };
            _运行监视计时器.Tick += (_, _) => 刷运行监视();
            _运行监视计时器.Start();
        }

        /// <summary> 采一次样,把那一行字拼出来。**任何一步拿不到就照"拿不到"写**,不编数。 </summary>
        private void 刷运行监视()
        {
            if (运行监视条 == null) return;
            try
            {
                // 调试那条腿(有断点)看的是"会话那一台",否则看"执行那一台" —— 与 F5 / 继续 走同一档
                bool 调试档 = 前端契约C.服务.调试.断点个数 > 0;
                var 机 = 前端契约C.服务.调试.取机器(调试档);

                var 现在 = DateTime.UtcNow;
                long 条数 = 机.已执行条数;
                double 墙钟秒 = _监视上次时刻 == DateTime.MinValue ? 0 : (现在 - _监视上次时刻).TotalSeconds;
                var 用量 = 机.进程用量();

                // ---- 条每秒:上一格条数到这一格的差(装载 / 复位会让条数变小 ⇒ 只当新基准) ----
                double 条频 = 0;
                if (墙钟秒 > 0.05 && 条数 >= _监视上次条数)
                {
                    double 现算 = (条数 - _监视上次条数) / 墙钟秒;
                    _监视条频[_监视条频位] = 现算;
                    _监视条频位 = (_监视条频位 + 1) % _监视条频.Length;
                    if (_监视条频个数 < _监视条频.Length) _监视条频个数++;
                    var 有效 = _监视条频.Take(_监视条频个数).Where(x => x > 0).OrderBy(x => x).ToArray();
                    if (有效.Length > 0) 条频 = 有效[有效.Length / 2];       // 中位数:一块跑完那一跳不刺眼
                }

                // ---- CPU:子进程累计处理器时间的差 ÷ 墙钟(单核口径,`一个核烧满` = 100%) ----
                string CPU = "";
                if (用量 is { } 今)
                {
                    if (墙钟秒 > 0.05 && _监视上次处理器 > TimeSpan.Zero && 今.处理器秒 >= _监视上次处理器.TotalSeconds)
                    {
                        double 占 = (今.处理器秒 - _监视上次处理器.TotalSeconds) / 墙钟秒 * 100;
                        CPU = $" · CPU {占:F0}%";
                    }
                    _监视上次处理器 = TimeSpan.FromSeconds(今.处理器秒);
                }

                _监视上次条数 = 条数;
                _监视上次时刻 = 现在;

                // ---- 那一行字 ----
                string 状态 = 机.停机 ? "停机"
                    : 机.正在等输入 ? "等输入"
                    : 机.命中断点 ? "停在断点"
                    : 机.有中断请求 ? "正在停止…"
                    : 机.已中断 ? "被停止"
                    : "跑着";
                bool 没跑过 = 条数 == 0 && 机.停机 && !调试档;
                string 内存档 = $"运行内存 {(当前内存大小 / 1048576.0):F0}MB";
                string 子进程 = 用量 is { } 用 ? $" · 子进程 {用.物理字节 / 1048576.0:F1}MB" : "";
                string 条频段 = 条频 > 0 ? $" · {条频 / 1000.0:F0}K 条/秒" : "";

                // ---- H100 第二步:池 / 堆 / 软栈(H100 第二步那一档;口径一处 = 引擎 `内存用量C`) ----
                // **不在这儿要内存**:跨进程那台要一次"读内存"就得等它回执,而它可能正在跑一块两千万条
                // ⇒ 界面当场冻住(那条通道自己的注释就警告过)。读的是**镜像内存**(子进程每帧把改动过的段贴回来),
                // 所以这几个数会略滞后于 PC —— 监视条本来就是"每 400 ms 看一眼"的东西,滞后一帧不要紧。
                var 内存用量 = 前端契约C.服务.调试.内存用量(机);
                static string 大小(int 字节) => 字节 >= 1048576 ? $"{字节 / 1048576.0:F1}MB"
                    : 字节 >= 1024 ? $"{字节 / 1024.0:F1}KB" : $"{字节}B";
                string 池段 = 内存用量.池顶 > 0 ? $" · 池 {大小(内存用量.池用)}/{大小(内存用量.池顶)}" : "";
                string 堆段 = 内存用量.堆共 > 0 ? $" · 堆 {大小(内存用量.堆用)}/{大小(内存用量.堆共)}" : "";
                string 软栈段 = 内存用量.软栈共 > 0 ? $" · 软栈 {大小(内存用量.软栈用)}/{大小(内存用量.软栈共)}" : "";

                运行监视条.Text = 没跑过
                    ? $"就绪 · {内存档}"
                    : $"{(调试档 ? "调试" : "执行")} · {状态} · PC 0x{机.程序计数器:X}" +
                      $" · 已执行 {条数:N0} 条{条频段}{CPU}{子进程} · {内存档}{池段}{堆段}{软栈段}";
                运行监视条.ToolTip =
                    "执行是**分块驱动**的:状态 / PC / 条数取的是上一块收尾时那一帧真值;\n" +
                    "CPU 与物理内存是**子进程**的 OS 读数(拿不到就不显示)。\n" +
                    "池 / 堆 / 软栈是**运行期那块内存里的实时用量**(池 = 已用/现在能长到;堆 = 已用/整块;\n" +
                    "软栈 = 帧指针走到的位置/整块)—— 读的是**镜像内存**,比 PC 略滞后一帧;\n" +
                    "没有那一项(比如没用到堆)就整段不显示,拿不到数就一个字都不编。";
            }
            catch (Exception 错)
            {
                运行监视条.Text = "运行监视不可用:" + 错.Message;      // 监视自己坏了不许影响跑程序
            }
        }
    }
}
