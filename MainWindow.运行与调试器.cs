        /// <summary>
        /// 找**能发布好**的宿主。`要自包含: true` 时只认**真自包含**那份(体积 + 无伴随 dll,判据在
        /// `打包规格C.自包含原因`)—— R3-6-4 批 4 那条"假自包含宿主"缺陷要的就是这一刀。
        ///
        /// H35 再补一刀:**这一份是不是这一版**(问一句 `--能力`,判据在 `宿主与文件服务C.问能力`)——
        /// 老宿主不认这句问话(退出码非 0、输出里也没有能力标记)⇒ 判陈旧。
        /// **先挑够新的**;一份够新的都没有,才退回去挑那份"能用但旧"的,由 `贴尾巴生成` 如实说清
        /// (程序用得到它没有的能力就这一轮不产 exe)。
        /// H26 又补一条轴:`该到包格式` —— 程序有顶层常量初值时要宿主读得动段式初值包(`HBE3`),
        /// 只认 `HBE2` / 不认「包格式」那一行的老宿主同样算"不够新"。
        /// </summary>
        private static string? 取宿主exe(bool 要自包含 = false, int 该到包格式 = 0)
        {
            string? 旧的 = null;
            foreach (string p in 列宿主候选())
            {
                if (要自包含 && !打包规格C.是自包含(p)) continue;
                if (前端契约C.服务.宿主.陈旧原因(p, 0, 该到包格式) == null) return p;      // 够新:就是它
                旧的 ??= p;
            }
            return 旧的;
        }

        /// <summary> 盘上可能放着宿主 exe 的地方,按优先级排(发布目录 → 自己旁边) </summary>
        private static IEnumerable<string> 列宿主候选()
        {
            var 根 = new DirectoryInfo(AppContext.BaseDirectory);
            for (int 上 = 0; 上 < 6 && 根?.Parent != null; 上++)
            {
                根 = 根.Parent;
                foreach (string 配置 in new[] { "Release", "Debug" })
