        /// <summary> 正在跑的是**调试会话那一台**吗(H38-2:界面不再存那台机器,只记"是哪一台";「停止」按它找)</summary>
        private volatile bool _跑着的是会话机;

        /// <summary>
        /// **正在跑的那一趟**(整趟:`跑一遍` / `继续` 那个 Task)。
        ///
        /// 为什么另立一格:`_正在跑` 只回答"有没有人在跑",它**等不住** —— 而「执行」在程序还在跑的时候
        /// 按下去要等上一趟**收工**(收尾那一步才会 `收掉图形窗口()`、把 `_正在跑` 置回假),
        /// 不等它,新那一趟的 `打开窗口` 就会撞上还挂着的呈现口。只在界面线程上读写:
        /// 谁置谁清都在同一个 `记一趟` 里(置在 `await` 之前、清在它自己的 `finally`)。
        /// </summary>
        private Task? _跑着的那一趟;

        /// <summary>
        /// 把一趟跑起来**并记账** —— 界面里每一处"真跑程序"都走它(`跑一遍` 与 `继续`),
        /// 于是"程序还在跑"这件事永远有一个等得住的 Task(见 `_跑着的那一趟`)。
        ///
        /// `finally` 里按**引用**比着清:`跑一遍` 自己撞上"程序正在跑"那一句早退时返回的是一个
        /// 已完成的任务,不能顺手把**别人**那一趟的账清掉。
        /// </summary>
        private async Task 记一趟(Task 这一趟)
        {
            _跑着的那一趟 = 这一趟;
            try { await 这一趟; }
            finally { if (ReferenceEquals(_跑着的那一趟, 这一趟)) _跑着的那一趟 = null; }
        }

        /// <summary>
        /// 「执行」在**程序还在跑**的时候按下去:先按「停止」那一套把它叫停,再**等这一趟收工**。
        ///
        /// 为什么非等不可:收工那一步里 `收掉图形窗口()` 是"下一趟能开出新窗口"的前提 ——
        /// 不等它,新那一趟的 `打开窗口` 会撞上还没摘掉的呈现口(用户 2026-10-12 实测的现象:
        /// 第二次 F5 不显示,前端那个窗口没被收掉)。
        ///
        /// 中断是**异步**的(虚拟机每 `中断闸门C.检查间隔` 条查一次请求),所以这里等的是
        /// "那一趟跑完"这件事本身,不是一个固定时长;等的过程中界面照旧能点能滚(`await` 回界面线程),
        /// 用户再按一次「执行」也只是再等同一趟(那一趟收工后由 `跑一遍` 那句挡板管)。
        /// </summary>
        private async Task 先停下正在跑的那一趟()
        {
            try
            {
                输出框.AppendText("\n⏹ 程序还在跑 —— 按「执行」= 重新执行:先把它停掉,再从程序开头跑一遍。\n");
