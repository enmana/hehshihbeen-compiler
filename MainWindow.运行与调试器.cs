        /// <summary>
        /// 跑一次 dotnet publish 把宿主发布成自包含单文件(输出写进日志)。
        /// R3-6-4 批 4:`-p:DebugType=none` 顺手不带 pdb —— 判"是不是真自包含"时 pdb 不参与运行,
        /// 但产物目录越干净,`打包规格C.自包含原因` 那三条判据越不容易被无关文件搅浑。
        /// </summary>
        private static bool 发布宿主(out string 日志)
        {
            日志 = "";
            try
            {
                var 根 = new DirectoryInfo(AppContext.BaseDirectory);
                string? 工程 = null;
                for (int 上 = 0; 上 < 6 && 根?.Parent != null; 上++)
                {
                    根 = 根.Parent;
                    string p = Path.Combine(根.FullName, "HB宿主", "HB宿主.csproj");
                    if (File.Exists(p)) { 工程 = p; break; }
                }
                if (工程 == null) { 日志 = "找不到 HB宿主\\HB宿主.csproj"; return false; }
                var 起 = new System.Diagnostics.ProcessStartInfo("dotnet")
                {
                    WorkingDirectory = Path.GetDirectoryName(工程)!,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                };
                起.ArgumentList.Add("publish");
                起.ArgumentList.Add("HB宿主.csproj");
                起.ArgumentList.Add("-c"); 起.ArgumentList.Add("Release");
                起.ArgumentList.Add("-r"); 起.ArgumentList.Add("win-x64");
                起.ArgumentList.Add("--self-contained");
                起.ArgumentList.Add("-p:PublishSingleFile=true");
                // **H36(第225批实测)**:单文件发布默认**不把原生库打进去** —— Avalonia 的
                // `libSkiaSharp.dll` / `libHarfBuzzSharp.dll` / `av_libglesv2.dll` 会留在发布目录旁边:
                // ① `是自包含()` 判"旁边躺着 dll ⇒ 不是单文件" ② 真贴出去的那个 exe 旁边什么都没有 ⇒
                // 桌面壳起不来(界面线程 15 秒都进不了消息循环)⇒ `打开窗口` 一律给 假,独立 exe 里看不见窗口。
               起.ArgumentList.Add("-p:IncludeNativeLibrariesForSelfExtract=true");
                起.ArgumentList.Add("-p:DebugType=none");
                using var 进程 = System.Diagnostics.Process.Start(起);
                if (进程 == null) { 日志 = "起不了 dotnet 进程"; return false; }
                string 出 = 进程.StandardOutput.ReadToEnd();
                string 错 = 进程.StandardError.ReadToEnd();
                进程.WaitForExit();
                日志 = 出 + 错;
                return 进程.ExitCode == 0;
            }
            catch (Exception ex)
            {
                日志 = ex.Message;
                return false;
            }
        }

