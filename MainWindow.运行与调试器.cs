        private void 热重载菜单_Click(object sender, RoutedEventArgs e)
        {
            if (!确保编译过())
            {
                编译框.AppendText("\n热重载:请先编译(运行→编译)。\n");
                切到底部编译();
                return;
            }
            切到底部输出();
            if (_正在跑)
            {
                前端契约C.服务.调试.请求中断(_跑着的是会话机);
                输出框.AppendText("热重载:程序还在跑 —— 已经请它停下(与「停止」同一套)。停下来之后再按一次 F6 换新机器码。\n");
                return;
            }
            // 换哪一台:"逐步"那一台装着这份机器码就换它,否则换"执行"那一台。
            // 机器那张面孔由契约给(界面侧不点名引擎类型 —— 那是「前后端边界」棘轮盯着的那条线)。
            bool 换会话机 = 前端契约C.服务.调试.会话机器码就是这一份(当前机器码)
                && 前端契约C.服务.调试.会话有机器码;
            var 机 = 前端契约C.服务.调试.取机器(换会话机);
            if (!前端契约C.服务.调试.热重载(机, 当前机器码))
            {
                输出框.AppendText("热重载:没有可用的编译结果(先编译一次)。\n");
                return;
            }
            输出框.AppendText($"热重载:新机器码已经换进{(换会话机 ? "调试会话那一台" : "执行那一台")}({当前机器码.Length} 字节)。\n");
            foreach (string 一条 in 机.上次重载说明) 输出框.AppendText($"  · {一条}\n");
            输出框.AppendText("重载后从程序开头重跑(寄存器 / 调用栈 / 堆里的对象不带过来);按 F5 接着跑。\n");
            本次重新编译过 = false;                  // 机器码已经换过了,别让下一次 F5 又从头装一遍
            刷新命令可用性();
        }

