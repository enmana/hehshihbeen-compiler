        /// <summary>
        /// 把程序跑一遍,结果写进"输出"页。
        /// 机 = 用哪台虚拟机(正常执行用 前端契约C.服务.调试.机器;有断点就换成调试会话那台,好"停住/接着跑");
        /// 跑到断点 = true 时逐条走到断点或停机 —— **停在断点上就不做断言**(程序还没跑完);
        /// 接上一次的输出 = true 时**不清**"本次程序输出"缓冲、也不再打一遍项目名头(C17:有断点时
        /// "执行"是分两段跑的,第二段接着跑,断言要比的是**整个程序**的输出,不是最后一段)。
        ///
        /// **H22(2026-09-20)**:整趟执行挪到**后台线程**(`在后台跑`)—— HB 程序死循环时界面不再冻住,
        /// 可以按「停止」叫停,不必杀进程。所以这个方法分三段:**界面线程准备 → 后台线程跑 → 界面线程收尾**;
        /// 中间那一段里一个界面对象都不许碰(程序输出的字节先进缓冲,由界面线程的节流器刷出来)。
        /// </summary>
        private async Task 跑一遍(bool 跑到断点, bool 接上一次的输出 = false)
        {
            if (_正在跑)
            {
                输出框.AppendText("\n程序正在跑 —— 先按「停止」,或者等它跑完。\n");
                切到底部输出();
                return;
            }
            // H38-2:"跑哪一台"由契约按"跑到断点"这一档给:跑到断点 = 调试会话那一台,否则是"执行"那一台。
            // 界面手里只剩一个局部变量(临时用),**一个字段都不留**。
            var 机 = 前端契约C.服务.调试.取机器(跑到断点);
            bool 停在断点 = false;
            bool 在等输入 = false;
            bool 被停 = false;
            try
            {
                // ---------- 第一段:界面线程上把这一趟准备好 ----------
                // 工程文件里的 `内存` 在这儿生效(和编译时显示的是同一个数);
                // **只在真的不一样时才设** —— 设内存大小会把栈指针重置到栈顶,程序跑一半时重置就把栈毁了
                if (机.内存大小 != 当前内存大小) 机.设内存大小(当前内存大小);
                // 这台虚拟机该不该重新装"当前这份机器码":判据在引擎侧(`调试服务C.要重新装载`)——
                // ① 装的不是这一份(刚换过工程 / 刚设过内存)② **上一轮已经停机**
