        /// <summary> 解析老式断言注释 "// 预期结果: R0 = N"(没有则 null) </summary>
        private static long? 取预期R0(string 源码)
        {
            foreach (string 行 in 源码.Split('\n'))
            {
                string 行文本 = 行.Trim();
                if (!行文本.Contains("预期结果") && !行文本.Contains("expected")) continue;
                var 匹配 = Regex.Match(行文本, @"R0\s*=\s*(0x[0-9A-Fa-f]+|\d+)");
                if (!匹配.Success) continue;
                string 数 = 匹配.Groups[1].Value;
                if (数.StartsWith("0x", StringComparison.OrdinalIgnoreCase)) return Convert.ToInt64(数, 16);
                if (long.TryParse(数, out long 十进制)) return 十进制;
            }
            return null;
        }

        /// <summary> 解析新式断言注释 "// 预期输出: a|b|c"(| 表示换行) </summary>
        private static List<string> 取预期输出行(string 源码)
        {
            var 结果 = new List<string>();
            foreach (string 行 in 源码.Split('\n'))
            {
                string 行文本 = 行.Trim();
                if (!行文本.StartsWith("//", StringComparison.Ordinal)) continue;
                int 位置 = 行文本.IndexOf("预期输出", StringComparison.Ordinal);
                if (位置 < 0) continue;
                int 冒号 = 行文本.IndexOf(':', 位置);
                if (冒号 < 0) 冒号 = 行文本.IndexOf('：', 位置);
                if (冒号 < 0) continue;
                string 值 = 行文本[(冒号 + 1)..].Trim();
                if (值.Length == 0) continue;
                foreach (string 段 in 值.Split('|')) 结果.Add(段.Trim());
            }
            return 结果;
        }

