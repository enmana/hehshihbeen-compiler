        // ── R3-6-4 批 4 收尾:原生 C 那条腿**下后台**(用户 2026-09-23 报"一切回 C 就卡死") ──
        // 病根:`cl /O2` 编大工程是**分钟级**的(实测这份仓库里 `示例10_浮点与64位` 转出 3.1 MB C 源码,
        // `cl /O2` 编它 22 分钟还没完),而这条腿以前是**在界面线程上同步跑完**才回来 —— 那几分钟里窗口不重绘、
        // 按钮不响应,看着就是"卡死";工具栏那个下拉又**一换档就重做一次打包**,
        // 所以"根本没点编译、只是切回 C"也一样冻住。现在三件事:
        //   ① **下后台** —— 界面照常能用,编好了把结果贴回编译页;
        //   ② **同一份程序 + 同一档不重做** —— 切走再切回来立刻说"已是最新",不再白等一遍;
        //   ③ **一次只跑一条** —— 跑着的时候又来了新请求就记下**最新**那条,当前这条完了接着做
        //      (不排队、也不让两条并发去写同一个产物)。

        /// <summary>
        /// 原生 C 那条腿正在后台编的那一条(输出路径 + 当时的内存大小 + 编的是哪一份编译结果)。
        ///
        /// **H38-2**:第三格从"编译结果对象"换成**寄存号** —— 界面攥不住引擎对象,就把那一份寄存到
        /// 引擎侧、攥一个号(`编译服务C.寄存结果`)。这一格非这么设计不可:静默编译每 400ms 就换一份
        /// "最近结果",后台那一段必须攥住"当时那一份",不能只认"最近那份"。
        /// </summary>
        private (string 输出, int 内存大小, int 结果号)? _原生C在做;
        /// <summary>后台忙的时候又来的请求:只记**最新**那条(中间那几条没必要各编一遍)</summary>
        private (string 输出, int 内存大小, int 结果号)? _原生C待做;
        /// <summary>最近一次真编完的那一条(切档不重做:产物还在就直说"已是最新")</summary>
        private (string 输出, int 内存大小, int 结果号)? _原生C已做;
        private Task? _原生C任务;
        private readonly object _原生C锁 = new();

        /// <summary>两条请求是不是同一份(同一个输出路径 + **同一个寄存号** = 同一份编译结果)</summary>
        private static bool 同一条((string 输出, int 内存大小, int 结果号)? 已, string 输出, int 结果号)
            => 已 is { } 条 && 条.输出 == 输出 && 条.结果号 == 结果号;

        /// <summary>
        /// 原生 C 那条腿的入口:**排给后台**(不占界面线程),当场回一句"正在编 / 已是最新 / 排在后面"。
        /// 真正的结果(成功那句、或失败那条带改法的说明)由后台线程贴回编译页。
        /// </summary>
        private string 原生C排后台(string 输出, int 内存大小)
        {
            // H38-2:界面攥不住编译结果对象,就先把它寄存到引擎侧拿一个号(同一份结果给同一个号)
            int 结果号 = 前端契约C.服务.编译.寄存结果(前端契约C.服务.编译.最近结果!);
            int 机器码字节数 = 当前机器码.Length;
            string 大工程提示 = 估算C源码字节(机器码字节数) >= 1024 * 1024
                ? $"\n  这份工程转出来约 {估算C源码字节(机器码字节数) / (1024 * 1024)} MB C 源码," +
                  "C 编译器要几分钟 —— 这一档本来就是分钟级的活,不用等着看(编好了会在这里说结果)。"
                : "";
            lock (_原生C锁)
            {
                if (同一条(_原生C已做, 输出, 结果号) && File.Exists(输出))
                    return $"原生程序:{输出}(**已是最新** —— 这一档这一份刚编过,不重做)";
                if (同一条(_原生C在做, 输出, 结果号) || 同一条(_原生C待做, 输出, 结果号))
                    return "原生程序:正在后台编这一份(**界面照常能用**,编好了在这里说结果)。" + 大工程提示;

                var 这一条 = (输出, 内存大小, 结果号);
                if (_原生C任务 is { IsCompleted: false })
                {
                    _原生C待做 = 这一条;
                    return "原生程序:后台正编着上一份,这一份排在它后面(编好会在这里说结果)。" + 大工程提示;
                }
                _原生C在做 = 这一条;
                _原生C任务 = Task.Run(后台编原生C);
            }
            return "原生程序:正在后台用 C 编译器编(**界面照常能用**,编好了在这里说结果)。" + 大工程提示;
        }

        /// <summary>
        /// 这份编译结果转成 C 源码**大概**多大(字节)。C 后端一条指令大约摊成 140 字节 C 源码
        /// (实测:`示例10_浮点与64位` 21671 条指令 → 3.1 MB)。只用来**提前说一句"这活得几分钟"**,
        /// 判据不靠它(真判据是 `C工具链C.编译预算秒` 与那次真编)。
        /// </summary>
        private static long 估算C源码字节(int 机器码字节数) => (long)机器码字节数 / 4 * 140;

        /// <summary>后台那一条:编完把结果贴回编译页;再看有没有"待做"的那条,有就接着编(没有就收工)</summary>
        private void 后台编原生C()
        {
            while (true)
            {
                (string 输出, int 内存大小, int 结果号) 这;
                lock (_原生C锁) { 这 = _原生C在做!.Value; }

                (string 说明, bool 成) 果;
                try { 果 = 用C后端生成(这.输出, 这.结果号, 这.内存大小); }
                catch (Exception 异常) { 果 = ($"原生程序没生成出来:{异常.Message}(编译和执行都不受影响)", false); }

                Dispatcher.Invoke(() =>
                {
                    编译框.AppendText($"\n{果.说明}\n");
                    // 只有真编出产物才记"已做":失败那次要是也记,切回来会说"已是最新" —— 那是假话
                    lock (_原生C锁) { if (果.成) _原生C已做 = 这; }
                });

                lock (_原生C锁)
                {
                    var 下 = _原生C待做;
                    _原生C待做 = null;
                    if (下 is { } 条 && !同一条(这, 条.输出, 条.结果号))
                    {
                        _原生C在做 = 条;
                        continue;
                    }
                    _原生C在做 = null;
                    _原生C任务 = null;
                    return;
                }
            }
        }

        /// <summary>
