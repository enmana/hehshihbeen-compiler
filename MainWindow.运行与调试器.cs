        private async void 执行按钮_Click(object sender, RoutedEventArgs e)
        {
            // ⚠ **程序还在跑的时候按「执行」= 重新执行**(用户 2026-10-12 当班拍板;第423批)。
            //   以前这条路一直走到 `跑一遍` 里那句"程序正在跑 —— 先按「停止」"就回来了 ——
            //   而示例55 那种"窗口转到用户自己关"的程序**本来就不会自己停** ⇒ 再按一次 F5
            //   屏幕上一点动静都没有(用户实测报的就是这个:"第二次 F5 不显示(前端那个窗口没被收掉)")。
            //   现在:先按「停止」那一套把它叫停、**等它真的收工**(收工那一步会把图形窗口收掉),
            //   再照下面这条老路从头跑一遍。
            bool 刚停过 = _正在跑;
            if (刚停过) await 先停下正在跑的那一趟();
            if (!确保编译过())
            {
                编译框.AppendText("\n请先编译(运行→编译)。\n");
                切到底部编译();                   // 这句话在"编译"页,别让人对着"输出"页发愣
                刷新命令可用性();
                return;
            }
            切到底部输出();                       // 程序输出、断言、寄存器都写在"输出"页
            同步宿主白名单();                    // D1/D5:起进程与连网址的白名单按**当前工程**重设(换工程不漏上一个)
            // H91(G4 批 23)那道弹窗闸 + **H92-1 起改由「运行 → 允许弹窗」这一格说了算**(默认不勾)。
            // 以前这里**无条件设真**(当时的想法是"桌面 IDE 是有人在看的那条腿"),后果有两条:
            //   ① `Sample\中间层\示例59_剪贴板与弹窗` 一跑就真弹模态框,而它的 `// 预期输出:` 是按"不弹"写的
            //      ⇒ **输出断言在 IDE 腿永远红**(H92-1);
            //   ② 弹窗会把人挡在"程序跑完"之前。
            // 现在默认走"这个宿主不弹窗"(状态 25)那一支 —— 与命令行 / 自检 / 独立 exe 同一个口径;
            // 想看真弹窗的人在菜单里勾一次(勾选存 `选项.json`)。
            // ⚠ 别在这儿关回去:它要活到**这个后台线程把程序跑完**(下一次执行会重设)。
            宿主弹窗C.设允许弹窗(允许弹窗菜单.IsChecked == true);
            提示一次构建配置();                     // Debug 构建的 IDE 跑程序慢约 10 倍:头一回执行时说一句(只说一次)
            // **先算"是不是接着上一次跑"**(C17,用户实测报的 bug):有断点时"执行"是**分两段**跑的 ——
            // 先跑到断点、再接着跑到停机。第二段要是把输出页与"本次程序输出"缓冲清掉,
            // 输出断言就只比得到**最后一段**(用户实测:实际输出少了断点之前那 7 段,
            // 而界面上的输出页也只剩后半截,看着像程序跑错了)。接着跑 = 同一个会话,输出连着攒。
            bool 接着跑 = !刚停过                       // 刚停过 = 用户按的是"重新执行" ⇒ 必须从头跑,不接上一次
                && 前端契约C.服务.调试.断点个数 > 0
