        /// <summary>
        /// D1/D5:把**当前工程**声明的可执行文件白名单与网址白名单交给宿主能力层
        /// (空 = 这个程序不许起子进程 / 不许连任何网址)。
        /// 每次"执行/单步"之前调一次 —— 换工程、改工程文件都能立刻生效,也不会把上一个工程的声明漏过来。
        ///
        /// **第419批(用户实测报的:示例54 在 IDE 里"网络那一族整段给 0",而命令行
        /// `hbcc -p … --run --跨进程` 全给 1)**:同一条跨进程腿、同一个子进程、同一份 `.hbp`
        /// (`"网址": ["127.0.0.1:45517"]` 明明白白写在里面)—— 差别只剩"这一侧交给子进程的那张表是不是空的"。
        /// 所以这里补两件:
        ///   ① ⭐ **兜底**:`当前工程` 上那份解析结果为空时,**照它自己的目录现读一次 `.hbp`**
        ///      (与命令行那条腿 `Program.取工程网址白名单` **同一条口径**:整棵工程树并起来、
        ///      复用同一个 `网址白名单C.由文本` 解析器)—— 顺带把 `可执行文件` 表也读一遍;
        ///   ② **诊断一行**:把"这次到底设了几条"打在输出页上 —— 空表 ⇒ 整族状态 1(没挂能力),
        ///      一眼就能与"不在白名单(状态 20)"分开(以前两者都折成一个 `0`,查不出来)。
        /// </summary>
        private void 同步宿主白名单()
        {
            try
            {
                var 可执行表 = 当前工程?.可执行白名单;
                网址白名单C 网址表 = 当前工程?.网址白名单 ?? 网址白名单C.空;
                string 来路 = "工程对象";

                // ① 兜底:工程对象上那张表是空的(没解析出来 / 对象不是解析过的那一份)⇒ 现从 `.hbp` 读
                if ((可执行表 is not { Count: > 0 }) || 网址表.项表.Count == 0)
                {
                    string? 目录 = 当前工程?.目录;
                    string? 工程路径 = string.IsNullOrEmpty(目录) ? null : 工程文件C.找工程文件(目录!);
                    if (工程路径 != null)
                    {
                        try
                        {
                            var 网址行 = new System.Collections.Generic.List<string>();
                            var 可执行表2 = new System.Collections.Generic.Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                            foreach (var 一份 in 工程文件C.读取工程树(工程路径))
                            {
                                网址行.AddRange(一份.网址);
                                string 基 = System.IO.Path.GetDirectoryName(一份.工程路径) ?? 目录!;
                                foreach (var (名字, 路径) in 一份.可执行文件)
                                    if (名字.Trim().Length > 0 && 路径.Trim().Length > 0)
                                        可执行表2[名字.Trim()] = System.IO.Path.GetFullPath(System.IO.Path.Combine(基, 路径.Trim()));
                            }
                            if (网址行.Count > 0) 网址表 = 网址白名单C.由文本(网址行);
                            if (可执行表2.Count > 0) 可执行表 = 可执行表2;
                            来路 = "现读 .hbp";
                        }
                        catch { /* 读不动就当没声明:与"没给工程"同一条口径,下面照样打诊断 */ }
                    }
                }

                前端契约C.服务.宿主.设可执行白名单(可执行表 is { Count: > 0 } ? 可执行表 : null);
                前端契约C.服务.宿主.设网址白名单(网址表.项表.Count > 0 ? 网址表 : null);

                // ② 诊断一行(用户 2026-10-11 当班:整族给 0 时"看不出是哪一档")
                输出框.AppendText($"[白名单] 工程={当前工程?.名称 ?? "(没有当前工程)"}({来路}):" +
                    $"网址 {网址表.项表.Count} 条 / 可执行 {可执行表?.Count ?? 0} 条" +
                    $"{(网址表.项表.Count == 0 ? " —— 空表 ⇒ 网络那一族会整段给状态 1(没挂能力)" : "")}\n");
            }
            catch
            {
                前端契约C.服务.宿主.设可执行白名单(null);
                前端契约C.服务.宿主.设网址白名单(null);
            }
        }

        /// <summary>
        /// **R1-6 批 1 尾巴 ③ 接线**(用户 2026-09-23 口径:"就像 VS 的 F5 —— 按了 F5 就能看见窗口,
        /// 还能单步调试"):这一份机器码**用到图形能力**就把 `IDE 自己的图形窗口` 挂上当呈现口;
        /// 没用到(或者换了别的程序)就把上一轮那个摘掉。
        ///
        /// 三条口径:
        /// ① **窗口画在这个进程里**(H39-2 之后程序跑在子进程里,但"画在哪儿"仍然是这里 ——
        ///    这就是拍板口径 a:断点 / 单步插得进;子进程把绘制命令打成帧过来,这一侧**回放**);
        /// ② **没挂呈现口 = 没这个能力**(引擎那条老口径一个字没改):不用图形的程序连窗口对象都不建,
        ///    老行为一字不变;独立 exe / 手机端照旧给 `假`(程序自己决定怎么办);
        /// ③ **只在界面线程上调**(`装载` 与收尾都在界面线程上),呈现口自己拿 `Dispatcher` 回界面线程画;
        ///    跨进程那条腿的命令是**泵线程**回放的,同一个呈现口两边共用一个实例(它内部自己派发)。
        ///
        /// H39-2 加的第四件:**事件出口** —— 窗口那一侧的键盘 / 鼠标 / 关窗请求要送回
        /// **当前正在跑的那台**(子进程里那台);出口指向"跑着的那台",没在跑就不投。
        /// </summary>
        private void 同步图形呈现()
        {
            if (!前端契约C.服务.图形.这段机器码用图形(当前机器码)) { 收掉图形窗口(); return; }
            if (前端契约C.服务.图形.呈现口 is not 界面控件.图形窗口呈现C 口)
            {
                口 = new 界面控件.图形窗口呈现C(Dispatcher);
                前端契约C.服务.图形.挂上(口);
            }
            前端契约C.服务.图形.清空();          // 新的一轮:窗口状态与两个队列从头来(呈现口自己留着,窗口由程序重新开)
            // 两台机器(执行 / 调试)各持同一个呈现口:谁在跑,子进程的绘制命令就回放到这个窗口
            前端契约C.服务.调试.机器.图形呈现口 = 口;
            前端契约C.服务.调试.会话机器.图形呈现口 = 口;
            前端契约C.服务.图形.事件出口 = (类型, 键码, x, y) =>
            {
                if (_正在跑) 前端契约C.服务.调试.取机器(_跑着的是会话机).送图形事件(类型, 键码, x, y);
            };
        }

        /// <summary>
        /// 收图形窗口:摘掉呈现口 + 关掉那个窗口。
        /// 叫它的地方 = "这一趟算完了":跑到停机(`程序结束清调试`)、被「停止」打断(`停止后收尾`)、
        /// 换成不用图形的程序(`同步图形呈现`)。**停在断点上不叫它** —— 那时候程序还活着,
        /// 窗口留着才看得见画面(接着跑 F5 就接着用这个窗口)。
        /// </summary>
        private void 收掉图形窗口()
        {
            if (前端契约C.服务.图形.呈现口 is 界面控件.图形窗口呈现C 口)
            {
                前端契约C.服务.图形.摘掉();        // 摘掉顺带清队列(与"宿主跑完一个程序"同一档)
                // H39-2:两台机器手里那个引用也一起摘掉 —— 留着的话程序下一次"刷新"还会往一个已经关掉的窗口画
                if (ReferenceEquals(前端契约C.服务.调试.机器.图形呈现口, 口)) 前端契约C.服务.调试.机器.图形呈现口 = null;
                if (ReferenceEquals(前端契约C.服务.调试.会话机器.图形呈现口, 口)) 前端契约C.服务.调试.会话机器.图形呈现口 = null;
                前端契约C.服务.图形.事件出口 = null;
                try { 口.关闭窗口(); } catch { }
            }
        }

        /// <summary>
        /// H13:**热重载(F6)** —— 编译成功且程序**已经停下**时,把新机器码换进正在跑的那台虚拟机,
        /// 上一轮还在的顶层变量接着用(判据在引擎那一段 `重载` 里;保不住什么如实写在输出页)。
        ///
