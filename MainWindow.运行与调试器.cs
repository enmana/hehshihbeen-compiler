        /// 以前只看"路径在不在",盘上那份 0.18 MB 的框架依赖 exe 被当自包含贴出去,文案还写"双击即跑",
        /// 拷到没装 .NET 的机器上就跑不起来。现在不是真自包含就**后台重新发布**,并如实说清。
