                刷新命令可用性();                       // 「停止」这会儿还是亮的,收工那一步它会灭
                前端契约C.服务.调试.请求中断(_跑着的是会话机);
            }
            catch (Exception 异常)
            {
                // 这几步都不该出事;真出事也**不许带走界面**(这条调用链挂在 `async void` 上,冒出去就是崩):
                // 记一笔,照旧往下等那一趟收工 —— 等不到就由 `跑一遍` 那句挡板兜住。
                记异常框($"重新执行:停上一趟时出错: {异常}");
            }
            var 这一趟 = _跑着的那一趟;
            if (这一趟 == null) return;             // 记账没跟上(理论上到不了):当"已经请它停"处理
            try { await 这一趟; }
            catch (Exception) { /* 那一趟自己把死因写进输出页(报跑程序故障);这里只等它收工 */ }
        }

        /// <summary> 输出节流器:程序在后台线程上吐字节,攒起来由**界面线程**每 80ms 刷一次(不是每吐一个字节就动一次界面)</summary>
        private DispatcherTimer? _输出节流;

        private readonly object _输出锁 = new();
        private readonly StringBuilder _待刷输出 = new();

        /// <summary>
        /// H22:把一段**会跑很久**的活儿挪到后台线程 —— 界面不冻,「停止」按钮亮着,程序输出每 80ms 刷一次。
        /// **长活里不许碰任何界面对象**(WPF 会抛跨线程异常):要碰界面就等 `await` 回来再碰。
        /// 敢这么挪的依据:`hbcc --selftest` 早就把同一个虚拟机跑在非界面线程上 —— 虚拟机本身不碰 WPF。
        ///
        /// H38-2:参数从"那一台机器对象"改成"**哪一台**"(`会话机`) —— 界面不再攥着引擎对象,
        /// 「停止」那一刻按同一个标记去问契约要机器。线程模型一个字没动(拍板 b:契约同步,长活照旧 `Task.Run`)。
        /// </summary>
        private async Task 在后台跑(bool 会话机, Action 长活)
        {
            _正在跑 = true;
            _跑着的是会话机 = 会话机;
            刷新命令可用性();
            开始输出节流();
            try { await Task.Run(长活); }
            finally
            {
                在界面上(() =>
                {
                    结束输出节流();       // 停表 + 把剩下的输出同步刷干净(输出断言读的就是这一刻的账)
                    _正在跑 = false;
                    刷新命令可用性();
                });
            }
        }

        /// <summary>
        /// 回到界面线程跑一段(H22):**不靠"环境同步上下文"**,直接问 Dispatcher ——
        /// `await Task.Run(...)` 之后到底回到哪个线程,取决于当时有没有装同步上下文(正常 IDE 里有,
        /// 离屏探针里没有 —— h22 探针就是这么把这个坑挖出来的:界面调用跑到线程池上抛跨线程异常,
        /// 异常又被 async void 吞成"什么都没发生")。已经在界面线程上就直接跑,不多一次派发。
        /// </summary>
        private void 在界面上(Action 活)
        {
            if (Dispatcher.CheckAccess()) 活();
            else Dispatcher.Invoke(活, DispatcherPriority.Normal);
        }

        private void 开始输出节流()
        {
            if (_输出节流 == null)
            {
                _输出节流 = new DispatcherTimer(DispatcherPriority.Background, Dispatcher) { Interval = TimeSpan.FromMilliseconds(80) };
                _输出节流.Tick += 输出节流_Tick;
            }
            _输出节流.Start();
        }

        /// <summary> 节流器每一拍:把后台攒下的程序输出刷到界面上(H23:关窗之后不碰界面)</summary>
        private void 输出节流_Tick(object? sender, EventArgs e)
        {
            if (_已关窗) return;
            刷程序输出();
        }

        private void 结束输出节流()
        {
            _输出节流?.Stop();
            刷程序输出();
        }

        /// <summary> 程序吐一段文字:先进缓冲,由界面线程统一刷(**后台线程上绝不动 输出框**) </summary>
        private void 收程序输出(string 文本)
        {
