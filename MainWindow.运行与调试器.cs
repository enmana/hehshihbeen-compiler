        /// <summary> 宿主没发布过:后台跑一次 dotnet publish(不挡着界面,好了下次编译就有 exe 了)</summary>
        private void 开始后台发布宿主()
        {
            if (_宿主发布中) return;
            _宿主发布中 = true;
            Task.Run(() =>
            {
                // T28(2026-09-27 评测整改):这一段以前**裸着** —— `发布宿主` 一抛异常,`Task.Run` 的
                // 任务就以 Faulted 收场(没人 await ⇒ 只能靠 `TaskScheduler.UnobservedTaskException`
                // 那条兜底,而且 `_宿主发布中` **永久 true**:之后整个会话再也自动发布不了宿主,
                // 界面一个字都不说)。现在补 try/catch/finally,照这个文件别处(`:196` / `:756`)的写法:
                // 失败要有可见回执(异常页 + 编译页各一行),旗子无论如何复位,下次还能再试。
                bool 好 = false;
                string 日志 = "";
                try
                {
                    好 = 发布宿主(out 日志);
                }
                catch (Exception 异常)
                {
                    日志 = 异常.Message;
                    异常收集C.记($"后台发布宿主时出错: {异常}");
                }
                finally
                {
                    Dispatcher.Invoke(() =>
                    {
                        _宿主发布中 = false;      // **无论如何复位**:不复位 = 这个会话再也发不出宿主
                        编译框.AppendText(好
                            ? "\n宿主发布好了:下次编译就会在项目目录里生成 exe。\n"
                            : $"\n宿主发布失败(不影响编译/执行):{日志.Split('\n').LastOrDefault(x => x.Trim().Length > 0)}\n");
                    });
                }
            });
        }

