            string 暂存 = Path.Combine(临时区C.基目录(), "hb_ide_C后端", Environment.ProcessId.ToString());
            Directory.CreateDirectory(暂存);
            string c源 = Path.Combine(暂存, Path.GetFileNameWithoutExtension(输出) + ".c");
            File.WriteAllText(c源, 转译.源码, new UTF8Encoding(false));

