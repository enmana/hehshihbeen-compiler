                清掉树里关掉的文件高亮();      // 关掉标签页 → 树里对应那行也不该再亮着
                刷新命令可用性();
            };
            foreach (var 页 in 模型.选卡页视图模型表)
                页.PropertyChanged += (_, _) => 刷新命令可用性();
            刷新命令可用性();
        }

