        /// <summary>
        /// 命令可用性的**唯一出口**。规则:
        ///   没有项目      → 新建文件 / 编译 / 执行 / 生成 / 调试 / 项目操作 全禁用
        ///   没打开编辑器  → 编辑类(撤销/重做/复制/粘贴/删除/全选/对齐/保存) 全禁用
        ///   编辑器是空的  → 没东西可编辑,也不值得编译:编辑类只留"粘贴",编译类禁用
        ///   执行          → 还要"已经编译过"(当前机器码非空)
        /// </summary>
        private void 刷新命令可用性()
        {
            bool 有项目可编译 = 有项目;
            bool 有页 = 当前选卡 != null;
            bool 有内容 = (当前选卡?.内容 ?? "").Length > 0;
            bool 有改动 = 当前选卡?.有未保存更改 ?? false;
            bool 能编辑 = 有页 && 有内容;
            bool 有选中 = 有页 && (当前编辑器?.选中长度 ?? 0) > 0;
            bool 能执行 = 有项目可编译;          // 不需要先编译:执行会自己先编译一遍(用户要求:直接能跑)

            // ---- 需要项目 ----
            新建文件菜单.IsEnabled = 有项目可编译;
            添加项目菜单.IsEnabled = 有项目可编译;
            生成工程文件菜单.IsEnabled = 有项目可编译;
            汇编菜单.IsEnabled = 有项目可编译;
            单步调试菜单.IsEnabled = 有项目可编译;
            新建文件按钮.IsEnabled = 有项目可编译;
            菜单设为启动项目.IsEnabled = 有项目可编译;
            菜单项目编译.IsEnabled = 有项目可编译;
            执行菜单.IsEnabled = 能执行;
            执行按钮.IsEnabled = 能执行;
            // C23:展开到汇编只对**源码页**有意义(汇编源码页自己就是展开结果,点了只会说一句)
            展开到汇编按钮.IsEnabled = 有页 && 当前选卡?.是汇编源码页 != true;
            // 调试菜单那几条(逐步 / 继续 / 复位):和"执行"一样,有项目就能点(没编译过会自动先编译)
            调试逐步菜单.IsEnabled = 有项目可编译;
            调试继续菜单.IsEnabled = 有项目可编译;
            调试复位菜单.IsEnabled = 有项目可编译;
            // H22「停止」:只有**真的在跑**的时候才亮(跑的时候整趟在后台线程上,这两个是唯一能按下去的)
            调试停止菜单.IsEnabled = _正在跑;
            停止按钮.IsEnabled = _正在跑;

            // ---- 编辑类:按"是否有编辑器/是否有内容/是否有选中/是否有历史"逐个判 ----
            撤销菜单.IsEnabled = 有页 && (当前编辑器?.CanUndo() ?? false);
            重做菜单.IsEnabled = 有页 && (当前编辑器?.CanRedo() ?? false);
            复制菜单.IsEnabled = 有选中;
            删除菜单.IsEnabled = 有选中;
            全选菜单.IsEnabled = 能编辑;
            语义对齐菜单.IsEnabled = 能编辑;
            重命名菜单.IsEnabled = 能编辑;
            反汇编菜单.IsEnabled = 能编辑;
            切换断点菜单.IsEnabled = 能编辑;
            清除断点菜单.IsEnabled = 有项目可编译 && 前端契约C.服务.调试.断点个数 > 0;
            粘贴菜单.IsEnabled = 有页;                     // 空文件也能粘贴
            // C22:『参与编译』这一档只对**汇编源码页**(`.hba`)有意义;勾的状态一律按工程文件里的事实重画
            // (点一下 WPF 会先把勾翻过去,这里随后用真数据盖回来 —— 写失败时勾会自己弹回去)
            bool 是汇编页 = 当前选卡?.是汇编源码页 == true;
            var 汇编页项目 = 是汇编页 ? (解决方案.找所属项目(当前选卡!.全称 ?? "") ?? 解决方案.启动项目) : null;
            参与编译菜单.IsEnabled = 是汇编页 && 有项目可编译 && 汇编页项目?.有工程文件 == true;
            参与编译菜单.IsChecked = 是汇编页 && 汇编页项目?.参与编译(当前选卡!.全称) == true;
            撤销按钮.IsEnabled = 撤销菜单.IsEnabled;
            重做按钮.IsEnabled = 重做菜单.IsEnabled;
            保存按钮.IsEnabled = 有页 && (有改动 || 页无路径());
            关闭标签菜单.IsEnabled = 有页;

            执行按钮.ToolTip = 能执行
                ? (前端契约C.服务.调试.断点个数 > 0 ? "编译并执行;有断点就停在断点上" : "编译并执行")
                : "没有项目:先 文件→新建项目 或 文件→打开项目";
        }

        private bool 页无路径() => string.IsNullOrWhiteSpace(当前选卡?.全称);

