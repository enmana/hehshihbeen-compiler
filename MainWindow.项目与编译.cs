        /// <list type="number">
        /// <item>**只展开当前文件自己**(不是整个工程):内容取"工程级展开表里属于这一页的那一段" ——
        ///       口径与真编译**同一份数据**(优化开关、`堆`、`程序集` 归属都对得上),不是另算一次的展开;</item>
        /// <item>落点统一成 `汇编源码C.落点路径按文件` ⇒ `<项目目录>\<文件名>_ASM.hba`
        ///       (C20 自动开的那页也走同一条路,全仓只有一个落名规则);</item>
        /// <item>旧的"整篇只读汇编视图"跟着退场:单步不再展开编辑器(`逐步` 见调试会话那套),
        ///       按钮也不再切视图 —— 展开的汇编一律在**真页**上给,能改能存。</item>
        /// </list>
        /// 与 C22 的关系:落点是 `.hba` ⇒ 天生"默认不参与编译",想拿它优化热路径仍走「运行 → 汇编源码参与编译」。
        /// </summary>
        private void 展开到汇编_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                if (当前选卡 is not { } 页 || string.IsNullOrWhiteSpace(页.全称)) { 提示需要项目(); return; }
                if (页.是汇编源码页)
                {
                    说一句("这一页已经是汇编源码(`.hba`)了。「展开到汇编」是给源码页用的。");
                    return;
                }
                if (解决方案.启动项目 is not { } 项目) { 提示需要项目(); return; }
                if (!确保编译过()) return;

                // 与旧按钮同一条口径:走**工程级**展开(一个展开器连吃多文件),再挑出属于这一页的那一段
                var 源码表 = 取当前源码(项目);
                var 全表 = 前端契约C.服务.宿主.建全工程表(源码表, 优化开, 项目.堆字节数, 工程归属表(项目, 源码表), 项目.池字节数, 项目.内存字节数, 项目.软栈字节数, 项目.边界检查, 项目.帧字节数);
                var 段 = 全表.FirstOrDefault(x => string.Equals(x.文件, 页.全称, StringComparison.OrdinalIgnoreCase));
                if (段 == null || 段.展开文本.Length == 0)
                {
                    说一句($"【{页.标题}】不在启动项目【{项目.名称}】这次的编译输入里" +
                        "(没被 `.hbp` 的 `文件` 表收进来,也不是 `包含` 进来的文件),没有它的展开汇编。");
                    return;
                }
                string 目标 = 汇编源码C.落点路径按文件(项目.目录, 页.全称);
                string 新文本 = 汇编源码C.页头(Path.GetFileName(页.全称), "展开到汇编") + "\n" + 段.展开文本;
                打开汇编源码页(目标, 新文本);
            }
            catch (Exception 异常)
            {
                记异常框($"展开到汇编失败: {异常}");
            }
        }

