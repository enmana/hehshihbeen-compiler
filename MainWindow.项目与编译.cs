        /// 落点全在工程文件:加 = 往 `.hbp` 的 `汇编` 表加一条(表还不存在就现开一个),
        /// 去 = 把那一项拿掉 —— **只动 `.hbp` 里那一处文本**(与 C6"新建文件进工程"同一套:
        /// 用户写在工程文件里的注释、缩进都原样留着);文本改不动(手工写坏了)才退回"读成对象再保存"。
        ///
        /// 编译顺序不在这里管:定死在引擎侧(`工程文件C.读全部编译输入` / `项目项C.刷新文件`)——
        /// **`.hb` 全在前、汇编段按声明序接在后**,所以入口永远是启动文件的第一条指令。
        /// 这一档只对**已经存在磁盘上**的 `.hba` 生效:没存盘就勾,编译会找不到文件 —— 先提示存盘,不硬勾。
        /// </summary>
        private void 汇编源码参与编译_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                if (当前选卡 is not { 是汇编源码页: true } 页 || string.IsNullOrWhiteSpace(页.全称)) { 刷新命令可用性(); return; }
                var 项目 = 解决方案.找所属项目(页.全称) ?? 解决方案.启动项目;
                if (项目 == null || !项目.有工程文件 || 项目.工程路径 is not { Length: > 0 } 工程路径)
                {
                    MessageBox.Show("这一档要写进工程文件(`.hbp`),可当前项目没有工程文件。\n" +
                        "先在「项目」菜单里生成一份工程文件,再回来勾。", "参与编译",
                        MessageBoxButton.OK, MessageBoxImage.Information);
                    刷新命令可用性();
                    return;
                }
                bool 要参与 = !项目.参与编译(页.全称);
                if (要参与 && !File.Exists(页.全称))
                {
                    MessageBox.Show($"这一份汇编源码还没有存到磁盘上({Path.GetFileName(页.全称)})。\n" +
                        "先按 Ctrl+S 存盘,再勾「参与编译」—— 编译读的是磁盘上的文件。", "参与编译",
                        MessageBoxButton.OK, MessageBoxImage.Warning);
                    刷新命令可用性();
                    return;
                }

                string 相对 = Path.GetRelativePath(项目.目录, 页.全称).Replace('\\', '/');
                string 工程文本 = File.ReadAllText(工程路径);
                string 说明;
                if (要参与)
                {
                    string? 新文本 = 工程维护C.工程文本加项(工程文本, 工程维护C.汇编字段, 相对, out 说明);
                    if (新文本 == null) { 对象加汇编项(工程路径, 相对); 说明 = $"在 `汇编` 表里加了 `{相对}`"; }
                    else if (!string.Equals(新文本, 工程文本, StringComparison.Ordinal)) 工程维护C.写回(工程路径, 新文本);
                }
                else
                {
                    string? 新文本 = 工程维护C.工程文本去项(工程文本, 工程维护C.汇编字段, 相对, out 说明);
                    if (新文本 == null) { 对象去汇编项(工程路径, 相对); 说明 = $"从 `汇编` 表里拿掉了 `{相对}`"; }
                    else if (!string.Equals(新文本, 工程文本, StringComparison.Ordinal)) 工程维护C.写回(工程路径, 新文本);
                }
                项目.刷新文件();
                说一句($"【{项目.名称}】{说明}。" +
                    (要参与 ? "下次编译它就跟着一起编(接在源码展开结果之后,标签与源码全局共用)。"
                            : "下次编译它又不参与了(编译产物与没有它时逐字节一致)。"));
            }
            catch (Exception 异常)
            {
                记异常框($"切换『参与编译』失败: {异常}");
                MessageBox.Show($"改工程文件没成功:{异常.Message}", "参与编译", MessageBoxButton.OK, MessageBoxImage.Warning);
            }
            刷新命令可用性();          // 不管成没成,勾的状态一律按**工程文件里的事实**重画
        }

        /// <summary> 文本改不动时的退路:读成对象 → 改 `汇编` 表 → 保存(会洗掉 `.hbp` 里的注释,所以只当兜底) </summary>
        private static void 对象加汇编项(string 工程路径, string 相对)
        {
            var 工程 = 工程文件C.加载(工程路径);
            if (!工程.汇编.Any(x => string.Equals(x.Replace('\\', '/'), 相对, StringComparison.OrdinalIgnoreCase)))
                工程.汇编.Add(相对);
            工程.保存(工程路径);
        }

        /// <summary> 同上,拿掉一项 </summary>
        private static void 对象去汇编项(string 工程路径, string 相对)
        {
            var 工程 = 工程文件C.加载(工程路径);
            工程.汇编.RemoveAll(x => string.Equals(x.Replace('\\', '/'), 相对, StringComparison.OrdinalIgnoreCase));
            工程.保存(工程路径);
        }

        #endregion

        #region C20:汇编源码页(编译出来的汇编在编辑器新页打开 / 同一个项目复用)

        /// <summary>
        /// C20(用户 2026-09-19 提:"编译成汇编后在编辑器的新页打开,关闭或者退出时提示是否保存";
        /// 当天拍板 a 落点 = 项目目录里的 `.hba` · b 算**汇编源码**、默认不进编译 · c 打开时机 = **编译后自动开、同项目复用**)。
        ///
        /// **C23(第158批)改的只有落名**:用户说"展开后的文件名称应该是被展开文件的名称 + `_ASM.hba`,
        /// 而不是项目的名称" ⇒ 这里也从 `<项目名>.hba` 改成 `<启动文件名>_ASM.hba`
        /// (`汇编源码C.落点路径按文件`,落点规则全仓只有那一处)。
        ///
        /// 口径(每条都对着清单里的验收):
        /// <list type="bullet">
        /// <item>**算汇编源码**:落点是项目目录里的**真文件** ⇒ 保存、标脏、关页 / 退出提示全沿用页面模型现成那一套
        ///       (`选卡页视图模型.有未保存更改` + `提示保存未保存更改`),不为它另写保存逻辑;</item>
        /// <item>**默认不进编译**:后缀 `.hba` —— 工程文件与目录扫描都只认 `*.hb`(`解决方案C.刷新文件` /
        ///       `工程文件C.从目录生成`),所以"不进编译"不用另写判断;想拿它优化热路径要走清单 C22(手动设置);</item>
        /// <item>**新页 / 复用**:同一个落点上开过就复用那一页(按**全称**比,大小写不敏感);</item>
        /// <item>**有未保存改动先问一句**:选"否"就留着现在这一份(它的改动照旧可以 Ctrl+S 存盘);</item>
        /// <item>**"已保存"快照 = 磁盘上现在那一份**:盘上还没有就给 `null` ⇒ 这一页显示为**未保存**,
        ///       关页 / 退程序会问"是否保存"(用户要的正是这句);盘上已经有同样一份时不标脏。</item>
        /// </list>
        /// 失败不打断编译:这里只记一行『异常』—— 汇编页是"看的东西",不该把编译本身搞成半截。
        /// </summary>
        private void 打开汇编源码页(项目项C 项目)
        {
            try
            {
                var 段表 = 前端契约C.服务.编译.调试文件表();
                if (段表.Count == 0) return;
                string 被展开 = 项目.启动文件 ?? 段表[0].文件 ?? 项目.名称;
                string 目标 = 汇编源码C.落点路径按文件(项目.目录, 被展开);
                // C22:这一份要是**正在参与编译**,自动刷新会把手写的内容冲掉(下一轮编译就撞标签了)——
                // 干脆不刷,并说清怎么才看得到这一次的展开。
                if (项目.参与编译(目标))
                {
                    编译框.AppendText($"\n提示:{Path.GetFileName(目标)} 正在参与编译,已跳过自动刷新(免得把里面手写的例程冲掉)。" +
                        "想看这一次编出来的展开:先取消勾选『运行 → 汇编源码参与编译』,或把它另存成别的名字。\n");
                    return;
                }
                string 新文本 = 汇编源码C.页头(Path.GetFileName(被展开), "编译(启动项目)") + "\n" +
                    汇编源码C.拼全工程汇编(段表.Select(段 => 段.展开文本));
                打开汇编源码页(目标, 新文本);
            }
            catch (Exception 异常)
            {
                异常收集C.记($"打开汇编源码页失败: {异常.Message}");
            }
        }

        /// <summary>
        /// 打开 / 复用一份汇编源码页(C20 与 C23 共用**这一条路**:落点、复用、未保存提示、磁盘快照、选中页
        /// 只写一遍)。调用方只管算好"落点 + 这一次的展开原文"。
        /// </summary>
        private void 打开汇编源码页(string 目标, string 新文本)
        {
            if (string.IsNullOrWhiteSpace(目标)) return;
            var 表 = 主视图模型.选卡页视图模型表;
            int 索引 = 汇编源码C.找复用页([.. 表.Select(页 => 页.全称)], 目标);
            选卡页视图模型 页;
            if (索引 >= 0)
            {
                页 = 表[索引];
                if (页.有未保存更改 && MessageBox.Show(
                        $"汇编源码页“{页.显示标题}”有未保存的改动,要用这次新展开出来的汇编刷新它吗?\n\n" +
                        "选“否”就留着你现在这一份(它的改动仍然可以 Ctrl+S 存盘)。",
                        "汇编源码页", MessageBoxButton.YesNo, MessageBoxImage.Question) != MessageBoxResult.Yes)
                {
                    主视图模型.选中页 = 页;          // 用户要留着改动:切过去让他自己看
                    return;
                }
            }
            else
            {
                主视图模型.添加(Path.GetFileName(目标), 新文本, 目标, 页面种类C.汇编源码);
                页 = 主视图模型.选中页!;
            }

            // 快照对**磁盘上现在那一份**(读法与"打开文件"那条路一致:同一个清洗);盘上没有 ⇒ null = 未保存
            string? 盘上 = null;
            try { if (File.Exists(目标)) 盘上 = 取磁盘文本(File.ReadAllText(目标)); } catch { 盘上 = null; }
            页.标记已保存(盘上);
            页.内容 = 新文本;
            主视图模型.选中页 = 页;
            刷新命令可用性();
        }

