        /// <summary>
        /// 打开一个文件到标签页(新建文件/打开项目/打开文件/双击项目树 都走它)。
        ///
        /// 第193批(用户 2026-09-21 报):**同一个文件只开一份** —— 已经在编辑框里开着的那一份,
        /// 再从资源管理器双击一次,以前会**又读一遍盘、又开一页**(同一个文件两份,改哪一份都对不上)。
        /// 现在先查一遍:命中就**切过去**(不碰那一页里的文本,所以页上没保存的改动不会被磁盘那份盖掉)。
        /// 认法借 `汇编源码C.找复用页`(全称归一后比,大小写不敏感):**故意不比文件名** ——
        /// 多文件工程里两个目录各有一个 `主程序.hb`,那是两份,不能切错页。
        /// **H61-3 起**这一条只管"普通页"那一档;导图双击跳转走下面那个 `临时:` 重载(预览页,见它)。
        /// </summary>
        private void 打开文件到标签页(string 全称) => 打开文件到标签页(全称, 临时: false);

        /// <summary>
        /// H61-3:**预览(临时)打开**那一档(只有导图双击跳转走它,别的入口一律 `临时: false`)。
        /// 三条口径:
        ///   ① 没开过 ⇒ 按**临时页**开出来(页头斜体;同一时刻只留一个,下一次预览 `换临时页` 把它整页顶掉);
        ///   ② 已经开着的若**正是那个临时页** ⇒ 再点一次 = **固定成普通页**(就是 VS 里"再双击一下就留住"那一下);
        ///   ③ 已经开着的若是**普通页** ⇒ 与从前一样,只是切过去(不动它)。
        /// </summary>
        private void 打开文件到标签页(string 全称, bool 临时)
        {
            if (string.IsNullOrWhiteSpace(全称) || !File.Exists(全称)) return;
            var 常规 = 主视图模型.常规页.ToList();
            int 复用 = 汇编源码C.找复用页([.. 常规.Select(页 => 页.全称)], 全称);
            if (复用 >= 0)
            {
                var 已有 = 常规[复用];
                主视图模型.选中页 = 已有;      // 已经开着:切过去,不再读盘开新页
                if (临时 && 已有.是临时页) 已有.是临时页 = false;   // 预览页再点一次 = 固定
            }
            else 读入文件内容(全称, out _, 临时);
            刷新命令可用性();
            稍后刷新断点显示();       // 编辑器这时才生成,红点要等布局完再画(否则断点加载了却看不见)
        }

