        /// <summary> 打开工程文件:成功返回 true(启动页据此决定要不要关掉自己) </summary>
        private bool 打开项目文件(string 工程路径)
        {
            try
            {
                // P36:换工程之前先把**旧工程**那一屏记下来(不然换过去就找不回来了)。
                // 用当前键记(此刻启动项目还是旧的);没有旧工程时这一步什么也不做。
                记会话();
                var 项目表 = 解决方案.添加工程(工程路径);
                if (项目表.Count == 0) return false;
                只留这些项目(项目表);      // 打开项目后只留这个工程(带它自己的子工程),旧项目先存盘再关掉
                项目树.UpdateLayout();
                var 主项目 = 项目表[0];
                设为启动项目(主项目);
                记最近项目(主项目);
                应用树展开状态();
                显示项目信息(主项目, 项目表.Count > 1 ? $"打开项目(+{项目表.Count - 1} 个子工程)" : "打开项目");
                if (主项目.启动文件 is { } 启动 && File.Exists(启动)) 打开文件到标签页(启动);
                刷新命令可用性();
                // P36:这个工程上次离开时的那一屏(标签 + 光标 + 没保存的正文 + 窗口四格)——
                // 有会话就按会话开页(**不再**去开启动文件那一页:那等于每次都多开一页);
                // 没有会话(第一次打开)才退回上面那一句。
                try
                {
                    string 键 = 会话键();
                    var 会话 = 键.Length == 0 ? new 会话工程C() : 会话表C.当前.取(键);
                    if (会话.页表.Count > 0 && 恢复会话(会话) > 0)
                    {
                        // 恢复成功后,上面那句"打开启动文件"开出来的页多半是**重复的**(会话里本来就有它)——
                        // 直接摘掉那一页(它刚从磁盘读出来、一个字没改,不必走"未保存先问"那条路);
                        // 会话里没有的页(例如启动文件刚被改过、进不了会话)留着不动。
                        var 多余的 = 主视图模型.选卡页视图模型表
                            .Where(页 => !页.是特殊页 && !页.有未保存更改
                                && !会话.页表.Any(x => x.全称.Length > 0 && 前端契约C.服务.宿主.是同一个文件(x.全称, 页.全称)))
                            .ToList();
                        foreach (var 页 in 多余的) 主视图模型.选卡页视图模型表.Remove(页);
                        if (多余的.Count > 0) 刷新命令可用性();
                    }
                }
                catch (Exception 异常) { 异常收集C.记($"恢复会话失败: {异常.Message}"); }
                return true;
            }
            catch (Exception 异常)
            {
                输出框.Text = $"打开项目失败: {异常.Message}\n";
                切到底部输出();
                记异常框($"打开项目失败: {异常}");
                刷新命令可用性();
                return false;
            }
        }

