        /// <summary>
        /// 资源管理器右键「添加文件…」(第193批,用户 2026-09-21 要求):把磁盘上**已经有的**文件
        /// 加进当前工程(可多选)。与「添加项目」一个口径:**只登记,不复制、不移动** ——
        /// 工程目录里(含子目录)的按**相对路径**登记(工程整体能拷走),工程目录外的按**绝对路径**登记
        /// (引擎本来就认绝对路径:`工程文件C.绝对路径`);落在工程目录外的那几条会在输出页里点明。
        ///
        /// **进哪张表按后缀定**(`工程维护C.该进哪个表`):`.hb` → `文件`(跟着一起编译)、
        /// `.hba` → `汇编`(C22 那张表:接在源码展开结果之后一起汇编,**不是当源码编**)、
        /// 别的 → `资源`(执行时当虚拟机的输入流;编译时会跳过)—— 工程树本来就分这三种节点。
