        /// <summary>
        /// 只保留这一批项目(新建项目/打开项目走它)。换项目 = 换工作区,所以顺手把编辑区收拾干净:
        /// 不属于"保留项目"的标签页(旧项目的文件、还有单独打开的文件)一律关掉,
        /// 否则会出现"编译的是新工程、断言看的却是旧文件"这种错位。
        /// </summary>
        private void 只留这些项目(IReadOnlyCollection<项目项C> 保留)
        {
            保存树展开状态();
            foreach (var 项目 in 解决方案.项目表.Where(p => !保留.Contains(p)).ToList()) 解决方案.移除(项目);
