            项目树.UpdateLayout();
            应用树展开状态();
            按当前工程加载断点();          // 换了工程就换一套断点(断点跟着工程目录走)
            刷新命令可用性();
        }

        /// <summary>
        /// 换项目时收拾编辑区:不属于"保留项目"目录的标签页,有改动先存盘、然后关掉。
        /// 没路径的未命名页(自己敲的临时内容)不动 —— 那种关了会丢东西。磁盘上的文件一个不删。
        /// </summary>
        private void 关掉不在项目里的标签页(IReadOnlyCollection<项目项C> 保留)
        {
            foreach (var 页 in 主视图模型.常规页.ToList())
            {
                if (页.全称 is not { Length: > 0 } 全称) continue;              // 未命名页:留着
                if (保留.Any(p => 在目录里(全称, p.目录))) continue;             // 新项目里的页:留着
                if (页.有未保存更改) 保存标签页(页, 强制另存为: false);
                主视图模型.选卡页视图模型表.Remove(页);
            }
        }

        /// <summary>
        /// 关掉标签页后,把项目树里那个文件的高亮也取消 —— 不然树还亮着,看着像"这个文件还开着"。
        /// (文件还在磁盘上、也还在项目里,所以只是取消选中,不从树上删掉)
        /// </summary>
        private void 清掉树里关掉的文件高亮()
        {
            if (项目树.SelectedItem is not 文件项C 文件) return;
            bool 还开着 = 主视图模型.常规页.Any(页 =>
                string.Equals(页.全称, 文件.全称, StringComparison.OrdinalIgnoreCase));
            if (!还开着) 取消树选中();
        }

        /// <summary>
        /// 取消项目树当前的选中(SelectedItem 是只读的,要动的是节点的 IsSelected)。
        /// 文件项在项目节点底下,所以要顺着"项目 → 文件"两层容器找;实在找不到就把高亮收回项目那行。
        /// </summary>
        private void 取消树选中()
        {
            try
            {
                if (项目树.SelectedItem is not { } 选中) return;
                if (项目树.ItemContainerGenerator.ContainerFromItem(选中) is TreeViewItem 根节点)
                {
                    根节点.IsSelected = false;
                    return;
                }
                if (选中 is not 文件项C 文件) return;
                var 项目 = 解决方案.项目表.FirstOrDefault(p => p.文件.Contains(文件));
                if (项目 == null || 项目树.ItemContainerGenerator.ContainerFromItem(项目) is not TreeViewItem 项目节点) return;
                if (项目节点.ItemContainerGenerator.ContainerFromItem(文件) is TreeViewItem 文件节点) 文件节点.IsSelected = false;
                else 项目节点.IsSelected = true;      // 树没展开、节点没生成:把高亮收回项目那行
            }
            catch { }
        }

        /// <summary> 这个文件是不是在这个目录里(含子目录) </summary>
        private static bool 在目录里(string 文件, string 目录)
        {
            try
            {
                string 全 = Path.GetFullPath(文件);
                string 头 = Path.GetFullPath(目录).TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar;
                return 全.StartsWith(头, StringComparison.OrdinalIgnoreCase);
            }
            catch { return false; }
        }

