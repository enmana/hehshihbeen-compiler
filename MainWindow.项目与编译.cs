        /// <summary> 有项目时记录"哪些项目是展开的";没项目就不记录(按你的要求) </summary>
        private void 保存树展开状态()
        {
            if (解决方案.项目表.Count == 0) return;
            var 展开的 = new List<string>();
            foreach (var 项目 in 解决方案.项目表)
                if (节点已展开(项目)) 展开的.Add(项目.工程路径 ?? 项目.目录);
            选项.当前.展开的项目表 = 展开的;
            选项.保存(选项.当前);
        }

        private bool 节点已展开(项目项C 项目)
        {
            var 节点 = 项目树.ItemContainerGenerator.ContainerFromItem(项目) as TreeViewItem;
            return 节点?.IsExpanded ?? false;
        }

        /// <summary>
        /// 应用展开状态:上次展开过就展开;
        /// 若当前一个都没展开,则展开"当前项目"的第一层(方便马上看到文件列表)
        /// </summary>
        private void 应用树展开状态()
        {
            项目树.UpdateLayout();
            bool 有展开的 = false;
            foreach (var 项目 in 解决方案.项目表)
            {
                if (项目树.ItemContainerGenerator.ContainerFromItem(项目) is not TreeViewItem 节点) continue;
                bool 记过 = 选项.当前.展开的项目表.Any(路径 =>
                    string.Equals(路径, 项目.工程路径 ?? 项目.目录, StringComparison.OrdinalIgnoreCase));
                节点.IsExpanded = 记过;
                if (记过) 有展开的 = true;
            }
            if (有展开的) return;
            var 目标 = 解决方案.启动项目 ?? 解决方案.项目表.FirstOrDefault();
            if (目标 != null && 项目树.ItemContainerGenerator.ContainerFromItem(目标) is TreeViewItem 首)
                首.IsExpanded = true;
        }

