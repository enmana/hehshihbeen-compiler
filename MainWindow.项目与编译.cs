        private void 新建文件_Click(object sender, RoutedEventArgs e)
        {
            var 目标项目 = 解决方案.启动项目;
            if (目标项目 == null) { 提示需要项目(); return; }
            string? 名 = 输入窗口.问(this, "新建文件", "新文件名(不用写 .hb):", "新文件", $"会建在:{目标项目.目录}");
            if (名 == null) return;
            try
            {
                string 全 = 解决方案C.新建文件(目标项目, 名, 新建文件文本(名));
                输出框.Text = $"已在项目【{目标项目.名称}】里新建:{Path.GetFileName(全)}\n";
                切到底部输出();
                打开文件到标签页(全);
            }
            catch (Exception 异常)
            {
                输出框.Text = $"新建文件失败: {异常.Message}\n";
                切到底部输出();
                记异常框($"新建文件失败: {异常}");
            }
            刷新命令可用性();
        }

