        #region C23:工具栏「展开到汇编」→ 新页(`<被展开文件>_ASM.hba`)

        /// <summary>
        /// C23(用户 2026-09-20:"修改工具栏的展开到汇编按钮的响应模式,就改成正常按钮,点一下把展开的汇编代码
        /// 在新 tabitem 里面展示出来,可编辑,可保存就行了。并且展开后的文件名称应该是被展开文件的名称 +
