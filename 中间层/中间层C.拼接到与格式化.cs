        #region 中间层展开器的一部分:串返回临时 / `格式化` 编译期拆串 / `拼接到` 的段机制
        private readonly Dictionary<(string 文本, int 行号), 列表绑定C> _串返回临时 = new();

        private 列表绑定C 建串临时(int 行号)
        {
            var 类型 = new 列表类型C("字符", 1, 初始列表容量, 容量写死: false);
            var 串 = new 列表绑定C { 名称 = $"串返回临时{_串返回临时.Count + 1}", 类型 = 类型, 是字符串 = true };
            串.指针槽 = 新槽任意(4);
            串.长度槽 = 新槽任意(4);
            串.容量槽 = 新槽任意(4);
            串.数据槽 = 串.指针槽.Value;
            return 串;
        }

        /// <summary>
        /// 临时串初始化成空串(池里要一块,头三个字都写好)。
        /// 与 生成动态列表初始化 同义,但**不重置寄存器占用** —— 物化发生在语句中间,
        /// 外面还活着的寄存器不能被当成临时寄存器发出去。
        /// </summary>
        private void 初始化串临时(列表绑定C 串, int 行号)
        {
            var 快照 = 记占用();
            try
            {
                string 需要 = 新临时();
                输出装载常量(需要, (uint)初始列表容量);
                string 块 = 池要一块(需要, 行号, 串.名称, 是字符串: true);
                发出写变量(块, 串.指针槽!.Value);
                string 容量寄存器 = 新临时();
                输出装载常量(容量寄存器, (uint)初始列表容量);
                发出写变量(容量寄存器, 串.容量槽!.Value);
                string 零 = 新临时();
                输出装载常量(零, 0);
                发出写变量(零, 串.长度槽);
            }
            finally { 还占用(快照); }        // 这一段只是"写头三个字":用完就把临时寄存器还掉
        }

        /// <summary>把"返回字符串的函数调用"物化进一个临时串(调用一次,结果住在池里)</summary>
        private 列表绑定C 物化串返回调用(string 调用文本, int 行号, string 原文)
        {
            string 键 = 调用文本.Trim();
            var 串 = _串返回临时.TryGetValue((键, 行号), out var 已有) ? 已有 : 建串临时(行号);
            _串返回临时[(键, 行号)] = 串;
            初始化串临时(串, 行号);
            if (是格式化调用文本(键)) { 发出格式化(串, 键, 行号, 原文); return 串; }   // B2:格式化也住这个临时串
            var 调用 = 试取字符串返回调用(键, 行号)
                ?? throw 报错(行号, $"'{键}' 不是返回字符串的函数调用", $"not a string-returning call: '{键}'");
            发出表达式调用(调用.链路, 调用.实参, 行号, 原文, 返回目的地址: 头地址(串));
            return 串;
        }

        /// <summary>
        /// 这一整段文本是不是"调用一个返回 `字符串` 的函数"(`取名字()` / `记录.取()`)?
        /// **只判断不出码**(给"当字符串用"的探测用) —— 出码走 物化串返回调用。
        /// </summary>
        private bool 是字符串返回调用文本(string 文本, int 行号)
        {
            string 内容 = 文本.Trim();
            if (内容.Length < 3 || !内容.EndsWith(')') || !内容.Contains('(')) return false;
            if (是格式化调用文本(内容)) return true;      // B2:`格式化(...)` 也返回字符串(格式串对不对由 发出格式化 报)
            try { return 试取字符串返回调用(内容, 行号) is not null; }
            catch (编译异常C) { return false; }
        }

        /// <summary> 是 `格式化(...)` / `format(...)` 吗?**只看名字** —— 格式串合法不合法由 发出格式化 报错 </summary>
        private static bool 是格式化调用文本(string 文本)
        {
            string 内容 = 文本.Trim();
            int 左 = 内容.IndexOf('(');
            if (左 <= 0) return false;
            string 名 = 内容[..左].Trim();
            return 名 is "格式化" || string.Equals(名, "format", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// B2(第111批):`格式化("坐标 {0},{1}", x, y)` → 一个**字符串**(能 `输出行(...)`、
        /// 赋给字符串变量、或当 `拼接到` 的一段)。全在编译期:**零运行期解析**。
        /// 口径:格式串**必须是字符串字面量**(占位符的个数/序号编译期查);`{0}`/`{1}` 按序号(从 0 开始)、
        /// `{}` 按顺序取下一个;`{{` / `}}` 是字面花括号;值按类型转 —— 字符串原样、文字(一个码点)原样、
        /// 逻辑 → `真`/`假`、其余 32 位数值走库里的 `转字符串`。段数**不限**(B3 之后 `拼接到` 本身也不限了;
        /// 这里只在"逻辑值"那里分句 —— 真/假是两条分支,各自得是独立的一条 `拼接到`)。
        /// </summary>
        private void 发出格式化(列表绑定C 目标, string 调用文本, int 行号, string 原文)
        {
            string 内容 = 调用文本.Trim();
            int 左 = 内容.IndexOf('(');
            int 右 = 内容.LastIndexOf(')');
            if (左 < 0 || 右 <= 左) throw 报错(行号, $"格式化(...) 括号不配对:'{调用文本}'", "bad format call");
            var 实参们 = 切实参(内容[(左 + 1)..右]);
            if (实参们.Count == 0)
                throw 报错(行号, "格式化 至少要写格式串:格式化(\"{0}\", 值)", "format needs a format string");
            string 格式文本 = 实参们[0].Trim();
            if (!是字符串字面量(格式文本))
                throw 报错(行号, $"格式化的**格式串要写成字符串字面量**(占位符个数与序号得在编译期查):'{格式文本}' 不是。" +
                    $"要把值拼起来请用 `拼接到(结果, …)`,要把数字变成文字请用 转字符串(数值)",
                    "format string must be a string literal");
            var 值们 = new List<string>();
            for (int k = 1; k < 实参们.Count; k++) 值们.Add(实参们[k].Trim());
            string 格式 = 格式文本[1..^1];                  // 去掉两边引号(里面的转义原样留着,当字面段发回去)
            var 段们 = new List<拼接段>();
            var 缓冲 = new StringBuilder();
            void 冲字面段()
            {
                if (缓冲.Length == 0) return;
                段们.Add(new 拼接段(false, "\"" + 缓冲 + "\""));
                缓冲.Clear();
            }
            void 冲段们()
            {
                if (段们.Count == 0) return;
                发出拼接到(目标, new List<拼接段>(段们), 行号, 原文);
                段们.Clear();
            }
            int 顺次 = 0, i = 0;
            while (i < 格式.Length)
            {
                char c = 格式[i];
                if (c == '{')
                {
                    if (i + 1 < 格式.Length && 格式[i + 1] == '{') { 缓冲.Append('{'); i += 2; continue; }
                    int 闭 = 格式.IndexOf('}', i + 1);
                    if (闭 < 0) throw 报错(行号, $"格式串里的 '{{' 没配上 '}}':'{格式文本}'", "unclosed placeholder");
                    string 号 = 格式[(i + 1)..闭].Trim();
                    int 取号;
                    if (号.Length == 0) 取号 = 顺次++;
                    else if (!int.TryParse(号, out 取号) || 取号 < 0)
                        throw 报错(行号, $"格式串里的占位符 '{号}' 不认(要写 `{{0}}` `{{1}}` 这种序号,或者空的 `{{}}` 按顺序取):'{格式文本}'",
                            "bad placeholder");
                    if (取号 >= 值们.Count)
                        throw 报错(行号, $"格式串要第 {取号 + 1} 个值(占位符 {{{号}}}),只给了 {值们.Count} 个 —— " +
                            $"补一个值,或者把占位符改对(值从 0 开始编号)", "placeholder out of range");
                    冲字面段();
                    string 值 = 值们[取号];
                    if (是字符串操作数(值)) 段们.Add(new 拼接段(false, 值));
                    else if (是文字值(值, 行号)) 段们.Add(new 拼接段(false, 值, 0, 是文字: true));
                    else if (查变量(值) is { 是逻辑: true })
                    {
                        冲段们();
                        var 值寄存器 = 落到寄存器(求值表达式(值, 行号, 原文));
                        string 假 = 新标签("格式假"), 完 = 新标签("格式完");
                        发出($"JZ {值寄存器.寄存器} {假}");
                        发出拼接到(目标, [new 拼接段(false, "\"真\"")], 行号, 原文);
                        发出($"JMP {完}");
                        发出($"{假}:");
                        发出拼接到(目标, [new 拼接段(false, "\"假\"")], 行号, 原文);
                        发出($"{完}:");
                    }
                    else if (查变量(值) is { 是结构: true } or { 是数组: true } or { 是列表: true })
                        throw 报错(行号, $"格式化的第 {取号 + 1} 个值不能整块格式化:'{值}' 是结构/数组/列表 —— " +
                            $"要打结构请点到字段(如 {值}.字段),要打数组请逐个取元素", "cannot format a whole struct/array");
                    else
                    {
                        // 数字 → 文字走库里的 `转字符串`;没 包含 那个库时给一句能照着做的错(别让它报成"未定义的函数")
                        if (!是用户函数名("转字符串"))
                            throw 报错(行号, $"格式化 里第 {取号 + 1} 个值是数字,要经过库里的 `转字符串` 才能变成文字 —— " +
                                $"请在文件开头加一行 `包含 \"库/string.hb\"`(字符串/文字/逻辑 那几类不需要它)",
                                "number formatting needs 转字符串 from 库/string.hb");
                        段们.Add(new 拼接段(false, $"转字符串({值})"));
                    }
                    i = 闭 + 1;
                    continue;
                }
                if (c == '}')
                {
                    if (i + 1 < 格式.Length && 格式[i + 1] == '}') { 缓冲.Append('}'); i += 2; continue; }
                    throw 报错(行号, $"格式串里多了一个 '}}'(要写字面花括号请写 '}}}}'):'{格式文本}'", "stray '}'");
                }
                缓冲.Append(c);
                i++;
            }
            冲字面段();
            冲段们();
        }

        /// <summary> 段里的"返回字符串的函数调用"先物化好(算长度与拷内容都用同一个结果,函数只调一次)</summary>
        private void 物化段们(List<拼接段> 段们, int 行号, string 原文)
        {
            foreach (var 段 in 段们)
            {
                if (段.是单字节 || 段.是文字) continue;
                if (!是字符串返回调用文本(段.文本, 行号)) continue;
                段.物化串 = 建串临时(行号);
                初始化串临时(段.物化串, 行号);
                if (是格式化调用文本(段.文本))
                {
                    发出格式化(段.物化串, 段.文本.Trim(), 行号, 原文);      // B2:格式化当段用
                    continue;
                }
                var 调用 = 试取字符串返回调用(段.文本.Trim(), 行号)
                    ?? throw 报错(行号, $"'{段.文本}' 不是返回字符串的函数调用", "not a string-returning call");
                发出表达式调用(调用.链路, 调用.实参, 行号, 原文, 返回目的地址: 头地址(段.物化串));
            }
        }


        /// <summary>
        /// 字符字面量 `'A'` / `'\n'` / `'\x41'` → 码值;不是字符字面量返回 null。
        /// R2-5:转义统一走 `转义表C`(唯一事实源),这里不再手抄第二份。
        /// </summary>
        private static int? 解字符字面量(string 文本)
        {
            string t = 文本.Trim();
            if (t.Length < 3 || t[0] != '\'' || t[^1] != '\'') return null;
            return 转义表C.解字符内文(t[1..^1], out _);
        }

        /// <summary>
        /// 这一段是不是"一个文字"(`文字` 变量,或字符串取字 `名字[下标]`)?**只认不生成代码**
        /// —— 拼接分段时要先问它(生成代码会往当前缓冲里写东西,不能拿来试探)。
        /// </summary>
        private bool 是文字值(string 文本, int 行号)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0) return false;
            if (是文字变量(名)) return true;
            if (!像引用链(名)) return false;
            try { return 解析引用链(名, 行号) is { } 链 && 是字符串取字(链); }
            catch (编译异常C) { return false; }
        }

        /// <summary>
        /// 这一段是不是"一个字节"(宽度 1 的 `字符`/`字节` 左值:变量、数组元素、结构字段)。
        /// 字符**字面量**不在这里判 —— 它在伪行表里已经被换成数字了,要靠 `_伪行原文` 认(见 处理拼接到)。
        /// </summary>
        private bool 是单字节段(string 文本, int 行号)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0 || !像引用链(名)) return false;
            try
            {
                if (解析引用链(名, 行号) is not { } 链) return false;
                if (是字符串取字(链)) return false;   // 字符串取出来的是一个 `文字`(码点),不是 1 个字节
                if (链.是数组或列表) return false;
                return 链.元素宽 == 1 || 链.标量读宽 == 1;
            }
            catch (编译异常C) { return false; }
        }

        /// <summary>
        /// `拼接到(结果, a, b…)` —— 把各段接到 `结果` 后面(结果原有内容保留;结果原来是空串就是"从头拼")。**段数不限**。
        /// 每段可以是**一个字符串**,也可以是**一个字节**(`字符`/`字节` 的变量、数组元素,或 `'-'` 这样的字符字面量)。
        /// 注意:`字符` 在 HB 里就是 1 个字节(和 C 的 char 一样),所以这里追加的是**字节** ——
        /// 汉字占 3 字节,想按"字"拼要等"按码点"那一步;库函数(取子串/替换/转字符串)就是靠"一个字节一个字节地接"写出来的。
        /// 例:`字符串 问候;` 然后 `拼接到(问候, "你好,", 名字);`
        /// 做法(ISA 一条指令都没加):先算新总长 = 现在的长度 + 各段长度 → 容量不够按 ×2 换块(老内容照旧搬过去)
        /// → 逐段拷到"老内容之后" → 写长度 + 补 0。
        /// **自己拼自己也对**(`拼接到(s, s, "x")`):源那几段读的是"还没被写过的"老内容,
        /// 而写入位置从"老长度"往后排,两片区域不重叠。
        /// </summary>
        private void 处理拼接到(ref int 位置)
        {
            int 行号 = _伪行号表[位置];
            string 内容 = _伪行表[位置];
            string 原文行 = 位置 < _伪行原文.Count ? _伪行原文[位置] : 内容;
            string 首词 = 取首词(内容);
            string 余下 = 内容[首词.Length..].Trim();
            if (!余下.StartsWith('(') || !余下.EndsWith(')'))
                throw 报错(行号, $"拼接到(...) 需要括号:{内容}", $"concat(...) needs parentheses: {内容}");
            var 参数 = 切实参(余下[1..^1]);
            if (参数.Count < 2)
                throw 报错(行号, "拼接到 至少要写两样:先写结果,再写要接上去的字符串(例如 拼接到(问候, \"你好,\", 名字);)",
                    "concat needs a target and at least one source");
            // B3(第114批):原来这里硬卡"一次最多 4 段"。查清了:那是**旧实现**留下的数(当年把各段地址
            // 一次全算出来才需要按寄存器预算定 4);现在展开是**逐段**做的 —— 每段 `自成一段`(里面重新分配
            // 临时寄存器池,外面在用的靠 `活的` 传进去),所以**段数与寄存器压力无关**。这里只留一个"明显是误写"的
            // 护栏(见 最多拼接段数),不再按 4 段卡。
            string 目标名 = 参数[0];
            if (是字符串参数(目标名) && !是出参(目标名))
                throw 报错(行号, $"字符串参数 '{目标名}' 不能当拼接结果(它是**只读**的,数据在调用方那边);" +
                    $"要拼就先复制到一个本地字符串;要让它可写,请把函数头写成 `字符串 出 {目标名}`",
                    $"string parameter '{目标名}' cannot be the concat target");
            // 每段:字符串 / 字符(字面量看**原文**,左值看替换后的文本)
            var 原文参数 = 切实参(原文行[取首词(原文行).Length..].Trim().TrimStart('(').TrimEnd(')'));
            var 段们 = new List<拼接段>();
            for (int i = 1; i < 参数.Count; i++)
            {
                string 源 = 参数[i];
                string 源原文 = i < 原文参数.Count ? 原文参数[i].Trim() : 源;
                if (解字符字面量(源原文) is { } 码)
                {
                    // A5:字面量的码点 ≤ 一个字节 → 当"一个字节";超出的(星平面,例如 '😀')是**一个文字**,
                    // 按 UTF-8 编码(与 `文字` 变量同一条路)
                    if (码 <= 0xFF) 段们.Add(new 拼接段(是单字节: true, 源, (uint)码));
                    else 段们.Add(new 拼接段(false, 源, (uint)码, 是文字: true));
                    continue;
                }
                if (是字符串操作数(源)) { 段们.Add(new 拼接段(false, 源, 0)); continue; }
                if (是单字节段(源, 行号)) { 段们.Add(new 拼接段(true, 源, 0)); continue; }
                if (是文字值(源, 行号)) { 段们.Add(new 拼接段(false, 源, 0, 是文字: true)); continue; }
                throw 报错(行号, $"拼接到 只能拼字符串、**一个字节**(`字符`/`字节` 的变量、数组元素,或 `'-'` 这样的字符字面量)" +
                    $"或**一个文字**(`文字` 变量 / 字符串取字 名字[下标]):'{源原文}' 不是。" +
                    $"数字要拼进文字,请用库里的 转字符串(数值)(包含 \"库/string.hb\")",
                    $"concat accepts strings, one byte, or one rune: '{源原文}'");
            }
            // `拼接到(出参数, …)`:目标在**调用方那边**(参数槽里是它字符串头的地址)—— 改动当场落回去
            if (是出参(目标名))
            {
                var 出绑定 = 查变量(目标名)!.Value;
                准备语句占用(内容);
                自成一段(() => 发出拼接到头地址(出头地址(出绑定), 段们, 行号, 内容));
                位置++;
                return;
            }
            // 目标也可以是**定长缓冲**(`字符 名字[16]`,放不下当场拦住)或**堆串字段/元素**
            // (`字符串 名字`,装不下自动换块;见 发出串目标写入)
            if (试取串写目标(目标名, 行号, 内容) is { } 写目标)
            {
                准备语句占用(内容);
                发出串目标写入(写目标, 段们, 覆盖: false, 行号, 内容);
                位置++;
                return;
            }
            var 目标 = 查列表(目标名);
            if (目标 is not { 是字符串: true })
                throw 报错(行号, $"拼接到 的第一个参数要是**字符串变量**、`字符 名字[16]` 这样的定长缓冲、" +
                    $"或者结构里的 `字符串` 字段:'{目标名}' 不是(先声明一个,例如 `字符串 {目标名};`)",
                    $"concat target must be a string variable or a fixed buffer: '{目标名}'");
            准备语句占用(内容);
            发出拼接到(目标, 段们, 行号, 内容);
            位置++;
        }

        /// <summary> 拼接的实际展开(见 处理拼接到 的说明);每段是字符串或一个字节 </summary>
        private void 发出拼接到(列表绑定C 目标, List<拼接段> 段们, int 行号, string 原文)
        {
            物化段们(段们, 行号, 原文);      // "返回字符串的函数调用"当段用时:先物化(函数只调一次)
            自成一段(() =>
            {
                var 需要槽 = 需要字节暂存槽();
                // ① 新总长 = 结果现在的长度 + 各段长度(要跨 CALL,所以先落进暂存槽)
                string 需要 = 新临时();
                发出读变量(需要, 目标.长度槽);
                累加段长(需要, 段们, 行号, 原文);
                发出写变量(需要, 需要槽);
                // ② 容量够不够:不够就反复"翻倍"(与字符串赋值共用那支子程序;扩容会把老内容搬过去)
                //    ⚠ **要比的是"需要 + 1"**:串写完之后④要在 `数据 + 已拷` 处补一个 0 ——
                //    只留"需要的字节数"的话,`已拷 == 容量` 那一次那个 0 就写到**块外**去了,
                //    踩的正是池里**下一块的第一个字节**(H102,2026-10-15 第445批:方法里
                //    `拼接到(行, 码文)` 之后 码文 首字节变成 0、长度却还对 —— 池里的块挨着放,
                //    谁的块排在下一位谁倒霉)。堆串那条路一直留着这一格(`堆串保证容量` 内部自己 +1),
                //    池串这三条路都漏了。
                string 够 = 新标签("拼够"), 扩 = 新标签("拼扩");
                string 容量 = 新临时();
                发出读变量(容量, 目标.容量槽!.Value);
                发出读变量(需要, 需要槽);
                发出($"ADD_IMMEDIATE {需要} 1");
                发出($"CMP {容量} {需要}");
                发出($"JL {扩}");
                发出($"JMP {够}");
                发出($"{扩}:");
                发出($"CALL {确保列表扩容例程(目标)}");
                发出读变量(容量, 目标.容量槽!.Value);
                发出读变量(需要, 需要槽);            // CALL 会冲掉寄存器 → 长度重新读一遍
                发出($"ADD_IMMEDIATE {需要} 1");       // 同上:末尾那个 0 也要有地方放
                发出($"CMP {容量} {需要}");
                发出($"JL {扩}");                     // 还小就再来一轮
                发出($"{够}:");
                // ③ 逐段拷到"老内容之后"。每段一段自立代码(每段现取源地址:扩容可能换过块),
                //    "写到哪儿"用 已拷 跟着走 —— 目标址/已拷 必须保护住(里面重新分配寄存器池)
                string 目标址 = 新临时();
                string 已拷 = 新临时();
                发出读变量(目标址, 目标.指针槽!.Value);
                发出读变量(已拷, 目标.长度槽);
                拷贝各段(目标址, 已拷, 段们, 行号, 原文);
                // ④ 长度 = **已拷**(老内容 + 各段真实字节数);末尾补一个 0(这样 输出/老库函数都能接上)
                自成一段(() =>
                {
                    发出写变量(已拷, 目标.长度槽);
                    string 数据 = 新临时();
                    发出读变量(数据, 目标.指针槽!.Value);
                    string 尾 = 新临时();
                    发出($"MOV {尾} {数据}");
                    发出($"ADD {尾} {已拷}");
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    发出($"存储间接寻址 {零} {尾}");
                }, 已拷);
            });
        }

        /// <summary>
        /// 把各段的**字节数**加到 需要 上(单字节 +1;一个文字先按上限 +4 —— 真实长度拷完才算,容量宁可大一点)。
        /// 池字符串拼接与"定长缓冲/堆串"写入共用这一处。
        /// </summary>
        private void 累加段长(string 需要, List<拼接段> 段们, int 行号, string 原文)
        {
            foreach (var 段 in 段们)
            {
                if (段.是单字节) { 发出($"ADD_IMMEDIATE {需要} 1"); continue; }
                if (段.是文字) { 发出($"ADD_IMMEDIATE {需要} 4"); continue; }
                if (段.物化串 is { } 已物化)             // "返回字符串的函数调用":长度读它的长度槽
                {
                    string t0 = 新临时();
                    发出读变量(t0, 已物化.长度槽);
                    发出($"ADD {需要} {t0}");
                    continue;
                }
                var 快照 = 记占用();
                try
                {
                    var 长 = 字符串实参地址(段.文本, 行号, 原文).长度;
                    if (长.槽 is { } 槽)
                    {
                        string t = 新临时();
                        发出读变量(t, 槽);
                        发出($"ADD {需要} {t}");
                    }
                    else if (长.常量 == 0) { }
                    else if (长.常量 <= 0xFFFFF) 发出($"ADD_IMMEDIATE {需要} {长.常量}");
                    else
                    {
                        string t = 常量入临时(长.常量);
                        发出($"ADD {需要} {t}");
                    }
                }
                finally { 还占用(快照, 需要); }        // 每段用完就把自己的临时还掉(段可能很多)
            }
        }

        /// <summary>
        /// 把各段拷到 `目标址 + 已拷`(每拷一段 已拷 往前走该段的真实字节数)。
        /// 每段自成一段:段里的源地址**现取**(扩容/换块之后目标或源都可能换了地方)。
        /// `也要护住`:调用方在这之后还要用的寄存器(例如"字符串头的地址"—— 里面的段用完就还,不护会被当临时寄存器用掉)。
        /// </summary>
        private void 拷贝各段(string 目标址, string 已拷, List<拼接段> 段们, int 行号, string 原文, params string[] 也要护住)
        {
            foreach (var 段 in 段们)
                自成一段(() =>
                {
                    string 写址 = 新临时();
                    发出($"MOV {写址} {目标址}");
                    发出($"ADD {写址} {已拷}");
                    if (段.是单字节)
                    {
                        string 单字节 = 新临时();
                        if (段.字节值 != 0 || 解字符字面量(段.文本) is not null)
                            输出装载常量(单字节, 段.字节值);
                        else
                        {
                            // 宽度 1 的左值(`字符`/`字节` 变量、数组元素、结构字段):读出来就是零扩展好的
                            var 链 = 解析引用链(段.文本, 行号)!;
                            发出($"MOV {单字节} {链读到寄存器(链, 行号, 段.文本)}");
                        }
                        发出($"存储间接寻址 {单字节} {写址}");
                        发出($"ADD_IMMEDIATE {已拷} 1");
                        return;
                    }
                    if (段.是文字)
                    {
                        // A5:**文字字面量**(码点超过一个字节,例如 '😀'):`替换字面量` 已经把它写成十进制数,
                        // 码点就存在 段.字节值 里 —— 直接编码,不用再去文本里认(那是给变量/取字用的)
                        if (段.字节值 != 0)
                        {
                            string 码点常量 = 常量入临时(段.字节值);
                            string 文字字节数 = 发出写文字字节(码点常量, 写址, 行号);
                            发出($"ADD {已拷} {文字字节数}");
                            return;
                        }
                        // 一个文字:如果它本来就是"从某个字符串里取出来的字"(`名字[下标]`),
                        // 直接把它那几个字节搬过去就行(不用先解码再编码,省寄存器也更快);
                        // 是 `文字` 变量(可能被算过)才走 UTF-8 编码
                        if (像引用链(段.文本) && 解析引用链(段.文本, 行号) is { } 文链 && 是字符串取字(文链))
                        {
                            // 同样:解码那一串临时全包进"自立一段",对外只留下**起点 + 字节数**
                            string 文起点 = "", 文字节数 = "";
                            自成一段保守(() =>
                            {
                                var (文数据, 文字节长) = 串数据与字节长(文链.基名, 行号, 原文);
                                string 文下标 = 取字下标寄存器(文链, 行号, 段.文本);
                                string 文数 = 发出数文字(文数据, 文字节长);
                                发出文字下标检查(文下标, 文数, 行号, 段.文本);
                                (_, 文起点, 文字节数) = 发出取文字(文数据, 文下标, 行号);
                            });
                            收下临时(文起点);
                            收下临时(文字节数);
                            发出字节拷贝(文起点, 写址, 文字节数);
                            发出($"ADD {已拷} {文字节数}");
                            return;
                        }
                        string 码点 = 试取文字值(段.文本, 行号, 原文)
                            ?? throw 报错(行号, $"拼接到 认不出这一段文字:'{段.文本}'", $"bad rune segment: '{段.文本}'");
                        string 文字字节 = 发出写文字字节(码点, 写址, 行号);
                        发出($"ADD {已拷} {文字字节}");
                        return;
                    }
                    var 源 = 段.物化串 is { } 已物化
                        ? (地址: 读临时(已物化.指针槽!.Value), 长度: ((uint)0, 已物化.长度槽))
                        : 字符串实参地址(段.文本, 行号, 原文);
                    string 源长 = 长度入寄存器(源.长度);
                    发出字节拷贝(源.地址, 写址, 源长);
                    发出($"ADD {已拷} {源长}");
                }, [目标址, 已拷, .. 也要护住]);
        }

