using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace hehshihbeen_compiler
{
    /// <summary> 中间层展开器的一部分:K5 编译期多错误:回滚现场接着编、收尾一次列全。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        #region 编译期多错误报告(K5):一处错不打断整篇,回滚现场接着编,收尾一次列全

        /// <summary> 出错前先记下"现场":缓冲层数/缓冲长度/各栈层数/函数正文与例程长度/当前函数 </summary>
        private (int 缓冲层, int 缓冲长, int 作用域层, int 上下文层, int 函数正文长, int 例程长, int 开头长,
            int 槽数, 函数上下文? 函数) 记现场()
            => (_缓冲栈.Count, _缓冲栈.Count > 0 ? _缓冲栈.Peek().Count : 0, _作用域栈.Count, _上下文栈.Count,
                _函数正文.Count, _列表例程.Count, _开头初始化.Count, _槽序表.Count, _当前函数);

        /// <summary>
        /// 把现场退回到出错之前:这一句**半路发出去的指令**与**半路登记的变量/作用域**都要撤掉,
        /// 不然接着编下一句时会生成"跳向不存在标签"之类的烂代码。
        /// (编译期本来就会因为"有错"在收尾时抛出,那份烂代码不会被拿去汇编 —— 但状态必须干净。)
        /// </summary>
        private void 回滚到((int 缓冲层, int 缓冲长, int 作用域层, int 上下文层, int 函数正文长, int 例程长, int 开头长,
            int 槽数, 函数上下文? 函数) 现场)
        {
            while (_缓冲栈.Count > 现场.缓冲层) _缓冲栈.Pop();
            if (_缓冲栈.Count > 0)
            {
                var 缓冲 = _缓冲栈.Peek();
                if (缓冲.Count > 现场.缓冲长) 缓冲.RemoveRange(现场.缓冲长, 缓冲.Count - 现场.缓冲长);
            }
            while (_作用域栈.Count > 现场.作用域层) _作用域栈.RemoveAt(_作用域栈.Count - 1);
            while (_上下文栈.Count > 现场.上下文层) _上下文栈.RemoveAt(_上下文栈.Count - 1);
            while (_函数正文.Count > 现场.函数正文长) _函数正文.RemoveAt(_函数正文.Count - 1);
            while (_列表例程.Count > 现场.例程长) _列表例程.RemoveAt(_列表例程.Count - 1);
            while (_开头初始化.Count > 现场.开头长) _开头初始化.RemoveAt(_开头初始化.Count - 1);
            while (_槽序表.Count > 现场.槽数) _槽序表.RemoveAt(_槽序表.Count - 1);
            _当前函数 = 现场.函数;
            _语句占用 = null;
            _语句常量 = null;
        }

        /// <summary>
        /// 出错那句要跳到哪里。
        ///
        /// **块头出错不再整块丢掉**(批 6):以前这里遇到 `{` 就 `跳过一个块` —— 一个块里 5 处错只报得出第 1 处。
        /// 现在改成进块的**里面**逐句编(`收块内错误`),里面的错照样一条条收;
        /// 只有**函数/方法/结构这类声明头**仍然整块跳 —— 它们自己错了的话,块体缺了帧/类型上下文,
        /// 里面的语句会报出一堆"返回 只能写在函数里"之类的**派生噪声**,那不是用户要看的。
        ///
        /// `如果 … { … } 否则 … { … }`(以及 `否则 如果 …` 串起来)是**一条**语句:每个分支块都要走一遍,
        /// 不然那个 `否则` 会变成"多余的 否则"(用户实测过这种牵连假错)。
        /// </summary>
        private int 跳过坏语句(int 句首, List<编译异常C> 错误表)
        {
            int i = 句首 + 1;
            if (i >= _伪行表.Count) return _伪行表.Count;
            if (_伪行表[i] != "{") return i;                       // 普通语句:跳一句

            bool 声明头 = 中间层C.到英文关键字(取首词(_伪行表[句首])) is "method" or "static" or "struct";
            // T2(2026-09-27 评测整改):这一句撞的是**语句块嵌套上限** ⇒ 里面那几层根本编不动,
            // 再走 `收块内错误` 只会"再撞一次护栏 → 再恢复 → 再撞",每一层还留一摞栈帧(实测 129 层就够把栈吃掉)。
            // 所以整块跳过(下面的 `否则` 串一并跳过),错误表里留着头一条"嵌套太深"就够用户改代码了。
            if (_块深度超限) return 跳过一个块(i);
            i = 声明头 ? 跳过一个块(i) : 收块内错误(i, 错误表);
            while (i < _伪行表.Count && 是否则行(_伪行表[i]))
            {
                i++;                                              // `否则` / `否则 如果 (…)` 那一行
                if (i >= _伪行表.Count || _伪行表[i] != "{") break;   // 形状不对就停手,交给正常流程去报错
                i = 收块内错误(i, 错误表);
            }
            return i;
        }

        /// <summary>
        /// 出错恢复最多嵌几层(`收块内错误` 自己那条递归链)。
        ///
        /// T20(2026-09-27 评测整改)实测出来的:畸形源码一层层套下去时,恢复那条路
        /// `收块内错误 → 处理语句 → 处理选择 → 抛错 → 跳过坏语句 → 收块内错误` 每层留的栈帧比正常编译多得多 ——
        /// 嵌套 `选择 (真) {` 但不写 `情况` 时,**100 层还报得出「共 100 处错误」、128 层就把栈吃穿**
        /// (`0xC00000FD`,stdout 零字节)。`_块深度` 那道 128 的预算不够用,所以恢复自己再收一道更紧的:
        /// 32 层恢复嵌套(离实测 128 层有 4 倍余量),撞上就**整块跳过** —— 少报几处内层错,换不崩。
        /// 真源码里没有哪份工程需要"错误恢复嵌 32 层",这条预算够用。
        /// </summary>
        private const int 恢复嵌套上限 = 32;

        /// <summary>
        /// 从一个 `{` 开始:开一层作用域,把块里的语句**逐句编**(每句自带现场回滚 + 出错跳句),直到配对的 `}`。
        /// 给"块头自己就错了"的恢复用 —— 这样块里还能再报出别的错(批 6)。返回 `}` 后面那一行。
        /// </summary>
        private int 收块内错误(int 花括号行, List<编译异常C> 错误表)
        {
            if (花括号行 >= _伪行表.Count || _伪行表[花括号行] != "{") return 花括号行;
            // T2(2026-09-27 评测整改):**恢复这条路也在递归**(收块内错误 → 处理语句 → 处理块 → 出错 →
            // 跳过坏语句 → 收块内错误),而且它一层源码嵌套就多留一摞帧、不像正常编译那样会退干净 ——
            // 实测 450 层嵌套 + 一处错时,栈就是在**这里**炸的(护栏只管住了正常那条路)。
            // 所以恢复也吃同一份嵌套预算:预算见底就**整块跳过**,不再往里走(少报几处内层错,换不崩)。
            if (_块深度 >= 硬上限C.语句块嵌套上限) return 跳过一个块(花括号行);
            // T20:恢复自己那一份更紧的预算(见 `恢复嵌套上限`)—— 畸形嵌套时上面那条 128 不够用。
            if (_恢复层数 >= 恢复嵌套上限) return 跳过一个块(花括号行);
            int i = 花括号行 + 1;
            int 起行 = _伪行号表[花括号行];
            int 止行 = 起行;
            _块深度++;
            _恢复层数++;
            压作用域(起行);
            try
            {
                while (i < _伪行表.Count)
                {
                    if (_伪行表[i] == "}") { 止行 = _伪行号表[i]; i++; break; }
                    if (_伪行表[i] == "{") { i = 跳过一个块(i); continue; }    // 形状不对的嵌套块:整块跳
                    int 句首 = i;
                    var 现场 = 记现场();
                    try
                    {
                        处理语句(ref i);
                        if (i <= 句首) i = 句首 + 1;                       // 防呆:没往前推就补一步
                    }
                    catch (编译异常C 错)
                    {
                        记一处错(错误表, 错);
                        回滚到(现场);
                        i = 跳过坏语句(句首, 错误表);
                    }
                }
            }
            finally { 弹作用域(止行); _块深度--; _恢复层数--; }
            return i;
        }

        /// <summary> 从 `{` 那一行开始跳过一个配对的块,返回块后面那一行 </summary>
        private int 跳过一个块(int i)
        {
            int 深 = 0;
            while (i < _伪行表.Count)
            {
                if (_伪行表[i] == "{") 深++;
                else if (_伪行表[i] == "}")
                {
                    深--;
                    if (深 == 0) return i + 1;
                }
                i++;
            }
            return _伪行表.Count;
        }

        /// <summary> 这一行是不是 `否则` / `else`(也可能是 `否则 如果 (…)`,首词仍是"否则") </summary>
        private bool 是否则行(string 内容)
            => 中间层C.到英文关键字(取首词(内容)) == "else";

        private static void 记一处错(List<编译异常C> 错误表, 编译异常C 错)
        {
            if (错误表.Any(x => x.行号 == 错.行号 && x.中文 == 错.中文)) return;   // 同一句别记两遍
            错误表.Add(错);
        }

        /// <summary>
        /// 把攒下的错误合成一条(按行号排)。**只有一处错时原样抛出原来那条** ——
        /// 报错文案与行号一个字都不变,既有断言与用户习惯都不受影响。
        /// </summary>
        private static 编译异常C 合成多错(List<编译异常C> 错误表)
        {
            var 排好 = 错误表.OrderBy(x => x.行号 ?? int.MaxValue).ToList();
            if (排好.Count == 1) return 排好[0];
            var 说明 = new StringBuilder($"共 {排好.Count} 处错误(一次列全,按行号排):");
            foreach (var 错 in 排好)
            {
                // 每条错误自己的 中文 里已经带了 `中间层展开错误 第N行: `(见 报错静态)——
                // 这里再套一次"第 N 行:"就变成 `第 2 行:中间层展开错误 第2行: …`,同一句话里两遍行号。
                // 剥掉内层那段(没有就原样用),只留外面统一的那一份。
                string 一条 = 错.中文;
                const string 内层前缀 = "中间层展开错误 第";
                if (一条.StartsWith(内层前缀, StringComparison.Ordinal))
                {
                    int 冒号 = 一条.IndexOf(':', 内层前缀.Length);
                    if (冒号 >= 0) 一条 = 一条[(冒号 + 1)..].TrimStart();
                }
                说明.Append($"\n  第 {错.行号?.ToString() ?? "?"} 行:{一条}");
            }
            var 首 = 排好[0];
            return new 编译异常C(说明.ToString(), $"multiple errors ({排好.Count})", 首.行号, 首.源行, 首.文件 ?? "")
            {
                子错 = 排好,      // P23:一条条挂上 —— 界面「问题」页按条列、按条跳
            };
        }
        #endregion
    }
}
