            return null;
        }

        /// <summary>
        /// H72(第353批):堆动作当**值**用 —— `整数 值 = 取字(p, 0);`、`如果 (取字(p, 0) == 5)`。
        ///
        /// 以前这几个只在 `替换地址取用` → `替换堆调用` 那一步按**整条文本**预先展开;普通表达式没问题,
        /// 可**条件**也走同一个入口 ⇒ `父 != 0 && 取字(父, 8) == 走` 里的 `取字` **不管左边真假都算过**
        /// (短路形同虚设,`父` 是 0 时当场撞堆头检查)。现在条件那一侧改成不预先展开(见
        /// `替换地址取用跳过堆`),由这里按 AST 懒算 —— 短路那一支真的不算。
        ///
        /// 实参文本用节点自己的 `显示()`;内层还嵌着堆调用(例如 `取字(取字(p, 0), 4)`)时,
        /// `生成取字 / 生成存字` 里的表达式求值会走同一条 `替换堆调用` 把它展开 —— 那一条照旧。
        /// </summary>
        private 表达式值 求值堆动作当值(string 动作, 调用节点C 调用, int 行号, string 原文)
        {
            string 参(int i) => 调用.实参[i].显示();
            switch (动作)
            {
                case "申请":
                    if (调用.实参.Count != 1)
                        throw 报错(行号, $"申请 要一个参数(字节数):申请(32);收到 {调用.实参.Count} 个 —— '{原文}'",
                            "alloc() takes exactly one argument");
                    return 表达式值.寄存器值(生成申请(参(0), 行号, 原文), 可写: true);
                case "取字":
                    if (调用.实参.Count != 2)
                        throw 报错(行号, $"取字 要两个参数(地址, 偏移):取字(p, 0);收到 {调用.实参.Count} 个 —— '{原文}'",
                            "loadword() takes exactly two arguments");
                    return 表达式值.寄存器值(生成取字(参(0), 参(1), 行号, 原文), 可写: true);
                case "存字":
                    if (调用.实参.Count != 3)
                        throw 报错(行号, $"存字 要三个参数(地址, 偏移, 值):存字(p, 0, 7);收到 {调用.实参.Count} 个 —— '{原文}'",
                            "storeword() takes exactly three arguments");
                    return 表达式值.寄存器值(生成存字(参(0), 参(1), 参(2), 行号, 原文), 可写: true);
                default:                                       // 释放:是个"动作",当值用给 0(它没有结果)
                    if (调用.实参.Count != 1)
                        throw 报错(行号, $"释放 要一个参数(申请 返回的那个地址):释放(p);收到 {调用.实参.Count} 个 —— '{原文}'",
                            "free() takes exactly one argument");
                    生成释放(参(0), 行号, 原文);
                    return 表达式值.常量值(0);
            }
        }

