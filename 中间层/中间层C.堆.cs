        /// <summary>
        /// **T10(2026-09-27 评测整改):取字 / 存字 的偏移必须落在这一块里。**
        ///
        /// 块头 [+4] 存着本块总长(含 12 字节块头)⇒ "这一块能用的字节" = 块长 - 块头字节;
        /// 一次访问是一个字(4 字节)⇒ 合法条件是 **偏移 + 4 ≤ 可用**,也就是 **偏移 + 16 ≤ 块长**。
        /// 展开成:`暂 = 数据地址 - 8(块长那个字)/ 读块长 / 比一下 / 越界就报错停机` —— 5 条(常量偏移)。
        ///
        /// 以前这里**只查"释放标志"、不查块长**(K8 的口径是"校验只在四个入口",漏了这一条):
        /// 实测 `整数 p = 申请(8); 整数 q = 申请(8); 存字(p, q - p, 999);` 把邻居块的头静默写坏,
        /// `存字(p, 1000000, 42)` 能写进 1MB 内任意地址 —— 全程不报错、退出码 0。
        ///
        /// **不给开关**(评测整改 T31 拍板):数组越界给 `边界="关"` 是有道理的(热循环省判据、
        /// 越界在语言语义里是"用户错误");堆偏移越界是**进程级破坏**,留一个"关掉就静默损坏"的入口
        /// 与"静默给错答案比报错更严重"这条硬规矩冲突。开销实测见 `K8实现细则.md` 第9节。
        ///
        /// 文案里**只说偏移,不打印块长** —— 块长是运行期值,而运行期报错是一份**静态说明表**
        /// (错误号 → 说明),塞不进运行期的数(同族见 T12)。
        /// </summary>
        private void 检查堆偏移不越块(string 数据地址寄存器, string 偏移文本, int 行号, string 原文)
        {
            var 快照 = 记占用();
            string 暂 = 新临时();
            发出($"MOV {暂} {数据地址寄存器}");
            发出($"SUB_IMMEDIATE {暂} {块头字节 - 4}");         // 块长那个字在 数据地址 - 8(= 块首 + 4)
            string 长 = 新临时();
            发出($"取字间接 {长} {暂}");
            string 继续 = 新标签("heapfit");
            bool 常量 = 解析无符号32(偏移文本, out uint 常量偏移);
            if (常量 && 常量偏移 + 块头字节 + 4 <= 0xFFFFFu)
            {
                发出($"CMP_IMMEDIATE {长} {常量偏移 + 块头字节 + 4}");   // 块长 vs "装下这一次访问至少要多少"
                发出($"JG {继续}");
                发出($"JEQ {继续}");
            }
            else
            {
                string 偏 = 偏移文本;
                if (常量)
                {
                    偏 = 新临时();
                    输出装载常量(偏, 常量偏移);
                }
                发出($"SUB_IMMEDIATE {长} {块头字节 + 4}");               // 长 = 这一块最大允许的偏移
                // ⚠ **贴边那一格也是合法的**(第345批修的):判据是"偏 ≤ 长",不是"偏 < 长"。
                //   原来这一支写的是 `CMP 偏 长` + `JL` —— 比上面那条常量路(`JG` + `JEQ`,允许 `长 == 需要`)
                //   紧一格:同一个偏移,常量写法(`取字(p, 16)`)过、变量写法(`取字(p, 偏)`)报"堆块越界"。
                //   实测(写 `缓冲.hb` 时撞上的):`申请(24)` 的块,`取字(a, 20)` 过、`偏 = 20; 取字(a, 偏)` 红。
                //   现在反过来比:`CMP 长 偏` 的旗标是 `长 - 偏`,`JG`/`JEQ` 合起来就是"长 ≥ 偏"。
                发出($"CMP {长} {偏}");
                发出($"JG {继续}");
                发出($"JEQ {继续}");
            }
            string 怎么绕 = "偏移从 0 起,别超出 申请 时的字节数(要更大就重新 申请 一块)";
            报错停机(行号, 常量
                ? $"堆块越界:{原文} —— 偏移 {常量偏移} 落到这一块外面了;{怎么绕}"
                : $"堆块越界:{原文} —— 偏移落到这一块外面了;{怎么绕}");
            发出($"{继续}:");
            还占用(快照);
        }

        /// <summary>取字/存字 的公共前半:算"数据地址 + 偏移"(指针先算,再做"释放后读写"与"越出块长"两道拦截)</summary>
        private string 堆元素地址(string 指针文本, string 偏移文本, int 行号, string 原文)
        {
            确保堆();
            var 快照 = 记占用();
            string 地址 = 新临时();
            输出赋值到寄存器(地址, 指针文本, 行号, 原文);
            检查堆没释放(地址, 行号);
            string 偏 = 偏移文本.Trim();
            if (偏.Length > 0)
            {
                if (解析无符号32(偏, out uint 常量偏移))
                {
                    if (常量偏移 > 0) 检查堆偏移不越块(地址, 常量偏移.ToString(System.Globalization.CultureInfo.InvariantCulture), 行号, 原文);
                    if (常量偏移 > 0 && 常量偏移 <= 0xFFFFF) 发出($"ADD_IMMEDIATE {地址} {常量偏移}");
                    else if (常量偏移 > 0)
                    {
                        string 常 = 常量操作数寄存器(常量偏移, 地址);
                        发出($"ADD {地址} {常}");
                    }
                }
                else
                {
                    string 偏寄存器 = 新临时();
                    输出赋值到寄存器(偏寄存器, 偏, 行号, 原文);
                    检查堆偏移不越块(地址, 偏寄存器, 行号, 原文);
                    发出($"ADD {地址} {偏寄存器}");
                }
            }
            还占用(快照, 地址);              // 偏移中转那些用完就还,只留"算好的数据地址"
            return 地址;
        }

        /// <summary>`取字(p, 偏移)` → 读出来的那个字所在的寄存器</summary>
        private string 生成取字(string 指针文本, string 偏移文本, int 行号, string 原文)
        {
            var 快照 = 记占用();
            string 地址 = 堆元素地址(指针文本, 偏移文本, 行号, 原文);
            string 值 = 新临时();
            发出($"取字间接 {值} {地址}");
            还占用(快照, 值);                // 只留读出来的值
            return 值;
        }

        /// <summary>
        /// `存字(p, 偏移, 值)` → 返回"写进去的那个值"所在的寄存器(表达式里能接着用)。
        /// **值先算、地址后算**(和 `记录.字段 = 值` 那条路同一个顺序):值里带用户函数调用时,
        /// 后算的地址不会把它冲掉(反过来先算地址就会被那个 CALL 冲掉)。
        /// </summary>
        private string 生成存字(string 指针文本, string 偏移文本, string 值文本, int 行号, string 原文)
        {
            var 快照 = 记占用();
            string 值 = 新临时();
            输出赋值到寄存器(值, 值文本, 行号, 原文);
            // H73(第355批):**地址那一段也会调函数**(指针写成 `取据(流)`、偏移写成 `下一个()`)
            // —— 那个 CALL 会把寄存器池整个冲一遍,值寄存器当场失效(实测最小复现 4 行:
            // `存字(取据(流), 8, 333); 输出行(取字(取据(流), 8));` 读回来是 3540,不是 333)。
            // 与 H71 同一条尺子(赋值右边算好的值会被"地址里的 CALL"冲掉):值先落临时槽,
            // 等地址算完、临到"存"那一步再读回来。判据用 `文本含调用`(宁可多存一次,不能漏)。
            地址位置? 值槽 = null;
            if (文本含调用(指针文本) || 文本含调用(偏移文本))
            {
                值槽 = 新临时槽();
                发出写变量(值, 值槽.Value);
            }
            string 地址 = 堆元素地址(指针文本, 偏移文本, 行号, 原文);
            if (值槽 is { } 槽回) 发出读变量(值, 槽回);
            发出($"存字间接 {值} {地址}");
            还占用(快照, 值);                // 只留写进去的那个值
            return 值;
        }

        // ---------------- 堆调用:申请/取字/存字 在表达式里"就地换成已经算好的临时寄存器" ----------------
        // 仿 `地址(x)` 那套文本替换(不动表达式求值器,改动面最小;理由见 K8实现细则.md 第8节)。

        private static readonly Regex 堆调用正则 = new(
            @"(?<![\p{L}\p{N}_])(申请|alloc|取字|loadword|存字|storeword)\s*\(",
            RegexOptions.Compiled | RegexOptions.IgnoreCase);

        /// <summary>
        /// 把表达式文本里的 `申请(n)` / `取字(p, 偏移)` / `存字(p, 偏移, 值)` 就地换成临时寄存器名。
        /// 用户自己声明了同名函数时**跳过那一处**(让正常调用那条路走)。
        /// </summary>
        private string 替换堆调用(string 文本, int 行号, string 原文)
        {
            int 起点 = 0;
            while (true)
            {
                var 匹配 = 堆调用正则.Match(文本, 起点);
                if (!匹配.Success) return 文本;
                string 名 = 匹配.Value[..^1].Trim();
                if (是用户函数名(名)) { 起点 = 匹配.Index + 匹配.Length; continue; }
                if (名 == "释放" || 名.Equals("free", StringComparison.OrdinalIgnoreCase))
                    throw 报错(行号, $"释放 要单独成句(写成 `释放(p);`),它不能当值用 —— '{原文}'",
                        "free() must be a statement of its own");
                int 左括号 = 匹配.Index + 匹配.Length - 1;
                int 右括号 = 找匹配右括号(文本, 左括号, 行号);
                var 参数 = 切实参(文本[(左括号 + 1)..右括号]);
                string 替换;
                if (名 == "申请" || 名.Equals("alloc", StringComparison.OrdinalIgnoreCase))
                {
                    if (参数.Count != 1)
                        throw 报错(行号, $"申请 要一个参数:申请(字节数);收到 {参数.Count} 个 —— '{原文}'",
                            "alloc() takes exactly one argument");
                    替换 = 生成申请(参数[0], 行号, 原文);
                }
                else if (名 == "取字" || 名.Equals("loadword", StringComparison.OrdinalIgnoreCase))
                {
                    if (参数.Count != 2)
                        throw 报错(行号, $"取字 要两个参数:取字(p, 偏移);收到 {参数.Count} 个 —— '{原文}'",
                            "loadword() takes two arguments");
                    替换 = 生成取字(参数[0], 参数[1], 行号, 原文);
                }
                else
                {
                    if (参数.Count != 3)
                        throw 报错(行号, $"存字 要三个参数:存字(p, 偏移, 值);收到 {参数.Count} 个 —— '{原文}'",
                            "storeword() takes three arguments");
                    替换 = 生成存字(参数[0], 参数[1], 参数[2], 行号, 原文);
                }
                int 尾 = 右括号 + 1;
                文本 = 文本[..匹配.Index] + 替换 + (尾 < 文本.Length ? 文本[尾..] : "");
                起点 = 匹配.Index + 替换.Length;
            }
        }
        #endregion
    }
