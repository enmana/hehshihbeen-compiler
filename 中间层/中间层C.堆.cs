    /// <summary> 中间层展开器的一部分:K8 堆:隐藏槽与初始化 / 分配与释放例程 / 四个入口。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        #region K8 堆:隐藏槽与初始化 / 分配与释放例程 / 四个入口(申请·释放·取字·存字)
        // 详见 K8实现细则.md。三条底线:
        //   ① 老池(字符串/列表)行为一个字不改 —— 堆是另一块内存;
        //   ② 校验只在**四个入口**(申请 / 释放 / 取字 / 存字),不给每次内存访问都加检查;
        //   ③ 例程自己不报错(只返回状态),**行号与报错文案放在调用点**,这样错误带得准行号。

        /// <summary>
        /// 堆:编译器自己开的独立一块(默认 64KB,工程文件 `堆` 可配;和"软栈槽/池槽"一个套路),`申请` 从这儿要地方、`释放` 还回来。
        /// 初始化必须**程序一开头就跑**(和池同一个理由:堆有可能第一次是在某个函数里用到的,那段代码留在函数体里
        /// 就会"函数还没被调用、堆表头还是 0"),所以走"程序开头跑一次"那份清单。
        /// 整块一开始就是**一个空闲块**:[下一块 = 0][大小 = 堆大小][空闲 = 1],空闲表头指向它。
        /// </summary>
        private void 确保堆()
        {
            // 被"逐句回滚"(K5 多错误报告)撤掉过就重新开:槽表里找不到说明那次回滚把槽删了
            if (_堆槽 != null && _槽序表.Any(x => x.名称 == _堆槽.Value.名称)) return;
            _堆槽 = 新槽(_堆大小);
            _堆首槽 = 新槽(4);
            _堆末槽 = 新槽(4);
            _空闲表头槽 = 新槽(4);
            var 存档 = _语句占用;
            var 初始化 = new List<string>();
            _缓冲栈.Push(初始化);
            try
            {
                自成一段(() =>
                {
                    string 首 = 新临时();
                    发出($"取地址 {首} {_堆槽!.Value.名称}");        // 堆首
                    发出($"存字 {首} {_堆首槽!.Value.名称}");
                    string 末 = 新临时();
                    发出($"MOV {末} {首}");
                    发出($"ADD_IMMEDIATE {末} {_堆大小}");
                    发出($"存字 {末} {_堆末槽!.Value.名称}");
                    string 零 = 新临时();
                    输出装载常量(零, 0u);
                    堆写字(首, 0, 零, 零);                          // [+0] 下一空闲块:没有
                    string 整 = 新临时();
                    输出装载常量(整, (uint)_堆大小);
                    堆写字(首, 4, 整, 零);                          // [+4] 整块大小 = 堆大小
                    string 一 = 新临时();
                    输出装载常量(一, 1u);
                    堆写字(首, 8, 一, 零);                          // [+8] 空闲
                    发出($"存字 {首} {_空闲表头槽!.Value.名称}");    // 空闲表头 = 整块
                });
            }
            finally
            {
                _缓冲栈.Pop();
                _语句占用 = 存档;
                _语句常量 = null;
            }
            插入主程序开头(初始化);
        }

        /// <summary> [基址寄存器 + 偏移] = 值寄存器(4 字节字)。暂 是调用方自己借的临时寄存器(中转地址用) </summary>
        private void 堆写字(string 基, int 偏移, string 值, string 暂)
        {
            if (偏移 == 0)
            {
                发出($"存字间接 {值} {基}");
                return;
            }
            发出($"MOV {暂} {基}");
            发出($"ADD_IMMEDIATE {暂} {偏移}");
            发出($"存字间接 {值} {暂}");
        }

        /// <summary> [基址寄存器 + 偏移] → 目标寄存器(4 字节字)。暂 是调用方自己借的临时寄存器 </summary>
        private void 堆读字(string 目标, string 基, int 偏移, string 暂)
        {
            if (偏移 == 0)
            {
                发出($"取字间接 {目标} {基}");
                return;
            }
            发出($"MOV {暂} {基}");
            发出($"ADD_IMMEDIATE {暂} {偏移}");
            发出($"取字间接 {目标} {暂}");
        }

        /// <summary>
        /// 分配子程序(编译期生成一次,进 `_列表例程` 那一列,和"列表扩容"同一个套路):
        /// **首次适配 + 切分**(装得下的第一块就给它;剩下的够 16 字节就切出一个新空闲块)。
        /// 调用约定:`R0` = 需要字节数 → `R0` = 数据地址(**0 = 堆里放不下**,不在这里报错)。
        /// **除 R0 外的寄存器全都"入栈保存 / 返回前恢复"**:这样调用点在语句中间用它(例如 `左 + 申请(4)`)
        /// 也不会踩坏外面已经算好的值 —— 分配例程自己要用一堆临时寄存器、还要用 CMP。
        /// **空闲块合并(P33 已做)**:释放时把相邻空闲块并回一块(前邻 / 后邻都看,见本文件后面"合并"那一段);
        /// 早先这里写的是"先不做合并",已经不成立(第195批改)。
        /// </summary>
        private string 确保堆分配例程()
        {
            if (_堆分配标签.Length > 0 && _列表例程.Contains(_堆分配标签 + ":")) return _堆分配标签;
            确保堆();
            string 标签 = 新标签("heapalloc");   // 标签前缀用 ASCII:多文件的 `_f…` 靠"唯一化展开标签"改名(中文前缀它认不出)
            _堆分配标签 = 标签;
            var 例程 = new List<string>();
            _缓冲栈.Push(例程);
            try
            {
                自成一段(() =>
                {
                    准备语句占用("R0");                                  // R0 是入参/出参,不交给临时分配
                    string 掩 = 新临时();                                // 4 字节取整掩码(用完当常量寄存器)
                    string 头 = 新临时();                                // 当前空闲块(块首)
                    string 前 = 新临时();                                // 它前面那一块(0 = 就是表头)
                    string 下一 = 新临时();                              // 摘链时要接上的下一块
                    string 大小 = 新临时();                              // 本块总大小
                    string 剩 = 新临时();                                // 切完还剩多少
                    string 新块 = 新临时();                              // 切出来的新空闲块
                    string 暂 = 新临时();                                // 地址中转
                    string[] 借用 = [掩, 头, 前, 下一, 大小, 剩, 新块, 暂];
                    foreach (string r in 借用) 发出($"入栈 {r}");         // 借用哪些先定下来,再统一保存

                    string 环 = 新标签("heapfind");
                    string 前进 = 新标签("heapnext");
                    string 不切 = 新标签("heapnosplit");
                    string 摘链 = 新标签("heapunlink");
                    string 改头 = 新标签("heaphead");
                    string 摘完 = 新标签("heapunlinked");
                    string 失败 = 新标签("heapfail");
                    string 完成 = 新标签("heapdone");

                    // ① 先挡"比整堆还大"的需要量:不然 加上块头 与 4 字节取整 会把大数回绕成小数,
                    //    反而"申请成功"了(例如 申请(4294967295) 会绕成一个 12 字节的块)
                    发出($"CMP_IMMEDIATE R0 {_堆大小}");
                    发出($"JG {失败}");
                    // ② 需要量(含块头、4 字节对齐)留在 R0
                    输出装载常量(掩, 0xFFFFFFFCu);
                    发出("ADD_IMMEDIATE R0 3");
                    发出($"AND R0 {掩}");
                    发出($"ADD_IMMEDIATE R0 {块头字节}");
                    // ③ 从空闲表头开始找第一块装得下的
                    发出($"取字 {头} {_空闲表头槽!.Value.名称}");
                    输出装载常量(前, 0u);
                    发出($"{环}:");
                    发出($"JZ {头} {失败}");                              // 链表走完:没有一块装得下
                    堆读字(大小, 头, 4, 暂);
                    发出($"CMP {大小} R0");
                    发出($"JL {前进}");                                   // 本块比需要量小 → 试下一块
                    发出($"MOV {剩} {大小}");
                    发出($"SUB {剩} R0");                                 // 剩 = 本块大小 - 需要量
                    发出($"CMP_IMMEDIATE {剩} {块头字节 + 4}");            // 剩下连"块头 + 一个字"都放不下就不切
                    发出($"JL {不切}");
                    // ④ 切分:新空闲块 = 头 + 需要量
                    堆读字(下一, 头, 0, 暂);
                    发出($"MOV {新块} {头}");
                    发出($"ADD {新块} R0");
                    堆写字(新块, 0, 下一, 暂);                             // 新块接上原来的下一块
                    堆写字(新块, 4, 剩, 暂);
                    输出装载常量(掩, 1u);
                    堆写字(新块, 8, 掩, 暂);                               // 新块空闲
                    堆写字(头, 4, "R0", 暂);                                // 本块缩到正好
                    发出($"MOV {下一} {新块}");                             // 摘链要接上的是**切出来的新空闲块**(它替下本块挂在表上)
                    发出($"JMP {摘链}");
                    // ⑤ 不切:整块给它
                    发出($"{不切}:");
                    堆读字(下一, 头, 0, 暂);
                    // ⑥ 摘链:前 == 0 → 空闲表头 = 下一;否则 [前+0] = 下一
                    发出($"{摘链}:");
                    发出($"JZ {前} {改头}");
                    堆写字(前, 0, 下一, 暂);
                    发出($"JMP {摘完}");
                    发出($"{改头}:");
                    发出($"存字 {下一} {_空闲表头槽.Value.名称}");
                    发出($"{摘完}:");
                    输出装载常量(掩, 0u);
                    堆写字(头, 8, 掩, 暂);                                 // 标记已分配
                    发出($"MOV R0 {头}");
                    发出($"ADD_IMMEDIATE R0 {块头字节}");                   // 返回数据地址
                    发出($"JMP {完成}");
                    // ⑦ 走完还没找到:返回 0(调用点报"堆里放不下")
                    发出($"{前进}:");
                    发出($"MOV {前} {头}");
                    堆读字(下一, 头, 0, 暂);
                    发出($"MOV {头} {下一}");
                    发出($"JMP {环}");
                    发出($"{失败}:");
                    输出装载常量("R0", 0u);
                    发出($"{完成}:");
                    foreach (string r in Enumerable.Reverse(借用)) 发出($"出栈 {r}");
                    发出("返回");
                });
            }
            finally
            {
                _缓冲栈.Pop();
            }
            例程.Insert(0, $"{标签}:");
            _列表例程.AddRange(例程);
            return 标签;
        }

        /// <summary>
        /// 释放子程序(编译期生成一次):`R0` = 数据地址 → `R0` = 状态(0 正常 / 1 非法地址 / 2 重复释放)。
        /// **不在这里报错**:具体哪一行、怎么改,由调用点带着行号说(和池的报错风格一致)。
        /// 校验办法:**从堆首顺着块头一块块走**(块是紧排铺满整堆的),地址正好落在某个块首上才算合法 ——
        /// 这样 `申请(4) + 4` 这种"块中间 / 块外"的地址也能拦住(只比范围是拦不住的)。
        ///
        /// 还回来的块**当场与相邻的空闲块合并**(P33):走这一遍的时候顺手记住**前一块**,
        /// 于是前邻空闲就并进去(前邻本来就在空闲表上,不用再插),后邻空闲就从空闲表摘下来并进来 ——
        /// 这样"申请大块 / 释放小块"反复折腾后,总空闲够就一定拿得出来,不会碎片化到单块不够。
        /// 被并掉的那一小块地址不再是"块首":再拿它去 `释放`,会按"地址落在空闲块里面"报**重复释放**
        /// (以前是"非法地址"——两种都当场停下,合并后这条诊断更贴切)。
        /// </summary>
        private string 确保堆释放例程()
        {
            if (_堆释放标签.Length > 0 && _列表例程.Contains(_堆释放标签 + ":")) return _堆释放标签;
            确保堆();
            string 标签 = 新标签("heapfree");
            _堆释放标签 = 标签;
            var 例程 = new List<string>();
            _缓冲栈.Push(例程);
            try
            {
                自成一段(() =>
                {
                    准备语句占用("R0");
                    string 块 = 新临时();          // 数据地址对应的块首(合并之后 = 合并块的块首)
                    string 游 = 新临时();          // 顺着块头走 / 摘链游标
                    string 大小 = 新临时();        // 本块大小 / 堆末 - 块头
                    string 标 = 新临时();          // 空闲标志 / 原空闲表头 / 摘链前驱
                    string 暂 = 新临时();          // 地址中转
                    string 常量 = 新临时();
                    string 前块 = 新临时();        // 地址上紧邻的前一块(0 = 本块就是第一块)
                    string 后 = 新临时();          // 地址上紧邻的后一块
                    string[] 借用 = [块, 游, 大小, 标, 暂, 常量, 前块, 后];
                    foreach (string r in 借用) 发出($"入栈 {r}");

                    string 环 = 新标签("heapwalk");
                    string 找到 = 新标签("heapfound");
                    string 非法 = 新标签("heapbad");
                    string 重复 = 新标签("heapdup");
                    string 走在空闲块里 = 新标签("heapinfree");
                    string 头插 = 新标签("heapinsert");
                    string 并后 = 新标签("heapmergenext");
                    string 摘环 = 新标签("heapunlink");
                    string 摘到 = 新标签("heapunlinked");
                    string 接表头 = 新标签("heaprelinkhead");
                    string 接完 = 新标签("heaprelinked");
                    string 完成 = 新标签("heapfreed");

                    // ① 块首 = 数据地址 - 12;先按 [堆首, 堆末-12] 粗筛一次(越界与减法回绕都在这里挡住)
                    发出($"MOV {块} R0");
                    发出($"SUB_IMMEDIATE {块} {块头字节}");
                    发出($"取字 {游} {_堆首槽!.Value.名称}");
                    发出($"CMP {块} {游}");
                    发出($"JL {非法}");
                    发出($"取字 {大小} {_堆末槽!.Value.名称}");
                    发出($"SUB_IMMEDIATE {大小} {块头字节}");
                    发出($"CMP {块} {大小}");
                    发出($"JG {非法}");
                    // ② 顺着块头走到这个块首上(对不上就是非法地址);路上记住**前一块**(合并要用)
                    输出装载常量(前块, 0u);
                    发出($"{环}:");
                    发出($"CMP {游} {块}");
                    发出($"JEQ {找到}");
                    发出($"JG {走在空闲块里}");                              // 走过头:地址落在"前块"里面
                    堆读字(大小, 游, 4, 暂);
                    发出($"CMP_IMMEDIATE {大小} {块头字节}");               // 块头坏掉(被写花过)宁可停下
                    发出($"JL {非法}");
                    发出($"MOV {前块} {游}");
                    发出($"ADD {游} {大小}");
                    发出($"JMP {环}");
                    // ③ 空闲标志已经是 1 → 重复释放
                    发出($"{找到}:");
                    堆读字(标, 块, 8, 暂);
                    发出($"CMP_IMMEDIATE {标} 1");
                    发出($"JEQ {重复}");
                    // ④ 先标记本块空闲(取字/存字 靠它拦"释放后读写";被并进来的邻居也保持 1)
                    输出装载常量(常量, 1u);
                    堆写字(块, 8, 常量, 暂);
                    // ⑤ 前邻也空闲 → 并进前邻(前邻本来就在空闲表上,不能再插一次)
                    发出($"JZ {前块} {头插}");
                    堆读字(标, 前块, 8, 暂);
                    发出($"CMP_IMMEDIATE {标} 1");
                    发出($"JNE {头插}");
                    堆读字(大小, 前块, 4, 暂);
                    堆读字(标, 块, 4, 暂);
                    发出($"ADD {大小} {标}");
                    堆写字(前块, 4, 大小, 暂);                             // 前邻变大,本块的头被吸收
                    发出($"MOV {块} {前块}");
                    发出($"JMP {并后}");
                    // ⑥ 前邻不空闲(或者根本没有前邻):头插进空闲表
                    发出($"{头插}:");
                    发出($"取字 {标} {_空闲表头槽!.Value.名称}");
                    堆写字(块, 0, 标, 暂);
                    发出($"存字 {块} {_空闲表头槽.Value.名称}");
                    // ⑦ 后邻也空闲 → 从空闲表摘掉它,并进本块
                    发出($"{并后}:");
                    // 走到这里就是"释放成功"了:下面的几条提前退出都不能把 R0 留成**入参地址**
                    // (调用点拿 R0 当状态看:0 成功 / 1 非法 / 2 重复 —— 漏了这一句会把成功的释放误报成非法)
                    输出装载常量("R0", 0u);
                    堆读字(后, 块, 4, 暂);
                    发出($"ADD {后} {块}");
                    发出($"取字 {大小} {_堆末槽!.Value.名称}");
                    发出($"CMP {后} {大小}");
                    发出($"JEQ {完成}");                                    // 本块就是最后一块:没有后邻
                    发出($"JG {完成}");                                     // 不该发生:保守处理
                    堆读字(标, 后, 8, 暂);
                    发出($"CMP_IMMEDIATE {标} 1");
                    发出($"JNE {完成}");                                    // 后邻不是空闲:没什么可并的
                    // 走一遍空闲表找 "后" 的前驱(找不到就不动它 —— 宁可少并,不许把表弄乱)
                    发出($"取字 {游} {_空闲表头槽!.Value.名称}");
                    输出装载常量(标, 0u);
                    发出($"{摘环}:");
                    发出($"JZ {游} {完成}");
                    发出($"CMP {游} {后}");
                    发出($"JEQ {摘到}");
                    发出($"MOV {标} {游}");
                    堆读字(游, 游, 0, 暂);
                    发出($"JMP {摘环}");
                    发出($"{摘到}:");
                    堆读字(大小, 后, 0, 暂);                               // 后邻的下一块
                    发出($"JZ {标} {接表头}");                              // 前驱是 0 → 后邻就是表头
                    堆写字(标, 0, 大小, 暂);
                    发出($"JMP {接完}");
                    发出($"{接表头}:");
                    发出($"存字 {大小} {_空闲表头槽.Value.名称}");
                    发出($"{接完}:");
                    堆读字(大小, 块, 4, 暂);
                    堆读字(标, 后, 4, 暂);
                    发出($"ADD {大小} {标}");
                    堆写字(块, 4, 大小, 暂);                                // 本块变大,后邻的头被吸收
                    发出($"JMP {完成}");
                    // ⑧ 地址落在空闲块里面(不是块首):最像"这块已经还回去了"
                    发出($"{走在空闲块里}:");
                    发出($"JZ {前块} {非法}");
                    堆读字(标, 前块, 8, 暂);
                    发出($"CMP_IMMEDIATE {标} 1");
                    发出($"JEQ {重复}");
                    发出($"{非法}:");
                    输出装载常量("R0", 1u);
                    发出($"JMP {完成}");
                    发出($"{重复}:");
                    输出装载常量("R0", 2u);
                    发出($"{完成}:");
                    foreach (string r in Enumerable.Reverse(借用)) 发出($"出栈 {r}");
                    发出("返回");
                });
            }
            finally
            {
                _缓冲栈.Pop();
            }
            例程.Insert(0, $"{标签}:");
            _列表例程.AddRange(例程);
            return 标签;
        }

        /// <summary>
        /// 堆动作(单独成句):`释放(p);` / `存字(p, 偏移, 值);`。
        /// 是堆动作就发出指令并返回 true;**报错文案与行号都放在这里**(例程只返回状态,这样行号才带得准)。
        /// `申请`/`取字` 单独成句没有意义(结果丢了)—— 给出该往哪儿写的提示。
        /// </summary>
        private bool 试处理堆动作(string 内容, int 行号)
        {
            string 文本 = 内容.Trim();
            int 左括号 = 文本.IndexOf('(');
            if (左括号 <= 0) return false;
            string 名 = 文本[..左括号].Trim();
            bool 是释放 = 名 == "释放" || 名.Equals("free", StringComparison.OrdinalIgnoreCase);
            bool 是存字 = 名 == "存字" || 名.Equals("storeword", StringComparison.OrdinalIgnoreCase);
            bool 是取字 = 名 == "取字" || 名.Equals("loadword", StringComparison.OrdinalIgnoreCase);
            bool 是申请 = 名 == "申请" || 名.Equals("alloc", StringComparison.OrdinalIgnoreCase);
            if (!(是释放 || 是存字 || 是取字 || 是申请)) return false;
            if (是用户函数名(名)) return false;                  // 用户自己定义了同名函数:走正常调用那条路
            if (!文本.EndsWith(')'))
                throw 报错(行号, $"{名} 这句写法不对:'{内容}'。括号要配平,整句末尾才是分号",
                    $"malformed heap call: '{内容}'");
            // **单独成句的堆动作也是一条语句**:进来先把临时寄存器池按本句重置。
            // 不重置的话 `生成存字` 结尾那句"只留写进去的那个值"会把值寄存器留在占用表里,
            // **一条语句漏一个** —— 实测连着写 11 条 `存字(p, 偏移, 值);` 就报
            // "这一句太复杂了:临时寄存器用光了"(G4 批 4 写 `转储` 自检夹具时撞上的)。
            准备语句占用(内容);
            var 参数 = 切实参(文本[(左括号 + 1)..^1]);
            if (是释放)
            {
                if (参数.Count != 1)
                    throw 报错(行号, $"释放 要一个参数(申请 返回的那个地址):释放(p);收到 {参数.Count} 个 —— '{内容}'",
                        "free() takes exactly one argument");
                生成释放(参数[0], 行号, 内容);
                return true;
            }
            if (是存字)
            {
                if (参数.Count != 3)
                    throw 报错(行号, $"存字 要三个参数:存字(p, 偏移, 值);收到 {参数.Count} 个 —— '{内容}'",
                        "storeword() takes three arguments");
                生成存字(参数[0], 参数[1], 参数[2], 行号, 内容);
                return true;
            }
            throw 报错(行号, 是取字
                ? $"取字 的结果要用起来:赋值给变量或写进表达式(例如 `整数 值 = 取字(p, 0);`);单独成句结果就丢了 —— '{内容}'"
                : $"申请 的结果要用起来:赋值给一个 `地址` 变量(例如 `地址 p = 申请(32);`);单独成句那块内存就找不到了 —— '{内容}'",
                是取字 ? "loadword() must be used as a value" : "alloc() must be used as a value");
        }

        /// <summary> H72(第353批):一个名字是不是"堆动作"(中文名或英文别名);不是给 null </summary>
        private static string? 到堆动作(string 名)
        {
            if (名 is "申请" || string.Equals(名, "alloc", StringComparison.OrdinalIgnoreCase)) return "申请";
            if (名 is "取字" || string.Equals(名, "loadword", StringComparison.OrdinalIgnoreCase)) return "取字";
            if (名 is "存字" || string.Equals(名, "storeword", StringComparison.OrdinalIgnoreCase)) return "存字";
