                发出($"CMP {容量} {需要}");
                发出($"JL {扩}");
                发出($"JMP {够}");
                发出($"{扩}:");
                发出($"CALL {确保列表扩容例程(串)}");
                发出读变量(容量, 串.容量槽!.Value);
                发出读变量(需要, 需要槽);
                发出($"ADD_IMMEDIATE {需要} 1");       // 同上:末尾那个 0 也要有地方放
                发出($"CMP {容量} {需要}");            // 还小就再来一轮
                发出($"JL {扩}");
                发出($"{够}:");

                // 地址在扩容后可能变过 → 现在才取
                string 目标址 = 新临时();
