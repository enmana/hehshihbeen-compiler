        /// <summary> 列表动作(单独成句):`分数.添加(值)` / `分数.清空()` / `筐.数.添加(值)`;是列表动作就处理掉并返回 true </summary>
        private bool 试处理列表动作(string 内容, int 行号)
        {
            string 文本 = 内容.Trim();
            // 从**右边**切:最后一个 `.` 之前是列表的名字(`分数` 或 `筐.数`),之后是动作名。
            // 字段里的列表(H1 第四件)名字里本来就带点 —— 老写法"切第一个点"会把动作名认成 `数.添加`。
            int 左括号 = 文本.IndexOf('(');
            if (左括号 <= 0 || !文本.EndsWith(')')) return false;
            string 动作全名 = 文本[..左括号].Trim();
            int 点 = 动作全名.LastIndexOf('.');
            if (点 <= 0) return false;
            string 基名 = 动作全名[..点].Trim();
            string 动作 = 中间层指令C.到方法中文名(动作全名[(点 + 1)..].Trim()) ?? 动作全名[(点 + 1)..].Trim();
            string 实参串 = 文本[(左括号 + 1)..^1].Trim();
            // `出` 参数(`字符串 出 名字`):动作只有 .清空() —— 把调用方那个头的长度清 0
            if (是出参(基名))
            {
                if (动作 == "长度")
                    throw 报错(行号, $"长度 要用在表达式里(例如 测试输出({基名}.长度()));单独成句没有意义",
                        "长度() must be used inside an expression");
                if (动作 != "清空")
                    throw 报错(行号, $"字符串只有 .长度() 和 .清空() 两个动作,没有 .{动作}()",
                        $"unsupported member .{动作}()");
                准备语句占用(内容);
                var 绑定 = 查变量(基名)!.Value;
                自成一段(() =>
                {
                    string 头 = 出头地址(绑定);
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    string 长度址 = 基址加偏移(头, 4);
                    发出($"存字间接 {零} {长度址}");
                    string 数据 = 读头里的字(头, 0);
                    发出($"存储间接寻址 {零} {数据}");       // 首字节也写 0:输出/老库"打到 0 为止"照样是空串
                });
                return true;
            }
            // 具名列表(`分数`)或**结构字段里的列表**(`筐.数`):取不到就交给别的路(不在这儿抢着报错)
            var 列表 = 查列表(基名) ?? 解析列表引用(基名, 行号);
            if (列表 is null)
            {
                // 名字是**认得的变量**、却既不是列表也不是数组 —— 那就是"拿标量当列表用"。这条不许落到
                // "未定义的函数/方法"那句上(用户 2026-09-21 实测:`短整数 分数;` 写 `分数.添加(85)`,
                // 原文案只说"未定义的函数/方法",看不出真因是"声明少写了 `[]`")。
                // **只对三个真方法名**(添加/清空/长度)生效:`原点.x = 内部加()` 这种"右边带调用"的式子
                // 也会切出个假动作名,那类照旧交回别的路(不然赋值语句全被这条误伤)。
                if (动作 is "添加" or "清空" && 查变量(基名) is { 是数组: false, 是列表: false, 是数组切片: false })
                    throw 报错(行号, $"'{基名}' 不是列表,没有 .{动作}() —— 要当列表用,声明时写成 `整数 {基名}[];`" +
                        $"(个数不写 = 列表,见示例06);标量变量只能直接赋值",
                        $"'{基名}' is not a list: declare it as '{基名}[]' to use .{动作}()");
                return false;
            }
            switch (动作)
            {
                case "添加":
                    if (列表.是字符串)
                        throw 报错(行号, $"字符串 '{基名}' 不能用 .添加():要改内容直接赋值(例如 {基名} = \"新的内容\";),要改某一个字节用 {基名}[下标] = '字'",
                            $"strings do not support .添加(): assign or index instead");
                    输出列表添加(列表, 实参串, 行号);
                    return true;
                case "清空":
                    输出列表清空(列表, 行号);
                    return true;
                case "长度":
                    throw 报错(行号, $"长度 要用在表达式里(例如 测试输出({基名}.长度()));单独成句没有意义",
                        "长度() must be used inside an expression");
                default:
                    throw 报错(行号, 列表.是字符串
                        ? $"字符串只有 .长度() 和 .清空() 两个动作,没有 .{动作}()(要拼接/查找这类方法,等下一阶段照 .NET 的 String 逐个加)"
                        : $"列表只有 .添加(值) / .长度() / .清空() 三个动作,没有 .{动作}()",
                        $"unsupported member .{动作}()");
            }
        }

        /// <summary> 运行期报错:错误号写进隐藏的"错误槽"再停机(IDE/命令行跑完读它给出明确错误,不悄悄踩坏数据)</summary>
        private void 报错停机(int 行号, string 说明) => 记运行期错误(行号, 说明, 停机: true);

        /// <summary>
        /// 运行期错误的公共实现。`停机 = false` 时**只记不停** —— 测试断言失败要用它:
