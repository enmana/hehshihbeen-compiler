        /// <summary>
        /// 递归深度上限:软栈用掉八成的位置(数据段里的隐藏槽,程序开头算好)。
        /// 函数入口拿 FP 跟它比一比 —— 超过就报"递归太深"并停机,而不是悄悄撞到别的东西上。
        /// 热路径只多 3 条指令(读限值 / 比较 / 跳过去),报错那段是冷代码。
        /// </summary>
        private 变量槽定义? _栈限槽;

        private 变量槽定义 确保栈限()
        {
            if (_栈限槽 != null) return _栈限槽.Value;
            _栈限槽 = 新槽(4);
            var 初始化 = new List<string>();
            var 存档 = _语句占用;
            _缓冲栈.Push(初始化);
            try
            {
                _语句占用 = [];
                自成一段(() =>
                {
                    string t = 新临时();
                    发出($"取地址 {t} {_软栈槽}");                       // 软栈底(FP 从这里往上长)
                    int 限 = 软栈大小 * 8 / 10;                          // 用到八成就算太深
                    发出($"ADD_IMMEDIATE {t} {限}");
                    发出($"存字 {t} {_栈限槽!.Value.名称}");
                });
            }
            finally
            {
                _缓冲栈.Pop();
                _语句占用 = 存档;
                _语句常量 = null;
            }
            插入主程序开头(初始化);
            return _栈限槽.Value;
        }

        /// <summary> 函数入口的"递归深度"检查(3 条指令 + 一段冷代码) </summary>
        private List<string> 生成栈检查序言(int 行号)
        {
            准备语句占用("");
            var 行 = new List<string>();
            string 限 = 新临时();
            行.Add($"LOAD_WORD {限} {确保栈限().名称}");
            行.Add($"CMP {帧指针寄存器} {限}");
            string 够 = 新标签("栈够");
            行.Add($"JL {够}");                       // FP 还没到上限 → 正常往下走
            var 报错行 = new List<string>();
            _缓冲栈.Push(报错行);
            try
            {
                报错停机(行号, $"递归(或调用)太深了:软栈用掉 {软栈大小 * 8 / 10} 字节(共 {软栈大小})就停下。" +
                    $"把递归改成循环,或者少套几层调用");
            }
            finally { _缓冲栈.Pop(); }
            行.AddRange(报错行);
            行.Add($"{够}:");
