        /// <summary>
        /// 把各段接到"某个字符串**头**"后面(头地址在寄存器里:数据地址 / 长度 / 容量 @ 0/4/8)。
        /// 容量不够就 ×2 从池里换一块(老内容搬过去,新的数据地址与容量写回头里);末尾补一个 0。
        /// 用法只有一个:**`出` 参数**(`拼接到(结果, …)`,那个"结果"住在调用方那边)。
        /// </summary>
        private void 发出拼接到头地址(string 头址, List<拼接段> 段们, int 行号, string 原文)
        {
