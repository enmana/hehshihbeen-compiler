        /// <summary> 这个名字是不是"字符串参数"(`字符串 名` / `字符串 出 名`) </summary>
        private bool 是字符串参数(string 名) =>
            查变量(名.Trim()) is { 引用类型: { 是字符串: true } };

        /// <summary> 这个名字是不是**可写的**字符串参数(`字符串 出 名`):槽里装的是"调用方字符串头的地址" </summary>
        private bool 是出参(string 名) =>
            查变量(名.Trim()) is { 引用类型: { 是字符串: true, 出参数: true } };

        // ---------------- 可写字符串参数(`字符串 出 名`)的头 ----------------
        //
        // 调用方把自己的 `字符串` 变量**三个字**的头(数据地址 / 长度 / 容量,紧挨着)的地址递进来,
        // 参数槽里装的就是这个头地址。函数里读内容 = 读 头+0 / 头+4;
        // 写回(赋值、拼接、清空)直接改这个头 —— 变长时容量一起长大,改动**当场**落在调用方那份上。

        /// <summary> 可写字符串参数的头地址(参数槽里装的就是它) </summary>
        private string 出头地址(变量绑定C 绑定)
        {
            string 头 = 新临时();
            发出读变量(头, 绑定.槽);
            return 头;
        }

        /// <summary> 读"头 + 常量偏移"里的一个 4 字节字(0 = 数据地址,4 = 长度,8 = 容量) </summary>
        private string 读头里的字(string 头, int 偏移)
        {
