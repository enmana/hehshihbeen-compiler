        /// <summary>
        /// 字段列表(住堆)的扩容:容量翻倍换个更大的块,老内容搬过去,旧块 `释放` 还回堆。
        /// 头一回(容量 0,还没要过块)给 `初始列表容量` 个 —— 与池里那条路的起点一致。
        /// 头的地址每次都按引用链**现算**(扩容之后地址还可能变,不许存)。
        /// </summary>
        private void 生成字段列表扩容(列表绑定C 列表, int 行号, string 原文)
        {
            int 宽 = 列表.类型.元素宽;
            自成一段(() =>
            {
                (_语句占用 ??= []).Add("R0");   // 这一段要 CALL 堆申请/释放(R0 是入参出参)
                var 快照 = 记占用();
                string 头 = 列表头地址省着算(列表, 行号, 原文);
                string 旧块 = 新临时();
                发出间接读(旧块, 头, 4);
                string 旧容量 = 新临时();
                发出间接读(旧容量, 基址加偏移(头, 列表头容量偏移), 4);
                string 新容量 = 新临时();
                string 先到头 = 新标签("字段列表首块"), 容量定了 = 新标签("字段列表容量定");
                发出($"JZ {旧容量} {先到头}");
                发出($"MOV {新容量} {旧容量}");
                发出($"ADD {新容量} {新容量}");                        // 翻倍(与池里那条路一致)
                发出($"JMP {容量定了}");
                发出($"{先到头}:");
                输出装载常量(新容量, (uint)初始列表容量);
                发出($"{容量定了}:");
                string 需要 = 新临时();
                发出($"MOV {需要} {新容量}");
                缩放下标(需要, 宽);
                string 新块 = 生成申请按寄存器(需要, 行号, 列表.名称, "字段里的列表");
                string 长度 = 新临时();
                发出间接读(长度, 基址加偏移(头, 列表头长度偏移), 4);
                string 要拷 = 新临时();
                发出($"MOV {要拷} {长度}");
                缩放下标(要拷, 宽);
                发出字节拷贝(旧块, 新块, 要拷);                        // 老内容搬过去(长度是运行期的)
                还占用(快照, 头, 旧块, 新容量, 新块);                 // 旧容量/需要/长度/要拷 用完就还
                发出间接写(新块, 头, 4);                                // 头 +0 = 新块
                发出间接写(新容量, 基址加偏移(头, 列表头容量偏移), 4);   // 头 +8 = 新容量
                // 还旧块放在**最后**:`释放` 报错那一段是"自成一段",会把临时寄存器再分一遍 ——
                // 所以上面几个还要用的寄存器先用完,别留在它后面
                string 还完了 = 新标签("字段列表还完");
                发出($"JZ {旧块} {还完了}");                            // 还没要过块:没有旧块可还
                生成释放按寄存器(旧块, 行号, 列表.名称, "字段里的列表");
                发出($"{还完了}:");
            });
        }

        /// <summary>
