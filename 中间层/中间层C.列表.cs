        /// <summary> `字符串 s = "…";` / `字符串 s;`(空串) </summary>
        private void 字符串声明(string 内容, string 首词, int 行号, int 伪行 = -1)
        {
            string 余下 = 内容[首词.Length..].Trim();
            int 等号 = 余下.IndexOf('=');
            string 名称 = (等号 >= 0 ? 余下[..等号] : 余下).Trim();
            string 初值文本 = 等号 >= 0 ? 余下[(等号 + 1)..].Trim() : "";
            if (名称.Length == 0)
                throw 报错(行号, "字符串声明缺少名字:写成 `字符串 名字 = \"内容\";`", "string declaration needs a name");
            if (!标识符全词正则.IsMatch(名称))
                throw 报错(行号, 名称.Contains('[')
                        ? $"字符串不能声明成数组: '{名称}'。要一段文字就用普通变量(字符串 名字 = \"内容\";);" +
                          $"要固定长度的缓冲区就写 字符 名字[16]; 再按字节填(数组的初值只收常量,收不了这一串文字)"
                        : $"字符串名非法: '{名称}'(只要一个名字,不带下标/点/空格)",
                    $"bad string name: '{名称}'");
            if (等号 >= 0 && 初值文本.Length == 0)
                throw 报错(行号, $"声明 '{名称}' 的等号右边是空的:要么写个初值(字符串 {名称} = \"…\";),要么把等号去掉(字符串 {名称};)",
                    $"string '{名称}' has nothing after '='");

            // 模块里的顶层字符串也带前缀(`数学.问候`);函数里的局部/参数不带
            string 注册名 = 声明注册名(名称);
            // "已预登记"协议(Q1b):预扫已经为这一行开好头三槽、登记过绑定了
            bool 已预登记 = !_预扫声明中 && 伪行 >= 0 && _当前函数 == null && 已预登记全局到本行(注册名, 伪行);
            if (_预扫声明中 && 当前作用域.ContainsKey(注册名)) return;   // 重名(字符串本来就不查重):预扫只收第一处
            var 串 = 已预登记 ? _列表表[名称] : 字符串分配(名称, 行号, 只分配: _预扫声明中);
            记私有(注册名);
            if (!已预登记)
            {
                当前作用域[注册名] = new 变量绑定C(串.长度槽, null, null, 串.类型);
                登记名字(注册名, 串.长度槽, null, null, null, 行号, 列表: 串);
            }
            if (_预扫声明中) { _已预登记全局[注册名] = 伪行; return; }   // 初值留在原语句那一句上,预扫绝不发它
            // 预扫那趟只开了头三槽(没从池里要地方):池初始化这句补在这儿 —— 顺序与原样一字不差
            if (已预登记) 生成动态列表初始化(串, 行号);
            if (等号 >= 0) 发出字符串赋值(注册名, 初值文本, 行号, 内容);
        }

        /// <summary>
