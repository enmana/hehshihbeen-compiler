        /// </summary>
        private string 确保列表扩容例程(列表绑定C 列表)
        {
            if (列表.扩容标签.Length > 0) return 列表.扩容标签;
            string 标签 = 新标签("列表扩容");
            列表.扩容标签 = 标签;
            var 例程 = new List<string>();
            _缓冲栈.Push(例程);              // 例程先写进临时缓冲(和函数正文一样,最后统一追加到程序末尾)
            try
            {
              自成一段(() =>
              {
                int 宽 = 列表.类型.元素宽;
                string 新容量 = 新临时();
                发出读变量(新容量, 列表.容量槽!.Value);
                发出($"ADD {新容量} {新容量}");                 // 容量翻倍
                string 需要 = 新临时();
                发出($"MOV {需要} {新容量}");
                缩放下标(需要, 宽);                             // 需要的字节数
                string 新块 = 池要一块(需要, 0, 列表.名称, 列表.是字符串);

                string 旧块 = 新临时();
                发出读变量(旧块, 列表.指针槽!.Value);
                // R6-5:`需要拷` 是**元素个数**(下面每轮搬一个元素、地址各走 `宽` 字节)。
                // 以前这里按字节算(`缩放下标(需要拷, 宽)`),而循环又按元素走 —— 于是搬了
                // `个数 × 宽 × 宽` 字节:4 个元素的 8 字节列表搬了 256 字节,把新块后面那片池内存
                // 整片盖掉(实测:`字符串 名单[]` 4→8 扩容那一次,元素 0/1 的字符串被换成后来加进去的)。
                string 需要拷 = 新临时();
                发出读变量(需要拷, 列表.长度槽);
                string i = 新临时();
                输出装载常量(i, 0);
                string 源 = 新临时();
                发出($"MOV {源} {旧块}");
                string 目标 = 新临时();
                发出($"MOV {目标} {新块}");
                string 环 = 新标签("拷贝");
                string 没完 = 新标签("还有");
                string 完 = 新标签("拷贝完");
                发出($"{环}:");
                发出($"CMP {i} {需要拷}");
                发出($"JL {没完}");
                发出($"JMP {完}");
                发出($"{没完}:");
                string 元素 = 新临时();
                发出间接读(元素, 源, 宽);
                发出间接写(元素, 目标, 宽);
                if (宽 > 0) 发出($"ADD_IMMEDIATE {源} {宽}");
                if (宽 > 0) 发出($"ADD_IMMEDIATE {目标} {宽}");
                发出($"ADD_IMMEDIATE {i} 1");
                发出($"JMP {环}");
                发出($"{完}:");
                // R6-5:拷贝完 `目标` 正好停在"没用到的尾部"开头 —— 这一段也得清 0(理由见 生成动态列表初始化)
                if (列表.类型.元素是字符串 || 列表.类型.元素结构 is { 有堆字段: true })
                {
                    string 尾止 = 新临时();
                    发出($"MOV {尾止} {新块}");
                    发出($"ADD {尾止} {需要}");
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    string 尾环 = 新标签("清尾");
                    string 尾完 = 新标签("清尾完");
                    string 尾写 = 新标签("清尾写");
                    发出($"{尾环}:");
                    发出($"CMP {目标} {尾止}");
                    发出($"JL {尾写}");
                    发出($"JMP {尾完}");
                    发出($"{尾写}:");
                    发出间接写(零, 目标, 1);
                    发出($"ADD_IMMEDIATE {目标} 1");
                    发出($"JMP {尾环}");
                    发出($"{尾完}:");
                }
                发出写变量(新块, 列表.指针槽!.Value);
                发出写变量(新容量, 列表.容量槽!.Value);
                发出("返回");
              });
            }
            finally
            {
                _缓冲栈.Pop();
            }
            例程.Insert(0, $"{标签}:");
            _列表例程.AddRange(例程);
            return 标签;
        }

