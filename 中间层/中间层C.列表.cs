                    $"string parameter '{目标名}' cannot be reassigned");
            var 串 = 查列表(目标名);
            if (串 is not { 是字符串: true })
                throw 报错(行号, $"'{目标名}' 不是字符串", $"'{目标名}' is not a string");
            if (源文本.Trim() == 目标名)
                throw 报错(行号, $"'{目标名}' 自己赋值给自己没有意义(而且扩容后地址会变)", $"self-assignment of '{目标名}'");

