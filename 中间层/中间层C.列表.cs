        }

        /// <summary> 函数体里先摆一个占位符,等整个程序展开完再决定要不要换成真的检查(见 收尾栈检查) </summary>
        private static string 栈检查占位(int 行号) => $"@栈检查 {行号}@";

        /// <summary>
        /// 收尾:决定每个函数入口到底留不留"递归深度"检查。
        /// 3 条指令听着不多,可要是**每个**函数都带(再各附一段冷代码),中型工程光序言就胖一圈。
        /// 真需要它的只有"能顺着调用回到自己"的函数(直接/间接递归);叶子函数一律删掉。
        /// 认不出目标的调用(内联汇编里的 CALL 标签)保守处理:那个函数照样保留检查。
        /// </summary>
        private void 收尾栈检查()
        {
            var 标签集 = new HashSet<string>(_函数标签.Values, StringComparer.Ordinal);
            var 边 = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
            var 位置表 = new List<(int 首行, string 名, int 尾行)>();
            string? 当前 = null;
            int 当前首 = 0;
            for (int i = 0; i < _函数正文.Count; i++)
            {
                string 行 = _函数正文[i].Trim();
                if (行.EndsWith(':') && 标签集.Contains(行[..^1]))
                {
                    if (当前 != null) 位置表.Add((当前首, 当前, i));
                    当前 = 行[..^1];
                    当前首 = i;
                    边.TryAdd(当前, new HashSet<string>(StringComparer.Ordinal));
                    continue;
                }
                if (当前 != null && 行.StartsWith("CALL ", StringComparison.Ordinal))
                {
                    string 目标 = 取首词(行[5..]);
                    if (目标.Length > 0) 边[当前].Add(目标);
                }
            }
            if (当前 != null) 位置表.Add((当前首, 当前, _函数正文.Count));
            if (位置表.Count == 0) return;

            // 认得出、但**不是函数**的标签(列表扩容、清零这类编译器自己的例程,或函数里的内部跳转标签):
            // 它们不会回头调用用户函数,不算"认不出的调用"。只有两边都不认识的才保守保留检查。
            var 别的标签 = new HashSet<string>(StringComparer.Ordinal);
            void 收标签(IEnumerable<string> 行表)
            {
                foreach (string 文本行 in 行表)
                {
                    string 干净 = 文本行.Trim();
                    if (干净.EndsWith(':') && 干净.Length > 1) 别的标签.Add(干净[..^1]);
                }
            }
            收标签(_函数正文);
            收标签(_列表例程);
            收标签(_缓冲栈.Peek());
            收标签(_开头初始化);

            var 要查 = new HashSet<string>(StringComparer.Ordinal);
            foreach (var (_, 名, _) in 位置表)
            {
                if (边.TryGetValue(名, out var 出))
                {
                    if (出.Any(目标 => !标签集.Contains(目标) && !别的标签.Contains(目标))) 要查.Add(名);   // 认不出的调用:宁可多查
                    if (能回到自己(名, 边)) 要查.Add(名);
                }
            }

            bool 有检查 = false;
            for (int k = 位置表.Count - 1; k >= 0; k--)   // 倒着走:前面的下标不会被后面的删改挪动
            {
                var (首行, 名, _) = 位置表[k];
                int 标记行 = 首行 + 1;
                if (标记行 >= _函数正文.Count) continue;
                string 行 = _函数正文[标记行].Trim();
                if (!行.StartsWith("@栈检查", StringComparison.Ordinal)) continue;
                if (要查.Contains(名))
                {
                    var 检查 = 生成栈检查序言(int.Parse(行["@栈检查".Length..].Trim('@').Trim()));
                    _函数正文.RemoveAt(标记行);
                    _函数正文.InsertRange(标记行, 检查);
                    有检查 = true;
                }
                else _函数正文.RemoveAt(标记行);
            }
            if (有检查) 确保栈限();   // 一个函数都不查,连那个隐藏槽都不用开
        }

        /// <summary> 顺着调用边能不能回到起点(直接递归 / 互相递归都算) </summary>
        private static bool 能回到自己(string 起点, Dictionary<string, HashSet<string>> 边)
        {
            if (!边.TryGetValue(起点, out var 头)) return false;
            var 待办 = new Stack<string>(头);
            var 走过 = new HashSet<string>(StringComparer.Ordinal);
            while (待办.Count > 0)
            {
                string 现在 = 待办.Pop();
                if (现在 == 起点) return true;
                if (!走过.Add(现在)) continue;
                if (边.TryGetValue(现在, out var 下一批))
                    foreach (string 下一个 in 下一批) 待办.Push(下一个);
            }
            return false;
        }

        /// <summary>
        /// 池:编译器自己开的隐藏区(和"软栈槽"一个套路),动态列表/字符串从这儿要地方。
        ///
        /// **R1-2 起池会自己长大**:这儿只定两件事 —— `_池大小`(一开始多大,工程文件 `池` 可配)、
        /// 以及"最多长到哪儿"= 运行内存末尾 − 给硬件栈留的余量(编译期常量,见 `池要一块`)。真长不下了才报错停机。
        /// 为此池的槽**排在数据段最后**(见 `运行`):它上面那块内存没有别的变量,正是留给它长的;
        /// 有软栈时,软栈与池之间再留一块**和软栈一样大的空闲**(`_软栈隙槽`)——
        /// 软栈真溢出时先写那块空闲,与"软栈槽排在最后、后面必须是空闲内存"的老口径同一个道理。
        /// </summary>
        private void 确保池()
        {
            // 被"逐句回滚"(K5 多错误报告)撤掉过就重新开:槽表里找不到说明那次回滚把槽删了
            if (_池槽 != null && _槽序表.Any(x => x.名称 == _池槽.Value.名称)) return;
            _池槽 = 新槽(_池大小);
            _池指针槽 = 新槽(4);
            _池末槽 = 新槽(4);
            // 软栈与池之间那块空闲:只占一个槽号,登记时排在软栈后面、池前面(见 运行)
            if (_软栈槽 != null && _软栈隙槽 == null) _软栈隙槽 = 预留槽号();
            // 池的初始化必须**程序一开头就跑**:池有可能第一次是在某个函数里用到的,
            // 那段代码要是留在函数体里,顶层先分配(函数还没被调用)时读到的池末还是 0 → 误报"池用完了"(真踩过)。
            // 所以走"程序开头跑一次"那份清单(和字符串字面量的数据段初始化同一条路)。
            var 存档 = _语句占用;
            var 初始化 = new List<string>();
            _缓冲栈.Push(初始化);
            try
            {
                自成一段(() =>
                {
                    string t = 新临时();
                    发出($"取地址 {t} {_池槽!.Value.名称}");        // 池首
                    发出($"存字 {t} {_池指针槽!.Value.名称}");
                    string 末 = 新临时();
                    发出($"MOV {末} {t}");
                    发出($"ADD_IMMEDIATE {末} {_池大小}");         // 一开始能用到"池首 + 池大小"
                    发出($"存字 {末} {_池末槽!.Value.名称}");
                    // 硬顶(最多长到哪儿)不占槽:它是**编译期常量**,池要一块那儿用 `比较立即数` 直接比
                });
            }
            finally
            {
                _缓冲栈.Pop();
                _语句占用 = 存档;
                _语句常量 = null;
            }
            插入主程序开头(初始化);
        }

        /// <summary>
        /// 动态列表/字符串刚声明:从池里要 初始容量×元素宽 一块,指针/容量/长度三个字都写好。
        /// **长度也要在这儿写 0**(不能靠"数据段本来就是 0"):函数里的字符串头放在**复用的帧**上,
        /// 第二次调用(或循环里第二次声明)会读到上一次留下的长度 —— 那样拼接就从错误的位置往后写(踩过)。
        /// </summary>
        private void 生成动态列表初始化(列表绑定C 列表, int 行号, int? 给容量 = null) => 自成一段(() =>
        {
            int 容量 = 给容量 ?? 初始列表容量;
            string 需要 = 新临时();
            输出装载常量(需要, (uint)(容量 * 列表.类型.元素宽));
            string 块 = 池要一块(需要, 行号, 列表.名称, 列表.是字符串);
            // R6-5:元素**带堆块**的列表(`字符串 名单[]`,或元素结构里有字符串/列表字段)从池里拿到的块
            // **先整块清零** —— 池是"要一块给一块",新块里是上一轮用过的旧字节;而字符串元素的 `添加`
            // 走"先把这一格当空堆串归还并清空",撞上旧字节就会把**别人的堆块释放掉**(实测:
            // `字符串 名单[]` 第 5 个添加触发 4→8 扩容,头几个元素的字符串被换成了后来加进去的那个)。
            if (列表.类型.元素是字符串 || 列表.类型.元素结构 is { 有堆字段: true })
                生成整块清零(块, 容量 * 列表.类型.元素宽, 需要);
            // 用 发出写变量:这样"头槽在帧里"(函数内的字符串/列表)也能写对 —— 直接 存字 只认数据段标签
            发出写变量(块, 列表.指针槽!.Value);
            string 容量寄存器 = 新临时();
            输出装载常量(容量寄存器, (uint)容量);
            发出写变量(容量寄存器, 列表.容量槽!.Value);
            string 零 = 新临时();
            输出装载常量(零, 0);
            发出写变量(零, 列表.长度槽);
        });

        /// <summary>
        /// 从池里要一块"需要字节"的地方(需要字节 = 寄存器里的运行期值);不够先**自己长大**,长到头才报错停机。
        /// 返回块首地址寄存器。
        ///
        /// 长大(R1-2):池末先 ×2,最多长到硬顶(运行内存末尾 − 给硬件栈留的余量);长到硬顶还装不下就报错。
        /// 每要一块只多一次"下一块 > 池末"的判断(热路),长大那段是冷路。
        /// </summary>
        private string 池要一块(string 需要寄存器, int 行号, string 谁, bool 是字符串 = false)
        {
            确保池();
            if (_当前函数 is { } 用池的函数) 用池的函数.用到池 = true;
            string 块 = 新临时();
            发出($"取字 {块} {_池指针槽!.Value.名称}");
            string 下一块 = 新临时();
            发出($"MOV {下一块} {块}");
            发出($"ADD {下一块} {需要寄存器}");
            string 池末 = 新临时();
            string 再看 = 新标签("池再看");
            string 够 = 新标签("池够");
            string 满了 = 新标签("池满");
            string 能长 = 新标签("池能长");
            string 可以长 = 新标签("池可以长");
            string 定下 = 新标签("池定下");
            // 硬顶是**编译期常量**(运行内存末尾 − 给硬件栈留的余量),所以冷路用 `比较立即数` 就行 ——
            // 一个寄存器都不多占(池/堆那几条路本来就把 15 个临时寄存器用到贴边,多占一个就编不过)
            uint 硬顶 = (uint)Math.Max(0, _内存大小 - 虚拟机C.栈顶保留(_内存大小));
            发出($"{再看}:");
            发出($"取字 {池末} {_池末槽!.Value.名称}");
            发出($"CMP {下一块} {池末}");
            发出($"JG {能长}");              // 下一块 > 池末 = 现在不够(ISA 没有 JLE,用"大于跳"反过来写)
            发出($"JMP {够}");
            发出($"{能长}:");
            发出($"CMP_IMMEDIATE {池末} {硬顶}");
            发出($"JL {可以长}");                              // 池末 < 硬顶 → 还能长
            发出($"JMP {满了}");                               // 已经到硬顶了
            发出($"{可以长}:");
            发出($"JZ {池末} {满了}");                          // 没初始化(池末 = 0)别死循环
            发出($"ADD {池末} {池末}");                         // 池末 = 旧池末 ×2
            发出($"CMP_IMMEDIATE {池末} {硬顶}");
            发出($"JL {定下}");
            发出($"JEQ {定下}");
            输出装载常量(池末, 硬顶);                            // ×2 超了硬顶 → 就用硬顶
            发出($"{定下}:");
            发出($"存字 {池末} {_池末槽.Value.名称}");
            发出($"JMP {再看}");
            发出($"{满了}:");
            string 一开始 = 工程文件C.大小文本(_池大小);
            string 最多 = 工程文件C.大小文本(_内存大小 - 虚拟机C.栈顶保留(_内存大小));
            string 总内存 = 工程文件C.大小文本(_内存大小);
            string 栈余量 = 工程文件C.大小文本(虚拟机C.栈顶保留(_内存大小));
            报错停机(行号, 是字符串
                ? $"字符串 {谁} 长不下了:编译器自己开的池用完了(池一开始 {一开始},会自己长大,最多长到 {最多})。" +
                  $"运行内存总共 {总内存},末尾要给硬件栈留 {栈余量}。" +
                  $"办法:在工程文件里把 `内存` 调大(最大 {工程文件C.大小文本(虚拟机C.最大内存大小)}),或者把内容拆成几个较短的字符串、少留几个同时存在的字符串。"
                : $"列表 {谁} 长不下了:编译器自己开的池用完了(池一开始 {一开始},会自己长大,最多长到 {最多})。" +
                  $"运行内存总共 {总内存},末尾要给硬件栈留 {栈余量}。" +
                  $"办法:在工程文件里把 `内存` 调大(最大 {工程文件C.大小文本(虚拟机C.最大内存大小)}),或者给它写个够大的数(例如 {谁}[200])、把数据拆成几个列表。");
            发出($"{够}:");
            发出($"存字 {下一块} {_池指针槽.Value.名称}");
            return 块;
        }


        /// <summary> 下标×元素宽:2 的幂用 `左移立即数`(P11:一条顶"自己加自己"若干条),不是 2 的幂退回乘法 </summary>
        /// <summary>
        /// 下标寄存器就地缩放到"字节偏移"(× 元素宽)。
        /// 2 的幂走 `左移立即数`(P11)—— 以前用"自加"要 元素宽 的对数次 ADD(×8 要 3 条),现在 1 条;
        /// 元素宽不是 2 的幂(结构大小可以是任意字节)就退回乘法。
        /// **8 字节元素以前没人缩放**(以前只有 1/2/4):结构数组元素宽 8、`字符串 名单[10]` 都靠这一条 ——
        /// 不缩放就会按"第 i 个字节"取,读到的一半是别人的数据(实测:字符串数组运行期下标直接越界崩)。
        /// </summary>
        private void 缩放下标(string 寄存器, int 元素宽)
        {
            if (元素宽 <= 1) return;
            if ((元素宽 & (元素宽 - 1)) == 0)
            {
                int 位 = 0;
                for (int 剩 = 元素宽; 剩 > 1; 剩 >>= 1) 位++;     // ×2^k → 左移 k 位
                发出左移立即数(寄存器, 位);
                return;
            }
            string 宽 = 新临时();
            输出装载常量(宽, (uint)元素宽);
            发出($"MUL {寄存器} {宽}");
        }

        /// <summary> 列表数据首址到寄存器:字段列表读"头里的数据地址";动态列表读指针槽;定容列表就是数据槽的地址 </summary>
        private string 取列表基址(列表绑定C 列表)
        {
            if (列表.是字段列表) return 读列表头字(列表, 列表头数据偏移);
            if (列表.指针槽 is { } 指针)
            {
                string 地址 = 新临时();
                发出读变量(地址, 指针);
                return 地址;
            }
            return 取基址(列表.数据槽.名称);
        }

        // ---------------- 字段里的列表(H1 第四件):头在结构内存里,一切读写走这三个小工具 ----------------
        //
        // 顶层/函数里的列表:头三个字是**具名槽**(数据段标签或 `@FP…`),一个 `取字 槽` 就读到了。
        // 字段里的列表(`筐.数`,以及结构数组元素里的 `表[i].数`):头在**结构内存**里,地址只有运行期才知道 ——
        // 所以先按引用链算"头的地址"(`链地址`,静态偏移与运行期下标它都管),再用 `取字间接 / 存字间接` 读写。
        // 这三个工具是唯一的进出口:凡是碰"列表的头"的代码都走它们,别再从 指针槽/长度槽/容量槽 直接读。

        /// <summary> 字段列表:头 12 字节的地址 → 寄存器 </summary>
        private string 列表头地址(列表绑定C 列表, int 行号 = 0, string 原文 = "")
            => 链地址(列表.字段链!, 行号, 原文.Length > 0 ? 原文 : 列表.名称);

        /// <summary>
        /// 算一次"字段列表的头地址",顺手把算址过程里的中转寄存器还掉(只留住头的那个地址)。
        /// 算址可能要走"运行期下标"(索引寄存器 / 缩放 / 基址三四个),一段代码里要算好几次头 ——
        /// 不还的话 15 个临时寄存器几下就用光(实测:`表[i].数.添加(1);` 这种就撞上了)。
        /// </summary>
        private string 列表头地址省着算(列表绑定C 列表, int 行号 = 0, string 原文 = "")
        {
            var 快照 = 记占用();
            string 头 = 列表头地址(列表, 行号, 原文);
            还占用(快照, 头);
            return 头;
        }

        /// <summary> 读列表头里的一个字(0 = 数据地址 / 4 = 长度 / 8 = 容量)→ 寄存器 </summary>
        private string 读列表头字(列表绑定C 列表, int 字偏移, int 行号 = 0, string 原文 = "")
        {
            if (!列表.是字段列表)
            {
                var 槽 = 字偏移 switch
                {
                    列表头数据偏移 => 列表.指针槽!.Value,
                    列表头长度偏移 => 列表.长度槽,
                    _ => 列表.容量槽!.Value,
                };
                string 老 = 新临时();
                发出读变量(老, 槽);
                return 老;
            }
            var 快照 = 记占用();
            string 头 = 列表头地址(列表, 行号, 原文);
            string 值 = 新临时();
            发出间接读(值, 基址加偏移(头, 字偏移), 4);
            还占用(快照, 值);          // 头的地址与中转寄存器用完就还,只把这个字留着
            return 值;
        }

        /// <summary> 把寄存器里的值写进列表头里的一个字(0 / 4 / 8) </summary>
        private void 写列表头字(列表绑定C 列表, int 字偏移, string 值寄存器, int 行号 = 0, string 原文 = "")
        {
            if (!列表.是字段列表)
            {
                var 槽 = 字偏移 switch
                {
                    列表头数据偏移 => 列表.指针槽!.Value,
                    列表头长度偏移 => 列表.长度槽,
                    _ => 列表.容量槽!.Value,
                };
                发出写变量(值寄存器, 槽);
                return;
            }
            string 头 = 列表头地址省着算(列表, 行号, 原文);
            发出间接写(值寄存器, 基址加偏移(头, 字偏移), 4);
        }

        /// <summary>
        /// 试把这段文本当"列表"取到绑定:先是具名列表(`分数` / 函数里的列表 / `模块.名`),
        /// 再是**结构字段里的列表**(`筐.数` / `盒.内.数` / `表[i].数`)。取不到返回 null(不报错 ——
        /// 不是列表的写法后面自有别的路去管,别在这儿抢着报错)。
        /// </summary>
        private 列表绑定C? 解析列表引用(string 文本, int 行号)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0) return null;
            if (查列表(名) is { } 具名) return 具名;
            if (!名.Contains('.') || !像引用链(名)) return null;
            try { return 解析引用链(名, 行号) is { 字段列表: { } 字段列表 } ? 字段列表 : null; }
            catch (编译异常C) { return null; }
        }

        /// <summary> 元素地址(地址寄存器)= 基址 + 下标寄存器 × 元素宽;下标寄存器会被就地缩放 </summary>
        private string 列表元素地址(列表绑定C 列表, string 下标寄存器)
        {
            缩放下标(下标寄存器, 列表.类型.元素宽);
            string 地址 = 取列表基址(列表);
            发出($"ADD {地址} {下标寄存器}");
            return 地址;
        }

        /// <summary>
        /// 查文本里出现的 `地址(局部变量/参数)` —— 有就报"不能存起来":
        /// 函数一返回帧就作废,存下来的地址迟早指到别人的数据(这是引用最容易踩的坑,能挡的直接挡)。
        /// 注意:**引用参数本身不算**(它里面装的地址指向调用方的对象,比这一层活得久)。
        /// </summary>
        private void 检查地址没被存起来(string 文本, int 行号, string 去向)
        {
            foreach (Match m in 地址引用正则.Matches(文本))
            {
                int 左括号 = m.Index + m.Length - 1;
                int 右括号 = 找匹配右括号(文本, 左括号, 行号);
                string 参数 = 文本[(左括号 + 1)..右括号].Trim();
                if (参数.Length == 0) continue;
                if (解析引用链(参数, 行号) is not { } 链) continue;
                if (链.绑定.是引用) continue;                                  // 引用参数:活的比这一层久
                if (!解析帧槽(链.绑定.槽.名称, out _)) continue;               // 全局/静态:随便存
                throw 报错(行号, $"不能把局部变量/参数的地址存进{去向}:函数一返回那个帧就作废,这地址迟早指到别人的数据。" +
                    $"办法:①存全局变量/结构字段的地址,②或者当场用完就丢(调用期间当参数传是安全的)",
                    $"cannot store the address of a local into {去向}");
            }
        }

        /// <summary> 这个左值是不是"帧内"(局部/参数):是的话把地址存进去不算逃逸 </summary>
        private bool 左值在帧内(string 左侧, int 行号)
        {
            try { return 解析引用链(左侧, 行号) is { } 链 && 解析帧槽(链.绑定.槽.名称, out _); }
            catch { return false; }
        }

        /// <summary>
        /// `分数.添加(值)` —— 放到末尾。放得下就直接写;放不下:动态列表 CALL 共用的"扩容"子程序,
        /// 定容列表(写死数字的)则报错停机。**值先落到临时槽**,因为 CALL 会冲掉寄存器。
        /// </summary>
        private void 输出列表添加(列表绑定C 列表, string 实参串, int 行号)
        {
            if (实参串.Length == 0)
                throw 报错(行号, $"添加 要一个值:{列表.名称}.添加(值)", "添加 needs a value");
            检查地址没被存起来(实参串, 行号, "列表");
            // 元素是**字符串**(`字符串 名单[]`,H1):新元素是"堆里一块数据的地址 + 容量",
            // 不能把 8 个字节直接搬过去(那样两个元素会共用同一块)。走"整份写入一个空堆串字段"那条路。
            if (列表.类型.元素是字符串)
            {
                输出列表添加字符串(列表, 实参串, 行号);
                return;
            }
            // 元素是结构:实参得是"同宽的整块"(结构变量/结构元素),按字节搬进去(大结构也放得下)
            if (列表.类型.元素结构 != null)
            {
                if (解析引用链(实参串, 行号) is { } 块链 && 块链.整块宽 == 列表.类型.元素宽)
                {
                    输出列表添加整块(列表, 块链, 实参串, 行号);
                    return;
                }
                throw 报错(行号, $"{列表.名称} 的元素是结构 {列表.类型.元素结构.名称}({列表.类型.元素宽} 字节),要放一个同宽的结构变量或结构元素",
                    $"list '{列表.名称}' expects a {列表.类型.元素宽}-byte struct element");
            }
            准备语句占用(实参串);
