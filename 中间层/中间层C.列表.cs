                    // "字符串赋值右边要写字符串字面量…",于是 `字符串 一 = 表[0];` 编不过(用户手里那个数组
                    // 自己取不回来)。它没有"长度字"(见 `串字段宽`:字段 8 字节 = 数据地址 + 容量,真正的字节
                    // 在堆里、0 结尾)⇒ 长度**现数**(与 `.长度()` 同一个口径:数到第一个 0)。
                    if (取堆串链(源文本) is { } 堆串链) 源堆串链 = 堆串链;
                    else if (是字符串返回调用文本(源文本, 行号)) 源临时串 = 物化串返回调用(源文本, 行号, 原文);
                    else throw 报错(行号, $"字符串赋值右边要写字符串字面量、另一个字符串(含结构字段 / 数组元素里的字符串),或一个返回字符串的调用:'{原文}'。" +
                        $"例如 字符串 左 = \"你好\"; / 左 = 右; / 左 = 表[0]; / 左 = 格式化(\"{{0}}\", 3);",
