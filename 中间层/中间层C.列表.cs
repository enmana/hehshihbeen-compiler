        }

        /// <summary> `出` 参数 → (数据地址寄存器, 长度来源):长度在调用方的头里,读出来先落进一个新槽 </summary>
        private (string 地址, (uint 常量, 变量槽定义? 槽) 长度) 出参数据与长度(string 名, int 行号, string 原文)
        {
            var 绑定 = 查变量(名.Trim())!.Value;
            string 头 = 出头地址(绑定);
            return (读头里的字(头, 0), 值落新槽(读头里的字(头, 4)));
        }

        /// <summary> 一个寄存器的值落进一个新数据段槽,交回 (0, 槽) 这个"长度来源"形状 </summary>
        private (uint 常量, 变量槽定义? 槽) 值落新槽(string 寄存器)
        {
            var 槽 = 新槽(4);
            发出写变量(寄存器, new 地址位置(槽.名称, 0, 4));
            return (0, 槽);
        }

        /// <summary>
        /// `出`(可写)字符串参数的实参 → 调用方字符串**头的地址**(寄存器)。两条调用路径(表达式里 / 单独成句)共用。
        /// 只接受"拿得到可写头"的东西:本函数里的 `字符串` 变量,或本函数自己的 `出` 参数(转发);
        /// 其余(字面量 / 结构里的字符串字段 / `字符 名字[16]` 缓冲)当场报错并给三条办法。
        /// </summary>
        private string 出实参头地址(string 实参文本, int 行号, string 原文, string 查名, int 第几个)
        {
            string 实 = 实参文本.Trim();
            bool 像名字 = 标识符全词正则.IsMatch(实) || 标识符带点正则.IsMatch(实);
            if (!像名字)
                throw 报错(行号, $"方法 '{查名}' 的第 {第几个} 个参数是 `出`(可写)字符串:" +
                    $"实参要写**一个字符串变量的名字**(不能是表达式/字面量) —— '{实参文本}'",
                    $"argument {第几个} of '{查名}' must be a writable string variable");
            if (查列表(实) is { 是字符串: true } 出目标串) return 头地址(出目标串);
            if (是出参(实)) return 出头地址(查变量(实)!.Value);
            throw 报错(行号, $"方法 '{查名}' 的第 {第几个} 个参数是 `出`(可写)字符串:实参 '{实}' 拿不出一个可写的头。" +
                $"办法:①传一个 `字符串` 变量(先 `字符串 临时;` 再把它传进去,调用完赋给别处);" +
                $"②本函数对应的参数也写成 `字符串 出 …`(转发);" +
                $"③字符串字面量、结构里的字符串字段、`字符 名字[16]` 缓冲都不能直接当 `出` 实参",
                $"argument {第几个} of '{查名}' needs a writable string variable");
        }

        /// <summary>
        /// 字符串实参 → (数据地址寄存器, 长度来源)。字符串的数据在池里,所以传的是**指针槽里的值**;
        /// 字面量直接给数据段地址 + 编译期长度;`出` 参数传的是它头里的数据地址与长度。
        /// </summary>
        private (string 地址, (uint 常量, 变量槽定义? 槽) 长度) 字符串实参地址(string 文本, int 行号, string 原文)
        {
            string 名 = 文本.Trim();
            if (是字符串字面量(名))
            {
                var (槽, 字节数) = 字符串槽(名[1..^1], 行号);
                string 址 = 新临时();
                发出($"取地址 {址} {槽.名称}");
                return (址, ((uint)字节数, null));
            }
            if (是出参(名)) return 出参数据与长度(名, 行号, 原文);
            // `返回 字符串` 的函数调用直接当字符串用:物化到一个隐藏临时串(只调一次),再用它的数据地址与长度
            if (是字符串返回调用文本(名, 行号))
            {
                var 临时串 = 物化串返回调用(名, 行号, 原文);
                string 址 = 新临时();
                发出读变量(址, 临时串.指针槽!.Value);
                return (址, (0, 临时串.长度槽));
            }
            if (是字符串参数(名))
            {
                var 绑定 = 查变量(名)!.Value;
                string 址 = 新临时();
                发出读变量(址, 绑定.槽);                    // 参数槽里装的就是数据地址
                return (址, (0, 绑定.长度槽));
            }
            if (查列表(名) is { 是字符串: true } 串)
            {
                string 址 = 新临时();
                发出读变量(址, 串.指针槽!.Value);           // 数据在池里:从指针槽读当前地址
                return (址, (0, 串.长度槽));
            }
            // 定长缓冲(`字符 名字[16]`,0 结尾)/ 堆串字段·元素(`字符串 名字`,数据在堆里)
            if (试取串视图(名, 行号, 原文) is { } 视图)
                return (视图.数据址, 数到零字节长入槽(视图.数据址, 行号, 原文));
            throw 报错(行号, $"要给字符串参数传一个字符串(字符串变量或字面量):'{原文}'",
                $"a string parameter needs a string argument: '{原文}'");
        }

        // ---------------- 字符串来源:**定长缓冲**与**堆串字段/元素**(2026-10 起) ----------------
        //
        // 语言里一共有四种"一段字符串",读取侧统一成"数据地址 + 字节长":
        //   ① 字面量            数据在数据段(编译期常量长度)
        //   ② `字符串` 变量/参数  数据在池里(长度槽);整名走 串数据与字节长
        //   ③ **定长缓冲** `字符 名字[16]`(也在结构字段/数组元素里):内联 16 字节,末尾的 0 定长度
        //   ④ **堆串** `字符串 名字`(结构字段/数组元素):字段 8 字节 = 数据地址 + 容量,真正的字节在堆里、0 结尾
        // ③④ 的长度都是**数到第一个 0** 数出来的(取值口径只有这一处)。

        /// <summary> 一段"字符串来源"的读视图(定长缓冲 / 堆串) </summary>
        private sealed class 串视图C
        {
            public string 说明 = "";          // 报错里怎么称呼它
            public string 数据址 = "";        // 数据起点(寄存器)
            public string 字节长 = "";        // 字节长(寄存器;数到 0 数为准)
            public bool 定长缓冲;             // true = 内联缓冲(容量是编译期常量/长度槽)
        }

        /// <summary>
        /// 这个引用链是不是"定长缓冲"(一整个 `字符`/`字节` 的**定长**数组:变量、结构字段、数组元素都算)。
        /// 列表不算(容量是运行期的、数据还会搬家);带下标取出来的单个字节更不算。
        /// </summary>
        private static bool 是定长缓冲链(引用链C 链)
            => !链.有运行期下标 && 链.是数组或列表 && !链.是列表 && 链.元素宽 == 1;

        /// <summary> 这个引用链指向的是一个"堆串"(结构里的 `字符串` 字段 / 字符串数组·列表的元素) </summary>
        private static bool 是堆串链(引用链C 链) => 链.是串元素 || 链.下标后是串元素;

        /// <summary>
        /// 这个引用链是**整段**堆串(不是 `记录.名字[下标]` 那种"取出来的一个字",H1)。
        /// 凡是"把整段字符串当字符串用"的地方(输出 / 比较 / 长度 / 赋值 / 取数据地址)都要用它 ——
        /// 用 是堆串链 会把"一个 `文字`"错当成"一整段字符串"。
        /// </summary>
        private static bool 是整段堆串链(引用链C 链) => 是堆串链(链) && !链.串取字;

        /// <summary>
        /// 堆串那个"8 字节小块"的地址(数据地址字 @+0、容量字 @+4)。
        ///   ① 元素地址已经算在手(字符串列表的 `添加`)就直接用;
        ///   ② `记录.名字[下标]`(H1):下标是"第几个文字",**不算址** —— 那个小块就是字段自己,走静态地址;
        ///   ③ 带运行期下标的(`名单[i]`)要运行期算元素地址;其余走 链地址。
        /// </summary>
        private string 串字地址(引用链C 链, int 行号, string 原文)
        {
            if (链.现成元素地址 is { } 现成) return 现成;
            if (链.串取字) return 链地址(链, 行号, 原文);
            return 链.下标后是串元素 ? 链元素地址(链, 行号, 原文) : 链地址(链, 行号, 原文);
        }

        /// <summary>
        /// 试把一段文本认成"堆串字段/元素"(`字符串 名字` / `记录.名字` / `名单[2]` / `名单[i]`);
        /// 不是就返回 null。**只认不出码**(要出码用 试取串视图)。
        /// </summary>
        private 引用链C? 取堆串链(string 文本)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0 || !像引用链(名)) return null;
            try { return 解析引用链(名, 0) is { } 链 && 是整段堆串链(链) ? 链 : null; }
            catch (编译异常C) { return null; }
        }

        /// <summary> 试把一段文本认成"定长缓冲"(`字符 名字[16]`,含结构字段/数组元素);不是就 null,只认不出码 </summary>
        private 引用链C? 试取定长缓冲链(string 文本)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0 || !像引用链(名)) return null;
            try { return 解析引用链(名, 0) is { } 链 && 是定长缓冲链(链) ? 链 : null; }
            catch (编译异常C) { return null; }
        }

        /// <summary>
        /// 试把一段文本当"定长缓冲 / 堆串"读出数据地址与字节长;不是这两种就返回 null(不报错)。
        /// 长度一律**数到第一个 0**(定长缓冲后面可能是别的字段、堆里那块后面是空闲区,都不能越读)。
        /// </summary>
        private 串视图C? 试取串视图(string 文本, int 行号, string 原文)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0 || !像引用链(名)) return null;
            引用链C 链;
            try { 链 = 解析引用链(名, 行号)!; }
            catch (编译异常C) { return null; }
            if (链 is null) return null;
            if (是整段堆串链(链))
            {
                string 字地址 = 串字地址(链, 行号, 原文);
                string 数据址 = 新临时();
                发出间接读(数据址, 字地址, 4);              // 字段 +0:数据地址(0 = 还没分配过,按空串办)
                return new 串视图C
                {
                    说明 = $"字符串 '{名}'",
                    数据址 = 数据址,
                    字节长 = 发出堆串长度(数据址),        // H112 第 2 段:读块首的长度字(不再数 0)
                };
            }
            if (是定长缓冲链(链))
            {
                string 数据址 = 链地址(链, 行号, 原文);
                return new 串视图C
                {
                    说明 = $"定长缓冲 '{名}'",
                    数据址 = 数据址,
                    字节长 = 发出数到零字节(数据址),
                    定长缓冲 = true,
                };
            }
            return null;
        }

        /// <summary>
        /// 堆串的**字节长**:块首那 4 字节(H112 第 1 段起,字段里的"数据地址" = 块首 + 4)。
        /// 数据地址 0 = 还没分配过 ⇒ 0。**它比"数到 0"省寄存器**:不开循环,只用 2 个临时
        /// (数 0 那版要 3 个 + 一圈循环)⇒ 热路径上换过来是**减负**,不是加负。
        /// ⚠ 只对**字符串字段 / 元素**那块用 —— 用户自己 `申请` 的**裸块没有块头**,那条路照旧数 0。
        /// </summary>
        private string 发出堆串长度(string 数据址)
        {
            string 长 = "";
            自成一段保守(() =>
            {
                长 = 新临时();
                输出装载常量(长, 0);
                string 空 = 新标签("堆串长空"), 完 = 新标签("堆串长完");
                发出($"CMP_IMMEDIATE {数据址} 0");
                发出($"JEQ {空}");
                string 指针 = 新临时();
                发出($"MOV {指针} {数据址}");
                发出($"SUB_IMMEDIATE {指针} {堆串长度头}");
                发出间接读(长, 指针, 4);
                发出($"JMP {完}");
                发出($"{空}:");
                发出($"{完}:");
            });
            return 收下临时(长);
        }

        /// <summary>
        /// 从 数据址 起数到第一个 0,数出来的是**字节长**(不含那个 0);地址是 0 就当空串(堆串还没分配过)。
        /// 定长缓冲 / 堆里的那块字符串都靠它定长度(`.长度()` 再按 UTF-8 数文字)。
        /// </summary>
        private string 发出数到零字节(string 数据址)
        {
            string 长 = "";
            自成一段保守(() =>
            {
                长 = 新临时();
                输出装载常量(长, 0);
                string 指针 = 新临时();
                发出($"MOV {指针} {数据址}");
                string 字节 = 新临时();
                string 环 = 新标签("串长环"), 完 = 新标签("串长完");
                发出($"CMP_IMMEDIATE {指针} 0");
                发出($"JEQ {完}");                       // 地址 0:空串(堆串字段还没分配过)
                发出($"{环}:");
                发出间接读(字节, 指针, 1);
                发出($"CMP_IMMEDIATE {字节} 0");
                发出($"JEQ {完}");
                发出($"ADD_IMMEDIATE {长} 1");
                发出($"ADD_IMMEDIATE {指针} 1");
                发出($"JMP {环}");
                发出($"{完}:");
            });
            return 收下临时(长);
        }

        /// <summary>
        /// 数出来的长度落进一个**新数据段槽**(4 字节),交回 (0, 槽) 这个"长度来源"形状 ——
        /// 字符串实参/比较那边要的是 (常量, 槽) 两选一,而数出来的长度是运行期值。
        /// 每次调用新开一个槽(不共用):`a == b` 两边都要长度,共用一个槽会被后一个盖掉。
        /// </summary>
        private (uint 常量, 变量槽定义? 槽) 数到零字节长入槽(string 数据址, int 行号, string 原文)
        {
            var 槽 = 新槽(4);
            string 长 = 发出数到零字节(数据址);
            发出写变量(长, new 地址位置(槽.名称, 0, 4));
            return (0, 槽);
        }

        /// <summary> 整段就是一个字符串字面量吗(`"…"`) </summary>
        private static bool 是字符串字面量(string 文本) =>
            文本.Length >= 2 && 文本[0] == '"' && 文本[^1] == '"' && 找字符串字面量(文本) != null;

        /// <summary>
        /// 字符串**头的地址**(数据地址 / 长度 / 容量 三个字,按 0/4/8 排)。
        /// 头三槽由 字符串分配 连续申请(帧里或数据段),所以取第一个槽的地址就够了 ——
        /// 函数返回字符串时,调用方递的就是这个地址。
        /// </summary>
        private string 头地址(列表绑定C 串) => 取位置地址(new 地址位置(串.指针槽!.Value.名称, 0, 4));

        // ---------------- 字符串:比较(按 UTF-8 字节,与 .NET 的序号比较一致) ----------------

        /// <summary>
        /// 这一段文本是不是"一个字符串"(字面量 / `字符串` 变量 / `字符串` 参数 /
        /// 定长缓冲 `字符 名字[16]` / 堆串字段·元素 `记录.名字`)。
        /// 比较走向、护栏报错、拼接分段都用它 —— 判断口径只有这一处。
        /// **只判断、不出码**:探测用得比取值多得多(见 试取串视图)。
        /// </summary>
        private bool 是字符串操作数(string 文本)
        {
            string 名 = 去外层括号(文本.Trim());
            if (名.Length == 0) return false;
            if (是字符串字面量(名)) return true;
            if (是字符串参数(名)) return true;
            if (查列表(名) is { 是字符串: true }) return true;
            // `返回 字符串` 的函数调用也能直接当字符串用(`输出行(取名字())` / `拼接到(s, 取名字())`)
            if (是字符串返回调用文本(名, 0)) return true;
            if (!像引用链(名)) return false;
            try { return 解析引用链(名, 0) is { } 链 && (是定长缓冲链(链) || 是整段堆串链(链)); }
            catch (编译异常C) { return false; }
        }

        /// <summary>
        /// 找**引号外**最靠左的一个关系符(`>=` `<=` `==` `!=` 优先于 `>` `<`)。
        /// 与数值那边的 找关系符 分开的原因:字符串字面量里可以写 `>` `<` `==`(`s == "a>b"`),
        /// 那些字符不算关系符。
        /// </summary>
        private static (int 位置, string 记号)? 找顶层关系符(string 文本)
        {
            bool 在字符串里 = false;
            for (int i = 0; i < 文本.Length; i++)
            {
                char c = 文本[i];
                if (c == '"') { 在字符串里 = !在字符串里; continue; }
                if (在字符串里) continue;
                if (c == '\'')                                  // 字符字面量('>' 这种)整段跳过
                {
                    i++;
                    while (i < 文本.Length && 文本[i] != '\'')
                    {
                        if (文本[i] == '\\' && i + 1 < 文本.Length) i++;
                        i++;
                    }
                    continue;
                }
                if (i + 1 < 文本.Length)
                {
                    string 双 = 文本.Substring(i, 2);
                    if (双 is ">=" or "<=" or "==" or "!=") return (i, 双);
                }
                if (c is '>' or '<') return (i, c.ToString());
            }
            return null;
        }

        /// <summary>
        /// 探测:这一段是不是**字符串比较**(顶层关系符的任一侧是字符串)。
        /// 只探测、不报错 —— 不是就交给原来那条数值比较的路;"只写了一侧是字符串"留给求值那边报错。
        /// </summary>
        private bool 是字符串比较文本(string 文本)
        {
            string 名 = 去外层括号(文本);
            if (找顶层关系符(名) is not { } 关系) return false;
            string 左 = 名[..关系.位置].Trim();
            string 右 = 名[(关系.位置 + 关系.记号.Length)..].Trim();
            return 是字符串操作数(左) || 是字符串操作数(右);
        }

