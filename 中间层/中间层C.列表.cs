        #region 列表(M8a):`类型 名字[]` = 个数不写,编译器先算、算不出就自己长
        /// <summary> 这个名字后面有没有 `.添加(`(有的话,写死个数的数组也得当"定容列表"办:要长度槽、满了报错)。
        /// 英文别名 `.add(` 一样算(第96批)。 </summary>
        private bool 会用到添加(string 名称)
        {
            var 添加正则 = new Regex(@"(?<![\p{L}\p{N}_.])" + Regex.Escape(名称) + @"\s*\.\s*(添加|add)\s*\(",
                RegexOptions.IgnoreCase);
            foreach (string 行 in _伪行表)
                if (添加正则.IsMatch(行)) return true;
            return false;
        }

        /// <summary> 按名查列表:函数体里声明的列表也要查得到(头放帧里、数据每次执行到声明就从池里要),
        /// 所以按名查列表够用。
        /// 模块里的顶层列表/字符串也带前缀:裸名字先按全局找,找不到再按 `模块.名` 找一次。
        /// **同名局部变量说了算**(Q1b + H76):`_列表表` 是按名字记的全局表,函数里若有一个同名的普通变量
        ///   · 普通变量(`整数 尾` 撞上全局 `字符串 尾`)⇒ 不认识,给 null(不然库函数里的普通局部会被误认成字符串);
        ///   · **非字符串的引用参数**(`整数 表[]` / 结构参数 / `引用 整数 数`)⇒ 也不认识,给 null ——
        ///     不挡的话,"另一个文件里有个 `字符串 数`、这里一个 `引用 整数 数`"会把那一份认成字符串
        ///     (H76 实测:`数 = 0;` 报"字符串赋值右边要写字符串字面量";同一个根因还让"两个模块各有拼字符串的
        ///     函数"一起编时算错,那是 H76 最小复现件);
        ///   · **字符串参数**(`字符串 名` / `字符串 出 名`)⇒ 这一档还是走老路(按名字找):它自己那一份
        ///     由 `查变量` / `字符串实参地址` 那条路取,H77 那一处"同名串参数被别人的同名串顶掉"另案登记。 </summary>
        private 列表绑定C? 查列表(string 名)
        {
            string 键 = 名.Trim();
            if (键.Length == 0) return null;
            for (int i = _作用域栈.Count - 1; i >= 0; i--)
                if (_作用域栈[i].TryGetValue(键, out var 绑定))
                {
                    if (!绑定.是列表) return null;          // 普通变量 / 引用参数(H76 / H77)
                    if (_列表表.TryGetValue(键, out var 同名)) return 同名;   // 局部 / 顶层自己那一份(按名字找,与老路一致)
                    var 本地 = 按槽找列表(绑定.名称);
                    if (本地 != null) return 本地;
                    break;      // 自己那一格反查不到(顶层那种槽名对不上):回落到按名字找
                }
            if (_列表表.TryGetValue(键, out var 列表)) { 校验可取用(键, _当前源行号); return 列表; }
            if (_当前模块.Length > 0 && !键.Contains('.') && _列表表.TryGetValue(_当前模块 + "." + 键, out var 本模块列表))
                return 本模块列表;      // 模块自己人:不算越界
            return null;
        }

        /// <summary> 这个名字在作用域里最近的那个绑定是不是"普通变量"(既不是列表也不是字符串)。
        /// **只认最里面那一层**:`整数 尾` 挡得住全局的 `字符串 尾`。
        /// **非字符串的引用参数也要挡住**(H76):`_列表表` 是按**裸名字**记的全局表,而 `整数 表[]` /
        /// 结构参数 / `引用 整数` 都不在那张表里 —— 不挡的话同名的那个字符串会被认成自己那一份。
        /// 字符串参数这一档**不挡**(它自己那一份要走按名字找那条老路,见 `查列表` 的说明)。 </summary>
        private bool 被非列表变量挡着(string 键)
        {
            for (int i = _作用域栈.Count - 1; i >= 0; i--)
                if (_作用域栈[i].TryGetValue(键, out var 绑定))
                    return !绑定.是列表 && !(绑定.是引用 && 绑定.引用类型!.是字符串);
            return false;
        }

        /// <summary> 按"长度槽的槽名"找回列表(变量绑定里存的是长度槽,不是列表名)</summary>
        private 列表绑定C? 按槽找列表(string 槽名) =>
            _列表表.Values.FirstOrDefault(l => string.Equals(l.长度槽.名称, 槽名, StringComparison.Ordinal));

        /// <summary>
        /// 试算这个列表"最多要用几个":扫描整个文件,数 `.添加(` 次数 / 找最大的常量下标。
        /// 只要有一次 添加 在 `{ }` 里面(循环/条件/函数里),或者出现运行期下标,就算不出来。
        /// </summary>
        private (int 容量, string 说明, bool 需要长大) 试算列表容量(string 名称)
        {
            int 添加次数 = 0, 最大下标 = -1;
            bool 添加在块里 = false, 有运行期下标 = false;
            int 深度 = 0;
            var 添加正则 = new Regex(@"(?<![\p{L}\p{N}_.])" + Regex.Escape(名称) + @"\s*\.\s*(添加|add)\s*\(",
                RegexOptions.IgnoreCase);
            var 下标正则 = new Regex(@"(?<![\p{L}\p{N}_.])" + Regex.Escape(名称) + @"\s*\[([^\]]*)\]");
            foreach (string 行 in _伪行表)
            {
                if (行 == "{") { 深度++; continue; }
                if (行 == "}") { 深度--; continue; }
                foreach (Match m in 添加正则.Matches(行))
                {
                    添加次数++;
                    if (深度 > 0) 添加在块里 = true;
                }
                foreach (Match m in 下标正则.Matches(行))
                {
                    string 索引 = m.Groups[1].Value.Trim();
                    if (uint.TryParse(索引, out uint 常量)) 最大下标 = Math.Max(最大下标, (int)常量);
                    else if (索引.Length > 0) 有运行期下标 = true;
                }
            }

            if (添加次数 > 0 && !添加在块里) return (添加次数, $"编译器数出来最多 {添加次数} 个", false);
            if (添加次数 > 0) return (0, "添加在循环/条件里,数目看运行期", true);
            if (最大下标 >= 0 && !有运行期下标) return (最大下标 + 1, $"编译器按最大的下标算出来要 {最大下标 + 1} 个", false);
            if (有运行期下标) return (-1, "下标是运行期的,编译器算不出要多大", false);
            return (1, "声明了但没见你用", false);
        }

        /// <summary> 声明一个列表:分配槽 + 发初始化代码。返回"登记到作用域里的那个槽"(长度槽) </summary>
        /// <summary>
        /// **函数里的列表**:头(指针 / 长度 / 容量 三个字)放当前帧,数据从池里要一块。
        /// 用法和全局列表完全一样(`.添加() .长度() .清空()`、下标读写);两点差别:
        ///   ① 写了个数只是"一开始给这么多",照样会自己长(数据在池里,不占帧);
        ///   ② 每次执行到声明都会从池里要一块,而**池不回收** —— 别在循环/递归里反复声明大列表。
        /// </summary>
        private 变量槽定义 列表分配局部(string 名称, 列表类型C 类型, int 行号)
        {
            if (_当前函数 is not { } 函数)
                throw 报错(行号, $"列表 '{名称}' 的分配方式不对(内部错误)", "list allocation without a frame");
            const int 头宽 = 12;                     // 指针 / 长度 / 容量
            if (函数.局部偏移 + 头宽 > 函数帧大小)
                throw 报错(行号, $"方法 '{函数.名称}' 的帧超出:放不下列表 '{名称}' —— 列表的头(数据地址 / 长度 / 容量 三个字)" +
                    $"要 {头宽} 字节,已经用到 {函数.局部偏移} 字节,再加就是 {函数.局部偏移 + 头宽} 字节," +
                    $"上限 {函数帧大小} 字节。最常见的办法是把列表挪到函数外面当全局列表用。" + 帧超限改法(),
                    $"frame overflow for list '{名称}'");
            int 起 = 函数.局部偏移;
            函数.局部偏移 += 头宽;
            var 列表 = new 列表绑定C
            {
                名称 = 名称,
                类型 = 类型,
                指针槽 = new 变量槽定义(帧槽(起), 4),
                长度槽 = new 变量槽定义(帧槽(起 + 4), 4),
                容量槽 = new 变量槽定义(帧槽(起 + 8), 4),
            };
            列表.数据槽 = 列表.指针槽!.Value;
            _列表表[名称] = 列表;
            int 容量 = 类型.容量 > 0 ? 类型.容量 : 初始列表容量;
            if (类型.初值个数 > 0 && 类型.容量 <= 0) 类型.容量 = Math.Max(类型.初值个数, 初始列表容量);
            生成动态列表初始化(列表, 行号, 容量);
            // H3 ②:声明时写的字面量初值要**在"从池里要一块"之后**再逐个添加 ——
            // 顺序反了的话 `生成动态列表初始化` 会把那几个元素原地盖掉(实测:局[0] 变成 7、局[1] 变成池指针,
            // 长度只剩添加进去的那一个 ⇒ `局[0]+局[1]+局[2]+长度` 得 10 而不是 27)。踩过。
            if (类型.初值个数 > 0) 发出列表初值添加(列表, 名称, 类型, 行号);
            _编译提示.Add($"列表 {名称}(函数内):头放帧里,数据每次执行到这里就从池里要 {容量} 个 × {类型.元素宽} 字节" +
                $"(不够翻倍;池不回收,别在循环里反复声明)");
            return 列表.长度槽;
        }

        private 变量槽定义 列表分配(string 名称, 列表类型C 类型, int 行号, string? 扫源码用的名 = null, bool 预扫 = false)
        {
            // H3 ②:声明时就写了一串字面量初值的列表(`整数 名[] = [1, 2, 3];`)——
            // 它是**会自己长的列表**(不是定长数组),容量按初值个数定(至少 初始列表容量 个),
            // 声明那一句随后把这几个元素逐个 `添加` 进去 ⇒ 长度 = 初值个数。预扫这趟只开槽、不发码。
            // 注意:**"容量由初值定"只算一次**(预扫那趟就算掉了)⇒ 逐元素添加要看 `类型.初值个数` 自己,
            // 不能再看 `带初值`(那时容量已经 > 0 了,再看就一条都不发 —— 踩过)。
            bool 有初值 = 类型.初值个数 > 0;
            if (有初值 && 类型.容量 <= 0) 类型.容量 = Math.Max(类型.初值个数, 初始列表容量);
            if (类型.容量 <= 0)
            {
                var 试算 = 试算列表容量(扫源码用的名 ?? 名称);
                if (试算.容量 < 0)
                    throw 报错(行号, $"列表 '{名称}' 的大小编译器算不出来:{试算.说明}。" +
                        $"两条路:①写个够大的数(例如 {名称}[100]),②用 .添加() 让它自己长(把 [] 留着不写数)",
                        $"cannot size list '{名称}': {试算.说明}");
                类型.容量 = 试算.容量;
                类型.容量是算出来的 = 试算.容量 > 0 && !试算.需要长大 && !试算.说明.Contains("声明了但没见你用", StringComparison.Ordinal);
                _需要长大 = 试算.需要长大;
                _试算说明 = 试算.说明;
            }
            else _需要长大 = false;
            if (有初值) _需要长大 = true;      // 带初值的列表要在线长大 ⇒ 数据住池里(头三槽)

            var 列表 = new 列表绑定C { 名称 = 名称, 类型 = 类型 };
            if (_需要长大)
            {
                // 动态:数据在池里(装不下就搬家),所以要 指针 + 长度 + 容量 三个槽
                列表.指针槽 = 新槽(4);
                列表.长度槽 = 新槽(4);
                列表.容量槽 = 新槽(4);
                列表.数据槽 = 列表.指针槽.Value;
                // Q1b 预扫:`生成动态列表初始化` 是**初始化代码**,必须留在原语句那一句上(见 声明预扫),
                // 所以预扫这一趟只开槽、不发码;逐句处理到那一句时再按 `列表.动态` 补发。
                if (!预扫)
                {
                    生成动态列表初始化(列表, 行号, 类型.容量);
                    if (有初值) 发出列表初值添加(列表, 名称, 类型, 行号);
                }
                if (有初值)
                    _编译提示.Add($"列表 {名称}:声明时给了 {类型.初值个数} 个初值 → 一开始给 {类型.容量} 个" +
                        $"(× {类型.元素宽} 字节),不够照样翻倍长");
                else
                    _编译提示.Add($"列表 {名称}:{_试算说明} → 自动长大(一开始给 {初始列表容量} 个,不够翻倍;池里要地方)");
            }
            else
            {
                列表.数据槽 = 新槽(类型.容量 * 类型.元素宽);
                列表.长度槽 = 新槽(4);
                if (类型.容量写死)
                    _编译提示.Add($"列表 {名称}:写了容量 {类型.容量} 个(× {类型.元素宽} 字节 = {类型.容量 * 类型.元素宽} 字节);它不自己长,填满就停下报错");
                else if (!_试算说明.Contains("声明了但没见你用", StringComparison.Ordinal))
                    _编译提示.Add($"列表 {名称}:{_试算说明} → 给它 {类型.容量} 个 × {类型.元素宽} 字节 = {类型.容量 * 类型.元素宽} 字节" +
                        (类型.容量是算出来的 ? "(不用你自己算)" : ""));
            }
            _列表表[名称] = 列表;
            return 列表.长度槽;
        }

        private bool _需要长大;
        private string _试算说明 = "";

        private const int 初始列表容量 = 4;      // 动态列表一开始给几个,不够翻倍

        /// <summary>
        /// **H3 ②**:把声明列表时写的那串字面量初值逐个当成 `.添加(值)` 发出去 ——
        /// 生成的机器码与用户自己一句一句写 `名.添加(1);` **完全同一条路**(就地按元素类型求值、
        /// 该深拷的深拷、该长的时候长),只是语句由编译器在"声明那一句"上生成。
        /// 元素是字符串的列表照旧不收初值(每个元素都要在堆里要块,见声明处那条报错)。
        /// </summary>
        private void 发出列表初值添加(列表绑定C 列表, string 列表名, 列表类型C 类型, int 行号)
        {
            if (类型.元素是字符串)
                throw 报错(行号, $"字符串列表 '{列表名}' 不能在声明时给初值(每个元素都要在堆里要块):" +
                    $"声明完再一个个 添加(例如 {列表名}.添加(\"第一项\");)",
                    $"a string list cannot have an initializer: use 添加");
            var 初值们 = 拆方括号初值(类型.初值原文, 行号);
            var 构型 = 类型.元素结构;
            for (int i = 0; i < 初值们.Count; i++)
            {
                string 原文 = 初值们[i].Trim();
                if (原文.Length == 0) continue;
                // H68-2:元素是枚举时成员当场折成常量(顺手做"不许跨枚举"的检查,与标量声明同一条口径)
                原文 = 折成员常量(原文, 行号, 查枚举类型(类型.元素类型名)?.名称 ?? "");
                if (构型 is { } 元素结构)
                {
                    if (!是方括号初值(原文))
                        throw 报错(行号, $"列表 '{列表名}' 的元素是结构 '{元素结构.名称}',初值要按字段写成一串:{原文} → 写成 [{原文}]" +
                            $"(与 `{元素结构.名称} 记录 = [1, 2];` 同一个口径)",
                            $"struct element initializer must look like [{原文}]");
                    校验全字段可取用(元素结构, 行号);
                    var 字段们 = 拆方括号初值(原文, 行号);
                    var 项们 = 折字面量初值(字段们, 元素结构.字段.Count,
                        c => $"列表 '{列表名}' 第 {i + 1} 个元素的初值写了 {c} 个,结构 '{元素结构.名称}' 只有 {元素结构.字段.Count} 个字段",
                        行号,
                        k =>
                        {
                            var 字段 = 元素结构.字段[k];
                            要求字段收数字(字段, 列表名, 行号);
                            return (字段.偏移, 字段.宽度, 字段.类型名);
                        });
                    var 位置 = 新临时槽();
                    发出常量填块(位置.地址文本, 项们);
                    输出列表添加(列表, 位置.地址文本, 行号);
                    continue;
                }
                // 普通标量元素:直接按文本求值添加 —— 与用户自己写 `名.添加(5)` 逐字节同一条路
                输出列表添加(列表, 原文, 行号);
            }
        }

        /// <summary>
        /// 结构字段 / 数组元素里的 `字符串` 占几个字节:**数据地址 + 容量**两个字。
        /// 真正的字节在**堆**里(0 结尾):容量字用来拦"写超了",地址字为 0 表示还没分配过。
        /// 注意这跟"函数里的 `字符串 变量`"不是一回事 —— 那个是池里的动态字符串(头三字:地址/长度/容量)。
        /// </summary>
        private const int 串字段宽 = 8;

        /// <summary> 堆里那块字符串的容量字,在字段里的偏移(紧跟在数据地址后面)</summary>
        private const int 串字段容量偏移 = 4;

        /// <summary>
        /// **堆里那块字符串的"长度字"占几个字节**(H112 第 1 段)。
        /// 块首那 4 字节放**字节长**,字段里的"数据地址"从此指着 **块首 + 4** ⇒
        /// 读数据的人(机器码 / 结构布局 / 数组步长)一个字不用改,只有"分配 / 拷贝 / 释放"要知道这 4 字节。
        /// ⚠ 用户自己 `申请` 出来的**裸块没有这个头** —— 那条路(`取字` / `存字`)不许套这个口径。
        /// ⚠ **热路径**:这一层每一处都**不许新增临时寄存器**(15 个的上限实测会被顶穿,见 `H112决策页.md` §8)——
        /// 一律靠"**就地 ±4** + 把长度字**并进那次块拷贝**"办。
        /// </summary>
        private const int 堆串长度头 = 4;

        /// <summary>
        /// 结构字段里的动态列表占几个字节(H1 第四件):**数据地址 + 长度 + 容量**三个字。
        /// 数据在堆里(与 `字符串` 字段同一口径),所以能 `释放` 还块;`记录 = 0;` 时三个字一起清 0。
        /// </summary>
        private const int 列表字段宽 = 12;
        /// <summary> 字段列表的头里:数据地址 @+0 / 长度 @+4 / 容量 @+8 </summary>
        private const int 列表头数据偏移 = 0;
        private const int 列表头长度偏移 = 4;
        private const int 列表头容量偏移 = 8;

        /// <summary> 开一个槽:在函数里就放**当前帧**(FP 相对,支持递归),在顶层就放数据段。
        /// 字符串的头(指针/长度/容量 三个字)要能声明在函数里,所以需要这个"看情况"的版本。 </summary>
        private 变量槽定义 新槽任意(int 宽度)
        {
            if (_当前函数 is { } 函数)
            {
                if (函数.局部偏移 + 宽度 > 函数帧大小)
                    throw 报错(_伪行号表.Count > 0 ? _伪行号表[^1] : 0,
                        $"方法 '{函数.名称}' 的帧超出 {函数帧大小} 字节(参数+局部太多)", $"function frame overflow in '{函数.名称}'");
                var 定义 = new 变量槽定义(帧槽(函数.局部偏移), 宽度);
                函数.局部偏移 += 宽度;
                return 定义;
            }
            return 新槽(宽度);
        }

        /// <summary>
