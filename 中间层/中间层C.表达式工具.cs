        #region 表达式工具:条件比较与跳转(输出条件跳过/关系符/数值化/输出假跳转)
        /// <summary> 展开条件:**条件为假时跳到 假标签**。写法(优先级从低到高)——
        ///   ?: :三目(`条件 ? 真支 : 假支`,只算被选中的那一支)
        ///   || :两边有一个真就真(左边真就**短路**,右边根本不求值)
        ///   &amp;&amp; :两边都真才真(左边假就短路)
        ///   !  :取反(可以连着写 !!x)
        ///   比较式 :表达式 关系符 表达式(两侧都可以是带括号的算术式子,常量比较编译期定真假)
        ///   真值式 :表达式(非零为真)
        /// **只用符号写法**(&amp;&amp; || !);顺手打了中文"且/或/非"会报一句提醒。
        /// R2-2(2026-09-21)起这一整套**与赋值右侧共用同一棵语法树**(`表达式语法C`),
        /// 不再按字面切左右两半 —— 见下面 输出条件 的注释。
        /// </summary>
        private void 输出条件跳过(string 条件, int 行号, string 假标签)
            => 输出条件(条件, 行号, 假标签, 跳则真: false, 条件);

        /// <summary> 展开条件:**条件为真时跳到 真标签**(和 输出条件跳过 同一套,只是真假对调)</summary>
        private void 输出条件为真(string 条件, int 行号, string 真标签)
            => 输出条件(条件, 行号, 真标签, 跳则真: true, 条件);

        /// <summary>
        /// 条件入口(**R2-2,2026-09-21:先走语法树**)。
        ///
        /// 以前条件这条路**完全绕过 AST**:用 找关系符 在字面上切左右两半,候选只有 `>= &lt;= == != &gt; &lt;`,
        /// 既不看括号深度也不跳字符串字面量、还不知道 `&lt;&lt;` `&gt;&gt;` —— 于是
        /// `如果 (左 &lt;&lt; 2 == 4)` 编不过,而同一句放赋值右边(走真 AST)编得过;`!左 &amp;&amp; 右` 更是
        /// 被当成 `!(左 &amp;&amp; 右)`(实测与赋值右侧不一致)。现在条件与赋值**共用同一个 `表达式语法C`**,
        /// 优先级 / 结合性 / 括号 / 字符串字面量只有一处说法,不可能再漂移。
        ///
        /// 语法树**认不出的老写法**退回老的文本切分路(`输出条件老路`,一个字没动)—— 例如
        /// `取名字().长度()`:词法不认"调用结果再点成员"。这样换实现**不会让既有写法突然编不过**。
        /// </summary>
        private void 输出条件(string 条件, int 行号, string 标签, bool 跳则真, string 原文)
        {
            string 内容 = 去外层括号(条件);
            if (条件里有中文逻辑词(内容))
                throw 报错(行号, $"条件的逻辑运算只认符号写法:用 && || !(没有中文的 且/或/非):'{原文}'",
                    $"use && || ! for boolean logic (no Chinese operators): '{原文}'");
            // H72(第353批):条件里**只换 `地址(...)`** —— 堆调用(申请 / 取字 / 存字 / 释放)
            // 不许在这儿按整条文本预先展开:`&& / ||` 是真短路,提前算等于右边那半句白算
            // (实测 `父 != 0 && 取字(父, 8) == 走` 在 `父 == 0` 时照样去读堆头,当场越界)。
            // 堆动作改由 AST 那一侧懒算(`求值堆动作当值`)。
            内容 = 替换地址取用跳过堆(内容, 行号, 原文);
            表达式节点C 根;
            try { 根 = 表达式语法C.解析(内容); }
            catch (表达式语法异常C)
            {
                输出条件老路(内容, 行号, 标签, 跳则真, 原文);
                return;
            }
            输出条件节点(根, 行号, 标签, 跳则真, 原文);
        }

        /// <summary>
        /// 条件分发(**语法树版**,R2-2):结构、优先级、结合性全照 AST 走 ——
        /// `!` / `&amp;&amp;` / `||` / 比较 / 真值式(含三目)。
        /// 短路语义**与手写汇编一样,ISA 一个字不改**:左边定了整个条件,右边那半句一条指令都不发
        /// (例如 `左 &gt; 0 || 右 &gt; 0`:左成立就直接跳走,右那个函数也不会被调用)。
        ///
        /// `独立寄存器池`:每个"条件原子"(比较 / 真值式)进来时重开一次临时寄存器池
        /// (老路在 输出比较跳转 里就是这么干的 —— 一个原子的临时寄存器用不到下一个原子)。
        /// **但条件嵌在表达式里求值时必须关掉**(见 求值三目节点):那时外面还有活着的寄存器
        /// (例如 `x == (条件 ? 1 : 2)` 里 x 那个),重开池子会把它们当空闲的再发一次 —— 实测踩过:
        /// x 与 条件 挤在同一个寄存器里,整个比较算错。
        /// </summary>
        private void 输出条件节点(表达式节点C 节点, int 行号, string 标签, bool 跳则真, string 原文,
            bool 独立寄存器池 = true)
        {
            // !:取反 = 真假目标对调,一条指令都不用多发(可以连着写 !!,对调两次回到原样)
            if (节点 is 一元节点C { 记号: "!" } 取反)
            {
                输出条件节点(取反.子, 行号, 标签, !跳则真, 原文, 独立寄存器池);
                return;
            }

            // ||:左真 → 整个真(所以 跳则真 时先试左边,不成立再算右边)
            if (节点 is 二元节点C { 记号: "||" } 或)
            {
                if (跳则真)
                {
                    string 再算 = 新标签("OrNext");
                    输出条件节点(或.左, 行号, 再算, 跳则真: false, 原文, 独立寄存器池);
                    发出($"JMP {标签}");
                    发出($"{再算}:");
                    输出条件节点(或.右, 行号, 标签, 跳则真: true, 原文, 独立寄存器池);
                }
                else
                {
                    string 真标签 = 新标签("Or真");
                    输出条件节点(或.左, 行号, 真标签, 跳则真: true, 原文, 独立寄存器池);
                    输出条件节点(或.右, 行号, 标签, 跳则真: false, 原文, 独立寄存器池);
                    发出($"{真标签}:");
                }
                return;
            }

            // &&:左假 → 整个假
            if (节点 is 二元节点C { 记号: "&&" } 且)
            {
                if (跳则真)
                {
                    string 落了空 = 新标签("AndNext");
                    输出条件节点(且.左, 行号, 落了空, 跳则真: false, 原文, 独立寄存器池);
                    输出条件节点(且.右, 行号, 标签, 跳则真: true, 原文, 独立寄存器池);
                    发出($"{落了空}:");
                }
                else
                {
                    输出条件节点(且.左, 行号, 标签, 跳则真: false, 原文, 独立寄存器池);
                    输出条件节点(且.右, 行号, 标签, 跳则真: false, 原文, 独立寄存器池);
                }
                return;
            }

            // 比较:字符串比较整句交给表达式引擎求成 0/1(比较在三态那里展开);数值比较左右各自求值再比
            if (节点 is 二元节点C 比较 && 比较.记号 is "==" or "!=" or "<" or ">" or "<=" or ">=")
            {
                if (是字符串节点(比较.左) || 是字符串节点(比较.右))
                {
                    发出真假跳转节点(节点, 行号, 标签, 跳则真, 原文, 独立寄存器池);
                    return;
                }
                if (独立寄存器池) 准备语句占用(节点);    // 每个比较点都重新分配寄存器池(与老路同一套规矩)
                表达式值 左 = 求值节点(比较.左, 行号, 原文, null, 是根: true);
                // 右边要调函数:左边的值先躲进槽(不然会被 CALL 冲掉)。判据直接用**树的 含调用**,
                // 比老路那个"文本里有没有 `名(`"更准(字符串字面量里的括号不会再误判)。
                if (比较.右.含调用) 左 = 暂存到槽(左);
                表达式值 右 = 求值节点(比较.右, 行号, 原文, null, 是根: true);
                比较跳转(左, 右, 比较.记号, 行号, 标签, 跳则真);
                return;
            }

            // 其余(三目 / 算术式 / 单个变量 …):整棵求成一个值,再"非零为真"
            发出真假跳转节点(节点, 行号, 标签, 跳则真, 原文, 独立寄存器池);
        }

        /// <summary>
        /// 真值式(**语法树版**):非零为真(条件与"字符串比较"共用这一段)。
        /// 字符串比较 / 逻辑运算在表达式引擎里算出来就是 0/1,所以到这儿只剩"判真假"。
        /// </summary>
        private void 发出真假跳转节点(表达式节点C 节点, int 行号, string 标签, bool 跳则真, string 原文,
            bool 独立寄存器池 = true)
        {
            if (独立寄存器池) 准备语句占用(节点);
            表达式值 值 = 落到寄存器(求值节点(节点, 行号, 原文, null, 是根: true));
            if (值.是常量)
            {
                if ((值.常量 != 0) == 跳则真) 发出($"JMP {标签}");        // 条件编译期就定死了
                return;
            }
            if (跳则真)
            {
                // 没有"非零跳转"这条指令:先跟 0 比一下,再用 PSW 的不相等跳
                发出($"CMP_IMMEDIATE {值.寄存器} 0");
                发出($"JNE {标签}");
            }
            else 发出($"JZ {值.寄存器} {标签}");                         // 值为 0 → 假
        }

        /// <summary>
        /// **老的文本切分路(R2-2 起只当兜底)**:`!` 去取反 → 顶层 `||` → 顶层 `&amp;&amp;` → `找关系符` 切两半。
        /// 只有 `表达式语法C` 词法认不出的写法才走这儿(例如 `取名字().长度()`),这样
        /// "换实现"不会变成"既有写法编不过"。这一段一个字没改。
        /// </summary>
        private void 输出条件老路(string 条件, int 行号, string 标签, bool 跳则真, string 原文)
        {
            string 内容 = 去外层括号(条件);
            if (去取反(ref 内容))
            {
                if (内容.Length == 0) throw 报错(行号, $"! 后面没有条件: '{原文}'", $"nothing after '!' in: '{原文}'");
                输出条件老路(内容, 行号, 标签, !跳则真, 原文);   // 取反 = 真假目标对调,一条指令都不用多发
                return;
            }

            // ||:左真 → 整个真(所以 跳则真 时先试左边,不成立再算右边)
            if (找顶层或(内容) is { } 或项)
            {
                (string 左, string 右) = 切两半(内容, 或项);
                要求两侧(左, 右, 或项.记号, 原文, 行号);
                if (跳则真)
                {
                    string 再算 = 新标签("OrNext");
                    输出条件老路(左, 行号, 再算, 跳则真: false, 原文);
                    发出($"JMP {标签}");
                    发出($"{再算}:");
                    输出条件老路(右, 行号, 标签, 跳则真: true, 原文);
                }
                else
                {
                    string 真标签 = 新标签("Or真");
                    输出条件老路(左, 行号, 真标签, 跳则真: true, 原文);
                    输出条件老路(右, 行号, 标签, 跳则真: false, 原文);
                    发出($"{真标签}:");
                }
                return;
            }

            // &&:左假 → 整个假
            if (找顶层且(内容) is { } 且项)
            {
                (string 左, string 右) = 切两半(内容, 且项);
                要求两侧(左, 右, 且项.记号, 原文, 行号);
                if (跳则真)
                {
                    string 落了空 = 新标签("AndNext");
                    输出条件老路(左, 行号, 落了空, 跳则真: false, 原文);
                    输出条件老路(右, 行号, 标签, 跳则真: true, 原文);
                    发出($"{落了空}:");
                }
                else
                {
                    输出条件老路(左, 行号, 标签, 跳则真: false, 原文);
                    输出条件老路(右, 行号, 标签, 跳则真: false, 原文);
                }
                return;
            }

            if (条件里有中文逻辑词(内容))
                throw 报错(行号, $"条件的逻辑运算只认符号写法:用 && || !(没有中文的 且/或/非):'{原文}'",
                    $"use && || ! for boolean logic (no Chinese operators): '{原文}'");

            输出比较跳转(内容, 行号, 标签, 跳则真, 原文);
        }

        /// <summary> 去掉最外层成对的括号(可以套好几层):`((a > 0))` → `a > 0`(条件和表达式都用它) </summary>
        private static string 去外层括号(string 条件)
        {
            string t = 条件.Trim();
            while (t.Length >= 2 && t[0] == '(')
            {
                int 深 = 0, 配对 = -1;
                for (int i = 0; i < t.Length; i++)
                {
                    if (t[i] == '(') 深++;
                    else if (t[i] == ')') { 深--; if (深 == 0) { 配对 = i; break; } }
                }
                if (配对 != t.Length - 1) break;      // 最外层括号没包住整句 → 不动它
                t = t[1..^1].Trim();
            }
            return t;
        }

        /// <summary>
        /// 看起来像"引用链"吗(`记录` / `记录.字段` / `记录[下标].字段` —— 只有名字、点、下标,没有运算符/括号/逗号)。
        /// 探测性调用(试字段访问)先拿它筛一遍:不然 `p.x + p.y`、`表.长度()` 这种表达式会被当成字段名而误报
        /// (实测踩过:"结构 '点' 没有字段 'x + p'")。
        /// </summary>
        private static readonly Regex 像引用链正则 = new(
            @"^[\p{L}_][\p{L}\p{N}_]*(\s*\.\s*[\p{L}_][\p{L}\p{N}_]*|\s*\[[^\[\]]*\])*$",
            RegexOptions.Compiled);

        private static bool 像引用链(string 文本) => 像引用链正则.IsMatch(文本.Trim());
        /// <summary> 去掉开头的 !(可连着好几个),返回"是不是取了反" </summary>
        private static bool 去取反(ref string 内容)
        {
            bool 取反 = false;
            while (true)
            {
                string t = 内容.TrimStart();
                if (t.StartsWith('!')) { 取反 = !取反; 内容 = t[1..].TrimStart(); continue; }
                break;
            }
            return 取反;
        }

        private (int 位置, string 记号, int 长度)? 找顶层或(string 文本) => 找顶层逻辑(文本, "||");
        private (int 位置, string 记号, int 长度)? 找顶层且(string 文本) => 找顶层逻辑(文本, "&&");

        /// <summary> 找**括号外**最靠左的一个逻辑运算符(|| 或 &amp;&amp;);没有就返回 null </summary>
        private static (int 位置, string 记号, int 长度)? 找顶层逻辑(string 文本, string 记号)
        {
            int 深 = 0;
            for (int i = 0; i + 1 < 文本.Length; i++)
            {
                char c = 文本[i];
                if (c == '(') { 深++; continue; }
                if (c == ')') { 深--; continue; }
                if (深 != 0) continue;
                if (c == 记号[0] && 文本[i + 1] == 记号[1]) return (i, 记号, 2);
            }
            return null;
        }

        /// <summary>
        /// 条件里冒出**独立成词**的中文 且/或/非 → 报一句"只认符号写法",别让人对着"无法识别的字符"发呆。
        /// 两边都得是分隔符(空白/括号/运算符)才算 —— 这样变量名里的这些字(如 `非常量`)不会被误报。
        /// </summary>
        private static bool 条件里有中文逻辑词(string 文本)
        {
            static bool 是分隔(char c) => c == '\0' || char.IsWhiteSpace(c) || c is '(' or ')' or ',' or '>' or '<' or '=' or '!' or '&' or '|';
            for (int i = 0; i < 文本.Length; i++)
            {
                char c = 文本[i];
                if (c is not ('且' or '或' or '非')) continue;
                char 前 = i > 0 ? 文本[i - 1] : '\0';
                char 后 = i + 1 < 文本.Length ? 文本[i + 1] : '\0';
                if (是分隔(前) && 是分隔(后)) return true;
            }
            return false;
        }

        private static (string 左, string 右) 切两半(string 文本, (int 位置, string 记号, int 长度) 项)
            => (文本[..项.位置].Trim(), 文本[(项.位置 + 项.长度)..].Trim());

        private void 要求两侧(string 左, string 右, string 记号, string 原文, int 行号)
        {
            if (左.Length == 0 || 右.Length == 0)
                throw 报错(行号, $"'{记号}' 两侧都要有条件: '{原文}'", $"operator '{记号}' lacks an operand: '{原文}'");
        }

        /// <summary>
        /// 文本里有没有"函数/方法调用"(标识符紧跟左括号)。
        /// 条件的比较式要据此决定"左值要不要先躲进槽" —— 右边只要可能调函数,左边的寄存器就保不住。
        /// 宁可多存一次(存了不用只是多一条),也不能漏(漏了就是静默算错)。
        /// </summary>
        private static bool 文本含调用(string 文本)
        {
            for (int i = 1; i < 文本.Length; i++)
                if (文本[i] == '(' && (char.IsLetterOrDigit(文本[i - 1]) || 文本[i - 1] == '_'))
                    return true;
            return false;
        }

        /// <summary> 条件的"到底":比较式 / 真值式(且或非 已经在 输出条件 里短路展开掉了)</summary>
        private void 输出比较跳转(string 条件, int 行号, string 标签, bool 跳则真, string 原文)
        {
            string 内容 = 条件.Trim();
            // 字符串比较:整句交给表达式那条路求成 0/1(比较在三态那里展开),这里只判真假
            if (是字符串比较文本(内容))
            {
                准备语句占用(内容);          // 每个比较点都重新分配寄存器池(与数值比较那条路同一套规矩)
                发出真假跳转(内容, 行号, 标签, 跳则真, 原文);
                return;
            }
            // 地址(...) 先展开;变量/字段的取值交给表达式引擎(用到才读,避免临时寄存器跨 CALL 被冲掉)
            准备语句占用(内容);
            内容 = 替换地址取用(内容, 行号, 原文);

            if (找关系符(内容) is not { } 关系)
            {
                // 真值式:非零为真
                发出真假跳转(内容, 行号, 标签, 跳则真, 原文);
                return;
            }

            string 左原文 = 内容[..关系.位置].Trim();
            string 右原文 = 内容[(关系.位置 + 关系.记号.Length)..].Trim();
            if (左原文.Length == 0 || 右原文.Length == 0)
                throw 报错(行号, $"关系符 '{关系.记号}' 两侧缺操作数: '{条件}'", $"operator '{关系.记号}' lacks an operand: '{条件}'");

            表达式值 左 = 落到寄存器(求值表达式(左原文, 行号, 条件));
            // 第97批(批 13 写浮点库时抓到):右边若含函数调用,左边这个寄存器会被 CALL 冲掉 ——
            //   `如果 (取号(A) != 取号(B))` 曾经两边算完只剩同一个寄存器,比较变成"自己跟自己比"。
            //   和 `求值比较值`(比较当值用)一个规矩:右边要调函数,左边的值先躲进临时槽。
            if (文本含调用(右原文)) 左 = 暂存到槽(左);
            表达式值 右 = 落到寄存器(求值表达式(右原文, 行号, 条件));
            比较跳转(左, 右, 关系.记号, 行号, 标签, 跳则真);
        }

        /// <summary>
        /// 真值式:非零为真(条件与"字符串比较"共用这一段)。
        /// 字符串比较在表达式引擎里算出来就是 0/1,所以到这儿只剩"判真假"。
        /// </summary>
        private void 发出真假跳转(string 内容, int 行号, string 标签, bool 跳则真, string 原文)
        {
            表达式值 值 = 落到寄存器(求值表达式(内容, 行号, 原文));
            if (值.是常量)
            {
                if ((值.常量 != 0) == 跳则真) 发出($"JMP {标签}");        // 条件编译期就定死了
                return;
            }
            if (跳则真)
            {
                // 没有"非零跳转"这条指令:先跟 0 比一下,再用 PSW 的不相等跳
                发出($"CMP_IMMEDIATE {值.寄存器} 0");
                发出($"JNE {标签}");
            }
            else 发出($"JZ {值.寄存器} {标签}");                         // 值为 0 → 假
        }

        /// <summary>
        /// R4-10:**浮点的条件跳转** —— `如果 (左 &lt; 右)` 里任一边是浮点时走这儿。
        ///
        /// <para>一条 `浮点比较`(0x3D)把"关系成不成立"折成 0/1,再拿这个 0/1 跟 0 比一次决定跳不跳
        /// (2 条指令)。为什么绕这一下:ISA 的 `浮点比较` 是**取值**指令(Rd 既是左操作数又是结果),
        /// 没有"浮点比较 + 条件跳转"合体那一条;整数那边能一条 `CMP` 直接跳,是因为有跳转族照着标志位走。</para>
        ///
        /// <para>**为什么必须有它**:整数比较(`CMP` + 有符号 `JG`/`JL`)对 IEEE754 位模式
        /// 只有非负数才单调 —— 有一边是负数就判反。实测两处中招:浮点转文字丢负号(`v &lt; 0.0` 对 -0.99 给假)、
        /// 3D 投影把负坐标判成出视口(整张网格画不出来)。</para>
        /// </summary>
        private void 浮点比较跳转(表达式值 左, 表达式值 右, string 关系符, int 行号, string 标签, bool 跳则真)
        {
            左 = 落到寄存器(左);
            右 = 落到寄存器(右);
            if (指令C.取关系码(关系符, false) is not { } 码)
                throw 报错(行号, $"浮点比较不支持这个记号:`{关系符}`(只支持 == != < > <= >=)",
                    $"unsupported float comparison operator '{关系符}'");
            string 左寄 = 浮点操作数寄存器(左, 行号, $"{关系符}");
            string 右寄 = 浮点操作数寄存器(右, 行号, $"{关系符}");
            string 果 = 选暂存寄存器([左寄, 右寄]);
            发出($"复制 {果} {左寄}");
            发出($"浮点比较 {果} {右寄} {码}");
            // 0/1 与 0 比:相等就是"假"。跳则真 = 不相等才跳。
            发出($"CMP_IMMEDIATE {果} 0");
            输出跳转("!=", 行号, 标签, 跳则真);
        }

        /// <summary>
        /// 比较两个**已经求好值**的操作数,条件成立就跳到 标签。
        /// 条件是"如果 (a &gt; b)",也是"比较当值用"((a &gt; b) 折成 0/1)—— 两处共用这一份:
        /// 常量折叠、有符号偏置、20 位立即数能省的那条,规矩只有一个地方写。
        /// </summary>
        private void 比较跳转(表达式值 左, 表达式值 右, string 关系符, int 行号, string 标签, bool 跳则真)
        {
            // 两侧都是常量 → 编译期定真假,不发比较指令
            if (左.是常量 && 右.是常量)
            {
                if (比较常量(关系符, 左.常量, 右.常量, 左.有符号 || 右.有符号) == 跳则真) 发出($"JMP {标签}");
                return;
            }

            // ── 通用化浮点(R4-10 补):**任一边是浮点 ⇒ 走 `浮点比较` 0x3D,不许走整数 `CMP`** ──
            // 为什么非补不可:`如果 (左 < 右)` 这条**条件跳转**以前只会发整数比较(`CMP` + 有符号
            // `JG`/`JL`)。IEEE754 的位模式**只有非负数**是单调的 —— 一旦有一边是负数,
            // 按整数比就判反(实测:`如果 (v < 0.0)` 对 v = -0.99 给假 ⇒ 浮点转文字丢负号、
            // 3D 投影把负坐标判成"出视口",整张网格一条都画不出来)。
            // "比较当值用"(`(左 < 右)` 折成 0/1)那条路**早就**走 `浮点比较` 了(见 `求值浮点比较值`)——
            // 这一处是漏掉的那一半,现在补齐,两处口径一致。
            if (左.是浮点 || 右.是浮点)
            {
                浮点比较跳转(左, 右, 关系符, 行号, 标签, 跳则真);
                return;
            }

            // 第96批(批 13 写浮点库时抓到):操作数可能是**槽值** ——
            // 函数调用的结果跨 CALL 会被编译器自动暂存到临时槽(`暂存到槽`),
            // 于是 `双_比较(a,b) == 0`、`某调用(...) != 常量` 这类式子拿到的左/右是"在槽里、
            // 没有寄存器"的值。以前这里直接取 `左.寄存器!` 就得到 null,发出来的
            // `CMP_IMMEDIATE <空> 0` 会让汇编器报「CMP_IMMEDIATE 需要两个参数」。
            // 先搬进寄存器,后面照旧。
            左 = 落到寄存器(左);
            右 = 落到寄存器(右);

            // **有符号比较**:把两边都异或 0x80000000,大小关系就从"有符号"变成"无符号"的(2 条异或 ↔ 省掉一整套符号判断)。
            // 任一边是有符号类型就按有符号比(比 C 的隐式转换好懂)。
            if (左.有符号 || 右.有符号)
            {
                左 = 偏置比较值(左);
                右 = 偏置比较值(右);
            }

            string 左寄存器 = 左.是常量 ? 常量操作数寄存器(左.常量) : 左.寄存器!;
            if (右.是常量 && 右.常量 <= 0xFFFFF)
            {
                发出($"CMP_IMMEDIATE {左寄存器} {右.常量}");
                输出跳转(关系符, 行号, 标签, 跳则真);
                return;
            }
            if (右.是常量)   // 大常量:20 位立即数装不下 —— 循环里提过的直接拿常驻寄存器(不再每轮装载)
            {
                发出($"CMP {左寄存器} {常量操作数寄存器(右.常量, 左寄存器)}");
                输出跳转(关系符, 行号, 标签, 跳则真);
                return;
            }
            发出($"CMP {左寄存器} {右.寄存器}");
            输出跳转(关系符, 行号, 标签, 跳则真);
        }

        /// <summary> 常量落进一个寄存器(给比较/调用当操作数用);循环里提过的、本语句装过的直接复用 </summary>
        private string 常量入临时(uint 常量) => 常量操作数寄存器(常量);

        /// <summary>
        /// 依据 PSW(0=等 1=大 2=小) 输出条件跳转。跳则真 = 假:条件为假跳走;真:条件为真跳走。
        /// 两种方向都在这里,是为了让 非/且/或 的对调不用多发一条跳转。
        /// </summary>
        private void 输出跳转(string 关系符, int 行号, string 标签, bool 跳则真)
        {
            if (!跳则真)
            {
                switch (关系符)
                {
                    case "==": 发出($"JNE {标签}"); break;   // 假: 不等
                    case "!=": 发出($"JEQ {标签}"); break;   // 假: 相等
                    case ">":                                   // 真=大; 假=等或小
                        发出($"JEQ {标签}"); 发出($"JL {标签}"); break;
                    case "<":                                   // 真=小; 假=等或大
                        发出($"JEQ {标签}"); 发出($"JG {标签}"); break;
                    case ">=": 发出($"JL {标签}"); break;    // 假=小
                    case "<=": 发出($"JG {标签}"); break;    // 假=大
                    default: throw 报错(行号, $"不支持的关系符: {关系符}", $"unsupported operator: {关系符}");
                }
                return;
            }
            switch (关系符)
            {
                case "==": 发出($"JEQ {标签}"); break;
                case "!=": 发出($"JNE {标签}"); break;
                case ">": 发出($"JG {标签}"); break;
                case "<": 发出($"JL {标签}"); break;
                // ISA 扩容批 4(0x5C / 0x5D):`>=` / `<=` 以前是"大于 + 相等"两条跳转,现在一条就够
                // (PSW 的 0/1/2 三档就是"等 / 大 / 小",`大于等于` = 不是"小")。
                case ">=": 发出($"JGE {标签}"); break;
                case "<=": 发出($"JLE {标签}"); break;
                default: throw 报错(行号, $"不支持的关系符: {关系符}", $"unsupported operator: {关系符}");
            }
        }
