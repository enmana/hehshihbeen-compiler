        /// <summary> 展开到指定寄存器:优先走"寄存器复制/常量装载"两条捷径,其余交给表达式引擎(括号/优先级/多运算符)。 </summary>
        /// <summary>
        /// `目标寄存器 = 右侧`。返回值:**这个值是不是已知"高 16 位为 0"**(C 档的宽槽写入可以省掉截断)。
        /// </summary>
        private bool 输出赋值到寄存器(string 目标寄存器, string 右侧, int 行号, string 文本)
        {
            string 内容 = 右侧.Trim();
            // R = R'(寄存器复制 → MOV)
            if (解析寄存器(内容, out string 复制源))
            {
                发出($"MOV {目标寄存器} {复制源}");
                return false;                     // 用户自己写的寄存器:不知道高半是什么
            }
            // R = 常量(≤20 位 → 1 条;否则拆 LUI+ORI)
            if (解析无符号32(内容, out uint 纯常量))
            {
                输出装载常量(目标寄存器, 纯常量);
                return 纯常量 <= 0xFFFF;
            }

            // 其余:表达式引擎(顶层直接算进目标寄存器,省一条 MOV)
            var 值 = 落到寄存器(求值表达式(内容, 行号, 文本, 目标寄存器));
            if (值.是常量) { 输出装载常量(目标寄存器, 值.常量); return 值.常量 <= 0xFFFF; }
            if (!string.Equals(值.寄存器, 目标寄存器, StringComparison.OrdinalIgnoreCase))
            {
                发出($"MOV {目标寄存器} {值.寄存器}");
                return false;                     // 值换了个寄存器:它自己带来的"零扩展"信息不再成立(保守)
            }
            return 值.已零扩展;
        }

        /// <summary> Rd = L op R 的展开(R 为寄存器或常量)。规则:MOV 把 L 送到 Rd 后再自运算;需保护 Rd 旧值时用暂存。 </summary>
        private void 输出二元到目标(string 目标, string 左, uint? 右常量, string 记号, int 行号, string 原文本, string? 右寄存器 = null)
        {
            bool 右为寄存器 = 右寄存器 != null;
            string 助记 = 运算符助记符(记号);
            string 右操作 = 右为寄存器 ? 右寄存器! : 右常量!.Value.ToString();

            // 常量右操作:加/减 ≤20 位可用立即数指令,否则先入暂存(或目标已有 L 再入暂存)
            if (!右为寄存器 && 记号 is "+" or "-" && 右常量!.Value <= 0xFFFFF)
            {
                if (目标 == 左)
                {
                    发出(记号 == "+" ? $"ADD_IMMEDIATE {目标} {右操作}" : $"SUB_IMMEDIATE {目标} {右操作}");
                    return;
                }
                发出($"MOV {目标} {左}");
                发出(记号 == "+" ? $"ADD_IMMEDIATE {目标} {右操作}" : $"SUB_IMMEDIATE {目标} {右操作}");
                return;
            }

            // 常量右操作:乘 2 的幂 = 左移(乘法的交换律,左移一条顶"装常量 + 乘法"两条)
            if (!右为寄存器 && 记号 == "*" && 右常量!.Value >= 2 && (右常量.Value & (右常量.Value - 1)) == 0)
            {
                int 位 = 0;
                for (uint 剩 = 右常量.Value; 剩 > 1; 剩 >>= 1) 位++;
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出左移立即数(目标, 位);
                return;
            }

            // 常量右操作:左移位数是常量 → 一条 `左移立即数`(位数 > 31 时老路才做 & 0x1F,这里不抢)
            if (!右为寄存器 && 记号 == "<<" && 右常量!.Value <= 31)
            {
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出左移立即数(目标, (int)右常量.Value);
                return;
            }

            // 常量右操作:右移位数是常量 → 一条 `右移立即数`(A9,第108批;位数 > 31 时老路才做 & 0x1F,这里不抢)
            // 只到得了这儿的是**逻辑**右移 —— 有符号的 `>>` 在 应用二元 里就被 求值算术右移 接走了
            if (!右为寄存器 && 记号 == ">>" && 右常量!.Value <= 31)
            {
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出右移立即数(目标, (int)右常量.Value);
                return;
            }

            // 常量右操作:除以 2 的幂(A9,第108批)→ 一条 `右移立即数` 顶"装常量 + DIV"两条
            // (无符号除:右移就是除;除数是 1 时下面这条什么都不发,相当于 目标 = 左)
            if (!右为寄存器 && 记号 == "/" && 右常量!.Value >= 1
                && (右常量.Value & (右常量.Value - 1)) == 0)
            {
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出右移立即数(目标, 尾零个数(右常量.Value));
                return;
            }

            // 常量右操作:取余数的 2 的幂(A2,第100批)→ 无符号取余 = 留低位,一条 `与立即数` 顶两条
            if (!右为寄存器 && 记号 == "%" && 右常量!.Value >= 1
                && (右常量.Value & (右常量.Value - 1)) == 0 && 右常量.Value - 1 <= 0xFFFFF)
            {
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出($"AND_IMMEDIATE {目标} {右常量.Value - 1}");
                return;
            }

            // 常量右操作:与上固定掩码(≤ 20 位)→ 一条 `与立即数`(P11)
            if (!右为寄存器 && 记号 == "&" && 右常量!.Value <= 0xFFFFF)
            {
                if (目标 != 左) 发出($"MOV {目标} {左}");
                发出($"AND_IMMEDIATE {目标} {右常量.Value}");
                return;
            }

            if (目标 == 左)
            {
                // Rd==L:自运算(寄存器右可以是 Rd 本身,ADD R0,R0 合法)
                if (右为寄存器) { 发出($"{助记} {目标} {右寄存器}"); return; }
                发出($"{助记} {目标} {常量操作数寄存器(右常量!.Value, 目标)}");
                return;
            }

            // Rd != L:MOV 之后 Rd 的旧值被覆盖;若 R==Rd(旧值仍被需要)→ 先保护
            if (右为寄存器 && 右寄存器 == 目标)
            {
                string 保护 = 选暂存寄存器([目标, 左]);
                发出($"MOV {保护} {目标}");     // 保存右操作数(=Rd 旧值)
                发出($"MOV {目标} {左}");
                发出($"{助记} {目标} {保护}");   // Rd_new op 旧R = L op R
                return;
            }

            发出($"MOV {目标} {左}");
            if (右为寄存器) { 发出($"{助记} {目标} {右寄存器}"); return; }
            发出($"{助记} {目标} {常量操作数寄存器(右常量!.Value, 目标, 左)}");
        }

        /// <summary> 常量装载到寄存器(≤20 位 1 条,否则 LUI+ORI) </summary>
        private void 输出装载常量(string 寄存器, uint 常量)
        {
            if (常量 <= 0xFFFFF)
            {
                发出($"LOAD_IMMEDIATE {寄存器} {常量}");
                return;
            }
            uint 高位 = 常量 >> 12;   // 0..0xFFFFF
            uint 低位 = 常量 & 0xFFF; // 0..0xFFF
            发出($"LUI {寄存器} {高位}");
            发出($"OR_IMMEDIATE {寄存器} {低位}");
        }

        private static string 运算符助记符(string 记号) => 记号 switch
        {
            "+" => "ADD", "-" => "SUB", "*" => "MUL", "/" => "DIV", "%" => "MOD",
            "&" => "AND", "|" => "OR", "^" => "XOR", "<<" => "SHL", ">>" => "SHR",
            _ => throw new InvalidOperationException($"未知运算符: {记号}")
        };

        /// <summary> 选一个不用到的暂存寄存器(避开本语句占用与额外占用;从 R15 向下找) </summary>
        private string 选暂存寄存器(params string[] 额外占用)
        {
            var 已用 = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            if (_语句占用 != null)
                foreach (var s in _语句占用) 已用.Add(s);
            foreach (var e in 额外占用) 已用.Add(e);
            for (int n = 硬上限C.临时寄存器数 - 1; n >= 0; n--)   // R15 保留给帧指针(FP),不作临时寄存器
                if (!已用.Contains($"R{n}")) return $"R{n}";
            // 报错里带上"第几行 + 占用了哪些 + 最近发的三条指令":排查用(这几条塞在**详情**里)。
            // **这是用户的错,不是编译器坏了**(批 7 实测:一段形状对但表达式很深的程序能把它踩出来),
            // 所以按"说人话的编译错误"报:带行号 + 给改法(拆成几句、用中间变量接),绝不甩内部异常。
            string 近况 = "";
            try
            {
                var 行 = 当前缓冲;
                近况 = 行.Count == 0 ? "(空)" : string.Join(" ;; ", 行.Skip(Math.Max(0, 行.Count - 3)));
            }
            catch { 近况 = "(取不到)"; }
            throw 报错(_当前源行号,
                $"这一句太复杂了:临时寄存器用光了(R0~R{硬上限C.临时寄存器数 - 1} 一共 {硬上限C.临时寄存器数} 个,都在用;" +
                $"上限 {硬上限C.临时寄存器数} 个)。办法:把它拆成两三句、用中间变量接一下 —— " +
                $"例如 `整数 半 = a + b; 结果 = 半 * c;`。(占用:{string.Join(",", 已用.OrderBy(x => x, StringComparer.Ordinal))};" +
                $"最近发的指令:{近况})",
                "expression too complex: out of scratch registers (split it into several statements)");
        }

        /// <summary>
        /// 编译期求值常量二元式(32 位回绕语义)。
        ///
        /// **移位次数按 0~31 卡死**(用户拍板,见 `内核加固与语法收口计划.md` D1):常量写越界直接报错。
        /// 运行期是"次数取低 5 位"(C#/x86 口径,`1 << 33` 会悄悄变成 `1 << 1`)——
        /// 变量次数保持这个语义(不动 ISA、不多发指令),但**常量这种一眼能看出来的手滑不该静默吞掉**。
        /// 窄类型(`短整数`/`字节`)的移位仍在 32 位槽里做、结果按声明宽截断(同 D1)。
        /// </summary>
        private static uint 计算常量(string 记号, uint 左, uint 右, int 行号, string 原文, bool 有符号 = false)
        {
            if (记号 is "<<" or ">>" && 右 > 31)
            {
                long 显示次数 = 有符号 ? (int)右 : 右;
                throw 报错静态(行号,
                    $"移位次数 {显示次数} 超出 0~31(整数按 32 位槽算):把它改到 0~31 之间;" +
                    $"真要一步移出去就直接写结果,例如 `1 << 33` 写成 `2`",
                    $"shift count {显示次数} out of range 0..31 (integers use a 32-bit slot)");
            }
            ulong a = 左, b = 右;
            try
            {
                // 有符号语境下 除/取余/右移 按有符号算(`-5 / 2` 该是 -2;`>>` 在运行期是逻辑右移,
                // 但常量折叠时按有符号算更符合直觉 —— 帮助里写明这一点)
                if (有符号 && 记号 is "/" or "%" or ">>")
                {
                    int sa = (int)左, sb = (int)右;
                    return 记号 switch
                    {
                        "/" when sb != 0 => (uint)(sa / sb),
                        "%" when sb != 0 => (uint)(sa % sb),
                        "/" or "%" => throw new DivideByZeroException(),
                        ">>" => (uint)(sa >> (int)(右 & 31)),
                        _ => throw new InvalidOperationException(),
                    };
                }
                return 记号 switch
                {
                    "+" => (uint)((a + b) & 0xFFFFFFFF),
                    "-" => (uint)((a - b) & 0xFFFFFFFF),
                    "*" => (uint)((a * b) & 0xFFFFFFFF),
                    "/" when 右 != 0 => 左 / 右,
                    "%" when 右 != 0 => 左 % 右,
                    "/" or "%" => throw new DivideByZeroException(),
                    "&" => 左 & 右, "|" => 左 | 右, "^" => 左 ^ 右,
                    "<<" => (uint)((左 << (int)(右 & 31)) & 0xFFFFFFFF),
                    ">>" => 左 >> (int)(右 & 31),
                    _ => throw new InvalidOperationException()
                };
            }
            catch (DivideByZeroException)
            {
                throw 报错静态(行号, $"常量除零: '{原文}'(除数是 0;除数先判断,或者把它改成非 0 的常量)",
                    $"constant divide by zero: '{原文}'");
            }
        }

        /// <summary> 解析 0~0xFFFFFFFF 的无符号常量(十进制或 0x 十六进制),供赋值用 </summary>
        private static bool 解析无符号32(string 文本, out uint 值)
        {
            文本 = 文本.Trim();
            if (文本.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
                return uint.TryParse(文本[2..], System.Globalization.NumberStyles.HexNumber, null, out 值);
            return uint.TryParse(文本, out 值);
        }

        /// <summary>
        /// 通用化(2026-10):这一小段文本是不是**浮点字面量**(`1.5` / `1.5f`),是的话给出 IEEE754 位模式。
        /// <para>
        /// 判据就是"整段只有一个词元、且那个词元是浮点档" —— 所以 `1.5 + 1` 这种**表达式**
        /// 不会被误判成"浮点常量"(它得走求值那条路,那条路现在还不支持浮点,会明确报错)。
        /// 只认正的:带 `-` 的会先切出运算符词元 ⇒ 这里返回 false(负浮点字面量还没接,不会静默算错)。
        /// </para>
        /// </summary>
        private static bool 是浮点字面量(string 文本, out uint 位模式)
        {
            位模式 = 0;
            string 洁 = 文本.Trim();
            if (洁.Length == 0) return false;
            List<词元C> 词元;
            try { 词元 = 表达式语法C.切词(洁); }
            catch { return false; }
            if (词元.Count != 1 || !词元[0].是浮点) return false;
            位模式 = 词元[0].浮点位;
            return true;
        }

        /// <summary>
        /// 通用化(2026-10):**这段表达式算出来是不是浮点**(不真的求值,只看类型)。
        /// <para>
        /// 为什么需要它:`是浮点字面量` 只认"整段一个浮点字面量",`是浮点变量` 只认"整段一个浮点变量名" ——
        /// 而 `输出行(左 + 右)`、`输出行(左 * 2.0)` 这种**表达式**两边都不沾,于是被当成整数去打,
        /// 打出 `1082130432`(4.0 的位模式)这种"看着像算错了"的数 —— **静默错误**。
        /// </para>
        /// <para>
        /// 判据与 `表达式值.是浮点` 那套**同源**(不求值、只按类型推):
        /// 浮点字面量 ⇒ 是;浮点变量 ⇒ 是;一元 `+`/`-` 跟着子节点;
        /// 二元只要有一边是浮点 ⇒ 是(`+ - * /` 合法,别的记号求值时会报错,这里也照样说"是浮点",
        /// 好让错误从求值那条路以**准确的文案**报出来)。
        /// </para>
        /// </summary>
        private bool 是浮点表达式(string 文本)
        {
            string 洁 = 文本.Trim();
            if (洁.Length == 0) return false;
            if (是浮点字面量(洁, out _)) return true;
            if (是浮点变量(洁)) return true;
            表达式节点C 节点;
            try { 节点 = 表达式语法C.解析(洁); }
            catch { return false; }                       // 解析不了就交给原来那条路去报错
            return 节点是浮点(节点);
        }

        private bool 节点是浮点(表达式节点C 节点) => 节点 switch
        {
            常量节点C 常量 => 常量.是浮点,
            // ⚠⚠ **数组元素 / 结构字段也算浮点**(2026-10-10 补,判据在 `是浮点标量引用` 里):
            //    `表[3]` / `顶点x[下标]` / `点.x` 这一档以前一律算"不是浮点" ⇒
            //    `整数(表[3] * 1000.0)` 里的元素被当**整数**用下去(位模式 × 1000.0),算出来是 NaN。
            //    它就是 R4-38/R4-39 那条"`着算亮度` 读顶点算成 NaN / 溢出哨兵"的语言层根因。
            名字节点C 名称 => 是浮点变量(名称.名),
            // ⚠ **显式转换的结果看转换那个名字**,不看参数:`整数(3.9)` 是整数、`浮点(3)` 是浮点。
            //    不先摘出来的话,`输出行(整数(-2.7))` 会被当成"浮点表达式"⇒ 走浮点打印
            //    ⇒ 把 -2 的补码当位模式打,打出 `1*2^-149` 或 `4294967294`(踩过)。
            调用节点C 调用 => 调用.名 switch
            {
                "浮点" or "float" => true,
                "整数" or "int" => false,
                // ISA 指令内建里那四条浮点(0x48~0x4B):结果就是浮点位模式 ⇒ 打印要走浮点那条路
                // (判据与 `求值ISA内建` 同源,别在两处各写一份名单)。
                _ => 是浮点内建名(调用.名),
            },
            一元节点C 一元 => 节点是浮点(一元.子),
            // ⚠ **比较与逻辑的结果是 0/1 的整数**(逻辑值),不是浮点 —— 必须先把它们摘出去,
            //    否则 `输出行(左 < 右)` 会拿 0/1 去走浮点打印,打出 `1*2^-149`(踩过)。
            二元节点C { 记号: "==" or "!=" or "<" or ">" or "<=" or ">=" or "&&" or "||" } => false,
            二元节点C 二元 => 节点是浮点(二元.左) || 节点是浮点(二元.右),
            三目节点C 三目 => 节点是浮点(三目.真) || 节点是浮点(三目.假),
            _ => false,
        };

        /// <summary>
        /// T6(2026-09-27 评测整改):解析**负常量**(`-39999` / `-0x8000`)→ 32 位补码值。
        /// 只认"负号 + 一个常量字面量"这一种形状;`-左`、`-(1+2)` 这类**表达式**照旧返回假
        /// (它们本来就走"非常量初值"那条路去求值)。
        /// </summary>
        private static bool 解析负常量32(string 文本, out uint 值)
        {
            值 = 0;
            文本 = 文本.Trim();
            if (!文本.StartsWith('-')) return false;
            string 余 = 文本[1..].Trim();
            if (!解析无符号32(余, out uint 正)) return false;
            值 = 0u - 正;      // 32 位补码:`-1` → 0xFFFFFFFF
            return true;
        }
