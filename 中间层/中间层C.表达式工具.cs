    /// <summary> 中间层展开器的一部分:表达式工具:词法与操作数解析 / 赋值与算术展开 / 条件比较与跳转。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        // ---------------- 表达式/条件 工具 ----------------
        #region 表达式工具:词法与操作数解析(取词/括号/寄存器/赋值判定/数值)
        private static string 取首词(string 文本)
        {
            var 匹配 = 首词正则.Match(文本);
            return 匹配.Success ? 匹配.Value : "";
        }

        /// <summary> 开头那一整段"带点的标识符"(`数学.结果` 整段;`记录.字段` 也整段) </summary>
        private static readonly Regex 首词带点正则 = new(@"^[\p{L}_][\p{L}\p{N}_]*(?:\.[\p{L}_][\p{L}\p{N}_]*)*", RegexOptions.Compiled);

        /// <summary>
        /// 2 的幂是 2 的几次方(尾零个数);不是 2 的幂返回 0。
        /// A9(第108批)用它算 `x / 2^k`、`x % 2^k` 里的 k。
        /// </summary>
        private static int 尾零个数(uint 值)
        {
            int n = 0;
            while (值 > 1 && (值 & 1) == 0) { 值 >>= 1; n++; }
            return n;
        }

        /// <summary>
        /// 声明的"类型词":模块里的结构要整段认出来 —— `数学.结果 记录;` 的类型词是 `数学.结果`,不是 `数学`。
        /// 从长到短试"是不是已声明的结构名";都不认就退回老的"第一个词"行为。
        ///
        /// **方法容器名不当"点号前面那一截"来切**(H60 步①):容器名从 H60 起同时是类型名,
        /// 可它同时还是**那个单例变量的名字** —— `数学.求和(3);` / `数学.累加器 = …;` 都是**成员访问**,
        /// 从点号处截断会把它们错认成声明(实测:示例08 当场报"非法变量名: '.置尺寸(8, 8)'")。
        /// 容器**类型**写在声明位时(`计数器 计数;` / `数学.计数器 计数;`)不带点或整段就是那个名字,
        /// 走下面"退回第一个词"那条路照样认得出来。
        /// </summary>
        private string 取声明类型词(string 内容)
        {
            // H68-3 元组:类型位置上一整对方括号(`[整数, 整数] 结果;` / `[整数 商, 整数 余] 一份;`)
            // 就是那个"类型词" —— 从 `[` 起配对到深度归零的 `]`。不是元组写法就一个字不走这一支。
            if (是元组类型词(内容))
            {
                string 元组 = 取元组词(内容);
                if (元组.Length > 0) return 元组;
            }
            string 长 = 首词带点正则.Match(内容.Trim()).Value;
            if (长.Length == 0) return "";
            if (!长.Contains('.')) return 长;
            for (int 止 = 长.Length; 止 > 0; )
            {
                if (!_容器表.ContainsKey(长[..止]) && (是结构名(长[..止]) || 是枚举名(长[..止]))) return 长[..止];
                止 = 长.LastIndexOf('.', 止 - 1);
            }
            return 长;   // 一段带点的标识符都不是已声明的结构:**整段**还回去(不能只还第一个词 ——
                         // `计数器.累加(5);` 只还 `计数器` 就会被当成"拿容器类型声明变量",见上面那段说明)
        }

        private string 取括号内容(string 头文本, int 位置)
        {
            int 左括号位置 = 头文本.IndexOf('(');
            int 右括号位置 = 头文本.LastIndexOf(')');
            if (左括号位置 < 0 || 右括号位置 <= 左括号位置)
                throw 报错(_伪行号表[位置], $"语法需要圆括号: '{头文本}'", $"expected parentheses: '{头文本}'");
            return 头文本[(左括号位置 + 1)..右括号位置];
        }

        private static bool 解析寄存器(string 文本, out string 寄存器)
        {
            if (!寄存器C.解析(文本, out int 编号))
            {
                寄存器 = 文本.Trim();
                return false;
            }
            寄存器 = 寄存器C.名称(编号);   // 规范成 R0..R15
            return true;
        }

        /// <summary>
        /// 是否中间层赋值语句:寄存器/已声明变量 = … 或 ++/--(原生汇编不使用 '='/++/-- 语法,可安全截获);
        /// 第96批(D5⑤)起也认**复合赋值** `计数 += 2` / `计数 <<= 1`(一共 10 个,见 `复合赋值表`)。
        /// </summary>
        private bool 是赋值语句(string 文本)
        {
            string 内容 = 文本.Trim();
            if (取复合赋值(内容) is not null) return true;
            string 前段;
            if (内容.EndsWith("++") || 内容.EndsWith("--"))
                前段 = 内容[..^2].Trim();
            else
            {
                int 等号 = 内容.IndexOf('=');
                if (等号 <= 0) return false;
                前段 = 内容[..等号].Trim();
            }
            if (前段.Length == 0) return false;
            if (解析寄存器(前段, out _)) return true;
            return 是已知左值(前段);
        }

        /// <summary> 批 12(D5⑤):全套复合赋值(`+= -= *= /= %= &amp;= |= ^= &lt;&lt;= &gt;&gt;=`)→ 对应的二元运算符 </summary>
        public static readonly (string 记号, string 运算符)[] 复合赋值表 =
        [
            ("+=", "+"), ("-=", "-"), ("*=", "*"), ("/=", "/"), ("%=", "%"),
            ("&=", "&"), ("|=", "|"), ("^=", "^"), ("<<=", "<<"), (">>=", ">>"),
        ];

        /// <summary>
        /// 批 12(D5⑤):这一行是不是复合赋值?是就返回 `(记号, 运算符, 左, 右)`,不是返回 null。
        /// **字符串字面量里的记号不算**(取字符串区让开);`==` / `!=` / `&lt;=` / `&gt;=` 不在表里,天然不会误认。
        /// </summary>
        private (string 记号, string 运算符, string 左, string 右)? 取复合赋值(string 文本)
        {
            string 内容 = 文本.Trim();
            var 串区 = 代码解析器.取字符串区(内容);
            bool 在串里(int i) => 串区.Any(r => i >= r.开始 && i < r.结束);
            foreach (var (记号, 运算符) in 复合赋值表)
            {
                int i = 内容.IndexOf(记号, StringComparison.Ordinal);
                if (i <= 0) continue;
                if (在串里(i)) continue;
                string 左 = 内容[..i].Trim();
                string 右 = 内容[(i + 记号.Length)..].Trim();
                return (记号, 运算符, 左, 右);
            }
            return null;
        }

        /// <summary> 批 12:复合赋值展开 —— 字符串的 `+=` 走**拼接**(同一个入口的糖),其余走 `左 = 左 op 右` </summary>
        private string? 展开复合赋值(string 文本, int 行号)
        {
            if (取复合赋值(文本) is not { } 拆) return null;
            if (拆.左.Length == 0 || 拆.右.Length == 0)
                throw 报错(行号, $"{拆.记号} 两边都要写东西(例如 `计数 {拆.记号} 1;`)", $"{拆.记号} needs both sides");
            if (拆.记号 == "+=" && 左值是字符串(拆.左, 行号)) return $"拼接到({拆.左}, {拆.右})";
            return $"{拆.左} = {拆.左} {拆.运算符} {拆.右}";
        }

        /// <summary> 批 12:`+=` 的左边是不是字符串(字符串变量 / `出` 字符串参数 / 结构字段或数组元素里的字符串) </summary>
        private bool 左值是字符串(string 左, int 行号)
        {
            try
            {
                if (是字符串参数(左) || 查列表(左) is { 是字符串: true }) return true;
                if (解析引用链(左, 行号) is { } 链) return 是整段堆串链(链);   // 结构字段/数组元素里的字符串(P8:住在堆里)
            }
            catch (编译异常C) { /* 左值不合法:交给常规赋值那条路去报 */ }
            return false;
        }

        private long 解析数值(string 文本, int 行号)
        {
            文本 = 文本.Trim();
            long 值;
            if (文本.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
            {
                if (!long.TryParse(文本[2..], System.Globalization.NumberStyles.HexNumber, null, out 值))
                    throw 报错(行号, $"无效十六进制数: '{文本}'", $"invalid hex literal: '{文本}'");
            }
            else if (!long.TryParse(文本, out 值))
                throw 报错(行号, $"无效数值: '{文本}'", $"invalid number: '{文本}'");

            if (值 < 0 || 值 > 0xFFFFF)
                throw 报错(行号, $"数值超出20位范围(0~0xFFFFF): {值}", $"value out of 20-bit range: {值}");
            return 值;
        }
        #endregion
        #region 表达式工具:赋值与算术展开(输出赋值/二元运算/常量装载)
        // 解析并展开一条赋值/表达式: 左值(R0~R15 或已声明变量) = 右值
        // 右值支持 寄存器/变量/常量(含32位) 与单个二元运算符;变量读写落地为 取值字→临时寄存器运算→存字,
        // 普通代码只写变量名,寄存器只在展开后的汇编文本里出现。
        private void 输出赋值(string 文本, int 行号, bool 保留占用 = false)
        {
            // 批 12(D5⑤):复合赋值先展开(语句与 for 头都走这里)—— 字符串 `+=` 展开成 拼接到,其余成 `左 = 左 op 右`
            if (展开复合赋值(文本, 行号) is { } 复合展开)
            {
                输出赋值(复合展开, 行号, 保留占用);
                return;
            }
            string 内容 = 文本.Trim();
            // 字符串赋值(`欢迎 = "…";` / `左 = 右;`):**要在整块赋值之前拦下来** ——
            // 字符串的头是 3 个字,按"结构整体搬"那套比宽度是对不上的
            if (!内容.EndsWith("++") && !内容.EndsWith("--"))
            {
                int 串等号 = 内容.IndexOf('=');
                if (串等号 > 0)
                {
                    string 串左 = 内容[..串等号].Trim();
                    string 串右 = 内容[(串等号 + 1)..].Trim();
                    if (串右.Length > 0 && 标识符全词正则.IsMatch(串左)
                        && (查列表(串左) is { 是字符串: true } || 是字符串参数(串左)))
                    {
                        发出字符串赋值(串左, 串右, 行号, 文本);
                        return;
                    }
                    // 左边是**定长缓冲**(`字符 名字[16]`)或**堆串字段/元素**(`字符串 名字`):
                    // 整份赋一段字符串(超容量当场拦住 / 堆串装不下自动换块)
                    if (串右.Length > 0 && 试取串写目标(串左, 行号, 文本) is { } 串写目标)
                    {
                        // `记录.名字 = 0;` = 清成空串(堆里那块先还回去);定长缓冲就是把第一个字节写 0
                        if (解析无符号32(串右, out uint 串清零) && 串清零 == 0)
                        {
                            准备语句占用(文本);
                            if (串写目标.堆串)
                                生成串字段归还并清空(串字地址(串写目标.链, 行号, 文本), 行号, 串写目标.说明);
                            else
                                自成一段(() =>
                                {
                                    string 零 = 新临时();
                                    输出装载常量(零, 0);
                                    发出($"存储间接寻址 {零} {串写目标.定长数据址}");
                                }, 串写目标.定长数据址);
                            return;
                        }
                        if (试取字符串返回调用(串右, 行号) is not null)
                        {
                            // `记录.名字 = 取名字();`:先把返回值物化到一个隐藏临时串,再整份写进字段
                            准备语句占用(文本);
                            发出串目标写入(串写目标, [new 拼接段(false, 串右, 0)], 覆盖: true, 行号, 文本);
                            return;
                        }
                        if (!是字符串操作数(串右))
                            throw 报错(行号, $"{串写目标.说明} 只能整份赋一个字符串(字符串字面量 / 另一个字符串):'{串右}' 不是。" +
                                $"要按字节填就写 {串左}[0] = '字';要接在原有内容后面用 拼接到({串左}, …)",
                                $"a string target needs a string value: '{串右}'");
                        准备语句占用(文本);
                        发出串目标写入(串写目标, [new 拼接段(false, 串右, 0)], 覆盖: true, 行号, 文本);
                        return;
                    }
                }
            }
            if (内容.EndsWith("++") || 内容.EndsWith("--"))
            {
                bool 是增 = 内容.EndsWith("++");
                string 前 = 内容[..^2].Trim();
                if (!保留占用) 准备语句占用(内容);
                if (解析寄存器(前, out string 自增寄存器))
                {
                    发出($"{(是增 ? "ADD" : "SUB")}_IMMEDIATE {自增寄存器} 1");
                    return;
                }
                if (查位置(前, 行号, 文本) is { } 位置)
                {
                    string t = 新临时();
                    发出读变量(t, 位置);
                    发出($"{(是增 ? "ADD" : "SUB")}_IMMEDIATE {t} 1");
                    // t 是本语句刚分配的临时寄存器,写回后再没有人用它 → 截断直接在它身上做,省一条 MOV
                    发出写变量(t, 位置, 源可改写: true);
                    return;
                }
                if (解析数组引用(前, 行号) is { } 自增引用)
                {
                    string t = 取数组元素到寄存器(自增引用.绑定, 自增引用.索引, 行号, 文本);
                    发出($"{(是增 ? "ADD" : "SUB")}_IMMEDIATE {t} 1");
                    写数组元素(t, 自增引用.绑定, 自增引用.索引, 行号, 文本);
                    return;
                }
                throw 报错(行号, $"自增/自减只能用于寄存器、变量或数组元素: '{前}'", $"increment/decrement needs a register, variable or array element: '{前}'");
            }

            int 等号位置 = 内容.IndexOf('=');
            if (等号位置 < 0) throw 报错(行号, $"无法解析的赋值: '{文本}'", $"cannot parse assignment: '{文本}'");
            string 左侧 = 内容[..等号位置].Trim();
            string 右侧 = 内容[(等号位置 + 1)..].Trim();
            if (右侧.Length == 0) throw 报错(行号, $"赋值缺少右侧: '{文本}'", $"missing rhs: '{文本}'");
            // H68-2:左边是枚举变量、右边是**另一个枚举的成员** ⇒ 当场报错(variables 那一格记了枚举身份)
            if (标识符全词正则.IsMatch(左侧)
                && _变量类型.TryGetValue(左侧, out string? 左类型名)
                && 查枚举类型(左类型名) is { } 左枚举)
                检查跨枚举(左枚举.名称, 右侧, 行号);
            if (!保留占用) 准备语句占用(内容);
            // 存"局部变量的地址"到帧外(全局/列表/结构字段)→ 函数返回后就是野地址,直接拦住
            if (!左值在帧内(左侧, 行号)) 检查地址没被存起来(右侧, 行号, "全局变量/结构字段");

            // 整块赋值:左边是结构/整数组/结构元素(不是标量)→ 按字节搬(右 = 左),或者整体清 0(左 = 0)
            if (解析引用链(左侧, 行号) is { 有运行期下标: false } 宽链 && 宽链.需要整块 && 宽链.整块宽 > 0)
            {
                int 宽 = 宽链.整块宽;
                if (解析无符号32(右侧, out uint 常量值) && 常量值 == 0)
                {
                    // 结构里有 `字符串` / 列表字段 → 先把那些块还回堆里再整块清零(字符串数组同理)
                    if (宽链.绑定.数组类型 is { 元素是字符串: true } 串数组型 && 宽链.偏移 == 0)
                        生成串数组清零(链地址(宽链, 行号, 左侧), 串数组型.长度, 行号, 左侧);
                    else if (宽链.结构 is { 有堆字段: true } 清零结构)
                        生成结构清零(链地址(宽链, 行号, 左侧), 清零结构, 行号);
                    else
                        生成整块清零(链地址(宽链, 行号, 左侧), 宽);
                    return;
                }
                // 字符串数组(`字符串 名单[10]`)整块赋值 = 把那些"数据地址"也拷过去,两个数组从此共用堆里同一块 ——
                // 要深拷贝得运行期一个个元素地要块、搬、还,暂时不做,给条明路
                if (宽链.元素是字符串 || 宽链.绑定.数组类型 is { 元素是字符串: true })
                    throw 报错(行号, $"字符串数组 '{左侧}' 不能整块赋值(那样两边会共用堆里同一块数据):" +
                        $"一个个元素赋值(例如 {左侧}[0] = {右侧}[0];),或者写个循环",
                        "a string array cannot be assigned as a whole");
                if (宽链.是串元素)
                    throw 报错(行号, $"{左侧} 是字符串(字段/元素),只能赋字符串(例如 {左侧} = \"…\";),或者整体清 0({左侧} = 0;)",
                        $"a string field only accepts a string value: '{右侧}'");
                // 字面量整体赋值:`名 = [1, 2, 3]` —— 与声明处的初值同一套口径(按位置给常量,没写到的归 0)
                if (是方括号初值(右侧))
                {
                    List<(int 偏移, int 宽度, uint 值)> 项们;
                    // **先看"链的落点是不是一个结构"**:`点 表[3];` 的 `表[0] = [1, 2];` 这种
                    // (结构数组的一个元素)也走结构那一支 —— 以前先按"根绑定是不是数组"分流,
                    // 它会被当成"整个数组的字面量初值"、报一句"元素是结构,只收普通数值"(指错方向)。
                    if (宽链.结构 is { } 构型2)
                    {
                        // H68-4:元组整体赋值里带**式子**(`结果 = [a / b, a % b];`)⇒ 逐个成员算出来写进左边那块;
                        // 整串都是常量(含枚举成员)照旧走下面那条常量填块的老路
                        if (是元组结构(构型2)
                            && !拆方括号初值(右侧, 行号).All(段 => 是常量字面量(段) || 查枚举成员常量(段) != null))
                        {
                            准备语句占用(右侧);
                            发出元组填块(链地址(宽链, 行号, 左侧), 构型2, 右侧, 行号, 左侧);
                            return;
                        }
                        if (构型2.有堆字段)
                            throw 报错(行号, $"结构 '{构型2.名称}' 里有字符串/列表字段,不能用字面量整体赋值" +
                                $"(那样堆里那几块没法对应上):请逐个字段赋值",
                                $"struct '{构型2.名称}' has heap fields; assign field by field");
                        校验全字段可取用(构型2, 行号);
                        var 常量们 = 拆方括号初值(右侧, 行号);
                        项们 = 折字面量初值(常量们, 构型2.字段.Count,
                            c => $"结构 '{构型2.名称}' 只有 {构型2.字段.Count} 个字段,初值却写了 {c} 个", 行号,
                            i =>
                            {
                                var 字段 = 构型2.字段[i];
