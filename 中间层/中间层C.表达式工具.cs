                    发出($"{清空}:");
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    发出间接写(零, 目标头地址, 4);
                    发出间接写(零, 基址加偏移(目标头地址, 列表头长度偏移), 4);
