        /// <summary>
        /// R6-6:主程序的**最后一条真指令**是不是 `停止`(是的话就不再补,免得白发一条用不上的指令)。
        ///
        /// 从后往前找,跳过三类不算指令的行:空行、纯注释行(含 `// 编译器生成` 那行开关标记)、
        /// 以及标签行(`完:` —— 它只是个入口名字,后面没指令了说明前一条才是真正的收尾)。
        /// 找出来的第一条看**头一个词**:`停止` / `HALT` / `halt` 才算(行尾可能挂着 `// 来自第 N 行` 标记或用户注释)。
        /// </summary>
        private static bool 主程序已停机(List<string> 主行)
        {
            for (int i = 主行.Count - 1; i >= 0; i--)
            {
                string 干 = 源行标记C.去标记(主行[i]).Trim();
                if (干.Length == 0 || 干.StartsWith("//", StringComparison.Ordinal)) continue;
                if (干.EndsWith(':')) continue;
                int 空 = 干.IndexOfAny([' ', '\t']);
                string 首词 = 空 < 0 ? 干 : 干[..空];
                return 首词 is "停止" or "HALT" or "halt";
            }
            return false;
        }


        /// <summary>
        /// 这一行 `;` 后面是不是还跟着**另一条语句**(是就返回它,用于"一行只能写一条语句"的报错)。
        ///
        /// 三个例外都得让开,否则全是误报:
        ///   · **字符串字面量里**的分号(`输出行("你好;世界");`)—— 按 `代码解析器.取字符串区` 跳过;
        ///   · **括号里**的分号 —— `循环 (整数 i = 0; i < 5; i++)` 的 for 头分段符就是这个,靠括号深度判;
        ///   · 分号后面的 `}` `{` —— `如果 (…) { 返回 初值; }` 这种一行块是合法的(一行块里也只能一条语句)。
        /// 注释不用管:`规范化文本` 早就把注释去掉了。
        /// </summary>
        private static string? 取第二个语句(string 内容)
        {
            var 串区 = 代码解析器.取字符串区(内容);
            bool 在串里(int i) => 串区.Any(r => i >= r.开始 && i < r.结束);
            int 括号深 = 0;
            for (int i = 0; i < 内容.Length; i++)
            {
                char c = 内容[i];
                if (在串里(i)) continue;
                if (c == '(') { 括号深++; continue; }
                if (c == ')') { 括号深 = Math.Max(0, 括号深 - 1); continue; }
                if (c != ';' || 括号深 > 0) continue;
                string 后 = 内容[(i + 1)..].Trim().Trim('}', '{', ';').Trim();
                return 后.Length > 0 ? 后 : null;
            }
            return null;
        }

        private void 处理语句(ref int 位置)
