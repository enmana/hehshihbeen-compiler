            {
                _伪行表[位置] = 复合展开;
                内容 = 复合展开;
                首词 = 取首词(内容);
            }
            // 批 10(D3):**语言结构里不许出现 R0~R15**(写/读都算)。
            // 让开两类真正的汇编:`加载立即数 R1, 5` 这种指令行,以及单独成句的 `R0 = …` / `R2++`
            // (它们和内联汇编同一档)。其余位置(表达式/条件/循环头/选择值/遍历/实参/声明)一律报错 + 给改法。
            if (!是汇编指令行(内容) && !是寄存器赋值句(内容) && !是声明行(内容)
                && 中间层C.到英文关键字(首词) != "foreach")
                检查没有寄存器(内容, _伪行号表[位置]);
            // 列表动作:`分数.添加(值)` / `分数.清空()`(单独成句)
            if (试处理列表动作(内容, _伪行号表[位置]))
            {
                位置++;
                return;
            }
            // 堆动作:`释放(p);` / `存字(p, 偏移, 值);`(单独成句;报错文案与行号都在这儿)
            if (试处理堆动作(内容, _伪行号表[位置]))
            {
                位置++;
                return;
            }
            // 图形命令(R1-6 批 1):`清屏(颜色);` / `画文字(…);` / `等待(16);` —— 它们是"命令",没有返回值
            if (试处理图形动作(内容, _伪行号表[位置]))
            {
                位置++;
                return;
            }
            // 声明:基本类型 / 已声明结构类型 / 变量|var
            if (是声明行(内容))
            {
                处理声明(ref 位置);
                return;
            }
            // 函数相关:调用 f(...) / 返回 值 / 函数声明
            if (是函数调用行(内容))
            {
                处理函数调用(内容, _伪行号表[位置]);
                位置++;
                return;
            }
            // 带返回类型的函数里,裸 `返回` 也是"语言的返回"→ 走 处理返回值 去报"必须返回值"
            // (裸 `返回` 在别处仍是汇编 RET,原样透传)
            bool 裸返回但声明了类型 = 内容 == "返回" && _当前函数 is { 返回类型词.Length: > 0 };
            if (是返回值行(内容) || 裸返回但声明了类型)
            {
                处理返回值(内容, _伪行号表[位置]);
                位置++;
                return;
            }
            string? 关键字 = 中间层C.到英文关键字(首词);
            // 读输入是"有结果的值":`读取字符()` 单独成句没意义(注意它们不能进关键字表 ——
            // `读取字符`/`输出字符` 本身就是汇编指令名,进表会被"中英切换"改坏)
            if (是读输入名(首词) && 内容.Contains('(') && 内容.TrimEnd().EndsWith(')'))
                throw 报错(_伪行号表[位置], "读输入的结果要用起来:赋值给变量或写进表达式(例如 `字符 c = 读取字符()`)",
                    "input functions must be used as a value");
            // 宿主能力(P28)同理:它们都返回一个值(成功/失败),单独成句就把"成没成"丢了
            if (是宿主能力名(首词) && 内容.Contains('(') && 内容.TrimEnd().EndsWith(')'))
                throw 报错(_伪行号表[位置], $"{首词}(...) 的结果要用起来(成没成 / 读到的内容):" +
                    $"例如 `如果 ({首词}(…)) {{ … }} 否则 {{ … }}`,或者 `测试输出({首词}(…));`",
                    "host functions must be used as a value");
            // 图形原语里**有结果**的那几条(打开窗口 / 关闭窗口 / 刷新 / 取事件 / 取文字宽度)一样要用起来;
            // `清屏` / `画文字` / `画矩形` / `画线` / `等待` 是"命令",已在上面 试处理图形动作 就地展开了
            if (是图形值能力名(首词) && 内容.Contains('(') && 内容.TrimEnd().EndsWith(')'))
                throw 报错(_伪行号表[位置], $"{首词}(...) 的结果要用起来(成没成):" +
                    $"例如 `如果 ({首词}(…)) {{ … }}`,或者 `测试输出({首词}(…));`",
                    "graphics functions must be used as a value");
            // 老写法(体/类/常驻)友好提示:认出来像声明就直说改名了
            if (关键字 == null && 首词 is "体" or "类" or "常驻" or "body" or "class" or "const"
                && (下一行是块(位置) || 内容.Contains('(')))
                throw 报错(_伪行号表[位置], "体/类/常驻 已改名:无状态用 `方法 名()`,带状态用 `静态 方法 名(...)`",
                    "体/类/常驻 were renamed: use `方法 名()` / `静态 方法 名(...)`");
            // 老写法(记录/record)友好提示:已经改名叫"结构/struct"
            if (关键字 == null && 首词 is "记录" or "record" && 下一行是块(位置))
                throw 报错(_伪行号表[位置], "`记录` 已改名为 `结构`(英文 record → struct),请把这一行改成 `结构 名字`",
                    "`记录` was renamed to `结构` (record → struct)");
            // H46(用户 2026-09-26 当班拍板):`函数` 这个关键字**撤了** —— 与上面"体/类/常驻/记录"同一套做法:
            // 认出来就直说改法,别让它掉进"非法变量名/未知的语句"那种看不出所以然的报错里。
            if (关键字 == null && 首词 is "函数" or "func" && (下一行是块(位置) || 内容.Contains('(')))
                throw 报错(_伪行号表[位置], "`函数` 这个关键字已撤掉:声明一个过程一律写 `方法 名(参数…) 返回 类型`" +
                    "(没有返回值就不写 `返回 类型`;要一组方法分个家、或者要常驻状态,写 `静态 方法 名(字段…) { … }`)",
                    "`函数` was removed: declare routines with `方法 名(...) 返回 类型`");
            switch (关键字)
            {
                case "if": 处理如果(ref 位置); break;
                case "else": throw 报错(_伪行号表[位置], "多余的 '否则/else'", "unexpected 'else'");
                case "switch": 处理选择(ref 位置); break;
                case "for": 处理循环(ref 位置); break;
                case "while": 处理当(ref 位置); break;
                case "foreach": 处理遍历(ref 位置); break;
                case "struct": 处理结构声明(ref 位置); break;
                case "enum": 处理枚举声明(ref 位置); break;      // H68-2:枚举(一行写完,成员是编译期常量)
                case "method": 处理方法声明(ref 位置, 静态: false); break;
                case "static": 处理方法声明(ref 位置, 静态: true); break;
                case "module":
                    throw 报错(_伪行号表[位置], "`模块` 要写在**文件第一条**(前面只能有空行和注释):" +
                        "整个文件都属于这个模块,里面的函数/结构/全局变量自动带上 `模块名.` 前缀",
                        "`module` must be the first line of the file");
                case "debug": 处理测试输出(ref 位置); break;
                case "print": 处理输出(ref 位置, 换行: false); break;
                case "println": 处理输出(ref 位置, 换行: true); break;
                case "concat": 处理拼接到(ref 位置); break;
                case "test": 处理测试块(ref 位置); break;
                case "assert": 处理断言(位置); 位置++; break;
                case "break": 处理跳出(ref 位置); break;
                case "continue": 处理继续(ref 位置); break;
                case "case":
                case "default":
                    throw 报错(_伪行号表[位置], $"'情况/case' 只能出现在 选择/switch 内", "'case' is only valid inside switch");
                default:
                    // M1:赋值语句(Rx = … / Rx++ / Rx--) 与 变量赋值(变量名 = …) 由中间层展开;其余行按原生汇编原样透传
                    if (是赋值语句(内容))
                    {
                        输出赋值(内容, _伪行号表[位置]);
                        位置++;
                    }
                    else if (内容.IndexOf('=') > 0 || 内容.EndsWith("++") || 内容.EndsWith("--"))
                    {
                        // 形如赋值但左值不是寄存器也不是已声明变量 → 明确报错(而非透传给汇编器)
                        throw 报错(_伪行号表[位置], $"未声明的变量或非法赋值左值: '{内容}'", $"undeclared variable or invalid assignment lhs: '{内容}'");
                    }
                    else
                    {
                        // 尖括号写法(以前讨论过"列表<短整数>"):给一句指路,别让汇编器报"未知指令"
                        if (内容.Contains('<') || 内容.Contains('《'))
                            throw 报错(_伪行号表[位置], $"列表不用尖括号:写成 类型 名字[] 即可(例如 短整数 分数[])",
                                "lists do not use angle brackets: write 类型 名字[]");
                        // 批 11(D4):调用只剩隐式写法 —— "像调用但名字没定义"要当场说清,
                        // 别透传给汇编器(那会报成"未知指令: xxx",把人往"指令拼错了"的方向带)
                        if (取调用形状名(内容) is { } 未知名)
                            throw 报错(_伪行号表[位置],
                                $"未定义的函数/方法: `{未知名}(…)`。检查名字有没有拼错;" +
                                $"要调**汇编标签**写 `调用 {未知名}`(不带括号,那是汇编指令)",
                                $"undefined function/method: '{未知名}'");
                        // H60 步①:容器名能当类型名用(`计数器 计数;`),而容器是逐句处理时登记的
                        // ⇒ "先用后声明"这行原本会透传给汇编器、报成"未知指令: 计数器"
                        // (把人往"指令拼错了"的方向带)。预扫收过容器名,这里就能当场说清该怎么办。
                        if (取首词(内容) is { Length: > 0 } 头词)
                        {
                            string 尾名 = 头词[(头词.LastIndexOf('.') + 1)..];
                            if (_预扫容器名.Contains(尾名))
                                throw 报错(_伪行号表[位置],
                                    $"'{尾名}' 是一个**方法容器**,容器要先声明再用 —— 把 `静态 方法 {尾名}(…)` 挪到这句话前面" +
                                    $"(容器名从 2026-10 起也能当类型名:`{尾名} 计数;` 就是拿它声明第二份)",
                                    $"'{尾名}' is a method container declared later: declare it before use");
                        }
                        发出(内容);
                        位置++;
                    }
                    break;
            }
        }

        // 处理一个由 { } 包裹的语句块，遇 '}' 结束并消费它。进入块 = 压一层变量作用域,出块弹掉。
        private void 处理块(ref int 位置)
        {
            if (位置 >= _伪行表.Count) throw 报错(_伪行号表[^1], "缺少 '}'", "missing '}'");
            if (_伪行表[位置] != "{") throw 报错(_伪行号表[位置], "缺少 '{' 开始代码块", "expected '{' to open a block");
            // T2(2026-09-27 评测整改):**语句块嵌套护栏**。这一段是照块递归下去的(`处理块 → 处理语句 → 处理块`),
            // 而 .NET 的栈溢出接不住 —— 以前嵌套 450 层 `如果` 就把 hbcc 自己打死(stdout 零字节、stderr 只有裸栈)。
            // 上限与"怎么绕"见 `引擎\硬上限C.cs` 的 `语句块嵌套上限`(报错走普通编译错误那条路:带行号、能继续编别的)。
            _块深度++;
            if (_块深度 > 硬上限C.语句块嵌套上限)
            {
                int 撞上的深度 = _块深度;
                _块深度--;        // 这一层没真进去,深度还回去(报错被上层收进错误表后还要接着编)
                _块深度超限 = true;   // 恢复时整块跳过(这几层里编不动,再往里走只会再撞一次护栏 + 把栈吃掉)
                throw 报错(_伪行号表[位置],
                    $"语句块嵌套太深({撞上的深度} 层,上限 {硬上限C.语句块嵌套上限} 层):" +
                    "把内层那半段提成一个 `方法` 再调用(少一层块);或者把深嵌套摊平成一串 `如果 … 返回`",
                    $"statement blocks nested too deep ({撞上的深度} > {硬上限C.语句块嵌套上限})");
            }
            位置++;
            int 起行 = _伪行号表[位置 - 1];       // `{` 所在行 = 这层块作用域的起点(调试用)
            int 止行 = 起行;
            压作用域(起行);
            try
            {
                while (true)
                {
                    if (位置 >= _伪行表.Count) throw 报错(_伪行号表[^1], "缺少 '}'", "missing '}'");
                    if (_伪行表[位置] == "}") { 止行 = _伪行号表[位置]; 位置++; return; }
                    if (_伪行表[位置] == "{") throw 报错(_伪行号表[位置], "意外的 '{'", "unexpected '{'");
                    处理语句(ref 位置);
                }
            }
            finally
            {
                弹作用域(止行);
                _块深度--;
            }
        }
        #endregion
    }
