    /// <summary> 中间层展开器的一部分:引用链解析(`变量.字段[下标].字段 …`)。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        #region 引用链解析(变量.字段[下标].字段 …,给数组/列表/嵌套结构共用)
        /// <summary>
        /// 一条引用链在编译期解析出来的结果:静态部分全算成"槽 + 常量偏移 + 宽度";
        /// 遇到**运行期下标**就把下标文本单独带出来(先只支持一个:再深请分两步算地址)。
        /// </summary>
        private sealed class 引用链C
        {
            /// <summary> 链的**根变量名**(用户在源码里写的那个名字)。字符串的"绑定.名称"是槽名,
            /// 而 `是字符串参数/查列表` 这些要按用户写的名字查 —— 所以名字单独留一份。 </summary>
            public string 基名 = "";
            public 变量绑定C 绑定;
            public int 偏移;                 // 相对变量起点的常量偏移
            public int 宽度;                 // 这一层整块的宽度
            public 结构类型C? 结构;          // 这一层是结构(可以继续 .字段)
            public int 元素宽;               // 这一层是数组/列表:元素宽
            public int 元素个数;
            public 结构类型C? 元素结构;      // 元素是结构时(结构数组 / 结构列表)
            public bool 是指针基址;          // 基址不是"变量槽的地址",而是"槽里装的地址"(引用变量)
            public string? 运行期下标;       // 有一个运行期下标时:它的文本
            public int 下标元素宽;           // 那个下标所在数组的元素宽(缩放用)
            public int 下标后偏移;           // 运行期下标之后的常量偏移(单位[i].y 的 y)
            public int 下标后宽度 = 4;
            public 结构类型C? 下标后结构;
            /// <summary> 被索引的那个数组/列表有几个元素(运行期下标的边界检查用;列表查容量槽,不读这个)</summary>
            public int 下标上界;
            /// <summary> 根变量是"宽槽装窄值"时的声明宽(C 档的 `短整数` 变量;0 = 普通紧排)</summary>
            public int 声明宽;
            /// <summary> 根变量的类型**是不是有符号**(整数/短整数):读出来要不要补符号位、比较要不要按有符号比</summary>
            public bool 有符号 = true;
            /// <summary>
            /// 这一层就是一个"字符串字段/元素"(`字符串 名字;` / `记录.名字` / `名单[2]`):
            /// 整块 8 字节(数据地址 + 容量),真正的字节在堆里、0 结尾。
            /// 当值用的时候读出来的是**数据地址**(和 `地址` 一样),当字符串用的时候走 串数据与字节长。
            /// </summary>
            public bool 是串元素;
            /// <summary> 这一层的元素是字符串(`字符串 名单[10]` 这种数组);下标之后就变成 是串元素 </summary>
            public bool 元素是字符串;
            /// <summary> 运行期下标之后的那个元素是字符串(`名单[i]`) </summary>
            public bool 下标后是串元素;
            /// <summary>
            /// H1:`记录.名字[下标]` —— 从**堆串字段/元素**里取第 N 个**文字**。
            /// 与池串的 `名字[下标]` 同口径(按 Unicode 码点、下标从 0 起),读出来是一个 `文字`;
            /// 写回去可以是任意长度(挪尾巴 + 装不下换块)。
            /// 与 是串元素 同时成立:是串元素 说"这是个 8 字节的堆串小块",本旗子说"再往下取了一个字"。
            /// </summary>
            public bool 串取字;
            /// <summary> 串取字 用**常量**下标时,那个常量(0 起);运行期下标时看 串取字下标文本 </summary>
            public int 串取字常量;
            /// <summary> 串取字 用**运行期**下标时,那个下标的源文本(是"第几个文字",**不参与算址** ——
            /// 所以不能塞进 运行期下标:那一位是"数组元素下标",会去缩放、加元素宽) </summary>
            public string? 串取字下标文本;
            /// <summary>
            /// 元素地址已经算在手的寄存器(字符串列表 `名单.添加(…),` 用:下标是"当前长度",编译期没有下标文本可存)。
            /// 有它时 串字地址 直接用它,不再从 链 现算。
            /// </summary>
            public string? 现成元素地址;

            /// <summary>
            /// H1 第四件:这一层是**结构字段里的动态列表**(`筐.数` / `表[i].数`)。
            /// 有它时 `是列表` 为真,但列表的头不在具名槽里,而在结构内存中 —— 所以
            /// `按槽找列表(绑定.名称)` 那条老路对它是错的,一切都要走 `取链列表(链, 行号)`。
            /// </summary>
            public 列表绑定C? 字段列表;

            /// <summary>
            /// 最内层元素的宽度(H68-1 多维数组:最后一个下标取出来的东西有多宽)
            /// </summary>
            public int 最内元素宽;

            /// <summary>
            /// **R4-41(2026-10-10)**:这一条链走到的最后那一格是**结构字段**时,它的**声明类型名**
            /// (字段不是结构字段时留空)。为什么要留一份:链走完字段之后 `结构` 会被清成 null
            /// (那一格的意义是"整块不能当标量用"),**字段自己的类型就此丢了** ——
            /// 于是 `点.x`(`浮点 x;`)会被当成整数(位模式 × 1000.0 = NaN,见 `是浮点标量引用`)。
            /// </summary>
            public string? 末字段类型名;

            /// <summary>
            /// **H68-1 多维数组**:还没走完的每一维(长度 / 一步多少字节 / 那一维的元素结构)。
            /// **单维数组是 null** —— 老写法一次都不会走到这一格。
            /// </summary>
            public List<维C>? 剩余维;

            /// <summary> **H68-1**:第一个运行期下标**之后**那几维的运行期下标(第一个照旧放在 运行期下标 那一格) </summary>
            public List<维C>? 后续维下标;

            /// <summary> 这一条链是多维数组链(H68-1) </summary>
            public bool 多维;

            /// <summary> 多维数组的一维:长度 / 一步的字节数 / 那一维的元素结构;运行期下标时 文本 有值 </summary>
            public sealed class 维C
            {
                public int 长度;
                public int 步长;
                public int 序号;                        // 0 起(报错文案里的"第几维")
                public 结构类型C? 元素结构;
                public string? 文本;                    // 运行期下标的源文本;走常量时是 null

                /// <summary>
                /// **H3 ④**:"下一维"其实是**结构里的一个定长数组字段**(`架[i].数[j]`)时,越界说明
                /// 说"字段 '数' 只有 N 个元素"比说"第 2 维"清楚 —— 那一档把这句话填在这儿。
                /// </summary>
                public string? 说明文本;

                /// <summary> 越界说明(与单维那句 `只有 N 个元素(下标 0~N-1)` 同一个口径,只多点明第几维) </summary>
                public string 说明 => 说明文本 ?? $"第 {序号 + 1} 维只有 {长度} 个元素(下标 0~{长度 - 1})";
            }

            /// <summary> 复制一条链(链走到某个字段那一刻的**快照**;以后再往下取下标不会改到它)</summary>
            public 引用链C 浅复制() => (引用链C)MemberwiseClone();

            public bool 是列表 => 绑定.列表类型 != null || 字段列表 != null;
            public bool 是数组或列表 => 元素宽 > 0;
            public bool 有运行期下标 => 运行期下标 != null;
            /// <summary> 链里**写没写过 `[下标]`**(常量下标也算)。没有它的话,`名字` 和 `名字[0]` 分不出来:
            /// 字符串是"元素宽 1 的列表",整名会被误当成"取第 0 个字"(踩过:`输出行(串变量)` 只打出第一个字)</summary>
            public bool 有下标;
            /// <summary> 当标量读几字节:数组/列表**整名**不带下标时不能当标量(0 = 不行)</summary>
            public int 标量读宽 => 有运行期下标 ? 下标后宽度 : 是数组或列表 ? 0 : 宽度;
            /// <summary> 读出来的值是不是"已知高半为 0"(窄类型读的时候本来就掩过码)。
            /// T6:有符号的 2 字节值读出来是**补过符号位**的(高半是符号),不能再当"零扩展"用。</summary>
            public bool 读即零扩展 => !有符号 && (标量读宽 is 1 or 2 || (标量读宽 == 4 && 声明宽 is > 0 and < 4));
            /// <summary> 整块多大:数组/列表就是"元素宽×个数";定容列表个数是编译期值,动态列表算 0(整块操作不支持)</summary>
            public int 整块宽 => 是数组或列表 ? 元素宽 * 元素个数 : 宽度;
            /// <summary> 这个引用不是 1/2/4 字节的标量 → 得当整块处理(整体赋值/整块拷贝)</summary>
            public bool 需要整块 => 标量读宽 is not (1 or 2 or 4);
            /// <summary> 元素是结构、又没往下点到字段 → 不能当标量读写 </summary>
            public bool 点到结构整块 => (有运行期下标 ? 下标后结构 : 结构) != null;
        }

        /// <summary>
        /// 名字里那些"可能是变量名结尾"的位置(从长到短):整体、每个点之前、第一个 `[` 之前。
        /// 模块里的 `数学.计数` / `数学.数组[3]` / `数学.点.x` 靠它认出"变量名其实是哪一段"。
        /// </summary>
        private static IEnumerable<int> 认长基名的切点(string 名)
        {
            var 切点 = new List<int> { 名.Length };
            for (int i = 名.Length - 1; i > 0; i--)
                if (名[i] == '.') 切点.Add(i);
            int 左 = 名.IndexOf('[');
            if (左 > 0) 切点.Add(左);
            return 切点.Distinct().OrderByDescending(x => x);
        }

        /// <summary>
        /// ⚠⚠ **R4-41(2026-10-10):这条引用链读出来的是一个浮点**标量元素 / 字段**吗。**
        ///
        /// 为什么要有它:`链读到寄存器` 只返回"装了值的那个寄存器",**类型标记全在调用方那边** ——
        /// 这里不判的话,`浮点 ux = 顶点x[填_v2] - 顶点x[填_v1];` 会被当成**整数减法**
        /// (IEEE754 位模式直接相减 = 垃圾),库里的 `着算亮度` 就是这么算出 NaN 的。
        ///
        /// 判据与 `是浮点标量引用` 同源(**正好点到一个 4 字节标量 + 那一格声明类型是 `浮点`**),
        /// 只是这里手上已经有一条解好的链,不必再按名字重解析一遍。
        /// </summary>
        private bool 链是浮点标量(引用链C 链)
        {
            if (链.多维 || 链.后续维下标 is { Count: > 0 }) return false;      // 少写了最后一维:那是整个子数组
            if (!链.有运行期下标 && 链.下标后宽度 != 4) return false;          // 常量下标走的不是"下标后宽度"
            // ⚠ **结构字段先判**:结构参数(`点 p`)在链上就是"指针基址",可字段类型是编译期定死的
            //    (见 `是浮点标量引用` 里那条注释)
            if (链.末字段类型名 is { } 字段类型)
                return 字段类型 == "浮点" || string.Equals(字段类型, "float", StringComparison.OrdinalIgnoreCase);
            if (链.是指针基址) return false;                                    // 引用变量指向什么由调用方定
            if (链.标量读宽 != 4) return false;                                 // 只有 4 字节才可能是单精度浮点
            if (链.是串元素 || 链.元素是字符串 || 链.下标后是串元素 || 链.串取字) return false;
            if (链.点到结构整块) return false;
            // 数组 / 列表元素(`表[3]`):根变量的声明类型是 `浮点` 才算(只查表,不许再解析链)
            return 是浮点变量(链.基名, 只查表: true);
        }

        /// <summary>
        /// 解析 `名`, `名.字段`, `名.字段[下标]`, `名[下标].字段` 这类引用链。
        /// 解析不了(不是已知变量/名字里带别的花样)返回 null;能解析但写法不对就给出明确错误。
        /// </summary>
        private 引用链C? 解析引用链(string 文本, int 行号)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0) return null;
            int 切 = 名.IndexOfAny(['.', '[']);
            string 基名 = (切 < 0 ? 名 : 名[..切]).Trim();
            if (基名.Length == 0) return null;
            var 变量查 = 查变量(基名);
            // 模块里的全局:`数学.计数` / `数学.数组[3]` / `数学.点.x` —— 模块名本身不是变量,
            // 得把"最长的那一段能当变量的前缀"认出来(整体先试,再从长到短试各个点之前的前缀)
            if (变量查 is null && 名.Contains('.'))
            {
                foreach (int 止 in 认长基名的切点(名))
                {
                    string 试 = 名[..止].Trim();
                    if (试.Length == 0 || !标识符带点正则.IsMatch(试)) continue;
                    if (查变量(试) is not { } 长绑定) continue;
                    基名 = 试;
                    切 = 止;
                    变量查 = 长绑定;
                    break;
                }
            }
            if (变量查 is not { } 绑定值)
            {
                // 方法体里能省容器名 / 结构名:字段名直接写(补上 `容器名.` / `_收方.` 再来一次)
                if (试字段全名(基名, out string 全名))
                    return 解析引用链(全名 + 名[基名.Length..], 行号);
                return null;
            }
            变量绑定C 绑定 = 绑定值;

            var 链 = new 引用链C { 基名 = 基名, 绑定 = 绑定, 偏移 = 0, 宽度 = 绑定.宽度, 声明宽 = 绑定.要截断 ? 绑定.声明宽 : 0, 有符号 = 绑定.有符号 };
            if (绑定.是引用)
            {
                // 引用:`p.x` / `p[i]` 全部按"它指向的东西"来解析,基址到时候从槽里读出来
                var 引 = 绑定.引用类型!;
                链.是指针基址 = true;
                链.宽度 = 引.整块宽;
                链.结构 = 引.结构类型;
                链.元素宽 = 引.元素宽;
                链.元素个数 = 引.元素个数;
                链.元素结构 = 引.元素结构;
            }
            else if (绑定.是列表)
            {
                链.元素宽 = 绑定.列表类型!.元素宽;
                // **会长大的列表**(数据在池里:全局动态列表、以及函数里的列表)不按"当前容量"卡常量下标 ——
                // 真实上界是运行期的长度/容量(常量下标超过最初的容量是合法的:添加过就长大了)
                var 列表状态 = 按槽找列表(绑定.名称);
                链.元素个数 = 列表状态 is null || 列表状态.动态 ? 0 : 绑定.列表类型!.容量;
                链.元素结构 = 绑定.列表类型!.元素结构;
                链.元素是字符串 = 绑定.列表类型!.元素是字符串;      // `字符串 名单[]`(H1):下标取出来的就是一个字符串(8 字节那块)
            }
            else if (绑定.是数组)
            {
                var 数型 = 绑定.数组类型!;
                链.最内元素宽 = 数型.元素宽;
                if (数型.是多维)
                {
                    // H68-1:各维摊成一张表(长度 / 步长 / 那一维的元素结构);只有最后一维的元素才带结构
                    链.多维 = true;
                    链.剩余维 = [];
                    for (int 维号 = 0; 维号 < 数型.各维长度!.Length; 维号++)
                        链.剩余维.Add(new 引用链C.维C
                        {
                            长度 = 数型.各维长度[维号],
                            步长 = 数型.维步长(维号),
                            序号 = 维号,
                            元素结构 = 维号 == 数型.各维长度.Length - 1 ? 数型.元素结构 : null,
                        });
                    对齐当前维(链);
                }
                else
                {
                    链.元素宽 = 数型.元素宽;
                    链.元素个数 = 数型.长度;
                    链.元素结构 = 数型.元素结构;
                    链.元素是字符串 = 数型.元素是字符串;
                }
            }
            else if (绑定.是结构) 链.结构 = 绑定.结构类型;

            int 位置 = 切;
            while (位置 >= 0 && 位置 < 名.Length)
            {
                char 记号 = 名[位置];
                if (记号 == '.')
                {
                    int 下个 = 名.IndexOfAny(['.', '['], 位置 + 1);
                    string 字段名 = (下个 < 0 ? 名[(位置 + 1)..] : 名[(位置 + 1)..下个]).Trim();
                    if (字段名.Length == 0) throw 报错(行号, $"'.' 后面缺字段名: '{名}'", $"missing field name in '{名}'");
                    if (链.有运行期下标)
                    {
                        if (链.剩余维 is { Count: > 0 } 缺维)
                            throw 报错(行号, $"'{名}' 还差 {缺维.Count} 维下标,不能直接点 .{字段名}:" +
                                $"它是定长多维数组,要写全各维下标(例如 {基名}[0][0])才能点字段",
                                $"'{名}' still needs {缺维.Count} subscript(s) before '.{字段名}'");
                        if (链.下标后结构 is not { } 后结构)
                            throw 报错(行号, $"'{名}' 里那个元素不是结构,不能再 .{字段名}",
                                $"'{字段名}' cannot follow a non-struct element in '{名}'");
                        var 后字段 = 后结构.找字段(字段名)
                            ?? throw 报错(行号, $"结构 '{后结构.名称}' 没有字段 '{字段名}'", $"struct '{后结构.名称}' has no field '{字段名}'");
                        校验字段可取用(后结构, 后字段, 行号);
                        // T13(2026-09-27 评测整改):运行期下标**之后**再点字段,也要把**字段自己的符号性**接过来。
                        // 上面那条(下标之前点字段)第96批就接对了,这一支漏了:链根是结构数组(`袋 表[3]`)时
                        // `类型C.有符号("袋")` 兜底给 true ⇒ `表[i].v`(`无符号短整数 v`)被当成有符号读。
                        // 实测:`表[1].v = 40000;` 常量下标读出 40000,运行期下标 `表[i].v` 读出 **-25536** ——
                        // 同一个值(同一格)两个答案,正是 T13 要收的口径。
                        链.有符号 = 类型C.有符号(后字段.类型名);
                        if (后字段.是数组)
                        {
                            // ---- H3 ④:`架[i].数[j]` —— 运行期下标后面接一个**定长数组字段** ----
                            // 把那个字段当成"**下一维**"挂进 `剩余维`(步长 = 它的元素宽、长度 = 它的个数),
                            // 于是后面那个 `[j]` 走的就是**多维数组那条现成的路**(下标 × 步长 线性累加),
                            // 一个字的新地址机制都不用加;越界文案按"字段"说,不冒充"第 2 维"。
                            // 以前这里一律报"运行期下标后面先不能再放数组字段"(H3 ④ 要放开的正是它)。
                            (链.剩余维 ??= []).Add(new 引用链C.维C
                            {
                                长度 = 后字段.元素个数,
                                步长 = 后字段.元素宽,
                                序号 = 1,
                                元素结构 = 后字段.元素结构,
                                说明文本 = $"字段 '{字段名}' 只有 {后字段.元素个数} 个元素(下标 0~{后字段.元素个数 - 1})",
                            });
                            对齐当前维(链);
                            链.最内元素宽 = 后字段.元素宽;
                            链.下标后偏移 += 后字段.偏移;
                            链.下标后宽度 = 后字段.元素宽;
                            链.下标后结构 = 后字段.元素结构;
                            链.下标后是串元素 = 后字段.元素是字符串;
                            位置 = 下个;
                            continue;
                        }
                        if (后字段.是列表)
                        {
                            // `表[i].数`(结构数组元素里的列表):那个运行期下标算的正是**头在哪儿** ——
                            // 让它留在快照里(头地址自带它),主链把它收掉:不然再取下标时会把它当"元素下标"再算一遍。
                            链.下标后偏移 += 后字段.偏移;
                            var 头快照 = 链.浅复制();
                            链.字段列表 = 建字段列表绑定(头快照, 后字段, 后结构.名称 + "." + 字段名);
                            链.运行期下标 = null;
                            链.下标上界 = 0;
                            链.下标后偏移 = 0;
                            链.下标后宽度 = 4;
                            链.下标后结构 = null;
                            链.下标后是串元素 = false;
                            链.结构 = null;
                            链.宽度 = 后字段.宽度;
                            链.元素宽 = 后字段.列表元素宽;
                            链.元素个数 = 0;                 // 个数是运行期的(容量在头里)
                            链.元素结构 = 后字段.列表元素结构;
                            链.元素是字符串 = false;
                            位置 = 下个;
                            continue;
                        }
                        链.下标后偏移 += 后字段.偏移;
                        链.下标后宽度 = 后字段.宽度;
                        链.下标后结构 = 后字段.结构类型;
                        链.下标后是串元素 = 后字段.是字符串;
                        位置 = 下个;
                        continue;
                    }
                    if (链.结构 is not { } 结构)
                        throw 报错(行号, $"'{基名}{名[基名.Length..位置]}' 不是结构变量,不能用 '.{字段名}'",
                            $"'{字段名}' requires a struct");
                    var 字段 = 结构.找字段(字段名)
                        ?? throw 报错(行号, $"结构 '{结构.名称}' 没有字段 '{字段名}'", $"struct '{结构.名称}' has no field '{字段名}'");
                    校验字段可取用(结构, 字段, 行号);
                    链.偏移 += 字段.偏移;
                    链.声明宽 = 0;                 // 进到字段里去了:字段是紧排的(不是宽槽)
                    // R4-41:字段自己的类型名留一份(见 `末字段类型名`)—— 下标那一支会把它清掉
                    链.末字段类型名 = 字段.类型名;
                    // 第96批(批 13 写浮点库时抓到):**字段要带上自己的符号性**。以前这一层的 `有符号`
                    // 一直沿用根变量的(从 `绑定.有符号` 抄来),而结构变量的类型名不是基本类型 →
                    // `类型C.有符号` 兜底给 true ⇒ `无符号整数 / 无符号短整数` 字段读出来被**符号扩展**、
                    // `>>` 走**算术**右移、比较按有符号比。实测:`结构{无符号整数 低;} 框.低 = 0xFFFFFFFF;`
                    // 打印得 -1、`框.低 >> 1` 得 -1(应为 2147483647、4294967295)。
                    链.有符号 = 类型C.有符号(字段.类型名);
                    if (字段.是列表)
                    {
                        // H1 第四件:字段里的**动态列表**(`整数 数[]`)。头 12 字节就在结构内存里,
                        // 拿"链走到这里"的快照当头的地址(`链地址` = 结构基址 + 偏移,有运行期下标也算得对),
                        // 再往下取下标 / `.添加` / `.长度` 全按列表办。
                        链.字段列表 = 建字段列表绑定(链.浅复制(), 字段, 结构.名称 + "." + 字段.名称);
                        链.结构 = null;
                        链.宽度 = 字段.宽度;
                        链.偏移 = 0;                       // 头地址已经记在快照里:主链的偏移从现在起只算"元素下标"
                        链.元素宽 = 字段.列表元素宽;
                        链.元素个数 = 0;                  // 个数是运行期的(容量在头里)
                        链.元素结构 = 字段.列表元素结构;
                        链.元素是字符串 = false;
                        链.是串元素 = false;
                    }
                    else if (字段.是结构)
                    {
                        链.结构 = 字段.结构类型;
                        链.宽度 = 字段.宽度;
                        链.元素宽 = 0; 链.元素个数 = 0; 链.元素结构 = null;
                    }
                    else if (字段.是数组)
                    {
                        链.结构 = null;
                        链.宽度 = 字段.宽度;
                        链.元素宽 = 字段.元素宽;
                        链.元素个数 = 字段.元素个数;
                        链.元素结构 = 字段.元素结构;
                        链.元素是字符串 = 字段.元素是字符串;
                    }
                    else
                    {
                        链.结构 = null;
                        链.宽度 = 字段.宽度;
                        链.元素宽 = 0; 链.元素个数 = 0; 链.元素结构 = null;
                        链.是串元素 = 字段.是字符串;
                    }
                    位置 = 下个;
                    continue;
                }

                // 下标
                int 右括号 = 找匹配方括号(名, 位置, 行号);
                string 索引文本 = 名[(位置 + 1)..右括号].Trim();
                if (索引文本.Length == 0) throw 报错(行号, $"下标是空的: '{名}'", $"empty index in '{名}'");
                if (链.有运行期下标 && 链.剩余维 is not { Count: > 0 })
                    throw 报错(行号, $"一条引用里先只支持一个运行期下标: '{名}'。分开两步:先算一次地址存进变量,再取第二次",
                        $"only one runtime index per reference: '{名}'");
                if (!链.是数组或列表)
                {
                    // `字符串` 字段/元素(H1 起):`记录.名字[下标]` = 取第几个**文字** —— 与池串的 `名字[下标]`
                    // 完全同一个口径(按 Unicode 码点、下标从 0 起;读出来是 `文字`,写回去可以不一样长)。
                    // 注意下标**不能**折进 链.偏移:那一位留着给"这个 8 字节小块的地址"用(串字地址 靠它)。
                    if (是堆串链(链))
                    {
                        链.串取字 = true;
                        链.有下标 = true;
                        链.宽度 = 4;                  // 取出来的是一个 `文字`(4 字节的码点),不是那块 8 字节
                        位置 = 右括号 + 1;
                        if (uint.TryParse(索引文本, out uint 字下标)) 链.串取字常量 = (int)字下标;
                        else 链.串取字下标文本 = 索引文本;
                        continue;
                    }
                    throw 报错(行号, $"'{名[..位置]}' 不是数组/列表,不能用 [] 下标", $"'{名[..位置]}' is not an array or list");
                }
                位置 = 右括号 + 1;
                链.有下标 = true;
                // R4-41:走到下标这一层,最后那一格就不是"字段"了(是元素)—— 上面记的字段类型名作废
                链.末字段类型名 = null;
                // H68-1:先记住"当前这一维"的形状 —— 走完一维之后 元素宽/元素结构 就换成下一维的了
                var 本维 = 链.剩余维 is { Count: > 0 } 待走 ? 待走[0] : null;
                bool 常量下标 = uint.TryParse(索引文本, out uint 常量);
                if (链.有运行期下标)
                {
                    // 走到这儿 = 前面已经有一个运行期下标,这一层又是个数组 ⇒ 只可能是多维数组接着往下走。
                    // 常量那一维直接折进"运行期下标之后的常量偏移"(与 `表[i].字段` 同一格,加法可交换);
                    // 又是个运行期下标就记进 后续维下标(地址那一步会把它们一维一维累加)。
                    if (常量下标)
                    {
                        if (链.元素个数 > 0 && 常量 >= 链.元素个数)
                            throw 报错(行号, 本维 != null
                                    ? $"下标越界:{名}({本维.说明})"
                                    : $"下标越界:{名}(最多 {链.元素个数} 个)",
                                $"index out of range: {名}");
                        链.下标后偏移 += (int)常量 * 链.元素宽;
                    }
                    else
                        (链.后续维下标 ??= []).Add(new 引用链C.维C
                        {
                            长度 = 链.元素个数,
                            步长 = 链.元素宽,
                            序号 = 本维?.序号 ?? 链.后续维下标.Count + 1,
                            元素结构 = 本维?.元素结构,
                            文本 = 索引文本,
                            说明文本 = 本维?.说明文本,      // H3 ④:数组字段那一档的越界说明要跟着走
                        });
                    走完一维(链);                      // 顺到下一维(走完了就退化成"最内层元素")
                    链.下标后宽度 = 链.剩余维 is { Count: > 0 } 剩 ? 剩[0].步长 : 链.最内元素宽;
                    链.下标后结构 = 链.剩余维 is { Count: > 0 } 剩2 ? 剩2[0].元素结构 : 本维?.元素结构;
                    continue;
                }
                if (常量下标)
                {
                    // 动态列表/容量未知时(元素个数 0)不越界检查:真实容量是运行期的
                    if (链.元素个数 > 0 && 常量 >= 链.元素个数)
                        throw 报错(行号, 链.多维 && 本维 != null
                                ? $"下标越界:{名}({本维.说明})"
                                : $"下标越界:{名}(最多 {链.元素个数} 个)",
                            $"index out of range: {名}");
                    链.偏移 += (int)常量 * 链.元素宽;
                    链.结构 = 链.元素结构;
                    链.宽度 = 链.元素宽;
                    链.是串元素 = 链.元素是字符串;      // `字符串 名单[2]` 取出来就是一个字符串(8 字节那块)
                    链.元素是字符串 = false;
                    链.声明宽 = 0;                 // 数组/列表元素是紧排的
                    if (链.多维) 走完一维(链);      // H68-1:还有下一维就顺过去;走完了 元素宽/个数/结构 都归 0
                    else { 链.元素宽 = 0; 链.元素个数 = 0; 链.元素结构 = null; }
                    continue;
                }
                链.运行期下标 = 索引文本;
                链.下标上界 = 链.元素个数;         // 边界检查要用的"这个数组有几个"(下面就把 元素个数 清掉了)
                链.下标元素宽 = 链.元素宽;
                链.下标后偏移 = 0;
                链.下标后是串元素 = 链.元素是字符串;
                链.元素是字符串 = false;
                链.声明宽 = 0;                 // 带运行期下标 → 元素紧排
                链.结构 = null;
                if (链.多维)
                {
                    走完一维(链);
                    链.下标后宽度 = 链.剩余维 is { Count: > 0 } 剩 ? 剩[0].步长 : 链.最内元素宽;
                    链.下标后结构 = 链.剩余维 is { Count: > 0 } 剩2 ? 剩2[0].元素结构 : 本维?.元素结构;
                }
                else
                {
                    链.下标后结构 = 链.元素结构;
                    链.下标后宽度 = 链.元素宽;
                    链.元素宽 = 0; 链.元素个数 = 0; 链.元素结构 = null;
                }
            }
            // H68-1:多维数组必须把各维下标写全(`袋[行][列]`)—— 只写一半既不是标量也不是数组,当场说清楚
            if (链.多维 && 链.剩余维 is { Count: > 0 } 还缺维)
                throw 报错(行号, $"多维数组 '{基名}' 不能这样用(还差 {还缺维.Count} 维下标):'{名}'。" +
                    $"读改一个元素要把各维下标写全(例如 {基名}[0][0]);" +
                    $"整块用法(当数组参数传 / 取地址 / 整体赋值 / 当值读)多维数组一律不做 ——" +
                    $"要整块用请改成一维数组(自己按下标算)或结构数组",
                    $"multi-dimensional array needs all subscripts: '{名}'");
            return 链;
        }

        /// <summary> H68-1:把链的"当前这一维"对齐到 `剩余维` 的第一维(多维数组专用;单维链一次都不会走到) </summary>
        private static void 对齐当前维(引用链C 链)
        {
            if (链.剩余维 is { Count: > 0 } 剩)
            {
                链.元素宽 = 剩[0].步长;
                链.元素个数 = 剩[0].长度;
                链.元素结构 = 剩[0].元素结构;
                链.元素是字符串 = false;
                return;
            }
            链.元素宽 = 0; 链.元素个数 = 0; 链.元素结构 = null; 链.元素是字符串 = false;
        }

        /// <summary>
        /// H68-1:走完一维 —— 多维链把"当前这一维"顺到下一维(走完了就退化成标量:个数/结构都清掉)。
        /// **单维链(剩余维 null)什么都不做** ⇒ 老写法那一句照旧由调用点自己写,机器码一个字节不变。
        /// </summary>
        private static void 走完一维(引用链C 链)
        {
            if (链.剩余维 is not { Count: > 0 } 剩) return;
            剩.RemoveAt(0);
            对齐当前维(链);
        }

        /// <summary> 找与 左方括号 配对的 ']' </summary>
        private int 找匹配方括号(string 文本, int 左方括号, int 行号)
        {
            int 深度 = 0;
            for (int i = 左方括号; i < 文本.Length; i++)
            {
                if (文本[i] == '[') 深度++;
                else if (文本[i] == ']' && --深度 == 0) return i;
            }
            throw 报错(行号, $"下标缺少 ']': '{文本}'", $"missing ']' in '{文本}'");
        }

        /// <summary>
        /// 造一个"字段里的列表"绑定(H1 第四件):头 12 字节在结构内存里,`头快照` 是"链走到那个字段"的样子;
        /// 元素按字段的声明(宽 / 结构)。**不进 `_列表表`** —— 它没有具名槽,是按引用链现算的。
        /// </summary>
        private 列表绑定C 建字段列表绑定(引用链C 头快照, 结构字段C 字段, string 名称)
        {
            var 类型 = new 列表类型C(字段.类型名, 字段.列表元素宽, 0, 容量写死: false, 字段.列表元素结构);
            return new 列表绑定C { 名称 = 名称, 类型 = 类型, 字段链 = 头快照 };
        }

        /// <summary> 这条链上的列表绑定:具名列表按槽名找,字段里的列表直接取链上带的那个 </summary>
        private 列表绑定C 取链列表(引用链C 链, int 行号)
        {
            if (链.字段列表 is { } 字段列表) return 字段列表;
            return 按槽找列表(链.绑定.名称)
                ?? throw 报错(行号, $"列表 '{链.基名}' 的内部状态丢了(不该发生)", "lost list state");
        }

        /// <summary>
        /// **H68-1 多维数组的元素地址**:`基址 + 偏移 + Σ(各维下标 × 维步长) + 下标后偏移`。
        /// 常量维已经折进 `偏移` / `下标后偏移`,这里只算运行期那几维。
        ///
        /// **硬约束(上一版就是栽在这儿、整批撤回的)**:累加寄存器**不许跨下标表达式活着** ——
        /// 每算完一维就把累加值**落进临时槽**,下一维的下标表达式求值期间一个寄存器都不多占。
        /// 为什么必须:`表达式临时寄存器` 只有 15 个,上一版把累加值一路攥在寄存器里,长表达式
        /// (示例13 哈希表 / 示例16 控件库)正好卡在天花板上,报「这一句太复杂了:临时寄存器用光了」。
        /// 落槽之后多了"一存一读"两条,但**寄存器存活期与单维数组完全一样**。
        /// </summary>
        private string 链多维元素地址(引用链C 链, int 行号, string 原文)
        {
            var 槽 = 新临时槽();
            // 每一维都**按段收回自己借的临时寄存器**:算完立刻落槽,这一段用掉的寄存器**全部还回池子**
            // (`记占用` / `还占用` 那一对:退回快照 ⇒ 外层表达式还在用的那几位**照旧占着、不会被重复发出去**)。
            // 这是"累加寄存器不许跨下标表达式活着"的落地形态 —— 光落槽不还寄存器等于没还:下一维的下标
            // 表达式照样撞那 15 个的上限(实测:不还的话一句里只放得下 2 个二维访问,摊平写法放得下 4 个;
            // 还了之后两者同为 4 个)。**别用 `自成一段`**:它把占用表清空重来,外层还活着的寄存器会被踩
            // (实测:值算错 —— `袋[r][c]` 读出隔壁那一格)。
            {
                var 省着 = 记占用();
                string 一 = 索引到寄存器(链.运行期下标!, 行号, 原文);
                输出下标检查(一, (链.下标上界, null, null, $"第 1 维只有 {链.下标上界} 个元素(下标 0~{链.下标上界 - 1})"), 行号, 原文);
                缩放下标(一, 链.下标元素宽);
                发出写变量(一, 槽);
                还占用(省着);
            }
            foreach (var 维 in 链.后续维下标!)
            {
                var 省着 = 记占用();
                string 下标 = 索引到寄存器(维.文本!, 行号, 原文);
                输出下标检查(下标, (维.长度, null, null, 维.说明), 行号, 原文);
                缩放下标(下标, 维.步长);
                string 累加 = 新临时();
                发出读变量(累加, 槽);
                发出($"ADD {累加} {下标}");
                发出写变量(累加, 槽);
                还占用(省着);
            }
            string 地址;
            // R6-3:字段里的列表(`筐.数[i]`)基址一律是"头里的数据地址",与基址是不是指针无关
            if (链.是指针基址 && 链.字段列表 is null)
            {
                地址 = 新临时();
                发出读变量(地址, 链.绑定.槽);
            }
            else if (链.是列表)
                地址 = 取列表基址(取链列表(链, 行号));
            else
                地址 = 取基址(链.绑定.名称);
            if (链.偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {链.偏移}");
            // 把"槽里那个累加值"并进地址:**这一段借的中转寄存器用完就还回池子**
            // (H3 ④:一条链里可能出现好几个 `下标 × 步长`,`末` 不还的话每个访问都白占一个,
            //  3 个访问就把 15 个临时寄存器占满 —— 实测 3 字段结构下 `架[i].数[j] + 架[i].数[0] + …` 编不过)
            {
                var 省着 = 记占用();
                string 末 = 新临时();
                发出读变量(末, 槽);
                发出($"ADD {地址} {末}");
                还占用(省着);
            }
            if (链.下标后偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {链.下标后偏移}");
            return 地址;
        }

        /// <summary> 引用链里"要运行时算地址"的那种(列表元素 / 运行期下标):把元素地址算进寄存器 </summary>
        /// <remarks> R6-3:字段里的列表(`筐.数[i]`)基址一律走"头里的数据地址",不用管基址是不是指针。 </remarks>
        private string 链元素地址(引用链C 链, int 行号, string 原文)
        {
            if (链.后续维下标 is { Count: > 0 }) return 链多维元素地址(链, 行号, 原文);
            // H3 ④ 顺手收的一处:`下标`(与它求值/检查/缩放期间借的那些中转寄存器)**用完就还回池子** ——
            // 以前一直占着,一个访问白占两三个,一句里放得下的访问个数就少一个(实测:结构数组里
            // 取下标 2 个就撞 15 个的上限,多维数组那条路能放 3 个,而两条路本应是同一个阈值)。
            var 省着 = 记占用();
            string 下标 = 索引到寄存器(链.运行期下标!, 行号, 原文);
            输出下标检查(下标, 下标上界(链, 行号, 原文), 行号, 原文);
            // P1 数组地址增量:循环里的归纳变量访问定长数组 → 直接拿常驻的步进指针当地址(缩放/取基址/相加全省了)。
            // 越界检查照旧做(比下标),所以越界行为与原来一模一样。
            if (步进指针(链.基名, 链.运行期下标!, 链.下标元素宽, 链.偏移) is { } 步进) return 步进;
            string 地址;
            // R6-3:字段里的列表(`筐.数[i]`)基址一律是"头里的数据地址",与基址是不是指针无关 ——
            // 结构参数 / 引用变量(是指针基址)也得先解引用头,不然下标会加在头本身上(写坏 长度 / 容量,数据全丢)。
            if (链.是指针基址 && 链.字段列表 is null)
            {
                地址 = 新临时();
                发出读变量(地址, 链.绑定.槽);
            }
            else if (链.是列表)
                地址 = 取列表基址(取链列表(链, 行号));
            else
                地址 = 取基址(链.绑定.名称);
            if (链.偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {链.偏移}");
            // ISA 扩容批 2(0x53 `取地址索引`):元素宽是 2 的幂时,"缩放 + 相加"两条并成一条
            // (不是 2 的幂(结构数组那种)照旧走 `缩放下标` + `ADD`)。
            if (缩放位数(链.下标元素宽) is { } 缩放)
            {
                发出($"取地址索引 {地址} {下标} {地址} {缩放}");
            }
            else
            {
                缩放下标(下标, 链.下标元素宽);
                发出($"ADD {地址} {下标}");
            }
            还占用(省着, 地址);            // `下标` 已经并进地址了:它和这一段的临时寄存器都还回去
            if (链.下标后偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {链.下标后偏移}");
            return 地址;
        }

        /// <summary>
        /// 引用链的"数据地址"到寄存器:静态的 = 基址 + 常量偏移;有运行期下标/列表的走 链元素地址。
        /// 注意:数组/列表**整名**也走这里(地址(表) 要的就是这个基址),所以这里不做"必须带下标"的检查 ——
        /// 那个检查在 链读到寄存器/链写 里(标量读宽 = 0 就报)。
        /// </summary>
        private string 链地址(引用链C 链, int 行号, string 原文)
        {
            if (链.有运行期下标) return 链元素地址(链, 行号, 原文);
            string 地址;
            // R6-3:字段里的列表(`筐.数[i]`)基址一律是"头里的数据地址",与基址是不是指针无关 ——
            // 结构参数 / 引用变量(是指针基址)也得先解引用头,不然下标会加在头本身上(写坏 长度 / 容量,数据全丢)。
            if (链.是指针基址 && 链.字段列表 is null)
            {
                // 引用:基址 = 槽里装的地址(读出来)
                地址 = 新临时();
                发出读变量(地址, 链.绑定.槽);
            }
            else if (链.是列表)
                地址 = 取列表基址(取链列表(链, 行号));
            else 地址 = 取基址(链.绑定.名称);
            if (链.偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {链.偏移}");
            return 地址;
        }

        /// <summary> 从引用链读一个标量到寄存器(1/2/4 字节);整块结构不能这么读,给明确报错 </summary>
        /// <summary>
        /// P12 + A3(索引寻址):`表[下标]` 读一个字,能用一条 `取字索引` 顶掉"缩放 + 相加 + 取字间接"。
        /// 只在这几种条件全满足时发(其余一律返回 null,交给老路 —— 老路连同它的报错一个字没改):
        ///   ① 读宽 4(一个字)/ 读宽 2(半个字,读完掩码)
        ///   ② 元素宽 4(缩放 2)、8(缩放 3,A3 起)、2(缩放 1,A3 起):`点 表[i].x`、`短整数 表[i]`
        ///      这种以前是"缩放 + 取基址 + 相加 + 取字间接(±掩码)"三到五条,现在两条(到三条)
        ///      —— 1 字节元素不做:老路本来就是一条**按字节**读,换成索引读要读 4 字节再掩码,不省还多读 3 字节
        ///   ③ 有运行期下标 ④ 不是"指针基址/引用" ⑤ 没吃上 P1 的步进指针(P1 那条本来就是 1 条,别抢)
        /// 常量偏移(链.偏移 / 下标后偏移)折进基址那一步(`ADD_IMMEDIATE`),各花 1 条,仍然净赚。
        /// 越界检查照旧(`输出下标检查`),所以越界行为与原来一模一样。
        /// </summary>
        private string? 试发取字索引(引用链C 链, int 行号, string 原文)
        {
            if (!链.有运行期下标) return null;
            // H68-1:多维数组(两个以上运行期下标)的地址要"各维累加 + 落槽",不是一条"基 + 下标×2^k"能表示的
            if (链.后续维下标 is { Count: > 0 }) return null;
            // 读宽 4:元素宽 4(缩放 2)/ 8(缩放 3,A3 起);读宽 2:元素宽 2(走 `取半字索引`,见下)
            bool 读半字 = 链.标量读宽 == 2 && 链.下标元素宽 == 2;
            int 缩放;
            if (链.标量读宽 == 4 && 链.下标元素宽 is 4 or 8) 缩放 = 链.下标元素宽 == 8 ? 3 : 2;
            else if (读半字) 缩放 = 1;
            else return null;
            if (链.是指针基址) return null;
            if (是字符串取字(链) || 是堆串链(链)) return null;
            // P1 的步进指针要问在**发下标检查之前**:1/2 字节元素的循环里 P1 本来就有常驻指针,
            // 那时候连越界检查都不该再发一遍(第98批的老代码把这条排在后面 —— 4 字节元素恰好
            // 碰不上步进指针才没露出来;A3 把 2 字节也放进这条路,就得重排)。
            if (步进指针(链.基名, 链.运行期下标!, 链.下标元素宽, 链.偏移) is not null) return null;
            string 下标 = 索引到寄存器(链.运行期下标!, 行号, 原文);
            输出下标检查(下标, 下标上界(链, 行号, 原文), 行号, 原文);
            string 基 = 链.是列表
                ? 取列表基址(取链列表(链, 行号))
                : 取基址(链.绑定.名称);
            if (链.偏移 > 0) 发出($"ADD_IMMEDIATE {基} {链.偏移}");
            if (链.下标后偏移 > 0) 发出($"ADD_IMMEDIATE {基} {链.下标后偏移}");
            if (读半字)
            {
                // ISA 扩容批 3(0x54 `取半字索引`):读出来就是低 16 位 ⇒ `与立即数 0xFFFF` 那一条省掉
                // (有符号的 2 字节元素仍要补符号位,与下面老路同一个口径)。
                发出($"取半字索引 {基} {下标} {基} 1");
                if (链.有符号) 发出符号扩展(基, 2);
                return 基;
            }
            发出($"LOAD_WORD_INDEX {基} {下标} {缩放}");
            return 基;
        }

        private string 链读到寄存器(引用链C 链, int 行号, string 原文)
        {
            // 字符串取一个字:按**文字**下标(越界按文字数查),解出来是 `文字`(Unicode 码点)
            if (是字符串取字(链))
            {
                // 同 试取文字值:内部临时全包进"自立一段",对外只占住最后那个码点
                string 码点 = "";
                自成一段保守(() =>
                {
                    var (数据址, 字节长) = 取字串数据与字节长(链, 行号, 原文);
                    string 下标 = 取字下标寄存器(链, 行号, 原文);
                    string 文字数 = 发出数文字(数据址, 字节长);
                    发出文字下标检查(下标, 文字数, 行号, 原文);
                    码点 = 发出取文字(数据址, 下标, 行号).码点;
                });
                return 收下临时(码点);
            }
            // 堆串字段/元素当**值**用 = 它存的那个"数据地址"(和 `地址` 一个意思;`释放(记录.名字)` 就靠这条)
            if (是整段堆串链(链))
            {
                string 串数据 = 新临时();
                发出间接读(串数据, 串字地址(链, 行号, 原文), 4);
                return 串数据;
            }
            // 可写字符串参数(`字符串 出 名字`)是整个字符串:当数字用就等于把"头的地址"当数用,直接拦住
            if (是出参(链.基名))
                throw 报错(行号, $"'{原文}' 是**字符串**(`出` 参数,可写),不能当数字用。" +
                    $"看内容用 输出({原文}) / 输出行({原文});看长度用 {原文}.长度();要取某个字写 {原文}[下标];要整份改就 {原文} = \"…\";",
                    $"'{原文}' is a writable string parameter; use it as a string");
            int 宽 = 链.标量读宽;
            if (宽 == 0)
                throw 报错(行号, $"'{原文}' 要带下标(如 {原文}[0])或者用 {原文}.长度();列表还能用 {原文}.添加(值)",
                    $"'{原文}' needs an index");
            if (宽 is < 0 or > 8)
                throw 报错(行号, $"'{原文}' 是一整块({宽} 字节),不能当数字读:点到字段(如 .x),或者用 右 = 左 整体赋值",
                    $"'{原文}' is {宽} bytes; use a field or whole-struct assignment");
            // P12:能一条 `取字索引` 搞定就搞定(条件见那个函数;发不成就走老路)
            if (试发取字索引(链, 行号, 原文) is { } 直接读) return 直接读;
            string 地址 = 链地址(链, 行号, 原文);
            string 目标 = 新临时();
            发出间接读(目标, 地址, 宽);
            // T6(2026-09-27 评测整改):2 字节**有符号**元素读出来要补符号位。
            // 常量下标的数组元素走的是 `发出读变量`(它本来就补),而**列表元素 / 带运行期下标的数组 /
            // 结构里的动态下标**走这一条:间接读只 `取字 + 与 0xFFFF`(零扩展)⇒
            // `列.添加(40000); 输出行(列[0]);` 打出 40000,而同一个值放进数组元素是 -25536 —— 同一族两个答案。
            if (宽 == 2 && 链.有符号) 发出符号扩展(目标, 2);
            return 目标;
        }

        /// <summary>
        /// A3(第102批)+ ISA 扩容批 3:`表[下标] = 值` 写一个元素,能用一条索引存储顶掉"缩放 + 相加 + 存字间接":
        /// **写宽 = 元素宽**的三种都做 —— 4 字节 → `存字索引`(0x33)、2 字节 → `存半字索引`(0x55)、
        /// 1 字节 → `存字节索引`(0x56)。条件与 `试发取字索引` 同一套(有运行期下标 + 不是指针基址 +
        /// 没吃上 P1 步进指针),偏移同样折进基址。老路那几条按字节存储照旧留着当兜底。
        /// </summary>
        private bool 试发存字索引(string 源寄存器, 引用链C 链, int 行号, string 原文, 地址位置? 值槽 = null)
        {
            bool 半字 = 链.标量读宽 == 2 && 链.下标元素宽 == 2;
            bool 字节 = 链.标量读宽 == 1 && 链.下标元素宽 == 1;
            if (!半字 && !字节 && (链.标量读宽 != 4 || 链.下标元素宽 is not (4 or 8))) return false;
            if (!链.有运行期下标) return false;
            if (链.后续维下标 is { Count: > 0 }) return false;      // H68-1:多维数组走"各维累加"那条路
            if (链.是指针基址) return false;
            if (是字符串取字(链) || 是堆串链(链)) return false;
            if (步进指针(链.基名, 链.运行期下标!, 链.下标元素宽, 链.偏移) is not null) return false;
            string 下标 = 索引到寄存器(链.运行期下标!, 行号, 原文);
            输出下标检查(下标, 下标上界(链, 行号, 原文), 行号, 原文);
            string 基 = 链.是列表
                ? 取列表基址(取链列表(链, 行号))
                : 取基址(链.绑定.名称);
            if (链.偏移 > 0) 发出($"ADD_IMMEDIATE {基} {链.偏移}");
            if (链.下标后偏移 > 0) 发出($"ADD_IMMEDIATE {基} {链.下标后偏移}");
            if (值槽 is { } 槽) 发出读变量(源寄存器, 槽);          // H71:算址那一段可能 CALL,值从槽里补回来
            if (半字) 发出($"存半字索引 {基} {下标} {源寄存器} 1");
            else if (字节) 发出($"存字节索引 {基} {下标} {源寄存器} 0");
            else 发出($"STORE_WORD_INDEX {基} {下标} {源寄存器} {(链.下标元素宽 == 8 ? 3 : 2)}");
            return true;
        }

        /// <summary>
        /// H71(第352批):**这一条引用链"算地址"那一段会不会调函数**。
        /// 会的话,赋值时"右边算出来的值"必须先在临时槽里躲一下 —— 那个 CALL 会把寄存器池整个冲一遍
        /// (被调方拿它们当草稿),值寄存器当场失效。实测最小复现(20 行,`--no-opt` 下必现):
        /// `表[尾(0, 0, 4)] = 10; 输出行(表[0]);` 打出 0(写进去的是被冲掉的寄存器);
        /// 把 `尾` 的三参数版换成"没有 `如果` 的一行版"也一样 —— **只要下标里有调用就中招**。
        /// 判据用 `文本含调用`(宁可多存一次,不能漏;漏了是静默写错值 —— 与 `输出比较跳转` 同一条尺子)。
        /// </summary>
        private static bool 链地址含调用(引用链C 链)
        {
            if (链.运行期下标 is { } 第一维 && 文本含调用(第一维)) return true;
            if (链.后续维下标 is { } 后面几维)
                foreach (var 维 in 后面几维)
                    if (维.文本 is { } 文本 && 文本含调用(文本)) return true;
            return false;
        }

        /// <summary> 往引用链写一个标量(1/2/4 字节);整块结构不能这么写(留给整体赋值) </summary>
        private void 链写(string 源寄存器, 引用链C 链, int 行号, string 原文, 地址位置? 值槽 = null)
        {
            // 字符串取一个字 = **换掉第几个文字**:新文字可以是任意长度(字节数变了就把后面的内容挪一挪),不够就扩容
            if (是字符串取字(链))
            {
                // 换字那一条**自带落槽**:`发出换一个字` 一上来就把新码点写进 `换字值(28)`,
                // 后面几段要跨 CALL 时从那个槽读回来(见那句"码点也要落槽")⇒ 它不用 `值槽`。
                发出换一个字(链, 源寄存器, 行号, 原文);
                return;
            }
            int 宽 = 链.标量读宽;
            if (宽 == 0)
                throw 报错(行号, $"'{原文}' 要带下标才能写(如 {原文}[0]);列表请用 {原文}.添加(值)",
                    $"'{原文}' needs an index");
            if (宽 is < 0 or > 8)
                throw 报错(行号, $"'{原文}' 是一整块({宽} 字节),不能这样写:点到字段,或者整体赋值(右 = 左)",
                    $"'{原文}' is {宽} bytes wide");
            // A3:4 字节元素一条 `存字索引` 搞定(条件见那个函数;发不成就走老路)
            if (试发存字索引(源寄存器, 链, 行号, 原文, 值槽)) return;
            // 地址先算完(这一段可能 CALL),再把值从槽里补回寄存器,最后才写 —— 顺序不能颠倒
            string 址 = 链地址(链, 行号, 原文);
            if (值槽 is { } 槽) 发出读变量(源寄存器, 槽);
            发出间接写(源寄存器, 址, 宽);
        }
        #endregion
