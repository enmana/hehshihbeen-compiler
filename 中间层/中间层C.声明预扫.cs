using System;
using System.Collections.Generic;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 中间层展开器的一部分:**工程级声明预扫**(第94批 Q1b)。
    ///
    /// 为什么要有这一趟:函数靠构造函数里的"预扫函数头"收签名,所以**跨文件任意顺序**都能调;
    /// 而**结构类型**与**顶层全局变量**是在**逐句处理**时登记的(第94批之前)⇒ 只有排在声明之后的
    /// 语句才看得见;工程文件又把启动文件排第一 ⇒ 库文件里的结构与全局,主程序根本用不了(只能靠 `包含` 绕)。
    ///
    /// 这一趟在构造函数里、逐句处理之前跑,**只登记、不发代码**:
    ///   · 结构:登记 `_结构表` + `_名字表.结构`(结构声明本来就不发码);
    ///   · 顶层全局变量:开数据槽 + 登记根作用域 + 调试名字表(列表/字符串只把这些提前),
    ///     **初始化代码一个字都不发**(它必须留在原语句那一句上:
    ///     `整数 a = 1; a = 5; 整数 b = a;` 里 b 要等到那一句才取 5)。
    ///
    /// **"已预登记"协议**(键 = 登记全名,值 = 声明在 `_伪行表` 里的下标):
    /// 预扫登记成功的声明记进 `_已预登记结构` / `_已预登记全局`;逐句处理到同一条声明时,
    /// 凭"全名 + 下标"认出它 ⇒ **跳过登记与重名检查,只发它该发的初始化代码**。
    /// 同名第二处声明(下标对不上)照旧走原路 ⇒ 重名照样报错、照样带两处位置(第94批 D2 口径不退化)。
    /// 下标要一起对上(而不是只看全名)正是为了这一条:两处同名声明全名相同,只看全名就会把第二处也当成
    /// "预登记过的"跳过去,重名就静悄悄地漏了。
    ///
    /// 预扫是**尽力而为**:哪一条认不出来/解析不动就跳过它,原样交给逐句处理那一趟去报错(报错文案与
    /// 行号一条都不变)。所以预扫里一条错误都不报,只 catch 掉。
    /// </summary>
    internal partial class 中间层展开器
    {
        /// <summary> 已预登记的结构:登记全名 → 声明所在伪行下标 </summary>
        private readonly Dictionary<string, int> _已预登记结构 = new(StringComparer.OrdinalIgnoreCase);

        /// <summary> 已预登记的顶层全局变量:登记全名 → 声明所在伪行下标 </summary>
        private readonly Dictionary<string, int> _已预登记全局 = new(StringComparer.OrdinalIgnoreCase);

        /// <summary>
        /// 预扫顺手收下的**方法容器裸名**(H60 步①)。**不改任何语义**,只为把一句报错说准:
        /// 容器名从 H60 起能当类型名用(`计数器 计数;`),而容器是**逐句处理**时登记的 ⇒
        /// "先用后声明"那行会一路透传到汇编器、报成"未知指令: 计数器"(把人往"指令拼错了"的方向带)。
        /// 有这样一份名单,就能当场说清"它是个方法容器,先声明再用"。
        /// </summary>
        private readonly HashSet<string> _预扫容器名 = new(StringComparer.OrdinalIgnoreCase);

        /// <summary> 现在跑的是"预扫声明"这一趟(只登记不发码;见 `预扫顶层声明`) </summary>
        private bool _预扫声明中;

        /// <summary>
        /// 预扫一遍**顶层声明**(结构与顶层全局变量)。调用点:构造函数里"预扫函数头"之后 ——
        /// 那一步已经把软栈槽的槽号占下了,所以这里的槽号接着它排,与"没有预扫"时的相对顺序一致。
        /// </summary>
        private void 预扫顶层声明()
        {
            var 顶层 = 收集顶层行();
            if (顶层.Count == 0) return;
            预扫枚举(顶层);        // H68-2:枚举排在结构前头 —— 结构字段可以是枚举类型(`结构 卡 { 颜色 花; }`)
            预扫结构(顶层);
            预扫容器名(顶层);
            预扫全局(顶层);
            // 现场复位:预扫只是"提前看一眼",处理语句 每条都会自己按表设一遍(不留状态更不容易出错)
            _当前模块 = "";
            _当前工程 = "";
            _当前文件 = "";
            _当前文件号 = -1;
            _当前来源文件 = "";
            _本句私有 = false;
            _本句程序集 = false;
            _本句来自包含 = false;
        }

        /// <summary>
        /// 收下"块深度正好是 0 的语句行"。深度 0 一条就把下面这些全排除了:
        /// 函数体、结构体自身(字段行)、方法容器、以及 `如果`/`循环`/`测试` 这些块里的局部声明
        /// —— 那些本来就不是"顶层全局变量"。
        /// 整块写在一行里的(`如果 (…) { 计数 = 1; }`)不用另外挡:那种行的首个词是 `如果`/`否则`/`测试` 之类,
        /// 本来就过不了"是不是声明行/结构头"那两道尺子(而一行里带 `{` 的**数组/结构字面量初值**
        /// 恰好要认,所以不能见 `{` 就跳过)。
        /// </summary>
        private List<int> 收集顶层行()
        {
            var 表 = new List<int>();
            int 深度 = 0;
            for (int i = 0; i < _伪行表.Count; i++)
            {
                string 行 = _伪行表[i];
                if (行 == "{") { 深度++; continue; }
                if (行 == "}") { 深度--; if (深度 < 0) return 表; continue; }   // 多余的 '}':形状已经坏了,预扫到此为止
                if (深度 != 0) continue;
                表.Add(i);
            }
            return 表;
        }

        /// <summary>
        /// 结构先扫,而且**一轮一轮扫到不再有新登记**:a 文件的结构可能把b 文件的结构当字段,
        /// 一个文件里也可能"前面的结构用了后面的结构"。转几轮就收敛(互相嵌套的死循环收敛不了,
        /// 照旧由逐句处理那一趟报"未知的字段类型")。
        /// </summary>
        private void 预扫结构(List<int> 顶层)
        {
            var 候选 = new List<int>();
            foreach (int i in 顶层)
            {
                string 行 = 去可见性前缀(_伪行表[i]);
                if (中间层C.到英文关键字(取首词(行)) == "struct") 候选.Add(i);
            }
            if (候选.Count == 0) return;
            bool 有进展 = true;
            while (有进展)
            {
                有进展 = false;
                foreach (int i in 候选)
                    if (尝试预登记结构(i)) 有进展 = true;
            }
        }

        /// <summary> 试登记一条结构声明;登记成功返回 true(失败一律不吭声,交给逐句处理那趟) </summary>
        private bool 尝试预登记结构(int 下标)
        {
            string 原始行 = _伪行表[下标];
            string 行 = 去可见性前缀(原始行);
            if (中间层C.到英文关键字(取首词(行)) != "struct") return false;
            try
            {
                设置预扫现场(下标, 原始行);
                string 结构名 = 限定名(行[取首词(行).Length..].Trim());
                if (_已预登记结构.ContainsKey(结构名) || _结构表.ContainsKey(结构名)) return false;
                int 位置 = 下标;
                处理结构声明(ref 位置, 预扫: true);
                return _已预登记结构.ContainsKey(结构名);
            }
            catch (Exception)
            {
                // 预扫一条错都不报:这一条原样留给逐句处理那一趟(报错文案/行号/两处位置都在那儿)
                return false;
            }
        }

        /// <summary>
        /// 收下顶层**方法容器**的裸名(只为报错说得准,见 `_预扫容器名`;一条错都不报、也不登记任何类型)。
        /// 形状与 `试读容器名` 同一把尺子:`静态 方法 名(...)`,不带尾缀 `返回 类型`。
        /// </summary>
        private void 预扫容器名(List<int> 顶层)
        {
            foreach (int i in 顶层)
            {
                string 行 = 去可见性前缀(_伪行表[i]);
                string 首词 = 取首词(行);
                if (中间层C.到英文关键字(首词) != "static") continue;
                string 余下 = 行[首词.Length..].Trim();
                string 次词 = 取首词(余下);
                if (中间层C.到英文关键字(次词) == "method") 余下 = 余下[次词.Length..].Trim();
                if (解析签名(余下) is { } 容器名) _预扫容器名.Add(容器名);
            }
        }

        /// <summary>
        /// 顶层全局变量:与逐句处理用**同一把尺子**(`是声明行`)认出来,再借 `处理声明文本` 登记。
        /// 预扫这一趟只做"登记该做的事":标量/数组/结构变量/字符串数组 = 开数据槽 + 登记绑定;
        /// 列表与字符串 = 只开槽(动态的那几槽由逐句处理那一句补发"从池里要一块");
        /// **初始化代码一律不发** —— 初值只属于原语句那一句。
        /// 唯一不进预扫的是**引用**声明(`引用 点 p = 位置`):它登记时就要算目标地址(发码),照旧"声明在前"。
        /// </summary>
        private void 预扫全局(List<int> 顶层)
        {
            foreach (int i in 顶层)
            {
                string 原始行 = _伪行表[i];
                string 行 = 去可见性前缀(原始行);
                if (行.Length == 0) continue;
                if (中间层C.到英文关键字(取首词(行)) is "struct" or "method" or "static") continue;
                try
                {
                    设置预扫现场(i, 原始行);
                    if (!是声明行(行)) continue;
                    _预扫声明中 = true;
                    处理声明文本(行, _伪行号表[i], i);
                }
                catch (Exception)
                {
                    // 同上:预扫不报错。登记成功与否看 `_已预登记全局`(逐句处理那一趟据此决定跳不跳登记)
                }
                finally
                {
                    _预扫声明中 = false;
                }
            }
        }

        /// <summary> 这个名字的声明就在 `声明下标` 这一行、而且是预扫登记的那一条?(Q1b 的"已预登记"协议) </summary>
        private bool 已预登记全局到本行(string 全名, int 声明下标)
            => 声明下标 >= 0 && _已预登记全局.TryGetValue(全名, out int 预行) && 预行 == 声明下标;

        /// <summary>
        /// 预扫某一行之前,把"这一行属于哪个模块/文件/工程、前面写了哪个可见性前缀"摆好 ——
        /// 与 `处理语句` 摆的是同一套(结构/全局的 `私有`/`程序集` 档位就靠它记对)。
        /// </summary>
        private void 设置预扫现场(int 下标, string 原始行)
        {
            _当前模块 = _伪行模块表[下标];
            _当前工程 = 文件工程(下标);
            _当前源行号 = _伪行号表[下标];
            _当前文件号 = _伪行文件表[下标];
            _当前文件 = _当前文件号 >= 0 && _当前文件号 < _工程文件表.Count ? _工程文件表[_当前文件号] : "";
            _当前来源文件 = _伪行来源表[下标];   // 真正写这一行的是哪一份文件(与 `处理语句` 摆同一套;见 `_当前来源文件`)
            _本句来自包含 = _伪行来自包含[下标];
            记文件归属();      // C19:预扫这一趟也要让"文件 → 模块/工程"这张表先有值(补全在编译后立刻要用)
            _本句私有 = false;
            _本句程序集 = false;
            string? 可见性 = 中间层C.到英文关键字(取首词(原始行));
            if (可见性 == "private") _本句私有 = true;
            else if (可见性 == "internal") _本句程序集 = true;
            // H2:`公共` / `public` 是显式"公开",不记档位(与不写同义)—— 这里照旧只认前两个
        }
    }
}
