using System.IO;
using System.Text.RegularExpressions;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary> 一个文件展开后的调试信息(单步调试用) </summary>
    public sealed class 文件映射C
    {
        /// <summary> 文件全称 </summary>
        public string 文件 = "";
        /// <summary> 这段代码在整段机器码里的起始地址 </summary>
        public int 基址;
        /// <summary> 这个文件编译出来有几条指令 </summary>
        public int 条数;
        /// <summary> 展开后的汇编文本(带 "// 来自第 N 行" 标记;"汇编单步"直接把它显示在编辑器里) </summary>
        public string 展开文本 = "";
        /// <summary>
        /// **机器码绝对地址** → 源码第几行(语言单步用)。
        /// 键是绝对地址、不是段内偏移:合并编译单元之后,一个文件的指令不再连成一段
        /// (各文件的主程序行在前、所有函数体统一排在后面),所以只能按绝对地址查。
        /// </summary>
        public Dictionary<int, int> 地址到源行 = [];
        /// <summary> **机器码绝对地址** → 展开文本第几行(汇编单步用;显示的就是 展开文本,行号直接对得上) </summary>
        public Dictionary<int, int> 地址到显示行 = [];
        /// <summary> 这个文件的调试名字表(变量名/类型/在哪;槽名已按文件序号唯一化,和机器码里的标签对得上) </summary>
        public 名字表C 名字表 = new();

        /// <summary> 这个地址落在本文件的代码里吗(按绝对地址查表,不要求本文件的指令连续) </summary>
        public bool 含地址(int 地址) => 地址到显示行.ContainsKey(地址);
    }

    /// <summary>
    /// "机器码地址 → 哪个文件、第几行"的映射,给单步调试在编辑器里标出当前执行行用。
    ///
    /// 为什么不能用老办法:老的 汇编器C.取地址到行号映射 假设"一行 = 一条指令 = 4 字节",
    /// 可语言(中间层)一行会展开成好几条指令 —— 地址会整体错位(用户实测:PC 都跑到别处了,黄条还停在 停止 那行)。
    ///
    /// 现在做法:展开时插 `// 来自第 N 行` 标记(汇编器把 `//` 当注释,不占字节、不影响编译),
    /// 再按"一条指令 4 字节"扫一遍带标记的展开文本 → 两个表:
    ///   ① 段内地址 → 源码行号(语言单步:黄条标在语言源码的那一行)
    ///   ② 段内地址 → 展开文本行号(汇编单步:编辑器里显示的就是展开文本,行号直接对得上)
    /// 多文件时按文件表顺序累加基址,和 汇编器C.汇编多文件 的拼接顺序完全一致。
    /// **第93批起:表里的键统一是绝对地址**,段与段不再要求连续(合并编译单元之后,
    /// 一个文件的指令会分散在多处);`条数` = 本文件编出多少条,`含地址` 改成查表。
    /// </summary>
    public static class 执行行映射C
    {
        /// <summary>
        /// 中间层展开时插的标记(写法与解析都见 `引擎\源行标记C.cs` —— **唯一事实源**):
        /// `// 来自第 12 行`(单文件)、`// 来自文件2第 12 行`(工程级,文件号 1 基,对应文件表顺序)、
        /// `// 来自第 7 到 12 行`(整块语句)、尾巴上的 `库`(来自被 `包含` 进来的文件 —— 行号是那个文件的)。
        ///
        /// 第136批修的 bug:这里以前自己写了一份正则,认的是"来自**库**第 N 行"(库在前面),
        /// 而真正写出来的是**尾巴**上的 `库`(`// 来自第 15 行 库`)—— 于是库里的行号被当成主文件的行号,
        /// 单步黄条在编辑器里乱跳(用户实测:示例 61 单步,一来就跳到 `缩写[1] = '中';`)。
        /// 现在统一走 `源行标记C.读`:带 `库` 的行**不记源行**(那是另一个文件的行号,记了只会指错行)。
        /// </summary>
        private static 源行标记C.标记 读标记(string 行) => 源行标记C.读(行);

        // 第94批:原来"逐文件扫展开"的两个入口(扫展开 / 建全表)已经退场 ——
        // 编译与调试表现**只剩一条路**:工程级展开 + 扫工程展开(见上面)。
        // 两条路并存最容易出的错就是"断点按另一份展开算、和机器码对不上",所以不留第二份。

        /// <summary>
        /// 扫一份**工程展开文本**(一个展开器连吃多文件展出来的那一份),按 `// 来自文件K第 N 行` 标记
        /// 把每条指令分回它所属文件的调试段。段与段**不必连续** —— 各文件的主程序行在前面、
        /// 所有函数体统一排在程序末尾,所以同一个文件的指令会分散在多处(所以键用绝对地址)。
        /// 没有标记的指令(编译器生成的池 / 堆例程等)归给"当前文件":展开顺序上它就属于那里。
        /// </summary>
        public static List<文件映射C> 扫工程展开(string 带标记展开文本, IReadOnlyList<string> 文件表)
        {
            int 段数 = Math.Max(1, 文件表.Count);
            var 段表 = new List<文件映射C>();
            var 行缓冲 = new List<List<string>>();
            for (int i = 0; i < 段数; i++)
            {
                段表.Add(new 文件映射C { 文件 = i < 文件表.Count ? 文件表[i] : "" });
                行缓冲.Add([]);
            }
            int 当前文件 = 0;
            int 源行 = 0;              // 语句内沿用(一条语句只有第一条指令带标记)
            bool 生成段 = false;       // `// 编译器生成` 之后:没有源行,直到下一个真标记
            int 下一条 = 0;
            var 行表 = 带标记展开文本.Split('\n');
            for (int i = 0; i < 行表.Length; i++)
            {
                string 行 = 行表[i];
                // 标记现在挂在指令后面(注释),所以先读标记、再去注释。
                // 尾巴上的 `库` = 被 `包含` 进来的文件的行号 —— 那是**另一个文件**的行号,置 0
                // (与"单文件展开"那条路同一口径;以前这里认错写法,把库的行号当成了主文件的行号)。
                //
                // 第136批(用户报"单步逐语句乱跑")修的两处:
                // ① 库里的行号当成主文件的行号 ⇒ 黄条跳到同号但不相干的行(示例 61 里那个 `缩写[1] = '中';`);
                // ② 编译器生成的代码(序言 / 字符串与容器初始化 / 池与列表扩容这些 `_f…` 内部例程)以前
                //    没有标记 ⇒ 查表时"沿用上一条语句的行号" ⇒ 单步走进内部例程就停在**最后一条语句**上
                //    (示例 61 里是 `停止` 那一行),再跳回来又变一行 —— 看着就是乱跳。
                //    现在 `中间层C.主流程.cs` 给这些块打了 `// 编译器生成`,它们一律**没有源行**。
                var 标记 = 读标记(行);
                if (标记.生成) 生成段 = true;
                else if (标记.有)
                {
                    生成段 = false;
                    if (标记.文件号 >= 1 && 标记.文件号 <= 段数) 当前文件 = 标记.文件号 - 1;
                    源行 = 标记.来自库 ? 0 : 标记.起始行;
                }
                var 段 = 段表[当前文件];
                var 缓冲 = 行缓冲[当前文件];
                缓冲.Add(行);                                   // 显示文本按文件分开攒,行号 = 它在缓冲里的位置
                int 注释 = 行.IndexOf("//", StringComparison.Ordinal);
                string 净 = (注释 >= 0 ? 行[..注释] : 行).Trim();
                if (净.Length == 0) continue;
                if (净.EndsWith(':')) continue;                 // 纯标签行:不占字节
                int 冒号 = 净.IndexOf(':');
                if (冒号 >= 0)                                  // "标签: 指令" 写在同一行
                {
                    净 = 净[(冒号 + 1)..].Trim();
                    if (净.Length == 0) continue;
                }
                if (段.条数 == 0) 段.基址 = 下一条;              // 本文件的第一条指令地址
                // 语句内沿用(一条语句只有第一条指令带标记);生成代码与库代码一律没有源行
                if (!生成段 && 源行 > 0) 段.地址到源行[下一条] = 源行;
                段.地址到显示行[下一条] = 缓冲.Count;            // 就是它在这一段显示文本里的行号(1 基)
                段.条数++;
                下一条 += 4;
            }
            for (int i = 0; i < 段数; i++) 段表[i].展开文本 = string.Join('\n', 行缓冲[i]);
            return 段表;
        }

        /// <summary>
        /// 工程版"整份文件表 → 每个文件的调试信息"(给 IDE 在没有编译结果时用):
        /// 走**工程级展开**,与编译那条路同一套口径,不会出现"断点按另一份展开算、和机器码对不上"。
        /// </summary>
        public static List<文件映射C> 建全工程表(IReadOnlyList<(string 名称, string 内容)> 文件表, bool 优化 = true, int 堆大小 = 中间层C.默认堆大小, IReadOnlyList<string>? 工程归属 = null,
            int 池大小 = 中间层C.默认池大小, int 内存大小 = 虚拟机C.默认内存大小, int 软栈大小 = -1, bool 边界检查 = true, int 帧大小 = -1)
        {
            string 展开 = 中间层C.展开工程带目录(文件表, 带源行标记: true, 优化: 优化, 堆大小: 堆大小, 工程归属: 工程归属, 池大小: 池大小, 内存大小: 内存大小, 软栈大小: 软栈大小, 边界检查: 边界检查, 帧大小: 帧大小).汇编文本;
            return 扫工程展开(展开, [.. 文件表.Select(x => x.名称)]);
        }

        /// <summary>
        /// 把调试文件表压成**程序包里那张"地址 → 源码位置"表**(H7;编到 `源行表C` 里)。
        /// `文件映射C.地址到源行` 是每份文件一张的绝对地址表;这里先按地址全排一遍再**合成段**
        /// (相邻指令同属一条语句是常态 ⇒ 几百条语句只要几百段)。
        /// 放在这一层而不是 `程序包C`:`HB宿主`只链引擎那几个文件、**不链这一份**,反向依赖编不过。
        /// </summary>
        public static 源行表C 压源行表(IReadOnlyList<文件映射C>? 段表)
        {
            var 表 = new 源行表C();
            if (段表 == null || 段表.Count == 0) return 表;
            var 全部 = new List<(int 地址, int 行号, int 文件号)>();
            foreach (var 段 in 段表)
            {
                if (段.地址到源行.Count == 0) continue;
                int 文件号 = 表.文件们.IndexOf(段.文件);
                if (文件号 < 0) { 表.文件们.Add(段.文件); 文件号 = 表.文件们.Count - 1; }
                foreach (var (地址, 行) in 段.地址到源行) 全部.Add((地址, 行, 文件号));
            }
            foreach (var (地址, 行, 文件号) in 全部.OrderBy(x => x.地址))
            {
                if (表.段们.Count > 0)
                {
                    var 末 = 表.段们[^1];
                    if (末.文件号 == 文件号 && 末.行号 == 行 && 地址 == 末.止址 && 末.条数 < ushort.MaxValue)
                    {
                        表.段们[^1] = 末 with { 条数 = 末.条数 + 1 };
                        continue;
                    }
                }
                表.段们.Add(new 源行表C.段C(地址, 1, 行, 文件号));
            }
            return 表;
        }

        /// <summary>
        /// 按机器码地址查"这是源码第几行"(0 = 查不到:地址不在任何文件的代码段里,或那条指令没有源码行)。
        /// 给运行期错误带行号用(见 `运行期错误C` / `虚拟机C.取源行号`)——
        /// 命令行与 IDE 都从这张表来,和调试时黄条标的那一行是**同一份数据**,不会两处对不上。
        /// </summary>
        public static int 查源行(IReadOnlyList<文件映射C> 表, uint 地址)
        {
            if (表 == null || 表.Count == 0) return 0;
            int 地址整数 = unchecked((int)地址);
            foreach (var 段 in 表)
                if (段.地址到源行.TryGetValue(地址整数, out int 行))
                    return 行;
            return 0;
        }

        /// <summary>
        /// H65(**进程内那条腿**按地址查"给人看的位置"):`工具.hb 第 3 行` / `第 3 行` / 空串(查不到)。
        ///
        /// 给 `虚拟机C.取源位置` 挂 —— 命令行 `--run`(不带 `--跨进程`)与 `调试会话C` 都用它,
        /// 于是**进程内那条腿**与独立 exe / 跨进程那条腿报的是同一副面孔(它们走 `源行表C.查位置`)。
        ///
        /// 判据与 `源行表C.查位置` 一字不差(那张表本来就是 `压源行表` 从这份调试表压出来的):
        /// **有源码行的文件只有一个就不带文件名** —— 单文件程序照旧只报 `第 N 行`,多文件才在前面加 `文件名 `。
        /// 这里按**文件**循环(表里一份文件一条),不按指令数 —— 运行期错误可能反复抛,不重建整张源行表。
        /// </summary>
        public static string 查位置(IReadOnlyList<文件映射C>? 表, uint 地址)
        {
            if (表 == null || 表.Count == 0) return "";
            var 文件集 = new HashSet<string>(StringComparer.Ordinal);
            foreach (var 段 in 表)
                if (段.地址到源行.Count > 0) 文件集.Add(段.文件);      // 与 `压源行表` 收 `文件们` 同一个口径
            int 地址整数 = unchecked((int)地址);
            foreach (var 段 in 表)
            {
                if (!段.地址到源行.TryGetValue(地址整数, out int 行) || 行 <= 0) continue;
                string 名 = 文件集.Count > 1 ? Path.GetFileName(段.文件) : "";
                return 名.Length > 0 ? $"{名} 第 {行} 行" : $"第 {行} 行";
            }
            return "";
        }

        /// <summary>
        /// 按**显示行**(展开文本里的第几行 —— 汇编单步视图里编辑器给出来的就是它)反查源码行;
        /// 0 = 这一行没有源码对应(编译器生成的代码 / `包含` 进来的库文件里的行 / 不是指令行)。
        ///
        /// 干什么用的(C18,用户实测报的 bug):汇编单步视图里点断点 —— 编辑器报出来的是**展开文本行号**,
        /// 而断点必须按**源码行**存(不然红点、重开工程、下次编译时的"清失效"全都对不上,
        /// 观感就是"打上了、存不住")。地址 ↔ 显示行 ↔ 源行 这三张表都在 `文件映射C` 里(见 `扫工程展开`),
        /// 这里只做"显示行 → 地址 → 源行"这两跳。
        /// </summary>
        public static int 查源行按显示行(文件映射C? 段, int 显示行)
        {
            if (段 == null || 显示行 <= 0) return 0;
            foreach (var (地址, 行) in 段.地址到显示行)
                if (行 == 显示行)
                    return 段.地址到源行.TryGetValue(地址, out int 源行) ? 源行 : 0;
            return 0;
        }

    }
}
