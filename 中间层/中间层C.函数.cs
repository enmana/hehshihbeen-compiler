using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace hehshihbeen_compiler
{
    /// <summary> 中间层展开器的一部分:函数(M7d):固定帧 + 软栈 + FP 相对寻址。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        #region 函数(M7d):固定帧 + 软栈 + FP 相对寻址
        /// <summary> 参数名前面写了 `出` / `result` 吗?(那是**字符串参数专用**的写法:`字符串 出 名字`) </summary>
        private static bool 是出参数写法(string 名文本) =>
            名文本.StartsWith("出 ", StringComparison.Ordinal) || 名文本.StartsWith("result ", StringComparison.OrdinalIgnoreCase);

        /// <summary> 去掉参数名前面的 `出` / `result`(报错文案里要指出"本该写的那个名字") </summary>
        private static string 取出去参数名(string 名文本) => 名文本[(名文本.IndexOf(' ') + 1)..].Trim();

        /// <summary> 解析 `函数 名(类型 参数, ...)`(中英:func);抛错=false 时非法返回 null(预扫用) </summary>
        private (string 名, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数, string 返回类型词)? 解析函数头(string 行, int 行号, bool 抛错)
        {
            // H86:每次解析都从空表开始 —— 上次那份(尤其是**预扫**那两处 `抛错: false` 的探路解析)
            // 不许漏到下一个函数头上,否则登记的回调签名会串到别人名下。
            _本次解析回调形参 = null;
            string 首词 = 取首词(行);
            string 余下 = 行[首词.Length..].Trim();
            int 左 = 余下.IndexOf('(');
            int 右 = 余下.LastIndexOf(')');
            // G2:参数表里可以再有括号(`回调 比较(整数, 整数)`),所以右括号要**配对**着找 ——
            // 原来那句 `LastIndexOf(')')` 会把回调那对括号当成本函数参数表的收尾,形参表当场被切掉
            if (左 >= 0)
            {
                int 配对 = 找匹配右括号(余下, 左, 行号);
                if (配对 >= 0) 右 = 配对;
            }
            string 名 = 左 >= 0 ? 余下[..左].Trim() : "";
            if (名.Length == 0 || 左 < 0 || 右 <= 左 || !标识符全词正则.IsMatch(名))
            {
                if (!抛错) return null;
                throw 报错(行号, $"方法声明格式应为:方法 名(类型 参数, ...)—— 名字后面要写一对括号: '{行}'", $"bad function header: '{行}'");
            }

            var 参数 = new List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)>();
            string 串 = 余下[(左 + 1)..右].Trim();
            if (串.Length > 0)
            {
                foreach (string 段 in 拆顶层逗号(串))
                {
                    string s = 段.Trim();
                    string 类型词 = 取声明类型词(s);
                    // 引用参数:引用 点 p(槽里存地址,4 字节;被调方改的就是调用方的对象)
                    引用类型C? 引用 = null;
                    if (类型词 == "引用" || string.Equals(类型词, "ref", StringComparison.OrdinalIgnoreCase))
                    {
                        string 余下段 = s[类型词.Length..].Trim();
                        string 指向词 = 取声明类型词(余下段);
                        string 名文本2 = 余下段[指向词.Length..].Trim();
                        引用 = 构造引用类型(指向词, 行号, s, 抛错);
                        // 预扫函数头时结构声明还没登记(结构在后面才解析),这时只按名字记下就够:
                        // 参数宽度固定 4 字节、类型名就是那个词,真正核对留到定义时(那时结构必须已声明)。
                        if (引用 == null && !抛错) 引用 = new 引用类型C(指向词, null, 类型C.字宽度);
                        if (引用 == null) return null;
                        if (!标识符全词正则.IsMatch(名文本2))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数名非法: '{s}'", $"bad parameter name: '{s}'");
                        }
                        if (参数.Any(p => p.名 == 名文本2))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数重复: '{名文本2}'", $"duplicate parameter: '{名文本2}'");
                        }
                        参数.Add((名文本2, 4, 引用.指向类型名, 引用));     // 引用参数只占 4 字节(地址)
                        continue;
                    }
                    string 名文本 = s[类型词.Length..].Trim();
                    // G2:`回调 比较` 参数 —— 4 字节的**代码地址**按值传(与标量参数同一档:
                    // 调用方写 `某函数(表, 地址(升序))`,被调方 `间接调用(比较, …)` 调它)。
                    // 它**不是**引用参数:`地址(…)` 出来的是个算好的值,没有"调用方那一格"可取。
                    if (类型词 is "回调" || string.Equals(类型词, "callback", StringComparison.OrdinalIgnoreCase))
                    {
                        // 形状:`回调 比较(整数, 整数)` —— 括号里是**被调方的形参类型表**;不写就只收 `回调 名`
                        string 回调名文本 = 名文本.Trim();
                        var 回调形参 = new List<string>();
                        int 回调左括号 = 回调名文本.IndexOf('(');
                        if (回调左括号 >= 0)
                        {
                            if (!回调名文本.EndsWith(')'))
                            {
                                if (!抛错) return null;
                                throw 报错(行号, $"`回调` 参数的形参表少了右括号: '{s}'", $"unclosed callback signature: '{s}'");
                            }
                            string 形参文本 = 回调名文本[(回调左括号 + 1)..^1].Trim();
                            回调名文本 = 回调名文本[..回调左括号].Trim();
                            if (形参文本.Length > 0)
                                foreach (string 一项 in 形参文本.Split(','))
                                {
                                    string 形参类型词 = 取声明类型词(一项.Trim());
                                    if (形参类型词.Length == 0 || !(类型C.是类型名(形参类型词)
                                        || 中间层C.到英文关键字(形参类型词) == "var"
                                        || 形参类型词 is "回调" || string.Equals(形参类型词, "callback", StringComparison.OrdinalIgnoreCase)))
                                    {
                                        if (!抛错) return null;
                                        throw 报错(行号, $"`回调` 参数 '{回调名文本}' 的形参表里这一项认不出来: '{一项.Trim()}'。" +
                                            $"形参类型只收标量类型(`整数` / `短整数` / `逻辑` / `字符` / `文字` / `字节` / `回调` 或 `var`)",
                                            $"unknown type in callback signature: '{一项.Trim()}'");
                                    }
                                    回调形参.Add(形参类型词);
                                }
                        }
                        if (!标识符全词正则.IsMatch(回调名文本))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"`回调` 参数名非法: '{s}'(写成 `回调 名字` 或 `回调 名字(形参类型…)`)",
                                $"bad callback parameter name: '{s}'");
                        }
                        if (参数.Any(p => p.名 == 回调名文本))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数重复: '{回调名文本}'", $"duplicate parameter: '{回调名文本}'");
                        }
                        参数.Add((回调名文本, 类型C.字宽度, "回调", null));
                        // H86:写了括号就登记 —— **空表也算**(`回调 条件()` 就是"零个参数的回调",
                        // 这是合法写法)。以前那一句是 `if (回调形参.Count > 0)`,空表被挡掉 ⇒
                        // **零参回调参数根本没法表达**,只剩"蹭别的函数那张表"这一条错路
                        // (实测 `试零参(回调 条件)` 蹭到 `试带参(回调 条件(整数), …)` 的表上)。
                        // 不写括号(`回调 条件`)才真的是"没写签名",那时才不给它登记。
                        if (回调左括号 >= 0) (_本次解析回调形参 ??= []).Add((回调名文本, 回调形参));
                        continue;
                    }
                    // **字符串参数**:`函数 f(字符串 名字)` —— 形状和数组参数一样(数据地址 + 长度两个字),
                    // 但语义按字符串办:长度是字节数、不许在函数里重新赋值(会换数据地址)
                    // 加了 `出` 的(`字符串 出 名字`)是**可写**的:只传"调用方字符串头的地址"4 字节,
                    // 赋值/拼接当场改调用方那份(见 出参数 / 字符串实参地址 / 发出字符串拷到头地址)
                    if (类型词 is "字符串" || string.Equals(类型词, "string", StringComparison.OrdinalIgnoreCase))
                    {
                        bool 是出参 = 名文本.StartsWith("出 ", StringComparison.Ordinal)
                            || 名文本.StartsWith("result ", StringComparison.OrdinalIgnoreCase);
                        if (是出参) 名文本 = 名文本[(名文本.IndexOf(' ') + 1)..].Trim();
                        string 串名 = 名文本.Trim();
                        if (!标识符全词正则.IsMatch(串名))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, 是出参
                                    ? $"`出` 参数名非法: '{s}'(写成 `字符串 出 名字`)"
                                    : $"字符串参数名非法: '{s}'",
                                $"bad string parameter name: '{s}'");
                        }
                        if (参数.Any(p => p.名 == 串名))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数重复: '{串名}'", $"duplicate parameter: '{串名}'");
                        }
                        var 串类型 = new 引用类型C("字符", null, 1, 1, 0) { 带长度 = true, 是字符串 = true, 出参数 = 是出参 };
                        参数.Add((串名, 是出参 ? 4 : 8, "字符", 串类型));
                        continue;
                    }
                    // **数组参数**:`函数 求和(整数 表[])` —— 数字不写(长度由调用方给),
                    // 参数占两个字(数据地址 + 元素个数);函数里能查越界、能用 表.长度()
                    if (取类型定义(类型词) is { } 元素类型 && 名文本.EndsWith("[]", StringComparison.Ordinal))
                    {
                        string 数组名 = 名文本[..^2].Trim();
                        if (!标识符全词正则.IsMatch(数组名))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"数组参数名非法: '{s}'", $"bad array parameter name: '{s}'");
                        }
                        if (参数.Any(p => p.名 == 数组名))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数重复: '{数组名}'", $"duplicate parameter: '{数组名}'");
                        }
                        string 切片元素名 = 查枚举类型(类型词)?.名称 ?? 元素类型.中文;   // H68-2:枚举数组参数记枚举名
                        var 切片类型 = new 引用类型C(切片元素名, null, 元素类型.宽度, 元素类型.宽度, 0) { 带长度 = true };
                        参数.Add((数组名, 8, 切片元素名, 切片类型));       // 地址 + 长度两个字
                        continue;
                    }
                    int 宽;
                    string 类型名;
                    if (取类型定义(类型词) is { } 基本)
                    {
                        宽 = 基本.宽度;
                        类型名 = 查枚举类型(类型词)?.名称 ?? 基本.中文;   // H68-2:枚举参数登记枚举名(宽度照样是 4)
                    }
                    else if (中间层C.到英文关键字(类型词) == "var") { 宽 = 类型C.字宽度; 类型名 = "32位字"; }
                    else
                    {
                        // **结构参数:默认按地址传**(我们有地址,和 C 的指针一个道理,不白复制一份)。
                        // 实现上就是把 `点 p` 当 `引用 点 p` 办:调用处自动取地址、被调方通过地址读写,
                        // 所以"改了就是改调用者的那份";要解耦就自己先拷一份(`点 副本 = 位置`)再传。
                        var 结构引用 = 构造引用类型(类型词, 行号, s, 抛错);
                        if (结构引用 == null && !抛错) 结构引用 = new 引用类型C(类型词, null, 类型C.字宽度);
                        if (结构引用 == null)
                            throw 报错(行号, $"参数类型须为基础类型(字节/短整数/整数/…)、结构名,或者 引用: '{s}'",
                                $"bad parameter type: '{s}'");
                        // A6(第105批):`出` 是**字符串参数专用**的写法(`字符串 出 名字`)。
                        // 写到结构上以前只说"参数名非法",看不出错在哪 —— 这里给人话 + 改法。
                        if (是出参数写法(名文本))
                        {
                            if (!抛错) return null;      // 预扫那趟是"悄悄过",报错留到正式那趟(行号才对)
                            throw 报错(行号,
                                $"**结构参数不用也不该写 `出`**:'{s}'。结构参数本来就是**按地址传**的" +
                                $"(被调方改了就是改调用方那份),直接写 `{类型词} {取出去参数名(名文本)}` 就行;" +
                                $"`出` 只有**字符串**参数能用(`字符串 出 名字`)",
                                $"struct parameters are already by-address; `出` is for strings only: '{s}'");
                        }
                        if (!标识符全词正则.IsMatch(名文本))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数名非法: '{s}'", $"bad parameter name: '{s}'");
                        }
                        if (参数.Any(p => p.名 == 名文本))
                        {
                            if (!抛错) return null;
                            throw 报错(行号, $"参数重复: '{名文本}'", $"duplicate parameter: '{名文本}'");
                        }
                        参数.Add((名文本, 4, 结构引用.指向类型名, 结构引用));   // 地址占 4 字节
                        continue;
                    }
                    // A6(第105批):基础类型写 `出` 也是同一个误会 —— 要可写就写 `引用`
                    if (是出参数写法(名文本))
                    {
                        if (!抛错) return null;          // 预扫那趟是"悄悄过",报错留到正式那趟(行号才对)
                        throw 报错(行号,
                            $"基础类型参数不能写 `出`:'{s}'。要「改了调用方也跟着变」,把参数写成引用:" +
                            $"`引用 {类型词} {取出去参数名(名文本)}`(调用处照旧写 `函数名(变量)`);" +
                            $"`出` 只有**字符串**参数能用(`字符串 出 名字`)",
                            $"`出` is for strings only; use `引用 {类型词} 名` instead: '{s}'");
                    }
                    if (!标识符全词正则.IsMatch(名文本))
                    {
                        if (!抛错) return null;
                        throw 报错(行号, $"参数名非法: '{s}'", $"bad parameter name: '{s}'");
                    }
                    if (参数.Any(p => p.名 == 名文本))
                    {
                        if (!抛错) return null;
                        throw 报错(行号, $"参数重复: '{名文本}'", $"duplicate parameter: '{名文本}'");
                    }
                    参数.Add((名文本, 宽, 类型名, null));
                }
            }
            // 尾缀返回类型:`函数 取中点(整数 a, 整数 b) 返回 点 { … }`(Rust 风;英文 `return 点`)
            // **不写 = 无返回值(void)**:函数里就只许裸 `返回`,调用处也不许把结果当值用。
            string 尾缀 = 余下[(右 + 1)..].Trim();
            string 返回词 = "";
            if (尾缀.Length > 0)
            {
                string 词 = 取首词(尾缀);
                if (!(词 == "返回" || string.Equals(词, "return", StringComparison.OrdinalIgnoreCase)))
                {
                    if (!抛错) return null;
                    throw 报错(行号, $"函数头参数表后面只能写 `返回 类型`(不写就是没有返回值): '{行}'",
                        $"only '返回 Type' may follow the parameter list: '{行}'");
                }
                返回词 = 取声明类型词(尾缀[词.Length..].Trim());   // 返回类型也可能是模块里的结构(`返回 数学.结果`)
                if (返回词.Length == 0)
                {
                    if (!抛错) return null;
                    throw 报错(行号, $"`返回` 后面要写返回类型(基础类型名或结构名): '{行}'", $"missing return type: '{行}'");
                }
            }
            // H104:形参名也要过保留字那一关。以前**只拦变量声明**(`校验变量名`),形参一路不查 ⇒
            // `方法 收(整数 记录)` 编得过、跑得动(库 `数据表.hb` 的 `追加(…, 字符串 记录)` 就是这么活下来的),
            // 而读代码的人会把那个名字当成"老写法那一档类型"。清单只有一份(`中间层指令C.为什么是保留字`),
            // 所以报错文案与 `变量名不能用…` 逐字同一套。**紧挨着的 `引用` / `出` / 数组那几条路都汇到这一个出口**,
            // 在这儿查一遍就等于全查了。
            foreach (var (参名, _, _, _) in 参数)
            {
                if (中间层指令C.为什么是保留字(参名) is not { } 原因) continue;
                if (!抛错) return null;          // 预扫那趟是"悄悄过",报错留到正式那趟(行号才对)
                throw 报错(行号, $"参数名不能用{原因}: '{参名}'。换个名字,例如 `{中间层指令C.建议变量名(参名)}`" +
                    $"(保留字清单见帮助『保留字』一节)",
                    $"parameter name is a reserved word ({原因}): '{参名}'");
            }
            return (名, 参数, 返回词);
        }

        /// <summary> `引用 点` 里的"点"→ 引用类型(基础类型 / var / 已声明的结构);不认识就给出明确错误(抛错=false 时返回 null)</summary>
        private 引用类型C? 构造引用类型(string 指向词, int 行号, string 原文, bool 抛错)
        {
            if (取类型定义(指向词) is { } 基本)
                return new 引用类型C(查枚举类型(指向词)?.名称 ?? 基本.中文, null, 基本.宽度);   // H68-2:枚举也能被引用
            if (中间层C.到英文关键字(指向词) == "var") return new 引用类型C("32位字", null, 类型C.字宽度);
            if (查结构类型(指向词) is { } 结构) return new 引用类型C(结构.名称, 结构, 结构.总宽度);
            if (!抛错) return null;
            // H68-3:元组写法坏掉时别报成"引用指向的类型不认识" —— 元组那一侧自己会把话说清楚
            if (是元组类型词(指向词)) 取元组类型(指向词, 行号);
            throw 报错(行号, $"引用指向的类型不认识: '{指向词}'(基础类型 / var / 已声明的结构): '{原文}'",
                $"unknown reference target type: '{指向词}'");
        }

        /// <summary>
        /// 是否是函数调用:带括号的 `调用 f(...)`(不带括号仍是汇编指令 调用 标签);
        /// 也认"直接写函数名"的糖 `f(...)` / `体名.方法名(...)`(名字确实是已知函数才算,免得吃掉汇编行)。
        /// </summary>
        private bool 是函数调用行(string 内容)
        {
            string 首词 = 取首词(内容);
            // G2:`间接调用(地址, 实参…)` 的"函数名"是**算出来的** —— `_函数表` 里当然没有它,
            // 所以这一档要在这里先认下来(不然它会被当成别的行报"未声明的变量或非法赋值左值")。
            if (首词 is "间接调用" or "invoke" || string.Equals(首词, "invoke", StringComparison.OrdinalIgnoreCase))
                return true;
            if (首词 == "调用" || string.Equals(首词, "CALL", StringComparison.OrdinalIgnoreCase))
            {
                string 余下 = 内容[首词.Length..];
                return 余下.Contains('(') && 余下.TrimEnd().EndsWith(')');
            }
            string 文本 = 内容.Trim();
            int 左 = 文本.IndexOf('(');
            if (左 <= 0 || !文本.EndsWith(')')) return false;
            string 名 = 文本[..左].Trim();
            if (!调用名正则.IsMatch(名)) return false;   // H60 步②起也认 `表[1].成员` 这种收方形态
            if (_函数表.ContainsKey(名)) return true;
            if (名.Contains('.')) return 是实例成员调用(名);   // H60 步②:`记录.累加(…)` 也是调用
            if (_当前容器 is { } 容器 && 容器.方法全名.ContainsKey(名)) return true;
            // 模块里的裸名字:也按"本模块的全名"认一次(不然模块内部调用会被当成汇编行透传)
            return _当前模块.Length > 0 && _函数表.ContainsKey(_当前模块 + "." + 名);
        }

        /// <summary>
        /// `实例.成员` 形态(H60 步②):点号前面那一截是**某一份实例**(变量 / 结构字段 / 数组元素),
        /// 它的类型是某个方法容器的内部结构,而尾段确实是那个容器的成员 —— 认得出才算"调用"。
        /// 认不出就照旧报"未定义的函数/方法"(**不在这里吞掉别的行**:结构字段访问、模块名和函数名都在别的路上判过了)。
        /// </summary>
        private bool 是实例成员调用(string 名)
        {
            int 点 = 名.LastIndexOf('.');
            if (点 <= 0 || 点 >= 名.Length - 1) return false;
            string 前 = 名[..点], 尾 = 名[(点 + 1)..];
            return 收方结构(前) is { } 结构 && 结构有这个方法(结构, 尾);
        }

        /// <summary> 这个结构类型下面有没有这个方法(容器成员看 `_容器表`,普通结构看 `_结构方法表`;H60 步④) </summary>
        private bool 结构有这个方法(结构类型C 结构, string 方法名)
        {
            if (结构.名称.StartsWith("_方法_", StringComparison.Ordinal))
                return _容器表.TryGetValue(结构.名称["_方法_".Length..], out var 容器) && 容器.方法全名.ContainsKey(方法名);
            return _结构方法表.TryGetValue(结构.名称, out var 表) && 表.ContainsKey(方法名);
        }

        /// <summary> 这个结构类型下面这个方法叫什么定义名(容器成员 / 普通结构各查各的表;找不到返回 null)</summary>
        private string? 结构方法定义名(结构类型C 结构, string 方法名)
        {
            if (结构.名称.StartsWith("_方法_", StringComparison.Ordinal))
                return _容器表.TryGetValue(结构.名称["_方法_".Length..], out var 容器)
                    && 容器.方法全名.TryGetValue(方法名, out string? 容器定义名) ? 容器定义名 : null;
            return _结构方法表.TryGetValue(结构.名称, out var 表) && 表.TryGetValue(方法名, out string? 定义名) ? 定义名 : null;
        }

        /// <summary>
        /// 收方文本指的东西是"某个**带方法的**结构"时给出那个结构类型(否则 null)。
        /// 三种写法都认:变量(`计数`)、结构字段(`箱.字段`)、数组/列表元素(`表[1]`、`名单[下标]`)——
        /// 靠 `解析引用链` 那一套(它本来就管"链的最后一层是什么结构")。出了岔子一律当"不是"。
        /// </summary>
        private 结构类型C? 收方结构(string 收方)
        {
            string 文本 = 收方.Trim();
            if (文本.Length == 0) return null;
            结构类型C? 结构 = null;
            try
            {
                if (查变量(文本) is { 结构类型: { } 直 }) 结构 = 直;
                else if (解析引用链(文本, _当前源行号) is { } 链)
                    结构 = 链.运行期下标 != null ? 链.下标后结构 ?? 链.元素结构
                        : 链.结构 ?? 链.元素结构;
            }
            catch (编译异常C) { return null; }
            if (结构 is not { } 候选) return null;
            if (候选.名称.StartsWith("_方法_", StringComparison.Ordinal)) return 候选;
            return _结构方法表.ContainsKey(候选.名称) ? 候选 : null;   // 普通结构:只有带方法的才算"收方"
        }

        /// <summary> 调用文本 → 函数名与实参串;兼容 `调用 f(a, b)` 与 `f(a, b)` 两种写法 </summary>
        private static (string 名, string 实参串) 解析调用(string 内容)
        {
            string 首词 = 取首词(内容);
            string 余下 = 首词 == "调用" || string.Equals(首词, "CALL", StringComparison.OrdinalIgnoreCase)
                ? 内容[首词.Length..].Trim()
                : 内容.Trim();
            int 左 = 余下.IndexOf('(');
            int 右 = 余下.LastIndexOf(')');
            return (余下[..左].Trim(), 余下[(左 + 1)..右].Trim());
        }

        /// <summary> 是否是"返回 值"(裸 返回/RET 仍是汇编指令;英文 return 两种都算) </summary>
        private static bool 是返回值行(string 内容)
        {
            string 首词 = 取首词(内容);
            bool 是返回词 = 首词 == "返回" || string.Equals(首词, "return", StringComparison.OrdinalIgnoreCase)
                || string.Equals(首词, "RET", StringComparison.OrdinalIgnoreCase);
            if (!是返回词) return false;
            // 裸 `返回`/`RET` 是汇编指令(原样透传);裸 `return` 是语言的英文写法 → 当"无值返回"
            if (内容[首词.Length..].Trim().Length == 0)
                return string.Equals(首词, "return", StringComparison.OrdinalIgnoreCase);
            return true;
        }

        /// <summary> 函数声明:参数与局部都放进"固定的一块帧"(大小可配,H34;默认 96 字节);函数体统一追加到主程序之后。
        /// `结构方法收方` 非空 = 这是**结构里声明的方法**(H60 步④):定义名带结构名、收方类型就是那个结构自己
        /// (其余与容器成员同一套 —— 都是"隐藏的第一个参数 = 收方")。</summary>
        private void 处理函数声明(ref int 位置, (string 名, 结构类型C 结构)? 结构方法收方 = null)
        {
            int 行号 = _伪行号表[位置];
            if (_当前函数 != null) throw 报错(行号, "函数不能嵌套定义", "nested functions are not allowed");
            string 头行 = _伪行表[位置].Trim();
            // 容器里的成员不用写 函数/方法 前缀(裸 `名(参数)` 头),这里补上再解析
            if (中间层C.到英文关键字(取首词(头行)) is not "method") 头行 = "方法 " + 头行;
            var 头 = 解析函数头(头行, 行号, 抛错: true)!.Value;
            // 兜底:有函数就必须有程序开头的 FP 初始化(预扫函数头时发的)。这条漏了会"静悄悄地错"——
            // 帧落到地址 0+64 = 代码区,把机器码当数据写,现象极难查(2026-09 引用那次就是这样)。
            if (_软栈槽 == null)
                throw 报错(行号, "编译器内部错误(请报告):这个程序有函数,但开头的帧初始化没生成", "internal: frame pointer init missing");
            // 体里的函数 = 方法:对外的定义名带体名(棋盘.面积),汇编标签用 '_' 连接(棋盘_面积)
            string 定义名 = 头.名;
            string 标签 = 头.名;
            bool 是成员方法 = _当前容器 != null || 结构方法收方 != null;
            if (_当前容器 is { } 所在容器)
            {
                if (头.名.Contains('.'))
                    throw 报错(行号, $"体里的函数名不要再带体名: '{头.名}'", $"do not qualify a method name inside its body: '{头.名}'");
                定义名 = 所在容器.名称 + "." + 头.名;
                // 汇编标签里不能有点:容器的点也要一起换成下划线(模块里的容器名字本身带点:`模块.工具`)
                标签 = (所在容器.名称 + "_" + 头.名).Replace('.', '_');
                所在容器.方法全名[头.名] = 定义名;
                所在容器.方法标签[头.名] = 标签;
                // ---- H60 步②:成员方法多一个**隐藏的第一个参数 = 收方** ----
                // 口径:`p.累加(3)` 就是 `累加(p, 3)` —— 收方当第一个参数,编译期彻底消失、零运行期机制。
                // 收方写成 `引用 那个内部结构`,与"结构参数 / 引用参数传地址"同一套既有机制(ISA 一条不加)。
                if (头.参数.Any(p => p.名 == 收方参数名))
                    throw 报错(行号, $"参数名 '{收方参数名}' 是编译器留给**收方**的({定义名} 里不能再叫这个名字)",
                        $"'{收方参数名}' is reserved for the receiver of a method");
                string 内部结构名 = "_方法_" + 所在容器.名称;
                if (!_结构表.TryGetValue(内部结构名, out var 收方结构))
                    throw 报错(行号, "编译器内部错误(请报告):方法容器的内部结构类型没登记", "internal: container struct type missing");
                头.参数.Insert(0, (收方参数名, 4, 内部结构名,
                    new 引用类型C(内部结构名, 收方结构, 收方结构.总宽度)));
                _成员收方[定义名] = 所在容器.名称;
            }
            else if (结构方法收方 is { } 收方信息)
            {
                // ---- H60 步④:**结构里声明的方法** —— 与容器成员同一套"隐藏收方",只是收方类型换成结构自己 ----
                if (头.名.Contains('.'))
                    throw 报错(行号, $"结构里的方法名不要再带结构名: '{头.名}'", $"do not qualify a method name inside its struct: '{头.名}'");
                定义名 = 收方信息.名 + "." + 头.名;
                标签 = (收方信息.名 + "_" + 头.名).Replace('.', '_');
                _当前结构方法表?[头.名] = 定义名;
                if (头.参数.Any(p => p.名 == 收方参数名))
                    throw 报错(行号, $"参数名 '{收方参数名}' 是编译器留给**收方**的({定义名} 里不能再叫这个名字)",
                        $"'{收方参数名}' is reserved for the receiver of a method");
                头.参数.Insert(0, (收方参数名, 4, 收方信息.名,
                    new 引用类型C(收方信息.名, 收方信息.结构, 收方信息.结构.总宽度)));
            }
            else if (_当前模块.Length > 0)
            {
                // 模块(K7):函数名带模块前缀,汇编标签把点换成下划线(和 方法容器 同一套规则)
                定义名 = 限定名(头.名);
                标签 = 定义名.Replace('.', '_');
            }
            if (_本句私有 || _本句程序集) 记私有(定义名);
            记可见性(定义名);        // C19:补全按它筛"这个名字在当前文件里看不看得见"
            // H86:回调形参的签名表按 **`定义名.参数名`** 登记(以前只按裸参数名 ⇒ 跨函数串味)。
            // 定义名到这儿才算定下来(模块前缀 / 容器前缀),所以登记只能放在这里,不能在解析函数头里做。
            if (_本次解析回调形参 is { Count: > 0 } 本次回调)
            {
                foreach (var (回调参数名, 形参表) in 本次回调) _函数回调形参[定义名 + "." + 回调参数名] = 形参表;
                _本次解析回调形参 = null;
            }
            if (_已定义函数.Contains(定义名))
                throw 报错(行号, $"函数重复定义: '{定义名}' —— {上一处声明(定义名)}{同名怎么办("函数")}" +
                    $"（`模块` 以外最快的办法:把它改成一个只有本文件用得到的名字)",
                    $"duplicate function: '{定义名}'");
            记声明出处(定义名, 行号);
            // 参数槽宽度:C 档下 `短整数` 参数也按 4 字节放(引用参数本来就是 4 字节地址)
            static int 参数槽宽(中间层展开器 自己, (string 名, int 宽度, string 类型名, 引用类型C? 引用) p) =>
                p.引用 != null ? p.宽度 : 自己.槽宽度(p.宽度);
            int 参数总宽 = 头.参数.Sum(p => 参数槽宽(this, p));
            if (参数总宽 > 函数帧大小)
                throw 报错(行号, $"方法 '{定义名}' 的参数放不下:参数一共 {参数总宽} 字节,上限 {函数帧大小} 字节" +
                    "(返回结构 / 返回字符串时还要多占 4 字节的存放地址)。" + 帧超限改法(),
                    $"parameters exceed frame size in '{定义名}'");

            // 返回类型:空 = 无返回值(void);基础类型名 = 标量;结构名 = 结构返回;`字符串` = 字符串返回
            // (结构/字符串返回都要藏一个"存放地址"参数,占帧里最前面 4 字节)
            string 返回类型词 = 头.返回类型词;
            _函数返回类型[定义名] = 返回类型词;          // 空字符串也记下来:调用点要能区分"没这个函数"和"void"
            结构类型C? 返回结构 = null;
            bool 要返回字符串 = 返回类型词 is "字符串" || string.Equals(返回类型词, "string", StringComparison.OrdinalIgnoreCase);
            if (返回类型词.Length > 0 && !要返回字符串)
            {
                if (取类型定义(返回类型词) == null)      // H68-2:枚举名也当标量返回类型(底层 整数)
                {
                    返回结构 = 查结构类型(返回类型词);
                    if (返回结构 == null)
                        throw 报错(行号, $"返回类型不认识: '{返回类型词}'(基础类型名、已声明的结构名,或 字符串)", $"unknown return type: '{返回类型词}'");
                }
            }
            // 返回结构 / 返回字符串:调用方把"结果放哪"的地址递进来,占帧里最前面 4 字节(参数往后挪)
            int 返回地址偏移 = 返回结构 != null || 要返回字符串 ? 0 : -1;
            int 用户参数起点 = 返回结构 != null || 要返回字符串 ? 4 : 0;
            if (返回结构 != null || 要返回字符串) 参数总宽 += 4;
            _函数返回类型[标签] = 返回类型词;            // 汇编标签也支持(直接写标签调用时)
            // C19 参数提示:把签名(返回类型 + 参数表)记进调试名字表 —— 补全的候选就靠它写出 `函数 名(整数 左, 整数 右) 返回 整数`
            // H60 步②:成员方法那个隐藏收方**不进签名**(它不是用户写的参数,补全 / 帮助里都不该露出来)
            _名字表.函数签名[定义名] = new 函数签名C
            {
                返回类型 = 返回类型词,
                参数 = [.. 头.参数.Where((p, i) => !(是成员方法 && i == 0)).Select(p => new 参数项C
                {
                    名字 = p.名,
                    类型名 = p.类型名,
                    是出 = p.引用 is { 出参数: true },
                    是引用 = p.引用 != null,
                    是数组 = p.引用 is { 带长度: true },
                })],
            };

            位置++;
            if (位置 >= _伪行表.Count || _伪行表[位置] != "{")
                throw 报错(行号, "函数声明后缺少 '{'", "expected '{' after function");
            int 左花括号行 = _伪行号表[位置];          // C14:进这个函数时黄条停在 `{` 这一行

            _缓冲栈.Push([]);
            压作用域(行号);
            var 上层函数 = _当前函数;
            var 本次函数 = new 函数上下文
            {
                名称 = 定义名,
                局部偏移 = 参数总宽,
                参数总宽 = 参数总宽,
                返回类型词 = 返回类型词,
                返回结构 = 返回结构,
                返回字符串 = 要返回字符串,
                返回地址偏移 = 返回地址偏移,
                收方名 = 是成员方法 ? 收方参数名 : "",
            };
            _当前函数 = 本次函数;
            int 偏移 = 用户参数起点;
            foreach (var p in 头.参数)
            {
                int 槽宽 = 参数槽宽(this, p);
                // 引用参数:槽里装的是地址(4 字节),被调方通过它改调用方的对象
                当前作用域[p.名] = p.引用 != null
                    ? new 变量绑定C(new 变量槽定义(帧槽(偏移), 槽宽), null, null, null, p.引用, 0, false, 类型C.有符号(p.类型名),
                        // 数组参数:长度在地址后面那个字。**`出` 参数没有长度槽**(长度在调用方的头里),
                        // 所以它不算"数组切片",由 引用类型.出参数 认
                        p.引用.带长度 && !p.引用.出参数 ? new 变量槽定义(帧槽(偏移 + 4), 4) : null)
                    : new 变量绑定C(new 变量槽定义(帧槽(偏移), 槽宽), null, null, null, null, 槽宽 != p.宽度 ? p.宽度 : 0,
                        string.Equals(p.类型名, "逻辑", StringComparison.Ordinal), 类型C.有符号(p.类型名));
                // 参数名字也进调试名字表(整函数体都可见) —— 这样调试器能直接显示"变量 字(字符) = 65",而不是冷冰冰的 FP+0
                登记名字(p.名, new 变量槽定义(帧槽(偏移), 槽宽), 类型C.解析(p.类型名), null, null, 行号, 是参数: true, 引用: p.引用);
                if (p.引用 == null) 登记变量类型(p.名, p.类型名);   // 参数类型也记下来(文字参数要能认)
                偏移 += 槽宽;
            }
            try
            {
                // H60 步②:方法体里的裸字段名走**收方**(`步` → `_收方.步`);出方法体换回单例那一套
                if (是成员方法 && _当前容器 is { } 成员容器) 换字段映射(成员容器, 走收方: true);
                处理块(ref 位置);
            }
            finally
            {
                if (是成员方法 && _当前容器 is { } 成员容器2) 换字段映射(成员容器2, 走收方: false);
                弹作用域(上一伪行源行号(位置));
                _当前函数 = 上层函数;
            }
            int 右花括号行 = 上一伪行源行号(位置);
            // 第 4 项 = **真正声明这个函数的那一份文件**(用户 2026-09-26 定的口径):`包含` 进来的库函数
            // 记的是**库文件**(行号本来就是库里的),不再记"把它包含进来的那一份"(那是调试段,见下一行)。
            _名字表.函数范围.Add((定义名, 行号, 右花括号行, _当前来源文件));
            // C14:单步"进函数停在 `{` 行、出函数停在 `}` 行"要找的就是这两行(与 函数范围 同一份文件归属)
            _名字表.函数边界.Add((定义名, 左花括号行, 右花括号行, _当前来源文件));
            // 而"这个函数的码编进了哪个调试段"是另一件事:被 `包含` 进来的函数**就地展开在包含它的那一份**里
            // ⇒ 段归属另记一份(`汇编器C.拆名字表` 靠它把库函数留在含它的那一段里:标签 ↔ 定义名、
            // 调用栈的层名都要用;不记就只剩"声明文件"这一个说法,库函数会从每一段里掉出去)。
            if (!文件判定C.同文件(_当前来源文件, _当前文件)) _名字表.函数段文件[定义名] = _当前文件;

            var 体 = _缓冲栈.Pop();
            // 函数入口的"递归深度"检查先摆个占位符:整个程序展开完再回头决定留不留(见 收尾栈检查)
            体.InsertRange(0, [栈检查占位(行号)]);
            // 帧是复用的:只有登记过"需要清零"的局部区才在入口清零(静态数据段那套零初始化不适用于帧;参数区不清)
            if (本次函数.需清零.Count > 0) 体.InsertRange(1, 生成清零序言(本次函数.需清零));
            string 末尾 = 体.Count > 0 ? 体[^1].Trim() : "";
            if (末尾 is not ("返回" or "RET" or "ret")) 体.Add("返回");   // 保底:函数末尾一定返回
            收尾池水位(本次函数, 体, 头.参数.Any(p => p.引用 != null), 行号);   // K4:池对象出不去的函数,返回时退池水位
            _已定义函数.Add(定义名);
            _函数表[定义名] = 头.参数;
            _函数标签[定义名] = 标签;
            _函数正文.Add($"{标签}:");
            _函数正文.AddRange(体);
            _帧用量.Add((定义名, 本次函数.局部偏移));   // R3-1:帧预算收尾汇总(帧复用、偏移只增不减 ⇒ 这里就是峰值)
        }

        /// <summary>
        /// **池水位回收(K4)**:函数进来时记下池指针,返回时退回去 —— 治"函数里声明字符串/列表,
        /// 每调用一次就从池里漏掉一块"(池一共 32KB,循环里调几千次就用光)。
        ///
        /// 判据(必须**池对象一个都出不去**,否则退水位会把别人还在用的数据划走):
        ///   ① 体里确实从池里要过地方;
        ///   ② 返回类型是 void / 标量(返回 字符串·结构 时池对象跟着返回值出去);
        ///   ③ 参数里没有 `引用`(数组/字符串参数都按引用递地址,被调方可能把指针写进调用方的结构);
        ///   ④ 体里没有 `引用` 声明;
        ///   ⑤ 体里没有直接写数据段(`STORE`/`STORE_WORD`/`存字` —— 全局变量与静态字段都住那儿);
        ///   ⑥ 体里没有取数据段地址(`取地址 ` —— 有了它就能把池指针间接写进全局);
        ///   ⑦ 体里没有"认得出的用户函数调用"(被调方会不会把指针存到别处,这里看不见)。
        /// **允许间接写**:字符串/列表往池里的拷贝本来就是间接写,禁掉就一条都用不上(第一版栽在这)。
        /// 满足①~⑦时池分配的地址只可能落在"自己帧里的头"上 —— 帧一返回就作废,整段退回是安全的。
        /// 水位放帧里一个隐藏的 4 字节局部(帧不够就不做)。
        /// </summary>
        private void 收尾池水位(函数上下文 函数, List<string> 体, bool 参数带引用, int 行号)
        {
            if (!函数.用到池) return;
            // ② **H84(2026-10-11):返回 `字符串` 的函数**也从"一律不回收"放开**一半** —— 出口那一句
            //    会先看**目的数据块在不在进来时的水位之上**(见下面 `回退` 那一段)。
            //    为什么原来一律拒绝:怕"池对象跟着返回值出去"。那个顾虑只对了一半:
            //      · `返回 字符串`:调用方把自己那个**头的地址**递进来(帧第 0 槽),被调方
            //        `发出字符串拷到头地址` **整份拷进去** ⇒ 被调方那条局部串确实是**孤儿**;
            //      · **但拷贝时若目标容量不够,给目的地换的那一块是在被调方水位之内要的**
            //        (`中间层C.列表.cs` 的 `发出拷贝到头地址长` 里那句 `池要一块(…, "返回值", …)`)——
            //        那一块**绝不能回收**,否则调用方那一格指向一块马上会被别人复用的内存
            //        (症状是"少一个字 / 变乱码",不是报错:2026-10-11 实测,一律回收会让整套回归 35 → 46 条红)。
            //    ⇒ 出口按**目的数据块地址 < 水位**才回退。长循环里只有**第一轮**会跳过
            //      (那一轮给目的地换块),后面每轮目的块都已经在水位之下 ⇒ 照常回收 ⇒ 池不再每轮涨一块。
            //    · `返回 结构`:**仍然一律不回收** —— 结构的字符串字段各自指向池块,而调用方给的是个
            //      **裸地址**(不是字符串头),出口那一句看不出它牵了几块 ⇒ 保守(只漏不崩)。
            if (函数.返回类型词.Length > 0 && !是标量返回词(函数.返回类型词) && !函数.返回字符串) return;
            if (参数带引用 || 函数.有引用) return;
            // ⑤ 体里没有"写用户数据段"(全局变量/静态字段)、⑥ 没有取用户数据段地址。
            //    注意别把**编译器自己的槽**算进去:池指针槽、错误槽、池槽、软栈槽本来就在数据段,
            //    它们每写一次都被当成"外流"的话,几乎没有一个函数能回收(第一版之外的第二版栽在这)。
            //
            //    ⚠ **批 8 施工记录(第91批)**:这里试过"只拦真把**池指针**写进用户数据段的那种写"
            //    (读头+0 / 内部池槽 / 取地址 → 污点;体里扫一遍传播,只在"污点值写进用户全局"时拦)。
            //    两条路都走不通,**已撤回**,原因是实测出来的:
            //      ① 按 `_vN` 前缀认"用户槽"会把**编译器自己的隐藏槽**(字符串字面量的头、池指针槽…)也算进去 ⇒ 几乎全拦;
            //      ② 改成只认调试名字表里的真全局之后,仍然过拦 —— 编译器把 **R14 当通用暂存**,
            //         流不敏感的污点分析会把它在体里别处沾的"污"算到"写全局计数器"这一处上
            //         (诊断输出:`把污点值 R14 写进了 _v2`)。
            //    要做到"既放宽又可靠",得写一个**沿定义回溯、遇标签/跳转即保守**的数据流分析(带记忆化),
            //    或者更稳的一条路:**在发射处标记** —— 赋值/字符串拷贝这些真正能外流的发射点自己知道
            //    "这次写进的是用户全局、值是池地址",直接置标志,不靠事后读汇编文本猜。
            //    方案与证据见 `内核加固与语法收口计划.md` 批 8。
            var 内部槽 = new List<string>();
            if (_错误槽 is { } 槽1) 内部槽.Add(槽1.名称);
            if (_池指针槽 is { } 槽2) 内部槽.Add(槽2.名称);
            if (_池槽 is { } 槽3) 内部槽.Add(槽3.名称);
            if (_池末槽 is { } 槽4) 内部槽.Add(槽4.名称);
            if (_软栈槽 is { } 槽5) 内部槽.Add(槽5);
            var 内部集 = 内部槽.ToHashSet(StringComparer.Ordinal);
            // **"用户数据段"只认调试名字表里登记过的真变量**(批 8 实测订正)。
            // 以前按 `_vN` 前缀认 —— 可编译器自己的**隐藏槽**也是这个形状:字符串字面量的头 `_v7`、
            // 池指针槽 `_v5`… 于是**凡是用字符串的函数**都被 ⑤/⑥ 误拦:实测 `字符串 临时 = "文本";` 的函数
            // 循环 4000 次就把池漏光(`回收池水位` 提示根本不出现),而**用列表的函数能回收** ——
            // 差别只在列表路径不碰字面量的头槽。按名字表认之后这一整类函数都能回收。
            // (内部槽不进名字表:`登记名字` 只登记用户声明,所以这张集合天然不含编译器自己的槽。)
            var 用户全局 = _名字表.变量.Where(x => x.是全局 && x.槽.Length > 0)
                .Select(x => x.槽).ToHashSet(StringComparer.Ordinal);
            // ⚠ **批 8 后半的根因(第92批实测)**:真正编译走的那条路是 `带源行标记: true` ——
            //    体里的行屁股上挂着 `// 来自第 N 行` 注释(`--asm` 那条路不带标记,所以**看着是对的**)。
            //    按整行相等去匹配 `返回`,标记那行就永远匹配不上 ⇒ 水位尾声被插到**用户那句 返回 之后** = 死代码,
            //    池照样每次调用漏一块;而"插了 N 处"的提示照样出现,于是八轮都判成"尾声插进去了"。
            //    判据扫描同理:`STORE_WORD R14 _v2   // 来自第 6 行` 的末词变成"行",⑤⑥ 在真编译路径上根本没生效。
            //    ⇒ 这里一律先**剥掉注释**再比对,两条路(带标记/不带标记)判据与插入位置必须逐字一致。
            static string 裸行(string 行)
            {
                int 注释 = 行.IndexOf("//", StringComparison.Ordinal);
                return (注释 >= 0 ? 行[..注释] : 行).Trim();
            }
            for (int 扫 = 0; 扫 < 体.Count; 扫++)
            {
                string 行 = 体[扫];
                string[] 部分 = 裸行(行).Split(' ', StringSplitOptions.RemoveEmptyEntries);
                if (部分.Length == 0) continue;
                string 末 = 部分[^1];
                bool 内部 = 内部集.Contains(末) || 内部槽.Any(x => 末.StartsWith(x + "+", StringComparison.Ordinal));
                if (内部) continue;
                string 基础 = 末.Contains('+') ? 末[..末.IndexOf('+')] : 末;
                if (!用户全局.Contains(基础)) continue;
                string 助记 = 部分[0];
                // ⑤(批 8 后半放宽)**写用户数据段**:只拦"装得下池地址"的那种写。
                //   · `取地址 <真用户全局>` —— 有了它就能把池指针间接写进全局 ⇒ 一律不回收(原样保留);
                //   · `STORE/STORE_WORD/存字 <真用户全局>` —— 只有"整格就是一个纯标量变量"才放行:
                //       标量格子里装不下池地址(取**局部**地址去存 = 编译期就报「不能把局部地址存起来」;
                //       取**全局**地址 = 上面那条 ⑥ 拦住),所以 `全局计数 = 全局计数 + 1` 这种计数器的写是安全的。
                //     字符串/列表/结构/数组元素/结构字段(带 `+偏移` 的)一律照旧不回收 —— 那里装的正是池块地址。
                if (助记 == "取地址")
                {
                    // ⑥ **H84 精确化(2026-10-11):槽 + 定义-使用**。
                    //    原来"取了数据段地址就拦"太粗:数组元素 / 结构字段的正常读写都要取地址
                    //    (实测:`拼接到(果, 填区)` 要取全局数组 `填区` 的地址,`填区[k] = 120` 也要 ⇒
                    //     连 H84 的最小复现都被它拦在外面,池照旧每轮漏一块)。
                    //    新口径:只在"这个地址**确实**被当**4 字节写的地址**用"时才拦 —— 从这一行往下找,
                    //    遇到**第一处重新定义该寄存器**就停(寄存器复用不算数,这是前两版栽的地方);
                    //    池指针是 4 字节,1 / 2 字节的写装不下它。★ 仍不流敏感(保守:宁可少回收,只漏不崩)。
                    string 址寄存器 = 部分.Length >= 2 ? 部分[1] : "";
                    if (址寄存器.Length > 0)
                    {
                        for (int 查 = 扫 + 1; 查 < 体.Count; 查++)
                        {
                            string[] 后续 = 裸行(体[查]).Split(' ', StringSplitOptions.RemoveEmptyEntries);
                            if (后续.Length == 0) continue;
                            if (后续.Length >= 2 && string.Equals(后续[1], 址寄存器, StringComparison.OrdinalIgnoreCase))
                                break;                                   // 该寄存器被重新定义 ⇒ 这处引用到此为止
                            if (后续.Length >= 3
                                && 后续[0] is "存字" or "STORE_WORD" or "存字间接" or "STORE_WORD_INDIRECT"
                                && string.Equals(后续[2], 址寄存器, StringComparison.OrdinalIgnoreCase))
                                return;                                  // 真把 4 字节值写进"取到的那个地址"⇒ 不回收
                        }
                    }
                    continue;
                }
                if ((助记 is "STORE" or "STORE_WORD" or "存字") && !是纯标量整格(基础, 末)) return;
            }
            var 用户标签 = new HashSet<string>(_函数标签.Values, StringComparer.Ordinal);
            foreach (string 行 in 体)
            {
                string t = 裸行(行);
                if (!t.StartsWith("CALL ", StringComparison.Ordinal)) continue;
                if (用户标签.Contains(取首词(t[5..]))) return;   // 用户函数调用:认不出被调方把池对象存到哪
            }
            if (函数.局部偏移 + 4 > 函数帧大小) return;          // 帧里放不下水位就不做
            确保池();
            int 水位偏移 = 函数.局部偏移;
            函数.局部偏移 += 4;
            string 池指针 = _池指针槽!.Value.名称;
            const string 暂 = "R14";                             // 入口/出口两处都没有活着的值(返回值走 R0),借它用一下
            体.InsertRange(1 + (函数.需清零.Count > 0 ? 1 : 0), new[]
            {
                $"取字 {暂} {池指针}",
                $"存字帧 {暂} {水位偏移}",                        // 记下进来时的池水位
            });
            // 出口那一句(H84):返回字符串的函数**不是无条件回退** —— 目的数据块若在进来时的水位
            // **之上**,说明它是**本次调用里刚给调用方换的块**,划走就把调用方那一格弄坏了。
            // R13 / R14 在 `返回` 前面都是空的(返回值走 R0,函数到这儿就结束了),借它们用。
            // ⚠ **每处 `返回` 都要现造一份 + 新标签**:一个函数可能有好几个 `返回`(还有 `如果` 里的),
            //   标签建在循环外面就会同名插多次 ⇒ 「标签重复定义」(实测踩到:27 个标准工程当场编不过)。
            int 插 = 0;
            for (int i = 0; i < 体.Count; i++)
            {
                string t = 裸行(体[i]);                       // ← 必须剥注释:带源行标记时 `返回` 后面挂着 `// 来自第 N 行`
                if (t is not ("返回" or "RET" or "ret")) continue;
                var 回退 = new List<string> { $"取字帧 {暂} {水位偏移}" };
                string 别退 = "";
                if (函数.返回字符串)
                {
                    别退 = 新标签("池不退");
                    回退.Add($"取字帧 R13 {函数.返回地址偏移}");    // R13 = 调用方那个字符串头的地址
                    回退.Add("取字间接 R13 R13");                 // R13 = 目的数据块地址(0 = 还没有块)
                    回退.Add($"CMP R13 {暂}");
                    回退.Add($"JG {别退}");                       // 目的块在进来时的水位**之上**
                    回退.Add($"JEQ {别退}");                      //   ⇒ 本次调用里刚换的块,不许划走
                }
                回退.Add($"存字 {暂} {池指针}");
                if (别退.Length > 0) 回退.Add($"{别退}:");
                体.InsertRange(i, 回退);
                i += 回退.Count;
                插++;
            }
            if (插 > 0) _编译提示.Add($"方法 {函数.名称}:返回时回收池水位(函数里声明的字符串/列表不再每次调用都漏一块)");
        }

        /// <summary>
        /// 批 8 后半(第92批):这一笔"写用户数据段"是不是**装不下池地址**的纯标量整格?
        /// 放行的只有一种:`STORE/... 一个真用户全局的标量变量`(不带 `+偏移`)。
        /// 字符串 / 列表 / 结构 / 数组、以及任何带偏移的格子(结构字段、数组元素、字符串头的三个字)
        /// 都可能正是池块地址 ⇒ 一律返回 false(保守:不回收,只漏不崩)。
        /// </summary>
        private bool 是纯标量整格(string 基础槽, string 末词)
        {
            if (末词.Contains('+')) return false;                       // 结构字段 / 数组元素 / 头偏移:保守
            var 绑定 = _名字表.变量.FirstOrDefault(x => x.槽 == 基础槽);
            if (绑定 is not { 是全局: true }) return false;
            if (绑定.是列表 || 绑定.是数组 || 绑定.元素宽 > 0 || 绑定.元素个数 > 0 || 绑定.是引用) return false;
            var 类型 = 类型C.解析(绑定.类型名);
            return 类型 is { 宽度: <= 4 };                              // 纯标量类型(字符串/结构名 解析不出来 ⇒ null ⇒ 不放行)
        }

        /// <summary> 标记"当前这个函数里有引用"(参数由调用方传,这里只管体里的声明) </summary>
        private void 函数有引用()
        {
            if (_当前函数 is { } 函数) 函数.有引用 = true;
        }

        /// <summary> 函数返回类型是不是"标量/无返回值"(池对象只有 字符串/结构 跟着返回值出去)。
        /// H68-2 起枚举名也算标量(底层就是有符号 整数 4 字节) </summary>
        private bool 是标量返回词(string 词) => 取类型定义(词) != null || 词 is "var";

        /// <summary>
        /// 这个局部要不要在函数入口清零?只有"声明时不会立刻把自己写满"的才要:
        /// 数组(只支持整体零初始化,不发存值)、结构变量(字段各自赋值)、以及**没写初值**的标量。
        /// 写了初值的标量,声明处马上就会存进整个宽度 —— 再清一遍是白干,这就是"序言按需清零"省下的部分。
        /// </summary>
        private static bool 需要入口清零(数组类型C? 数组, 结构类型C? 结构, string 初值文本) =>
            数组 != null || 结构 != null || 初值文本.Length == 0;

        /// <summary>
        /// 声明后面**紧跟着一句"纯赋值"**吗?`短整数 p` 后面马上 `p = 算()` —— 那一句就把整个槽写满了,
        /// 入口再清零纯属白干。认得很保守,只认下面这一种,免得把"先读后写"的当成不需要清零:
        /// 下一行必须是 `名字 = 右边`,而且**右边不能提到这个名字**(`p = p + 1` 是读旧的 p:要清)。
        /// 下一行是 `}` / 别的语句 / `p++` 都不算。
        /// </summary>
        private bool 下一句就赋值(int 伪行, string 名称)
        {
            if (!_优化开 || 伪行 < 0 || 伪行 + 1 >= _伪行表.Count) return false;
            string 下一句 = _伪行表[伪行 + 1].Trim();
            if (下一句.Length == 0 || 被写名字(下一句) != 名称) return false;
            int 等号 = 下一句.IndexOf('=');
            if (等号 < 0) return false;
            string 右边 = 下一句[(等号 + 1)..];
            return !Regex.IsMatch(右边, $@"(?<![A-Za-z0-9_]){Regex.Escape(名称)}(?![A-Za-z0-9_])");
        }

        /// <summary>
        /// 函数入口的清零序言:把"需要清零"的帧区间按地址排好、**相邻的合成一段**,
        /// 每 4 字节一条 `存字帧 0, 段内偏移`(FP+常量偏移直写,连指针都不用摆)。
        /// 段很大(&gt;8 个字)才退回循环(指针用 `取地址帧` 一条摆好),免得代码膨胀。
        /// 可能多写 &lt;3 字节(只可能落在帧内其它局部或软栈余量上,序言先跑,后面都会被覆盖或本来就该是 0)。
        /// </summary>
        private List<string> 生成清零序言(IReadOnlyList<(int 起, int 宽)> 区间表)
        {
            准备语句占用("");
            var 行 = new List<string>();
            string 零 = 新临时();
            行.Add($"LOAD_IMMEDIATE {零} 0");

            // 排序 + 合并相邻(重叠也算):分成"必须逐字写"的段
            var 段表 = new List<(int 起, int 宽)>();
            foreach (var (起, 宽) in 区间表.OrderBy(x => x.起))
            {
                if (宽 <= 0) continue;
                if (段表.Count > 0)
                {
                    var 末 = 段表[^1];
                    if (起 <= 末.起 + 末.宽)      // 相邻或重叠 → 并成一段
                    {
                        段表[^1] = (末.起, Math.Max(末.起 + 末.宽, 起 + 宽) - 末.起);
                        continue;
                    }
                }
                段表.Add((起, 宽));
            }

            string 指针 = 新临时();
            foreach (var (起, 宽) in 段表)
            {
                int 字数 = Math.Max(1, (宽 + 3) / 4);                 // 不足 4 字节也写一个字(最多多写 3 字节)
                if (字数 > 8)
                {
                    // 段很大:退回循环(指针用 `取地址帧` 一条指令摆到段起点)
                    行.Add($"取地址帧 {指针} {起}");
                    string 终点 = 新临时();
                    string 环 = 新标签("FnZero");
                    行.Add($"MOV {终点} {指针}");
                    行.Add($"ADD_IMMEDIATE {终点} {字数 * 4}");
                    行.Add($"{环}:");
                    行.Add($"存字间接 {零} {指针}");
                    行.Add($"ADD_IMMEDIATE {指针} 4");
                    行.Add($"CMP {指针} {终点}");
                    行.Add($"JL {环}");
                    continue;
                }
                // 小段:一条 `存字帧` 写一个字,连指针都不用摆(FP+常量偏移)
                for (int i = 0; i < 字数; i++) 行.Add($"存字帧 {零} {起 + i * 4}");
            }
            return 行;
        }

        /// <summary> 定义名 → 汇编标签:体方法 / 模块函数的标签把名字里的 '.' 换成 '_'(预扫先登记的签名还没有标签表项,
        /// 所以这里**按同一套规则现算**,别靠表里有值 —— 调用写在定义前面时也能对得上) </summary>
        private string 汇编标签(string 定义名) =>
            _函数标签.TryGetValue(定义名, out string? 标签) ? 标签 : 定义名.Replace('.', '_');

        /// <summary>
        /// **G2(回调 / 事件的语言面):`间接调用(回调变量, 实参…)`。**
        ///
        /// 调的是哪个函数**运行期才知道**(地址来自 `地址(函数名)`,通常经参数 / 变量传进来),
        /// 所以"参数表长什么样"由**声明那一步**说了算:`回调 处理 = 地址(f);` 把 `处理 → f` 登记下来,
        /// 调用点再照 `f` 的参数表摆帧(实参个数 / 类型 / 引用参数全在编译期核对,与直接调用同一把尺子)。
        /// **调用约定与直接调用逐字同一条**(帮助第29节与 `基础库框架.md` 第6节 B 那两条配套):
        /// ①实参照旧算进"新帧的参数槽"、`MOV {帧指针寄存器} {帧基}` 照旧切帧、返回后照旧
        /// `SUB_IMMEDIATE` 复原 —— 只有最后那一条从 `CALL 标签` 换成"把地址取进寄存器 + `调用寄存器`";
        /// ②被调方 `返回` 照旧回来(`调用寄存器` 压的是**硬件栈**上的返回地址,与 `调用` 同一个口径);
        /// ③帧布局由**被调方**的声明说了算,所以地址那一格**不占参数槽**(它是"去哪",不是"传什么")。
        /// </summary>
        private void 处理间接调用(string 实参串, int 行号, string 原文)
        {
            准备语句占用(原文);
            var 快照 = 记占用();
            try { 间接调用到寄存器(实参串, 行号, 原文, null); }
            finally { _语句占用 = [.. 快照]; }     // 调用内部用的临时寄存器一次放回(与直接调用同一条纪律)
        }

        /// <summary> H86:照"回调形参的类型词表"摆出调用帧的参数表(`间接调用` 那三处回调解析共用)。
        /// 参数名一律叫 `参数1 / 参数2…` —— 回调那边只关心**槽数、宽度、类型**,不关心名字。 </summary>
        private static List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 按回调形参摆(List<string> 形参类型表)
        {
            var 表 = new List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)>();
            foreach (string 形参类型词 in 形参类型表)
            {
                int 形参宽 = 类型C.解析(形参类型词)?.宽度 ?? 类型C.字宽度;
                表.Add(($"参数{表.Count + 1}", 形参宽, 形参类型词, null));
            }
            return 表;
        }

        /// <summary> 表达式里的那一档:`整数 果 = 间接调用(处理, 3);` —— 结果按约定在 R0(不是根就落槽) </summary>
        private 表达式值 求值间接调用(调用节点C 调用, int 行号, string 原文, bool 是根)
        {
            准备语句占用(原文);
            string 文本 = string.Join(", ", 调用.实参.Select(实参 => 实参.显示()));
            间接调用到寄存器(文本, 行号, 原文, null);
            var 结果 = 表达式值.寄存器值("R0", 可写: false, 有符号: true);
            return 是根 ? 结果 : 暂存到槽(结果);
        }

        /// <summary> 间接调用的实发码:返回值按约定在 R0(返回它,便于上游按需搬走) </summary>
        private string 间接调用到寄存器(string 实参串, int 行号, string 原文, string? 首选目标)
        {
            var 实参 = 切实参(实参串);
            if (实参.Count < 1)
                throw 报错(行号, $"间接调用(回调变量, 实参…):第一个参数是**装地址的回调变量**" +
                    $"(声明写成 `回调 名字 = 地址(函数名);`)", "an indirect call needs a callback variable");
            string 回调名 = 实参[0].Trim();
            变量绑定C? 目标变量 = 查变量(回调名);
            if (目标变量 == null)
                throw 报错(行号, $"间接调用 的第一个参数要是一个**变量或参数**(它装着 `地址(函数名)` 取来的代码地址)," +
                    $"'{回调名}' 不是这层能查到的变量 —— 不能是表达式:要算就先落一个变量,再 `间接调用(那个变量, 实参…)`",
                    $"the first argument of an indirect call must be a variable holding a code address: '{回调名}'");
            if (目标变量.Value.名称 is "间接调用" or "invoke")
                throw 报错(行号, $"'{目标变量.Value.名称}' 是这条语法的名字,不能同时又当一个变量名", "reserved name");
            // 这个回调"照谁的参数表摆帧"(**H86 起分辨顺序照变量那一套:本函数的参数最先**):
            // ① **当前函数的回调参数**(`回调 比较(整数, 整数)` 写在参数表里,键 = `函数名.参数名`);
            // ② 本地 `回调 名字 = 地址(函数名);` 有登记就照那个函数;
            // ③ 兜底:裸参数名那份(老键,不该再有)。
            // 都没有 ⇒ 如实报错,绝不让运行期去猜。
            // ⚠ 为什么 ① 必须排在 ② 前面:以前是先查裸名字 ⇒ **模块级那个同名回调会把本函数的参数顶掉**
            //   (实测 `试带参(回调 条件(整数), 整数 从)` 里的 `间接调用(条件, 从)` 被模块级
            //    `回调 条件 = 地址(零参);` 抢走,报"照 `零参` 需要 0 个实参,收到 1 个")。
            //   参数是"自己人",与 `查变量` 的"局部/参数 → 本模块 → 顶层"同一条口径。
            List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 声明;
            string 形参提示 = "";
            string? 指向函数 = null;      // ② 那一支要用它;声明提到链外 —— 下面的实参收尾(出参那一路)也要读它
            string 本函数键 = _当前函数 is { } 本函数 ? 本函数.名称 + "." + 回调名 : "";
            if (本函数键.Length > 0 && _函数回调形参.TryGetValue(本函数键, out var 本函数形参表))
            {
                声明 = 按回调形参摆(本函数形参表);
                形参提示 = $"本函数那个参数 `{回调名}({string.Join(", ", 本函数形参表)})` 的形参表";
            }
            else if (试查回调表(回调名, out 指向函数))
            {
                var 链路 = 解析函数链路(指向函数, 行号);
                if (链路.收方.Length > 0)
                    throw 报错(行号, $"间接调用 只认不带收方的函数 / 方法: '{指向函数}' 是个成员方法(它的收方要自己当第一个实参传)",
                        "an indirect call cannot supply a member receiver implicitly");
                声明 = 链路.参数表;
                形参提示 = $"'{指向函数}'";
            }
            else if (_函数回调形参.TryGetValue(回调名, out var 形参类型表))
            {
                声明 = 按回调形参摆(形参类型表);
                形参提示 = $"`{回调名}({string.Join(", ", 形参类型表)})` 那份形参表";
            }
            else
                throw 报错(行号, $"间接调用 的 '{回调名}' 不是编译器认得的**回调**:它有可能是别处传来的参数。" +
                    $"要按地址调函数,请把声明写成 `回调 {回调名} = 地址(函数名);`" +
                    $"(库函数收回调就写成形参 `回调 {回调名}(整数, 整数)`)—— 编译器要照那个签名摆参数槽" +
                    $"(参数个数 / 类型 / 引用参数都在编译期核对)",
                    $"'{回调名}' is not a known callback: declare it as 回调 {回调名} = 地址(函数名);");
            if (实参.Count - 1 != 声明.Count)
                throw 报错(行号, $"间接调用:{回调名} 照 {形参提示} 需要 {声明.Count} 个实参,收到 {实参.Count - 1} 个",
                    $"wrong argument count for the callback '{回调名}'");

            // ① 实参逐个算进"新帧的参数槽" —— 与直接调用同一套(往下那几支是照 `发出表达式调用` 搬的)
            string 帧基 = 新临时();
            发出($"取地址帧 {帧基} {函数帧大小}");
            string 存址 = 新临时();
            string 长值 = 新临时();
            var 基准占用 = new List<string>(_语句占用 ?? []);
            // **推迟写**:实参在**后面的实参**里出现"取地址 / 回调地址"时不能马上写进参数槽 ——
            // 后面那次 CALL 会把临时寄存器冲掉(实测 `试(地址(加一), 41)` 的偏移 0 里最后是 41)。
            // 所以先把它落进一个临时槽,等所有实参都算完、CALL 也发完,再读回来写帧(槽不会被 CALL 动)。
            var 推迟寄存器 = new List<(int 偏移, 地址位置 槽)>();
            int 偏移 = 0;
            for (int i = 0; i < 声明.Count; i++)
            {
                int 宽度 = 声明[i].宽度;
                int 槽宽 = 声明[i].引用 != null ? 宽度 : 槽宽度(宽度);
                if (声明[i].引用 != null)
                {
                    // 引用参数:传的是**地址**(编译器自动取,与直接调用一字不差)
                    bool 是串参 = 声明[i].引用 is { 是字符串: true };
                    string 实参地址 = 声明[i].引用 is { 是字符串: true, 出参数: true }
                        ? 出实参头地址(实参[i + 1], 行号, 原文, 指向函数, i + 1)
                        : 是串参 ? 字符串实参地址(实参[i + 1], 行号, 原文).地址 : 取左值地址(实参[i + 1], 行号, 原文);
                    发出($"MOV {存址} {帧基}");
                    if (偏移 > 0) 发出($"ADD_IMMEDIATE {存址} {偏移}");
                    发出($"存字间接 {实参地址} {存址}");
                    if (声明[i].引用 is { 带长度: true })
                    {
                        if (是串参)
                        {
                            var 串源 = 字符串实参地址(实参[i + 1], 行号, 原文);
                            写数组长度到帧(帧基, 偏移, 串源.长度);
                        }
                        else if (数组实参长度(实参[i + 1], 行号) is { } 长) 写数组长度到帧(帧基, 偏移, 长);
                    }
                }
                else
                {
                    // 普通参数:走表达式那一套(常量就装载、窄槽按声明宽截断,与直接调用同办)
                    var 节点 = 表达式语法C.解析(替换地址取用(实参[i + 1], 行号, 原文));
                    表达式值 值 = 求值节点(节点, 行号, 原文, null);
                    if (槽宽 != 宽度 && 值.是常量 && (值.常量 >> (宽度 * 8)) != 0)
                        值 = 表达式值.常量值(值.常量 & 截断掩码(宽度));
                    bool 后面还有调用 = false;
                    for (int j = i + 2; j < 实参.Count; j++) if (实参[j].Contains('(')) { 后面还有调用 = true; break; }
                    if (后面还有调用)
                    {
                        值 = 暂存到槽(值);                       // 落临时槽:CALL 动不了它
                        推迟寄存器.Add((偏移, 值.槽!.Value));
                    }
                    else
                    {
                        发出($"MOV {存址} {帧基}");
                        if (偏移 > 0) 发出($"ADD_IMMEDIATE {存址} {偏移}");
                        发出($"存字间接 {取操作数寄存器(值)} {存址}");
                    }
                }
                偏移 += 槽宽;
                _语句占用 = [.. 基准占用];
                _语句常量 = null;   // 常量缓存里的寄存器可能刚被放回池子(与直接调用同一条纪律)
            }
            // 所有实参都算完了:这时才把**推迟**的那几格写进参数槽(CALL 已经发完,临时槽还在)
            foreach (var (推偏移, 推槽) in 推迟寄存器)
            {
                string 读回 = 新临时();
                发出读变量(读回, 推槽);
                发出($"MOV {存址} {帧基}");
                if (推偏移 > 0) 发出($"ADD_IMMEDIATE {存址} {推偏移}");
                发出($"存字间接 {读回} {存址}");
            }
            // 地址那格留到**最后**才读:实参求值里的内层 CALL 会冲掉它占的临时寄存器(踩过不改)
            string 目标 = 读槽到临时(目标变量.Value.槽);
            // ② 切帧 + 调寄存器 + 复原(只差最后那一条:直接调用是 `CALL 标签`)
            发出($"MOV {帧指针寄存器} {帧基}");
            发出($"调用寄存器 {目标}");
            发出($"SUB_IMMEDIATE {帧指针寄存器} {函数帧大小}");
            // 返回值照调用约定落到 **R0**(与直接调用一模一样)。被调方最后一句话未必停在 R0 里
            // (实测被调方 `取字帧 R14 0` 把参数读进 R14、`MOV R0 R14` 还没执行),所以这里显式搬一次 ——
            // 搬不走的东西:这一步之后 `目标` 就不用了,复用它当落点没有副作用。
            if (首选目标 is { } 首选 && 首选 != "R0") 发出($"MOV {首选} R0");
            else if (目标 != "R0") { 发出($"MOV {目标} R0"); return 目标; }
            return "R0";
        }

        /// <summary>
        /// 函数调用:实参逐个算进临时 → 写进"新帧的参数槽" → 切 FP → CALL → 复原 FP(结果在 R0)
        /// </summary>
        private void 处理函数调用(string 内容, int 行号)
        {
            // 批 11(D4,2026-10):带括号的 `调用 f(...)` **退役** —— 语言调用只剩"直接写名字"一种写法。
            // 不带括号的 `调用 标签` 是**汇编指令**(ISA CALL),不归这里管、也不受影响。
            string 调用首词 = 取首词(内容);
            if (调用首词 is "调用" || string.Equals(调用首词, "CALL", StringComparison.OrdinalIgnoreCase))
                throw 报错(行号,
                    $"`调用 名字(…)` 这种写法退役了:函数/方法调用**直接写名字** —— `名字(实参);`;" +
                    $"要用返回值就写进表达式(例如 `整数 果 = 名字(实参);`);" +
                    $"要调**汇编标签**仍写 `调用 标签`(不带括号,那是汇编指令)",
                    "the `调用 f(…)` form is retired: write `f(…)` directly");

            var (名, 实参串) = 解析调用(内容);
            // G2(回调 / 事件):`间接调用(地址, 实参…)` —— 调的那个函数**算出来**是哪个(与直接调用同一个调用约定)
            if (名 is "间接调用" or "invoke" || string.Equals(名, "invoke", StringComparison.OrdinalIgnoreCase))
            {
                处理间接调用(实参串, 行号, 内容);
                return;
            }
            var 链路 = 解析函数链路(名, 行号);          // 名字解析只有这一处(体里可省容器名)
            var 参数表 = 链路.参数表;

            // 返回结构 / 返回字符串的函数:结果得**有地方接** —— 单独成句的调用没有"存放地址"可递,
            // 被调方会往一个说不清的地方写(字符串还会直接踩内存)。这里直接拦住并给出写法。
            if (链路.返回类型词 is "字符串" || string.Equals(链路.返回类型词, "string", StringComparison.OrdinalIgnoreCase))
                throw 报错(行号, $"方法 '{名}' 返回 字符串,返回值要有地方接:写成 `字符串 临时 = {名}(…);` —— 字符串返回值不能单独成句",
                    $"the string returned by '{名}' needs a variable to go into");
            if (链路.返回类型词.Length > 0 && 取类型定义(链路.返回类型词) == null)   // H68-2:枚举返回算标量
                throw 报错(行号, $"方法 '{名}' 返回 {链路.返回类型词}(结构),返回值要有地方接:写成 `{链路.返回类型词} 临时 = {名}(…);`" +
                    $" —— 结构返回值不能单独成句", $"the struct returned by '{名}' needs a variable to go into");

            // 实参里还带括号(嵌套调用/带括号的式子)→ 交给表达式引擎:
            // 它会把每个实参算好并落到临时槽,免得"新帧"被内层调用覆盖
            if (实参串.Contains('('))
            {
                准备语句占用(内容);
                string 实参展开 = 替换地址取用(实参串, 行号, 内容);   // 地址(...) 先变成寄存器
                // H60 步②:成员方法的收方是编译器补的第一个实参(`p.累加(3)` ≡ `累加(p, 3)`)
                string 收方前缀 = 链路.收方.Length > 0 ? 链路.收方 + ", " : "";
                var 节点 = (调用节点C)表达式语法C.解析($"{名}({收方前缀}{实参展开})");
                if (节点.实参.Count != 参数表.Count)
                    throw 报错(行号, $"方法 '{名}' 需要 {参数表.Count} 个参数,收到 {节点.实参.Count} 个", $"wrong argument count for '{名}'");
                发出表达式调用(链路, 节点.实参, 行号, 内容);
                return;
            }

            var 实参 = 切实参(实参串);
            // H60 步②:同上一处 —— 收方补在最前面(它是个 `引用` 参数,取地址那一步自己会走)
            if (链路.收方.Length > 0) 实参.Insert(0, 链路.收方);
            if (实参.Count != 参数表.Count)
                throw 报错(行号, $"方法 '{名}' 需要 {参数表.Count - (链路.收方.Length > 0 ? 1 : 0)} 个参数," +
                    $"收到 {实参.Count - (链路.收方.Length > 0 ? 1 : 0)} 个", $"wrong argument count for '{名}'");

            准备语句占用(内容);
            string 帧基 = 新临时();
            发出($"取地址帧 {帧基} {函数帧大小}");            // 新帧紧跟本帧之后(FP+帧大小,一条指令)

            // 实参是"算一个、立刻写进新帧"的:每个实参用完就把它的临时寄存器收回,
            // 否则 8 个参数的函数会把 R0~R14 用光(帧基与语句里显式写的寄存器必须留着)
            var 基准占用 = new List<string>(_语句占用 ?? []);

            int 偏移 = 0;            for (int i = 0; i < 实参.Count; i++)
            {
                int 宽度 = 参数表[i].宽度;
                int 槽宽 = 参数表[i].引用 != null ? 宽度 : 槽宽度(宽度);
                if (参数表[i].引用 != null)
                {
                    // `出`(可写)字符串参数:传的是**调用方字符串头的地址**(一个字,没有长度字)
                    if (参数表[i].引用 is { 是字符串: true, 出参数: true })
                    {
                        string 出地址 = 出实参头地址(实参[i], 行号, 内容, 链路.查名, i + 1);
                        string 出放哪 = 新临时();
                        发出($"MOV {出放哪} {帧基}");
                        if (偏移 > 0) 发出($"ADD_IMMEDIATE {出放哪} {偏移}");
                        发出($"存字间接 {出地址} {出放哪}");
                        偏移 += 槽宽;
                        _语句占用 = [.. 基准占用];
                        _语句常量 = null;
                        continue;
                    }
                    // 引用参数:传的是"地址",编译器自动取(不用你手写 地址(...))
                    bool 是串参 = 参数表[i].引用 is { 是字符串: true };
                    string 实参地址 = 是串参 ? 字符串实参地址(实参[i], 行号, 内容).地址 : 取左值地址(实参[i], 行号, 内容);
                    string 放哪 = 新临时();
                    发出($"MOV {放哪} {帧基}");
                    if (偏移 > 0) 发出($"ADD_IMMEDIATE {放哪} {偏移}");
                    发出($"存字间接 {实参地址} {放哪}");
                    // 数组/字符串参数占两个字:地址 + 长度。长度那个字也得写进去,
                    // 不然被调方 `表.长度()`/越界检查读到 0,循环直接跳过(什么都不干)。
                    if (参数表[i].引用 is { 带长度: true })
                    {
                        if (是串参)
                        {
                            var 串源 = 字符串实参地址(实参[i], 行号, 内容);
                            写数组长度到帧(帧基, 偏移, 串源.长度);
                        }
                        else if (数组实参长度(实参[i], 行号) is { } 长) 写数组长度到帧(帧基, 偏移, 长);
                        else throw 报错(行号, $"方法 '{链路.查名}' 的第 {i + 1} 个参数是数组参数({参数表[i].类型名} 表[]):要传数组/列表的名字",
                            $"argument {i + 1} needs an array or list");
                    }
                    偏移 += 槽宽;
                    _语句占用 = [.. 基准占用];
                _语句常量 = null;   // 常量缓存里的寄存器可能刚被放回池子,别再用
                    continue;
                }
                string 值 = 新临时();
                bool 值零扩展 = 输出赋值到寄存器(值, 实参[i], 行号, 内容);   // 实参可以是表达式
                // 参数槽是宽槽(短整数按 4 字节放)→ 值的高半必须先处理,被调方读的时候才敢不掩码:
                // 无符号补 0(掩码)、有符号补符号位(符号扩展)
                if (槽宽 != 宽度 && !值零扩展)
                {
                    bool 参数有符号 = 类型C.有符号(参数表[i].类型名);
                    if (参数有符号 && 宽度 is 2) 发出符号扩展(值, 宽度, 需先掩码: true);
                    else
                    {
                        发出与立即数(值, 截断掩码(宽度));      // P11:掩码是编译期常量 → 一条 与立即数
                    }
                }
                string 地址 = 新临时();
                发出($"MOV {地址} {帧基}");
                if (偏移 > 0) 发出($"ADD_IMMEDIATE {地址} {偏移}");
                // 一次写 4 字节(省寄存器):越界那部分要么被后面的实参覆盖,要么落在局部区里被清零
                发出($"存字间接 {值} {地址}");
                // 数组参数:紧跟一个"长度"字(它占两个字:地址 + 长度)
                if (参数表[i].引用 is { 带长度: true })
                {
                    if (数组实参长度(实参[i], 行号) is { } 长) 写数组长度到帧(帧基, 偏移, 长);
                    else throw 报错(行号, $"方法 '{链路.查名}' 的第 {i + 1} 个参数是数组参数({参数表[i].类型名} 表[]):要传数组/列表的名字",
                        $"argument {i + 1} needs an array or list");
                }
                偏移 += 槽宽;
                _语句占用 = [.. 基准占用];
                _语句常量 = null;   // 常量缓存里的寄存器可能刚被放回池子,别再用
            }

            发出($"MOV {帧指针寄存器} {帧基}");
            发出($"CALL {链路.标签}");
            发出($"SUB_IMMEDIATE {帧指针寄存器} {函数帧大小}");   // 复原本函数的帧
        }

        /// <summary> `返回 值`:按函数头声明的返回类型核对/处理;不写返回类型 = 无返回值(void),不许返回值 </summary>
        private void 处理返回值(string 内容, int 行号)
        {
            if (_当前函数 is not { } 函数)
                throw 报错(行号, "'返回 值' 只能写在函数内(裸 返回 仍是汇编指令)", "'return value' is only valid inside a function");
            string 首词 = 取首词(内容);
            string 值文本 = 内容[首词.Length..].Trim();
            string 短名 = 函数.名称.Contains('.') ? 函数.名称[(函数.名称.LastIndexOf('.') + 1)..] : 函数.名称;

            // ① 无返回值(void):只能裸 `返回`
            if (函数.返回类型词.Length == 0)
            {
                if (值文本.Length > 0)
                    throw 报错(行号, $"方法 '{短名}' 没写返回类型(= 没有返回值),所以不能 `返回 值`。" +
                        $"要返回值就把函数头写成:函数 {短名}(…) 返回 <类型> {{ … }}", $"'{短名}' has no return type, cannot return a value");
                发出("返回");
                return;
            }

            // ② 声明了返回类型:必须返回值
            if (值文本.Length == 0)
                throw 报错(行号, $"方法 '{短名}' 声明了返回 {函数.返回类型词},`返回` 后面要跟一个值", $"'{短名}' must return a value of type {函数.返回类型词}");

            // ③ 返回字符串:调用方把自己那个字符串**头的地址**递进来(帧里第 0 槽),
            //    被调方把内容整份拷进去(容量不够就 ×2 换块)—— 值语义与赋值一致,不共享数据
            if (函数.返回字符串)
            {
                string 放哪 = 新临时();
                发出读变量(放哪, new 地址位置(帧槽(函数.返回地址偏移), 0, 4));
                // 转发:`返回 别的字符串函数()` —— 直接把调用方给我们的头地址再递下去,中间不用拷两次
                if (试取字符串返回调用(值文本, 行号) is { } 串调用)
                    发出表达式调用(串调用.链路, 串调用.实参, 行号, 值文本, 返回目的地址: 放哪);
                else if (是字符串操作数(值文本))
                    发出字符串拷到头地址(放哪, 值文本, 行号, 值文本);
                else
                    throw 报错(行号, $"方法 '{短名}' 要返回 字符串,这里给的不是字符串(要写字符串变量、字符串参数、字面量," +
                        $"或者另一个返回字符串的函数调用): '{值文本}'", $"'{短名}' must return a string");
                发出($"MOV R0 {放哪}");
                发出("返回");
                return;
            }

            // ④ 返回结构:把结构整块拷到"调用方给的地址",再把那个地址放进 R0(结构本身从不作为值搬来搬去)
            if (函数.返回结构 is { } 结构)
            {
                // H68-4:`返回 [式子, 式子];` —— 元组值按成员算出来,直接写进"调用方给的那块"
                // (不必先落一个局部变量再整块拷;每个成员的式子照旧走表达式那一套)
                if (是元组结构(结构) && 是元组字面量(值文本))
                {
                    准备语句占用(值文本);
                    string 结果放哪 = 新临时();
                    发出读变量(结果放哪, new 地址位置(帧槽(函数.返回地址偏移), 0, 4));   // 隐藏参数:调用方指定"结果放哪"
                    发出元组填块(结果放哪, 结构, 值文本, 行号, 值文本);
                    发出($"MOV R0 {结果放哪}");
                    发出("返回");
                    return;
                }
                bool 是它 = 像引用链(值文本) && 解析引用链(值文本, 行号) is { } 链
                    && 链.整块宽 == 结构.总宽度 && (链.需要整块 || 链.结构?.名称 == 结构.名称);
                if (!是它)
                    throw 报错(行号, $"方法 '{短名}' 要返回 {结构.名称},这里给的不是它。" +
                        $"结构必须是一个 {结构.名称} 变量/字段(先算好赋给它再 返回): '{值文本}'",
                        $"'{短名}' must return a {结构.名称}");
                var 链2 = 解析引用链(值文本, 行号)!;
                string 放哪 = 新临时();
                发出读变量(放哪, new 地址位置(帧槽(函数.返回地址偏移), 0, 4));   // 隐藏参数:调用方指定"结果放哪"
                生成结构拷贝(链地址(链2, 行号, 值文本), 放哪, 结构);          // 有字符串字段就深拷贝
                发出($"MOV R0 {放哪}");
                发出("返回");
                return;
            }

            // ④ 标量返回:不能是整块(结构/整数组),值按声明类型处理(截断/补符号)后放进 R0
            检查地址没被存起来(值文本, 行号, "返回值");
            // H68-2:返回类型是枚举 ⇒ `返回 别的枚举成员;` 当场报错(与声明 / 赋值同一条口径)
            检查跨枚举(函数.返回类型词, 值文本, 行号);
            if (像引用链(值文本) && 解析引用链(值文本, 行号) is { } 值链 && 值链.需要整块)
                throw 报错(行号, $"方法 '{短名}' 声明返回 {函数.返回类型词},但 '{值文本}' 是整块({值链.整块宽} 字节)。" +
                    $"办法:①返回一个字段,②把结果写进外面的变量,③传地址进去让被调方写(地址(某变量))",
                    "a whole block cannot be returned as a scalar");
            输出赋值($"R0 = {值文本}", 行号);
            // 声明的是窄类型 → 返回值也按它处理一次(短整数 返回 70000 会截断/补符号,和变量赋值一套规则)
            var 返回类型 = 类型C.解析(函数.返回类型词);
            if (返回类型 is { } 类型 && 类型.宽度 is 2 && (int)类型.宽度 < 类型C.字宽度)
            {
                if (类型.有符号) 发出符号扩展("R0", 2, 需先掩码: true);
                else
                {
                    发出与立即数("R0", 0xFFFFu);          // P11:一条 与立即数
                }
            }
            发出("返回");
        }
        #endregion
    }
