            }

            throw 报错(行号, $"'{规范}' 不是 G3 的运行时能力(能用的:睡眠 / 冲刷 / 改名 / 临时目录)",
                $"'{规范}' is not a runtime capability");
        }

        /// <summary>
        /// G3 域 5 **异步输入输出**的三条:`发起异步(种类, 参数一, 参数二, 参数三, 任务)` /
        /// `任务就绪(任务号, 状态, 字节数)` / `取消任务(任务号)`。
        ///
        /// 路是**宿主线程池**(用户 2026-10-03 拍板,见 `基础库施工计划.md` §1.3):
        /// `发起异步` 把活交出去、**立刻**返回任务号;真阻塞那一趟在宿主后台线程上跑;
        /// VM 照旧单线程,`任务就绪` 只是"读一格状态 + 把结果搬回来"。
        ///
        /// **三个实参按种类解释**(这是本域的施工图;`参数二` 那一格三种用途不一样):
        ///   · 种类 `1` 读文件:参数一 = 路径,**参数二 = 收内容的 `字符串` 变量**,参数三 = 上限字节数(1~1048576);
        ///   · 种类 `2` 写文件:参数一 = 路径,参数二 = 要写的串,参数三 = 要写的字节数(0 = 整段都写);
        ///   · 种类 `3` 连接:参数一 = 主机,参数二 = 不用(写 `""`),参数三 = 端口。
        ///
        /// **结果怎么出来**(`任务就绪` 那两个写回的 `整数` 变量):
        ///   · `状态` = 这一趟的**结果状态**(0 = 成了;失败是具体状态码:2 打不开 / 4 读写失败 / 17 连不上…);
        ///   · `字节数` = 这一趟的**结果数字**(读 / 写:做了几个字节;**连接**:新连接的句柄 ——
        ///     连接没有"字节数",那一格就是它的结果,拿它去 `发送` / `接收` / `关闭`)。
        ///   读文件的内容**不进这两个变量**:它在 `任务就绪` 说"好了"那一刻直接写进 `发起` 时指定的那个
        ///   `字符串` 变量(与 `读文件` / `读一块` 同一条路:写的是字符串的**头 + 池**,不是标量槽)。
        ///
        /// ⚠ **中文名为什么是 `发起异步` / `任务就绪` / `取消任务`**:施工图上先写的是
        ///   `发起` / `查就绪` / `取消`,而 **`取消` 已经被 `Sample\库\定时.hb` 的 `方法 取消(整数 号)` 占了**
        ///   (那个库内部还写着裸的 `取消(号)`),语言内建名又**优先于用户函数**(见 `是宿主能力名` 那一路)——
        ///   内建叫 `取消` 会把 `定时.hb` 整段打断。这正是 `连到` 不叫 `连接` 那一条让路(硬规矩 8);
        ///   三个名字一起让位,语义一字不差。
        /// </summary>
        private 表达式值 求值异步(string 规范, 调用节点C 调用, int 行号, string 原文)
        {
            // ---- 发起异步:`(种类, 参数一, 参数二, 参数三, 任务)` → 任务号(排不上给 -1) ----
            if (规范 == "startasync")
            {
                if (调用.实参.Count != 5)
                    throw 报错(行号, "发起异步(种类, 参数一, 参数二, 参数三, 任务) 要五个参数:种类(1 读文件 / 2 写文件 / 3 连接)、" +
                        "参数一(路径 / 主机)、参数二(读文件:收内容的 `字符串` 变量;写文件:要写的串;连接:写 `\"\"`)、" +
                        "参数三(上限字节数 / 要写的字节数 / 端口)、任务号收进哪个 `整数` 变量",
                        "startasync(kind, a, b, c, task) takes five arguments");
                if (调用.实参[0] is not 常量节点C 种类节点 || 种类节点.值 is not (宿主能力C.种类_读文件
                        or 宿主能力C.种类_写文件 or 宿主能力C.种类_连接))
                    throw 报错(行号, "发起异步 的第一个参数 `种类` 要写一个编译期就定下来的数字:" +
                        "**1 = 读文件** / **2 = 写文件** / **3 = 连接**;" +
                        $"现在给的是 '{调用.实参[0].显示()}'。办法:写 `发起异步(1, \"数据/大.txt\", 内容, 4096, 任务)` 这样的数字",
                        "startasync kind must be a compile-time number (1 read / 2 write / 3 connect)");
                if (调用.实参[4] is not 名字节点C)
                    throw 报错(行号, "发起异步 的第五个参数要写**一个 `整数` 变量的名字**(任务号收进它里面):" +
                        $"现在给的是 '{调用.实参[4].显示()}'",
                        "startasync fifth argument must be an integer variable name");
                int 种类 = (int)种类节点.值;
                变量槽定义 任务槽 = 变量数据槽(实参文本(4, 调用.实参), 行号, "发起异步");

                // 请求块 40 字节(与 `宿主能力C.处理发起异步` / C 侧 `hb_host_发起异步` 同一张表):
                //   +0 种类 / +4 参数一址 / +8 参数一长 / +12 参数二址 / +16 参数二长 / +20 参数三 / +24 任务号(写回)
                //   / +28 头址 / +32 池指针槽 / +36 池末槽
                变量槽定义 块 = 新槽(40);
                string 块名 = 块.名称;

                string 种类寄存器 = 新临时();
                输出装载常量(种类寄存器, (uint)种类);
                发出($"存字 {种类寄存器} {块名}");

                (string 参数一址, string 参数一长) = 字符串地址与长(调用.实参[1], 行号, 原文);
                发出($"存字 {参数一址} {块名}+4");
                发出($"存字 {参数一长} {块名}+8");

                string 参数三寄存器 = 新临时();
                if (种类 == 宿主能力C.种类_连接)
                {
                    // 连接:参数二 那一格不用(施工图里 `参数二` 只给写文件用);参数三 = 端口(随便算)
                    (string 参数二址, string 参数二长) = 字符串地址与长(调用.实参[2], 行号, 原文);
                    发出($"存字 {参数二址} {块名}+12");
                    发出($"存字 {参数二长} {块名}+16");
                    表达式值 端口值 = 求值表达式(调用.实参[3].显示(), 行号, 原文);
                    发出($"存字 {取操作数寄存器(端口值)} {块名}+20");
                }
                else
                {
                    if (调用.实参[3] is not 常量节点C 参数三节点 || 参数三节点.值 > 1024 * 1024)
                        throw 报错(行号, $"发起异步 的第四个参数 `参数三` 要写一个编译期就定下来的数字(0 ~ 1048576):" +
                            $"{(种类 == 宿主能力C.种类_读文件 ? "读文件时它是**上限字节数**(0 = 4096 兜底)" : "写文件时它是**要写的字节数**(0 = 整段都写)")};" +
                            $"现在给的是 '{调用.实参[3].显示()}'",
                            "startasync fourth argument must be a compile-time number (0..1048576)");
                    输出装载常量(参数三寄存器, 参数三节点.值);
                    发出($"存字 {参数三寄存器} {块名}+20");
                    if (种类 == 宿主能力C.种类_读文件)
                    {
                        if (调用.实参[2] is not 名字节点C)
                            throw 报错(行号, "发起异步 的第三个参数要写**一个 `字符串` 变量的名字**(读回来的内容放它里面):" +
                                $"现在给的是 '{调用.实参[2].显示()}'",
                                "startasync third argument must be a string variable name for a read task");
                        string 读内容变量 = 实参文本(2, 调用.实参);
                        string 块头址 = 出实参头地址(读内容变量, 行号, 原文, "发起异步", 3);
                        确保池();                       // 与 `读一块` 同一条次序:先拿到头地址、再把池备好
                        发出($"存字 {块头址} {块名}+28");
                        自成一段(() =>
                        {
                            string 池指针址 = 新临时();
                            发出($"取地址 {池指针址} {_池指针槽!.Value.名称}");
                            发出($"存字 {池指针址} {块名}+32");
                            string 池末址 = 新临时();
                            发出($"取地址 {池末址} {_池末槽!.Value.名称}");
                            发出($"存字 {池末址} {块名}+36");
                        });
                    }
                    else
                    {
                        (string 写数据址, string 写数据长) = 字符串地址与长(调用.实参[2], 行号, 原文);
                        发出($"存字 {写数据址} {块名}+12");
                        发出($"存字 {写数据长} {块名}+16");
                    }
                }

                // ⚠ 任务号**先由宿主写进请求块自己那一格**(+24),再由中间层 `发出写变量` 搬进用户变量 ——
                //   理由与 `打开读流` 同一条(顶层标量槽会被后面的数组 / 压缩盖掉)
                string 开状态 = 发出宿主调用(块, 宿主能力C.功能_发起异步);
                发出($"存字 {开状态} {块名}+12");
                string 任务号 = 新临时();
                发出($"LOAD_WORD {任务号} {块名}+24");
                发出写变量(任务号, 任务槽);
                return 表达式值.寄存器值(任务号, 可写: true);
            }

            // ---- 任务就绪:`(任务号, 状态, 字节数)` → 状态码(0 还没好 / 1 好了 / …) ----
            if (规范 == "taskready")
            {
                if (调用.实参.Count != 3)
                    throw 报错(行号, "任务就绪(任务号, 状态, 字节数) 要三个参数:哪个任务、结果状态写进哪个 `整数` 变量、" +
                        "结果数字写进哪个 `整数` 变量(读 / 写:几个字节;**连接**:新连接的句柄);" +
                        "返回值 = 0 还没好 / 1 好了 / 2 这一趟失败 / 3 任务号作废 / 22 任务号不成形",
                        "taskready(task, status, count) takes three arguments");
                if (调用.实参[1] is not 名字节点C)
                    throw 报错(行号, "任务就绪 的第二个参数要写**一个 `整数` 变量的名字**(结果状态写进它里面):" +
                        $"现在给的是 '{调用.实参[1].显示()}'", "taskready second argument must be an integer variable name");
                if (调用.实参[2] is not 名字节点C)
                    throw 报错(行号, "任务就绪 的第三个参数要写**一个 `整数` 变量的名字**(结果数字写进它里面):" +
                        $"现在给的是 '{调用.实参[2].显示()}'", "taskready third argument must be an integer variable name");
                变量槽定义 状态槽 = 变量数据槽(实参文本(1, 调用.实参), 行号, "任务就绪");
                变量槽定义 字节槽 = 变量数据槽(实参文本(2, 调用.实参), 行号, "任务就绪");

                // 请求块 16 字节:+0 任务号 / +4 状态(写回)/ +8 字节数(写回)/ +12 状态码(本层存)
                // ⚠ 状态与字节数是**两格**(域 1 踩过"状态 0 把字节数盖成 0");状态码另存 +12,三格一个都不撞
                变量槽定义 查块 = 新槽(16);
                string 查块名 = 查块.名称;
                string 查号 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {查号} {查块名}");
                string 查码 = 发出宿主调用(查块, 宿主能力C.功能_任务就绪);
                发出($"存字 {查码} {查块名}+12");
                string 状态值 = 新临时();
                发出($"取字 {状态值} {查块名}+4");
                发出写变量(状态值, 状态槽);
                string 字节值 = 新临时();
                发出($"取字 {字节值} {查块名}+8");
                发出写变量(字节值, 字节槽);
                string 查结果 = 新临时();
                发出($"取字 {查结果} {查块名}+12");
                return 表达式值.寄存器值(查结果, 可写: true);
            }

            // ---- 取消任务:`(任务号)` → 状态码(0 取消成功 / 3 号已作废 / 22 号不成形) ----
            if (规范 == "canceltask")
            {
                if (调用.实参.Count != 1)
                    throw 报错(行号, "取消任务(任务号) 要一个参数:不要哪个任务了(0 = 取消成功;" +
                        "**尽力而为** —— 已经在跑的那一趟拦不住,但它跑完的结果不会再交出来)",
                        "canceltask(task) takes one argument");
                变量槽定义 消块 = 新槽(8);
                string 消号 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {消号} {消块.名称}");
                return 表达式值.寄存器值(发出宿主调用(消块, 宿主能力C.功能_取消任务), 可写: true);
            }

            throw 报错(行号, $"'{规范}' 不是 G3 的异步能力(能用的:发起异步 / 任务就绪 / 取消任务)",
                $"'{规范}' is not an async capability");
        }

        /// <summary>
        /// G3 域 3 网络(裸 socket)的七条:`连到(主机, 端口, 句柄)` / `发送(句柄, 数据)` /
        /// `接收(句柄, 数据变量, 上限)` / `关闭(句柄)` / `监听(网卡地址, 端口, 句柄)` /
        /// `接受(监听句柄, 句柄)` / `主机解析(主机, 地址变量)`。
        ///
        /// 句柄接法与 G3 流**一字不差**(用一个 `整数` 变量接、`-1` = 没开成):宿主给的是
        /// `((表下标 + 流表格数) &lt;&lt; 16) | 版本`,两张表的句柄永远撞不上(见 `宿主能力C.拼套接字句柄`)。
        /// 返回值:`连到` / `监听` / `接受` 给**句柄**(失败 -1),`发送` / `接收` 给**字节数**
        /// (失败 -1;`接收` 收到 0 = 对端关掉了),`关闭` 给状态码,`主机解析` 给逻辑。
        ///
        /// ⚠ **`连到` 为什么不叫 `连接`**:`连接`(以及它的英文 `connect`)是 `Sample\库\string.hb`
        /// 里"把几段拼成一条"那个库函数的名字 —— 一个标识符不能同时是两样东西(硬规矩 8:
        /// `出` 的英文别名当年也从 `out` 改成了 `result`)。新这一条让路,语义一字不差。
        /// </summary>
        private 表达式值 求值网络(string 规范, 调用节点C 调用, int 行号, string 原文)
        {
            // ---- 连到 / 监听:`(主机, 端口, 句柄)` → 句柄 ----
            if (规范 is "connect" or "listen")
            {
                string 谁 = 规范 == "connect" ? "连到" : "监听";
                if (调用.实参.Count != 3)
                    throw 报错(行号, $"{谁}({(规范 == "connect" ? "主机, 端口" : "网卡地址, 端口")}, 句柄) 要三个参数:" +
                        (规范 == "connect"
                            ? "连哪台主机(主机名或 IP)、哪个端口(1~65535)、句柄收进哪个 `整数` 变量"
                            : "绑哪块网卡的 **IP**(`127.0.0.1` 只收本机、`0.0.0.0` 哪块都收;不认主机名)、" +
                              "哪个端口(1~65535)、句柄收进哪个 `整数` 变量") +
                        $";**主机 + 端口要先写进工程文件 `.hbp` 的 `网址` 表**(要写到端口)," +
                        (规范 == "connect" ? "不在表里连试都不试" : "不在表里绑都不绑"),
                        $"{规范}(host, port, handle) takes three arguments");
                if (调用.实参[2] is not 名字节点C)
                    throw 报错(行号, $"{谁} 的第三个参数要写**一个 `整数` 变量的名字**(句柄收进它里面):" +
                        $"现在给的是 '{调用.实参[2].显示()}'", $"{规范} third argument must be an integer variable name");
                string 句柄名 = 实参文本(2, 调用.实参);
                变量槽定义 句柄槽 = 变量数据槽(句柄名, 行号, 谁);

                // ⚠ 句柄**先由宿主写进请求块自己那一格**(+12),再由中间层 `发出写变量` 搬进用户变量 ——
                //   理由与 `打开读流` 同一条(顶层标量槽会被后面的数组 / 压缩盖掉)。
                变量槽定义 网块 = 新槽(16);
                (string 主机址, string 主机长) = 字符串地址与长(调用.实参[0], 行号, 原文);
                发出($"存字 {主机址} {网块.名称}");
                发出($"存字 {主机长} {网块.名称}+4");
                // ⚠ 端口**先算先落块**:寄存器在表达式的求值之间会重分配,算晚了就被后面的人抢走
                表达式值 端口值 = 求值表达式(调用.实参[1].显示(), 行号, 原文);
                string 端口寄存器 = 取操作数寄存器(端口值);
                发出($"存字 {端口寄存器} {网块.名称}+8");
                string 开状态 = 发出宿主调用(网块, 规范 == "connect" ? 宿主能力C.功能_连接 : 宿主能力C.功能_监听);
                发出($"存字 {开状态} {网块.名称}");            // 状态写 +0(句柄那一格留给宿主写的句柄)
                string 句柄值 = 新临时();
                发出($"LOAD_WORD {句柄值} {网块.名称}+12");     // 宿主写进来的句柄(失败时是 -1)
                发出写变量(句柄值, 句柄槽);
