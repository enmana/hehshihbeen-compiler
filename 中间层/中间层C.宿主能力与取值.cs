        private void 输出一个值(string 参数, int 行号, string 原文)
        {
            // ⓪ 一个"文字"(`文字` 变量,或字符串取字 `名字[下标]`):按 UTF-8 编出来再打印(中文不会打成乱码)
            if (试取文字值(参数, 行号, 原文) is { } 码点)
            {
                输出一个文字(码点);
                return;
            }
            // ① 字符串字面量
            if (参数.Length >= 2 && 参数[0] == '"' && 参数[^1] == '"' && 找字符串字面量(参数) is { } 内文 && 内文.Length == 参数.Length - 2)
            {
                var (槽, 字节数) = 字符串槽(内文, 行号);
                确保打印串例程();
                占住子程序约定寄存器();                       // R11/R12 是子程序的约定,先占住再分配临时寄存器
                string 地址 = 新临时();
                发出($"取地址 {地址} {槽.名称}");
                发出($"MOV R12 {地址}");
                string 长 = 新临时();
                输出装载常量(长, (uint)字节数);
                发出($"MOV R11 {长}");
                发出($"CALL {_打印串例程}");
                return;
            }
            // ①' 字符串变量 / 字符串参数(整名):按**长度**打。
            //    不能像字符数组那样"打到第一个 0 为止" —— 池里紧跟其后的可能就是别的字符串。
            if (是池串整名(参数))
            {
                确保打印串例程();
                占住子程序约定寄存器();                       // R11/R12 是子程序的约定,先占住再分配临时寄存器
                var (数据址, 字节长) = 串数据与字节长(参数, 行号, 原文);
                发出($"MOV R12 {数据址}");
                发出($"MOV R11 {字节长}");
                发出($"CALL {_打印串例程}");
                return;
            }
            // ①'' 堆串字段/元素(`记录.名字` / `名单[i]`):数据在堆里、0 结尾 —— 数出长度按长度打
            //     (堆块后面就是空闲区,不能"打到 0 为止"那样越读)
            if (取堆串链(参数) is { } 堆链)
            {
                确保打印串例程();
                占住子程序约定寄存器();
                string 堆字地址 = 串字地址(堆链, 行号, 原文);
                string 堆数据 = 新临时();
                发出间接读(堆数据, 堆字地址, 4);
                发出($"MOV R12 {堆数据}");
                发出($"MOV R11 {发出堆串长度(堆数据)}");        // H112 第 2 段:读块首的长度字(夹 \0 也不截断)
                发出($"CALL {_打印串例程}");
                return;
            }
            // ①''' `返回 字符串` 的函数调用直接当输出参数(`输出行(取名字())`):
            //      物化到隐藏临时串,再按长度打(和字符串变量一个口径)
            if (是字符串返回调用文本(参数, 行号))
            {
                var 临时串 = 物化串返回调用(参数, 行号, 原文);
                确保打印串例程();
                占住子程序约定寄存器();                       // R11/R12 是子程序的约定,先占住再分配临时寄存器
                string 数据 = 读临时(临时串.指针槽!.Value);
                string 长度 = 读临时(临时串.长度槽);
                发出($"MOV R12 {数据}");
                发出($"MOV R11 {长度}");
                发出($"CALL {_打印串例程}");
                return;
            }
            // ② 字符/字节的数组或列表(整名;结构里的数组字段 `记录.名字` 也算)→ 按字节打
            if (查变量(参数) is { } 块绑定 && (块绑定.是数组 || 块绑定.是列表) && 块绑定.元素宽 == 1)
            {
                输出字节块(块绑定, 行号);
                return;
            }
            // 注意:下面这两处"看是不是数组/字段链"只能用**不带括号**的写法去试 ——
            // `输出行(表.长度())` 这种"表达式实参"传给 解析引用链 会被它当成字段访问而报"不是结构变量"(用户实测踩到)
            bool 像链 = 像引用链(参数);
            if (像链 && 解析引用链(参数, 行号) is { 有运行期下标: false } 块链 && 块链.是数组或列表 && 块链.元素宽 == 1)
            {
                确保打印到零例程();
                占住子程序约定寄存器();
                发出($"MOV R12 {链地址(块链, 行号, 原文)}");
                发出($"CALL {_打印串到零例程}");
                return;
            }
            // ③ 其余:算进寄存器;字符/字节(1 字节、不是逻辑)按字节打,数字按十进制打
            var 值 = 落到寄存器(求值表达式(参数, 行号, 原文));
            // 编译期就知道是负数:直接打个 '-' 再打绝对值的常量,一个临时寄存器都不用
            if (值.是常量 && 值.有符号 && (int)值.常量 < 0)
            {
                string 负号 = 新临时();
                发出($"LOAD_IMMEDIATE {负号} 45");
                发出($"OUT {负号}");
                发出打印十进制(常量入临时(0u - 值.常量));
                return;
            }
            string 寄存器 = 值.是常量 ? 常量入临时(值.常量) : 值.寄存器!;
            if (是单字节值(参数, 行号)) { 发出($"OUT {寄存器}"); return; }
            if (值.有符号)
            {
                发出处理负号(ref 寄存器, 可改写: 值.可写);
            }
            发出打印十进制(寄存器);
        }

        /// <summary> 这个写法读出来的是不是"一个字节"(字符/字节);逻辑按数字打(0/1),看得见</summary>
        private bool 是单字节值(string 参数, int 行号)
        {
            string 名 = 参数.Trim();
            if (!像引用链(名)) return false;      // 表达式(如 表.长度()、读取字符())不是"一个字节变量"
            if (查变量(名) is { } 绑定 && !绑定.是数组 && !绑定.是列表 && !绑定.是结构 && !绑定.是引用)
                return 绑定.槽.宽度 == 1 && !绑定.是逻辑;
            if (解析引用链(名, 行号) is { } 链 && !链.需要整块) return 链.标量读宽 == 1;
            return false;
        }

        /// <summary>
        /// 把"内部子程序约定用的寄存器"先占住(R11/R12/R13、读输入还要 R0)。
        /// **必须在分配临时寄存器之前调**:不然 新临时() 可能正好选中 R12,后脚 `MOV R12 …` 就把地址冲了
        /// (测评后加 I/O 时踩过:读取行读到的 5 个字节写到了地址 8 上,缓冲区一个字节没进)。
        /// `含读行标志`(B1,第110批):读行例程还用 **R1** 报"是不是缓冲满了停的",调用方要跨 CALL 读它。
        /// </summary>
        private void 占住子程序约定寄存器(bool 含返回 = false, bool 含读行标志 = false)
        {
            _语句占用 ??= [];
            _语句占用.Add("R11");
            _语句占用.Add("R12");
            _语句占用.Add("R13");
            if (含返回) _语句占用.Add("R0");
            if (含读行标志) _语句占用.Add("R1");
        }

        /// <summary> 打印 字符/字节 的数组或列表:R12 = 数据地址,打到第一个 0 为止
        /// (数组多半比文字长,后面全是 0;`读取行` 读进来的也是这种情况)</summary>
        private void 输出字节块(变量绑定C 绑定, int 行号)
        {
            确保打印到零例程();
            占住子程序约定寄存器();
