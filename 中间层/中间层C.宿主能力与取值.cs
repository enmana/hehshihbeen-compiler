        /// 读的结果是"值",所以它们走表达式那条路(可以赋值、可以比较、可以当实参)。
        /// </summary>
        private 表达式值 求值读取(调用节点C 调用, int 行号, string 原文)
        {
            string 规范 = 调用.名 is "读取字符" or "readchar" ? "readchar"
                : 调用.名 is "读取数字" or "readnum" ? "readnum"
                : 调用.名 is "读取行" or "readline" ? "readline"
                : "";
            if (规范 == "readchar")
            {
                if (调用.实参.Count != 0) throw 报错(行号, "读取字符() 不带参数", "readchar() takes no arguments");
                string t = 新临时();
                发出($"IN {t}");                                   // 没有输入了给 0xFFFFFFFF(判断写 == -1)
                return 表达式值.寄存器值(t, 可写: true);
            }
            if (规范 == "readnum")
            {
                if (调用.实参.Count != 0) throw 报错(行号, "读取数字() 不带参数", "readnum() takes no arguments");
                确保读数字例程();
                占住子程序约定寄存器(含返回: true);
