            string 偏移文本 = 调用.实参[1].显示();

            确保池();
            string 块请求 = 新槽(32).名称;
            (string 块路径址, string 块路径长) = 字符串地址与长(调用.实参[0], 行号, 原文);
            string 块请求址 = 新临时();
            发出($"取地址 {块请求址} {块请求}");
            发出($"存字 {块路径址} {块请求}");
            发出($"存字 {块路径长} {块请求}+4");
            发出($"存字 {块头址} {块请求}+8");
            自成一段(() =>
            {
                string 池指针址 = 新临时();
                发出($"取地址 {池指针址} {_池指针槽!.Value.名称}");
                发出($"存字 {池指针址} {块请求}+12");
                string 池末址 = 新临时();
                发出($"取地址 {池末址} {_池末槽!.Value.名称}");
                发出($"存字 {池末址} {块请求}+16");
            });
            // ⚠ 偏移**必须在这之后**才算:上面那个 `自成一段`(池槽)会重开寄存器池,
            // 先算好的寄存器会被它拿去做临时寄存器(实测:偏移被写成池末槽的地址 → 宿主报参数不合法)
            表达式值 偏移值 = 求值表达式(偏移文本, 行号, 原文);
            string 偏移寄存器 = 取操作数寄存器(偏移值);
            发出($"存字 {偏移寄存器} {块请求}+20");
            string 块上限寄存器 = 新临时();
            输出装载常量(块上限寄存器, 块上限节点.值);
            发出($"存字 {块上限寄存器} {块请求}+24");
            string 块状态 = 发出宿主调用(块请求址, 宿主能力C.功能_读文件块);
            发出($"存字 {块状态} {块请求}+28");
            string 块最终状态 = 新临时();
            发出($"取字 {块最终状态} {块请求}+28");
            return 状态转逻辑(块最终状态, 行号, "读文件块");
        }

        /// <summary>
        /// G3 流式读写的七条:`打开读流(路径, 句柄)` / `读一块(句柄, 块, 上限)` / `定位(句柄, 偏移)` /
        /// `关读流(句柄)` / `打开写流(路径, 句柄)` / `写一块(句柄, 内容, 字节数)` / `关写流(句柄)`。
        ///
        /// 为什么句柄用**一个 `整数` 变量**接:语言里没有"文件指针"这种类型 —— 宿主给的是
        /// `(表下标 &lt;&lt; 16) | 版本` 的整数(见 `宿主能力C.流表格数`),句柄当场作废就认不出来了。
        /// 返回值照用户 2026-10-02 拍板:`读一块` / `写一块` 给字节数(失败 -1;`读一块` 到末尾给 0),
        /// `打开*` 给句柄(失败 -1),`定位` / `关*` 给**状态码**(0 = 成功)。
        /// </summary>
        private 表达式值 求值流(string 规范, 调用节点C 调用, int 行号, string 原文)
        {
            // ---- 打开读流 / 打开写流:`(路径, 句柄变量)` ----
            if (规范 is "openread" or "openwrite")
            {
                string 谁 = 规范 == "openread" ? "打开读流" : "打开写流";
                if (调用.实参.Count != 2)
                    throw 报错(行号, $"{谁}(路径, 句柄) 要两个参数:开哪个文件、句柄收进哪个 `整数` 变量" +
                        (规范 == "openread" ? "(文件必须已经存在)" : "(文件不存在就新建;已存在就**从头写起**)"),
                        $"{规范}(path, handle) takes two arguments");
                if (调用.实参[1] is not 名字节点C)
                    throw 报错(行号, $"{谁} 的第二个参数要写**一个 `整数` 变量的名字**(句柄收进它里面):" +
                        $"现在给的是 '{调用.实参[1].显示()}'", $"{规范} second argument must be an integer variable name");
                string 句柄名 = 实参文本(1, 调用.实参);
                变量槽定义 句柄槽 = 变量数据槽(句柄名, 行号, 谁);

                // ⚠ 句柄**先由宿主写进请求块自己那一格**(+8),再由中间层 `发出写变量` 搬进用户变量。
                //   不能让宿主直接往用户变量的槽号写:顶层标量槽在汇编那一步会被压缩 / 被包住它的数组覆盖
                //   (实测踩过:`整数 表[64];` 一排在前面,宿主写进那个槽号的值被数组那块盖掉,
                //   读回来是 -1,后面每一句都报"句柄无效")。请求块是**本层自己开的槽**,地址最稳。
                变量槽定义 开块 = 新槽(16);
                (string 开路径址, string 开路径长) = 字符串地址与长(调用.实参[0], 行号, 原文);
                发出($"存字 {开路径址} {开块.名称}");
                发出($"存字 {开路径长} {开块.名称}+4");
                string 开状态 = 发出宿主调用(开块, 规范 == "openread" ? 宿主能力C.功能_打开读流 : 宿主能力C.功能_打开写流);
                发出($"存字 {开状态} {开块.名称}+12");
                string 句柄值 = 新临时();
                发出($"LOAD_WORD {句柄值} {开块.名称}+8");     // 宿主写进来的句柄(失败时是 -1)
                发出写变量(句柄值, 句柄槽);
                return 表达式值.寄存器值(句柄值, 可写: true);
            }

            // ---- 关读流 / 关写流:`(句柄)` → 状态码 ----
            if (规范 is "closeread" or "closewrite")
            {
                string 谁 = 规范 == "closeread" ? "关读流" : "关写流";
                if (调用.实参.Count != 1)
                    throw 报错(行号, $"{谁}(句柄) 要一个参数:开流时拿到的那个句柄(0 = 成功,别的值见帮助)" +
                        (规范 == "closewrite" ? ";它**先把缓冲冲刷到盘上**再关" : ""),
                        $"{规范}(handle) takes one argument");
                变量槽定义 关块 = 新槽(8);
                string 关句柄 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {关句柄} {关块.名称}");
                return 表达式值.寄存器值(
                    发出宿主调用(关块, 规范 == "closeread" ? 宿主能力C.功能_关读流 : 宿主能力C.功能_关写流), 可写: true);
            }

            // ---- 定位:`(句柄, 偏移)` → 状态码 ----
            if (规范 == "seek")
            {
                if (调用.实参.Count != 2)
                    throw 报错(行号, "定位(句柄, 偏移) 要两个参数:哪条流、挪到第几个字节(从文件开头算的绝对位置;" +
                        "读流 / 写流都能定,写流定位过再写就是从那儿覆盖)", "seek(handle, offset) takes two arguments");
                变量槽定义 位块 = 新槽(12);
                // ⚠ 先算第二条(偏移)、再算第一条(句柄),两个都**当场落进请求块** ——
                //   请求块地址由 `发出宿主调用(槽, 号)` 现取,不再依赖"上一条语句留下的寄存器"
                表达式值 位偏移 = 求值表达式(调用.实参[1].显示(), 行号, 原文);
                string 位偏移寄存器 = 取操作数寄存器(位偏移);
                string 位句柄 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {位句柄} {位块.名称}");
                发出($"存字 {位偏移寄存器} {位块.名称}+4");
                return 表达式值.寄存器值(发出宿主调用(位块, 宿主能力C.功能_定位), 可写: true);
            }

            // ---- 读一块:`(句柄, 块, 上限)` → 字节数(0 = 到末尾,-1 = 失败) ----
            if (规范 == "readblock")
            {
                if (调用.实参.Count != 3)
                    throw 报错(行号, "读一块(句柄, 块, 上限) 要三个参数:哪条读流、读进哪个 `字符串` 变量、" +
                        "这一块最多多少字节(编译期写死的数字)", "readblock(handle, target, limit) takes three arguments");
                if (调用.实参[2] is not 常量节点C 读上限节点 || 读上限节点.值 == 0 || 读上限节点.值 > 1024 * 1024)
                    throw 报错(行号, $"读一块 的第三个参数 `上限` 要写一个编译期就定下来的数字(1 ~ 1048576 字节):" +
                        $"现在给的是 '{调用.实参[2].显示()}'。办法:写 `读一块(句柄, 块, 4096)` 这样的数字",
                        "readblock limit must be a compile-time number (1..1048576)");
                if (调用.实参[1] is not 名字节点C)
                    throw 报错(行号, "读一块 的第二个参数要写**一个 `字符串` 变量的名字**(这一块内容放它里面):" +
                        $"现在给的是 '{调用.实参[1].显示()}'", "readblock target must be a string variable name");
                string 读块变量 = 实参文本(1, 调用.实参);
                string 读头址 = 出实参头地址(读块变量, 行号, 原文, "读一块", 2);

                确保池();
                变量槽定义 读块 = 新槽(28);
                string 读块名字 = 读块.名称;
                // 请求块与 `读文件块` **同形**(宿主那两条共用 `写进字符串变量`,偏移一个都不能错):
                //   +0 句柄 / +4(空)/ +8 头址 / +12 池指针槽 / +16 池末槽 / +20 上限 / +24 字节数
                // ⚠ 每一个值**算完就立刻落进请求块**:寄存器在语句之间 / 在 `自成一段` 与后续求值里都会重分配
                //   (实测:上限被后面的求值抢走 → 宿主读到 0;参数块地址被循环体里的 CALL 冲掉 →
                //   第二遍起 `读一块` 一直读到 0)
                string 读上限寄存器 = 新临时();
                输出装载常量(读上限寄存器, 读上限节点.值);
                发出($"存字 {读上限寄存器} {读块名字}+20");
                发出($"存字 {读头址} {读块名字}+8");
                string 读句柄 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {读句柄} {读块名字}");               // 句柄落块,紧接着就发宿主调用
                自成一段(() =>
                {
                    string 池指针址 = 新临时();
                    发出($"取地址 {池指针址} {_池指针槽!.Value.名称}");
                    发出($"存字 {池指针址} {读块名字}+12");
                    string 池末址 = 新临时();
                    发出($"取地址 {池末址} {_池末槽!.Value.名称}");
                    发出($"存字 {池末址} {读块名字}+16");
                });
                string 读状态 = 发出宿主调用(读块, 宿主能力C.功能_读一块);
                // ⚠ 状态写到 **+16**(池末槽那一格,宿主读完就不用了),**绝不能写 +24** ——
                //   那正是宿主刚写回来的字节数(踩过:状态 0 把字节数盖成 0,`读一块` 永远返回 0)
                发出($"存字 {读状态} {读块名字}+16");
                string 读字节数 = 新临时();
                发出($"取字 {读字节数} {读块名字}+24");
                return 表达式值.寄存器值(读字节数, 可写: true);
            }

            // ---- 写一块:`(句柄, 内容, 字节数)` → 真写下去的字节数(-1 = 失败) ----
            if (规范 == "writeblock")
            {
                if (调用.实参.Count != 3)
                    throw 报错(行号, "写一块(句柄, 内容, 字节数) 要三个参数:哪条写流、写哪段内容(一个 `字符串`:" +
                        "变量 / 字面量 / `字符 缓冲[16]` 都行,缓冲按**头一个 0 字节之前**算长度)、写几个字节" +
                        "(写 0 就表示\"上面那段内容全写下去\")", "writeblock(handle, content, count) takes three arguments");
                if (调用.实参[2] is not 常量节点C 写个数节点 || 写个数节点.值 > 1024 * 1024)
                    throw 报错(行号, $"写一块 的第三个参数 `字节数` 要写一个编译期就定下来的数字(0 ~ 1048576;" +
                        $"0 = 整段都写):现在给的是 '{调用.实参[2].显示()}'。办法:写 `写一块(句柄, 内容, 0)` 这样的数字",
                        "writeblock count must be a compile-time number (0..1048576)");
                变量槽定义 写块 = 新槽(16);
                (string 写数据址, string 写数据长) = 字符串地址与长(调用.实参[1], 行号, 原文);
                发出($"存字 {写数据址} {写块.名称}+4");
                if (写个数节点.值 > 0)
                {
                    string 写个数寄存器 = 新临时();
                    输出装载常量(写个数寄存器, 写个数节点.值);
                    发出($"存字 {写个数寄存器} {写块.名称}+8");
                }
                else
                {
                    发出($"存字 {写数据长} {写块.名称}+8");       // 0 = 整段都写:长度就用字符串自己的
                }
                string 写句柄 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {写句柄} {写块.名称}");
                // ⚠ 这里**不再写状态**:写一块的返回值就是宿主写回 `+12` 的那个**字节数**,而状态
                //   (0 = 成功)一个字都没有用武之地。以前那句"存字 状态 槽+12"正好把字节数盖成 0 ——
                //   `写一块` 于是永远返回 0(示例27 的预期输出里那三个 0 就是这一条留下的疤;
                //   与 `读一块` 那个"绝不能写 +24"是同一个坑,这里干脆连写都不写)。
                发出宿主调用(写块, 宿主能力C.功能_写一块);
                string 写字节数 = 新临时();
                发出($"取字 {写字节数} {写块.名称}+12");
                return 表达式值.寄存器值(写字节数, 可写: true);
            }

            throw 报错(行号, $"'{规范}' 不是 G3 的流能力(能用的:打开读流 / 读一块 / 定位 / 关读流 / 打开写流 / 写一块 / 关写流)",
                $"'{规范}' is not a stream capability");
        }

        /// <summary>
        /// G3 域 6 **运行时**的四条:`睡眠(毫秒)` / `冲刷(句柄)` / `改名(旧路径, 新路径)` /
        /// `临时目录(目录变量, 上限)`。
        ///
        /// 返回形态照用户的拍板(2026-10-02,见 `任务清单.md` 第340节):
        ///   · `睡眠` / `冲刷` 给**整数状态码**(0 = 成功;睡负数给 9、冲刷读流给 9、句柄作废给 22)——
        ///     与 `定位` / `关读流` 那一族同形(它们本来就不返回"成败"两个值,值本身有别的意思);
        ///   · `改名` 给 **`逻辑`**(与同族的 `移动到` / `复制到` 一个样:`状态转逻辑`);
        ///   · `临时目录` 是**把结果写进一个 `字符串` 变量**再给 `逻辑` —— 与 `环境变量` / `列目录`
        ///     同形(HB 的内建函数不能"返回一个字符串",要拿到串就得给一个变量接)。
        ///
        /// ⚠ **`睡眠` 的英文别名不是 `sleep`**:`sleep` 已经是 GUI 那条 `等待(毫秒)`(让出一帧)的英文名,
        /// 一个标识符不能同时是两样东西(硬规矩 8)⇒ 这一条取 `sleepms`。中文名两个都在,不会混。
        /// </summary>
        private 表达式值 求值运行时(string 规范, 调用节点C 调用, int 行号, string 原文)
        {
            // ---- 睡眠:`(毫秒)` → 状态码(0 = 睡满;负数给 9) ----
            if (规范 == "sleepms")
            {
                if (调用.实参.Count != 1)
                    throw 报错(行号, "睡眠(毫秒) 要一个参数:睡多少毫秒(负数不睡,给状态 9)。" +
                        "它**会把程序停在那儿** —— 界面程序请用 `等待(毫秒)` 或 `定时.hb`,别拿它睡界面主循环",
                        "sleepms(ms) takes one argument");
                变量槽定义 睡块 = 新槽(8);
                表达式值 睡毫秒 = 求值表达式(调用.实参[0].显示(), 行号, 原文);
                string 睡毫秒寄存器 = 取操作数寄存器(睡毫秒);
                发出($"存字 {睡毫秒寄存器} {睡块.名称}");
                return 表达式值.寄存器值(发出宿主调用(睡块, 宿主能力C.功能_睡眠), 可写: true);
            }

            // ---- 冲刷:`(句柄)` → 状态码(只认写流:读流给 9) ----
            if (规范 == "flush")
            {
                if (调用.实参.Count != 1)
                    throw 报错(行号, "冲刷(句柄) 要一个参数:开写流时拿到的那个句柄(0 = 成功;" +
                        "它只认**写流**,读流给 9)。它把缓冲落盘、**流还开着**,后头接着 `写一块` 就行",
                        "flush(handle) takes one argument");
                变量槽定义 冲块 = 新槽(8);
                string 冲句柄 = 求值表达式寄存器(调用.实参[0], 行号, 原文);
                发出($"存字 {冲句柄} {冲块.名称}");
                return 表达式值.寄存器值(发出宿主调用(冲块, 宿主能力C.功能_冲刷), 可写: true);
            }

            // ---- 改名:`(旧路径, 新路径)` → 逻辑(目标存在就**整体替换**,与 `移动到` 的"不覆盖"是两回事) ----
            if (规范 == "renameto")
            {
                if (调用.实参.Count != 2)
                    throw 报错(行号, "改名(旧路径, 新路径) 要两个参数:哪个路径改成哪个路径(文件 / 整个目录都行;" +
                        "**目标已存在就整体替换** —— 要\"不许覆盖\"请用 `移动到`)",
                        "renameto(old, new) takes two arguments");
                变量槽定义 名块 = 新槽(16);
                (string 名旧址, string 名旧长) = 字符串地址与长(调用.实参[0], 行号, 原文);
                发出($"存字 {名旧址} {名块.名称}");
                发出($"存字 {名旧长} {名块.名称}+4");
                (string 名新址, string 名新长) = 字符串地址与长(调用.实参[1], 行号, 原文);
                发出($"存字 {名新址} {名块.名称}+8");
                发出($"存字 {名新长} {名块.名称}+12");
                return 状态转逻辑(发出宿主调用(名块, 宿主能力C.功能_改名), 行号, "改名");
            }

            // ---- 临时目录:`(目录变量, 上限)` → 逻辑(与 `环境变量` 那条"结果写进字符串变量"同形) ----
            if (规范 == "tempdir")
            {
                if (调用.实参.Count != 2)
                    throw 报错(行号, "临时目录(目录变量, 上限) 要两个参数:本机临时目录写进哪个 `字符串` 变量、" +
