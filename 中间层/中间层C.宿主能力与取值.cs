                        "tempdir(target, limit) takes two arguments");
                if (调用.实参[1] is not 常量节点C 目录上限节点 || 目录上限节点.值 == 0 || 目录上限节点.值 > 1024 * 1024)
                    throw 报错(行号, $"临时目录 的第二个参数 `上限` 要写一个编译期就定下来的数字(1 ~ 1048576 字节):" +
