                string 目录头址 = 出实参头地址(目录变量, 行号, 原文, "临时目录", 1);

                确保池();
                变量槽定义 目录块 = 新槽(28);
                发出($"存字 {目录头址} {目录块.名称}+8");
                自成一段(() =>
                {
                    string 池指针址 = 新临时();
