                string t = 新临时();
                发出($"MOV {t} R0");
                return 表达式值.寄存器值(t, 可写: true);
            }
            if (规范 == "readline")
            {
                if (调用.实参.Count != 1 || 调用.实参[0] is not 名字节点C 名字)
                    throw 报错(行号, "读取行(缓冲) 要传一个名字:字符/字节 的数组、列表,或一个 `字符串` 变量(例如 读取行(字符 缓冲) / 读取行(行))",
                        "readline(buffer) needs an array, list or string name");
                确保读行例程();
                // B1(第110批):**字符串变量**这一支 —— 上限取"容量"(不够就 ×2 扩容接着读),
                // 读完把"已收"写进长度槽并补结尾 0。必须排在数组/列表那支**前面**:字符串在绑定里
                // 也是"列表"(元素宽 1),老代码于是把"当前长度"当上限 —— 新串长度 0 就一个字节都读不进。
                if (查列表(名字.名) is { 是字符串: true } 串绑定 && 查变量(名字.名) is { 是列表: true, 是数组: false })
                {
                    占住子程序约定寄存器(含返回: true, 含读行标志: true);
                    var 已收槽 = 需要字节暂存槽();
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    发出写变量(零, 已收槽);
                    发出写变量(零, 串绑定.长度槽);              // 长度先清 0:扩容按长度搬,别把上一次的内容带上
                    string 环 = 新标签("读行环"), 完 = 新标签("读行完"), 扩 = 新标签("读行扩");
                    发出($"{环}:");
                    string 已收 = 新临时();
                    发出读变量(已收, 已收槽);
                    string 剩 = 新临时();
                    发出读变量(剩, 串绑定.容量槽!.Value);
                    发出($"SUB {剩} {已收}");                // 这一轮还能收几个
                    发出($"CMP_IMMEDIATE {剩} 1");           // 剩 < 1 → 满了,先扩容再读
                    发出($"JL {扩}");
                    string 址 = 新临时();
                    发出读变量(址, 串绑定.指针槽!.Value);
                    发出($"ADD {址} {已收}");
                    发出($"MOV R12 {址}");
                    发出($"MOV R11 {剩}");
                    发出($"CALL {_读行例程}");
                    发出($"JZ R1 {完}");                     // R1 = 0 → 遇到行尾/没输入,收工(R0 = 本轮收的)
                    // R1 = 1 → 是"缓冲满了"停的:把本轮收的记上,扩容,接着读
                    发出($"{扩}:");
                    发出读变量(已收, 已收槽);                 // CALL 会冲寄存器:已收 从暂存槽重新读
                    发出($"ADD {已收} R0");                  // 加上本轮收的
                    发出写变量(已收, 已收槽);
                    发出写变量(已收, 串绑定.长度槽);          // 扩容按长度搬 ⇒ 长度先跟上
                    发出($"CALL {确保列表扩容例程(串绑定)}");
                    发出($"JMP {环}");
                    发出($"{完}:");
                    发出读变量(已收, 已收槽);                 // 前面几轮收的
                    发出($"ADD {已收} R0");                  // 加上本轮(最后一段)
                    发出写变量(已收, 已收槽);
                    发出写变量(已收, 串绑定.长度槽);
                    string 终 = 新临时();
                    发出读变量(终, 串绑定.指针槽!.Value);
                    发出($"ADD {终} {已收}");
                    发出间接写(零, 终, 1);                   // 结尾 0:输出/老库函数能接着用
                    return 表达式值.寄存器值(已收, 可写: true);
                }
                占住子程序约定寄存器(含返回: true);
                string 地址;
                int 常量上界 = 0;
                变量槽定义? 上界槽 = null;
                if (查变量(名字.名) is { } 绑定 && (绑定.是数组 || 绑定.是列表) && 绑定.元素宽 == 1)
                {
                    地址 = 绑定.是列表
                        ? 取列表基址(按槽找列表(绑定.名称) ?? throw 报错(行号, $"列表 '{绑定.名称}' 的内部状态丢了(不该发生)", "lost list state"))
                        : 取基址(绑定.名称);
                    if (绑定.是列表) 上界槽 = 按槽找列表(绑定.名称)!.长度槽;    // 上限 = 现在有几个(不会写越界)
                    else 常量上界 = 绑定.数组类型!.长度;
                }
                else if (解析引用链(名字.名, 行号) is { 有运行期下标: false } 缓冲链 && 缓冲链.是数组或列表 && 缓冲链.元素宽 == 1)
                {
                    地址 = 链地址(缓冲链, 行号, 原文);                            // 结构里的数组字段 `记录.名字`
                    常量上界 = 缓冲链.元素个数;
                }
                else if (查变量(名字.名) is { 数组类型: { 是多维: true } })
                    throw 报错(行号, $"读取行(...) 的缓冲要是一维的 字符/字节 数组:'{名字.名}' 是定长多维数组。" +
                        $"要一块缓冲就写 `字节 缓冲[12];`(行最长 11 个字符,末尾留一个 0)",
                        $"readline() needs a one-dimensional buffer: '{名字.名}'");
                else
                    throw 报错(行号, $"读取行(...) 的缓冲要是 字符/字节 的数组或列表:'{名字.名}' 不是",
                        $"readline() needs a char/byte array or list: '{名字.名}'");
                发出($"MOV R12 {地址}");
                string 上限 = 新临时();
                if (上界槽 is { } 槽) 发出读变量(上限, 槽);
                else 输出装载常量(上限, (uint)常量上界);
                发出($"MOV R11 {上限}");
                发出($"CALL {_读行例程}");
                string t = 新临时();
                发出($"MOV {t} R0");
                return 表达式值.寄存器值(t, 可写: true);
            }
            throw 报错(行号, $"'{调用.名}' 不是能读输入的东西(能用的:读取字符() / 读取行(缓冲) / 读取数字())",
                $"'{调用.名}' is not an input function");
        }
        #endregion
    }
