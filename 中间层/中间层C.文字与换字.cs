        /// <summary>
        /// `名字[下标] = 新文字`:换掉第几个**文字**,新文字可以是**任意长度** —— 字节数变了就把后面的内容
        /// (连同末尾那个 0)整体挪一挪;容量不够先按 ×2 扩容(扩容子程序会把老内容搬过去,之后数据地址
        /// 与"起点"都要重新算一遍)。字符串参数没有容量(长度在调用方那边):只允许换成**同样字节数**的文字。
        /// H1 起 `记录.名字[下标]`(堆串字段/元素)也走这里:长度按"数到第一个 0"算,容量在字段 +4 那个字,
        /// 装不下就换一块(与 `记录.名字 = "…"` 共用同一个 堆串保证容量)。
        /// </summary>
        private void 发出换一个字(引用链C 链, string 新码点, int 行号, string 原文)
        {
            string 基名 = 链.基名;
            bool 是参 = 是字符串参数(基名);
            bool 是堆 = !是参 && 链.串取字;          // H1:那个 8 字节小块的地址由 串字地址 现算(可能换过块)
            var 串 = (是参 || 是堆) ? null : 查列表(基名);
            string 不挪 = 新标签("换字不挪");
            自成一段(() =>
            {
                // ① 新文字先编码到隐藏缓冲(拿到"新字节数"),下标也只算一遍(存起来)
                自成一段(() =>
                {
                    string 缓址 = 新临时();
                    发出($"取地址 {缓址} {文字缓冲槽().名称}");
                    string 新数 = 发出写文字字节(新码点, 缓址, 行号);
                    发出写变量(新数, 换字值(0));
                    发出写变量(新码点, 换字值(28));      // 码点也要落槽:后面几段会把它那个寄存器冲掉
                }, 新码点);
                自成一段(() =>
                {
                    string 下标 = 取字下标寄存器(链, 行号, 原文);
                    发出写变量(下标, 换字值(4));
                });
                // ② 查下标(按文字数)→ 取旧文字的起点与字节数 → 增量 = 新数 - 旧数、新长度
                自成一段保守(() =>
                {
                    var (数据址, 字节长) = 取字串数据与字节长(链, 行号, 原文);
                    string 下标 = 新临时();
                    发出读变量(下标, 换字值(4));
                    string 文字数 = 发出数文字(数据址, 字节长);
                    发出文字下标检查(下标, 文字数, 行号, 原文);
                    var (_, 起点, 旧数) = 发出取文字(数据址, 下标, 行号);
                    string 新数 = 新临时();
                    发出读变量(新数, 换字值(0));
                    string 增量 = 新临时();
                    发出($"MOV {增量} {新数}");
                    发出($"SUB {增量} {旧数}");
                    发出写变量(增量, 换字值(24));
                    发出写变量(起点, 换字值(12));
                    发出写变量(旧数, 换字值(32));
                    if (是参)
                    {
                        // 字符串参数:长度在调用方那边,这里改不了 → 还是只收同样字节数的替换
                        string 一样 = 新标签("换字一样");
                        发出($"CMP {新数} {旧数}");
                        发出($"JEQ {一样}");
                        报错停机(行号, $"换字符串参数 '{基名}' 里的一个字,只能换成**同样字节数**的文字 —— " +
                            "它的长度在调用方那边,这里改不了。" +
                            $"要换成不一样长的内容:先 `字符串 临时 = {基名};`,在临时串上换完再整体赋回去;" +
                            $"或者把函数头写成 `字符串 出 {基名}`。(出错处:'{原文}')");
                        发出($"{一样}:");
                        return;
                    }
                    string 需要 = 新临时();
                    发出($"MOV {需要} {字节长}");
                    发出($"ADD {需要} {增量}");
                    发出写变量(需要, 换字值(8));
                });
                // ②b-堆 堆串字段/元素(`记录.名字[下标]`,H1):容量不够就换块,换完重算起点与尾巴;
                //     它**没有"长度字"**要写(长度是"数到第一个 0"数出来的,挪尾巴时那个 0 一起挪走了)
                if (是堆)
                {
                    自成一段保守(() =>                       // b1:增量是 0 就整段跳过
                    {
                        string 增量 = 新临时();
                        发出读变量(增量, 换字值(24));
                        发出($"JZ {增量} {不挪}");
                        string 需要 = 新临时();
                        发出读变量(需要, 换字值(8));
                        string 少 = 新临时();
                        发出($"MOV {少} {需要}");
                        发出($"SUB_IMMEDIATE {少} 1");     // 堆串保证容量 内部自己 +1(末尾那个 0),这里先减掉
                        发出写变量(少, 需要字节暂存槽());
                        堆串保证容量(串字地址(链, 行号, 原文), 行号, 原文);
                    });
                    自成一段保守(() =>                       // b2:换过块(或干脆是第一次)→ 起点/尾巴全部重算
                    {
                        string 字地址 = 串字地址(链, 行号, 原文);
                        string 址2 = 新临时();
                        发出间接读(址2, 字地址, 4);
                        string 长2 = 发出数到零字节(址2);
                        string 下标2 = 新临时();
                        发出读变量(下标2, 换字值(4));
                        var (_, 起点2, 旧数2) = 发出取文字(址2, 下标2, 行号);
                        发出写变量(起点2, 换字值(12));
                        string 尾起 = 新临时();
                        发出($"MOV {尾起} {起点2}");
                        发出($"ADD {尾起} {旧数2}");
                        发出写变量(尾起, 换字值(16));
                        string 尾长 = 新临时();
                        发出($"MOV {尾长} {址2}");
                        发出($"ADD {尾长} {长2}");
                        发出($"SUB {尾长} {尾起}");
                        发出($"ADD_IMMEDIATE {尾长} 1");      // 末尾那个 0 一起挪
                        发出写变量(尾长, 换字值(20));
                    });
                    换字挪尾巴();
                }
                // ②b-池 住池里的字符串:长度变了才挪尾巴,容量不够先 ×2 扩容。
                //     拆成四小段:b1 判增量 + 扩容 / b2 重算起点与尾巴 / b3 挪 / b4 写新长度 ——
                //     一段里塞太多临时寄存器会"用光 15 个"(而且嵌套的挪尾巴自己还要几个)。
                else if (!是参)
                {
                    自成一段保守(() =>                       // b1:增量是 0 就整段跳过
                    {
                        string 增量 = 新临时();
                        发出读变量(增量, 换字值(24));
                        发出($"JZ {增量} {不挪}");
                        string 需要 = 新临时();
                        发出读变量(需要, 换字值(8));
                        发出($"ADD_IMMEDIATE {需要} 1");     // +1:末尾那个 0 也要跟着挪
                        string 够 = 新标签("换字够"), 扩 = 新标签("换字扩");
                        string 容量 = 新临时();
                        发出读变量(容量, 串!.容量槽!.Value);
                        发出($"CMP {容量} {需要}");
                        发出($"JL {扩}");
                        发出($"JMP {够}");
                        发出($"{扩}:");
                        发出($"CALL {确保列表扩容例程(串)}");
                        发出读变量(容量, 串.容量槽!.Value);
                        发出($"CMP {容量} {需要}");
                        发出($"JL {扩}");
                        发出($"{够}:");
                    });
                    自成一段保守(() =>                       // b2:扩容可能换过块 → 起点/尾巴全部重算
                    {
                        string 址2 = 新临时();
                        发出读变量(址2, 串!.指针槽!.Value);
                        string 长2 = 新临时();
                        发出读变量(长2, 串.长度槽);
                        string 下标2 = 新临时();
