        /// <summary>
        /// 换字的 ②b-3:**把尾巴整体挪 增量 个字节**(增量 > 0 往后挪要反序、< 0 往前挪要正序)。
        /// 池串(`名字[下标]`)与堆串(`记录.名字[下标]`,H1)共用:两边的 ②b-2 都把
        /// 尾起@16 / 尾长@20 / 增量@24 / 新数@0 / 旧数@32 算进暂存槽了,这里只读不算。
        /// </summary>
        private void 换字挪尾巴()
        {
            自成一段保守(() =>
            {
                string 增量 = 新临时();
                发出读变量(增量, 换字值(24));
                string 尾起 = 新临时();
                发出读变量(尾起, 换字值(16));
                string 尾长 = 新临时();
                发出读变量(尾长, 换字值(20));
                string 新数 = 新临时();
                发出读变量(新数, 换字值(0));
                string 旧数 = 新临时();
                发出读变量(旧数, 换字值(32));
                string 往 = 新标签("换字往"), 往完 = 新标签("换字往完");
                发出($"CMP {新数} {旧数}");      // 按字节数比:增量是负数时别拿它跟 0 比(无符号下 -2 > 0)
                发出($"JG {往}");
                发出挪尾巴(尾起, 尾长, 增量, 正序: true);
                发出($"JMP {往完}");
                发出($"{往}:");
                发出挪尾巴(尾起, 尾长, 增量, 正序: false);
                发出($"{往完}:");
            });
        }

        /// <summary> 把"尾起 之后的 尾长 个字节"整体挪 增量 个字节(正序 = 从前往后;反序 = 从后往前)。
        /// 重叠时方向必须对:往后挪要反序(否则先写的会盖掉还没读的),往前挪要正序。 </summary>
        private void 发出挪尾巴(string 尾起, string 尾长, string 增量, bool 正序)
        {
            自成一段保守(() =>
            {
            string 剩 = 新临时();
            发出($"MOV {剩} {尾长}");
            string 源 = 新临时();
            string 目标 = 新临时();
            string 字节 = 新临时();
            string 环 = 新标签(正序 ? "挪正环" : "挪反环"), 完 = 新标签(正序 ? "挪正完" : "挪反完");
            发出($"JZ {剩} {完}");
            发出($"{环}:");
            // 正序:j 从 0 往上 → 源 = 尾起 + (尾长 - 剩)
            // 反序:j 从 尾长-1 往下 → 源 = 尾起 + (剩 - 1)
            string 序 = 新临时();
            发出($"MOV {序} {尾长}");
            发出($"SUB {序} {剩}");                    // 正序用:已挪几个
            if (正序)
            {
                发出($"MOV {源} {尾起}");
                发出($"ADD {源} {序}");
            }
            else
            {
                发出($"MOV {源} {尾起}");
                发出($"ADD {源} {剩}");
                发出($"SUB_IMMEDIATE {源} 1");
            }
            发出($"MOV {目标} {源}");
            发出($"ADD {目标} {增量}");
            发出间接读(字节, 源, 1);
            发出间接写(字节, 目标, 1);
            发出($"SUB_IMMEDIATE {剩} 1");
            发出($"JZ {剩} {完}");
            发出($"JMP {环}");
            发出($"{完}:");
            });
        }

        /// <summary> 一个"文字表达式"的码点到寄存器:`文字` 变量,或字符串取字(`名字[下标]`)。
