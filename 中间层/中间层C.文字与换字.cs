        /// <summary>
        /// 取第 下标 个**文字**:返回 (码点寄存器, 该文字的起点地址, 该文字的字节数)。
        /// 约定:调用方**先查过越界**(下标 &lt; 文字数)。码点按 UTF-8 解出来(1~4 字节)。
        /// </summary>
        private (string 码点, string 起点, string 字节数) 发出取文字(string 数据址, string 下标, int 行号)
        {
            string 码点 = "", 起点 = "", 字节数 = "";
            自成一段保守(() =>
            {
            string 指针 = 新临时();
            发出($"MOV {指针} {数据址}");
            string 剩 = 新临时();
            发出($"MOV {剩} {下标}");
            string 字节 = 新临时();
            string 环 = 新标签("取字环"), 解 = 新标签("取字解"), 完 = 新标签("取字完");
            string 跳1 = 新标签("取字跳1"), 跳2 = 新标签("取字跳2"), 跳3 = 新标签("取字跳3");
            // ① 先跳过前 下标 个文字(每个文字按它的前导字节决定跨几字节)
            发出($"{环}:");
            发出($"JZ {剩} {解}");
            发出间接读(字节, 指针, 1);
            发出($"CMP_IMMEDIATE {字节} 128");
            发出($"JL {跳1}");
            发出($"CMP_IMMEDIATE {字节} 224");
            发出($"JL {跳2}");
            发出($"CMP_IMMEDIATE {字节} 240");
            发出($"JL {跳3}");
            发出($"ADD_IMMEDIATE {指针} 4");
            发出($"JMP {环}下");
            发出($"{跳3}:");
            发出($"ADD_IMMEDIATE {指针} 3");
            发出($"JMP {环}下");
            发出($"{跳2}:");
            发出($"ADD_IMMEDIATE {指针} 2");
            发出($"JMP {环}下");
            发出($"{跳1}:");
            发出($"ADD_IMMEDIATE {指针} 1");
            发出($"{环}下:");
            发出($"SUB_IMMEDIATE {剩} 1");
            发出($"JMP {环}");
            // ② 解码这一个文字(注意:这些变量是**外层**的,不能再写 string 声明 —— 会遮蔽成另一个变量)
            发出($"{解}:");
            起点 = 指针;                      // 指针刚好停在这个字的头一个字节上 → 直接当起点(省一个寄存器)
            字节数 = 新临时();
            码点 = 新临时();
            string 一 = 新标签("取字1"), 两 = 新标签("取字2"), 三 = 新标签("取字3"), 四 = 新标签("取字4");
            发出间接读(字节, 指针, 1);
            发出($"CMP_IMMEDIATE {字节} 128");
            发出($"JL {一}");
            发出($"CMP_IMMEDIATE {字节} 224");
            发出($"JL {两}");
            发出($"CMP_IMMEDIATE {字节} 240");
            发出($"JL {三}");
            // 四字节:11110xxx 10xxxxxx 10xxxxxx 10xxxxxx
            发出($"{四}:");
            发出与立即数(字节, 0x07u);
            发出左移立即数(字节, 18);             // <<18(一条顶三条:P11)
            发出($"MOV {码点} {字节}");
            for (int k = 1; k <= 3; k++)
            {
                int 位 = 6 * (3 - k);                     // 12 / 6 / 0
                发出($"MOV {字节} {起点}");
                发出($"ADD_IMMEDIATE {字节} {k}");
                发出间接读(字节, 字节, 1);
                发出与立即数(字节, 0x3Fu);
                发出左移立即数(字节, 位);
                发出($"OR {码点} {字节}");
            }
            输出装载常量(字节数, 4u);
            发出($"JMP {完}");
            // 三字节:1110xxxx 10xxxxxx 10xxxxxx
            发出($"{三}:");
            发出与立即数(字节, 0x0Fu);
            发出左移立即数(字节, 12);             // <<12(一条顶两条:P11)
            发出($"MOV {码点} {字节}");
            for (int k = 1; k <= 2; k++)
            {
                int 位 = 6 * (2 - k);                     // 6 / 0
                发出($"MOV {字节} {起点}");
                发出($"ADD_IMMEDIATE {字节} {k}");
                发出间接读(字节, 字节, 1);
                发出与立即数(字节, 0x3Fu);
                发出左移立即数(字节, 位);
                发出($"OR {码点} {字节}");
            }
            输出装载常量(字节数, 3u);
            发出($"JMP {完}");
            // 两字节:110xxxxx 10xxxxxx
            发出($"{两}:");
            发出与立即数(字节, 0x1Fu);
            发出左移立即数(字节, 6);
            发出($"MOV {码点} {字节}");
            发出($"MOV {字节} {起点}");
            发出($"ADD_IMMEDIATE {字节} 1");
            发出间接读(字节, 字节, 1);
            发出与立即数(字节, 0x3Fu);
            发出($"OR {码点} {字节}");
            输出装载常量(字节数, 2u);
            发出($"JMP {完}");
            // 一字节
            发出($"{一}:");
            发出($"MOV {码点} {字节}");
            输出装载常量(字节数, 1u);
            发出($"{完}:");
            });
            return (收下临时(码点), 收下临时(起点), 收下临时(字节数));
        }

        /// <summary>
        /// 把一个**文字**(Unicode 码点)按 UTF-8 写进"目标地址"(1~4 字节),返回字节数寄存器。
        /// 编码规则:&lt;0x80 一字节; &lt;0x800 两字节; &lt;0x10000 三字节; 其余四字节。
        /// </summary>
        private string 发出写文字字节(string 码点, string 目标地址, int 行号)
        {
            string 字节数 = "";
            自成一段保守(() =>
            {
            字节数 = 新临时();
            string 尾 = 新临时();
            string 值 = 新临时();                    // 每个分支复用这一个(不再各要一个)
            string 段 = 新临时();
            string 一 = 新标签("写文1"), 两 = 新标签("写文2"), 三 = 新标签("写文3"), 完 = 新标签("写文完");
            发出($"CMP_IMMEDIATE {码点} 128");
            发出($"JL {一}");
            发出($"CMP_IMMEDIATE {码点} 2048");
            发出($"JL {两}");
            发出($"CMP_IMMEDIATE {码点} 65536");
            发出($"JL {三}");
            // 四字节:11110xxx 10xxxxxx 10xxxxxx 10xxxxxx
            {
                发出($"MOV {值} {码点}");
                发出右移立即数(值, 18);                                   // A9:一条顶"装常量 6 + 移三次"
                发出($"OR_IMMEDIATE {值} 240");
                发出间接写(值, 目标地址, 1);
                for (int k = 1; k <= 3; k++)
                {
                    发出($"MOV {尾} {目标地址}");
                    发出($"ADD_IMMEDIATE {尾} {k}");
                    发出($"MOV {段} {码点}");
                    发出右移立即数(段, 6 * (3 - k));                       // 12 / 6 / 0(0 时什么都不发)
                    发出与立即数(段, 0x3Fu);           // P11:一条 与立即数
                    发出($"OR_IMMEDIATE {段} 128");
                    发出间接写(段, 尾, 1);
                }
                输出装载常量(字节数, 4u);
                发出($"JMP {完}");
            }
            // 三字节:1110xxxx 10xxxxxx 10xxxxxx
            {
                发出($"{三}:");
                发出($"MOV {值} {码点}");
                发出右移立即数(值, 12);
                发出($"OR_IMMEDIATE {值} 224");
                发出间接写(值, 目标地址, 1);
                for (int k = 1; k <= 2; k++)
                {
                    发出($"MOV {尾} {目标地址}");
                    发出($"ADD_IMMEDIATE {尾} {k}");
                    发出($"MOV {段} {码点}");
                    发出右移立即数(段, 6 * (2 - k));                       // 6 / 0
                    发出与立即数(段, 0x3Fu);           // P11:一条 与立即数
                    发出($"OR_IMMEDIATE {段} 128");
                    发出间接写(段, 尾, 1);
                }
                输出装载常量(字节数, 3u);
                发出($"JMP {完}");
            }
            // 两字节:110xxxxx 10xxxxxx
            {
                发出($"{两}:");
                发出($"MOV {值} {码点}");
                发出右移立即数(值, 6);
                发出($"OR_IMMEDIATE {值} 192");
                发出间接写(值, 目标地址, 1);
                发出($"MOV {尾} {目标地址}");
                发出($"ADD_IMMEDIATE {尾} 1");
                发出($"MOV {段} {码点}");
                发出与立即数(段, 0x3Fu);           // P11:一条 与立即数
                发出($"OR_IMMEDIATE {段} 128");
                发出间接写(段, 尾, 1);
                输出装载常量(字节数, 2u);
                发出($"JMP {完}");
            }
            // 一字节
            {
                发出($"{一}:");
                发出($"MOV {值} {码点}");
                发出与立即数(值, 0xFFu);           // P11:一条 与立即数
                发出间接写(值, 目标地址, 1);
                输出装载常量(字节数, 1u);
            }
            发出($"{完}:");
            });
            return 收下临时(字节数);
        }

