                    return t;
                }
                return null;
            }
            if (像引用链(名) && 解析引用链(名, 行号) is { } 链 && 是字符串取字(链))
            {
                // 取一次字内部要用好几个临时(数据址/字节长/下标/文字数/起点/字节数),
                // 但它们出了这一步就没用了 —— 全包在"自立一段"里,对外**只占住最后那个码点**。
                // (踩过:`如果 (主串[i + j] != 子串[j])` 两边各占 7 个,内层保守块一个寄存器都发不出来)
                string 码点 = "";
                自成一段保守(() =>
