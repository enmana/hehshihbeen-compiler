        // ---------------- 字符串写入:定长缓冲(`字符 名字[16]`)/ 堆串(结构字段·元素) ----------------
        //
        // 与"池里的 `字符串` 变量"(老路)的区别:
        //   · **定长缓冲**:内联在变量/结构里,**容量编译期就知道**;末尾要留一个字节放 0,
        //     所以能装的内容是"容量 - 1"字节。放不下就拦住 —— 字面量能算出来的**编译期**报错,
        //     算不出的**运行期**停机报错(带容量与改法)。
        //   · **堆串**:字段里只有"数据地址 + 容量"(8 字节),真正的字节在**堆**里(0 结尾)。
        //     装不下就 `申请` 一块更大的(至少翻倍)、把老内容搬过去、把老块 `释放`、新地址与新容量写回字段。
        // 赋值 = 从第 0 个字节开始写(覆盖);拼接到 = 接在现有内容后面。两者共用这一支。

        /// <summary> 一段"可写字符串目标"(定长缓冲 或 堆串;池里的 `字符串` 变量不走这里) </summary>
        private sealed class 串写目标C
        {
            public string 名字 = "";
            public string 说明 = "";
            public 引用链C 链 = null!;
            public bool 堆串;
            public int 容量常量;                  // 定长缓冲:元素个数(0 = 容量在 容量槽 里)
            public 变量槽定义? 容量槽;             // 定长缓冲是数组参数时:容量是运行期长度(调用方给的)
            public string 定长数据址 = "";         // 定长缓冲:数据起点(寄存器,固定不变)
            /// <summary> 堆串目标:那个 8 字节小块的地址**已经算在某个寄存器里**时填它(字符串列表的 `添加` 用)。
            /// 它是外面算好的、要活过 自成一段,所以必须进"护住"那一份(不然会被当成空闲寄存器发出去)。 </summary>
            public string 现成字地址 = "";
        }

        /// <summary>
        /// 把一段文本认成"可写字符串目标"(定长缓冲 / 堆串);不是就返回 null。
        /// 池里的 `字符串` 变量与 `字符串` 参数**返回 null** —— 它们走老路(容量在池里、×2 扩容子程序)。
        /// </summary>
        private 串写目标C? 试取串写目标(string 文本, int 行号, string 原文)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0) return null;
            if (是字符串参数(名) || 查列表(名) is { 是字符串: true }) return null;
            引用链C? 链 = 取堆串链(名) ?? 试取定长缓冲链(名);
            if (链 is null) return null;
            var 目标 = new 串写目标C { 名字 = 名, 链 = 链 };
            if (是堆串链(链))
            {
                目标.堆串 = true;
                目标.说明 = $"字符串字段 '{名}'";
                return 目标;
            }
            目标.说明 = $"定长缓冲 '{名}'";
            if (链.绑定.是数组切片 && 链.绑定.长度槽 is { } 长槽) 目标.容量槽 = 长槽;
            else 目标.容量常量 = 链.元素个数;
            目标.定长数据址 = 链地址(链, 行号, 原文);
            return 目标;
        }

        /// <summary> 目标现在有几个字节(定长缓冲与堆串都按"数到第一个 0"算) </summary>
        private string 取串长度(串写目标C 目标, string 字地址, int 行号)
            => 发出数到零字节(目标.堆串 ? 读堆串数据址(字地址) : 目标.定长数据址);

        /// <summary> 堆串字段 +0 那个字:数据地址(0 = 还没分配过) </summary>
        private string 读堆串数据址(string 字地址)
        {
            string 数据 = 新临时();
            发出间接读(数据, 字地址, 4);
            return 数据;
        }

        /// <summary>
        /// 往"定长缓冲 / 堆串"里写各段(段的形状见 拼接段:整段字符串 / 一个字节 / 一个文字)。
        /// 覆盖 = true:从第 0 个字节开始写(赋值);false:接在现有内容后面(拼接到)。末尾一律补一个 0。
        /// </summary>
        private void 发出串目标写入(串写目标C 目标, List<拼接段> 段们, bool 覆盖, int 行号, string 原文)
        {
            物化段们(段们, 行号, 原文);      // "返回字符串的函数调用"当段用时:先物化(函数只调一次)
            自成一段(() =>
            {
                string 字地址 = 目标.堆串 ? 串字地址(目标.链, 行号, 原文) : "";
                var 起点槽 = 串起点暂存槽();
                var 需要槽 = 需要字节暂存槽();
                // ① 起始长度(覆盖 = 0)+ 各段长度 = 这次要写到第几个字节。
                //    算完就**把这一段用的临时寄存器还掉**(只留 字地址):后面 换块/拷贝 还要用不少寄存器
                var 快照 = 记占用();
                try
                {
                    string 起点 = 新临时();
                    if (覆盖) 输出装载常量(起点, 0);
                    else 发出($"MOV {起点} {取串长度(目标, 字地址, 行号)}");
                    发出写变量(起点, 起点槽);
                    string 需要 = 新临时();
                    发出($"MOV {需要} {起点}");
                    累加段长(需要, 段们, 行号, 原文);
                    发出写变量(需要, 需要槽);
                }
                finally { 还占用(快照); }
                // ② 容量:定长缓冲放不下就拦住;堆串装不下就换块(换块后数据地址会变 → ③ 里现取)
                if (目标.堆串) 堆串保证容量(字地址, 行号, 原文);
                else 定长缓冲查容量(目标, 段们, 覆盖, 行号, 原文);
                // ③ 逐段拷进去
                string 目标址 = 目标.堆串 ? 读堆串数据址(字地址) : 目标.定长数据址;
                string 已拷 = 新临时();
                发出读变量(已拷, 起点槽);
                拷贝各段(目标址, 已拷, 段们, 行号, 原文);
                // ④ 末尾补一个 0(定长缓冲的读取侧数到 0 定长度);堆串**另外**把块首那 4 字节写成本次写到的字节数
                自成一段(() =>
                {
                    string 尾 = 新临时();
                    发出($"MOV {尾} {目标址}");
                    发出($"ADD {尾} {已拷}");
                    string 零 = 新临时();
                    输出装载常量(零, 0);
                    发出($"存储间接寻址 {零} {尾}");
                    if (目标.堆串)
                    {
                        // H112 第 1 段:`已拷` 到这儿正好是"这一趟写到了第几个字节" ⇒ 它就是长度字。
                        // ⚠ 这里多要 1 个临时寄存器(`长址`)是**这一层唯一的一处**;别处一律就地 ±4。
                        string 长址 = 新临时();
                        发出($"MOV {长址} {目标址}");
                        发出($"SUB_IMMEDIATE {长址} {堆串长度头}");
                        发出($"存储间接寻址 {已拷} {长址}");
                    }
                }, 目标址, 已拷);
            }, [目标.定长数据址, 目标.现成字地址]);
        }

        /// <summary>
        /// 定长缓冲的容量检查:内容最多"容量 - 1"字节(末尾那个 0 也要地方)。
        /// 覆盖赋值且各段长度都是编译期常量 → **当场编译期报错**(能报出准确字节数);
        /// 其余情况在**运行期**比一次,不够就报错停机。
        /// </summary>
        private void 定长缓冲查容量(串写目标C 目标, List<拼接段> 段们, bool 覆盖, int 行号, string 原文)
        {
            long 可用常量 = 目标.容量常量 > 0 ? 目标.容量常量 - 1 : -1;
            if (可用常量 >= 0 && 覆盖 && 段常量总长(段们, 行号, 原文) is { } 常量长)
            {
                if (常量长 > 可用常量)
                    throw 报错(行号, 定长不够说明(目标, 目标.容量常量, 常量长),
                        "fixed buffer is too small for this text");
                return;                                  // 编译期就证明了装得下,不用再比
            }
            var 快照 = 记占用();
            try
            {
                string 可用 = 新临时();
                if (可用常量 >= 0) 输出装载常量(可用, (uint)可用常量);
                else
                {
                    发出读变量(可用, 目标.容量槽!.Value);
                    发出($"SUB_IMMEDIATE {可用} 1");
                }
                string 需要 = 新临时();
                发出读变量(需要, 需要字节暂存槽());
                string 不够 = 新标签("定长不够"), 完 = 新标签("定长完");
                发出($"CMP {可用} {需要}");
                发出($"JL {不够}");                          // 可用 < 需要 → 装不下
                发出($"JMP {完}");
                发出($"{不够}:");
                报错停机(行号, $"第 {行号} 行:{定长不够说明(目标, 目标.容量常量, null)}");
                发出($"{完}:");
            }
            finally { 还占用(快照); }
        }

        /// <summary>"定长缓冲装不下"的说明(编译期与运行期共用;运行期那版由调用处补行号前缀)</summary>
        private static string 定长不够说明(串写目标C 目标, long 容量, long? 常量长)
        {
            string 装 = 容量 > 0
                ? $"这个缓冲一共 {容量} 字节(末尾要留一个 0,能装 {容量 - 1} 字节内容)"
                : "这个缓冲的长度是调用方给的";
            string 多 = 常量长 is { } 长 ? $"这次要写 {长} 字节" : "这次要写的内容比它长";
            return $"{目标.说明} 装不下:{装},{多}。" +
                $"办法:①把容量写大一点(例如 字符 名字[32]);②只装前面一段(先截断再写);" +
                $"③要用会长大的字符串,就声明成 `字符串 名字;`(数据放在堆里,装不下会自动换块)";
        }

        /// <summary>
        /// 各段长度的编译期总和(只要有一段算不出来就返回 null)。
        /// 用途:字面量赋值太长的**当场**就报错,不用等到跑起来才发现。
        /// </summary>
        private long? 段常量总长(List<拼接段> 段们, int 行号, string 原文)
        {
            long 总 = 0;
            foreach (var 段 in 段们)
            {
                if (段.是单字节) { 总 += 1; continue; }
                if (段.是文字) return null;                    // `文字` 变量/取字:运行期才知道编出来几个字节
                string 文本 = 段.文本.Trim();
                if (是字符串字面量(文本)) { 总 += 解码字符串(文本[1..^1], 行号).Length; continue; }
                return null;                                   // 别的字符串:运行期才知道长度(它自己会数)
            }
            return 总;
        }

        /// <summary>
        /// 堆串的容量保证:装得下就什么都不做;装不下就换一块更大的 ——
        /// 新容量 = max(需要 + 1, 旧容量 × 2)(×2 是为了"在循环里一个字节一个字节接"时不至于每次都换块)。
        /// 换块 = `申请` 新的 + 把老内容搬过去 + 新地址/新容量写回字段 + `释放` 老块。
        /// </summary>
        private void 堆串保证容量(string 字地址, int 行号, string 原文)
        {
            var 快照 = 记占用();
            try
            {
                string 容量址 = 新临时();
                发出($"MOV {容量址} {字地址}");
                发出($"ADD_IMMEDIATE {容量址} {串字段容量偏移}");
                string 旧容量 = 新临时();
                发出间接读(旧容量, 容量址, 4);
                string 旧数据 = 新临时();
                发出间接读(旧数据, 字地址, 4);
                string 要 = 新临时();                                // 末尾那个 0 也要地方
                发出读变量(要, 需要字节暂存槽());
                发出($"ADD_IMMEDIATE {要} 1");
                // 新容量 = max(要, 旧容量 × 2):两倍是为了"在循环里一个字节一个字节接"时不用每次都换块
                string 新容量 = 新临时();
                发出($"MOV {新容量} {旧容量}");
                发出($"ADD {新容量} {新容量}");
                string 不翻 = 新标签("堆串不翻");
                发出($"CMP {新容量} {要}");
                发出($"JG {不翻}");                                  // 两倍还比"要"多 → 就按两倍给
                发出($"MOV {新容量} {要}");
                发出($"{不翻}:");
                string 换 = 新标签("堆串换"), 写回 = 新标签("堆串写回"), 完 = 新标签("堆串完");
                发出($"CMP {旧容量} {要}");
                发出($"JL {换}");                                    // 旧容量 < 要 → 装不下,换块
                发出($"JMP {完}");
                发出($"{换}:");
                发出($"存字间接 {新容量} {容量址}");                  // H112:先把净容量落账(申请失败会停机,不存在半截状态)
                发出($"ADD_IMMEDIATE {新容量} {堆串长度头}");         // 就地变成"要申请多少字节"(块首 4 字节放长度字)
                string 新块 = 生成申请(新容量, 行号, 原文);
                发出($"JZ {旧数据} {写回}");                          // 还没分配过:没有老内容要搬(长度字交给 ④ 写)
                发出($"SUB_IMMEDIATE {旧数据} {堆串长度头}");         // 旧数据 → 老块首(连长度字一起搬,释放也正好用它)
                发出($"ADD_IMMEDIATE {旧容量} {堆串长度头}");         // 搬 旧容量 + 4 个字节 = 长度字 + 数据区
                发出字节拷贝(旧数据, 新块, 旧容量);
                发出($"{写回}:");
                发出($"ADD_IMMEDIATE {新块} {堆串长度头}");           // 新块 → 数据地址(字段里存的就是它)
                发出($"存字间接 {新块} {字地址}");
                发出($"JZ {旧数据} {完}");
                生成释放(旧数据, 行号, 原文);                         // 旧数据 这时正好是块首
                发出($"{完}:");
            }
            finally { 还占用(快照); }
        }

        /// <summary>
        /// 切实参:只按**括号外、引号外**的逗号切 —— 逗号写在字符串/字符字面量里不算分隔符。
        /// (踩过:`拼接到(问候, "你好,", 名字)` 里的 `"你好,"` 被切成两段;函数调用那边同一个毛病一起修了。)
        /// </summary>
        private static List<string> 切实参(string 参数串)
        {
            var 结果 = new List<string>();
            string 原文 = 参数串.Trim();
            if (原文.Length == 0) return 结果;
            int 段起 = 0, 深 = 0;
            for (int i = 0; i < 原文.Length; i++)
            {
                char c = 原文[i];
                if (c is '"' or '\'')
                {
                    char 收尾 = c;
                    i++;
                    while (i < 原文.Length && 原文[i] != 收尾)
                    {
                        if (原文[i] == '\\' && i + 1 < 原文.Length) i++;    // 转义:连着的下一个字符不当收尾
                        i++;
                    }
                    continue;
                }
                if (c is '(' or '[') { 深++; continue; }
                if (c is ')' or ']') { 深--; continue; }
                if (c == ',' && 深 == 0)
                {
                    结果.Add(原文[段起..i].Trim());
                    段起 = i + 1;
                }
            }
            结果.Add(原文[段起..].Trim());
            return 结果;
        }

        // ---------------- 字符串:按"文字"(Unicode 码点)的下标与长度 ----------------
        // 用户看得见的语义(2026-09 起):`.长度()` = **文字数**,`名字[下标]` = 第几个**文字**(取出来是 `文字` 类型)。
        // 字节层面只在内部用 —— 拼接/赋值/比较/输出本身都是字节安全的,不会把中文切出乱码。

        /// <summary> 变量名 → 声明的类型名(基本类型与函数参数登记;结构/数组/字符串不登记)。
        /// 用途:判断"这个值是不是 `文字`"(拼接与输出要按文字处理)。
        /// **按作用域回滚**(见 压作用域/弹作用域):函数里叫 `c` 的 `文字` 局部不能把外面的字符串 `c` 带歪 —— 踩过。 </summary>
        private readonly Dictionary<string, string> _变量类型 = new(StringComparer.OrdinalIgnoreCase);
        /// <summary> 每一层作用域里登记过的 (名字, 进层前的旧值);旧值为 null = 进层前没有 </summary>
        private readonly Stack<List<(string 名, string? 旧值)>> _类型回滚栈 = new();

        private void 登记变量类型(string 名, string 类型名)
        {
            if (名.Length == 0 || 类型名.Length == 0) return;
            if (_类型回滚栈.Count > 0 && _类型回滚栈.Peek() is { } 回滚 && !回滚.Any(x => x.名 == 名))
                回滚.Add((名, _变量类型.TryGetValue(名, out string? 旧) ? 旧 : null));
            _变量类型[名] = 类型名;
        }

        private bool 是文字变量(string 名)
        {
            string 键 = 名.Trim();
            if (_变量类型.TryGetValue(键, out string? t)
                && (t == "文字" || string.Equals(t, "rune", StringComparison.OrdinalIgnoreCase))) return true;
            // 模块里的顶层 `文字` 变量:登记的是全名(`数学.字`),裸名字也认一次
            return _当前模块.Length > 0 && !键.Contains('.')
                && _变量类型.TryGetValue(_当前模块 + "." + 键, out string? 本模块类型)
                && (本模块类型 == "文字" || string.Equals(本模块类型, "rune", StringComparison.OrdinalIgnoreCase));
        }

        /// <summary>
        /// 通用化(2026-10):这个名字是不是**浮点**(声明类型是 `浮点` / `float`)。
        /// 与 <see cref="是文字变量"/> 同一套(含"模块里的顶层变量登记的是全名,裸名字也认一次")。
        /// <para>
        /// 为什么要它:浮点值就是 32 位位模式,**按整数用会静默算错**(打印出 `1069547520`、
        /// 或者位模式直接进乘法算成 NaN)—— 所以类型推断与输出那两条路都要先认出它。
        /// </para>
        /// <para>
        /// ⚠ **R4-41(2026-10-10)起它还管"元素 / 字段"**:`表[3]` / `点.x` 走
        /// <see cref="是浮点标量引用"/> 那一档 —— 库 `三维网格.着算亮度()` 就是栽在
        /// "元素被当成整数"上(法线 NaN ⇒ 颜色塌成一个,见 `下一班从这里开始.md` R4-38)。
        /// </para>
        /// <param name="只查表">只按"变量名 → 声明类型"查表,**不走引用链**那一档。
        /// 引用链那一段回过头来问"根变量是不是浮点"时必须给 true(不然无限递归,见 `是浮点标量引用`)。</param>
        /// </summary>
        private bool 是浮点变量(string 名, bool 只查表 = false)
        {
            string 键 = 名.Trim();
            if (_变量类型.TryGetValue(键, out string? t)
                && (t == "浮点" || string.Equals(t, "float", StringComparison.OrdinalIgnoreCase))) return true;
            if (_当前模块.Length > 0 && !键.Contains('.')
                && _变量类型.TryGetValue(_当前模块 + "." + 键, out string? 本模块类型)
                && (本模块类型 == "浮点" || string.Equals(本模块类型, "float", StringComparison.OrdinalIgnoreCase))) return true;
            // ⚠⚠ R4-41:`表[3]`(浮点数组的元素)/ `点.x`(浮点字段)—— **标量元素也是浮点**。
            // ⚠ `只查表` = **不许再往下走引用链**:这一档是"解析链"那条路回过头来问"根变量是不是浮点"用的,
            //   不设这道闸就是 变量 → 链 → 变量 → … **当场栈溢出**(见 `是浮点标量引用`)。
            return !只查表 && 是浮点标量引用(键);
        }

        /// <summary>
        /// ⚠ **R4-41:重入深度** —— 见 <see cref="是浮点标量引用"/> 里那条注释。
        /// `是浮点变量` ↔ `是浮点标量引用` 必须**只降一层**(变量 → 元素/字段),再深就是死循环。
        /// </summary>
        private int _浮点推断深度;

        /// <summary>
        /// ⚠⚠ **R4-41(2026-10-10):`表[3]` / `点.x` 这类"标量引用"是不是浮点。**
        /// <para>
        /// **为什么必须单列一条**:`_变量类型` 登记的是**变量的声明类型**(键就是变量名),
        /// 所以 `是浮点变量("顶点x")` 为真、而 `是浮点变量("顶点x[下标]")` / `是浮点变量("点.x")`
        /// 一律为假 —— 于是"元素/字段直接进表达式"这一档(不是先落进浮点变量)全被判成**整数**:
        /// `整数(表[3] * 1000.0)` 里 `表[3]` 是**位模式当整数**,乘出来是 NaN(溢出哨兵 `-2147483648`)。
        /// 库里的 `着算亮度`(`浮点 ux = 顶点x[填_v2] - 顶点x[填_v1];`)正是栽在这儿 ——
        /// 症状是法线 NaN ⇒ 亮度哨兵 ⇒ 颜色塌成一个(见 `下一班从这里开始.md` R4-38 / R4-39)。
        /// </para>
        /// <para>
        /// 判据两道(**都是现成的表,不靠猜**):
        /// ① **链那一道**:`解析引用链` 解出来的链必须"正好点到**一个标量**" ——
        ///    读宽 4 字节、不是结构 / 字符串元素、没有没走完的维;
        /// ② **那一格自己的类型**:字段看字段的声明类型(`点.x`);
        ///    数组 / 列表元素看**根变量**的声明类型(`表[3]` ⇒ `表` 是 `浮点` 数组)。
        /// 两道都过才算浮点 ⇒ `整数 表[4]` 的元素照旧是整数、`字符串 名单[10]` 的元素照旧是字符串、
        /// `点.数[i]`(结构字段里的数组)照旧按字段自己的类型走。
        /// </para>
        /// <para>
        /// ⚠ **解析链那条路不许再递归回自己**(`只查表` + `_浮点推断深度`):② 里"问根变量是不是浮点"
        /// 那一次必须是**直接查表**。不设这道闸:`是浮点变量("计数")` → `是浮点标量引用("计数")`
        /// → `是浮点变量("计数")` → …**当场栈溢出**(2026-10-10 实测:整棵工程编不动,
        /// 报 `Stack overflow` + 一万行调用栈)。
        /// </para>
        /// <para>
        /// 解析要**容错**:这里只是"推类型",推不出来就得让**求值那一侧**去报那条准确的错
        /// (解析失败 / 报错一律当"不是浮点",不在这里抛)。
        /// </para>
        /// </summary>
        private bool 是浮点标量引用(string 名)
        {
            if (_浮点推断深度 > 0) return false;      // 解析链那一段里又绕回来了:当场收手(见上面那条)
            _浮点推断深度++;
            try
            {
                return 是浮点标量引用内(名);
            }
            finally { _浮点推断深度--; }
        }

        private bool 是浮点标量引用内(string 名)
        {
            引用链C? 链;
            try { 链 = 解析引用链(名, 0); }
            catch { return false; }
            if (链 == null) return false;
            if (链.多维 || 链.后续维下标 is { Count: > 0 }) return false;      // 少写了最后一维:那是整个子数组
            if (!链.有运行期下标 && 链.下标后宽度 != 4) return false;          // 常量下标走的不是"下标后宽度"
            // ⚠ **结构字段先判**(写在"引用基址"那道之前):结构参数(`点 p` 编译成 `引用 点 p`)
            //    在链上就是 `是指针基址 = true`;对字段来说"指向哪个结构"是**编译期定死的**
            //    (结构参数按地址传的是它自己那个类型),所以字段这一档照判不误。
            if (链.末字段类型名 is { } 字段类型)
                return 字段类型 == "浮点" || string.Equals(字段类型, "float", StringComparison.OrdinalIgnoreCase);
            if (链.是指针基址) return false;                                    // 只是"引用变量指向谁"不知道,不在这儿猜
            if (链.标量读宽 != 4) return false;                                 // 只有 4 字节才可能是单精度浮点
            if (链.是串元素 || 链.元素是字符串 || 链.下标后是串元素 || 链.串取字) return false;
            if (链.点到结构整块) return false;
            // 数组 / 列表元素:`表[3]` —— 根变量的声明类型是 `浮点` 才算
            // (⚠ `只查表: true`:这一次**只许查表**,不许再往下解析链 —— 见上面那条"不许递归回自己")
            return 是浮点变量(链.基名, 只查表: true);
        }

        /// <summary> 这个名字是不是"整段字符串变量 / 字符串参数"(不是 `名字[下标]`,也不是定长缓冲/堆串字段)。
        /// 取"数据地址 + 字节长两个寄存器"那条路(串数据与字节长)只认它 —— 定长缓冲/堆串走各自的分支。 </summary>
        private bool 是池串整名(string 名)
        {
            string n = 名.Trim();
            return n.Length > 0 && 像引用链(n) && (是字符串参数(n) || 查列表(n) is { 是字符串: true });
        }

        /// <summary>
        /// 字符串的"数据地址 + 字节长"两个寄存器。
        /// 支持:`字符串` 变量 / `字符串` 参数 / 定长缓冲 `字符 名字[16]` / 堆串字段·元素 `记录.名字`
        /// (后两种的长度是**数到第一个 0** 数出来的)。
        /// </summary>
        private (string 数据址, string 字节长) 串数据与字节长(string 基名, int 行号, string 原文)
        {
            if (是出参(基名))
            {
                var (址0, 长0) = 出参数据与长度(基名, 行号, 原文);
                return (址0, 长度入寄存器(长0));
            }
            if (是字符串参数(基名))
            {
                var 绑定 = 查变量(基名)!.Value;
                string 址 = 新临时();
                发出读变量(址, 绑定.槽);
                string 长 = 新临时();
                发出读变量(长, 绑定.长度槽!.Value);
                return (址, 长);
            }
            var 串 = 查列表(基名);
            if (串 is { 是字符串: true })
            {
                string 址2 = 新临时();
                发出读变量(址2, 串.指针槽!.Value);
                string 长2 = 新临时();
                发出读变量(长2, 串.长度槽);
                return (址2, 长2);
            }
            if (试取串视图(基名, 行号, 原文) is { } 视图) return (视图.数据址, 视图.字节长);
            throw 报错(行号, $"'{基名}' 不是字符串", $"'{基名}' is not a string");
        }

        /// <summary> 这个引用链是不是"字符串取一个字"(`名字[下标]`,下标可常量可运行期)。
        /// H1 起 `记录.名字[下标]`(堆串字段/元素取一个字)也算 —— 与池串同口径。 </summary>
        private bool 是字符串取字(引用链C 链)
            => 链.串取字
               || (链.有下标 && ((链.是列表 && 按槽找列表(链.绑定.名称) is { 是字符串: true }) || 是字符串参数(链.基名)));

        /// <summary> 取字的下标 → 寄存器(H1:堆串取字的下标另存,别跟"数组元素下标"混;池串沿用"偏移当文字下标"的老口径) </summary>
        private string 取字下标寄存器(引用链C 链, int 行号, string 原文)
        {
            if (链.串取字)
                return 链.串取字下标文本 is { } 文本
                    ? 索引到寄存器(文本, 行号, 原文)
                    : 常量入临时((uint)链.串取字常量);
            return 链.有运行期下标 ? 索引到寄存器(链.运行期下标!, 行号, 原文) : 常量入临时((uint)链.偏移);
        }

        /// <summary>
        /// "取字"那条路要的"数据地址 + 字节长":池串按整名走老路(`串数据与字节长`),
        /// 堆串字段/元素(`记录.名字`,H1 起)按 链 现读 —— 数据地址在字段 +0,长度**数到第一个 0**。
        /// </summary>
        private (string 数据址, string 字节长) 取字串数据与字节长(引用链C 链, int 行号, string 原文)
        {
            if (链.串取字)
            {
                string 字地址 = 串字地址(链, 行号, 原文);
                string 数据址 = 新临时();
                发出间接读(数据址, 字地址, 4);
                return (数据址, 发出数到零字节(数据址));
            }
            return 串数据与字节长(链.基名, 行号, 原文);
        }

        /// <summary>
        /// 数一数字符串里有几个**文字**(Unicode 码点)。UTF-8 里"前导字节"(&lt;0x80 或 &gt;=0xC0)才算一个字,
        /// 连续字节(0x80~0xBF)是同一个字的后续字节。
        /// **每次都真的数一遍**:字符串短;而且不用在头里多存一份"文字数"(存了就得在每次改动后更新,容易对不上)。
        /// </summary>
        private string 发出数文字(string 数据址, string 字节长)
        {
            string 数 = "";
            自成一段保守(() =>
            {
            数 = 新临时();
            输出装载常量(数, 0);
            string 指针 = 新临时();
            发出($"MOV {指针} {数据址}");
            string 余 = 新临时();
            发出($"MOV {余} {字节长}");
            string 字节 = 新临时();
            string 环 = 新标签("数字环"), 一个 = 新标签("数字一"), 下一个 = 新标签("数字下"), 完 = 新标签("数字完");
            发出($"JZ {余} {完}");                       // 空串
            发出($"{环}:");
            发出间接读(字节, 指针, 1);
            发出($"CMP_IMMEDIATE {字节} 128");
            发出($"JL {一个}");                          // < 0x80:ASCII,一个字
            发出($"CMP_IMMEDIATE {字节} 192");
            发出($"JL {下一个}");                        // 0x80~0xBF:连续字节,不算新字
            发出($"{一个}:");
            发出($"ADD_IMMEDIATE {数} 1");
            发出($"{下一个}:");
            发出($"ADD_IMMEDIATE {指针} 1");
            发出($"SUB_IMMEDIATE {余} 1");
            发出($"JZ {余} {完}");
            发出($"JMP {环}");
            发出($"{完}:");
            });
            return 收下临时(数);
        }

        /// <summary> 字符串下标越界检查:按**文字数**查(下标 0 ~ 文字数-1),越界给出明确错误并停机。
        /// **T12(2026-09-27 评测整改)**:文案里不许再出现 `R11` 这种**编译器内部的寄存器名** ——
        /// 以前这里直接把装着"文字数"的那个寄存器名拼进了说明(`这个字符串只有 R11 个字符`),
        /// 用户看到的是内部编号。文字数是**运行期**值,而运行期报错是一份静态说明表(错误号 → 说明),
        /// 塞不进运行期的数 ⇒ 改成说清"下标到不了那里"并指路 `.长度()`(同族:常量下标的数组越界
        /// 有编译期就知道的个数,那几条照旧带数字)。 </summary>
        private void 发出文字下标检查(string 下标, string 文字数, int 行号, string 原文)
        {
            string 继续 = 新标签("字IdxOk");
            发出($"CMP {下标} {文字数}");
            发出($"JL {继续}");
            报错停机(行号, $"下标越界:{原文} —— 这个字符串没有那么多个字符(下标从 0 起,最大是 长度() - 1);" +
                $"文字数用 `名字.长度()` 取(按**文字**算,中文一个字算一个)");
            发出($"{继续}:");
        }

