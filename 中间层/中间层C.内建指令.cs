using System;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// **ISA 指令内建**(2026-10-13;ISA 扩容那 27 条的"用在哪"那一列)。
    /// <para>
    /// 为什么要有这一档:**库作者写不了内联汇编** —— 内联汇编只认真寄存器名,而库函数的参数在**帧**里,
    /// `取字帧` 的偏移由编译器算、源码层拿不到(实测报「字节交换 需要一个寄存器参数」)。
    /// 于是"指令加进 ISA 了"并不等于"库能用上";把它们登记成**内建函数名**(与 `读文件` / `画文字` 同一档,
    /// 中英可整体切换)之后,库与用户都能直接调,高亮 / 补全 / 帮助 / 中英切换自动跟上。
    /// </para>
    /// <para>
    /// **口径两条**:① 这些是**指令的直接映射**(一条调用发一条指令),不是"库函数"——
    /// 语义与 `指令集说明.md` §3 那几行**逐字对齐**(改这里必须同时改那张表);
    /// ② **内建优先于同名用户函数**(与 `是宿主能力名` 那一路同档):`位.hb` 里那几个同名方法
    /// 就是靠这条转发到指令上的(带点的 `位.数一位(…)` 照旧走库方法 —— 解析器认这个边界)。
    /// </para>
    /// </summary>
    internal partial class 中间层展开器
    {
        /// <summary> 这个名字的结果是不是**浮点**(位模式在寄存器里):四条浮点指令内建 + 中英两侧 </summary>
        private static bool 是浮点内建名(string 词) => 词 is
            "取较大" or "maxof" or "取较小" or "minof" or "向下取整" or "rounddown" or "搬符号" or "copysign";

        /// <summary> 是不是这几个"指令内建"的名字(中英两侧都认) </summary>
        private static bool 是ISA内建名(string 词) => 词 is
            "取较大" or "maxof" or "取较小" or "minof" or "向下取整" or "rounddown" or "搬符号" or "copysign"
            or "数一位" or "popcount" or "前导零" or "leadingzeros" or "尾随零" or "trailingzeros"
            or "循环左移" or "rotateleft" or "循环右移" or "rotateright" or "字节交换" or "swapbytes"
            or "取字节" or "extractbyte" or "取整数绝对值" or "absint" or "双字乘高" or "mulhigh"
            or "双字乘加" or "muladdhigh";

        /// <summary> 这个名字该写成什么样(报错里给改法用) </summary>
        private static string 内建写法(string 名) => 名 switch
        {
            "取较大" or "取较小" => $"{名}(左, 右)",
            "搬符号" => "搬符号(值, 号源)",
            "向下取整" or "字节交换" or "取整数绝对值" => $"{名}(值)",
            "数一位" or "前导零" or "尾随零" => $"{名}(值)",
            "循环左移" or "循环右移" => $"{名}(值, 位数)",
            "取字节" => "取字节(值, 第几段)",
            "双字乘高" or "双字乘加" => $"{名}(左, 右)",
            _ => $"{名}(…)",
        };

        private void 要实参个数(调用节点C 调用, int 行号, string 名, int 个数)
        {
            if (调用.实参.Count != 个数)
                throw 报错(行号,
                    $"{名}(...) 要 {个数} 个参数,你给了 {调用.实参.Count} 个 —— 写法是 `{内建写法(名)}`",
                    $"{名}(...) takes {个数} argument(s), got {调用.实参.Count}: `{内建写法(名)}`");
        }

        /// <summary> 把一个值摆进"可写的目标寄存器":常量装载 / 槽里读回 / 只读寄存器先复制过去 </summary>
        private void 摆进目标(表达式值 值, string 目标, int 行号, string 原文)
        {
            值 = 落到寄存器(值);
            if (值.是常量) { 输出装载常量(目标, 值.常量); return; }
            if (值.寄存器 != 目标) 发出($"复制 {目标} {值.寄存器}");
        }

        /// <summary> 第二个操作数(整数那几条):常量就装进一个临时,寄存器直接用 </summary>
        private string 第二操作数寄存器(表达式值 值, string 避开, int 行号)
        {
            值 = 落到寄存器(值);
            if (值.是常量) return 常量操作数寄存器(值.常量, 避开);
            return 值.寄存器!;
        }

        /// <summary>
        /// 展开一条"指令内建"调用。每条的名字、参数表、语义都在这里一处写死,
        /// 与 `引擎\指令C.cs` 的指令表 + `指令集说明.md` §3 那几行**逐字对齐**。
        /// </summary>
        private 表达式值 求值ISA内建(调用节点C 调用, int 行号, string 原文)
        {
            string 名 = 中间层指令C.到内建函数中文名(调用.名) ?? 调用.名;
            switch (名)
            {
                // ---------- 浮点那一族(0x48~0x4B) ----------
                case "取较大" or "取较小":                  // `浮点最大值` / `浮点最小值`(双寄存器)
                {
                    要实参个数(调用, 行号, 名, 2);
                    string 目标 = 新临时();
                    string 甲寄 = 浮点操作数寄存器(落到寄存器(求值节点(调用.实参[0], 行号, 原文, null)), 行号, 原文);
                    string 乙寄 = 浮点操作数寄存器(落到寄存器(求值节点(调用.实参[1], 行号, 原文, null)), 行号, 原文);
                    if (甲寄 != 目标) 发出($"复制 {目标} {甲寄}");
                    发出($"{(名 == "取较大" ? "浮点最大值" : "浮点最小值")} {目标} {乙寄}");
                    return 表达式值.寄存器值(目标, 可写: true, 是浮点: true);
                }

                case "向下取整":                            // `浮点向下取整`(单寄存器)
                {
                    要实参个数(调用, 行号, 名, 1);
                    string 目标 = 新临时();
                    string 值寄 = 浮点操作数寄存器(落到寄存器(求值节点(调用.实参[0], 行号, 原文, null)), 行号, 原文);
                    if (值寄 != 目标) 发出($"复制 {目标} {值寄}");
                    发出($"浮点向下取整 {目标}");
                    return 表达式值.寄存器值(目标, 可写: true, 是浮点: true);
                }

                case "搬符号":                              // `浮点符号复制`(双寄存器):|值| 配上号源的符号位
                {
                    要实参个数(调用, 行号, 名, 2);
                    string 目标 = 新临时();
                    string 值寄 = 浮点操作数寄存器(落到寄存器(求值节点(调用.实参[0], 行号, 原文, null)), 行号, 原文);
                    string 号寄 = 浮点操作数寄存器(落到寄存器(求值节点(调用.实参[1], 行号, 原文, null)), 行号, 原文);
                    if (值寄 != 目标) 发出($"复制 {目标} {值寄}");
                    发出($"浮点符号复制 {目标} {号寄}");
                    return 表达式值.寄存器值(目标, 可写: true, 是浮点: true);
                }

                // ---------- 位统计那三条(0x43~0x45;`位.hb` 那三个方法以前是 32 轮软件循环) ----------
                case "数一位" or "前导零" or "尾随零":       // 单寄存器,对 32 位整体算
                {
                    要实参个数(调用, 行号, 名, 1);
                    string 目标 = 新临时();
                    摆进目标(求值节点(调用.实参[0], 行号, 原文, null), 目标, 行号, 原文);
                    发出($"{名} {目标}");
                    return 表达式值.寄存器值(目标, 可写: true);
                }

                // ---------- 位与字节那一族(0x4C~0x53) ----------
                case "循环左移" or "循环右移" or "双字乘高" or "双字乘加":
                {
                    要实参个数(调用, 行号, 名, 2);
                    string 目标 = 新临时();
                    表达式值 甲 = 求值节点(调用.实参[0], 行号, 原文, null);
                    表达式值 乙 = 求值节点(调用.实参[1], 行号, 原文, null);
                    摆进目标(甲, 目标, 行号, 原文);
                    string 右 = 第二操作数寄存器(乙, 目标, 行号);
                    发出($"{名} {目标} {右}");
                    return 表达式值.寄存器值(目标, 可写: true);
                }

                case "字节交换" or "取整数绝对值":          // 单寄存器(逐位口径,与有符号无关)
                {
                    要实参个数(调用, 行号, 名, 1);
                    string 目标 = 新临时();
                    摆进目标(求值节点(调用.实参[0], 行号, 原文, null), 目标, 行号, 原文);
                    发出($"{名} {目标}");
                    return 表达式值.寄存器值(目标, 可写: true, 有符号: 名 == "取整数绝对值");
                }

                case "取字节":                              // `取字节 Rd, Rs, n`:n 是**编译期常量** 0~3
                {
                    要实参个数(调用, 行号, 名, 2);
                    if (调用.实参[1] is not 常量节点C 段节 || 段节.值 > 3)
                        throw 报错(行号,
                            $"取字节 的第二个参数是第几个字节,只认 **0~3 的常量**(你给的是 '{调用.实参[1].显示()}')。" +
                            $"写法:`取字节(值, 0)` 取最低那个字节,`取字节(值, 3)` 取最高那个;" +
                            $"要拿运行期下标取字节,写 `(值 >> (下标 * 8)) & 255`",
                            $"the second argument of 取字节 must be a constant 0~3, got '{调用.实参[1].显示()}'");
                    string 目标 = 新临时();
                    摆进目标(求值节点(调用.实参[0], 行号, 原文, null), 目标, 行号, 原文);
                    发出($"取字节 {目标} {目标} {段节.值}");
                    return 表达式值.寄存器值(目标, 可写: true);
                }

                default:
                    throw 报错(行号, $"不认识的指令内建函数: '{调用.名}'", $"unknown instruction builtin: '{调用.名}'");
            }
        }
    }
}
