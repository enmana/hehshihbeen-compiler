        #region 结构与引用(变量系统的后半:结构类型声明、数组/结构引用解析)

        /// <summary>
        /// 结构类型声明(编译期,纯数据):
        /// 结构 点 { 短整数 x / 字节 y / 变量 z } —— 字段按声明序紧排,结构本身不占存储,变量才占。
        /// 字段的类型还能是**已声明的结构**(嵌套)或**数组**(`点 单位[3]`、`短整数 表[8]`)——
        /// 全是编译期偏移累加,运行期一个额外指令都不多。结构只能用"前面已经声明过的"结构,
        /// 所以不会出现"结构套自己"(循环)。
        /// (以前叫"记录",已改名为"结构";老写法会报错提示)
        /// </summary>
        /// <param name="预扫">
        /// true = 现在跑的是构造函数的"工程级声明预扫"(Q1b):只登记、重名不报错(原样留给逐句处理那趟),
        /// 登记成功时把"全名 → 伪行下标"记进 `_已预登记结构`(见 `中间层C.声明预扫.cs`)。
        /// </param>
        private void 处理结构声明(ref int 位置, bool 预扫 = false)
        {
            int 行号 = _伪行号表[位置];
            int 声明下标 = 位置;
            string 首词 = 取首词(_伪行表[位置]);          // 结构/struct
            string 结构名 = _伪行表[位置][首词.Length..].Trim();
            if (!标识符全词正则.IsMatch(结构名))
                throw 报错(行号, $"结构名非法: '{结构名}'", $"invalid struct name: '{结构名}'");
            if (类型C.是类型名(结构名) || 中间层指令C.到英文关键字(结构名) != null)
                throw 报错(行号, $"结构名冲突: '{结构名}'", $"struct name conflicts: '{结构名}'");
            结构名 = 限定名(结构名);                       // 模块里的结构也带前缀(`数学.点`)
            bool 已预登记 = !预扫 && 已预登记结构到本行(结构名, 声明下标);
            if (预扫)
            {
                // 预扫撞重名不报错(该报给谁、带哪两处位置,得看逐句处理那趟的上下文);已经登记过的也不重登
                if (_结构表.ContainsKey(结构名) || _已预登记结构.ContainsKey(结构名)) return;
            }
            else if (!已预登记 && _结构表.ContainsKey(结构名))
            {
                throw 报错(行号, $"结构名冲突: '{结构名}' —— {上一处声明(结构名)}{同名怎么办("结构")}",
                    $"struct name conflicts: '{结构名}'");
            }
            if (!已预登记)
            {
                // 出处两趟都要记:预扫这趟记下(逐句处理那趟跳过登记,不会再记);重名报错就靠它带出上一处位置
                记声明出处(结构名, 行号);
                记私有(结构名);
            }
            // 已预登记:字段照旧重解析一遍(校验照做),但 `_结构表`/`_名字表`/编译提示/出处都不再写第二遍

            位置++;
            if (位置 >= _伪行表.Count || _伪行表[位置] != "{")
                throw 报错(行号, "结构声明后缺少 '{'", "expected '{' after struct");

            var 字段表 = new List<结构字段C>();
            var 字段初值 = new Dictionary<string, string>(StringComparer.Ordinal);
            var 方法待办 = new List<int>();          // H60 步④:结构里 `方法 …` 那一行的起始伪行下标(字段收完再处理)
            int 偏移 = 0;
            while (true)
            {
                if (++位置 >= _伪行表.Count) throw 报错(行号, "结构声明缺少 '}'", "missing '}' for struct");
                if (_伪行表[位置] == "}") { 位置++; break; }
                if (_伪行表[位置] == "{") throw 报错(_伪行号表[位置], "结构内出现意外的 '{'", "unexpected '{' inside struct");

                string 字段行 = _伪行表[位置];
                int 字段行号 = _伪行号表[位置];
                // H60 步④:结构里也能声明方法 —— **必须带 `方法` 关键字**(数据与方法在同一层,得一眼分得开)。
                // 方法与字段分两趟:字段要先把 `结构类型C` 建出来(方法的收方是 `引用 结构名`),所以这里只记下标、
                // 跳到方法体末尾,等结构登记好了再逐个处理(顺序与源码一致)。
                if (中间层C.到英文关键字(取首词(去可见性前缀(字段行))) == "method")
                {
                    方法待办.Add(位置);
                    位置 = 找块结束(位置 + 1, 字段行号);
                    continue;
                }
                // 裸成员头(`到原点() 返回 整数` 直接写在结构里):按字段认不出来,给一句改法提示
                if (字段行.IndexOf('(') > 0 && !字段行.Contains('['))
                    throw 报错(字段行号, $"结构里的方法要写 `方法` 前缀:'{字段行.Trim()}'。写法:`方法 名(参数) 返回 类型 {{ … }}`" +
                        $"(字段就是 `类型 名;` 那种,不带括号)", $"method inside a struct needs the `方法` keyword: '{字段行.Trim()}'");
                // H3 ①:结构字段的**标量**初值放开(`整数 x = 5;`)—— 数组 / 字符串 / 结构的初值照旧不收(见 解析字段行)
                var 字段 = 解析字段行(字段行, 字段行号, 偏移, 允许初值: true, 场合: "结构字段", out string 初值文本);
                if (字段表.Any(f => f.名称 == 字段.名称))
                    throw 报错(字段行号, $"字段重复: '{字段.名称}'", $"duplicate field: '{字段.名称}'");
                字段表.Add(字段);
                if (初值文本.Length > 0) 字段初值[字段.名称] = 初值文本;
                偏移 += 字段.宽度;
            }

            if (字段表.Count == 0)
                throw 报错(行号, $"结构 '{结构名}' 没有任何字段", $"struct '{结构名}' has no fields");
            if (偏移 > 0x10000)
                throw 报错(行号, $"结构 '{结构名}' 太大了({偏移} 字节):最大 65536 字节", $"struct '{结构名}' is too large");
            var 已折初值 = 展开字段初值(结构名, 字段表, 字段初值, 行号);
            var 结构 = new 结构类型C(结构名, 字段表, 字段初值, 已折初值);
            // ---- H60 步④:结构里的方法(字段收完、类型定下之后再处理 —— 收方的类型就是它自己)----
            // 预扫那趟**只登记签名**(见 中间层C.cs 的预扫),不在这儿编方法体(编两遍就把码发重了)。
            if (!预扫 && 方法待办.Count > 0)
            {
                结构类型C 收方结构 = _结构表.TryGetValue(结构名, out var 已登记结构) ? 已登记结构 : 结构;
                处理结构方法们(方法待办, 结构名, 收方结构);
            }
            if (已预登记) return;      // 预扫已经登记过(含名字表与编译提示):这里只当"再校验一遍字段"
            _结构表[结构名] = 结构;
            // A4:字段级 `程序集` 要知道"这个结构是哪个工程声明的"(顶层那条路记的是标了 `程序集` 的名字)
            _声明工程[结构名] = _当前工程;
            _名字表.结构[结构名] = 字段表.Select(字段项).ToList();
            记可见性(结构名);        // C19:补全按它筛结构名与 `结构变量.` 的字段可见性
            // 编译页把"平铺字段表"写出来 —— 嵌套之后要能一眼看全每个字段落在哪
            _编译提示.Add($"结构 {结构名}:{偏移} 字节 → {平铺字段说明(结构)}");
            if (已折初值.Count > 0)
                _编译提示.Add($"结构 {结构名}:{已折初值.Count} 个字段带默认值(" +
                    string.Join(" ", 字段初值.Select(kv => $"{kv.Key} = {kv.Value.Trim()}")) + ")—— 声明这个结构的变量时写进那一格," +
                    $"变量自己再写初值就盖掉对应的默认值");
            if (预扫) _已预登记结构[结构名] = 声明下标;
        }

        /// <summary>
        /// H60 步④:把结构里那几条 `方法 …` 逐个当成**成员方法**处理(与容器成员同一套:隐藏收方 + 字段走收方)。
        /// 处理期间摆好两份上下文:
        ///   · `_当前结构字段全名` = 裸字段名 → `_收方.字段`(方法体里直接写字段名就靠它);
        ///   · `_当前结构方法表` = 方法短名 → 定义名(结构方法体里裸叫兄弟成员就靠它,收方照传)。
        /// 两份都是"进方法区摆好、出方法区还原",与容器那两格(`换字段映射`)同一个道理。
        /// </summary>
        private void 处理结构方法们(List<int> 待办, string 结构名, 结构类型C 结构)
        {
            if (!_结构方法表.TryGetValue(结构名, out var 表))
                _结构方法表[结构名] = 表 = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            _名字表.结构方法[结构名] = 表.Values.ToList();
            var 字段映射 = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var 字段 in 结构.字段) 字段映射[字段.名称] = 收方参数名 + "." + 字段.名称;

            var 上层字段映射 = _当前结构字段全名;
            var 上层方法表 = _当前结构方法表;
            string 上层结构名 = _当前结构名;
            _当前结构字段全名 = 字段映射;
            _当前结构方法表 = 表;
            _当前结构名 = 结构名;
            try
            {
                foreach (int 起始 in 待办)
                {
                    int 位置 = 起始;
                    处理函数声明(ref 位置, (结构名, 结构));
                    _名字表.结构方法[结构名] = 表.Values.ToList();   // 方法表会长大,名字表跟着刷一遍
                }
            }
            finally
            {
                _当前结构字段全名 = 上层字段映射;
                _当前结构方法表 = 上层方法表;
                _当前结构名 = 上层结构名;
            }
        }

        /// <summary>
        /// **H3 ①**:把结构字段的标量默认值当成**常量**验一遍,并折成 32 位值(字段名 → 值)。
        /// 口径与"声明变量的常量初值"完全一致:只认**字面量**(`5` / `-5` / `0x10`),表达式(`5 + 1`)当场报错;
        /// 按**字段自己的类型**做范围检查(`字节 b = 300;` 报错,`短整数 s = -5;` 合法)。
        /// 报错指在这一行(字段声明行),改法写清 —— 与硬规矩 2 一个口径。
        /// </summary>
        private Dictionary<string, uint> 展开字段初值(string 结构名, List<结构字段C> 字段表,
            Dictionary<string, string> 字段初值, int 兜底行号)
        {
            var 表 = new Dictionary<string, uint>(StringComparer.Ordinal);
            if (字段初值.Count == 0) return 表;
            foreach (var 字段 in 字段表)
            {
                if (!字段初值.TryGetValue(字段.名称, out string? 原文)) continue;
                int 指到行 = 字段声明行(结构名, 字段.名称, 兜底行号);
                // H68-2:枚举成员也是常量(`颜色 花 = 绿;`)—— 先折成十进制原文,再走同一套检查
                原文 = 折成员常量(原文, 指到行, 查枚举类型(字段.类型名)?.名称 ?? "");
                if (!是常量字面量(原文))
                    throw 报错(指到行, $"字段 '{结构名}.{字段.名称}' 的默认值只能是**常量字面量**:" +
                        $"现在的 '{原文.Trim()}' 编译器算不出来。写法:`{字段.类型名} {字段.名称} = 5;`;" +
                        $"要在声明变量时算一个式子,就把它写成变量自己的初值(`{结构名} 位置 = …` 那条路只认整块初值)",
                        $"field default must be a literal constant: '{原文.Trim()}'");
                表[字段.名称] = 元素初值常量(原文, 字段.类型名, 指到行);
            }
            return 表;
        }

        /// <summary> 这一行是不是一个常量字面量(十进制 / 0x 十六进制 / 带负号) </summary>
        private static bool 是常量字面量(string 文本)
            => 解析无符号32(文本, out _) || 解析负常量32(文本, out _);

        /// <summary> 报错指到"这个字段声明在哪一行"—— 按 `字段偏移` 回源码行;查不到就用传进来的那一行 </summary>
        private int 字段声明行(string 结构名, string 字段名, int 兜底行号)
        {
            int 偏移 = _结构表.TryGetValue(结构名, out var 老结构) ? 老结构.找字段(字段名)?.偏移 ?? -1 : -1;
            return 偏移 >= 0 && 偏移 < _伪行表.Count ? _伪行号表[偏移] : 兜底行号;
        }

        /// <summary> 把"结构默认值"与"变量自己写的字面量初值"并成一张表:**同一格以变量写的为准** </summary>
        private static List<(int 偏移, int 宽度, uint 值)> 并结构默认(
            IReadOnlyList<(int 偏移, int 宽度, uint 值)> 默认,
            List<(int 偏移, int 宽度, uint 值)> 变量写的)
        {
            if (默认.Count == 0) return 变量写的;
            if (变量写的.Count == 0) return [.. 默认];
            var 占了的 = new HashSet<int>(变量写的.Select(项 => 项.偏移));
            var 表 = 默认.Where(项 => !占了的.Contains(项.偏移)).ToList();
            表.AddRange(变量写的);
            return 表;
        }

        /// <summary>
        /// 把"结构自己带的默认值"写进这一份变量:顶层槽**并进装载期初值**(一个字节的指令都不多发),
        /// 帧槽 / 循环体里现场按偏移写(帧是复用的,数据段"天生是 0"不作数)。
        /// </summary>
        private void 发出结构默认初值(变量槽定义 定义, 地址位置 该位置, 结构类型C 构型)
        {
            if (构型.默认初值们.Count == 0) return;
            if (初值可搬(定义)) 记顶层填块(定义.名称, [.. 构型.默认初值们], 该位置.偏移);
            else 发出常量填块(取位置地址(该位置), [.. 构型.默认初值们]);
        }

        /// <summary>
        /// **收一条字段声明 —— 结构字段与容器常驻字段用的是同一把尺子**(H52)。
        /// 类型:基础类型 / `var` / 已声明的结构 / `字符串`;名字后面可以跟 `[个数]`(数组,元素是结构也行)
        /// 或 `[]`(动态列表:头 12 字节在结构里、元素在堆里);A4 的 `私有` / `程序集` 前缀照收。
        /// **初值**只有容器那一侧收(`允许初值`,且只收标量 —— 数组/字符串/结构的初始化写到容器第一层去);
        /// 结构字段照旧不收初值(见 H3)。重名检查 / 进字段表 / 累加偏移由调用方做(两边的报错文案不一样)。
        /// </summary>
        private 结构字段C 解析字段行(string 原始行, int 行号, int 偏移, bool 允许初值, string 场合, out string 初值文本)
        {
            // A4:字段上也能写可见性(`私有 整数 余额;`)—— 与顶层声明同一套词
            string 字段行 = 去可见性前缀带标记(原始行, out bool 字段私有, out bool 字段程序集);
            string 字段首词 = 取声明类型词(字段行);
            string 字段余下 = 字段行[字段首词.Length..].Trim();
            初值文本 = "";
            int 等号 = 字段余下.IndexOf('=');
            if (等号 >= 0)
            {
                if (!允许初值)
                    throw 报错(行号, $"{场合}不支持初值", $"{场合} cannot have initializers");
                初值文本 = 字段余下[(等号 + 1)..].Trim();
                字段余下 = 字段余下[..等号].Trim();
                if (初值文本.Length == 0)
                    throw 报错(行号, $"字段初值的等号右边是空的:'{原始行.Trim()}'", $"empty field initializer: '{原始行.Trim()}'");
            }

            // 字段类型:基础类型 / var / 已声明的结构 / 字符串
            结构类型C? 字段结构 = null;
            bool 字段是字符串 = false;
            int 单个宽;
            string 字段类型名;
            if (类型C.解析(字段首词) is { } 字段类型)
            {
                单个宽 = 字段类型.宽度;
                字段类型名 = 字段类型.中文;
            }
            else if (中间层指令C.到英文关键字(字段首词) == "var")
            {
                单个宽 = 类型C.字宽度;
                字段类型名 = "32位字";
            }
            // H68-2 枚举字段:`颜色 花;`(底层 4 字节有符号整数 —— 与 `整数 花;` 逐字节同构)
            else if (查枚举类型(字段首词) is { } 字段枚举)
            {
                单个宽 = 类型C.枚举底层.宽度;
                字段类型名 = 字段枚举.名称;
            }
            else if (查结构类型(字段首词) is { } 已声明结构)
            {
                字段结构 = 已声明结构;
                单个宽 = 已声明结构.总宽度;
                字段类型名 = 已声明结构.名称;
            }
            else if (字段首词 is "字符串" || string.Equals(字段首词, "string", StringComparison.OrdinalIgnoreCase))
            {
                // 结构里放字符串:字段里存的是"数据地址 + 容量"(8 字节),真正的字节在**堆**里
                // (`字符 名字[16]` 那种内联缓冲也能当字符串用,容量固定、放不下会拦住)
                字段是字符串 = true;
                单个宽 = 串字段宽;
                字段类型名 = "字符串";
            }
            else
            {
                // H68-3:元组写法坏掉时,让元组那一侧把"哪儿写坏了"说清楚
                if (是元组类型词(字段首词)) 取元组类型(字段首词, 行号);
                throw 报错(行号, $"未知的字段类型: '{字段首词}'(结构要先声明再用)", $"unknown field type: '{字段首词}'");
            }

            // 字段名,可以带 [个数] = 数组字段
            string 字段名 = 字段余下.Trim();
            int 元素个数 = 0;
            int 方括号 = 字段名.IndexOf('[');
            if (方括号 >= 0)
            {
                if (!字段名.EndsWith(']'))
                    throw 报错(行号, $"字段数组缺少 ']': '{字段名}'", $"missing ']' in field: '{字段名}'");
                string 长度文本 = 字段名[(方括号 + 1)..^1].Trim();
                if (长度文本.Length == 0)
                {
                    // H1 第四件:字段里的**动态列表**(`整数 数[]`)—— 头 12 字节在结构里
                    // (数据地址 / 长度 / 容量),元素在**堆**里、按容量翻倍,`记录 = 0;` 时把块还回去。
                    // 与 `字符串` 字段同一个口径(用户 2026-09-20 拍板:住堆 / 深拷贝 / 还块)。
                    string 列表名 = 字段名[..方括号].Trim();
                    if (字段是字符串)
                        throw 报错(行号, $"字段里的列表,元素先不放 `字符串`:'{列表名}'(每个元素的堆块都要逐个归还、整体赋值要逐个深拷,还没做)。" +
                            $"改法:①放到结构外面的顶层列表(`字符串 名单[];`),②字段里放定长数组(`字符串 名单[16];`)",
                            $"string elements in a struct-field list are not supported yet: '{列表名}'");
                    if (字段结构 is { 有堆字段: true } 元素结构)
                        throw 报错(行号, $"字段里的列表,元素先不放带堆块的结构:'{列表名}'(结构 {元素结构.名称} 里有 `字符串` 或列表字段,逐元素归还/深拷还没做)。" +
                            $"改法:①放到结构外面的顶层列表,②字段里放定长数组",
                            $"struct elements with heap fields in a struct-field list are not supported yet: '{列表名}'");
                    if (!标识符全词正则.IsMatch(列表名))
                        throw 报错(行号, $"字段名非法: '{列表名}'", $"invalid field name: '{列表名}'");
                    if (初值文本.Length > 0)
                        throw 报错(行号, $"字段 '{列表名}' 是动态列表,不能写初值 —— 把初始化写到容器第一层" +
                            $"(那是程序开头的初始化脚本),例如 `{列表名}.添加(1);`", $"a list field cannot have an initializer: '{列表名}'");
                    return new 结构字段C(列表名, 字段类型名, 列表字段宽, 偏移,
                        是列表: true, 列表元素宽: 单个宽, 列表元素结构: 字段结构,
                        私有: 字段私有, 程序集: 字段程序集);
                }
                if (!uint.TryParse(长度文本, out uint 个数) || 个数 == 0 || 个数 > 0x10000)
                    throw 报错(行号, $"字段数组长度非法: '{长度文本}'(须为 1~65536 的常量)", $"invalid field array length: '{长度文本}'");
                元素个数 = (int)个数;
                字段名 = 字段名[..方括号].Trim();
            }

            if (!标识符全词正则.IsMatch(字段名))
                throw 报错(行号, $"字段名非法: '{字段名}'", $"invalid field name: '{字段名}'");
            // 数组 / 字符串 / 结构字段的初值:一律不收 —— 初始化写到容器第一层(那是程序开头的初始化脚本)
            if (初值文本.Length > 0 && (元素个数 > 0 || 字段是字符串 || 字段结构 != null))
                throw 报错(行号, $"字段 '{字段名}' 是{(元素个数 > 0 ? "数组" : 字段是字符串 ? "字符串" : "结构")},不能写初值 —— " +
                    $"把初始化写到容器第一层(那里是程序开头的初始化脚本),例如 `{字段名}[0] = 1;` / `{字段名} = \"文字\";`",
                    $"a non-scalar field cannot have an initializer: '{字段名}'");

            int 字段宽度 = 元素个数 > 0 ? 单个宽 * 元素个数 : 单个宽;
            if (元素个数 > 0)
                return new 结构字段C(字段名, 字段类型名, 字段宽度, 偏移,
                    结构类型: 字段结构, 元素宽: 单个宽, 元素个数: 元素个数,
                    元素是字符串: 字段是字符串, 私有: 字段私有, 程序集: 字段程序集);
            return new 结构字段C(字段名, 字段类型名, 字段宽度, 偏移, 结构类型: 字段结构,
                是字符串: 字段是字符串, 私有: 字段私有, 程序集: 字段程序集);
        }

        /// <summary> 这个结构名的声明就在 `声明下标` 这一行、而且是预扫登记的那一条?(Q1b 的"已预登记"协议) </summary>
        private bool 已预登记结构到本行(string 全名, int 声明下标)
            => 声明下标 >= 0 && _已预登记结构.TryGetValue(全名, out int 预行) && 预行 == 声明下标;

        /// <summary> 把一个结构摊平成人能看的一行(嵌套的用 点.字段 一层层写出来,数组写明个数)</summary>
        private static string 平铺字段说明(结构类型C 结构, string 前缀 = "", int 基偏移 = 0)
        {
            var 段 = new List<string>();
            foreach (var 字段 in 结构.字段)
            {
                string 名 = 前缀.Length == 0 ? 字段.名称 : $"{前缀}.{字段.名称}";
                if (字段.是结构 && 字段.结构类型 != null)
                {
                    段.Add(平铺字段说明(字段.结构类型, 名, 基偏移 + 字段.偏移));
                    continue;
                }
                string 形状 = 字段.是列表 ? $"列表(元素 {字段.列表元素宽} 字节,头 12 字节)"
                    : 字段.是数组 ? $"{字段.元素个数}×{字段.元素宽}字节" : $"{字段.宽度}字节";
                string 可见 = 字段.私有 ? "私有 " : 字段.程序集 ? "程序集 " : "";
                段.Add($"{可见}{名}@{基偏移 + 字段.偏移}({形状})");
            }
            return string.Join(" ", 段);
        }

        /// <summary>
        /// 读位置:1 字节 → 字节加载(零扩展);2 字节 → 字加载取低 16 位;4 字节 → 字加载。
        /// C 档优化下 `短整数` 变量是"4 字节槽"(宽度 4)→ 一条 `取字` 就够(存的时候已经补好了)。
        /// **紧排的 2 字节有符号值**(结构字段/数组元素/4 字节以下的槽)读出来要补符号位,不然
        /// `-5` 会读成 65531。
        /// </summary>
        private void 发出读变量(string 目标寄存器, 地址位置 位置)
        {
            if (解析帧槽(位置.槽, out int 帧偏移))
            {
                发出帧读(目标寄存器, 帧偏移 + 位置.偏移, 位置.宽度);
                if (位置.读要符号扩展) 发出符号扩展(目标寄存器, 位置.有效宽, 需先掩码: 位置.宽度 > 位置.有效宽);
                return;
            }
            switch (位置.宽度)
            {
                case 1:
                    发出($"LOAD {目标寄存器} {位置.地址文本}");
                    break;
                case 2:
                    发出($"LOAD_WORD {目标寄存器} {位置.地址文本}");
                    if (位置.有符号)
                    {
                        // 2 字节槽:取字会连隔壁两个字节一起读进来,所以先掩码再补符号位
                        发出符号扩展(目标寄存器, 2, 需先掩码: true);
                    }
                    else
                    {
                        发出与立即数(目标寄存器, 0xFFFFu);   // P11:一条 与立即数
                    }
                    break;
                default:
                    发出($"LOAD_WORD {目标寄存器} {位置.地址文本}");
                    break;
            }
        }

        /// <summary>
        /// 把寄存器里的**有符号**窄值补成 32 位(高半 = 符号位)。没有算术右移指令,所以用
        /// `x = (x 异或 半界) - 半界` 这个恒等式(2 条指令,ISA 不用加东西)。
        /// `需先掩码` = 输入可能带着高位垃圾(写回宽槽时就是这样)→ 先 `与 低半掩码` 把它清成纯窄值,
        /// 不然异或/减会动到不该动的高位(踩过:`短整数 s = -300` 变成 -65836)。
        /// </summary>
        private void 发出符号扩展(string 寄存器, int 声明宽, bool 需先掩码 = false)
        {
            uint 掩 = 1u << (声明宽 * 8 - 1);          // 2 字节 → 0x8000;4 字节不用补
            if (声明宽 >= 4) return;
            if (需先掩码)
            {
                发出与立即数(寄存器, (1u << (声明宽 * 8)) - 1);   // P11:一条 与立即数
            }
            string 半界 = 常量操作数寄存器(掩, 寄存器);
            发出($"XOR {寄存器} {半界}");
            发出($"SUB_IMMEDIATE {寄存器} {掩}");
        }

        private void 发出读变量(string 目标寄存器, 变量槽定义 定义) =>
            发出读变量(目标寄存器, new 地址位置(定义.名称, 0, 定义.宽度));

        /// <summary>
        /// 写位置:1 字节 → 字节存储;2 字节 → 两字节存储;4 字节 → 字存储。
        /// C 档优化下 `短整数` 变量是"4 字节槽"(宽度 4)→ 一条 `存字`,但存之前先按 声明宽 处理:
        /// **无符号补 0**(掩码)、**有符号补符号位**(符号扩展);`源已零扩展` 时连这一步都省了。
        /// </summary>
        private void 发出写变量(string 源寄存器, 地址位置 位置, bool 源已零扩展 = false, bool 源可改写 = false)
        {
            // T6(2026-09-27 评测整改):**有符号窄槽不能靠"源已零扩展"省掉截断**。
            // `源已零扩展` 只说"高 16 位是 0",可低 16 位的最高位(bit15)仍可能是 1:
            // `短整数 s = 40000; s = 0x8000; s = 0xFFFF;` 这种值零扩展进去、按 16 位读出来是负数,
            // 于是默认档打 40000 / 65535、`--no-opt` 打 -25536 / -1 —— **同一份源码两个答案**。
            // 修法照 `写要符号扩展` 那一支:一律补符号位(多两条指令,换"两档同答案")。
            bool 能省截断 = 源已零扩展 && !位置.写要符号扩展;
            if (位置.要截断 && !能省截断)
            {
                if (位置.写要符号扩展)
                {
                    // 有符号:补符号位(高半全是符号位)。源可能带高位垃圾,所以先掩一次低半。
                    if (源可改写)
                    {
                        发出符号扩展(源寄存器, 位置.声明宽, 需先掩码: true);
                    }
                    else
                    {
                        string 截 = 新临时();
                        发出($"MOV {截} {源寄存器}");
                        发出符号扩展(截, 位置.声明宽, 需先掩码: true);
                        发出写变量(截, 位置 with { 声明宽 = 0 });
                        return;
                    }
                }
                else
                {
                    if (源可改写)
                    {
                        发出与立即数(源寄存器, 截断掩码(位置.声明宽));   // P11:一条 与立即数
                    }
                    else
                    {
                        string 截 = 新临时();
                        发出($"MOV {截} {源寄存器}");
                        发出与立即数(截, 截断掩码(位置.声明宽));
                        发出写变量(截, 位置 with { 声明宽 = 0 });
                        return;
                    }
                }
            }
            if (解析帧槽(位置.槽, out int 帧偏移))
            {
                发出帧写(源寄存器, 帧偏移 + 位置.偏移, 位置.宽度);
                return;
            }
            switch (位置.宽度)
            {
                case 1:
                    发出($"STORE {源寄存器} {位置.地址文本}");
                    break;
                case 2:
                    发出($"STORE {源寄存器} {位置.地址文本}");            // 低字节
                    string 高 = 新临时();
                    发出($"MOV {高} {源寄存器}");
                    发出右移立即数(高, 8);                                  // A9:一条顶"装常量 8 + 右移"
                    发出($"STORE {高} {位置.地址文本加(1)}");               // 次字节
                    break;
                default:
                    发出($"STORE_WORD {源寄存器} {位置.地址文本}");
                    break;
            }
        }

        private void 发出写变量(string 源寄存器, 变量槽定义 定义) =>
            发出写变量(源寄存器, new 地址位置(定义.名称, 0, 定义.宽度));

        /// <summary>
        /// 帧内读:`取字帧`(FP+偏移 一条指令,ISA 0x2A)就是"局部变量直通车"。
        /// 4 字节及以上的槽(数组参数的"地址"槽就是 8 字节)一条就够;2 字节槽照旧读一个字再掩码;
        /// 1 字节走"取地址帧 + 间接字节读"。**别把 &gt;4 的宽槽掉进字节分支** —— 踩过:
        /// 数组参数的地址槽是 8 字节,读成 1 字节 → 基址只剩低 8 位,求和读出天文数字。
        /// </summary>
        private void 发出帧读(string 目标寄存器, int 偏移, int 宽度)
        {
            if (宽度 >= 4)
            {
                发出($"取字帧 {目标寄存器} {偏移}");
                return;
            }
            if (宽度 == 2)
            {
                // 槽只有 2 字节:取字会连隔壁一起读进来,掩码清掉高位(和无符号 2 字节槽一个规矩)
                发出($"取字帧 {目标寄存器} {偏移}");
                发出与立即数(目标寄存器, 0xFFFFu);    // P11:一条 与立即数
                return;
            }
            string 地址 = 新临时();
            发出($"取地址帧 {地址} {偏移}");
            发出($"加载间接寻址 {目标寄存器} {地址}");
        }

        /// <summary> 帧内写:`存字帧`(FP+偏移 一条指令,ISA 0x2B);窄格子照旧走间接写(按宽度截断) </summary>
        private void 发出帧写(string 源寄存器, int 偏移, int 宽度)
        {
            if (宽度 >= 4)
            {
                发出($"存字帧 {源寄存器} {偏移}");
                return;
            }
            string 地址 = 新临时();
            发出($"取地址帧 {地址} {偏移}");
            发出间接写(源寄存器, 地址, 宽度);
        }

        /// <summary> 间接读:1 字节 → 间接字节读;2 字节 → 间接字读取低 16 位;4 字节 → 间接字读 </summary>
        private void 发出间接读(string 目标寄存器, string 地址寄存器, int 宽度)
        {
            if (宽度 == 1)
            {
                发出($"加载间接寻址 {目标寄存器} {地址寄存器}");
                return;
            }
            发出($"取字间接 {目标寄存器} {地址寄存器}");
            if (宽度 == 2)
            {
                发出与立即数(目标寄存器, 0xFFFFu);    // P11:一条 与立即数
            }
        }

        /// <summary> 间接写(按宽度截断);2 字节用两条间接字节存储,避免踩到邻居 </summary>
        private void 发出间接写(string 源寄存器, string 地址寄存器, int 宽度)
        {
            if (宽度 == 1)
            {
                发出($"存储间接寻址 {源寄存器} {地址寄存器}");
                return;
            }
            if (宽度 >= 4)
            {
                发出($"存字间接 {源寄存器} {地址寄存器}");
                return;
            }
            发出($"存储间接寻址 {源寄存器} {地址寄存器}");
            string 高 = 新临时();
            发出($"MOV {高} {源寄存器}");
            发出右移立即数(高, 8);                     // A9:一条顶"装常量 8 + 右移"(2 字节元素写少一条)
            string 下一个 = 新临时();
            发出($"MOV {下一个} {地址寄存器}");
            发出($"加立即数 {下一个} 1");
            发出($"存储间接寻址 {高} {下一个}");
        }


        /// <summary> 解析"数组/列表[下标]…"引用(兼容老写法);不是数组/列表引用返回 null(非数组用 [] 会报错) </summary>
        private (变量绑定C 绑定, string 索引)? 解析数组引用(string 文本, int 行号)
        {
            string 名 = 文本.Trim();
            int 方括号 = 名.IndexOf('[');
            if (方括号 <= 0) return null;
            if (!名.EndsWith(']'))
                throw 报错(行号, $"下标缺少 ']': '{名}'", $"missing ']' in '{名}'");
            string 基名 = 名[..方括号].Trim();
            var 绑定 = 查变量(基名);
            if (绑定 is not { } 变量) return null;
            if (变量.数组类型 is null && 变量.列表类型 is null)
                throw 报错(行号, $"'{基名}' 不是数组/列表,不能用 [] 下标", $"'{基名}' is not an array or list");
            return (变量, 名[(方括号 + 1)..^1].Trim());
        }

        /// <summary> 下标 → 寄存器:常量/寄存器/变量/字段,实在不行就当**表达式**算(如 `表[表.长度() - 1]`) </summary>
        private string 索引到寄存器(string 索引文本, int 行号, string 原文)
        {
            if (解析寄存器(索引文本, out string 直接)) return 直接;
            if (像引用链(索引文本) && 查位置(索引文本, 行号, 原文) is { } 位置)
            {
                要求标量(位置, 行号, 索引文本);
                string t = 新临时();
                发出读变量(t, 位置);
                return t;
            }
            if (解析无符号32(索引文本, out uint 常量))
            {
                string t = 新临时();
                输出装载常量(t, 常量);
                return t;
            }
            // 带括号/运算符的写法(下标里的算术、`.长度()`、函数调用…)交给表达式引擎;
            // 以前一律报"数组下标须为 常量/寄存器/变量/字段",用户写 `表[表.长度() - 1]` 就撞墙
            if (索引文本.Contains('(') || 索引文本.IndexOfAny(['+', '-', '*', '/', '%']) > 0)
            {
                var 值 = 求值表达式(索引文本, 行号, 原文);
                if (值.是常量)
                {
                    string t = 新临时();
                    输出装载常量(t, 值.常量);
                    return t;
                }
                var 落 = 落到寄存器(值);
                if (落.寄存器 is { } 寄存器) return 寄存器;
            }
            throw 报错(行号, $"数组下标须为 常量/寄存器/变量/字段/表达式: '{索引文本}'", $"invalid array index: '{索引文本}'");
        }

        /// <summary>
        /// 运行期下标的**边界检查**(数组与列表都查)。下标是 32 位无符号 → 只用挡上界(负数会变成极大值,一样挡住)。
        /// 展开成:`比较 下标, 上界 / 小于就跳过 / 越界:写错误槽 + 停机 / 继续:`
        /// 热路径只多 2 条(动态列表多 1 条"读容量"),越界那一块是冷代码而且一定停机,所以它能随便用临时寄存器。
        /// 为什么必须有:没有它,越界会**静悄悄写坏隔壁变量**(测评实测:`短整数 表[4]` 的 `表[4]=999` 把邻居改了)。
        ///
        /// **H14**:工程文件里写 `"边界": "关"` ⇒ `_边界检查 = 假` ⇒ 这里**一条都不发**(极限速度那一档,
        /// 每次访问省 2~3 条)。关掉之后上面那个"写坏隔壁变量"的后果**如实存在** —— 由工程作者自己保证不越界;
        /// 编译期算得出的常量下标越界仍由 `引用链C.拆` 当场报错(那一条不花运行期的码),字符串取字另有一套。
        /// </summary>
        private void 输出下标检查(string 下标寄存器, (int 常量, 变量槽定义? 槽, string? 现成寄存器, string 说明) 上界, int 行号, string 原文)
        {
            if (!_边界检查) return;   // H14:`边界="关"` —— 不发检查(热路径那 2~3 条全省掉)
            if (上界.常量 <= 0 && 上界.槽 == null && 上界.现成寄存器 == null) return;   // 上界在编译期未知(不应发生):不做拦截
            string 继续 = 新标签("IdxOk");
            if (上界.现成寄存器 is { } 已算好)
            {
                发出($"CMP {下标寄存器} {已算好}");                      // 字段里的列表:容量在头里,已经读进寄存器
            }
            else if (上界.槽 is { } 上界槽)
            {
                string 寄存器 = 新临时();
                发出读变量(寄存器, 上界槽);
                发出($"CMP {下标寄存器} {寄存器}");
            }
            else
            {
                发出($"CMP_IMMEDIATE {下标寄存器} {上界.常量}");
            }
            发出($"JL {继续}");
            报错停机(行号, $"下标越界:{原文} —— {上界.说明}");
            发出($"{继续}:");
        }

        /// <summary>
        /// 引用链版的下标上界:具名列表与老路完全一样;`筐.数`(字段里的列表)的上界在**头的 +8 那个字**里,
        /// 现读进一个寄存器交给 `输出下标检查`(它认"现成寄存器"那一档)。
        /// </summary>
        private (int 常量, 变量槽定义? 槽, string? 现成寄存器, string 说明) 下标上界(引用链C 链, int 行号, string 原文)
        {
            if (链.字段列表 is { } 字段列表)
            {
                var 省着 = 记占用();
                string 头 = 列表头地址(字段列表, 行号, 原文);
                string 上界 = 新临时();
                // T14(2026-09-27 评测整改):查**长度**(头 +4),不是容量(头 +8)——
                // 容量是"还能装几个",长度才是"现在有几个"。按容量查的话,`表.添加()` 之后
                // 长度 3 / 容量 4 的列表 `表[3]` 会静默读出 0(实测),而文档口径是"下标越界一律当场拦住"。
                发出间接读(上界, 基址加偏移(头, 列表头长度偏移), 4);
                还占用(省着, 上界);
                return (0, null, 上界, "列表只能用到它现在的长度(下标从 0 开始,到 .长度()-1;要更多先 .添加())");
            }
            var 老 = 下标上界(链.绑定, 链.下标上界);
            return (老.常量, 老.槽, null, 老.说明);
        }

        /// <summary> 数组/列表/数组引用的下标上界:常量长度,或者"动态列表"的**长度槽**(运行期读)。
        /// 说明文字里**只写"几个"**,不写槽名(`_v1` 那种是编译器内部的,不该让用户看见 —— 原文里有变量名)。
        /// **T14(2026-09-27 评测整改)**:动态列表以前拿**容量槽**当上界 —— 容量是"还能装几个",
        /// 长度才是"现在有几个";`循环 { 表.添加(k); } 表[3]`(长度 3 / 容量 4)以前静默读出 0、退出码 0。
        /// `.添加()` 到容量边界照旧正常(这条只改下标读写的判据,不碰扩容)。</summary>
        private (int 常量, 变量槽定义? 槽, string? 现成寄存器, string 说明) 下标上界(变量绑定C 绑定, int 链上界 = 0)
        {
            // 列表要排在最前面:动态列表的"现在有几个"是运行期的(长度槽),比链上记录的初始容量准
            if (绑定.是列表)
            {
                var 列表 = 按槽找列表(绑定.名称);
                if (列表 is { 动态: true, 长度槽: { } 列长槽 })
                    return (0, 列长槽, null, "列表只能用到它现在的长度(下标从 0 开始,到 .长度()-1;要更多先 .添加())");
                int 容量 = 列表?.类型.容量 ?? 0;
                return 容量 > 0 ? (容量, null, null, $"列表最多 {容量} 个(下标 0~{容量 - 1})") : (0, null, null, "");
            }
            // 数组参数(切片):长度是调用方给的运行期值(在它自己的槽里)
            if (绑定.长度槽 is { } 长度槽)
                return (0, 长度槽, null, "这个数组参数只能用到它的长度(下标从 0 开始)");
            // H68-1:多维数组这里查的是**第一维**(报错点明第几维,与 `链多维元素地址` 那一侧的文案一个口径)
            if (链上界 > 0)
                return (链上界, null, null, 绑定.数组类型 is { 是多维: true }
                    ? $"第 1 维只有 {链上界} 个元素(下标 0~{链上界 - 1})"
                    : $"只有 {链上界} 个元素(下标 0~{链上界 - 1})");
            if (绑定.是数组)
            {
                int 长 = 绑定.数组类型!.长度;
                // H68-1:多维数组这里查的是**第一维**(报错点明第几维,与 `链多维元素地址` 那一侧的文案一个口径)
                return (长, null, null, 绑定.数组类型!.是多维
                    ? $"第 1 维只有 {长} 个元素(下标 0~{长 - 1})"
                    : $"只有 {长} 个元素(下标 0~{长 - 1})");
            }
            return (0, null, null, "");
        }

        private string 数组元素地址(变量绑定C 绑定, string 索引文本, int 行号, string 原文)
        {
            int 元素宽 = 绑定.元素宽;
            string 下标 = 索引到寄存器(索引文本, 行号, 原文);
            输出下标检查(下标, 下标上界(绑定), 行号, 原文);
            // P1 数组地址增量:`表[归纳变量]++` 这类也吃得上步进指针(按槽名对得上就行)
            if (!绑定.是列表 && 步进指针(绑定.名称, 索引文本, 元素宽, 0) is { } 步进) return 步进;
            var 列表 = 绑定.是列表 ? 按槽找列表(绑定.名称) : null;
            string 地址 = 列表 != null ? 取列表基址(列表) : 取基址(绑定.名称);
            // ISA 扩容批 2(0x53 `取地址索引`):元素宽是 2 的幂时,"缩放 + 相加"两条并成一条
            // (地址算式在热路径上;不是 2 的幂(结构数组那种)照旧走 `缩放下标` + `ADD`)。
            if (缩放位数(元素宽) is { } 缩放)
            {
                发出($"取地址索引 {地址} {下标} {地址} {缩放}");
                return 地址;
            }
            缩放下标(下标, 元素宽);
            发出($"ADD {地址} {下标}");
            return 地址;
        }

        /// <summary> 元素宽 → 2 的幂次(1→0 / 2→1 / 4→2 / 8→3);不是 2 的幂、或超过 `指令C.最大缩放` 给 null </summary>
        private static int? 缩放位数(int 元素宽)
        {
            if (元素宽 <= 0 || (元素宽 & (元素宽 - 1)) != 0) return null;
            int 位 = 0;
            for (int 剩 = 元素宽; 剩 > 1; 剩 >>= 1) 位++;
            return 位 <= 指令C.最大缩放 ? 位 : null;
        }

        /// <summary> 取槽基址到寄存器:帧内变量/数组 → FP+偏移;全局 → 取地址 标签 </summary>
        private string 取基址(string 槽名)
        {
            string 地址 = 新临时();
            输出基址到(地址, 槽名);
            return 地址;
        }

        /// <summary> 读数组/列表元素到寄存器:1 字节 → 间接字节读;2 字节 → 间接字读取低 16 位;4 字节 → 间接字读 </summary>
        private string 取数组元素到寄存器(变量绑定C 绑定, string 索引文本, int 行号, string 原文)
        {
            int 元素宽 = 绑定.元素宽;
            // P12 + A3:索引寻址 —— 4 字节元素一条 `取字索引`;2 字节元素再补一条 `与立即数`(低 16 位就是元素,
            // 与老路的"取字间接 + 与立即数"读的是**同一个字**,所以越界行为一模一样)。
            // 1 字节元素不做:老路本来就是一条按字节读,换成索引读要读 4 字节再掩码,不省还多读 3 字节。
            if (元素宽 is 4 or 2)
            {
                // P1 的步进指针优先(1/2 字节元素的循环里它本来就有一个常驻指针):要让就整段让掉 ——
                // 连越界检查都不发(先问再发,别先发检查再回头)。
                if (绑定.是列表 || 步进指针(绑定.名称, 索引文本, 元素宽, 0) is null)
                {
                    string 下标 = 索引到寄存器(索引文本, 行号, 原文);
                    输出下标检查(下标, 下标上界(绑定), 行号, 原文);
                    var 列表 = 绑定.是列表 ? 按槽找列表(绑定.名称) : null;
                    string 基 = 列表 != null ? 取列表基址(列表) : 取基址(绑定.名称);
                    if (元素宽 == 2)
                    {
                        // ISA 扩容批 3(0x54 `取半字索引`):读出来就是低 16 位 ⇒ `与立即数` 那一条省掉
                        // (有符号的 2 字节元素仍要补符号位 —— 与 `试发取字索引` / `发出读变量` 同一口径)。
                        发出($"取半字索引 {基} {下标} {基} 1");
                        if (绑定.有符号) 发出符号扩展(基, 2);
                        return 基;
                    }
                    发出($"LOAD_WORD_INDEX {基} {下标} 2");
                    return 基;
                }
            }
            string 地址 = 数组元素地址(绑定, 索引文本, 行号, 原文);
            string 目标 = 新临时();
            发出间接读(目标, 地址, 元素宽);
            return 目标;
        }

        /// <summary> 写数组/列表元素(按元素宽截断);2 字节用两条间接字节存储,避免踩到邻居 </summary>
        private void 写数组元素(string 源寄存器, 变量绑定C 绑定, string 索引文本, int 行号, string 原文, 地址位置? 值槽 = null)
        {
            int 元素宽 = 绑定.元素宽;
            // A3 + ISA 扩容批 3:4 字节走 `存字索引`(0x33)、2 字节走 `存半字索引`(0x55)、
            // 1 字节走 `存字节索引`(0x56) —— 都顶掉"缩放 + 相加 + 按宽间接写"那一串;
            // 半字 / 字节那两条**只写元素自己那几个字节**(老路本来就是按字节一条条写,越界与邻居行为一样)。
            if (元素宽 is 4 or 2 or 1 && (绑定.是列表 || 步进指针(绑定.名称, 索引文本, 元素宽, 0) is null))
            {
                string 下标 = 索引到寄存器(索引文本, 行号, 原文);
                输出下标检查(下标, 下标上界(绑定), 行号, 原文);
                var 列表 = 绑定.是列表 ? 按槽找列表(绑定.名称) : null;
                string 基 = 列表 != null ? 取列表基址(列表) : 取基址(绑定.名称);
                if (值槽 is { } 槽) 发出读变量(源寄存器, 槽);       // H71:算下标那一段可能 CALL,值从槽里补回来
                (string 指令名, int 缩放) = 元素宽 switch { 4 => ("存字索引", 2), 2 => ("存半字索引", 1), _ => ("存字节索引", 0) };
                发出($"{指令名} {基} {下标} {源寄存器} {缩放}");
                return;
            }
            // 地址先算完(这一段可能 CALL),再把值从槽里补回寄存器,最后才写 —— 顺序不能颠倒
            string 地址 = 数组元素地址(绑定, 索引文本, 行号, 原文);
            if (值槽 is { } 补) 发出读变量(源寄存器, 补);
            发出间接写(源寄存器, 地址, 元素宽);
        }

        /// <summary>
        /// 裸字段名 → "该写成什么"(H60):容器成员方法体里是 `容器名.字段`(**单例**自己)**或** `_收方.字段`
        /// (有收方时);结构方法体里一律 `_收方.字段`。两处上下文各一张表,这里按"先容器、后结构"问一遍。
        /// </summary>
        private bool 试字段全名(string 裸名, out string 全名)
        {
            全名 = "";
            if (_当前容器 is { } 容器 && 容器.字段全名.TryGetValue(裸名, out string? 容器全名))
            {
                全名 = 容器全名;
                return true;
            }
            if (_当前结构字段全名 is { } 结构映射 && 结构映射.TryGetValue(裸名, out string? 结构全名))
            {
                全名 = 结构全名;
                return true;
            }
            return false;
        }

        /// <summary> 解析可寻址位置:变量名 / 结构变量.字段 / 数组[常量下标];不是静态位置返回 null,非法则报错。
        /// 方法体内还可以直接写本体的字段名(先按普通名字找,找不到再补上 体名.) </summary>
        private 地址位置? 查位置(string 文本, int 行号, string 原文)
        {
            var 直接 = 查位置原样(文本, 行号, 原文);
            if (直接 != null) return 直接;
            if (试字段全名(文本.Trim(), out string 全名))
                return 查位置原样(全名, 行号, 原文);
            return null;
        }

        private 地址位置? 查位置原样(string 文本, int 行号, string 原文)
        {
            string 名 = 文本.Trim();
            if (名.Length == 0) return null;
            if (解析引用链(名, 行号) is not { } 链) return null;
            // 运行时算址的(引用基址 / 列表元素 / 运行期下标):不在这儿,交给 链读到寄存器 / 链写
            if (链.有运行期下标 || 链.是指针基址) return null;
            // `字符串` 字段/元素(8 字节小块)也不在这儿:当值用它就是"数据地址",交给 链读到寄存器
            if (是堆串链(链)) return null;
            if (链.是数组或列表)
            {
                // 字符串单独用是一个常见误写(它既不是数字,也不能整份塞进别处)—— 单独给说法
                if (查列表(名) is { 是字符串: true })
                    throw 报错(行号,
                        $"字符串 '{名}' 不能这样单独用(它不是数字):看内容用 输出({名}) / 输出行({名})," +
                        $"看长度用 {名}.长度(),取某个字节用 {名}[下标];要整份传给函数就当参数传(函数 f(字符串 s))",
                        $"'{名}' is a string and cannot be used as a value");
                throw 报错(行号, 链.是列表
                        ? $"列表 '{名}' 要带下标(如 {名}[0])或者用 {名}.长度() / {名}.添加(值)"
                        : $"数组 '{名}' 必须带下标使用,如 {名}[0]",
                    $"'{名}' needs an index");
            }
            if (链.是列表)
            {
                if (链.字段列表 is not null) return null;   // 字段里的列表:头在结构内存里,只能运行时算址
                var 列表 = 按槽找列表(链.绑定.名称)
                    ?? throw 报错(行号, $"列表 '{链.基名}' 的内部状态丢了(不该发生)", "lost list state");
                if (列表.动态) return null;          // 数据在池里、还会迁移:必须运行时算址
                // T6(2026-09-27 评测整改):这里也要带**符号性**(以前只给了槽/偏移/宽度)——
                // `短整数 列[]; 列.添加(-5); 输出行(列[0]);` 与数组那条路同一个东西,漏了 有符号
                // 就读成 65531(元素是紧排的 2 字节,不补符号位)。
                // R4-41:浮点那一格见 `地址位置.是浮点`。
                return new 地址位置(列表.数据槽.名称, 链.偏移, 链.整块宽, 链.声明宽, 链.有符号, 链是浮点标量(链));
            }
            return new 地址位置(链.绑定.名称, 链.偏移, 链.标量读宽, 链.声明宽, 链.有符号, 链是浮点标量(链));
        }

        /// <summary>
        /// 左值形态检查(不报错、只判形态):寄存器 / 已知变量 / 已知变量开头的"点.字段[下标]"链 / 方法体里省的体字段。
        /// 故意不在这里报详情错 —— 让后面的 输出赋值/求值 去报,免得报出重复或位置不对的错误。
        /// </summary>
        private bool 是已知左值(string 文本)
        {
            string 名 = 文本.Trim();
            if (解析寄存器(名, out _)) return true;
            if (查变量(名) != null) return true;
            if (名.Contains('.'))
                foreach (int 止 in 认长基名的切点(名))
                {
                    string 试 = 名[..止].Trim();
                    if (试.Length > 0 && 标识符带点正则.IsMatch(试) && 查变量(试) != null) return true;
                }
            int 切 = 名.IndexOfAny(['.', '[']);
            string 基名 = (切 < 0 ? 名 : 名[..切]).Trim();
            if (基名.Length == 0) return false;
            if (查变量(基名) != null) return true;
            if (试字段全名(基名, out _)) return true;
            return false;
        }

        /// <summary> 标量检查:整块(结构 / 结构元素 / 数组整名)不能当数字读写,给指路 </summary>
        private void 要求标量(地址位置 位置, int 行号, string 原文)
        {
            if (位置.宽度 is 1 or 2 or 4) return;
            throw 报错(行号, $"'{原文}' 是一整块({位置.宽度} 字节),不能当数字用:点到字段(如 .x),或者整体赋值(右 = 左)",
                $"'{原文}' is {位置.宽度} bytes; use a field or whole-block assignment");
        }

        private void 校验变量名(string 名称, int 行号)
        {
            // 模块(或容器)前缀不算在"用户写的名字"里:`数学.计数` 只看最后一段 计数
            string 裸名 = 名称[(名称.LastIndexOf('.') + 1)..];
            if (!标识符全词正则.IsMatch(裸名))
                throw 报错(行号, $"非法变量名: '{名称}'(名字要以文字或 `_` 开头,后面只能跟文字/数字/`_`;" +
                    $"要用模块里的名字就写 `模块.名字`)", $"invalid variable name: '{名称}'");
            if (解析寄存器(裸名, out _) || 寄存器形正则.IsMatch(裸名))
                throw 报错(行号, $"变量名不能与寄存器冲突: '{裸名}'。换个名字,例如 `{裸名}值`" +
                    $"(寄存器 R0~R15 是编译器与内联汇编在用的)",
                    $"variable name conflicts with a register: '{裸名}'");
            // 保留字:清单只有一份(中间层指令C.全部保留字 = 关键字 + 类型名 + 历史词 + 指令名),
            // 报错必须说清"它是什么"和"改成什么"(不然用户只能猜)
            if (中间层指令C.为什么是保留字(裸名) is { } 原因)
                throw 报错(行号, $"变量名不能用{原因}: '{裸名}'。换个名字,例如 `{中间层指令C.建议变量名(裸名)}`" +
                    $"(保留字清单见帮助『保留字』一节)",
                    $"'{裸名}' is a reserved word ({原因})");
            if (_结构表.ContainsKey(名称))
                throw 报错(行号, $"变量名不能与结构类型名冲突: '{名称}'。换个名字,例如 `{名称}值`," +
                    $"或者把结构类型改个名(类型名和变量名在同一片名字空间里)",
                    $"variable name conflicts with a struct type: '{名称}'");
            // H68-2:枚举名与枚举成员名同样占着名字空间 —— 变量叫 `绿` 会让表达式里的 `绿` 说不清指谁
            if (_枚举表.ContainsKey(名称))
                throw 报错(行号, $"变量名不能与枚举名冲突: '{名称}'。换个名字,例如 `{名称}值`," +
                    $"或者把枚举改个名(类型名和变量名在同一片名字空间里)",
                    $"variable name conflicts with an enum type: '{名称}'");
            if (查枚举成员常量(名称) is { } 占位)
                throw 报错(行号, $"变量名不能与枚举成员冲突: '{名称}'(`{占位.枚举名}.{名称}` 是编译期常量," +
                    $"同名之后表达式里的 `{名称}` 就说不清指谁了)。换个名字,例如 `{名称}值`",
                    $"variable name conflicts with an enum member: '{名称}'");
        }

        /// <summary> 从当前作用域起向外找 变量名 → 变量绑定(槽+结构类型);找不到返回 null。
        /// 顺序(**R4-11 改过,原先是"裸名一路找到底"**):① 函数 / 块里的局部与参数 →
        /// ② **正写在某个模块里时,本模块自己那一份(`模块.名`)优先** → ③ 最外层的裸名(顶层 / 全局)。
        /// ⚠ 第 ② 步为什么要提到前面:库(`包含` 进来的 `模块`)**内部**写一个裸名字时,原先会一路找到
        /// 调用方顶层的同名变量上 —— 于是调用方只要起个和库里内部变量同名的名字,库自己那份状态就被
        /// 顶掉(实测 `三维网格.hb` 的 `顶点数` 被调用方的 `顶点数` 顶掉:`清空()` 把调用方的 4 抹成 0,
        /// 实参传进去就是 0,而**编译器一声不响**)。模块内的裸名字应当是"自己人优先",
        /// 这与 `私有` 的口径一致;模块里找不到才落回顶层(有些库就是要读调用方的全局,那条路照旧)。 </summary>
        private 变量绑定C? 查变量(string 名)
        {
            string 键 = 名.Trim();
            // 正在算某次声明的初值:`这个名字`算"还没进作用域" —— 从**次内层**起找(初值里的同名引用落到外层)
            int 最内 = _作用域栈.Count - 1;
            if (_初值借出名.Length > 0 && string.Equals(_初值借出名, 键, StringComparison.OrdinalIgnoreCase)) 最内--;
            // ① 局部 / 参数:内层作用域(下标 ≥ 1;下标 0 是最外层,全局与模块变量都住那一层)
            for (int i = 最内; i >= 1; i--)
                if (_作用域栈[i].TryGetValue(键, out var 定义)) { 校验可取用(键, _当前源行号); return 定义; }
            // ② 模块自己人优先:只在这条语句真属于某个模块、且名字没带点的时候试
            if (_当前模块.Length > 0 && !键.Contains('.'))
            {
                string 全名 = _当前模块 + "." + 键;
                for (int i = 最内; i >= 0; i--)
                    if (_作用域栈[i].TryGetValue(全名, out var 定义)) { 校验可取用(键, _当前源行号); return 定义; }
            }
            // ③ 最外层的裸名(顶层变量 / 全局):本模块没有这一份时才落回这里
            //    (有些库就是要读调用方的全局,那条老路照旧放行)
            if (最内 >= 0 && _作用域栈[0].TryGetValue(键, out var 全局))
            {
                校验可取用(键, _当前源行号); return 全局;
            }
            return null;
        }

