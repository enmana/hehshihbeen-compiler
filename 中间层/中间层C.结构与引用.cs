        /// <summary> 把一个常量放进寄存器当操作数:循环里提过的常量/本语句前面装过的常量直接用(省一条装载、更省寄存器)</summary>
        private string 常量操作数寄存器(uint 常量, params string[] 避开)
        {
            if (常驻常量寄存器(常量) is { } 常驻) { _优化省下++; return 常驻; }
            // 同一条语句里前面已经装过这个常量?直接用那个寄存器(不然 31 / 0 / 0x80000000 这种会被装好几遍,寄存器一下就没了)
            // **但要避开"这次点名不许碰"的那些**:`偏置比较值` 就有这种场景 —— 它把 0x80000000 装进一个临时寄存器,
            // 再 `XOR 操作数 掩`;如果那个掩寄存器正好就是操作数自己(老代码会踩:缓存命中时不看 避开),
            // 发出来的就是 `XOR R13 R13`(恒 0),有符号比较整个算错。
            if (_语句常量 != null && _语句常量.TryGetValue(常量, out string? 已有)
                && !避开.Contains(已有, StringComparer.OrdinalIgnoreCase)) return 已有;
            string 暂存 = 选暂存寄存器(避开);
            // **登记到"本语句占用"里**:不然同一条语句后面再要临时寄存器时,选暂存寄存器 会把同一号又发一次 ——
            // 现象:`发出写变量` 的截断掩码被紧跟着的 MOV 覆盖,变成 `MOV R13 R14` + `AND R13 R13`(自己与自己):
            // 白两条指令,而且**截断丢了**(短整数 65535+1 会变成 65536 而不是 0)。
            _语句占用 ??= [];
            _语句占用.Add(暂存);
            _语句常量 ??= [];
            _语句常量[常量] = 暂存;
            输出装载常量(暂存, 常量);
            return 暂存;
        }

