        // ---------------- 地址取用:地址(变量|字段|数组元素|数组) ----------------
        private static readonly Regex 地址引用正则 = new(@"(?<![0-9A-Za-z_\u4E00-\u9FFF\u3400-\u4DBF])(地址|address)\s*\(", RegexOptions.Compiled | RegexOptions.IgnoreCase);

        /// <summary> 把 地址(x)/address(x) 就地换成"保存 x 地址的临时寄存器"(支持嵌套在表达式/实参里) </summary>
        private string 替换地址取用(string 文本, int 行号, string 原文)
        {
            文本 = 替换堆调用(文本, 行号, 原文);   // 申请/取字/存字 也在这儿就地换成寄存器(同一套文本替换手法)
            while (true)
            {
                var 匹配 = 地址引用正则.Match(文本);
                if (!匹配.Success) return 文本;
                int 左括号 = 匹配.Index + 匹配.Length - 1;
                int 右括号 = 找匹配右括号(文本, 左括号, 行号);
                string 参数 = 文本[(左括号 + 1)..右括号].Trim();
                if (参数.Length == 0)
                    throw 报错(行号, $"地址() 缺少参数: '{文本}'", $"address() needs an argument: '{文本}'");
                string 地址寄存器 = 取左值地址(参数, 行号, 原文);
                文本 = 文本[..匹配.Index] + 地址寄存器 + 文本[(右括号 + 1)..];
            }
        }

        /// <summary>
        /// H72(第353批):**只换 `地址(...)`、不换堆调用**的那一份 —— 专门给**条件**用。
        ///
        /// 条件里的 `&& / ||` 是**真短路**(右边那半句不该算),而 `替换堆调用` 是按**整条文本**
        /// 先把堆访问全算掉的 —— 提前算就等于短路失效。实测最小复现(5 行):
        /// ```
        /// 整数 走 = 5;
        /// 整数 父 = 0;
        /// 逻辑 果 = 假;
        /// 如果 (父 != 0 && 取字(父, 8) == 走) { 果 = 真; }
        /// ```
        /// 左边那句 `父 != 0` 明明为假,`取字(父, 8)` 还是先读了 `内存[父 - 4]`(堆头检查)
        /// ⇒ `字读取越界: 0xFFFFFFFC`(写 `树.hb` 的"中序后继"时撞上的:`父` 走到 0 就该收手)。
        /// 堆动作改由 `求值调用` 按 AST **懒算**(`求值堆动作当值`),短路那一支才真的不算。
        /// </summary>
        private string 替换地址取用跳过堆(string 文本, int 行号, string 原文)
        {
            while (true)
            {
                var 匹配 = 地址引用正则.Match(文本);
                if (!匹配.Success) return 文本;
                int 左括号 = 匹配.Index + 匹配.Length - 1;
                int 右括号 = 找匹配右括号(文本, 左括号, 行号);
                string 参数 = 文本[(左括号 + 1)..右括号].Trim();
                if (参数.Length == 0)
                    throw 报错(行号, $"地址() 缺少参数: '{文本}'", $"address() needs an argument: '{文本}'");
                string 地址寄存器 = 取左值地址(参数, 行号, 原文);
                文本 = 文本[..匹配.Index] + 地址寄存器 + 文本[(右括号 + 1)..];
            }
        }

        private int 找匹配右括号(string 文本, int 左括号, int 行号)
        {
            int 深度 = 0;
            for (int i = 左括号; i < 文本.Length; i++)
            {
                if (文本[i] == '(') 深度++;
                else if (文本[i] == ')' && --深度 == 0) return i;
            }
            throw 报错(行号, $"地址() 缺少 ')': '{文本}'", $"address() missing ')': '{文本}'");
        }

        /// <summary>
        /// "为什么取不到地址 + 怎么办"的说明。字符串与列表的改法不同,分开写:
        /// 字符串要整份传出去,就当参数传(`函数 f(字符串 s)`);要一个不动的地址,就用定长数组。
        /// 列表这一支按 R3-3(第310批,拍板取 d 档:保持禁止 + 补指引)把"那怎么办"的三条明路写全 ——
        /// 硬规矩 2 要求报错给改法;不能取地址是**有意设计**(列表长大要搬家),不是漏做。
        /// </summary>
        private string 取不到地址的说明(string 参数, string 名字) =>
            查列表(名字.Trim()) is { 是字符串: true }
                ? $"字符串 '{参数}' 的地址不能取(内容变长时数据会迁移,地址随之失效);要整份传出去请当参数传(函数 f(字符串 s)),要一个固定地址请用固定数组(例如 短整数 表[20])"
                : $"列表 '{参数}' 的地址不能取(长大时数据会迁移,地址就失效了);" +
                  "要一个不动的地址请改用定长数组(例如 短整数 表[20] —— 它声明后不搬家,`地址(表[i])` 与 `引用` 都能指向它);" +
                  "只是按下标读改请照旧写 `表[i]`(列表与数组取用完全一样,本来就不需要地址);" +
                  "要在几处之间共享同一份可改的数据请用变量 / 字段 / 数组元素,再拿 `引用` 指它";

        /// <summary> 取左值地址:整数组 → 基址;变量/字段/常量下标元素 → 基址+偏移;动态下标元素 → 运行时算址 </summary>
        private string 取左值地址(string 参数, int 行号, string 原文)
        {
            // 可写字符串参数:槽里是"头的地址",整份字符串的大小时刻会变 —— 取地址没有意义,给明路
            if (是出参(参数))
                throw 报错(行号, $"`出` 参数 '{参数}' 是整个字符串,不能取地址(要按字节看就写 {参数}[下标],要整份用就 输出({参数}) / " +
                    $"{参数}.长度(),要改就 {参数} = \"…\")", $"cannot take the address of a string parameter");
            // R6-1:引用链**优先**判。老入口 `解析数组引用` 只认 `表[下标]` 那一种形状(它按 `名.EndsWith(']')` 判尾),
            // `队[1].y` 这种"下标之后再点字段"的链会被它当成"老写法下标没闭合",报出一句**与事实无关**的
            // 「下标缺少 ']'」(第186批抓的 R6-1)。同一条路 `引用 整数 r = 队[0].x;` 也走这个入口。
            if (解析引用链(参数, 行号) is { } 链)
            {
                if (链.是列表) throw 报错(行号, 取不到地址的说明(参数, 参数),
                    $"cannot take the address of a dynamic container (it may move when it grows)");
                // 堆串字段/元素:它的"地址"就是**数据在堆里的地址**(字段本身那 8 字节是编译器的家事)。
                // `记录.名字[下标]`(H1:取出来的一个字)没有"地址"可言 —— 取一个 `文字` 的地址没有意义,直接拦住。
                if (链.串取字)
                    throw 报错(行号, $"'{参数}' 是取出来的**一个文字**,取它的地址没有意义。" +
                        $"要整串的地址用 `地址 p = {参数[..参数.LastIndexOf('[')]};`(再 取字(p, 字节偏移) 按字节看)",
                        $"cannot take the address of a single character: '{参数}'");
                if (是整段堆串链(链))
                {
                    string 数据 = 新临时();
                    发出间接读(数据, 串字地址(链, 行号, 参数), 4);
                    return 数据;
                }
                return 链地址(链, 行号, 参数);
            }
            // 不是引用链了,才轮到老入口 —— 但**只有基名真的存在**时才让它开口:名字本身不认识时,
            // 它那句「下标缺少 ']'」同样是误导(该说"这个地址取不到",不是"老写法下标没闭合")。
            // 列表会搬家(动态的长大时数据换地方),取它的地址迟早指空 —— 直接不让取,给条明路
            if (数组基名存在(参数) && 解析数组引用(参数, 行号) is { 绑定.是列表: true })
                throw 报错(行号, 取不到地址的说明(参数, 参数),
                    $"cannot take the address of a dynamic container (it may move when it grows)");
            if (查变量(参数.Trim()) is { 列表类型: not null })
                throw 报错(行号, 取不到地址的说明(参数, 参数.Trim()),
                    $"cannot take the address of a dynamic container");
            if (查位置(参数, 行号, 原文) is { } 位置)
            {
                if (解析帧槽(位置.槽, out int 帧偏移))
                {
                    string 帧地址 = 新临时();
                    发出($"取地址帧 {帧地址} {帧偏移 + 位置.偏移}");
                    return 帧地址;
                }
                string 地址 = 新临时();
                发出($"取地址 {地址} {位置.地址文本}");
                return 地址;
            }
            if (数组基名存在(参数) && 解析数组引用(参数, 行号) is { } 引用)   // 动态下标:运行时算元素地址
                return 数组元素地址(引用.绑定, 引用.索引, 行号, 原文);
            // G2(回调 / 事件的语言面):`地址(函数名)` = 那个函数的**代码地址**。
            // 它排在**最后**是有意的 —— 变量 / 字段 / 数组元素优先:同名时 `地址(x)` 仍指数据那一份,
            // 要拿代码地址就把函数改个名(或把变量改个名)。拿到地址以后按 `间接调用(地址, 实参…)` 调。
            if (试取函数代码地址(参数, 行号) is { } 码址) return 码址;
            throw 报错(行号, $"地址() 需要变量/字段/数组元素或函数名: '{参数}'" +
                "(函数名那一档取的是**代码地址**,要调它就写 `间接调用(地址, 实参…)`)",
                $"address() needs a variable, field, array element or function name: '{参数}'");
        }

        /// <summary>
        /// **G2:函数名 → 代码地址。** 解析不出来(没这个名字)给 null —— 让调用方照旧报"地址() 需要…"。
        /// 三个口径:①走的是**同一处**名字解析(`解析函数链路`,体里可省容器名 / 模块可省模块名 / 私有一并照管);
        /// ②`取地址` 那一档汇编指令本来就收标签(与 `调用 标签` 同一个标记表)⇒ 发出来的地址就是
        /// 直接调用那条 `CALL 标签` 的目标,**ISA / 机器码一个字没动**;
        /// ③反正 4 字节对齐(机器码定长),正好满足 `调用寄存器` 运行期那道对齐检查。
        /// </summary>
        private string? 试取函数代码地址(string 参数, int 行号)
        {
            string 名 = 参数.Trim();
            if (名.Length == 0 || 名.Contains('.') || 名.Contains('[') || 名.Contains('(')) return null;
            string 标签;
            try { 标签 = 解析函数链路(名, 行号).标签; }
            catch (编译异常C) { return null; }   // 库里没有这个名字 ⇒ 按"取不到地址"如实报
            string 码址 = 新临时();
            发出($"取地址 {码址} {标签}");
            return 码址;
        }

        /// <summary>
        /// 参数里"第一个 `[` 之前那一段"是不是一个已知变量。老入口 `解析数组引用` 一进门就先按
        /// `EndsWith(']')` 判"下标没闭合",名字本身不认识时那句话是误导 ⇒ 调用它之前先问这一句(R6-1)。
        /// </summary>
        private bool 数组基名存在(string 参数)
        {
            string 名 = 参数.Trim();
            int 方括号 = 名.IndexOf('[');
            return 方括号 > 0 && 查变量(名[..方括号].Trim()) is not null;
        }
        #endregion
    }
