        /// <summary>
        /// 上面那个的**语法树版**(R2-2,2026-09-21):条件改走 AST 之后,手上只有节点、没有那段文本了。
        /// 口径与文本版**完全一致**:先清池,再把树里显式写到的寄存器(R0~R15)与循环保留的寄存器记进占用。
        /// 只认 名字节点 —— 寄存器在源码里就是一个名字词元(`R0` / `R12`),树里也是那个节点。
        /// </summary>
        private void 准备语句占用(表达式节点C 节点)
        {
            _语句占用 = [];
            _语句常量 = [];
            var 待看 = new Stack<表达式节点C>();
            待看.Push(节点);
            while (待看.Count > 0)
            {
                switch (待看.Pop())
                {
                    case 名字节点C 名:
                        if (寄存器提及正则.IsMatch(名.名)) _语句占用.Add(名.名.ToUpperInvariant());
                        break;
                    case 一元节点C 一元: 待看.Push(一元.子); break;
                    case 二元节点C 二元: 待看.Push(二元.左); 待看.Push(二元.右); break;
                    case 三目节点C 三目:
                        待看.Push(三目.条件); 待看.Push(三目.真); 待看.Push(三目.假);
                        break;
                    case 调用节点C 调用:
                        foreach (var 实参 in 调用.实参) 待看.Push(实参);
                        break;
                }
            }
            // 循环里提到外面的不变量/常量占着的寄存器:整段循环体(含自成一段)都不许再分配它们
            foreach (var 层 in _循环保留栈)
                foreach (string r in 层.寄存器) _语句占用.Add(r);
        }

