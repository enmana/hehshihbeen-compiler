using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace hehshihbeen_compiler
{
    /// <summary> 中间层展开器的一部分:方法容器(M7f):`方法 名()` 与 `静态 方法 名(字段…)`。(第88批从 `中间层C.cs` 按 region 原样搬出,逻辑一字未改) </summary>
    internal partial class 中间层展开器
    {
        #region 方法容器(M7f):`方法 名()` = 代码的名字空间;`静态 方法 名(字段...)` = 带常驻状态
        /// <summary> 找与 `开括号` 配对的 '}' 的下标(伪行表里 { } 已经各占一行) </summary>
        private int 找块结束(int 开括号, int 行号)
        {
            int 深度 = 0;
            for (int i = 开括号; i < _伪行表.Count; i++)
            {
                if (_伪行表[i] == "{") 深度++;
                else if (_伪行表[i] == "}") { 深度--; if (深度 == 0) return i; }
            }
            throw 报错(行号, "缺少 '}'", "missing '}'");
        }

        private bool 下一行是块(int 行下标) => 行下标 + 1 < _伪行表.Count && _伪行表[行下标 + 1] == "{";

        /// <summary> 裸成员头:`名(参数...)`,整行就是这个形状(没有 函数/方法 前缀) </summary>
        private static bool 是裸函数头(string 行) => 标识符带点正则.IsMatch(行.Trim()) == false && 解析签名(行) != null;

        /// <summary> `返回` / `return` —— 它不在关键字表里(是语句),比较时单独认 </summary>
        private static bool 是返回词(string 词) =>
            词 == "返回" || string.Equals(词, "return", StringComparison.OrdinalIgnoreCase);
        /// <summary> 从 `名(参数...)` 里取名字;形状不对返回 null(预扫/成员判定用,不报错)。
        /// 允许尾缀返回类型:`名(参数) 返回 类型`。 </summary>
        private static string? 解析签名(string 行)
        {
            string 文本 = 行.Trim();
            int 左 = 文本.IndexOf('(');
            int 右 = 文本.LastIndexOf(')');
            if (左 <= 0 || 右 <= 左) return null;
            string 尾 = 文本[(右 + 1)..].Trim();
            if (尾.Length > 0)
            {
                string 尾首词 = 取首词(尾);
                if (!是返回词(尾首词)) return null;
                if (取首词(尾[尾首词.Length..].Trim()).Length == 0) return null;
            }
            string 名 = 文本[..左].Trim();
            return 标识符全词正则.IsMatch(名) ? 名 : null;
        }

        /// <summary>
        /// 容器头 → 容器名;不是容器返回 null(预扫用,不报错)。
        /// **H46 起的口径**:`静态 方法 名(...)` = 容器(参数即常驻字段;不带 `返回 类型` 时);
        /// **`方法` 一个人只管"过程"**(有参数、没参数、写不写 `返回 类型` 都是普通函数)——
        /// 从前"空括号 = 容器"那条判据撤了:空括号的普通过程(`方法 记一次() { … }`)是常见写法,
        /// 而"容器"有一个 `静态` 就够标了,一个词管一件事。
        /// </summary>
        private static string? 试读容器名(string 行)
        {
            string 首词 = 取首词(行);
            string 余下 = 行[首词.Length..].Trim();
            bool 静态 = 中间层C.到英文关键字(首词) == "static";
            if (!静态) return null;                 // 非静态:一律不是容器(交给 处理函数声明)
            string 次词 = 取首词(余下);
            if (中间层C.到英文关键字(次词) == "method") 余下 = 余下[次词.Length..].Trim();
            return 解析签名(余下);
        }

        /// <summary>
        /// 方法声明(**H46 起一个词只管一件事**):
        ///   · `方法 名(...)`(有没有参数、写不写 `返回 类型` 都一样)= **普通过程/函数**;
        ///   · `静态 方法 名(参数)` = **容器**(名字空间):参数即常驻字段(零初值),
        ///     容器里的普通语句是"程序开头跑一次的初始化脚本";写了尾缀 `返回 类型` 的仍是普通函数。
        /// 有状态容器编译成"一个内部结构类型 + 一个常驻结构变量",所以 `棋盘.宽` 走的是既有字段寻址。
        /// </summary>
        private void 处理方法声明(ref int 位置, bool 静态)
        {
            int 行号 = _伪行号表[位置];
            string 头行 = _伪行表[位置].Trim();
            string 首词 = 取首词(头行);
            string 余下 = 头行[首词.Length..].Trim();
            if (中间层C.到英文关键字(首词) == "static")
            {
                静态 = true;
                string 次词 = 取首词(余下);
                if (中间层C.到英文关键字(次词) == "method") 余下 = 余下[次词.Length..].Trim();
            }
            int 左 = 余下.IndexOf('(');
            int 右 = 余下.LastIndexOf(')');
            // 头行可能带尾缀返回类型:`静态 方法 棋盘(short 边) 返回 整数 {` —— 那种是普通函数,交给 处理函数声明
            if (左 > 0 && 右 > 左 && 右 < 余下.Length - 1
                && 是返回词(取首词(余下[(右 + 1)..].Trim())))
            {
                处理函数声明(ref 位置);
                return;
            }
            // **非静态的 `方法` 一律是普通函数**(容器必须有那个 `静态`)—— 摆在下面的"括号形状"检查
            // **前面**:尾缀写错(`方法 f() 误写 整数`)要报"函数头参数表后面只能写 `返回 类型`",
            // 而不是拿容器那句"状态写在括号里"去糊弄。
            if (!静态)
            {
                处理函数声明(ref 位置);
                return;
            }
            if (左 <= 0 || 右 != 余下.Length - 1)
                throw 报错(行号, $"方法名后面要写括号(状态写在括号里): '{头行}'", $"expected parentheses after the method name: '{头行}'");
            string 容器名 = 余下[..左].Trim();
            string 参数串 = 余下[(左 + 1)..右].Trim();
            if (!标识符全词正则.IsMatch(容器名))
                throw 报错(行号, $"方法名非法: '{容器名}'", $"invalid method name: '{容器名}'");

            if (_容器表.ContainsKey(容器名))
                throw 报错(行号, $"方法重复定义: '{容器名}'", $"duplicate method container: '{容器名}'");
            if (中间层C.到英文关键字(容器名) != null || 类型C.是类型名(容器名) || 指令C.取指令码表(容器名) != null)
                throw 报错(行号, $"方法名不能与关键字/类型/指令重名: '{容器名}'", $"name conflicts: '{容器名}'");

            位置++;
            if (位置 >= _伪行表.Count || _伪行表[位置] != "{")
                throw 报错(行号, "方法声明后缺少 '{'", "expected '{' after the method declaration");
            if (_当前函数 != null) throw 报错(行号, "方法容器不能定义在函数里", "cannot declare a method container inside a function");
            if (_当前容器 != null) throw 报错(行号, "方法容器不能嵌套定义", "nested method containers are not allowed");
            // 模块里的容器也带模块前缀(`数学.棋盘.面积`),这样两个库各有一个同名容器也不会撞
            容器名 = 限定名(容器名);
            if (_本句私有 || _本句程序集) 记私有(容器名);
            处理容器块(ref 位置, 行号, 静态, 容器名, 参数串.Length == 0 ? null : 参数串);
        }

        /// <summary> 容器体:先收字段(容器自己的参数 + 第一层的 `类型 名 [= 常量]`),再处理成员方法与初始化语句 </summary>
        private void 处理容器块(ref int 位置, int 头行号, bool 静态, string 容器名, string? 参数串)
        {
            int 开括号 = 位置;                       // "{" 的下标
            int 结束 = 找块结束(开括号, 头行号);
            var 容器 = new 方法容器C { 名称 = 容器名, 静态 = 静态 };

            // ---- 第一遍:收字段 ----
            var 字段表 = new List<结构字段C>();
            var 初值表 = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            int 偏移 = 0;
            if (参数串 != null)
            {
                foreach (string 段 in 参数串.Split(','))
                {
                    string s = 段.Trim();
                    if (s.Length == 0) continue;
                    // H52:括号里的字段与结构字段**同一把尺子**(基础类型 / var / 结构 / 字符串 / 数组 / 列表)
                    var 字段 = 解析字段行(s, 头行号, 偏移, 允许初值: false, 场合: "括号里的字段", out _);
                    if (字段表.Any(f => f.名称 == 字段.名称))
                        throw 报错(头行号, $"字段重复: '{字段.名称}'", $"duplicate field: '{字段.名称}'");
                    字段表.Add(字段);
                    偏移 += 字段.宽度;
                }
            }
            for (int i = 开括号 + 1; i < 结束; i++)
            {
                string 行 = _伪行表[i];
                if (行 == "{") { i = 找块结束(i, 头行号); continue; }   // 跳过成员体
                if (行 == "}") continue;
                string 首词 = 取首词(行);
                string? 词 = 中间层C.到英文关键字(首词);
                if (词 is "method" || 是成员头(i)) continue;
                if (词 is "static") throw 报错(_伪行号表[i], "方法容器不能嵌套定义", "nested method containers are not allowed");
                if (词 == "struct") throw 报错(_伪行号表[i], "结构请写在容器外面", "declare structs outside method containers");
                if (!是声明行(行)) continue;          // 其余语句 = 初始化脚本,第二遍再展开

                // H52:第一层的字段也走结构字段那一把尺子(数组 / 字符串 / 结构 / 列表都收);
                // 初值只有**标量**收(非标量的初始化写到容器第一层的脚本里,那句话本来就在那儿)
                var 字段 = 解析字段行(行, _伪行号表[i], 偏移, 允许初值: true, 场合: "容器字段", out string 初值文本);
                if (字段表.Any(f => f.名称 == 字段.名称))
                    throw 报错(_伪行号表[i], $"字段重复(注意括号里的参数也是字段): '{字段.名称}'", $"duplicate field (parameters are fields too): '{字段.名称}'");
                if (初值文本.Length > 0)
                {
                    // H68-2:枚举成员也是常量(`颜色 落子 = 蓝;`)—— 先折成十进制原文再走同一套范围检查
                    string 折后 = 折成员常量(初值文本, _伪行号表[i], 查枚举类型(字段.类型名)?.名称 ?? "");
                    if (!解析无符号32(折后, out uint 初值) && !解析负常量32(折后, out 初值))
                        throw 报错(_伪行号表[i], $"字段初值必须是常量: '{初值文本}'", $"field initializer must be a constant: '{初值文本}'");
                    if (初值 > 类型C.最大值(字段.宽度))
                        throw 报错(_伪行号表[i], $"常量 {初值} 超出 {字段.类型名} 范围", $"constant {初值} out of range for {字段.类型名}");
                    初值表[字段.名称] = 初值.ToString();
                }
                字段表.Add(字段);
                偏移 += 字段.宽度;
            }

            // ---- 建"常驻变量 + 内部结构类型" ----
            // H46:字段可以一个都没有 —— 那就是**无状态容器**(纯名字空间:`静态 方法 数学() { 平方(…) {…} }`)。
            // 从前这里报"静态方法没有任何状态",撤了:容器靠 `静态` 标之后,"没有状态"不再是错,
            // 而且"有成员方法"本身就是它的用处(示例08 的 `数学工具` 就是这种)。
            if (静态)
            {
                string 内部结构名 = "_方法_" + 容器名;
                var 结构类型 = new 结构类型C(内部结构名, 字段表);
                _结构表[内部结构名] = 结构类型;
                校验变量名(容器名, 头行号);
                if (当前作用域.ContainsKey(容器名))
                    throw 报错(头行号, $"方法名与已有变量重名: '{容器名}'", $"name conflicts with a variable: '{容器名}'");
                var 定义 = 新槽(结构类型.总宽度);
                当前作用域[容器名] = new 变量绑定C(定义, 结构类型);
                // 调试名字表:有状态容器本身也算一个"变量"(调试器可以展开看它那些常驻字段)
                // H52:字段项要带上"是数组 / 是字符串 / 是列表 / 元素几个"—— 调试面板才展开得了
                var 字段项表 = 字段表.Select(字段项).ToList();
                _名字表.结构[内部结构名] = 字段项表;
                // ---- H60 步①:容器名**同时是源码里写得出来的类型名**(像"类名 = 静态单例名")----
                // 内部结构名照旧是 `_方法_计数器`(调试与机器口径一字不改),这一份只是**别名入口**
                // ⇒ 源码里 `计数器 计数;` 能声明第二份(与 `_方法_计数器 计数;` 编出来的是同一样东西)。
                // 为什么摆在 `校验变量名` **之后**:那一步正是拿 `_结构表` 判"变量名撞类型名"的,
                // 别名先登记的话,容器自己的单例名会被自己拦住。
                _结构表[容器名] = 结构类型;
                _名字表.结构[容器名] = 字段项表;
                _名字表.容器类型.Add(容器名);
                记声明出处(容器名, 头行号);     // 以后拿它当结构名重名时,报错带得出"这一处在哪一行"
                _名字表.变量.Add(new 名字项C
                {
                    名字 = 容器名,
                    类型名 = 内部结构名,
                    宽度 = 定义.宽度,
                    是全局 = true,
                    槽 = 定义.名称,
                    声明行 = 头行号,
                    声明文件 = _当前文件,
                });
                记可见性(容器名);     // C19:补全按它筛容器名 / 容器成员的可见性
                foreach (var 字段 in 字段表)
                    if (初值表.TryGetValue(字段.名称, out string? 初值))
                        输出赋值($"{容器名}.{字段.名称} = {初值}", 头行号);
                foreach (var 字段 in 字段表) 容器.字段全名[字段.名称] = 容器名 + "." + 字段.名称;
                // 编译页把"平铺字段表"写出来(与结构同一份说明):嵌套 / 数组 / 列表一眼看全每个字段落在哪
                if (字段表.Count > 0) _编译提示.Add($"方法容器 {容器名}:{偏移} 字节 → {平铺字段说明(结构类型)}");
            }
            // (H46:这里原来还有一条"非静态容器不能有常驻字段"的报错 —— 非静态的 `方法` 现在一律走
            //  函数那条路,根本到不了这个容器分支,那条报错是够不着的死壳,连壳一起删了。)
            _容器表[容器名] = 容器;

            // ---- 第二遍:成员方法 + 初始化脚本 ----
            位置 = 开括号 + 1;
            var 初始化 = new List<string>();
            var 上层容器 = _当前容器;
            _当前容器 = 容器;
            _缓冲栈.Push(初始化);                    // 容器第一层的普通语句先收进"初始化脚本"缓冲
            try
            {
                while (位置 < 结束)
                {
                    string 行 = _伪行表[位置];
                    if (行 == "{") throw 报错(_伪行号表[位置], "意外的 '{'", "unexpected '{'");
                    if (是成员头(位置) || 中间层C.到英文关键字(取首词(行)) is "method")
                    {
                        处理函数声明(ref 位置);          // 成员(裸名字头也能被 解析函数头 认出来)
                        continue;
                    }
                    if (是字段声明行(行)) { 位置++; continue; }   // 第一遍已登记(初值也发过了)
                    处理语句(ref 位置);                            // 初始化脚本
                }
            }
            finally
            {
                _缓冲栈.Pop();
                _当前容器 = 上层容器;
            }
            if (初始化.Count > 0) 插入程序开头(初始化);
            位置 = 结束 + 1;
        }

        /// <summary>
        /// H60 步②:容器字段的"裸名字 → 怎么写"这张表要**按场合换一换**。
        ///   · 容器第一层的初始化脚本 = 那个**单例**自己的家事 ⇒ `字段` 写成 `容器名.字段`;
        ///   · 成员方法体里 ⇒ 必须走**收方**(隐藏的第一个参数,`引用 那个内部结构`)⇒ `字段` 写成 `_收方.字段`。
        /// 换法就是把这本表的**值**全改一遍(键不动);进出方法体各换一次,方法体里嵌套的块照旧有效。
        /// </summary>
        private static void 换字段映射(方法容器C 容器, bool 走收方)
        {
            foreach (string 字段名 in 容器.字段全名.Keys.ToList())
                容器.字段全名[字段名] = 走收方 ? 收方参数名 + "." + 字段名 : 容器.名称 + "." + 字段名;
        }

        /// <summary> 是否是"基础类型 / 枚举名(H68-2)/ var 的字段声明行"(容器第一遍收过的那类) </summary>
        private bool 是字段声明行(string 行)
        {
            string 首词 = 取首词(行);
            return 是声明行(行) && (类型C.解析(首词) != null || 是枚举名(首词) || 中间层C.到英文关键字(首词) == "var");
        }

        /// <summary> 容器第一层的成员头(裸 `名(...)` 且下一行是 `{`;关键字开头的行不算) </summary>
        private bool 是成员头(int 行下标)
        {
            if (!下一行是块(行下标)) return false;
            string 行 = _伪行表[行下标];
            string 首词 = 取首词(行);
            if (中间层C.到英文关键字(首词) is "method") return true;
            if (中间层C.到英文关键字(首词) != null) return false;   // 如果/当/循环/遍历… 交给 处理语句
            return 解析签名(行) != null;
        }

        /// <summary>
        /// "程序开头跑一次"的代码(字符串初始化 / 容器初始化脚本)先**拼接**,等整篇展开完了再统一插到序言后面。
        /// 为什么不能当场 Insert:展开过程中缓冲栈会变(函数体/流程块各自压一层),按"行数下标"插会插进**别的缓冲**,
        /// 或者插到当前语句中间 —— 用户实测过:函数体里的一个字符串,初始化代码插进了主程序中间,把帧里的参数写坏
        /// (现象:`输出行(n * 2)` 打出字符串的字节)。缓冲到最后统一插,谁都插不错。
        /// </summary>
        private void 插入主程序开头(List<string> 行表) => _开头初始化.AddRange(行表);

        /// <summary> 容器(静态方法)的初始化脚本走同一份"程序开头"清单(见 插入主程序开头)</summary>
        private void 插入程序开头(List<string> 行表) => _开头初始化.AddRange(行表);
        #endregion
    }
}
