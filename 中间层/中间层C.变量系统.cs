        /// <summary> 可寻址位置:数据槽标签 + 字节偏移 + 宽度(普通变量偏移 0,结构字段为字段偏移) </summary>
        /// <param name="声明宽">
        /// 声明宽度(0 = 与 宽度 相同)。C 档优化下 `短整数` 变量是"4 字节槽装 2 字节值",
        /// 这时 宽度=4、声明宽=2 → 写进去之前要先按声明宽处理(见 要截断):
        /// **无符号补 0**(掩码)、**有符号补符号位**(符号扩展),这样"读的时候一条取字就够"。
        /// </param>
        /// <param name="有符号">声明类型是不是有符号(整数/短整数)。1 字节的 字节/字符/逻辑 都是无符号。</param>
        /// <param name="是浮点">
        /// **R4-41(2026-10-10)**:这一格是一个 **IEEE754 单精度位模式**(`浮点` 变量 / `浮点` 字段 /
        /// `浮点` 数组元素)。少了它,"静态位置"这一条读法(结构字段 `点.x`、常量下标元素 `表[3]`)
        /// 会把浮点当整数用下去 —— 位模式 × 1000.0 = NaN(见 `是浮点标量引用`)。
        /// </param>
        private readonly record struct 地址位置(string 槽, int 偏移, int 宽度, int 声明宽 = 0, bool 有符号 = false,
            bool 是浮点 = false)
        {
            public string 地址文本 => 偏移 == 0 ? 槽 : $"{槽}+{偏移}";
            public string 地址文本加(int 额外偏移) => 偏移 + 额外偏移 == 0 ? 槽 : $"{槽}+{偏移 + 额外偏移}";
            /// <summary> 宽槽装窄值:存值前要按声明宽处理</summary>
            public bool 要截断 => 声明宽 > 0 && 声明宽 < 宽度;
            /// <summary> 有效的那几字节的宽度(有声明宽就用声明宽)</summary>
            public int 有效宽 => 声明宽 > 0 && 声明宽 < 宽度 ? 声明宽 : 宽度;
            /// <summary> 读出来的值是不是"已知高半为 0"(紧排无符号窄类型读的时候本来就掩过码)</summary>
            public bool 读即零扩展 => 宽度 < 4 || 要截断;
            /// <summary> 紧排的窄**有符号**值:读出来要补符号位(3 字节及以上没有这种情况)</summary>
            public bool 读要符号扩展 => 有符号 && 有效宽 is 2;
            /// <summary> 宽槽装**有符号**窄值:写进去要补符号位</summary>
            public bool 写要符号扩展 => 有符号 && 要截断 && 声明宽 is 2;
        }

        /// <summary> 正在算"声明初值"的那个名字(声明符在初值之后才进作用域)。
        /// HB 的标识符不分大小写:`整数 m = 62 - 位长(M)` 里的 `M` 与 `m` 是同一个名字,
        /// 求初值期间查变量要**跳过最内层那一格**,让同名的外层绑定(参数/全局)接住。 </summary>
        private string _初值借出名 = "";

        /// <summary>
        /// `引用 点 p = 位置` / `引用 短整数 n = 某数` / `引用 短整数 表 = 某数组`:
        /// 分配一个 4 字节槽(全局进数据段,函数里进帧),把目标的地址存进去。
        /// **必须写初值**(不写就报错)—— 免得出现"指空(地址 0)"这种最难查的错。
        /// </summary>
        private void 处理引用声明(string 类型词, string 名称, string 初值文本, int 行号)
        {
            函数有引用();
            if (初值文本.Length == 0)
                throw 报错(行号, $"引用 '{名称}' 要写清指向谁:引用 {类型词} {名称} = 某个变量",
                    $"reference '{名称}' needs a target");
            if (名称.Contains('[') || 名称.Contains('<'))
                throw 报错(行号, $"引用先不支持数组/列表: '{名称}'。要指向一整个数组就写 引用 {类型词} {名称} = 某数组",
                    $"array/list references are not supported: '{名称}'");
            校验变量名(名称, 行号);
            string 注册名 = 声明注册名(名称);
            记私有(注册名);
            if (当前作用域.ContainsKey(注册名))
                throw 报错(行号, $"变量 '{注册名}' 在本作用域重复声明 —— {上一处声明(注册名)}{同名怎么办("变量")}",
                    $"duplicate variable '{注册名}' in this scope");
            if (_当前函数 == null) 记声明出处(注册名, 行号);      // 顶层声明:重复时能报出两处位置

            结构类型C? 结构 = null;
            类型C.类型定义? 基本 = null;
            int 元素宽 = 0, 元素个数 = 0;
            结构类型C? 元素结构 = null;
            int 整块宽;
            string 指向类型名;
            if (类型C.解析(类型词) is { } 基本类型)
            {
                基本 = 基本类型;
                整块宽 = 基本类型.宽度;
                指向类型名 = 基本类型.中文;
            }
            else if (中间层C.到英文关键字(类型词) == "var")
            {
                整块宽 = 类型C.字宽度;
                指向类型名 = "32位字";
            }
            else if (查枚举类型(类型词) is { } 引用枚举)      // H68-2:枚举也能被引用(底层 4 字节有符号整数)
            {
                基本 = 类型C.枚举底层;
                整块宽 = 基本.Value.宽度;
                指向类型名 = 引用枚举.名称;
            }
            else if (查结构类型(类型词) is { } 已声明)
            {
                结构 = 已声明;
                整块宽 = 已声明.总宽度;
                指向类型名 = 已声明.名称;
            }
            else
                throw 报错(行号, $"引用指向的类型不认识: '{类型词}'(基础类型 / var / 已声明的结构)", $"unknown reference target type: '{类型词}'");

            变量槽定义 定义;
            if (_当前函数 is { } 函数)
            {
                if (函数.局部偏移 + 4 > 函数帧大小)
                    throw 报错(行号, $"方法 '{函数.名称}' 的帧超出:放不下引用 '{名称}' —— 已经用到 {函数.局部偏移} 字节," +
                        $"再加这个 4 字节就是 {函数.局部偏移 + 4} 字节,上限 {函数帧大小} 字节。" + 帧超限改法(),
                        $"function frame overflow in '{函数.名称}'");
                定义 = new 变量槽定义(帧槽(函数.局部偏移), 4);
                函数.局部偏移 += 4;
            }
            else 定义 = 新槽(4);

            // 先把地址算出来,再存进这个槽(引用变量和参数靠它拿基址)
            准备语句占用($"引用 {名称} = {初值文本}");
            // 全局的引用不许指向局部(函数返回后帧作废)
            bool 引用在帧内 = _当前函数 != null;
            if (!引用在帧内) 检查地址没被存起来(初值文本, 行号, "全局的引用");
            string 地址 = 取左值地址(初值文本, 行号, $"引用 {名称} = {初值文本}");
            var 引用类型 = new 引用类型C(指向类型名, 结构, 整块宽, 元素宽, 元素个数, 元素结构);
            当前作用域[注册名] = new 变量绑定C(定义, null, null, null, 引用类型, 0, false, 类型C.有符号(类型词));
            发出写变量(地址, 定义);
            登记名字(注册名, 定义, 基本, null, null, 行号, 引用: 引用类型);
            _编译提示.Add($"引用 {注册名}:指向 {指向类型名}({整块宽} 字节) → 只占 4 字节地址,访问走间接");
        }

        /// <summary> 变量/数组声明(语句形式):类型前置 / 结构名 / 变量|var </summary>
        private void 处理声明(ref int 位置)
        {
            处理声明文本(_伪行表[位置], _伪行号表[位置], 位置);
            位置++;
        }

        /// <summary>
        /// **找一条回调声明**(`间接调用` 要用它):先按写下来的名字找,再按**本模块全名**找一次。
        ///
        /// 为什么要有这一手(与 `查变量` 同一个道理):模块里的顶层回调登记的是**带前缀的全名**
        /// (`定时.处理表0`),而方法体里引用它写的是裸名(`处理表0`)——
        /// 只按裸名查会报"不是编译器认得的回调",明明声明就在同一个模块里(实测定到:
        /// `Sample\库\定时.hb` 一写就撞上)。带点的名字一律原样,不去补前缀。
        /// </summary>
        private bool 试查回调表(string 名, out string? 指向函数)
        {
            if (_回调表.TryGetValue(名, out 指向函数)) return true;
            if (_当前模块.Length > 0 && !名.Contains('.'))
                return _回调表.TryGetValue(_当前模块 + "." + 名, out 指向函数);
            return false;
        }

        /// <summary>
        /// **G2:`回调 名字 = 地址(函数名);`** —— 4 字节的代码地址槽 + 一条"它指向哪个函数"的登记。
        ///
        /// 为什么要有这一个类型名:`间接调用(回调变量, 实参…)` 那一步必须知道**被调方的参数表**
        /// (帧布局、实参个数、引用参数怎么传),而运行期那个地址认不出类型 —— 声明时把函数写清,
        /// 调用点就有据可依(参数表全在编译期核对,与直接调用同一把尺子)。
        /// 存储上与 `整数` 一模一样(4 字节、有符号),所以 `地址(…)` 的比较、传参、赋值照旧全是老路。
        /// </summary>
        private void 处理回调声明(string 名称, string 初值文本, int 行号)
        {
            if (_预扫声明中) return;      // 预扫只登记一次(它与引用同一档:登记时就要算代码地址,那一步要发码)
            if (初值文本.Length == 0)
                throw 报错(行号, $"回调 '{名称}' 要写清指向哪个函数:回调 {名称} = 地址(函数名);",
                    $"callback '{名称}' needs 地址(函数名) as its initializer");
            if (名称.Contains('[') || 名称.Contains('<'))
                throw 报错(行号, $"回调不支持数组/列表: '{名称}'", $"a callback is a single 4-byte value: '{名称}'");
            校验变量名(名称, 行号);
            string 注册名 = 声明注册名(名称);
            记私有(注册名);
            if (当前作用域.ContainsKey(注册名))
                throw 报错(行号, $"变量 '{注册名}' 在本作用域重复声明 —— {上一处声明(注册名)}{同名怎么办("变量")}",
                    $"duplicate variable '{注册名}' in this scope");
            if (_当前函数 == null) 记声明出处(注册名, 行号);      // 顶层声明:重复时能报出两处位置
            // 认初值里那个函数名(整条初值就是 `地址(函数名)`),登记给 `间接调用` 用
            string 指向 = 回调初值函数名(初值文本, 行号, 名称);
            if (指向.Length > 0) _回调表[注册名] = 指向;

            变量槽定义 定义;
            if (_当前函数 is { } 函数)
            {
                if (函数.局部偏移 + 4 > 函数帧大小)
                    throw 报错(行号, $"方法 '{函数.名称}' 的帧超出:放不下回调 '{名称}' —— 已经用到 {函数.局部偏移} 字节," +
                        $"再加这个 4 字节就是 {函数.局部偏移 + 4} 字节,上限 {函数帧大小} 字节。" + 帧超限改法(),
                        $"function frame overflow in '{函数.名称}'");
                定义 = new 变量槽定义(帧槽(函数.局部偏移), 4);
                函数.局部偏移 += 4;
            }
            else 定义 = 新槽(4);

            准备语句占用($"回调 {名称} = {初值文本}");
            // `地址(函数名)` 走与别处**同一处**展开(`替换地址取用`):它把整段就地换成"装着代码地址的临时"
            string 码址 = 替换地址取用(初值文本, 行号, $"回调 {名称} = {初值文本}");
            当前作用域[注册名] = new 变量绑定C(定义, null, null, null, null, 0, false, true);
            发出写变量(码址, 定义);
            登记名字(注册名, 定义, null, null, null, 行号);
            _编译提示.Add(指向.Length > 0
                ? $"回调 {注册名}:指向 {指向}(4 字节代码地址) → 用 `间接调用({注册名}, 实参…)` 调"
                : $"回调 {注册名}:4 字节代码地址");
        }

        /// <summary> 回调初值 `地址(函数名)` / `address(函数名)` 里那个函数名;写法不对(不是取址)给报错 </summary>
        private string 回调初值函数名(string 初值文本, int 行号, string 回调名)
        {
            string 文本 = 初值文本.Trim();
            var 匹配 = 地址引用正则.Match(文本);
            if (!匹配.Success || 匹配.Index != 0)
                throw 报错(行号, $"回调 '{回调名}' 的初值要写成 `地址(函数名)`:现在是 '{初值文本}'。" +
                    $"要一个指向函数 f 的回调就写 回调 {回调名} = 地址(f);",
                    $"a callback must be initialized with 地址(function-name): '{初值文本}'");
            int 左 = 匹配.Index + 匹配.Length - 1;
            int 右 = 找匹配右括号(文本, 左, 行号);
            string 参数 = 文本[(左 + 1)..右].Trim();
            if (文本[(右 + 1)..].Trim().Length > 0)
                throw 报错(行号, $"回调 '{回调名}' 的初值只能是 `地址(函数名)` 一项: '{初值文本}'",
                    $"a callback initializer must be exactly 地址(function-name): '{初值文本}'");
            return 参数;
        }

        /// <summary>
        /// 变量声明(文本版,for 头也复用): `类型 名 [= 常量]` / `结构名 名` / `变量|var 名 [= 常量]`。
        /// 声明是普通语句:进循环体每次都重新执行(带初值则重新写回);常量按类型宽度做范围检查。
        /// 函数内声明则分配在当前帧(FP 相对)。
        /// </summary>
        private void 处理声明文本(string 内容, int 行号, int 伪行 = -1)
        {
            // 引用声明:`引用 点 p = 位置` —— 槽里存的是地址(4 字节),以后 p.x 走间接寻址
            if (引用声明拆解(内容, out string 引用类型词, out string 引用名, out string 引用初值, out _))
            {
                if (_预扫声明中) return;      // 引用登记时要算目标地址(发码):不进预扫,照旧"声明在前"
                处理引用声明(引用类型词, 引用名, 引用初值, 行号);
                return;
            }
            string 首词 = 取声明类型词(内容);    // 类型名 / 结构名(可带模块前缀)/ 变量|var / 字符串
            bool 声明是字符串 = 首词 is "字符串" || string.Equals(首词, "string", StringComparison.OrdinalIgnoreCase);
            string 余下0 = 内容[首词.Length..].Trim();
            int 等号0 = 余下0.IndexOf('=');
            string 名称0 = (等号0 >= 0 ? 余下0[..等号0] : 余下0).Trim();
            // 字符串:`字符串 s = "字面量";` —— 底层是"动态字符列表"(头三槽 + 池里的数据)
            // 带 `[个数]` 的是另一回事(`字符串 名单[10]`):元素 8 字节(数据地址 + 容量),真正的字节在**堆**里 ——
            // 走下面的数组那条路
            if (声明是字符串 && !名称0.Contains('['))
            {
                字符串声明(内容, 首词, 行号, 伪行);      // 预扫那一趟由它自己认(只开头三槽、不发池初始化)
                return;
            }
            // G2(回调 / 事件):`回调 处理 = 地址(f);` —— 4 字节的**代码地址**,外加"它指向哪个函数"的登记。
            // 登记那一条是给调用点用的:`间接调用(处理, 实参…)` 拿它核对实参表、摆参数槽(运行期值认不出类型)。
            if (首词 is "回调" or "callback" || string.Equals(首词, "callback", StringComparison.OrdinalIgnoreCase))
            {
                处理回调声明(名称0, 等号0 >= 0 ? 余下0[(等号0 + 1)..].Trim() : "", 行号);
                return;
            }
            类型C.类型定义? 类型 = 类型C.解析(首词);
            // H68-2 枚举:枚举名能当类型名写 —— 底层就是**有符号 整数 4 字节**,所以宽度 / 有无符号 /
            // 范围检查 / 机器码那一整套**一个字都不用改**(枚举不占存储,成员在表达式里当场折成常量)
            枚举类型C? 枚举类型 = 类型 == null ? 查枚举类型(首词) : null;
            if (枚举类型 != null) 类型 = 类型C.枚举底层;
            // H68-3 元组:`[…, …]` 是类型位置上的一对方括号 —— 解析不动时由元组那一侧报错(带行号 + 改法),
            // 别落到下面那句"无法识别的声明"里(那句话看不出是元组写法写坏了)
            结构类型C? 结构类型 = 类型 != null ? null
                : 是元组类型词(内容) ? 取元组类型(内容, 行号) : 查结构类型(首词);
            if (类型 == null && 结构类型 == null && !声明是字符串 && 中间层C.到英文关键字(首词) != "var")
                throw 报错(行号, $"无法识别的声明: '{内容}'", $"unrecognized declaration: '{内容}'");
            string 余下 = 内容[首词.Length..].Trim();
            int 等号 = 余下.IndexOf('=');
            string 名称 = (等号 >= 0 ? 余下[..等号] : 余下).Trim();
            string 初值文本 = 等号 >= 0 ? 余下[(等号 + 1)..].Trim() : "";
            if (名称.Length == 0) throw 报错(行号, "变量声明缺少名称", "variable declaration needs a name");
            // `整数 初值 =` 这种"等号写了、右边空的":以前静默当成 0(最容易写漏一半还看不出来)
            if (等号 >= 0 && 初值文本.Length == 0)
            {
                if (名称.Contains('['))
                    throw 报错(行号, $"数组/列表声明不能带初值:把那个 '=' 去掉(写成 {首词} {名称},元素按下标逐个赋值)",
                        $"array/list declaration takes no initializer: drop the '=' ({首词} {名称})");
                throw 报错(行号, $"声明 '{名称}' 的等号右边是空的:'{内容.Trim()}'。" +
                    $"要么写个初值(例如 {首词} {名称} = 0),要么把等号去掉({首词} {名称})",
                    $"declaration of '{名称}' has nothing after '=': '{内容.Trim()}'");
            }

            // 数组 / 列表声明:类型 名[长度](数组) 或 类型 名[](列表);元素可以是结构(结构数组 / 结构列表)
            数组类型C? 数组类型 = null;
            列表类型C? 列表类型 = null;
            string 列表初值文本 = "";      // H3 ②:列表声明带的字面量初值(空闲列表那边逐元素添加用)
            int 初值个数 = 0;
            int 方括号 = 名称.IndexOf('[');
            if (方括号 >= 0)
            {
                string 元素名 = 名称[..方括号].Trim();
                // H68-1 多维数组:一对方括号算一维(`整数 袋[3][4];`)—— 逐维取出来;单维与老写法同一个口径
                var 各维 = new List<string>();
                for (int 走 = 方括号; 走 < 名称.Length; 走++)
                {
                    if (名称[走] != '[')
                        throw 报错(行号, $"数组声明里 ']' 后面只能接下一维的 '[': '{名称}'。" +
                            $"多维数组写成 `类型 名字[行][列];`(定长);别的花样(数组的数组 / 省略某一维)不收",
                            $"only '[size]' may follow in an array declaration: '{名称}'");
                    int 闭 = 名称.IndexOf(']', 走 + 1);
                    if (闭 < 0)
                        throw 报错(行号, $"数组声明缺少 ']': '{名称}'", $"array declaration needs ']': '{名称}'");
                    各维.Add(名称[(走 + 1)..闭].Trim());
                    走 = 闭;
                }
                string 长度文本 = 各维[0];
                不许当数组长度(长度文本, 行号);      // H68-2:枚举成员不当数组长度(给一句指路)
                if (元素名.Length == 0)
                    throw 报错(行号, "数组/列表缺少名字", "array/list needs a name");
                if (初值文本.Length > 0 && !声明是字符串 && !是方括号初值(初值文本))
                {
                    throw 报错(行号, $"数组/列表 '{元素名}' 的初值要用**方括号**写成一串常量:{首词} {名称} = [1, 2, 3];" +
                        $"(写几个算几个,剩下的自动是 0)。**`{{ }}` 只用于语句块**(方法体 / 条件 / 循环 / 容器体),两处不混用",
                        $"array literal initializer must look like [1, 2, 3]");
                }
                // H68-1 多维数组:先逐维核对长度与上限(下面那一大段单维代码一个字不改 —— 多维只是"把第一维
                // 当长度先造出类型、最后再补上各维",老写法命中的仍是同一条路)
                if (各维.Count > 1)
                {
                    if (声明是字符串)
                        throw 报错(行号, $"字符串数组只能是一维:`字符串 名单[8];`。" +
                            $"多维的字符串数组还没做(一个元素 8 字节,整块给的时候要逐个在堆里要块)——" +
                            $"要二维就写 `字符串 名单[8];` 再按下标算,或者把那一格换成结构",
                            $"multi-dimensional string arrays are not supported");
                    if (各维.Count > 硬上限C.数组维数上限)
                        throw 报错(行号, $"多维数组最多 {硬上限C.数组维数上限} 维(这一句写了 {各维.Count} 维):'{名称}'",
                            $"at most {硬上限C.数组维数上限} dimensions: '{名称}'");
                    long 总个数 = 1;
                    foreach (string 一维 in 各维)
                    {
                        if (一维.Length == 0)
                            throw 报错(行号, $"多维数组的每一维都要写长度:'{名称}' 里有空的 []。" +
                                $"`整数 表[][];`(列表的列表)还没做 —— 要二维就写定长的 `整数 表[行][列];`," +
                                $"要自己长就用一维列表 `整数 表[]`",
                                $"every dimension needs a length: '{名称}'");
                        不许当数组长度(一维, 行号);
                        if (!uint.TryParse(一维, out uint 一维长) || 一维长 == 0 || 一维长 > 硬上限C.数组长度上限)
                            throw 报错(行号, $"数组长度非法: '{一维}'(多维数组的每一维都须为 1~{硬上限C.数组长度上限} 的常量)",
                                $"invalid array length: '{一维}'");
                        总个数 *= 一维长;
                    }
                    if (总个数 > 硬上限C.数组长度上限)
                        throw 报错(行号, $"多维数组太大: 各维乘起来 {总个数} 个元素,超过上限 {硬上限C.数组长度上限} 个。" +
                            $"把某一维改小,或者拆成几个数组",
                            $"multi-dimensional array too large: {总个数} elements");
                }
                名称 = 元素名;
                // H3 ②:`整数 名[] = [1, 2, 3];` = **列表**(会自己长),不是定长数组(用户 2026-09-30 拍板)
                if (长度文本.Length == 0 && 初值文本.Length > 0 && !声明是字符串)
                {
                    if (!是方括号初值(初值文本))
                        throw 报错(行号, $"列表 '{元素名}' 的初值要用方括号写成一串常量:{首词} {元素名}[] = [1, 2, 3];" +
                            $"(写几个算几个)。要定长数组就把个数写上({首词} {元素名}[3])," +
                            $"要一个个加就写 {元素名}.添加(值);。**`{{ }}` 只用于语句块**(方法体 / 条件 / 循环 / 容器体),两处不混用",
                            $"list initializer must look like [1, 2, 3]");
                    var 初值们 = 拆方括号初值(初值文本, 行号);
                    if (初值们.Count == 0)
                        throw 报错(行号, $"列表 '{元素名}' 的初值是空的 '[]':要么写几个常量(如 [1, 2, 3])," +
                            $"要么把它声明成空列表 `{首词} {元素名}[]` 再用 .添加(值) 一个个加",
                            $"empty initializer for list '{元素名}'");
                    初值个数 = 初值们.Count;
                }
                int 元素宽 = 声明是字符串 ? 串字段宽 : 结构类型?.总宽度 ?? 类型?.宽度 ?? 类型C.字宽度;
                // H68-2:元素是枚举时类型名写枚举自己(宽度照样是 4 —— 只是报错/补全/字面量初值那边认得出"要哪个枚举")
                string 元素类型名 = 声明是字符串 ? "字符串" : 结构类型?.名称 ?? 枚举类型?.名称 ?? 类型?.中文 ?? "32位字";
                if (声明是字符串)
                {
                    // `字符串 名单[10]`:每个元素 8 字节(数据地址 + 容量),真正的字节在堆里
                    // `字符串 名单[]`(H1 起):个数不定 —— 元素同样 8 字节,数据块住池里、装不下自己长
                    if (长度文本.Length == 0)
                    {
                        if (初值文本.Length > 0)
                            throw 报错(行号, $"字符串列表 '{元素名}' 不能在声明时给初值(每个元素都要在堆里要块):" +
                                $"声明完再一个个 添加(例如 {元素名}.添加(\"第一项\");)",
                                $"a string list cannot have an initializer: use 添加");
                        列表类型 = new 列表类型C(元素类型名, 元素宽, 0, 容量写死: false, null) { 元素是字符串 = true };
                    }
                    else
                    {
                        if (初值文本.Length > 0)
                            throw 报错(行号, $"字符串数组 '{元素名}' 不能在声明时给初值(每个元素都要在堆里要块):" +
                                $"声明完再一个个赋值(例如 {元素名}[0] = \"第一项\";)",
                                $"a string array cannot have an initializer: assign elements one by one");
                        if (!uint.TryParse(长度文本, out uint 串个数) || 串个数 == 0 || 串个数 > 硬上限C.字符串数组长度上限)
                            throw 报错(行号, $"字符串数组长度非法: '{长度文本}'(须为 1~{硬上限C.字符串数组长度上限} 的常量;" +
                                $"每个元素占 {串字段宽} 字节,整块不能超过 {硬上限C.数组长度上限} 字节)。" +
                                $"要更多就用字符串列表 `字符串 {元素名}[]`(元素同样 {串字段宽} 字节,装不下自己换块)",
                                $"invalid string array length: '{长度文本}'");
                        数组类型 = new 数组类型C(元素类型名, 元素宽, (int)串个数, null) { 元素是字符串 = true };
                    }
                }
                else if (长度文本.Length == 0)
                {
                    // 空 [] = 列表:个数不写,编译器先算,算不出就自己长
                    // H3 ②:带了字面量初值的话,容量就按初值个数定(那一句再逐个 添加 进去)
                    列表类型 = new 列表类型C(元素类型名, 元素宽, 0, 容量写死: false, 结构类型) { 初值个数 = 初值个数, 初值原文 = 初值文本 };
                    if (初值个数 > 0) 列表初值文本 = 初值文本;
                }
                else
                {
                    if (!uint.TryParse(长度文本, out uint 个数) || 个数 == 0 || 个数 > 硬上限C.数组长度上限)
                        throw 报错(行号, $"数组长度非法: '{长度文本}'(须为 1~{硬上限C.数组长度上限} 的常量;不写数字就是列表,它会自己长)",
                            $"invalid array length: '{长度文本}'");
                    // 写了数字的数组只要用了 .添加(),就当成"容量写死的列表"(不长大、满了报错)—— 所以它也要一个长度槽
                    // 但**带字面量初值的不能再当列表**:那条路上初值会被默默丢掉(实测过)—— 要初值就按下标改
                    if (会用到添加(名称))
                    {
                        if (初值文本.Length > 0)
                            throw 报错(行号, $"数组 '{元素名}' 既写了字面量初值、又用了 .添加():两样只能挑一样 ——" +
                                $"要初值就删掉 {元素名}.添加(…) 那几句(数组本来就能按下标改)," +
                                $"要自己往末尾加就别写初值",
                                $"array '{元素名}' has both a literal initializer and .添加() calls");
                        列表类型 = new 列表类型C(元素类型名, 元素宽, (int)个数, 容量写死: true, 结构类型);
                    }
                    else
                        数组类型 = new 数组类型C(元素类型名, 元素宽, (int)个数, 结构类型);
                }
                结构类型 = null;     // 结构数组/结构列表:东西在"数组/列表"里,变量本身不再是结构
                // H68-1 多维数组:上面那条单维路已经按第一维造好了类型,这里把"各维长度"补上
                // (单维一律不补 ⇒ 老写法的类型对象逐字段与以前相同)
                if (各维.Count > 1)
                {
                    if (数组类型 is null)
                        throw 报错(行号, $"多维数组 '{元素名}' 不能用 .添加():它按各维长度定长(例如 整数 袋[3][4]),不会自己长。" +
                            $"要自己长的列表只能是一维:`整数 {元素名}[]` 配 {元素名}.添加(值)",
                            $"a multi-dimensional array cannot use .添加()");
                    var 各维长 = new int[各维.Count];
                    for (int i = 0; i < 各维.Count; i++) 各维长[i] = int.Parse(各维[i]);
                    数组类型 = new 数组类型C(数组类型.元素类型名, 数组类型.元素宽, 数组类型.长度, 数组类型.元素结构, 各维长);
                }
            }
            if (名称.Contains('<'))
                throw 报错(行号, $"列表不用尖括号:写成 类型 名字[] 即可(例如 短整数 分数[])",
                    $"lists do not use angle brackets: write 类型 名字[]");

            // 预扫的边界(Q1b):**引用**声明登记时要算目标地址(发码),那代码不能搬到文件开头 ——
            // 引用不进预扫,照旧"声明在前"(列表与字符串只把"开槽"提前,初始化代码仍留在原语句那一句上)。
            校验变量名(名称, 行号);
            // 模块里的**顶层**声明带前缀(`数学.计数`);函数里的局部/参数不带(它们只在函数里可见)
            string 注册名 = 声明注册名(名称);
            记私有(注册名);
            // "已预登记"协议(Q1b):预扫已经为**这一行**登记过这个名字 ⇒ 这里既不重登、也不报重名
            bool 已预登记 = !_预扫声明中 && 伪行 >= 0 && _当前函数 == null && 已预登记全局到本行(注册名, 伪行);
            if (当前作用域.ContainsKey(注册名) && !已预登记)
            {
                if (_预扫声明中) return;      // 预扫撞重名不吭声:报给谁、带哪两处位置,交给逐句处理那趟
                throw 报错(行号, $"变量 '{注册名}' 在本作用域重复声明 —— {上一处声明(注册名)}{同名怎么办("变量")}",
                    $"duplicate variable '{注册名}' in this scope");
            }
            if (_当前函数 == null && !已预登记) 记声明出处(注册名, 行号);      // 顶层声明:重复时能报出两处位置
            // 只差大小写的"遮蔽":HB 的标识符**不分大小写** —— 参数 `M` 与局部 `m` 其实是同一个名字。
            // 初值已经按"声明符在初值之后才进作用域"算(见 _初值借出名),但**从这一句起**,本层里的 `M`/`m`
            // 都指这个新局部了;作者本意往往是两个变量,所以给一条看得见的提示(不改语义:遮蔽是设计允许的)。
            if (!已预登记)
            {
                for (int 层 = _作用域栈.Count - 2; 层 >= 0; 层--)
                {
                    string? 只差大小写 = null;
                    foreach (string 外层名 in _作用域栈[层].Keys)
                        if (外层名.Length == 注册名.Length
                            && string.Equals(外层名, 注册名, StringComparison.OrdinalIgnoreCase)
                            && !string.Equals(外层名, 注册名, StringComparison.Ordinal))
                        {
                            只差大小写 = 外层名;
                            break;
                        }
                    if (只差大小写 is { } 撞名)
                    {
                        _编译提示.Add($"提示:局部 '{名称}' 与外层的 '{撞名}' **只差大小写** —— HB 的标识符不分大小写," +
                            $"从这一句起本层里的 '{撞名}' 都指这个新局部;要两个不同的变量请改名(想遮蔽就写成同名 '{撞名}')");
                        break;
                    }
                }
            }

            int 声明宽 = 数组类型?.总宽度 ?? 类型?.宽度 ?? 结构类型?.总宽度 ?? 类型C.字宽度;
            // C 档优化:`短整数` 这种**独立标量变量**按 4 字节放(读一条、写一条,写完按声明宽截断);
            // 数组/列表/结构的宽度不动(它们的布局是用户看得见的)
            bool 宽槽 = 数组类型 == null && 结构类型 == null && 列表类型 == null;
            int 宽度 = 宽槽 ? 槽宽度(声明宽) : 声明宽;
            宽槽 = 宽度 != 声明宽;
            变量槽定义 定义;
            if (已预登记)
            {
                // 预扫已经分配好槽、登记好绑定了:这里**一个字节都不许再分**(不然数据段会多出一块空槽)
                定义 = 当前作用域[注册名].槽;
                if (列表类型 != null)
                {
                    // 列表/字符串:预扫那趟只开了槽(头三槽或 数据槽+长度槽),初始化代码在这儿补发 ——
                    // 动态的要"从池里要一块",这句**必须留在原语句那一句上**,顺序一点不动
                    if (_列表表[注册名].动态) 生成动态列表初始化(_列表表[注册名], 行号);
                    // H3 ②:声明时写的那串字面量初值也在这一句上逐个 `添加`(预扫那趟一条都不许发)
                    if (列表类型.初值个数 > 0) 发出列表初值添加(_列表表[注册名], 注册名, 列表类型, 行号);
                    return;
                }
                if (定义.宽度 != 宽度)
                    throw 报错(行号, $"编译器内部错误(请报告):预扫登记的槽宽 {定义.宽度} 与这里算出来的 {宽度} 对不上",
                        "internal: pre-scanned slot width mismatch");
            }
            else if (列表类型 != null)
            {
                // 函数里的列表:头放当前帧、数据从池里要一块(以前这里直接报"只能声明在顶层")
                if (_当前函数 is not null)
                {
                    定义 = 列表分配局部(注册名, 列表类型, 行号);
                    宽度 = 定义.宽度;
                    当前作用域[注册名] = new 变量绑定C(定义, null, null, 列表类型);
                    登记名字(注册名, 定义, 类型, null, null, 行号, 列表: _列表表[注册名]);
                    return;
                }
                定义 = 列表分配(注册名, 列表类型, 行号, 扫源码用的名: 名称, 预扫: _预扫声明中);
                宽度 = 定义.宽度;
                当前作用域[注册名] = new 变量绑定C(定义, null, null, 列表类型);
                登记名字(注册名, 定义, 类型, null, null, 行号, 列表: _列表表[注册名]);
                if (_预扫声明中) { _已预登记全局[注册名] = 伪行; return; }   // 初始化代码留在原语句那一句上
                return;      // 列表的初始化代码在 列表分配 里发完了,没有初值可写
            }
            else if (_当前函数 is { } 函数)
            {
                // 函数内:参数与局部都放当前帧(FP 相对),支持递归
                if (函数.局部偏移 + 宽度 > 函数帧大小)
                    throw 报错(行号, $"方法 '{函数.名称}' 的帧超出:放不下局部变量 '{名称}' —— 已经用到 {函数.局部偏移} 字节," +
                        $"再加这个 {宽度} 字节就是 {函数.局部偏移 + 宽度} 字节,上限 {函数帧大小} 字节。" + 帧超限改法(),
                        $"function frame overflow in '{函数.名称}'");
                int 起 = 函数.局部偏移;
                定义 = new 变量槽定义(帧槽(起), 宽度);
                函数.局部偏移 += 宽度;
                // 帧是复用的:只有"声明时不会立刻把自己写满"的局部才要入口清零(见 需要入口清零)
                if (需要入口清零(数组类型, 结构类型, 初值文本) && !下一句就赋值(伪行, 名称)) 函数.需清零.Add((起, 宽度));
            }
            else
            {
                定义 = 新槽(宽度);
            }
            if (!已预登记)
            {
                当前作用域[注册名] = new 变量绑定C(定义, 结构类型, 数组类型, null, null, 宽槽 ? 声明宽 : 0, 类型?.类型 == 基本类型.逻辑, 类型?.有符号 ?? true);
                if (类型 is { } 基础类型) 登记变量类型(注册名, 基础类型.中文);   // 记下声明类型:`文字` 要认得出(拼接/输出按文字处理)
                // H68-2:枚举变量的**枚举身份**也记一份 —— `画 = 别的枚举成员;` 那一条约束就靠它认
                if (枚举类型 is { } 枚) 登记变量类型(注册名, 枚.名称);
                登记名字(注册名, 定义, 类型, 结构类型, 数组类型, 行号, 显示类型名: 枚举类型?.名称);   // 调试名字表(旁路信息)
            }
            if (_预扫声明中)
            {
                _已预登记全局[注册名] = 伪行;     // 登记完成:逐句处理到这一行时据此跳过登记,只发下面的初始化代码
                return;                            // **初始化代码绝不提前**:它只属于原语句那一句
            }
            // **声明的初值不许看见"自己"**(标准作用域:声明符在初值之后才进作用域)。
            // 为什么必须:HB 的标识符**不分大小写**,`整数 m = 62 - 位长(M)` 里的 `M` 与 `m` 是同一个
            // 名字 —— 旧版初值会读到刚登记、还没初始化的那个 m 槽(实测读出 0,静默错值;库里的
            // `整数 m = 62 - 双_位长(M)` 就是这么栽的)。这里把名字借出去,查变量跳过最内层那一格。
            _初值借出名 = 注册名;
            try
            {
                var 该位置 = new 地址位置(定义.名称, 0, 定义.宽度, 宽槽 ? 声明宽 : 0, 类型?.有符号 ?? true);

                if (数组类型 != null)
                {
                    // 数组:整体零初始化;也可以写字面量初值 [1,2,3](只收常量,写几个算几个,剩下的是 0)
                    // 数组:整体零初始化。**循环体里的声明每轮都要重新执行** —— 那时"数据段天生是 0"不作数,得真清一遍
                    bool 数组零初值 = 初值文本.Length == 0 || (解析无符号32(初值文本, out uint 数组清零) && 数组清零 == 0);
                    if (数组零初值)
                    {
                        if (在循环里()) 发出清零填块(该位置, 数组类型.总宽度);
                        return;
                    }
                    if (是方括号初值(初值文本))
                    {
                        var 数型 = 数组类型!;
                        var 元素们 = 拆方括号初值(初值文本, 行号);
                        // H68-1:多维数组的初值**按行铺开**(最后一维最快),与 `袋[r][c]` 的落点一一对应
                        var 项们 = 折字面量初值(元素们, 数型.总元素数,
                            c => 数型.是多维
                                ? $"数组 '{注册名}' 一共 {数型.总元素数} 个元素(各维 {数型.各维文本}),初值却写了 {c} 个"
                                : $"数组 '{注册名}' 只有 {数型.长度} 个元素,初值却写了 {c} 个", 行号,
                            i =>
                            {
                                要求元素收数字(注册名, 数型.元素结构, 行号);
                                return (i * 数型.元素宽, 数型.元素宽, 数型.元素类型名);
                            });
                        if (初值可搬(定义)) 记顶层填块(定义.名称, 项们);
                        else
                        {
                            // 每轮重新执行:没写到的那几个元素必须是 0,不能留着上一轮的值
                            if (在循环里()) 发出清零填块(该位置, 数型.总宽度);
                            发出常量填块(取位置地址(该位置), 项们);
                        }
                        return;
                    }
                    throw 报错(行号, $"数组 '{注册名}' 要么整体清 0,要么写字面量初值(如 {注册名} = [1, 2, 3]);" +
                        $"其余情况请按下标逐个赋值", $"array '{注册名}' supports only zero init or a literal initializer");
                }

                if (结构类型 != null)
                {
                    // 结构变量:零初始化;也支持 `点 副本 = 位置`(同一个结构的另一份 → 整块拷贝)、
                    // `点 位置 = [1, 2]`(按字段声明顺序给常量,写几个算几个)
                    // 结构变量:零初始化。同上 —— 循环体里的声明每轮都要重新执行,得真清(帧更是复用的)
                    bool 结构零初值 = 初值文本.Length == 0 || (解析无符号32(初值文本, out uint 结构清零) && 结构清零 == 0);
                    if (结构零初值)
                    {
                        if (在循环里()) 发出清零填块(该位置, 结构类型.总宽度);
                        发出结构默认初值(定义, 该位置, 结构类型);   // H3 ①:字段自带的默认值照旧落上
                        return;
                    }
                    if (是方括号初值(初值文本))
                    {
                        var 构型 = 结构类型!;
                        var 字段们 = 拆方括号初值(初值文本, 行号);
                        // H68-4:元组值里带**式子**(`[被除 / 除数, 被除 % 除数]`)⇒ 按成员逐个算出来写进这一格;
                        // 整串都是常量(含枚举成员)就照旧走下面那条"装载期常量填块"的老路 —— 老写法机器码一个字节不变
                        if (是元组结构(构型)
                            && !字段们.All(段 => 是常量字面量(段) || 查枚举成员常量(段) != null))
                        {
                            准备语句占用(初值文本);
                            发出元组填块(取位置地址(该位置), 构型, 初值文本, 行号, 初值文本);
                            return;
                        }
                        // A4:字面量初值按字段顺序整块写 —— 等于隔着字段名碰了每一格,私有/程序集字段不能这么绕
                        校验全字段可取用(构型, 行号);
                        var 项们 = 折字面量初值(字段们, 构型.字段.Count,
                            c => $"结构 '{构型.名称}' 只有 {构型.字段.Count} 个字段,初值却写了 {c} 个", 行号,
                            i =>
                            {
                                var 字段 = 构型.字段[i];
                                要求字段收数字(字段, 注册名, 行号);
                                return (字段.偏移, 字段.宽度, 字段.类型名);
                            });
                        // H3 ①:没被这次字面量写到的那些格,结构自己的默认值照旧生效(同一格以这次写的为准)
                        项们 = 并结构默认(构型.默认初值们, 项们);
                        if (初值可搬(定义)) 记顶层填块(定义.名称, 项们, 该位置.偏移);
                        else
                        {
                            if (在循环里()) 发出清零填块(该位置, 结构类型.总宽度);   // 没写到的字段必须是 0
                            发出常量填块(取位置地址(该位置), 项们);
                        }
                        return;
                    }
                    if (像引用链(初值文本) && 解析引用链(初值文本, 行号) is { } 来源
                        && 来源.整块宽 == 结构类型.总宽度
                        && (来源.需要整块 || 来源.结构?.名称 == 结构类型.名称))
                    {
                        // H3 ①:拷过来的那一份要么从别的变量来(人家自己已经带默认值了),要么从函数返回的结构来
                        // (那种结构的值由被调方给)。**拷贝会把整块盖掉** ⇒ 这一份自己的默认值不用再写;
                        // 但"被拷的那一份"如果没有默认值(老写法),照旧与 H3 之前逐字节相同。
                        // H68-3:元组按写法认类型 —— 写法不同的元组(或长得像的结构)不能这样拷
                        检查整块类型相配(结构类型, 来源.结构, 行号, 注册名, 初值文本);
                        生成结构拷贝(链地址(来源, 行号, 初值文本), 取位置地址(该位置), 结构类型);   // 有字符串字段就深拷贝
                        return;
                    }
                    // `点 中 = 取中点(3, 9)`:函数返回结构 → 把这块的地址递进去,被调方直接写到这儿
                    if (试取结构返回调用(初值文本, 行号) is { } 结构调用)
                    {
                        准备语句占用(初值文本);
                        发出表达式调用(结构调用.链路, 结构调用.实参, 行号, 初值文本, 返回目的地址: 取位置地址(该位置));
                        return;
                    }
                    throw 报错(行号, $"结构变量 '{注册名}' 要么整体清 0,要么用同一种结构的另一份拷过来(如 点 副本 = 位置)," +
                        $"其余情况请对字段分别赋值", $"struct variable '{名称}' supports only zero init or a copy from the same struct");
                }

                if (初值文本.Length == 0) return;          // 数据段零初始化
                // 通用化(2026-10):**浮点常量初值**(`浮点 初值 = 1.5;`)。
                // 浮点值就是那 32 位 IEEE754 位模式 ⇒ 走"常量装进临时寄存器 → 按宽度写回变量"这条现成路
                // (与下面"非常量初值"那条同一个口子),只是不做整数那套范围检查(位模式不是"数的大小")。
                // ⚠ 只有**浮点类型**的变量收它:别的类型写成 `整数 x = 1.5;` 要**当场报错**,
                //    不许把位模式静静当成 1069547520 装进去(那是**静默错误**)。
                if (是浮点字面量(初值文本, out uint 浮点位))
                {
                    if (类型?.类型 != 基本类型.浮点)
                        throw 报错(行号,
                            $"浮点字面量 `{初值文本}` 只能给 `浮点`(float)类型的变量:" +
                            $"现在声明的是 `{类型?.中文 ?? 首词}`。要一个整数值请写整数,要浮点请把类型写成 `浮点`",
                            $"float literal '{初值文本}' needs a 浮点 variable");
                    登记变量类型(注册名, "浮点");
                    准备语句占用(初值文本);
                    string 浮点临时 = 新临时();
                    输出装载常量(浮点临时, 浮点位);
                    发出写变量(浮点临时, 该位置, 源已零扩展: true, 源可改写: true);
                    return;
                }
                // H68-2:初值整段就是一个枚举成员(`绿` / `颜色.绿`)⇒ 折成十进制原文,下面那一整套
                // "字面量 + 范围检查 + 装载期初值"一个字都不用改;顺手做"不许跨枚举"的检查
                初值文本 = 折成员常量(初值文本, 行号, 枚举类型?.名称 ?? "");
                // T6(2026-09-27 评测整改):**负常量也是常量**。以前 `解析无符号32`(`uint.TryParse`)
                // 一见 `-` 就失败 ⇒ `短整数 s = -39999;` / `整数 x = -3000000000;` 掉进"非常量初值"那条路,
                // 下面整段范围检查被绕过 ⇒ 静默截断成 25537 / 1294967296(正数 39999 反而报错,两边不对称)。
                // 现在负号常量先按 32 位补码读进来,与正数走**同一段**检查。
                if (!解析无符号32(初值文本, out uint 初值) && !解析负常量32(初值文本, out 初值))
                {
                    // 非常量初值:`类型 名 = 式子` / `var 名 = 式子` —— 算进临时寄存器再按宽度写回(与赋值同一套规则)
                    准备语句占用(初值文本);
                    string 临时 = 新临时();
                    bool 初值零扩展 = 输出赋值到寄存器(临时, 替换地址取用(初值文本, 行号, 初值文本), 行号, 初值文本);
                    发出写变量(临时, 该位置, 初值零扩展, 源可改写: true);
                    return;
                }
                string 类型名 = 类型?.中文 ?? "32位字";
                // 范围检查:**有符号类型按有符号看**(`短整数 x = -5` 合法、`短整数 x = 40000` 报错)。
                // 常量在寄存器里就是 32 位补码,所以先把它按 32 位有符号解释一遍,再跟类型值域比。
                {
                    // 常量在文本里带负号 → 按 32 位有符号解释;不然就按"正整数"看(这样 `整数 x = 4000000000` 会报错,
                    // 而不是偷偷变成 -294967296)
                    bool 带负号 = 初值文本.TrimStart().StartsWith('-');
                    // T6:负常量按**数学上那个负数**报范围(不看 32 位回绕后的值):
                    // `整数 x = -3000000000;` 该说"常量 -3000000000 超出范围",不是 1294967296
                    long 看值 = (类型?.有符号 ?? true) && 带负号 ? -(long)(0u - 初值) : 初值;
                    long 下限 = 类型?.最小值 ?? 类型C.有符号最小值(声明宽);
                    long 上限 = 类型?.最大值 ?? 类型C.有符号最大值(声明宽);
                    if (类型?.类型 == 基本类型.逻辑 && 初值 > 1)
                        throw 报错(行号, $"逻辑常量只能是 真/假/0/1,收到 {初值}", $"logic constant must be 真/假/0/1, got {初值}");
                    if (看值 < 下限 || 看值 > 上限)
                        throw 报错(行号, $"常量 {看值} 超出 {类型名} 范围({下限} ~ {上限})" + 迁移提示(类型, 看值),
                            $"constant {看值} out of range for {类型名}");
                }
                // 常量 0:数据段本来就零初始化,可以免发存值指令;
                // 但**会重复执行的声明**(循环体里)与**函数帧**(内存复用)都不行 —— 必须真写一个 0 进去。
                // 踩过:嵌套循环里 `整数 j = 0;` 省掉以后,第二轮 j 还留着上一轮的 4,内层直接不跑
                // (和只加了第一轮 → 输出 6 而不是 48)。
                if (初值 == 0 && 初值可搬(定义)) return;
                // 顶层(数据段)的常量初值:登记进初值表,装载时写进内存,不发"程序开头一条存储指令"
                if (初值可搬(定义))
                {
                    _顶层初值.Add((定义.名称, 0, 定义.宽度, 初值));
                    return;
                }
                准备语句占用(内容);
                string t = 新临时();
                输出装载常量(t, 初值);
                // 常量已经过范围检查:无符号的话高半就是 0,有符号的话符号位已经对 —— 都能省掉写回时那一步
                发出写变量(t, 该位置, 源已零扩展: true, 源可改写: true);
            }
            finally
            {
                _初值借出名 = "";        // 初值算完(含中途报错/提前 return)就还回去
            }
        }

        /// <summary> 常量放不下时给一句"换哪个类型"的指路(用户从无符号时代过来的最容易撞这个)</summary>
        private static string 迁移提示(类型C.类型定义? 类型, long 看值)
        {
            if (类型 == null) return "";
            if (类型.Value.类型 == 基本类型.短整数)
                return $"。**短整数 现在是有符号的**;要存 0~65535 这么大的数,写 无符号短整数(ushort)";
            if (类型.Value.类型 == 基本类型.整数)
                return $"。**整数 是有符号的**;要存 0~4294967295 这么大的数,写 无符号整数(uint)";
            if (看值 < 0)
                return "。这个类型是无符号的,存不了负数";
            return "";
        }

        /// <summary> 这个槽是不是"函数帧里的槽"(局部/参数) </summary>
        private static bool 是帧槽(变量槽定义 槽) => 槽.名称.StartsWith(帧槽前缀, StringComparison.Ordinal);

        /// <summary>
        /// 伪输出 `测试输出()` / `测试输出(值)`:相当于 Debug.WriteLine —— 把值按无符号十进制打到宿主输出流,末尾补换行。
        /// 不带参数 → 打印 R0(只读,不改动它);带参数 → 寄存器 / 变量 / 结构字段 / 常量(基础类型都行)。
        /// 展开成一小段循环:逐位取余压栈,再弹栈按原顺序输出;只用高位临时寄存器,不碰用户寄存器。
        /// </summary>
        private void 处理测试输出(ref int 位置)
        {
            int 行号 = _伪行号表[位置];
            string 内容 = _伪行表[位置];
            string 首词 = 取首词(内容);
            string 余下 = 内容[首词.Length..].Trim();
            if (!余下.StartsWith('(') || !余下.EndsWith(')'))
                throw 报错(行号, $"测试输出(...) 需要括号:{内容}", $"debug(...) needs parentheses: {内容}");
            string 参数 = 余下[1..^1].Trim();
            准备语句占用(内容);

            string 值寄存器;
            bool 有符号 = false;
            if (参数.Length == 0)
            {
                值寄存器 = "R0";            // 默认输出 R0
            }
            else if (解析寄存器(参数, out string 直接寄存器))
            {
                值寄存器 = 直接寄存器;
            }
            else
            {
                // 其余一律当表达式:变量/字段/数组元素/括号/优先级/多运算符/函数调用都行
                var 结果 = 落到寄存器(求值表达式(参数, 行号, 内容));
                有符号 = 结果.有符号;
                if (结果.是常量)
                {
                    // 编译期就知道符号:负数直接打 '-' 再打绝对值
                    if (有符号 && (int)结果.常量 < 0)
                    {
                        string 负号 = 新临时();
                        发出($"LOAD_IMMEDIATE {负号} 45");
                        发出($"OUT {负号}");
                        发出打印十进制带换行(常量入临时(0u - 结果.常量));
                        位置++;
                        return;
                    }
                    值寄存器 = 常量入临时(结果.常量);
                }
                else 值寄存器 = 结果.寄存器!;
            }

            if (有符号) 发出处理负号(ref 值寄存器, 可改写: true);
            发出打印十进制带换行(值寄存器);
            位置++;
        }

        /// <summary> 有符号值打印前的处理:负数先打一个 '-',并把寄存器里的值取负(之后就按无符号那套打印)。
        /// `可改写` = 这个寄存器是本语句自己的临时(可以就地取负);不然先复制一份,别改别人的寄存器。</summary>
        private void 发出处理负号(ref string 寄存器, bool 可改写)
        {
            if (!可改写) 寄存器 = 复制到临时(寄存器);
            string 符号 = 新临时();
            发出($"MOV {符号} {寄存器}");
            发出右移立即数(符号, 31);                      // 1 = 负数(A9:一条顶"装常量 31 + 右移")
            string 跳过 = 新标签("Pos");
            发出($"JZ {符号} {跳过}");
            发出($"LOAD_IMMEDIATE {符号} 45");              // '-'
            发出($"OUT {符号}");
            发出($"NOT {寄存器}");
            发出($"ADD_IMMEDIATE {寄存器} 1");               // 取负 = (~x) + 1
            发出($"{跳过}:");
        }

        /// <summary> 生成"十进制打印 + 换行"的展开序列(高位临时寄存器 + 栈,平衡进出) </summary>
        private void 发出打印十进制(string 源寄存器)
        {
            string 值 = 新临时();
            string 除十 = 新临时();
            string 位 = 新临时();
            string 个数 = 新临时();
            string 取位循环 = 新标签("Out取位");
            string 打印循环 = 新标签("Out打印");
            string 结束 = 新标签("Out结束");

            发出($"MOV {值} {源寄存器}");
            输出装载常量(除十, 10);
            输出装载常量(个数, 0);

            发出($"{取位循环}:");
            发出($"MOV {位} {值}");
            发出($"MOD {位} {除十}");        // 位 = 值 % 10
            发出($"PUSH {位}");              // 低位先入栈,弹出时自然是高位在前
            发出($"ADD_IMMEDIATE {个数} 1");
            发出($"DIV {值} {除十}");        // 值 = 值 / 10
            发出($"JZ {值} {打印循环}");
            发出($"JMP {取位循环}");

            发出($"{打印循环}:");
            发出($"POP {位}");
            发出($"ADD_IMMEDIATE {位} 48");  // 0x30 = '0'
            发出($"OUT {位}");
            发出($"SUB_IMMEDIATE {个数} 1");
            发出($"JZ {个数} {结束}");
            发出($"JMP {打印循环}");
            发出($"{结束}:");
        }

        /// <summary> 生成"十进制打印 + 换行"的展开序列(只给 `测试输出()` 用:它一直带换行) </summary>
        private void 发出打印十进制带换行(string 源寄存器)
        {
            发出打印十进制(源寄存器);
            发出("NEWLINE");
        }

