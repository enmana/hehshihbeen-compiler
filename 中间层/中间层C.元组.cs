using System.Collections.Generic;
using System.Linq;

namespace hehshihbeen_compiler
{
    /// <summary>
    /// 中间层展开器的一部分:**元组(H68-3 / H68-4)**。
    ///
    /// 语法只有一处新写法 —— **类型位置上的一对方括号**:
    /// <code>
    /// [整数, 整数] 结果 = [7, 3];        // 不写名字 ⇒ 成员依次叫 .项0 / .项1
    /// [整数 商, 整数 余] 一份;           // 写了名字 ⇒ .商 / .余
    /// [整数, 整数] 表[10];               // 元组数组(元素就是这种元组)
    /// 方法 除法(整数 被除, 整数 除数) 返回 [整数, 整数] { 返回 [被除 / 除数, 被除 % 除数]; }
    /// </code>
    ///
    /// **落地形态:元组就是一个"照字段名现造的结构类型"**(施工图 §9 H68「五」)——
    /// `[整数, 整数]` ⇒ 结构类型 `[整数, 整数]`,字段 `项0`(偏移 0)/ `项1`(偏移 4),紧排;
    /// 于是**声明 / 字段访问 / 整体赋值 / 传参 / 元组数组 / 返回**全部走结构那一套现成机制,
    /// ISA / 机器码**一个字节都不改**(元组不是新类型,是给结构起的一个名字)。
    ///
    /// 三条口径(与施工图一致):
    ///   · **名义制**:类型身份 = 那份规范写法,所以 `[整数, 整数]` 与 `结构 点 { 整数 x; 整数 y; }`
    ///     **互不相容**(字段名/类型名都对不上就是两个类型),`[整数 商, 整数 余]` 与 `[整数, 整数]`
    ///     也是两个类型(成员名不同);
    ///   · **成员从 0 起**:不写名时依次 `项0` / `项1` …(与字符串取字、数组、列表统一从 0 起);
    ///   · **不做拆包**(`[整数 商, 整数 余] = …`):要拆就 `整数 商 = 结果.项0;`。
    ///
    /// **明确不做**(撞上当场给"怎么写"的指路,不默默收下):元组元素是 `字符串` / 数组 / 列表、
    /// 空元组 `[]`、字面量里再套一层元组(`[[1, 2], 3]`)、结构性相等(只按形状相等的另一套类型系统)。
    /// </summary>
    internal partial class 中间层展开器
    {
        /// <summary>
        /// 已经造出来的元组类型:**规范写法 → 结构类型**(全仓唯一一处)。
        /// 元组不进 `_结构表`(它不是 `结构` 声明,也不该在"结构名"那一栏里露头),
        /// 只在这里缓存;`查结构类型` 认到方括号就转到这里。
        /// </summary>
        private readonly Dictionary<string, 结构类型C> _元组表 = new(StringComparer.Ordinal);

        /// <summary> 这个类型词是不是元组写法(`[` 开头) </summary>
        private static bool 是元组类型词(string 词)
        {
            string t = 词.TrimStart();
            return t.Length > 0 && t[0] == '[';
        }

        /// <summary>
        /// 从"以 `[` 开头"的文本里取**配对到深度归零那一格 `]`** 的整段(支持嵌套元组)。
        /// 括号不配对 / 不是方括号开头 ⇒ 空串(调用方据此报错)。
        /// </summary>
        private static string 取元组词(string 内容)
        {
            string t = 内容.TrimStart();
            if (t.Length == 0 || t[0] != '[') return "";
            int 深 = 0;
            for (int i = 0; i < t.Length; i++)
            {
                if (t[i] == '[') 深++;
                else if (t[i] == ']')
                {
                    深--;
                    if (深 == 0) return t[..(i + 1)];
                    if (深 < 0) return "";
                }
            }
            return "";
        }

        /// <summary>
        /// 按**顶层逗号**拆一段文本(方括号里的逗号不算 —— 元组、数组字面量都靠它)。
        /// `认全角` = 中文逗号 `，` 与顿号 `、` 也算分隔符(字面量初值那一侧的老口径就是这样;
        /// 参数表那一侧只认英文逗号,别悄悄放宽)。
        /// </summary>
        private static List<string> 拆顶层逗号(string 文本, bool 认全角 = false)
        {
            var 结果 = new List<string>();
            int 深 = 0, 起 = 0;
            for (int i = 0; i < 文本.Length; i++)
            {
                char c = 文本[i];
                if (c == '[' || c == '(') 深++;
                else if (c == ']' || c == ')') { if (深 > 0) 深--; }
                else if ((c == ',' || (认全角 && (c == '，' || c == '、'))) && 深 == 0)
                {
                    结果.Add(文本[起..i].Trim());
                    起 = i + 1;
                }
            }
            结果.Add(文本[起..].Trim());
            return 结果;
        }

        /// <summary>
        /// 元组类型词 → 结构类型;**解析不动给 null**(一条错都不报 —— 报错带行号、带改法,
        /// 交给 `取元组类型` 那一档)。同一份写法只造一次,之后全走缓存 ⇒ **同一个类型处处是同一个对象**。
        /// </summary>
        private 结构类型C? 试取元组类型(string 词) => 解析元组类型(词, out _);

        /// <summary>
        /// 元组类型词 → 结构类型;解析不动**当场报错**(行号 + 说人话 + 给改法)。
        /// 声明 / 字段 / 参数三处都走它,免得写坏一个元组只落一句"无法识别的声明"。
        /// </summary>
        private 结构类型C 取元组类型(string 词, int 行号)
        {
            var 类型 = 解析元组类型(词, out string 为什么);
            if (类型 == null)
                throw 报错(行号, $"元组类型写不出来: '{词.Trim()}' —— {为什么}。" +
                    $"元组写法:`[整数, 整数]`(成员依次叫 .项0 / .项1),也可以给成员起名 `[整数 商, 整数 余]`," +
                    $"元素类型可以再是枚举 / 结构 / 另一个元组",
                    $"bad tuple type: '{词.Trim()}'");
            return 类型;
        }

        /// <summary> 真正的解析:规范写法 / 成员表 / 偏移;失败时 `为什么` 里是一句人话 </summary>
        private 结构类型C? 解析元组类型(string 词, out string 为什么)
        {
            为什么 = "";
            string 类型词 = 取元组词(词);
            if (类型词.Length == 0) { 为什么 = "方括号没配对(少一个 `]`)"; return null; }
            if (_元组表.TryGetValue(类型词, out var 已有)) return 已有;
            string 内 = 类型词[1..^1].Trim();
            if (内.Length == 0) { 为什么 = "`[]` 里一个元素都没有"; return null; }

            var 字段表 = new List<结构字段C>();
            var 规范段 = new List<string>();
            int 偏移 = 0;
            int 序号 = 0;
            foreach (string 一段 in 拆顶层逗号(内))
            {
                string s = 一段.Trim();
                if (s.Length == 0) { 为什么 = "有两个逗号挨在一起(空元素)"; return null; }
                // 元素类型词:可能又是一个元组(嵌套),也可能是一个词(`整数` / 枚举名 / 结构名)
                string 元素类型词 = 取元组词(s);
                string 剩;
                if (元素类型词.Length > 0) 剩 = s[元素类型词.Length..].Trim();
                else
                {
                    元素类型词 = 首词正则.Match(s).Value;
                    if (元素类型词.Length == 0) { 为什么 = $"'{s}' 不像一个类型"; return null; }
                    剩 = s[元素类型词.Length..].Trim();
                }
                string 元素名 = 剩.Length > 0 ? 剩 : $"项{序号}";
                if (剩.Length > 0 && !标识符全词正则.IsMatch(元素名))
                { 为什么 = $"成员名 '{元素名}' 不是合法的名字(要以文字或 `_` 开头)"; return null; }
                if (字段表.Any(f => string.Equals(f.名称, 元素名, StringComparison.OrdinalIgnoreCase)))
                { 为什么 = $"成员名 '{元素名}' 重复了"; return null; }

                // 元素类型:基础类型 / 枚举(底层有符号 整数 4 字节)/ 结构 / 另一个元组
                int 元素宽;
                string 元素类型名;
                结构类型C? 元素结构 = null;
                if (类型C.解析(元素类型词) is { } 基础)
                {
                    元素宽 = 基础.宽度;
                    元素类型名 = 基础.中文;
                }
                else if (查枚举类型(元素类型词) is { } 枚举)
                {
                    元素宽 = 类型C.枚举底层.宽度;
                    元素类型名 = 枚举.名称;
                }
                else if (查结构类型(元素类型词) is { } 结构)
                {
                    元素宽 = 结构.总宽度;
                    元素类型名 = 结构.名称;
                    元素结构 = 结构;
                }
                else if (元素类型词 is "字符串" || string.Equals(元素类型词, "string", StringComparison.OrdinalIgnoreCase))
                {
                    为什么 = "元素是 `字符串` 的元组还没做(字符串字段要住堆、整体赋值要深拷)";
                    return null;
                }
                else
                {
                    为什么 = $"元素类型 '{元素类型词}' 不认识(只能是基础类型 / 枚举 / 结构 / 另一个元组)";
                    return null;
                }

                字段表.Add(new 结构字段C(元素名, 元素类型名, 元素宽, 偏移, 结构类型: 元素结构));
                规范段.Add(元素名 == $"项{序号}" ? 元素类型名 : $"{元素类型名} {元素名}");
                偏移 += 元素宽;
                序号++;
            }

            string 规范 = "[" + string.Join(", ", 规范段) + "]";
            if (_元组表.TryGetValue(规范, out var 同款)) return 同款;      // 空格/写法不同,落地是同一个类型
            var 类型 = new 结构类型C(规范, 字段表);
            _元组表[规范] = 类型;
            _元组表[类型词] = 类型;                                      // 用户这一种写法也记住(下次直接命中)
            // 补全 / 调试窗口要按"结构名 + 字段"认它:`[整数, 整数].` 后面才给得出 项0 / 项1
            _名字表.结构[规范] = 字段表.Select(字段项).ToList();
            return 类型;
        }

        /// <summary> 元组类型的名字(`[整数, 整数]`)——报错 / 编译提示 / 帮助里都用它,别另拼一份 </summary>
        private static string 元组名(结构类型C 结构) => 结构.名称;

        /// <summary> 这个结构类型是不是元组(名字就是那份写法,`[` 开头;老结构名不可能这样起) </summary>
        private static bool 是元组结构(结构类型C? 结构) =>
            结构 is { } 结构值 && 结构值.名称.StartsWith("[", StringComparison.Ordinal);

        /// <summary>
        /// **名义制检查(H68-3)**:两边都是结构、而且**至少一边是元组**时,写法必须一模一样
        /// (`[整数, 整数]` / `[整数 商, 整数 余]` / 同名结构是三个类型)。
        /// <para>
        /// 为什么只查元组这一档:**普通结构之间维持老口径**(同宽就能整块搬)—— 这条只**新增**元组这一档,
        /// 老程序一个字不受影响。元组是这一批新加的语法,严格一点不欠谁的账。
        /// </para>
        /// </summary>
        private void 检查整块类型相配(结构类型C? 目标, 结构类型C? 来源, int 行号, string 目标文本, string 来源文本)
        {
            if (目标 is null || 来源 is null) return;
            if (!是元组结构(目标) && !是元组结构(来源)) return;
            if (string.Equals(目标.名称, 来源.名称, StringComparison.Ordinal)) return;
            throw 报错(行号, $"两边不是同一种类型:'{目标文本}' 是 {目标.名称},'{来源文本}' 是 {来源.名称}。" +
                $"元组按**写法**认类型(`[整数, 整数]` 与 `[整数 商, 整数 余]` 是两个类型,与长得像的结构也不相干)。" +
                $"改法:①两边写成同一种元组;②一个成员一个成员搬(`目标.项0 = 源.商;`),元素类型对得上就行",
                "tuple types are nominal: the written form is the type");
        }

        /// <summary>
        /// 这一段是不是"元组字面量"(`[式子, 式子]`;元组值就是按字段顺序摆一连串式子)。
        /// 与 `是方括号初值` 同一把尺子 —— 区别只在**用在哪**:字面量初值只收常量,
        /// 元组值(H68-4 的 `返回 [a / b, a % b]` 那一档)收**任意式子**。
        /// </summary>
        private static bool 是元组字面量(string 文本)
        {
            string t = 文本.Trim();
            return t.Length >= 2 && t[0] == '[' && t[^1] == ']';
        }

        /// <summary> 元组字面量里的各段式子(`[a / b, a % b]` ⇒ `a / b` / `a % b`);空的那一段留着,由调用点报错 </summary>
        private static List<string> 拆元组字面量(string 文本) => 拆顶层逗号(文本.Trim()[1..^1], 认全角: true);

        /// <summary>
        /// **H68-4**:把元组值 `[式子, 式子]` 按成员顺序算出来,写进**目标那一块**。
        /// `目标地址` = 装着那块起点的寄存器(声明里是变量自己那一格;整体赋值是左边那块;
        /// 函数返回是**调用方给的那个"结果放哪"**)。
        ///
        /// **寄存器纪律**(与 H68-1 多维数组那条硬约束同一个道理):每个成员算完就把这一段借的临时寄存器
        /// **还回池子**(`记占用` / `还占用`)—— 目标地址在快照之前就占着,照旧不会被重复发出去;
        /// 不还的话,成员一多就会撞「临时寄存器用光了」。
        /// </summary>
        private void 发出元组填块(string 目标地址, 结构类型C 结构, string 值文本, int 行号, string 原文)
        {
            var 段们 = 拆元组字面量(值文本);
            if (段们.Count != 结构.字段.Count)
                throw 报错(行号, $"{结构.名称} 有 {结构.字段.Count} 个成员,这里写了 {段们.Count} 个 —— " +
                    $"元组值按成员顺序写,成员之间用逗号隔开", "wrong number of tuple members");
            for (int i = 0; i < 结构.字段.Count; i++)
            {
                var 字段 = 结构.字段[i];
                string 段 = 段们[i].Trim();
                if (段.Length == 0)
                    throw 报错(行号, $"元组值里第 {i + 1} 个成员是空的:'{值文本.Trim()}'", "empty tuple member");
                if (字段.是结构 || 字段.是数组 || 字段.是列表 || 字段.是串字段)
                {
                    string 什么样 = 字段.是结构 ? "结构" : 字段.是数组 ? "数组" : 字段.是串字段 ? "字符串" : "列表";
                    throw 报错(行号, $"元组 {结构.名称} 的成员 '{字段.名称}' 是{什么样},元组值里只收普通数值" +
                        $"(整块塞进去只会写一串假地址)—— 先声明一份,再对它的 '{字段.名称}' 单独赋值",
                        $"tuple member '{字段.名称}' is a {什么样}; assign it separately");
                }
                var 省着 = 记占用();
                string 值 = 新临时();
                输出赋值到寄存器(值, 替换地址取用(段, 行号, 原文), 行号, 原文);
                发出间接写(值, 基址加偏移(目标地址, 字段.偏移), 字段.宽度);
                还占用(省着);
            }
        }
    }
