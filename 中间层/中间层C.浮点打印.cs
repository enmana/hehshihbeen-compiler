    /// ③ **打不出来就如实打"尾数*2^指"**(见下"两段路"),不猜、不静默算错。
    /// ④ **不建帧、不改 R15** —— 例程只用硬件栈(PUSH/POP)与 R0~R13,`调用`/`返回` 配平。
    /// </para>
    /// </summary>
