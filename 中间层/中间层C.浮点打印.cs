        /// <para>
        /// **调用约定**:R0 进 = 那 32 位单精度位模式,出来时文字已经打到标准输出上了;
        /// 允许破坏 R0~R11(项目里别处也是这个口径:跨 `调用` 的临时寄存器一概不算数);
        /// **R12~R15 保持不动**(R15 是帧指针,例程一个字都不碰)。
        /// </para>
        /// <para>
        /// **两段路**(按二进制指数 `binExp` 分):
        /// </para>
        /// <list type="bullet">
        /// <item><b>十进制那条</b>(`binExp` 在 `[-46, 41]`,也就是 |值| 约 `1.4e-14` ~ `4.4e12`):
        ///       把值缩成 `[1e6, 1e7)` 的 **7 位有效数字**,小数点按 `d = floor(binExp × log10 2)` 摆;
        ///       `d` 在 `[-5, 6]` 内(即 |值| 在 `1e-4` ~ `1e7`)打**定点**(`1.5` / `0.3333333`),
        ///       否则打**指数写法**(`1.234568e+30` / `5e-45`)。</item>
        /// <item><b>二进制那条</b>(超出上面那个区间,即 |值| 大于约 `4.4e12` 或小于约 `1.4e-14`):
        ///       十进制展开要**128 位除法**(这一步还没做),这一段就**如实打 `尾数*2^指`** ——
        ///       精确、可逆,绝不猜一个"看着像对的"十进制数出来。
        ///       (例:`3.4028235e38` 打 `16777215*2^104`;`1e-20` 打 `11920929*2^-73`。)</item>
        /// </list>
        /// <para>
        /// **缩放怎么算**(十进制那条):`h = m × 10^n / 2^sh`,`m × 10^n` 是 64 位量(高低 32 位各一个寄存器)。
        /// `sh` 按大小分三档:小于 32 时"高 32 位右移 + 把移出去的位接到低 32 位前面"一步到位;
        /// 32~63 时先除 `2^32` 再除 `2^(sh-32)`;大于 63 时商必为 0。
        /// **两次截断除与一次除同商**(整数除法那条 `⌊⌊x/a⌋/b⌋ = ⌊x/(ab)⌋` 的余数条件),逐档验过。
        /// </para>
        /// <para>
        /// 有效数字以外的位**一律丢掉**(不猜十进制)—— 与库里 `浮点32转字符串` 同一个取舍:
        /// `0.1` 打出来就是 `0.1`,不是 `0.100000001490116`。
        /// </para>
        /// </summary>
