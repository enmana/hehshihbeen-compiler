    /// 这么留着是**有意的**:宁可报错,也绝不把位模式当整数打出去(那会打出 `1069547520` 这种静默错误)。
    /// 本文件与 <see cref="浮点打印例程正文"/> 是**可以继续的下一步**:骨架、口径、算法都定死了,
    /// 剩下的是把例程里的算术调对(下面"已查明/已修/下一个坑"那张清单就是交接)。
    /// </para>
    /// <para>
    /// **为什么要有它**:浮点值就是一个寄存器里的 32 位 IEEE754 单精度**位模式**,
    /// 按整数打印会打出 `1069547520` 这种"看着像算错了"的数 —— 那是**静默错误**。
    /// </para>
