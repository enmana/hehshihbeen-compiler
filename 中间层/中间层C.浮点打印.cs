        /// <summary>
        /// 生成"位模式 → 十进制文字并打印"的例程 —— 只生成一次,进 `_列表例程` 那一列
        /// (与打印串例程同一个套路)。汇编正文在 <see cref="浮点打印例程正文"/> 里
        /// (由 `工具\临时\通用化测量\生成浮点打印例程.py` 生成),这里只做两件事:
