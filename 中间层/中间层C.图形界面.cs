    /// <summary>
    /// 中间层展开器的一部分:**图形界面(R1-6 批 1)的 10 条原语**。
    ///
    /// 它们与 P28 的宿主能力**同一档**(不是关键字,是内建函数;中英可整体切换),走的是**同一条通道**
    /// (`宿主调用` 0x31 + 功能号 60~69,见 `图形宿主C`),所以 ISA 一条指令都没加。
    ///
    /// 返回值分两档,和它们在语言里的身份对应(`未做任务清单.md` §19 那张定案表):
    ///
    /// | 档 | 名字 | 怎么写 | 语言上的返回值 |
    /// |---|---|---|---|
    /// | **命令** | 清屏 / 画文字 / 画矩形 / 画线 / 等待 / 关闭窗口 / 刷新 | 单独成句(`清屏(颜色);`) | 没有 |
    /// | **有结果** | 打开窗口 / 取事件 | 结果要用起来 | `逻辑` |
    /// | **有结果** | 取文字宽度 | 结果要用起来 | `整数` |
    ///
    /// 为什么画图的那些**不给返回值**:它们本来就是"发一条命令",逼着用户写
    /// `如果 (画文字(…)) { … }` 是把画面代码写坏;成没成看**开头那一问**就够
    /// (`打开窗口` 给 `假` = 这个宿主没有图形能力,别画了)—— 与 `输出行(…)` 一样的身份。
    /// </summary>
    internal partial class 中间层展开器
    {
        #region 图形界面(R1-6 批 1):打开窗口 / 关闭窗口 / 清屏 / 画文字 / 画矩形 / 画线 / 刷新 / 取事件 / 等待 / 取文字宽度

        /// <summary> 名字口径见 `未做任务清单.md` §19(用户 2026-09-22 定名:写 `打开窗口`/`关闭窗口`,不写"开窗/关窗")</summary>
        private static bool 是图形语句名(string 词) =>
            词 is "清屏" or "clearwindow"
               or "画文字" or "drawtext"
               or "画矩形" or "drawrect"
               or "画线" or "drawline"
               or "等待" or "sleep"
               or "关闭窗口" or "closewindow"
               or "刷新" or "present";

        /// <summary> 有返回值的那三条:`打开窗口` / `取事件`(逻辑)与 `取文字宽度`(整数) </summary>
        private static bool 是图形值能力名(string 词) =>
            词 is "打开窗口" or "openwindow"
               or "取事件" or "pollevent"
               or "取文字宽度" or "textwidth";

        private static bool 是图形能力名(string 词) => 是图形语句名(词) || 是图形值能力名(词) || 是位图能力名(词);

        // ================= R4-12:位图那一族(功能号 70~74)=================
        //
        //   口径(写给用的人看,与帮助那一节逐字对齐):
        //     `建位图(宽, 高) → 整数`            建一张离屏图;拿到的是**句柄**(≥1),建不出给 -1
        //     `释放位图(句柄) → 逻辑`            还给宿主;**再用那个号一律给假**(旧号永不复用)
        //     `画点到图(句柄, x, y, 颜色) → 逻辑`  离屏画一个像素(越界**不报错**,什么都不做)
        //     `取图像素(句柄, x, y) → 整数`       读一个像素(0xAARRGGBB;坐标越界给 0;句柄不认那一格**不做承诺**)
        //     `位图尺寸(句柄, 宽变量, 高变量) → 逻辑` 两个出参写回那张图的宽高
        //
        //   ⚠ **它不要窗口**:离屏画点与"窗口开没开"无关(宿主那边也是这么接的)。
        //   ⚠ 句柄是**宿主侧**的号(位图的像素不放 HB 的运行内存里 —— 一张 480×520 的图就 1 MB)。
        private static bool 是位图能力名(string 词) =>
            词 is "建位图" or "makebitmap"
               or "释放位图" or "freebitmap"
               or "画点到图" or "putpixel"
               or "取图像素" or "getpixel"
               or "贴位图" or "blitbitmap"
               or "画线到图" or "drawlineto"
               or "画矩形到图" or "drawrectto"
               or "位图尺寸" or "bitmapsize"
               // 号 78(控 1-①,第417批):位图上画字 —— **这一条要呈现口**(字形光栅化只有平台有)
               or "贴文字到位图" or "texttobitmap";

        private static string 位图规范名(string 名) => 名 switch
        {
            "建位图" or "makebitmap" => "makebitmap",
            "释放位图" or "freebitmap" => "freebitmap",
            "画点到图" or "putpixel" => "putpixel",
            "取图像素" or "getpixel" => "getpixel",
            "贴位图" or "blitbitmap" => "blitbitmap",
            "画线到图" or "drawlineto" => "drawlineto",
            "画矩形到图" or "drawrectto" => "drawrectto",
            "贴文字到位图" or "texttobitmap" => "texttobitmap",
            _ => "bitmapsize",
        };

        /// <summary> 图形原语的规范名(中英两侧归一) </summary>
        private static string 图形规范名(string 名) => 名 switch
        {
            "打开窗口" or "openwindow" => "openwindow",
            "关闭窗口" or "closewindow" => "closewindow",
            "清屏" or "clearwindow" => "clearwindow",
            "画文字" or "drawtext" => "drawtext",
            "画矩形" or "drawrect" => "drawrect",
            "画线" or "drawline" => "drawline",
            "刷新" or "present" => "present",
            "取事件" or "pollevent" => "pollevent",
            "等待" or "sleep" => "sleep",
            _ => "textwidth",
        };

        /// <summary>
        /// 单独成句的图形命令(`清屏(颜色);` / `画文字(…);` / `等待(16);`)。
        ///
        /// 与 `试处理堆动作` / `试处理列表动作` 同一处下手:在关键字分发之前认出来就地展开。
        /// 认不出返回 false(不是这几条,接着走原来的路)。
        /// </summary>
        private bool 试处理图形动作(string 内容, int 行号)
        {
            string 文本 = 内容.Trim();
            int 左括号 = 文本.IndexOf('(');
            if (左括号 <= 0) return false;
            string 名 = 文本[..左括号].Trim();
            // R4-12:**位图那几条也能单独成句**(`画点到图(图, x, y, 红);` / `贴位图(图, 0, 0);`)。
            //   为什么单列一档:它们是"有返回值的那一类",而单独成句时**返回值丢掉就行** ——
            //   第一版没接这一档,于是 `画点到图(图,0,0,红);` 报"未定义的函数/方法",
            //   逼着用户写 `逻辑 画了 = 画点到图(…);`(实测踩过)。
            if (是位图能力名(名))
            {
                if (是用户函数名(名)) return false;                // 用户自己定义了同名函数:走正常调用那条路
                if (!文本.EndsWith(')'))
                    throw 报错(行号, $"{名} 这句写法不对:'{内容}'。括号要配平,整句末尾才是分号",
                        $"malformed bitmap call: '{内容}'");
                准备语句占用(文本);
                string 位图展开 = 替换地址取用(文本, 行号, 内容);
                var 位图调用 = (调用节点C)表达式语法C.解析(位图展开);
                求值位图能力(位图调用, 行号, 内容);                  // 返回值不要:单独成句时它只是个动作
                return true;
            }
            if (!是图形语句名(名)) return false;
            if (是用户函数名(名)) return false;                    // 用户自己定义了同名函数:走正常调用那条路
            if (!文本.EndsWith(')'))
                throw 报错(行号, $"{名} 这句写法不对:'{内容}'。括号要配平,整句末尾才是分号",
                    $"malformed graphics call: '{内容}'");

            准备语句占用(文本);
            string 展开 = 替换地址取用(文本, 行号, 内容);           // 实参里的 地址(...) / 堆调用 先变成寄存器
            var 调用 = (调用节点C)表达式语法C.解析(展开);
            发图形原语(调用, 行号, 内容);                          // 状态码不要:这几条是"命令"
            return true;
        }

        /// <summary>
        /// 表达式里的图形原语(`打开窗口("标题", 320, 200)` / `刷新()` / `取事件(类型, 键码, x, y)` / `取文字宽度(文本)`)。
        ///
        /// 一律"先攒命令、`刷新` 时整批交给呈现口"(即时模式);参数块在数据段里,一次调用最多多占一个临时寄存器。
        /// </summary>
        private 表达式值 求值图形能力(调用节点C 调用, int 行号, string 原文)
        {
            // R4-12:位图那一族自己一条路(它不要窗口、参数形状也与那十条原语不同)
            if (是位图能力名(调用.名) && !是用户函数名(调用.名))
                return 求值位图能力(调用, 行号, 原文);

            string 规范 = 图形规范名(调用.名);

            // 取事件:四个出参要写回调用方的变量(实参必须是变量名)—— 它是"有值"那一档的
            if (规范 == "pollevent") return 求值取事件(调用, 行号, 原文);

            // 取文字宽度:唯一的"返回整数"那条(纯计算,不需要窗口)
            if (规范 == "textwidth")
            {
                if (调用.实参.Count != 1)
                    throw 报错(行号, $"取文字宽度(文本) 要一个参数:{说明写法(规范)}",
                        "textwidth(…) takes one argument");
                string 量块 = 新槽(16).名称;
                实参串入块(调用, 0, 量块, 0, 行号, 原文);
                string 量块址 = 新临时();
                发出($"取地址 {量块址} {量块}");
                string 量状态 = 发出宿主调用(量块址, 图形宿主C.功能_取文字宽度);
                发出($"存字 {量状态} {量块}+12");            // 状态先落内存:下面 取字 要用临时寄存器
                string 宽寄存器 = 新临时();
                发出($"取字 {宽寄存器} {量块}+8");
                return 表达式值.寄存器值(宽寄存器, 可写: true);
            }

            string 状态 = 发图形原语(调用, 行号, 原文);
            return 状态转逻辑(状态, 行号, 谁写法(规范));
        }

        /// <summary>
        /// 把一个表达式的值弄进一个寄存器(`表达式值` 有三种形状:常量 / 已在寄存器 / 在槽里)。
        /// 位图那一族要"算一个、立刻存进参数块",所以需要一个统一的出口。
        /// </summary>
        private string 位图值进寄存器(表达式值 值, int 行号, string 谁)
        {
            if (值.寄存器 is { } 已有) return 已有;
            if (值.是常量)
            {
                string 寄 = 新临时();
                输出装载常量(寄, 值.常量);
                return 寄;
            }
            if (值.槽 is { } 位置)
            {
                string 寄 = 新临时();
                发出读变量(寄, 位置);
                return 寄;
            }
            throw 报错(行号, $"{谁} 的参数算不出一格能用的值(内部问题,请回报)", "bitmap argument is not a value");
        }

        /// <summary>
        /// **位图那一族**(R4-12)。五条各要几个参数、哪个是出参,见 `是位图能力名` 上面那段口径。
        /// 参数块一律 16 字节(参数区最多用到 +12 那一格)。
        /// </summary>
        private 表达式值 求值位图能力(调用节点C 调用, int 行号, string 原文)
        {
            string 规范 = 位图规范名(调用.名);
            int 要几个 = 规范 switch
            {
                "makebitmap" => 3,      // 宽, 高, 句柄变量(❗句柄**写回这个变量**,所以要给变量名)
                "freebitmap" => 1,      // 句柄
                "putpixel" => 4,        // 句柄, x, y, 颜色
                "getpixel" => 3,        // 句柄, x, y
                "blitbitmap" => 3,      // 句柄, x, y
                "drawlineto" => 6,      // 句柄, x1, y1, x2, y2, 颜色
                "drawrectto" => 6,      // 句柄, x, y, 宽, 高, 颜色
                "texttobitmap" => 5,    // 句柄, x, y, 文本, 颜色(号 78)
                _ => 3,                 // 位图尺寸:句柄, 宽变量, 高变量
            };
            if (调用.实参.Count != 要几个)
                throw 报错(行号, $"{调用.名} 要 {要几个} 个参数:" + 规范 switch
                {
                    "makebitmap" => "建位图(宽, 高, 句柄变量) —— 句柄**写回第三个参数那个整数变量**(建不出写 -1)。" +
                        "图在**宿主侧**,不占运行内存;句柄从 1 起,拿它去 画点到图 / 取图像素 / 位图尺寸 / 释放位图",
                    "freebitmap" => "释放位图(句柄) —— 还给宿主;再用那个号一律给假",
                    "putpixel" => "画点到图(句柄, x, y, 颜色) —— 离屏画一个像素;越界不报错(什么都不做)",
                    "getpixel" => "取图像素(句柄, x, y) —— 读一个像素(0xAARRGGBB);坐标越界给 0;" +
                        "⚠ **句柄不认**那一档(int 那条路只给状态码、不写结果)**那一格的值不做承诺** ——" +
                        "要判『这张图还在不在』先用 `位图尺寸(句柄, 宽, 高)`(它给假)",
                    "blitbitmap" => "贴位图(句柄, x, y) —— 把整张图**一次**贴到窗口那个位置;" +
                        "这一条就是『帧数不再随画了多少东西涨』的那个出口(**一次贴一整块**,不是几万条画矩形)",
                    "drawlineto" => "画线到图(句柄, x1, y1, x2, y2, 颜色) —— 与 `画线` 同口径,画到**离屏**;" +
                        "**一条命令画一整条线**(不是逐个像素画)",
                    "drawrectto" => "画矩形到图(句柄, x, y, 宽, 高, 颜色) —— 实心矩形,画到**离屏**",
                    "texttobitmap" => "贴文字到位图(句柄, x, y, 文本, 颜色) —— 把一行字**画进这张图**;" +
                        "⚠ 这一条**要呈现口**(字形光栅化只有平台有):没挂呈现口 / 无头那一档给『没挂能力』," +
                        "图一个像素都不动;两套字体栈不保证逐字节相同 ⇒ 跨腿只能做到形状级",
                    _ => "位图尺寸(句柄, 宽变量, 高变量) —— 两个出参要写**变量名**,宽高写回它们",
                }, $"bitmap call takes {要几个} arguments");

            // ⚠ 参数块要 **24 字节**(6 格):位图那几条最多用到 +20
            //   (`取图像素` 的出参地址在 +16、状态落脚 +20 —— 与宿主那张 `参数区字节数` 表对齐)
            string 块 = 新槽(24).名称;
            string 块址 = 新临时();
            发出($"取地址 {块址} {块}");

            // ① 输入参数按顺序填参数块。
            //   ⚠ `建位图` 的**第一个**格是"句柄写回哪个槽"(地址),不是句柄 —— 见宿主那段说明。
            if (规范 == "makebitmap")
            {
                string 句柄址 = 取左值地址(实参文本(2, 调用.实参), 行号, 原文);
                发出($"存字 {句柄址} {块}+0");
                表达式值 宽值 = 求值节点(调用.实参[0], 行号, 原文, null);
                发出($"存字 {位图值进寄存器(宽值, 行号, 调用.名)} {块}+4");
                表达式值 高值 = 求值节点(调用.实参[1], 行号, 原文, null);
                发出($"存字 {位图值进寄存器(高值, 行号, 调用.名)} {块}+8");
            }
            else
            {
                int 输入数 = 规范 switch { "freebitmap" => 1, "putpixel" => 4, "getpixel" => 3, "blitbitmap" => 3, "drawlineto" => 6, "drawrectto" => 6, "texttobitmap" => 3, _ => 1 };
                for (int i = 0; i < 输入数; i++)
                {
                    表达式值 值 = 求值节点(调用.实参[i], 行号, 原文, null);
                    发出($"存字 {位图值进寄存器(值, 行号, 调用.名)} {块}+{i * 4}");
                }
                // ②-0 `贴文字到位图`(号 78):文本那一格是**字符串**(实参串入块 写址 + 长),
                //     颜色跟在 +20 —— 与宿主那张参数区表(24 字节:句柄/x/y/文本址/文本长/颜色)逐格对齐
                if (规范 == "texttobitmap")
                {
                    实参串入块(调用, 3, 块, 12, 行号, 原文);
                    实参入块(调用, 4, 块, 20, 行号, 原文);
                }
                // ② `位图尺寸` 的两个出参:把**变量地址**写进 +4 / +8
                if (规范 == "bitmapsize")
                {
                    string 宽址 = 取左值地址(实参文本(1, 调用.实参), 行号, 原文);
                    string 高址 = 取左值地址(实参文本(2, 调用.实参), 行号, 原文);
                    发出($"存字 {宽址} {块}+4");
                    发出($"存字 {高址} {块}+8");
                }
                // ③ `取图像素` **不要出参变量** —— 它是"当表达式用"的那一条:
                //   结果由宿主写回参数块 +12(颜色输入那一格用不上),下面从那儿取。
                //   ⚠ 第一版这里给它要了个"出参变量",而调用方写的是 `输出行(取图像素(图, 10, 20))`
                //   —— 于是 实参文本(2) 拿到的是 `10`,`取左值地址` 当场报错(实测)。
            }

            int 功能号 = 规范 switch
            {
                "makebitmap" => 图形宿主C.功能_建位图,
                "freebitmap" => 图形宿主C.功能_释放位图,
                "putpixel" => 图形宿主C.功能_画点到图,
                "getpixel" => 图形宿主C.功能_取图像素,
                "blitbitmap" => 图形宿主C.功能_贴位图,
                "drawlineto" => 图形宿主C.功能_画线到图,
                "drawrectto" => 图形宿主C.功能_画矩形到图,
                "texttobitmap" => 图形宿主C.功能_贴文字到位图,
                _ => 图形宿主C.功能_位图尺寸,
            };
            string 块址2 = 新临时();
            发出($"取地址 {块址2} {块}");
            string 状态 = 发出宿主调用(块址2, 功能号);

            // ③ 有没有返回值:`取图像素` 给颜色;别的给逻辑(`建位图` 的句柄已经**直接写进调用方那个变量**了)
            if (规范 == "getpixel")
            {
                // ⚠ 结果就在参数块 **+12**(宿主写回的"参数4");状态落脚在没人用的 +20。
                发出($"存字 {状态} {块}+20");
                string 颜色 = 新临时();
                发出($"取字 {颜色} {块}+12");
                return 表达式值.寄存器值(颜色, 可写: true);
            }
            return 状态转逻辑(状态, 行号, 调用.名);
        }

        /// <summary>
        /// 攒一条命令 / 开窗 / 关窗 / 刷新 / 等待:填参数块、发一条 `宿主调用`,返回**状态码寄存器**(0 = 成功)。
        /// 参数一律"算一个、立刻存进参数块",后面再算别的也不会把它冲掉。
        /// </summary>
        private string 发图形原语(调用节点C 调用, int 行号, string 原文)
        {
            string 规范 = 图形规范名(调用.名);
            int 要几个 = 规范 switch
            {
                "openwindow" => 3,
                "drawtext" => 4,
                "drawrect" or "drawline" => 5,
                "clearwindow" or "sleep" => 1,
                _ => 0,                                  // closewindow / present
            };
            if (调用.实参.Count != 要几个)
                throw 报错(行号, $"{谁写法(规范)}({参数写法(规范)}) 要{要几个}个参数:{说明写法(规范)}",
                    $"{规范}(…) takes {要几个} argument(s)");

            // ---- 没有参数的两位:关闭窗口 / 刷新 ----
            if (规范 is "closewindow" or "present")
            {
                string 空块 = 新槽(16).名称;
                string 空块址 = 新临时();
                发出($"取地址 {空块址} {空块}");
                return 发出宿主调用(空块址, 规范 == "closewindow" ? 图形宿主C.功能_关闭窗口 : 图形宿主C.功能_刷新);
            }

            string 块 = 新槽(规范 == "openwindow" ? 16 : 20).名称;
            switch (规范)
            {
                case "openwindow":
                    实参串入块(调用, 0, 块, 0, 行号, 原文);     // 标题址 / 标题长
                    实参入块(调用, 1, 块, 8, 行号, 原文);       // 宽
                    实参入块(调用, 2, 块, 12, 行号, 原文);      // 高
                    break;
                case "clearwindow":
                    实参入块(调用, 0, 块, 0, 行号, 原文);       // 颜色
                    break;
                case "drawtext":
                    实参入块(调用, 0, 块, 0, 行号, 原文);       // x
                    实参入块(调用, 1, 块, 4, 行号, 原文);       // y
                    实参串入块(调用, 2, 块, 8, 行号, 原文);     // 文本址 / 文本长
                    实参入块(调用, 3, 块, 16, 行号, 原文);      // 颜色
                    break;
                case "drawrect":
                    实参入块(调用, 0, 块, 0, 行号, 原文);       // x
                    实参入块(调用, 1, 块, 4, 行号, 原文);       // y
                    实参入块(调用, 2, 块, 8, 行号, 原文);       // 宽
                    实参入块(调用, 3, 块, 12, 行号, 原文);      // 高
                    实参入块(调用, 4, 块, 16, 行号, 原文);      // 颜色
                    break;
                case "drawline":
                    实参入块(调用, 0, 块, 0, 行号, 原文);       // x1
                    实参入块(调用, 1, 块, 4, 行号, 原文);       // y1
                    实参入块(调用, 2, 块, 8, 行号, 原文);       // x2
                    实参入块(调用, 3, 块, 12, 行号, 原文);      // y2
                    实参入块(调用, 4, 块, 16, 行号, 原文);      // 颜色
                    break;
                default:                                     // sleep
                    实参入块(调用, 0, 块, 0, 行号, 原文);       // 毫秒
                    break;
            }
            string 块址 = 新临时();
            发出($"取地址 {块址} {块}");
            int 功能号 = 规范 switch
            {
                "openwindow" => 图形宿主C.功能_打开窗口,
                "clearwindow" => 图形宿主C.功能_清屏,
                "drawtext" => 图形宿主C.功能_画文字,
                "drawrect" => 图形宿主C.功能_画矩形,
                "drawline" => 图形宿主C.功能_画线,
                _ => 图形宿主C.功能_等待,
            };
            return 发出宿主调用(块址, 功能号);
        }

        /// <summary>
        /// `取事件(类型, 键码, x, y) 返回 逻辑` —— 有事件给真(四个变量被写满),没有给假(不阻塞)。
        /// 实参写的是**四个变量名**(不是表达式):宿主只往它的参数块里写,中间层再把四个值搬进那几个变量。
        /// </summary>
        private 表达式值 求值取事件(调用节点C 调用, int 行号, string 原文)
        {
            if (调用.实参.Count != 4)
                throw 报错(行号, $"取事件({参数写法("pollevent")}) 要四个参数:{说明写法("pollevent")}",
                    "pollevent(…) takes four arguments");
            for (int i = 0; i < 4; i++)
                if (调用.实参[i] is not 名字节点C)
                    throw 报错(行号, $"取事件(类型, 键码, x, y) 的四个参数要写**变量名**(事件的值写回它们):" +
                        $"第 {i + 1} 个现在是 '{调用.实参[i].显示()}'。" +
                        $"办法:先 `整数 类型; 整数 键码; 整数 x; 整数 y;`,再 `如果 (取事件(类型, 键码, x, y)) {{ … }}`",
                        "pollevent needs four variable names");

            // 事件块 5 个字:类型 / 键码 / x / y / 状态
            string 块 = 新槽(20).名称;
            string 块址 = 新临时();
            发出($"取地址 {块址} {块}");
            string 状态 = 发出宿主调用(块址, 图形宿主C.功能_取事件);
            发出($"存字 {状态} {块}+16");                       // 状态先落内存:下面每一步都要用临时寄存器
            // 四个出参**一次一对寄存器**,写完就还回去 —— 不然 8 个寄存器一起占着,
            // 这个调用又常常写在 `当 (取事件(…))` 这种"外面本来就占着寄存器"的位置(实测当场"临时寄存器用光")
            var 基准占用 = new List<string>(_语句占用 ?? []);
            for (int i = 0; i < 4; i++)
            {
                string 名字 = 实参文本(i, 调用.实参);
                string 值 = 新临时();
                发出($"取字 {值} {块位(块, i * 4)}");
                // 变量直接写(**一条 存字/存字帧**):不走"取地址 + 间接写"那条 ——
                // 间接写对循环不变量提升是隐形的(它只看源码里的赋值形态),而这条是编译器自己造的写
                if (查位置(名字, 行号, 原文) is { } 位置) 发出写变量(值, 位置);
                else
                {
                    string 目标址 = 取左值地址(名字, 行号, 原文);
                    发出间接写(值, 目标址, 4);
                }
                _语句占用 = [.. 基准占用];
                _语句常量 = null;
            }
            string 最终状态 = 新临时();
            发出($"取字 {最终状态} {块}+16");
            return 状态转逻辑(最终状态, 行号, "取事件");
        }

        /// <summary> 参数块里第 `偏移` 个字的写法(0 偏移不写 `+0`,与 P28 那批的文本一致) </summary>
        private static string 块位(string 块, int 偏移) => 偏移 == 0 ? 块 : $"{块}+{偏移}";

        /// <summary> 算第 i 个实参,算完**立刻**存进参数块(这样后面再算别的也不会冲掉它)</summary>
        private void 实参入块(调用节点C 调用, int i, string 块, int 偏移, int 行号, string 原文)
        {
            表达式值 值 = 求值表达式(调用.实参[i].显示(), 行号, 原文);
            发出($"存字 {取操作数寄存器(值)} {块位(块, 偏移)}");
        }

        /// <summary> 第 i 个实参是字符串:地址与长度一起进参数块(算完立刻存)</summary>
        private void 实参串入块(调用节点C 调用, int i, string 块, int 偏移, int 行号, string 原文)
        {
            (string 址, string 长) = 字符串地址与长(调用.实参[i], 行号, 原文);
            发出($"存字 {址} {块位(块, 偏移)}");
            发出($"存字 {长} {块位(块, 偏移 + 4)}");
        }

