        /// <summary>
        /// `调用名` 尾部的方法名换成规范中文:`表.length` → `表.长度`、`记录.名字.Clear` → `记录.名字.清空`;
        /// 尾部不是方法名就**原样返回**(普通函数名 / 无点名字一个字不动)。
        /// 编译器各处的"方法是中文名"判断因此不用各自再认一遍英文 —— 先归一,后照旧。
        /// </summary>
        public static string 规范方法名(string 名)
        {
            if (string.IsNullOrEmpty(名)) return 名;
            int 点 = 名.LastIndexOf('.');
            if (点 < 0 || 点 == 名.Length - 1) return 名;
            string 动作 = 名[(点 + 1)..].Trim();
            if (动作.Length == 0) return 名;
            return 到方法中文名(动作) is { } 中文 ? string.Concat(名.AsSpan(0, 点 + 1), 中文) : 名;
        }

        /// <summary>
        /// 文本**结尾**是不是"点 + 方法名"(`…长度()` / `…length`),中英都认。
        /// 给出 (规范中文名, 结尾实际写成的那段文本) —— 调用方按 `后缀.Length` 砍掉它拿基名
        /// (英文比中文长,所以不能按中文那段的长度砍)。
        /// 只认紧贴结尾、中间不隔空格的写法;结尾允许带一对 `()`。
        /// </summary>
        public static (string 中文, string 后缀)? 取结尾方法(string 文本)
        {
            if (string.IsNullOrEmpty(文本)) return null;
            string 段 = 文本;
            if (段.EndsWith("()", StringComparison.Ordinal)) 段 = 段[..^2];
            int 点 = 段.LastIndexOf('.');
            if (点 < 0) return null;
            string 动作 = 段[(点 + 1)..];
            if (动作.Length == 0) return null;
            foreach (char c in 动作)
                if (!char.IsLetterOrDigit(c) && c != '_') return null;
            return 到方法中文名(动作) is { } 中文 ? (中文, 文本[点..]) : null;
        }

        /// <summary> 同上,但 `.长度()` 是**只读**的,不算"动作"(S12:循环里提字符串字数要用它)</summary>
