        /// </summary>
        public static string 建议变量名(string 词)
        {
            string 名 = (词 ?? "").Trim();
            if (名.Length == 0) return "变量1";
            bool 全ASCII = 名.All(c => c < 128);
            string[] 候选 = 全ASCII
                ? [名 + "_", "我的" + 名, 名 + "1"]
                : [名 + "值", 名 + "项", "我的" + 名];
            foreach (string 试 in 候选)
                if (!是保留字(试)) return 试;
            for (int i = 2; ; i++)
            {
                string 试 = 名 + i;
                if (!是保留字(试)) return 试;
            }
        }

