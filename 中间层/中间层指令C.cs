        /// <summary>
        /// 这个位置往后(跳过空格/制表符)是不是紧跟一个 `(`。
        /// 中英切换用它区分"函数/运算符那种带括号的写法"与"类型名/汇编助记符那种裸写法"。
        /// </summary>
        public static bool 后面紧跟左括号(string 段, int 从哪)
        {
            if (string.IsNullOrEmpty(段)) return false;
            for (int i = 从哪; i < 段.Length; i++)
            {
                char c = 段[i];
                if (c is ' ' or '\t') continue;
                return c == '(';
            }
            return false;
        }

        /// <summary>
        /// `返回` 的**两张皮**(中英切换两个 pass 都靠它决定去向):
        ///   · 这一行从它往后到行尾只有空白 → **汇编那种裸写法**(= RET),不该翻成语言关键字 `return`;
        ///   · 后面还跟着东西(`返回 值`)→ 语言的返回。
        /// 传进来的"段"是去掉注释与字面量之后的一段代码,所以行尾的 `// 注释` 不会干扰这里的判断。
        /// </summary>
        public static bool 是裸返回(string 段, int 从哪)
        {
            if (string.IsNullOrEmpty(段)) return true;
            for (int i = 从哪; i < 段.Length; i++)
            {
                if (段[i] == '\n') return true;
                if (!char.IsWhiteSpace(段[i])) return false;
            }
            return true;
        }

        /// <summary>
        /// 这一段(位置=词在本行里的起始下标)算不算一个"内建函数 / 方法"的高亮位。
        /// **编辑器(语法高亮C)与综合自检共用这一套判断** —— 免得"高亮用的边界规则"两处各写一份。
        /// 规则:
        ///   · 左右两边都不能粘着字母/数字(和指令/关键字高亮一致);
        ///   · 方法(`长度`/`清空`/`添加`)是**带点调用**的,要求前面紧跟 `.`
        ///     —— 不然用户起个叫 `添加` 的变量也会被涂成方法色。
        /// </summary>
        public static bool 是内建词高亮位(string 行, int 位置, string 词)
        {
            if (string.IsNullOrEmpty(行) || string.IsNullOrEmpty(词)) return false;
            if (位置 < 0 || 位置 + 词.Length > 行.Length) return false;
            if (string.CompareOrdinal(行, 位置, 词, 0, 词.Length) != 0) return false;
            if (是方法名(词))
            {
                if (位置 == 0 || 行[位置 - 1] != '.') return false;
            }
            else if (位置 > 0 && char.IsLetterOrDigit(行[位置 - 1])) return false;
            int 止 = 位置 + 词.Length;
            return 止 >= 行.Length || !char.IsLetterOrDigit(行[止]);
        }

        /// <summary>
        /// 把源码中的流程控制关键字整体切换语言（英文→中文 或 中文→英文）。
        /// 供“中英切换”按钮使用；指令名由 指令C.切换指令名语言 负责。
        /// **注释与字符串/字符字面量原样保留**,只替换代码段
        /// (字面量里也常写着 `字符串`/`如果` 这种词,改了就是偷偷改了程序的数据)。
        /// </summary>
        public static string 切换关键字语言(bool 使用中文, string 代码)
        {
            var 替换表 = 关键字表
                .Select(x => 使用中文 ? (旧: x.英文, 新: x.中文) : (旧: x.中文, 新: x.英文))
                .OrderByDescending(x => x.旧.Length)
                .ToArray();

            string 局部替换(string 段)
            {
                string 当前 = 段;
                foreach (var (旧词, 新词) in 替换表)
                {
                    var 替换正则 = new Regex($"(?<![\\p{{L}}\\p{{N}}])(?:{Regex.Escape(旧词)})(?![\\p{{L}}\\p{{N}}])");
                    string 本段 = 当前;
                    当前 = 替换正则.Replace(本段, m =>
                    {
                        int 词后 = m.Index + m.Length;
                        // `地址` 有**三张脸**,带不带括号去向不一样:
                        //   类型名 `地址 地 = 申请(16);`  → `addr`(英文类型名,不是 address)
                        //   取址运算符 `地址(x)`            → `address(x)`(见 中间层C.地址引用正则)
                        // 同名不同词,所以这里要按"后面跟不跟 `(`"分开翻,不能一律翻成 `addr`(实测踩到)。
                        if (旧词 == "地址" && 后面紧跟左括号(本段, 词后)) return "address";
                        if (旧词 == "addr" && 后面紧跟左括号(本段, 词后)) return "地址";
                        // 裸 `返回`(整行只有它)是**汇编 RET**:交给 指令C.切换指令名语言 翻成 `RET`,
                        // 这里一个字不动 —— 翻成语言关键字 `return` 就变成"函数外的 return",当场报错(实测踩到)。
                        if (旧词 == "返回" && 是裸返回(本段, 词后)) return m.Value;
                        return 新词;
                    });
                }
                // 英文那份取址运算符 `address(x)`(中文 `地址(x)`)不在 关键字表 里(类型名是 `addr`),
                // 所以单独补一条,让带括号的运算符两边都能来回翻。
                if (使用中文)
                    当前 = new Regex(@"(?<![\p{L}\p{N}])address(?=\s*\()").Replace(当前, "地址");
                return 当前;
            }

            var 结果 = new StringBuilder();
            var 保护区表 = 代码解析器.取保护改写区(代码);
            int 位置 = 0;
            foreach (var (开始, 结束) in 保护区表)
            {
                结果.Append(局部替换(代码[位置..开始]));
                结果.Append(代码, 开始, 结束 - 开始);   // 注释/字面量原样保留
                位置 = 结束;
            }
            if (位置 < 代码.Length) 结果.Append(局部替换(代码[位置..]));
            return 结果.ToString();
        }

        /// <summary>
        /// **整体中英切换** = 关键字一边(`切换关键字语言`)+ 指令名/内建函数名/附加类型名一边
        /// (`指令C.切换指令名语言`)。**顺序不能反**:指令名那一步要先认出"裸 `返回`"(汇编 RET)并翻成 `RET`,
        /// 关键字那一步才不会把它当成语言的 `return`(见两处各自的注释)。
