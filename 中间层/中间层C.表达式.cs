        #region 表达式求值:AST → 汇编
        /// <summary>
        /// 求值结果:常量 / 寄存器 / 槽(临时内存槽)。
        /// 槽是为了"跨 CALL 暂存"存在的:调函数会把 R0 覆盖、还会用掉临时寄存器,
        /// 所以左边算完的值一旦右边还要调函数,就先存进槽里,等右边算完再读回来。
        /// `已零扩展` = 这个值**已知高 16 位为 0**(窄类型读出来、小常量、按窄宽截断过的结果)——
        /// C 档 `短整数` 宽槽写回时可以省掉那条截断掩码。
        /// `有符号` = 这个值来自有符号类型(整数/短整数)或负数字面量 —— 比较要按有符号比、打印要带负号、
        /// 除法要按有符号除。**任一边有符号就按有符号算**(比 C 的隐式转换好懂)。
        /// `是浮点` = 这个值是一个 **IEEE754 单精度位模式**(4 字节,放在寄存器里)。
        /// 它决定三件事:① 二元运算走 `浮点加法` 0x38 一族(不是整数 `加法`);② 比较走 `浮点比较` 0x3D;
        /// ③ `输出行` 走位模式 → 十进制的打印例程(否则会打出 `1069547520` 这种静默错误)。
        /// **任一边是浮点就按浮点算**(与 `有符号` 同一条口径)。
        /// </summary>
        private readonly record struct 表达式值(uint 常量, string? 寄存器, bool 可写, 地址位置? 槽,
            bool 已零扩展 = false, bool 有符号 = false, bool 是浮点 = false)
        {
            public bool 是常量 => 寄存器 == null && 槽 == null;
            public bool 在槽里 => 槽 != null;
            public static 表达式值 常量值(uint 值, bool 有符号 = false, bool 是浮点 = false)
                => new(值, null, false, null, 值 <= 0xFFFF, 有符号, 是浮点);
            public static 表达式值 寄存器值(string 名, bool 可写, bool 已零扩展 = false, bool 有符号 = false,
                bool 是浮点 = false)
                => new(0, 名, 可写, null, 已零扩展, 有符号, 是浮点);
            public static 表达式值 槽值(地址位置 位置) => new(0, null, false, 位置, false, 位置.有符号);
        }

        /// <summary> 申请一个匿名的 4 字节临时槽:函数里放进当前帧,顶层代码放进数据段 </summary>
        private 地址位置 新临时槽()
        {
            if (_当前函数 is { } 函数)
            {
                if (函数.局部偏移 + 4 > 函数帧大小)
                    throw new 编译异常C(
                        $"表达式太复杂(函数 '{函数.名称}' 的帧超出):放不下临时槽 —— 已经用到 {函数.局部偏移} 字节," +
                        $"再加这个 4 字节就是 {函数.局部偏移 + 4} 字节,上限 {函数帧大小} 字节。" + 帧超限改法(),
                        $"expression too complex: no room for a spill slot in '{函数.名称}' ({函数.局部偏移}/{函数帧大小})",
                        _伪行号表.Count == 0 ? 0 : _伪行号表[^1]);
                var 位置 = new 地址位置(帧槽(函数.局部偏移), 0, 4);
                函数.局部偏移 += 4;
                return 位置;
            }
            return new 地址位置(新槽(4).名称, 0, 4);
        }

        /// <summary> 值要跨过"右边的函数调用"→ 存进临时槽(常量不用,已经在槽里的也不用) </summary>
        private 表达式值 暂存到槽(表达式值 值)
        {
            if (值.是常量 || 值.在槽里) return 值;
            var 位置 = 新临时槽();
            发出写变量(值.寄存器!, 位置);
            // R6-4:暂存只是**换个地方放**,值的语义一个字没变 —— `有符号` / `已零扩展` 得跟着走。
            // 不跟的话,函数调用结果一进临时槽就变成"按无符号看":实测 `取差值() < 0` 恒假、
            // `找条目(...) >= 0` 恒真(负数被当成 4294967295)。
            // 通用化(2026-10):**`是浮点` 同理必须跟着走** —— 掉了它,`浮点 结果 = 左 + 右;` 里
            // 那个加法就会退化成整数 `加法`(位模式相加,结果是个看着像算错了的数)。
            return 表达式值.槽值(位置) with { 已零扩展 = 值.已零扩展, 有符号 = 值.有符号, 是浮点 = 值.是浮点 };
        }

        /// <summary> 把"在槽里"的值读回寄存器(常量/寄存器原样返回) </summary>
        private 表达式值 落到寄存器(表达式值 值)
        {
            if (!值.在槽里) return 值;
            string t = 新临时();
            发出读变量(t, 值.槽!.Value);
            // R6-4:同上 —— 槽 → 寄存器也是"换个地方放",语义不变
            return 表达式值.寄存器值(t, 可写: true, 已零扩展: 值.已零扩展, 有符号: 值.有符号, 是浮点: 值.是浮点);
        }

        /// <summary> 取一个能当运算操作数的寄存器(常量→装载,槽→读回） </summary>
        private string 取操作数寄存器(表达式值 值)
        {
            if (值.在槽里) { string t = 新临时(); 发出读变量(t, 值.槽!.Value); return t; }
            if (值.是常量) return 常量入临时(值.常量);
            return 值.寄存器!;
        }

        /// <summary>
        /// 求值一个完整表达式(已做 变量化/地址 替换的文本)。
        /// 首选目标:顶层运算可以直接算进这个寄存器,省一条 MOV;传 null 表示随便给个临时寄存器。
        /// 支持 `条件 ? 真支 : 假支`(三目):**编译期展开成跳转**,两边只算被选中的那个。
        /// </summary>
        private 表达式值 求值表达式(string 文本, int 行号, string 原文, string? 首选目标 = null)
        {
            string 去空白 = 去外层括号(文本.Trim());   // `(x < 10 ? 7 : 8)` 这种:先把外层括号去掉才看得见三目
            // 三目要在"替换地址取用"之前切开:不然没被选中的那一支也会把 地址(...) 先算出来(白算,还可能占着寄存器)
            (string 条件, string 真, string 假)? 三目 = null;
            try { 三目 = 找顶层三目(去空白); }
            catch (表达式语法异常C ex)
            {
                throw 报错(行号, $"{ex.Message}(第 {ex.位置 + 1} 个字符): '{去空白}'", $"{ex.Message} at char {ex.位置 + 1}: '{去空白}'");
            }
            if (三目 is { } 三目项) return 求值三目(三目项, 行号, 原文, 首选目标);

            string 内容 = 替换地址取用(去空白, 行号, 原文);   // 地址(...) 先变成寄存器
            if (内容.Length == 0) throw 报错(行号, $"表达式为空: '{原文}'", $"empty expression: '{原文}'");
            // 顺手打了中文"且/或/非"→ 给一句说明(条件那边也是同一句)
            if (条件里有中文逻辑词(内容))
                throw 报错(行号, $"逻辑运算只认符号写法:用 && || !(没有中文的 且/或/非):'{原文}'",
                    $"use && || ! for boolean logic (no Chinese operators): '{原文}'");
            // `取名字().长度()`:函数调用的结果直接当字符串用(先物化到隐藏临时串,再数字数)
            // 方法名中英都认(`.length()` 是 `.长度()` 的别名),所以按"结尾方法"取,别写死中文那段
            var 长度尾 = 中间层指令C.取结尾方法(去空白);
            if (长度尾 is { 中文: "长度" } 尾)
            {
                string 基 = 去空白[..^尾.后缀.Length].Trim();
                if (是字符串返回调用文本(基, 行号))
                {
                    var 临时串 = 物化串返回调用(基, 行号, 原文);
                    string 数据 = 读临时(临时串.指针槽!.Value);
                    string 字节长 = 读临时(临时串.长度槽);
                    return 表达式值.寄存器值(发出数文字(数据, 字节长), 可写: true);
                }
            }
            // `f().字段` 这种"拿函数结果直接点字段":语言里先得用变量接住(结构返回是先给地址再写进去)
            if (System.Text.RegularExpressions.Regex.IsMatch(内容, @"[\p{L}\p{N}_)]\s*\([^()]*\)\s*\."))
                throw 报错(行号, $"函数调用的结果不能直接点字段: '{内容}'。先用变量接住再用,例如 " +
                    $"`点 临时 = 取点()` 然后 `临时.字段`;标量函数也一样:`var v = f()` 再 `v`",
                    $"cannot access a field of a call result directly: '{内容}'");
            表达式节点C 根;
            try
            {
                根 = 表达式语法C.解析(内容);
            }
            catch (表达式语法异常C ex)
            {
                throw 报错(行号, $"{ex.Message}(第 {ex.位置 + 1} 个字符): '{内容}'", $"{ex.Message} at char {ex.位置 + 1}: '{内容}'");
            }
            return 求值节点(根, 行号, 原文, 首选目标, 是根: true);
        }

        /// <summary> 找**括号外**的三目 `?` 以及和它配对的那个 `:`(支持右边再套三目)` </summary>
        private static (string 条件, string 真, string 假)? 找顶层三目(string 文本)
        {
            int 深 = 0, 问号 = -1, 待配 = 0;
            for (int i = 0; i < 文本.Length; i++)
            {
                char c = 文本[i];
                if (c == '(') { 深++; continue; }
                if (c == ')') { 深--; continue; }
                if (深 != 0) continue;
                if (c == '?') { if (问号 < 0) { 问号 = i; 待配 = 1; } else 待配++; continue; }
                if (c == ':' && 问号 >= 0)
                {
                    待配--;
                    if (待配 == 0)
                        return (文本[..问号].Trim(), 文本[(问号 + 1)..i].Trim(), 文本[(i + 1)..].Trim());
                }
            }
            return 问号 < 0 ? null : throw new 表达式语法异常C("三目少了配对的 ':'", 问号);
        }

        /// <summary> `条件 ? 真支 : 假支`:条件为假跳到算假支;两支都算进同一个目标寄存器(只算被选中的那支)</summary>
        private 表达式值 求值三目((string 条件, string 真, string 假) 三目, int 行号, string 原文, string? 首选目标)
        {
            if (三目.条件.Length == 0 || 三目.真.Length == 0 || 三目.假.Length == 0)
                throw 报错(行号, $"三目 '条件 ? 真支 : 假支' 三边都不能空: '{原文}'", $"incomplete ternary 'cond ? a : b': '{原文}'");

            // ISA 扩容批 3(0x59 `条件移动`):`甲 关系 乙 ? 甲 : 乙`(最大 / 最小那一族)一条指令选完;
            // 认不出照旧走下面的跳转老路(只算被选中的那一支)。
            if (试发条件移动文本(三目.条件, 三目.真, 三目.假, 行号, 原文, 首选目标) is { } 条件移动值) return 条件移动值;

            string 目标 = 首选目标 ?? 新临时();
            string 假标签 = 新标签("Cond假");
            string 结束标签 = 新标签("CondEnd");
            输出条件跳过(三目.条件, 行号, 假标签);
            表达式值 真值 = 求值表达式(三目.真, 行号, 原文, 目标);
            落到目标(真值, 目标);
            发出($"JMP {结束标签}");
            发出($"{假标签}:");
            表达式值 假值 = 求值表达式(三目.假, 行号, 原文, 目标);
            落到目标(假值, 目标);
            发出($"{结束标签}:");
            // 只有两支都"高 16 位必定是 0",这个结果才算零扩展(不然窄槽写回时不能省掩码)
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: 真值.已零扩展 && 假值.已零扩展);
        }

        /// <summary>
        /// `条件 ? 真支 : 假支` 的**语法树版**(R2-2):三边都已经是节点,不再切文本。
        /// 条件走 输出条件节点(短路语义与 `如果` 一模一样),两支各算进同一个目标寄存器,**只算被选中的那支**。
        /// </summary>
        private 表达式值 求值三目节点(三目节点C 三目, int 行号, string 原文, string? 首选目标)
        {
            // ISA 扩容批 3(0x59 `条件移动`):`甲 关系 乙 ? 甲 : 乙`(最大 / 最小 / 钳位那一族)一条指令选完;
            // 认不出照旧走下面的跳转老路(只算被选中的那一支)。
            if (试发条件移动(三目.条件, 三目.真, 三目.假, 行号, 原文, 首选目标) is { } 条件移动值) return 条件移动值;

            string 目标 = 首选目标 ?? 新临时();
            string 假标签 = 新标签("Cond假");
            string 结束标签 = 新标签("CondEnd");
            // 独立寄存器池:false —— 外面还有活着的寄存器(例如 `x == (条件 ? 1 : 2)` 里 x 那个),
            // 重开池子会把它们当空闲的再发一次(实测踩过:x 与 条件 挤在同一个寄存器里,比较整个算错)。
            输出条件节点(三目.条件, 行号, 假标签, 跳则真: false, 原文, 独立寄存器池: false);
            表达式值 真值 = 求值节点(三目.真, 行号, 原文, 目标);
            落到目标(真值, 目标);
            发出($"JMP {结束标签}");
            发出($"{假标签}:");
            表达式值 假值 = 求值节点(三目.假, 行号, 原文, 目标);
            落到目标(假值, 目标);
            发出($"{结束标签}:");
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: 真值.已零扩展 && 假值.已零扩展);
        }

        /// <summary> 把一个求值结果落到指定寄存器(常量装载 / 槽里读回 / 不同寄存器 MOV)</summary>
        private void 落到目标(表达式值 值, string 目标)
        {
            if (值.是常量) { 输出装载常量(目标, 值.常量); return; }
            if (值.在槽里) { 发出读变量(目标, 值.槽!.Value); return; }
            if (值.寄存器 == 目标) return;
            发出($"复制 {目标} {值.寄存器}");
        }

        private 表达式值 求值节点(表达式节点C 节点, int 行号, string 原文, string? 首选目标, bool 是根 = false)
        {
            switch (节点)
            {
                case 常量节点C 常量:
                    // 通用化(2026-10):浮点字面量(`1.5`)在词法层就认出来了,位模式一路带到这儿。
                    // 标记 `是浮点` 之后:二元运算走 `浮点加法` 0x38 一族、比较走 `浮点比较` 0x3D、
                    // `输出行` 走位模式 → 十进制的打印例程 —— 这个位模式**绝不会**被当成整数用下去。
                    if (常量.是浮点)
                        return 表达式值.常量值(常量.值, 是浮点: true);
                    return 表达式值.常量值(常量.值);

                case 名字节点C 名称:
                {
                    // 用到才取值:这样每次出现都拿到当时的寄存器,值不会被后面的 CALL 冲掉
                    if (解析寄存器(名称.名, out string 直接寄存器))
                        return 表达式值.寄存器值(直接寄存器, 可写: false);   // 用户自己写的寄存器:别往里写
                    // H68-2 枚举成员(`绿` / `颜色.绿`):**编译期常量** —— 当场折成立即数,一条指令都不多发。
                    // 摆在查变量之前:成员名与变量名重名在声明处就被拦住了(校验变量名),这里不会抢走谁
                    if (查枚举成员常量(名称.名) is { } 枚举成员)
                    {
                        uint 位 = unchecked((uint)枚举成员.值);
                        return 表达式值.常量值(位, 有符号: true);
                    }
                    // 优化:循环体里"一直没变过"的变量已经常驻在寄存器里 —— 直接用它,一次内存都不读
                    if (常驻变量寄存器(名称.名) is { } 常驻)
                        return 表达式值.寄存器值(常驻, 可写: false, 是浮点: 是浮点变量(名称.名));
                    if (查位置(名称.名, 行号, 原文) is { } 位置)
                    {
                        要求标量(位置, 行号, 名称.名);
                        // 优化:首选目标直接当载入目标(以前是先载进一个临时寄存器,再 MOV 到目标 —— 白花一条)
                        string t = _优化开 && 首选目标 != null ? 首选目标 : 新临时();
                        发出读变量(t, 位置);
                        if (_优化开 && 首选目标 != null) _优化省下++;
                        // 窄类型读出来就是零扩展的:紧排的读的时候掩过码,宽槽的高半本来就写着 0
                        // ⚠ R4-41:浮点这一档**优先看位置自己**(`点.x` / `表[3]` 这类静态位置走的是这条路 ——
                        //    它们的名字不在 `_变量类型` 里,只看 `是浮点变量(名称.名)` 会漏成整数)
                        return 表达式值.寄存器值(t, 可写: true, 已零扩展: 位置.读即零扩展,
                            有符号: 位置.有符号, 是浮点: 位置.是浮点 || 是浮点变量(名称.名));
                    }
                    // 运行时算址的(列表元素 / 运行期下标 / 嵌套字段里的动态下标)
                    if (解析引用链(名称.名, 行号) is { } 链)
                    {
                        string 读 = 链读到寄存器(链, 行号, 名称.名);
                        // ⚠⚠ **浮点数组元素 / 浮点字段**这个标记必须带上(否则 `顶点x[i] - 顶点x[j]` 会走整数减法
                        // —— 位模式直接相减,结果是垃圾;见 `是浮点标量引用`)
                        return 表达式值.寄存器值(读, 可写: true, 已零扩展: 链.读即零扩展, 有符号: 链.有符号,
                            是浮点: 链是浮点标量(链));
                    }
                    throw 报错(行号, $"表达式里出现未知名字: '{名称.名}'(变量/字段请确认已声明)",
                        $"unknown name in expression: '{名称.名}'");
                }

                case 一元节点C { 记号: "-" } 一元:
                {
                    表达式值 子 = 求值节点(一元.子, 行号, 原文, null);
                    // 通用化(2026-10):**浮点的取负 = 翻转符号位**(位模式最高位),
                    // 不是整数取补(那算出来是另一个数)。与 `Sample\库\float32.hb` 的 `浮点32取负` 同口径。
                    if (子.是浮点)
                    {
                        if (子.是常量)
                            return 表达式值.常量值(子.常量 ^ 0x80000000u, 是浮点: true);
                        子 = 落到寄存器(子);
                        string 浮目标 = 首选目标 ?? 新临时();
                        if (子.寄存器 != 浮目标) 发出($"复制 {浮目标} {子.寄存器}");
                        string 符号 = 新临时();
                        输出装载常量(符号, 0x80000000u);
                        发出($"异或 {浮目标} {符号}");            // 只翻符号位
                        return 表达式值.寄存器值(浮目标, 可写: true, 是浮点: true);
                    }
                    if (子.是常量) return 表达式值.常量值(计算常量("-", 0, 子.常量, 行号, 原文), 有符号: true);   // -常量 直接折叠
                    子 = 落到寄存器(子);
                    string 目标 = 首选目标 ?? 新临时();
                    if (子.寄存器 == 目标)
                    {
                        // 目标正好装着子表达式:先保护,再算 0 - 子
                        string 保护 = 选暂存寄存器([目标]);
                        发出($"MOV {保护} {目标}");
                        输出装载常量(目标, 0);
                        发出($"SUB {目标} {保护}");
                    }
                    else
                    {
                        输出装载常量(目标, 0);
                        发出($"SUB {目标} {子.寄存器}");
                    }
                    return 表达式值.寄存器值(目标, 可写: true, 有符号: true);   // 取负之后就是有符号语境了
                }

                case 一元节点C { 记号: "!" } 一元:
                    return 求值取反(一元.子, 行号, 原文, 首选目标);

                // 按位取反(第96批,D5②):ISA 的 `取反`(NOT)是**32 位整体取反**,一条就够
                // (与 `!` 一个路子:子表达式直接算进首选目标,能原地取反就不多搬一次)
                case 一元节点C { 记号: "~" } 一元:
                {
                    表达式值 取反值 = 求值节点(一元.子, 行号, 原文, 首选目标);
                    if (取反值.是常量) return 表达式值.常量值(~取反值.常量);            // ~常量 直接折叠
                    string 取反目标 = 首选目标 ?? 新临时();
                    落到目标(取反值, 取反目标);
                    发出($"取反 {取反目标}");
                    return 表达式值.寄存器值(取反目标, 可写: true);
                }

                case 字符串节点C 串:
                    throw 报错(行号, $"字符串不能当数字用: '{串.原文}'(在 '{原文}' 里)。要和另一个字符串比就写 `s == \"内容\"`;" +
                        $"要看长度写 s.长度(),要取某个字节写 s[下标]",
                        $"a string literal cannot be used as a number: '{串.原文}'");

                case 二元节点C { 记号: "&&" or "||" } 二元:
                    return 求值逻辑值(二元, 行号, 原文, 首选目标);

                // 三目(R2-2):AST 里已经有它了 ⇒ 条件那条路与赋值那条路共用这一份展开
                case 三目节点C 三目:
                    return 求值三目节点(三目, 行号, 原文, 首选目标);

                case 二元节点C { 记号: "==" or "!=" or "<" or ">" or "<=" or ">=" } 二元:
                    // 字符串比较走单独一条路(按字节比);数字那边一点没动
                    if (是字符串节点(二元.左) || 是字符串节点(二元.右))
                        return 求值字符串比较值(二元, 行号, 原文, 首选目标);
                    return 求值比较值(二元, 行号, 原文, 首选目标);

                case 二元节点C { 记号: "|" } 换字节 when
                        试发字节交换(换字节, 行号, 原文, 首选目标) is { } 换值:
                    return 换值;
                case 二元节点C { 记号: "|" } 移位或 when !移位或.左.含调用 &&
                        试发循环移位(移位或, 行号, 原文, 首选目标) is { } 移位值:
                    return 移位值;

                case 二元节点C 二元:
                {
                    // 先左后右(C 的求值顺序);右边要调函数时,左边先落槽暂存(否则会被 CALL 冲掉)
                    // 优化:首选目标直接给左子节点 —— 左操作数一算就落在目标寄存器里,省掉外面那条 `MOV 目标, 左`
                    // (以前是先把左算进一个临时寄存器,再 MOV 进目标;现在 `x = a + b` 就是 ADD 直接算进目标)
                    表达式值 左 = 求值节点(二元.左, 行号, 原文, 首选目标);
                    if (二元.右.含调用) 左 = 暂存到槽(左);
                    表达式值 右 = 求值节点(二元.右, 行号, 原文, null);
                    return 应用二元(二元.记号, 左, 右, 行号, 原文, 首选目标);
                }

                case 调用节点C 调用:
                    return 求值调用(调用, 行号, 原文, 是根);

                default:
                    throw 报错(行号, $"无法求值的表达式: '{原文}'", $"cannot evaluate expression: '{原文}'");
            }
        }

        /// <summary>
        /// 通用化(2026-10):**显式类型转换** `浮点(x)` / `整数(x)`。
        /// <para>
        /// 为什么要它:混合运算(`左 + 3`)编译器会**自动**插转换,但
        /// "我要的就是这个舍入"这种话得能自己说出来 —— 而且**打印/比较之外**,
        /// 把浮点收成整数(下标、计数、循环)是最常见的需求。
        /// </para>
        /// <list type="bullet">
        /// <item>`浮点(x)`:整数 ⇒ `整数转浮点`(0x3F,那 32 位按**有符号**读);
        ///       本来就是浮点 ⇒ 原样(不白发指令)。</item>
        /// <item>`整数(x)`:浮点 ⇒ `浮点转整数`(0x3E,**按零截断**;越界 / NaN 给 `0x80000000` ——
        ///       **不报错**,要判"转不了"就自己比范围);本来就是整数 ⇒ 原样。</item>
        /// </list>
        /// </summary>
        private 表达式值 求值类型转换(调用节点C 调用, int 行号, string 原文)
        {
            bool 要浮点 = 调用.名 is "浮点" or "float";
            string 类型名 = 要浮点 ? "浮点" : "整数";
            if (调用.实参.Count != 1)
                throw 报错(行号,
                    $"{类型名}(...) 只收一个值(你给了 {调用.实参.Count} 个):`{类型名}(表达式)`",
                    $"{类型名}(...) takes exactly one value");

            表达式值 值 = 求值节点(调用.实参[0], 行号, 原文, null);
            // 已经是目标类型 ⇒ 原样返回,一条指令都不发
            if (值.是浮点 == 要浮点) return 值;

            值 = 落到寄存器(值);
            string 目标 = 新临时();
            if (值.是常量) 输出装载常量(目标, 值.常量);
            else 发出($"复制 {目标} {值.寄存器}");
            发出(要浮点 ? $"整数转浮点 {目标}" : $"浮点转整数 {目标}");
            // ⚠ `整数(...)` 的**结果是有符号的**(`浮点转整数` 按零截断,负数就是负数)——
            //    不标 `有符号` 的话 `输出行(整数(-2.7))` 会走无符号打印、打出 `4294967294`(踩过)。
            return 表达式值.寄存器值(目标, 可写: true, 有符号: !要浮点, 是浮点: 要浮点);
        }

        /// <summary>
        /// 表达式里的函数/方法调用。结果按约定在 R0:
        /// 只要它不是整条表达式的根(上面还要继续算),就先落进临时槽 —— 下一次 CALL 会覆盖 R0。
        /// </summary>
        private 表达式值 求值调用(调用节点C 调用, int 行号, string 原文, bool 是根)
        {
            // G2(回调 / 事件):`间接调用(地址, 实参…)` 也能当**值**用(`整数 果 = 间接调用(处理, 3);`)。
            // 结果按约定在 R0,与直接调用一模一样(帧、返回地址、返回值全走同一条)。
            if (调用.名 is "间接调用" or "invoke" || string.Equals(调用.名, "invoke", StringComparison.OrdinalIgnoreCase))
                return 求值间接调用(调用, 行号, 原文, 是根);
            // 通用化(2026-10):**显式类型转换** —— `浮点(x)` / `整数(x)`,各一条硬件指令。
            // 摆在这里(所有内建名之前):`浮点` / `整数` 是**类型名**,不可能是用户函数名(声明处拦住了)。
            if (调用.名 is "浮点" or "float" or "整数" or "int")
                return 求值类型转换(调用, 行号, 原文);
            // ISA 扩容那 27 条的"用在哪":14 个**指令内建**(取较大 / 数一位 / 循环左移 / 取整数绝对值 …)。
            // 摆在这里(**用户函数之前**)是有意的:内建优先,`位.hb` 那几个同名方法才转发得到指令上
            // (带点的 `位.数一位(…)` 走库方法,两边互不打扰 —— 见 中间层C.内建指令.cs 的头注释)。
            if (是ISA内建名(调用.名))
                return 求值ISA内建(调用, 行号, 原文);
            // 控制台输入:读取字符() / 读取行(缓冲) / 读取数字() —— 结果是个值,能赋值/比较/当实参
            if (是读输入名(调用.名))
                return 求值读取(调用, 行号, 原文);
            // 宿主能力(P28):读文件 / 写文件 / 当前时间
            if (是宿主能力名(调用.名))
                return 求值宿主能力(调用, 行号, 原文);
            // 图形界面(R1-6 批 1;G3 域 2 起号段 60~69):打开窗口 / 画文字 / 刷新 / 取事件…(同一条 `宿主调用` 通道)
            if (是图形能力名(调用.名))
                return 求值图形能力(调用, 行号, 原文);
            // ---- H72(第353批):堆动作当**值**用(申请 / 取字 / 存字 / 释放)----
            //   以前这几个只在 `替换地址取用` → `替换堆调用` 那一步按**整条文本**预先展开 ——
            //   对普通表达式没问题,可**条件**那一侧也走同一个入口 ⇒
            //   `父 != 0 && 取字(父, 8) == 走` 里的 `取字` **不管左边真假都已经算过**了:
            //   左边那半句的短路保护不了它,`父` 是 0 时当场撞"堆地址非法"(实测 5 行必现)。
            //   现在条件那一侧改成**不预先展开堆调用**(`替换地址取用跳过堆`),交给这里按 AST 懒算:
            //   短路那一支真的不算,与 `&& / ||` 的短路口径一致。
            //   (`是用户函数名` 那一档让路:用户自己定义了同名函数就照普通调用走,与 `试处理堆动作` 同一条。)
            if (!是用户函数名(调用.名) && 到堆动作(调用.名) is { } 堆动作)
                return 求值堆动作当值(堆动作, 调用, 行号, 原文);
            // `分数.长度()`:不是函数,编译器直接知道 —— 列表读它的长度槽,数组/写死容量的列表是编译期常量;
            // **字符串按"文字"数**(2026-09 起):数一遍 UTF-8 码点,中文一个字算一个
            // 方法名先归一(`.length` → `.长度`),下面全部照中文那套走
            string 调用名 = 中间层指令C.规范方法名(调用.名);
            if (调用.实参.Count == 0 && 调用名.EndsWith(".长度", StringComparison.Ordinal))
            {
                string 基名 = 调用名[..^".长度".Length].Trim();
                if (是字符串参数(基名) || 查列表(基名) is { 是字符串: true }
                    || 取堆串链(基名) is not null || 试取定长缓冲链(基名) is not null)
                {
                    if (循环保留的长度寄存器(基名) is { } 常驻字数)
                        return 表达式值.寄存器值(常驻字数, 可写: false);      // S12:循环外已经数过一遍了
                    var (数据址, 字节长) = 串数据与字节长(基名, 行号, 原文);
                    return 表达式值.寄存器值(发出数文字(数据址, 字节长), 可写: true);
                }
                // 数组参数(切片):长度是调用方传进来的运行期值,读它那个槽
                if (查变量(基名) is { 长度槽: { } 参数长度槽 })
                {
                    string t = 新临时();
                    发出读变量(t, 参数长度槽);
                    return 表达式值.寄存器值(t, 可写: true);
                }
                if (解析列表引用(基名, 行号) is { } 列表)
                {
                    string t = 读列表头字(列表, 列表头长度偏移, 行号, 原文);
                    return 表达式值.寄存器值(t, 可写: true);
                }
                if (查变量(基名) is { 数组类型: not null } 数组绑定)
                    return 表达式值.常量值((uint)数组绑定.数组类型!.长度);
                throw 报错(行号, $"'{基名}' 不是列表/数组,没有 .长度()", $"'{基名}' has no .长度()");
            }
            if (调用名.EndsWith(".添加", StringComparison.Ordinal) || 调用名.EndsWith(".清空", StringComparison.Ordinal))
                throw 报错(行号, $"添加/清空 要单独成句,不能写在表达式里:{调用.名}(...)",
                    $"添加/清空 must be a statement of their own");

            var 链路 = 解析函数链路(调用.名, 行号);
            // 成员方法的收方是**编译器补的**第一个实参,不算用户写的那几个
            int 应有实参 = 链路.参数表.Count - (链路.收方.Length > 0 ? 1 : 0);
            if (调用.实参.Count != 应有实参)
                throw 报错(行号, $"方法 '{调用.名}' 需要 {应有实参} 个参数,收到 {调用.实参.Count} 个",
                    $"wrong argument count for '{调用.名}'");
            发出表达式调用(链路, 调用.实参, 行号, 原文);
            // 返回值按声明处理:没写返回类型(void)的函数结果不能当值用;结构返回必须直接赋给变量(这儿没有存放处)
            if (链路.返回类型词.Length == 0)
                throw 报错(行号, $"方法 '{调用.名}' 没有返回值(函数头没写 `返回 类型`),不能把它的结果当值用",
                    $"'{调用.名}' returns nothing (void)");
            if (取类型定义(链路.返回类型词) == null)      // H68-2:枚举返回也是标量
            {
                bool 是串 = 链路.返回类型词 is "字符串" || string.Equals(链路.返回类型词, "string", StringComparison.OrdinalIgnoreCase);
                throw 报错(行号, 是串
                        ? $"方法 '{调用.名}' 返回 字符串,要有地方接:写成 `字符串 临时 = {调用.名}(…);` 再用 临时" +
                          $"(字符串返回值不能直接写在表达式里)"
                        : $"方法 '{调用.名}' 返回的是结构({链路.返回类型词}),要直接赋给一个 {链路.返回类型词} 变量" +
                          $"(或当声明初值),不能写在表达式里 —— 先存到变量再用",
                    $"'{调用.名}' returns a string or struct: assign it to a variable first");
            }
            // 返回值按**有符号**看(默认类型就是有符号的 整数):这样 `测试输出(取半(-300))` 打得出 -150。
            // 返回"很大的无符号数"时,先赋给 无符号整数 变量再打印就行(帮助里写了这条)。
            return 是根 ? 表达式值.寄存器值("R0", 可写: false, 有符号: true)
                        : 暂存到槽(表达式值.寄存器值("R0", 可写: false, 有符号: true));
        }

        /// <summary>
        /// 这段文本是不是"调用一个返回结构的函数"(如 `取中点(3, 9)`)—— 是就给出链路与实参,
        /// 让调用处把"结果放哪"的地址递进去(结构返回只能直接赋给变量/当声明初值)。
        /// </summary>
        private ((string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 链路,
                 IReadOnlyList<表达式节点C> 实参)? 试取结构返回调用(string 文本, int 行号)
            => 试取整块返回调用(文本, 行号, 要字符串: false);

        /// <summary>
        /// 这段文本是不是"调用一个返回字符串的函数"(`取名字()` / `拼起来(a, b)`)—— 同上一套,
        /// 只是递进去的地址是**调用方那个字符串头的地址**(被调方把内容整份拷进去)。
        /// </summary>
        private ((string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 链路,
                 IReadOnlyList<表达式节点C> 实参)? 试取字符串返回调用(string 文本, int 行号)
            => 试取整块返回调用(文本, 行号, 要字符串: true);

        /// <summary> "返回结构 / 返回字符串"两种调用一起认(它们的调用形状完全一样:多一个隐藏地址参数) </summary>
        private ((string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 链路,
                 IReadOnlyList<表达式节点C> 实参)? 试取整块返回调用(string 文本, int 行号, bool 要字符串)
        {
            string 内容 = 文本.Trim();
            if (内容.Length == 0 || !内容.Contains('(')) return null;
            表达式节点C 根;
            try { 根 = 表达式语法C.解析(替换地址取用(内容, 行号, 内容)); }
            catch (表达式语法异常C) { return null; }
            if (根 is not 调用节点C 调用) return null;
            (string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 链路;
            try { 链路 = 解析函数链路(调用.名, 行号); }
            catch (编译异常C) { return null; }
            bool 是字符串返回 = 链路.返回类型词 is "字符串" || string.Equals(链路.返回类型词, "string", StringComparison.OrdinalIgnoreCase);
            if (要字符串 != 是字符串返回) return null;
            // 结构返回:void / 标量 / 字符串都不算
            if (!要字符串 && (链路.返回类型词.Length == 0 || 取类型定义(链路.返回类型词) != null)) return null;
            if (调用.实参.Count != 链路.参数表.Count - (链路.收方.Length > 0 ? 1 : 0)) return null;
            return (链路, 调用.实参);
        }

        /// <summary>
        /// 数组参数要的"长度"那个字从哪儿来:静态数组是编译期常量(元素个数);列表读它的长度槽(运行期)。
        /// 返回 null 说明这个实参不是数组/列表。
        /// </summary>
        private (uint 常量, 变量槽定义? 槽)? 数组实参长度(string 名, int 行号)
        {
            if (查变量(名.Trim()) is not { } 绑定) return null;
            // H68-1:多维数组**不当数组参数传** —— 参数那头只认"元素宽 × 个数"这一层,
            // 2 维数组传进去会被当成"元素宽 = 最内层宽"的一维数组,下标全错(明说,不静默传递)
            if (绑定.数组类型 is { 是多维: true } 多维型)
                throw 报错(行号, $"多维数组不能当数组参数传:'{名}' 是 {多维型.各维文本} 的定长多维数组。" +
                    $"要传一整块就把它改成一维数组(自己按下标算),或者把每一维分别当参数传",
                    $"a multi-dimensional array cannot be passed as an array parameter: '{名}'");
            if (绑定.是数组) return ((uint)绑定.数组类型!.长度, null);
            // 数组参数再往下传(转发):长度就在本帧的那个槽里,运行期读
            if (绑定.是数组切片 && 绑定.长度槽 is { } 本帧长度槽) return (0, 本帧长度槽);
            if (绑定.是列表)
            {
                var 列表 = 按槽找列表(绑定.名称);
                if (列表 is { 动态: true, 长度槽: { } 槽 }) return (0, 槽);
                int 容量 = 列表?.类型.容量 ?? 0;
                return ((uint)容量, null);
            }
            return null;
        }

        /// <summary> 把"数组长度"那个字写进新帧的 偏移+4 处(数组参数占两个字:地址 + 长度)</summary>
        private void 写数组长度到帧(string 帧基, int 偏移, (uint 常量, 变量槽定义? 槽) 长度)
        {
            string 值 = 新临时();
            if (长度.槽 is { } 槽) 发出读变量(值, 槽);
            else 输出装载常量(值, 长度.常量);
            string 地址 = 新临时();
            发出($"MOV {地址} {帧基}");
            发出($"ADD_IMMEDIATE {地址} {偏移 + 4}");
            发出($"存字间接 {值} {地址}");
        }

        /// <summary>
        /// 第 i 个实参的文本(数组/字符串参数只接受"一个名字",拿它去查是哪个数组/列表;
        /// 字符串字面量节点也算 —— 这样 `输出行(是(x, "ab"))` 这种**写在表达式里的字面量**也能传)。
        /// </summary>
        private static string 实参文本(int i, IReadOnlyList<表达式节点C> 实参)
            => i < 实参.Count && 实参[i] is 名字节点C 名 ? 名.名
             : i < 实参.Count && 实参[i] is 字符串节点C 串 ? 串.原文
             : i < 实参.Count && 实参[i] is 调用节点C 调用 ? 调用.显示()   // 返回字符串的函数调用也能当字符串实参
             : "";
        /// <summary> 函数名解析(含"体里可省容器名"与"模块里可省模块名"):定义名 / 汇编标签 / 参数表
        /// **多一项 `收方`**(H60 步②):成员方法要额外递一个收方当**第一个实参**;空串 = 普通函数。
        /// 三种写法都认:`容器.成员(…)`(收方 = 那个单例)、`实例.成员(…)`(收方 = 那个实例)、
        /// 容器体里裸叫成员(成员方法体内 = 本函数的收方照传,初始化脚本里 = 单例)。</summary>
        private (string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 解析函数链路(string 名, int 行号)
        {
            string 查名 = 名;
            string 收方 = "";
            // ① 容器体里裸叫成员:`累加(…)` —— 补上容器名。
            if (!_函数表.ContainsKey(查名) && !查名.Contains('.') && _当前容器 is { } 所在容器
                && 所在容器.方法全名.TryGetValue(查名, out string? 全方法名))
            {
                查名 = 全方法名;
                收方 = _当前函数 is { 收方名.Length: > 0 } 本函数 ? 本函数.收方名 : 所在容器.名称;
            }
            // ①b 结构方法体里裸叫兄弟成员(H60 步④):收方 = 本函数的 `_收方`(照传下去)
            if (收方.Length == 0 && !_函数表.ContainsKey(查名) && !查名.Contains('.')
                && _当前结构方法表 is { } 本结构方法 && 本结构方法.TryGetValue(查名, out string? 兄弟定义名)
                && _当前函数 is { 收方名.Length: > 0 } 本方法)
            {
                查名 = 兄弟定义名;
                收方 = 本方法.收方名;
            }
            // ② `实例.成员(…)`:前面那一截是**某一份实例**(变量 / 结构字段 / 数组元素),
            //    它的类型指向某个方法容器(或带方法的普通结构)⇒ 尾段就是那个成员
            if (收方.Length == 0 && 查名.Contains('.'))
            {
                int 点 = 查名.LastIndexOf('.');
                string 前 = 查名[..点], 尾 = 查名[(点 + 1)..];
                if (前.Length > 0 && 尾.Length > 0
                    && 收方结构(前) is { } 结构
                    && 结构方法定义名(结构, 尾) is { } 实例成员全名)
                {
                    查名 = 实例成员全名;
                    收方 = 前;
                }
            }
            // 模块(K7 · **H79 改过:顺序反过来 —— 本模块自己人优先**):原先这一句是
            // "裸名字**先按全局找**(老习惯),找不到再按本模块的全名找一次" —— 于是库
            // (`包含` 进来的 `模块`)**内部**写一个裸名字时,只要**别的库 / 调用方**有一个同名
            // 的公开函数,就会解析到那一个上去;两处的签名往往不一样,报出来的是一堆莫名其妙的
            // 类型错(实测:`探针79.hb` 的 `私有 取段(字符串,整数,整数)` 被 `string.hb` 的公开
            // `取段(字符串,字符串,整数)` 顶掉,报"要给字符串参数传一个字符串")。
            // 现在:**本模块有这一份就用本模块的**,本模块没有才落回全局裸名 ——
            // `main` 那一档"库就是要调调用方的全局"照旧放行。
            // ⚠ 与变量侧同一条口径:`查变量` 第 ② 步(R4-11 / H74)早就是"自己人优先",
            //    函数侧这一处当时漏掉了(硬规矩:同一个坑的两侧要一起改)。
            if (!查名.Contains('.') && _当前模块.Length > 0)
            {
                string 本模块全名 = 限定名(查名);
                if (_函数表.ContainsKey(本模块全名)) 查名 = 本模块全名;
            }
            // ②b 不写结构名的结构方法(`到原点(p)`,H60 步④):**全工程同名唯一**时才认 —— 收方由调用方自己传
            if (!_函数表.ContainsKey(查名) && !查名.Contains('.') && 收方.Length == 0
                && 找唯一结构方法(查名, 行号) is { } 唯一定义名)
                查名 = 唯一定义名;
            if (!_函数表.TryGetValue(查名, out var 参数表))
                throw 报错(行号, $"未定义的函数: '{名}'(函数要先声明或后定义都行,但不能没有)", $"undefined function: '{名}'");
            // ③ 写成 `容器.成员(…)`(单例那一份):收方就是点号前面那一截。
            //    结构方法写成 `点.到原点(…)` 时**不收方** —— 那一截是**类型名**,收方由调用方当第 1 个实参传进去。
            if (收方.Length == 0 && _成员收方.ContainsKey(查名))
            {
                int 点 = 查名.LastIndexOf('.');
                if (点 > 0) 收方 = 查名[..点];
            }
            校验可取用(查名, 行号);
            return (查名, 汇编标签(查名), 参数表, _函数返回类型.TryGetValue(查名, out string? 返) ? 返 : "", 收方);
        }

        /// <summary>
        /// 不写结构名的结构方法名(`到原点(…)`)在**全工程同名唯一**时给出它的定义名;0 个或 ≥2 个返回 null
        /// (≥2 个当场报错并点名是哪几个结构,别让人猜)。H60 步④。
        /// </summary>
        private string? 找唯一结构方法(string 短名, int 行号)
        {
            string? 中 = null;
            var 出处 = new List<string>();
            foreach (var (结构名, 表) in _结构方法表)
                if (表.TryGetValue(短名, out string? 定义名)) { 中 = 定义名; 出处.Add(结构名); }
            if (出处.Count <= 1) return 中;
            throw 报错(行号, $"方法名 '{短名}' **有歧义**:{出处.Count} 个结构里都有({string.Join(" / ", 出处)})," +
                $"写清是哪一个:`结构名.{短名}(…)`(带收方)或 `实例.{短名}(…)`", $"ambiguous method name '{短名}' ({string.Join(" / ", 出处)})");
        }

        /// <summary>
        /// 发一次"表达式里的调用":先把每个实参算出来并放进调用者侧的临时槽,
        /// 再统一把槽里的值搬进新帧(FP+64 起)—— 中间不能再夹 CALL,否则新帧会被内层调用覆盖。
        /// `返回目的地址` 只在"函数返回结构"时给:它是调用方那块结构的地址,作为**隐藏的第一个参数**递进去,
        /// 被调方把结果整块写到那儿(结构本身从不作为值搬来搬去)。
        /// </summary>
        private void 发出表达式调用((string 查名, string 标签, List<(string 名, int 宽度, string 类型名, 引用类型C? 引用)> 参数表, string 返回类型词, string 收方) 链路, IReadOnlyList<表达式节点C> 实参, int 行号, string 原文, string? 返回目的地址 = null)
        {
            // H60 步②:成员方法的**第一个实参就是收方**(`p.累加(3)` ≡ `累加(p, 3)`)——
            // 合成一个名字节点塞在最前面,后面那套"引用参数自动取地址"的机制原样接着走。
            if (链路.收方.Length > 0)
            {
                var 带收方 = new List<表达式节点C>(实参.Count + 1) { new 名字节点C(链路.收方) };
                带收方.AddRange(实参);
                实参 = 带收方;
            }
            // 调用内部用掉的临时寄存器,调用一返回就全部作废 —— 它们不能一直占着,否则长表达式会"无可用暂存寄存器"
            var 调用前占用 = new List<string>(_语句占用 ?? []);

            // 第96批(B1):返回目的地址(结构/字符串返回的隐藏第 0 槽)是**调用方**在进这里之前
            // 就算进某个寄存器的(如 `取地址 R14 _v8`)。而实参求值里可能夹着内层 CALL —— 内层调用
            // 会把那个寄存器用掉/冲掉,于是隐藏指针变成了内层调用的返回值:
            // 实测 `输出行(转字符串(取半(10)))` 把 0x40000000 当"临时串地址"写进第 0 槽,被调方
            // `取字间接 [0x40000000+8]` 当场越界崩。所以只要实参里有调用,就先把目的地址**落进临时槽**,
            // 写帧时再读回来(和下面"实参先落槽"是同一条纪律)。
            表达式值? 目的值 = null;
            if (返回目的地址 != null)
            {
                目的值 = 表达式值.寄存器值(返回目的地址, 可写: false);
                foreach (var 参 in 实参)
                    if (参.含调用)
                    {
                        目的值 = 暂存到槽(目的值.Value);
                        break;
                    }
            }

            var 实参值 = new List<表达式值>(实参.Count);
            // 带长度的参数(数组/字符串)的"长度"在算实参时就一并取出来:
            // 写帧那一步不要再回头去算一次(会多占寄存器,3 个字符串实参就能把 15 个用光 —— 踩过)
            var 实参长度 = new List<(uint 常量, 变量槽定义? 槽)?>(实参.Count);
            // 后面的实参里有没有调用 —— 有的话,前面算出来的**地址**(引用/结构参数的实参)必须先落槽:
            // 否则内层 CALL 会把那个寄存器冲掉,被调方拿一个"数值"当地址读(第96批 B4:
            // `浮点32打包(乘积, 浮点32取指数(A) + 浮点32取指数(B), 0, 乘号)` 被冲成 0x80000080 → 越界崩)
            for (int i = 0; i < 实参.Count; i++)
            {
                bool 后面还有调用 = false;
                for (int j = i + 1; j < 实参.Count; j++) if (实参[j].含调用) { 后面还有调用 = true; break; }
                // 引用参数:要的是"地址",不是值 → 实参必须是个能取地址的东西(变量/字段/元素)
                if (链路.参数表[i].引用 != null)
                {
                    // 可写字符串参数(`字符串 出 名字`):传的是**调用方字符串头的地址** ——
                    // 实参必须能拿出一个可写的头:本函数里的 `字符串` 变量,或者本函数自己的 `出` 参数(转发)
                    if (链路.参数表[i].引用 is { 是字符串: true, 出参数: true })
                    {
                        表达式值 址值 = 表达式值.寄存器值(
                            出实参头地址(实参文本(i, 实参), 行号, 原文, 链路.查名, i + 1), 可写: false);
                        实参值.Add(后面还有调用 ? 暂存到槽(址值) : 址值);
                        实参长度.Add(null);
                        continue;
                    }
                    // 只读字符串参数:传的是数据地址(在池里,写在指针槽里),不是变量自己的地址 ——
                    // 直接 取左值地址 会撞上"列表的地址不能取"(踩过)
                    if (链路.参数表[i].引用 is { 是字符串: true })
                    {
                        var 串源 = 字符串实参地址(实参文本(i, 实参), 行号, 原文);
                        表达式值 址值 = 表达式值.寄存器值(串源.地址, 可写: false);
                        实参值.Add(后面还有调用 ? 暂存到槽(址值) : 址值);
                        实参长度.Add(串源.长度);
                        continue;
                    }
                    if (实参[i] is not 名字节点C 名字)
                        throw 报错(行号, $"方法 '{链路.查名}' 的第 {i + 1} 个参数要传**变量/字段/数组元素**(结构和引用参数传的是地址,不复制),不能是表达式;" +
                            $"想传一个算出来的值就先存到变量里", $"argument {i + 1} of '{链路.查名}' needs an addressable value");
                    表达式值 名址 = 表达式值.寄存器值(取左值地址(名字.名, 行号, 原文), 可写: false);
                    实参值.Add(后面还有调用 ? 暂存到槽(名址) : 名址);
                    实参长度.Add(链路.参数表[i].引用 is { 带长度: true } ? 数组实参长度(名字.名, 行号) : null);
                    continue;
                }
                // 后面还有实参要调函数的话,这个实参必须先落槽(否则它的寄存器会被内层 CALL 用掉)
                表达式值 值 = 求值节点(实参[i], 行号, 原文, null);
                实参值.Add(后面还有调用 ? 暂存到槽(值) : 值);
                实参长度.Add(null);
            }

            string 帧基 = 新临时();                       // FP + 帧大小 = 新帧起点
            发出($"取地址帧 {帧基} {函数帧大小}");
            string 存址 = 新临时();                       // 写帧时反复用这一个(每段只改偏移),不再一段一个新临时
            string 长值 = 新临时();                       // 写"长度字"时反复用这一个

            int 偏移 = 0;
            // 返回结构/返回字符串:第 0 槽是"结果放哪"的地址(和 处理函数声明 里的布局对应)
            if (目的值 is { } 目的地)
            {
                string 放哪 = 取操作数寄存器(目的地);
                发出($"MOV {存址} {帧基}");
                发出($"存字间接 {放哪} {存址}");
                偏移 = 4;
            }
            for (int i = 0; i < 实参值.Count; i++)
            {
                int 声明宽 = 链路.参数表[i].宽度;
                int 槽宽 = 链路.参数表[i].引用 != null ? 声明宽 : 槽宽度(声明宽);
                bool 参数有符号 = 链路.参数表[i].引用 == null && 类型C.有符号(链路.参数表[i].类型名);
                表达式值 这个 = 实参值[i];
                // 参数槽是宽槽(C 档 `短整数` 按 4 字节放)→ 存之前按声明宽处理,要不被调方读到的就是脏高半:
                // **无符号补 0**(掩码)、**有符号补符号位**(符号扩展)
                if (槽宽 != 声明宽 && !这个.是常量 && !这个.已零扩展 && !这个.在槽里)
                {
                    string 源 = 这个.寄存器!;
                    if (参数有符号 && 声明宽 is 2)
                    {
                        if (!这个.可写) { 源 = 复制到临时(源); 这个 = 这个 with { 寄存器 = 源, 可写 = true }; }
                        发出符号扩展(源, 声明宽, 需先掩码: true);
                    }
                    else
                    {
                        string 掩码 = 常量操作数寄存器(截断掩码(声明宽), 源);
                        发出($"AND {源} {掩码}");
                    }
                    这个 = 这个 with { 已零扩展 = true };
                }
                else if (槽宽 != 声明宽 && 这个.是常量)
                {
                    // T6:常量装进窄类型的宽槽也要按声明宽处理 —— 以前只治了无符号(掩码),
                    // 有符号的常量(低 16 位 bit15 = 1)照原样存进去,被调方读出来就是正数而不是负数
                    // (`f(40000)` 传成 短整数 参数时读到 40000,而不是 -25536)。
                    if (参数有符号 && 声明宽 is 2 && (这个.常量 & 0x8000u) != 0)
                        这个 = 表达式值.常量值(这个.常量 | 0xFFFF0000u, 有符号: true);   // 就地补符号位,不花指令
                    else if ((这个.常量 >> (声明宽 * 8)) != 0)
                        这个 = 表达式值.常量值(这个.常量 & 截断掩码(声明宽));            // 常量就地截断(编译期,不花指令)
                }
                string 值寄存器 = 取操作数寄存器(这个);
                发出($"MOV {存址} {帧基}");
                if (偏移 > 0) 发出($"ADD_IMMEDIATE {存址} {偏移}");
                发出($"存字间接 {值寄存器} {存址}");      // 一次写 4 字节:越界部分会被后面的实参或局部区清零盖掉
                // 数组/字符串参数:地址存完,紧接着把"长度"也存进去(它占两个字)。
                // `出` 参数不占长度字(它整个就是"调用方字符串头的地址"一个字)
                if (链路.参数表[i].引用 is { 带长度: true, 出参数: false })
                {
                    if (实参长度[i] is { } 长)
                    {
                        if (长.槽 is { } 长槽) 发出读变量(长值, 长槽);
                        else 输出装载常量(长值, 长.常量);
                        发出($"MOV {存址} {帧基}");
                        发出($"ADD_IMMEDIATE {存址} {偏移 + 4}");
                        发出($"存字间接 {长值} {存址}");
                    }
                    else
                    {
                        throw 报错(行号, $"方法 '{链路.查名}' 的第 {i + 1} 个参数是数组参数({链路.参数表[i].类型名} 表[]):" +
                            "要传一个数组或列表的名字(不能是表达式)", $"argument {i + 1} of '{链路.查名}' needs an array or list");
                    }
                }
                偏移 += 槽宽;
            }

            发出($"MOV {帧指针寄存器} {帧基}");
            发出($"CALL {链路.标签}");
            发出($"SUB_IMMEDIATE {帧指针寄存器} {函数帧大小}");   // 复原本函数的帧(结果在 R0)

            _语句占用 = [.. 调用前占用];                   // 释放调用内部占用的临时寄存器
            _语句常量 = null;                               // 常量缓存跟着一起失效(寄存器已经放回池子)
        }

        /// <summary>
        /// 这个节点算出来必定是 0/1 吗?(比较、&amp;&amp;、||、!)—— `!` 靠它省掉一整段比较(直接异或 1)。
        /// </summary>
        private static bool 是零一节点(表达式节点C 节点) => 节点 switch
        {
            二元节点C 二元 => 二元.记号 is "==" or "!=" or "<" or ">" or "<=" or ">=" or "&&" or "||",
            一元节点C { 记号: "!" } => true,
            _ => false,
        };

        /// <summary>
        /// **比较当值用**:`(a &gt; b)` 就是一个 `逻辑` 值(0/1)。
        /// **不动 ISA** —— 展开成"成立取 1、不成立取 0"的一小段跳转(约 4~5 条),
        /// 语义、有符号处理、常量折叠全都和 `如果 (a &gt; b)` 共用同一套(比较跳转)。
        /// </summary>
        private 表达式值 求值比较值(二元节点C 二元, int 行号, string 原文, string? 首选目标)
        {
            // 左操作数直接算进首选目标(和普通二元运算一套):嵌套比较时省一个临时寄存器。
            // 安全:0/1 是**比较做完之后**才写进目标的,那时左操作数已经用完了。
            表达式值 左 = 求值节点(二元.左, 行号, 原文, 首选目标);
            if (二元.右.含调用) 左 = 暂存到槽(左);          // 右边要调函数:左边的值先躲进槽
            表达式值 右 = 求值节点(二元.右, 行号, 原文, null);

            // 通用化(2026-10):**浮点比较走 `浮点比较`(0x3D,关系码在 §3.1)**,不走整数 `比较`。
            // 结果是一个 0/1 的**整数**(逻辑值)—— 所以 `是浮点` 明确置 false,
            // 否则 `输出行(左 < 右)` 会拿 0/1 去走浮点打印,打出 `1*2^-149`(踩过)。
            if (左.是浮点 || 右.是浮点)
                return 求值浮点比较值(二元, 左, 右, 行号, 原文, 首选目标);

            // 两边都是常量 → 编译期定死(按有符号与否折叠,和条件那边一个规矩)
            if (左.是常量 && 右.是常量)
                return 表达式值.常量值(比较常量(二元.记号, 左.常量, 右.常量, 左.有符号 || 右.有符号) == true ? 1u : 0u);

            string 目标 = 首选目标 ?? 新临时();
            // P13:两边都在寄存器里(右边是常量就装进一个临时)时,一条 `比较取值` 顶掉整段跳转
            if (试发比较取值(左, 右, 二元.记号, 目标, 行号))
                return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true, 是浮点: false);
            string 真标签 = 新标签("Cmp真");
            string 完标签 = 新标签("CmpEnd");
            比较跳转(左, 右, 二元.记号, 行号, 真标签, 跳则真: true);
            输出装载常量(目标, 0);        // 比较已经做完 → 这时候才写目标,目标可以正好是操作数寄存器
            发出($"JMP {完标签}");
            发出($"{真标签}:");
            输出装载常量(目标, 1);
            发出($"{完标签}:");
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true, 是浮点: false);
        }

        /// <summary>
        /// 通用化(2026-10):**浮点比较当值用**(`(左 &lt; 右)` ⇒ 0/1),一条 `浮点比较`(0x3D)。
        /// <para>
        /// 口径(与 `Sample\库\float32.hb` 一致,也就是 IEEE754):
        /// **无序(NaN)时有序比较一律 0,而 `!=` 给 1** —— 这条由 ISA 的 `浮点比较` 自己实现,
        /// 中间层只负责把关系码算对。
        /// </para>
        /// <para>
        /// 结果**是整数**(逻辑值 0/1),不是浮点 —— 所以调用方那条打印路会走整数打印。
        /// 整数那一边的操作数先 `整数转浮点`(混合比较:`左 &lt; 3` 里的 3)。
        /// </para>
        /// </summary>
        private 表达式值 求值浮点比较值(二元节点C 二元, 表达式值 左, 表达式值 右,
            int 行号, string 原文, string? 首选目标)
        {
            左 = 落到寄存器(左);
            右 = 落到寄存器(右);
            // 关系码:第 3 位 = 按有符号 —— 浮点比较用不上那一位,但 `取关系码` 的记号表是共用的
            if (指令C.取关系码(二元.记号, false) is not { } 码)
                throw 报错(行号, $"浮点比较不支持这个记号:`{二元.记号}`(只支持 == != < > <= >=)",
                    $"unsupported float comparison operator '{二元.记号}'");

            string 左寄 = 浮点操作数寄存器(左, 行号, 原文);
            string 右寄 = 浮点操作数寄存器(右, 行号, 原文);
            string 目标 = 首选目标 ?? 新临时();
            // `浮点比较 Rd, Rs, 码` 的 Rd 既是左操作数又是结果 ⇒ 摆寄存器的规矩与 `试发比较取值` 一样:
            if (左寄 == 右寄)
            {
                // 同一个寄存器(如 `左 == 左`):自己跟自己比,一条就够
                发出($"浮点比较 {左寄} {左寄} {码}");
                return 表达式值.寄存器值(左寄, 可写: true, 已零扩展: true, 是浮点: false);
            }
            if (目标 == 左寄)
            {
                发出($"浮点比较 {目标} {右寄} {码}");
            }
            else if (目标 == 右寄)
            {
                // 目标就是右操作数那个寄存器:借一个临时算,再搬回目标(不能先动目标)
                string 借 = 选暂存寄存器([目标, 左寄]);
                发出($"复制 {借} {左寄}");
                发出($"浮点比较 {借} {目标} {码}");
                发出($"复制 {目标} {借}");
            }
            else
            {
                发出($"复制 {目标} {左寄}");
                发出($"浮点比较 {目标} {右寄} {码}");
            }
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true, 是浮点: false);
        }

        /// <summary>
        /// P13:试着用一条 `比较取值`(ISA 0x2F)算出"关系成立取 1、不成立取 0"。
        /// 发不发得成看三件事:①记号认识(==/!=/&gt;/&lt;/&gt;=/&lt;=)②两边都不在槽里
        /// ③右边要能塞进一个寄存器(常量就先装一次)。发成了返回 true;发不成返回 false,交给老的跳转那条路
        /// (老路还管报错,一个字都没改)。
        /// `比较取值 Rd, Rs, 码` 的 Rd 既是左操作数也是结果 —— 所以左值不在 Rd 里时先 `复制` 一次;
        /// 目标正好是右操作数那个寄存器时,用临时寄存器算完再搬回去(不能先把左值写进 Rd,那会盖掉右值)。
        /// </summary>
        /// <summary>
        /// **循环移位的形状识别**(ISA 扩容批 2/批 3 的"用在哪"):把
        /// `(值 &lt;&lt; n) | (值 &gt;&gt; (32 - n))` 认成**一条 `循环左移`(0x4E)**,
        /// 把 `(值 &gt;&gt; n) | (值 &lt;&lt; (32 - n))` 认成**一条 `循环右移`(0x4F)**。
        /// <para>
        /// 为什么值得单开一条快路:老写法展开出来是"左移 + 右移 + 或"三条,再算一次 `32 - n`,
        /// 实测(`ISA扩容落地台账.md` §6.3)`位.hb` 的 `循环右移` 老写法**约 48 条指令一次**。
        /// </para>
        /// <para>
        /// **口径与老写法逐位相同**(不许改语义):`n = 0` 与 `n = 32` 老写法给的就是"值本身"
        /// (移 0 位:左移 = 值、右移 = 值、或起来还是值;移 32 位:硬件取 `n &amp; 31` ⇒ 也是 0 位)
        /// ⇒ 新指令 `n &amp; 31 = 0` 时原样返回,两边一致。
        /// </para>
        /// <para>
        /// **保守三条**:① 只在 `值` 那一半**不含函数调用**时认(含调用时求值顺序与暂存更绕,不值得为它冒险);
        /// ② 两边必须移的是**同一个写法**的 `值`;③ `n` 与 `32 - n` 都要是**编译期常量**且落在 `1~31`。
        /// </para>
        /// </summary>
        /// <summary>
        /// **字节交换的形状识别**(ISA 扩容批 2 的"用在哪"):把
        /// `((值 &amp; 255) &lt;&lt; 24) | ((值 &amp; 65280) &lt;&lt; 8) | ((值 &amp; 16711680) &gt;&gt; 8) | (值 &gt;&gt; 24)`
        /// 认成**一条 `字节交换`(0x50)**。
        /// <para>
        /// 为什么用这个形状而不是库里的"四轮循环":循环体里有临时变量与计数器,**语句层**认整个循环太脆;
        /// 这条式子形状固定、认得住,库那边把它改写成这一句就行(公开 API 一个字不改)。
        /// </para>
        /// <para>
        /// **逐位口径**:每一段管"把第几个字节搬到第几个",四段的**目标字节**必须 0 / 1 / 2 / 3 **各一次**
        /// —— 那才是字节反转(掩码定的是**源**字节;没写掩码那一段只有 `值 &gt;&gt; 24`,源就是最高的那个字节)。
        /// 位移量必须是 8 的整数倍(整字节搬运)。任一条对不上就不认(宁可走老路,不许改语义)。
        /// </para>
        /// <para>
        /// ⚠ **有符号值不认**(2026-10-13 补的):有符号的 `&gt;&gt;` 走**算术右移**(见 `求值算术右移`),
        /// 补的是符号位,与"字节反转"逐位不同 ⇒ 那种写法一律退回老路。
        /// 这一条同时管住"常量折叠"那一支(折叠出来的位模式也一样)。
        /// </para>
        /// </summary>
        private 表达式值? 试发字节交换(二元节点C 根, int 行号, string 原文, string? 首选目标)
        {
            var 段 = new List<表达式节点C>();
            void 拆(表达式节点C 节)
            {
                if (节 is 二元节点C { 记号: "|" } 或) { 拆(或.左); 拆(或.右); }
                else 段.Add(节);
            }
            拆(根);
            if (段.Count != 4) return null;

            string? 值原文 = null;
            var 见到 = new bool[4];
            foreach (表达式节点C 节 in 段)
            {
                // 每一段都要是 `X << k` / `X >> k`;`X` 要么是"值"本身,要么是 `值 & 掩码`
                if (节 is not 二元节点C { 记号: "<<" or ">>" } 移) return null;
                if (移.右 is not 常量节点C 移位量) return null;
                int 移几位 = (int)移位量.值;
                if (移几位 is 0 or > 24 || 移几位 % 8 != 0) return null;       // 只认整字节搬运
                表达式节点C 基 = 移.左;
                int 源;
                if (基 is 二元节点C { 记号: "&" } 与)
                {
                    if (与.右 is not 常量节点C 掩码节) return null;
                    源 = -1;
                    for (int 号 = 0; 号 < 4; 号++)
                        if (掩码节.值 == (0xFFu << (8 * 号))) 源 = 号;          // 掩码必须是"恰好一个字节"
                    if (源 < 0) return null;
                    基 = 与.左;
                }
                else
                {
                    // 没写掩码:只认 `值 >> 24`(最高那个字节整体落到第 0 个字节)
                    if (移.记号 != ">>" || 移几位 != 24) return null;
                    源 = 3;
                }
                if (基 is not 名字节点C 名) return null;
                值原文 ??= 名.名;
                if (名.名 != 值原文) return null;

                int 目标 = 移.记号 == "<<" ? 源 + 移几位 / 8 : 源 - 移几位 / 8; // 这一段搬到第几个字节
                if (目标 is < 0 or > 3) return null;
                if (见到[目标]) return null;                                   // 同一个目标字节只许搬一次
                见到[目标] = true;
            }
            if (!见到[0] || !见到[1] || !见到[2] || !见到[3]) return null;

            // 有符号值的 `>>` 是算术右移:先按声明查一次,免得白发一条读(查不到就交给下面的求值去报错)
            if (查变量(值原文!) is { 有符号: true }) return null;

            表达式值 值 = 求值节点(new 名字节点C(值原文!), 行号, 原文, 首选目标);
            if (值.是浮点) return null;                        // 浮点写这个形状本来就该报错,交回老路去报
            if (值.是常量) return 表达式值.常量值(位反转常量(值.常量), 有符号: false);
            if (值.在槽里 || !值.可写)
            {
                string 借 = 新临时();
                发出($"复制 {借} {值.寄存器}");
                值 = 表达式值.寄存器值(借, 可写: true);
            }
            发出($"字节交换 {值.寄存器}");
            return 值;
        }

        /// <summary> 常量版的字节交换(编译期折叠用;与 `字节交换` 0x50 逐位一致) </summary>
        private static uint 位反转常量(uint v)
            => ((v & 0x000000FFu) << 24) | ((v & 0x0000FF00u) << 8) | ((v & 0x00FF0000u) >> 8) | ((v & 0xFF000000u) >> 24);
        /// <summary>
        /// **循环移位的形状识别**(ISA 扩容批 2 / 批 3 的"用在哪"):把
        /// `(值 &lt;&lt; n) | (值 &gt;&gt; (32 - n))` 认成**一条 `循环左移`(0x4E)**、
        /// `(值 &gt;&gt; n) | (值 &lt;&lt; (32 - n))` 认成**一条 `循环右移`(0x4F)**。
        /// <para>
        /// 为什么值得单开一条快路:老写法展开出来是"左移 + 右移 + 或"三条,再算一次 `32 - n`,
        /// 实测约 **48 条 / 次**(`ISA扩容落地台账.md` §6.3 的探针读数)。
        /// </para>
        /// <para>
        /// **两档都认**:① **常量档**(`n` 与 `32 - n` 都是字面量)② **变量档**(右边写成 `32 - n`,
        /// 与左边同一个 `n`)—— 库 `位.hb` 的 `循环左移` / `循环右移` 的移位量是**形参**,靠的就是变量档。
        /// </para>
        /// <para>
        /// **口径与老写法逐位相同**(不许改语义):`左移` / `右移` 的移位量都**取低 5 位**、`右移` 是逻辑右移
        /// (见 `引擎\指令C.cs` 那两行),而 `循环左移` / `循环右移` 的移位量同样取低 5 位
        /// ⇒ 对**任意** `n`(含 `0` 与 `≥32`)两边都是同一个结果,不是"只对 1~31 成立"。
        /// </para>
        /// <para>
        /// 三条不让认的:**有符号值**(它的 `&gt;&gt;` 是算术右移,补符号位 ≠ 循环移位)、
        /// **带调用的子表达式**(老写法把 `值` 与 `n` 各求值两次,合并成一次就改了行为)、
        /// **浮点**(那本来就该报"浮点不能这么算",不能让识别器抢在前面把它变成一条静默的循环移位)。
        /// </para>
        /// </summary>
        private 表达式值? 试发循环移位(二元节点C 或, int 行号, string 原文, string? 首选目标)
        {
            if (或.左 is not 二元节点C { 记号: "<<" or ">>" } 左 || 或.右 is not 二元节点C { 记号: "<<" or ">>" } 右) return null;
            if (左.记号 == 右.记号) return null;                      // 同向:不是循环移位
            if (左.左.显示() != 右.左.显示()) return null;             // 两边移的必须是同一个东西
            if (左.左.含调用) return null;                            // 有调用:老写法求值两次,合并就改了行为
            bool 是左循环 = 左.记号 == "<<" && 右.记号 == ">>";

            // 移位量:常量档直接比两个字面量;变量档认右边那棵 `32 - n`(n 与左边同一个式子)
            常量节点C? 常量量 = null;
            表达式节点C? 变量量 = null;
            if (左.右 is 常量节点C 左量)
            {
                if (左量.值 is 0 or > 31) return null;
                if (右.右 is not 常量节点C 右量 || 右量.值 != 32 - 左量.值) return null;
                常量量 = 左量;
            }
            else if (右.右 is 二元节点C { 记号: "-" } 差
                     && 差.左 is 常量节点C { 值: 32 }
                     && 差.右.显示() == 左.右.显示())
            {
                if (左.右.含调用) return null;
                变量量 = 左.右;
            }
            else return null;

            // 有符号值的 `>>` 是算术右移:先按声明查一次,免得白发一条读(查不到就交给下面的求值去报错)
            if (左.左 is 名字节点C 基名 && 查变量(基名.名) is { 有符号: true }) return null;

            表达式值 值 = 求值节点(左.左, 行号, 原文, 首选目标);
            if (值.是浮点) return null;                                // 交回老路去报"浮点不能这么算"
            if (值.有符号) return null;                                // 同上:算术右移 ≠ 循环移位

            if (常量量 is { } 常)                                      // ---- 常量档:移位量是字面量 ----
            {
                uint n = 常.值;
                if (值.是常量)
                    return 表达式值.常量值(是左循环 ? (值.常量 << (int)n) | (值.常量 >> (32 - (int)n))
                                                    : (值.常量 >> (int)n) | (值.常量 << (32 - (int)n)), 有符号: false);
                if (值.在槽里 || !值.可写)
                {
                    string 借 = 新临时();
                    发出($"复制 {借} {值.寄存器}");
                    值 = 表达式值.寄存器值(借, 可写: true);
                }
                string 量 = 新临时();
                发出($"加载立即数 {量} {n}");
                发出($"{(是左循环 ? "循环左移" : "循环右移")} {值.寄存器} {量}");
                return 值;
            }

            // ---- 变量档:移位量算一次进临时寄存器(ROL / ROR 的第二操作数就是寄存器) ----
            if (值.在槽里 || !值.可写)
            {
                string 借 = 新临时();
                发出($"复制 {借} {值.寄存器}");
                值 = 表达式值.寄存器值(借, 可写: true);
            }
            string 移量 = 新临时();
            表达式值 量值 = 求值节点(变量量!, 行号, 原文, null);
            if (量值.是浮点) return null;
            if (量值.是常量) 输出装载常量(移量, 量值.常量);
            else if (量值.寄存器 != 移量) 发出($"复制 {移量} {量值.寄存器}");
            发出($"{(是左循环 ? "循环左移" : "循环右移")} {值.寄存器} {移量}");
            return 值;
        }

        /// <summary> 关系符两边对调之后等价的写法(`甲 &gt; 乙` ⇔ `乙 &lt; 甲`);相等 / 不等对调还是自己 </summary>
        private static string 对调关系(string 记号) => 记号 switch
        {
            ">" => "<",
            "<" => ">",
            ">=" => "<=",
            "<=" => ">=",
            _ => 记号,
        };

        /// <summary>
        /// 这个节点求值"不会出错、也没有副作用"吗:常量、一个名字(变量 / 字段),
        /// 或者由它们拼起来的关系式 / 三目(**不含调用、不做除法取余、不取下标、不碰堆**)。
        /// 给"两边都要先算出来"的那类快路当门槛用(见 `试发条件移动`)。
        /// </summary>
        private static bool 是纯取值(表达式节点C 节) => 节 switch
        {
            常量节点C or 名字节点C => true,
            三目节点C 三 => 是纯取值(三.条件) && 是纯取值(三.真) && 是纯取值(三.假),
            二元节点C { 记号: "==" or "!=" or "<" or ">" or "<=" or ">=" } 比 => 是纯取值(比.左) && 是纯取值(比.右),
            _ => false,
        };

        /// <summary>
        /// **三目 → 一条 `条件移动`(0x59)**:`甲 关系 乙 ? 甲 : 乙` 这种(最大 / 最小 / 钳位那一族典型写法)
        /// 展开成**一条 `条件移动`**,老路是"条件跳转 + 两支各搬一次 + 跳转 + 两个标签"约 5~7 条。
        /// <para>
        /// ⚠ **`条件移动` 是按"两个操作数自己的关系"选的,不看 PSW**(2026-10-13 核过三条腿:
        /// `引擎\虚拟机C.cs` / `C后端\运行时.c` / `C后端\转译器C.cs` 都是 `(甲 关系 乙) ? 甲 : 乙`;
        /// 文档以前写"按 PSW 选"是错的,已改)⇒ **两支必须就是条件那两个操作数**(顺序可以换,
        /// 关系符跟着对调),别的一律不认。
        /// </para>
        /// <para>
        /// 三条门槛(缺一条就退回老路):① 四个操作数都只许是**常量或一个名字**(字段也算)——
        /// 老路只算被选中的那一支,而这条两边都要先取出来;② **不含调用**(同上,副作用不能多算);
        /// ③ **不许是浮点**(位模式按整数比大小是错的,浮点那一档走 `浮点比较` + 跳转)。
        /// </para>
        /// </summary>
        private 表达式值? 试发条件移动(表达式节点C 条件, 表达式节点C 真节, 表达式节点C 假节,
            int 行号, string 原文, string? 首选目标)
        {
            if (条件 is not 二元节点C { 记号: "==" or "!=" or "<" or ">" or "<=" or ">=" } 比) return null;
            if (!是纯取值(比.左) || !是纯取值(比.右) || !是纯取值(真节) || !是纯取值(假节)) return null;

            string 左文 = 比.左.显示(), 右文 = 比.右.显示();
            string 真文 = 真节.显示(), 假文 = 假节.显示();
            string 码记号;
            if (真文 == 左文 && 假文 == 右文) 码记号 = 比.记号;
            else if (真文 == 右文 && 假文 == 左文) 码记号 = 对调关系(比.记号);
            else return null;

            string 到寄存器(表达式值 值) => 值.是常量 ? 常量操作数寄存器(值.常量) : 落到寄存器(值).寄存器!;

            string 目标 = 首选目标 ?? 新临时();
            var 省着 = 记占用();
            表达式值 真值 = 求值节点(真节, 行号, 原文, null);
            if (真值.是浮点) { 还占用(省着); return null; }
            表达式值 假值 = 求值节点(假节, 行号, 原文, null);
            if (假值.是浮点) { 还占用(省着); return null; }
            string 真寄 = 到寄存器(真值), 假寄 = 到寄存器(假值);
            if (指令C.取关系码(码记号, 真值.有符号 || 假值.有符号) is not { } 码) { 还占用(省着); return null; }
            发出($"条件移动 {目标} {真寄} {假寄} {码}");
            还占用(省着, 目标);
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: 真值.已零扩展 && 假值.已零扩展);
        }

        /// <summary>
        /// 三目快路(一条 `条件移动`)的**文本入口**:三边各自解析成节点,再交给上面那个节点版。
        /// 为什么需要它:`求值表达式` 是**先按文本把三目切开**的(`找顶层三目`,为的是"没被选中的那一支
        /// 连 `地址(...)` 都别算"),绝大多数三目走的是那条文本路 —— 只在 AST 那一侧挂钩子会够不着。
        /// </summary>
        private 表达式值? 试发条件移动文本(string 条件, string 真, string 假, int 行号, string 原文, string? 首选目标)
        {
            try
            {
                return 试发条件移动(表达式语法C.解析(条件), 表达式语法C.解析(真), 表达式语法C.解析(假),
                    行号, 原文, 首选目标);
            }
            catch (表达式语法异常C)
            {
                return null;      // 认不出的写法:退回老路(老路自己会报它该报的错)
            }
        }
        private bool 试发比较取值(表达式值 左, 表达式值 右, string 记号, string 目标, int 行号)
        {
            if (左.在槽里 || 右.在槽里) return false;
            if (指令C.取关系码(记号, 左.有符号 || 右.有符号) is not { } 码) return false;
            if (左.是常量 && 右.是常量) return false;      // 都常量:上面已经折叠过了

            // 右操作数:寄存器直接用;常量就装进一个临时(避开目标寄存器,免得盖掉左值要写的目标)
            string 右寄;
            if (右.寄存器 is { } 右r) 右寄 = 右r;
            else 右寄 = 常量操作数寄存器(右.常量, 目标);

            if (左.寄存器 is not { } 左r)
            {
                // 左是常量、右在寄存器里:把常量装进目标再比(目标这时还是空的)
                输出装载常量(目标, 左.常量);
                发出($"CMP_SET {目标} {右寄} {码}");
                return true;
            }
            if (目标 == 左r)
            {
                发出($"CMP_SET {目标} {右寄} {码}");
                return true;
            }
            if (目标 == 右寄)
            {
                // 目标就是右操作数那个寄存器:借一个临时算,再搬回目标(不能先动目标)
                string 借 = 选暂存寄存器([目标, 左r]);
                发出($"MOV {借} {左r}");
                发出($"CMP_SET {借} {目标} {码}");
                发出($"MOV {目标} {借}");
                return true;
            }
            发出($"MOV {目标} {左r}");
            发出($"CMP_SET {目标} {右寄} {码}");
            return true;
        }

        /// <summary>
        /// **字符串比较当值用**:`(s == "内容")` 是一个 `逻辑` 值(0/1)。
        /// 形状和数字那边完全一样(成立取 1、不成立取 0),只是比较本身按"三态"展开(见 发出字符串比较三态)。
        /// </summary>
        private 表达式值 求值字符串比较值(二元节点C 二元, int 行号, string 原文, string? 首选目标)
        {
            if (!是字符串节点(二元.左) || !是字符串节点(二元.右))
                throw 报错(行号, $"字符串只能和字符串比: '{二元.显示()}'。要比长度写 a.长度()(整数)再比,要取某个字节写 a[下标]",
                    $"a string can only be compared with another string: '{二元.显示()}'");
            string 目标 = 首选目标 ?? 新临时();
            string 真标签 = 新标签("串比真");
            string 完标签 = 新标签("串比完");
            (uint 命中, string 指令) = 关系符对三态(二元.记号, 行号);
            // 比较要占 7~8 个寄存器(两边的地址/长度 + 下标 + 两个字节 + 三态),
            // 所以**自成一段**:里面重新分配寄存器池,只把结果目标保护住 —— 不然嵌在 && / 或函数实参里会把 15 个用光。
            自成一段(() =>
            {
                string 三 = 发出字符串比较三态(字符串节点文本(二元.左), 字符串节点文本(二元.右), 行号, 原文);
                发出($"CMP_IMMEDIATE {三} {命中}");
                发出($"{指令} {真标签}");
                输出装载常量(目标, 0);
                发出($"JMP {完标签}");
                发出($"{真标签}:");
                输出装载常量(目标, 1);
                发出($"{完标签}:");
            }, 目标);
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true);
        }

        /// <summary> 这个 AST 节点是不是"一个字符串"(字面量节点 / 名字指向字符串变量或字符串参数 / 返回字符串的调用) </summary>
        private bool 是字符串节点(表达式节点C 节点) => 节点 switch
        {
            字符串节点C => true,
            名字节点C 名 => 是字符串操作数(名.名),
            调用节点C 调用 => 是字符串返回调用文本(调用.显示(), 0),
            _ => false,
        };

        /// <summary> 字符串节点的原文(字面量带引号;名字就是名字;返回字符串的调用是调用写法)
        /// —— 交给 字符串实参地址 去取地址与长度 </summary>
        private static string 字符串节点文本(表达式节点C 节点) => 节点 switch
        {
            字符串节点C 串 => 串.原文,
            名字节点C 名 => 名.名,
            调用节点C 调用 => 调用.显示(),
            _ => "",
        };

        /// <summary>
        /// `(a &gt; 0) &amp;&amp; (b &gt; 0)` 当值用:结果 0/1,**短路语义照旧**
        /// (左边定了就不再算右边,右边的函数也不会被调用)。
        /// </summary>
        private 表达式值 求值逻辑值(二元节点C 二元, int 行号, string 原文, string? 首选目标)
        {
            bool 是且 = 二元.记号 == "&&";
            表达式值 左 = 求值节点(二元.左, 行号, 原文, 首选目标);
            if (左.是常量)
            {
                bool 左真 = 左.常量 != 0;
                if (是且 && !左真) return 表达式值.常量值(0);     // 0 && 任何 → 0(短路,右边不求值)
                if (!是且 && 左真) return 表达式值.常量值(1);     // 非 0 || 任何 → 1(短路)
                // 左边定不了整个结果 → 结果就是"右边非不非 0"
                表达式值 右 = 求值节点(二元.右, 行号, 原文, 首选目标);
                return 折成零一(右, 行号, 首选目标);
            }

            string 目标 = 首选目标 ?? 新临时();
            string 算右 = 新标签("Log右");
            string 完 = 新标签("LogEnd");
            落到目标(左, 目标);
            if (是且)
            {
                发出($"JZ {目标} {完}");            // 左假 → 结果就是 0(目标里已经是 0)
                表达式值 右 = 求值节点(二元.右, 行号, 原文, 目标);   // 目标这时候已经没用了,右边直接算进来
                落到目标(右, 目标);
                发出($"JZ {目标} {完}");            // 右假 → 0
                输出装载常量(目标, 1);              // 两边都非 0 → 1
            }
            else
            {
                发出($"JZ {目标} {算右}");
                输出装载常量(目标, 1);              // 左真 → 1,右边不用算了
                发出($"JMP {完}");
                发出($"{算右}:");
                表达式值 右 = 求值节点(二元.右, 行号, 原文, 目标);
                落到目标(右, 目标);
                发出($"JZ {目标} {完}");            // 右假 → 0
                输出装载常量(目标, 1);
            }
            发出($"{完}:");
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true);
        }

        /// <summary> `!值`:0/1 的走一条 `异或 1`;其它值按"是不是 0"折成 0/1(常量直接折叠) </summary>
        private 表达式值 求值取反(表达式节点C 子节点, int 行号, string 原文, string? 首选目标)
        {
            表达式值 值 = 求值节点(子节点, 行号, 原文, 首选目标);
            if (值.是常量) return 表达式值.常量值(值.常量 == 0 ? 1u : 0u);
            // 第96批(批 13 写浮点库时抓到):**调用结果会先暂存到临时槽**(跨 CALL 要落槽),
            // 于是这里的 `值` 可能是"槽值"而不是寄存器 —— 直接拿去 `比较跳转` 会发出
            // `CMP_IMMEDIATE <非寄存器> 0`,汇编器当场报「CMP_IMMEDIATE 需要两个参数」。
            // 所以先搬进寄存器(与下面 `折成零一` 同一套做法)。
            值 = 落到寄存器(值);

            string 目标 = 首选目标 ?? 新临时();
            if (是零一节点(子节点))
            {
                落到目标(值, 目标);
                string 一 = 新临时();
                输出装载常量(一, 1);
                发出($"XOR {目标} {一}");           // 0 ↔ 1
                return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true);
            }

            string 真标签 = 新标签("Not真");
            string 完标签 = 新标签("NotEnd");
            比较跳转(值, 表达式值.常量值(0), "==", 行号, 真标签, 跳则真: true);
            输出装载常量(目标, 0);
            发出($"JMP {完标签}");
            发出($"{真标签}:");
            输出装载常量(目标, 1);
            发出($"{完标签}:");
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true);
        }

        /// <summary> 把一个值折成 0/1(非 0 → 1);常量直接折叠 </summary>
        private 表达式值 折成零一(表达式值 值, int 行号, string? 首选目标)
        {
            if (值.是常量) return 表达式值.常量值(值.常量 != 0 ? 1u : 0u);
            值 = 落到寄存器(值);
            string 目标 = 首选目标 ?? (值.可写 ? 值.寄存器! : 新临时());
            落到目标(值, 目标);
            string 真标签 = 新标签("Bool真");
            string 完标签 = 新标签("BoolEnd");
            发出($"CMP_IMMEDIATE {目标} 0");
            发出($"JEQ {真标签}");
            输出装载常量(目标, 0);
            发出($"JMP {完标签}");
            发出($"{真标签}:");
            输出装载常量(目标, 1);
            发出($"{完标签}:");
            return 表达式值.寄存器值(目标, 可写: true, 已零扩展: true);
        }

        /// <summary>
        /// **浮点的二元运算**(通用化 2026-10):`+ - * /` 各一条硬件指令,结果还是浮点。
        /// <para>
        /// 口径:
        /// </para>
        /// <list type="bullet">
        /// <item>`+ - * /` ⇒ `浮点加法`(0x38)/`浮点减法`(0x39)/`浮点乘法`(0x3A)/`浮点除法`(0x3B),
        ///       **除零给 ±Inf / NaN,不报错**(IEEE754 口径,与 `float32.hb` 一致)。</item>
        /// <item>**一边是整数、一边是浮点** ⇒ 整数那边先 `整数转浮点`(0x3F)——那 32 位按**有符号**读,
        ///       所以 `浮点 初值 = -1 + 0.5;` 得 `-0.5`(不是把 -1 当成 4294967295)。</item>
        /// <item>`%`(取余)**浮点没有** —— 当场报错,不悄悄退化成整数取余(那是静默错误)。</item>
        /// <item>移位/位运算(`& | ^ << >>`)对浮点**没意义** —— 同样当场报错。</item>
        /// </list>
        /// </summary>
        private 表达式值 应用浮点二元(string 记号, 表达式值 左, 表达式值 右, int 行号, string 原文, string? 首选目标)
        {
            string? 指令 = 记号 switch
            {
                "+" => "浮点加法",
                "-" => "浮点减法",
                "*" => "浮点乘法",
                "/" => "浮点除法",
                _ => null,
            };
            if (指令 == null)
                throw 报错(行号,
                    $"浮点不能这么算:`{记号}` —— 浮点只支持 `+ - * /`(ISA 那四条硬件指令)。" +
                    "取余要先转成整数,位运算(`& | ^ << >>`)对浮点没有意义。" +
                    (记号 == "%" ? "要取余可以 `整数(...) % 整数(...)`。" : ""),
                    $"invalid operator '{记号}' for float operands");

            string 左寄 = 浮点操作数寄存器(左, 行号, 原文);
            string 右寄 = 浮点操作数寄存器(右, 行号, 原文);
            string 目标 = 首选目标 ?? 新临时();
            // `浮点加法 Rd, Rs` 的 Rd 既是左操作数又是结果 ⇒ 左值不在目标里就先搬一次
            if (左寄 != 目标) 发出($"复制 {目标} {左寄}");
            // 目标正好是右操作数那个寄存器:先借一个临时算完再搬回去(不能算进目标,那会盖掉右值)
            if (目标 == 右寄)
            {
                string 借 = 选暂存寄存器([目标, 左寄]);
                发出($"复制 {借} {目标}");
                发出($"{指令} {借} {目标}");
                发出($"复制 {目标} {借}");
                return 表达式值.寄存器值(目标, 可写: true, 是浮点: true);
            }
            发出($"{指令} {目标} {右寄}");
            return 表达式值.寄存器值(目标, 可写: true, 是浮点: true);
        }

        /// <summary>
        /// 把一个操作数摆成"能喂给浮点指令"的寄存器:浮点值原样给寄存器;
        /// 整数(常量或寄存器)**先 `整数转浮点`**(0x3F)。
        /// </summary>
        private string 浮点操作数寄存器(表达式值 值, int 行号, string 原文)
        {
            string 寄 = 取操作数寄存器(值);
            if (值.是浮点) return 寄;
            // 整数那一边:借一个临时做转换,别改原寄存器(它可能还被别处用着)
            string t = 新临时();
            发出($"复制 {t} {寄}");
            发出($"整数转浮点 {t}");
            return t;
        }

        private 表达式值 应用二元(string 记号, 表达式值 左, 表达式值 右, int 行号, string 原文, string? 首选目标)
        {
            // 运算前把"在槽里"的操作数读回寄存器
            左 = 落到寄存器(左);
            右 = 落到寄存器(右);

            // ================= 通用化(2026-10):浮点那一支 =================
            // **任一边是浮点就按浮点算**(与下面 `有符号` 同一条口径)。
            // 浮点值就是寄存器里那 32 位 IEEE754 位模式,所以四则运算**各一条硬件指令**
            // (`浮点加法` 0x38 / `浮点减法` 0x39 / `浮点乘法` 0x3A / `浮点除法` 0x3B)——
            // 不走 `Sample\库\float32.hb` 那套软件展开,一个函数调用都不发。
            // 整数这边一个字没动:不进这个分支的老路原样跑。
            if (左.是浮点 || 右.是浮点)
                return 应用浮点二元(记号, 左, 右, 行号, 原文, 首选目标);

            // **任一边有符号就按有符号算**(比 C 的隐式转换好懂):除/取余要单独走一段(ISA 的 DIV/MOD 是无符号的)
            bool 有符号 = 左.有符号 || 右.有符号;
            // 例外:**移位**"算术还是逻辑"只看**左**操作数 —— 移几位是个计数,它的符号性不该改变结果怎么移。
            // 第96批(写 float32 库时抓到):`无符号整数 x; 整数 n; x >> n` 以前走**算术**右移,
            // 实测 `双_右移` 里 `x.低 >> n` 把 0xFFFFFFFF 移成了 0xFFFFFFFF(修前)。
            bool 移位有符号 = 记号 is "<<" or ">>" ? 左.有符号 : 有符号;

            // 两个都是常量 → 编译期折叠
            // T4(2026-09-27 评测整改):**折出来的常量,符号性不能只看"左右有没有符号"**。
            // `(0-1)` 折出来是 0xFFFFFFFF —— 它**就是 -1**,与 `-1` 这个写法同一个值、同一个答案;
            // 以前这里照 `有符号`(两个正常量 ⇒ false)标,于是
            // `(0-1) < 0` 判 0、`输出行(0-1)` 打 4294967295、`(2-5)/2` 打 2147483646(全是静默给错答案)。
            // 规矩:算术记号(+ - * / % >>)折出的值**32 位补码最高位是 1 就当负数**;
            // 位运算(& | ^ <<)与一元 `~` 保持原样 —— 它们算的是位,不说正负。
            // 移位按哪一边的符号性算,与上面 `移位有符号` 那条口径一致。
            if (左.是常量 && 右.是常量)
            {
                bool 算术 = 记号 is "+" or "-" or "*" or "/" or "%" or ">>";
                uint 折出 = 计算常量(记号, 左.常量, 右.常量, 行号, 原文, 有符号 || 移位有符号);
                bool 折后符号 = 有符号 || (算术 && (折出 & 0x80000000u) != 0);
                return 表达式值.常量值(折出, 折后符号);
            }

            if (有符号 && 记号 is "/" or "%")
            {
                // A2(第100批)+ A9(第108批):**除数是 2 的幂**时除 / 取余都走短路径 ——
                //   `x % 2^k` = 取绝对值后的低位 → `与立即数` 一条(不用 MOD);
                //   `x / 2^k` = 取绝对值后**逻辑右移 k 位**(绝对值非负,逻辑移就是算术移)→ `右移立即数` 一条
                //   (以前没做是因为 ISA 没有立即数右移,"装常量 + DIV"那两条省不掉;A9 加了 0x34 之后就划算了)。
                //   实测(对照程序 2000 轮,见 任务清单 第101节 / 第109节):`% 8` 13 → **10** 条,`/ 8` 13 → **10** 条。
                if (右.是常量 && 右.常量 != 0
                    && (右.常量 & (右.常量 - 1)) == 0 && 右.常量 - 1 <= 0xFFFFF)
                {
                    if (记号 == "%" && 右.常量 == 1) return 表达式值.常量值(0, 有符号: true);   // `x % 1` 恒为 0
                    string 幂目标 = 首选目标 ?? 新临时();
                    string 幂被除 = 取操作数寄存器(左);
                    if (幂目标 == 幂被除) 幂被除 = 复制到临时(幂被除);
                    if (记号 == "%") 输出有符号取余二的幂(幂目标, 幂被除, 右.常量 - 1);
                    else 输出有符号除二的幂(幂目标, 幂被除, 尾零个数(右.常量));
                    return 表达式值.寄存器值(幂目标, 可写: true, 有符号: true);
                }
                string 除目标 = 首选目标 ?? 新临时();
                string 被除 = 取操作数寄存器(左);
                string 除数 = 取操作数寄存器(右);
                if (被除 == 除数) 除数 = 复制到临时(除数);
                if (除目标 == 被除) 被除 = 复制到临时(被除);
                if (除目标 == 除数) 除数 = 复制到临时(除数);
                // 通用化第2批(2026-10-10):ISA 新加的 `有符号除法`(0x40)/`有符号取余`(0x41)
                // 一条包干 —— 以前这里要按"除数是正数常量 / 通用"分两档各展开十几条(见那个方法的注释)
                输出有符号除取余(记号, 除目标, 被除, 除数);
                return 表达式值.寄存器值(除目标, 可写: true, 有符号: true);
            }
            // 有符号的右移 = **算术右移**(高位移进来的是符号位);ISA 只有逻辑右移,所以在编译期展开
            if (移位有符号 && 记号 == ">>") return 求值算术右移(左, 右, 行号, 原文, 首选目标);

            string 目标;
            if (左.是常量)
            {
                // 常量在左:可交换的记号翻成"寄存器 op 常量",否则 目标 = 常量 再运算
                bool 可交换 = 记号 is "+" or "*" or "&" or "|" or "^";
                if (可交换)
                {
                    目标 = 首选目标 ?? (右.可写 ? 右.寄存器! : 新临时());
                    输出二元到目标(目标, 右.寄存器!, 左.常量, 记号, 行号, 原文);
                    return 表达式值.寄存器值(目标, 可写: true, 有符号: 有符号);
                }
                目标 = 首选目标 ?? 新临时();
                if (右.寄存器 == 目标)
                {
                    // 目标正好装着右操作数(例如 R0 = 5 - R0):先保护再装载常量
                    string 保护 = 选暂存寄存器([目标]);
                    发出($"MOV {保护} {目标}");
                    输出装载常量(目标, 左.常量);
                    发出($"{运算符助记符(记号)} {目标} {保护}");
                }
                else
                {
                    输出装载常量(目标, 左.常量);
                    if (右.是常量) { string 暂存 = 选暂存寄存器([目标]); 输出装载常量(暂存, 右.常量); 发出($"{运算符助记符(记号)} {目标} {暂存}"); }
                    else 发出($"{运算符助记符(记号)} {目标} {右.寄存器}");
                }
                return 表达式值.寄存器值(目标, 可写: true, 有符号: 有符号);
            }

            // 寄存器在左:能省一条 MOV 就用左寄存器自身当目标(只限"自己分配的临时")
            目标 = 首选目标 ?? (左.可写 ? 左.寄存器! : 新临时());
            输出二元到目标(目标, 左.寄存器!, 右.是常量 ? 右.常量 : null, 记号, 行号, 原文, 右.是常量 ? null : 右.寄存器);
            return 表达式值.寄存器值(目标, 可写: true, 有符号: 有符号);
        }

        /// <summary>
        /// **有符号右移(算术右移)**:高位移进来的必须是符号位。ISA 只有逻辑右移,所以在这一层展开:
        ///   `x >> n` = (x 逻辑右移 n) | 掩码,掩码 = `0xFFFFFFFF 左移 (32-n)`(即高 n 位是 1)
        /// 常量次数:n = 0 → 原样;n ≥ 32 → 全符号位(负数 -1 / 正数 0);1~31 → 掩码是编译期常量,一条装载指令。
        /// 运行期次数:掩码用 `0xFFFFFFFF << (32-n)` 现算(ISA 的移位只看低 5 位,所以 32-n 正好),
        /// 并用"无分支判零"把 n = 0(掩码必须是 0)也处理对。
        /// </summary>
        private 表达式值 求值算术右移(表达式值 左, 表达式值 右, int 行号, string 原文, string? 首选目标)
        {
            bool 次数是常量 = 右.是常量;
            string 目标 = "";
            自成一段保守(() =>
            {
                string 值 = 取操作数寄存器(左);
                目标 = 首选目标 ?? (左.可写 ? 值 : 新临时());
                // 符号掩码:值是负数 → 0xFFFFFFFF,否则 0(铺符号位只对负数做)
                string 号 = 新临时();
                发出($"MOV {号} {值}");
                发出右移立即数(号, 31);                  // A9:一条顶"装常量 31 + 右移"
                发出($"NOT {号}");
                发出($"ADD_IMMEDIATE {号} 1");
                if (次数是常量)
                {
                    uint 次 = 右.常量;
                    if (次 == 0)
                    {
                        if (目标 != 值) 发出($"MOV {目标} {值}");
                        return;
                    }
                    if (次 >= 32)
                    {
                        // 移出 32 位以上:结果全是符号位(负数 → -1,正数 → 0)
                        发出($"MOV {目标} {值}");
                        发出右移立即数(目标, 31);
                        发出($"NOT {目标}");
                        发出($"ADD_IMMEDIATE {目标} 1");
                        return;
                    }
                    string 常掩 = 新临时();
                    输出装载常量(常掩, 0xFFFFFFFFu << (int)(32 - 次));
                    发出($"AND {常掩} {号}");
                    发出($"MOV {目标} {值}");
                    发出右移立即数(目标, (int)次);
                    发出($"OR {目标} {常掩}");
                    return;
                }
                // 运行期次数
                string 次数 = 取操作数寄存器(右);
                string 掩 = 新临时();
                输出装载常量(掩, 0xFFFFFFFFu);
                string 位移量 = 新临时();
                发出($"MOV {位移量} {次数}");
                发出($"NOT {位移量}");
                发出($"ADD_IMMEDIATE {位移量} 1");            // -次数
                发出($"ADD_IMMEDIATE {位移量} 32");           // 32 - 次数(移位只看低 5 位,正好)
                发出($"SHL {掩} {位移量}");                    // 掩 = 高"次数"位是 1
                string 判 = 新临时();
                发出($"MOV {判} {次数}");
                发出($"NOT {判}");
                发出($"ADD_IMMEDIATE {判} 1");
                发出($"OR {判} {次数}");                       // 次数非 0 时最高位是 1
                发出右移立即数(判, 31);                        // A9:一条顶"装常量 31 + 右移"
                发出($"NOT {判}");                             // 折成 0 / 0xFFFFFFFF 两种掩码再 AND
                发出($"ADD_IMMEDIATE {判} 1");
                发出($"AND {掩} {判}");                        // 次数为 0 → 掩码清 0(结果就是原值)
                发出($"AND {掩} {号}");                        // 值是正数 → 不铺符号位
                发出($"MOV {目标} {值}");
                发出($"SHR {目标} {次数}");
                发出($"OR {目标} {掩}");
            });
            return 表达式值.寄存器值(收下临时(目标), 可写: true, 有符号: true);
        }

        /// <summary>
        /// **有符号取余,除数是 2 的幂**(A2,第100批):`x % 2^k`,向零截断、余数符号看被除数(与 C 一样)。
        /// 与 输出有符号除取余正除数 同一套路(取绝对值 → 无符号取余 → 补符号),只差中间那一步:
        /// `装常量 + MOD` 两条 → `与立即数 掩码` 一条(P11),掩码 = 2^k - 1 ≤ 0xFFFFF(被除数是正数,
        /// 绝对值就是它自己)。顺带把"符号位 → 0/0xFFFFFFFF"从 5 条压到 4 条(符号位直接算在 掩 自己身上)。
        /// <para>
        /// **取绝对值那一步走 `取整数绝对值`(0x52)**(第434批):原来是位级两条(`XOR 被除 掩` + `SUB 被除 掩`,
        /// 恒等式 `|x| = (x ^ 掩) - 掩`),现在一条指令 —— 连 `-2^31` 的回绕口径都**逐位相同**
        /// (0x52 的定义就是 `R = |(有符号)R|`,`-2^31` 回绕成它自己),`x % 8` 因此 10 → **9** 条。
        /// 掩那 4 条**留着**:补符号还要它,`0x52` 只管把值变正、不产生符号掩码。
        /// </para>
        /// </summary>
        private void 输出有符号取余二的幂(string 目标, string 被除, uint 掩码)
        {
            string 掩 = 新临时();

            发出($"MOV {掩} {被除}");
            发出右移立即数(掩, 31);               // 0 / 1(A9:一条顶"装常量 31 + 右移")
            发出($"NOT {掩}");
            发出($"ADD_IMMEDIATE {掩} 1");        // 掩 = 0 / 0xFFFFFFFF(被除为负)
            发出($"取整数绝对值 {被除}");           // 被除 = |被除|(0x52 一条顶"异或 掩 + 减 掩"两条)

            发出($"MOV {目标} {被除}");
            发出($"AND_IMMEDIATE {目标} {掩码}");  // |被除| % 2^k(低位就是余数)

            发出($"XOR {目标} {掩}");
            发出($"SUB {目标} {掩}");             // 补符号:余数符号跟着被除数
        }

        /// <summary>
        /// **有符号除,除数是 2 的幂**(A9,第108批 —— A2 当时判"等 ISA 加立即数右移再说"的那一件):
        /// `x / 2^k`,向零截断、商的符号看被除数。与 `输出有符号除取余正除数` 同一套路(取绝对值 →
        /// 无符号除 → 补符号),把"`装常量 + DIV`"换成一条 `右移立即数`:绝对值非负,**逻辑右移就是算术右移**。
        /// A2 实测(对照程序 2000 轮):这条 13 条/轮 → **10 条/轮**。
        /// <para>
        /// **取绝对值那一步同样换成 `取整数绝对值`(0x52)**(第434批,与 `输出有符号取余二的幂` 同一个理由):
        /// 位级两条 → 一条,`x / 8` 10 → **9** 条;`-2^31` 的回绕口径与老写法逐位相同。
        /// </para>
        /// </summary>
        private void 输出有符号除二的幂(string 目标, string 被除, int 幂)
        {
            string 掩 = 新临时();

            发出($"MOV {掩} {被除}");
            发出右移立即数(掩, 31);               // 0 / 1
            发出($"NOT {掩}");
            发出($"ADD_IMMEDIATE {掩} 1");        // 掩 = 0 / 0xFFFFFFFF(被除为负)
            发出($"取整数绝对值 {被除}");           // 被除 = |被除|(0x52 一条顶"异或 掩 + 减 掩"两条)

            发出($"MOV {目标} {被除}");
            发出右移立即数(目标, 幂);             // |被除| ÷ 2^k

            发出($"XOR {目标} {掩}");
            发出($"SUB {目标} {掩}");             // 补符号:商跟着被除数
        }

        /// <summary> 复制到一个新临时寄存器 </summary>
        private string 复制到临时(string 寄存器)
        {
            string t = 新临时();
            发出($"MOV {t} {寄存器}");
            return t;
        }

        /// <summary>
        /// **有符号除 / 取余**。
        ///
        /// <para>
        /// **通用化第2批(2026-10-10)起这条只用一条指令**:ISA 新加的 `有符号除法`(0x40)/
        /// `有符号取余`(0x41) 自己就把"向零截断 + 商的符号 / 余数符号跟被除数"办好了
        /// (口径与 C99 一致,两边实现逐位对拍)。
        /// </para>
        /// <para>
        /// **以前那一段**(留作对照,别再退回去):ISA 只有无符号 `DIV`/`MOD`,所以这里**无分支展开**过
        /// 一大段符号整理 ——
        /// `负 ⟺ (x 逻辑右移 31) == 1`、`|x| = (x 异或 掩码) - 掩码`(掩码 = 0 或 `0xFFFFFFFF`),
        /// 商的符号 = 两个符号异或、余数看被除数符号;被除/除数各 4 条、补符号再 4 条 ⇒ **十几条指令**,
        /// 而且把 15 个临时寄存器吃掉一大半 —— 实测"一句里两处运行期除法就用光寄存器"(**H88**)。
        /// `输出有符号除取余正除数`(除数是正数常量那一档)也是同一族老路子,已一并删掉。
        /// </para>
        /// <para>
        /// ⚠ **除数是 2 的幂那一档不走这里**(调用方在前面就返回了):`x % 2^k` 走 `与立即数`、
        /// `x / 2^k` 走 `右移立即数`,那是**更短**的路(各 10 条左右),新指令顶不掉它。
        /// </para>
        /// <para>被除/除数/目标 三个寄存器必须互不相同(调用方保证)。</para>
        /// </summary>
        private void 输出有符号除取余(string 记号, string 目标, string 被除, string 除数)
        {
            发出($"MOV {目标} {被除}");
            发出($"{(记号 == "/" ? "有符号除法" : "有符号取余")} {目标} {除数}");
        }

        /// <summary> 关系符:最靠左出现者(>= &lt;= == != 优先于 &gt; &lt;) </summary>
        private static (int 位置, string 记号)? 找关系符(string 文本)
        {
            int 位置 = -1; string 记号 = "";
            foreach (string 候选 in new[] { ">=", "<=", "==", "!=", ">", "<" })
            {
                int i = 文本.IndexOf(候选, StringComparison.Ordinal);
                if (i >= 0 && (位置 < 0 || i < 位置)) { 位置 = i; 记号 = 候选; }
            }
            return 位置 < 0 ? null : (位置, 记号);
        }

        /// <summary> 条件里的常量比较(两侧都是常量时编译期定真假);返回 null 表示不是常量比较 </summary>
        private static bool? 比较常量(string 关系符, uint 左, uint 右, bool 有符号 = false)
        {
            if (有符号) { int a = (int)左, b = (int)右; return 关系符 switch
            {
                "==" => a == b,
                "!=" => a != b,
                ">" => a > b,
                "<" => a < b,
                ">=" => a >= b,
                "<=" => a <= b,
                _ => null
            }; }
            return 关系符 switch
            {
                "==" => 左 == 右,
                "!=" => 左 != 右,
                ">" => 左 > 右,
                "<" => 左 < 右,
                ">=" => 左 >= 右,
                "<=" => 左 <= 右,
                _ => null
            };
        }

        /// <summary>
        /// 给"有符号比较"做准备:值 异或 0x80000000 之后,有符号的大小关系就等于无符号的大小关系。
        /// 常量直接折叠(不花指令);寄存器不可改写(用户寄存器/循环不变量)时先复制一份,绝不就地改别人的寄存器。
        /// </summary>
        private 表达式值 偏置比较值(表达式值 值)
        {
            if (值.是常量) return 表达式值.常量值(值.常量 ^ 0x80000000u);
            string 寄存器 = 值.寄存器!;
            if (!值.可写) 寄存器 = 复制到临时(寄存器);
            string 偏 = 常量操作数寄存器(0x80000000u, 寄存器);
            发出($"XOR {寄存器} {偏}");
            return 表达式值.寄存器值(寄存器, 可写: true);
        }
