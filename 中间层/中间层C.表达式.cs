    /// <summary>
    /// 表达式求值(3 号改进的后半段):把 表达式语法C 建好的 AST 变成汇编。
    ///
    /// 分工:中间层\表达式语法C.cs 负责"文本 → 词元 → 语法树"(纯语法、可单测);
    ///       本文件负责"语法树 → 汇编"(选寄存器、常量折叠、调函数时暂存)。
    ///
    /// 求值结果只有两种:编译期常量,或一个寄存器。寄存器分"可写"(编译器为本次表达式新分配的临时寄存器)
    /// 与"只读"(用户自己写在源码里的寄存器),只有可写的才能当场当运算目标,否则会踩用户的值。
